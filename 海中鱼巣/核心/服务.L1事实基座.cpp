L1事实基座持久运行包建立结果 建立L1事实基座持久运行包(
    const L1事实基座持久存储配置& 配置) noexcept {
    L1事实基座持久运行包建立结果 结果;
    const auto& 根 = 配置.受控根;
    if (根.empty() || !根.is_absolute()) { 结果.恢复.状态 = L1事实基座持久恢复状态::入口拒绝; return 结果; }
    for (const auto& 分量 : 根) if (分量 == L"." || 分量 == L"..") {
        结果.恢复.状态 = L1事实基座持久恢复状态::入口拒绝; return 结果;
    }
    try {
        auto 状态 = std::make_shared<L1事实基座实例状态>();
        结果.恢复 = 映射持久恢复结果(状态->仓库.初始化持久恢复(根));
        const bool 空仓 = 结果.恢复.状态 == L1事实基座持久恢复状态::已建立空仓
            && !结果.恢复.恢复见证;
        const bool 已恢复 = 结果.恢复.状态 == L1事实基座持久恢复状态::已恢复
            && 结果.恢复.恢复见证
            && 结果.恢复.恢复见证->格式版本 == L1事实基座持久快照格式版本_v1
            && 结果.恢复.恢复见证->快照序号 != 0
            && std::any_of(结果.恢复.恢复见证->载荷SHA256.begin(),
                结果.恢复.恢复见证->载荷SHA256.end(), [](std::uint8_t 值) { return 值 != 0; });
        if (!空仓 && !已恢复) return 结果;
        结果.运行包.reset(new L1事实基座运行包(std::move(状态)));
        return 结果;
    } catch (const std::bad_alloc&) { 结果.恢复.状态 = L1事实基座持久恢复状态::资源失败; return 结果; }
    catch (...) { 结果.恢复.状态 = L1事实基座持久恢复状态::内部不一致; return 结果; }
}

