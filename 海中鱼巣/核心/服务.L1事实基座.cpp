bool L1所有者范围写端口::有效() const noexcept {
    const auto 状态 = 状态_.lock();
    if (!状态 || !持有租约_ || !海中鱼巣::有效(所有者_)) return false;
    std::lock_guard 锁(状态->租约锁);
    return 状态->活动端口所有者.contains(所有者_.编码.值);
}
bool L1所有者范围写端口::绑定于(const L1事实基座服务& 服务) const noexcept {
    const auto 状态 = 状态_.lock();
    return 状态 && &状态->仓库 == &服务.仓库_ && 有效();
}
void L1所有者范围写端口::释放租约() noexcept {
    if (!持有租约_) return;
    if (const auto 状态 = 状态_.lock()) {
        std::lock_guard 锁(状态->租约锁);
        状态->活动端口所有者.erase(所有者_.编码.值);
    }
    持有租约_ = false; 所有者_ = {};
}
