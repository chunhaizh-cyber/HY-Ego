#include "自检.关系概念出站.h"
#include "初始化.关系概念.h"

#include <algorithm>

namespace 海中鱼巣 {
namespace {
void 记(关系概念出站自检结果& r, std::string 标识, bool 通过, std::string 说明) {
    关系概念出站自检条目 e;
    e.标识 = std::move(标识);
    e.通过 = 通过;
    e.实际验证说明 = std::move(说明);
    r.条目组.push_back(std::move(e));
}
} // namespace

关系概念出站自检结果 运行关系概念出站自检(const 关系概念出站自检依赖& d) {
    关系概念出站自检结果 r;
    初始化关系概念请求 请求{d.种子文本, d.中文语言, d.英文语言};
    const auto 一 = 初始化世界关系概念(请求, d.关系, d.词);
    记(r, "init.首次建立", 一.状态 == 初始化关系概念状态::已完成 && 一.项组.size() >= 5,
        "首次初始化世界关系概念种子，期望已完成且≥5项；实际状态="
            + std::to_string(static_cast<int>(一.状态))
            + " 项数=" + std::to_string(一.项组.size()));

    const auto 读回 = 读取世界关系概念种子(请求, d.关系, d.词);
    记(r, "init.读回形状", 读回.状态 == 初始化关系概念状态::已完成,
        "种子读回校验端点/连接/附加连接/表达槽与尾词");

    std::string 组成句;
    std::string 属于句;
    std::vector<稳定编码> 属于所用知识;

    if (d.正式整体存在 && d.正式部分存在) {
        关系陈述请求 正{
            "existence.composition",
            {{"整体", *d.正式整体存在}, {"部分", *d.正式部分存在}},
            d.中文语言, {}, {}};
        const auto 正句 = d.陈述.生成关系陈述(正);
        组成句 = 正句.UTF8正文;
        记(r, "gen.正式组成成句",
            正句.状态 == 关系陈述状态::已生成且唯一回读 && !正句.UTF8正文.empty()
                && 正句.所用表达为预置
                && 正句.UTF8正文.find("一部分") != std::string::npos
                && !正句.所用知识节点组.empty(),
            "正式存在组成边→中文成句；状态="
                + std::to_string(static_cast<int>(正句.状态))
                + " 文=" + 正句.UTF8正文
                + " 知识数=" + std::to_string(正句.所用知识节点组.size()));

        关系陈述请求 反{
            "existence.composition",
            {{"整体", *d.正式部分存在}, {"部分", *d.正式整体存在}},
            d.中文语言, {}, {}};
        const auto 反向 = d.陈述.生成关系陈述(反);
        记(r, "gen.方向错误",
            反向.状态 == 关系陈述状态::方向或角色错误
                || 反向.状态 == 关系陈述状态::关系不成立,
            "对调整体/部分应方向错误或关系不成立；状态="
                + std::to_string(static_cast<int>(反向.状态)));

        // 等价正确表述：同事实，尾词=属于 →「部分属于整体」，非倒置。
        关系陈述请求 属于请求{
            "existence.composition.belong",
            {{"整体", *d.正式整体存在}, {"部分", *d.正式部分存在}},
            d.中文语言, {}, {}};
        const auto 属于结果 = d.陈述.生成关系陈述(属于请求);
        属于句 = 属于结果.UTF8正文;
        属于所用知识 = 属于结果.所用知识节点组;
        const bool 属于通过 =
            属于结果.状态 == 关系陈述状态::已生成且唯一回读
            && !属于结果.UTF8正文.empty()
            && 属于结果.所用表达为预置
            && 属于结果.UTF8正文.find("属于") != std::string::npos
            && 属于结果.UTF8正文.find("一部分") == std::string::npos
            && 正句.状态 == 关系陈述状态::已生成且唯一回读
            && 属于结果.UTF8正文 != 正句.UTF8正文
            && !属于结果.所用知识节点组.empty();
        记(r, "gen.等价正确表述差异", 属于通过,
            "同入口同端点仅知识选尾词不同→正确不同句；属于文="
                + 属于结果.UTF8正文 + " 对照组成文=" + 正句.UTF8正文);

        // 后天表达知识节点优先于预置尾词：把「属于」知识挂到 composition 后应改写组成句。
        bool 后天优先通过 = false;
        std::string 后天说明 = "未执行";
        if (属于通过 && !属于所用知识.empty()) {
            const auto 读组 = d.关系.按种子键读取("existence.composition");
            if (读组.状态 == 关系概念操作状态::已读取 && 读组.信息) {
                const auto st = d.关系.追加表达知识(
                    读组.信息->节点, d.中文语言, 属于所用知识.front());
                const auto 再 = d.陈述.生成关系陈述(正);
                后天优先通过 =
                    (st == 关系概念操作状态::已建立 || st == 关系概念操作状态::已复用)
                    && 再.状态 == 关系陈述状态::已生成且唯一回读
                    && 再.UTF8正文.find("属于") != std::string::npos
                    && 再.UTF8正文 != 组成句
                    && !再.所用知识节点组.empty()
                    && std::find(再.所用知识节点组.begin(), 再.所用知识节点组.end(),
                           属于所用知识.front())
                        != 再.所用知识节点组.end();
                后天说明 = "追加状态=" + std::to_string(static_cast<int>(st))
                    + " 再成文状态=" + std::to_string(static_cast<int>(再.状态))
                    + " 文=" + 再.UTF8正文;
            }
        }
        记(r, "gen.后天表达知识优先", 后天优先通过, 后天说明);
    } else {
        记(r, "gen.正式组成成句", false,
            "未提供正式整体/部分存在节点：未验证（不记功能通过）");
        记(r, "gen.方向错误", false, "未提供正式端点：未验证");
        记(r, "gen.等价正确表述差异", false, "未提供正式端点：未验证");
        记(r, "gen.后天表达知识优先", false, "未提供正式端点：未验证");
    }

    关系陈述请求 需缺端{
        "demand.parent_child",
        {},
        d.中文语言, {}, {}};
    const auto 缺端 = d.陈述.生成关系陈述(需缺端);
    记(r, "gen.需求父子缺端点", 缺端.状态 == 关系陈述状态::端点不合法,
        "需求父子无端点绑定应端点不合法");

    if (d.正式父需求 && d.正式子需求) {
        关系陈述请求 正需{
            "demand.parent_child",
            {{"父", *d.正式父需求}, {"子", *d.正式子需求}},
            d.中文语言, {}, {}};
        const auto 正句 = d.陈述.生成关系陈述(正需);
        const bool 正向通过 =
            正句.状态 == 关系陈述状态::已生成且唯一回读
            && !正句.UTF8正文.empty()
            && 正句.所用表达为预置
            && 正句.UTF8正文.find("子需求") != std::string::npos
            && 正句.UTF8正文.find("一部分") == std::string::npos
            && !正句.所用知识节点组.empty();
        记(r, "gen.正式需求父子成句", 正向通过,
            "正式需求父子边→中文成句；状态="
                + std::to_string(static_cast<int>(正句.状态))
                + " 文=" + 正句.UTF8正文);

        关系陈述请求 反需{
            "demand.parent_child",
            {{"父", *d.正式子需求}, {"子", *d.正式父需求}},
            d.中文语言, {}, {}};
        const auto 反向 = d.陈述.生成关系陈述(反需);
        记(r, "gen.需求父子方向错误",
            反向.状态 == 关系陈述状态::方向或角色错误
                || 反向.状态 == 关系陈述状态::关系不成立,
            "对调父/子应方向错误或关系不成立；状态="
                + std::to_string(static_cast<int>(反向.状态)));

        if (d.正式整体存在) {
            关系陈述请求 非法端{
                "demand.parent_child",
                {{"父", *d.正式父需求}, {"子", *d.正式整体存在}},
                d.中文语言, {}, {}};
            const auto 非法 = d.陈述.生成关系陈述(非法端);
            记(r, "gen.需求父子非法端点",
                非法.状态 == 关系陈述状态::端点不合法,
                "子端绑存在节点应端点不合法；状态="
                    + std::to_string(static_cast<int>(非法.状态)));
        } else {
            记(r, "gen.需求父子非法端点", false, "缺组成夹具存在：未验证");
        }

        if (d.英文语言) {
            关系陈述请求 英需{
                "demand.parent_child",
                {{"父", *d.正式父需求}, {"子", *d.正式子需求}},
                *d.英文语言, {}, {}};
            const auto 英句 = d.陈述.生成关系陈述(英需);
            记(r, "gen.需求父子英文缺知识",
                英句.状态 == 关系陈述状态::缺语言知识,
                "英文无需求父子表达关联须缺语言知识；状态="
                    + std::to_string(static_cast<int>(英句.状态)));
        } else {
            记(r, "gen.需求父子英文缺知识", false, "装配未提供英文语言：未验证");
        }
    } else {
        记(r, "gen.正式需求父子成句", false,
            "未提供正式父/子需求节点：未验证（不记功能通过）");
        记(r, "gen.需求父子方向错误", false, "未提供正式需求端点：未验证");
        记(r, "gen.需求父子非法端点", false, "未提供正式需求端点：未验证");
        记(r, "gen.需求父子英文缺知识", false, "未提供正式需求端点：未验证");
    }

    if (d.正式部分目标需求 && d.正式部分存在) {
        关系陈述请求 字段正{
            "demand.target_existence",
            {{"需求", *d.正式部分目标需求}, {"目标", *d.正式部分存在}},
            d.中文语言, {}, {}};
        const auto 字段句 = d.陈述.生成关系陈述(字段正);
        记(r, "gen.字段引用目标存在成句",
            字段句.状态 == 关系陈述状态::已生成且唯一回读
                && !字段句.UTF8正文.empty()
                && 字段句.所用表达为预置
                && 字段句.UTF8正文.find("要") != std::string::npos
                && !字段句.所用知识节点组.empty(),
            "字段引用需求.目标存在→成句；状态="
                + std::to_string(static_cast<int>(字段句.状态))
                + " 文=" + 字段句.UTF8正文);

        if (d.正式整体存在) {
            关系陈述请求 字段错{
                "demand.target_existence",
                {{"需求", *d.正式部分目标需求}, {"目标", *d.正式整体存在}},
                d.中文语言, {}, {}};
            const auto 错 = d.陈述.生成关系陈述(字段错);
            记(r, "gen.字段引用值不匹配",
                错.状态 == 关系陈述状态::关系不成立,
                "目标绑定与字段值不一致应关系不成立；状态="
                    + std::to_string(static_cast<int>(错.状态)));
        } else {
            记(r, "gen.字段引用值不匹配", false, "缺整体存在：未验证");
        }
    } else {
        记(r, "gen.字段引用目标存在成句", false,
            "未提供部分目标需求夹具：未验证");
        记(r, "gen.字段引用值不匹配", false, "未提供部分目标需求夹具：未验证");
    }

    if (d.正式整体存在 && d.正式部分存在 && d.正式部分目标需求) {
        关系陈述请求 多连{
            "existence.part_under_whole_as_demand_target",
            {{"整体", *d.正式整体存在}, {"部分", *d.正式部分存在},
                {"需求", *d.正式部分目标需求}},
            d.中文语言, {}, {}};
        const auto 多句 = d.陈述.生成关系陈述(多连);
        记(r, "gen.多连接组成且需求目标",
            多句.状态 == 关系陈述状态::已生成且唯一回读
                && !多句.UTF8正文.empty()
                && 多句.UTF8正文.find("一部分") != std::string::npos
                && !多句.所用知识节点组.empty(),
            "组成边+字段附加连接同时成立→成句；状态="
                + std::to_string(static_cast<int>(多句.状态))
                + " 文=" + 多句.UTF8正文);

        if (d.正式父需求) {
            关系陈述请求 多连缺{
                "existence.part_under_whole_as_demand_target",
                {{"整体", *d.正式整体存在}, {"部分", *d.正式部分存在},
                    {"需求", *d.正式父需求}},
                d.中文语言, {}, {}};
            const auto 缺 = d.陈述.生成关系陈述(多连缺);
            记(r, "gen.多连接附加不成立",
                缺.状态 == 关系陈述状态::关系不成立,
                "父需求目标不是部分时应附加连接不成立；状态="
                    + std::to_string(static_cast<int>(缺.状态)));
        } else {
            记(r, "gen.多连接附加不成立", false, "缺父需求：未验证");
        }
    } else {
        记(r, "gen.多连接组成且需求目标", false, "缺多连接夹具：未验证");
        记(r, "gen.多连接附加不成立", false, "缺多连接夹具：未验证");
    }

    if (d.英文语言) {
        关系陈述请求 英{
            "existence.composition",
            d.正式整体存在 && d.正式部分存在
                ? std::map<std::string, 稳定编码>{
                    {"整体", *d.正式整体存在}, {"部分", *d.正式部分存在}}
                : std::map<std::string, 稳定编码>{},
            *d.英文语言, {}, {}};
        if (d.正式整体存在 && d.正式部分存在) {
            const auto 英句 = d.陈述.生成关系陈述(英);
            记(r, "gen.英文缺知识不暗退",
                英句.状态 == 关系陈述状态::缺语言知识,
                "英文无表达关联须缺语言知识，不得暗退中文；状态="
                    + std::to_string(static_cast<int>(英句.状态)));
        } else {
            记(r, "gen.英文缺知识不暗退", false, "缺正式端点：未验证");
        }
    } else {
        记(r, "gen.英文缺知识不暗退", false, "装配未提供英文语言：未验证");
    }

    // 后天追加放在成文断言之后，避免假节点进入真消费允许集。
    稳定编码 假知识 = 全局基础数据集.新建节点();
    bool 追加成功 = false;
    if (一.状态 == 初始化关系概念状态::已完成 && 有效(假知识)) {
        const auto 读需 = d.关系.按种子键读取("demand.parent_child");
        if (读需.状态 == 关系概念操作状态::已读取 && 读需.信息) {
            const auto st = d.关系.追加表达知识(
                读需.信息->节点, d.中文语言, 假知识);
            追加成功 = st == 关系概念操作状态::已建立 || st == 关系概念操作状态::已复用;
        }
    }
    记(r, "learn.追加表达关联", 追加成功,
        "向 demand.parent_child 追加后天表达知识节点引用");

    const auto 二 = 初始化世界关系概念(请求, d.关系, d.词);
    bool 保留后天 = false;
    if (二.状态 == 初始化关系概念状态::已完成) {
        const auto 读 = d.关系.按种子键读取("demand.parent_child");
        if (读.状态 == 关系概念操作状态::已读取 && 读.信息) {
            for (const auto& a : 读.信息->定义.表达关联组) {
                if (a.语言节点 != d.中文语言) continue;
                for (const auto k : a.表达知识节点组) if (k == 假知识) 保留后天 = true;
            }
        }
    }
    记(r, "init.重复不覆盖后天",
        二.状态 == 初始化关系概念状态::已完成 && 保留后天,
        "二次初始化须复用且保留追加的表达知识节点");

    r.全部强制通过 = true;
    for (const auto& e : r.条目组) {
        if (!e.通过 && e.实际验证说明.find("未验证") == std::string::npos)
            r.全部强制通过 = false;
    }
    return r;
}

} // namespace 海中鱼巣
