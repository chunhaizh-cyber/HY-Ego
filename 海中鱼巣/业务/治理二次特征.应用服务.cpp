治理二次特征应用服务::治理二次特征应用服务(
    概念_二次特征类& 概念, 新_词类& 词, 概念_名称关系类& 名称) noexcept
    : 概念服务_(概念), 词服务_(词), 名称服务_(名称) {}

治理时间概念初始化结果 治理二次特征应用服务::初始化(
    稳定编码 中文语言节点) noexcept {
    治理时间概念初始化结果 输出;
    try {
        std::lock_guard 守卫(锁_);
        if (!有效(中文语言节点) || (语言_ && *语言_ != 中文语言节点)) {
            输出.状态 = 治理二次特征状态::输入不合法;
            return 输出;
        }
        已初始化_ = false;
        if (!有效(定位_.时间窗口余量)) {
            const auto 建立 = 概念服务_.建立或取得默认二次特征概念(
                二次特征算法::治理时间窗口余量, 时间输入());
            if (!建立成功(建立)) { 输出.状态 = 概念失败(建立.状态); return 输出; }
            定位_.时间窗口余量 = *建立.概念节点;
        }
        const auto 单位 = 概念服务_.获取纳秒单位节点();
        const auto 根 = 概念服务_.获取二次特征概念(定位_.时间窗口余量);
        if (!单位 || !根 || !定义正确(*根, 定位_.时间窗口余量, *单位)
            || 根->输出特征概念.值域 != 特征概念值域{区间组{{最小, 最大}}}) {
            输出.状态 = 治理二次特征状态::结构不一致; return 输出;
        }
        const std::array 子节点{&定位_.时间不足, &定位_.恰好足够, &定位_.时间有余量};
        const std::array<特征概念I64闭区间, 3> 域{{{最小, -1}, {0, 0}, {1, 最大}}};
        const std::array 关系{二次特征结果域种类::小于,
            二次特征结果域种类::等于, 二次特征结果域种类::大于};
        for (std::size_t i = 0; i < 子节点.size(); ++i) {
            if (有效(*子节点[i])) continue;
            const auto 建立 = 概念服务_.建立或取得结果值域概念(
                定位_.时间窗口余量, 区间组{域[i]}, {}, 关系[i]);
            if (!建立成功(建立)) { 输出.状态 = 概念失败(建立.状态); return 输出; }
            *子节点[i] = *建立.概念节点;
        }
        if (!集合正确(概念服务_, 定位_)) {
            输出.状态 = 治理二次特征状态::结构不一致; return 输出;
        }
        const std::array 节点{定位_.时间窗口余量, 定位_.时间不足,
            定位_.恰好足够, 定位_.时间有余量};
        const std::array<const char*, 4> 词面{"时间窗口余量", "时间不足", "恰好足够", "时间有余量"};
        for (std::size_t i = 0; i < 节点.size(); ++i) {
            const auto 词 = 词服务_.建立或取得词条({中文语言节点,
                严格UTF8字节精确规范化合同节点, 词面[i], std::nullopt});
            if ((词.状态 != 新词条建立状态::已建立 && 词.状态 != 新词条建立状态::已复用)
                || !词.词条节点) {
                输出.状态 = 词.状态 == 新词条建立状态::资源失败
                    ? 治理二次特征状态::资源失败 : 治理二次特征状态::结构不一致;
                return 输出;
            }
            const auto 名称 = 名称服务_.建立或取得名称关系(节点[i], *词.词条节点);
            if ((名称.状态 != 概念名称关系建立状态::已建立
                    && 名称.状态 != 概念名称关系建立状态::已复用) || !名称.名称关系节点) {
                输出.状态 = 名称.状态 == 概念名称关系建立状态::资源失败
                    ? 治理二次特征状态::资源失败 : 治理二次特征状态::结构不一致;
                return 输出;
            }
            const auto 词读回 = 词服务_.获取词条(*词.词条节点);
            const auto 名称读回 = 名称服务_.获取名称关系(*名称.名称关系节点);
            if (!词读回.信息 || !名称读回.信息
                || 词读回.信息->语言节点 != 中文语言节点
                || 词读回.信息->规范化合同节点 != 严格UTF8字节精确规范化合同节点
                || 词读回.信息->规范化词面 != 词面[i]
                || 名称读回.信息->概念节点 != 节点[i]
                || 名称读回.信息->词条节点 != *词.词条节点) {
                输出.状态 = 治理二次特征状态::结构不一致; return 输出;
            }
        }
        if (!集合正确(概念服务_, 定位_)) {
            输出.状态 = 治理二次特征状态::结构不一致; return 输出;
        }
        语言_ = 中文语言节点;
        已初始化_ = true;
        输出.状态 = 治理二次特征状态::已完成;
        输出.概念 = 定位_;
    } catch (const std::bad_alloc&) { 输出.状态 = 治理二次特征状态::资源失败; }
    catch (...) { 输出.状态 = 治理二次特征状态::结构不一致; }
    return 输出;
}

治理时序解释结果 治理二次特征应用服务::裁决时序(
    const 需求时序可达性裁决请求& 请求) const noexcept {
    try {
        std::lock_guard 守卫(锁_);
        if (!已初始化_) return 失败(治理二次特征状态::尚未初始化);
        if (!集合正确(概念服务_, 定位_)) return 失败(治理二次特征状态::结构不一致);
        auto 裁决 = 任务时序可达性裁决器::裁决(请求);
        switch (裁决.状态) {
        case 需求时序裁决状态::输入不合法: return 失败(治理二次特征状态::输入不合法);
        case 需求时序裁决状态::材料不足: return 失败(治理二次特征状态::材料不足);
        case 需求时序裁决状态::计算不可表示: return 失败(治理二次特征状态::计算不可表示);
        case 需求时序裁决状态::资源失败: return 失败(治理二次特征状态::资源失败);
        case 需求时序裁决状态::结构不一致: return 失败(治理二次特征状态::结构不一致);
        default: break;
        }
        治理时序解释结果 输出;
        const auto 单位 = 概念服务_.获取纳秒单位节点();
        if (!单位) return 失败(治理二次特征状态::结构不一致);
        for (const auto* 路线 : {&裁决.第一后第二, &裁决.第二后第一}) {
            if (路线->状态 == 时序路线状态::计算不可表示)
                return 失败(治理二次特征状态::计算不可表示);
            for (const auto* 材料 : {&路线->最短比较, &路线->预计比较, &路线->保证比较}) {
                if (材料->路线.empty()) continue; // 合同缺失或前置门否决，无虚构时间。
                if (!材料->可表示 || !材料->第一需求满足时刻 || !材料->第二需求满足时刻
                    || !材料->第一需求窗口余量纳秒 || !材料->第二需求窗口余量纳秒)
                    return 失败(治理二次特征状态::结构不一致);
                for (const bool 第一 : {true, false}) {
                    const auto& 需求 = 第一 ? 请求.第一需求 : 请求.第二需求;
                    const auto 时刻 = 第一 ? *材料->第一需求满足时刻 : *材料->第二需求满足时刻;
                    const auto 余量 = 第一 ? *材料->第一需求窗口余量纳秒 : *材料->第二需求窗口余量纳秒;
                    if (余量 != 需求.最晚满足纳秒 - 时刻)
                        return 失败(治理二次特征状态::结构不一致);
                    const auto 查找 = 概念服务_.查找结果对应最具体概念(定位_.时间窗口余量, 余量);
                    if (查找.状态 != 二次特征概念操作状态::已找到 || !查找.概念节点)
                        return 失败(概念失败(查找.状态));
                    const auto 命中 = 概念服务_.获取二次特征概念(*查找.概念节点);
                    if (!命中 || !定义正确(*命中, 定位_.时间窗口余量, *单位))
                        return 失败(治理二次特征状态::结构不一致);
                    const auto* 域 = std::get_if<区间组>(&命中->输出特征概念.值域);
                    const auto 下 = 余量 < 0 ? 最小 : (余量 == 0 ? 0 : 1);
                    const auto 上 = 余量 < 0 ? -1 : (余量 == 0 ? 0 : 最大);
                    if (!域 || 域->empty()
                        || !std::all_of(域->begin(), 域->end(), [下, 上](const auto& 项) {
                            return 项.下界 >= 下 && 项.上界 <= 上;
                        }) || !std::any_of(域->begin(), 域->end(), [余量](const auto& 项) {
                            return 项.下界 <= 余量 && 余量 <= 项.上界;
                        })) return 失败(治理二次特征状态::结构不一致);
                    输出.时间比较组.push_back({路线->顺序, 材料->依据, 需求.需求节点,
                        定位_.时间窗口余量, *查找.概念节点, 时刻, 需求.最晚满足纳秒, 余量});
                }
            }
        }
        输出.来源请求 = 请求;
        输出.裁决 = std::move(裁决);
        输出.状态 = 治理二次特征状态::已完成;
        return 输出;
    } catch (const std::bad_alloc&) { return 失败(治理二次特征状态::资源失败); }
    catch (...) { return 失败(治理二次特征状态::结构不一致); }
}
