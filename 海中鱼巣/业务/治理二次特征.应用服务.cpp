using 区间组 = std::vector<特征概念I64闭区间>;
constexpr auto 最小 = (std::numeric_limits<std::int64_t>::min)();
constexpr auto 最大 = (std::numeric_limits<std::int64_t>::max)();

std::vector<二次特征概念输入定义> 时间输入() {
    return {{0, 二次特征输入角色::左输入,
                二次特征输入来源种类::治理时间合同投影, std::nullopt},
            {1, 二次特征输入角色::右输入,
                二次特征输入来源种类::治理时间合同投影, std::nullopt}};
}

bool 定义正确(const 二次特征概念信息& 信息, 稳定编码 根,
    稳定编码 单位) {
    const auto& 输出 = 信息.输出特征概念;
    return 信息.二次特征类型根节点 == 根
        && 信息.算法 == 二次特征算法::治理时间窗口余量
        && 信息.输入定义组 == 时间输入() && !信息.参照特征概念节点
        && 输出.材料类型 == 特征概念材料物理类型::I64标量
        && 输出.单位 == 单位 && 输出.比较规则 == 特征概念比较规则::I64数值
        && 输出.聚合规则 == 特征概念聚合规则::不自动聚合;
}

bool 集合正确(const 概念_二次特征类& 服务, const 治理时间概念集合& 集合) {
    const auto 单位 = 服务.获取纳秒单位节点();
    if (!单位 || !有效(*单位)) return false;
    const std::array 节点{集合.时间窗口余量, 集合.时间不足,
        集合.恰好足够, 集合.时间有余量};
    const std::array<特征概念I64闭区间, 4> 域{{{最小, 最大}, {最小, -1}, {0, 0}, {1, 最大}}};
    const std::array 关系{二次特征结果域种类::任意, 二次特征结果域种类::小于,
        二次特征结果域种类::等于, 二次特征结果域种类::大于};
    for (std::size_t i = 0; i < 节点.size(); ++i) {
        if (!有效(节点[i])) return false;
        for (std::size_t j = 0; j < i; ++j) if (节点[i] == 节点[j]) return false;
        const auto 信息 = 服务.获取二次特征概念(节点[i]);
        if (!信息 || !定义正确(*信息, 集合.时间窗口余量, *单位)
            || 信息->输出特征概念.值域 != 特征概念值域{区间组{域[i]}}
            || std::find(信息->结果域种类组.begin(), 信息->结果域种类组.end(),
                关系[i]) == 信息->结果域种类组.end()) return false;
    }
    return true;
}

治理二次特征状态 概念失败(二次特征概念操作状态 状态) noexcept {
    return 状态 == 二次特征概念操作状态::资源失败
        ? 治理二次特征状态::资源失败 : 治理二次特征状态::结构不一致;
}

bool 建立成功(const 二次特征概念建立结果& 结果) noexcept {
    return (结果.状态 == 二次特征概念操作状态::已建立
        || 结果.状态 == 二次特征概念操作状态::已复用)
        && 结果.概念节点 && 有效(*结果.概念节点);
}

治理时序解释结果 失败(治理二次特征状态 状态) {
    治理时序解释结果 结果;
    结果.状态 = 状态;
    return 结果;
}
