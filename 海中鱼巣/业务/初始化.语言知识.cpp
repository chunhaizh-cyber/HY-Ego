bool 未完成(初始化语言知识结果& 结果, 初始化语言知识状态 状态,
    std::string 诊断) {
    结果.状态 = 状态;
    结果.诊断说明 = std::move(诊断);
    return false;
}

bool 读取非负标准I64(std::string_view 词, std::int64_t& 值) noexcept {
    if (词.empty() || (词.size() > 1 && 词.front() == '0')) return false;
    for (const auto 字节 : 词) if (字节 < '0' || 字节 > '9') return false;
    const auto 结果 = std::from_chars(词.data(), 词.data() + 词.size(), 值);
    return 结果.ec == std::errc{} && 结果.ptr == 词.data() + 词.size() && 值 >= 0;
}

// 此处只解码有限元格式名字，不依据知识标签补目标或规则结构。
template<class 枚举>
std::optional<枚举> 读取元枚举(std::string_view 词,
    std::initializer_list<std::pair<std::string_view, 枚举>> 表) {
    for (const auto& [名称, 值] : 表) if (词 == 名称) return 值;
    return std::nullopt;
}

bool 核验并规范化知识草稿(初始化知识草稿& 草稿, std::string& 诊断) {
    const auto 拒绝 = [&](const char* 原因) { 诊断 = 原因; return false; };
    auto& 目标 = 草稿.目标;
    if (目标.目的 != 新语言知识表达目的::陈述 || !目标.适用条件组.empty()
        || 目标.角色组.empty() || 目标.含义组.size() != 1 || 草稿.有序项组.empty())
        return 拒绝("目标、单含义或有序结构不完整");
    std::map<std::int64_t, 新语言知识角色定义*> 角色表;
    for (auto& 角色 : 目标.角色组) {
        if (角色.局部编号 < 0 || !角色表.emplace(角色.局部编号, &角色).second
            || 角色.数量 != 新语言知识角色数量::单项 || 角色.必要约束组.size() != 1)
            return 拒绝("角色编号重复、数量或约束不合法");
        auto& 约束 = 角色.必要约束组.front();
        if (约束.被约束角色 != 角色.局部编号 || 约束.允许类别组.empty())
            return 拒绝("角色类别约束未明确指向自己");
        auto& 类别组 = 约束.允许类别组;
        std::sort(类别组.begin(), 类别组.end());
        类别组.erase(std::unique(类别组.begin(), 类别组.end()), 类别组.end());
        const auto 仅为 = [&](角色类别 类别) {
            return 类别组.size() == 1 && 类别组.front() == 类别;
        };
        switch (角色.种类) {
        case 角色种类::领域对象引用:
            if (!仅为(角色类别::存在)) return 拒绝("存在角色类别不相容");
            break;
        case 角色种类::概念引用:
            for (const auto 类别 : 类别组)
                if (类别 != 角色类别::存在概念 && 类别 != 角色类别::特征概念)
                    return 拒绝("概念角色类别不相容");
            break;
        case 角色种类::特征类型引用:
            if (!仅为(角色类别::正式特征类型) && !仅为(角色类别::I64标量特征类型))
                return 拒绝("特征类型角色类别不相容");
            break;
        case 角色种类::准确值:
            if (!仅为(角色类别::I64标量)) return 拒绝("准确值角色不是I64标量");
            break;
        default: return 拒绝("角色种类未支持");
        }
    }
    auto& 含义 = 目标.含义组.front();
    if (含义.局部编号 < 0 || 含义.作用域 != 新语言知识作用域::普通陈述)
        return 拒绝("含义编号或作用域不合法");
    std::map<参数角色, 新语言知识角色定义*> 参数表;
    std::set<std::int64_t> 目标引用;
    for (const auto& 参数 : 含义.参数组) {
        const auto 角色 = 角色表.find(参数.规则角色);
        if (角色 == 角色表.end() || !参数表.emplace(参数.参数, 角色->second).second)
            return 拒绝("具名参数重复或悬空");
        目标引用.insert(参数.规则角色);
    }
    const auto 参数为 = [&](参数角色 参数, 角色种类 种类) {
        const auto 项 = 参数表.find(参数);
        return 项 != 参数表.end() && 项->second->种类 == 种类;
    };
    const auto 参数仅为 = [&](参数角色 参数, 角色类别 类别) {
        const auto 项 = 参数表.find(参数);
        return 项 != 参数表.end()
            && 项->second->必要约束组.front().允许类别组 == std::vector<角色类别>{类别};
    };
    switch (含义.操作) {
    case 含义操作::概念归类:
        if (含义.特征值分支 || 参数表.size() != 2
            || !参数为(参数角色::归类概念, 角色种类::概念引用))
            return 拒绝("概念归类参数不完整");
        if (参数为(参数角色::主体, 角色种类::领域对象引用)) {
            if (!参数仅为(参数角色::归类概念, 角色类别::存在概念))
                return 拒绝("存在只能归类到存在概念");
        } else if (参数为(参数角色::主体, 角色种类::概念引用)) {
            if (参数表.at(参数角色::主体)->必要约束组.front().允许类别组
                != 参数表.at(参数角色::归类概念)->必要约束组.front().允许类别组)
                return 拒绝("概念上下位角色类别集合必须相同");
        } else return 拒绝("概念归类主体不合法");
        break;
    case 含义操作::特征描述:
        if (参数表.size() != 3 || !参数为(参数角色::主体, 角色种类::领域对象引用)
            || !参数为(参数角色::特征类型, 角色种类::特征类型引用))
            return 拒绝("特征描述参数不完整");
        if (含义.特征值分支 == 值分支::准确值) {
            if (!参数为(参数角色::特征值, 角色种类::准确值)
                || !参数仅为(参数角色::特征类型, 角色类别::I64标量特征类型))
                return 拒绝("准确值与特征类型材料限制不相容");
        } else if (含义.特征值分支 == 值分支::概念条件) {
            if (!参数为(参数角色::特征值, 角色种类::概念引用)
                || !参数仅为(参数角色::特征值, 角色类别::特征概念))
                return 拒绝("特征概念条件角色不相容");
        } else return 拒绝("特征值分支未支持");
        break;
    case 含义操作::组成描述:
        if (含义.特征值分支 || 参数表.size() != 2
            || !参数为(参数角色::整体, 角色种类::领域对象引用)
            || !参数为(参数角色::部分, 角色种类::领域对象引用))
            return 拒绝("组成描述须显式声明整体与部分");
        break;
    default: return 拒绝("含义操作未支持");
    }
    std::set<std::int64_t> 项编号;
    std::map<std::int64_t, std::int64_t> 重编号;
    for (auto& 项 : 草稿.有序项组) {
        if (项.局部编号 < 0 || !项编号.insert(项.局部编号).second)
            return 拒绝("结构项编号重复或负数");
        if (const auto* 词面 = std::get_if<std::string>(&项.载荷)) {
            if (!新_语言类::严格UTF8字节串有效(*词面)) return 拒绝("固定词面不合法");
        } else if (auto* 表达 = std::get_if<新语言知识角色表达项>(&项.载荷)) {
            const auto 角色 = 角色表.find(表达->规则角色);
            if (角色 == 角色表.end()) return 拒绝("结构角色悬空");
            const auto 种类 = 角色->second->种类;
            const bool 相容 = (表达->方式 == 表达方式::明确对象描述 && 种类 == 角色种类::领域对象引用)
                || (表达->方式 == 表达方式::名称表达
                    && (种类 == 角色种类::概念引用 || 种类 == 角色种类::特征类型引用))
                || (表达->方式 == 表达方式::类型化字面值 && 种类 == 角色种类::准确值);
            if (!相容) return 拒绝("角色表达方式不相容");
            if (!重编号.contains(表达->规则角色))
                重编号.emplace(表达->规则角色, static_cast<std::int64_t>(重编号.size()));
        } else return 拒绝("结构项载荷不完整");
    }
    if (目标引用.size() != 角色表.size() || 重编号.size() != 角色表.size())
        return 拒绝("存在未被目标或结构实际引用的角色");
    for (auto& 角色 : 目标.角色组) {
        角色.局部编号 = 重编号.at(角色.局部编号);
        角色.必要约束组.front().被约束角色 = 角色.局部编号;
    }
    std::sort(目标.角色组.begin(), 目标.角色组.end(), [](const auto& 左, const auto& 右) {
        return 左.局部编号 < 右.局部编号;
    });
    含义.局部编号 = 0;
    for (auto& 参数 : 含义.参数组) 参数.规则角色 = 重编号.at(参数.规则角色);
    std::sort(含义.参数组.begin(), 含义.参数组.end(), [](const auto& 左, const auto& 右) {
        return 左.参数 < 右.参数;
    });
    for (std::size_t i = 0; i < 草稿.有序项组.size(); ++i) {
        auto& 项 = 草稿.有序项组[i];
        项.局部编号 = static_cast<std::int64_t>(i);
        if (auto* 表达 = std::get_if<新语言知识角色表达项>(&项.载荷))
            表达->规则角色 = 重编号.at(表达->规则角色);
    }
    return true;
}

初始化语言知识结果 解码及预检语言知识种子(
    const 初始化语言知识请求& 请求, 初始化知识草稿组& 草稿) {
    初始化语言知识结果 结果;
    const auto 到限 = [&](初始化语言知识额度种类 额度) {
        结果.工程控制 = 初始化语言知识工程控制::资源未完成;
        结果.状态.reset();
        结果.到限额度 = 额度;
        结果.诊断说明 = "初始化语言知识的完整输入超出本次工程额度";
        return false;
    };
    const auto 文本拒绝 = [&](const char* 原因) {
        return 未完成(结果, 初始化语言知识状态::文本未完成, 原因);
    };
    const auto& 原文 = 请求.标准文本;
    if (原文.size() > 1024 * 1024) { 到限(初始化语言知识额度种类::源字节); return 结果; }
    if (原文.empty()) { 文本拒绝("知识种子原文为空"); return 结果; }
    std::vector<std::size_t> 标量边界{0};
    for (std::size_t 位置 = 0; 位置 < 原文.size();) {
        const auto 首 = static_cast<unsigned char>(原文[位置]);
        const std::size_t 长度 = 首 < 0x80 ? 1
            : (首 >= 0xC2 && 首 <= 0xDF ? 2
                : (首 >= 0xE0 && 首 <= 0xEF ? 3 : (首 >= 0xF0 && 首 <= 0xF4 ? 4 : 0)));
        if (长度 == 0 || 长度 > 原文.size() - 位置) {
            文本拒绝("原文不是完整UTF8"); return 结果;
        }
        std::uint32_t 标量 = 首 & (长度 == 1 ? 0x7F : (长度 == 2 ? 0x1F : (长度 == 3 ? 0x0F : 0x07)));
        for (std::size_t i = 1; i < 长度; ++i) {
            const auto 后续 = static_cast<unsigned char>(原文[位置 + i]);
            if ((后续 & 0xC0) != 0x80) { 文本拒绝("UTF8后续字节不合法"); return 结果; }
            标量 = (标量 << 6) | (后续 & 0x3F);
        }
        if ((长度 == 2 && 标量 < 0x80) || (长度 == 3 && 标量 < 0x800)
            || (长度 == 4 && 标量 < 0x10000) || 标量 > 0x10FFFF
            || (标量 >= 0xD800 && 标量 <= 0xDFFF) || 标量 == 0xFEFF) {
            文本拒绝("UTF8标量或BOM不合法"); return 结果;
        }
        if ((标量 < 0x20 && 标量 != '\r' && 标量 != '\n')
            || (标量 >= 0x7F && 标量 <= 0x9F) || 标量 == 0xA0 || 标量 == 0x1680
            || (标量 >= 0x2000 && 标量 <= 0x200A) || 标量 == 0x2028 || 标量 == 0x2029
            || 标量 == 0x202F || 标量 == 0x205F || 标量 == 0x3000) {
            文本拒绝("元格式不接受非标准空白或控制字符"); return 结果;
        }
        位置 += 长度;
        标量边界.push_back(位置);
        if (标量边界.size() - 1 > 262144) { 到限(初始化语言知识额度种类::源标量); return 结果; }
    }
    const auto 标量位置 = [&](std::size_t 字节位置) {
        const auto 位置 = std::lower_bound(标量边界.begin(), 标量边界.end(), 字节位置);
        if (位置 == 标量边界.end() || *位置 != 字节位置)
            throw std::logic_error("已解码元格式行不在Unicode标量边界");
        return static_cast<std::int64_t>(位置 - 标量边界.begin());
    };
    std::optional<初始化知识草稿> 当前;
    bool 已有目的 = false, 已有操作 = false;
    std::set<std::string> 标签组;
    std::size_t 非空行数 = 0;
    for (std::size_t 起点 = 0; 起点 < 原文.size();) {
        const auto 换行 = 原文.find('\n', 起点);
        const auto 行末 = 换行 == std::string::npos ? 原文.size() : 换行;
        auto 终点 = 行末;
        if (终点 > 起点 && 原文[终点 - 1] == '\r' && 换行 != std::string::npos) --终点;
        const auto 下一行 = 换行 == std::string::npos ? 原文.size() : 换行 + 1;
        const std::string_view 行(原文.data() + 起点, 终点 - 起点);
        if (行.empty()) { 起点 = 下一行; continue; }
        if (++非空行数 > 4096) { 到限(初始化语言知识额度种类::非空行); return 结果; }
        if (行.front() == ' ' || 行.back() == ' ' || 行.find("  ") != std::string_view::npos
            || 行.find('\r') != std::string_view::npos) {
            文本拒绝("非空行必须以单个ASCII空格分词且只用LF或CRLF换行"); return 结果;
        }
        std::vector<std::string_view> 词;
        for (std::size_t i = 0; i < 行.size();) {
            const auto 间隔 = 行.find(' ', i);
            const auto 末 = 间隔 == std::string_view::npos ? 行.size() : 间隔;
            词.push_back(行.substr(i, 末 - i));
            i = 末 == 行.size() ? 末 : 末 + 1;
        }
        bool 合法 = false;
        if (词.front() == "知识") {
            if (!当前 && 词.size() == 2 && 标签组.emplace(词[1]).second) {
                if (草稿.知识组.size() >= 128) { 到限(初始化语言知识额度种类::知识块); return 结果; }
                当前.emplace();
                当前->来源标签 = 词[1];
                当前->起始标量 = 标量位置(起点);
                当前->目标.含义组.emplace_back();
                已有目的 = 已有操作 = false;
                合法 = true;
            }
        } else if (当前) {
            auto& 含义 = 当前->目标.含义组.front();
            if (词.front() == "目的") {
                合法 = 词.size() == 2 && 词[1] == "陈述" && !已有目的;
                if (合法) 已有目的 = true;
            } else if (词.front() == "操作") {
                if (!已有操作 && (词.size() == 3 || 词.size() == 4) && 词[2] == "普通陈述") {
                    const auto 操作 = 读取元枚举<含义操作>(词[1], {
                        {"概念归类", 含义操作::概念归类}, {"特征描述", 含义操作::特征描述},
                        {"组成描述", 含义操作::组成描述}});
                    if (操作) {
                        含义.操作 = *操作;
                        合法 = true;
                        if (词.size() == 4) {
                            含义.特征值分支 = 读取元枚举<值分支>(词[3], {
                                {"准确值", 值分支::准确值}, {"概念条件", 值分支::概念条件}});
                            合法 = 含义.特征值分支.has_value();
                        }
                        已有操作 = 合法;
                    }
                }
            } else if (词.front() == "角色" && 词.size() == 5 && 词[4] == "单项") {
                if (当前->目标.角色组.size() >= 128) { 到限(初始化语言知识额度种类::单块角色); return 结果; }
                新语言知识角色定义 角色{};
                const auto 种类 = 读取元枚举<角色种类>(词[2], {
                    {"领域对象引用", 角色种类::领域对象引用}, {"概念引用", 角色种类::概念引用},
                    {"特征类型引用", 角色种类::特征类型引用}, {"准确值", 角色种类::准确值}});
                合法 = 种类 && 读取非负标准I64(词[1], 角色.局部编号);
                if (合法) {
                    角色.种类 = *种类;
                    新语言知识角色类别约束 约束{角色.局部编号, {}};
                    std::size_t i = 0;
                    do {
                        const auto 加号 = 词[3].find('+', i);
                        const auto 末 = 加号 == std::string_view::npos ? 词[3].size() : 加号;
                        const auto 类别 = 读取元枚举<角色类别>(词[3].substr(i, 末 - i), {
                            {"存在", 角色类别::存在}, {"存在概念", 角色类别::存在概念},
                            {"特征概念", 角色类别::特征概念}, {"正式特征类型", 角色类别::正式特征类型},
                            {"I64标量特征类型", 角色类别::I64标量特征类型}, {"I64标量", 角色类别::I64标量}});
                        if (!类别) { 合法 = false; break; }
                        约束.允许类别组.push_back(*类别);
                        if (加号 == std::string_view::npos) break;
                        i = 加号 + 1;
                    } while (i <= 词[3].size());
                    角色.必要约束组.push_back(std::move(约束));
                    if (合法) 当前->目标.角色组.push_back(std::move(角色));
                }
            } else if (词.front() == "参数" && 词.size() == 3) {
                if (含义.参数组.size() >= 128) { 到限(初始化语言知识额度种类::单块参数); return 结果; }
                const auto 参数 = 读取元枚举<参数角色>(词[1], {
                    {"主体", 参数角色::主体}, {"归类概念", 参数角色::归类概念},
                    {"特征类型", 参数角色::特征类型}, {"特征值", 参数角色::特征值},
                    {"整体", 参数角色::整体}, {"部分", 参数角色::部分}});
                std::int64_t 角色 = 0;
                合法 = 参数 && 读取非负标准I64(词[2], 角色);
                if (合法) 含义.参数组.push_back({*参数, 角色});
            } else if (词.front() == "项" && (词.size() == 4 || 词.size() == 5)) {
                if (当前->有序项组.size() >= 512) { 到限(初始化语言知识额度种类::单块结构项); return 结果; }
                初始化知识草稿项 项;
                if (读取非负标准I64(词[1], 项.局部编号)) {
                    if (词.size() == 4 && 词[2] == "词") {
                        项.载荷 = std::string(词[3]);
                        合法 = true;
                    } else if (词.size() == 5 && 词[2] == "角色") {
                        std::int64_t 角色 = 0;
                        const auto 方式 = 读取元枚举<表达方式>(词[4], {
                            {"名称表达", 表达方式::名称表达}, {"明确对象描述", 表达方式::明确对象描述},
                            {"类型化字面值", 表达方式::类型化字面值}});
                        合法 = 方式 && 读取非负标准I64(词[3], 角色);
                        if (合法) 项.载荷 = 新语言知识角色表达项{角色, *方式};
                    }
                    if (合法) 当前->有序项组.push_back(std::move(项));
                }
            } else if (词.front() == "结束" && 词.size() == 1 && 已有目的 && 已有操作) {
                当前->结束标量 = 标量位置(终点);
                结果.当前项 = 草稿.知识组.size();
                if (!核验并规范化知识草稿(*当前, 结果.诊断说明)) {
                    结果.状态 = 初始化语言知识状态::定义拒绝;
                    return 结果;
                }
                草稿.知识组.push_back(std::move(*当前));
                当前.reset();
                合法 = true;
            }
        }
        if (!合法) { 文本拒绝("未知、重复、缺失或位置不合法的元格式声明"); return 结果; }
        起点 = 下一行;
    }
    if (当前 || 草稿.知识组.empty()) { 文本拒绝("知识块未完整结束或批次为空"); return 结果; }
    草稿.固定原文 = 原文;
    for (const auto& 知识 : 草稿.知识组) {
        结果.知识项组.push_back({知识.来源标签, 知识.起始标量, 知识.结束标量, {}, {}, {}});
        for (const auto& 项 : 知识.有序项组)
            if (const auto* 词面 = std::get_if<std::string>(&项.载荷))
                if (std::find(草稿.固定词面组.begin(), 草稿.固定词面组.end(), *词面) == 草稿.固定词面组.end())
                    草稿.固定词面组.push_back(*词面);
    }
    for (const auto& 词面 : 草稿.固定词面组) 结果.词项组.push_back({词面, {}, {}});
    结果.当前项.reset();
    结果.状态 = 初始化语言知识状态::已完成;
    return 结果;
}

bool 核验初始化知识语言(const 初始化语言知识请求& 请求,
    const 新_语言类& 语言服务, 初始化语言知识结果& 结果) {
    if (!有效(请求.语言节点) || !有效(请求.规范化合同节点)
        || 请求.规范化合同节点 != 严格UTF8字节精确规范化合同节点)
        return 未完成(结果, 初始化语言知识状态::语言未完成, "正式中文语言或严格UTF8合同缺失");
    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    const auto 中文 = 语言服务.按登记键查询("zh-CN");
    if (语言.状态 != 新语言查询状态::已找到 || !语言.信息
        || 中文.状态 != 新语言查询状态::已找到 || !中文.信息)
        return 未完成(结果, 初始化语言知识状态::语言未完成,
            "正式中文读取未完成；身份读取状态=" + std::to_string(static_cast<int>(语言.状态))
                + "；登记键查询状态=" + std::to_string(static_cast<int>(中文.状态)));
    if (语言.信息->节点 != 请求.语言节点 || 语言.信息->登记键 != "zh-CN"
        || *语言.信息 != *中文.信息)
        return 未完成(结果, 初始化语言知识状态::语言未完成, "正式中文语言身份与登记键完整读取不一致");
    return true;
}

新语言知识定义 绑定知识正式词条(const 初始化知识草稿& 草稿,
    稳定编码 语言节点, const std::vector<新词条信息>& 实际词条组) {
    新语言知识定义 定义;
    定义.目标 = 草稿.目标;
    定义.结构.语言节点 = 语言节点;
    for (const auto& 项 : 草稿.有序项组) {
        if (const auto* 词面 = std::get_if<std::string>(&项.载荷)) {
            const 新词条信息* 选中 = nullptr;
            for (const auto& 词条 : 实际词条组) {
                if (词条.规范化词面 != *词面) continue;
                if (选中 || !有效(词条.节点) || 词条.语言节点 != 语言节点
                    || 词条.规范化合同节点 != 严格UTF8字节精确规范化合同节点)
                    throw std::logic_error("已确认的知识固定词不唯一或端点合同漂移");
                选中 = &词条;
            }
            if (!选中) throw std::logic_error("已完成词条读取材料缺少知识固定词");
            定义.结构.有序项组.push_back({项.局部编号, 新语言知识固定词项{选中->节点}});
        } else {
            定义.结构.有序项组.push_back({项.局部编号,
                std::get<新语言知识角色表达项>(项.载荷)});
        }
    }
    return 定义;
}

bool 核验知识完整读回(const 初始化语言知识项& 项,
    const 新语言知识来源绑定& 必需来源, const 新语言知识结果& 读回,
    初始化语言知识结果& 结果) {
    if (读回.状态 != 新语言知识状态::已完成 || !读回.信息 || !项.定稿) {
        return 未完成(结果, 初始化语言知识状态::读回未完成,
            "知识完整读取未完成；状态=" + std::to_string(static_cast<int>(读回.状态)) + "；" + 读回.诊断说明);
    }
    const auto& 信息 = *读回.信息;
    if (读回.发布种类 || 读回.已发生定义身份 || !有效(信息.节点)
        || !有效(信息.目标节点) || !有效(信息.结构节点)
        || 信息.定义 != *项.定稿
        || std::count(信息.来源组.begin(), 信息.来源组.end(), 必需来源) != 1)
        return 未完成(结果, 初始化语言知识状态::读回未完成, "知识定稿、组成身份或完整来源关系读回不一致");
    return true;
}

template<bool 只读, class 语言服务类型, class 词服务类型>
初始化语言知识结果 处理最小语言知识(const 初始化语言知识请求& 请求,
    语言服务类型& 语言服务, 词服务类型& 词服务) {
    初始化知识草稿组 草稿;
    auto 结果 = 解码及预检语言知识种子(请求, 草稿);
    if (结果.工程控制 != 初始化语言知识工程控制::已完成
        || 结果.状态 != 初始化语言知识状态::已完成) return 结果;
    // 这只是解码阶段完成；任何后续失败均记录真实阶段，不对已发生步骤作回滚声明。
    结果.状态.reset();
    结果.阶段 = 初始化语言知识阶段::结构初始化;
    if constexpr (!只读) {
        const auto 状态 = 语言服务.初始化语言知识结构();
        if (状态 != 新语言知识状态::已完成) {
            未完成(结果, 初始化语言知识状态::知识未完成,
                "语言知识结构初始化未完成；状态=" + std::to_string(static_cast<int>(状态)));
            return 结果;
        }
    }
    if (!核验初始化知识语言(请求, 语言服务, 结果)) return 结果;

    结果.阶段 = 初始化语言知识阶段::功能词处理;
    std::vector<新词条信息> 实际词条组;
    for (std::size_t i = 0; i < 结果.词项组.size(); ++i) {
        结果.当前项 = i;
        auto& 项 = 结果.词项组[i];
        if constexpr (!只读) {
            项.发布 = 词服务.建立或取得词条({请求.语言节点, 请求.规范化合同节点, 项.词面, {}});
            if ((项.发布->状态 != 新词条建立状态::已建立 && 项.发布->状态 != 新词条建立状态::已复用)
                || !项.发布->词条节点 || !有效(*项.发布->词条节点)) {
                未完成(结果, 初始化语言知识状态::词条未完成,
                    "功能词发布未完成；状态=" + std::to_string(static_cast<int>(项.发布->状态)));
                return 结果;
            }
        }
        项.读回 = 词服务.按规范化词面查询(请求.语言节点, 请求.规范化合同节点, 项.词面);
        if (项.读回->状态 != 新词条查询状态::已找到 || !项.读回->信息) {
            未完成(结果, 初始化语言知识状态::词条未完成,
                "功能词查询未完成；状态=" + std::to_string(static_cast<int>(项.读回->状态)));
            return 结果;
        }
        const auto 查询 = *项.读回;
        项.读回 = 词服务.获取词条(查询.信息->节点);
        const auto& 正向 = *项.读回;
        if (正向.状态 != 新词条查询状态::已找到 || !正向.信息) {
            未完成(结果, 初始化语言知识状态::读回未完成,
                "功能词身份读取未完成；状态=" + std::to_string(static_cast<int>(正向.状态)));
            return 结果;
        }
        if (!有效(正向.信息->节点) || *正向.信息 != *查询.信息
            || 正向.信息->语言节点 != 请求.语言节点
            || 正向.信息->规范化合同节点 != 请求.规范化合同节点
            || 正向.信息->规范化词面 != 项.词面
            || (项.发布 && 项.发布->词条节点 != 正向.信息->节点)) {
            未完成(结果, 初始化语言知识状态::读回未完成, "功能词正式身份及词面正反向读回不一致");
            return 结果;
        }
        实际词条组.push_back(*正向.信息);
    }
    结果.当前项.reset();
    // 所有正式词条确认后，才能形成携带稳定编码的公开定义。
    for (std::size_t i = 0; i < 草稿.知识组.size(); ++i)
        结果.知识项组[i].定稿 = 绑定知识正式词条(草稿.知识组[i], 请求.语言节点, 实际词条组);

    结果.阶段 = 初始化语言知识阶段::来源处理;
    const 新语言知识来源请求 来源请求{
        新语言知识来源种类::经确认先天定义, 请求.语言节点, 草稿.固定原文};
    if constexpr (!只读) {
        结果.来源发布 = 语言服务.建立或取得知识先天来源(来源请求);
        if (结果.来源发布->状态 != 新语言知识状态::已完成 || !结果.来源发布->信息) {
            未完成(结果, 初始化语言知识状态::来源未完成,
                "先天来源发布未完成；状态=" + std::to_string(static_cast<int>(结果.来源发布->状态)));
            return 结果;
        }
    }
    结果.来源读回 = 语言服务.查询知识先天来源(来源请求);
    if (结果.来源读回->状态 != 新语言知识状态::已完成 || !结果.来源读回->信息) {
        未完成(结果, 初始化语言知识状态::来源未完成,
            "先天来源查询未完成；状态=" + std::to_string(static_cast<int>(结果.来源读回->状态)));
        return 结果;
    }
    const auto 来源查询 = *结果.来源读回;
    const auto 来源身份 = 来源查询.信息->节点;
    结果.来源读回 = 语言服务.获取知识先天来源(来源身份);
    const auto& 来源正向 = *结果.来源读回;
    const auto 来源相符 = [&](const 新语言知识来源信息& 来源) {
        return 有效(来源.节点) && 来源.节点 == 来源身份 && 来源.种类 == 来源请求.种类
            && 来源.语言节点 == 来源请求.语言节点 && 来源.固定原文 == 来源请求.固定原文;
    };
    if (来源正向.状态 != 新语言知识状态::已完成 || !来源正向.信息) {
        未完成(结果, 初始化语言知识状态::读回未完成,
            "先天来源身份读取未完成；状态=" + std::to_string(static_cast<int>(来源正向.状态)));
        return 结果;
    }
    if (!来源相符(*来源正向.信息) || !来源相符(*来源查询.信息)
        || 来源正向.发布种类 || 来源查询.发布种类
        || (结果.来源发布 && !来源相符(*结果.来源发布->信息))) {
        未完成(结果, 初始化语言知识状态::读回未完成, "先天来源完整原文及身份正反向读回不一致");
        return 结果;
    }
    for (std::size_t i = 0; i < 结果.知识项组.size(); ++i) {
        结果.当前项 = i;
        auto& 项 = 结果.知识项组[i];
        const 新语言知识来源绑定 来源{来源身份, 项.起始标量, 项.结束标量};
        if constexpr (!只读) {
            结果.阶段 = 初始化语言知识阶段::知识处理;
            项.发布 = 语言服务.建立或取得语言知识({*项.定稿, {来源}}, 词服务);
            if (项.发布->状态 != 新语言知识状态::已完成 || !项.发布->信息
                || !项.发布->发布种类 || 项.发布->已发生定义身份 != 项.发布->信息->节点) {
                未完成(结果, 初始化语言知识状态::知识未完成,
                    "知识发布未完成；状态=" + std::to_string(static_cast<int>(项.发布->状态)) + "；" + 项.发布->诊断说明);
                return 结果;
            }
        }
        结果.阶段 = 初始化语言知识阶段::完整读回;
        项.读回 = 语言服务.查询语言知识(*项.定稿, 词服务);
        if (!核验知识完整读回(项, 来源, *项.读回, 结果)) return 结果;
        const auto 知识身份 = 项.读回->信息->节点;
        if (项.发布 && 项.发布->信息->节点 != 知识身份) {
            未完成(结果, 初始化语言知识状态::读回未完成, "知识发布和完整定义查询身份不一致");
            return 结果;
        }
        项.读回 = 语言服务.获取语言知识(知识身份, 词服务);
        if (!核验知识完整读回(项, 来源, *项.读回, 结果)) return 结果;
        if (项.读回->信息->节点 != 知识身份) {
            未完成(结果, 初始化语言知识状态::读回未完成, "知识身份正向读取漂移");
            return 结果;
        }
    }
    结果.当前项.reset();
    结果.阶段 = 初始化语言知识阶段::完成;
    结果.状态 = 初始化语言知识状态::已完成;
    return 结果;
}

