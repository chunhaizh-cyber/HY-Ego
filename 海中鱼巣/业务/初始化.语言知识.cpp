bool 读取非负标准I64(std::string_view 词, std::int64_t& 值) noexcept {
    if (词.empty() || (词.size() > 1 && 词.front() == '0')) return false;
    for (const auto 字节 : 词) if (字节 < '0' || 字节 > '9') return false;
    const auto 结果 = std::from_chars(词.data(), 词.data() + 词.size(), 值);
    return 结果.ec == std::errc{} && 结果.ptr == 词.data() + 词.size() && 值 >= 0;
}

// 此处只解码有限元格式名字，不依据知识标签补目标或规则结构。
template<class 枚举>
std::optional<枚举> 读取元枚举(std::string_view 词,
    std::initializer_list<std::pair<std::string_view, 枚举>> 表) {
    for (const auto& [名称, 值] : 表) if (词 == 名称) return 值;
    return std::nullopt;
}

using 图角色键 = std::pair<std::int64_t, std::int64_t>;

std::vector<角色类别> 规范草稿类别(std::vector<角色类别> 类别组) {
    for (auto& 类别 : 类别组)
        if (类别 == 角色类别::I64标量) 类别 = 角色类别::十进制整数;
    std::sort(类别组.begin(), 类别组.end());
    return 类别组;
}

bool 草稿角色相容(const 新语言知识角色定义& 左, const 新语言知识角色定义& 右) {
    return 左.种类 == 右.种类 && 左.数量 == 右.数量
        && 左.必要约束组.size() == 1 && 右.必要约束组.size() == 1
        && 规范草稿类别(左.必要约束组.front().允许类别组)
            == 规范草稿类别(右.必要约束组.front().允许类别组);
}

// 仅对本批AST作值式投影，不创建正式知识或世界节点。
新语言知识含义图 形成草稿含义图(const 初始化知识草稿& 草稿) {
    if (草稿.目标.含义图) return *草稿.目标.含义图;
    const auto& 原 = 草稿.目标.含义组.front();
    新语言知识含义图 图{1, {}};
    新语言图含义节点 根{1, 原.操作, 原.作用域, 草稿.目标.角色组,
        原.参数组, 原.特征值分支, 原.确认范围, {}, {}};
    if (原.被询含义) {
        const auto& 子 = *原.被询含义;
        图.节点组.push_back({2, 子.操作, 子.作用域, 草稿.目标.角色组,
            子.参数组, 子.特征值分支, {}, {}, {}});
        根.角色组 = {{0, 角色种类::子含义引用, 新语言知识角色数量::单项,
            {{0, {角色类别::子含义}}}}};
        根.参数组 = {{参数角色::被询内容, 0}};
        根.子含义组 = {{0, 2, 新语言子含义用途::被询内容, {}}};
    }
    图.节点组.push_back(std::move(根));
    return 图;
}

bool 核验并规范化图草稿(初始化知识草稿& 草稿, std::string& 诊断) {
    const auto 拒绝 = [&](const char* 原因) { 诊断 = 原因; return false; };
    auto& 目标 = 草稿.目标;
    if (!目标.含义组.empty() || !目标.角色组.empty() || !目标.适用条件组.empty()
        || 草稿.有序项组.empty()) return 拒绝("图旧载荷混写或图表达为空");
    auto& 图 = *目标.含义图;
    std::map<std::int64_t, 新语言图含义节点*> 节点表;
    std::map<图角色键, const 新语言知识角色定义*> 角色表;
    for (auto& 节点 : 图.节点组) {
        if (节点.局部编号 < 0 || !节点表.emplace(节点.局部编号, &节点).second
            || 节点.作用域 < 新语言知识作用域::普通陈述
            || 节点.作用域 > 新语言知识作用域::需求目标范围)
            return 拒绝("图节点编号、作用域非法或重复");
        std::sort(节点.角色组.begin(), 节点.角色组.end(),
            [](const auto& 左, const auto& 右) { return 左.局部编号 < 右.局部编号; });
        for (auto& 角色 : 节点.角色组) {
            if (角色.局部编号 < 0 || 角色.数量 != 新语言知识角色数量::单项
                || !角色表.emplace(图角色键{节点.局部编号, 角色.局部编号}, &角色).second
                || 角色.必要约束组.size() != 1) return 拒绝("图角色重复或数量约束非法");
            auto& 约束 = 角色.必要约束组.front();
            if (约束.被约束角色 != 角色.局部编号 || 约束.允许类别组.size() != 1)
                return 拒绝("图角色必须具有唯一自约束");
            const auto 类别 = 约束.允许类别组.front();
            if (!((角色.种类 == 角色种类::领域对象引用 && (类别 == 角色类别::存在||类别==角色类别::正式信息节点))
                || (角色.种类 == 角色种类::特征类型引用 && (类别 == 角色类别::I64标量特征类型||类别==角色类别::正式特征类型))
                || (角色.种类 == 角色种类::准确值 && 类别 == 角色类别::十进制整数)
                || (角色.种类 == 角色种类::查询变量 && (类别 == 角色类别::查询特征值 || 类别 == 角色类别::查询存在))
                || (角色.种类 == 角色种类::子含义引用 && 类别 == 角色类别::子含义)))
                return 拒绝("图角色种类与类别不相容");
        }
        std::map<参数角色, std::int64_t> 参数表;
        std::set<std::int64_t> 参数角色组;
        for (const auto& 参数 : 节点.参数组)
            if (!角色表.contains({节点.局部编号, 参数.规则角色})
                || !参数表.emplace(参数.参数, 参数.规则角色).second
                || !参数角色组.insert(参数.规则角色).second)
                return 拒绝("图参数重复、悬空或角色复用");
        std::vector<std::pair<参数角色, 角色种类>> 签名;
        switch (节点.操作) {
        case 含义操作::特征描述:
            if (节点.特征值分支 && 节点.特征值分支 != 值分支::准确值) return 拒绝("H单值必须是准确值或待求");
            签名 = {{参数角色::主体, 角色种类::领域对象引用},
                {参数角色::特征类型, 角色种类::特征类型引用}, {参数角色::特征值, 节点.特征值分支 ? 角色种类::准确值:角色种类::查询变量}};
            break;
        case 含义操作::特征区间描述:
            签名 = {{参数角色::主体, 角色种类::领域对象引用},
                {参数角色::特征类型, 角色种类::特征类型引用}, {参数角色::下界, 角色种类::准确值},
                {参数角色::上界, 角色种类::准确值}};
            break;
        case 含义操作::特征方向描述:
            if (节点.方向 != 新语言知识特征方向::增加 && 节点.方向 != 新语言知识特征方向::减少)
                return 拒绝("H方向必须明确增加或减少");
            签名 = {{参数角色::主体, 角色种类::领域对象引用},
                {参数角色::特征类型, 角色种类::特征类型引用}};
            break;
        case 含义操作::需求描述:
            // 最小需求句式“Y要X”与目标栏问题：需求描述直接带目标存在（陈述为存在，提问为待求），不带目标子含义。
            if (参数表.contains(参数角色::目标存在))
                签名 = {{参数角色::主体, 角色种类::领域对象引用}, {参数角色::目标存在,
                    节点.作用域 == 新语言知识作用域::提问范围 ? 角色种类::查询变量 : 角色种类::领域对象引用}};
            else 签名 = {{参数角色::主体, 角色种类::领域对象引用}, {参数角色::目标内容, 角色种类::子含义引用}};
            break;
        case 含义操作::行动请求:
            if (节点.作用域 != 新语言知识作用域::请求范围) return 拒绝("行动请求必须使用请求范围");
            签名 = {{参数角色::受请求者, 角色种类::领域对象引用}, {参数角色::目标内容, 角色种类::子含义引用}};
            break;
        case 含义操作::信息请求:
            if (节点.确认范围 != 新语言知识确认范围::主张成立与否&&节点.确认范围!=新语言知识确认范围::填项内容) return 拒绝("图询问范围未支持");
            签名 = {{参数角色::被询内容, 角色种类::子含义引用}};
            break;
        case 含义操作::招呼发起: case 含义操作::招呼维持: case 含义操作::招呼结束:
            if (节点.作用域 != 新语言知识作用域::普通陈述) return 拒绝("招呼必须使用普通陈述作用域");
            break; // 零角色、零参数、无子含义。
        default: return 拒绝("图操作不属于本叶闭集");
        }
        if (参数表.size() != 签名.size() || 节点.角色组.size() != 签名.size())
            return 拒绝("图必要参数或角色数量不符");
        for (const auto& [参数, 种类] : 签名)
            if (!参数表.contains(参数) || 角色表.at({节点.局部编号, 参数表.at(参数)})->种类 != 种类)
                return 拒绝("图必要参数签名或类型不符");
        if (节点.操作 == 含义操作::行动请求
            && 角色表.at({节点.局部编号, 参数表.at(参数角色::受请求者)})->必要约束组.front().允许类别组
                != std::vector<角色类别>{角色类别::存在}) return 拒绝("行动请求受请求者必须为存在");
        if (节点.特征值分支.has_value() != (节点.操作 == 含义操作::特征描述&&角色表.at({节点.局部编号,参数表.at(参数角色::特征值)})->种类!=角色种类::查询变量)
            || 节点.确认范围.has_value() != (节点.操作 == 含义操作::信息请求)
            || 节点.方向.has_value() != (节点.操作 == 含义操作::特征方向描述))
            return 拒绝("图含义分支混用");
        const bool 目标存在需求 = 节点.操作 == 含义操作::需求描述 && 参数表.contains(参数角色::目标存在);
        if (目标存在需求 && (角色表.at({节点.局部编号, 参数表.at(参数角色::主体)})->必要约束组.front().允许类别组
                != std::vector<角色类别>{角色类别::存在}
            || 角色表.at({节点.局部编号, 参数表.at(参数角色::目标存在)})->必要约束组.front().允许类别组
                != std::vector<角色类别>{节点.作用域 == 新语言知识作用域::提问范围 ? 角色类别::查询存在 : 角色类别::存在}))
            return 拒绝("目标存在需求的主体或目标类别不符");
        if (!目标存在需求 && (节点.操作 == 含义操作::需求描述 || 节点.操作 == 含义操作::信息请求 || 节点.操作 == 含义操作::行动请求)
            ? 节点.子含义组.size() != 1 : !节点.子含义组.empty())
            return 拒绝("图子边数量与操作不符");
        if (!节点.子含义组.empty()) {
            const auto& 边 = 节点.子含义组.front();
            const auto 参数 = 节点.操作 == 含义操作::信息请求 ? 参数角色::被询内容 : 参数角色::目标内容;
            const auto 用途 = 节点.操作 == 含义操作::行动请求 ? 新语言子含义用途::期望目标
                : 节点.操作 == 含义操作::需求描述 ? 新语言子含义用途::需求目标 : 新语言子含义用途::被询内容;
            if (边.本节点角色编号 != 参数表.at(参数) || 边.用途 != 用途)
                return 拒绝("图子边用途或角色与操作不符");
        }
        std::sort(节点.参数组.begin(), 节点.参数组.end(),
            [](const auto& 左, const auto& 右) { return 左.参数 < 右.参数; });
    }
    if (!节点表.contains(图.根含义编号)) return 拒绝("图根不存在");
    std::map<std::int64_t, int> 颜色;
    const auto 访问 = [&](auto&& 自身, std::int64_t 编号) -> bool {
        if (颜色[编号] == 1) return false;
        if (颜色[编号] == 2) return true;
        颜色[编号] = 1;
        const auto& 节点 = *节点表.at(编号);
        for (const auto& 边 : 节点.子含义组) {
            if (!节点表.contains(边.子含义编号)) return false;
            const auto& 子 = *节点表.at(边.子含义编号);
            if (边.用途 == 新语言子含义用途::需求目标) {
                if (子.作用域 != 新语言知识作用域::需求目标范围
                    || (子.操作 != 含义操作::特征描述 && 子.操作 != 含义操作::特征区间描述
                        && 子.操作 != 含义操作::特征方向描述)) return false;
            } else if (边.用途 == 新语言子含义用途::期望目标) {
                if (节点.操作 != 含义操作::行动请求 || 子.操作 != 含义操作::需求描述
                    || 子.作用域 != 新语言知识作用域::需求目标范围) return false;
            } else if (子.作用域 != 新语言知识作用域::提问范围
                ||(节点.确认范围==新语言知识确认范围::填项内容
                    ? !((子.操作==含义操作::特征描述&&!子.特征值分支.has_value())
                        ||(子.操作==含义操作::需求描述&&std::any_of(子.参数组.begin(),子.参数组.end(),[](const auto& 参数){return 参数.参数==参数角色::目标存在;})))
                    :子.操作!=含义操作::需求描述)) return false;
            std::set<图角色键> 已映射;
            for (const auto& 映射 : 边.显式映射组) {
                const 图角色键 源{映射.来源.含义编号, 映射.来源.角色编号};
                const 图角色键 末{映射.目标.含义编号, 映射.目标.角色编号};
                if (!角色表.contains(源) || !角色表.contains(末) || !已映射.insert(末).second
                    || !草稿角色相容(*角色表.at(源), *角色表.at(末))) return false;
            }
            if (!自身(自身, 边.子含义编号)) return false;
        }
        颜色[编号] = 2;
        return true;
    };
    if (!访问(访问, 图.根含义编号) || 颜色.size() != 节点表.size()) return 拒绝("图环、悬空、孤立或子边不相容");
    const auto& 根 = *节点表.at(图.根含义编号);
    if ((目标.目的 == 新语言知识表达目的::陈述 && 根.作用域 != 新语言知识作用域::普通陈述)
        || (目标.目的 == 新语言知识表达目的::提问 && 根.作用域 != 新语言知识作用域::提问范围)
        || ((目标.目的 == 新语言知识表达目的::提问) != (根.操作 == 含义操作::信息请求))
        || ((目标.目的 == 新语言知识表达目的::提出需求) != (根.操作 == 含义操作::行动请求))
        || (目标.目的 == 新语言知识表达目的::提出需求 && 根.作用域 != 新语言知识作用域::请求范围)
        || ((目标.目的 == 新语言知识表达目的::招呼) != 新语言含义操作是招呼(根.操作))
        || (目标.目的 == 新语言知识表达目的::招呼 && (图.节点组.size() != 1
            || 根.作用域 != 新语言知识作用域::普通陈述)))
        return 拒绝("图目的、根操作或作用域不符");
    std::set<图角色键> 已表达角色;
    for (std::size_t i = 0; i < 草稿.有序项组.size(); ++i) {
        auto& 项 = 草稿.有序项组[i];
        项.局部编号 = static_cast<std::int64_t>(i);
        if (const auto* 角色 = std::get_if<新语言知识图角色表达项>(&项.载荷)) {
            const 图角色键 键{角色->角色.含义编号, 角色->角色.角色编号};
            if (!角色表.contains(键) || 角色表.at(键)->种类 == 角色种类::子含义引用)
                return 拒绝("图表达角色悬空或不是叶角色");
            const bool 数值 = 角色表.at(键)->种类 == 角色种类::准确值;
            if ((数值 && 角色->方式 != 表达方式::类型化字面值)
                || (!数值 && 角色->方式 != 表达方式::名称表达 && 角色->方式 != 表达方式::明确对象描述
                    &&角色->方式!=表达方式::带概念指代&&角色->方式!=表达方式::查询变量词面
                    &&角色->方式!=表达方式::已消解指代))
                return 拒绝("图角色表达方式与类型不符");
            if (角色->方式 == 表达方式::已消解指代) {
                const auto 材料 = 草稿.图词面组.find(项.局部编号);
                const auto& 所在 = *节点表.at(角色->角色.含义编号);
                // 最小需求句式与目标栏问题：目标存在需求的需求主体可由“我”（SPEAKER）或“你”（ADDRESSEE）表达。
                const bool 需求主体 = 所在.操作 == 含义操作::需求描述
                    && std::any_of(所在.参数组.begin(), 所在.参数组.end(), [&](const auto& 参数) {
                        return 参数.参数 == 参数角色::主体 && 参数.规则角色 == 角色->角色.角色编号; })
                    && std::any_of(所在.参数组.begin(), 所在.参数组.end(), [](const auto& 参数) { return 参数.参数 == 参数角色::目标存在; });
                if (需求主体) {
                    if (角色表.at(键)->必要约束组.front().允许类别组 != std::vector<角色类别>{角色类别::存在}
                        || 材料 == 草稿.图词面组.end()
                        || (材料->second.指代语义键 != "ADDRESSEE" && 材料->second.指代语义键 != "SPEAKER"))
                        return 拒绝("需求主体指代表达须为说话者或受话者存在角色");
                } else if (角色表.at(键)->种类 != 角色种类::领域对象引用
                    || 角色表.at(键)->必要约束组.front().允许类别组 != std::vector<角色类别>{角色类别::存在}
                    || 材料 == 草稿.图词面组.end() || 材料->second.指代语义键 != "ADDRESSEE"
                    || 根.操作 != 含义操作::行动请求 || 角色->角色.含义编号 != 图.根含义编号
                    || std::none_of(根.参数组.begin(), 根.参数组.end(), [&](const auto& 参数) {
                        return 参数.参数 == 参数角色::受请求者 && 参数.规则角色 == 角色->角色.角色编号;
                    })) return 拒绝("行动请求指代表达未对应唯一受请求者存在角色");
            }
            已表达角色.emplace(角色->角色.含义编号,角色->角色.角色编号);
        } else if (const auto* 子 = std::get_if<初始化图子规则草稿>(&项.载荷)) {
            if (!节点表.contains(子->子角色.含义编号) || 子->标签组.empty()) return 拒绝("图子规则无节点或依赖");
            const auto& 边组 = 节点表.at(子->子角色.含义编号)->子含义组;
            if (std::none_of(边组.begin(), 边组.end(), [&](const auto& 边) { return 边.本节点角色编号 == 子->子角色.角色编号; }))
                return 拒绝("图子规则没有对应子边");
            std::set<std::string> 标签;
            for (const auto& 值 : 子->标签组) if (!标签.insert(值).second) return 拒绝("图子规则依赖重复");
            已表达角色.emplace(子->子角色.含义编号,子->子角色.角色编号);
        } else if (!std::holds_alternative<std::string>(项.载荷)) return 拒绝("图表达混入旧结构项");
    }
    const auto 完整表达=[&](auto&& 自身,std::int64_t 编号)->bool {
        const auto& 节点=*节点表.at(编号);
        for(const auto& 角色:节点.角色组)if(!已表达角色.contains({编号,角色.局部编号})) {
            const auto 边=std::find_if(节点.子含义组.begin(),节点.子含义组.end(),[&](const auto& 项){return 项.本节点角色编号==角色.局部编号;});
            if(边==节点.子含义组.end()||!自身(自身,边->子含义编号))return false;
        }
        return true;
    };
    if(!完整表达(完整表达,图.根含义编号))return 拒绝("图表达缺少必要角色或子含义");
    std::sort(图.节点组.begin(), 图.节点组.end(),
        [](const auto& 左, const auto& 右) { return 左.局部编号 < 右.局部编号; });
    return true;
}

bool 核验并规范化知识草稿(初始化知识草稿& 草稿, std::string& 诊断) {
    const auto 拒绝 = [&](const char* 原因) { 诊断 = 原因; return false; };
    auto& 目标 = 草稿.目标;
    if(目标.含义图) {
        return 核验并规范化图草稿(草稿, 诊断);
    }
    if ((目标.目的 != 新语言知识表达目的::陈述
            && 目标.目的 != 新语言知识表达目的::提问
            && 目标.目的 != 新语言知识表达目的::提出需求)
        || !目标.适用条件组.empty()
        || 目标.含义组.size() != 1 || 草稿.有序项组.empty())
        return 拒绝("目标、单含义或有序结构不完整");
    if (目标.目的 != 新语言知识表达目的::提出需求 && 目标.角色组.empty())
        return 拒绝("目标、单含义或有序结构不完整");
    std::map<std::int64_t, 新语言知识角色定义*> 角色表;
    for (auto& 角色 : 目标.角色组) {
        if (角色.局部编号 < 0 || !角色表.emplace(角色.局部编号, &角色).second
            || 角色.数量 != 新语言知识角色数量::单项 || 角色.必要约束组.size() != 1)
            return 拒绝("角色编号重复、数量或约束不合法");
        auto& 约束 = 角色.必要约束组.front();
        if (约束.被约束角色 != 角色.局部编号 || 约束.允许类别组.empty())
            return 拒绝("角色类别约束未明确指向自己");
        auto& 类别组 = 约束.允许类别组;
        std::sort(类别组.begin(), 类别组.end());
        类别组.erase(std::unique(类别组.begin(), 类别组.end()), 类别组.end());
        const auto 仅为 = [&](角色类别 类别) {
            return 类别组.size() == 1 && 类别组.front() == 类别;
        };
        switch (角色.种类) {
        case 角色种类::领域对象引用:
            if (!仅为(角色类别::存在)) return 拒绝("存在角色类别不相容");
            break;
        case 角色种类::概念引用:
            for (const auto 类别 : 类别组)
                if (类别 != 角色类别::存在概念 && 类别 != 角色类别::特征概念)
                    return 拒绝("概念角色类别不相容");
            break;
        case 角色种类::特征类型引用:
            if (!仅为(角色类别::正式特征类型) && !仅为(角色类别::I64标量特征类型))
                return 拒绝("特征类型角色类别不相容");
            break;
        case 角色种类::准确值:
            if (!仅为(角色类别::I64标量)) return 拒绝("准确值角色不是I64标量");
            break;
        case 角色种类::查询变量:
            if (!仅为(角色类别::查询特征值)) return 拒绝("查询变量须约束为查询特征值");
            break;
        default: return 拒绝("角色种类未支持");
        }
    }
    auto& 含义 = 目标.含义组.front();
    if (目标.目的 == 新语言知识表达目的::提问
        || 目标.目的 == 新语言知识表达目的::提出需求) {
        if (含义.局部编号 != 0 || !含义.被询含义) return 拒绝("提问或提出需求缺少子含义");
        auto& 子 = *含义.被询含义;
        std::sort(子.参数组.begin(), 子.参数组.end(),
            [](const auto& 左, const auto& 右) { return 左.参数 < 右.参数; });
        std::sort(含义.参数组.begin(), 含义.参数组.end(),
            [](const auto& 左, const auto& 右) { return 左.参数 < 右.参数; });
        std::set<参数角色> 外参数组, 子参数组;
        for (const auto& 参数 : 含义.参数组)
            if (!角色表.contains(参数.规则角色) || !外参数组.insert(参数.参数).second)
                return 拒绝("外层参数角色悬空或参数重复");
        for (const auto& 参数 : 子.参数组)
            if (!角色表.contains(参数.规则角色) || !子参数组.insert(参数.参数).second)
                return 拒绝("子参数角色悬空或参数重复");
        std::set<std::int64_t> 结构项编号组;
        for (auto& 项 : 草稿.有序项组) {
            if (项.局部编号 < 0 || !结构项编号组.insert(项.局部编号).second)
                return 拒绝("结构项编号不合法或重复");
            if (const auto* 词面 = std::get_if<std::string>(&项.载荷)) {
                if (!新_语言类::严格UTF8字节串有效(*词面)) return 拒绝("固定词面不合法");
            } else if (const auto* 表达 = std::get_if<新语言知识角色表达项>(&项.载荷)) {
                if (!角色表.contains(表达->规则角色)) return 拒绝("结构角色悬空");
                const auto 种类 = 角色表.at(表达->规则角色)->种类;
                if (!((表达->方式 == 表达方式::明确对象描述 && 种类 == 角色种类::领域对象引用)
                    || (表达->方式 == 表达方式::名称表达
                        && (种类 == 角色种类::概念引用 || 种类 == 角色种类::特征类型引用))
                    || (表达->方式 == 表达方式::类型化字面值 && 种类 == 角色种类::准确值)))
                    return 拒绝("提问角色表达方式不相容");
            } else if (const auto* 指代 = std::get_if<初始化指代角色草稿>(&项.载荷)) {
                if (!角色表.contains(指代->规则角色) || 指代->名称 != "我")
                    return 拒绝("指代角色不合法");
                if (角色表.at(指代->规则角色)->种类 != 角色种类::领域对象引用)
                    return 拒绝("指代表达须指向存在角色");
            } else if (!std::holds_alternative<初始化子规则草稿>(项.载荷)) {
                return 拒绝("提问结构项载荷不完整");
            }
        }
        for (std::size_t i = 0; i < 草稿.有序项组.size(); ++i)
            草稿.有序项组[i].局部编号 = static_cast<std::int64_t>(i);
        子.局部编号 = 1;
        std::sort(目标.角色组.begin(), 目标.角色组.end(),
            [](const auto& 左, const auto& 右) { return 左.局部编号 < 右.局部编号; });
        if (目标.目的 == 新语言知识表达目的::提出需求) {
            if (含义.操作 != 含义操作::需求描述
                || 含义.作用域 != 新语言知识作用域::请求范围
                || 含义.确认范围 || 含义.特征值分支
                || 含义.参数组.size() != 1
                || 含义.参数组[0].参数 != 参数角色::主体
                || 角色表.at(含义.参数组[0].规则角色)->种类 != 角色种类::领域对象引用
                || 子.作用域 != 新语言知识作用域::请求范围
                || 草稿.有序项组.size() != 3)
                return 拒绝("S11提出需求目标不合法");
            const auto* 角色项 = std::get_if<新语言知识角色表达项>(&草稿.有序项组[0].载荷);
            const auto* 词 = std::get_if<std::string>(&草稿.有序项组[1].载荷);
            const auto* 子规则 = std::get_if<初始化子规则草稿>(&草稿.有序项组[2].载荷);
            if (!角色项 || !词 || !子规则
                || 角色项->规则角色 != 含义.参数组[0].规则角色
                || 角色项->方式 != 表达方式::明确对象描述)
                return 拒绝("S11结构不合法");
            return true;
        }
        if (含义.操作 != 含义操作::信息请求
            || 含义.作用域 != 新语言知识作用域::提问范围
            || 含义.特征值分支 || !含义.确认范围)
            return 拒绝("提问外层含义不合法");
        if (*含义.确认范围 == 新语言知识确认范围::主张成立与否
            && 子.操作 == 含义操作::概念归类) {
            if (角色表.size() != 2 || !角色表.contains(0) || !角色表.contains(1)
                || 草稿.有序项组.size() != 2 || !含义.参数组.empty()
                || 子.参数组.size() != 2
                || 子.参数组[0] != 新语言知识角色参数{参数角色::主体, 0}
                || 子.参数组[1] != 新语言知识角色参数{参数角色::归类概念, 1}
                || 子.作用域 != 新语言知识作用域::提问范围)
                return 拒绝("S09外层目标不合法");
            for (const auto& [编号, 角色] : 角色表)
                if (角色->种类 != 角色种类::概念引用
                    || 角色->必要约束组.front().允许类别组
                        != std::vector{角色类别::存在概念, 角色类别::特征概念})
                    return 拒绝("S09角色类型不合法");
            const auto* 子规则 = std::get_if<初始化子规则草稿>(&草稿.有序项组[0].载荷);
            const auto* 词 = std::get_if<std::string>(&草稿.有序项组[1].载荷);
            if (!子规则 || !词 || 子规则->映射组.size() != 2
                || 子规则->映射组[0] != 新语言知识子规则映射{0, 0}
                || 子规则->映射组[1] != 新语言知识子规则映射{1, 1})
                return 拒绝("S09子规则、映射或固定词不合法");
            return true;
        }
        if (*含义.确认范围 == 新语言知识确认范围::主张成立与否
            && 子.操作 == 含义操作::需求描述) {
            if (草稿.有序项组.size() != 2 || !含义.参数组.empty()
                || 子.作用域 != 新语言知识作用域::提问范围)
                return 拒绝("需求确认外层不合法");
            const auto* 子规则 = std::get_if<初始化子规则草稿>(&草稿.有序项组[0].载荷);
            const auto* 词 = std::get_if<std::string>(&草稿.有序项组[1].载荷);
            if (!子规则 || !词) return 拒绝("需求确认结构须为子规则后接吗");
            return true;
        }
        if (*含义.确认范围 == 新语言知识确认范围::填项内容
            && 子.操作 == 含义操作::特征描述 && 含义.参数组.empty()
            && 草稿.有序项组.size() == 5 && 子.参数组.size() == 3) {
            if (子.作用域 != 新语言知识作用域::提问范围 || !子.特征值分支)
                return 拒绝("S10子含义不合法");
            if (子.参数组[0].参数 != 参数角色::主体
                || 子.参数组[1].参数 != 参数角色::特征类型
                || 子.参数组[2].参数 != 参数角色::特征值)
                return 拒绝("S10子参数签名不合法");
            if (角色表.at(子.参数组[0].规则角色)->种类 != 角色种类::领域对象引用
                || 角色表.at(子.参数组[1].规则角色)->种类 != 角色种类::特征类型引用
                || 角色表.at(子.参数组[2].规则角色)->种类 != 角色种类::查询变量)
                return 拒绝("S10角色种类不相容");
            const auto& 类别组 = 角色表.at(子.参数组[1].规则角色)->必要约束组.front().允许类别组;
            if ((*子.特征值分支 == 值分支::准确值 && 类别组 != std::vector{角色类别::I64标量特征类型})
                || (*子.特征值分支 == 值分支::概念条件 && 类别组 != std::vector{角色类别::正式特征类型}))
                return 拒绝("S10值分支与特征类型类别不相容");
            if (!std::holds_alternative<新语言知识角色表达项>(草稿.有序项组[0].载荷)
                || !std::holds_alternative<std::string>(草稿.有序项组[1].载荷)
                || !std::holds_alternative<新语言知识角色表达项>(草稿.有序项组[2].载荷)
                || !std::holds_alternative<std::string>(草稿.有序项组[3].载荷)
                || !std::holds_alternative<std::string>(草稿.有序项组[4].载荷))
                return 拒绝("S10结构项类别不合法");
            const auto& 主项 = std::get<新语言知识角色表达项>(草稿.有序项组[0].载荷);
            const auto& 类项 = std::get<新语言知识角色表达项>(草稿.有序项组[2].载荷);
            if (主项.规则角色 != 子.参数组[0].规则角色 || 主项.方式 != 表达方式::明确对象描述
                || 类项.规则角色 != 子.参数组[1].规则角色 || 类项.方式 != 表达方式::名称表达)
                return 拒绝("S10角色表达方向不合法");
            return true;
        }
        if (*含义.确认范围 == 新语言知识确认范围::填项内容
            && 含义.参数组.size() == 2 && 草稿.有序项组.size() >= 5) {
            if (含义.参数组[0].参数 != 参数角色::受询者
                || 含义.参数组[1].参数 != 参数角色::询求者
                || 子.参数组.size() < 2
                || 子.作用域 != 新语言知识作用域::提问范围)
                return 拒绝("S13外层参数不合法");
            if (!std::holds_alternative<std::string>(草稿.有序项组[0].载荷)
                || !std::holds_alternative<新语言知识角色表达项>(草稿.有序项组[1].载荷)
                || !std::holds_alternative<std::string>(草稿.有序项组[2].载荷)
                || !(std::holds_alternative<新语言知识角色表达项>(草稿.有序项组[3].载荷)
                    || std::holds_alternative<初始化指代角色草稿>(草稿.有序项组[3].载荷)))
                return 拒绝("S13结构前缀不合法");
            const auto& 受询 = std::get<新语言知识角色表达项>(草稿.有序项组[1].载荷);
            const auto* 询求 = std::get_if<初始化指代角色草稿>(&草稿.有序项组[3].载荷);
            if (受询.规则角色 != 含义.参数组[0].规则角色 || 受询.方式 != 表达方式::明确对象描述
                || !询求 || 询求->规则角色 != 含义.参数组[1].规则角色)
                return 拒绝("S13受询者或询求者表达不合法");
            if (!std::holds_alternative<初始化子规则草稿>(草稿.有序项组.back().载荷)
                && !(草稿.有序项组.size() == 5
                    && std::holds_alternative<std::string>(草稿.有序项组[4].载荷)))
                return 拒绝("S13查询内容结构不合法");
            return true;
        }
        return 拒绝("提问形状未支持");
    }
    if (含义.局部编号 < 0 || 含义.作用域 != 新语言知识作用域::普通陈述)
        return 拒绝("含义编号或作用域不合法");
    std::map<参数角色, 新语言知识角色定义*> 参数表;
    std::set<std::int64_t> 目标引用;
    for (const auto& 参数 : 含义.参数组) {
        const auto 角色 = 角色表.find(参数.规则角色);
        if (角色 == 角色表.end() || !参数表.emplace(参数.参数, 角色->second).second)
            return 拒绝("具名参数重复或悬空");
        目标引用.insert(参数.规则角色);
    }
    const auto 参数为 = [&](参数角色 参数, 角色种类 种类) {
        const auto 项 = 参数表.find(参数);
        return 项 != 参数表.end() && 项->second->种类 == 种类;
    };
    const auto 参数仅为 = [&](参数角色 参数, 角色类别 类别) {
        const auto 项 = 参数表.find(参数);
        return 项 != 参数表.end()
            && 项->second->必要约束组.front().允许类别组 == std::vector<角色类别>{类别};
    };
    switch (含义.操作) {
    case 含义操作::概念归类:
        if (含义.特征值分支 || 参数表.size() != 2
            || !参数为(参数角色::归类概念, 角色种类::概念引用))
            return 拒绝("概念归类参数不完整");
        if (参数为(参数角色::主体, 角色种类::领域对象引用)) {
            if (!参数仅为(参数角色::归类概念, 角色类别::存在概念))
                return 拒绝("存在只能归类到存在概念");
        } else if (参数为(参数角色::主体, 角色种类::概念引用)) {
            if (参数表.at(参数角色::主体)->必要约束组.front().允许类别组
                != 参数表.at(参数角色::归类概念)->必要约束组.front().允许类别组)
                return 拒绝("概念上下位角色类别集合必须相同");
        } else return 拒绝("概念归类主体不合法");
        break;
    case 含义操作::特征描述:
        if (参数表.size() != 3 || !参数为(参数角色::主体, 角色种类::领域对象引用)
            || !参数为(参数角色::特征类型, 角色种类::特征类型引用))
            return 拒绝("特征描述参数不完整");
        if (含义.特征值分支 == 值分支::准确值) {
            if (!参数为(参数角色::特征值, 角色种类::准确值)
                || !参数仅为(参数角色::特征类型, 角色类别::I64标量特征类型))
                return 拒绝("准确值与特征类型材料限制不相容");
        } else if (含义.特征值分支 == 值分支::概念条件) {
            if (!参数为(参数角色::特征值, 角色种类::概念引用)
                || !参数仅为(参数角色::特征值, 角色类别::特征概念))
                return 拒绝("特征概念条件角色不相容");
        } else return 拒绝("特征值分支未支持");
        break;
    case 含义操作::组成描述:
        if (含义.特征值分支 || 参数表.size() != 2
            || !参数为(参数角色::整体, 角色种类::领域对象引用)
            || !参数为(参数角色::部分, 角色种类::领域对象引用))
            return 拒绝("组成描述须显式声明整体与部分");
        break;
    default: return 拒绝("含义操作未支持");
    }
    std::set<std::int64_t> 项编号;
    std::map<std::int64_t, std::int64_t> 重编号;
    for (auto& 项 : 草稿.有序项组) {
        if (项.局部编号 < 0 || !项编号.insert(项.局部编号).second)
            return 拒绝("结构项编号重复或负数");
        if (const auto* 词面 = std::get_if<std::string>(&项.载荷)) {
            if (!新_语言类::严格UTF8字节串有效(*词面)) return 拒绝("固定词面不合法");
        } else if (std::holds_alternative<新语言知识角色表达项>(项.载荷)
            || std::holds_alternative<初始化指代角色草稿>(项.载荷)) {
            const auto* 指代 = std::get_if<初始化指代角色草稿>(&项.载荷);
            const auto* 表达 = std::get_if<新语言知识角色表达项>(&项.载荷);
            const auto 规则角色 = 指代 ? 指代->规则角色 : 表达->规则角色;
            const auto 角色 = 角色表.find(规则角色);
            if (角色 == 角色表.end()) return 拒绝("结构角色悬空");
            const auto 种类 = 角色->second->种类;
            const bool 相容 = (指代 && 指代->名称 == "我"
                    && 含义.操作 == 含义操作::概念归类
                    && 参数表.contains(参数角色::主体)
                    && 参数表.at(参数角色::主体) == 角色->second
                    && 种类 == 角色种类::领域对象引用)
                || (表达 && 表达->方式 == 表达方式::明确对象描述 && 种类 == 角色种类::领域对象引用)
                || (表达 && 表达->方式 == 表达方式::名称表达
                    && (种类 == 角色种类::概念引用 || 种类 == 角色种类::特征类型引用))
                || (表达 && 表达->方式 == 表达方式::类型化字面值 && 种类 == 角色种类::准确值);
            if (!相容) return 拒绝("角色表达方式不相容");
            if (!重编号.contains(规则角色))
                重编号.emplace(规则角色, static_cast<std::int64_t>(重编号.size()));
        } else return 拒绝("陈述知识结构项载荷不完整");
    }
    if (目标引用.size() != 角色表.size() || 重编号.size() != 角色表.size())
        return 拒绝("存在未被目标或结构实际引用的角色");
    for (auto& 角色 : 目标.角色组) {
        角色.局部编号 = 重编号.at(角色.局部编号);
        角色.必要约束组.front().被约束角色 = 角色.局部编号;
    }
    std::sort(目标.角色组.begin(), 目标.角色组.end(), [](const auto& 左, const auto& 右) {
        return 左.局部编号 < 右.局部编号;
    });
    含义.局部编号 = 0;
    for (auto& 参数 : 含义.参数组) 参数.规则角色 = 重编号.at(参数.规则角色);
    std::sort(含义.参数组.begin(), 含义.参数组.end(), [](const auto& 左, const auto& 右) {
        return 左.参数 < 右.参数;
    });
    for (std::size_t i = 0; i < 草稿.有序项组.size(); ++i) {
        auto& 项 = 草稿.有序项组[i];
        项.局部编号 = static_cast<std::int64_t>(i);
        if (auto* 表达 = std::get_if<新语言知识角色表达项>(&项.载荷))
            表达->规则角色 = 重编号.at(表达->规则角色);
        else if (auto* 指代 = std::get_if<初始化指代角色草稿>(&项.载荷))
            指代->规则角色 = 重编号.at(指代->规则角色);
    }
    return true;
}

bool 读图局部引用(std::string_view 原文,新语言局部角色引用& 引用) {
    const auto 点=原文.find('.');
    return 点!=std::string_view::npos&&读取非负标准I64(原文.substr(0,点),引用.含义编号)
        &&读取非负标准I64(原文.substr(点+1),引用.角色编号);
}
