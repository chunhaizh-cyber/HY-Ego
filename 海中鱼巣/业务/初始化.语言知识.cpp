初始化语言知识结果 初始化最小语言知识(const 初始化语言知识请求& 请求,
    新_语言类& 语言服务, 新_词类& 词服务,
    概念_存在类& 存在概念服务, 概念_名称关系类& 名称服务) {
    return 处理最小语言知识<false>(请求, 语言服务, 词服务,
        存在概念服务, 名称服务);
}

初始化语言知识结果 读取最小语言知识(const 初始化语言知识请求& 请求,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_存在类& 存在概念服务, const 概念_名称关系类& 名称服务) {
    return 处理最小语言知识<true>(请求, 语言服务, 词服务,
        存在概念服务, 名称服务);
}

