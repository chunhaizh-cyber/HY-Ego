void 记(特征当前值语言桥自检结果& r, std::string 标识, bool 通过,
    bool 合成, std::string 说明) {
    特征当前值语言桥自检条目 e;
    e.标识 = std::move(标识);
    e.通过 = 通过;
    e.合成夹具 = 合成;
    e.说明 = std::move(说明);
    if (通过) ++r.通过数; else ++r.失败数;
    r.条目组.push_back(std::move(e));
}

std::optional<新语言结构概念信息> 找结构概念(
    新_语言类& 语言, const std::string& 种子标识) {
    const auto 列表 = 语言.枚举全部结构概念();
    if (列表.状态 != 新语言知识状态::已完成) return std::nullopt;
    for (const auto& 项 : 列表.信息组)
        if (项.定义.种子标识 == 种子标识) return 项;
    return std::nullopt;
}

std::optional<新语言表达模式信息> 找首模式(
    新_语言类& 语言, const 新_词类& 词,
    稳定编码 语言节点, 稳定编码 结构概念) {
    const auto 列表 = 语言.枚举全部表达模式(语言节点, 词);
    if (列表.状态 != 新语言知识状态::已完成) return std::nullopt;
    for (const auto& 项 : 列表.信息组)
        if (项.结构概念节点 == 结构概念) return 项;
    return std::nullopt;
}

std::optional<稳定编码> 选I64有值特征(
    稳定编码 E, const 新_存在类& 存在, const 新_特征类& 特征,
    const 概念_特征类& 特征概念) {
    const auto 定位 = 存在.读取存在顶层特征定位保护(E);
    if (定位.状态 != 新存在顶层特征定位状态::已读取 || !定位.信息)
        return std::nullopt;
    for (const auto f : 定位.信息->顶层特征节点组) {
        const auto 完整 = 特征.读取特征完整保护(f);
        if (完整.状态 != 新特征完整读取状态::已读取 || !完整.信息) continue;
        if (!完整.信息->特征.当前值) continue;
        if (!std::holds_alternative<std::int64_t>(*完整.信息->特征.当前值))
            continue;
        const auto 概念 = 特征概念.获取特征概念(完整.信息->特征.特征概念节点);
        if (!概念 || 概念->材料类型 != 特征概念材料物理类型::I64标量) continue;
        return f;
    }
    return std::nullopt;
}

std::optional<稳定编码> 选概念条件有值特征(
    稳定编码 E, const 新_存在类& 存在, const 新_特征类& 特征,
    const 概念_特征类& 特征概念) {
    const auto 定位 = 存在.读取存在顶层特征定位保护(E);
    if (定位.状态 != 新存在顶层特征定位状态::已读取 || !定位.信息)
        return std::nullopt;
    for (const auto f : 定位.信息->顶层特征节点组) {
        const auto 完整 = 特征.读取特征完整保护(f);
        if (完整.状态 != 新特征完整读取状态::已读取 || !完整.信息) continue;
        if (!完整.信息->特征.当前值) continue;
        const auto* 码 = std::get_if<稳定编码>(&*完整.信息->特征.当前值);
        if (!码 || !有效(*码)) continue;
        if (!特征概念.获取特征概念(*码)) continue;
        return f;
    }
    return std::nullopt;
}

std::optional<稳定编码> 选存在引用有值特征(
    稳定编码 E, const 新_存在类& 存在, const 新_特征类& 特征,
    const 概念_特征类& 特征概念) {
    const auto 定位 = 存在.读取存在顶层特征定位保护(E);
    if (定位.状态 != 新存在顶层特征定位状态::已读取 || !定位.信息)
        return std::nullopt;
    for (const auto f : 定位.信息->顶层特征节点组) {
        const auto 完整 = 特征.读取特征完整保护(f);
        if (完整.状态 != 新特征完整读取状态::已读取 || !完整.信息) continue;
        if (!完整.信息->特征.当前值) continue;
        const auto* 码 = std::get_if<稳定编码>(&*完整.信息->特征.当前值);
        if (!码 || !有效(*码) || !存在.是存在节点(*码)) continue;
        const auto 概念 = 特征概念.获取特征概念(完整.信息->特征.特征概念节点);
        if (!概念) continue;
        if (概念->材料类型 != 特征概念材料物理类型::存在节点引用
            && !存在.是存在节点(*码)) continue;
        return f;
    }
    return std::nullopt;
}

