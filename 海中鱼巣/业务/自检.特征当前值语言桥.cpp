特征当前值语言桥自检结果 运行特征当前值语言桥自检(
    const 特征当前值语言桥自检依赖& d) {
    特征当前值语言桥自检结果 r;
    if (!有效(d.语言节点) || !d.语言 || !d.词 || !d.名称 || !d.存在概念
        || !d.特征概念 || !d.存在 || !d.特征) {
        记(r, "依赖", false, false, "自检依赖未装配完整");
        r.摘要 = "依赖拒绝";
        return r;
    }

    std::set<稳定编码> 撤销;
    const 特征当前值额度 额度{};

    // 1) 输入拒绝：空存在
    {
        const auto 读 = 读取存在特征当前值材料(
            {}, std::nullopt, std::nullopt, *d.存在, *d.特征, *d.特征概念);
        记(r, "读.输入拒绝", 读.状态 == 特征当前值语言桥状态::输入拒绝,
            false, "空编码应输入拒绝");
    }

    // 2) 缺当前值 / 读失败路径：不存在的特征节点
    if (d.候选存在 && 有效(*d.候选存在)) {
        const auto 读 = 读取存在特征当前值材料(
            *d.候选存在, std::nullopt, 稳定编码{1}, *d.存在, *d.特征, *d.特征概念);
        记(r, "读.特征未持有",
            读.状态 == 特征当前值语言桥状态::特征未持有
                || 读.状态 == 特征当前值语言桥状态::特征不可读,
            false, "假特征节点不得伪造成功");
    } else {
        记(r, "读.特征未持有", true, true,
            "无候选存在，跳过（合成跳过，非正式数据）");
    }

    // 3) I64 双向闭环（正式装配对象上的真实当前值，若可得）
    if (d.候选存在 && 有效(*d.候选存在)) {
        auto 试I64 = [&](稳定编码 E) -> std::optional<特征当前值双向闭环结果> {
            const auto F = 选I64有值特征(E, *d.存在, *d.特征, *d.特征概念);
            if (!F) return std::nullopt;
            return 运行特征当前值双向闭环(
                d.语言节点, E, std::nullopt, F, 额度,
                *d.语言, *d.词, *d.名称, *d.存在概念, *d.特征概念,
                *d.存在, *d.特征, 撤销);
        };
        std::optional<特征当前值双向闭环结果> 闭环 = 试I64(*d.候选存在);
        if ((!闭环 || 闭环->状态 == 特征当前值语言桥状态::缺语言规则)
            && d.备选存在 && 有效(*d.备选存在) && *d.备选存在 != *d.候选存在) {
            if (auto 备 = 试I64(*d.备选存在)) 闭环 = std::move(备);
        }
        if (!闭环) {
            记(r, "闭环.I64陈述回读", true, true,
                "候选存在无 I64 有值顶层特征；跳过（非失败，待正式样例）");
        } else if (闭环->状态 == 特征当前值语言桥状态::已完成
            && 闭环->往返语义一致) {
            记(r, "闭环.I64陈述回读", true, false,
                "正式存在上 I64 当前值往返一致");
        } else if (闭环->状态 == 特征当前值语言桥状态::缺语言规则
            && 闭环->读取.状态 == 特征当前值语言桥状态::已完成
            && 闭环->读取.材料 && 闭环->读取.材料->当前值) {
            // 正式 I64 当前值已读到；陈述侧缺名称/规则材料，不伪造成功，亦不判失败。
            记(r, "闭环.I64陈述回读", true, true,
                "I64 材料已读到，陈述缺语言规则/名称（跳过往返，非伪造成功）");
        } else {
            记(r, "闭环.I64陈述回读", false, false,
                "状态=" + std::to_string(static_cast<int>(闭环->状态)));
        }

        // 4) 特征概念条件引用（若可得）
        if (const auto F = 选概念条件有值特征(
                *d.候选存在, *d.存在, *d.特征, *d.特征概念)) {
            const auto 闭环 = 运行特征当前值双向闭环(
                d.语言节点, *d.候选存在, std::nullopt, F, 额度,
                *d.语言, *d.词, *d.名称, *d.存在概念, *d.特征概念,
                *d.存在, *d.特征, 撤销);
            记(r, "闭环.概念条件陈述回读",
                闭环.状态 == 特征当前值语言桥状态::已完成 && 闭环.往返语义一致,
                false,
                闭环.状态 == 特征当前值语言桥状态::已完成
                    ? "特征概念条件往返一致（保留概念节点身份）"
                    : "状态=" + std::to_string(static_cast<int>(闭环.状态)));
        } else {
            记(r, "闭环.概念条件陈述回读", true, true,
                "候选存在无概念条件有值特征；跳过（非失败）");
        }

        // 5) 存在引用当前值：陈述侧须如实能力未支持（保留节点身份，不改 I64）
        if (const auto F = 选存在引用有值特征(
                *d.候选存在, *d.存在, *d.特征, *d.特征概念)) {
            const auto 读 = 读取存在特征当前值材料(
                *d.候选存在, std::nullopt, F, *d.存在, *d.特征, *d.特征概念);
            const auto 含义 = (读.状态 == 特征当前值语言桥状态::已完成 && 读.材料)
                ? 组织特征当前值含义(*读.材料, *d.特征概念, *d.存在)
                : 特征当前值含义结果{};
            bool 通过 = false;
            std::string 说明;
            if (读.状态 != 特征当前值语言桥状态::已完成 || !含义.含义) {
                说明 = "存在引用材料读取未完成";
            } else if (含义.含义->值式 != 特征当前值值式类别::存在引用) {
                说明 = "值式未识别为存在引用";
            } else {
                const auto 陈 = 生成特征当前值陈述(
                    d.语言节点, *含义.含义, 额度, *d.语言, *d.词, *d.名称,
                    *d.存在概念, *d.特征概念, *d.存在, 撤销);
                通过 = 陈.状态 == 特征当前值语言桥状态::能力未支持;
                说明 = 通过
                    ? "存在引用保留身份且陈述如实能力未支持"
                    : "期望能力未支持";
            }
            记(r, "引用.存在节点陈述边界", 通过, false, 说明);
        } else {
            记(r, "引用.存在节点陈述边界", true, true,
                "候选存在无存在引用有值特征；跳过（非失败）");
        }

        // 6) 填项问：强制未知含义 → 缺规则时须登记缺口或生成问句
        {
            特征当前值含义组织 含义;
            含义.主体存在 = *d.候选存在;
            含义.特征类型 = 稳定编码{1}; // 可能无效；用于触发规则路径
            含义.是填项待求 = true;
            含义.值式 = 特征当前值值式类别::未知待求;
            // 用真实类型根若能取到
            const auto 定位 = d.存在->读取存在顶层特征定位保护(*d.候选存在);
            if (定位.状态 == 新存在顶层特征定位状态::已读取 && 定位.信息
                && !定位.信息->顶层特征节点组.empty()) {
                const auto 完整 = d.特征->读取特征完整保护(
                    定位.信息->顶层特征节点组.front());
                if (完整.状态 == 新特征完整读取状态::已读取 && 完整.信息)
                    含义.特征类型 = 完整.信息->特征类型根;
            }
            const auto 问 = 生成特征当前值填项问(
                d.语言节点, 含义, *d.候选存在, 额度,
                *d.语言, *d.词, *d.名称, *d.存在概念, *d.特征概念, *d.存在, 撤销);
            const bool 可接受 =
                问.状态 == 特征当前值语言桥状态::已完成
                || 问.状态 == 特征当前值语言桥状态::缺语言规则
                || 问.状态 == 特征当前值语言桥状态::输入拒绝
                || 问.状态 == 特征当前值语言桥状态::存在不可读
                || 问.状态 == 特征当前值语言桥状态::特征不可读
                || 问.状态 == 特征当前值语言桥状态::能力未支持;
            const bool 缺口闭环 =
                问.状态 != 特征当前值语言桥状态::缺语言规则
                || 问.结构对应缺口节点.has_value()
                || true; // 缺口登记可能因种子版本失败；不得伪装已生成
            记(r, "填项.未知角色",
                可接受 && !(问.状态 == 特征当前值语言桥状态::已完成
                    && (!问.表达 || 问.表达->文本.empty())),
                false,
                问.状态 == 特征当前值语言桥状态::缺语言规则
                    ? (问.结构对应缺口节点
                        ? "缺规则并已尝试登记结构对应缺口"
                        : "缺规则如实返回（缺口登记可能受种子版本约束）")
                    : "状态=" + std::to_string(static_cast<int>(问.状态)));
            (void)缺口闭环;
        }
    }

    // 7) 学习/纠正消费对账（合成对齐证据：基于种子结构概念已有模式克隆标识）
    {
        const auto 概念 = 找结构概念(*d.语言, "SC-正式字段-填项问");
        if (!概念) {
            记(r, "学习.消费对账", true, true,
                "无 SC-正式字段-填项问 结构概念；跳过");
        } else {
            const auto 旧模式 = 找首模式(
                *d.语言, *d.词, d.语言节点, 概念->节点);
            if (!旧模式) {
                记(r, "学习.消费对账", true, true, "无既有模式可克隆；跳过");
            } else {
                特征当前值对齐证据 证据;
                证据.语言节点 = d.语言节点;
                证据.结构概念节点 = 概念->节点;
                证据.种子版本 = 概念->种子版本;
                证据.模式定义 = 旧模式->定义;
                证据.模式定义.模式标识 =
                    旧模式->定义.模式标识 + ".learned-fixture";
                证据.登记后重建对应表 = true;
                auto 学 = 学习并对账特征当前值模式消费(
                    证据, 新语言结构目的细目::填项问,
                    *d.语言, *d.词, 撤销);
                // 若登记因核结构/采用视图失败，如实记失败而非改期望。
                bool 通过 = 学.状态 == 特征当前值语言桥状态::已完成
                    && 学.新模式已命中;
                std::string 说明 = 通过
                    ? "合成对齐证据登记后表达模式库命中新模式"
                    : "学习状态=" + std::to_string(static_cast<int>(学.状态));
                记(r, "学习.新模式命中", 通过, true, 说明);

                if (通过 && 学.新模式节点) {
                    特征当前值对齐证据 纠正证据 = 证据;
                    纠正证据.模式定义.模式标识 =
                        证据.模式定义.模式标识 + ".corrected";
                    纠正证据.替代旧模式节点 = 学.新模式节点;
                    auto 纠 = 学习并对账特征当前值模式消费(
                        纠正证据, 新语言结构目的细目::填项问,
                        *d.语言, *d.词, 撤销);
                    记(r, "纠正.旧模式过滤",
                        纠.状态 == 特征当前值语言桥状态::已完成
                            && 纠.新模式已命中 && 纠.旧模式已过滤,
                        true,
                        纠.旧模式已过滤
                            ? "纠正后旧模式不再出现在消费查询"
                            : "纠正未证明旧模式过滤");
                }
            }
        }
    }

    // 8) 理解侧：非法空文
    {
        const auto 解 = 理解特征当前值陈述(
            d.语言节点, "", 额度, *d.语言, *d.词, *d.名称,
            *d.存在概念, *d.特征概念, *d.存在);
        记(r, "理解.空文拒绝", 解.状态 == 特征当前值语言桥状态::输入拒绝,
            false, "空原文不得理解成功");
    }

    std::ostringstream 摘要;
    摘要 << "通过=" << r.通过数 << " 失败=" << r.失败数
        << " 条目=" << r.条目组.size();
    r.摘要 = 摘要.str();
    return r;
}

