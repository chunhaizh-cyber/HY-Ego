// 存在—特征—当前值：领域正式读取裁决事实；语言知识只组织角色与表达。
// 准确值保持 variant<I64,稳定编码>；未知=nullopt；理解不自动写世界事实。

enum class 特征当前值语言桥状态 : std::uint8_t {
    已完成 = 1,
    当前值未知,
    特征未持有,
    多特征同型,
    存在不可读,
    特征不可读,
    类型不相容,
    缺语言规则,
    多规则待选,
    理解未闭合,
    输入拒绝,
    读取漂移,
    工程未完成,
    内部不一致,
    能力未支持,
    往返不一致,
    学习未消费
};

enum class 特征当前值值式类别 : std::uint8_t {
    未知待求 = 0,
    I64准确值,
    特征概念条件,
    存在引用,
    其它引用
};

