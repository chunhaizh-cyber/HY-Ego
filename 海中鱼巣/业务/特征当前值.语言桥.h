// 首片：存在—特征—当前值 的领域正式读取 ↔ 语言含义组织 ↔ 陈述/填项/理解/模式学习。
// 事实只来自存在/特征正式读取；话语只经既有语言知识生成与解释；不发明关系本体。
// 当前值保持 新特征准确值=variant<I64,稳定编码>；未知为 nullopt，不作默认值。

enum class 特征当前值语言桥状态 : std::uint8_t {
    已完成 = 1,
    当前值未知,
    特征未持有,
    多特征同型,
    存在不可读,
    特征不可读,
    类型不相容,
    缺语言规则,
    多规则待选,
    理解未闭合,
    输入拒绝,
    读取漂移,
    工程未完成,
    内部不一致,
    能力未支持
};

struct 特征当前值正式材料 final {
    稳定编码 存在节点{};
    稳定编码 特征节点{};
    稳定编码 特征概念节点{};
    稳定编码 特征类型根{};
    特征概念材料物理类型 材料类型 = 特征概念材料物理类型::I64标量;
    std::optional<稳定编码> 单位;
    // 空 = 领域上尚无当前值；不是 0、不是空编码。
    std::optional<新特征准确值> 当前值;
};

struct 特征当前值含义组织 final {
    稳定编码 主体存在{};
    稳定编码 特征类型{};
    std::optional<稳定编码> 单位;
    std::optional<新特征准确值> 准确值;
    bool 是填项待求 = false;
};

struct 特征当前值额度 final {
    std::size_t 最大知识条目数 = 256;
    std::size_t 最大名称条目数 = 256;
    std::size_t 最大输出标量数 = 4096;
    std::size_t 最大原文标量数 = 4096;
    std::size_t 最大名称候选数 = 64;
    std::size_t 最大组合候选数 = 64;
    std::size_t 最大确认候选数 = 64;
};

struct 特征当前值读取结果 final {
    特征当前值语言桥状态 状态 = 特征当前值语言桥状态::输入拒绝;
    std::optional<特征当前值正式材料> 材料;
};

struct 特征当前值含义结果 final {
    特征当前值语言桥状态 状态 = 特征当前值语言桥状态::输入拒绝;
    std::optional<特征当前值含义组织> 含义;
};

struct 特征当前值陈述结果 final {
    特征当前值语言桥状态 状态 = 特征当前值语言桥状态::输入拒绝;
    std::optional<基础表达结果> 表达;
    std::optional<特征当前值含义组织> 所用含义;
};

struct 特征当前值理解结果 final {
    特征当前值语言桥状态 状态 = 特征当前值语言桥状态::输入拒绝;
    std::optional<特征当前值含义组织> 含义;
    std::optional<语言基础统一构式> 构式;
    std::optional<语言场景基础输入状态> 解释状态;
    std::string 固定原文;
};

struct 特征当前值模式登记结果 final {
    特征当前值语言桥状态 状态 = 特征当前值语言桥状态::输入拒绝;
    std::optional<新语言表达模式信息> 模式;
    std::optional<新语言知识发布种类> 发布种类;
    std::vector<稳定编码> 受阻节点组;
};

struct 特征当前值模式查询结果 final {
    特征当前值语言桥状态 状态 = 特征当前值语言桥状态::输入拒绝;
    std::vector<新语言结构对应行> 行组;
    std::vector<稳定编码> 受阻节点组;
    std::size_t 已过滤撤销数 = 0;
};

// 按存在+特征类型根，或存在+特征节点，正式读取当前值材料。
特征当前值读取结果 读取存在特征当前值材料(
    稳定编码 存在节点,
    std::optional<稳定编码> 特征类型根,
    std::optional<稳定编码> 特征节点,
    const 新_存在类&,
    const 新_特征类&,
    const 概念_特征类&) noexcept;

// 领域材料 → 语言无关含义；未知当前值标为填项待求。
特征当前值含义结果 组织特征当前值含义(
    const 特征当前值正式材料&) noexcept;

// 已知 I64 当前值 → 特征描述陈述（复用 生成基础语言表达 / S03整数知识）。
特征当前值陈述结果 生成特征当前值陈述(
    稳定编码 语言节点,
    const 特征当前值含义组织&,
    const 特征当前值额度&,
    const 新_语言类&,
    const 新_词类&,
    const 概念_名称关系类&,
    const 概念_存在类&,
    const 概念_特征类&,
    const 新_存在类&);

// 未知当前值 → 填项问；无可用规则时如实 缺语言规则（普通存在特征询问模板可能仍缺）。
特征当前值陈述结果 生成特征当前值填项问(
    稳定编码 语言节点,
    const 特征当前值含义组织&,
    稳定编码 受询者存在,
    const 特征当前值额度&,
    const 新_语言类&,
    const 新_词类&,
    const 概念_名称关系类&,
    const 概念_存在类&,
    const 概念_特征类&,
    const 新_存在类&);

