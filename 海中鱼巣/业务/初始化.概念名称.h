#pragma once

#include "解释.初始化最小结构.h"
#include "../领域/概念_特征类.h"
#include "../领域/概念_名称关系类.h"
#include "../领域/新_词类.h"

namespace 海中鱼巣 {

enum class 初始化先天名称目标 : std::uint8_t {
    三维空间坐标, 三维空间尺寸, RGB颜色, 二维轮廓, 三维体素
};
struct 初始化已知概念目标 final {
    初始化先天名称目标 来源;
    std::string 标准词面;
    特征概念信息 定义依据;
};
struct 初始化概念名称环境 final {
    std::vector<初始化已知概念目标> 目标组;
};
struct 初始化概念名称请求 final {
    std::string 标准文本;
    稳定编码 语言节点, 规范化合同节点;
    初始化概念名称环境 环境;
    初始化最小资源额度 解释额度;
};
enum class 初始化名称来源 : std::uint8_t {
    显式先天标准词面, 显式允许别名
};
struct 初始化名称发布项 final {
    初始化先天名称目标 目标;
    初始化名称来源 来源;
    std::string 词面;
    稳定编码 概念节点;
    std::vector<初始化源范围> 来源范围组;
    std::vector<std::size_t> 来源定义编号组;
    std::optional<新词条建立结果> 词条发布;
    std::optional<新词条查询结果> 词条读回;
    std::optional<概念名称关系建立结果> 名称发布;
    std::optional<概念名称关系查询结果> 名称读回;
    std::optional<概念名称关系列表查询结果> 概念正向读回;
    std::optional<概念名称关系列表查询结果> 词条反向读回;
};
struct 初始化名称符号绑定 final {
    初始化符号引用 出现;
    稳定编码 概念节点;
};
enum class 初始化概念名称状态 : std::uint8_t {
    已完成, 前置拒绝, 解释未完成, 目标未覆盖, 工程未完成
};
enum class 初始化概念名称阶段 : std::uint8_t {
    前置核验, 标准文本解释, 目标覆盖,
    词条发布, 词条读回, 名称发布, 三路读回, 完成
};
struct 初始化概念名称结果 final {
    初始化概念名称状态 状态 = 初始化概念名称状态::前置拒绝;
    初始化概念名称阶段 阶段 = 初始化概念名称阶段::前置核验;
    std::optional<初始化最小解释结果> 解释结果;
    std::vector<初始化名称发布项> 名称项组;
    std::vector<初始化名称符号绑定> 符号绑定组;
    std::vector<初始化符号引用> 未绑定符号组;
    std::vector<std::size_t> 未应用定义编号组;
    std::vector<std::size_t> 未处理别名定义编号组;
    std::optional<std::size_t> 当前名称项;
    std::string 诊断说明;
};

// 仅公开读取已有先天身份；环境是本次命名依据，不是第二份概念权威。
// 三入口工程异常向上送出，由正式调用方在最终工程边界诊断中断。
初始化概念名称环境 读取先天概念名称环境(
    const 概念_特征类& 特征概念服务);

// 完整解释和来源核验先于写入；逐项发布，失败保留已发生步骤，不批量回滚。
// 已完成仅表示五个已有FT名称及RGB别名闭合，其它定义仍未应用。
初始化概念名称结果 初始化已有概念名称(
    const 初始化概念名称请求& 请求,
    const 新_语言类& 语言服务, 新_词类& 词服务,
    概念_名称关系类& 名称服务, const 概念_特征类& 特征概念服务);

// 完整复核同一组目标；零写入，发布结果始终为空，不修补缺失关系。
初始化概念名称结果 读取已有概念名称(
    const 初始化概念名称请求& 请求,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_特征类& 特征概念服务);

} // namespace 海中鱼巣
