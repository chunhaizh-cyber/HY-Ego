bool 键有效且互异(const L1所有者范围写入幂等身份& 概念键,
                 const 原子I64特征出生键& 出生键) noexcept {
  const std::array<L1所有者范围写入幂等身份, 6> 全部{
      概念键, 出生键.组合, 出生键.内容,
      出生键.已知, 出生键.组织, 出生键.概念使用};
  for (std::size_t i = 0; i < 全部.size(); ++i) {
    if (!有效(全部[i])) return false;
    for (std::size_t j = 0; j < i; ++j)
      if (全部[i] == 全部[j]) return false;
  }
  return true;
}

bool 域包含(const std::vector<概念树I64区间>& 外,
            const std::vector<概念树I64区间>& 内) noexcept {
  return std::all_of(内.begin(), 内.end(), [&](const auto& 目标) {
    return std::any_of(外.begin(), 外.end(), [&](const auto& 候选) {
      return 候选.下界 <= 目标.下界 && 候选.上界 >= 目标.上界;
    });
  });
}

std::vector<概念树I64区间> 转为概念域(const 特征规范I64域& 域) {
  std::vector<概念树I64区间> 结果;
  结果.reserve(域.区间.size());
  for (const auto& 项 : 域.区间) 结果.push_back({项.下界, 项.上界});
  return 结果;
}

bool 单点属于完整域(const 特征规范I64域& 域, std::int64_t 值) noexcept {
  return std::any_of(域.区间.begin(), 域.区间.end(), [&](const auto& 项) {
    return 项.下界 <= 值 && 值 <= 项.上界;
  });
}

