I64原子准确特征出生应用结果 特征概念应用服务::处理I64原子准确特征出生(
    const I64原子准确特征出生应用请求& 请求) {
  I64原子准确特征出生应用结果 结果;
  结果.原请求 = 请求;
  if (!请求有效(请求)) return 结果;
  try {
    结果.FCv确保 = 确保FCv(请求);
    if (!结果.FCv确保->成功()) {
      结果.状态 = 结果.FCv确保->状态 == I64单值出生概念确保状态::未实现
                      ? I64原子准确特征出生应用状态::未实现
                      : I64原子准确特征出生应用状态::FCv确保失败;
      return 结果;
    }
    const 原子I64特征候选查询请求 查询{请求.位置, 请求.FT.编码, 请求.准确I64};
    结果.候选查询 = 原子服务_.查询精确候选(查询);
    if (结果.候选查询->状态 != 原子I64特征候选查询状态::已读取 ||
        结果.候选查询->原请求 != 查询) {
      结果.状态 = I64原子准确特征出生应用状态::候选查询失败;
      return 结果;
    }
    for (const auto& 候选 : 结果.候选查询->候选) {
      if (!有效(候选.F)) {
        结果.状态 = I64原子准确特征出生应用状态::候选读取失败;
        return 结果;
      }
      const 原子I64特征出生读取请求 读取请求{候选.F, 请求.位置};
      结果.候选读取组.push_back(原子服务_.读取(读取请求));
      if (!结果.候选读取组.back().成功(读取请求)) {
        结果.状态 = I64原子准确特征出生应用状态::候选读取失败;
        return 结果;
      }
    }
    if (结果.候选读取组.size() > 1) {
      结果.状态 = I64原子准确特征出生应用状态::需选择F;
      return 结果;
    }
    if (结果.候选读取组.size() == 1) {
      结果.事实 = 结果.候选读取组.front().事实;
      结果.状态 = I64原子准确特征出生应用状态::已复用;
      return 结果;
    }
    const 原子I64特征出生请求 创建{请求.位置, 请求.FT.编码, 请求.准确I64,
                                    结果.FCv确保->FCv->概念, 请求.F出生键};
    结果.出生 = 原子服务_.创建(创建);
    if (!结果.出生->成功()) {
      结果.状态 = 映射出生状态(结果.出生->状态);
      return 结果;
    }
    结果.事实 = 结果.出生->事实;
    结果.状态 = 结果.出生->状态 == 原子I64特征出生状态::已创建
                    ? I64原子准确特征出生应用状态::已创建
                    : I64原子准确特征出生应用状态::精确重复;
  } catch (...) {
    结果.状态 = 结果.FCv确保 && 结果.FCv确保->成功()
                    ? I64原子准确特征出生应用状态::出生失败
                    : I64原子准确特征出生应用状态::FCv确保失败;
  }
  return 结果;
}

