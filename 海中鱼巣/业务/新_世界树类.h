enum class 新世界初始化状态 : std::uint8_t {
    已完成 = 1,
    无变化 = 2,
    依赖初始化失败 = 3,
    根场景建立失败 = 4,
    结构不一致 = 5,
    资源失败 = 6
};

struct 新世界初始化结果 final {
    新世界初始化状态 状态 = 新世界初始化状态::依赖初始化失败;
    std::optional<稳定编码> 世界树根场景;
    std::optional<稳定编码> 根场景专属存在概念;
};

enum class 新世界动态发布状态 : std::uint8_t {
    已完成并保留实例概念 = 1,
    已完成并采用已有概念 = 2,
    已完成并形成上位概念 = 3,
    已完成且已有聚合概念 = 4,
    入口拒绝 = 5,
    世界树未初始化 = 6,
    动态建立失败 = 7,
    动态挂接失败 = 8,
    动态挂接失败且回滚失败 = 9,
    已登记但概念识别冲突 = 10,
    动态已登记但概念处理未完成 = 11,
    资源失败 = 12
};

struct 新世界动态发布结果 final {
    新世界动态发布状态 状态 = 新世界动态发布状态::入口拒绝;
    std::optional<新动态建立结果> 动态建立结果;
    std::optional<新场景操作状态> 场景挂接结果;
    std::optional<新动态操作状态> 失败回滚结果;
    std::optional<新动态概念自动抽象结果> 概念处理结果;

    bool 成功() const noexcept;
};

