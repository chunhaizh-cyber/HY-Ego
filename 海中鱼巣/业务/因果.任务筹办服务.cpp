std::vector<特征概念I64闭区间> 规范新增目标域(const 新需求目标定义& 目标,
    const 二次特征概念信息& 定义, const 概念_特征类& 概念) {
    派生要求(目标.目标值域概念节点.has_value());
    const auto 域 = 概念.读取特征概念定义保护(*目标.目标值域概念节点);
    if (域.前提已变化 || 域.状态 == 基础结构操作状态::节点不存在) {派生材料变化行=__LINE__;throw 派生材料变化{};}
    派生要求(域.状态 == 基础结构操作状态::已完成 && !域.前提已变化 && 域.信息
        && 域.信息->类型根 == 定义.二次特征类型根节点);
    const auto* 要求 = std::get_if<std::vector<特征概念I64闭区间>>(&域.信息->定义.值域);
    const auto* 输出 = std::get_if<std::vector<特征概念I64闭区间>>(&定义.输出特征概念.值域);
    派生要求(要求 && 输出 && 域.信息->定义.材料类型 == 特征概念材料物理类型::I64标量
        && !域.信息->定义.单位 && !要求->empty() && !输出->empty());
    std::vector<特征概念I64闭区间> 交集;
    for (const auto& a : *要求) for (const auto& b : *输出) {
        派生要求(a.下界 <= a.上界 && b.下界 <= b.上界);
        const auto lo = (std::max)({a.下界, b.下界, std::int64_t{0}});
        const auto hi = (std::min)(a.上界, b.上界);
        if (lo <= hi) 交集.push_back({lo, hi});
    }
    std::sort(交集.begin(), 交集.end(), [](const auto& a, const auto& b) { return a.下界 < b.下界; });
    std::vector<特征概念I64闭区间> 规范;
    for (const auto& r : 交集) {
        if (规范.empty() || (规范.back().上界 != (std::numeric_limits<std::int64_t>::max)()
            && r.下界 > 规范.back().上界 + 1)) 规范.push_back(r);
        else 规范.back().上界 = (std::max)(规范.back().上界, r.上界);
    }
    return 规范;
}
