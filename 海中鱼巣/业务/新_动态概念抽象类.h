#pragma once

#include <cstdint>
#include <optional>
#include <vector>

#include "新_动态特征抽取类.h"

namespace 海中鱼巣 {

enum class 新动态概念自动抽象状态 : std::uint8_t {
    已采用已有概念 = 1,
    已形成并采用上位概念 = 2,
    已是聚合概念 = 3,
    入口拒绝 = 4,
    动态不存在 = 5,
    实例概念不存在 = 6,
    特征抽取失败 = 7,
    特征保存失败 = 8,
    无同结构候选 = 9,
    最具体概念冲突 = 10,
    聚合失败 = 11,
    采用失败 = 12,
    结构不一致 = 13,
    资源失败 = 14
};

struct 新动态概念自动抽象结果 final {
    新动态概念自动抽象状态 状态 =
        新动态概念自动抽象状态::入口拒绝;
    std::optional<稳定编码> 动态节点;
    std::optional<稳定编码> 原实例概念节点;
    std::optional<稳定编码> 采用概念节点;
    std::vector<稳定编码> 冲突候选;
    std::optional<新动态特征抽取状态> 特征抽取失败状态;
    std::optional<动态概念操作状态> 动态概念失败状态;
    std::optional<新动态操作状态> 动态采用失败状态;
};

// 业务编排只决定识别和一次抽象的顺序；动态概念事实仍由概念_动态类
// 唯一持有，动态实例的概念字段仍由新_动态类唯一修改。
class 新_动态概念抽象类 final {
public:
    新_动态概念抽象类(
        新_动态类& 动态服务,
        概念_动态类& 动态概念服务,
        const 概念_二次特征类& 二次特征概念服务,
        const 新_动态特征抽取类& 动态特征抽取服务) noexcept;

    // 一次调用只完成一层：先保存实例动态特征，再识别唯一最具体已有
    // 聚合概念；若没有包含候选，则与最近的同结构概念形成一个上位概念。
    新动态概念自动抽象结果 处理新动态(
        稳定编码 动态节点) noexcept;

private:
    新_动态类& 动态服务_;
    概念_动态类& 动态概念服务_;
    const 概念_二次特征类& 二次特征概念服务_;
    const 新_动态特征抽取类& 动态特征抽取服务_;
};

} // namespace 海中鱼巣
