关系陈述语言服务::关系陈述语言服务(
    const 关系概念类& 关系,
    const 新_语言类& 语言,
    const 新_词类& 词,
    const 概念_名称关系类& 名称,
    const 概念_存在类& 存在概念,
    const 概念_特征类& 特征概念,
    const 新_存在类& 存在,
    const 新_需求类& 需求,
    const 新_自然语言世界树类& 语言世界) noexcept
    : 关系_(关系), 语言_(语言), 词_(词), 名称_(名称), 存在概念_(存在概念),
      特征概念_(特征概念), 存在_(存在), 需求_(需求), 语言世界_(语言世界) {}

关系陈述结果 关系陈述语言服务::生成关系陈述(const 关系陈述请求& 请求) const {
    关系陈述结果 out;
    if (请求.关系种子键.empty() || !有效(请求.目标语言节点)) {
        out.状态 = 关系陈述状态::输入拒绝;
        out.诊断 = "缺种子键或目标语言";
        return out;
    }
    if (!语言_.是语言节点(请求.目标语言节点)) {
        out.状态 = 关系陈述状态::输入拒绝;
        out.诊断 = "目标语言不是语言节点";
        return out;
    }
    const auto 概念读 = 关系_.按种子键读取(请求.关系种子键);
    if (概念读.状态 == 关系概念操作状态::未找到) {
        out.状态 = 关系陈述状态::缺关系概念;
        return out;
    }
    if (概念读.状态 != 关系概念操作状态::已读取 || !概念读.信息) {
        out.状态 = 关系陈述状态::前提已变化;
        out.诊断 = "关系概念读取未完成";
        return out;
    }
    out.所用关系概念 = *概念读.信息;
    const auto& 定义 = 概念读.信息->定义;

    for (const auto& 端 : 定义.端点组) {
        const auto it = 请求.端点绑定.find(端.角色键);
        if (it == 请求.端点绑定.end() || !有效(it->second)) {
            out.状态 = 关系陈述状态::端点不合法;
            out.诊断 = "缺端点:" + 端.角色键;
            return out;
        }
        if (端.对象种类 == 关系端点对象种类::存在) {
            if (!存在_.获取存在(it->second)) {
                out.状态 = 关系陈述状态::端点不合法;
                out.诊断 = "端点不是存在:" + 端.角色键;
                return out;
            }
        } else if (!需求_.获取需求(it->second)) {
            out.状态 = 关系陈述状态::端点不合法;
            out.诊断 = "端点不是需求:" + 端.角色键;
            return out;
        }
    }

    if (const auto* 字段 = std::get_if<关系字段引用连接>(&定义.连接)) {
        (void)字段;
        out.状态 = 关系陈述状态::范围未支持;
        out.诊断 = "字段引用连接生成尚未接线（结构已可登记）";
        return out;
    }
    const auto* 边 = std::get_if<关系外部边连接>(&定义.连接);
    if (!边) {
        out.状态 = 关系陈述状态::输入拒绝;
        return out;
    }
    const auto 源 = 请求.端点绑定.at(边->源角色键);
    const auto 目标 = 请求.端点绑定.at(边->目标角色键);

    bool 正向成立 = false;
    bool 反向成立 = false;
    if (边->owner标识 == "新_存在类"
        && 边->边类型 == 基础外部关系类型::父子
        && 边->角色或顺序 == 2) {
        正向成立 = 存在组成边成立(存在_, 源, 目标);
        反向成立 = 存在组成边成立(存在_, 目标, 源);
    } else if (边->owner标识 == "新_需求类"
        && 边->边类型 == 基础外部关系类型::父子
        && 边->角色或顺序 == 1) {
        正向成立 = 需求父子边成立(需求_, 源, 目标);
        反向成立 = 需求父子边成立(需求_, 目标, 源);
    } else {
        out.状态 = 关系陈述状态::范围未支持;
        out.诊断 = "未接线的 owner/角色组合:" + 边->owner标识;
        return out;
    }
    if (!正向成立) {
        out.状态 = 反向成立 ? 关系陈述状态::方向或角色错误
                            : 关系陈述状态::关系不成立;
        out.诊断 = 反向成立 ? "端点方向与关系概念源/目标相反"
                            : "正式读未找到匹配边";
        return out;
    }

    const 关系概念表达关联* 表达 = nullptr;
    for (const auto& a : 定义.表达关联组) {
        if (a.语言节点 == 请求.目标语言节点) {
            表达 = &a;
            break;
        }
    }
    if (!表达 || 表达->含义操作码 == 0) {
        out.状态 = 关系陈述状态::缺语言知识;
        out.诊断 = "目标语言无关系表达关联（不暗退其它语言）";
        return out;
    }
    out.所用表达为预置 = 表达->预置;

    if (表达->含义操作码
        != static_cast<std::int64_t>(新语言知识含义操作::组成描述)) {
        out.状态 = 关系陈述状态::缺语言知识;
        out.诊断 = "本切片仅接线组成描述成文；其它含义操作待表达知识";
        return out;
    }
    // 组成描述：源=整体，目标=部分（与种子一致）。
    const auto 部分 = 目标;
    const auto 整体 = 源;
    const auto 图 = 构造组成描述图(请求.目标语言节点, 部分, 整体);
    const auto 无限 = (std::numeric_limits<std::size_t>::max)();
    语言基础统一输出请求 成文{
        请求.目标语言节点, 图, 无限, 无限, 无限, 无限, 无限, 无限,
        请求.说话者, 请求.受话者};
    const auto 输出 = 从基础信息生成可回读单句(
        成文, 语言世界_, 语言_, 词_, 名称_, 存在概念_, 特征概念_, 存在_, nullptr);
    switch (输出.状态) {
    case 语言场景基础输出状态::已生成且唯一回读:
        out.状态 = 关系陈述状态::已生成且唯一回读;
        out.UTF8正文 = 输出.文本;
        out.所用知识节点组 = 输出.所用知识节点组;
        return out;
    case 语言场景基础输出状态::缺规则:
    case 语言场景基础输出状态::结构未支持:
    case 语言场景基础输出状态::回读含义不一致:
        out.状态 = 关系陈述状态::缺语言知识;
        out.诊断 = "成文缺规则或回读不一致";
        return out;
    case 语言场景基础输出状态::缺名称:
        out.状态 = 关系陈述状态::缺名称;
        return out;
    case 语言场景基础输出状态::名称待选:
    case 语言场景基础输出状态::回读多义:
        out.状态 = 关系陈述状态::多义;
        return out;
    case 语言场景基础输出状态::读取漂移:
    case 语言场景基础输出状态::引用不可读:
        out.状态 = 关系陈述状态::前提已变化;
        return out;
    default:
        out.状态 = 关系陈述状态::范围未支持;
        out.诊断 = "统一成文状态=" + std::to_string(static_cast<int>(输出.状态));
        return out;
    }
}

