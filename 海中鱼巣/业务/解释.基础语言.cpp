struct S05布局 final {
    解释原文范围 部分, 整体, 是词, 的词, 一部分词;
};
bool S05范围相同(解释原文范围 左, 解释原文范围 右) noexcept {
    return 左.起始标量 == 右.起始标量
        && 左.结束标量 == 右.结束标量;
}
std::vector<S05布局> 枚举S05布局(
    const std::vector<新语言词条匹配片段>& 片段,
    const std::array<稳定编码, 3>& 固定节点,
    std::size_t 总长) {
    std::vector<S05布局> 结果;
    if (片段.size() < 5 || 片段.front().原文码点起点 != 0) return 结果;
    std::vector<解释原文范围> 范围;
    范围.reserve(片段.size());
    for (const auto& 项 : 片段) {
        if (项.原文码点起点 > 总长
            || !项.原文码点数量
            || 项.原文码点数量 > 总长 - 项.原文码点起点
            || (!范围.empty() && 项.原文码点起点 != 范围.back().结束标量))
            return {};
        范围.push_back({项.原文码点起点,
            项.原文码点起点 + 项.原文码点数量});
    }
    if (范围.back().结束标量 != 总长) return {};
    for (std::size_t i = 1; i < 片段.size(); ++i) {
        if (片段[i].词条节点 != 固定节点[0]) continue;
        for (std::size_t j = i + 2; j + 1 < 片段.size(); ++j) {
            if (片段[j].词条节点 != 固定节点[1]
                || 片段[j + 1].词条节点 != 固定节点[2]
                || j + 1 != 片段.size() - 1) continue;
            结果.push_back({{0, 范围[i].起始标量},
                {范围[i].结束标量, 范围[j].起始标量},
                范围[i], 范围[j], 范围[j + 1]});
        }
    }
    return 结果;
}

bool S05成员相同(const 新场景范围成员读取结果& 左,
    const 新场景范围成员读取结果& 右) {
    return 左.根场景节点 == 右.根场景节点
        && 左.范围成员存在组 == 右.范围成员存在组
        && 左.场景成员组.size() == 右.场景成员组.size()
        && std::equal(左.场景成员组.begin(), 左.场景成员组.end(),
            右.场景成员组.begin(), [](const auto& a, const auto& b) {
                return a.场景节点 == b.场景节点
                    && a.直接成员存在组 == b.直接成员存在组;
            });
}
