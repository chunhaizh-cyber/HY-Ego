对象读取快照 读取对象一次(const 基础现实对象短语候选请求& 请求,
    const 新_世界树类& 世界树, const 新_场景类& 场景服务,
    const 新_存在类& 存在服务, const 新_语言类& 语言服务,
    const 新_词类& 词服务, const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    对象读取快照 快照{{对象状态::输入拒绝, 请求.固定原文,
        请求.语言节点, 请求.未核验来源语言记录节点, {},
        请求.短语范围, {}, {}, {}, {}}};
    auto& 结果 = 快照.结果;
    const auto 标量 = 解码标准UTF8(请求.固定原文);
    if (!标量) { 结果.状态 = 对象状态::格式失败; return 快照; }
    if (标量->码点.empty() || !有效(请求.语言节点)
        || !有效范围(请求.短语范围, 标量->码点.size())) return 快照;
    if (对象短语禁用标量(*标量, 请求.短语范围)) {
        结果.状态 = 对象状态::短语结构未支持; return 快照;
    }
    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    快照.语言读回 = 语言;
    if (语言.状态 != 新语言查询状态::已找到) {
        结果.状态 = 对象语言状态(语言.状态); return 快照;
    }
    if (!语言.信息 || 语言.信息->节点 != 请求.语言节点) {
        结果.状态 = 对象状态::内部不一致; return 快照;
    }
    结果.语言信息 = *语言.信息;
    const auto 匹配 = 语言服务.按已登记词条最长匹配(
        请求.语言节点, 请求.固定原文, 词服务);
    快照.匹配读回 = 匹配;
    if (匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 对象语言状态(匹配.状态); return 快照;
    }
    const 新语言词条匹配片段* 片段 = nullptr;
    for (const auto& 项 : 匹配.片段组)
        if (项.原文码点起点 == 请求.短语范围.起始标量
            && 项.原文码点数量
                == 请求.短语范围.结束标量 - 请求.短语范围.起始标量) {
            if (片段) {
                结果.状态 = 对象状态::内部不一致; return 快照;
            }
            片段 = &项;
        }
    if (!片段) {
        结果.状态 = 对象状态::短语结构未支持; return 快照;
    }
    if (!片段->词条节点) {
        结果.状态 = 对象状态::未知词; return 快照;
    }
    const auto 词 = 词服务.获取词条(*片段->词条节点);
    快照.词读回 = 词;
    if (词.状态 != 新词条查询状态::已找到) {
        结果.状态 = 词.状态 == 新词条查询状态::未找到
            ? 对象状态::内部不一致 : 对象词状态(词.状态);
        return 快照;
    }
    const auto 字节始 = 标量->字节边界[请求.短语范围.起始标量];
    const auto 字节末 = 标量->字节边界[请求.短语范围.结束标量];
    if (!词.信息 || 词.信息->节点 != *片段->词条节点
        || 词.信息->语言节点 != 请求.语言节点
        || 词.信息->规范化词面 != 片段->原文
        || 片段->原文字节起点 != 字节始
        || 片段->原文字节长度 != 字节末 - 字节始
        || 片段->原文 != 请求.固定原文.substr(字节始, 字节末 - 字节始)) {
        结果.状态 = 对象状态::内部不一致; return 快照;
    }
    结果.词条信息 = *词.信息;
    const auto 根 = 世界树.获取世界树根场景();
    快照.根 = 根;
    if (!根 || !有效(*根)) {
        结果.状态 = 对象状态::世界根不可读; return 快照;
    }
    if (请求.显式所述世界根
        && 请求.显式所述世界根->场景根 != *根) {
        结果.状态 = 对象状态::世界能力未支持; return 快照;
    }
    快照.场景根 = 场景服务.获取根场景();
    if (快照.场景根 != 根) {
        结果.状态 = 对象状态::内部不一致; return 快照;
    }
    快照.成员 = 场景服务.读取本树范围成员完整();
    if (快照.成员->状态 != 新场景范围成员读取状态::已完成) {
        结果.状态 = 对象成员状态(快照.成员->状态); return 快照;
    }
    if (!对象成员自证(*快照.成员, *根)) {
        结果.状态 = 对象状态::内部不一致; return 快照;
    }
    结果.实际所述世界根 = 解释目标世界根{*根};
    const auto 列表 = 名称服务.查询词条候选概念(词.信息->节点);
    快照.名称列表读回 = 列表;
    if (列表.状态 == 概念名称关系查询状态::未找到) {
        结果.状态 = 对象状态::缺名称; return 快照;
    }
    if (列表.状态 != 概念名称关系查询状态::已找到) {
        结果.状态 = 对象名称状态(列表.状态); return 快照;
    }
    if (列表.名称关系节点组.empty()
        || !std::is_sorted(列表.名称关系节点组.begin(),
            列表.名称关系节点组.end())) {
        结果.状态 = 对象状态::内部不一致; return 快照;
    }
    std::set<稳定编码> 已见名称;
    struct 抽象名称 final { 稳定编码 关系; 存在概念信息 概念; };
    std::vector<抽象名称> 抽象组;
    for (const auto 关系节点 : 列表.名称关系节点组) {
        if (!有效(关系节点) || !已见名称.insert(关系节点).second) {
            结果.状态 = 对象状态::内部不一致; return 快照;
        }
        语言名称候选读回 名称;
        对象名称读回记录 名称读回;
        const auto 读状态 = 读取对象精确名称(关系节点, *词.信息,
            *语言.信息, 名称服务, 存在概念服务, 特征概念服务,
            名称, 名称读回);
        快照.名称读回组.push_back(std::move(名称读回));
        if (读状态 != 对象状态::已形成完整评估) {
            结果.状态 = 读状态; return 快照;
        }
        结果.未过滤名称候选组.push_back(名称);
        const auto* 普通 = std::get_if<普通名称候选读回>(&名称);
        const auto* E概念 = 普通
            ? std::get_if<存在概念信息>(&普通->目标概念) : nullptr;
        if (!E概念) continue;
        if (E概念->种类 == 存在概念种类::专属) {
            if (!E概念->对应存在节点) {
                结果.状态 = 对象状态::内部不一致; return 快照;
            }
            continue;
        }
        if (E概念->种类 != 存在概念种类::抽象
            || E概念->对应存在节点) {
            结果.状态 = 对象状态::内部不一致; return 快照;
        }
        抽象组.push_back({关系节点, *E概念});
    }
    if (抽象组.empty()) {
        结果.状态 = 对象状态::无抽象存在概念名称; return 快照;
    }
    std::map<稳定编码, 新存在信息> E组;
    for (const auto E节点 : 快照.成员->范围成员存在组) {
        const auto E = 存在服务.获取存在(E节点);
        快照.存在读回组.push_back(E);
        if (!E || E->节点 != E节点 || !E组.emplace(E节点, *E).second) {
            结果.状态 = 对象状态::内部不一致; return 快照;
        }
    }
    std::map<稳定编码, 存在概念信息> C组;
    for (const auto& 名称 : 抽象组) {
        if (C组.contains(名称.概念.节点)) continue;
        const auto C = 存在概念服务.获取存在概念(名称.概念.节点);
        快照.概念读回组.push_back(C);
        if (!C || *C != 名称.概念) {
            结果.状态 = 对象状态::内部不一致; return 快照;
        }
        C组.emplace(C->节点, *C);
    }
    const auto E数 = E组.size(), 名称数 = 抽象组.size();
    if (名称数 > 0
        && E数 > std::numeric_limits<std::size_t>::max() / 名称数) {
        结果.状态 = 对象状态::资源失败; return 快照;
    }
    const auto 项数 = E数 * 名称数;
    if (项数 > 结果.评估组.max_size()) {
        结果.状态 = 对象状态::资源失败; return 快照;
    }
    结果.评估组.reserve(项数);
    快照.采集组.reserve(项数);
    for (const auto& 名称 : 抽象组) {
        const auto& C = C组.at(名称.概念.节点);
        for (const auto& [E节点, E] : E组) {
            const auto 采集 = 存在服务.采集存在概念匹配材料(E节点, C.节点);
            if (采集.采集期间材料变化) {
                结果.状态 = 对象状态::读取漂移; return 快照;
            }
            快照.采集组.push_back(采集);
            if (!对象采集自证(采集, E, C)) {
                结果.状态 = 对象状态::内部不一致; return 快照;
            }
            结果.评估组.push_back({词.信息->节点, 名称.关系, C.节点,
                E节点, 采集.匹配, *采集.材料,
                采集.尚缺固定比较依据特征组});
        }
    }
    auto 排序 = [](const auto& a, const auto& b) {
        return std::tie(a.名称关系节点, a.存在概念节点, a.存在节点)
            < std::tie(b.名称关系节点, b.存在概念节点, b.存在节点);
    };
    std::sort(结果.评估组.begin(), 结果.评估组.end(), 排序);
    结果.状态 = 对象状态::已形成完整评估;
    return 快照;
}

bool 对象名称读回相同(const 对象名称读回记录& a,
    const 对象名称读回记录& b) {
    if (a.指代.状态 != b.指代.状态
        || a.指代.信息.has_value() != b.指代.信息.has_value()
        || (a.指代.信息 && !名称相同(
            语言名称候选读回{*a.指代.信息},
            语言名称候选读回{*b.指代.信息}))
        || a.普通.has_value() != b.普通.has_value()
        || (a.普通 && (a.普通->状态 != b.普通->状态
            || a.普通->信息 != b.普通->信息))
        || a.存在概念 != b.存在概念
        || a.特征概念 != b.特征概念)
        return false;
    return true;
}

bool 对象快照相同(const 对象读取快照& a, const 对象读取快照& b) {
    if (a.结果.状态 != b.结果.状态
        || a.结果.语言信息 != b.结果.语言信息
        || a.结果.词条信息 != b.结果.词条信息
        || a.语言读回.has_value() != b.语言读回.has_value()
        || (a.语言读回 && (a.语言读回->状态 != b.语言读回->状态
            || a.语言读回->信息 != b.语言读回->信息))
        || a.匹配读回.has_value() != b.匹配读回.has_value()
        || (a.匹配读回 && (a.匹配读回->状态 != b.匹配读回->状态
            || a.匹配读回->片段组 != b.匹配读回->片段组))
        || a.词读回.has_value() != b.词读回.has_value()
        || (a.词读回 && (a.词读回->状态 != b.词读回->状态
            || a.词读回->信息 != b.词读回->信息))
        || a.名称列表读回.has_value() != b.名称列表读回.has_value()
        || (a.名称列表读回
            && (a.名称列表读回->状态 != b.名称列表读回->状态
                || a.名称列表读回->名称关系节点组
                    != b.名称列表读回->名称关系节点组))
        || a.名称读回组.size() != b.名称读回组.size()
        || a.根 != b.根
        || a.场景根 != b.场景根
        || a.成员.has_value() != b.成员.has_value()
        || (a.成员 && (a.成员->状态 != b.成员->状态
            || !S05成员相同(*a.成员, *b.成员)))
        || a.存在读回组 != b.存在读回组
        || a.概念读回组 != b.概念读回组
        || a.采集组 != b.采集组
        || a.结果.未过滤名称候选组.size() != b.结果.未过滤名称候选组.size()
        || a.结果.评估组.size() != b.结果.评估组.size())
        return false;
    for (std::size_t i = 0; i != a.名称读回组.size(); ++i)
        if (!对象名称读回相同(a.名称读回组[i], b.名称读回组[i]))
            return false;
    for (std::size_t i = 0; i != a.结果.未过滤名称候选组.size(); ++i)
        if (!名称相同(a.结果.未过滤名称候选组[i],
            b.结果.未过滤名称候选组[i])) return false;
    for (std::size_t i = 0; i != a.结果.评估组.size(); ++i) {
        const auto& x = a.结果.评估组[i], &y = b.结果.评估组[i];
        if (std::tie(x.词条节点, x.名称关系节点, x.存在概念节点, x.存在节点)
                != std::tie(y.词条节点, y.名称关系节点, y.存在概念节点, y.存在节点)
            || x.匹配 != y.匹配 || x.匹配材料 != y.匹配材料
            || x.尚缺固定比较依据特征组 != y.尚缺固定比较依据特征组)
            return false;
    }
    return true;
}
