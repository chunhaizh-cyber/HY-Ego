std::vector<基础特征概念条件短语布局> 枚举S03布局(
    const std::vector<新语言词条匹配片段>& 片段,
    const std::array<稳定编码, 3>& 固定, std::size_t 总长,
    稳定编码 知识节点) {
    std::vector<基础特征概念条件短语布局> 结果;
    if (片段.size() < 6) return 结果;
    std::vector<解释原文范围> 范围;
    for (const auto& 项 : 片段) {
        if (!项.原文码点数量 || 项.原文码点起点 > 总长
            || 项.原文码点数量 > 总长 - 项.原文码点起点
            || (范围.empty() ? 项.原文码点起点 != 0
                : 项.原文码点起点 != 范围.back().结束标量)) return {};
        范围.push_back({项.原文码点起点,
            项.原文码点起点 + 项.原文码点数量});
    }
    if (范围.back().结束标量 != 总长) return {};
    for (std::size_t i = 1; i + 4 < 片段.size(); ++i) {
        if (i + 5 != 片段.size()
            || 片段[i].词条节点 != 固定[0]
            || 片段[i].原文 != "的"
            || !片段[i + 1].词条节点
            || 片段[i + 2].词条节点 != 固定[1]
            || 片段[i + 2].原文 != "是"
            || 片段[i + 3].词条节点 != 固定[2]
            || 片段[i + 3].原文 != "概念"
            || !片段[i + 4].词条节点) continue;
        结果.push_back({知识节点, {0, 范围[i].起始标量},
            范围[i + 1], 范围[i + 4], 范围[i],
            范围[i + 2], 范围[i + 3]});
    }
    return 结果;
}

struct S03名称快照 final {
    稳定编码 词条节点;
    S02词槽 内容;
};
struct S03比较快照 final {
    稳定编码 左, 右;
    单特征概念关系结果 结果;
};
struct S03读取快照 final {
    基础特征概念条件输入结果 结果;
    std::optional<新语言信息> 语言;
    std::vector<新语言词条匹配片段> 匹配;
    std::vector<新语言知识信息> 知识;
    std::vector<新词条信息> 固定词;
    std::vector<S03名称快照> 名称;
    std::vector<S03比较快照> 比较;
    std::optional<稳定编码> 根;
    std::optional<新场景范围成员读取结果> 成员;
    std::optional<新存在信息> 主体;
};

S03读取快照 读取S03一次(const 基础特征概念条件输入请求& 请求,
    const 新_世界树类& 世界树, const 新_场景类& 场景服务,
    const 新_存在类& 存在服务, const 新_语言类& 语言服务,
    const 新_词类& 词服务, const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    S03读取快照 快照{{S03状态::输入拒绝, 请求.固定原文,
        请求.未核验来源语言记录节点, {}, {}, {}, {}}, {}, {}, {},
        {}, {}, {}, {}, {}, {}};
    auto& 结果 = 快照.结果;
    const auto 标量 = 解码标准UTF8(请求.固定原文);
    if (!标量) { 结果.状态 = S03状态::格式失败; return 快照; }
    const auto 总长 = 标量->码点.size();
    if (!总长 || !有效(请求.语言节点)
        || !请求.最大原文标量数 || !请求.最大知识条目数
        || !请求.最大名称候选数 || !请求.最大组合候选数)
        return 快照;
    结果.未覆盖范围组.push_back({0, 总长});
    if (总长 > 请求.最大原文标量数) {
        结果.状态 = S03状态::额度不足; return 快照;
    }
    if (不支持的句面(*标量)) {
        结果.状态 = S03状态::结构未支持; return 快照;
    }
    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    if (语言.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S03(映射S02语言状态(语言.状态)); return 快照;
    }
    if (!语言.信息 || 语言.信息->节点 != 请求.语言节点) {
        结果.状态 = S03状态::内部不一致; return 快照;
    }
    快照.语言 = *语言.信息;
    const auto 匹配 = 语言服务.按已登记词条最长匹配(
        请求.语言节点, 请求.固定原文, 词服务);
    if (匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S03(映射S02语言状态(匹配.状态)); return 快照;
    }
    快照.匹配 = 匹配.片段组;
    const auto 知识 = 语言服务.枚举语言知识候选(
        请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
    if (知识.状态 != 新语言知识状态::已完成) {
        结果.状态 = 映射S03(映射S02知识状态(知识.状态)); return 快照;
    }
    快照.知识 = 知识.信息组;
    bool 有规则 = false, 不符固定词面 = false;
    std::set<稳定编码> 已见;
    for (const auto& 规则 : 知识.信息组) {
        if (!有效(规则.节点) || !已见.insert(规则.节点).second) {
            结果.状态 = S03状态::内部不一致; return 快照;
        }
        if (!是S03概念结构(规则, 请求.语言节点)) continue;
        有规则 = true;
        const auto& 项 = 规则.定义.结构.有序项组;
        std::array<稳定编码, 3> 固定;
        std::array<std::string, 3> 词面;
        for (std::size_t i = 0; i != 3; ++i) {
            const auto 位置 = std::array<std::size_t, 3>{1, 3, 4}[i];
            固定[i] = std::get<新语言知识固定词项>(项[位置].载荷).词条节点;
            const auto 词 = 词服务.获取词条(固定[i]);
            if (词.状态 != 新词条查询状态::已找到) {
                结果.状态 = 映射S03(映射S02词状态(词.状态)); return 快照;
            }
            if (!词.信息 || 词.信息->节点 != 固定[i]
                || 词.信息->语言节点 != 请求.语言节点) {
                结果.状态 = S03状态::内部不一致; return 快照;
            }
            快照.固定词.push_back(*词.信息);
            词面[i] = 词.信息->规范化词面;
        }
        auto 布局 = 枚举S03布局(匹配.片段组, 固定, 总长, 规则.节点);
        if (词面 != std::array<std::string, 3>{"的", "是", "概念"}) {
            不符固定词面 |= !布局.empty();
            continue;
        }
        结果.短语布局候选组.insert(结果.短语布局候选组.end(),
            布局.begin(), 布局.end());
    }
    if (!有规则) { 结果.状态 = S03状态::缺规则; return 快照; }
    if (不符固定词面) { 结果.状态 = S03状态::缺规则; return 快照; }
    auto& 布局组 = 结果.短语布局候选组;
    std::sort(布局组.begin(), 布局组.end(),
        [](const auto& a, const auto& b) { return S03布局键(a) < S03布局键(b); });
    布局组.erase(std::unique(布局组.begin(), 布局组.end(),
        [](const auto& a, const auto& b) { return S03布局键(a) == S03布局键(b); }),
        布局组.end());
    if (布局组.empty()) { 结果.状态 = S03状态::结构未支持; return 快照; }
    if (!请求.主体槽) {
        结果.状态 = S03状态::短语定位待提供; return 快照;
    }
    // 主体槽已给定后，布局只参与内部匹配；公开布局仅服务缺槽定位。
    const auto 全部布局 = std::move(布局组);
    const auto& 主体槽 = *请求.主体槽;
    if (!有效范围(主体槽.原文范围, 总长)
        || (主体槽.已消解存在节点 && !有效(*主体槽.已消解存在节点)))
        return 快照;
    std::vector<基础特征概念条件短语布局> 匹配布局;
    for (const auto& 布局 : 全部布局)
        if (S03范围相同(布局.主体范围, 主体槽.原文范围))
            匹配布局.push_back(布局);
    if (匹配布局.empty()) {
        结果.状态 = S03状态::结构未支持; return 快照;
    }
    bool 缺名称 = false;
    const auto 取名称 = [&](解释原文范围 范围)
        -> const S02词槽* {
        const auto 片 = std::find_if(匹配.片段组.begin(), 匹配.片段组.end(),
            [&](const auto& 项) {
                return 项.原文码点起点 == 范围.起始标量
                    && 项.原文码点数量 == 范围.结束标量 - 范围.起始标量;
            });
        if (片 == 匹配.片段组.end() || !片->词条节点) {
            缺名称 = true; return nullptr;
        }
        const auto 已取 = std::find_if(快照.名称.begin(), 快照.名称.end(),
            [&](const auto& 项) { return 项.词条节点 == *片->词条节点; });
        if (已取 != 快照.名称.end()) return &已取->内容;
        S02词槽 槽;
        const auto 状态 = 读取S02内容槽(*片->词条节点, 请求.语言节点,
            *片, 请求.最大名称候选数, 词服务, 名称服务,
            存在概念服务, 特征概念服务, 槽);
        if (状态 == S02状态::缺名称) { 缺名称 = true; return nullptr; }
        if (状态 != S02状态::已形成唯一含义) {
            结果.状态 = 映射S03(状态); return nullptr;
        }
        if (槽.全名称组.empty()) { 缺名称 = true; return nullptr; }
        快照.名称.push_back({*片->词条节点, std::move(槽)});
        return &快照.名称.back().内容;
    };
    // 名称缓存只在各布局取完后用索引，避免 vector 扩容使引用失效。
    for (const auto& 布局 : 匹配布局) {
        取名称(布局.特征类型范围);
        if (结果.状态 != S03状态::输入拒绝) return 快照;
        取名称(布局.概念范围);
        if (结果.状态 != S03状态::输入拒绝) return 快照;
    }
    if (缺名称) { 结果.状态 = S03状态::缺名称; return 快照; }
    const auto 查槽 = [&](解释原文范围 范围) -> const S02词槽* {
        const auto 片 = std::find_if(匹配.片段组.begin(), 匹配.片段组.end(),
            [&](const auto& 项) { return 项.原文码点起点 == 范围.起始标量; });
        if (片 == 匹配.片段组.end() || !片->词条节点) return nullptr;
        const auto 它 = std::find_if(快照.名称.begin(), 快照.名称.end(),
            [&](const auto& 项) { return 项.词条节点 == *片->词条节点; });
        return 它 == 快照.名称.end() ? nullptr : &它->内容;
    };
    std::set<std::tuple<稳定编码, std::size_t, std::size_t,
        std::size_t, std::size_t>> 来源布局;
    for (const auto& 布局 : 匹配布局) {
        const auto* FT槽 = 查槽(布局.特征类型范围);
        const auto* C槽 = 查槽(布局.概念范围);
        if (!FT槽 || !C槽) {
            结果.状态 = S03状态::内部不一致; return 快照;
        }
        for (const auto& FT名 : FT槽->全名称组) {
            const auto* FT = std::get_if<普通名称候选读回>(&FT名);
            if (!FT || !std::holds_alternative<特征概念信息>(FT->目标概念))
                continue;
            const auto FT节点 = FT->名称关系.概念节点;
            const auto 根比较 = 特征概念服务.比较单特征概念(FT节点, FT节点);
            快照.比较.push_back({FT节点, FT节点, 根比较});
            if (根比较.状态 != 特征概念规则状态::已完成) {
                结果.状态 = 映射S03比较(根比较.状态); return 快照;
            }
            if (!根比较.特征类型根 || !根比较.关系
                || !根比较.最近共同上位) {
                结果.状态 = S03状态::内部不一致; return 快照;
            }
            if (*根比较.特征类型根 != FT节点) continue;
            for (const auto& C名 : C槽->全名称组) {
                const auto* C = std::get_if<普通名称候选读回>(&C名);
                if (!C || !std::holds_alternative<特征概念信息>(C->目标概念))
                    continue;
                const auto C节点 = C->名称关系.概念节点;
                const auto 比较 = 特征概念服务.比较单特征概念(FT节点, C节点);
                快照.比较.push_back({FT节点, C节点, 比较});
                if (比较.状态 != 特征概念规则状态::已完成) {
                    结果.状态 = 映射S03比较(比较.状态); return 快照;
                }
                if (!比较.关系) {
                    结果.状态 = S03状态::内部不一致; return 快照;
                }
                if (比较.特征类型根 != FT节点) continue;
                if (结果.候选组.size() == 请求.最大组合候选数) {
                    结果.状态 = S03状态::额度不足; return 快照;
                }
                结果.候选组.push_back({布局.所用知识节点,
                    新语言知识特征值分支::概念条件, 布局.主体范围,
                    布局.特征类型范围, 布局.概念范围,
                    布局.的词范围, 布局.是词范围, 布局.概念词范围,
                    主体槽.已消解存在节点, FT节点, C节点,
                    FT->名称关系.节点, C->名称关系.节点});
                来源布局.emplace(布局.所用知识节点,
                    布局.主体范围.结束标量,
                    布局.特征类型范围.起始标量,
                    布局.特征类型范围.结束标量,
                    布局.概念范围.起始标量);
            }
        }
    }
    if (结果.候选组.empty()) {
        结果.状态 = S03状态::角色不相容; return 快照;
    }
    std::sort(结果.候选组.begin(), 结果.候选组.end(),
        [](const auto& a, const auto& b) { return S03候选键(a) < S03候选键(b); });
    if (主体槽.已消解存在节点) {
        const auto 根 = 世界树.获取世界树根场景();
        if (!根 || !有效(*根)) {
            结果.状态 = S03状态::世界根不可读; return 快照;
        }
        if (请求.显式所述世界根
            && 请求.显式所述世界根->场景根 != *根) {
            结果.状态 = S03状态::世界能力未支持; return 快照;
        }
        if (场景服务.获取根场景() != 根) {
            结果.状态 = S03状态::内部不一致; return 快照;
        }
        快照.根 = 根;
        auto 成员 = 场景服务.读取本树范围成员完整();
        if (成员.状态 != 新场景范围成员读取状态::已完成) {
            结果.状态 = 映射S03成员(成员.状态); return 快照;
        }
        if (成员.根场景节点 != 根) {
            结果.状态 = S03状态::内部不一致; return 快照;
        }
        快照.成员 = std::move(成员);
        快照.主体 = 存在服务.获取存在(*主体槽.已消解存在节点);
        if (!快照.主体 || 快照.主体->节点 != *主体槽.已消解存在节点) {
            结果.状态 = S03状态::引用不可读; return 快照;
        }
        if (std::find(快照.成员->范围成员存在组.begin(),
                快照.成员->范围成员存在组.end(), *主体槽.已消解存在节点)
            == 快照.成员->范围成员存在组.end()) {
            结果.状态 = S03状态::对象不属于世界; return 快照;
        }
        结果.实际所述世界根 = 解释目标世界根{*根};
    }
    结果.未覆盖范围组.clear();
    if (!主体槽.已消解存在节点)
        结果.未覆盖范围组.push_back(主体槽.原文范围);
    结果.状态 = 来源布局.size() > 1 ? S03状态::多规则待解
        : 结果.候选组.size() > 1 ? S03状态::概念多义待解
        : 主体槽.已消解存在节点 ? S03状态::已形成唯一主张候选
            : S03状态::主体待绑定;
    return 快照;
}

bool S03快照相同(const S03读取快照& a, const S03读取快照& b) {
    if (a.结果.状态 != b.结果.状态 || a.语言 != b.语言
        || a.匹配 != b.匹配 || a.固定词 != b.固定词
        || a.知识.size() != b.知识.size()
        || !std::equal(a.知识.begin(), a.知识.end(), b.知识.begin(), 知识相同)
        || a.名称.size() != b.名称.size()
        || a.比较.size() != b.比较.size()
        || a.根 != b.根 || a.主体 != b.主体
        || a.成员.has_value() != b.成员.has_value()
        || (a.成员 && !S05成员相同(*a.成员, *b.成员))
        || a.结果.候选组.size() != b.结果.候选组.size()
        || a.结果.短语布局候选组.size() != b.结果.短语布局候选组.size())
        return false;
    for (std::size_t i = 0; i != a.名称.size(); ++i) {
        const auto& x = a.名称[i], &y = b.名称[i];
        if (x.词条节点 != y.词条节点 || x.内容.词 != y.内容.词
            || x.内容.全关系节点组 != y.内容.全关系节点组
            || x.内容.全名称组.size() != y.内容.全名称组.size()
            || !std::equal(x.内容.全名称组.begin(), x.内容.全名称组.end(),
                y.内容.全名称组.begin(), 名称相同)) return false;
    }
    for (std::size_t i = 0; i != a.比较.size(); ++i) {
        const auto& x = a.比较[i], &y = b.比较[i];
        if (x.左 != y.左 || x.右 != y.右
            || x.结果.状态 != y.结果.状态
            || x.结果.关系 != y.结果.关系
            || x.结果.特征类型根 != y.结果.特征类型根
            || x.结果.最近共同上位 != y.结果.最近共同上位) return false;
    }
    for (std::size_t i = 0; i != a.结果.候选组.size(); ++i)
        if (S03候选键(a.结果.候选组[i]) != S03候选键(b.结果.候选组[i]))
            return false;
    for (std::size_t i = 0; i != a.结果.短语布局候选组.size(); ++i)
        if (S03布局键(a.结果.短语布局候选组[i])
            != S03布局键(b.结果.短语布局候选组[i])) return false;
    return true;
}
