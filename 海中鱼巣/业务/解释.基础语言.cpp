语言候选路由结果 语言候选路由业务::形成候选(
    const 语言候选路由请求& 请求, const 新_世界树类& 世界树,
    const 新_场景类& 场景服务,
    const 新_存在类& 存在服务, const 新_语言类& 语言服务,
    const 新_词类& 词服务, const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务, const 概念_特征类& 特征概念服务) const {
    语言候选路由结果 结果{基础语言输入状态::输入拒绝,
        请求, 请求.未过滤名称候选组, {}};
    const auto 标量 = 解码标准UTF8(请求.固定原文);
    if (!标量) { 结果.状态 = 基础语言输入状态::格式失败; return 结果; }
    const auto 总长 = 标量->码点.size();
    if (!有效(请求.所述世界根.场景根) || 请求.最大名称候选数 == 0
        || 请求.全句范围.起始标量 != 0 || 请求.全句范围.结束标量 != 总长
        || !有效范围(请求.主体范围, 总长)
        || !有效范围(请求.概念范围, 总长)
        || 请求.主体范围.结束标量 >= 请求.概念范围.起始标量
        || 请求.未过滤名称候选组.size() > 请求.最大名称候选数
        || !是S01结构(请求.所用知识)
        || 请求.所用知识.定义.结构.语言节点 != 请求.概念词条.语言节点
        || !有效(请求.概念词条.节点)) return 结果;
    if (不支持的句面(*标量)
        || 请求.主体范围.起始标量 != 0
        || 请求.主体范围.结束标量 != 1
        || 标量->码点[0] < 'A' || 标量->码点[0] > 'Z') {
        结果.状态 = 基础语言输入状态::结构未支持; return 结果;
    }
    if (请求.主体绑定 && (请求.主体绑定->原文范围.起始标量 != 请求.主体范围.起始标量
        || 请求.主体绑定->原文范围.结束标量 != 请求.主体范围.结束标量
        || !有效(请求.主体绑定->存在节点))) return 结果;
    const auto 现实根 = 世界树.获取世界树根场景();
    if (!现实根 || !有效(*现实根)) {
        结果.状态 = 基础语言输入状态::世界根不可读; return 结果;
    }
    if (请求.所述世界根.场景根 != *现实根) {
        结果.状态 = 基础语言输入状态::世界能力未支持; return 结果;
    }
    if (场景服务.获取根场景() != *现实根) {
        结果.状态 = 基础语言输入状态::内部不一致; return 结果;
    }
    const auto 知识 = 语言服务.获取语言知识(请求.所用知识.节点, 词服务, 存在概念服务);
    if (知识.状态 != 新语言知识状态::已完成 || !知识.信息
        || !知识相同(*知识.信息, 请求.所用知识)) {
        结果.状态 = 基础语言输入状态::引用不可读; return 结果;
    }
    const auto 固定节点 = std::get<新语言知识固定词项>(
        请求.所用知识.定义.结构.有序项组[1].载荷).词条节点;
    const auto 固定词 = 词服务.获取词条(固定节点);
    const auto 概念词 = 词服务.获取词条(请求.概念词条.节点);
    if (固定词.状态 != 新词条查询状态::已找到 || !固定词.信息
        || 固定词.信息->规范化词面 != "是"
        || 固定词.信息->语言节点 != 请求.概念词条.语言节点
        || 概念词.状态 != 新词条查询状态::已找到 || !概念词.信息
        || *概念词.信息 != 请求.概念词条) {
        结果.状态 = 基础语言输入状态::引用不可读; return 结果;
    }
    // 值式路由请求不能只凭调用方给出的标量位置声明结构已覆盖原文。
    if (请求.主体范围.起始标量 != 0
        || 请求.概念范围.结束标量 != 总长
        || 请求.固定原文.substr(
            标量->字节边界[请求.主体范围.结束标量],
            标量->字节边界[请求.概念范围.起始标量]
                - 标量->字节边界[请求.主体范围.结束标量])
            != 固定词.信息->规范化词面
        || 请求.固定原文.substr(
            标量->字节边界[请求.概念范围.起始标量],
            标量->字节边界[请求.概念范围.结束标量]
                - 标量->字节边界[请求.概念范围.起始标量])
            != 请求.概念词条.规范化词面) {
        结果.状态 = 基础语言输入状态::结构未支持; return 结果;
    }
    const auto 名称组 = 名称服务.查询词条候选概念(请求.概念词条.节点);
    if (名称组.状态 == 概念名称关系查询状态::未找到) {
        结果.状态 = 基础语言输入状态::缺名称; return 结果;
    }
    if (名称组.状态 != 概念名称关系查询状态::已找到) {
        结果.状态 = 映射名称状态(名称组.状态); return 结果;
    }
    if (名称组.名称关系节点组.size() > 请求.最大名称候选数) {
        结果.状态 = 基础语言输入状态::额度不足; return 结果;
    }
    std::vector<稳定编码> 请求关系;
    for (const auto& 项 : 请求.未过滤名称候选组) 请求关系.push_back(名称关系身份(项));
    std::sort(请求关系.begin(), 请求关系.end());
    if (请求关系 != 名称组.名称关系节点组) {
        结果.状态 = 基础语言输入状态::引用不可读; return 结果;
    }
    for (const auto& 项 : 请求.未过滤名称候选组) {
        auto 失败状态 = 基础语言输入状态::引用不可读;
        const auto 当前 = 读取强类型名称(名称关系身份(项),
            请求.概念词条.节点, 名称服务, 存在概念服务,
            特征概念服务, 失败状态);
        if (!当前 || !名称相同(*当前, 项)) {
            结果.状态 = 当前 ? 基础语言输入状态::引用不可读 : 失败状态;
            return 结果;
        }
        if (const auto* 普通 = std::get_if<普通名称候选读回>(&项))
            if (const auto* 存在 = std::get_if<存在概念信息>(&普通->目标概念))
                结果.相容候选组.push_back({存在->节点, 普通->名称关系.节点,
                    请求.所用知识.节点, 请求.主体范围, 请求.概念范围,
                    请求.主体绑定 ? std::optional<稳定编码>{请求.主体绑定->存在节点}
                        : std::nullopt});
    }
    if (结果.相容候选组.empty()) {
        结果.状态 = 基础语言输入状态::角色不相容; return 结果;
    }
    std::sort(结果.相容候选组.begin(), 结果.相容候选组.end(), 候选顺序);
    if (请求.主体绑定) {
        const auto 当前 = 存在服务.获取存在(请求.主体绑定->存在节点);
        if (!当前 || 当前->节点 != 请求.主体绑定->存在节点) {
            结果.状态 = 基础语言输入状态::引用不可读; return 结果;
        }
        if (!场景服务.存在属于场景范围(
            *现实根, 请求.主体绑定->存在节点)) {
            结果.状态 = 基础语言输入状态::主体不属于世界; return 结果;
        }
    }
    if (世界树.获取世界树根场景() != 现实根
        || 场景服务.获取根场景() != 现实根) {
        结果.状态 = 基础语言输入状态::引用不可读;
        结果.相容候选组.clear(); return 结果;
    }
    std::set<稳定编码> 不同归类概念;
    for (const auto& 候选 : 结果.相容候选组)
        不同归类概念.insert(候选.归类概念节点);
    if (不同归类概念.size() > 1) 结果.状态 = 基础语言输入状态::概念多义待解;
    else if (!请求.主体绑定) 结果.状态 = 基础语言输入状态::主体待绑定;
    else 结果.状态 = 基础语言输入状态::已形成唯一含义;
    return 结果;
}

基础语言输入结果 解释单句基础归类(
    const 基础语言输入请求& 请求, const 新_世界树类& 世界树,
    const 新_场景类& 场景服务, const 新_存在类& 存在服务,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务, const 概念_特征类& 特征概念服务) {
    基础语言输入结果 结果{基础语言输入状态::输入拒绝,
        请求.固定原文, 请求.未核验来源语言记录节点, {}, {}, {}, {}};
    const auto 标量 = 解码标准UTF8(请求.固定原文);
    if (!标量) { 结果.状态 = 基础语言输入状态::格式失败; return 结果; }
    const auto 总长 = 标量->码点.size();
    if (总长 == 0 || 请求.最大原文标量数 == 0
        || 请求.最大知识条目数 == 0 || 请求.最大名称候选数 == 0
        || !有效(请求.语言节点)
        || (请求.主体绑定 && (!有效范围(请求.主体绑定->原文范围, 总长)
            || !有效(请求.主体绑定->存在节点)))) return 结果;
    结果.未覆盖范围组.push_back({0, 总长});
    if (总长 > 请求.最大原文标量数) {
        结果.状态 = 基础语言输入状态::额度不足; return 结果;
    }
    if (不支持的句面(*标量)) {
        结果.状态 = 基础语言输入状态::结构未支持; return 结果;
    }
    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    if (语言.状态 != 新语言查询状态::已找到 || !语言.信息
        || 语言.信息->节点 != 请求.语言节点) {
        结果.状态 = 映射语言状态(语言.状态); return 结果;
    }
    const auto 根 = 世界树.获取世界树根场景();
    if (!根 || !有效(*根)) {
        结果.状态 = 基础语言输入状态::世界根不可读; return 结果;
    }
    if (请求.显式所述世界根 && 请求.显式所述世界根->场景根 != *根) {
        结果.状态 = 基础语言输入状态::世界能力未支持; return 结果;
    }
    if (场景服务.获取根场景() != 根 || 世界树.获取世界树根场景() != 根) {
        结果.状态 = 基础语言输入状态::内部不一致; return 结果;
    }
    结果.实际所述世界根 = 解释目标世界根{*根};
    const auto 匹配 = 语言服务.按已登记词条最长匹配(请求.语言节点,
        请求.固定原文, 词服务);
    if (匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射语言状态(匹配.状态); return 结果;
    }
    const auto 知识组 = 语言服务.枚举语言知识候选(请求.语言节点,
        请求.最大知识条目数, 词服务, 存在概念服务);
    if (知识组.状态 != 新语言知识状态::已完成) {
        结果.状态 = 映射知识状态(知识组.状态); return 结果;
    }
    std::vector<新语言知识信息> 规则组;
    for (const auto& 知识 : 知识组.信息组) {
        if (!是S01结构(知识)) continue;
        const auto 固定节点 = std::get<新语言知识固定词项>(
            知识.定义.结构.有序项组[1].载荷).词条节点;
        const auto 固定词 = 词服务.获取词条(固定节点);
        if (固定词.状态 != 新词条查询状态::已找到 || !固定词.信息) {
            结果.状态 = 基础语言输入状态::引用不可读; return 结果;
        }
        if (固定词.信息->语言节点 == 请求.语言节点
            && 固定词.信息->规范化词面 == "是") 规则组.push_back(知识);
    }
    if (规则组.empty()) { 结果.状态 = 基础语言输入状态::缺规则; return 结果; }
    const auto 固定节点 = std::get<新语言知识固定词项>(
        规则组.front().定义.结构.有序项组[1].载荷).词条节点;
    std::optional<std::size_t> 固定位置;
    for (std::size_t i = 0; i < 匹配.片段组.size(); ++i)
        if (匹配.片段组[i].词条节点 == 固定节点) {
            if (固定位置) {
                结果.状态 = 基础语言输入状态::结构未支持; return 结果;
            }
            固定位置 = i;
        }
    if (!固定位置 || *固定位置 != 1 || 匹配.片段组.size() != 3) {
        结果.状态 = 基础语言输入状态::结构未支持; return 结果;
    }
    const auto& 左 = 匹配.片段组[0];
    const auto& 中 = 匹配.片段组[1];
    const auto& 右 = 匹配.片段组[2];
    const 解释原文范围 左范围{左.原文码点起点,
        左.原文码点起点 + 左.原文码点数量};
    const 解释原文范围 右范围{右.原文码点起点,
        右.原文码点起点 + 右.原文码点数量};
    if (!有效范围(左范围, 总长) || !有效范围(右范围, 总长)
        || 左范围.起始标量 != 0 || 左范围.结束标量 != 中.原文码点起点
        || 右范围.起始标量 != 中.原文码点起点 + 中.原文码点数量
        || 右范围.结束标量 != 总长 || !右.词条节点) {
        结果.状态 = 右.词条节点 ? 基础语言输入状态::结构未支持
            : 基础语言输入状态::未知词;
        return 结果;
    }
    if (左范围.结束标量 != 1 || 标量->码点[0] < 'A'
        || 标量->码点[0] > 'Z') {
        结果.状态 = 基础语言输入状态::结构未支持; return 结果;
    }
    if (请求.主体绑定
        && (请求.主体绑定->原文范围.起始标量 != 左范围.起始标量
            || 请求.主体绑定->原文范围.结束标量 != 左范围.结束标量)) {
        结果.状态 = 基础语言输入状态::输入拒绝; return 结果;
    }
    const auto 词 = 词服务.获取词条(*右.词条节点);
    if (词.状态 != 新词条查询状态::已找到 || !词.信息
        || 词.信息->规范化词面 != 右.原文
        || 词.信息->语言节点 != 请求.语言节点) {
        结果.状态 = 基础语言输入状态::引用不可读; return 结果;
    }
    const auto 名称组 = 名称服务.查询词条候选概念(词.信息->节点);
    if (名称组.状态 != 概念名称关系查询状态::已找到) {
        结果.状态 = 映射名称状态(名称组.状态); return 结果;
    }
    if (名称组.名称关系节点组.size() > 请求.最大名称候选数) {
        结果.状态 = 基础语言输入状态::额度不足; return 结果;
    }
    std::set<稳定编码> 已见;
    for (const auto 关系节点 : 名称组.名称关系节点组) {
        if (!已见.insert(关系节点).second) {
            结果.状态 = 基础语言输入状态::内部不一致; return 结果;
        }
        auto 失败状态 = 基础语言输入状态::引用不可读;
        const auto 快照 = 读取强类型名称(关系节点, 词.信息->节点,
            名称服务, 存在概念服务, 特征概念服务, 失败状态);
        if (!快照) {
            结果.状态 = 失败状态; return 结果;
        }
        结果.未过滤名称候选组.push_back(*快照);
    }
    std::vector<基础语言输入状态> 路由状态组;
    std::vector<语言候选路由请求> 已用路由请求组;
    for (const auto& 知识 : 规则组) {
        语言候选路由请求 路由请求{请求.固定原文,
            请求.未核验来源语言记录节点, {*根}, {0, 总长},
            左范围, 右范围, 请求.主体绑定, *词.信息, 知识,
            结果.未过滤名称候选组, 请求.最大名称候选数};
        const auto 路由 = 语言候选路由业务{}.形成候选(路由请求,
            世界树, 场景服务, 存在服务, 语言服务, 词服务, 名称服务,
            存在概念服务, 特征概念服务);
        if (路由.状态 != 基础语言输入状态::已形成唯一含义
            && 路由.状态 != 基础语言输入状态::主体待绑定
            && 路由.状态 != 基础语言输入状态::概念多义待解) {
            结果.状态 = 路由.状态;
            结果.候选组.clear();
            return 结果;
        }
        路由状态组.push_back(路由.状态);
        已用路由请求组.push_back(std::move(路由请求));
        结果.候选组.insert(结果.候选组.end(), 路由.相容候选组.begin(),
            路由.相容候选组.end());
    }
    std::sort(结果.候选组.begin(), 结果.候选组.end(), 候选顺序);
    std::vector<基础语言归类候选> 复核候选组;
    for (std::size_t i = 0; i < 已用路由请求组.size(); ++i) {
        const auto 复核 = 语言候选路由业务{}.形成候选(已用路由请求组[i],
            世界树, 场景服务, 存在服务, 语言服务, 词服务, 名称服务,
            存在概念服务, 特征概念服务);
        if (复核.状态 != 路由状态组[i]) {
            结果.状态 = 基础语言输入状态::引用不可读;
            结果.候选组.clear(); return 结果;
        }
        复核候选组.insert(复核候选组.end(), 复核.相容候选组.begin(),
            复核.相容候选组.end());
    }
    std::sort(复核候选组.begin(), 复核候选组.end(), 候选顺序);
    if (结果.候选组.size() != 复核候选组.size()
        || !std::equal(结果.候选组.begin(), 结果.候选组.end(),
            复核候选组.begin(), 候选相同)) {
        结果.状态 = 基础语言输入状态::引用不可读;
        结果.候选组.clear(); return 结果;
    }
    // 重读全集而非仅重读已选端点：新增长词可遮住“是”，新增规则可破坏唯一性。
    const auto 最终匹配 = 语言服务.按已登记词条最长匹配(
        请求.语言节点, 请求.固定原文, 词服务);
    if (最终匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射语言状态(最终匹配.状态);
        结果.候选组.clear(); return 结果;
    }
    if (最终匹配.片段组 != 匹配.片段组) {
        结果.状态 = 基础语言输入状态::引用不可读;
        结果.候选组.clear(); return 结果;
    }
    const auto 最终知识组 = 语言服务.枚举语言知识候选(
        请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
    if (最终知识组.状态 != 新语言知识状态::已完成) {
        结果.状态 = 映射知识状态(最终知识组.状态);
        结果.候选组.clear(); return 结果;
    }
    if (最终知识组.信息组.size() != 知识组.信息组.size()
        || !std::equal(最终知识组.信息组.begin(), 最终知识组.信息组.end(),
            知识组.信息组.begin(), 知识相同)) {
        结果.状态 = 基础语言输入状态::引用不可读;
        结果.候选组.clear(); return 结果;
    }
    if (世界树.获取世界树根场景() != 根 || 场景服务.获取根场景() != 根) {
        结果.状态 = 基础语言输入状态::引用不可读;
        结果.候选组.clear(); return 结果;
    }
    if (规则组.size() > 1) 结果.状态 = 基础语言输入状态::多规则待解;
    else 结果.状态 = 路由状态组.front();
    结果.未覆盖范围组.clear();
    if (!请求.主体绑定) 结果.未覆盖范围组.push_back(左范围);
    return 结果;
}

