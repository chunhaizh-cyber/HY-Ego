对象状态 读取对象精确名称(稳定编码 关系节点,
    const 新词条信息& 词, const 新语言信息& 语言,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务,
    语言名称候选读回& 输出, 对象名称读回记录& 读回) {
    const auto 指代 = 名称服务.获取指代名称关系(关系节点);
    读回.指代 = 指代;
    if (指代.状态 == 指代名称读取状态::已读取) {
        if (!指代.信息 || 指代.信息->节点 != 关系节点
            || 指代.信息->词条 != 词 || 指代.信息->语言 != 语言
            || !有效(指代.信息->概念.节点)) return 对象状态::内部不一致;
        输出 = *指代.信息;
        return 对象状态::已形成完整评估;
    }
    if (指代.状态 != 指代名称读取状态::未找到)
        return 对象指代状态(指代.状态);
    const auto 普通 = 名称服务.获取名称关系(关系节点);
    读回.普通 = 普通;
    if (普通.状态 != 概念名称关系查询状态::已找到)
        return 普通.状态 == 概念名称关系查询状态::未找到
            || 普通.状态 == 概念名称关系查询状态::依赖不存在
            || 普通.状态 == 概念名称关系查询状态::输入不合法
                ? 对象状态::内部不一致 : 对象名称状态(普通.状态);
    if (!普通.信息 || 普通.信息->节点 != 关系节点
        || 普通.信息->词条节点 != 词.节点
        || !有效(普通.信息->概念节点)) return 对象状态::内部不一致;
    const auto E概念 = 存在概念服务.获取存在概念(普通.信息->概念节点);
    const auto F概念 = 特征概念服务.获取特征概念(普通.信息->概念节点);
    读回.存在概念 = E概念;
    读回.特征概念 = F概念;
    if (E概念.has_value() == F概念.has_value())
        return 对象状态::内部不一致;
    输出 = E概念
        ? 语言名称候选读回{普通名称候选读回{*普通.信息, *E概念}}
        : 语言名称候选读回{普通名称候选读回{*普通.信息, *F概念}};
    return 对象状态::已形成完整评估;
}

bool 对象成员自证(const 新场景范围成员读取结果& 成员,
    稳定编码 根) {
    if (成员.状态 != 新场景范围成员读取状态::已完成
        || 成员.根场景节点 != 根 || 成员.场景成员组.empty())
        return false;
    std::set<稳定编码> 场景组, 实际成员;
    for (const auto& 场景 : 成员.场景成员组) {
        if (!有效(场景.场景节点) || !场景组.insert(场景.场景节点).second
            || !std::is_sorted(场景.直接成员存在组.begin(),
                场景.直接成员存在组.end())
            || std::adjacent_find(场景.直接成员存在组.begin(),
                场景.直接成员存在组.end()) != 场景.直接成员存在组.end())
            return false;
        for (auto E : 场景.直接成员存在组)
            if (!有效(E) || !实际成员.insert(E).second) return false;
    }
    return 场景组.contains(根)
        && std::is_sorted(成员.范围成员存在组.begin(),
            成员.范围成员存在组.end())
        && std::adjacent_find(成员.范围成员存在组.begin(),
            成员.范围成员存在组.end()) == 成员.范围成员存在组.end()
        && std::vector<稳定编码>(实际成员.begin(), 实际成员.end())
            == 成员.范围成员存在组;
}

bool 对象采集自证(const 新存在概念匹配采集结果& 采集,
    const 新存在信息& E, const 存在概念信息& C) {
    if (采集.采集期间材料变化 || !采集.材料
        || 采集.材料->存在节点 != E.节点
        || 采集.材料->专属存在概念节点 != E.专属存在概念节点
        || 采集.材料->目标存在概念节点 != C.节点)
        return false;
    std::vector<存在概念特征项> 必需;
    for (const auto& 项 : 采集.材料->必需特征组) {
        if (项.定义.概念节点 != 项.来源.具体特征概念
            || 项.定义.特征类型根 != 项.来源.特征类型概念)
            return false;
        必需.push_back(项.来源);
    }
    auto 排序 = [](const auto& a, const auto& b) {
        return std::tie(a.特征类型概念, a.具体特征概念)
            < std::tie(b.特征类型概念, b.具体特征概念);
    };
    auto 定义必需 = C.特征组;
    std::sort(必需.begin(), 必需.end(), 排序);
    std::sort(定义必需.begin(), 定义必需.end(), 排序);
    if (必需 != 定义必需) return false;
    std::vector<稳定编码> 实际;
    for (const auto& 项 : 采集.材料->实际特征组) 实际.push_back(项.特征节点);
    std::sort(实际.begin(), 实际.end());
    return 实际 == E.特征节点组
        && (采集.匹配.状态 == 新存在概念匹配状态::匹配
            || 采集.匹配.状态 == 新存在概念匹配状态::不符合
            || 采集.匹配.状态 == 新存在概念匹配状态::材料不足);
}

