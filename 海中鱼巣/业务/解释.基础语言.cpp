bool S09候选顺序(const 基础概念归类确认候选& 左,
    const 基础概念归类确认候选& 右) {
    return std::tie(左.外层知识节点, 左.子知识节点, 左.被询归类.类别,
        左.被询归类.主体概念节点, 左.被询归类.归类概念节点,
        左.被询归类.主体名称关系节点, 左.被询归类.归类名称关系节点)
        < std::tie(右.外层知识节点, 右.子知识节点, 右.被询归类.类别,
            右.被询归类.主体概念节点, 右.被询归类.归类概念节点,
            右.被询归类.主体名称关系节点, 右.被询归类.归类名称关系节点);
}
bool S09候选相同(const 基础概念归类确认候选& 左,
    const 基础概念归类确认候选& 右) {
    return !S09候选顺序(左, 右) && !S09候选顺序(右, 左)
        && S02候选相同(左.被询归类, 右.被询归类)
        && 左.受询者存在节点 == 右.受询者存在节点
        && 左.子句范围.起始标量 == 右.子句范围.起始标量
        && 左.子句范围.结束标量 == 右.子句范围.结束标量
        && 左.确认词范围.起始标量 == 右.确认词范围.起始标量
        && 左.确认词范围.结束标量 == 右.确认词范围.结束标量;
}

