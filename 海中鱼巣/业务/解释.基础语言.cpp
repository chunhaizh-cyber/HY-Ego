基础单句分派结果 解释已支持单句构式(
    const 基础单句分派请求& 请求, const 新_世界树类& 世界树,
    const 新_场景类& 场景服务, const 新_存在类& 存在服务,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    基础单句分派结果 结果;
    结果.固定原文 = 请求.固定原文;
    结果.未核验来源语言记录节点 = 请求.未核验来源语言记录节点;
    const auto 标量 = 解码标准UTF8(请求.固定原文);
    if (!标量) { 结果.状态 = 基础单句分派状态::格式失败; return 结果; }
    if (标量->码点.empty() || !有效(请求.语言节点)
        || !请求.最大原文标量数 || !请求.最大知识条目数) return 结果;
    if (标量->码点.size() > 请求.最大原文标量数) {
        结果.状态 = 基础单句分派状态::输入拒绝; return 结果;
    }

    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    结果.语言读取状态 = 语言.状态;
    if (语言.状态 != 新语言查询状态::已找到) {
        结果.状态 = 基础单句分派状态::知识读取未完成; return 结果;
    }
    if (!语言.信息 || 语言.信息->节点 != 请求.语言节点) {
        结果.状态 = 基础单句分派状态::内部不一致; return 结果;
    }
    const auto 知识组 = 语言服务.枚举语言知识候选(
        请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
    结果.知识读取状态 = 知识组.状态;
    if (知识组.状态 != 新语言知识状态::已完成) {
        结果.状态 = 基础单句分派状态::知识读取未完成; return 结果;
    }
    bool 有S01 = false, 有S02 = false, 有S09 = false, 有S05 = false, 有S03概念 = false;
    std::set<稳定编码> 已见知识;
    for (const auto& 知识 : 知识组.信息组) {
        if (!有效(知识.节点) || !已见知识.insert(知识.节点).second
            || 知识.定义.结构.语言节点 != 请求.语言节点) {
            结果.状态 = 基础单句分派状态::内部不一致; return 结果;
        }
        const bool S01 = 是S01结构(知识);
        const bool S02 = 是S02结构(知识, 请求.语言节点);
        const bool S09 = 是S09结构(知识, 请求.语言节点);
        const bool S05 = 是S05结构(知识, 请求.语言节点);
        const bool S03概念 = 是S03概念结构(知识, 请求.语言节点);
        if (static_cast<int>(S01) + static_cast<int>(S02)
            + static_cast<int>(S09) + static_cast<int>(S05)
            + static_cast<int>(S03概念) > 1) {
            结果.状态 = 基础单句分派状态::内部不一致; return 结果;
        }
        有S01 |= S01; 有S02 |= S02; 有S09 |= S09; 有S05 |= S05;
        有S03概念 |= S03概念;
        if (!S01 && !S02 && !S09 && !S05 && !S03概念)
            结果.尚无输入解释器的知识节点组.push_back(知识.节点);
    }
    if (有S01) {
        auto 子 = 解释单句基础归类({请求.固定原文, 请求.语言节点,
            请求.未核验来源语言记录节点, 请求.显式所述世界根,
            请求.主体绑定, 请求.最大原文标量数,
            请求.最大知识条目数, 请求.S01预算.最大名称候选数},
            世界树, 场景服务, 存在服务, 语言服务, 词服务,
            名称服务, 存在概念服务, 特征概念服务);
        结果.已调用分支组.push_back({基础单句构式种类::S01对象归类, std::move(子)});
    }
    if (有S02) {
        auto 子 = 解释单句概念上下位({请求.固定原文, 请求.语言节点,
            请求.未核验来源语言记录节点, 请求.最大原文标量数,
            请求.最大知识条目数, 请求.S02预算.最大名称候选数,
            请求.S02预算.最大组合候选数}, 语言服务, 词服务,
            名称服务, 存在概念服务, 特征概念服务);
        结果.已调用分支组.push_back({基础单句构式种类::S02概念上下位, std::move(子)});
    }
    if (有S09) {
        auto 子 = 解释单句概念归类确认({请求.固定原文, 请求.语言节点,
            请求.未核验来源语言记录节点, 请求.受询者存在节点,
            请求.最大原文标量数, 请求.最大知识条目数,
            请求.S09预算.最大名称候选数,
            请求.S09预算.最大组合候选数,
            请求.S09预算.最大确认候选数}, 语言服务, 词服务,
            名称服务, 存在概念服务, 特征概念服务, 存在服务);
        结果.已调用分支组.push_back({基础单句构式种类::S09概念归类确认, std::move(子)});
    }
    if (有S05) {
        auto 子 = 解释单句组成陈述({请求.固定原文, 请求.语言节点,
            请求.未核验来源语言记录节点, 请求.显式所述世界根,
            请求.S05部分槽, 请求.S05整体槽, 请求.最大原文标量数,
            请求.最大知识条目数, 请求.S05最大组成候选数},
            世界树, 场景服务, 存在服务, 语言服务, 词服务,
            存在概念服务);
        结果.已调用分支组.push_back({基础单句构式种类::S05组成陈述, std::move(子)});
    }
    if (有S03概念) {
        auto 子 = 解释单句特征概念条件({请求.固定原文, 请求.语言节点,
            请求.未核验来源语言记录节点, 请求.显式所述世界根,
            请求.S03主体槽, 请求.最大原文标量数,
            请求.最大知识条目数, 请求.S03预算.最大名称候选数,
            请求.S03预算.最大组合候选数},
            世界树, 场景服务, 存在服务, 语言服务, 词服务,
            名称服务, 存在概念服务, 特征概念服务);
        结果.已调用分支组.push_back({
            基础单句构式种类::S03特征概念条件, std::move(子)});
    }
    const auto 复读 = 语言服务.枚举语言知识候选(
        请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
    结果.知识读取状态 = 复读.状态;
    if (复读.状态 != 新语言知识状态::已完成) {
        结果.状态 = 基础单句分派状态::知识读取未完成; return 结果;
    }
    if (复读.信息组.size() != 知识组.信息组.size()
        || !std::equal(复读.信息组.begin(), 复读.信息组.end(),
            知识组.信息组.begin(), 知识相同)) {
        结果.状态 = 基础单句分派状态::读取漂移; return 结果;
    }
    if (结果.已调用分支组.empty()) {
        结果.状态 = 基础单句分派状态::无已实现知识; return 结果;
    }

    bool 未完成 = false, 多义 = false, 待绑定 = false;
    unsigned 顶层候选数 = 0;
    for (const auto& 分支 : 结果.已调用分支组) {
        const auto 裁决 = std::visit([](const auto& 子) {
            return 裁决分支(子);
        }, 分支.结果);
        if (裁决 == 单句分支裁决::内部不一致) {
            结果.状态 = 基础单句分派状态::内部不一致; return 结果;
        }
        if (裁决 == 单句分支裁决::未完成) 未完成 = true;
        if (裁决 == 单句分支裁决::多义) 多义 = true;
        if (裁决 == 单句分支裁决::待绑定) 待绑定 = true;
        const auto 数量 = std::visit([](const auto& 子) {
            return 子.候选组.size();
        }, 分支.结果);
        if (数量 > 1 || (数量 && 顶层候选数)) 顶层候选数 = 2;
        else if (数量) 顶层候选数 = 1;
    }
    结果.状态 = 未完成 ? 基础单句分派状态::分支未完成
        : 多义 || 顶层候选数 > 1 ? 基础单句分派状态::闭集多义待解
        : 顶层候选数 == 0 ? 基础单句分派状态::无闭集句面匹配
        : 待绑定 ? 基础单句分派状态::闭集唯一待绑定
        : 基础单句分派状态::闭集唯一已解;
    return 结果;
}

