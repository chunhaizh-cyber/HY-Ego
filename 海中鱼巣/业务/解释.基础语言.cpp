基础概念上下位输入结果 解释单句概念上下位(
    const 基础概念上下位输入请求& 请求, const 新_语言类& 语言服务,
    const 新_词类& 词服务, const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    auto 初次 = 读取S02一次(请求, 语言服务, 词服务, 名称服务,
        存在概念服务, 特征概念服务);
    switch (初次.结果.状态) {
    case S02状态::已形成唯一含义:
    case S02状态::概念多义待解:
    case S02状态::多规则待解:
    case S02状态::角色不相容: break;
    default: return 初次.结果;
    }
    const auto 最终 = 读取S02一次(请求, 语言服务, 词服务, 名称服务,
        存在概念服务, 特征概念服务);
    if (!S02快照相同(初次, 最终)) {
        初次.结果.状态 = S02状态::引用不可读;
        初次.结果.候选组.clear();
        const auto 标量 = 解码标准UTF8(请求.固定原文);
        初次.结果.未覆盖范围组 = 标量
            ? std::vector<解释原文范围>{{0, 标量->码点.size()}}
            : std::vector<解释原文范围>{};
    }
    return 初次.结果;
}

基础概念上下位可逆表达结果 生成可唯一回读的概念上下位表达(
    const 基础概念上下位可逆表达请求& 请求,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务,
    const 新_存在类& 受询者存在服务) {
    基础概念上下位可逆表达结果 结果{
        基础概念上下位可逆表达状态::输入拒绝, {}, {}, {}};
    const auto& 表达 = 请求.表达;
    if (!请求.最大回读原文标量数 || !请求.最大回读知识条目数
        || !请求.最大回读名称候选数 || !请求.最大回读组合候选数
        || 表达.目的 != 新语言知识表达目的::陈述
        || 表达.操作 != 新语言知识含义操作::概念归类
        || 表达.作用域 != 新语言知识作用域::普通陈述
        || 表达.受询者 || 表达.被询操作 || 表达.确认范围
        || 表达.指代选择 || 表达.网页自我来源
        || 表达.参数组.size() != 2) return 结果;
    const 基础表达参数* 主体 = nullptr;
    const 基础表达参数* 归类 = nullptr;
    for (const auto& 参数 : 表达.参数组) {
        if (参数.参数 == 新语言知识参数角色::主体) 主体 = &参数;
        else if (参数.参数 == 新语言知识参数角色::归类概念) 归类 = &参数;
        else return 结果;
    }
    if (!主体 || !归类 || 主体->种类 != 基础表达参数种类::概念
        || 归类->种类 != 基础表达参数种类::概念
        || 主体->类别 != 归类->类别
        || (主体->类别 != 新语言知识角色类别::存在概念
            && 主体->类别 != 新语言知识角色类别::特征概念)
        || !std::holds_alternative<稳定编码>(主体->内容)
        || !std::holds_alternative<稳定编码>(归类->内容)
        || !有效(std::get<稳定编码>(主体->内容))
        || !有效(std::get<稳定编码>(归类->内容))) return 结果;
    const auto 生成 = 生成基础语言表达(表达, 语言服务, 词服务,
        名称服务, 存在概念服务, 特征概念服务, 受询者存在服务);
    结果.原始表达状态 = 生成.状态;
    if (生成.状态 != 基础表达状态::已生成) {
        结果.状态 = 基础概念上下位可逆表达状态::表达未生成;
        return 结果;
    }
    const auto 回读 = 解释单句概念上下位({生成.文本, 表达.语言节点, {},
        请求.最大回读原文标量数, 请求.最大回读知识条目数,
        请求.最大回读名称候选数, 请求.最大回读组合候选数},
        语言服务, 词服务, 名称服务, 存在概念服务, 特征概念服务);
    结果.回读状态 = 回读.状态;
    if (回读.状态 != S02状态::已形成唯一含义) {
        switch (回读.状态) {
        case S02状态::概念多义待解:
        case S02状态::多规则待解:
        case S02状态::未知词:
        case S02状态::缺名称:
        case S02状态::缺规则:
        case S02状态::角色不相容:
        case S02状态::结构未支持:
            结果.状态 = 基础概念上下位可逆表达状态::回读语义未闭合;
            break;
        default: 结果.状态 = 基础概念上下位可逆表达状态::回读技术未完成;
        }
        return 结果;
    }
    const auto& 对齐 = 生成.对齐组;
    if (!生成.知识节点 || 对齐.size() != 4 || 生成.已用绑定.size() != 2
        || !生成.指代出现组.empty() || 生成.已核验受询者) {
        结果.状态 = 基础概念上下位可逆表达状态::含义不一致;
        return 结果;
    }
    const auto 对齐合法 = [&](std::size_t i) {
        const auto& 项 = 对齐[i];
        return 项.结构项编号 == static_cast<std::int64_t>(i)
            && 项.所属知识节点 == 生成.知识节点
            && 项.结构项路径 == std::vector<std::int64_t>{static_cast<std::int64_t>(i)}
            && 项.起始标量 < 项.结束标量
            && (i == 0 ? 项.起始标量 == 0
                : 项.起始标量 == 对齐[i - 1].结束标量)
            && !项.指代名称关系节点;
    };
    if (!对齐合法(0) || !对齐合法(1) || !对齐合法(2)
        || !对齐合法(3) || !对齐[1].词条节点 || !对齐[2].词条节点
        || 对齐[0].参数 != 新语言知识参数角色::主体
        || 对齐[3].参数 != 新语言知识参数角色::归类概念
        || 对齐[1].参数 || 对齐[2].参数 || 对齐[0].词条节点
        || 对齐[3].词条节点 || !对齐[0].名称关系节点
        || !对齐[3].名称关系节点 || 对齐[1].名称关系节点
        || 对齐[2].名称关系节点
        || (主体->选用名称关系
            && 主体->选用名称关系 != 对齐[0].名称关系节点)
        || (归类->选用名称关系
            && 归类->选用名称关系 != 对齐[3].名称关系节点)) {
        结果.状态 = 基础概念上下位可逆表达状态::含义不一致;
        return 结果;
    }
    const auto 已用参数 = [&](新语言知识参数角色 角色) -> const 基础表达参数* {
        const auto 它 = std::find_if(生成.已用绑定.begin(), 生成.已用绑定.end(),
            [&](const auto& 参数) { return 参数.参数 == 角色; });
        return 它 == 生成.已用绑定.end() ? nullptr : &*它;
    };
    const auto* 已用主体 = 已用参数(新语言知识参数角色::主体);
    const auto* 已用归类 = 已用参数(新语言知识参数角色::归类概念);
    if (!已用主体 || !已用归类
        || 已用主体->类别 != 主体->类别 || 已用归类->类别 != 归类->类别
        || 已用主体->种类 != 主体->种类 || 已用归类->种类 != 归类->种类
        || 已用主体->内容 != 主体->内容 || 已用归类->内容 != 归类->内容
        || 已用主体->选用名称关系 != 对齐[0].名称关系节点
        || 已用归类->选用名称关系 != 对齐[3].名称关系节点) {
        结果.状态 = 基础概念上下位可逆表达状态::含义不一致;
        return 结果;
    }
    for (const auto& 候选 : 回读.候选组) {
        if (候选.类别 != 主体->类别
            || 候选.主体概念节点 != std::get<稳定编码>(主体->内容)
            || 候选.归类概念节点 != std::get<稳定编码>(归类->内容)
            || 候选.所用知识节点 != *生成.知识节点
            || 候选.主体名称关系节点 != *对齐[0].名称关系节点
            || 候选.归类名称关系节点 != *对齐[3].名称关系节点
            || 候选.主体范围.起始标量 != 对齐[0].起始标量
            || 候选.主体范围.结束标量 != 对齐[0].结束标量
            || 候选.归类范围.起始标量 != 对齐[3].起始标量
            || 候选.归类范围.结束标量 != 对齐[3].结束标量) {
            结果.状态 = 基础概念上下位可逆表达状态::含义不一致;
            return 结果;
        }
    }
    if (回读.候选组.empty()) {
        结果.状态 = 基础概念上下位可逆表达状态::含义不一致;
        return 结果;
    }
    结果.状态 = 基础概念上下位可逆表达状态::已生成且可唯一回读;
    结果.可用表达 = 生成;
    return 结果;
}

