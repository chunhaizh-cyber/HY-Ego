S09读取快照 读取S09一次(const 基础概念归类确认输入请求& 请求,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务,
    const 新_存在类& 存在服务) {
    S09读取快照 快照{{S09状态::输入拒绝, 请求.固定原文,
        请求.未核验来源语言记录节点, {}, {}}, {}, {}, {}, {}, {}, {}};
    auto& 结果 = 快照.结果;
    if (!有效(请求.语言节点) || 请求.固定原文.empty()
        || !请求.最大原文标量数 || !请求.最大知识条目数
        || !请求.最大名称候选数 || !请求.最大组合候选数
        || !请求.最大确认候选数
        || (请求.受询者存在节点 && !有效(*请求.受询者存在节点))) return 快照;
    const auto 标量 = 解码标准UTF8(请求.固定原文);
    if (!标量) { 结果.状态 = S09状态::格式失败; return 快照; }
    const auto 总长 = 标量->码点.size();
    if (!总长) return 快照;
    结果.未覆盖范围组.push_back({0, 总长});
    if (总长 > 请求.最大原文标量数) {
        结果.状态 = S09状态::额度不足; return 快照;
    }
    if (不支持的句面(*标量)) {
        结果.状态 = S09状态::结构未支持; return 快照;
    }
    if (请求.受询者存在节点) {
        快照.受询者 = 存在服务.获取存在(*请求.受询者存在节点);
        if (!快照.受询者 || 快照.受询者->节点 != *请求.受询者存在节点) {
            结果.状态 = S09状态::受询者不可读; return 快照;
        }
    }
    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    if (语言.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S09语言状态(语言.状态); return 快照;
    }
    if (!语言.信息 || 语言.信息->节点 != 请求.语言节点) {
        结果.状态 = S09状态::引用不可读; return 快照;
    }
    const auto 匹配 = 语言服务.按已登记词条最长匹配(
        请求.语言节点, 请求.固定原文, 词服务);
    if (匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S09语言状态(匹配.状态); return 快照;
    }
    快照.整句片段组 = 匹配.片段组;
    const auto 知识 = 语言服务.枚举语言知识候选(
        请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
    if (知识.状态 != 新语言知识状态::已完成) {
        结果.状态 = 映射S09知识状态(知识.状态); return 快照;
    }
    快照.知识全集 = 知识.信息组;
    std::vector<新语言知识信息> 规则组;
    std::set<稳定编码> 已见规则;
    for (const auto& 项 : 知识.信息组) {
        if (!是S09结构(项, 请求.语言节点)) continue;
        if (!有效(项.节点) || !已见规则.insert(项.节点).second) {
            结果.状态 = S09状态::内部不一致; return 快照;
        }
        const auto& 结构项 = 项.定义.结构.有序项组;
        const auto 子节点 = std::get<新语言知识子规则项>(结构项[0].载荷).子知识节点;
        const auto 子 = std::find_if(知识.信息组.begin(), 知识.信息组.end(),
            [&](const auto& 信息) { return 信息.节点 == 子节点; });
        if (子 == 知识.信息组.end() || !是S02结构(*子, 请求.语言节点)) {
            结果.状态 = S09状态::引用不可读; return 快照;
        }
        const auto 固定节点 = std::get<新语言知识固定词项>(结构项[1].载荷).词条节点;
        const auto 词 = 词服务.获取词条(固定节点);
        if (词.状态 != 新词条查询状态::已找到) {
            结果.状态 = 映射S09词状态(词.状态); return 快照;
        }
        if (!词.信息 || 词.信息->节点 != 固定节点
            || 词.信息->语言节点 != 请求.语言节点) {
            结果.状态 = S09状态::引用不可读; return 快照;
        }
        快照.外层固定词组.push_back(*词.信息);
        if (词.信息->规范化词面 == "吗") 规则组.push_back(项);
    }
    if (规则组.empty()) { 结果.状态 = S09状态::缺规则; return 快照; }
    if (匹配.片段组.size() < 2) {
        结果.状态 = S09状态::结构未支持; return 快照;
    }
    const auto& 末 = 匹配.片段组.back();
    const auto 末范围 = 解释原文范围{末.原文码点起点,
        末.原文码点起点 + 末.原文码点数量};
    if (!有效范围(末范围, 总长) || 末范围.结束标量 != 总长
        || 末.原文 != "吗" || !末.词条节点) {
        结果.状态 = S09状态::结构未支持; return 快照;
    }
    std::vector<新语言知识信息> 匹配规则;
    for (const auto& 规则 : 规则组)
        if (末.词条节点 == std::get<新语言知识固定词项>(
                规则.定义.结构.有序项组[1].载荷).词条节点)
            匹配规则.push_back(规则);
    if (匹配规则.empty()) {
        结果.状态 = S09状态::结构未支持; return 快照;
    }
    if (末范围.起始标量 == 0 || 末.原文字节起点 == 0
        || 末.原文字节起点 != 标量->字节边界[末范围.起始标量]) {
        结果.状态 = S09状态::结构未支持; return 快照;
    }
    const auto 前缀 = 请求.固定原文.substr(0, 末.原文字节起点);
    const auto 子匹配 = 语言服务.按已登记词条最长匹配(
        请求.语言节点, 前缀, 词服务);
    if (子匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S09语言状态(子匹配.状态); return 快照;
    }
    快照.子句片段组 = 子匹配.片段组;
    if (子匹配.片段组.size() != 匹配.片段组.size() - 1
        || !std::equal(子匹配.片段组.begin(), 子匹配.片段组.end(),
            匹配.片段组.begin())) {
        结果.状态 = S09状态::结构未支持; return 快照;
    }
    const auto 子 = 解释单句概念上下位({前缀, 请求.语言节点,
        请求.未核验来源语言记录节点, 请求.最大原文标量数,
        请求.最大知识条目数, 请求.最大名称候选数,
        请求.最大组合候选数}, 语言服务, 词服务, 名称服务,
        存在概念服务, 特征概念服务);
    快照.子结果 = 子;
    if (子.候选组.empty()) {
        结果.状态 = 映射S09子状态(子.状态);
        if (结果.状态 == S09状态::未知词 || 结果.状态 == S09状态::缺名称
            || 结果.状态 == S09状态::角色不相容)
            结果.未覆盖范围组 = 子.未覆盖范围组;
        return 快照;
    }
    // 子解释必须完整召回；外层预算只计真正被 S09 强引用的组合。
    std::size_t 剩余额度 = 请求.最大确认候选数;
    for (const auto& 规则 : 匹配规则) {
        const auto 子节点 = std::get<新语言知识子规则项>(
            规则.定义.结构.有序项组[0].载荷).子知识节点;
        const auto 数量 = static_cast<std::size_t>(std::count_if(
            子.候选组.begin(), 子.候选组.end(), [&](const auto& 候选) {
                return 候选.所用知识节点 == 子节点;
            }));
        if (数量 > 剩余额度) {
            结果.状态 = S09状态::额度不足; return 快照;
        }
        剩余额度 -= 数量;
    }
    for (const auto& 规则 : 匹配规则) {
        const auto 子节点 = std::get<新语言知识子规则项>(
            规则.定义.结构.有序项组[0].载荷).子知识节点;
        for (const auto& 候选 : 子.候选组) {
            if (候选.所用知识节点 != 子节点) continue;
            结果.候选组.push_back({规则.节点, 子节点, 候选,
                请求.受询者存在节点, {0, 末范围.起始标量}, 末范围});
        }
    }
    if (结果.候选组.empty()) {
        结果.状态 = S09状态::缺规则; return 快照;
    }
    std::sort(结果.候选组.begin(), 结果.候选组.end(), S09候选顺序);
    std::set<std::pair<稳定编码, 稳定编码>> 路径组;
    std::set<std::tuple<新语言知识角色类别, 稳定编码, 稳定编码>> 语义组;
    for (const auto& 候选 : 结果.候选组) {
        路径组.emplace(候选.外层知识节点, 候选.子知识节点);
        语义组.emplace(候选.被询归类.类别,
            候选.被询归类.主体概念节点, 候选.被询归类.归类概念节点);
    }
    结果.状态 = 路径组.size() > 1 ? S09状态::多规则待解
        : 语义组.size() > 1 ? S09状态::概念多义待解
        : 请求.受询者存在节点 ? S09状态::已形成唯一信息请求
        : S09状态::受询者待绑定;
    结果.未覆盖范围组.clear();
    return 快照;
}

bool S09快照相同(const S09读取快照& 左, const S09读取快照& 右) {
    if (左.结果.状态 != 右.结果.状态 || 左.受询者 != 右.受询者
        || 左.整句片段组 != 右.整句片段组
        || 左.子句片段组 != 右.子句片段组
        || 左.外层固定词组 != 右.外层固定词组
        || 左.知识全集.size() != 右.知识全集.size()
        || !std::equal(左.知识全集.begin(), 左.知识全集.end(),
            右.知识全集.begin(), 知识相同)
        || 左.结果.候选组.size() != 右.结果.候选组.size()
        || 左.子结果.has_value() != 右.子结果.has_value()) return false;
    if (左.子结果) {
        const auto& a = *左.子结果;
        const auto& b = *右.子结果;
        if (a.状态 != b.状态 || a.候选组.size() != b.候选组.size()
            || !std::equal(a.候选组.begin(), a.候选组.end(),
                b.候选组.begin(), S02候选相同)) return false;
    }
    return std::equal(左.结果.候选组.begin(), 左.结果.候选组.end(),
        右.结果.候选组.begin(), S09候选相同);
}

