基础组成输入结果 解释单句组成陈述(
    const 基础组成输入请求& 请求, const 新_世界树类& 世界树,
    const 新_场景类& 场景服务, const 新_存在类& 存在服务,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_存在类& 存在概念服务) {
    using 状态 = 基础组成输入状态;
    基础组成输入结果 结果{状态::输入拒绝, 请求.固定原文,
        请求.未核验来源语言记录节点, {}, {}, {}, {}};
    const auto 标量 = 解码标准UTF8(请求.固定原文);
    if (!标量) { 结果.状态 = 状态::格式失败; return 结果; }
    const auto 总长 = 标量->码点.size();
    if (!总长 || !有效(请求.语言节点)
        || !请求.最大原文标量数 || !请求.最大知识条目数) return 结果;
    结果.未覆盖范围组.push_back({0, 总长});
    if (总长 > 请求.最大原文标量数) {
        结果.状态 = 状态::额度不足; return 结果;
    }
    if (不支持的句面(*标量)) {
        结果.状态 = 状态::结构未支持; return 结果;
    }
    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    if (语言.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S05语言状态(语言.状态); return 结果;
    }
    if (!语言.信息 || 语言.信息->节点 != 请求.语言节点) {
        结果.状态 = 状态::内部不一致; return 结果;
    }
    const auto 匹配 = 语言服务.按已登记词条最长匹配(
        请求.语言节点, 请求.固定原文, 词服务);
    if (匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S05语言状态(匹配.状态); return 结果;
    }
    const auto 知识组 = 语言服务.枚举语言知识候选(
        请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
    if (知识组.状态 != 新语言知识状态::已完成) {
        结果.状态 = 映射S05知识状态(知识组.状态); return 结果;
    }
    struct 固定词读回 final {
        稳定编码 节点;
        新词条信息 词;
    };
    std::vector<固定词读回> 已用固定词;
    std::vector<基础组成候选> 所有布局;
    bool 不支持词面有布局 = false, 有S05知识 = false;
    std::set<稳定编码> 已见知识;
    for (const auto& 知识 : 知识组.信息组) {
        if (!有效(知识.节点) || !已见知识.insert(知识.节点).second) {
            结果.状态 = 状态::内部不一致; return 结果;
        }
        if (!是S05结构(知识, 请求.语言节点)) continue;
        有S05知识 = true;
        std::array<稳定编码, 3> 固定节点;
        std::array<std::string, 3> 词面;
        for (std::size_t i = 0; i != 3; ++i) {
            const auto 项号 = std::array<std::size_t, 3>{1, 3, 4}[i];
            固定节点[i] = std::get<新语言知识固定词项>(
                知识.定义.结构.有序项组[项号].载荷).词条节点;
            const auto 词 = 词服务.获取词条(固定节点[i]);
            if (词.状态 != 新词条查询状态::已找到) {
                结果.状态 = 映射S05词状态(词.状态); return 结果;
            }
            if (!词.信息 || 词.信息->节点 != 固定节点[i]
                || 词.信息->语言节点 != 请求.语言节点) {
                结果.状态 = 状态::内部不一致; return 结果;
            }
            已用固定词.push_back({固定节点[i], *词.信息});
            词面[i] = 词.信息->规范化词面;
        }
        const auto 布局组 = 枚举S05布局(匹配.片段组, 固定节点, 总长);
        if (词面 != std::array<std::string, 3>{"是", "的", "一部分"}) {
            不支持词面有布局 |= !布局组.empty();
            continue;
        }
        for (const auto& 布局 : 布局组)
            所有布局.push_back({知识.节点, 布局.部分, 布局.整体,
                布局.是词, 布局.的词, 布局.一部分词, {}, {}});
    }
    if (!有S05知识) { 结果.状态 = 状态::缺规则; return 结果; }
    if (所有布局.empty() && !不支持词面有布局) {
        结果.状态 = 状态::结构未支持; return 结果;
    }
    if (不支持词面有布局) { 结果.状态 = 状态::缺规则; return 结果; }
    if (!请求.部分槽 || !请求.整体槽) {
        const auto 复语言 = 语言服务.获取语言(请求.语言节点);
        if (复语言.状态 != 新语言查询状态::已找到) {
            结果.状态 = 映射S05语言状态(复语言.状态); return 结果;
        }
        if (!复语言.信息 || *复语言.信息 != *语言.信息) {
            结果.状态 = 状态::读取漂移; return 结果;
        }
        for (const auto& 项 : 已用固定词) {
            const auto 复词 = 词服务.获取词条(项.节点);
            if (复词.状态 != 新词条查询状态::已找到) {
                结果.状态 = 映射S05词状态(复词.状态); return 结果;
            }
            if (!复词.信息 || *复词.信息 != 项.词) {
                结果.状态 = 状态::读取漂移; return 结果;
            }
        }
        const auto 复匹配 = 语言服务.按已登记词条最长匹配(
            请求.语言节点, 请求.固定原文, 词服务);
        if (复匹配.状态 != 新语言查询状态::已找到) {
            结果.状态 = 映射S05语言状态(复匹配.状态); return 结果;
        }
        if (复匹配.片段组 != 匹配.片段组) {
            结果.状态 = 状态::读取漂移; return 结果;
        }
        const auto 复知识 = 语言服务.枚举语言知识候选(
            请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
        if (复知识.状态 != 新语言知识状态::已完成) {
            结果.状态 = 映射S05知识状态(复知识.状态); return 结果;
        }
        if (复知识.信息组.size() != 知识组.信息组.size()
            || !std::equal(复知识.信息组.begin(), 复知识.信息组.end(),
                知识组.信息组.begin(), 知识相同)) {
            结果.状态 = 状态::读取漂移; return 结果;
        }
        std::vector<基础组成短语布局候选> 布局组;
        布局组.reserve(所有布局.size());
        for (const auto& 布局 : 所有布局) {
            基础组成短语布局候选 候选{布局.所用知识节点,
                布局.部分范围, 布局.整体范围, 布局.是词范围,
                布局.的词范围, 布局.一部分词范围};
            if (!S05布局自证(候选, 知识组.信息组, 匹配.片段组, 总长)) {
                结果.状态 = 状态::内部不一致; return 结果;
            }
            布局组.push_back(候选);
        }
        std::sort(布局组.begin(), 布局组.end(), S05布局顺序);
        布局组.erase(std::unique(布局组.begin(), 布局组.end(), S05布局相同),
            布局组.end());
        结果.短语布局候选组 = std::move(布局组);
        结果.状态 = 状态::短语定位待提供; return 结果;
    }
    const auto& 部分槽 = *请求.部分槽;
    const auto& 整体槽 = *请求.整体槽;
    if (!有效范围(部分槽.原文范围, 总长)
        || !有效范围(整体槽.原文范围, 总长)
        || !(部分槽.原文范围.结束标量 <= 整体槽.原文范围.起始标量
            || 整体槽.原文范围.结束标量 <= 部分槽.原文范围.起始标量)
        || (部分槽.已消解存在节点 && !有效(*部分槽.已消解存在节点))
        || (整体槽.已消解存在节点 && !有效(*整体槽.已消解存在节点))) return 结果;
    std::vector<基础组成候选> 匹配布局;
    for (auto& 布局 : 所有布局)
        if (S05范围相同(布局.部分范围, 部分槽.原文范围)
            && S05范围相同(布局.整体范围, 整体槽.原文范围)) {
            布局.部分存在节点 = 部分槽.已消解存在节点;
            布局.整体存在节点 = 整体槽.已消解存在节点;
            匹配布局.push_back(布局);
        }
    if (匹配布局.empty()) {
        结果.状态 = 状态::结构未支持; return 结果;
    }
    if (!请求.最大组成候选数
        || 匹配布局.size() > 请求.最大组成候选数) {
        结果.状态 = 状态::额度不足; return 结果;
    }
    const auto 根 = 世界树.获取世界树根场景();
    if (!根 || !有效(*根)) {
        结果.状态 = 状态::世界根不可读; return 结果;
    }
    if (请求.显式所述世界根
        && 请求.显式所述世界根->场景根 != *根) {
        结果.状态 = 状态::世界能力未支持; return 结果;
    }
    if (场景服务.获取根场景() != 根) {
        结果.状态 = 状态::内部不一致; return 结果;
    }
    const auto 成员 = 场景服务.读取本树范围成员完整();
    if (成员.状态 != 新场景范围成员读取状态::已完成) {
        结果.状态 = 映射S05成员状态(成员.状态); return 结果;
    }
    if (成员.根场景节点 != 根) {
        结果.状态 = 状态::内部不一致; return 结果;
    }
    结果.实际所述世界根 = 解释目标世界根{*根};
    std::array<std::optional<新存在信息>, 2> 已用存在;
    const auto 节点组 = std::array{部分槽.已消解存在节点, 整体槽.已消解存在节点};
    for (std::size_t i = 0; i != 2; ++i) {
        if (!节点组[i]) continue;
        已用存在[i] = 存在服务.获取存在(*节点组[i]);
        if (!已用存在[i] || 已用存在[i]->节点 != *节点组[i]) {
            结果.状态 = 状态::引用不可读; return 结果;
        }
        if (std::find(成员.范围成员存在组.begin(),
                成员.范围成员存在组.end(), *节点组[i])
            == 成员.范围成员存在组.end()) {
            结果.状态 = 状态::对象不属于世界; return 结果;
        }
    }
    const auto 复词 = [&]() -> 状态 {
        for (const auto& 项 : 已用固定词) {
            const auto 词 = 词服务.获取词条(项.节点);
            if (词.状态 != 新词条查询状态::已找到)
                return 映射S05词状态(词.状态);
            if (!词.信息 || *词.信息 != 项.词) return 状态::读取漂移;
        }
        return 状态::已形成唯一主张候选;
    }();
    if (复词 != 状态::已形成唯一主张候选) {
        结果.状态 = 复词; return 结果;
    }
    const auto 复匹配 = 语言服务.按已登记词条最长匹配(
        请求.语言节点, 请求.固定原文, 词服务);
    if (复匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S05语言状态(复匹配.状态); return 结果;
    }
    if (复匹配.片段组 != 匹配.片段组) {
        结果.状态 = 状态::读取漂移; return 结果;
    }
    const auto 复知识 = 语言服务.枚举语言知识候选(
        请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
    if (复知识.状态 != 新语言知识状态::已完成) {
        结果.状态 = 映射S05知识状态(复知识.状态); return 结果;
    }
    if (复知识.信息组.size() != 知识组.信息组.size()
        || !std::equal(复知识.信息组.begin(), 复知识.信息组.end(),
            知识组.信息组.begin(), 知识相同)) {
        结果.状态 = 状态::读取漂移; return 结果;
    }
    const auto 复成员 = 场景服务.读取本树范围成员完整();
    if (复成员.状态 != 新场景范围成员读取状态::已完成) {
        结果.状态 = 映射S05成员状态(复成员.状态); return 结果;
    }
    if (世界树.获取世界树根场景() != 根
        || 场景服务.获取根场景() != 根
        || !S05成员相同(成员, 复成员)) {
        结果.状态 = 状态::读取漂移; return 结果;
    }
    for (std::size_t i = 0; i != 2; ++i)
        if (节点组[i] && 存在服务.获取存在(*节点组[i]) != 已用存在[i]) {
            结果.状态 = 状态::读取漂移; return 结果;
        }
    结果.候选组 = std::move(匹配布局);
    if (结果.候选组.size() > 1) 结果.状态 = 状态::多规则待解;
    else if (!部分槽.已消解存在节点 || !整体槽.已消解存在节点)
        结果.状态 = 状态::对象待绑定;
    else 结果.状态 = 状态::已形成唯一主张候选;
    结果.未覆盖范围组.clear();
    if (!部分槽.已消解存在节点)
        结果.未覆盖范围组.push_back(部分槽.原文范围);
    if (!整体槽.已消解存在节点)
        结果.未覆盖范围组.push_back(整体槽.原文范围);
    return 结果;
}

