bool 是S05结构(const 新语言知识信息& 知识, 稳定编码 语言节点) {
    const auto& 定义 = 知识.定义;
    if (定义.结构.语言节点 != 语言节点
        || 定义.结构.类别 != 新语言知识结构类别::基础表达
        || 定义.结构.有序项组.size() != 5
        || 定义.目标.目的 != 新语言知识表达目的::陈述
        || !定义.目标.适用条件组.empty()
        || 定义.目标.角色组.size() != 2
        || 定义.目标.含义组.size() != 1) return false;
    const auto& 角色 = 定义.目标.角色组;
    const auto 找角色 = [&](std::int64_t 编号) {
        return std::find_if(角色.begin(), 角色.end(),
            [&](const auto& 项) { return 项.局部编号 == 编号; });
    };
    const auto 部分 = 找角色(0), 整体 = 找角色(1);
    if (部分 == 角色.end() || 整体 == 角色.end()
        || !角色是(*部分, 0, 新语言知识角色种类::领域对象引用,
            新语言知识角色类别::存在)
        || !角色是(*整体, 1, 新语言知识角色种类::领域对象引用,
            新语言知识角色类别::存在)) return false;
    const auto& 含义 = 定义.目标.含义组.front();
    if (含义.局部编号 != 0
        || 含义.操作 != 新语言知识含义操作::组成描述
        || 含义.作用域 != 新语言知识作用域::普通陈述
        || 含义.特征值分支 || 含义.被询含义 || 含义.确认范围
        || 含义.参数组.size() != 2) return false;
    const auto 有参数 = [&](新语言知识参数角色 参数, std::int64_t 编号) {
        return std::count_if(含义.参数组.begin(), 含义.参数组.end(),
            [&](const auto& 项) { return 项.参数 == 参数 && 项.规则角色 == 编号; }) == 1;
    };
    if (!有参数(新语言知识参数角色::部分, 0)
        || !有参数(新语言知识参数角色::整体, 1)) return false;
    const auto& 项 = 定义.结构.有序项组;
    for (std::size_t i = 0; i != 5; ++i)
        if (项[i].局部编号 != static_cast<std::int64_t>(i)) return false;
    const auto* 左 = std::get_if<新语言知识角色表达项>(&项[0].载荷);
    const auto* 中 = std::get_if<新语言知识角色表达项>(&项[2].载荷);
    if (!左 || !中 || 左->规则角色 != 0 || 中->规则角色 != 1
        || 左->方式 != 新语言知识表达方式::明确对象描述
        || 中->方式 != 新语言知识表达方式::明确对象描述
        || 左->指代概念节点 || 中->指代概念节点) return false;
    for (const auto i : {1u, 3u, 4u}) {
        const auto* 固定 = std::get_if<新语言知识固定词项>(&项[i].载荷);
        if (!固定 || !有效(固定->词条节点)) return false;
    }
    return true;
}

