基础现实对象短语候选结果 枚举现实对象短语概念候选(
    const 基础现实对象短语候选请求& 请求, const 新_世界树类& 世界树,
    const 新_场景类& 场景服务, const 新_存在类& 存在服务,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    try {
        auto 首读 = 读取对象一次(请求, 世界树, 场景服务, 存在服务,
            语言服务, 词服务, 名称服务, 存在概念服务, 特征概念服务);
        switch (首读.结果.状态) {
        case 对象状态::已形成完整评估:
        case 对象状态::无抽象存在概念名称:
        case 对象状态::缺名称:
        case 对象状态::内部不一致:
        case 对象状态::引用不可读:
            break;
        default:
            首读.结果.评估组.clear();
            首读.结果.未过滤名称候选组.clear();
            return 首读.结果;
        }
        const auto 复读 = 读取对象一次(请求, 世界树, 场景服务, 存在服务,
            语言服务, 词服务, 名称服务, 存在概念服务, 特征概念服务);
        if (!对象快照相同(首读, 复读)) {
            switch (复读.结果.状态) {
            case 对象状态::资源失败:
            case 对象状态::工程未完成:
                首读.结果.状态 = 复读.结果.状态; break;
            default: 首读.结果.状态 = 对象状态::读取漂移;
            }
            首读.结果.评估组.clear();
            首读.结果.未过滤名称候选组.clear();
            首读.结果.实际所述世界根.reset();
        }
        if (首读.结果.状态 != 对象状态::已形成完整评估
            && 首读.结果.状态 != 对象状态::无抽象存在概念名称)
            首读.结果.未过滤名称候选组.clear();
        if (首读.结果.状态 != 对象状态::已形成完整评估)
            首读.结果.评估组.clear();
        return 首读.结果;
    } catch (const std::bad_alloc&) {
        return {对象状态::资源失败, {},
            请求.语言节点, 请求.未核验来源语言记录节点,
            {}, 请求.短语范围, {}, {}, {}, {}};
    } catch (const std::length_error&) {
        return {对象状态::资源失败, {},
            请求.语言节点, 请求.未核验来源语言记录节点,
            {}, 请求.短语范围, {}, {}, {}, {}};
    }
}

