单句分支裁决 裁决分支(const 基础组成输入结果& 结果) {
    const auto 有效候选 = [](const 基础组成候选& 候选) {
        return 有效(候选.所用知识节点)
            && 候选.部分范围.起始标量 < 候选.部分范围.结束标量
            && 候选.整体范围.起始标量 < 候选.整体范围.结束标量;
    };
    switch (结果.状态) {
    case 基础组成输入状态::已形成唯一主张候选:
        return 结果.候选组.size() == 1
            && 有效候选(结果.候选组.front())
            && 结果.候选组.front().部分存在节点
            && 结果.候选组.front().整体存在节点
            ? 单句分支裁决::唯一 : 单句分支裁决::内部不一致;
    case 基础组成输入状态::对象待绑定:
        return 结果.候选组.size() == 1
            && 有效候选(结果.候选组.front())
            && (!结果.候选组.front().部分存在节点
                || !结果.候选组.front().整体存在节点)
            ? 单句分支裁决::待绑定 : 单句分支裁决::内部不一致;
    case 基础组成输入状态::多规则待解:
        return 结果.候选组.size() > 1
            && std::all_of(结果.候选组.begin(), 结果.候选组.end(), 有效候选)
            ? 单句分支裁决::多义 : 单句分支裁决::内部不一致;
    case 基础组成输入状态::结构未支持:
        return 结果.候选组.empty() ? 单句分支裁决::句面不匹配
            : 单句分支裁决::内部不一致;
    default: return 结果.候选组.empty() ? 单句分支裁决::未完成
        : 单句分支裁决::内部不一致;
    }
}

