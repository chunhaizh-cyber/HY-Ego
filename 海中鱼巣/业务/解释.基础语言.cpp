bool 是S03概念结构(const 新语言知识信息& 知识, 稳定编码 语言节点) {
    const auto& 定义 = 知识.定义;
    if (定义.结构.语言节点 != 语言节点
        || 定义.结构.类别 != 新语言知识结构类别::基础表达
        || 定义.结构.有序项组.size() != 6
        || 定义.目标.目的 != 新语言知识表达目的::陈述
        || !定义.目标.适用条件组.empty()
        || 定义.目标.角色组.size() != 3
        || 定义.目标.含义组.size() != 1) return false;
    for (std::int64_t i = 0; i != 3; ++i) {
        const auto 角色 = std::find_if(定义.目标.角色组.begin(),
            定义.目标.角色组.end(),
            [&](const auto& 项) { return 项.局部编号 == i; });
        if (角色 == 定义.目标.角色组.end()
            || !角色是(*角色, i,
                i == 0 ? 新语言知识角色种类::领域对象引用
                    : i == 1 ? 新语言知识角色种类::特征类型引用
                        : 新语言知识角色种类::概念引用,
                i == 0 ? 新语言知识角色类别::存在
                    : i == 1 ? 新语言知识角色类别::正式特征类型
                        : 新语言知识角色类别::特征概念)) return false;
    }
    const auto& 含义 = 定义.目标.含义组.front();
    if (含义.局部编号 != 0
        || 含义.操作 != 新语言知识含义操作::特征描述
        || 含义.作用域 != 新语言知识作用域::普通陈述
        || 含义.特征值分支 != 新语言知识特征值分支::概念条件
        || 含义.被询含义 || 含义.确认范围
        || 含义.参数组.size() != 3) return false;
    const auto 有参数 = [&](新语言知识参数角色 参数, std::int64_t 编号) {
        return std::count_if(含义.参数组.begin(), 含义.参数组.end(),
            [&](const auto& 项) { return 项.参数 == 参数 && 项.规则角色 == 编号; }) == 1;
    };
    if (!有参数(新语言知识参数角色::主体, 0)
        || !有参数(新语言知识参数角色::特征类型, 1)
        || !有参数(新语言知识参数角色::特征值, 2)) return false;
    const auto& 项 = 定义.结构.有序项组;
    for (std::size_t i = 0; i != 6; ++i)
        if (项[i].局部编号 != static_cast<std::int64_t>(i)) return false;
    for (const auto [位置, 角色, 方式] :
        std::array<std::tuple<std::size_t, std::int64_t, 新语言知识表达方式>, 3>{
            std::tuple{0u, 0ll, 新语言知识表达方式::明确对象描述},
            std::tuple{2u, 1ll, 新语言知识表达方式::名称表达},
            std::tuple{5u, 2ll, 新语言知识表达方式::名称表达}}) {
        const auto* 表达 = std::get_if<新语言知识角色表达项>(&项[位置].载荷);
        if (!表达 || 表达->规则角色 != 角色 || 表达->方式 != 方式
            || 表达->指代概念节点) return false;
    }
    for (const auto i : {1u, 3u, 4u}) {
        const auto* 固定 = std::get_if<新语言知识固定词项>(&项[i].载荷);
        if (!固定 || !有效(固定->词条节点)) return false;
    }
    return true;
}

S03状态 映射S03(S02状态 状态) {
    switch (状态) {
    case S02状态::已形成唯一含义: return S03状态::已形成唯一主张候选;
    case S02状态::缺名称: return S03状态::缺名称;
    case S02状态::角色不相容: return S03状态::角色不相容;
    case S02状态::能力未支持: return S03状态::能力未支持;
    case S02状态::输入拒绝: return S03状态::输入拒绝;
    case S02状态::引用不可读: return S03状态::引用不可读;
    case S02状态::额度不足: return S03状态::额度不足;
    case S02状态::内部不一致: return S03状态::内部不一致;
    case S02状态::工程未完成: return S03状态::工程未完成;
    default: return S03状态::引用不可读;
    }
}
S03状态 映射S03成员(新场景范围成员读取状态 状态) {
    switch (状态) {
    case 新场景范围成员读取状态::根不可读: return S03状态::世界根不可读;
    case 新场景范围成员读取状态::读取已变化: return S03状态::读取漂移;
    case 新场景范围成员读取状态::结构不一致: return S03状态::内部不一致;
    default: return S03状态::工程未完成;
    }
}
S03状态 映射S03比较(特征概念规则状态 状态) {
    switch (状态) {
    case 特征概念规则状态::值不存在: return S03状态::引用不可读;
    case 特征概念规则状态::资源失败:
    case 特征概念规则状态::读取接口未装配: return S03状态::工程未完成;
    case 特征概念规则状态::入口拒绝:
    case 特征概念规则状态::规则不支持: return S03状态::能力未支持;
    default: return S03状态::内部不一致;
    }
}

bool S03范围相同(解释原文范围 左, 解释原文范围 右) noexcept {
    return 左.起始标量 == 右.起始标量
        && 左.结束标量 == 右.结束标量;
}
