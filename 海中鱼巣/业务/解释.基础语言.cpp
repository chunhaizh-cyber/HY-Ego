bool S02候选顺序(const 基础概念上下位候选& 左,
    const 基础概念上下位候选& 右) {
    return std::tie(左.所用知识节点, 左.类别, 左.主体概念节点,
        左.归类概念节点, 左.主体名称关系节点, 左.归类名称关系节点)
        < std::tie(右.所用知识节点, 右.类别, 右.主体概念节点,
            右.归类概念节点, 右.主体名称关系节点, 右.归类名称关系节点);
}
bool S02候选相同(const 基础概念上下位候选& 左,
    const 基础概念上下位候选& 右) {
    return !S02候选顺序(左, 右) && !S02候选顺序(右, 左)
        && 左.主体范围.起始标量 == 右.主体范围.起始标量
        && 左.主体范围.结束标量 == 右.主体范围.结束标量
        && 左.归类范围.起始标量 == 右.归类范围.起始标量
        && 左.归类范围.结束标量 == 右.归类范围.结束标量;
}

S02状态 读取S02内容槽(稳定编码 词条节点, 稳定编码 语言节点,
    const 新语言词条匹配片段& 片段, std::size_t 最大名称候选数,
    const 新_词类& 词服务, const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务, S02词槽& 槽) {
    const auto 词 = 词服务.获取词条(词条节点);
    if (词.状态 != 新词条查询状态::已找到) return 映射S02词状态(词.状态);
    if (!词.信息 || 词.信息->节点 != 词条节点
        || 词.信息->语言节点 != 语言节点
        || 词.信息->规范化词面 != 片段.原文) return S02状态::引用不可读;
    槽.词 = *词.信息;
    const auto 列表 = 名称服务.查询词条候选概念(词条节点);
    if (列表.状态 == 概念名称关系查询状态::未找到) return S02状态::缺名称;
    if (列表.状态 != 概念名称关系查询状态::已找到)
        return 映射S02名称状态(列表.状态);
    if (列表.名称关系节点组.size() > 最大名称候选数) return S02状态::额度不足;
    槽.全关系节点组 = 列表.名称关系节点组;
    std::set<稳定编码> 已见;
    for (const auto 节点 : 列表.名称关系节点组) {
        if (!有效(节点) || !已见.insert(节点).second) return S02状态::内部不一致;
        auto 失败状态 = 基础语言输入状态::引用不可读;
        const auto 读回 = 读取强类型名称(节点, 词条节点, 名称服务,
            存在概念服务, 特征概念服务, 失败状态);
        if (!读回) {
            switch (失败状态) {
            case 基础语言输入状态::工程未完成: return S02状态::工程未完成;
            case 基础语言输入状态::内部不一致: return S02状态::内部不一致;
            default: return S02状态::引用不可读;
            }
        }
        if (const auto* 普通 = std::get_if<普通名称候选读回>(&*读回)) {
            if (普通->名称关系.词条节点 != 词条节点
                || 普通->名称关系.概念节点 != std::visit(
                    [](const auto& 信息) { return 信息.节点; }, 普通->目标概念))
                return S02状态::引用不可读;
        } else {
            const auto& 指代 = std::get<指代名称关系信息>(*读回);
            if (指代.词条 != *词.信息 || 指代.语言.节点 != 语言节点)
                return S02状态::引用不可读;
        }
        槽.全名称组.push_back(*读回);
    }
    return S02状态::已形成唯一含义;
}

S02读取快照 读取S02一次(const 基础概念上下位输入请求& 请求,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    S02读取快照 快照{{S02状态::输入拒绝, 请求.固定原文,
        请求.未核验来源语言记录节点, {}, {}}, {}, {}, {}, {}, {}};
    auto& 结果 = 快照.结果;
    if (!有效(请求.语言节点) || 请求.固定原文.empty()
        || !请求.最大原文标量数 || !请求.最大知识条目数
        || !请求.最大名称候选数 || !请求.最大组合候选数) return 快照;
    const auto 标量 = 解码标准UTF8(请求.固定原文);
    if (!标量) { 结果.状态 = S02状态::格式失败; return 快照; }
    const auto 总长 = 标量->码点.size();
    if (总长 == 0) return 快照;
    结果.未覆盖范围组.push_back({0, 总长});
    if (总长 > 请求.最大原文标量数) {
        结果.状态 = S02状态::额度不足; return 快照;
    }
    if (不支持的句面(*标量)) {
        结果.状态 = S02状态::结构未支持; return 快照;
    }
    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    if (语言.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S02语言状态(语言.状态); return 快照;
    }
    if (!语言.信息 || 语言.信息->节点 != 请求.语言节点) {
        结果.状态 = S02状态::引用不可读; return 快照;
    }
    const auto 匹配 = 语言服务.按已登记词条最长匹配(
        请求.语言节点, 请求.固定原文, 词服务);
    if (匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射S02语言状态(匹配.状态); return 快照;
    }
    快照.匹配片段组 = 匹配.片段组;
    const auto 知识 = 语言服务.枚举语言知识候选(
        请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
    if (知识.状态 != 新语言知识状态::已完成) {
        结果.状态 = 映射S02知识状态(知识.状态); return 快照;
    }
    快照.知识全集 = 知识.信息组;
    std::vector<新语言知识信息> 规则组;
    std::set<稳定编码> 已见规则;
    for (const auto& 项 : 知识.信息组) {
        if (!是S02结构(项, 请求.语言节点)) continue;
        if (!有效(项.节点) || !已见规则.insert(项.节点).second) {
            结果.状态 = S02状态::内部不一致; return 快照;
        }
        bool 合法固定 = true;
        for (const auto& [位置, 词面] : std::array<std::pair<std::size_t, const char*>, 2>{
                std::pair<std::size_t, const char*>{1, "是"}, {2, "一种"}}) {
            const auto 节点 = std::get<新语言知识固定词项>(
                项.定义.结构.有序项组[位置].载荷).词条节点;
            const auto 词 = 词服务.获取词条(节点);
            if (词.状态 != 新词条查询状态::已找到) {
                结果.状态 = 映射S02词状态(词.状态); return 快照;
            }
            if (!词.信息 || 词.信息->节点 != 节点
                || 词.信息->语言节点 != 请求.语言节点) {
                结果.状态 = S02状态::引用不可读; return 快照;
            }
            快照.规则固定词组.push_back(*词.信息);
            if (词.信息->规范化词面 != 词面) 合法固定 = false;
        }
        if (合法固定) 规则组.push_back(项);
    }
    if (规则组.empty()) { 结果.状态 = S02状态::缺规则; return 快照; }
    if (匹配.片段组.size() != 4) {
        结果.状态 = S02状态::结构未支持; return 快照;
    }
    const auto& 片 = 匹配.片段组;
    std::array<解释原文范围, 4> 范围;
    for (std::size_t i = 0; i != 4; ++i) {
        范围[i] = {片[i].原文码点起点,
            片[i].原文码点起点 + 片[i].原文码点数量};
        if (!有效范围(范围[i], 总长)
            || (i == 0 ? 范围[i].起始标量 != 0
                : 范围[i].起始标量 != 范围[i - 1].结束标量)) {
            结果.状态 = S02状态::结构未支持; return 快照;
        }
    }
    if (范围[3].结束标量 != 总长) {
        结果.状态 = S02状态::结构未支持; return 快照;
    }
    std::vector<新语言知识信息> 匹配规则;
    for (const auto& 规则 : 规则组) {
        const auto& 项 = 规则.定义.结构.有序项组;
        if (片[1].词条节点 == std::get<新语言知识固定词项>(项[1].载荷).词条节点
            && 片[2].词条节点 == std::get<新语言知识固定词项>(项[2].载荷).词条节点
            && 片[1].原文 == "是" && 片[2].原文 == "一种")
            匹配规则.push_back(规则);
    }
    if (匹配规则.empty()) {
        结果.状态 = S02状态::结构未支持; return 快照;
    }
    if (!片[0].词条节点 || !片[3].词条节点) {
        结果.状态 = S02状态::未知词;
        结果.未覆盖范围组.clear();
        if (!片[0].词条节点) 结果.未覆盖范围组.push_back(范围[0]);
        if (!片[3].词条节点) 结果.未覆盖范围组.push_back(范围[3]);
        return 快照;
    }
    bool 缺名称 = false;
    for (std::size_t i = 0; i != 2; ++i) {
        S02词槽 槽;
        const auto 位置 = i == 0 ? 0 : 3;
        const auto 状态 = 读取S02内容槽(*片[位置].词条节点, 请求.语言节点,
            片[位置], 请求.最大名称候选数, 词服务, 名称服务,
            存在概念服务, 特征概念服务, 槽);
        if (状态 == S02状态::缺名称) { 缺名称 = true; continue; }
        if (状态 != S02状态::已形成唯一含义) {
            结果.状态 = 状态; return 快照;
        }
        快照.内容槽[i] = std::move(槽);
        const auto& 名称组 = 快照.内容槽[i]->全名称组;
        if (std::none_of(名称组.begin(), 名称组.end(),
                [](const auto& 名称) { return std::holds_alternative<普通名称候选读回>(名称); }))
            缺名称 = true;
    }
    if (缺名称) {
        结果.状态 = S02状态::缺名称;
        结果.未覆盖范围组.clear();
        for (std::size_t i = 0; i != 2; ++i) {
            const auto& 槽 = 快照.内容槽[i];
            if (!槽 || std::none_of(槽->全名称组.begin(), 槽->全名称组.end(),
                    [](const auto& 名称) { return std::holds_alternative<普通名称候选读回>(名称); }))
                结果.未覆盖范围组.push_back(范围[i == 0 ? 0 : 3]);
        }
        return 快照;
    }
    std::array<std::vector<普通名称候选读回>, 2> 普通组;
    for (std::size_t i = 0; i != 2; ++i)
        for (const auto& 名称 : 快照.内容槽[i]->全名称组)
            if (const auto* 普通 = std::get_if<普通名称候选读回>(&名称))
                普通组[i].push_back(*普通);
    const auto 限额 = 请求.最大组合候选数;
    if (普通组[0].size() > 限额
        || 普通组[1].size() > 限额 / 普通组[0].size()
        || 匹配规则.size() > 限额 / (普通组[0].size() * 普通组[1].size())) {
        结果.状态 = S02状态::额度不足; return 快照;
    }
    for (const auto& 规则 : 匹配规则)
        for (const auto& 左 : 普通组[0])
            for (const auto& 右 : 普通组[1]) {
                if (左.目标概念.index() != 右.目标概念.index()) continue;
                const auto 类别 = 左.目标概念.index() == 0
                    ? 新语言知识角色类别::存在概念
                    : 新语言知识角色类别::特征概念;
                if (类别 == 新语言知识角色类别::特征概念) {
                    const auto 比较 = 特征概念服务.比较单特征概念(
                        左.名称关系.概念节点, 右.名称关系.概念节点);
                    快照.同根比较组.push_back(比较);
                    const auto 状态 = 核验S02同根(比较);
                    if (状态 == S02状态::角色不相容) continue;
                    if (状态 != S02状态::已形成唯一含义) {
                        结果.状态 = 状态;
                        结果.候选组.clear();
                        return 快照;
                    }
                }
                结果.候选组.push_back({类别, 左.名称关系.概念节点,
                    右.名称关系.概念节点, 左.名称关系.节点,
                    右.名称关系.节点, 规则.节点, 范围[0], 范围[3]});
            }
    if (结果.候选组.empty()) {
        结果.状态 = S02状态::角色不相容;
        结果.未覆盖范围组.clear();
        return 快照;
    }
    std::sort(结果.候选组.begin(), 结果.候选组.end(), S02候选顺序);
    std::set<std::tuple<新语言知识角色类别, 稳定编码, 稳定编码>> 语义组;
    for (const auto& 候选 : 结果.候选组)
        语义组.emplace(候选.类别, 候选.主体概念节点, 候选.归类概念节点);
    结果.状态 = 匹配规则.size() > 1 ? S02状态::多规则待解
        : 语义组.size() > 1 ? S02状态::概念多义待解
        : S02状态::已形成唯一含义;
    结果.未覆盖范围组.clear();
    return 快照;
}

bool S02快照相同(const S02读取快照& 左, const S02读取快照& 右) {
    if (左.结果.状态 != 右.结果.状态
        || 左.匹配片段组 != 右.匹配片段组
        || 左.知识全集.size() != 右.知识全集.size()
        || !std::equal(左.知识全集.begin(), 左.知识全集.end(),
            右.知识全集.begin(), 知识相同)
        || 左.规则固定词组 != 右.规则固定词组
        || 左.同根比较组.size() != 右.同根比较组.size()
        || 左.结果.候选组.size() != 右.结果.候选组.size()) return false;
    for (std::size_t i = 0; i != 左.同根比较组.size(); ++i) {
        const auto& a = 左.同根比较组[i];
        const auto& b = 右.同根比较组[i];
        if (a.状态 != b.状态 || a.关系 != b.关系
            || a.特征类型根 != b.特征类型根
            || a.最近共同上位 != b.最近共同上位) return false;
    }
    for (std::size_t i = 0; i != 2; ++i) {
        if (左.内容槽[i].has_value() != 右.内容槽[i].has_value()) return false;
        if (!左.内容槽[i]) continue;
        const auto& a = *左.内容槽[i];
        const auto& b = *右.内容槽[i];
        if (a.词 != b.词 || a.全关系节点组 != b.全关系节点组
            || a.全名称组.size() != b.全名称组.size()
            || !std::equal(a.全名称组.begin(), a.全名称组.end(),
                b.全名称组.begin(), 名称相同)) return false;
    }
    return std::equal(左.结果.候选组.begin(), 左.结果.候选组.end(),
        右.结果.候选组.begin(), S02候选相同);
}

