struct 原文标量 final {
    std::vector<std::uint32_t> 码点;
    std::vector<std::size_t> 字节边界{0};
};

std::optional<原文标量> 解码标准UTF8(const std::string& 原文) {
    原文标量 结果;
    for (std::size_t i = 0; i < 原文.size();) {
        const auto 首 = static_cast<unsigned char>(原文[i]);
        std::size_t 长度 = 0;
        std::uint32_t 值 = 0, 最小值 = 0;
        if (首 < 0x80) { 长度 = 1; 值 = 首; }
        else if (首 >= 0xC2 && 首 <= 0xDF) { 长度 = 2; 值 = 首 & 0x1F; 最小值 = 0x80; }
        else if (首 >= 0xE0 && 首 <= 0xEF) { 长度 = 3; 值 = 首 & 0x0F; 最小值 = 0x800; }
        else if (首 >= 0xF0 && 首 <= 0xF4) { 长度 = 4; 值 = 首 & 0x07; 最小值 = 0x10000; }
        else return std::nullopt;
        if (长度 > 原文.size() - i) return std::nullopt;
        for (std::size_t j = 1; j < 长度; ++j) {
            const auto 后 = static_cast<unsigned char>(原文[i + j]);
            if ((后 & 0xC0) != 0x80) return std::nullopt;
            值 = (值 << 6) | (后 & 0x3F);
        }
        if ((长度 > 1 && 值 < 最小值) || 值 > 0x10FFFF
            || (值 >= 0xD800 && 值 <= 0xDFFF)) return std::nullopt;
        i += 长度;
        结果.码点.push_back(值);
        结果.字节边界.push_back(i);
    }
    return 结果;
}

bool 有效范围(解释原文范围 范围, std::size_t 总长) noexcept {
    return 范围.起始标量 < 范围.结束标量 && 范围.结束标量 <= 总长;
}

bool 不支持的句面(const 原文标量& 原文) {
    for (auto c : 原文.码点) {
        if (c <= 0x20 || c == 0x7F || c == 0xFEFF || c == 0xFFFD
            || c == 0x3002 || c == 0xFF01 || c == 0xFF1F
            || c == 0xFF0C || c == 0x3001 || c == 0xFF1B
            || c == 0xFF1A || c == 0x201C || c == 0x201D
            || c == 0x2018 || c == 0x2019 || c == 0x300A
            || c == 0x300B || c == 0x300C || c == 0x300D
            || c == '?' || c == '!' || c == ',' || c == ';'
            || c == ':' || c == '(' || c == ')'
            || c == '\'' || c == '"' || c == '[' || c == ']') return true;
    }
    return false;
}

bool 角色是(const 新语言知识角色定义& 角色, std::int64_t 编号,
    新语言知识角色种类 种类, 新语言知识角色类别 类别) {
    return 角色.局部编号 == 编号 && 角色.种类 == 种类
        && 角色.数量 == 新语言知识角色数量::单项
        && 角色.必要约束组.size() == 1
        && 角色.必要约束组.front().被约束角色 == 编号
        && 角色.必要约束组.front().允许类别组
            == std::vector<新语言知识角色类别>{类别};
}

bool 是S01结构(const 新语言知识信息& 知识) {
    const auto& 定义 = 知识.定义;
    if (定义.目标.目的 != 新语言知识表达目的::陈述
        || !定义.目标.适用条件组.empty()
        || 定义.目标.角色组.size() != 2 || 定义.目标.含义组.size() != 1
        || 定义.结构.类别 != 新语言知识结构类别::基础表达
        || 定义.结构.有序项组.size() != 3) return false;
    const auto 找角色 = [&](std::int64_t 编号) {
        return std::find_if(定义.目标.角色组.begin(), 定义.目标.角色组.end(),
            [&](const auto& 角色) { return 角色.局部编号 == 编号; });
    };
    const auto 主体 = 找角色(0), 归类 = 找角色(1);
    if (主体 == 定义.目标.角色组.end() || 归类 == 定义.目标.角色组.end()
        || !角色是(*主体, 0, 新语言知识角色种类::领域对象引用,
            新语言知识角色类别::存在)
        || !角色是(*归类, 1, 新语言知识角色种类::概念引用,
            新语言知识角色类别::存在概念)) return false;
    const auto& 含义 = 定义.目标.含义组.front();
    if (含义.操作 != 新语言知识含义操作::概念归类
        || 含义.作用域 != 新语言知识作用域::普通陈述
        || 含义.特征值分支 || 含义.被询含义 || 含义.确认范围
        || 含义.参数组.size() != 2) return false;
    const auto 有参数 = [&](新语言知识参数角色 参数, std::int64_t 角色) {
        return std::count_if(含义.参数组.begin(), 含义.参数组.end(),
            [&](const auto& 项) { return 项.参数 == 参数 && 项.规则角色 == 角色; }) == 1;
    };
    if (!有参数(新语言知识参数角色::主体, 0)
        || !有参数(新语言知识参数角色::归类概念, 1)) return false;
    const auto& 项 = 定义.结构.有序项组;
    if (项[0].局部编号 != 0 || 项[1].局部编号 != 1
        || 项[2].局部编号 != 2) return false;
    const auto* 左 = std::get_if<新语言知识角色表达项>(&项[0].载荷);
    const auto* 中 = std::get_if<新语言知识固定词项>(&项[1].载荷);
    const auto* 右 = std::get_if<新语言知识角色表达项>(&项[2].载荷);
    return 左 && 中 && 右 && 左->规则角色 == 0
        && 左->方式 == 新语言知识表达方式::明确对象描述
        && !左->指代概念节点 && 右->规则角色 == 1
        && 右->方式 == 新语言知识表达方式::名称表达
        && !右->指代概念节点 && 有效(中->词条节点);
}

bool 知识相同(const 新语言知识信息& 左, const 新语言知识信息& 右) {
    return 左.节点 == 右.节点 && 左.目标节点 == 右.目标节点
        && 左.结构节点 == 右.结构节点 && 左.定义 == 右.定义
        && 左.来源组 == 右.来源组;
}

基础语言输入状态 映射语言状态(新语言查询状态 状态) {
    switch (状态) {
    case 新语言查询状态::未找到: return 基础语言输入状态::引用不可读;
    case 新语言查询状态::输入不合法: return 基础语言输入状态::输入拒绝;
    case 新语言查询状态::资源失败: return 基础语言输入状态::工程未完成;
    default: return 基础语言输入状态::内部不一致;
    }
}
基础语言输入状态 映射知识状态(新语言知识状态 状态) {
    switch (状态) {
    case 新语言知识状态::未找到: return 基础语言输入状态::缺规则;
    case 新语言知识状态::额度不足: return 基础语言输入状态::额度不足;
    case 新语言知识状态::工程未完成: return 基础语言输入状态::工程未完成;
    case 新语言知识状态::输入拒绝: return 基础语言输入状态::输入拒绝;
    case 新语言知识状态::内部不一致: return 基础语言输入状态::内部不一致;
    default: return 基础语言输入状态::引用不可读;
    }
}
基础语言输入状态 映射名称状态(概念名称关系查询状态 状态) {
    switch (状态) {
    case 概念名称关系查询状态::未找到: return 基础语言输入状态::缺名称;
    case 概念名称关系查询状态::资源失败:
    case 概念名称关系查询状态::工程未完成: return 基础语言输入状态::工程未完成;
    case 概念名称关系查询状态::结构不一致: return 基础语言输入状态::内部不一致;
    default: return 基础语言输入状态::引用不可读;
    }
}

std::optional<语言名称候选读回> 读取强类型名称(稳定编码 节点,
    稳定编码 词条, const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务, const 概念_特征类& 特征概念服务,
    基础语言输入状态& 失败状态) {
    失败状态 = 基础语言输入状态::引用不可读;
    const auto 指代 = 名称服务.获取指代名称关系(节点);
    if (指代.状态 == 指代名称读取状态::已读取) {
        if (!指代.信息 || 指代.信息->节点 != 节点
            || 指代.信息->词条.节点 != 词条
            || 指代.信息->词条.语言节点 != 指代.信息->语言.节点
            || 指代.信息->概念.节点 == 稳定编码{}) return std::nullopt;
        return 语言名称候选读回{*指代.信息};
    }
    if (指代.状态 != 指代名称读取状态::未找到) {
        if (指代.状态 == 指代名称读取状态::资源失败
            || 指代.状态 == 指代名称读取状态::工程未完成)
            失败状态 = 基础语言输入状态::工程未完成;
        else if (指代.状态 == 指代名称读取状态::结构不一致)
            失败状态 = 基础语言输入状态::内部不一致;
        return std::nullopt;
    }
    const auto 关系 = 名称服务.获取名称关系(节点);
    if (关系.状态 != 概念名称关系查询状态::已找到 || !关系.信息
        || 关系.信息->节点 != 节点 || 关系.信息->词条节点 != 词条)
    {
        失败状态 = 映射名称状态(关系.状态);
        return std::nullopt;
    }
    const auto 存在 = 存在概念服务.获取存在概念(关系.信息->概念节点);
    const auto 特征 = 特征概念服务.获取特征概念(关系.信息->概念节点);
    if (存在.has_value() == 特征.has_value()) return std::nullopt;
    if (存在) return 语言名称候选读回{普通名称候选读回{*关系.信息, *存在}};
    return 语言名称候选读回{普通名称候选读回{*关系.信息, *特征}};
}

bool 名称相同(const 语言名称候选读回& 左, const 语言名称候选读回& 右) {
    if (左.index() != 右.index()) return false;
    if (const auto* 普通左 = std::get_if<普通名称候选读回>(&左)) {
        const auto& 普通右 = std::get<普通名称候选读回>(右);
        return 普通左->名称关系 == 普通右.名称关系
            && 普通左->目标概念 == 普通右.目标概念;
    }
    const auto& 指代左 = std::get<指代名称关系信息>(左);
    const auto& 指代右 = std::get<指代名称关系信息>(右);
    return 指代左.节点 == 指代右.节点
        && 指代左.概念 == 指代右.概念
        && 指代左.词条 == 指代右.词条
        && 指代左.语言 == 指代右.语言
        && 指代左.角色 == 指代右.角色
        && 指代左.来源.节点 == 指代右.来源.节点
        && 指代左.来源.种类 == 指代右.来源.种类
        && 指代左.来源.语言节点 == 指代右.来源.语言节点
        && 指代左.来源.固定原文 == 指代右.来源.固定原文;
}

稳定编码 名称关系身份(const 语言名称候选读回& 候选) {
    if (const auto* 普通 = std::get_if<普通名称候选读回>(&候选))
        return 普通->名称关系.节点;
    return std::get<指代名称关系信息>(候选).节点;
}

bool 候选顺序(const 基础语言归类候选& 左, const 基础语言归类候选& 右) {
    return std::tie(左.归类概念节点, 左.名称关系节点, 左.所用知识节点)
        < std::tie(右.归类概念节点, 右.名称关系节点, 右.所用知识节点);
}

bool 候选相同(const 基础语言归类候选& 左, const 基础语言归类候选& 右) {
    return 左.归类概念节点 == 右.归类概念节点
        && 左.名称关系节点 == 右.名称关系节点
        && 左.所用知识节点 == 右.所用知识节点
        && 左.主体范围.起始标量 == 右.主体范围.起始标量
        && 左.主体范围.结束标量 == 右.主体范围.结束标量
        && 左.概念范围.起始标量 == 右.概念范围.起始标量
        && 左.概念范围.结束标量 == 右.概念范围.结束标量
        && 左.主体存在节点 == 右.主体存在节点;
}

