bool 是S09结构(const 新语言知识信息& 知识, 稳定编码 语言节点) {
    const auto& 定义 = 知识.定义;
    const auto& 目标 = 定义.目标;
    const auto& 结构 = 定义.结构;
    if (目标.目的 != 新语言知识表达目的::提问
        || !目标.适用条件组.empty() || 目标.角色组.size() != 2
        || 目标.含义组.size() != 1
        || 结构.类别 != 新语言知识结构类别::基础表达
        || 结构.语言节点 != 语言节点 || 结构.有序项组.size() != 2)
        return false;
    const auto 类别组 = std::vector<新语言知识角色类别>{
        新语言知识角色类别::存在概念, 新语言知识角色类别::特征概念};
    for (std::int64_t 编号 = 0; 编号 != 2; ++编号) {
        const auto 角色 = std::find_if(目标.角色组.begin(), 目标.角色组.end(),
            [&](const auto& 项) { return 项.局部编号 == 编号; });
        if (角色 == 目标.角色组.end()
            || 角色->种类 != 新语言知识角色种类::概念引用
            || 角色->数量 != 新语言知识角色数量::单项
            || 角色->必要约束组.size() != 1
            || 角色->必要约束组.front().被约束角色 != 编号
            || 角色->必要约束组.front().允许类别组 != 类别组) return false;
    }
    const auto& 含义 = 目标.含义组.front();
    if (含义.局部编号 != 0
        || 含义.操作 != 新语言知识含义操作::信息请求
        || 含义.作用域 != 新语言知识作用域::提问范围
        || 含义.确认范围 != 新语言知识确认范围::主张成立与否
        || 含义.特征值分支 || !含义.参数组.empty() || !含义.被询含义)
        return false;
    const auto& 子 = *含义.被询含义;
    if (子.局部编号 != 1 || 子.操作 != 新语言知识含义操作::概念归类
        || 子.作用域 != 新语言知识作用域::提问范围
        || 子.参数组.size() != 2) return false;
    const auto 有参数 = [&](新语言知识参数角色 参数, std::int64_t 角色) {
        return std::count_if(子.参数组.begin(), 子.参数组.end(),
            [&](const auto& 项) { return 项.参数 == 参数 && 项.规则角色 == 角色; }) == 1;
    };
    if (!有参数(新语言知识参数角色::主体, 0)
        || !有参数(新语言知识参数角色::归类概念, 1)) return false;
    const auto& 项 = 结构.有序项组;
    if (项[0].局部编号 != 0 || 项[1].局部编号 != 1) return false;
    const auto* 子规则 = std::get_if<新语言知识子规则项>(&项[0].载荷);
    const auto* 固定 = std::get_if<新语言知识固定词项>(&项[1].载荷);
    return 子规则 && 固定 && 有效(子规则->子知识节点)
        && 有效(固定->词条节点)
        && 子规则->映射组 == std::vector<新语言知识子规则映射>{
            {0, 0}, {1, 1}};
}

