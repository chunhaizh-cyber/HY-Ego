#include "表达.含义网过渡.h"
// 计划2完成时删除。旧图的全部默认槽位保持原值。
namespace 海中鱼巣 {
std::optional<语言图含义材料> 含义网转旧含义图(const 新语言含义网& 网,const 正式表达需求& 需求) {
    核验含义网结构(网);
    if(需求.表达用途!=新表达用途::疑问||网.内容项组.size()!=2||网.身份||网.所属语言场景)return std::nullopt;
    const auto& d=std::get<正式表达需求字段>(需求.表达对象);
    const auto root=std::find_if(网.内容项组.begin(),网.内容项组.end(),[](const auto& i){return i.编号==1;});
    const auto child=std::find_if(网.内容项组.begin(),网.内容项组.end(),[](const auto& i){return i.编号==2;});
    if(root==网.内容项组.end()||child==网.内容项组.end())return std::nullopt;
    const auto* s=std::get_if<新静态含义单元>(&child->内容);if(!s)return std::nullopt;
    const auto* p=std::get_if<新特征值谓项>(&s->谓项);if(!p)return std::nullopt;
    const auto* v=std::get_if<新表达指称>(&p->值);if(!v)return std::nullopt;
    const auto* q=std::get_if<新疑问代词实例>(v);if(!q)return std::nullopt;
    // 完整比对支持形状，不能静默丢弃否定、时间、角色或其它已绑定意义。
    新语言含义网 expected;expected.顶层项组={{std::nullopt,新表达用途::疑问,1}};
    新内容算子 attitude;attitude.种类=新内容算子种类::态度;attitude.态度种类=新态度种类::询问;
    attitude.确认范围=新确认范围::填项内容;attitude.内容引用组={2};
    attitude.角色组={{"询问者",需求.说话者},{"受询者",需求.受话者}};
    新静态含义单元 statement;statement.主体=新绑定指称{新指称类别::需求,d.需求D,d.需求范围概念};
    statement.谓项=新特征值谓项{新绑定指称{新指称类别::特征类型,d.字段特征类型,d.字段特征类型},
        新表达指称{新疑问代词实例{0,q->待求类型概念,1,std::nullopt}}};
    expected.内容项组={{1,attitude,{},{},{}},{2,statement,{},{},{}}};
    if(网!=expected)return std::nullopt;
    using 种类=新语言知识角色种类;using 类别=新语言知识角色类别;using 参数=新语言知识参数角色;
    const auto 角色=[](std::int64_t 编号,种类 种,类别 类){return 新语言知识角色定义{编号,种,新语言知识角色数量::单项,{{编号,{类}}}};};
    语言图含义材料 图;图.语言节点=需求.成文参数.语言节点;图.定义图.根含义编号=1;图.根出现编号=0;
    图.定义图.节点组={
        {1,新语言知识含义操作::信息请求,新语言知识作用域::提问范围,{角色(0,种类::子含义引用,类别::子含义)},
            {{参数::被询内容,0}},{},新语言知识确认范围::填项内容,{},{{0,2,新语言子含义用途::被询内容,{}}}},
        {2,新语言知识含义操作::特征描述,新语言知识作用域::提问范围,
            {角色(0,种类::领域对象引用,类别::正式信息节点),角色(1,种类::特征类型引用,类别::正式特征类型),角色(2,种类::查询变量,类别::查询特征值)},
            {{参数::主体,0},{参数::特征类型,1},{参数::特征值,2}},{},{},{},{}}
    };
    图.出现组={
        {0,{},1,新语言知识作用域::提问范围,{},{{0,语言图子出现引用{1}}},{}},
        {1,{},2,新语言知识作用域::提问范围,{},{{0,语言图引用值{类别::正式信息节点,d.需求D,d.需求范围概念,{}}},
            {1,语言图引用值{类别::正式特征类型,d.字段特征类型,d.字段特征类型,{}}},{2,语言图待求值{0,q->待求类型概念}}},{}}
    };
    图.被询正式内容=正式内容引用定位{d.需求D,{d.字段特征类型}};
    图.正式指称作用域=需求.成文参数.交互作用域;
    return 图;
}
} // namespace 海中鱼巣
