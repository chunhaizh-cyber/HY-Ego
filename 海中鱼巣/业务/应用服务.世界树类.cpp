世界树操作状态 映射场景状态(场景直接包含状态 状态) noexcept {
    switch (状态) {
    case 场景直接包含状态::幂等冲突:
        return 世界树操作状态::幂等冲突;
    case 场景直接包含状态::资源失败:
        return 世界树操作状态::资源失败;
    case 场景直接包含状态::形成场景环:
        return 世界树操作状态::形成场景环;
    case 场景直接包含状态::引用冲突:
        return 世界树操作状态::引用冲突;
    case 场景直接包含状态::原父不匹配:
        return 世界树操作状态::原位置不匹配;
    case 场景直接包含状态::目标父相同:
        return 世界树操作状态::目标位置相同;
    case 场景直接包含状态::场景未找到:
        return 世界树操作状态::场景不在现实树;
    case 场景直接包含状态::已可能发布:
        return 世界树操作状态::结果未知;
    case 场景直接包含状态::未实现:
        return 世界树操作状态::未实现;
    default:
        return 世界树操作状态::内部不一致;
    }
}

const 场景树节点当前事实* 查找场景(
    const 场景树当前事实& 树, 稳定编码 场景) noexcept {
    const auto it = std::find_if(
        树.场景组.begin(), 树.场景组.end(),
        [&](const 场景树节点当前事实& 项) {
            return 项.场景角色.场景 == 场景;
        });
    return it == 树.场景组.end() ? nullptr : &*it;
}

std::optional<世界树存在位置> 查找直接存在位置(
    const 场景树当前事实& 树, 稳定编码 存在,
    bool& 多重) noexcept {
    std::optional<世界树存在位置> 位置;
    多重 = false;
    for (const auto& 场景 : 树.场景组) {
        for (const auto& 成员 : 场景.直接存在成员组) {
            if (成员.成员 != 存在) continue;
            if (位置) {
                多重 = true;
                return std::nullopt;
            }
            位置 = 世界树存在位置{存在, 场景.场景角色.场景, 成员};
        }
    }
    return 位置;
}

bool 包含节点(const std::vector<稳定编码>& 节点组, 稳定编码 节点) noexcept {
    return std::find(节点组.begin(), 节点组.end(), 节点) != 节点组.end();
}

