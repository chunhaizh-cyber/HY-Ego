bool 世界树根验证结果::成功(const 世界树根验证请求& 请求) const noexcept {
    if (结果头.状态 != 世界树操作状态::已验证现实根 ||
        结果头.阶段 != 世界树操作阶段::现实树预读 || !树 ||
        !有效(树->根场景) || 树->场景组.empty())
        return false;
    return !请求.期望根 || *请求.期望根 == 树->根场景;
}

bool 世界树层级位置结果::成功(
    const 世界树层级位置读取请求& 请求) const noexcept {
    return 结果头.状态 == 世界树操作状态::已读取存在位置 && 位置 &&
           有效(请求.节点) && 位置->节点 == 请求.节点 &&
           位置->视角 == 请求.预期视角 && 有效(位置->世界根);
}

bool 世界树存在位置结果::成功(
    const 世界树存在位置读取请求& 请求) const noexcept {
    return 结果头.状态 == 世界树操作状态::已读取存在位置 && 位置 &&
           有效(请求.存在) && 位置->存在 == 请求.存在 &&
           有效(位置->所在场景) &&
           位置->成员关系.种类 == 场景直接包含种类::存在成员 &&
           位置->成员关系.父场景 == 位置->所在场景 &&
           位置->成员关系.成员 == 请求.存在;
}

bool 世界树节点组查询结果::成功(
    const 世界树节点查询请求& 请求) const noexcept {
    return 结果头.状态 == 世界树操作状态::已读取存在位置 &&
           有效(请求.节点);
}

bool 世界树移动结果::成功(const 世界树成员移动请求& 请求) const noexcept {
    return (结果头.状态 == 世界树操作状态::已移动 ||
            结果头.状态 == 世界树操作状态::精确重复) &&
           结果头.阶段 == 世界树操作阶段::现实树最终确认 && 原请求 &&
           *原请求 == 请求 && 投影 && 投影->成员 == 请求.成员 &&
           投影->原场景 == 请求.原场景 &&
           投影->目标场景 == 请求.目标场景 && 有效(投影->新关系);
}

