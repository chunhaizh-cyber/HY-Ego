世界树应用服务::世界树应用服务(
    场景类数据服务& 场景, 存在类数据服务& 存在,
    概念树类数据服务& 概念, 稳定编码 根,
    已验证世界根令牌)
    : scene_(场景), existence_(存在), concept_(概念),
      joint_(存在, 场景), root_(根) {}

std::optional<场景树当前事实> 世界树应用服务::读取树() const {
    const 场景树当前读取请求 请求{root_};
    auto 结果 = scene_.读取当前场景树(请求, joint_);
    if (!结果.成功(请求) || !结果.树) return std::nullopt;
    return std::move(结果.树);
}

世界树根验证结果 世界树应用服务::验证现实世界根(
    const 世界树根验证请求& 请求) const noexcept {
    世界树根验证结果 结果;
    结果.结果头.阶段 = 世界树操作阶段::现实树预读;
    if (!有效(root_) || (请求.期望根 && *请求.期望根 != root_)) {
        结果.结果头.状态 = 世界树操作状态::入口拒绝;
        return 结果;
    }
    try {
        结果.树 = 读取树();
        if (!结果.树) {
            结果.结果头.状态 = 世界树操作状态::场景不在现实树;
            return 结果;
        }
        if (结果.树->根场景 != root_ || !查找场景(*结果.树, root_)) {
            结果.树.reset();
            结果.结果头.状态 = 世界树操作状态::内部不一致;
            return 结果;
        }
        结果.结果头.状态 = 世界树操作状态::已验证现实根;
    } catch (const std::bad_alloc&) {
        结果.结果头.状态 = 世界树操作状态::资源失败;
    } catch (...) {
        结果.结果头.状态 = 世界树操作状态::内部不一致;
    }
    return 结果;
}

世界树根验证结果 世界树应用服务::读取当前现实世界根() const noexcept {
    return 验证现实世界根({root_});
}

世界树层级位置结果 世界树应用服务::读取世界树层级位置(
    const 世界树层级位置读取请求& 请求) const noexcept {
    世界树层级位置结果 结果;
    结果.结果头.阶段 = 世界树操作阶段::现实树预读;
    if (!有效(请求.节点)) return 结果;
    try {
        const auto 树 = 读取树();
        if (!树) {
            结果.结果头.状态 = 世界树操作状态::内部不一致;
            return 结果;
        }
        世界树层级位置 位置{请求.节点, root_, 请求.预期视角};
        if (请求.预期视角 == 世界树节点视角::世界根场景) {
            if (请求.节点 != root_) {
                结果.结果头.状态 = 世界树操作状态::场景不在现实树;
                return 结果;
            }
            结果.位置 = std::move(位置);
            结果.结果头.状态 = 世界树操作状态::已读取存在位置;
            return 结果;
        }
        if (请求.预期视角 == 世界树节点视角::场景) {
            const auto* 场景 = 查找场景(*树, 请求.节点);
            if (!场景 || 请求.节点 == root_) {
                结果.结果头.状态 = 世界树操作状态::场景不在现实树;
                return 结果;
            }
            位置.直接结构父 = 场景->直接父;
            位置.父场景语境 = 场景->父语境投影;
            位置.上行路径 = 场景->从上游场景到本场景路径;
            结果.位置 = std::move(位置);
            结果.结果头.状态 = 世界树操作状态::已读取存在位置;
            return 结果;
        }
        bool 多重 = false;
        const auto 存在位置 = 查找直接存在位置(*树, 请求.节点, 多重);
        if (多重) {
            结果.结果头.状态 = 世界树操作状态::成员多重位置;
            return 结果;
        }
        if (!存在位置) {
            // 待实现：嵌套存在需要一次返回组成父与场景路径的联合投影。
            结果.结果头.状态 = 世界树操作状态::未实现;
            return 结果;
        }
        位置.直接结构父 = 直接归属联合事实{
            直接归属来源::场景成员, 存在位置->成员关系.关系.编码,
            存在位置->所在场景, 请求.节点};
        结果.位置 = std::move(位置);
        结果.结果头.状态 = 世界树操作状态::已读取存在位置;
    } catch (const std::bad_alloc&) {
        结果.结果头.状态 = 世界树操作状态::资源失败;
    } catch (...) {
        结果.结果头.状态 = 世界树操作状态::内部不一致;
    }
    return 结果;
}

世界树存在位置结果 世界树应用服务::读取现实世界存在位置(
    const 世界树存在位置读取请求& 请求) const noexcept {
    世界树存在位置结果 结果;
    结果.结果头.阶段 = 世界树操作阶段::现实树预读;
    if (!有效(请求.存在)) return 结果;
    try {
        const auto 树 = 读取树();
        if (!树) {
            结果.结果头.状态 = 世界树操作状态::内部不一致;
            return 结果;
        }
        bool 多重 = false;
        结果.位置 = 查找直接存在位置(*树, 请求.存在, 多重);
        if (多重) {
            结果.结果头.状态 = 世界树操作状态::成员多重位置;
        } else if (结果.位置) {
            结果.结果头.状态 = 世界树操作状态::已读取存在位置;
        } else {
            // 嵌套存在的场景归属不能由两次current-only读取拼成共同快照。
            结果.结果头.状态 = 世界树操作状态::未实现;
        }
    } catch (const std::bad_alloc&) {
        结果.结果头.状态 = 世界树操作状态::资源失败;
    } catch (...) {
        结果.结果头.状态 = 世界树操作状态::内部不一致;
    }
    return 结果;
}

世界树节点组查询结果 世界树应用服务::查询父节点(
    const 世界树节点查询请求& 请求) const noexcept {
    世界树节点组查询结果 结果;
    结果.结果头.阶段 = 世界树操作阶段::现实树预读;
    if (!有效(请求.节点)) return 结果;
    try {
        const auto 树 = 读取树();
        if (!树) {
            结果.结果头.状态 = 世界树操作状态::内部不一致;
            return 结果;
        }
        if (请求.视角 == 世界树节点视角::世界根场景) {
            if (请求.节点 != root_) {
                结果.结果头.状态 = 世界树操作状态::场景不在现实树;
                return 结果;
            }
        } else if (请求.视角 == 世界树节点视角::场景) {
            const auto* 场景 = 查找场景(*树, 请求.节点);
            if (!场景) {
                结果.结果头.状态 = 世界树操作状态::场景不在现实树;
                return 结果;
            }
            if (场景->直接父) 结果.节点组.push_back(场景->直接父->父);
        } else {
            bool 多重 = false;
            const auto 位置 = 查找直接存在位置(*树, 请求.节点, 多重);
            if (多重) {
                结果.结果头.状态 = 世界树操作状态::成员多重位置;
                return 结果;
            }
            if (!位置) {
                结果.结果头.状态 = 世界树操作状态::未实现;
                return 结果;
            }
            结果.节点组.push_back(位置->所在场景);
        }
        结果.结果头.状态 = 世界树操作状态::已读取存在位置;
    } catch (const std::bad_alloc&) {
        结果.结果头.状态 = 世界树操作状态::资源失败;
    } catch (...) {
        结果.结果头.状态 = 世界树操作状态::内部不一致;
    }
    return 结果;
}

世界树节点组查询结果 世界树应用服务::查询子节点(
    const 世界树节点查询请求& 请求) const noexcept {
    世界树节点组查询结果 结果;
    结果.结果头.阶段 = 世界树操作阶段::现实树预读;
    if (!有效(请求.节点)) return 结果;
    try {
        if (请求.视角 == 世界树节点视角::存在) {
            const 存在组成子组读取请求 读取{请求.节点};
            const auto 子组 = existence_.读取当前组成子组(读取);
            if (!子组.子组读取成功(读取)) {
                结果.结果头.状态 =
                    子组.状态 == 存在结构身份只读状态::资源失败
                        ? 世界树操作状态::资源失败
                        : 子组.状态 == 存在结构身份只读状态::未实现
                              ? 世界树操作状态::未实现
                              : 世界树操作状态::内部不一致;
                return 结果;
            }
            for (const auto& 子 : 子组.子组) 结果.节点组.push_back(子.子存在);
        } else {
            const auto 树 = 读取树();
            if (!树) {
                结果.结果头.状态 = 世界树操作状态::内部不一致;
                return 结果;
            }
            const auto* 场景 = 查找场景(*树, 请求.节点);
            if (!场景 || (请求.视角 == 世界树节点视角::世界根场景 &&
                          请求.节点 != root_)) {
                结果.结果头.状态 = 世界树操作状态::场景不在现实树;
                return 结果;
            }
            for (const auto& 子场景 : 场景->直接子场景组)
                结果.节点组.push_back(子场景.成员);
            for (const auto& 存在 : 场景->直接存在成员组)
                结果.节点组.push_back(存在.成员);
        }
        结果.结果头.状态 = 世界树操作状态::已读取存在位置;
    } catch (const std::bad_alloc&) {
        结果.结果头.状态 = 世界树操作状态::资源失败;
    } catch (...) {
        结果.结果头.状态 = 世界树操作状态::内部不一致;
    }
    return 结果;
}

世界树节点组查询结果 世界树应用服务::查找兄弟节点(
    const 世界树节点查询请求& 请求) const noexcept {
    世界树节点组查询结果 结果;
    结果.结果头.阶段 = 世界树操作阶段::现实树预读;
    if (!有效(请求.节点)) return 结果;
    try {
        const auto 树 = 读取树();
        if (!树) {
            结果.结果头.状态 = 世界树操作状态::内部不一致;
            return 结果;
        }
        const 场景树节点当前事实* 父场景 = nullptr;
        if (请求.视角 == 世界树节点视角::场景) {
            const auto* 当前 = 查找场景(*树, 请求.节点);
            if (!当前) {
                结果.结果头.状态 = 世界树操作状态::场景不在现实树;
                return 结果;
            }
            if (!当前->直接父) {
                结果.结果头.状态 = 世界树操作状态::已读取存在位置;
                return 结果;
            }
            父场景 = 查找场景(*树, 当前->直接父->父);
            if (!父场景) {
                结果.结果头.状态 = 世界树操作状态::内部不一致;
                return 结果;
            }
            for (const auto& 项 : 父场景->直接子场景组)
                if (项.成员 != 请求.节点) 结果.节点组.push_back(项.成员);
        } else if (请求.视角 == 世界树节点视角::存在) {
            bool 多重 = false;
            const auto 位置 = 查找直接存在位置(*树, 请求.节点, 多重);
            if (多重) {
                结果.结果头.状态 = 世界树操作状态::成员多重位置;
                return 结果;
            }
            if (!位置) {
                // 待实现：组成存在的兄弟需要父与子组联合current-only投影。
                结果.结果头.状态 = 世界树操作状态::未实现;
                return 结果;
            }
            父场景 = 查找场景(*树, 位置->所在场景);
            if (!父场景) {
                结果.结果头.状态 = 世界树操作状态::内部不一致;
                return 结果;
            }
            for (const auto& 项 : 父场景->直接存在成员组)
                if (项.成员 != 请求.节点) 结果.节点组.push_back(项.成员);
        }
        结果.结果头.状态 = 世界树操作状态::已读取存在位置;
    } catch (const std::bad_alloc&) {
        结果.结果头.状态 = 世界树操作状态::资源失败;
    } catch (...) {
        结果.结果头.状态 = 世界树操作状态::内部不一致;
    }
    return 结果;
}

