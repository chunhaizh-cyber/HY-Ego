世界树移动结果 世界树应用服务::移动(
    const 世界树成员移动请求& 请求, bool 场景移动) noexcept {
    世界树移动结果 结果;
    结果.结果头.阶段 = 世界树操作阶段::场景包含发布;
    结果.原请求 = 请求;
    if (!有效(请求.幂等身份) || !有效(请求.原场景) ||
        !有效(请求.目标场景) || !有效(请求.成员))
        return 结果;
    if (请求.原场景 == 请求.目标场景) {
        结果.结果头.状态 = 世界树操作状态::目标位置相同;
        return 结果;
    }
    if (场景移动 && 请求.成员 == root_) {
        结果.结果头.状态 = 世界树操作状态::现实根不可移动;
        return 结果;
    }
    try {
        const 场景直接包含迁移请求 下层请求{
            请求.幂等身份, 请求.原场景, 请求.目标场景, 请求.成员};
        const auto 下层结果 = 场景移动
            ? scene_.迁移直接子场景(下层请求, joint_)
            : scene_.迁移直接存在成员(下层请求, joint_);
        结果.结果头.场景原因 = 下层结果.结果头.状态;
        if (!下层结果.成功(下层请求) || !下层结果.已建立新包含) {
            结果.结果头.状态 = 映射场景状态(下层结果.结果头.状态);
            return 结果;
        }
        结果.结果头.阶段 = 世界树操作阶段::现实树最终确认;
        结果.结果头.状态 =
            下层结果.结果头.状态 == 场景直接包含状态::精确重复
                ? 世界树操作状态::精确重复
                : 世界树操作状态::已移动;
        结果.投影 = 世界树移动投影{
            请求.成员, 请求.原场景, 请求.目标场景,
            下层结果.已建立新包含->关系.编码};
    } catch (const std::bad_alloc&) {
        结果.结果头.状态 = 世界树操作状态::资源失败;
    } catch (...) {
        结果.结果头.状态 = 世界树操作状态::内部不一致;
    }
    return 结果;
}

