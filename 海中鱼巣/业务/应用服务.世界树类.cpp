bool 世界树应用服务建立结果::成功() const noexcept {
    return 状态 == 世界树应用服务建立状态::已建立 && 服务 && 有效(根) &&
           服务->世界根() == 根;
}

世界树应用服务建立结果 建立世界树应用服务(
    场景类数据服务& 场景, 存在类数据服务& 存在,
    概念树类数据服务& 概念, 稳定编码 世界根) noexcept {
    世界树应用服务建立结果 结果;
    结果.根 = 世界根;
    if (!有效(世界根)) return 结果;
    try {
        const auto& l1 = 存在.世界树根底座();
        if (!场景.绑定于(l1) || !场景.使用存在提供者(存在) ||
            !概念.绑定于(l1)) {
            结果.状态 = 世界树应用服务建立状态::提供者不一致;
            return 结果;
        }
        auto 候选 = std::unique_ptr<世界树应用服务>(new 世界树应用服务(
            场景, 存在, 概念, 世界根,
            世界树应用服务::已验证世界根令牌{}));
        const 世界树根验证请求 验证{世界根};
        if (!候选->验证现实世界根(验证).成功(验证)) {
            结果.状态 = 世界树应用服务建立状态::根未找到;
            return 结果;
        }
        结果.服务 = std::move(候选);
        结果.状态 = 世界树应用服务建立状态::已建立;
    } catch (const std::bad_alloc&) {
        结果.状态 = 世界树应用服务建立状态::资源失败;
    } catch (...) {
        结果.状态 = 世界树应用服务建立状态::内部不一致;
    }
    return 结果;
}

