bool 生命周期可用(概念树生命周期状态 状态) noexcept {
  return 状态 == 概念树生命周期状态::活跃 ||
         状态 == 概念树生命周期状态::冷却;
}

bool 通用存在概念完整(const 纯概念事实& 事实) noexcept {
  const auto* 定义 = std::get_if<通用存在概念定义>(&事实.定义);
  return 有效(事实.概念.值) && 事实.类别 == 相关概念类别::存在 &&
         生命周期可用(事实.治理状态) && 定义 && 定义->规则版本 == 1 &&
         定义->规则 == 通用存在定义规则::不预设特征 &&
         事实.直接上位.empty();
}

bool 写读取用量为零(const 特征I64比较绑定结果& 结果) noexcept {
  return !结果.读取用量.节点数 && !结果.读取用量.关系数 &&
         !结果.读取用量.值数 && !结果.读取用量.材料总数;
}

