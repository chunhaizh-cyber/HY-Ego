通用概念前缀 收敛通用概念(概念树类数据服务& 服务,
                             const 概念树预算& 预算) {
  const 纯概念定义 定义 =
      通用存在概念定义{1, 通用存在定义规则::不预设特征};
  const auto 当前 = 服务.读取当前事实代次();
  if (!当前.成功()) throw 初始化失败{初始化状态::当前性漂移};
  const 纯概念查询请求 查询请求{2, 当前.Gread, 当前.Gread, 定义, 预算};
  const auto 查询 = 服务.精确查询纯概念(查询请求);
  if (查询.成功(查询请求) && 查询.事实) {
    if (!通用存在概念完整(*查询.事实))
      throw 初始化失败{查询.事实->治理状态 == 概念树生命周期状态::退役
                           ? 初始化状态::类型或概念已退出
                           : 初始化状态::内部不一致};
    return {*查询.事实, false};
  }
  if (!查询.确认未找到(查询请求))
    throw 初始化失败{映射纯概念状态(查询.状态)};

  const 纯概念创建恢复请求 恢复请求{
      2, 查询.Gread, 通用存在概念键, 定义,
      概念初始组织指定::显式顶层, {}, 预算};
  const auto 恢复 = 服务.读取纯概念创建首次结果(恢复请求);
  if (恢复.成功(恢复请求) && 恢复.事实) {
    if (!通用存在概念完整(*恢复.事实))
      throw 初始化失败{初始化状态::内部不一致};
    return {*恢复.事实, false};
  }
  if (恢复.状态 != 纯概念恢复状态::未派发)
    throw 初始化失败{映射纯概念恢复状态(恢复.状态)};

  const 纯概念创建请求 建立请求{
      2, 恢复.Gread, 通用存在概念键, 定义,
      概念初始组织指定::显式顶层, {}, 预算};
  const auto 建立 = 服务.创建或复用纯概念(建立请求);
  if (!建立.成功(建立请求) || !建立.事实) {
    if (建立.状态 != 纯概念状态::已可能发布)
      throw 初始化失败{映射纯概念状态(建立.状态)};
    const auto 收敛 = 服务.读取纯概念创建首次结果(恢复请求);
    if (收敛.成功(恢复请求) && 收敛.事实) {
      if (!通用存在概念完整(*收敛.事实))
        throw 初始化失败{初始化状态::内部不一致};
      return {*收敛.事实, false};
    }
    throw 初始化失败{初始化状态::已可能发布};
  }
  if (!通用存在概念完整(*建立.事实))
    throw 初始化失败{初始化状态::内部不一致};
  return {*建立.事实, 建立.状态 == 纯概念状态::已创建};
}

struct K前缀 final {
  特征I64比较绑定事实 事实;
  bool 本调用新建 = false;
};

K前缀 收敛K(特征类数据服务& 服务, 概念树类数据服务& 截止服务,
            特征类型身份 FT, L1所有者范围写入幂等身份 键,
            const 有界事实读取预算_B1& 预算,
            std::uint64_t 最大扫描候选数量) {
  const auto 定义 = 形成目标判断K定义(FT);
  const auto 读取当前 = [&]() {
    const auto 当前 = 截止服务.读取当前事实代次();
    if (!当前.成功()) throw 初始化失败{初始化状态::当前性漂移};
    return 服务.读取当前I64比较绑定(
        {1, 当前.Gread, FT, 特征I64比较用途::目标判断,
         最大扫描候选数量, 预算});
  };
  auto 当前路由 = 读取当前();
  if (当前路由.成功() && 当前路由.事实) {
    if (!K事实符合(*当前路由.事实, 定义, 当前路由.H))
      throw 初始化失败{初始化状态::引用冲突};
    return {*当前路由.事实, false};
  }
  if (当前路由.状态 != 特征I64比较绑定状态::未找到)
    throw 初始化失败{映射K状态(当前路由.状态)};

  const 特征I64比较绑定建立请求 建立请求{
      1, 当前路由.Gread, 键, 定义};
  auto 建立 = 服务.建立I64比较绑定(建立请求);
  if (!写读取用量为零(建立))
    throw 初始化失败{初始化状态::内部不一致};
  if (建立.成功() && 建立.事实) {
    if (!K事实符合(*建立.事实, 定义, 建立.Gread))
      throw 初始化失败{初始化状态::内部不一致};
    return {*建立.事实,
            建立.状态 == 特征I64比较绑定状态::已创建};
  }
  if (建立.状态 != 特征I64比较绑定状态::已可能发布 ||
      !建立.建立原请求)
    throw 初始化失败{映射K状态(建立.状态)};

  auto 重放 = 服务.建立I64比较绑定(*建立.建立原请求);
  if (!写读取用量为零(重放))
    throw 初始化失败{初始化状态::内部不一致};
  if (重放.成功() && 重放.事实) {
    if (!K事实符合(*重放.事实, 定义, 重放.Gread))
      throw 初始化失败{初始化状态::内部不一致};
    return {*重放.事实, false};
  }
  if (重放.状态 != 特征I64比较绑定状态::已可能发布)
    throw 初始化失败{初始化状态::已可能发布};

  try {
    当前路由 = 读取当前();
    if (当前路由.成功() && 当前路由.事实) {
      if (!K事实符合(*当前路由.事实, 定义, 当前路由.H))
        throw 初始化失败{初始化状态::已可能发布};
      return {*当前路由.事实, false};
    }
  } catch (...) {
    throw 初始化失败{初始化状态::已可能发布};
  }
  throw 初始化失败{初始化状态::已可能发布};
}

struct RC前缀 final {
  二次关系概念事实 事实;
  bool 本调用新建 = false;
};

RC前缀 收敛RC(概念树类数据服务& 服务, const 二次关系定义& 定义,
              L1所有者范围写入幂等身份 键,
              const 二次关系预算& 预算) {
  const auto 查找 = [&]() {
    const auto 当前 = 服务.读取当前事实代次();
    if (!当前.成功()) throw 初始化失败{初始化状态::当前性漂移};
    return 服务.查找二次关系完整定义(
        {1, {1, 当前.Gread, 当前.Gread}, 定义, 预算});
  };
  auto 已有 = 查找();
  if (已有.成功() && 已有.事实) {
    if (已有.状态 == 二次关系数据状态::退役命中)
      throw 初始化失败{初始化状态::类型或概念已退出};
    if (!RC事实符合(*已有.事实, 定义, 已有.Gread))
      throw 初始化失败{初始化状态::内部不一致};
    return {*已有.事实, false};
  }
  if (已有.状态 != 二次关系数据状态::同义缺失)
    throw 初始化失败{映射RC状态(已有.状态)};

  const auto 建立一次 = [&](std::uint64_t G) {
    return 服务.建立二次关系概念(
        {1, {1, G, 键}, 定义, 概念初始组织指定::显式顶层,
         {}, {}, 预算});
  };
  auto 建立 = 建立一次(已有.Gread);
  if (建立.成功() && 建立.事实) {
    if (建立.事实->定义 != 定义)
      throw 初始化失败{初始化状态::内部不一致};
    return {*建立.事实,
            建立.状态 == 二次关系数据状态::已创建};
  }
  if (建立.状态 != 二次关系数据状态::发布未知 || !建立.建立原请求)
    throw 初始化失败{映射RC状态(建立.状态)};

  auto 重放 = 服务.收敛二次关系概念建立(*建立.建立原请求);
  if (重放.成功() && 重放.事实) {
    if (重放.事实->定义 != 定义)
      throw 初始化失败{初始化状态::内部不一致};
    return {*重放.事实, false};
  }
  if (重放.状态 != 二次关系数据状态::未找到)
    throw 初始化失败{初始化状态::已可能发布};

  已有 = 查找();
  if (已有.成功() && 已有.事实) {
    if (已有.状态 == 二次关系数据状态::退役命中)
      throw 初始化失败{初始化状态::类型或概念已退出};
    if (!RC事实符合(*已有.事实, 定义, 已有.Gread))
      throw 初始化失败{初始化状态::内部不一致};
    return {*已有.事实, false};
  }
  if (已有.状态 != 二次关系数据状态::同义缺失)
    throw 初始化失败{映射RC状态(已有.状态)};
  建立 = 建立一次(已有.Gread);
  if (!建立.成功() || !建立.事实)
    throw 初始化失败{映射RC状态(建立.状态)};
  if (建立.事实->定义 != 定义)
    throw 初始化失败{初始化状态::内部不一致};
  return {*建立.事实,
          建立.状态 == 二次关系数据状态::已创建};
}

bool 先天交付形状有效(const 先天I64特征概念交付& 交付,
                      本能值角色 角色, std::uint64_t Gread) noexcept {
  const auto 最大值 = std::numeric_limits<std::int64_t>::max();
  const auto* 定义 = std::get_if<纯I64特征概念定义>(&交付.完整域概念.定义);
  return 交付.角色 == 角色 && 交付.Gread == Gread &&
         交付.FT首次H && 交付.FT首次H <= Gread && 交付.概念首次H &&
         交付.概念首次H <= Gread && 有效(交付.类型.身份) &&
         交付.类型.规格.来源 == 特征类型来源::先天定义 &&
         !交付.类型.规格.外设提供者 &&
         交付.类型.规格.单位 == 交付.类型.身份.编码 &&
         交付.类型.规格.缩放分子 == 1 &&
         交付.类型.规格.缩放分母 == 1 &&
         交付.类型.规格.允许集合 ==
             std::vector<特征I64闭区间>{{0, 最大值}} &&
         交付.完整域概念.类别 == 相关概念类别::特征 &&
         生命周期可用(交付.完整域概念.治理状态) && 定义 &&
         定义->特征类型.值 == 交付.类型.身份.编码 &&
         定义->规范域 == std::vector<概念树I64区间>{{0, 最大值}} &&
         交付.完整域概念.直接上位.empty();
}

