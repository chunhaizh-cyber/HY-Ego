bool 本能根二次关系概念交付::完整() const noexcept {
  if (!Gread || 角色 != 先天.角色 ||
      !先天交付形状有效(先天, 角色, Gread) ||
      !通用存在概念完整(通用存在概念))
    return false;
  const auto K定义 = 形成目标判断K定义(先天.类型.身份);
  if (!K事实符合(目标判断K, K定义, Gread)) return false;
  const auto RC定义 = 形成正差距RC定义(
      目标判断K.身份, 先天.完整域概念.概念, 通用存在概念.概念);
  return RC事实符合(正差距RC, RC定义, Gread);
}

bool 本能双根二次关系概念初始化结果::成功() const noexcept {
  if (版本 != 本能双根二次关系概念初始化合同版本 ||
      原请求.版本 != 本能双根二次关系概念初始化合同版本 ||
      !原请求.G0 || 原请求.纯概念预算 != 本能双根RC纯概念预算 ||
      原请求.K读取预算 != 本能双根RCK读取预算 ||
      原请求.K最大扫描候选数量 != 本能双根RCK最大扫描候选数量 ||
      原请求.RC预算 != 本能双根RC二次关系预算 ||
      !原请求.先天交付.成功() ||
      原请求.先天交付.Gread != 原请求.G0 || !Gread ||
      (状态 != 初始化状态::已形成 && 状态 != 初始化状态::已恢复) ||
      !安全根 || !服务根 || !安全根->完整() || !服务根->完整() ||
      安全根->角色 != 本能值角色::安全值 ||
      服务根->角色 != 本能值角色::服务值 ||
      安全根->Gread != Gread || 服务根->Gread != Gread)
    return false;
  return 安全根->先天.类型.身份 != 服务根->先天.类型.身份 &&
         安全根->先天.完整域概念.概念 !=
             服务根->先天.完整域概念.概念 &&
         安全根->目标判断K.身份 != 服务根->目标判断K.身份 &&
         安全根->正差距RC.身份 != 服务根->正差距RC.身份 &&
         安全根->通用存在概念.概念 ==
             服务根->通用存在概念.概念;
}

本能双根二次关系概念初始化提供者::
    本能双根二次关系概念初始化提供者(
        特征类数据服务& 特征服务, 概念树类数据服务& 概念服务) noexcept
    : 特征服务_(特征服务), 概念服务_(概念服务) {}

本能双根二次关系概念初始化结果
本能双根二次关系概念初始化提供者::初始化(
    const 本能双根二次关系概念初始化请求& 请求) noexcept {
  本能双根二次关系概念初始化结果 输出;
  输出.原请求 = 请求;
  try {
    if (请求.版本 != 本能双根二次关系概念初始化合同版本 ||
        !请求.G0 || 请求.纯概念预算 != 本能双根RC纯概念预算 ||
        请求.K读取预算 != 本能双根RCK读取预算 ||
        请求.K最大扫描候选数量 != 本能双根RCK最大扫描候选数量 ||
        请求.RC预算 != 本能双根RC二次关系预算)
      return 输出;
    if (!请求.先天交付.成功() || 请求.先天交付.Gread != 请求.G0 ||
        !请求.先天交付.安全值交付 || !请求.先天交付.服务值交付 ||
        !先天交付形状有效(*请求.先天交付.安全值交付,
                            本能值角色::安全值, 请求.G0) ||
        !先天交付形状有效(*请求.先天交付.服务值交付,
                            本能值角色::服务值, 请求.G0)) {
      输出.状态 = 初始化状态::初始化交付不完整;
      return 输出;
    }
    const auto& L1 = 概念服务_.原子I64底座();
    if (!特征服务_.绑定于(L1) || !概念服务_.绑定于(L1)) return 输出;
    const auto 初始截止 = 概念服务_.读取当前事实代次();
    if (!初始截止.成功() || 初始截止.Gread != 请求.G0)
      throw 初始化失败{初始化状态::当前性漂移};

    bool 本调用新建 = false;
    const auto 通用 = 收敛通用概念(概念服务_, 请求.纯概念预算);
    本调用新建 = 通用.本调用新建;
    const auto& 安全先天 = *请求.先天交付.安全值交付;
    const auto& 服务先天 = *请求.先天交付.服务值交付;
    const auto 安全K = 收敛K(
        特征服务_, 概念服务_, 安全先天.类型.身份, 安全K键,
        请求.K读取预算, 请求.K最大扫描候选数量);
    本调用新建 = 本调用新建 || 安全K.本调用新建;
    const auto 服务K = 收敛K(
        特征服务_, 概念服务_, 服务先天.类型.身份, 服务K键,
        请求.K读取预算, 请求.K最大扫描候选数量);
    本调用新建 = 本调用新建 || 服务K.本调用新建;

    const auto 安全RC定义 = 形成正差距RC定义(
        安全K.事实.身份, 安全先天.完整域概念.概念, 通用.事实.概念);
    const auto 服务RC定义 = 形成正差距RC定义(
        服务K.事实.身份, 服务先天.完整域概念.概念, 通用.事实.概念);
    const auto 安全RC =
        收敛RC(概念服务_, 安全RC定义, 安全RC键, 请求.RC预算);
    本调用新建 = 本调用新建 || 安全RC.本调用新建;
    const auto 服务RC =
        收敛RC(概念服务_, 服务RC定义, 服务RC键, 请求.RC预算);
    本调用新建 = 本调用新建 || 服务RC.本调用新建;

    const auto 最终截止 = 概念服务_.读取当前事实代次();
    if (!最终截止.成功())
      throw 初始化失败{初始化状态::当前性漂移};
    const auto Gfinal = 最终截止.Gread;
    const auto 通用读回 = 概念服务_.读取纯概念(
        {2, Gfinal, Gfinal, 通用.事实.概念, 请求.纯概念预算});
    if (!通用读回.成功(
            {2, Gfinal, Gfinal, 通用.事实.概念, 请求.纯概念预算}) ||
        !通用读回.事实 || !通用存在概念完整(*通用读回.事实))
      throw 初始化失败{映射纯概念状态(通用读回.状态)};

    const auto 完成根 = [&](本能值角色 角色,
                           const 先天I64特征概念交付& 初始先天,
                           特征I64比较绑定身份 K身份,
                           概念树概念身份 RC身份)
        -> 本能根二次关系概念交付 {
      const auto FT读回 = 特征服务_.读取I64基础特征类型事实(
          {1, Gfinal, Gfinal, 初始先天.类型.身份});
      const auto* FT事实 =
          std::get_if<特征截止事实<I64基础特征类型信息>>(&FT读回);
      if (!FT事实 || FT事实->Gread != Gfinal || FT事实->H != Gfinal)
        throw 初始化失败{初始化状态::初始化交付不完整};
      const 纯概念读取请求 FC请求{
          2, Gfinal, Gfinal, 初始先天.完整域概念.概念,
          请求.纯概念预算};
      const auto FC读回 = 概念服务_.读取纯概念(FC请求);
      if (!FC读回.成功(FC请求) || !FC读回.事实)
        throw 初始化失败{映射纯概念状态(FC读回.状态)};
      const 特征I64比较绑定读取请求 K请求{
          1, Gfinal, Gfinal, K身份, 请求.K读取预算};
      const auto K读回 = 特征服务_.读取I64比较绑定(K请求);
      if (!K读回.成功() || !K读回.事实)
        throw 初始化失败{映射K状态(K读回.状态)};
      const 特征I64当前比较绑定读取请求 当前K请求{
          1, Gfinal, 初始先天.类型.身份,
          特征I64比较用途::目标判断, 请求.K最大扫描候选数量,
          请求.K读取预算};
      const auto 当前K = 特征服务_.读取当前I64比较绑定(当前K请求);
      if (!当前K.成功() || !当前K.事实 || 当前K.事实->身份 != K身份)
        throw 初始化失败{当前K.状态 == 特征I64比较绑定状态::已读取
                               ? 初始化状态::内部不一致
                               : 映射K状态(当前K.状态)};
      const 二次关系概念读取请求 RC请求{
          1, {1, Gfinal, Gfinal}, RC身份, 请求.RC预算};
      const auto RC读回 = 概念服务_.读取二次关系概念(RC请求);
      if (!RC读回.成功() || !RC读回.事实 ||
          RC读回.状态 == 二次关系数据状态::退役命中)
        throw 初始化失败{映射RC状态(RC读回.状态)};
      先天I64特征概念交付 先天{角色,
          FT事实->数据, *FC读回.事实, 初始先天.FT首次H,
          初始先天.概念首次H, Gfinal};
      return {角色, std::move(先天), *通用读回.事实,
              *K读回.事实, *RC读回.事实, Gfinal};
    };

    输出.安全根 = 完成根(本能值角色::安全值, 安全先天,
                           安全K.事实.身份, 安全RC.事实.身份);
    输出.服务根 = 完成根(本能值角色::服务值, 服务先天,
                           服务K.事实.身份, 服务RC.事实.身份);
    const auto 尾截止 = 概念服务_.读取当前事实代次();
    if (!尾截止.成功() || 尾截止.Gread != Gfinal)
      throw 初始化失败{初始化状态::当前性漂移};
    输出.Gread = Gfinal;
    输出.状态 = 本调用新建 ? 初始化状态::已形成 : 初始化状态::已恢复;
    if (!输出.成功()) throw 初始化失败{初始化状态::内部不一致};
  } catch (const 初始化失败& 错误) {
    输出.状态 = 错误.状态;
    输出.安全根.reset();
    输出.服务根.reset();
    输出.Gread = 0;
  } catch (const std::bad_alloc&) {
    输出.状态 = 初始化状态::资源失败;
    输出.安全根.reset();
    输出.服务根.reset();
    输出.Gread = 0;
  } catch (const std::length_error&) {
    输出.状态 = 初始化状态::资源失败;
    输出.安全根.reset();
    输出.服务根.reset();
    输出.Gread = 0;
  } catch (...) {
    输出.状态 = 初始化状态::内部不一致;
    输出.安全根.reset();
    输出.服务根.reset();
    输出.Gread = 0;
  }
  return 输出;
}

