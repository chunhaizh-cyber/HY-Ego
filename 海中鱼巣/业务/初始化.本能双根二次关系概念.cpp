bool K事实符合(const 特征I64比较绑定事实& 事实,
               const 特征I64比较绑定定义& 定义,
               std::uint64_t 截止) noexcept {
  return 事实.定义 == 定义 && I64绑定事实完整(事实, 截止);
}

bool RC事实符合(const 二次关系概念事实& 事实,
                const 二次关系定义& 定义,
                std::uint64_t 截止) noexcept {
  return 事实.Gread == 截止 && 事实.H == 截止 &&
         生命周期可用(事实.治理状态) && 事实.定义 == 定义;
}

