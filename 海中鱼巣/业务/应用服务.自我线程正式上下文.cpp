using 外部状态 = 自我线程外部调用状态;

[[nodiscard]] 自我线程正式上下文结果_v1 失败(
    const 外部状态 状态) noexcept {
  return {状态, std::nullopt, false};
}

[[nodiscard]] 外部状态 映射世界状态(const 世界树操作状态 状态) noexcept {
  switch (状态) {
  case 世界树操作状态::入口拒绝:
    return 外部状态::入口拒绝;
  case 世界树操作状态::事实代次漂移:
    return 外部状态::当前性漂移;
  case 世界树操作状态::场景不在现实树:
  case 世界树操作状态::引用冲突:
  case 世界树操作状态::形成场景环:
    return 外部状态::引用冲突;
  case 世界树操作状态::数量预算不足:
  case 世界树操作状态::资源失败:
    return 外部状态::资源失败;
  default:
    return 外部状态::内部错误;
  }
}

[[nodiscard]] 外部状态 映射自我状态(const 真实自我形成状态 状态) noexcept {
  switch (状态) {
  case 真实自我形成状态::入口拒绝:
    return 外部状态::入口拒绝;
  case 真实自我形成状态::读取未完成:
    return 外部状态::当前性漂移;
  case 真实自我形成状态::请求冲突:
  case 真实自我形成状态::根无效:
  case 真实自我形成状态::角色冲突:
  case 真实自我形成状态::概念阶段失败:
  case 真实自我形成状态::世界阶段失败:
    return 外部状态::引用冲突;
  case 真实自我形成状态::资源失败:
    return 外部状态::资源失败;
  default:
    return 外部状态::内部错误;
  }
}

[[nodiscard]] 外部状态 映射方法状态(const 方法登记根结构状态 状态) noexcept {
  switch (状态) {
  case 方法登记根结构状态::入口拒绝:
    return 外部状态::入口拒绝;
  case 方法登记根结构状态::尚未建立:
  case 方法登记根结构状态::当前根缺失:
    return 外部状态::依赖未就绪;
  case 方法登记根结构状态::所有者非空冲突:
    return 外部状态::引用冲突;
  case 方法登记根结构状态::事实代次漂移:
    return 外部状态::当前性漂移;
  case 方法登记根结构状态::数量预算不足:
  case 方法登记根结构状态::资源失败:
    return 外部状态::资源失败;
  default:
    return 外部状态::内部错误;
  }
}

[[nodiscard]] 外部状态 映射根状态(const 本能根材料状态 状态) noexcept {
  switch (状态) {
  case 本能根材料状态::入口拒绝:
    return 外部状态::入口拒绝;
  case 本能根材料状态::事实代次漂移:
    return 外部状态::当前性漂移;
  case 本能根材料状态::实际特征未找到:
  case 本能根材料状态::实际特征类型不匹配:
  case 本能根材料状态::幂等冲突:
  case 本能根材料状态::引用冲突:
  case 本能根材料状态::根材料未闭合:
    return 外部状态::引用冲突;
  case 本能根材料状态::资源失败:
    return 外部状态::资源失败;
  default:
    return 外部状态::内部错误;
  }
}

[[nodiscard]] 外部状态 映射代次状态(const 需求类数据状态 状态) noexcept {
  switch (状态) {
  case 需求类数据状态::入口拒绝:
    return 外部状态::入口拒绝;
  case 需求类数据状态::事实代次漂移:
    return 外部状态::当前性漂移;
  case 需求类数据状态::资源失败:
    return 外部状态::资源失败;
  default:
    return 外部状态::内部错误;
  }
}

[[nodiscard]] bool 世界根匹配(
    const 场景树当前事实& 树,
    const 自我线程世界启动材料_v1& 锁定) noexcept {
  return 树.根场景.值 == 锁定.世界.值 &&
      树.根场景.值 == 锁定.根场景.值;
}

[[nodiscard]] bool 根材料匹配(
    const 本能根材料& 材料,
    const 自我线程单根启动材料_v1& 锁定,
    const 本能根角色 角色,
    const std::uint64_t Gread) noexcept {
  return 材料.完整() && 材料.角色 == 角色 &&
      材料.根需求.值 == 锁定.需求.值 &&
      材料.根列表项.值 == 锁定.列表项.值 &&
      材料.实际特征.值 == 锁定.实际特征.值 &&
      材料.根目标合同.值 == 锁定.目标合同.值 &&
      材料.读取事实代次 == Gread;
}

