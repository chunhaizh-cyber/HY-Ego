#include "应用服务.自我线程正式上下文.h"

#include <new>

namespace 海中鱼巣 {
namespace {

bool 请求有效(const 自我线程正式上下文请求& 请求) noexcept {
  const 稳定编码 身份[]{请求.期望世界根, 请求.期望自我,
                         请求.期望所在场景, 请求.角色.值,
                         请求.安全实际特征.编码,
                         请求.服务实际特征.编码};
  for (std::size_t i = 0; i < std::size(身份); ++i) {
    if (!有效(身份[i])) return false;
    for (std::size_t j = 0; j < i; ++j)
      if (身份[i] == 身份[j]) return false;
  }
  return true;
}

自我线程正式上下文状态 映射自我状态(真实自我形成状态 状态) noexcept {
  switch (状态) {
    case 真实自我形成状态::未实现:
      return 自我线程正式上下文状态::未实现;
    case 真实自我形成状态::资源失败:
      return 自我线程正式上下文状态::资源失败;
    case 真实自我形成状态::入口拒绝:
      return 自我线程正式上下文状态::入口拒绝;
    case 真实自我形成状态::角色冲突:
    case 真实自我形成状态::根无效:
      return 自我线程正式上下文状态::引用冲突;
    case 真实自我形成状态::读取未完成:
      return 自我线程正式上下文状态::依赖未就绪;
    default:
      return 自我线程正式上下文状态::内部错误;
  }
}

} // namespace

bool 自我线程正式上下文投影::完整() const noexcept {
  return 有效(世界) && 有效(自我所在场景) && 有效(自我) &&
         世界 != 自我所在场景 && 世界 != 自我 &&
         自我所在场景 != 自我 && 安全根.完整() && 服务根.完整() &&
         安全根.角色 == 本能根角色::安全 &&
         服务根.角色 == 本能根角色::服务 &&
         安全根.实际特征 != 服务根.实际特征;
}

bool 自我线程正式上下文结果::成功(
    const 自我线程正式上下文请求& 请求) const noexcept {
  return 状态 == 自我线程正式上下文状态::成功 && !写业务事实 &&
         投影 && 投影->完整() && 投影->世界 == 请求.期望世界根 &&
         投影->自我 == 请求.期望自我 &&
         投影->自我所在场景 == 请求.期望所在场景 &&
         投影->安全根.实际特征 == 请求.安全实际特征.编码 &&
         投影->服务根.实际特征 == 请求.服务实际特征.编码;
}

自我线程正式上下文提供者::自我线程正式上下文提供者(
    世界树应用服务& 世界, const 真实自我形成服务& 自我,
    const 需求类数据服务& 需求, const L2方法结构服务& 方法,
    存在单例角色身份 角色) noexcept
    : 世界_(世界), 自我_(自我), 需求_(需求), 方法_(方法), 角色_(角色) {}

自我线程正式上下文结果 自我线程正式上下文提供者::读取正式上下文(
    const 自我线程正式上下文请求& 请求) noexcept {
  自我线程正式上下文结果 结果;
  if (!请求有效(请求) || 请求.角色 != 角色_) return 结果;
  try {
    const 真实自我读取请求 自我请求{请求.期望世界根, 请求.角色};
    const auto 自我结果 = 自我_.读取当前自我(自我请求);
    if (!自我结果.成功(自我请求) || !自我结果.投影) {
      结果.状态 = 映射自我状态(自我结果.状态);
      return 结果;
    }
    if (自我结果.投影->E != 请求.期望自我 ||
        自我结果.投影->所在场景 != 请求.期望所在场景) {
      结果.状态 = 自我线程正式上下文状态::引用冲突;
      return 结果;
    }

    // 待实现：安全根和服务根必须由一个联合current-only入口同时读回。
    // 两次独立读取不能制造共同当前投影，治理门保持关闭。
    结果.状态 = 自我线程正式上下文状态::未实现;
  } catch (const std::bad_alloc&) {
    结果.状态 = 自我线程正式上下文状态::资源失败;
  } catch (...) {
    结果.状态 = 自我线程正式上下文状态::内部错误;
  }
  return 结果;
}

} // namespace 海中鱼巣
