自我线程正式上下文提供者::自我线程正式上下文提供者(
    世界树应用服务& 世界,
    const 真实自我形成服务& 自我,
    const 需求类数据服务& 需求,
    const L2方法结构服务& 方法,
    const 存在单例角色身份 角色) noexcept
    : 世界_(世界), 自我_(自我), 需求_(需求), 方法_(方法), 角色_(角色) {}

自我线程正式上下文结果_v1
自我线程正式上下文提供者::读取正式上下文(
    const 自我线程正式上下文请求_v1& 请求) noexcept {
  if (!请求.完整() || !有效(角色_.值)) return 失败(外部状态::入口拒绝);
  try {
    const 世界树读取预算 世界预算{
        请求.预算.最大世界场景数量,
        请求.预算.最大世界关系数量};
    const auto 世界根 = 世界_.读取当前现实世界根(世界预算);
    if (!世界根.成功(世界预算) || !世界根.树)
      return 失败(映射世界状态(世界根.结果头.状态));
    if (!世界根匹配(*世界根.树, 请求.锁定世界))
      return 失败(外部状态::引用冲突);
    const auto Gread = 世界根.结果头.Gread;

    const 真实自我读取请求 自我请求{
        1,
        Gread,
        世界根.树->根场景,
        角色_,
        {请求.预算.最大世界场景数量,
         请求.预算.最大世界关系数量,
         请求.预算.最大自我位置祖先数量},
        {请求.预算.最大自我概念数量,
         请求.预算.最大自我概念关系数量,
         0,
         0,
         请求.预算.最大自我概念世界成员数量,
         请求.预算.最大自我概念特征属性数量,
         0,
         0}};
    const auto 自我 = 自我_.读取当前自我(自我请求);
    if (!自我.成功(自我请求) || !自我.投影)
      return 失败(映射自我状态(自我.状态));
    const auto& 自我投影 = *自我.投影;
    if (自我投影.E.值 != 请求.锁定自我.自我.值 ||
        自我投影.世界根.值 != 请求.锁定世界.根场景.值 ||
        自我投影.角色.角色 != 角色_ ||
        自我投影.角色.E != 自我投影.E ||
        !自我投影.位置.直接结构父 ||
        自我投影.位置.直接结构父->成员 != 自我投影.E ||
        !有效(自我投影.位置.直接结构父->父))
      return 失败(外部状态::引用冲突);

    const auto 方法根 = 方法_.读取全部当前方法登记根({1, Gread});
    if (!方法根.成功()) return 失败(映射方法状态(方法根.状态));
    if (方法根.Gread != Gread || 方法根.根组.size() != 1 ||
        !有效(方法根.根组.front().身份.结点) ||
        !方法根.根组.front().创建事实代次 ||
        方法根.根组.front().创建事实代次 > Gread)
      return 失败(外部状态::内部错误);

    const 本能根材料请求 安全请求{
        本能根材料合同版本, Gread, 本能根角色::安全,
        {请求.锁定本能根.安全根.实际特征.值}};
    const auto 安全 = 需求_.读取本能根材料(安全请求);
    if (安全.状态 != 本能根材料状态::已读取 || !安全.成功(安全请求) || !安全.材料)
      return 失败(映射根状态(安全.状态));
    if (安全.事实代次 != Gread ||
        !根材料匹配(*安全.材料, 请求.锁定本能根.安全根,
            本能根角色::安全, Gread))
      return 失败(外部状态::引用冲突);

    const 本能根材料请求 服务请求{
        本能根材料合同版本, Gread, 本能根角色::服务,
        {请求.锁定本能根.服务根.实际特征.值}};
    const auto 服务 = 需求_.读取本能根材料(服务请求);
    if (服务.状态 != 本能根材料状态::已读取 || !服务.成功(服务请求) || !服务.材料)
      return 失败(映射根状态(服务.状态));
    if (服务.事实代次 != Gread ||
        !根材料匹配(*服务.材料, 请求.锁定本能根.服务根,
            本能根角色::服务, Gread) ||
        安全.材料->根需求 == 服务.材料->根需求 ||
        安全.材料->根列表项 == 服务.材料->根列表项 ||
        安全.材料->实际特征 == 服务.材料->实际特征 ||
        安全.材料->根目标合同 == 服务.材料->根目标合同)
      return 失败(外部状态::引用冲突);

    const auto 代次 = 需求_.核验当前事实代次(Gread);
    if (!代次.成功()) return 失败(映射代次状态(代次.状态));

    const 世界树根验证请求 末次请求{2, Gread, 世界预算};
    const auto 末次世界根 = 世界_.验证现实世界根(末次请求);
    if (!末次世界根.成功(末次请求) || !末次世界根.树)
      return 失败(映射世界状态(末次世界根.结果头.状态));
    if (!世界根匹配(*末次世界根.树, 请求.锁定世界))
      return 失败(外部状态::引用冲突);

    自我线程正式上下文投影_v1 投影;
    投影.Gread = Gread;
    投影.世界 = 请求.锁定世界.世界;
    投影.自我所在场景 = {自我投影.位置.直接结构父->父.值};
    投影.自我 = 请求.锁定自我.自我;
    投影.安全根 = 请求.锁定本能根.安全根;
    投影.服务根 = 请求.锁定本能根.服务根;
    if (!投影.完整()) return 失败(外部状态::内部错误);
    return {外部状态::成功, std::move(投影), false};
  } catch (const std::bad_alloc&) {
    return 失败(外部状态::资源失败);
  } catch (const std::length_error&) {
    return 失败(外部状态::资源失败);
  } catch (...) {
    return 失败(外部状态::内部错误);
  }
}

