#pragma once

#include <cstdint>
#include <optional>
#include <vector>

#include "../领域/新_动态类.h"
#include "../领域/新_二次特征类.h"

namespace 海中鱼巣 {

// 抽取结果可直接交给概念_动态类::保存动态特征，不复制第二套DTO。
using 新动态特征项 = 动态概念特征项;

struct 新动态特征抽取请求 final {
    稳定编码 动态节点;
    friend bool operator==(const 新动态特征抽取请求&,
        const 新动态特征抽取请求&) = default;
};

enum class 新动态特征抽取状态 : std::uint8_t {
    已完成 = 1,
    入口拒绝 = 2,
    动态不存在 = 3,
    状态不足 = 4,
    状态不存在 = 5,
    状态轨迹不一致 = 6,
    二次特征计算失败 = 7,
    结构不一致 = 8,
    资源失败 = 9,
    原子特征尚未生成 = 10
};

struct 新动态特征抽取结果 final {
    新动态特征抽取状态 状态 = 新动态特征抽取状态::入口拒绝;
    std::optional<稳定编码> 动态节点;
    std::optional<新二次特征计算状态> 二次特征失败状态;
    std::optional<新二次跨类型变化比较状态> 跨类型比较失败状态;
    std::vector<新动态特征项> 特征组;
};

struct 新动态间特征比较请求 final {
    稳定编码 左动态节点;
    稳定编码 右动态节点;
    friend bool operator==(const 新动态间特征比较请求&,
        const 新动态间特征比较请求&) = default;
};

struct 新动态间特征比较项 final {
    std::int64_t 状态间位置 = 0;
    // 两个来源动态内部已经形成、且本次互相对应的二次特征类型。
    稳定编码 来源二次特征类型概念节点;
    std::int64_t 左准确结果 = 0;
    std::int64_t 右准确结果 = 0;
    // 对上面两个既有结果再次比较后形成的新二次特征。
    稳定编码 比较二次特征类型概念节点;
    std::int64_t 比较准确结果 = 0;
    稳定编码 比较结果值域概念节点;
    friend bool operator==(const 新动态间特征比较项&,
        const 新动态间特征比较项&) = default;
};

enum class 新动态间特征比较状态 : std::uint8_t {
    已完成 = 1,
    入口拒绝 = 2,
    动态不存在 = 3,
    动态概念不存在 = 4,
    内部特征尚未生成 = 5,
    特征结构不一致 = 6,
    二次特征计算失败 = 7,
    资源失败 = 8
};

struct 新动态间特征比较结果 final {
    新动态间特征比较状态 状态 = 新动态间特征比较状态::入口拒绝;
    std::optional<稳定编码> 左动态节点;
    std::optional<稳定编码> 右动态节点;
    std::optional<新二次特征计算状态> 二次特征失败状态;
    std::vector<新动态间特征比较项> 比较项组;
};

class 新_动态特征抽取类 final {
public:
    新_动态特征抽取类(
        const 新_动态类& 动态服务,
        const 新_状态类& 状态服务,
        const 新_二次特征类& 二次特征服务,
        const 概念_动态类& 动态概念服务) noexcept;

    // 原子动态的唯一状态对形成三条二次特征：值差异或相似度、时间间隔，以及
    // 以时间变化为参照且以该动态特征值变化为目标的带时间二次特征。
    // 组合动态只按成员顺序组合各原子动态概念中已经保存的特征，不重新遍历
    // 推导状态进行计算。计算会确保类型概念和结果域概念存在，但不修改来源事实。
    新动态特征抽取结果 抽取(
        const 新动态特征抽取请求& 请求) const noexcept;

    // 只比较两个动态概念中已经保存的内部特征；不重新读取状态进行抽取。
    // 当前要求两边的“状态间位置＋来源二次特征类型”集合完全相同。
    新动态间特征比较结果 比较动态特征(
        const 新动态间特征比较请求& 请求) const noexcept;

private:
    const 新_动态类& 动态服务_;
    const 新_状态类& 状态服务_;
    const 新_二次特征类& 二次特征服务_;
    const 概念_动态类& 动态概念服务_;
};

} // namespace 海中鱼巣
