特征当前值模式查询结果 过滤撤销行(
    新语言知识状态 源状态,
    std::vector<新语言结构对应行> 行组,
    std::vector<稳定编码> 受阻,
    const std::set<稳定编码>& 撤销) {
    特征当前值模式查询结果 r;
    r.受阻节点组 = std::move(受阻);
    if (源状态 != 新语言知识状态::已完成) {
        r.状态 = 映射知识状态(源状态);
        return r;
    }
    r.状态 = 桥状态::已完成;
    r.行组.reserve(行组.size());
    for (auto& 行 : 行组) {
        if (行.表达模式节点 && 撤销.contains(*行.表达模式节点)) {
            ++r.已过滤撤销数;
            continue;
        }
        r.行组.push_back(std::move(行));
    }
    return r;
}

std::optional<std::int64_t> 解析规范十进制(const std::string& 文本) {
    if (文本.empty()) return std::nullopt;
    std::size_t i = 0;
    bool 负 = false;
    if (文本[0] == '-') {
        负 = true;
        i = 1;
        if (i >= 文本.size()) return std::nullopt;
    }
    if (文本[i] == '0' && 文本.size() != i + 1) return std::nullopt;
    std::int64_t v = 0;
    for (; i < 文本.size(); ++i) {
        const char c = 文本[i];
        if (c < '0' || c > '9') return std::nullopt;
        const auto d = static_cast<std::int64_t>(c - '0');
        if (负) {
            if (v < (std::numeric_limits<std::int64_t>::min() + d) / 10)
                return std::nullopt;
            v = v * 10 - d;
        } else {
            if (v > (std::numeric_limits<std::int64_t>::max() - d) / 10)
                return std::nullopt;
            v = v * 10 + d;
        }
    }
    return v;
}

