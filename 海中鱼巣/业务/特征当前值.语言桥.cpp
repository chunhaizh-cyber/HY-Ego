特征当前值模式登记结果 纠正特征当前值模式(
    稳定编码 语言节点,
    稳定编码 结构概念节点,
    稳定编码 旧模式节点,
    const 新语言表达模式定义& 新定义,
    const std::string& 种子版本,
    新_语言类& 语言,
    const 新_词类& 词,
    std::set<稳定编码>& 会话已撤销模式节点) {
    特征当前值模式登记结果 r;
    if (!有效(旧模式节点)) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    const auto 旧 = 语言.获取表达模式(旧模式节点, 词);
    if (旧.状态 != 新语言知识状态::已完成 || !旧.信息) {
        r.状态 = 映射知识状态(旧.状态);
        r.受阻节点组 = 旧.受阻节点组;
        return r;
    }
    if (旧.信息->语言节点 != 语言节点
        || 旧.信息->结构概念节点 != 结构概念节点) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    if (新定义.模式标识 == 旧.信息->定义.模式标识) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    r = 登记特征当前值对齐模式(
        语言节点, 结构概念节点, 新定义, 种子版本, 语言, 词);
    if (r.状态 == 桥状态::已完成)
        会话已撤销模式节点.insert(旧模式节点);
    return r;
}

