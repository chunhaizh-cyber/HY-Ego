特征当前值双向闭环结果 运行特征当前值双向闭环(
    稳定编码 语言节点,
    稳定编码 存在节点,
    std::optional<稳定编码> 特征类型根,
    std::optional<稳定编码> 特征节点,
    const 特征当前值额度& 额度,
    新_语言类& 语言,
    const 新_词类& 词,
    const 概念_名称关系类& 名称,
    const 概念_存在类& 存在概念,
    const 概念_特征类& 特征概念,
    const 新_存在类& 存在,
    const 新_特征类& 特征,
    const std::set<稳定编码>& 会话已撤销模式节点) {
    特征当前值双向闭环结果 r;
    r.读取 = 读取存在特征当前值材料(
        存在节点, 特征类型根, 特征节点, 存在, 特征, 特征概念);
    if (r.读取.状态 != 桥状态::已完成 || !r.读取.材料) {
        r.状态 = r.读取.状态;
        return r;
    }
    r.含义 = 组织特征当前值含义(*r.读取.材料, 特征概念, 存在);
    if (r.含义.状态 != 桥状态::已完成 || !r.含义.含义) {
        r.状态 = r.含义.状态;
        return r;
    }
    r.陈述 = 生成特征当前值陈述(
        语言节点, *r.含义.含义, 额度, 语言, 词, 名称, 存在概念, 特征概念, 存在,
        会话已撤销模式节点);
    if (r.陈述.状态 != 桥状态::已完成 || !r.陈述.表达
        || r.陈述.表达->状态 != 基础表达状态::已生成
        || r.陈述.表达->文本.empty()) {
        r.状态 = r.陈述.状态;
        return r;
    }
    r.理解 = 理解特征当前值陈述(
        语言节点, r.陈述.表达->文本, 额度, 语言, 词, 名称, 存在概念, 特征概念, 存在);
    if (r.理解.状态 != 桥状态::已完成 || !r.理解.含义) {
        r.状态 = r.理解.状态 == 桥状态::已完成 ? 桥状态::往返不一致 : r.理解.状态;
        return r;
    }
    r.往返语义一致 = 含义语义可对齐(*r.含义.含义, *r.理解.含义);
    r.状态 = r.往返语义一致 ? 桥状态::已完成 : 桥状态::往返不一致;
    return r;
}

特征当前值学习消费结果 学习并对账特征当前值模式消费(
    const 特征当前值对齐证据& 证据,
    新语言结构目的细目 消费细目,
    新_语言类& 语言,
    const 新_词类& 词,
    std::set<稳定编码>& 会话已撤销模式节点) {
    特征当前值学习消费结果 r;
    if (证据.替代旧模式节点) {
        r.登记 = 纠正特征当前值模式(
            证据.语言节点, 证据.结构概念节点, *证据.替代旧模式节点,
            证据.模式定义, 证据.种子版本, 语言, 词, 会话已撤销模式节点);
    } else {
        r.登记 = 登记特征当前值对齐模式(
            证据.语言节点, 证据.结构概念节点, 证据.模式定义, 证据.种子版本,
            语言, 词);
    }
    if (r.登记.状态 != 桥状态::已完成 || !r.登记.模式) {
        r.状态 = r.登记.状态;
        return r;
    }
    r.新模式节点 = r.登记.模式->节点;
    if (证据.登记后重建对应表) {
        r.重建 = 重建特征当前值语言结构对应(
            证据.语言节点, 证据.种子版本, 语言, 词);
        if (r.重建->状态 != 新语言知识状态::已完成) {
            r.状态 = 映射知识状态(r.重建->状态);
            return r;
        }
    }
    r.消费查询 = 查询特征当前值生成模式(
        证据.语言节点, 消费细目, 语言, 词, 会话已撤销模式节点);
    if (r.消费查询.状态 != 桥状态::已完成) {
        r.状态 = r.消费查询.状态;
        return r;
    }
    for (const auto& 行 : r.消费查询.行组) {
        if (行.表达模式节点 && *行.表达模式节点 == *r.新模式节点)
            r.新模式已命中 = true;
        if (证据.替代旧模式节点 && 行.表达模式节点
            && *行.表达模式节点 == *证据.替代旧模式节点)
            r.旧模式已过滤 = false;
    }
    if (证据.替代旧模式节点) {
        r.旧模式已过滤 = true;
        for (const auto& 行 : r.消费查询.行组)
            if (行.表达模式节点 && *行.表达模式节点 == *证据.替代旧模式节点)
                r.旧模式已过滤 = false;
        if (r.消费查询.已过滤撤销数 == 0 && 会话已撤销模式节点.contains(*证据.替代旧模式节点)) {
            // 查询结果中本就不含该行时，撤销集仍生效；以集合成员为准。
            r.旧模式已过滤 = true;
        }
    }
    if (!r.新模式已命中) {
        r.状态 = 桥状态::学习未消费;
        return r;
    }
    if (证据.替代旧模式节点 && !r.旧模式已过滤) {
        r.状态 = 桥状态::学习未消费;
        return r;
    }
    r.状态 = 桥状态::已完成;
    return r;
}

特征当前值领域核对结果 核对值陈述与领域当前值(
    稳定编码 存在节点,
    稳定编码 特征类型根,
    const 特征当前值含义组织& 陈述含义,
    const 新_存在类& 存在,
    const 新_特征类& 特征,
    const 概念_特征类& 特征概念) noexcept {
    特征当前值领域核对结果 r;
    r.陈述含义 = 陈述含义;
    if (!有效(存在节点) || !有效(特征类型根)) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    const auto 读 = 读取存在特征当前值材料(
        存在节点, 特征类型根, std::nullopt, 存在, 特征, 特征概念);
    r.领域材料 = 读.材料;
    if (读.状态 == 桥状态::当前值未知) {
        r.状态 = 桥状态::当前值未知;
        r.与领域一致 = 陈述含义.是填项待求 || !陈述含义.准确值;
        return r;
    }
    if (读.状态 != 桥状态::已完成 || !读.材料 || !读.材料->当前值) {
        r.状态 = 读.状态;
        return r;
    }
    if (!陈述含义.准确值) {
        r.状态 = 桥状态::往返不一致;
        return r;
    }
    r.与领域一致 = 准确值相等(*读.材料->当前值, *陈述含义.准确值);
    r.状态 = r.与领域一致 ? 桥状态::已完成 : 桥状态::往返不一致;
    return r;
}

