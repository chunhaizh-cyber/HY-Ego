特征当前值理解结果 理解特征当前值陈述(
    稳定编码 语言节点,
    const std::string& 固定原文,
    const 特征当前值额度& 额度,
    const 新_语言类& 语言,
    const 新_词类& 词,
    const 概念_名称关系类& 名称,
    const 概念_存在类& 存在概念,
    const 概念_特征类& 特征概念,
    const 新_存在类& 存在) {
    特征当前值理解结果 r;
    r.固定原文 = 固定原文;
    if (!有效(语言节点) || 固定原文.empty()) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }

    语言基础统一输入请求 请求;
    请求.语言节点 = 语言节点;
    请求.固定原文 = 固定原文;
    请求.最大原文标量数 = 额度.最大原文标量数;
    请求.最大知识条目数 = 额度.最大知识条目数;
    请求.最大名称候选数 = 额度.最大名称候选数;
    请求.最大组合候选数 = 额度.最大组合候选数;
    请求.最大确认候选数 = 额度.最大确认候选数;

    try {
        const auto 解释 = 只读解释单句基础语言(
            请求, 语言, 词, 名称, 存在概念, 特征概念, 存在);
        r.解释状态 = 解释.状态;
        r.构式 = 解释.构式;
        r.状态 = 映射解释状态(解释.状态);
        if (r.状态 != 桥状态::已完成) return r;
        if (!解释.构式) {
            r.状态 = 桥状态::理解未闭合;
            return r;
        }

        const auto 取绑定主体 = [&](std::int64_t 主体编号) -> 稳定编码 {
            if (解释.含义 && std::holds_alternative<语言场景基础含义>(*解释.含义)) {
                for (const auto& 绑 : std::get<语言场景基础含义>(*解释.含义).对象绑定组)
                    if (绑.局部出现编号 == 主体编号 && 有效(绑.实例节点))
                        return 绑.实例节点;
            }
            for (const auto& 绑 : 解释.已取得对象绑定组)
                if (绑.局部出现编号 == 主体编号 && 有效(绑.实例节点))
                    return 绑.实例节点;
            return {};
        };

        if (*解释.构式 == 语言基础统一构式::S03整数) {
            const 语言场景基础候选* 候选 = nullptr;
            if (解释.含义 && std::holds_alternative<语言场景基础含义>(*解释.含义))
                候选 = &std::get<语言场景基础含义>(*解释.含义).解释;
            else if (解释.完整候选组.size() == 1
                && std::holds_alternative<语言场景基础候选>(解释.完整候选组.front()))
                候选 = &std::get<语言场景基础候选>(解释.完整候选组.front());
            if (!候选 || 候选->构式 != 语言场景基础构式::S03整数) {
                r.状态 = 桥状态::理解未闭合;
                return r;
            }
            const auto* 主张 = std::get_if<语言场景整数特征主张>(&候选->主张);
            if (!主张) {
                r.状态 = 桥状态::内部不一致;
                return r;
            }
            特征当前值含义组织 含义;
            含义.值式 = 特征当前值值式类别::I64准确值;
            含义.主体存在 = 取绑定主体(主张->主体出现编号);
            for (const auto& 出现 : 候选->出现组) {
                if (const auto* 名 = std::get_if<语言场景基础命名出现>(&出现)) {
                    if (名->局部出现编号 == 主张->特征类型出现编号)
                        含义.特征类型 = 名->概念节点;
                } else if (const auto* 数 = std::get_if<语言场景基础整数出现>(&出现)) {
                    if (数->局部出现编号 == 主张->整数出现编号) {
                        const auto v = 解析规范十进制(数->规范十进制);
                        if (!v) {
                            r.状态 = 桥状态::内部不一致;
                            return r;
                        }
                        含义.准确值 = *v;
                    }
                }
            }
            if (!有效(含义.特征类型) || !含义.准确值) {
                r.状态 = 桥状态::理解未闭合;
                return r;
            }
            r.含义 = std::move(含义);
            r.状态 = 桥状态::已完成;
            return r;
        }

        if (*解释.构式 == 语言基础统一构式::S03特征概念条件) {
            const 语言场景基础候选* 候选 = nullptr;
            if (解释.含义 && std::holds_alternative<语言场景基础含义>(*解释.含义))
                候选 = &std::get<语言场景基础含义>(*解释.含义).解释;
            else if (解释.完整候选组.size() == 1
                && std::holds_alternative<语言场景基础候选>(解释.完整候选组.front()))
                候选 = &std::get<语言场景基础候选>(解释.完整候选组.front());
            if (!候选 || 候选->构式 != 语言场景基础构式::S03特征概念条件) {
                r.状态 = 桥状态::理解未闭合;
                return r;
            }
            const auto* 主张 = std::get_if<语言场景特征概念主张>(&候选->主张);
            if (!主张) {
                r.状态 = 桥状态::内部不一致;
                return r;
            }
            特征当前值含义组织 含义;
            含义.值式 = 特征当前值值式类别::特征概念条件;
            含义.引用类别 = 新语言知识角色类别::特征概念;
            含义.主体存在 = 取绑定主体(主张->主体出现编号);
            for (const auto& 出现 : 候选->出现组) {
                if (const auto* 名 = std::get_if<语言场景基础命名出现>(&出现)) {
                    if (名->局部出现编号 == 主张->特征类型出现编号)
                        含义.特征类型 = 名->概念节点;
                    if (名->局部出现编号 == 主张->特征概念出现编号)
                        含义.准确值 = 名->概念节点;
                }
            }
            if (!有效(含义.特征类型) || !含义.准确值) {
                r.状态 = 桥状态::理解未闭合;
                return r;
            }
            r.含义 = std::move(含义);
            r.状态 = 桥状态::已完成;
            return r;
        }

        r.状态 = 桥状态::能力未支持;
        return r;
    } catch (const std::bad_alloc&) {
        r.状态 = 桥状态::工程未完成;
        return r;
    } catch (const std::logic_error&) {
        r.状态 = 桥状态::内部不一致;
        return r;
    }
}

