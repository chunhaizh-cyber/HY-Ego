特征当前值读取结果 读取存在特征当前值材料(
    稳定编码 存在节点,
    std::optional<稳定编码> 特征类型根,
    std::optional<稳定编码> 特征节点,
    const 新_存在类& 存在,
    const 新_特征类& 特征,
    const 概念_特征类& 特征概念) noexcept {
    try {
        if (!有效(存在节点)) return 拒绝读取(桥状态::输入拒绝);
        if (!特征类型根 && !特征节点) return 拒绝读取(桥状态::输入拒绝);
        if (特征类型根 && !有效(*特征类型根)) return 拒绝读取(桥状态::输入拒绝);
        if (特征节点 && !有效(*特征节点)) return 拒绝读取(桥状态::输入拒绝);

        const auto 定位 = 存在.读取存在顶层特征定位保护(存在节点);
        switch (定位.状态) {
        case 新存在顶层特征定位状态::已读取:
            break;
        case 新存在顶层特征定位状态::输入不适用:
            return 拒绝读取(桥状态::输入拒绝);
        case 新存在顶层特征定位状态::存在不存在:
            return 拒绝读取(桥状态::存在不可读);
        case 新存在顶层特征定位状态::依赖未就绪:
        case 新存在顶层特征定位状态::资源失败:
            return 拒绝读取(桥状态::工程未完成);
        case 新存在顶层特征定位状态::前提已变化:
            return 拒绝读取(桥状态::读取漂移);
        default:
            return 拒绝读取(桥状态::内部不一致);
        }
        if (!定位.信息) return 拒绝读取(桥状态::内部不一致);

        std::vector<稳定编码> 候选;
        if (特征节点) {
            const auto& 组 = 定位.信息->顶层特征节点组;
            if (std::find(组.begin(), 组.end(), *特征节点) == 组.end())
                return 拒绝读取(桥状态::特征未持有);
            候选.push_back(*特征节点);
        } else {
            for (const auto f : 定位.信息->顶层特征节点组) {
                const auto 完整 = 特征.读取特征完整保护(f);
                if (完整.状态 == 新特征完整读取状态::特征不存在) continue;
                if (完整.状态 == 新特征完整读取状态::依赖未就绪
                    || 完整.状态 == 新特征完整读取状态::资源失败)
                    return 拒绝读取(桥状态::工程未完成);
                if (完整.状态 == 新特征完整读取状态::前提已变化)
                    return 拒绝读取(桥状态::读取漂移);
                if (完整.状态 == 新特征完整读取状态::类型未支持)
                    return 拒绝读取(桥状态::能力未支持);
                if (完整.状态 != 新特征完整读取状态::已读取 || !完整.信息)
                    return 拒绝读取(桥状态::内部不一致);
                if (完整.信息->特征类型根 == *特征类型根)
                    候选.push_back(f);
            }
            if (候选.empty()) return 拒绝读取(桥状态::特征未持有);
            if (候选.size() > 1) return 拒绝读取(桥状态::多特征同型);
        }

        const auto 完整 = 特征.读取特征完整保护(候选.front());
        switch (完整.状态) {
        case 新特征完整读取状态::已读取:
            break;
        case 新特征完整读取状态::特征不存在:
            return 拒绝读取(桥状态::特征不可读);
        case 新特征完整读取状态::依赖未就绪:
        case 新特征完整读取状态::资源失败:
            return 拒绝读取(桥状态::工程未完成);
        case 新特征完整读取状态::前提已变化:
            return 拒绝读取(桥状态::读取漂移);
        case 新特征完整读取状态::类型未支持:
            return 拒绝读取(桥状态::能力未支持);
        default:
            return 拒绝读取(桥状态::内部不一致);
        }
        if (!完整.信息) return 拒绝读取(桥状态::内部不一致);
        if (特征类型根 && 完整.信息->特征类型根 != *特征类型根)
            return 拒绝读取(桥状态::类型不相容);

        auto 材料 = 自完整保护形成材料(存在节点, *完整.信息);
        if (!材料) return 拒绝读取(桥状态::内部不一致);
        const auto 概念 = 特征概念.获取特征概念(材料->特征概念节点);
        if (!概念) return 拒绝读取(桥状态::特征不可读);
        材料->材料类型 = 概念->材料类型;
        if (!材料->单位) 材料->单位 = 概念->单位;

        特征当前值读取结果 r;
        r.状态 = 材料->当前值 ? 桥状态::已完成 : 桥状态::当前值未知;
        r.材料 = std::move(*材料);
        return r;
    } catch (const std::bad_alloc&) {
        return 拒绝读取(桥状态::工程未完成);
    } catch (...) {
        return 拒绝读取(桥状态::内部不一致);
    }
}

特征当前值含义结果 组织特征当前值含义(
    const 特征当前值正式材料& 材料) noexcept {
    特征当前值含义结果 r;
    if (!有效(材料.存在节点) || !有效(材料.特征节点)
        || !有效(材料.特征类型根) || !有效(材料.特征概念节点)) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    特征当前值含义组织 m;
    m.主体存在 = 材料.存在节点;
    m.特征类型 = 材料.特征类型根;
    m.单位 = 材料.单位;
    m.准确值 = 材料.当前值;
    m.是填项待求 = !材料.当前值.has_value();
    r.含义 = std::move(m);
    r.状态 = 材料.当前值 ? 桥状态::已完成 : 桥状态::当前值未知;
    return r;
}

特征当前值陈述结果 生成特征当前值陈述(
    稳定编码 语言节点,
    const 特征当前值含义组织& 含义,
    const 特征当前值额度& 额度,
    const 新_语言类& 语言,
    const 新_词类& 词,
    const 概念_名称关系类& 名称,
    const 概念_存在类& 存在概念,
    const 概念_特征类& 特征概念,
    const 新_存在类& 存在) {
    if (!有效(语言节点) || !有效(含义.主体存在) || !有效(含义.特征类型))
        return 失败陈述(桥状态::输入拒绝);
    if (含义.是填项待求 || !含义.准确值)
        return 失败陈述(桥状态::当前值未知);

    const auto* i64 = std::get_if<std::int64_t>(&*含义.准确值);
    if (!i64) {
        // 首片只闭合 I64 准确值陈述；稳定编码型当前值另片扩展。
        return 失败陈述(桥状态::能力未支持);
    }

    // 特征类型根须为可读特征概念；否则下游生成会引用不可读。
    if (!特征概念.获取特征概念(含义.特征类型)) {
        const auto 自比 = 特征概念.比较单特征概念(含义.特征类型, 含义.特征类型);
        if (自比.状态 != 特征概念规则状态::已完成 || !自比.特征类型根)
            return 失败陈述(桥状态::特征不可读);
    }

    基础表达请求 请求;
    请求.语言节点 = 语言节点;
    请求.目的 = 新语言知识表达目的::陈述;
    请求.操作 = 新语言知识含义操作::特征描述;
    请求.作用域 = 新语言知识作用域::普通陈述;
    请求.最大知识条目数 = 额度.最大知识条目数;
    请求.最大名称条目数 = 额度.最大名称条目数;
    请求.最大输出标量数 = 额度.最大输出标量数;
    请求.参数组 = {
        {新语言知识参数角色::主体, 新语言知识角色类别::存在,
            基础表达参数种类::领域对象, 含义.主体存在, {}},
        {新语言知识参数角色::特征类型, 新语言知识角色类别::正式特征类型,
            基础表达参数种类::特征类型, 含义.特征类型, {}},
        {新语言知识参数角色::特征值, 新语言知识角色类别::I64标量,
            基础表达参数种类::准确值, *i64, {}},
    };

    特征当前值陈述结果 r;
    r.所用含义 = 含义;
    try {
        auto 表达 = 生成基础语言表达(
            请求, 语言, 词, 名称, 存在概念, 特征概念, 存在, nullptr);
        r.状态 = 映射表达状态(表达.状态);
        r.表达 = std::move(表达);
        return r;
    } catch (const std::bad_alloc&) {
        return 失败陈述(桥状态::工程未完成);
    } catch (const std::logic_error&) {
        return 失败陈述(桥状态::内部不一致);
    }
}

特征当前值陈述结果 生成特征当前值填项问(
    稳定编码 语言节点,
    const 特征当前值含义组织& 含义,
    稳定编码 受询者存在,
    const 特征当前值额度& 额度,
    const 新_语言类& 语言,
    const 新_词类& 词,
    const 概念_名称关系类& 名称,
    const 概念_存在类& 存在概念,
    const 概念_特征类& 特征概念,
    const 新_存在类& 存在) {
    if (!有效(语言节点) || !有效(含义.主体存在) || !有效(含义.特征类型)
        || !有效(受询者存在))
        return 失败陈述(桥状态::输入拒绝);
    if (!含义.是填项待求 && 含义.准确值)
        return 失败陈述(桥状态::输入拒绝);

    // 提问：特征描述 + 填项内容；特征值以查询变量占位。普通存在特征询问模板若仍缺，
    // 生成器返回缺规则，本桥如实映射，不伪造问句。
    基础表达请求 请求;
    请求.语言节点 = 语言节点;
    请求.目的 = 新语言知识表达目的::提问;
    请求.操作 = 新语言知识含义操作::信息请求;
    请求.作用域 = 新语言知识作用域::提问范围;
    请求.被询操作 = 新语言知识含义操作::特征描述;
    请求.确认范围 = 新语言知识确认范围::填项内容;
    请求.受询者 = 受询者存在;
    请求.最大知识条目数 = 额度.最大知识条目数;
    请求.最大名称条目数 = 额度.最大名称条目数;
    请求.最大输出标量数 = 额度.最大输出标量数;
    请求.参数组 = {
        {新语言知识参数角色::主体, 新语言知识角色类别::存在,
            基础表达参数种类::领域对象, 含义.主体存在, {}},
        {新语言知识参数角色::特征类型, 新语言知识角色类别::正式特征类型,
            基础表达参数种类::特征类型, 含义.特征类型, {}},
    };

    特征当前值陈述结果 r;
    auto 待求含义 = 含义;
    待求含义.准确值.reset();
    待求含义.是填项待求 = true;
    r.所用含义 = std::move(待求含义);
    try {
        auto 表达 = 生成基础语言表达(
            请求, 语言, 词, 名称, 存在概念, 特征概念, 存在, nullptr);
        r.状态 = 映射表达状态(表达.状态);
        r.表达 = std::move(表达);
        return r;
    } catch (const std::bad_alloc&) {
        return 失败陈述(桥状态::工程未完成);
    } catch (const std::logic_error&) {
        return 失败陈述(桥状态::内部不一致);
    }
}

特征当前值理解结果 理解特征当前值陈述(
    稳定编码 语言节点,
    const std::string& 固定原文,
    const 特征当前值额度& 额度,
    const 新_语言类& 语言,
    const 新_词类& 词,
    const 概念_名称关系类& 名称,
    const 概念_存在类& 存在概念,
    const 概念_特征类& 特征概念,
    const 新_存在类& 存在) {
    特征当前值理解结果 r;
    r.固定原文 = 固定原文;
    if (!有效(语言节点) || 固定原文.empty()) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }

    语言基础统一输入请求 请求;
    请求.语言节点 = 语言节点;
    请求.固定原文 = 固定原文;
    请求.最大原文标量数 = 额度.最大原文标量数;
    请求.最大知识条目数 = 额度.最大知识条目数;
    请求.最大名称候选数 = 额度.最大名称候选数;
    请求.最大组合候选数 = 额度.最大组合候选数;
    请求.最大确认候选数 = 额度.最大确认候选数;

    try {
        const auto 解释 = 只读解释单句基础语言(
            请求, 语言, 词, 名称, 存在概念, 特征概念, 存在);
        r.解释状态 = 解释.状态;
        r.构式 = 解释.构式;
        r.状态 = 映射解释状态(解释.状态);
        if (r.状态 != 桥状态::已完成) return r;
        if (!解释.构式 || *解释.构式 != 语言基础统一构式::S03整数) {
            r.状态 = 桥状态::能力未支持;
            return r;
        }

        const 语言场景基础候选* 候选 = nullptr;
        if (解释.含义 && std::holds_alternative<语言场景基础含义>(*解释.含义)) {
            候选 = &std::get<语言场景基础含义>(*解释.含义).解释;
        } else if (解释.完整候选组.size() == 1
            && std::holds_alternative<语言场景基础候选>(解释.完整候选组.front())) {
            候选 = &std::get<语言场景基础候选>(解释.完整候选组.front());
        }
        if (!候选 || 候选->构式 != 语言场景基础构式::S03整数) {
            r.状态 = 桥状态::理解未闭合;
            return r;
        }
        const auto* 主张 = std::get_if<语言场景整数特征主张>(&候选->主张);
        if (!主张) {
            r.状态 = 桥状态::内部不一致;
            return r;
        }

        特征当前值含义组织 含义;
        含义.是填项待求 = false;
        for (const auto& 出现 : 候选->出现组) {
            if (const auto* 名 = std::get_if<语言场景基础命名出现>(&出现)) {
                if (名->局部出现编号 == 主张->特征类型出现编号)
                    含义.特征类型 = 名->概念节点;
            } else if (const auto* 数 = std::get_if<语言场景基础整数出现>(&出现)) {
                if (数->局部出现编号 == 主张->整数出现编号) {
                    const auto v = 解析规范十进制(数->规范十进制);
                    if (!v) {
                        r.状态 = 桥状态::内部不一致;
                        return r;
                    }
                    含义.准确值 = *v;
                }
            }
        }
        if (!有效(含义.特征类型) || !含义.准确值) {
            r.状态 = 桥状态::理解未闭合;
            return r;
        }

        // 主体：优先对象绑定；否则保留空主体（概念级主张，不冒充现实存在）。
        if (解释.含义 && std::holds_alternative<语言场景基础含义>(*解释.含义)) {
            const auto& 场景含义 = std::get<语言场景基础含义>(*解释.含义);
            for (const auto& 绑 : 场景含义.对象绑定组) {
                if (绑.局部出现编号 == 主张->主体出现编号 && 有效(绑.实例节点)) {
                    含义.主体存在 = 绑.实例节点;
                    break;
                }
            }
        }
        for (const auto& 绑 : 解释.已取得对象绑定组) {
            if (绑.局部出现编号 == 主张->主体出现编号 && 有效(绑.实例节点)) {
                含义.主体存在 = 绑.实例节点;
                break;
            }
        }

        r.含义 = std::move(含义);
        r.状态 = 桥状态::已完成;
        return r;
    } catch (const std::bad_alloc&) {
        r.状态 = 桥状态::工程未完成;
        return r;
    } catch (const std::logic_error&) {
        r.状态 = 桥状态::内部不一致;
        return r;
    }
}

特征当前值模式登记结果 登记特征当前值对齐模式(
    稳定编码 语言节点,
    稳定编码 结构概念节点,
    const 新语言表达模式定义& 定义,
    const std::string& 种子版本,
    新_语言类& 语言,
    const 新_词类& 词) {
    特征当前值模式登记结果 r;
    if (!有效(语言节点) || !有效(结构概念节点) || 种子版本.empty()
        || 定义.模式标识.empty()) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    try {
        const auto 发布 = 语言.建立或取得表达模式(
            语言节点, 结构概念节点, 定义, 种子版本, 词);
        r.受阻节点组 = 发布.受阻节点组;
        r.发布种类 = 发布.发布种类;
        r.模式 = 发布.信息;
        r.状态 = 映射知识状态(发布.状态);
        return r;
    } catch (const std::bad_alloc&) {
        r.状态 = 桥状态::工程未完成;
        return r;
    } catch (const std::logic_error&) {
        r.状态 = 桥状态::内部不一致;
        return r;
    }
}

特征当前值模式登记结果 纠正特征当前值模式(
    稳定编码 语言节点,
    稳定编码 结构概念节点,
    稳定编码 旧模式节点,
    const 新语言表达模式定义& 新定义,
    const std::string& 种子版本,
    新_语言类& 语言,
    const 新_词类& 词,
    std::set<稳定编码>& 会话已撤销模式节点) {
    特征当前值模式登记结果 r;
    if (!有效(旧模式节点)) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    const auto 旧 = 语言.获取表达模式(旧模式节点, 词);
    if (旧.状态 != 新语言知识状态::已完成 || !旧.信息) {
        r.状态 = 映射知识状态(旧.状态);
        r.受阻节点组 = 旧.受阻节点组;
        return r;
    }
    if (旧.信息->语言节点 != 语言节点
        || 旧.信息->结构概念节点 != 结构概念节点) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    if (新定义.模式标识 == 旧.信息->定义.模式标识) {
        // 同标识不同定义会被建立入口拒绝；纠正必须换标识。
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    r = 登记特征当前值对齐模式(
        语言节点, 结构概念节点, 新定义, 种子版本, 语言, 词);
    if (r.状态 == 桥状态::已完成)
        会话已撤销模式节点.insert(旧模式节点);
    return r;
}

特征当前值模式查询结果 查询特征当前值生成模式(
    稳定编码 语言节点,
    新语言结构目的细目 细目,
    const 新_语言类& 语言,
    const 新_词类& 词,
    const std::set<稳定编码>& 会话已撤销模式节点) {
    特征当前值模式查询结果 r;
    if (!有效(语言节点)) {
        r.状态 = 桥状态::输入拒绝;
        return r;
    }
    新语言结构生成查询 q;
    q.语言节点 = 语言节点;
    q.种类 = 新语言结构信息种类::特征值;
    q.细目 = 细目;
    const auto 查 = 语言.查询结构对应_生成(q, 词);
    return 过滤撤销行(查.状态, 查.信息组, 查.受阻节点组, 会话已撤销模式节点);
}

