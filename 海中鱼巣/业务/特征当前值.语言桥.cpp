    if (!含义.是填项待求 && 含义.准确值)
        return 失败陈述(桥状态::输入拒绝);

    特征当前值陈述结果 r;
    auto 待求含义 = 含义;
    待求含义.准确值.reset();
    待求含义.是填项待求 = true;
    待求含义.值式 = 特征当前值值式类别::未知待求;
