特征当前值模式查询结果 过滤撤销行(
    新语言知识状态 源状态,
    std::vector<新语言结构对应行> 行组,
    std::vector<稳定编码> 受阻,
    const std::set<稳定编码>& 撤销) {
    特征当前值模式查询结果 r;
    r.受阻节点组 = std::move(受阻);
    if (源状态 != 新语言知识状态::已完成) {
        r.状态 = 映射知识状态(源状态);
        return r;
    }
    r.状态 = 桥状态::已完成;
    r.行组.reserve(行组.size());
    for (auto& 行 : 行组) {
        if (行.表达模式节点 && 撤销.contains(*行.表达模式节点)) {
            ++r.已过滤撤销数;
            continue;
        }
        r.行组.push_back(std::move(行));
    }
    return r;
}

std::optional<std::int64_t> 解析规范十进制(const std::string& 文本) {
    if (文本.empty()) return std::nullopt;
    std::size_t i = 0;
    bool 负 = false;
    if (文本[0] == '-') {
        负 = true;
        i = 1;
        if (i >= 文本.size()) return std::nullopt;
    }
    if (文本[i] == '0' && 文本.size() != i + 1) return std::nullopt;
    std::int64_t v = 0;
    for (; i < 文本.size(); ++i) {
        const char c = 文本[i];
        if (c < '0' || c > '9') return std::nullopt;
        const auto d = static_cast<std::int64_t>(c - '0');
        if (负) {
            if (v < (std::numeric_limits<std::int64_t>::min() + d) / 10)
                return std::nullopt;
            v = v * 10 - d;
        } else {
            if (v > (std::numeric_limits<std::int64_t>::max() - d) / 10)
                return std::nullopt;
            v = v * 10 + d;
        }
    }
    return v;
}

std::optional<新语言结构对应行> 首选生成模式行(
    稳定编码 语言节点,
    新语言结构目的细目 细目,
    const 新_语言类& 语言,
    const 新_词类& 词,
    const std::set<稳定编码>& 撤销) {
    const auto 查 = 查询特征当前值生成模式(语言节点, 细目, 语言, 词, 撤销);
    if (查.状态 != 桥状态::已完成 || 查.行组.empty()) return std::nullopt;
    // 优先交互纠正来源，其次已登记且有表达模式的行。
    const 新语言结构对应行* 选 = nullptr;
    for (const auto& 行 : 查.行组) {
        if (行.状态 != 新语言结构对应状态::已登记 || !行.表达模式节点) continue;
        if (行.来源 == 新语言结构来源种类::交互纠正) return 行;
        if (!选) 选 = &行;
    }
    if (选) return *选;
    return 查.行组.front();
}

bool 准确值相等(const 新特征准确值& a, const 新特征准确值& b) noexcept {
    if (a.index() != b.index()) return false;
    if (const auto* x = std::get_if<std::int64_t>(&a))
        return *x == std::get<std::int64_t>(b);
    return std::get<稳定编码>(a) == std::get<稳定编码>(b);
}

bool 含义语义可对齐(
    const 特征当前值含义组织& 出,
    const 特征当前值含义组织& 回) noexcept {
    if (出.值式 != 回.值式) return false;
    if (有效(出.特征类型) && 有效(回.特征类型) && 出.特征类型 != 回.特征类型)
        return false;
    if (出.是填项待求 || 回.是填项待求) return 出.是填项待求 == 回.是填项待求;
    if (!出.准确值 || !回.准确值) return false;
    if (!准确值相等(*出.准确值, *回.准确值)) return false;
    // 主体：回读可能仅有概念级主张；有双方存在绑定时才强制同指。
    if (有效(出.主体存在) && 有效(回.主体存在) && 出.主体存在 != 回.主体存在)
        return false;
    return true;
}

特征当前值值式类别 判定值式(
    const 特征当前值正式材料& 材料,
    const 概念_特征类& 特征概念,
    const 新_存在类& 存在) noexcept {
    if (!材料.当前值) return 特征当前值值式类别::未知待求;
    if (std::holds_alternative<std::int64_t>(*材料.当前值))
        return 特征当前值值式类别::I64准确值;
    const auto 码 = std::get<稳定编码>(*材料.当前值);
    if (!有效(码)) return 特征当前值值式类别::其它引用;
    if (材料.材料类型 == 特征概念材料物理类型::存在节点引用
        || 存在.是存在节点(码))
        return 特征当前值值式类别::存在引用;
    if (特征概念.获取特征概念(码))
        return 特征当前值值式类别::特征概念条件;
    if (材料.比较规则 == 特征概念比较规则::概念集合身份判等)
        return 特征当前值值式类别::特征概念条件;
    return 特征当前值值式类别::其它引用;
}

