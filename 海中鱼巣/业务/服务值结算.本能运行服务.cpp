std::int64_t 加一(std::int64_t 值) noexcept {
    return 值 == (std::numeric_limits<std::int64_t>::max)() ? 值 : 值 + 1;
}
std::optional<std::int64_t> 单值(const 概念_特征类& 服务, 稳定编码 节点) {
    const auto 概念 = 服务.获取特征概念(节点);
    if (!概念 || 概念->材料类型 != 特征概念材料物理类型::I64标量) return std::nullopt;
    const auto* 域 = std::get_if<std::vector<特征概念I64闭区间>>(&概念->值域);
    if (!域 || 域->size() != 1 || 域->front().下界 != 域->front().上界) return std::nullopt;
    return 域->front().下界;
}
std::optional<新特征值域比较输入> 结算值域输入(const 概念_特征类& 概念,
    稳定编码 类型, std::optional<稳定编码> 概念域,
    const std::optional<特征概念I64闭区间>& 精确域) {
    if (概念域.has_value() == 精确域.has_value()) return std::nullopt;
    const auto 信息 = 概念.获取特征概念(类型);
    if (!信息 || 信息->材料类型 != 特征概念材料物理类型::I64标量) return std::nullopt;
    新特征值域比较输入 输入{类型, 信息->单位, {}};
    if (精确域) 输入.材料 = 新特征直接I64值域比较材料{*精确域};
    else 输入.材料 = 新特征概念值域比较材料{*概念域};
    return 输入;
}
std::optional<std::int64_t> 结算单值(const 新_特征类& 特征, const 概念_特征类& 概念,
    稳定编码 类型, std::optional<稳定编码> 概念域,
    const std::optional<特征概念I64闭区间>& 精确域) {
    const auto 输入 = 结算值域输入(概念, 类型, 概念域, 精确域);
    if (!输入) return std::nullopt;
    const auto 比较 = 特征.比较特征值域(*输入, *输入);
    if (比较.状态 != 新特征比较状态::已完成 || !比较.关系编码) return std::nullopt;
    if (精确域) return 精确域->下界 == 精确域->上界
        ? std::optional<std::int64_t>{精确域->下界} : std::nullopt;
    return 单值(概念, *概念域);
}
