新方法建立结果 服务需求本能运行服务::确保方法登记(新服务需求获取方式 方式,
    const 新方法知识建立请求& 请求) noexcept {
    if (!实现_ || 登记名(方式).empty()) return {};
    try {
        std::optional<新服务需求获取配置> 配置;
        { std::lock_guard 锁(实现_->互斥);
          if (实现_->已关闭 || !实现_->配置) return {};
          配置 = 实现_->配置; }
        if (!配置 || !请求.条件结果组.empty()) return {};
        新方法信息 校验;
        校验.本能函数登记名 = 登记名(方式); 校验.作用域 = 请求.作用域;
        校验.实现方式 = 请求.实现方式; 校验.方法头 = 请求.方法头; 校验.参数规格组 = 请求.参数规格组;
        校验.行为 = 请求.行为; 校验.初始模拟关系组 = 请求.初始模拟关系组;
        if (!规格一致(校验, *配置, 方式)) return {};
        const auto 结果 = 实现_->方法.确保本能方法登记(std::string(登记名(方式)), 请求);
        if (!结果.方法节点 || (结果.状态 != 新方法操作状态::已建立 && 结果.状态 != 新方法操作状态::已找到)) return 结果;
        const auto 读回 = 实现_->方法.获取方法(*结果.方法节点);
        if (!读回 || !规格一致(*读回, *配置, 方式) || 读回->来源方法节点 || 读回->实例根节点
            || (结果.状态 == 新方法操作状态::已建立 && !读回->条件结果组.empty()))
            return {新方法操作状态::结构不一致, {}};
        { std::lock_guard 锁(实现_->互斥); 实现_->登记方法.insert_or_assign(方式, *结果.方法节点); }
        return 结果;
    } catch (...) { return {新方法操作状态::资源失败, {}}; }
}
新方法本能调用结果 服务需求本能运行服务::执行(稳定编码 M,
    const 方法参数场景& 场景, 稳定编码 X) noexcept {
    if (!实现_ || 场景.用途() != 新方法参数场景用途::执行 || 场景.方法节点() != M) return {};
    try {
        const auto 保活 = shared_from_this();
        auto& s = *实现_;
        const auto m = s.方法.获取方法(M);
        if (!m) return {};
        const auto 方式 = m->本能函数登记名 == 新本能函数登记名_主动获取服务需求
            ? 新服务需求获取方式::主动 : 新服务需求获取方式::被动;
        std::optional<新服务需求获取配置> 配置;
        稳定编码 抽象;
        { std::lock_guard 锁(s.互斥);
          if (!s.就绪 || s.已关闭 || !s.登记方法.contains(方式)) return {};
          配置 = s.配置; 抽象 = s.登记方法.at(方式); }
        if (!配置 || !s.校验任务方法(M, X, 方式, *配置, 抽象)
            || s.任务.复核执行本能输入(X, 场景) != 新任务本能输入复核状态::仍具备) return {};
        // 独立调用包装与通用W3共用同一守卫；已在W3内不得再次调用本包装。
        新_本能函数管理类::本能执行守卫 守卫(场景, X);
        return s.方法.调用本能函数(M, 场景);
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求执行", L"执行绑定异常。");
    }
}
新本能函数本次条件结果对 服务需求本能运行服务::执行任务(
    新服务需求获取方式 方式, const 方法参数场景& 场景, 稳定编码 X) noexcept {
    新本能函数本次条件结果对 运行;
    运行.结果.状态 = 新本能函数执行状态::参数不匹配;
    try {
        auto& s = *实现_;
        新服务需求获取配置 c; 稳定编码 M{};
        { std::lock_guard 锁(s.互斥);
          if (!s.就绪 || s.已关闭 || !s.配置 || !s.登记方法.contains(方式)) return 运行;
          c = *s.配置; M = s.登记方法.at(方式); ++s.活动; }
        实现::调用票 票{s};
        if (场景.用途() != 新方法参数场景用途::执行 || 场景.全部角色绑定().size() != 6
            || 新_本能函数管理类::读取本次执行实例(场景) != std::optional{X}) return 运行;
        std::array<稳定编码, 6> p{};
        for (std::uint32_t i = 0; i < 6; ++i) {
            const auto* 引用 = 场景.查询参数(i + 1);
            const auto 类型 = i == 2 || i >= 4 ? 新方法参数信息类型::特征 : 新方法参数信息类型::存在;
            if (!引用 || 引用->信息类型 != 类型) return 运行;
            const auto& b = 场景.全部角色绑定()[i];
            if (b.有序引用 != *引用 || b.参数角色节点.值 || b.实际存在节点 || !b.实际特征组.empty()
                || b.任务虚拟存在引用 || b.服务要求分项引用 || b.服务要求确认引用) return 运行;
            p[i] = 引用->信息节点;
        }
        if (p[1] != c.自我存在节点 || p[1] == p[3] || p[5] != c.服务任务集合特征节点) return 运行;
        auto 事实 = s.世界.获取事实服务引用();
        const auto 复核 = [&]() {
            if (s.停止源.stop_requested() || !s.校验任务方法(场景.方法节点(), X, 方式, c, M)
                || s.任务.复核执行本能输入(X, 场景) != 新任务本能输入复核状态::仍具备) return false;
            const auto S = s.世界.查询场景(p[0]);
            const auto E = s.世界.查询存在(p[1]), H = s.世界.查询存在(p[3]);
            if (!S || !E || !H) return false;
            for (auto 节点 : {p[1], p[3]})
                if (std::find(S->直接成员存在组.begin(), S->直接成员存在组.end(), 节点) == S->直接成员存在组.end()) return false;
            for (auto i : {2, 4, 5}) {
                const auto F = s.世界.查询特征(p[i]);
                const auto 定义 = F ? 事实.特征服务.捕获特征匹配定义(F->特征概念节点) : std::nullopt;
                const auto 根 = i == 2 ? c.交互者特征类型节点 : i == 4 ? c.对象需求类型 : c.服务任务集合类型;
                const auto& 主体 = i == 4 ? H : E;
                if (!F || !定义 || 定义->特征类型根 != 根
                    || std::find(主体->特征节点组.begin(), 主体->特征节点组.end(), p[i]) == 主体->特征节点组.end()) return false;
            }
            return 事实.存在服务.采集存在概念匹配材料(p[3], c.人类概念节点).匹配.状态 == 新存在概念匹配状态::匹配
                && !s.连接.读取已确认连接事实(p[0], p[1], p[3], p[2]).empty();
        };
        const auto 候选 = [&]() {
            std::vector<稳定编码> 合法;
            const auto 当前 = s.需求发布.读取主体需求(p[0], p[3]);
            if (当前.状态 != 服务对象需求发布状态::已读取 || 当前.需求特征节点 != std::optional{p[4]}
                || !当前.当前需求节点) return 合法;
            for (auto D : {*当前.当前需求节点}) {
                const auto d = s.需求.获取需求(D);
                if (!d || d->执行域 != 新需求执行域::被认知 || d->需求主体存在节点 != p[3]
                    || !d->认知来源 || !d->认知来源->来源要求节点) continue;
                const auto& 来源 = *d->认知来源;
                const auto C = s.材料读取.复核服务要求确认语义(来源.内容确认节点);
                if (C.状态 == 新服务要求确认状态::未装配 || C.状态 == 新服务要求确认状态::结构不一致
                    || C.状态 == 新服务要求确认状态::资源失败)
                    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求", L"确认读取工程故障。");
                if (C.状态 != 新服务要求确认状态::当前有效 || !C.确认
                    || C.确认->来源人类节点 != p[3]
                    || C.确认->理解节点 != 来源.理解节点 || C.确认->来源要求节点 != 来源.来源要求节点
                    || d->目标存在节点 != C.确认->目标存在节点 || d->目标 != C.确认->目标) continue;
                const auto R = s.部分读取.读取部分服务要求(*来源.来源要求节点);
                if (R.状态 == 新部分服务要求读取状态::工程故障)
                    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求", L"来源材料读取故障。");
                if (R.状态 != 新部分服务要求读取状态::已读取 || !R.材料
                    || R.材料->要求节点 != *来源.来源要求节点
                    || R.材料->来源人类节点 != p[3] || R.材料->理解节点 != std::optional{来源.理解节点}
                    || R.材料->确认节点 != std::optional{来源.内容确认节点}
                    || !查询服务要求缺项(*R.材料).empty()) continue;
                const auto& 已知 = R.材料->已知目标;
                if (已知.目标存在节点 != std::optional{C.确认->目标存在节点}
                    || 已知.目标特征类型概念节点 != std::optional{C.确认->目标.目标特征类型概念节点}
                    || 已知.目标形式 != std::optional{C.确认->目标.目标形式}
                    || 已知.目标值域概念节点 != C.确认->目标.目标值域概念节点
                    || 已知.目标比较关系概念节点 != C.确认->目标.目标比较关系概念节点
                    || 已知.目标变化方向 != C.确认->目标.目标变化方向) continue;
                合法.push_back(D);
            }
            return 合法;
        };
        if (!复核()) return 运行;
        const auto ds = 候选();
        if (ds.size() != 1) return 运行;
        const auto D = ds.front();
        for (std::size_t i = 0; i < 6; ++i) {
            const auto& b = 场景.全部角色绑定()[i];
            新本能函数条件角色材料 材料;
            材料.有序引用 = b.有序引用; 材料.世界场景节点 = b.世界场景节点;
            if (i == 2 || i >= 4) {
                const auto F = 场景.读取绑定特征(p[i]);
                if (!F) return 运行;
                材料.实际特征组.push_back({p[i], F->当前值});
            }
            运行.条件.参数角色组.push_back(std::move(材料));
        }
        if (!复核() || 候选() != ds) return 运行;
        const auto 旧 = s.动态.按来源查询动作(X);
        if (旧.状态 != 新动态操作状态::已完成 || 旧.动作)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求", L"动作来源重复或不可读。");
        const auto 时间 = UTC时钟适配器{}.读取当前UTC时间证据_v1({});
        if (!时间.成功()) 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求", L"UTC不可读。");
        新_本能函数管理类::标记本次动作入口(场景);
        const auto 发布 = s.世界.建立动作动态(p[0], {p[1], 场景.方法节点(), X, p[1], p[5],
            {新状态时间语义::实例绝对UTC, 时间.证据->UTC纳秒}});
        const auto 动作 = s.动态.按来源查询动作(X);
        if (发布.状态 != 新世界动作发布状态::已完成 || 动作.状态 != 新动态操作状态::已完成 || !动作.动作)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求", L"动作发布读回失败。");
        运行.结果.动作动态节点 = 动作.动作->节点;
        运行.结果.动作阶段 = 新本能函数动作阶段::已进入动作;
        运行.结果.状态 = 新本能函数执行状态::动作结果未知;
        运行.结果.结果取得状态 = 新本能函数结果取得状态::部分取得;
        if (!复核() || 候选() != ds) return 运行;
        const auto 采用 = 执行服务需求采用(方式, 场景, 动作.动作->节点, D);
        if (采用.控制 == 新服务需求执行控制::已收束) {
            运行.结果.状态 = 新本能函数执行状态::已按合同返回;
            运行.结果.动作阶段 = 新本能函数动作阶段::已按函数合同返回;
        }
        return 运行;
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求", L"执行异常，保留真实动作。");
    }
}
新服务需求执行回执 服务需求本能运行服务::执行服务需求采用(
    新服务需求获取方式 方式, const 方法参数场景& 场景, 稳定编码 动作节点, 稳定编码 对方需求节点) noexcept {
    try {
        if (!实现_ || 场景.用途() != 新方法参数场景用途::执行 || 登记名(方式).empty())
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"执行内采用服务需求", L"调用场景或依赖不一致。");
        auto& s = *实现_;
        const auto X = 新_本能函数管理类::读取本次执行实例(场景);
        const auto 执行 = X ? s.任务.获取执行实例(*X) : std::nullopt;
        if (!执行 || 执行->方法节点 != 场景.方法节点()
            || !s.自我线程.使用服务需求执行依赖(s.任务, s.任务管理))
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"执行内采用服务需求", L"当前执行或owner不一致。");
        // 先保存已经发生的动作及其采用依据；停止不能把它变成空执行。
        s.任务.记录服务需求执行依据(执行->任务节点, *X, 场景, 动作节点, 对方需求节点);
        const auto 自我停止 = s.自我线程.读取停止令牌();
        const auto 管理停止 = s.任务管理.读取停止令牌();
        const auto 停止中 = [&] { return s.停止源.stop_requested()
            || 自我停止.stop_requested() || 管理停止.stop_requested(); };
        if (停止中()) return {};
        const 新服务需求取得反馈定位 定位{执行->任务节点, *X};
        const auto 接收 = s.自我线程.提交服务需求执行(定位);
        if (接收.状态 == 新自我消息接收状态::已停止接收) return {};
        if (接收.状态 == 新自我消息接收状态::尚未启动)
            return {新服务需求执行控制::条件已变化, {}};
        if (接收.状态 == 新自我消息接收状态::入口拒绝) {
            if (停止中()) return {};
            const auto 当前任务 = s.任务.获取任务(定位.任务节点);
            const auto 当前执行 = s.任务.获取执行实例(定位.执行实例节点);
            if (!当前任务 || !当前执行 || 当前执行->任务节点 != 定位.任务节点)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"执行内采用服务需求", L"拒绝后执行身份不可读。");
            if (当前任务->最近执行实例节点 != 定位.执行实例节点
                || 当前任务->当前状态 != 新任务状态::执行中
                || 当前执行->状态 != 新任务执行状态::执行中)
                return {新服务需求执行控制::条件已变化, {}};
        }
        if ((接收.状态 != 新自我消息接收状态::已接收
                && 接收.状态 != 新自我消息接收状态::精确重复) || !接收.处理结果.valid())
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"执行内采用服务需求", L"专用采用消息接收或future不完整。");
        // 只等内部治理处理，不等人类输入。停止不依赖manager join后的收尾。
        while (接收.处理结果.wait_for(std::chrono::milliseconds(10)) != std::future_status::ready)
            if (停止中()) return {};
        if (停止中()) return {};
        const auto 处理 = 接收.处理结果.get();
        if (!处理.原消息.服务需求取得反馈 || *处理.原消息.服务需求取得反馈 != 定位)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"执行内采用服务需求", L"采用回执来源不一致。");
        if (处理.状态 == 新自我消息处理状态::停止取消
            || 处理.状态 == 新自我消息处理状态::已交接未收回
            || 处理.状态 == 新自我消息处理状态::任务管理未就绪) return {};
        if (处理.状态 == 新自我消息处理状态::等待材料
            || 处理.状态 == 新自我消息处理状态::任务结果定位已变化)
            return {新服务需求执行控制::条件已变化, {}};
        if (处理.状态 != 新自我消息处理状态::任务已承接)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"执行内采用服务需求", L"采用处理未按合同收束。");
        const auto 读回 = s.任务.读回服务需求取得结果(定位.任务节点, 定位.执行实例节点);
        if (读回.状态 == 新任务操作状态::状态材料不足 || 读回.状态 == 新任务操作状态::任务状态不允许)
            return {新服务需求执行控制::条件已变化, {}};
        if (读回.状态 != 新任务操作状态::已找到 || !读回.采用需求节点 || !读回.采用任务节点
            || !读回.来源新增数 || *读回.来源新增数 < 0 || *读回.来源新增数 > 1
            || (*读回.来源新增数 == 1 && 读回.结果状态节点组.empty())
            || (*读回.来源新增数 == 0 && !读回.结果状态节点组.empty()))
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"执行内采用服务需求", L"正式D/T/来源贡献或集合状态读回不完整。");
        // D/T已由正式owner收束；集合S没有显式动作来源，不能冒充本能直接输出。
        // 后续W3-B结合本X出生来源独立读取当前集合并核验，不按时间推断因果。
        return {新服务需求执行控制::已收束, {}};
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"执行内采用服务需求", L"动作后采用异常，保留事实。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"执行内采用服务需求", L"动作后采用未知异常，保留事实。");
    }
}
void 服务需求本能运行服务::报告工程故障(std::string_view 文本) noexcept {
    if (实现_ && 实现_->报告) 实现_->报告(文本);
}
