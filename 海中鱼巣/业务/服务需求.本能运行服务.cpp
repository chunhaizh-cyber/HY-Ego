struct 服务需求本能运行服务::实现 final {
    新_世界树类& 世界;
    新_方法类& 方法;
    新_任务类& 任务;
    新_需求类& 需求;
    新_动态类& 动态;
    服务对象需求发布服务& 需求发布;
    连接本能运行服务& 连接;
    const 新服务要求材料读取接口& 材料读取;
    const 新部分服务要求读取接口& 部分读取;
    新_自我线程类& 自我线程;
    新_任务管理线程类& 任务管理;
    新服务需求工程报告函数 报告;
    std::stop_source 停止源;
    mutable std::mutex 互斥;
    std::condition_variable 退出条件;
    std::size_t 活动 = 0;
    struct 调用票 { 实现& s; ~调用票() { std::lock_guard 锁(s.互斥); --s.活动; s.退出条件.notify_all(); } };
    std::optional<新服务需求获取配置> 配置;
    std::map<新服务需求获取方式, 稳定编码> 登记方法;
    bool 初始化中 = false, 就绪 = false, 已关闭 = false;

    bool 校验任务方法(稳定编码 M, 稳定编码 X, 新服务需求获取方式 方式,
        const 新服务需求获取配置& 配置值, 稳定编码 抽象方法) const {
        const auto 执行 = 任务.获取执行实例(X);
        if (!执行 || 执行->状态 != 新任务执行状态::执行中 || 执行->结束时间
            || 执行->方法节点 != M) return false;
        const auto t = 任务.获取任务(执行->任务节点);
        const auto m = 方法.获取方法(M);
        if (!t || !m)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"服务需求执行核验", L"已存在X的任务或方法不可读。");
        if (t->当前状态 != 新任务状态::执行中 || t->最近执行实例节点 != X
            || !规格一致(*m, 配置值, 方式)) return false;
        if (m->实例根节点 || m->来源方法节点 || M != 抽象方法
            || t->最近方法节点 != M) return false;
        const auto 采用 = 任务.读取执行本能采用(X);
        return 采用 && 采用->来源方法节点 == M
            && 采用->定位.组织节点 == t->方法执行组织节点;
    }
};
