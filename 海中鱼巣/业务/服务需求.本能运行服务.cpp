std::string_view 登记名(新服务需求获取方式 方式) noexcept {
    return 方式 == 新服务需求获取方式::主动 ? 新本能函数登记名_主动获取服务需求
        : 方式 == 新服务需求获取方式::被动 ? 新本能函数登记名_被动获取服务需求 : std::string_view{};
}
bool 规格一致(const 新方法信息& 方法, const 新服务需求获取配置& 配置,
    新服务需求获取方式 方式) {
    if (登记名(方式).empty() || 方法.本能函数登记名 != 登记名(方式)
        || 方法.作用域 != 新方法作用域::普通世界 || 方法.行为 != 新方法行为::改变 || 方法.实现方式 != 新方法实现方式::本能
        || 方法.启用状态 != 新方法启用状态::启用 || 方法.参数规格组.size() != 6
        || 方法.方法头.作用存在概念组 != std::vector<稳定编码>{配置.自我存在概念节点}
        || 方法.方法头.涉及特征类型概念组 != std::vector<稳定编码>{配置.数量变化量类型}
        || 方法.方法头.可能结果概念组 != std::vector<稳定编码>{配置.已新增值域}) return false;
    const std::array 范围{配置.通用存在概念节点, 配置.自我存在概念节点,
        配置.交互者特征类型节点, 配置.人类概念节点, 配置.对象需求类型, 配置.服务任务集合类型};
    for (std::uint32_t i = 0; i < 6; ++i) {
        const auto& p = 方法.参数规格组[i];
        const 新方法有序参数规格 预期{i + 1,
            i == 2 || i >= 4 ? 新方法参数信息类型::特征 : 新方法参数信息类型::存在, 范围[i]};
        if (p.有序规格 != 预期 || p.参数角色节点.值 || p.存在概念节点 || p.要求场景
            || !p.特征规格组.empty() || p.集合成员约束 || p.对象种类 != 新方法参数对象种类::普通世界) return false;
    }
    return 方法.初始模拟关系组 == std::vector<新方法参数关系>{
        {新方法参数关系种类::特征所属存在, 3, 2}, {新方法参数关系种类::特征所属存在, 5, 4},
        {新方法参数关系种类::特征所属存在, 6, 2}, {新方法参数关系种类::同属场景, 2, 4}};
}
