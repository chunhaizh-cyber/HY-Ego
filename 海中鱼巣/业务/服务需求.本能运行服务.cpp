bool 服务需求本能运行服务::初始化(const 新服务需求获取配置& 配置) noexcept {
    if (!实现_) return false;
    auto& s = *实现_;
    try {
        const auto 初始化未完成 = [](const wchar_t* 步骤) {
            (void)记录运行日志(L"获取服务需求", L"初始化停止步骤", 步骤);
            return false;
        };
        const auto 保活 = shared_from_this();
        const auto 自我停止 = s.自我线程.读取停止令牌();
        const auto 管理停止 = s.任务管理.读取停止令牌();
        if (!s.自我线程.使用服务需求执行依赖(s.任务, s.任务管理)
            || s.停止源.stop_requested() || 自我停止.stop_requested()
            || 管理停止.stop_requested()) return 初始化未完成(L"自我与任务管理依赖或停止状态");
        {
            std::lock_guard 锁(s.互斥);
            if (s.已关闭 || s.初始化中 || (s.配置 && *s.配置 != 配置)) return false;
            if (s.就绪) return true;
            s.初始化中 = true;
        }
        struct 守卫 {
            实现& s;
            服务需求本能运行服务& 服务;
            ~守卫() {
                {
                    std::lock_guard 锁(s.互斥);
                    s.初始化中 = false;
                    if (s.停止源.stop_requested()) s.就绪 = false;
                }
                if (s.停止源.stop_requested()) 服务.关闭();
            }
        } 完成{s, *this};
        const auto 场景 = s.世界.查询场景(配置.所在场景节点);
        const auto 自我 = s.世界.查询存在(配置.自我存在节点);
        const auto 集合 = s.世界.查询特征(配置.服务任务集合特征节点);
        const auto 全域 = s.世界.获取事实服务引用().特征概念服务.获取特征概念(配置.服务任务集合全域);
        const auto 类型根 = s.世界.获取事实服务引用().特征概念服务.获取特征概念(配置.服务任务集合类型);
        const auto* 集合域 = 全域 ? std::get_if<特征概念任务集合值域>(&全域->值域) : nullptr;
        const bool 无限制全域 = 全域 && 类型根
            && 全域->材料类型 == 特征概念材料物理类型::U64数组
            && 全域->比较规则 == 特征概念比较规则::服务任务集合身份判等
            && !全域->单位
            && 类型根->材料类型 == 特征概念材料物理类型::U64数组
            && 类型根->比较规则 == 特征概念比较规则::服务任务集合身份判等
            && !类型根->单位
            && ((配置.服务任务集合全域 == 配置.服务任务集合类型
                    && std::holds_alternative<特征概念全材料值域>(全域->值域))
                || (集合域 && !集合域->至少一个任务 && 集合域->必含任务节点组.empty()
                    && 集合域->必含需求任务组.empty() && 集合域->必含服务要求任务组.empty()));
        const auto 类型 = s.世界.获取事实服务引用().特征概念服务.比较单特征概念(配置.服务任务集合全域, 配置.服务任务集合类型);
        if (!场景 || !自我 || 自我->专属存在概念节点 != 配置.自我存在概念节点
            || !s.世界.获取事实服务引用().存在概念服务.获取存在概念(配置.自我存在概念节点) || !集合 || !集合->当前值
            || !s.世界.获取事实服务引用().存在概念服务.获取存在概念(配置.通用存在概念节点)
            || !s.世界.获取事实服务引用().存在概念服务.获取存在概念(配置.人类概念节点)
            || !s.世界.获取事实服务引用().特征概念服务.获取特征概念(配置.交互者特征类型节点)
            || !s.世界.获取事实服务引用().特征概念服务.获取特征概念(配置.对象需求类型)
            || !无限制全域
            || 类型.状态 != 特征概念规则状态::已完成 || 类型.特征类型根 != 配置.服务任务集合类型
            || std::find(场景->直接成员存在组.begin(), 场景->直接成员存在组.end(), 配置.自我存在节点)
                == 场景->直接成员存在组.end()
            || std::find(自我->特征节点组.begin(), 自我->特征节点组.end(), 配置.服务任务集合特征节点)
                == 自我->特征节点组.end()) return 初始化未完成(L"场景、自我、集合及正式范围核验");
        for (auto 名 : {新本能函数登记名_旧主动获取服务需求, 新本能函数登记名_旧被动获取服务需求,
                新本能函数登记名_旧有序主动获取服务需求, 新本能函数登记名_旧有序被动获取服务需求,
                std::string_view{"主动获取服务需求"}, std::string_view{"被动获取服务需求"}}) {
            const auto 旧 = s.方法.查询本能登记(std::string(名));
            if (!旧.方法节点) continue;
            const auto m = s.方法.获取方法(*旧.方法节点);
            if (!m || m->参数规格组.size() != 6)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"服务需求迁移", L"旧规格不可确认。");
            if (m->启用状态 == 新方法启用状态::启用) {
                s.方法.修改启用状态(m->节点, 新方法启用状态::停用);
                const auto 读回 = s.方法.获取方法(m->节点);
                if (!读回 || 读回->启用状态 != 新方法启用状态::停用)
                    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"服务需求迁移", L"旧方法停用未读回。");
            }
        }
        const auto 合同 = s.任务.配置服务需求取得合同({配置.自我存在节点, 配置.服务任务集合特征节点,
            配置.服务任务集合类型, 配置.数量变化量类型, 配置.已新增值域});
        if (合同 != 新任务操作状态::已修改 && 合同 != 新任务操作状态::精确重复)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求初始化", L"任务取得合同配置或互证失败。");
        const auto 注册 = 新_本能函数管理类::初始化();
        if (注册 != 新本能函数登记状态::已登记 && 注册 != 新本能函数登记状态::精确重复) return 初始化未完成(L"本能函数登记表初始化");
        { std::lock_guard 锁(s.互斥); s.配置 = 配置; }
        const auto 装配 = 新_本能函数管理类::装配服务需求获取端口(保活);
        if (装配 != 新本能函数端口装配状态::已装配 && 装配 != 新本能函数端口装配状态::精确重复) return 初始化未完成(L"获取服务需求端口装配");
        const auto 参数 = s.方法.建立服务需求登记参数场景();
        if (!参数.参数场景) return 初始化未完成(L"空登记参数场景建立");
        for (auto 方式 : {新服务需求获取方式::主动, 新服务需求获取方式::被动}) {
            const auto 结果 = 新_本能函数管理类::执行(登记名(方式), *参数.参数场景);
            if (结果.结果.状态 != 新本能函数执行状态::已按合同返回)
                return 初始化未完成(方式 == 新服务需求获取方式::主动 ? L"主动方法六参数首次登记" : L"被动方法六参数首次登记");
        }
        { std::lock_guard 锁(s.互斥);
          s.就绪 = !s.已关闭 && !s.停止源.stop_requested()
              && !自我停止.stop_requested() && !管理停止.stop_requested()
              && s.登记方法.size() == 2;
          return s.就绪; }
    } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求初始化", L"初始化异常。"); }
}
bool 服务需求本能运行服务::关闭() noexcept {
    if (!实现_) return false;
    try {
        实现_->停止源.request_stop();
        { std::lock_guard 锁(实现_->互斥);
          if (实现_->初始化中) return false;
          实现_->已关闭 = true; 实现_->就绪 = false; }
        { std::unique_lock 锁(实现_->互斥);
          实现_->退出条件.wait(锁, [&] { return 实现_->活动 == 0; }); }
        return 新_本能函数管理类::关闭服务需求获取端口(*this) == 新本能函数端口装配状态::已关闭;
    } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求关闭", L"关闭异常。"); }
}
