基础表达结果 生成基础语言表达(
    const 基础表达请求& 请求,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务,
    const 新_存在类& 受询者存在服务) {
    if (!合法请求(请求)) return 失败(基础表达状态::输入拒绝);
    try {
        const auto 候选 = 语言服务.枚举语言知识候选(
            请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
        if (候选.状态 != 新语言知识状态::已完成)
            return 失败(映射知识状态(候选.状态));
        const 新语言知识信息* 选中 = nullptr;
        规则绑定 选中绑定;
        for (const auto& 知识 : 候选.信息组) {
            规则绑定 本次绑定;
            if (!匹配规则(知识, 请求, 本次绑定)
                || !匹配指代选择(知识, 请求)) continue;
            if (选中) return 失败(基础表达状态::多规则待选);
            选中 = &知识;
            选中绑定 = std::move(本次绑定);
        }
        if (!选中) return 失败(基础表达状态::缺规则);

        std::optional<新存在信息> 受询者快照;
        if (请求.目的 == 新语言知识表达目的::提问) {
            受询者快照 = 受询者存在服务.获取存在(*请求.受询者);
            if (!受询者快照 || 受询者快照->节点 != *请求.受询者)
                return 失败(基础表达状态::引用不可读);
        }
        std::optional<新存在信息> 指代目标快照;
        std::optional<新存在信息> 窗口快照;
        if (请求.指代选择) {
            指代目标快照 = 受询者存在服务.获取存在(请求.指代选择->目标存在节点);
            窗口快照 = 受询者存在服务.获取存在(请求.网页自我来源->读取().交互窗口节点);
            if (!指代目标快照 || 指代目标快照->节点 != 请求.指代选择->目标存在节点
                || !窗口快照 || 窗口快照->节点 != 请求.网页自我来源->读取().交互窗口节点)
                return 失败(基础表达状态::引用不可读);
        }

        规则绑定 展开绑定 = 选中绑定;
        std::vector<展开结构项> 展开项组;
        if (请求.目的 == 新语言知识表达目的::提问) {
            const auto& 外层项组 = 选中->定义.结构.有序项组;
            if (外层项组.size() != 2) return 失败(基础表达状态::内部不一致);
            const auto* 子规则 = std::get_if<新语言知识子规则项>(&外层项组.front().载荷);
            if (!子规则 || !std::holds_alternative<新语言知识固定词项>(外层项组.back().载荷))
                return 失败(基础表达状态::内部不一致);
            const auto 子 = std::find_if(候选.信息组.begin(), 候选.信息组.end(),
                [&](const auto& 信息) { return 信息.节点 == 子规则->子知识节点; });
            if (子 == 候选.信息组.end() || 子->定义.结构.语言节点 != 请求.语言节点)
                return 失败(基础表达状态::引用不可读);
            展开绑定.clear();
            for (const auto& 映射 : 子规则->映射组) {
                const auto 原 = 选中绑定.find(映射.外层角色编号);
                if (原 == 选中绑定.end()
                    || !展开绑定.emplace(映射.子规则角色编号, 原->second).second)
                    return 失败(基础表达状态::内部不一致);
            }
            if (展开绑定.size() != 选中绑定.size()) return 失败(基础表达状态::内部不一致);
            for (const auto& 项 : 子->定义.结构.有序项组)
                展开项组.push_back({&项, 子->节点, {外层项组.front().局部编号, 项.局部编号}});
            展开项组.push_back({&外层项组.back(), 选中->节点, {外层项组.back().局部编号}});
        } else {
            for (const auto& 项 : 选中->定义.结构.有序项组)
                展开项组.push_back({&项, 选中->节点, {项.局部编号}});
        }

        for (const auto& 展开 : 展开项组) {
            const auto& 项 = *展开.项;
            if (const auto* 角色项 = std::get_if<新语言知识角色表达项>(&项.载荷)) {
                if (!展开绑定.contains(角色项->规则角色))
                    return 失败(基础表达状态::内部不一致);
                if (角色项->方式 == 新语言知识表达方式::明确对象描述)
                    return 失败(基础表达状态::缺指称);
                if (角色项->方式 == 新语言知识表达方式::已消解指代
                    && (!请求.指代选择 || !角色项->指代概念节点
                        || *角色项->指代概念节点 != 请求.指代选择->指代概念节点))
                    return 失败(基础表达状态::输入拒绝);
            }
        }
        const auto& 含义 = 选中->定义.目标.含义组.front();
        const auto& 参数组 = 请求.目的 == 新语言知识表达目的::提问
            ? 含义.被询含义->参数组 : 含义.参数组;
        if ((请求.目的 == 新语言知识表达目的::陈述
                && 含义.操作 != 新语言知识含义操作::概念归类)
            || 参数组.size() != 2 || 展开绑定.size() != 2)
            return 失败(基础表达状态::能力未支持);
        const 基础表达参数* 主体参数 = nullptr;
        const 基础表达参数* 归类参数 = nullptr;
        for (const auto& [编号, 参数] : 展开绑定) {
            if (参数->参数 == 新语言知识参数角色::主体) 主体参数 = 参数;
            else if (参数->参数 == 新语言知识参数角色::归类概念) 归类参数 = 参数;
        }
        if (!主体参数 || !归类参数) return 失败(基础表达状态::能力未支持);
        if (请求.指代选择) {
            if (主体参数->种类 != 基础表达参数种类::领域对象
                || 主体参数->类别 != 新语言知识角色类别::存在
                || 归类参数->种类 != 基础表达参数种类::概念
                || 归类参数->类别 != 新语言知识角色类别::存在概念)
                return 失败(基础表达状态::输入拒绝);
        } else {
            if (主体参数->种类 != 基础表达参数种类::概念
                || 归类参数->种类 != 基础表达参数种类::概念
                || 主体参数->类别 != 归类参数->类别
                || (主体参数->类别 != 新语言知识角色类别::存在概念
                    && 主体参数->类别 != 新语言知识角色类别::特征概念))
                return 失败(请求.目的 == 新语言知识表达目的::提问
                    ? 基础表达状态::输入拒绝 : 基础表达状态::能力未支持);
        }

        std::optional<单特征概念关系结果> 同根快照;
        std::map<新语言知识参数角色, 概念快照> 比较前概念组;
        if (主体参数->类别 == 新语言知识角色类别::特征概念) {
            for (const auto* 参数 : {主体参数, 归类参数}) {
                const auto 概念 = 读取正式概念(参数->类别,
                    std::get<稳定编码>(参数->内容), 存在概念服务, 特征概念服务);
                if (!概念) return 失败(基础表达状态::引用不可读);
                比较前概念组.emplace(参数->参数, *概念);
            }
            const auto 比较 = 特征概念服务.比较单特征概念(
                std::get<稳定编码>(主体参数->内容),
                std::get<稳定编码>(归类参数->内容));
            const auto 状态 = 核验特征概念同根(比较);
            if (状态 != 基础表达状态::已生成) return 失败(状态);
            同根快照 = 比较;
        }

        std::map<std::int64_t, 名称快照> 名称组;
        for (const auto& [编号, 参数] : 展开绑定) {
            if (请求.指代选择 && 参数->参数 == 新语言知识参数角色::主体) continue;
            名称快照 快照;
            const auto 状态 = 读取名称(*参数, 请求.语言节点,
                请求.最大名称条目数,
                存在概念服务, 特征概念服务,
                名称服务, 词服务, 快照);
            if (状态 != 基础表达状态::已生成) return 失败(状态);
            if (同根快照 && 快照.概念 != 比较前概念组.at(参数->参数))
                return 失败(基础表达状态::读取漂移);
            名称组.emplace(编号, std::move(快照));
        }

        std::optional<指代名称快照> 指代名称;
        if (请求.指代选择) {
            指代名称快照 快照;
            const auto 状态 = 读取指代名称(请求.指代选择->指代概念节点,
                请求.语言节点, 请求.最大名称条目数, 存在概念服务, 名称服务, 快照);
            if (状态 != 基础表达状态::已生成) return 失败(状态);
            指代名称 = std::move(快照);
        }

        基础表达结果 结果;
        std::size_t 标量位置 = 0;
        std::map<稳定编码, 新词条信息> 已用固定词组;
        for (const auto& 展开 : 展开项组) {
            const auto& 项 = *展开.项;
            std::string 片段;
            基础表达对齐项 对齐{标量位置, 标量位置, 项.局部编号, {}, {}, {}};
            对齐.所属知识节点 = 展开.所属知识;
            对齐.结构项路径 = 展开.路径;
            if (const auto* 固定 = std::get_if<新语言知识固定词项>(&项.载荷)) {
                const auto 词条 = 词服务.获取词条(固定->词条节点);
                if (词条.状态 == 新词条查询状态::资源失败)
                    return 失败(基础表达状态::工程未完成);
                if (词条.状态 == 新词条查询状态::结构不一致)
                    return 失败(基础表达状态::内部不一致);
                if (词条.状态 != 新词条查询状态::已找到 || !词条.信息
                    || 词条.信息->节点 != 固定->词条节点
                    || 词条.信息->语言节点 != 请求.语言节点)
                    return 失败(基础表达状态::引用不可读);
                片段 = 词条.信息->规范化词面;
                对齐.词条节点 = 固定->词条节点;
                const auto [位置, 插入] = 已用固定词组.emplace(固定->词条节点, *词条.信息);
                if (!插入 && 位置->second != *词条.信息)
                    return 失败(基础表达状态::读取漂移);
            } else if (const auto* 角色 = std::get_if<新语言知识角色表达项>(&项.载荷)) {
                const auto* 绑定 = 展开绑定.at(角色->规则角色);
                对齐.参数 = 绑定->参数;
                if (角色->方式 == 新语言知识表达方式::已消解指代) {
                    if (!指代名称 || !请求.指代选择
                        || 角色->规则角色 != 请求.指代选择->规则角色)
                        return 失败(基础表达状态::内部不一致);
                    片段 = 指代名称->关系.词条.规范化词面;
                    对齐.指代名称关系节点 = 指代名称->关系.节点;
                } else if (角色->方式 == 新语言知识表达方式::名称表达
                    && 名称组.contains(角色->规则角色)) {
                    片段 = 名称组.at(角色->规则角色).词条.规范化词面;
                    对齐.名称关系节点 = 名称组.at(角色->规则角色).关系节点;
                } else return 失败(基础表达状态::能力未支持);
            } else return 失败(基础表达状态::内部不一致);
            const auto 数量 = 统计标量(片段);
            if (!数量) return 失败(基础表达状态::内部不一致);
            if (*数量 > 请求.最大输出标量数 - 标量位置)
                return 失败(基础表达状态::额度不足);
            标量位置 += *数量;
            对齐.结束标量 = 标量位置;
            结果.文本 += 片段;
            if (对齐.指代名称关系节点) {
                const auto& 选择 = *请求.指代选择;
                结果.指代出现组.push_back({0, 请求.网页自我来源->读取(),
                    选择.指代概念节点, *对齐.指代名称关系节点,
                    选择.目标类型, 选择.目标存在节点, 展开.所属知识,
                    展开.路径, 对齐.起始标量, 对齐.结束标量});
            }
            结果.对齐组.push_back(std::move(对齐));
        }

        // 各 owner 没有共同事务；结束前复读所用材料与全部候选范围。
        for (const auto& [编号, 快照] : 名称组) {
            const auto 类别 = std::holds_alternative<存在概念信息>(快照.概念)
                ? 新语言知识角色类别::存在概念
                : 新语言知识角色类别::特征概念;
            const auto 概念 = 读取正式概念(类别, 快照.概念节点,
                存在概念服务, 特征概念服务);
            const auto 列表 = 名称服务.查询概念名称(快照.概念节点);
            const auto 关系 = 名称服务.获取名称关系(快照.关系节点);
            const auto 词条 = 词服务.获取词条(快照.词条.节点);
            const auto 列表状态 = 映射名称查询状态(列表.状态);
            if (列表状态 != 基础表达状态::已生成) return 失败(列表状态);
            const auto 关系状态 = 映射名称查询状态(关系.状态);
            if (关系状态 != 基础表达状态::已生成) return 失败(关系状态);
            if (词条.状态 == 新词条查询状态::资源失败)
                return 失败(基础表达状态::工程未完成);
            if (词条.状态 == 新词条查询状态::结构不一致)
                return 失败(基础表达状态::内部不一致);
            if (!概念 || !关系.信息 || !词条.信息
                || 关系.状态 != 概念名称关系查询状态::已找到
                || 词条.状态 != 新词条查询状态::已找到)
                return 失败(基础表达状态::读取漂移);
            if ((列表.状态 != 概念名称关系查询状态::已找到
                    && 列表.状态 != 概念名称关系查询状态::未找到)
                || 列表.名称关系节点组 != 快照.全关系节点组)
                return 失败(基础表达状态::读取漂移);
            if (*概念 != 快照.概念 || *关系.信息 != 快照.关系
                || *词条.信息 != 快照.词条)
                return 失败(基础表达状态::读取漂移);
        }
        if (同根快照) {
            const auto 最终比较 = 特征概念服务.比较单特征概念(
                std::get<稳定编码>(主体参数->内容),
                std::get<稳定编码>(归类参数->内容));
            const auto 状态 = 核验特征概念同根(最终比较);
            if (状态 == 基础表达状态::输入拒绝
                || 状态 == 基础表达状态::引用不可读)
                return 失败(基础表达状态::读取漂移);
            if (状态 != 基础表达状态::已生成) return 失败(状态);
            if (!比较结果相同(*同根快照, 最终比较))
                return 失败(基础表达状态::读取漂移);
        }
        if (受询者快照) {
            const auto 当前受询者 = 受询者存在服务.获取存在(*请求.受询者);
            if (!当前受询者 || *当前受询者 != *受询者快照)
                return 失败(基础表达状态::读取漂移);
        }
        if (指代目标快照) {
            const auto 当前目标 = 受询者存在服务.获取存在(请求.指代选择->目标存在节点);
            const auto 当前窗口 = 受询者存在服务.获取存在(请求.网页自我来源->读取().交互窗口节点);
            if (!当前目标 || *当前目标 != *指代目标快照
                || !当前窗口 || *当前窗口 != *窗口快照)
                return 失败(基础表达状态::读取漂移);
            指代名称快照 最终名称;
            const auto 名称状态 = 读取指代名称(请求.指代选择->指代概念节点,
                请求.语言节点, 请求.最大名称条目数, 存在概念服务, 名称服务, 最终名称);
            if (名称状态 == 基础表达状态::工程未完成
                || 名称状态 == 基础表达状态::内部不一致)
                return 失败(名称状态);
            if (名称状态 != 基础表达状态::已生成
                || 最终名称.概念 != 指代名称->概念
                || 最终名称.全关系节点组 != 指代名称->全关系节点组
                || !同一指代名称关系(最终名称.关系, 指代名称->关系))
                return 失败(基础表达状态::读取漂移);
        }
        for (const auto& [身份, 原词] : 已用固定词组) {
            const auto 当前词 = 词服务.获取词条(身份);
            if (当前词.状态 == 新词条查询状态::资源失败)
                return 失败(基础表达状态::工程未完成);
            if (当前词.状态 == 新词条查询状态::结构不一致)
                return 失败(基础表达状态::内部不一致);
            if (当前词.状态 != 新词条查询状态::已找到 || !当前词.信息
                || *当前词.信息 != 原词) return 失败(基础表达状态::读取漂移);
        }
        const auto 最终候选 = 语言服务.枚举语言知识候选(
            请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
        if (最终候选.状态 != 新语言知识状态::已完成)
            return 失败(映射知识状态(最终候选.状态));
        if (!知识列表相同(候选.信息组, 最终候选.信息组))
            return 失败(基础表达状态::读取漂移);
        结果.状态 = 基础表达状态::已生成;
        结果.知识节点 = 选中->节点;
        结果.已核验受询者 = 请求.受询者;
        结果.已用绑定 = 请求.参数组;
        for (auto& 绑定 : 结果.已用绑定) {
            for (const auto& [编号, 参数] : 展开绑定)
                if (参数->参数 == 绑定.参数 && 名称组.contains(编号))
                    绑定.选用名称关系 = 名称组.at(编号).关系节点;
        }
        return 结果;
    } catch (const std::bad_alloc&) {
        return 失败(基础表达状态::工程未完成);
    } catch (const std::length_error&) {
        return 失败(基础表达状态::工程未完成);
    }
}

