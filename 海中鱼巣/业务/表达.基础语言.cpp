基础表达状态 核验特征概念同根(const 单特征概念关系结果& 比较) {
    switch (比较.状态) {
    case 特征概念规则状态::已完成:
        if (!比较.关系) return 基础表达状态::内部不一致;
        if (*比较.关系 == 单特征概念关系::无可比关系)
            return (比较.特征类型根 || 比较.最近共同上位)
                ? 基础表达状态::内部不一致
                : 基础表达状态::输入拒绝;
        if (!比较.特征类型根 || !有效(*比较.特征类型根)
            || !比较.最近共同上位 || !有效(*比较.最近共同上位))
            return 基础表达状态::内部不一致;
        switch (*比较.关系) {
        case 单特征概念关系::同一:
        case 单特征概念关系::左为上位:
        case 单特征概念关系::右为上位:
        case 单特征概念关系::具有共同上位:
            return 基础表达状态::已生成;
        default: return 基础表达状态::内部不一致;
        }
    case 特征概念规则状态::值不存在:
        return 基础表达状态::引用不可读;
    case 特征概念规则状态::资源失败:
        return 基础表达状态::工程未完成;
    case 特征概念规则状态::入口拒绝:
    case 特征概念规则状态::规则不支持:
        return 基础表达状态::能力未支持;
    default: return 基础表达状态::内部不一致;
    }
}

