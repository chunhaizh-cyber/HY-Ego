bool 合法参数(const 基础表达参数& 参数) {
    const auto 参数号 = static_cast<std::uint8_t>(参数.参数);
    const auto 类别号 = static_cast<std::uint8_t>(参数.类别);
    const auto 种类号 = static_cast<std::uint8_t>(参数.种类);
    if (参数号 < 1 || 参数号 > 6 || 类别号 < 1 || 类别号 > 6
        || 种类号 < 1 || 种类号 > 4) return false;
    switch (参数.种类) {
    case 基础表达参数种类::概念:
        return (参数.类别 == 新语言知识角色类别::存在概念
            || 参数.类别 == 新语言知识角色类别::特征概念)
            && std::holds_alternative<稳定编码>(参数.内容)
            && 有效(std::get<稳定编码>(参数.内容));
    case 基础表达参数种类::领域对象:
        return 参数.类别 == 新语言知识角色类别::存在
            && std::holds_alternative<稳定编码>(参数.内容)
            && 有效(std::get<稳定编码>(参数.内容))
            && !参数.选用名称关系;
    case 基础表达参数种类::特征类型:
        return (参数.类别 == 新语言知识角色类别::正式特征类型
            || 参数.类别 == 新语言知识角色类别::I64标量特征类型)
            && std::holds_alternative<稳定编码>(参数.内容)
            && 有效(std::get<稳定编码>(参数.内容))
            && !参数.选用名称关系;
    case 基础表达参数种类::准确值:
        return 参数.类别 == 新语言知识角色类别::I64标量
            && std::holds_alternative<std::int64_t>(参数.内容)
            && !参数.选用名称关系;
    default: return false;
    }
}

bool 合法请求(const 基础表达请求& 请求) {
    if (!有效(请求.语言节点) || 请求.最大知识条目数 == 0
        || 请求.最大名称条目数 == 0
        || 请求.最大输出标量数 == 0 || 请求.参数组.empty()
        || 请求.目的 != 新语言知识表达目的::陈述
        || 请求.作用域 != 新语言知识作用域::普通陈述) return false;
    const auto 操作号 = static_cast<std::uint8_t>(请求.操作);
    if (操作号 < 1 || 操作号 > 3) return false;
    std::set<新语言知识参数角色> 已有;
    for (const auto& 参数 : 请求.参数组) {
        if (!合法参数(参数) || !已有.insert(参数.参数).second) return false;
        if (参数.选用名称关系 && !有效(*参数.选用名称关系)) return false;
    }
    return true;
}

基础表达状态 映射知识状态(新语言知识状态 状态) {
    switch (状态) {
    case 新语言知识状态::已完成: return 基础表达状态::已生成;
    case 新语言知识状态::未找到: return 基础表达状态::缺规则;
    case 新语言知识状态::输入拒绝: return 基础表达状态::输入拒绝;
    case 新语言知识状态::尚未初始化:
    case 新语言知识状态::未支持: return 基础表达状态::能力未支持;
    case 新语言知识状态::引用不可读: return 基础表达状态::引用不可读;
    case 新语言知识状态::读取漂移: return 基础表达状态::读取漂移;
    case 新语言知识状态::内部不一致: return 基础表达状态::内部不一致;
    case 新语言知识状态::工程未完成: return 基础表达状态::工程未完成;
    case 新语言知识状态::额度不足: return 基础表达状态::额度不足;
    default: return 基础表达状态::内部不一致;
    }
}

bool 种类相容(新语言知识角色种类 规则种类, 基础表达参数种类 实参种类) {
    switch (规则种类) {
    case 新语言知识角色种类::领域对象引用:
        return 实参种类 == 基础表达参数种类::领域对象;
    case 新语言知识角色种类::概念引用:
        return 实参种类 == 基础表达参数种类::概念;
    case 新语言知识角色种类::特征类型引用:
        return 实参种类 == 基础表达参数种类::特征类型;
    case 新语言知识角色种类::准确值:
        return 实参种类 == 基础表达参数种类::准确值;
    default: return false;
    }
}

using 规则绑定 = std::map<std::int64_t, const 基础表达参数*>;

bool 匹配规则(const 新语言知识信息& 知识, const 基础表达请求& 请求,
    规则绑定& 绑定) {
    const auto& 定义 = 知识.定义;
    if (定义.目标.目的 != 请求.目的 || 定义.结构.语言节点 != 请求.语言节点
        || 定义.结构.类别 != 新语言知识结构类别::基础表达
        || 定义.目标.含义组.size() != 1
        || !定义.目标.适用条件组.empty()) return false;
    const auto& 含义 = 定义.目标.含义组.front();
    if (含义.操作 != 请求.操作 || 含义.作用域 != 请求.作用域
        || 含义.参数组.size() != 请求.参数组.size()) return false;
    规则绑定 候选绑定;
    for (const auto& 角色参数 : 含义.参数组) {
        const auto 实参 = std::find_if(请求.参数组.begin(), 请求.参数组.end(),
            [&](const auto& 项) { return 项.参数 == 角色参数.参数; });
        const auto 角色 = std::find_if(定义.目标.角色组.begin(), 定义.目标.角色组.end(),
            [&](const auto& 项) { return 项.局部编号 == 角色参数.规则角色; });
        if (实参 == 请求.参数组.end() || 角色 == 定义.目标.角色组.end()
            || !种类相容(角色->种类, 实参->种类)
            || 角色->数量 != 新语言知识角色数量::单项) return false;
        for (const auto& 约束 : 角色->必要约束组)
            if (约束.被约束角色 != 角色->局部编号
                || std::find(约束.允许类别组.begin(), 约束.允许类别组.end(), 实参->类别)
                    == 约束.允许类别组.end()) return false;
        if (!候选绑定.emplace(角色参数.规则角色, &*实参).second) return false;
    }
    绑定 = std::move(候选绑定);
    return true;
}

using 概念快照 = std::variant<存在概念信息, 特征概念信息>;

struct 名称快照 final {
    稳定编码 概念节点;
    概念快照 概念;
    std::vector<稳定编码> 全关系节点组;
    稳定编码 关系节点;
    概念名称关系信息 关系;
    新词条信息 词条;
};

std::optional<概念快照> 读取正式概念(
    新语言知识角色类别 类别, 稳定编码 概念节点,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    switch (类别) {
    case 新语言知识角色类别::存在概念: {
        const auto 概念 = 存在概念服务.获取存在概念(概念节点);
        if (概念 && 概念->节点 == 概念节点) return 概念快照{*概念};
        return std::nullopt;
    }
    case 新语言知识角色类别::特征概念: {
        const auto 概念 = 特征概念服务.获取特征概念(概念节点);
        if (概念 && 概念->节点 == 概念节点) return 概念快照{*概念};
        return std::nullopt;
    }
    default: return std::nullopt;
    }
}

const std::vector<稳定编码>& 概念名称关系组(const 概念快照& 概念) {
    return std::visit([](const auto& 信息) -> const std::vector<稳定编码>& {
        return 信息.名称关系;
    }, 概念);
}

基础表达状态 核验特征概念同根(const 单特征概念关系结果& 比较) {
    switch (比较.状态) {
    case 特征概念规则状态::已完成:
        if (!比较.关系) return 基础表达状态::内部不一致;
        if (*比较.关系 == 单特征概念关系::无可比关系)
            return (比较.特征类型根 || 比较.最近共同上位)
                ? 基础表达状态::内部不一致
                : 基础表达状态::输入拒绝;
        if (!比较.特征类型根 || !有效(*比较.特征类型根)
            || !比较.最近共同上位 || !有效(*比较.最近共同上位))
            return 基础表达状态::内部不一致;
        switch (*比较.关系) {
        case 单特征概念关系::同一:
        case 单特征概念关系::左为上位:
        case 单特征概念关系::右为上位:
        case 单特征概念关系::具有共同上位:
            return 基础表达状态::已生成;
        default: return 基础表达状态::内部不一致;
        }
    case 特征概念规则状态::值不存在:
        return 基础表达状态::引用不可读;
    case 特征概念规则状态::资源失败:
        return 基础表达状态::工程未完成;
    case 特征概念规则状态::入口拒绝:
    case 特征概念规则状态::规则不支持:
        return 基础表达状态::能力未支持;
    default: return 基础表达状态::内部不一致;
    }
}

bool 比较结果相同(const 单特征概念关系结果& 左,
    const 单特征概念关系结果& 右) {
    return 左.状态 == 右.状态 && 左.关系 == 右.关系
        && 左.特征类型根 == 右.特征类型根
        && 左.最近共同上位 == 右.最近共同上位;
}

基础表达状态 映射名称查询状态(概念名称关系查询状态 状态) {
    switch (状态) {
    case 概念名称关系查询状态::已找到:
    case 概念名称关系查询状态::未找到:
        return 基础表达状态::已生成;
    case 概念名称关系查询状态::读取漂移:
    case 概念名称关系查询状态::依赖已变化:
        return 基础表达状态::读取漂移;
    case 概念名称关系查询状态::资源失败:
    case 概念名称关系查询状态::工程未完成:
        return 基础表达状态::工程未完成;
    case 概念名称关系查询状态::结构不一致:
        return 基础表达状态::内部不一致;
    case 概念名称关系查询状态::输入不合法:
        return 基础表达状态::输入拒绝;
    default:
        return 基础表达状态::引用不可读;
    }
}

基础表达状态 读取名称(const 基础表达参数& 参数, 稳定编码 语言节点,
    std::size_t 最大名称条目数,
    const 概念_存在类& 存在概念服务, const 概念_特征类& 特征概念服务,
    const 概念_名称关系类& 名称服务, const 新_词类& 词服务,
    名称快照& 快照) {
    const auto 概念节点 = std::get<稳定编码>(参数.内容);
    const auto 概念 = 读取正式概念(参数.类别, 概念节点,
        存在概念服务, 特征概念服务);
    if (!概念) return 基础表达状态::引用不可读;
    const auto 列表 = 名称服务.查询概念名称(概念节点);
    const auto 列表状态 = 映射名称查询状态(列表.状态);
    if (列表状态 != 基础表达状态::已生成) return 列表状态;
    if (列表.名称关系节点组.size() > 最大名称条目数)
        return 基础表达状态::额度不足;
    if (列表.名称关系节点组 != 概念名称关系组(*概念))
        return 基础表达状态::读取漂移;
    std::vector<std::pair<概念名称关系信息, 新词条信息>> 同语言名称组;
    for (const auto 关系节点 : 列表.名称关系节点组) {
        const auto 关系 = 名称服务.获取名称关系(关系节点);
        const auto 关系状态 = 映射名称查询状态(关系.状态);
        if (关系状态 != 基础表达状态::已生成) return 关系状态;
        if (关系.状态 != 概念名称关系查询状态::已找到 || !关系.信息
            || 关系.信息->节点 != 关系节点
            || 关系.信息->概念节点 != 概念节点)
            return 基础表达状态::读取漂移;
        const auto 词条 = 词服务.获取词条(关系.信息->词条节点);
        if (词条.状态 == 新词条查询状态::资源失败)
            return 基础表达状态::工程未完成;
        if (词条.状态 == 新词条查询状态::结构不一致)
            return 基础表达状态::内部不一致;
        if (词条.状态 != 新词条查询状态::已找到 || !词条.信息
            || 词条.信息->节点 != 关系.信息->词条节点)
            return 基础表达状态::引用不可读;
        if (词条.信息->语言节点 == 语言节点) {
            if (词条.信息->规范化词面.empty()
                || !新_语言类::严格UTF8字节串有效(词条.信息->规范化词面))
                return 基础表达状态::内部不一致;
            同语言名称组.emplace_back(*关系.信息, *词条.信息);
        }
    }
    if (参数.选用名称关系) {
        const auto 选中 = std::find_if(同语言名称组.begin(), 同语言名称组.end(),
            [&](const auto& 项) { return 项.first.节点 == *参数.选用名称关系; });
        if (选中 == 同语言名称组.end()) return 基础表达状态::输入拒绝;
        快照 = {概念节点, *概念, 列表.名称关系节点组,
            选中->first.节点, 选中->first, 选中->second};
    } else {
        if (同语言名称组.empty()) return 基础表达状态::缺名称;
        if (同语言名称组.size() != 1) return 基础表达状态::名称待选;
        快照 = {概念节点, *概念, 列表.名称关系节点组,
            同语言名称组.front().first.节点,
            同语言名称组.front().first, 同语言名称组.front().second};
    }
    return 基础表达状态::已生成;
}

bool 知识列表相同(const std::vector<新语言知识信息>& 左,
    const std::vector<新语言知识信息>& 右) {
    if (左.size() != 右.size()) return false;
    for (std::size_t i = 0; i < 左.size(); ++i)
        if (左[i].节点 != 右[i].节点 || 左[i].目标节点 != 右[i].目标节点
            || 左[i].结构节点 != 右[i].结构节点 || 左[i].定义 != 右[i].定义
            || 左[i].来源组 != 右[i].来源组) return false;
    return true;
}

std::optional<std::size_t> 统计标量(const std::string& 文本) {
    if (文本.empty() || !新_语言类::严格UTF8字节串有效(文本)) return std::nullopt;
    std::size_t 数量 = 0;
    for (const unsigned char 字节 : 文本)
        if ((字节 & 0xC0) != 0x80) ++数量;
    return 数量;
}

