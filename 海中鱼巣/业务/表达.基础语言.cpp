bool 同一指代名称关系(const 指代名称关系信息& 左,
    const 指代名称关系信息& 右) {
    return 左.节点 == 右.节点 && 左.概念 == 右.概念
        && 左.词条 == 右.词条 && 左.语言 == 右.语言
        && 左.角色 == 右.角色
        && 左.来源.节点 == 右.来源.节点
        && 左.来源.种类 == 右.来源.种类
        && 左.来源.语言节点 == 右.来源.语言节点
        && 左.来源.固定原文 == 右.来源.固定原文;
}

基础表达状态 读取指代名称(稳定编码 指代概念节点, 稳定编码 语言节点,
    std::size_t 最大名称条目数, const 概念_存在类& 存在概念服务,
    const 概念_名称关系类& 名称服务, 指代名称快照& 快照) {
    const auto 概念 = 存在概念服务.获取指代概念(指代概念节点);
    if (概念.状态 == 指代概念查询状态::资源失败) return 基础表达状态::工程未完成;
    if (概念.状态 == 指代概念查询状态::结构不一致) return 基础表达状态::内部不一致;
    if (概念.状态 == 指代概念查询状态::依赖已变化
        || 概念.状态 == 指代概念查询状态::读取漂移)
        return 基础表达状态::读取漂移;
    if (概念.状态 == 指代概念查询状态::输入拒绝) return 基础表达状态::输入拒绝;
    if (概念.状态 != 指代概念查询状态::已找到 || !概念.信息)
        return 基础表达状态::引用不可读;
    if (概念.信息->定义.目标范围 != 指代目标范围::单个已登记强类型信息节点
        || 概念.信息->定义.规则 != 指代声明规则::作用域说话者
        || 概念.信息->定义.参数组 != std::vector<指代参数定义>{
            {指代参数角色::目标, 指代参数类型::强类型信息节点},
            {指代参数角色::作用域, 指代参数类型::交互作用域}}
        || !概念.信息->定义.特征约束组.empty())
        return 基础表达状态::输入拒绝;
    const auto 名称 = 名称服务.查询指代概念名称(指代概念节点);
    if (名称.状态 == 指代名称读取状态::资源失败
        || 名称.状态 == 指代名称读取状态::工程未完成)
        return 基础表达状态::工程未完成;
    if (名称.状态 == 指代名称读取状态::结构不一致)
        return 基础表达状态::内部不一致;
    if (名称.状态 == 指代名称读取状态::依赖已变化
        || 名称.状态 == 指代名称读取状态::读取漂移)
        return 基础表达状态::读取漂移;
    if (名称.状态 == 指代名称读取状态::输入拒绝)
        return 基础表达状态::输入拒绝;
    if (名称.状态 == 指代名称读取状态::未找到) return 基础表达状态::缺名称;
    if (名称.状态 != 指代名称读取状态::已读取) return 基础表达状态::引用不可读;
    if (名称.信息组.size() > 最大名称条目数) return 基础表达状态::额度不足;
    std::vector<稳定编码> 身份组;
    std::optional<指代名称关系信息> 选中;
    for (const auto& 项 : 名称.信息组) {
        if (项.概念 != *概念.信息 || !有效(项.节点))
            return 基础表达状态::读取漂移;
        身份组.push_back(项.节点);
        if (项.语言.节点 != 语言节点 || 项.角色 != 指代名称角色::首选名称) continue;
        if (选中) return 基础表达状态::名称待选;
        选中 = 项;
    }
    if (!选中) return 基础表达状态::缺名称;
    if (选中->词条.规范化词面 != "我"
        || 选中->词条.语言节点 != 语言节点)
        return 基础表达状态::输入拒绝;
    快照 = {*概念.信息, std::move(身份组), *选中};
    return 基础表达状态::已生成;
}

std::optional<概念快照> 读取正式概念(
    新语言知识角色类别 类别, 稳定编码 概念节点,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    switch (类别) {
    case 新语言知识角色类别::存在概念: {
        const auto 概念 = 存在概念服务.获取存在概念(概念节点);
        if (概念 && 概念->节点 == 概念节点) return 概念快照{*概念};
        return std::nullopt;
    }
    case 新语言知识角色类别::特征概念: {
        const auto 概念 = 特征概念服务.获取特征概念(概念节点);
        if (概念 && 概念->节点 == 概念节点) return 概念快照{*概念};
        return std::nullopt;
    }
    default: return std::nullopt;
    }
}

const std::vector<稳定编码>& 概念名称关系组(const 概念快照& 概念) {
    return std::visit([](const auto& 信息) -> const std::vector<稳定编码>& {
        return 信息.名称关系;
    }, 概念);
}

基础表达状态 核验特征概念同根(const 单特征概念关系结果& 比较) {
    switch (比较.状态) {
    case 特征概念规则状态::已完成:
        if (!比较.关系) return 基础表达状态::内部不一致;
        if (*比较.关系 == 单特征概念关系::无可比关系)
            return (比较.特征类型根 || 比较.最近共同上位)
                ? 基础表达状态::内部不一致
                : 基础表达状态::输入拒绝;
        if (!比较.特征类型根 || !有效(*比较.特征类型根)
            || !比较.最近共同上位 || !有效(*比较.最近共同上位))
            return 基础表达状态::内部不一致;
        switch (*比较.关系) {
        case 单特征概念关系::同一:
        case 单特征概念关系::左为上位:
        case 单特征概念关系::右为上位:
        case 单特征概念关系::具有共同上位:
            return 基础表达状态::已生成;
        default: return 基础表达状态::内部不一致;
        }
    case 特征概念规则状态::值不存在:
        return 基础表达状态::引用不可读;
    case 特征概念规则状态::资源失败:
        return 基础表达状态::工程未完成;
    case 特征概念规则状态::入口拒绝:
    case 特征概念规则状态::规则不支持:
        return 基础表达状态::能力未支持;
    default: return 基础表达状态::内部不一致;
    }
}

bool 比较结果相同(const 单特征概念关系结果& 左,
    const 单特征概念关系结果& 右) {
    return 左.状态 == 右.状态 && 左.关系 == 右.关系
        && 左.特征类型根 == 右.特征类型根
        && 左.最近共同上位 == 右.最近共同上位;
}

基础表达状态 映射名称查询状态(概念名称关系查询状态 状态) {
    switch (状态) {
    case 概念名称关系查询状态::已找到:
    case 概念名称关系查询状态::未找到:
        return 基础表达状态::已生成;
    case 概念名称关系查询状态::读取漂移:
    case 概念名称关系查询状态::依赖已变化:
        return 基础表达状态::读取漂移;
    case 概念名称关系查询状态::资源失败:
    case 概念名称关系查询状态::工程未完成:
        return 基础表达状态::工程未完成;
    case 概念名称关系查询状态::结构不一致:
        return 基础表达状态::内部不一致;
    case 概念名称关系查询状态::输入不合法:
        return 基础表达状态::输入拒绝;
    default:
        return 基础表达状态::引用不可读;
    }
}

基础表达状态 读取名称(const 基础表达参数& 参数, 稳定编码 语言节点,
    std::size_t 最大名称条目数,
    const 概念_存在类& 存在概念服务, const 概念_特征类& 特征概念服务,
    const 概念_名称关系类& 名称服务, const 新_词类& 词服务,
    名称快照& 快照) {
    const auto 概念节点 = std::get<稳定编码>(参数.内容);
    const auto 概念 = 读取正式概念(参数.类别, 概念节点,
        存在概念服务, 特征概念服务);
    if (!概念) return 基础表达状态::引用不可读;
    const auto 列表 = 名称服务.查询概念名称(概念节点);
    const auto 列表状态 = 映射名称查询状态(列表.状态);
    if (列表状态 != 基础表达状态::已生成) return 列表状态;
    if (列表.名称关系节点组.size() > 最大名称条目数)
        return 基础表达状态::额度不足;
    if (列表.名称关系节点组 != 概念名称关系组(*概念))
        return 基础表达状态::读取漂移;
    std::vector<std::pair<概念名称关系信息, 新词条信息>> 同语言名称组;
    for (const auto 关系节点 : 列表.名称关系节点组) {
        const auto 关系 = 名称服务.获取名称关系(关系节点);
        const auto 关系状态 = 映射名称查询状态(关系.状态);
        if (关系状态 != 基础表达状态::已生成) return 关系状态;
        if (关系.状态 != 概念名称关系查询状态::已找到 || !关系.信息
            || 关系.信息->节点 != 关系节点
            || 关系.信息->概念节点 != 概念节点)
            return 基础表达状态::读取漂移;
        const auto 词条 = 词服务.获取词条(关系.信息->词条节点);
        if (词条.状态 == 新词条查询状态::资源失败)
            return 基础表达状态::工程未完成;
        if (词条.状态 == 新词条查询状态::结构不一致)
            return 基础表达状态::内部不一致;
        if (词条.状态 != 新词条查询状态::已找到 || !词条.信息
            || 词条.信息->节点 != 关系.信息->词条节点)
            return 基础表达状态::引用不可读;
        if (词条.信息->语言节点 == 语言节点) {
            if (词条.信息->规范化词面.empty()
                || !新_语言类::严格UTF8字节串有效(词条.信息->规范化词面))
                return 基础表达状态::内部不一致;
            同语言名称组.emplace_back(*关系.信息, *词条.信息);
        }
    }
    if (参数.选用名称关系) {
        const auto 选中 = std::find_if(同语言名称组.begin(), 同语言名称组.end(),
            [&](const auto& 项) { return 项.first.节点 == *参数.选用名称关系; });
        if (选中 == 同语言名称组.end()) return 基础表达状态::输入拒绝;
        快照 = {概念节点, *概念, 列表.名称关系节点组,
            选中->first.节点, 选中->first, 选中->second};
    } else {
        if (同语言名称组.empty()) return 基础表达状态::缺名称;
        if (同语言名称组.size() != 1) return 基础表达状态::名称待选;
        快照 = {概念节点, *概念, 列表.名称关系节点组,
            同语言名称组.front().first.节点,
            同语言名称组.front().first, 同语言名称组.front().second};
    }
    return 基础表达状态::已生成;
}

bool 知识列表相同(const std::vector<新语言知识信息>& 左,
    const std::vector<新语言知识信息>& 右) {
    if (左.size() != 右.size()) return false;
    for (std::size_t i = 0; i < 左.size(); ++i)
        if (左[i].节点 != 右[i].节点 || 左[i].目标节点 != 右[i].目标节点
            || 左[i].结构节点 != 右[i].结构节点 || 左[i].定义 != 右[i].定义
            || 左[i].来源组 != 右[i].来源组) return false;
    return true;
}

std::optional<std::size_t> 统计标量(const std::string& 文本) {
    if (文本.empty() || !新_语言类::严格UTF8字节串有效(文本)) return std::nullopt;
    std::size_t 数量 = 0;
    for (const unsigned char 字节 : 文本)
        if ((字节 & 0xC0) != 0x80) ++数量;
    return 数量;
}

struct 展开结构项 final {
    const 新语言知识结构项* 项;
    稳定编码 所属知识;
    std::vector<std::int64_t> 路径;
};

