结构概念理解结果 理解结构概念表达(
    const 结构概念理解请求& 请求,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 新_方法类* 方法服务) {
    结构概念理解结果 结果;
    if (!有效(请求.语言节点)
        || (请求.模式标识.empty() && !请求.表达模式节点))
        return 结果;
    新语言结构理解查询 查询{};
    查询.语言节点 = 请求.语言节点;
    查询.表达模式节点 = 请求.表达模式节点;
    查询.模式标识 = 请求.模式标识;
    const auto 对应 = 语言服务.查询结构对应_理解(查询, 词服务);
    if (对应.状态 != 新语言知识状态::已完成) {
        结果.状态 = 对应.状态;
        结果.受阻节点组 = 对应.受阻节点组;
        结果.诊断说明 = "结构对应理解查询未完成";
        return 结果;
    }
    结果.对应行组 = 对应.信息组;
    if (结果.对应行组.empty()) {
        结果.状态 = 新语言知识状态::未找到;
        结果.诊断说明 = "无已登记结构对应";
        return 结果;
    }
    // 请求执行方法 → 新_方法类::查询候选方法
    bool 需方法 = false;
    for (const auto& 行 : 结果.对应行组) {
        if (行.种类 == 新语言结构信息种类::请求执行方法
            || 行.结构概念种子标识 == "SC-请求执行方法") {
            需方法 = true; break;
        }
    }
    if (需方法) {
        if (!方法服务) {
            结果.状态 = 新语言知识状态::输入拒绝;
            结果.诊断说明 = "请求执行方法理解需要方法服务";
            结果.对应行组.clear();
            return 结果;
        }
        新方法候选查询 方法查询{};
        方法查询.可能结果概念组 = 请求.可能结果概念组;
        const auto 候选 = 方法服务->查询候选方法(方法查询);
        if (候选.状态 != 新方法操作状态::已找到) {
            switch (候选.状态) {
            case 新方法操作状态::入口拒绝:
                结果.状态 = 新语言知识状态::输入拒绝; break;
            case 新方法操作状态::尚未初始化:
                结果.状态 = 新语言知识状态::尚未初始化; break;
            case 新方法操作状态::资源失败:
                结果.状态 = 新语言知识状态::工程未完成; break;
            default:
                结果.状态 = 新语言知识状态::内部不一致; break;
            }
            结果.诊断说明 = "查询候选方法未完成";
            结果.对应行组.clear();
            return 结果;
        }
        结果.候选方法节点组 = 候选.方法节点组;
    }
    结果.状态 = 新语言知识状态::已完成;
    return 结果;
}

