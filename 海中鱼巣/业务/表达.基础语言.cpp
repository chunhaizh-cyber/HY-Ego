基础表达状态 读取指代名称(稳定编码 指代概念节点, 稳定编码 语言节点,
    std::size_t 最大名称条目数, const 概念_存在类& 存在概念服务,
    const 概念_名称关系类& 名称服务, 指代名称快照& 快照) {
    const auto 概念 = 存在概念服务.获取指代概念(指代概念节点);
    if (概念.状态 == 指代概念查询状态::资源失败) return 基础表达状态::工程未完成;
    if (概念.状态 == 指代概念查询状态::结构不一致) return 基础表达状态::内部不一致;
    if (概念.状态 == 指代概念查询状态::依赖已变化
        || 概念.状态 == 指代概念查询状态::读取漂移)
        return 基础表达状态::读取漂移;
    if (概念.状态 == 指代概念查询状态::输入拒绝) return 基础表达状态::输入拒绝;
    if (概念.状态 != 指代概念查询状态::已找到 || !概念.信息)
        return 基础表达状态::引用不可读;
    if (概念.信息->定义.目标范围 != 指代目标范围::单个已登记强类型信息节点
        || 概念.信息->定义.规则 != 指代声明规则::作用域说话者
        || 概念.信息->定义.参数组 != std::vector<指代参数定义>{
            {指代参数角色::目标, 指代参数类型::强类型信息节点},
            {指代参数角色::作用域, 指代参数类型::交互作用域}}
        || !概念.信息->定义.特征约束组.empty())
        return 基础表达状态::输入拒绝;
    const auto 名称 = 名称服务.查询指代概念名称(指代概念节点);
    if (名称.状态 == 指代名称读取状态::资源失败
        || 名称.状态 == 指代名称读取状态::工程未完成)
        return 基础表达状态::工程未完成;
    if (名称.状态 == 指代名称读取状态::结构不一致)
        return 基础表达状态::内部不一致;
    if (名称.状态 == 指代名称读取状态::依赖已变化
        || 名称.状态 == 指代名称读取状态::读取漂移)
        return 基础表达状态::读取漂移;
    if (名称.状态 == 指代名称读取状态::输入拒绝)
        return 基础表达状态::输入拒绝;
    if (名称.状态 == 指代名称读取状态::未找到) return 基础表达状态::缺名称;
    if (名称.状态 != 指代名称读取状态::已读取) return 基础表达状态::引用不可读;
    if (名称.信息组.size() > 最大名称条目数) return 基础表达状态::额度不足;
    std::vector<稳定编码> 身份组;
    std::optional<指代名称关系信息> 选中;
    for (const auto& 项 : 名称.信息组) {
        if (项.概念 != *概念.信息 || !有效(项.节点))
            return 基础表达状态::读取漂移;
        身份组.push_back(项.节点);
        if (项.语言.节点 != 语言节点 || 项.角色 != 指代名称角色::首选名称) continue;
        if (选中) return 基础表达状态::名称待选;
        选中 = 项;
    }
    if (!选中) return 基础表达状态::缺名称;
    if (选中->词条.规范化词面 != "我"
        || 选中->词条.语言节点 != 语言节点)
        return 基础表达状态::输入拒绝;
    快照 = {*概念.信息, std::move(身份组), *选中};
    return 基础表达状态::已生成;
}

std::optional<概念快照> 读取正式概念(
    新语言知识角色类别 类别, 稳定编码 概念节点,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    switch (类别) {
    case 新语言知识角色类别::存在概念: {
        const auto 概念 = 存在概念服务.获取存在概念(概念节点);
        if (概念 && 概念->节点 == 概念节点) return 概念快照{*概念};
        const auto 结构=存在概念服务.读取正式结构概念(概念节点);
        if(结构.状态==正式结构操作状态::已读取&&结构.信息)return 概念快照{*结构.信息};
        return std::nullopt;
    }
    case 新语言知识角色类别::特征概念: {
        const auto 概念 = 特征概念服务.获取特征概念(概念节点);
        if (概念 && 概念->节点 == 概念节点) return 概念快照{*概念};
        return std::nullopt;
    }
    default: return std::nullopt;
    }
}

