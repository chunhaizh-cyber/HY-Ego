bool 合法参数(const 基础表达参数& 参数) {
    const auto 参数号 = static_cast<std::uint8_t>(参数.参数);
    const auto 类别号 = static_cast<std::uint8_t>(参数.类别);
    const auto 种类号 = static_cast<std::uint8_t>(参数.种类);
    if (参数号 < 1 || 参数号 > 6 || 类别号 < 1 || 类别号 > 6
        || 种类号 < 1 || 种类号 > 4) return false;
    switch (参数.种类) {
    case 基础表达参数种类::概念:
        return (参数.类别 == 新语言知识角色类别::存在概念
            || 参数.类别 == 新语言知识角色类别::特征概念)
            && std::holds_alternative<稳定编码>(参数.内容)
            && 有效(std::get<稳定编码>(参数.内容));
    case 基础表达参数种类::领域对象:
        return 参数.类别 == 新语言知识角色类别::存在
            && std::holds_alternative<稳定编码>(参数.内容)
            && 有效(std::get<稳定编码>(参数.内容))
            && !参数.选用名称关系;
    case 基础表达参数种类::特征类型:
        return (参数.类别 == 新语言知识角色类别::正式特征类型
            || 参数.类别 == 新语言知识角色类别::I64标量特征类型)
            && std::holds_alternative<稳定编码>(参数.内容)
            && 有效(std::get<稳定编码>(参数.内容))
            && !参数.选用名称关系;
    case 基础表达参数种类::准确值:
        return 参数.类别 == 新语言知识角色类别::I64标量
            && std::holds_alternative<std::int64_t>(参数.内容)
            && !参数.选用名称关系;
    default: return false;
    }
}

bool 合法请求(const 基础表达请求& 请求) {
    if (!有效(请求.语言节点) || 请求.最大知识条目数 == 0
        || 请求.最大名称条目数 == 0
        || 请求.最大输出标量数 == 0 || 请求.参数组.empty()) return false;
    const bool 提问 = 请求.目的 == 新语言知识表达目的::提问;
    if (提问) {
        if (请求.操作 != 新语言知识含义操作::信息请求
            || 请求.作用域 != 新语言知识作用域::提问范围
            || 请求.被询操作 != 新语言知识含义操作::概念归类
            || 请求.确认范围 != 新语言知识确认范围::主张成立与否
            || !请求.受询者 || !有效(*请求.受询者)) return false;
    } else if (请求.目的 != 新语言知识表达目的::陈述
        || 请求.作用域 != 新语言知识作用域::普通陈述
        || 请求.操作 == 新语言知识含义操作::信息请求
        || 请求.受询者 || 请求.被询操作 || 请求.确认范围) return false;
    const auto 操作号 = static_cast<std::uint8_t>(请求.操作);
    if (操作号 < 1 || 操作号 > 4) return false;
    std::set<新语言知识参数角色> 已有;
    for (const auto& 参数 : 请求.参数组) {
        if (!合法参数(参数) || !已有.insert(参数.参数).second) return false;
        if (参数.选用名称关系 && !有效(*参数.选用名称关系)) return false;
    }
    if (提问) {
        if (请求.参数组.size() != 2 || !已有.contains(新语言知识参数角色::主体)
            || !已有.contains(新语言知识参数角色::归类概念)) return false;
        for (const auto& 参数 : 请求.参数组)
            if (参数.种类 != 基础表达参数种类::概念
                || 参数.类别 != 请求.参数组.front().类别) return false;
    }
    if (请求.指代选择.has_value() != 请求.网页自我来源.has_value()) return false;
    if (请求.指代选择) {
        const auto& 选择 = *请求.指代选择;
        const auto& 来源 = 请求.网页自我来源->读取();
        if (提问 || 请求.操作 != 新语言知识含义操作::概念归类
            || 选择.规则角色 != 0 || !有效(选择.指代概念节点)
            || 选择.目标类型 != 基础表达目标节点类型::存在
            || !有效(选择.目标存在节点)
            || 来源.种类 != 基础表达来源种类::网页自我待发
            || 来源.公开会话标识.empty()
            || !新_语言类::严格UTF8字节串有效(来源.公开会话标识)
            || !有效(来源.说话者存在节点) || !有效(来源.交互窗口节点)
            || 来源.说话者存在节点 != 选择.目标存在节点) return false;
        const auto 主体 = std::find_if(请求.参数组.begin(), 请求.参数组.end(),
            [](const auto& 参数) { return 参数.参数 == 新语言知识参数角色::主体; });
        if (主体 == 请求.参数组.end() || 主体->种类 != 基础表达参数种类::领域对象
            || std::get<稳定编码>(主体->内容) != 选择.目标存在节点) return false;
    }
    return true;
}

基础表达状态 映射知识状态(新语言知识状态 状态) {
    switch (状态) {
    case 新语言知识状态::已完成: return 基础表达状态::已生成;
    case 新语言知识状态::未找到: return 基础表达状态::缺规则;
    case 新语言知识状态::输入拒绝: return 基础表达状态::输入拒绝;
    case 新语言知识状态::尚未初始化:
    case 新语言知识状态::未支持: return 基础表达状态::能力未支持;
    case 新语言知识状态::引用不可读: return 基础表达状态::引用不可读;
    case 新语言知识状态::读取漂移: return 基础表达状态::读取漂移;
    case 新语言知识状态::内部不一致: return 基础表达状态::内部不一致;
    case 新语言知识状态::工程未完成: return 基础表达状态::工程未完成;
    case 新语言知识状态::额度不足: return 基础表达状态::额度不足;
    default: return 基础表达状态::内部不一致;
    }
}

bool 种类相容(新语言知识角色种类 规则种类, 基础表达参数种类 实参种类) {
    switch (规则种类) {
    case 新语言知识角色种类::领域对象引用:
        return 实参种类 == 基础表达参数种类::领域对象;
    case 新语言知识角色种类::概念引用:
        return 实参种类 == 基础表达参数种类::概念;
    case 新语言知识角色种类::特征类型引用:
        return 实参种类 == 基础表达参数种类::特征类型;
    case 新语言知识角色种类::准确值:
        return 实参种类 == 基础表达参数种类::准确值;
    default: return false;
    }
}

using 规则绑定 = std::map<std::int64_t, const 基础表达参数*>;

bool 匹配规则(const 新语言知识信息& 知识, const 基础表达请求& 请求,
    规则绑定& 绑定) {
    const auto& 定义 = 知识.定义;
    if (定义.目标.目的 != 请求.目的 || 定义.结构.语言节点 != 请求.语言节点
        || 定义.结构.类别 != 新语言知识结构类别::基础表达
        || 定义.目标.含义组.size() != 1
        || !定义.目标.适用条件组.empty()) return false;
    const auto& 含义 = 定义.目标.含义组.front();
    if (含义.操作 != 请求.操作 || 含义.作用域 != 请求.作用域) return false;
    const auto* 参数组 = &含义.参数组;
    if (请求.目的 == 新语言知识表达目的::提问) {
        if (含义.确认范围 != 请求.确认范围 || !含义.被询含义
            || 含义.被询含义->操作 != 请求.被询操作
            || 含义.被询含义->作用域 != 新语言知识作用域::提问范围)
            return false;
        参数组 = &含义.被询含义->参数组;
    } else if (含义.被询含义 || 含义.确认范围) return false;
    if (参数组->size() != 请求.参数组.size()) return false;
    规则绑定 候选绑定;
    for (const auto& 角色参数 : *参数组) {
        const auto 实参 = std::find_if(请求.参数组.begin(), 请求.参数组.end(),
            [&](const auto& 项) { return 项.参数 == 角色参数.参数; });
        const auto 角色 = std::find_if(定义.目标.角色组.begin(), 定义.目标.角色组.end(),
            [&](const auto& 项) { return 项.局部编号 == 角色参数.规则角色; });
        if (实参 == 请求.参数组.end() || 角色 == 定义.目标.角色组.end()
            || !种类相容(角色->种类, 实参->种类)
            || 角色->数量 != 新语言知识角色数量::单项) return false;
        for (const auto& 约束 : 角色->必要约束组)
            if (约束.被约束角色 != 角色->局部编号
                || std::find(约束.允许类别组.begin(), 约束.允许类别组.end(), 实参->类别)
                    == 约束.允许类别组.end()) return false;
        if (!候选绑定.emplace(角色参数.规则角色, &*实参).second) return false;
    }
    绑定 = std::move(候选绑定);
    return true;
}

bool 匹配指代选择(const 新语言知识信息& 知识, const 基础表达请求& 请求) {
    std::size_t 指代项数 = 0;
    for (const auto& 项 : 知识.定义.结构.有序项组) {
        const auto* 角色 = std::get_if<新语言知识角色表达项>(&项.载荷);
        if (!角色 || 角色->方式 != 新语言知识表达方式::已消解指代) continue;
        ++指代项数;
        if (!请求.指代选择 || 角色->规则角色 != 请求.指代选择->规则角色
            || 角色->指代概念节点 != 请求.指代选择->指代概念节点)
            return false;
    }
    return 请求.指代选择 ? 指代项数 == 1 : 指代项数 == 0;
}

