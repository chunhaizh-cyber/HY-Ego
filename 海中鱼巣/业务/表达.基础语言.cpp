结构项概念保护结果 读取正式字段询问范围(const 正式信息参数读取结果& D,稳定编码 FT,
    const 概念_存在类& 存在概念,const 概念_特征类& 特征概念) {
    using S=结构项概念保护状态;
    const auto 失败=[](S 状态){结构项概念保护结果 r;r.状态=状态;return r;};
    if(D.状态==正式信息参数读取状态::前提已变化)return 失败(S::前提已变化);
    if(D.状态==正式信息参数读取状态::依赖未就绪)return 失败(S::依赖未就绪);
    if(D.状态==正式信息参数读取状态::资源失败)throw std::bad_alloc{};
    if(D.状态!=正式信息参数读取状态::已读取||!D.信息||D.完整保护组.empty()||!有效(FT)
        ||!有效(D.信息->信息节点)||!有效(D.信息->类别概念))return 失败(S::输入拒绝);
    std::vector<基础联合节点快照> 保护=D.完整保护组;
    const auto 并保护=[&](const std::vector<基础联合节点快照>& 组) {
        for(const auto& 项:组) {
            const auto 旧=std::find_if(保护.begin(),保护.end(),[&](const auto& p){return p.结构.节点.编码==项.结构.节点.编码;});
            if(旧==保护.end()){保护.push_back(项);continue;}
            if(旧->结构.节点!=项.结构.节点||旧->结构.字段组!=项.结构.字段组||旧->入向外部关系组!=项.入向外部关系组
                ||旧->出向外部关系组!=项.出向外部关系组||旧->入向字段组!=项.入向字段组)return false;
        }
        return true;
    };
    std::optional<std::uint32_t> 字段槽;
    稳定编码 形式FT{};
    for(auto 槽:std::array<std::uint32_t,6>{先天特征类型槽::需求目标存在,先天特征类型槽::需求目标FT,
        先天特征类型槽::需求目标形式,先天特征类型槽::目标域,先天特征类型槽::目标比较,先天特征类型槽::目标方向}) {
        const auto r=特征概念.读取先天特征类型槽(槽);
        if(r.状态==特征概念规则状态::前提已变化)return 失败(S::前提已变化);
        if(r.状态==特征概念规则状态::值不存在||r.状态==特征概念规则状态::读取接口未装配)return 失败(S::依赖未就绪);
        if(r.状态==特征概念规则状态::资源失败)throw std::bad_alloc{};
        if(r.状态!=特征概念规则状态::已完成||!r.类型根||r.完整保护组.empty())throw std::logic_error("字段询问先天FT槽不完整");
        if(!并保护(r.完整保护组))return 失败(S::前提已变化);
        if(*r.类型根==FT){if(字段槽)throw std::logic_error("字段询问先天FT槽身份重复");字段槽=槽;}
        if(槽==先天特征类型槽::需求目标形式)形式FT=*r.类型根;
    }
    if(!字段槽)return 失败(S::未取得正式概念证明);
    const auto 找内容=[&](稳定编码 类型)->const 正式内容值* {
        const 正式内容值* 值=nullptr;
        for(const auto& 项:D.信息->直接内容组)if(项.特征类型==类型){if(值)throw std::logic_error("字段询问正式内容重复");值=&项.内容;}
        return 值;
    };
    const auto* 内容=找内容(FT);
    if(!内容||内容->状态==正式内容值状态::不适用)return 失败(S::未取得正式概念证明);
    const auto 先天=存在概念.读取先天需求任务方法概念();
    if(先天.状态==正式结构操作状态::前提已变化)return 失败(S::前提已变化);
    if(先天.状态==正式结构操作状态::依赖未就绪||先天.状态==正式结构操作状态::未找到)return 失败(S::依赖未就绪);
    if(先天.状态!=正式结构操作状态::已读取||!先天.信息)throw std::logic_error("字段询问先天需求定义读取失败");
    auto 结构身份=先天.信息->需求;
    const bool 分支字段=*字段槽==先天特征类型槽::目标域||*字段槽==先天特征类型槽::目标比较||*字段槽==先天特征类型槽::目标方向;
    if(分支字段) {
        const std::uint32_t 分支槽 = *字段槽 == 先天特征类型槽::目标方向 ? 205u : 204u;
        std::optional<稳定编码> 分支;
        for(const auto& 项:先天.信息->子类与支持定义)if(项.first==分支槽){if(分支)return 失败(S::未取得正式概念证明);分支=项.second;}
        if(!分支)return 失败(S::未取得正式概念证明);
        结构身份=*分支;
    }
    const auto 结构=存在概念.读取正式结构有效内容保护(结构身份);
    if(结构.状态==正式结构有效内容读取状态::前提已变化)return 失败(S::前提已变化);
    if(结构.状态==正式结构有效内容读取状态::依赖未就绪||结构.状态==正式结构有效内容读取状态::未找到)return 失败(S::依赖未就绪);
    if(结构.状态==正式结构有效内容读取状态::资源失败)throw std::bad_alloc{};
    if(结构.状态!=正式结构有效内容读取状态::已读取||!结构.信息||结构.完整保护组.empty())throw std::logic_error("字段询问正式结构范围读取失败");
    if(!并保护(结构.完整保护组))return 失败(S::前提已变化);
    const 正式结构有效内容项* 项目=nullptr;
    for(const auto& 项:结构.信息->内容项组)if(项.特征类型==FT){if(项目)return 失败(S::未取得正式概念证明);项目=&项;}
    if(!项目)return 失败(S::未取得正式概念证明);
    if(分支字段) {
        const auto* 形式=找内容(形式FT);
        if(!形式||形式->状态==正式内容值状态::不适用)return 失败(S::未取得正式概念证明);
        if(形式->状态==正式内容值状态::已知) {
            if(!形式->值||!std::holds_alternative<std::int64_t>(*形式->值))throw std::logic_error("字段询问目标形式物理值错误");
            const auto 槽=std::find_if(结构.信息->内容项组.begin(),结构.信息->内容项组.end(),[&](const auto& 项){return 项.特征类型==形式FT;});
            if(槽==结构.信息->内容项组.end())throw std::logic_error("字段询问分支缺少目标形式声明");
            const auto 域=存在概念.读取正式结构概念保护(槽->内容概念);
            if(域.状态==正式结构操作状态::前提已变化)return 失败(S::前提已变化);
            if(域.状态==正式结构操作状态::依赖未就绪)return 失败(S::依赖未就绪);
            if(域.状态!=正式结构操作状态::已读取||!域.信息)throw std::logic_error("字段询问分支形式范围未就绪");
            if(!并保护(域.完整保护组))return 失败(S::前提已变化);
            const auto* 枚举=std::get_if<基础范围概念定义>(&域.信息->定义);
            if(!枚举||枚举->原语!=基础概念原语::I64有限枚举||枚举->整数参数.size()!=1)throw std::logic_error("字段询问分支形式非唯一正式枚举");
            if(枚举->整数参数.front()!=std::get<std::int64_t>(*形式->值))return 失败(S::未取得正式概念证明);
        }else if(形式->状态!=正式内容值状态::当前未知)throw std::logic_error("字段询问目标形式状态错误");
    }
    const std::array<const 正式概念身份读取接口*,2> 提供者{&存在概念,&特征概念};
    auto 证明=存在概念.读取结构项概念保护(FT,项目->内容概念,提供者);
    if(证明.状态!=S::已读取)return 证明;
    if(!并保护(证明.完整保护组))return 失败(S::前提已变化);
    证明.完整保护组=std::move(保护);return 证明;
}
