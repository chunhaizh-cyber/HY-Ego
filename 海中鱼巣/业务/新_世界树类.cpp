新_世界树类::~新_世界树类() = default;

新世界初始化结果 新_世界树类::初始化() noexcept {
    新世界初始化结果 结果;
    try {
        std::lock_guard 锁(新世界树互斥);
        const bool 依赖完整 = 特征值服务_.初始化()
            && 特征概念服务_.初始化(特征值服务_)
            && 特征服务_.初始化()
            && 二次特征概念服务_.初始化()
            && 存在概念服务_.初始化()
            && 状态服务_.初始化()
            && 存在服务_.初始化()
            && 动态概念服务_.初始化()
            && 动态服务_.初始化()
            && 场景服务_.初始化();
        if (!依赖完整) {
            结果.状态 = 新世界初始化状态::依赖初始化失败;
            return 结果;
        }
        const auto 根结果 = 场景服务_.建立根场景();
        if (根结果.状态 != 新场景操作状态::已完成
            && 根结果.状态 != 新场景操作状态::无变化) {
            结果.状态 = 根结果.状态 == 新场景操作状态::结构不一致
                ? 新世界初始化状态::结构不一致
                : 新世界初始化状态::根场景建立失败;
            return 结果;
        }
        if (!根结果.场景节点 || !根结果.专属存在概念节点) {
            结果.状态 = 新世界初始化状态::结构不一致;
            return 结果;
        }
        已初始化_ = true;
        结果.状态 = 根结果.状态 == 新场景操作状态::已完成
            ? 新世界初始化状态::已完成
            : 新世界初始化状态::无变化;
        结果.世界树根场景 = 根结果.场景节点;
        结果.根场景专属存在概念 = 根结果.专属存在概念节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新世界初始化状态::资源失败;
        return 结果;
    }
}

bool 新_世界树类::已初始化() const noexcept {
    try {
        std::lock_guard 锁(新世界树互斥);
        return 已初始化_
            && 场景服务_.是场景节点(场景树根节点);
    } catch (...) {
        return false;
    }
}

std::optional<稳定编码> 新_世界树类::初始化需求树结构(
    bool& 本次建立) noexcept {
    本次建立 = false;
    try {
        std::lock_guard 锁(新世界树互斥);
        const bool 原根有效 = 有效(需求树根节点);
        if (!已初始化_ || !需求服务_.初始化()
            || !有效(需求树根节点)) {
            return std::nullopt;
        }
        本次建立 = !原根有效;
        return 需求树根节点;
    } catch (...) {
        return std::nullopt;
    }
}

std::optional<稳定编码> 新_世界树类::获取世界树根场景() const noexcept {
    try {
        std::lock_guard 锁(新世界树互斥);
        return 已初始化_ && 场景服务_.是场景节点(场景树根节点)
            ? std::optional<稳定编码>{场景树根节点} : std::nullopt;
    } catch (...) {
        return std::nullopt;
    }
}

新世界自我治理基础结果
新_世界树类::建立或取得自我治理基础() noexcept {
    try {
        std::lock_guard 锁(新世界树互斥);
        auto& 结果 = 自我治理基础_;
        if (!已初始化_) {
            结果.状态 = 新世界自我治理基础状态::世界树未初始化;
            return 结果;
        }

        constexpr auto 最大值 = (std::numeric_limits<std::int64_t>::max)();
        const 特征概念定义 完整域定义{
            特征概念材料物理类型::I64标量,
            std::vector<特征概念I64闭区间>{{0, 最大值}},
            std::nullopt,
            特征概念比较规则::I64数值,
            特征概念聚合规则::I64连续值归组,
            {}};
        const 特征概念定义 目标定义{
            特征概念材料物理类型::I64标量,
            std::vector<特征概念I64闭区间>{{最大值, 最大值}},
            std::nullopt,
            特征概念比较规则::I64数值,
            特征概念聚合规则::I64连续值归组,
            {}};

        bool 本次建立 = false;
        const auto 定义一致 = [](const 特征概念信息& 信息,
            const 特征概念定义& 定义) noexcept {
            return 信息.材料类型 == 定义.材料类型
                && 信息.值域 == 定义.值域
                && 信息.单位 == 定义.单位
                && 信息.比较规则 == 定义.比较规则
                && 信息.聚合规则 == 定义.聚合规则
                && 信息.名称关系 == 定义.名称关系;
        };
        const auto 确保根 = [&](std::optional<稳定编码>& 位置) {
            if (位置) {
                const auto 信息 = 特征概念服务_.获取特征概念(*位置);
                const auto 关系 = 特征概念服务_.比较单特征概念(*位置, *位置);
                return 信息 && 定义一致(*信息, 完整域定义)
                    && 关系.状态 == 特征概念规则状态::已完成
                    && 关系.特征类型根 && *关系.特征类型根 == *位置;
            }
            const auto 节点 = 特征概念服务_.建立或取得特征概念(
                完整域定义, 特征值服务_);
            if (!有效(节点)) return false;
            位置 = 节点;
            本次建立 = true;
            return true;
        };
        if (!确保根(结果.安全值特征类型根)
            || !确保根(结果.服务值特征类型根)
            || *结果.安全值特征类型根 == *结果.服务值特征类型根) {
            结果.状态 = 新世界自我治理基础状态::特征类型建立失败;
            return 结果;
        }

        const auto 确保目标 = [&](std::optional<稳定编码>& 位置,
            稳定编码 类型根) {
            if (位置) {
                const auto 信息 = 特征概念服务_.获取特征概念(*位置);
                const auto 关系 = 特征概念服务_.比较单特征概念(*位置, 类型根);
                return 信息 && 定义一致(*信息, 目标定义)
                    && 关系.状态 == 特征概念规则状态::已完成
                    && 关系.关系 == 单特征概念关系::右为上位
                    && 关系.特征类型根 && *关系.特征类型根 == 类型根;
            }
            const auto 节点 = 特征概念服务_.建立或取得特征概念(
                目标定义, 特征值服务_, 类型根);
            if (!有效(节点)) return false;
            位置 = 节点;
            本次建立 = true;
            return true;
        };
        if (!确保目标(结果.安全值目标概念,
                *结果.安全值特征类型根)
            || !确保目标(结果.服务值目标概念,
                *结果.服务值特征类型根)) {
            结果.状态 = 新世界自我治理基础状态::目标值域建立失败;
            return 结果;
        }

        const auto 确保比较 = [&](std::optional<稳定编码>& 类型位置,
            std::optional<稳定编码>& 关系位置,
            稳定编码 特征类型根, 稳定编码 目标概念) {
            const std::vector<二次特征概念输入定义> 输入组{
                {0, 二次特征输入角色::左输入,
                    二次特征输入来源种类::特征准确值, 特征类型根},
                {1, 二次特征输入角色::右输入,
                    二次特征输入来源种类::特征准确值, 特征类型根}};
            if (类型位置) {
                const auto 信息 = 二次特征概念服务_.获取二次特征概念(
                    *类型位置);
                if (!信息 || 信息->二次特征类型根节点 != *类型位置
                    || 信息->算法 != 二次特征算法::有向特征差值
                    || 信息->输入定义组 != 输入组
                    || 信息->参照特征概念节点 != 目标概念) {
                    return false;
                }
            } else {
                const auto 建立 =
                    二次特征概念服务_.建立或取得默认二次特征概念(
                        二次特征算法::有向特征差值, 输入组, 目标概念);
                if ((建立.状态 != 二次特征概念操作状态::已建立
                        && 建立.状态 != 二次特征概念操作状态::已复用)
                    || !建立.概念节点) {
                    return false;
                }
                类型位置 = 建立.概念节点;
                本次建立 = 本次建立
                    || 建立.状态 == 二次特征概念操作状态::已建立;
            }

            if (关系位置) {
                const auto 信息 = 二次特征概念服务_.获取二次特征概念(
                    *关系位置);
                return 信息
                    && 信息->二次特征类型根节点 == *类型位置
                    && 信息->算法 == 二次特征算法::有向特征差值
                    && 信息->输入定义组 == 输入组
                    && 信息->参照特征概念节点 == 目标概念
                    && std::find(信息->结果域种类组.begin(),
                        信息->结果域种类组.end(),
                        二次特征结果域种类::包含于参照值域)
                        != 信息->结果域种类组.end();
            }
            const auto 建立 =
                二次特征概念服务_.建立或取得参照结果域概念(
                    *类型位置, 二次特征结果域种类::包含于参照值域);
            if ((建立.状态 != 二次特征概念操作状态::已建立
                    && 建立.状态 != 二次特征概念操作状态::已复用)
                || !建立.概念节点) {
                return false;
            }
            关系位置 = 建立.概念节点;
            本次建立 = 本次建立
                || 建立.状态 == 二次特征概念操作状态::已建立;
            return true;
        };
        if (!确保比较(结果.安全值比较类型根,
                结果.安全值目标比较关系,
                *结果.安全值特征类型根, *结果.安全值目标概念)
            || !确保比较(结果.服务值比较类型根,
                结果.服务值目标比较关系,
                *结果.服务值特征类型根, *结果.服务值目标概念)) {
            结果.状态 = 新世界自我治理基础状态::比较关系建立失败;
            return 结果;
        }
        if (结果.安全值目标比较关系
                == 结果.服务值目标比较关系
            || 结果.安全值比较类型根 == 结果.服务值比较类型根) {
            结果.状态 = 新世界自我治理基础状态::结构不一致;
            return 结果;
        }
        结果.状态 = 本次建立
            ? 新世界自我治理基础状态::已建立
            : 新世界自我治理基础状态::已复用;
        return 结果;
    } catch (...) {
        自我治理基础_.状态 = 新世界自我治理基础状态::资源失败;
        return 自我治理基础_;
    }
}

