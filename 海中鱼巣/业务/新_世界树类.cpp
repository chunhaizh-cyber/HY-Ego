std::optional<std::vector<新世界任务执行读回结果>>
新_世界树类::查询等待结果任务执行() const noexcept {
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) return std::nullopt;
        const auto 任务组 = 任务服务_.查询全部任务();
        if (任务组.状态 != 新任务操作状态::已找到) {
            return std::nullopt;
        }

        std::vector<新世界任务执行读回结果> 结果组;
        结果组.reserve(任务组.任务节点组.size());
        for (const auto 任务节点 : 任务组.任务节点组) {
            const auto 任务 = 任务服务_.获取任务(任务节点);
            if (任务 && 任务->当前状态 == 新任务状态::已完成
                && 任务->完成结算节点) {
                continue;
            }
            if (任务 && 任务->当前状态 != 新任务状态::执行中
                && 任务->当前状态 != 新任务状态::待影响评估
                && 任务->当前状态 != 新任务状态::等待自我决议
                && 任务->当前状态 != 新任务状态::已完成) {
                continue;
            }
            if (!任务 || !任务->最近执行实例节点) return std::nullopt;
            const auto 执行 = 任务服务_.获取执行实例(
                *任务->最近执行实例节点);
            if (!执行 || 执行->任务节点 != 任务节点) {
                return std::nullopt;
            }
            新世界任务执行读回结果 读回;
            读回.任务 = *任务;
            读回.执行 = *执行;
            if (任务->当前状态 == 新任务状态::执行中
                && 执行->状态 == 新任务执行状态::执行中
                && !执行->结束时间 && !执行->影响评估节点) {
                读回.状态 = 新世界任务执行读回状态::已读回等待观察;
            } else if (任务->当前状态 == 新任务状态::待影响评估
                && 执行->状态 == 新任务执行状态::已结束待评估
                && 执行->结束时间 && !执行->影响评估节点) {
                读回.状态 = 新世界任务执行读回状态::已读回等待评估;
            } else if ((任务->当前状态 == 新任务状态::等待自我决议
                    || (任务->当前状态 == 新任务状态::已完成
                        && !任务->完成结算节点))
                && 执行->状态 == 新任务执行状态::已评估
                && 执行->结束时间 && 执行->影响评估节点) {
                读回.影响评估 = 任务服务_.获取影响评估(
                    *执行->影响评估节点);
                if (!读回.影响评估
                    || 读回.影响评估->任务节点 != 任务节点
                    || 读回.影响评估->执行实例节点 != 执行->节点) {
                    return std::nullopt;
                }
                读回.状态 = 新世界任务执行读回状态::已读回影响评估;
            } else {
                return std::nullopt;
            }
            结果组.push_back(std::move(读回));
        }
        return 结果组;
    } catch (...) {
        return std::nullopt;
    }
}

新任务操作状态 新_世界树类::准备任务查找方法(
    稳定编码 任务节点) noexcept {
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) {
            return 新任务操作状态::尚未初始化;
        }
        const auto 任务 = 任务服务_.获取任务(任务节点);
        if (!任务) return 新任务操作状态::任务不存在;
        if (任务->当前状态 == 新任务状态::待查找方法) {
            return 新任务操作状态::无变化;
        }
        if (任务->当前状态 != 新任务状态::已建立) {
            return 新任务操作状态::任务状态不允许;
        }
        return 任务服务_.修改任务状态(
            任务节点, 新任务状态::待查找方法);
    } catch (...) {
        return 新任务操作状态::资源失败;
    }
}

新世界任务方法召回结果 新_世界树类::查询任务方法候选并发布(
    稳定编码 任务节点) noexcept {
    新世界任务方法召回结果 结果;
    结果.任务节点 = 任务节点;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_ || !有效(新方法组织根节点)) {
            结果.状态 = 新世界任务方法召回状态::尚未初始化;
            return 结果;
        }
        const auto 任务 = 任务服务_.获取任务(任务节点);
        if (!任务) {
            结果.状态 = 新世界任务方法召回状态::任务不存在;
            return 结果;
        }
        结果.需求节点 = 任务->需求节点;
        if (任务->当前状态 != 新任务状态::待查找方法) {
            结果.状态 = 新世界任务方法召回状态::任务状态已变化;
            return 结果;
        }
        const auto 需求 = 需求服务_.获取需求(任务->需求节点);
        if (!需求) {
            结果.状态 = 新世界任务方法召回状态::需求不存在;
            return 结果;
        }

        新方法候选查询 查询;
        查询.涉及特征类型概念组.push_back(
            需求->目标.目标特征类型概念节点);
        结果.方法查询 = 方法服务_.查询候选方法(查询);
        if (结果.方法查询->状态 != 新方法操作状态::已找到) {
            结果.状态 = 结果.方法查询->状态 == 新方法操作状态::资源失败
                ? 新世界任务方法召回状态::资源失败
                : (结果.方法查询->状态 == 新方法操作状态::结构不一致
                    ? 新世界任务方法召回状态::结构不一致
                    : 新世界任务方法召回状态::方法查询未完成);
            return 结果;
        }
        for (const auto 方法节点 : 结果.方法查询->方法节点组) {
            if (!方法服务_.是方法节点(方法节点)) {
                结果.状态 = 新世界任务方法召回状态::结构不一致;
                return 结果;
            }
        }

        新任务候选方法发布请求 发布;
        发布.任务节点 = 任务节点;
        发布.需求节点 = 任务->需求节点;
        发布.需求目标 = 需求->目标;
        发布.查询 = 查询;
        发布.查询状态 = 结果.方法查询->状态;
        发布.查询完整 = true;
        发布.候选方法节点组 = 结果.方法查询->方法节点组;
        结果.发布已尝试 = true;
        结果.发布结果 = 任务服务_.发布候选方法材料(std::move(发布));
        if ((结果.发布结果->状态 != 新任务操作状态::已建立
                && 结果.发布结果->状态 != 新任务操作状态::已修改
                && 结果.发布结果->状态 != 新任务操作状态::精确重复)
            || !结果.发布结果->材料节点) {
            结果.状态 = 结果.发布结果->状态 == 新任务操作状态::资源失败
                ? 新世界任务方法召回状态::资源失败
                : (结果.发布结果->状态 == 新任务操作状态::任务状态不允许
                    ? 新世界任务方法召回状态::任务状态已变化
                    : 新世界任务方法召回状态::候选发布未完成);
            return 结果;
        }
        结果.候选材料节点 = 结果.发布结果->材料节点;
        结果.状态 = 结果.方法查询->方法节点组.empty()
            ? 新世界任务方法召回状态::已发布完整无候选
            : 新世界任务方法召回状态::已发布有候选;
        return 结果;
    } catch (...) {
        结果.状态 = 新世界任务方法召回状态::资源失败;
        return 结果;
    }
}

新世界任务候选读回结果 新_世界树类::读回任务方法候选(
    稳定编码 任务节点, 稳定编码 材料节点) const noexcept {
    新世界任务候选读回结果 结果;
    结果.任务节点 = 任务节点;
    结果.材料节点 = 材料节点;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) {
            结果.状态 = 新世界任务候选读回状态::尚未初始化;
            return 结果;
        }
        结果.任务 = 任务服务_.获取任务(任务节点);
        if (!结果.任务) {
            结果.状态 = 新世界任务候选读回状态::任务不存在;
            return 结果;
        }
        if (结果.任务->当前状态 != 新任务状态::待查找方法) {
            结果.状态 = 新世界任务候选读回状态::任务状态已变化;
            return 结果;
        }
        if (结果.任务->当前候选方法材料节点 != 材料节点) {
            结果.状态 = 新世界任务候选读回状态::材料不存在;
            return 结果;
        }
        结果.材料 = 任务服务_.获取候选方法材料(材料节点);
        if (!结果.材料) {
            结果.状态 = 新世界任务候选读回状态::材料不存在;
            return 结果;
        }
        const auto 需求 = 需求服务_.获取需求(结果.任务->需求节点);
        if (!需求 || 结果.材料->任务节点 != 任务节点
            || 结果.材料->需求节点 != 结果.任务->需求节点
            || 结果.材料->需求目标 != 需求->目标
            || 结果.材料->查询状态 != 新方法操作状态::已找到
            || !结果.材料->查询完整
            || 结果.材料->查询.作用域
            || 结果.材料->查询.实现方式
            || !结果.材料->查询.作用存在概念组.empty()
            || !结果.材料->查询.可能结果概念组.empty()
            || 结果.材料->查询.涉及特征类型概念组
                != std::vector<稳定编码>{需求->目标.目标特征类型概念节点}) {
            结果.状态 = 新世界任务候选读回状态::结构不一致;
            return 结果;
        }
        for (const auto 方法节点 : 结果.材料->候选方法节点组) {
            if (!方法服务_.是方法节点(方法节点)) {
                结果.状态 = 新世界任务候选读回状态::结构不一致;
                return 结果;
            }
        }
        结果.状态 = 结果.材料->候选方法节点组.empty()
            ? 新世界任务候选读回状态::已读回完整无候选
            : 新世界任务候选读回状态::已读回有候选;
        return 结果;
    } catch (...) {
        结果.状态 = 新世界任务候选读回状态::资源失败;
        return 结果;
    }
}

新世界任务候选消费结果 新_世界树类::消费任务方法候选(
    稳定编码 任务节点, 稳定编码 材料节点) noexcept {
    新世界任务候选消费结果 结果;
    try {
        std::lock_guard 锁(新世界树互斥);
        结果.读回 = 读回任务方法候选(任务节点, 材料节点);
        if (结果.读回.状态 == 新世界任务候选读回状态::任务状态已变化) {
            结果.状态 = 新世界任务候选消费状态::任务状态已变化;
            return 结果;
        }
        const bool 有候选 = 结果.读回.状态
            == 新世界任务候选读回状态::已读回有候选;
        const bool 完整无候选 = 结果.读回.状态
            == 新世界任务候选读回状态::已读回完整无候选;
        if (!有候选 && !完整无候选) {
            结果.状态 = 结果.读回.状态 == 新世界任务候选读回状态::尚未初始化
                ? 新世界任务候选消费状态::尚未初始化
                : (结果.读回.状态 == 新世界任务候选读回状态::资源失败
                    ? 新世界任务候选消费状态::资源失败
                    : 新世界任务候选消费状态::读回失败);
            return 结果;
        }
        const auto 目标状态 = 有候选
            ? 新任务状态::待检查条件 : 新任务状态::等待条件;
        结果.状态写入 = 任务服务_.修改任务状态(任务节点, 目标状态);
        if (*结果.状态写入 != 新任务操作状态::已修改
            && *结果.状态写入 != 新任务操作状态::无变化) {
            结果.状态 = *结果.状态写入 == 新任务操作状态::资源失败
                ? 新世界任务候选消费状态::资源失败
                : (*结果.状态写入 == 新任务操作状态::任务状态不允许
                    ? 新世界任务候选消费状态::任务状态已变化
                    : 新世界任务候选消费状态::状态写入失败);
            return 结果;
        }
        const auto 写后 = 任务服务_.获取任务(任务节点);
        if (!写后 || 写后->当前状态 != 目标状态) {
            结果.状态 = 新世界任务候选消费状态::状态写入失败;
            return 结果;
        }
        结果.状态 = 有候选
            ? 新世界任务候选消费状态::已进入条件检查
            : 新世界任务候选消费状态::已进入等待条件;
        return 结果;
    } catch (...) {
        结果.状态 = 新世界任务候选消费状态::资源失败;
        return 结果;
    }
}

新世界任务条件筹办结果 新_世界树类::筹办任务条件和参数(
    稳定编码 任务节点) const noexcept {
    新世界任务条件筹办结果 结果;
    结果.任务节点 = 任务节点;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) {
            结果.状态 = 新世界任务条件筹办状态::尚未初始化;
            return 结果;
        }
        const auto 任务 = 任务服务_.获取任务(任务节点);
        if (!任务) {
            结果.状态 = 新世界任务条件筹办状态::任务不存在;
            return 结果;
        }
        if (任务->当前状态 != 新任务状态::待检查条件) {
            结果.状态 = 新世界任务条件筹办状态::任务状态已变化;
            return 结果;
        }
        if (!任务->当前候选方法材料节点) {
            结果.状态 = 新世界任务条件筹办状态::候选材料不存在;
            return 结果;
        }
        结果.候选材料节点 = 任务->当前候选方法材料节点;
        const auto 材料 = 任务服务_.获取候选方法材料(
            *任务->当前候选方法材料节点);
        const auto 需求 = 需求服务_.获取需求(任务->需求节点);
        if (!材料 || !需求 || 材料->任务节点 != 任务节点
            || 材料->需求节点 != 任务->需求节点
            || 材料->需求目标 != 需求->目标
            || 材料->查询状态 != 新方法操作状态::已找到
            || !材料->查询完整 || 材料->候选方法节点组.empty()) {
            结果.状态 = 新世界任务条件筹办状态::结构不一致;
            return 结果;
        }

        const auto 存在概念兼容 = [&](稳定编码 实际概念,
                                      稳定编码 要求概念) noexcept {
            if (实际概念 == 要求概念) return true;
            std::vector<稳定编码> 待查{实际概念};
            std::set<稳定编码> 已查;
            while (!待查.empty()) {
                const auto 当前 = 待查.back();
                待查.pop_back();
                if (!已查.insert(当前).second) continue;
                for (const auto 上位 : 存在概念服务_.查询上位存在概念(当前)) {
                    if (上位 == 要求概念) return true;
                    待查.push_back(上位);
                }
            }
            return false;
        };
        const auto 特征概念兼容 = [&](稳定编码 实际概念,
                                      稳定编码 要求概念) noexcept {
            const auto 比较 = 特征概念服务_.比较单特征概念(
                实际概念, 要求概念);
            return 比较.状态 == 特征概念规则状态::已完成
                && 比较.关系
                && (*比较.关系 == 单特征概念关系::同一
                    || *比较.关系 == 单特征概念关系::右为上位);
        };

        enum class 值域核验 : std::uint8_t {
            命中, 未命中, 材料未到, 结构缺口
        };
        const auto 当前值命中概念 = [&](const 新特征信息& 特征,
                                        稳定编码 要求概念) noexcept {
            if (!特征.当前值) return 值域核验::材料未到;
            const auto 关系 = 特征概念服务_.比较单特征概念(
                特征.特征概念节点, 要求概念);
            if (关系.状态 != 特征概念规则状态::已完成
                || !关系.特征类型根) return 值域核验::结构缺口;
            const auto 查找 = 特征概念服务_.查找值对应的最具体概念(
                *关系.特征类型根, *特征.当前值, 特征.实例单位,
                特征值服务_);
            if (查找.状态 == 特征概念查找状态::未找到) {
                return 值域核验::未命中;
            }
            if (查找.状态 != 特征概念查找状态::已找到
                || !查找.概念节点) return 值域核验::结构缺口;
            return 特征概念兼容(*查找.概念节点, 要求概念)
                ? 值域核验::命中 : 值域核验::未命中;
        };

        struct 对象材料 final {
            稳定编码 节点;
            稳定编码 专属概念;
            std::vector<稳定编码> 特征组;
            std::optional<稳定编码> 直接所属场景;
        };
        const auto 读取对象 = [&](稳定编码 节点)
            -> std::optional<对象材料> {
            if (场景服务_.是场景节点(节点)) {
                const auto 场景 = 场景服务_.获取场景(节点);
                if (!场景) return std::nullopt;
                return 对象材料{节点, 场景->专属存在概念节点,
                    场景->特征节点组, 节点};
            }
            const auto 存在 = 存在服务_.获取存在(节点);
            if (!存在) return std::nullopt;
            return 对象材料{节点, 存在->专属存在概念节点,
                存在->特征节点组, 场景服务_.查询所属场景(节点)};
        };
        const auto 查找所属场景 = [&](稳定编码 节点)
            -> std::optional<稳定编码> {
            if (场景服务_.是场景节点(节点)) return 节点;
            std::set<稳定编码> 已查;
            auto 当前 = 节点;
            while (有效(当前) && 已查.insert(当前).second) {
                if (const auto 所属 = 场景服务_.查询所属场景(当前)) {
                    return 所属;
                }
                const auto 存在 = 存在服务_.获取存在(当前);
                if (!存在 || !存在->父存在节点) return std::nullopt;
                当前 = *存在->父存在节点;
            }
            return std::nullopt;
        };
        const auto 收集场景范围对象 = [&](稳定编码 根场景) {
            std::vector<稳定编码> 对象组;
            std::vector<稳定编码> 待查场景{根场景};
            std::vector<稳定编码> 待查存在;
            std::set<稳定编码> 已查场景;
            std::set<稳定编码> 已查存在;
            while (!待查场景.empty()) {
                const auto 场景 = 待查场景.back();
                待查场景.pop_back();
                if (!已查场景.insert(场景).second) continue;
                对象组.push_back(场景);
                const auto 子场景 = 场景服务_.查询直接子场景(场景);
                待查场景.insert(待查场景.end(), 子场景.begin(), 子场景.end());
                const auto 成员 = 场景服务_.查询直接成员存在(场景);
                待查存在.insert(待查存在.end(), 成员.begin(), 成员.end());
            }
            while (!待查存在.empty()) {
                const auto 存在 = 待查存在.back();
                待查存在.pop_back();
                if (!已查存在.insert(存在).second) continue;
                对象组.push_back(存在);
                const auto 子存在 = 存在服务_.查询直接子存在(存在);
                待查存在.insert(待查存在.end(), 子存在.begin(), 子存在.end());
            }
            std::sort(对象组.begin(), 对象组.end());
            对象组.erase(std::unique(对象组.begin(), 对象组.end()), 对象组.end());
            return 对象组;
        };

        std::optional<稳定编码> 目标宿主 = 需求->目标宿主节点;
        if (!目标宿主 && 需求->根实际特征节点) {
            std::vector<稳定编码> 命中宿主;
            for (const auto 对象节点 : 收集场景范围对象(场景树根节点)) {
                const auto 对象 = 读取对象(对象节点);
                if (!对象) {
                    结果.状态 = 新世界任务条件筹办状态::结构不一致;
                    return 结果;
                }
                if (std::find(对象->特征组.begin(), 对象->特征组.end(),
                        *需求->根实际特征节点) != 对象->特征组.end()) {
                    命中宿主.push_back(对象节点);
                }
            }
            if (命中宿主.size() != 1) {
                结果.状态 = 新世界任务条件筹办状态::结构不一致;
                return 结果;
            }
            目标宿主 = 命中宿主.front();
        }
        if (!目标宿主) {
            结果.状态 = 新世界任务条件筹办状态::结构不一致;
            return 结果;
        }
        const auto 目标场景 = 查找所属场景(*目标宿主);
        if (!目标场景 || !场景服务_.是场景节点(*目标场景)) {
            结果.状态 = 新世界任务条件筹办状态::结构不一致;
            return 结果;
        }
        const auto 范围对象组 = 收集场景范围对象(*目标场景);

        enum class 对象匹配状态 : std::uint8_t {
            匹配, 不匹配, 材料未到, 结构缺口
        };
        for (const auto 方法节点 : 材料->候选方法节点组) {
            新世界候选方法筹办项 方法项;
            方法项.方法节点 = 方法节点;
            const auto 方法 = 方法服务_.获取方法(方法节点);
            if (!方法 || 方法->启用状态 != 新方法启用状态::启用) {
                结果.状态 = 新世界任务条件筹办状态::结构不一致;
                return 结果;
            }

            bool 参数材料未到 = false;
            bool 参数结构缺口 = false;
            bool 参数不唯一 = false;
            for (const auto& 规格 : 方法->参数规格组) {
                if (std::any_of(规格.特征规格组.begin(), 规格.特征规格组.end(),
                        [](const auto& 特征规格) {
                            return !特征规格.二次特征概念组.empty();
                        })) {
                    参数结构缺口 = true;
                    break;
                }
                std::vector<新方法参数角色绑定> 命中绑定;
                for (const auto 对象节点 : 范围对象组) {
                    const auto 对象 = 读取对象(对象节点);
                    if (!对象) {
                        参数结构缺口 = true;
                        break;
                    }
                    if (规格.存在概念节点
                        && !存在概念兼容(
                            对象->专属概念, *规格.存在概念节点)) continue;

                    对象匹配状态 对象状态 = 对象匹配状态::匹配;
                    std::vector<新方法实际特征绑定> 特征绑定组;
                    for (const auto& 特征规格 : 规格.特征规格组) {
                        std::vector<稳定编码> 特征命中;
                        bool 当前值缺失 = false;
                        for (const auto 特征节点 : 对象->特征组) {
                            const auto 特征 = 特征服务_.获取特征(特征节点);
                            if (!特征) {
                                对象状态 = 对象匹配状态::结构缺口;
                                break;
                            }
                            if (!特征概念兼容(特征->特征概念节点,
                                    特征规格.特征类型概念节点)) continue;
                            if (特征规格.值域概念节点) {
                                const auto 命中 = 当前值命中概念(
                                    *特征, *特征规格.值域概念节点);
                                if (命中 == 值域核验::材料未到) {
                                    当前值缺失 = true;
                                    continue;
                                }
                                if (命中 == 值域核验::结构缺口) {
                                    对象状态 = 对象匹配状态::结构缺口;
                                    break;
                                }
                                if (命中 != 值域核验::命中) continue;
                            }
                            特征命中.push_back(特征节点);
                        }
                        if (对象状态 == 对象匹配状态::结构缺口) break;
                        if (特征命中.empty()) {
                            对象状态 = 当前值缺失
                                ? 对象匹配状态::材料未到
                                : 对象匹配状态::不匹配;
                            break;
                        }
                        if (特征命中.size() != 1) {
                            对象状态 = 对象匹配状态::结构缺口;
                            break;
                        }
                        特征绑定组.push_back({特征命中.front()});
                    }
                    if (对象状态 == 对象匹配状态::材料未到) {
                        参数材料未到 = true;
                        continue;
                    }
                    if (对象状态 == 对象匹配状态::结构缺口) {
                        参数结构缺口 = true;
                        break;
                    }
                    if (对象状态 != 对象匹配状态::匹配) continue;
                    新方法参数角色绑定 绑定;
                    绑定.参数角色节点 = 规格.参数角色节点;
                    绑定.实际存在节点 = 对象节点;
                    绑定.实际特征组 = std::move(特征绑定组);
                    if (对象->直接所属场景
                        && 场景服务_.存在属于场景范围(
                            *目标场景, 对象节点)) {
                        绑定.世界场景节点 = *目标场景;
                    }
                    if (规格.要求场景 && !绑定.世界场景节点) continue;
                    命中绑定.push_back(std::move(绑定));
                }
                if (参数结构缺口) break;
                if (命中绑定.size() != 1) {
                    参数不唯一 = true;
                    break;
                }
                方法项.参数绑定组.push_back(std::move(命中绑定.front()));
            }
            if (参数结构缺口) {
                方法项.状态 = 新世界候选方法筹办状态::结构缺口;
                结果.方法筹办组.push_back(std::move(方法项));
                continue;
            }
            if (参数不唯一) {
                方法项.状态 = 参数材料未到
                    ? 新世界候选方法筹办状态::材料未到
                    : 新世界候选方法筹办状态::参数缺失;
                结果.方法筹办组.push_back(std::move(方法项));
                continue;
            }
            std::sort(方法项.参数绑定组.begin(), 方法项.参数绑定组.end(),
                [](const auto& 左, const auto& 右) {
                    return 左.参数角色节点 < 右.参数角色节点;
                });
            const auto 参数场景 = 方法服务_.建立参数场景(
                方法节点, 方法项.参数绑定组);
            if (参数场景.状态 != 新方法操作状态::已建立
                || !参数场景.参数场景) {
                方法项.状态 = 参数场景.状态 == 新方法操作状态::资源失败
                    ? 新世界候选方法筹办状态::资源失败
                    : 新世界候选方法筹办状态::结构缺口;
                结果.方法筹办组.push_back(std::move(方法项));
                continue;
            }

            const auto 查找角色对象 = [&](稳定编码 角色)
                -> std::optional<对象材料> {
                const auto 位置 = std::find_if(
                    方法项.参数绑定组.begin(), 方法项.参数绑定组.end(),
                    [&](const auto& 绑定) {
                        return 绑定.参数角色节点 == 角色;
                    });
                return 位置 != 方法项.参数绑定组.end()
                    && 位置->实际存在节点
                    ? 读取对象(*位置->实际存在节点) : std::nullopt;
            };
            bool 任一条件具备 = false;
            bool 有材料未到 = false;
            bool 有结构缺口 = false;
            for (const auto& 配对 : 方法->条件结果组) {
                新世界方法条件结果核验 配对结果{
                    配对.配对节点, 配对.条件节点, 配对.结果节点,
                    新世界方法条件项核验状态::结构缺口};
                std::vector<新世界方法条件项核验状态> 项状态组;
                for (const auto& 条件项 : 配对.条件.条件项组) {
                    if (条件项.二次特征概念节点
                        || 条件项.状态或动态概念节点) {
                        项状态组.push_back(
                            新世界方法条件项核验状态::结构缺口);
                        continue;
                    }
                    const auto 对象 = 查找角色对象(条件项.参数角色节点);
                    if (!对象) {
                        项状态组.push_back(
                            新世界方法条件项核验状态::结构缺口);
                        continue;
                    }
                    if (条件项.存在概念节点
                        && !存在概念兼容(
                            对象->专属概念, *条件项.存在概念节点)) {
                        项状态组.push_back(
                            新世界方法条件项核验状态::不具备);
                        continue;
                    }
                    if (!条件项.特征类型概念节点
                        && !条件项.特征值域概念节点) {
                        项状态组.push_back(
                            新世界方法条件项核验状态::具备);
                        continue;
                    }
                    bool 命中特征 = false;
                    bool 缺当前值 = false;
                    bool 特征结构错误 = false;
                    for (const auto 特征节点 : 对象->特征组) {
                        const auto 特征 = 特征服务_.获取特征(特征节点);
                        if (!特征) {
                            特征结构错误 = true;
                            break;
                        }
                        if (条件项.特征类型概念节点
                            && !特征概念兼容(特征->特征概念节点,
                                *条件项.特征类型概念节点)) continue;
                        if (条件项.特征值域概念节点) {
                            const auto 命中 = 当前值命中概念(
                                *特征, *条件项.特征值域概念节点);
                            if (命中 == 值域核验::材料未到) {
                                缺当前值 = true;
                                continue;
                            }
                            if (命中 == 值域核验::结构缺口) {
                                特征结构错误 = true;
                                break;
                            }
                            if (命中 != 值域核验::命中) continue;
                        }
                        命中特征 = true;
                        break;
                    }
                    项状态组.push_back(特征结构错误
                        ? 新世界方法条件项核验状态::结构缺口
                        : (命中特征
                            ? 新世界方法条件项核验状态::具备
                            : (缺当前值
                                ? 新世界方法条件项核验状态::材料未到
                                : 新世界方法条件项核验状态::不具备)));
                }
                const auto 有 = [&](新世界方法条件项核验状态 状态) {
                    return std::find(项状态组.begin(), 项状态组.end(), 状态)
                        != 项状态组.end();
                };
                switch (配对.条件.关系规则) {
                case 新方法项关系规则::单项:
                    if (项状态组.size() == 1) 配对结果.状态 = 项状态组.front();
                    break;
                case 新方法项关系规则::全部成立:
                    配对结果.状态 = 有(新世界方法条件项核验状态::不具备)
                        ? 新世界方法条件项核验状态::不具备
                        : (有(新世界方法条件项核验状态::结构缺口)
                            ? 新世界方法条件项核验状态::结构缺口
                            : (有(新世界方法条件项核验状态::材料未到)
                                ? 新世界方法条件项核验状态::材料未到
                                : 新世界方法条件项核验状态::具备));
                    break;
                case 新方法项关系规则::任一成立:
                    配对结果.状态 = 有(新世界方法条件项核验状态::具备)
                        ? 新世界方法条件项核验状态::具备
                        : (有(新世界方法条件项核验状态::结构缺口)
                            ? 新世界方法条件项核验状态::结构缺口
                            : (有(新世界方法条件项核验状态::材料未到)
                                ? 新世界方法条件项核验状态::材料未到
                                : 新世界方法条件项核验状态::不具备));
                    break;
                case 新方法项关系规则::有序成立:
                case 新方法项关系规则::条件选择:
                case 新方法项关系规则::主要结果及允许副作用:
                    配对结果.状态 =
                        新世界方法条件项核验状态::结构缺口;
                    break;
                }
                任一条件具备 = 任一条件具备
                    || 配对结果.状态 == 新世界方法条件项核验状态::具备;
                有材料未到 = 有材料未到
                    || 配对结果.状态 == 新世界方法条件项核验状态::材料未到;
                有结构缺口 = 有结构缺口
                    || 配对结果.状态 == 新世界方法条件项核验状态::结构缺口;
                方法项.条件结果组.push_back(std::move(配对结果));
            }
            方法项.状态 = 任一条件具备
                ? 新世界候选方法筹办状态::条件具备
                : (有结构缺口
                    ? 新世界候选方法筹办状态::结构缺口
                    : (有材料未到
                        ? 新世界候选方法筹办状态::材料未到
                        : 新世界候选方法筹办状态::条件不具备));
            结果.方法筹办组.push_back(std::move(方法项));
        }
        结果.候选已完整核验 =
            结果.方法筹办组.size() == 材料->候选方法节点组.size();
        结果.状态 = 结果.候选已完整核验
            ? 新世界任务条件筹办状态::已完成
            : 新世界任务条件筹办状态::结构不一致;
        return 结果;
    } catch (...) {
        结果.状态 = 新世界任务条件筹办状态::资源失败;
        结果.候选已完整核验 = false;
        结果.方法筹办组.clear();
        return 结果;
    }
}

新世界任务执行方向核验结果 新_世界树类::核验任务执行方向(
    稳定编码 任务节点,
    稳定编码 方法节点,
    稳定编码 配对节点,
    稳定编码 结果节点,
    稳定编码 自我存在节点,
    稳定编码 安全需求节点,
    稳定编码 服务需求节点) const noexcept {
    新世界任务执行方向核验结果 结果;
    结果.任务节点 = 任务节点;
    结果.方法节点 = 方法节点;
    结果.配对节点 = 配对节点;
    结果.结果节点 = 结果节点;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) {
            结果.状态 = 新世界任务执行方向核验状态::等待材料;
            return 结果;
        }
        const auto 任务 = 任务服务_.获取任务(任务节点);
        const auto 方法 = 方法服务_.获取方法(方法节点);
        if (!任务 || !方法 || 方法->启用状态 != 新方法启用状态::启用) {
            结果.状态 = 新世界任务执行方向核验状态::定位已变化;
            return 结果;
        }
        if (任务->当前状态 != 新任务状态::待检查条件) {
            结果.状态 = 新世界任务执行方向核验状态::任务状态已变化;
            return 结果;
        }
        if (方法->实现方式 != 新方法实现方式::本能) {
            结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
            return 结果;
        }

        const auto 当前筹办 = 筹办任务条件和参数(任务节点);
        if (当前筹办.状态 == 新世界任务条件筹办状态::任务状态已变化) {
            结果.状态 = 新世界任务执行方向核验状态::任务状态已变化;
            return 结果;
        }
        if (当前筹办.状态 == 新世界任务条件筹办状态::资源失败) {
            结果.状态 = 新世界任务执行方向核验状态::资源失败;
            return 结果;
        }
        if (当前筹办.状态 != 新世界任务条件筹办状态::已完成
            || !当前筹办.候选已完整核验) {
            结果.状态 = 新世界任务执行方向核验状态::等待材料;
            return 结果;
        }

        const 新世界候选方法筹办项* 唯一方法 = nullptr;
        const 新世界方法条件结果核验* 唯一配对 = nullptr;
        std::size_t 具备数量 = 0;
        for (const auto& 方法项 : 当前筹办.方法筹办组) {
            if (方法项.状态 != 新世界候选方法筹办状态::条件具备) continue;
            for (const auto& 配对项 : 方法项.条件结果组) {
                if (配对项.状态 != 新世界方法条件项核验状态::具备) continue;
                ++具备数量;
                唯一方法 = &方法项;
                唯一配对 = &配对项;
            }
        }
        if (具备数量 != 1 || !唯一方法 || !唯一配对
            || 唯一方法->方法节点 != 方法节点
            || 唯一配对->配对节点 != 配对节点
            || 唯一配对->结果节点 != 结果节点) {
            结果.状态 = 新世界任务执行方向核验状态::定位已变化;
            return 结果;
        }
        const auto 配对位置 = std::find_if(
            方法->条件结果组.begin(), 方法->条件结果组.end(),
            [&](const 新方法条件结果信息& 候选) {
                return 候选.配对节点 == 配对节点
                    && 候选.结果节点 == 结果节点;
            });
        if (配对位置 == 方法->条件结果组.end()) {
            结果.状态 = 新世界任务执行方向核验状态::定位已变化;
            return 结果;
        }
        if (配对位置->结果.关系规则 != 新方法项关系规则::单项
            && 配对位置->结果.关系规则 != 新方法项关系规则::全部成立
            && 配对位置->结果.关系规则
                != 新方法项关系规则::主要结果及允许副作用) {
            结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
            return 结果;
        }

        struct 已绑定预计变化 final {
            新任务预计特征变化 变化;
            稳定编码 特征类型根;
            预计变化方向 方向 = 预计变化方向::不明确;
        };
        std::vector<已绑定预计变化> 已绑定组;
        新任务预计变化阶段 阶段;
        阶段.顺序 = 0;
        for (const auto& 项 : 配对位置->结果.结果项组) {
            if (!项.特征类型概念节点
                || 项.状态或动态概念节点
                || (!项.特征值域概念节点 && !项.变化方向概念节点)) {
                结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
                return 结果;
            }
            const auto 绑定位置 = std::find_if(
                唯一方法->参数绑定组.begin(), 唯一方法->参数绑定组.end(),
                [&](const 新方法参数角色绑定& 绑定) {
                    return 绑定.参数角色节点 == 项.参数角色节点;
                });
            if (绑定位置 == 唯一方法->参数绑定组.end()
                || !绑定位置->实际存在节点) {
                结果.状态 = 新世界任务执行方向核验状态::等待材料;
                return 结果;
            }
            const auto 类型根 = 取得特征概念类型根(
                特征概念服务_, *项.特征类型概念节点);
            if (!类型根) {
                结果.状态 = 新世界任务执行方向核验状态::结构不一致;
                return 结果;
            }
            if (项.变化方向概念节点) {
                const auto 方向概念 = 二次特征概念服务_.获取二次特征概念(
                    *项.变化方向概念节点);
                if (!方向概念
                    || 方向概念->算法 != 二次特征算法::有向特征差值
                    || 方向概念->参照特征概念节点
                    || 方向概念->输入定义组.empty()) {
                    结果.状态 = 新世界任务执行方向核验状态::结构不一致;
                    return 结果;
                }
                for (const auto& 输入 : 方向概念->输入定义组) {
                    if (输入.来源种类
                            != 二次特征输入来源种类::特征准确值
                        || !输入.特征类型概念节点
                        || 取得特征概念类型根(
                                特征概念服务_, *输入.特征类型概念节点)
                            != 类型根) {
                        结果.状态 = 新世界任务执行方向核验状态::结构不一致;
                        return 结果;
                    }
                }
            }
            新任务预计特征变化 变化;
            变化.作用对象节点 = *绑定位置->实际存在节点;
            变化.特征类型概念节点 = *项.特征类型概念节点;
            变化.预期变化关系节点 = 项.变化方向概念节点;
            const auto 方向 = 项.变化方向概念节点
                ? 读取预计变化方向(
                    二次特征概念服务_, *项.变化方向概念节点)
                : 预计变化方向::不明确;
            if (方向 == 预计变化方向::增加) {
                变化.预期方向 = 新任务预期变化方向::增加;
            } else if (方向 == 预计变化方向::减少) {
                变化.预期方向 = 新任务预期变化方向::减少;
            } else if (方向 == 预计变化方向::不变) {
                变化.预期方向 = 新任务预期变化方向::不变;
            }
            变化.预期值域概念节点 = 项.特征值域概念节点;
            变化.必须出现 = 配对位置->结果.关系规则
                    != 新方法项关系规则::主要结果及允许副作用
                || 项.主要结果;
            阶段.变化组.push_back(变化);
            已绑定组.push_back({变化, *类型根, 方向});
        }
        if (阶段.变化组.empty()) {
            结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
            return 结果;
        }
        结果.预计变化阶段组.push_back(std::move(阶段));

        新世界任务结果获取方案 获取方案;
        const auto& 确认要求 = 配对位置->结果.确认要求;
        // 当前生产链只接通了状态owner正式通知这一条直接事实渠道。方法若
        // 要求共同/备用多渠道、固定等待上限或具名等待条件，不能伪装可执行。
        if (确认要求.多证据关系 != 新方法多证据关系::任一满足
            || 确认要求.最大等待纳秒
            || 确认要求.等待条件概念节点) {
            结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
            return 结果;
        }
        if (!确认要求.禁止结果项组.empty()
            && 确认要求.禁止结果关系规则 != 新方法项关系规则::单项
            && 确认要求.禁止结果关系规则 != 新方法项关系规则::任一成立
            && 确认要求.禁止结果关系规则 != 新方法项关系规则::全部成立) {
            结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
            return 结果;
        }
        获取方案.多渠道关系 = 确认要求.多证据关系;
        获取方案.渠道方案组.push_back({
            新任务结果获取渠道::世界树状态通知,
            0,
            新任务必要证据质量::正式直接事实,
            std::nullopt,
            std::nullopt});
        获取方案.禁止结果关系规则 = 确认要求.禁止结果关系规则;
        for (const auto& 预计 : 已绑定组) {
            std::vector<稳定编码> 特征节点组;
            if (const auto 存在 = 存在服务_.获取存在(
                    预计.变化.作用对象节点)) {
                特征节点组 = 存在->特征节点组;
            } else if (const auto 场景 = 场景服务_.获取场景(
                    预计.变化.作用对象节点)) {
                特征节点组 = 场景->特征节点组;
            } else {
                结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
                return 结果;
            }
            std::optional<稳定编码> 实际特征;
            for (const auto 特征节点 : 特征节点组) {
                const auto 特征 = 特征服务_.获取特征(特征节点);
                if (!特征) {
                    结果.状态 = 新世界任务执行方向核验状态::结构不一致;
                    return 结果;
                }
                const auto 类型根 = 取得特征概念类型根(
                    特征概念服务_, 特征->特征概念节点);
                if (!类型根) {
                    结果.状态 = 新世界任务执行方向核验状态::结构不一致;
                    return 结果;
                }
                if (*类型根 != 预计.特征类型根) continue;
                if (实际特征) {
                    结果.状态 = 新世界任务执行方向核验状态::结构不一致;
                    return 结果;
                }
                实际特征 = 特征节点;
            }
            if (!实际特征) {
                // 没有可由世界树状态通知读回的实际特征，当前执行没有
                // 明确可实现的结果获取途径，必须保持零动作。
                结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
                return 结果;
            }
            const auto 特征 = 特征服务_.获取特征(*实际特征);
            if (!特征 || !特征->当前值) {
                结果.状态 = 新世界任务执行方向核验状态::等待材料;
                return 结果;
            }
            获取方案.目标组.push_back({预计.变化.作用对象节点,
                *实际特征, 预计.特征类型根, *特征->当前值,
                预计.变化.必须出现});
        }
        for (const auto& 禁止项 : 确认要求.禁止结果项组) {
            if (!禁止项.特征类型概念节点
                || 禁止项.状态或动态概念节点
                || (!禁止项.特征值域概念节点
                    && !禁止项.变化方向概念节点)) {
                结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
                return 结果;
            }
            const auto 绑定位置 = std::find_if(
                唯一方法->参数绑定组.begin(), 唯一方法->参数绑定组.end(),
                [&](const 新方法参数角色绑定& 绑定) {
                    return 绑定.参数角色节点 == 禁止项.参数角色节点;
                });
            if (绑定位置 == 唯一方法->参数绑定组.end()
                || !绑定位置->实际存在节点) {
                结果.状态 = 新世界任务执行方向核验状态::等待材料;
                return 结果;
            }
            const auto 类型根 = 取得特征概念类型根(
                特征概念服务_, *禁止项.特征类型概念节点);
            if (!类型根) {
                结果.状态 = 新世界任务执行方向核验状态::结构不一致;
                return 结果;
            }
            std::optional<新任务预期变化方向> 禁止方向;
            if (禁止项.变化方向概念节点) {
                const auto 方向 = 读取预计变化方向(
                    二次特征概念服务_, *禁止项.变化方向概念节点);
                if (方向 == 预计变化方向::增加) {
                    禁止方向 = 新任务预期变化方向::增加;
                } else if (方向 == 预计变化方向::减少) {
                    禁止方向 = 新任务预期变化方向::减少;
                } else if (方向 == 预计变化方向::不变) {
                    禁止方向 = 新任务预期变化方向::不变;
                } else {
                    结果.状态 =
                        新世界任务执行方向核验状态::结果定义暂不支持;
                    return 结果;
                }
            }

            const auto 目标位置 = std::find_if(
                获取方案.目标组.begin(), 获取方案.目标组.end(),
                [&](const 新任务结果获取目标& 目标) {
                    return 目标.作用对象节点 == *绑定位置->实际存在节点
                        && 目标.特征类型根概念节点 == *类型根;
                });
            if (目标位置 == 获取方案.目标组.end()) {
                // 单一“状态通知”渠道只能在同一必需结果状态上同时核验禁止
                // 条件；其它特征没有变化通知时无法证明禁止结果未发生。
                结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
                return 结果;
            }
            目标位置->必须出现 = true;
            获取方案.禁止结果组.push_back({
                目标位置->作用对象节点,
                目标位置->实际特征节点,
                目标位置->特征类型根概念节点,
                目标位置->动作前准确值,
                禁止方向,
                禁止项.特征值域概念节点,
                std::nullopt});
        }
        if (!获取方案.完整()) {
            结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
            return 结果;
        }
        结果.结果获取方案 = std::move(获取方案);

        const auto 需求 = 需求服务_.获取需求(任务->需求节点);
        const auto 安全需求 = 需求服务_.获取需求(安全需求节点);
        const auto 服务需求 = 需求服务_.获取需求(服务需求节点);
        const auto 自我 = 存在服务_.获取存在(自我存在节点);
        if (!需求 || !安全需求 || !服务需求 || !自我
            || 安全需求->根角色 != 新需求根角色::安全
            || 服务需求->根角色 != 新需求根角色::服务
            || !安全需求->根实际特征节点
            || !服务需求->根实际特征节点
            || std::find(自我->特征节点组.begin(), 自我->特征节点组.end(),
                    *安全需求->根实际特征节点) == 自我->特征节点组.end()
            || std::find(自我->特征节点组.begin(), 自我->特征节点组.end(),
                    *服务需求->根实际特征节点) == 自我->特征节点组.end()) {
            结果.状态 = 新世界任务执行方向核验状态::结构不一致;
            return 结果;
        }
        结果.任务目标当前结果 = 需求服务_.复核当前满足(任务->需求节点);
        结果.安全当前结果 = 需求服务_.复核当前满足(安全需求节点);
        结果.服务当前结果 = 需求服务_.复核当前满足(服务需求节点);
        const auto 当前结果可用 = [](const 新需求当前满足结果& 当前) {
            return 当前.状态 == 新需求当前满足状态::已满足
                || 当前.状态 == 新需求当前满足状态::需增加
                || 当前.状态 == 新需求当前满足状态::需减少;
        };
        const auto 当前结果等待 = [](const 新需求当前满足结果& 当前) {
            return 当前.状态 == 新需求当前满足状态::目标特征尚未形成
                || 当前.状态 == 新需求当前满足状态::当前值不存在;
        };
        if (结果.任务目标当前结果->状态 == 新需求当前满足状态::资源失败
            || 结果.安全当前结果->状态 == 新需求当前满足状态::资源失败
            || 结果.服务当前结果->状态 == 新需求当前满足状态::资源失败) {
            结果.状态 = 新世界任务执行方向核验状态::资源失败;
            return 结果;
        }
        if (当前结果等待(*结果.任务目标当前结果)
            || 当前结果等待(*结果.安全当前结果)
            || 当前结果等待(*结果.服务当前结果)) {
            结果.状态 = 新世界任务执行方向核验状态::等待材料;
            return 结果;
        }
        if (!当前结果可用(*结果.任务目标当前结果)
            || !当前结果可用(*结果.安全当前结果)
            || !当前结果可用(*结果.服务当前结果)) {
            结果.状态 = 新世界任务执行方向核验状态::结构不一致;
            return 结果;
        }
        if (结果.任务目标当前结果->状态 == 新需求当前满足状态::已满足) {
            结果.状态 = 新世界任务执行方向核验状态::任务目标已满足;
            return 结果;
        }

        const auto 任务目标对象 = 需求->根角色
            ? std::optional<稳定编码>{自我存在节点} : 需求->目标宿主节点;
        if (!任务目标对象) {
            结果.状态 = 新世界任务执行方向核验状态::结构不一致;
            return 结果;
        }
        bool 找到任务目标 = false, 任务目标推进 = false;
        bool 任务目标相反 = false, 任务目标不明确 = false;
        for (const auto& 预计 : 已绑定组) {
            if (!预计.变化.必须出现
                || 预计.变化.作用对象节点 != *任务目标对象
                || 预计.特征类型根 != 需求->目标.目标特征类型概念节点) {
                continue;
            }
            找到任务目标 = true;
            bool 值域结构有效 = true;
            const bool 值域保证 = 预计.变化.预期值域概念节点
                && 预计值域保证命中目标(特征概念服务_,
                    需求->目标.目标值域概念节点,
                    *预计.变化.预期值域概念节点, 值域结构有效);
            if (!值域结构有效) {
                结果.状态 = 新世界任务执行方向核验状态::结构不一致;
                return 结果;
            }
            const bool 需要增加 = 结果.任务目标当前结果->状态
                == 新需求当前满足状态::需增加;
            const bool 方向推进 = 需要增加
                ? 预计.方向 == 预计变化方向::增加
                : 预计.方向 == 预计变化方向::减少;
            const bool 方向相反 = 需要增加
                ? 预计.方向 == 预计变化方向::减少
                : 预计.方向 == 预计变化方向::增加;
            if (值域保证 && 方向相反) {
                结果.状态 = 新世界任务执行方向核验状态::结构不一致;
                return 结果;
            }
            任务目标推进 = 任务目标推进 || 值域保证 || 方向推进;
            任务目标相反 = 任务目标相反 || 方向相反;
            任务目标不明确 = 任务目标不明确
                || (!值域保证 && !方向推进 && !方向相反
                    && 预计.方向 != 预计变化方向::不变);
        }
        if (任务目标不明确) {
            结果.状态 = 新世界任务执行方向核验状态::结果定义暂不支持;
            return 结果;
        }
        if (!找到任务目标 || 任务目标相反 || !任务目标推进) {
            结果.状态 = 新世界任务执行方向核验状态::任务目标方向不一致;
            return 结果;
        }

        const auto 核验根影响 = [&](const 新需求信息& 根需求,
                                    const 新需求当前满足结果& 当前) {
            for (const auto& 预计 : 已绑定组) {
                if (预计.变化.作用对象节点 != 自我存在节点
                    || 预计.特征类型根
                        != 根需求.目标.目标特征类型概念节点) continue;
                bool 值域结构有效 = true;
                const bool 值域保证 = 预计.变化.预期值域概念节点
                    && 预计值域保证命中目标(特征概念服务_,
                        根需求.目标.目标值域概念节点,
                        *预计.变化.预期值域概念节点, 值域结构有效);
                if (!值域结构有效) return 2;
                if (值域保证) continue;
                if (当前.状态 == 新需求当前满足状态::需增加) {
                    if (预计.方向 == 预计变化方向::减少) return 1;
                    if (预计.方向 == 预计变化方向::不明确) return 3;
                    continue;
                }
                if (当前.状态 == 新需求当前满足状态::需减少) {
                    if (预计.方向 == 预计变化方向::增加) return 1;
                    if (预计.方向 == 预计变化方向::不明确) return 3;
                    continue;
                }
                // 根已经位于INT64_MAX目标时，只接受明确不变或仍保证落在目标值域。
                if (预计.方向 != 预计变化方向::不变) return 1;
            }
            return 0;
        };
        const auto 安全核验 = 核验根影响(*安全需求, *结果.安全当前结果);
        if (安全核验) {
            结果.状态 = 安全核验 == 1
                ? 新世界任务执行方向核验状态::安全方向不一致
                : 安全核验 == 3
                    ? 新世界任务执行方向核验状态::结果定义暂不支持
                    : 新世界任务执行方向核验状态::结构不一致;
            return 结果;
        }
        const auto 服务核验 = 核验根影响(*服务需求, *结果.服务当前结果);
        if (服务核验) {
            结果.状态 = 服务核验 == 1
                ? 新世界任务执行方向核验状态::服务方向不一致
                : 服务核验 == 3
                    ? 新世界任务执行方向核验状态::结果定义暂不支持
                    : 新世界任务执行方向核验状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新世界任务执行方向核验状态::已核验可执行;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 新世界任务执行方向核验状态::资源失败;
        结果.预计变化阶段组.clear();
        return 结果;
    } catch (...) {
        结果.状态 = 新世界任务执行方向核验状态::结构不一致;
        结果.预计变化阶段组.clear();
        return 结果;
    }
}

新世界任务待执行确认状态 新_世界树类::确认任务进入待执行(
    稳定编码 任务节点,
    稳定编码 方法节点,
    稳定编码 配对节点,
    稳定编码 结果节点) noexcept {
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) {
            return 新世界任务待执行确认状态::结构不一致;
        }
        const auto 任务 = 任务服务_.获取任务(任务节点);
        if (!任务) return 新世界任务待执行确认状态::结构不一致;
        if (任务->当前状态 != 新任务状态::待检查条件) {
            return 新世界任务待执行确认状态::任务状态已变化;
        }
        const auto 当前筹办 = 筹办任务条件和参数(任务节点);
        if (当前筹办.状态 == 新世界任务条件筹办状态::资源失败) {
            return 新世界任务待执行确认状态::资源失败;
        }
        if (当前筹办.状态 != 新世界任务条件筹办状态::已完成
            || !当前筹办.候选已完整核验) {
            return 当前筹办.状态 == 新世界任务条件筹办状态::任务状态已变化
                ? 新世界任务待执行确认状态::任务状态已变化
                : 新世界任务待执行确认状态::结构不一致;
        }
        std::size_t 具备数量 = 0;
        bool 精确命中 = false;
        for (const auto& 方法项 : 当前筹办.方法筹办组) {
            if (方法项.状态 != 新世界候选方法筹办状态::条件具备) continue;
            for (const auto& 配对项 : 方法项.条件结果组) {
                if (配对项.状态 != 新世界方法条件项核验状态::具备) continue;
                ++具备数量;
                精确命中 = 方法项.方法节点 == 方法节点
                    && 配对项.配对节点 == 配对节点
                    && 配对项.结果节点 == 结果节点;
            }
        }
        if (具备数量 != 1 || !精确命中) {
            return 新世界任务待执行确认状态::定位已变化;
        }
        const auto 修改 = 任务服务_.修改任务状态(
            任务节点, 新任务状态::待执行);
        if (修改 == 新任务操作状态::已修改) {
            return 新世界任务待执行确认状态::已确认;
        }
        if (修改 == 新任务操作状态::资源失败) {
            return 新世界任务待执行确认状态::资源失败;
        }
        return 修改 == 新任务操作状态::任务状态不允许
            ? 新世界任务待执行确认状态::任务状态已变化
            : 新世界任务待执行确认状态::结构不一致;
    } catch (const std::bad_alloc&) {
        return 新世界任务待执行确认状态::资源失败;
    } catch (...) {
        return 新世界任务待执行确认状态::结构不一致;
    }
}

新世界任务本能执行结果 新_世界树类::执行任务本能方法(
    const 新世界任务本能执行请求& 请求) noexcept {
    新世界任务本能执行结果 结果;
    结果.原请求 = 请求;
    if (!请求.完整()) return 结果;

    std::shared_ptr<const 方法参数场景> 参数场景;
    std::optional<新任务信息> 开始前任务;
    try {
        {
            std::lock_guard 锁(新世界树互斥);
            if (!已初始化_ || !任务集合已初始化_) {
                结果.状态 = 新世界任务本能执行状态::结构不一致;
                return 结果;
            }

            结果.临近方向核验 = 核验任务执行方向(
                请求.任务节点, 请求.方法节点, 请求.配对节点,
                请求.结果节点, 请求.自我存在节点,
                请求.安全需求节点, 请求.服务需求节点);
            if (结果.临近方向核验->状态
                    != 新世界任务执行方向核验状态::已核验可执行
                || 结果.临近方向核验->预计变化阶段组
                    != 请求.预计变化阶段组
                || !结果.临近方向核验->结果获取方案
                || *结果.临近方向核验->结果获取方案
                    != 请求.结果获取方案) {
                switch (结果.临近方向核验->状态) {
                case 新世界任务执行方向核验状态::任务状态已变化:
                    结果.状态 = 新世界任务本能执行状态::任务状态已变化;
                    break;
                case 新世界任务执行方向核验状态::资源失败:
                    结果.状态 = 新世界任务本能执行状态::资源失败;
                    break;
                case 新世界任务执行方向核验状态::定位已变化:
                case 新世界任务执行方向核验状态::任务目标已满足:
                case 新世界任务执行方向核验状态::任务目标方向不一致:
                case 新世界任务执行方向核验状态::安全方向不一致:
                case 新世界任务执行方向核验状态::服务方向不一致:
                case 新世界任务执行方向核验状态::等待材料:
                    结果.状态 = 新世界任务本能执行状态::定位已变化;
                    break;
                default:
                    结果.状态 = 新世界任务本能执行状态::结构不一致;
                    break;
                }
                return 结果;
            }

            const auto 当前筹办 = 筹办任务条件和参数(请求.任务节点);
            const auto 方法位置 = std::find_if(
                当前筹办.方法筹办组.begin(), 当前筹办.方法筹办组.end(),
                [&](const 新世界候选方法筹办项& 项) {
                    return 项.方法节点 == 请求.方法节点
                        && 项.状态 == 新世界候选方法筹办状态::条件具备;
                });
            if (当前筹办.状态 != 新世界任务条件筹办状态::已完成
                || !当前筹办.候选已完整核验
                || 方法位置 == 当前筹办.方法筹办组.end()
                || 方法位置->参数绑定组 != 请求.参数绑定组) {
                结果.状态 = 当前筹办.状态
                        == 新世界任务条件筹办状态::资源失败
                    ? 新世界任务本能执行状态::资源失败
                    : 新世界任务本能执行状态::定位已变化;
                return 结果;
            }

            const auto 方法 = 方法服务_.获取方法(请求.方法节点);
            if (!方法 || 方法->实现方式 != 新方法实现方式::本能
                || !方法->本能函数登记名) {
                结果.状态 = 新世界任务本能执行状态::定位已变化;
                return 结果;
            }
            const auto 可用 = 新_本能函数集::检查可用(
                *方法->本能函数登记名);
            if (可用 != 新本能函数可用状态::可调用) {
                结果.状态 = 可用 == 新本能函数可用状态::依赖未装配
                        || 可用 == 新本能函数可用状态::未登记
                    ? 新世界任务本能执行状态::执行依赖未就绪
                    : 新世界任务本能执行状态::结构不一致;
                return 结果;
            }

            const auto 场景结果 = 方法服务_.建立参数场景(
                请求.方法节点, 请求.参数绑定组);
            if (场景结果.状态 != 新方法操作状态::已建立
                || !场景结果.参数场景) {
                结果.状态 = 场景结果.状态 == 新方法操作状态::资源失败
                    ? 新世界任务本能执行状态::资源失败
                    : 新世界任务本能执行状态::参数场景失效;
                return 结果;
            }
            参数场景 = 场景结果.参数场景;

            const auto 确认 = 确认任务进入待执行(
                请求.任务节点, 请求.方法节点,
                请求.配对节点, 请求.结果节点);
            if (确认 != 新世界任务待执行确认状态::已确认) {
                结果.状态 = 确认 == 新世界任务待执行确认状态::资源失败
                    ? 新世界任务本能执行状态::资源失败
                    : (确认 == 新世界任务待执行确认状态::任务状态已变化
                        ? 新世界任务本能执行状态::任务状态已变化
                        : 新世界任务本能执行状态::定位已变化);
                return 结果;
            }

            const auto 开始时间 = 当前实例UTC强时间();
            if (!开始时间) {
                结果.状态 = 新世界任务本能执行状态::执行开始失败;
                return 结果;
            }
            开始前任务 = 任务服务_.获取任务(请求.任务节点);
            if (!开始前任务
                || 开始前任务->当前状态 != 新任务状态::待执行) {
                结果.状态 = 新世界任务本能执行状态::结构不一致;
                return 结果;
            }
            结果.执行开始 = 任务服务_.开始方法执行({
                请求.任务节点, 请求.方法节点,
                *开始时间, 请求.预计变化阶段组,
                请求.结果获取方案});
            if (结果.执行开始->状态 != 新任务操作状态::已开始执行
                || !结果.执行开始->执行实例节点) {
                if (结果.执行开始->执行实例节点) {
                    结果.状态 = 新世界任务本能执行状态::已开始但无法收束;
                } else if (结果.执行开始->状态
                    == 新任务操作状态::任务状态不允许) {
                    结果.状态 = 新世界任务本能执行状态::任务状态已变化;
                } else if (结果.执行开始->状态 == 新任务操作状态::资源失败) {
                    结果.状态 = 新世界任务本能执行状态::资源失败;
                } else {
                    结果.状态 = 新世界任务本能执行状态::执行开始失败;
                }
                return 结果;
            }
        }

        // 外部动作入口可能阻塞或回调其它宿主；不得持有世界树聚合锁。
        结果.方法调用 = 方法服务_.调用本能函数(
            请求.方法节点, *参数场景);

        const auto 撤销未进入动作 = [&]() noexcept {
            if (!开始前任务 || !结果.执行开始
                || !结果.执行开始->执行实例节点) return false;
            结果.未进入动作撤销状态 =
                任务服务_.撤销未进入动作执行({
                    请求.任务节点,
                    *结果.执行开始->执行实例节点,
                    开始前任务->最近方法节点,
                    开始前任务->最近执行实例节点});
            return *结果.未进入动作撤销状态
                    == 新任务操作状态::已修改
                || *结果.未进入动作撤销状态
                    == 新任务操作状态::精确重复;
        };

        const bool 已调用 = 结果.方法调用->状态
                == 新方法本能调用状态::已调用
            && 结果.方法调用->函数结果.has_value();
        if (!已调用) {
            结果.状态 = 撤销未进入动作()
                ? 新世界任务本能执行状态::动作未进入
                : 新世界任务本能执行状态::已开始但无法收束;
            return 结果;
        }
        const auto& 函数结果 = *结果.方法调用->函数结果;
        if (函数结果.动作阶段 == 新本能函数动作阶段::未进入动作) {
            if (!函数结果.已形成状态节点组.empty()
                || !函数结果.已形成动态节点组.empty()
                || !撤销未进入动作()) {
                结果.状态 = 新世界任务本能执行状态::已开始但无法收束;
                return 结果;
            }
            结果.状态 = 函数结果.状态
                    == 新本能函数执行状态::依赖未装配
                ? 新世界任务本能执行状态::执行依赖未就绪
                : 新世界任务本能执行状态::动作未进入;
            return 结果;
        }
        if (!函数结果.已形成状态节点组.empty()) {
            结果.动作输出记录状态 = 任务服务_.记录方法动作输出(
                请求.任务节点, *结果.执行开始->执行实例节点,
                函数结果.已形成状态节点组);
            if (*结果.动作输出记录状态 != 新任务操作状态::已修改
                && *结果.动作输出记录状态 != 新任务操作状态::精确重复) {
                结果.状态 = *结果.动作输出记录状态
                        == 新任务操作状态::资源失败
                    ? 新世界任务本能执行状态::资源失败
                    : 新世界任务本能执行状态::已开始但无法收束;
                return 结果;
            }
        }
        结果.状态 = 函数结果.已形成状态节点组.empty()
            ? 新世界任务本能执行状态::动作已发出等待结果
            : 新世界任务本能执行状态::动作已发出且结果材料已具备;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 新世界任务本能执行状态::资源失败;
    } catch (...) {
        结果.状态 = 新世界任务本能执行状态::结构不一致;
    }
    return 结果;
}

新世界任务结果材料核验结果 新_世界树类::核验任务结果材料(
    稳定编码 任务节点,
    稳定编码 执行实例节点,
    const std::vector<稳定编码>& 状态节点组) const noexcept {
    新世界任务结果材料核验结果 结果;
    if (!有效(任务节点) || !有效(执行实例节点)
        || 状态节点组.empty()) return 结果;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) return 结果;
        const auto 任务 = 任务服务_.获取任务(任务节点);
        const auto 执行 = 任务服务_.获取执行实例(执行实例节点);
        if (!任务 || !执行 || 执行->任务节点 != 任务节点
            || 任务->当前状态 != 新任务状态::执行中
            || 执行->状态 != 新任务执行状态::执行中) {
            结果.状态 = 新世界任务结果材料核验状态::任务或执行已变化;
            return 结果;
        }

        struct 已读状态 final {
            稳定编码 节点;
            新状态信息 信息;
            稳定编码 特征类型根;
        };
        std::vector<已读状态> 已读组;
        std::set<std::uint64_t> 已见;
        for (const auto 状态节点 : 状态节点组) {
            if (!有效(状态节点) || !已见.insert(状态节点.值).second) continue;
            const auto 状态 = 状态服务_.获取状态(状态节点);
            if (!状态 || 状态->强时间.语义 != 执行->开始时间.语义
                || 状态->强时间.纳秒 < 执行->开始时间.纳秒) continue;
            const auto 类型根 = 取得特征概念类型根(
                特征概念服务_, 状态->特征类型概念节点);
            if (!类型根) {
                结果.状态 = 新世界任务结果材料核验状态::结构不一致;
                return 结果;
            }
            bool 相关 = false;
            for (const auto& 目标 : 执行->结果获取方案.目标组) {
                const auto 实际特征 = 特征服务_.获取特征(
                    目标.实际特征节点);
                if (!实际特征) {
                    结果.状态 = 新世界任务结果材料核验状态::结构不一致;
                    return 结果;
                }
                if (目标.作用对象节点 == 状态->被描述存在节点
                    && 目标.实际特征节点
                        == 状态->来源实例特征节点
                    && 目标.特征类型根概念节点 == *类型根
                    && 实际特征->特征概念节点
                        == 状态->特征类型概念节点) {
                    相关 = true;
                    break;
                }
            }
            if (相关) 已读组.push_back({状态节点, *状态, *类型根});
        }
        if (已读组.empty()) {
            结果.状态 = 新世界任务结果材料核验状态::与本次执行无关;
            return 结果;
        }
        for (const auto& 状态 : 已读组) {
            结果.已接受状态节点组.push_back(状态.节点);
        }
        std::sort(结果.已接受状态节点组.begin(),
            结果.已接受状态节点组.end());

        for (const auto& 目标 : 执行->结果获取方案.目标组) {
            if (!目标.必须出现) continue;
            const auto 实际特征 = 特征服务_.获取特征(
                目标.实际特征节点);
            if (!实际特征) {
                结果.状态 = 新世界任务结果材料核验状态::结构不一致;
                return 结果;
            }
            const bool 已具备 = std::any_of(
                已读组.begin(), 已读组.end(), [&](const 已读状态& 状态) {
                    return 状态.信息.被描述存在节点 == 目标.作用对象节点
                        && 状态.信息.来源实例特征节点
                            == 目标.实际特征节点
                        && 状态.特征类型根
                            == 目标.特征类型根概念节点
                        && 状态.信息.特征类型概念节点
                            == 实际特征->特征概念节点;
                });
            if (!已具备) {
                结果.状态 = 新世界任务结果材料核验状态::已接受但仍不足;
                return 结果;
            }
        }
        结果.状态 = 新世界任务结果材料核验状态::材料已足够;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 新世界任务结果材料核验状态::资源失败;
    } catch (...) {
        结果.状态 = 新世界任务结果材料核验状态::结构不一致;
    }
    return 结果;
}

新世界任务结果材料核验结果 新_世界树类::查找任务结果材料(
    稳定编码 任务节点,
    稳定编码 执行实例节点) const noexcept {
    新世界任务结果材料核验结果 结果;
    if (!有效(任务节点) || !有效(执行实例节点)) return 结果;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) return 结果;
        const auto 任务 = 任务服务_.获取任务(任务节点);
        const auto 执行 = 任务服务_.获取执行实例(执行实例节点);
        if (!任务 || !执行 || 执行->任务节点 != 任务节点
            || 任务->当前状态 != 新任务状态::执行中
            || 执行->状态 != 新任务执行状态::执行中) {
            结果.状态 = 新世界任务结果材料核验状态::任务或执行已变化;
            return 结果;
        }

        std::set<std::uint64_t> 已见状态;
        std::vector<稳定编码> 候选状态组;
        for (const auto& 目标 : 执行->结果获取方案.目标组) {
            for (const auto 状态节点 :
                    状态服务_.按实例特征查询状态(目标.实际特征节点)) {
                if (有效(状态节点) && 已见状态.insert(状态节点.值).second) {
                    候选状态组.push_back(状态节点);
                }
            }
        }
        if (候选状态组.empty()) {
            结果.状态 = 新世界任务结果材料核验状态::与本次执行无关;
            return 结果;
        }
        return 核验任务结果材料(
            任务节点, 执行实例节点, 候选状态组);
    } catch (const std::bad_alloc&) {
        结果.状态 = 新世界任务结果材料核验状态::资源失败;
    } catch (...) {
        结果.状态 = 新世界任务结果材料核验状态::结构不一致;
    }
    return 结果;
}

新世界任务结果获取结果 新_世界树类::获取任务本能结果(
    const 新世界任务结果获取请求& 请求) noexcept {
    新世界任务结果获取结果 结果;
    结果.原请求 = 请求;
    if (!请求.完整()) {
        结果.状态 = 新世界任务结果获取状态::等待结果材料;
        return 结果;
    }
    try {
        const auto 当前结束时间 = 当前实例UTC强时间();
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) return 结果;
        const auto 执行 = 任务服务_.获取执行实例(请求.执行实例节点);
        if (!执行 || 执行->任务节点 != 请求.任务节点) return 结果;
        if (执行->状态 == 新任务执行状态::执行中) {
            const auto 材料核验 = 核验任务结果材料(
                请求.任务节点, 请求.执行实例节点, 请求.状态节点组);
            if (材料核验.状态
                    != 新世界任务结果材料核验状态::材料已足够) {
                结果.状态 = 材料核验.状态
                        == 新世界任务结果材料核验状态::资源失败
                    ? 新世界任务结果获取状态::资源失败
                    : (材料核验.状态
                            == 新世界任务结果材料核验状态::任务或执行已变化
                        ? 新世界任务结果获取状态::任务状态已变化
                        : (材料核验.状态
                                == 新世界任务结果材料核验状态::结构不一致
                            ? 新世界任务结果获取状态::结构不一致
                            : 新世界任务结果获取状态::等待结果材料));
                return 结果;
            }
            auto 已接受状态 = 材料核验.已接受状态节点组;
            auto 请求状态 = 请求.状态节点组;
            std::sort(已接受状态.begin(), 已接受状态.end());
            std::sort(请求状态.begin(), 请求状态.end());
            if (已接受状态 != 请求状态) {
                结果.状态 = 新世界任务结果获取状态::结构不一致;
                return 结果;
            }
            if (!当前结束时间) {
                结果.状态 = 新世界任务结果获取状态::资源失败;
                return 结果;
            }
            if (当前结束时间->纳秒 < 执行->开始时间.纳秒) {
                结果.状态 = 新世界任务结果获取状态::结构不一致;
                return 结果;
            }
            结果.执行结束状态 = 任务服务_.结束方法执行({
                请求.任务节点, 请求.执行实例节点,
                *当前结束时间, 请求.状态节点组});
        } else if (执行->状态 == 新任务执行状态::已结束待评估) {
            auto 已有状态 = 执行->实际状态节点组;
            auto 请求状态 = 请求.状态节点组;
            std::sort(已有状态.begin(), 已有状态.end());
            std::sort(请求状态.begin(), 请求状态.end());
            结果.执行结束状态 = 已有状态 == 请求状态
                ? 新任务操作状态::精确重复
                : 新任务操作状态::任务状态不允许;
        } else {
            结果.执行结束状态 = 新任务操作状态::任务状态不允许;
        }
        if (*结果.执行结束状态 != 新任务操作状态::已结束执行
            && *结果.执行结束状态 != 新任务操作状态::精确重复) {
            结果.状态 = *结果.执行结束状态
                    == 新任务操作状态::任务状态不允许
                ? 新世界任务结果获取状态::任务状态已变化
                : (*结果.执行结束状态 == 新任务操作状态::资源失败
                    ? 新世界任务结果获取状态::资源失败
                    : 新世界任务结果获取状态::执行结束失败);
            return 结果;
        }
        结果.影响评估 = 任务服务_.评估方法执行影响(
            请求.任务节点, 请求.执行实例节点);
        if (结果.影响评估->状态 != 新任务操作状态::已完成评估
            && 结果.影响评估->状态 != 新任务操作状态::精确重复) {
            结果.状态 = 结果.影响评估->状态
                    == 新任务操作状态::资源失败
                ? 新世界任务结果获取状态::资源失败
                : 新世界任务结果获取状态::影响评估失败;
            return 结果;
        }
        结果.状态 = 新世界任务结果获取状态::已完成影响评估;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 新世界任务结果获取状态::资源失败;
    } catch (...) {
        结果.状态 = 新世界任务结果获取状态::结构不一致;
    }
    return 结果;
}

新世界任务执行读回结果 新_世界树类::读回任务执行(
    稳定编码 任务节点,
    稳定编码 执行实例节点) const noexcept {
    新世界任务执行读回结果 结果;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) return 结果;
        结果.任务 = 任务服务_.获取任务(任务节点);
        结果.执行 = 任务服务_.获取执行实例(执行实例节点);
        if (!结果.任务 || !结果.执行) {
            结果.状态 = 新世界任务执行读回状态::任务或执行不存在;
            return 结果;
        }
        if (结果.执行->任务节点 != 任务节点
            || !结果.任务->最近执行实例节点
            || *结果.任务->最近执行实例节点 != 执行实例节点
            || !结果.任务->最近方法节点
            || *结果.任务->最近方法节点 != 结果.执行->方法节点) {
            return 结果;
        }
        if (结果.执行->状态 == 新任务执行状态::执行中
            && 结果.任务->当前状态 == 新任务状态::执行中
            && !结果.执行->影响评估节点) {
            结果.状态 = 新世界任务执行读回状态::已读回等待观察;
            return 结果;
        }
        if (结果.执行->状态 == 新任务执行状态::已结束待评估
            && 结果.任务->当前状态 == 新任务状态::待影响评估
            && !结果.执行->影响评估节点) {
            结果.状态 = 新世界任务执行读回状态::已读回等待评估;
            return 结果;
        }
        if (结果.执行->状态 == 新任务执行状态::已评估
            && (结果.任务->当前状态 == 新任务状态::等待自我决议
                || (结果.任务->当前状态 == 新任务状态::已完成
                    && !结果.任务->完成结算节点))
            && 结果.执行->影响评估节点) {
            结果.影响评估 = 任务服务_.获取影响评估(
                *结果.执行->影响评估节点);
            if (结果.影响评估
                && 结果.影响评估->任务节点 == 任务节点
                && 结果.影响评估->执行实例节点 == 执行实例节点) {
                结果.状态 = 新世界任务执行读回状态::已读回影响评估;
            }
        }
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 新世界任务执行读回状态::资源失败;
    } catch (...) {
        结果.状态 = 新世界任务执行读回状态::结构不一致;
    }
    return 结果;
}

