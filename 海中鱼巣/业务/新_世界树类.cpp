新世界初始化结果 新_世界树类::初始化() noexcept {
    新世界初始化结果 结果;
    try {
        std::lock_guard 锁(新世界树互斥);
        const bool 依赖完整 = 特征值服务_.初始化()
            && 特征概念服务_.初始化(特征值服务_)
            && 特征服务_.初始化()
            && 二次特征概念服务_.初始化()
            && 存在概念服务_.初始化()
            && 语言服务_.初始化()
            && 词服务_.初始化()
            && 名称关系服务_.初始化()
            && 状态服务_.初始化()
            && 存在服务_.初始化()
            && 动态概念服务_.初始化()
            && 动态服务_.初始化()
            && 场景服务_.初始化()
            && 因果服务_.初始化();
        if (!依赖完整) {
            结果.状态 = 新世界初始化状态::依赖初始化失败;
            return 结果;
        }
        const auto 根结果 = 场景服务_.建立根场景();
        if (根结果.状态 != 新场景操作状态::已完成
            && 根结果.状态 != 新场景操作状态::无变化) {
            结果.状态 = 根结果.状态 == 新场景操作状态::结构不一致
                ? 新世界初始化状态::结构不一致
                : 新世界初始化状态::根场景建立失败;
            return 结果;
        }
        if (!根结果.场景节点 || !根结果.专属存在概念节点) {
            结果.状态 = 新世界初始化状态::结构不一致;
            return 结果;
        }
        已初始化_ = true;
        结果.状态 = 根结果.状态 == 新场景操作状态::已完成
            ? 新世界初始化状态::已完成
            : 新世界初始化状态::无变化;
        结果.世界树根场景 = 根结果.场景节点;
        结果.根场景专属存在概念 = 根结果.专属存在概念节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新世界初始化状态::资源失败;
        return 结果;
    }
}

