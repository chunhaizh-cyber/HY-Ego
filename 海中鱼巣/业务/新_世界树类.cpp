新世界任务后继发布结果 新_世界树类::发布自我任务后继决议(
    const 新自我任务后继决议& 决议) noexcept {
    新世界任务后继发布结果 结果;
    结果.决议 = 决议;
    if (!有效(决议.任务节点) || !有效(决议.执行实例节点)
        || !有效(决议.影响评估节点)) return 结果;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) return 结果;
        const auto 任务 = 任务服务_.获取任务(决议.任务节点);
        const auto 执行 = 任务服务_.获取执行实例(决议.执行实例节点);
        const auto 评估 = 任务服务_.获取影响评估(决议.影响评估节点);
        if (!任务 || !执行 || !评估) {
            结果.状态 = 新世界任务后继发布状态::定位已变化;
            return 结果;
        }
        if (执行->任务节点 != 决议.任务节点
            || 评估->任务节点 != 决议.任务节点
            || 评估->执行实例节点 != 决议.执行实例节点
            || !执行->影响评估节点
            || *执行->影响评估节点 != 决议.影响评估节点
            || !任务->最近执行实例节点
            || *任务->最近执行实例节点 != 决议.执行实例节点) {
            结果.状态 = 新世界任务后继发布状态::定位已变化;
            return 结果;
        }
        if (决议.类型 == 新自我任务后继类型::完成
            && !评估->允许形成完成决议()) {
            // manager不能只凭self传来的枚举发布完成；必须重新读回同一A并
            // 证明完整结果闭包允许完成。
            结果.状态 = 新世界任务后继发布状态::状态发布失败;
            return 结果;
        }
        新任务状态 目标状态 = 新任务状态::等待条件;
        switch (决议.类型) {
        case 新自我任务后继类型::完成:
            目标状态 = 新任务状态::已完成; break;
        case 新自我任务后继类型::继续:
        case 新自我任务后继类型::重试:
        case 新自我任务后继类型::重新筹办:
            目标状态 = 新任务状态::待查找方法; break;
        case 新自我任务后继类型::等待:
            目标状态 = 新任务状态::等待条件; break;
        case 新自我任务后继类型::失败:
            目标状态 = 新任务状态::已失败; break;
        case 新自我任务后继类型::取消:
            目标状态 = 新任务状态::已取消; break;
        }
        if (任务->当前状态 == 目标状态) {
            结果.状态 = 新世界任务后继发布状态::精确重复;
            结果.任务 = 任务;
            return 结果;
        }
        if (任务->当前状态 != 新任务状态::等待自我决议
            || 执行->状态 != 新任务执行状态::已评估) {
            结果.状态 = 新世界任务后继发布状态::任务状态已变化;
            return 结果;
        }
        const auto 写入 = 任务服务_.修改任务状态(
            决议.任务节点, 目标状态);
        if (写入 != 新任务操作状态::已修改
            && 写入 != 新任务操作状态::无变化) {
            结果.状态 = 写入 == 新任务操作状态::资源失败
                ? 新世界任务后继发布状态::资源失败
                : 新世界任务后继发布状态::状态发布失败;
            return 结果;
        }
        结果.任务 = 任务服务_.获取任务(决议.任务节点);
        if (!结果.任务 || 结果.任务->当前状态 != 目标状态) {
            结果.状态 = 新世界任务后继发布状态::结构不一致;
            return 结果;
        }
        结果.状态 = 写入 == 新任务操作状态::无变化
            ? 新世界任务后继发布状态::精确重复
            : 新世界任务后继发布状态::已发布并读回;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 新世界任务后继发布状态::资源失败;
    } catch (...) {
        结果.状态 = 新世界任务后继发布状态::结构不一致;
    }
    return 结果;
}

