bool 是I64最大值单点概念(
    const 概念_特征类& 特征概念服务,
    稳定编码 概念节点) noexcept {
    const auto 概念 = 特征概念服务.获取特征概念(概念节点);
    if (!概念 || 概念->材料类型 != 特征概念材料物理类型::I64标量) {
        return false;
    }
    const auto* 区间组 = std::get_if<std::vector<特征概念I64闭区间>>(
        &概念->值域);
    constexpr auto 最大值 = (std::numeric_limits<std::int64_t>::max)();
    return 区间组 && 区间组->size() == 1
        && 区间组->front().下界 == 最大值
        && 区间组->front().上界 == 最大值;
}

std::optional<std::int64_t> 读取非负I64当前值(
    const 新_特征类& 特征服务,
    稳定编码 特征节点) noexcept {
    const auto 特征 = 特征服务.获取特征(特征节点);
    if (!特征 || !特征->当前值) return std::nullopt;
    const auto* 值 = std::get_if<std::int64_t>(&*特征->当前值);
    return 值 && *值 >= 0 ? std::optional<std::int64_t>{*值} : std::nullopt;
}

enum class 预计变化方向 : std::uint8_t {
    增加 = 1,
    减少,
    不变,
    不明确
};

std::optional<稳定编码> 取得特征概念类型根(
    const 概念_特征类& 服务,
    稳定编码 概念节点) noexcept {
    const auto 关系 = 服务.比较单特征概念(概念节点, 概念节点);
    return 关系.状态 == 特征概念规则状态::已完成
            && 关系.关系 == 单特征概念关系::同一
        ? 关系.特征类型根 : std::nullopt;
}

预计变化方向 读取预计变化方向(
    const 概念_二次特征类& 服务,
    稳定编码 方向概念节点) noexcept {
    const auto 概念 = 服务.获取二次特征概念(方向概念节点);
    if (!概念 || 概念->算法 != 二次特征算法::有向特征差值
        || 概念->参照特征概念节点) {
        return 预计变化方向::不明确;
    }
    bool 可增加 = false, 可减少 = false, 可不变 = false;
    auto 关系组 = 概念->结果域种类组;
    if (关系组.empty()) 关系组.push_back(二次特征结果域种类::任意);
    for (const auto 关系 : 关系组) {
        switch (关系) {
        case 二次特征结果域种类::大于:
            可增加 = true; break;
        case 二次特征结果域种类::大于等于:
            可增加 = true; 可不变 = true; break;
        case 二次特征结果域种类::等于:
            可不变 = true; break;
        case 二次特征结果域种类::小于等于:
            可减少 = true; 可不变 = true; break;
        case 二次特征结果域种类::小于:
            可减少 = true; break;
        case 二次特征结果域种类::任意:
            可增加 = 可减少 = 可不变 = true; break;
        default:
            return 预计变化方向::不明确;
        }
    }
    if (可增加 && !可减少 && !可不变) return 预计变化方向::增加;
    if (可减少 && !可增加 && !可不变) return 预计变化方向::减少;
    if (可不变 && !可增加 && !可减少) return 预计变化方向::不变;
    return 预计变化方向::不明确;
}

bool 预计值域保证命中目标(
    const 概念_特征类& 服务,
    稳定编码 目标值域概念,
    稳定编码 预计值域概念,
    bool& 结构有效) noexcept {
    结构有效 = false;
    const auto 目标 = 服务.获取特征概念(目标值域概念);
    const auto 预计 = 服务.获取特征概念(预计值域概念);
    const auto 目标根 = 取得特征概念类型根(服务, 目标值域概念);
    const auto 预计根 = 取得特征概念类型根(服务, 预计值域概念);
    if (!目标 || !预计 || !目标根 || !预计根 || *目标根 != *预计根
        || 目标->材料类型 != 预计->材料类型) return false;
    const auto 比较 = 服务.比较值域(
        目标->材料类型, 目标->值域, 预计->值域);
    if (比较.状态 != 特征概念规则状态::已完成 || !比较.关系) return false;
    结构有效 = true;
    return *比较.关系 == 特征概念值域关系::相等
        || *比较.关系 == 特征概念值域关系::左包含右;
}

std::optional<新状态强时间> 当前实例UTC强时间() noexcept {
    try {
        const auto 计数 = std::chrono::duration_cast<std::chrono::nanoseconds>(
            std::chrono::system_clock::now().time_since_epoch()).count();
        if (计数 < 0
            || static_cast<std::uintmax_t>(计数)
                > static_cast<std::uintmax_t>(
                    (std::numeric_limits<std::int64_t>::max)())) {
            return std::nullopt;
        }
        return 新状态强时间{
            新状态时间语义::实例绝对UTC,
            static_cast<std::int64_t>(计数)};
    } catch (...) {
        return std::nullopt;
    }
}

