bool 新世界动态发布结果::成功() const noexcept {
    return 状态 == 新世界动态发布状态::已完成并保留实例概念
        || 状态 == 新世界动态发布状态::已完成并采用已有概念
        || 状态 == 新世界动态发布状态::已完成并形成上位概念
        || 状态 == 新世界动态发布状态::已完成且已有聚合概念;
}

bool 新世界本能双根初始化结果::成功() const noexcept {
    return (状态 == 新世界本能双根初始化状态::已建立
            || 状态 == 新世界本能双根初始化状态::已复用)
        && 安全实际特征节点.has_value()
        && 服务实际特征节点.has_value()
        && 需求双根结果.has_value()
        && (需求双根结果->状态 == 新需求操作状态::已建立
            || 需求双根结果->状态 == 新需求操作状态::已复用)
        && 需求双根结果->安全根.has_value()
        && 需求双根结果->服务根.has_value()
        && 需求双根结果->安全根列表项.has_value()
        && 需求双根结果->服务根列表项.has_value()
        && 有效(*安全实际特征节点)
        && 有效(*服务实际特征节点)
        && *安全实际特征节点 != *服务实际特征节点
        && 有效(*需求双根结果->安全根)
        && 有效(*需求双根结果->服务根)
        && *需求双根结果->安全根 != *需求双根结果->服务根
        && 有效(*需求双根结果->安全根列表项)
        && 有效(*需求双根结果->服务根列表项)
        && *需求双根结果->安全根列表项
            != *需求双根结果->服务根列表项;
}

