新世界本能需求复核结果 新_世界树类::复核自我本能需求(
    稳定编码 自我存在, 稳定编码 安全需求, 稳定编码 服务需求,
    std::optional<稳定编码> 来源状态) const noexcept {
    新世界本能需求复核结果 结果;
    结果.自我存在 = 自我存在;
    结果.安全需求 = 安全需求;
    结果.服务需求 = 服务需求;
    结果.来源状态 = 来源状态;
    try {
        // 仅保证经世界树入口的读写不交错；不声称阻止直接领域调用。
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_) {
            结果.状态 = 新世界需求复核状态::世界树未初始化;
            return 结果;
        }
        const auto 自我 = 存在服务_.获取存在(自我存在);
        const auto 安全 = 需求服务_.获取需求(安全需求);
        const auto 服务 = 需求服务_.获取需求(服务需求);
        if (!自我 || !安全 || !服务 || 安全需求 == 服务需求
            || 需求服务_.查询根需求(新需求根角色::安全) != 安全需求
            || 需求服务_.查询根需求(新需求根角色::服务) != 服务需求
            || 安全->根角色 != 新需求根角色::安全
            || 服务->根角色 != 新需求根角色::服务
            || !安全->根实际特征节点 || !服务->根实际特征节点
            || 安全->根实际特征节点 == 服务->根实际特征节点
            || std::find(自我->特征节点组.begin(), 自我->特征节点组.end(),
                *安全->根实际特征节点) == 自我->特征节点组.end()
            || std::find(自我->特征节点组.begin(), 自我->特征节点组.end(),
                *服务->根实际特征节点) == 自我->特征节点组.end()) {
            return 结果;
        }
        if (来源状态) {
            const auto 来源 = 状态服务_.获取状态(*来源状态);
            // S1只接纳自我特征变化。状态中的概念可能已细化或被回收，
            // 不以它猜测当前类型，也不消费其过去的固定准确值。
            if (!来源 || 来源->被描述存在节点 != 自我存在
                || 来源->强时间.语义 != 新状态时间语义::实例绝对UTC
                || 来源->强时间.纳秒 < 0) {
                结果.状态 = 新世界需求复核状态::来源状态不存在;
                return 结果;
            }
        }
        结果.安全结果 = 需求服务_.复核当前满足(安全需求);
        结果.服务结果 = 需求服务_.复核当前满足(服务需求);
        const auto 安全当前 = 读取非负I64当前值(
            特征服务_, *安全->根实际特征节点);
        const auto 服务当前 = 读取非负I64当前值(
            特征服务_, *服务->根实际特征节点);
        if (!安全当前 || !服务当前
            || !是I64最大值单点概念(
                特征概念服务_, 安全->目标.目标值域概念节点)
            || !是I64最大值单点概念(
                特征概念服务_, 服务->目标.目标值域概念节点)) {
            结果.状态 = 新世界需求复核状态::需求比较失败;
            return 结果;
        }
        constexpr auto 最大值 = (std::numeric_limits<std::int64_t>::max)();
        const auto 根结果一致 = [最大值](
            std::int64_t 当前,
            const 新需求当前满足结果& 根结果) noexcept {
            if (当前 == 最大值) {
                return 根结果.状态 == 新需求当前满足状态::已满足
                    && 根结果.准确差异 == 0;
            }
            return 根结果.状态 == 新需求当前满足状态::需增加
                && 根结果.准确差异 == 最大值 - 当前;
        };
        if (!根结果一致(*安全当前, *结果.安全结果)
            || !根结果一致(*服务当前, *结果.服务结果)) {
            结果.状态 = 新世界需求复核状态::需求比较失败;
            return 结果;
        }
        const auto 安全状态 = 结果.安全结果->状态;
        const auto 服务状态 = 结果.服务结果->状态;
        const auto 比较错误 = [](新需求当前满足状态 状态) noexcept {
            switch (状态) {
            case 新需求当前满足状态::已满足:
            case 新需求当前满足状态::需增加:
            case 新需求当前满足状态::未满足但无有向差值:
            case 新需求当前满足状态::当前值不存在:
            case 新需求当前满足状态::目标特征尚未形成:
            case 新需求当前满足状态::资源失败:
                return false;
            default:
                return true;
            }
        };
        if (安全状态 == 新需求当前满足状态::结构不一致
            || 服务状态 == 新需求当前满足状态::结构不一致
            || 安全状态 == 新需求当前满足状态::需求不存在
            || 服务状态 == 新需求当前满足状态::需求不存在) {
            结果.状态 = 新世界需求复核状态::自我或根关系不一致;
        } else if (比较错误(安全状态) || 比较错误(服务状态)) {
            // 永久错误优先，不能被另一根的资源失败掩盖为无限重试。
            结果.状态 = 新世界需求复核状态::需求比较失败;
        } else if (安全状态 == 新需求当前满足状态::资源失败
            || 服务状态 == 新需求当前满足状态::资源失败) {
            结果.状态 = 新世界需求复核状态::资源失败;
        } else if (安全状态 == 新需求当前满足状态::当前值不存在
            || 服务状态 == 新需求当前满足状态::当前值不存在
            || 安全状态 == 新需求当前满足状态::目标特征尚未形成
            || 服务状态 == 新需求当前满足状态::目标特征尚未形成) {
            结果.状态 = 新世界需求复核状态::需求材料未就绪;
        } else {
            结果.状态 = 新世界需求复核状态::已复核;
        }
        return 结果;
    } catch (...) {
        结果.状态 = 新世界需求复核状态::资源失败;
        return 结果;
    }
}

bool 新_世界树类::初始化任务集合() noexcept {
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !有效(需求树根节点)) return false;
        任务集合已初始化_ = 任务服务_.初始化();
        return 任务集合已初始化_;
    } catch (...) { return false; }
}

新世界任务承接结果 新_世界树类::读回需求任务(
    稳定编码 需求节点, 稳定编码 任务节点) const noexcept {
    新世界任务承接结果 结果;
    结果.需求节点 = 需求节点;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) {
            结果.状态 = 新世界任务承接状态::尚未初始化;
            return 结果;
        }
        if (!需求服务_.获取需求(需求节点)) {
            结果.状态 = 新世界任务承接状态::需求不存在;
            return 结果;
        }
        结果.任务 = 任务服务_.获取任务(任务节点);
        结果.虚拟存在 = 任务服务_.获取任务虚拟存在(任务节点);
        const auto 集合 = 任务服务_.查询全部任务();
        if (集合.状态 == 新任务操作状态::资源失败) {
            结果.状态 = 新世界任务承接状态::资源失败;
            return 结果;
        }
        if (集合.状态 != 新任务操作状态::已找到 || !结果.任务 || !结果.虚拟存在
            || 任务服务_.查询需求任务(需求节点) != 任务节点
            || 结果.任务->节点 != 任务节点 || 结果.任务->需求节点 != 需求节点
            || 结果.任务->任务虚拟存在节点 != 结果.虚拟存在->节点
            || 结果.虚拟存在->任务节点 != 任务节点
            || 结果.任务->当前状态 != 结果.虚拟存在->当前状态
            || std::find(集合.任务节点组.begin(), 集合.任务节点组.end(), 任务节点)
                == 集合.任务节点组.end()) return 结果;
        const auto 状态 = 结果.任务->当前状态;
        结果.状态 = 状态 == 新任务状态::已完成 || 状态 == 新任务状态::已失败
                || 状态 == 新任务状态::已取消
            ? 新世界任务承接状态::既有终结任务 : 新世界任务承接状态::已读回;
        return 结果;
    } catch (...) {
        结果.状态 = 新世界任务承接状态::资源失败;
        return 结果;
    }
}

新世界任务承接结果 新_世界树类::承接需求任务(
    稳定编码 需求节点,
    bool 自我新鲜自动决议) noexcept {
    新世界任务承接结果 结果;
    结果.需求节点 = 需求节点;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_ || !任务集合已初始化_) {
            结果.状态 = 新世界任务承接状态::尚未初始化;
            return 结果;
        }
        if (!需求服务_.获取需求(需求节点)) {
            结果.状态 = 新世界任务承接状态::需求不存在;
            return 结果;
        }
        if (自我新鲜自动决议) {
            结果.当前复核 = 需求服务_.复核当前满足(需求节点);
            if (结果.当前复核->状态 == 新需求当前满足状态::已满足) {
                结果.状态 = 新世界任务承接状态::需求当前已满足;
                return 结果;
            }
            if (结果.当前复核->状态 != 新需求当前满足状态::需增加) {
                结果.状态 = 新世界任务承接状态::任务操作未完成;
                return 结果;
            }
        }
        结果.写入已尝试 = true;
        结果.建立结果 = 任务服务_.建立或取得任务(需求节点);
        const auto& 建立 = *结果.建立结果;
        if ((建立.状态 != 新任务操作状态::已建立 && 建立.状态 != 新任务操作状态::已复用)
            || !建立.任务节点 || !建立.任务虚拟存在节点) {
            结果.状态 = 新世界任务承接状态::任务操作未完成;
            return 结果;
        }
        auto 读回 = 读回需求任务(需求节点, *建立.任务节点);
        读回.写入已尝试 = true;
        读回.建立结果 = 建立;
        读回.当前复核 = 结果.当前复核;
        if (读回.虚拟存在 && 读回.虚拟存在->节点 != *建立.任务虚拟存在节点)
            读回.状态 = 新世界任务承接状态::读回不一致;
        if (读回.状态 != 新世界任务承接状态::既有终结任务
            || !自我新鲜自动决议) {
            return 读回;
        }

        // 旧消息本身不能复活任务。即使上层声明这是新鲜决议，仍在同一
        // 世界树串行区内重新读取当前需求，只接受根需求的正向缺口。
        读回.当前复核 = 需求服务_.复核当前满足(需求节点);
        if (读回.当前复核->状态 == 新需求当前满足状态::已满足) {
            读回.状态 = 新世界任务承接状态::需求当前已满足;
            return 读回;
        }
        if (读回.当前复核->状态 != 新需求当前满足状态::需增加) {
            读回.状态 = 新世界任务承接状态::任务操作未完成;
            return 读回;
        }
        读回.重新启用结果 = 任务服务_.重新启用任务(*建立.任务节点);
        if (*读回.重新启用结果 != 新任务操作状态::已修改) {
            读回.状态 = 新世界任务承接状态::任务操作未完成;
            return 读回;
        }
        auto 已重新启用 = 读回需求任务(需求节点, *建立.任务节点);
        已重新启用.写入已尝试 = true;
        已重新启用.建立结果 = 建立;
        已重新启用.当前复核 = 读回.当前复核;
        已重新启用.重新启用结果 = 读回.重新启用结果;
        if (已重新启用.状态 != 新世界任务承接状态::已读回
            || !已重新启用.任务
            || 已重新启用.任务->当前状态 != 新任务状态::待查找方法) {
            已重新启用.状态 = 新世界任务承接状态::读回不一致;
            return 已重新启用;
        }
        已重新启用.状态 = 新世界任务承接状态::已重新启用;
        return 已重新启用;
    } catch (...) {
        结果.状态 = 新世界任务承接状态::资源失败;
        return 结果;
    }
}

