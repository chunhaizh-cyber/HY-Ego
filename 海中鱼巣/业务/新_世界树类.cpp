新世界本能双根初始化结果
新_世界树类::建立或取得自我本能双根(
    稳定编码 自我存在节点,
    const 新世界本能双根定义& 定义) noexcept {
    新世界本能双根初始化结果 结果;
    try {
        std::lock_guard 锁(新世界树互斥);
        if (!已初始化_) {
            结果.状态 = 新世界本能双根初始化状态::世界树未初始化;
            return 结果;
        }
        if (!有效(自我存在节点)
            || !有效(定义.安全根.特征类型根概念节点)
            || !有效(定义.服务根.特征类型根概念节点)
            || !有效(定义.安全根.目标值域概念节点)
            || !有效(定义.服务根.目标值域概念节点)
            || !有效(定义.安全根.目标比较关系概念节点)
            || !有效(定义.服务根.目标比较关系概念节点)
            || 定义.安全根.初始权重 < 0
            || 定义.服务根.初始权重 < 0) {
            return 结果;
        }
        if (定义.安全根.特征类型根概念节点
                == 定义.服务根.特征类型根概念节点) {
            结果.状态 = 新世界本能双根初始化状态::双根定义冲突;
            return 结果;
        }
        const auto 自我 = 存在服务_.获取存在(自我存在节点);
        if (!自我) {
            结果.状态 = 新世界本能双根初始化状态::自我不存在;
            return 结果;
        }

        const auto 读取类型根 = [&](稳定编码 概念节点)
            -> std::optional<稳定编码> {
            const auto 关系 = 特征概念服务_.比较单特征概念(
                概念节点, 概念节点);
            if (关系.状态 != 特征概念规则状态::已完成
                || !关系.特征类型根) {
                return std::nullopt;
            }
            return 关系.特征类型根;
        };
        const auto 安全根 = 读取类型根(
            定义.安全根.特征类型根概念节点);
        const auto 服务根 = 读取类型根(
            定义.服务根.特征类型根概念节点);
        if (!安全根 || !服务根
            || *安全根 != 定义.安全根.特征类型根概念节点
            || *服务根 != 定义.服务根.特征类型根概念节点) {
            结果.状态 = 新世界本能双根初始化状态::特征类型根不合法;
            return 结果;
        }

        std::vector<稳定编码> 安全候选;
        std::vector<稳定编码> 服务候选;
        for (const auto 特征节点 : 自我->特征节点组) {
            const auto 特征 = 特征服务_.获取特征(特征节点);
            if (!特征) {
                结果.状态 = 新世界本能双根初始化状态::结构不一致;
                return 结果;
            }
            const auto 类型根 = 读取类型根(特征->特征概念节点);
            if (!类型根) {
                结果.状态 = 新世界本能双根初始化状态::结构不一致;
                return 结果;
            }
            if (*类型根 == *安全根) 安全候选.push_back(特征节点);
            if (*类型根 == *服务根) 服务候选.push_back(特征节点);
        }
        if (安全候选.empty()) {
            结果.状态 = 新世界本能双根初始化状态::安全特征不存在;
            return 结果;
        }
        if (服务候选.empty()) {
            结果.状态 = 新世界本能双根初始化状态::服务特征不存在;
            return 结果;
        }
        if (安全候选.size() != 1) {
            结果.状态 = 新世界本能双根初始化状态::安全特征不唯一;
            return 结果;
        }
        if (服务候选.size() != 1) {
            结果.状态 = 新世界本能双根初始化状态::服务特征不唯一;
            return 结果;
        }
        if (安全候选.front() == 服务候选.front()) {
            结果.状态 = 新世界本能双根初始化状态::双根定义冲突;
            return 结果;
        }
        if (!是I64最大值单点概念(
                特征概念服务_, 定义.安全根.目标值域概念节点)
            || !是I64最大值单点概念(
                特征概念服务_, 定义.服务根.目标值域概念节点)) {
            结果.状态 = 新世界本能双根初始化状态::根目标不是I64最大值;
            return 结果;
        }
        if (!读取非负I64当前值(特征服务_, 安全候选.front())
            || !读取非负I64当前值(特征服务_, 服务候选.front())) {
            结果.状态 = 新世界本能双根初始化状态::根当前值不合法;
            return 结果;
        }
        结果.安全实际特征节点 = 安全候选.front();
        结果.服务实际特征节点 = 服务候选.front();
        结果.需求双根结果 = 需求服务_.建立或取得本能双根({
            {安全候选.front(), 定义.安全根.目标值域概念节点,
                定义.安全根.目标比较关系概念节点,
                定义.安全根.初始权重},
            {服务候选.front(), 定义.服务根.目标值域概念节点,
                定义.服务根.目标比较关系概念节点,
                定义.服务根.初始权重}});
        switch (结果.需求双根结果->状态) {
        case 新需求操作状态::已建立:
            结果.状态 = 新世界本能双根初始化状态::已建立;
            break;
        case 新需求操作状态::已复用:
            结果.状态 = 新世界本能双根初始化状态::已复用;
            break;
        case 新需求操作状态::双根定义冲突:
        case 新需求操作状态::权重不合法:
            结果.状态 = 新世界本能双根初始化状态::双根定义冲突;
            break;
        case 新需求操作状态::结构不一致:
        case 新需求操作状态::尚未初始化:
            结果.状态 = 新世界本能双根初始化状态::结构不一致;
            break;
        case 新需求操作状态::资源失败:
            结果.状态 = 新世界本能双根初始化状态::资源失败;
            break;
        default:
            结果.状态 = 新世界本能双根初始化状态::需求双根建立失败;
            break;
        }
        return 结果;
    } catch (...) {
        结果.状态 = 新世界本能双根初始化状态::资源失败;
        return 结果;
    }
}

