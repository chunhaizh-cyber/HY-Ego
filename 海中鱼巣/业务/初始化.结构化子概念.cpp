初始化结构化子概念结果 初始化结构化子概念(
    const 初始化结构化子概念请求& 请求,
    const 新_语言类& 语言服务, 概念_特征类& 特征概念服务,
    const 新_特征值类& 特征值服务, 新_词类& 词服务,
    概念_名称关系类& 名称服务) {
    初始化结构化子概念结果 结果;
    子概念筹备材料 筹备;
    if (!准备结构化子概念(请求, 语言服务, 特征概念服务, false, 结果, 筹备)) return 结果;
    for (std::size_t i = 0; i < 结果.子概念组.size(); ++i) {
        auto& 项 = 结果.子概念组[i];
        结果.当前声明编号 = 项.声明编号;
        结果.阶段 = 初始化结构化子概念阶段::概念建立;
        项.建立调用身份 = 特征概念服务.建立或取得特征概念(
            项.完整定义, 特征值服务, 项.直接父概念);
        if (!项.建立调用身份->值) {
            (void)停止初始化(结果, 初始化结构化子概念状态::概念建立未完成,
                "明确父下建立或取得未返回有效身份；不进入名称");
            return 结果;
        }
        结果.阶段 = 初始化结构化子概念阶段::写后直接子查询;
        项.写后匹配 = 特征概念服务.查询直接子特征概念(项.直接父概念, 项.完整定义);
        if (项.写后匹配->状态 != 特征概念直接子查询状态::已完成
            || 项.写后匹配->子概念节点组.size() != 1
            || 项.写后匹配->子概念节点组.front() != *项.建立调用身份) {
            (void)停止初始化(结果, 初始化结构化子概念状态::直接子查询未完成,
                "写后完整直接子查询不能唯一证明实际建立返回身份");
            return 结果;
        }
        if (!读取确认身份(特征概念服务, *项.建立调用身份, 结果, 项)) return 结果;
        追加确认符号绑定(结果, 项, 筹备.项组[i]);
    }
    结果.阶段 = 初始化结构化子概念阶段::名称处理;
    const auto 命名请求 = 形成子概念名称请求(请求, 结果, 筹备);
    结果.名称结果 = 发布已确认特征概念名称(命名请求, 语言服务, 词服务, 名称服务, 特征概念服务);
    完成名称处理(结果);
    return 结果;
}

初始化结构化子概念结果 读取结构化子概念(
    const 初始化结构化子概念请求& 请求,
    const 新_语言类& 语言服务, const 概念_特征类& 特征概念服务,
    const 新_词类& 词服务, const 概念_名称关系类& 名称服务) {
    初始化结构化子概念结果 结果;
    子概念筹备材料 筹备;
    if (!准备结构化子概念(请求, 语言服务, 特征概念服务, true, 结果, 筹备)) return 结果;
    for (std::size_t i = 0; i < 结果.子概念组.size(); ++i) {
        auto& 项 = 结果.子概念组[i];
        结果.当前声明编号 = 项.声明编号;
        const auto 身份 = 项.写前匹配->子概念节点组.front();
        if (!读取确认身份(特征概念服务, 身份, 结果, 项)) return 结果;
        追加确认符号绑定(结果, 项, 筹备.项组[i]);
    }
    结果.阶段 = 初始化结构化子概念阶段::名称处理;
    const auto 命名请求 = 形成子概念名称请求(请求, 结果, 筹备);
    结果.名称结果 = 读取已确认特征概念名称(命名请求, 语言服务, 词服务, 名称服务, 特征概念服务);
    完成名称处理(结果);
    return 结果;
}

