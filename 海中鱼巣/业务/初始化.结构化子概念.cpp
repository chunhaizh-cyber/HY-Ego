struct 子概念名称来源 final {
    std::string 词面;
    初始化源范围 范围;
    std::size_t 定义编号 = 0;
};
struct 子概念筹备项 final {
    std::size_t 父序号 = 0;
    初始化符号引用 上位出现;
    std::vector<初始化符号引用> 主体出现组;
    std::vector<bool> 分量已声明;
    std::vector<子概念名称来源> 名称来源组;
};
struct 子概念筹备材料 final {
    std::array<特征概念信息, 3> 父定义组;
    std::vector<子概念筹备项> 项组;
};
constexpr std::array<std::string_view, 3> 父词面组{
    "RGB颜色", "三维空间坐标", "三维空间尺寸"};

bool 停止初始化(初始化结构化子概念结果& 结果,
    初始化结构化子概念状态 状态, const char* 说明) {
    结果.状态 = 状态;
    结果.诊断说明 = 说明;
    return false;
}

const 初始化词面符号& 已解释概念符号(
    const 初始化定义材料& 材料, 初始化符号引用 引用) {
    if (引用.局部编号 >= 材料.符号组.size())
        throw std::logic_error("结构化子概念符号引用越界");
    const auto& 符号 = 材料.符号组[引用.局部编号];
    if (符号.引用.局部编号 != 引用.局部编号
        || 符号.角色类型 != 初始化符号角色类型::概念引用)
        throw std::logic_error("结构化子概念已解释符号不一致");
    return 符号;
}

const 初始化源范围& 已解释角色范围(
    const 初始化定义项& 项, 初始化源角色 角色, std::size_t 词序) {
    for (const auto& 来源 : 项.角色来源组)
        if (来源.角色 == 角色 && 来源.行内词序 == 词序) return 来源.来源;
    throw std::logic_error("结构化子概念已解释角色缺失");
}

bool 定义一致(const 特征概念信息& 信息, const 特征概念定义& 定义) noexcept {
    return 信息.材料类型 == 定义.材料类型 && 信息.值域 == 定义.值域
        && 信息.单位 == 定义.单位 && 信息.比较规则 == 定义.比较规则
        && 信息.聚合规则 == 定义.聚合规则;
}

bool 命名语言可用(const 初始化结构化子概念请求& 请求,
    const 新_语言类& 语言服务) {
    if (!请求.语言节点.值 || !请求.规范化合同节点.值
        || 请求.规范化合同节点 != 严格UTF8字节精确规范化合同节点) return false;
    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    const auto 中文 = 语言服务.按登记键查询("zh-CN");
    return 语言.状态 == 新语言查询状态::已找到 && 语言.信息
        && 中文.状态 == 新语言查询状态::已找到 && 中文.信息
        && 语言.信息->节点 == 请求.语言节点 && 语言.信息->登记键 == "zh-CN"
        && *语言.信息 == *中文.信息;
}

bool 准备结构化子概念(const 初始化结构化子概念请求& 请求,
    const 新_语言类& 语言服务, const 概念_特征类& 特征概念服务,
    bool 必须已存在, 初始化结构化子概念结果& 结果, 子概念筹备材料& 筹备) {
    结果.解释结果 = 解释初始化标准文本(请求.标准文本, 请求.解释额度);
    const auto& 解释 = *结果.解释结果;
    if (解释.工程控制 != 初始化工程控制::已完成
        || 解释.解释状态 != 初始化解释状态::已完整解释 || !解释.材料)
        return 停止初始化(结果, 初始化结构化子概念状态::解释未完成,
            "标准文本未完整解释；保留原解释语义与独立工程控制，不继续构造");
    const auto& 材料 = *解释.材料;
    std::map<std::string, std::size_t, std::less<>> 声明索引;
    结果.阶段 = 初始化结构化子概念阶段::声明与类型;
    // 先收集全篇声明，分量和别名可以先于其声明出现。
    for (const auto& 项 : 材料.定义组) {
        if (项.模板 != 初始化最小模板::概念归类
            && 项.模板 != 初始化最小模板::结构化分量区间
            && 项.模板 != 初始化最小模板::显式别名)
            return 停止初始化(结果, 初始化结构化子概念状态::声明不合法,
                "本批仅支持子概念声明、分量区间和显式别名；其它定义未覆盖");
        if (项.模板 != 初始化最小模板::概念归类) continue;
        结果.当前声明编号 = 项.局部编号;
        const auto& 归类 = std::get<初始化概念归类材料>(项.载荷);
        const auto& 主体 = 已解释概念符号(材料, 归类.下位);
        const auto& 上位 = 已解释概念符号(材料, 归类.上位);
        const auto 父 = std::find(父词面组.begin(), 父词面组.end(), 上位.词面);
        if (父 == 父词面组.end()
            || std::find(父词面组.begin(), 父词面组.end(), 主体.词面) != 父词面组.end()
            || !声明索引.emplace(主体.词面, 结果.子概念组.size()).second)
            return 停止初始化(结果, 初始化结构化子概念状态::声明不合法,
                "主体重复、与父词面冲突或上位不是明确的三个先天FT");
        初始化结构化子概念项 子项;
        子项.声明编号 = 项.局部编号;
        子项.主体词面 = 主体.词面;
        子项.来源定义编号组.push_back(项.局部编号);
        结果.子概念组.push_back(std::move(子项));
        子概念筹备项 准备项;
        准备项.父序号 = static_cast<std::size_t>(父 - 父词面组.begin());
        准备项.上位出现 = 归类.上位;
        准备项.主体出现组.push_back(归类.下位);
        准备项.名称来源组.push_back({主体.词面,
            已解释角色范围(项, 初始化源角色::下位概念, 0), 项.局部编号});
        筹备.项组.push_back(std::move(准备项));
    }
    if (结果.子概念组.empty())
        return 停止初始化(结果, 初始化结构化子概念状态::声明不合法, "没有子概念声明");

    const auto 先天 = 特征概念服务.获取先天特征概念();
    if (!先天)
        return 停止初始化(结果, 初始化结构化子概念状态::父定义未完成, "先天FT身份未读回");
    const std::array<稳定编码, 3> 父身份组{
        先天->RGB颜色, 先天->三维空间坐标, 先天->三维空间尺寸};
    for (std::size_t i = 0; i < 父身份组.size(); ++i) {
        if (!父身份组[i].值)
            return 停止初始化(结果, 初始化结构化子概念状态::父定义未完成, "明确父身份缺失");
        for (std::size_t j = 0; j < i; ++j)
            if (父身份组[i] == 父身份组[j])
                return 停止初始化(结果, 初始化结构化子概念状态::父定义未完成, "明确父身份重复");
        const auto 父 = 特征概念服务.获取特征概念(父身份组[i]);
        if (!父 || 父->节点 != 父身份组[i]
            || 父->材料类型 != 特征概念材料物理类型::I64数组
            || !std::holds_alternative<特征概念结构化I64值域>(父->值域)
            || std::get<特征概念结构化I64值域>(父->值域).分量.empty())
            return 停止初始化(结果, 初始化结构化子概念状态::父定义未完成,
                "父不是完整可读的结构化I64数组定义");
        筹备.父定义组[i] = *父;
    }
    for (std::size_t i = 0; i < 结果.子概念组.size(); ++i) {
        auto& 子项 = 结果.子概念组[i];
        auto& 准备项 = 筹备.项组[i];
        const auto& 父 = 筹备.父定义组[准备项.父序号];
        子项.直接父概念 = 父.节点;
        子项.完整定义 = {父.材料类型, 父.值域, 父.单位, 父.比较规则, 父.聚合规则, {}};
        准备项.分量已声明.resize(std::get<特征概念结构化I64值域>(父.值域).分量.size());
    }

    结果.阶段 = 初始化结构化子概念阶段::分量完整性;
    for (const auto& 项 : 材料.定义组) {
        if (项.模板 == 初始化最小模板::概念归类) continue;
        const auto 主体引用 = 项.模板 == 初始化最小模板::显式别名
            ? std::get<初始化名称提议材料>(项.载荷).概念
            : std::get<初始化结构化分量区间材料>(项.载荷).主体概念;
        const auto& 主体 = 已解释概念符号(材料, 主体引用);
        const auto 声明 = 声明索引.find(主体.词面);
        if (声明 == 声明索引.end())
            return 停止初始化(结果, 初始化结构化子概念状态::声明不合法,
                "分量或别名主体没有唯一显式声明；别名不作为声明键");
        auto& 子项 = 结果.子概念组[声明->second];
        auto& 准备项 = 筹备.项组[声明->second];
        结果.当前声明编号 = 子项.声明编号;
        子项.来源定义编号组.push_back(项.局部编号);
        准备项.主体出现组.push_back(主体引用);
        if (项.模板 == 初始化最小模板::显式别名) {
            const auto& 别名 = std::get<初始化名称提议材料>(项.载荷);
            准备项.名称来源组.push_back({别名.别名词面,
                已解释角色范围(项, 初始化源角色::别名词面, 2), 项.局部编号});
            continue;
        }
        const auto& 区间 = std::get<初始化结构化分量区间材料>(项.载荷);
        if (区间.分量序号 < 0 || 区间.下界 > 区间.上界
            || static_cast<std::uint64_t>(区间.分量序号)
                > (std::numeric_limits<std::size_t>::max)())
            return 停止初始化(结果, 初始化结构化子概念状态::分量域不合法,
                "分量序号不能安全转换或闭区间上下界不合法");
        const auto 序号 = static_cast<std::size_t>(区间.分量序号);
        auto& 域 = std::get<特征概念结构化I64值域>(子项.完整定义.值域);
        if (序号 >= 域.分量.size() || 准备项.分量已声明[序号])
            return 停止初始化(结果, 初始化结构化子概念状态::分量域不合法,
                "分量序号越界或重复；重复同值也拒绝");
        域.分量[序号].值域 = {{区间.下界, 区间.上界}};
        准备项.分量已声明[序号] = true;
    }
    for (std::size_t i = 0; i < 筹备.项组.size(); ++i) {
        结果.当前声明编号 = 结果.子概念组[i].声明编号;
        const auto& 覆盖 = 筹备.项组[i].分量已声明;
        if (std::find(覆盖.begin(), 覆盖.end(), false) != 覆盖.end())
            return 停止初始化(结果, 初始化结构化子概念状态::分量域不合法,
                "必须完整声明父的全部有序分量，不以缺省表示无限制");
    }

    结果.阶段 = 初始化结构化子概念阶段::父域包含;
    for (std::size_t i = 0; i < 结果.子概念组.size(); ++i) {
        auto& 子项 = 结果.子概念组[i];
        结果.当前声明编号 = 子项.声明编号;
        const auto& 父 = 筹备.父定义组[筹备.项组[i].父序号];
        子项.父域比较 = 特征概念服务.比较值域(
            父.材料类型, 父.值域, 子项.完整定义.值域);
        if (子项.父域比较->状态 != 特征概念规则状态::已完成)
            return 停止初始化(结果, 初始化结构化子概念状态::父域比较未完成,
                "父域比较未完成，不能解释为域不满足");
        if (子项.父域比较->关系 != 特征概念值域关系::左包含右
            || 父.值域 == 子项.完整定义.值域)
            return 停止初始化(结果, 初始化结构化子概念状态::分量域不合法,
                "子域须被父域包含且至少一个分量严格收缩");
    }

    结果.阶段 = 初始化结构化子概念阶段::写前直接子查询;
    for (auto& 子项 : 结果.子概念组) {
        结果.当前声明编号 = 子项.声明编号;
        子项.写前匹配 = 特征概念服务.查询直接子特征概念(子项.直接父概念, 子项.完整定义);
        if (子项.写前匹配->状态 != 特征概念直接子查询状态::已完成
            || 子项.写前匹配->子概念节点组.size() > 1
            || (必须已存在 && 子项.写前匹配->子概念节点组.empty()))
            return 停止初始化(结果, 初始化结构化子概念状态::直接子查询未完成,
                "完整直接子查询未完成、重复定义，或只读请求的子概念缺失");
    }

    结果.阶段 = 初始化结构化子概念阶段::名称处理;
    if (!命名语言可用(请求, 语言服务))
        return 停止初始化(结果, 初始化结构化子概念状态::名称未完成,
            "正式中文语言或严格字节精确规范化合同未完整确认");
    for (std::size_t i = 0; i < 筹备.项组.size(); ++i) {
        结果.当前声明编号 = 结果.子概念组[i].声明编号;
        for (const auto& 名称 : 筹备.项组[i].名称来源组) {
            if (名称.词面.empty() || !新_语言类::严格UTF8字节串有效(名称.词面)
                || 名称.定义编号 >= 材料.定义组.size())
                throw std::logic_error("结构化子概念已解释命名来源不完整");
            const auto& 定义 = 材料.定义组[名称.定义编号];
            if (名称.范围.字节起点 < 定义.来源.字节起点
                || 名称.范围.字节终点 > 定义.来源.字节终点
                || 名称.范围.字节起点 >= 名称.范围.字节终点
                || 名称.范围.字节终点 > 材料.原文.size()
                || std::string_view(材料.原文).substr(名称.范围.字节起点,
                    名称.范围.字节终点 - 名称.范围.字节起点) != 名称.词面)
                throw std::logic_error("结构化子概念已解释名称原文不一致");
        }
    }
    结果.当前声明编号.reset();
    return true;
}

bool 读取确认身份(const 概念_特征类& 服务, 稳定编码 身份,
    初始化结构化子概念结果& 结果, 初始化结构化子概念项& 项) {
    结果.阶段 = 初始化结构化子概念阶段::概念读回;
    项.概念读回 = 服务.获取特征概念(身份);
    if (!身份.值 || !项.概念读回 || 项.概念读回->节点 != 身份
        || !定义一致(*项.概念读回, 项.完整定义))
        return 停止初始化(结果, 初始化结构化子概念状态::身份读回未完成,
            "子概念完整身份或五项定义没有正式读回");
    return true;
}

void 追加确认符号绑定(初始化结构化子概念结果& 结果,
    const 初始化结构化子概念项& 项, const 子概念筹备项& 筹备) {
    结果.符号绑定组.push_back({筹备.上位出现, 项.直接父概念});
    for (const auto 出现 : 筹备.主体出现组)
        结果.符号绑定组.push_back({出现, 项.概念读回->节点});
}

初始化已确认特征名称请求 形成子概念名称请求(
    const 初始化结构化子概念请求& 请求,
    初始化结构化子概念结果& 结果, const 子概念筹备材料& 筹备) {
    std::sort(结果.符号绑定组.begin(), 结果.符号绑定组.end(),
        [](const auto& 左, const auto& 右) { return 左.出现.局部编号 < 右.出现.局部编号; });
    if (结果.符号绑定组.size() != 结果.解释结果->材料->符号组.size())
        throw std::logic_error("结构化子概念没有覆盖全部符号出现");
    for (std::size_t i = 0; i < 结果.符号绑定组.size(); ++i)
        if (结果.符号绑定组[i].出现.局部编号 != i || !结果.符号绑定组[i].概念节点.值)
            throw std::logic_error("结构化子概念符号绑定不唯一或身份缺失");
    初始化已确认特征名称请求 命名;
    命名.语言节点 = 请求.语言节点;
    命名.规范化合同节点 = 请求.规范化合同节点;
    命名.来源解释 = *结果.解释结果;
    for (std::size_t i = 0; i < 筹备.项组.size(); ++i)
        for (const auto& 名称 : 筹备.项组[i].名称来源组)
            命名.目标组.push_back({*结果.子概念组[i].概念读回,
                名称.词面, {名称.范围}, {名称.定义编号}});
    return 命名;
}

void 完成名称处理(初始化结构化子概念结果& 结果) {
    if (结果.名称结果->状态 != 初始化概念名称状态::已完成) {
        (void)停止初始化(结果, 初始化结构化子概念状态::名称未完成,
            "通用命名未完成；此前概念及词条、名称实际步骤全部保留");
        return;
    }
    结果.当前声明编号.reset();
    结果.阶段 = 初始化结构化子概念阶段::完成;
    结果.状态 = 初始化结构化子概念状态::已完成;
}

