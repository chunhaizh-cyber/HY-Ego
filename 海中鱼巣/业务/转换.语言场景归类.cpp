语言场景归类输入结果 转换单句归类到空白语言场景(
    const 语言场景归类输入请求& 请求, 新_自然语言世界树类& 语言世界,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    语言场景归类输入结果 结果;
    try {
        auto 解释 = 语言场景转换内部::只读识别语言场景S01(请求, 语言服务, 词服务,
            名称服务, 存在概念服务, 特征概念服务);
        结果.状态 = 解释.状态;
        结果.完整候选组 = std::move(解释.完整候选组);
        if (结果.状态 != 输入状态::已形成且读回) return 结果;
        const auto 复核 = 语言场景转换内部::只读识别语言场景S01(请求, 语言服务, 词服务,
            名称服务, 存在概念服务, 特征概念服务);
        if (复核.状态 != 输入状态::已形成且读回
            || 复核.完整候选组.size() != 1 || 结果.完整候选组.size() != 1
            || !候选相同(复核.完整候选组.front(), 结果.完整候选组.front())) {
            结果.状态 = 输入状态::读取漂移;
            结果.完整候选组.clear(); return 结果;
        }
        const auto 候选 = 结果.完整候选组.front();
        const auto 场景 = 语言世界.建立空场景();
        if (场景.场景节点) 结果.已取得场景节点 = *场景.场景节点;
        if (场景.状态 != 新自然语言场景操作状态::已建立
            || !场景.场景节点) {
            结果.状态 = 输入状态::场景建立未完成; return 结果;
        }
        const auto 实例 = 语言世界.实例化概念(*场景.场景节点,
            候选.主体概念节点);
        if (实例.实例) 结果.已取得实例节点 = 实例.实例->节点;
        if (实例.状态 != 新自然语言概念实例操作状态::已建立
            || !实例.实例) {
            结果.状态 = 输入状态::实例建立未完成; return 结果;
        }
        const auto 场景读回 = 语言世界.获取场景(*场景.场景节点);
        const auto 实例读回 = 语言世界.获取概念实例(实例.实例->节点);
        const auto 右概念 = 存在概念服务.获取存在概念(候选.归类概念节点);
        const auto 知识 = 语言服务.获取语言知识(候选.所用知识节点,
            词服务, 存在概念服务);
        if (!场景读回
            || !实例读回 || *实例读回 != *实例.实例
            || 实例读回->所属场景节点 != *场景.场景节点
            || 实例读回->概念节点 != 候选.主体概念节点
            || 实例读回->种类 != 新自然语言概念实例种类::存在概念
            || !右概念 || 右概念->种类 != 存在概念种类::抽象
            || 知识.状态 != 新语言知识状态::已完成 || !知识.信息
            || 知识.信息->节点 != 候选.所用知识节点
            || !语言场景转换内部::是S01知识(*知识.信息, 请求.语言节点)) {
            结果.状态 = 输入状态::写后读回未完成; return 结果;
        }
        const auto 写后解释 = 语言场景转换内部::只读识别语言场景S01(请求,
            语言服务, 词服务, 名称服务, 存在概念服务, 特征概念服务);
        if (写后解释.状态 != 输入状态::已形成且读回
            || 写后解释.完整候选组.size() != 1
            || !候选相同(写后解释.完整候选组.front(), 候选)) {
            结果.状态 = 输入状态::写后读回未完成; return 结果;
        }
        结果.含义 = 语言场景归类含义{*场景.场景节点,
            实例.实例->节点, 候选.主体概念节点,
            候选.归类概念节点, 候选.所用知识节点,
            新语言知识作用域::普通陈述, 请求.固定原文,
            请求.未核验来源语言记录节点, 候选.出现组};
        结果.状态 = 输入状态::已形成且读回;
        return 结果;
    } catch (...) {
        结果.状态 = 输入状态::工程未完成;
        结果.含义.reset();
        return 结果;
    }
}

语言场景归类输出结果 从语言场景归类含义生成可回读短句(
    const 语言场景归类输出请求& 请求,
    const 新_自然语言世界树类& 语言世界,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    语言场景归类输出结果 结果;
    try {
        const auto& 含义 = 请求.含义;
        if (!有效(请求.语言节点) || 请求.最大知识条目数 == 0
            || !有效(含义.场景节点) || !有效(含义.主体实例节点)
            || !有效(含义.主体来源概念节点)
            || !有效(含义.归类概念节点) || !有效(含义.所用知识节点)
            || 含义.作用域 != 新语言知识作用域::普通陈述
            || 含义.固定原文.empty() || 含义.出现组.size() != 2
            || 含义.出现组[0].局部出现编号 != 1
            || 含义.出现组[1].局部出现编号 != 2
            || 含义.出现组[0].角色 != 语言场景归类角色::主体
            || 含义.出现组[1].角色 != 语言场景归类角色::归类概念
            || 含义.出现组[0].概念节点 != 含义.主体来源概念节点
            || 含义.出现组[1].概念节点 != 含义.归类概念节点)
            return 结果;
        结果.状态 = 核验来源对齐(含义, 请求.语言节点, 词服务, 名称服务);
        if (结果.状态 != 输出状态::已生成且唯一回读) return 结果;
        const auto 场景 = 语言世界.获取场景(含义.场景节点);
        const auto 实例 = 语言世界.获取概念实例(含义.主体实例节点);
        const auto 左概念 = 存在概念服务.获取存在概念(含义.主体来源概念节点);
        const auto 右概念 = 存在概念服务.获取存在概念(含义.归类概念节点);
        if (!场景
            || !实例 || 实例->所属场景节点 != 含义.场景节点
            || 实例->概念节点 != 含义.主体来源概念节点
            || 实例->种类 != 新自然语言概念实例种类::存在概念
            || !左概念 || 左概念->种类 != 存在概念种类::抽象
            || !右概念 || 右概念->种类 != 存在概念种类::抽象) {
            结果.状态 = 输出状态::引用不可读; return 结果;
        }
        const auto 知识 = 语言服务.获取语言知识(含义.所用知识节点,
            词服务, 存在概念服务);
        if (知识.状态 != 新语言知识状态::已完成 || !知识.信息) {
            结果.状态 = 输出状态::引用不可读; return 结果;
        }
        if (!语言场景转换内部::是S01知识(*知识.信息, 请求.语言节点)) {
            结果.状态 = 输出状态::缺规则; return 结果;
        }
        const auto 是词节点 = std::get<新语言知识固定词项>(
            知识.信息->定义.结构.有序项组[1].载荷).词条节点;
        const auto 是词 = 词服务.获取词条(是词节点);
        if (是词.状态 != 新词条查询状态::已找到 || !是词.信息
            || 是词.信息->语言节点 != 请求.语言节点
            || 是词.信息->规范化词面 != "是") {
            结果.状态 = 输出状态::引用不可读; return 结果;
        }
        std::vector<std::pair<稳定编码, 新词条信息>> 左名称, 右名称;
        结果.状态 = 读取当前名称(含义.主体来源概念节点,
            请求.语言节点, 名称服务, 词服务, 存在概念服务, 特征概念服务, 左名称);
        if (结果.状态 != 输出状态::已生成且唯一回读) return 结果;
        结果.状态 = 读取当前名称(含义.归类概念节点,
            请求.语言节点, 名称服务, 词服务, 存在概念服务, 特征概念服务, 右名称);
        if (结果.状态 != 输出状态::已生成且唯一回读) return 结果;
        struct 可用 final {
            std::string 文本;
            稳定编码 左名称, 右名称;
            std::vector<语言场景归类出现> 对齐;
        };
        std::vector<可用> 可用组;
        bool 遇多义 = false, 遇不一致 = false;
        for (const auto& a : 左名称) for (const auto& b : 右名称)
            for (const auto* 分隔 : {"", " "}) {
            const auto 文本 = a.second.规范化词面 + 分隔 + 是词.信息->规范化词面
                + 分隔 + b.second.规范化词面;
            const auto 回读 = 语言场景转换内部::只读识别语言场景S01(
                {请求.语言节点, 文本, {}, 请求.最大知识条目数},
                语言服务, 词服务, 名称服务, 存在概念服务, 特征概念服务);
            if (回读.状态 == 输入状态::额度不足) {
                结果.状态 = 输出状态::额度不足; return 结果;
            }
            if (回读.状态 == 输入状态::内部不一致
                || 回读.状态 == 输入状态::工程未完成
                || 回读.状态 == 输入状态::引用不可读
                || 回读.状态 == 输入状态::读取漂移) {
                结果.状态 = 映射输出失败(回读.状态); return 结果;
            }
            if (回读.状态 == 输入状态::概念多义待解
                || 回读.状态 == 输入状态::多规则待解) {
                遇多义 = true; continue;
            }
            if (回读.状态 != 输入状态::已形成且读回
                || 回读.完整候选组.size() != 1) {
                遇不一致 = true; continue;
            }
            const auto& 唯一 = 回读.完整候选组.front();
            if (唯一.主体概念节点 != 含义.主体来源概念节点
                || 唯一.归类概念节点 != 含义.归类概念节点
                || 唯一.所用知识节点 != 含义.所用知识节点
                || 唯一.出现组[0].名称关系节点 != a.first
                || 唯一.出现组[1].名称关系节点 != b.first) {
                遇不一致 = true; continue;
            }
            可用组.push_back({文本, a.first, b.first, 唯一.出现组});
        }
        if (可用组.empty()) {
            结果.状态 = 遇多义 ? 输出状态::回读多义
                : 遇不一致 ? 输出状态::回读含义不一致
                : 输出状态::名称待选;
            return 结果;
        }
        std::sort(可用组.begin(), 可用组.end(), [](const auto& a, const auto& b) {
            return std::tie(a.文本, a.左名称, a.右名称)
                < std::tie(b.文本, b.左名称, b.右名称);
        });
        结果.文本 = 可用组.front().文本;
        结果.输出对齐组 = 可用组.front().对齐;
        结果.所用知识节点 = 含义.所用知识节点;
        结果.状态 = 输出状态::已生成且唯一回读;
        return 结果;
    } catch (...) {
        结果.状态 = 输出状态::工程未完成;
        结果.文本.clear();
        结果.输出对齐组.clear();
        结果.所用知识节点.reset();
        return 结果;
    }
}

词典义项语言转换结果 转换词典义项到语言场景(
    const 词典义项语言消息& 消息, const 离线词典数据源& 源,
    新_自然语言世界树类& 世界, 新_语言类& 语言,
    const 新_词类& 词, const 新_存在类& 存在) {
    词典义项语言转换结果 out;out.来源义项=消息.义项;
    const auto 解读组=解读词典义项释义(源,消息.义项);
    const auto& s=消息.义项;
    const auto 查询=源.精确查询({s.词头语种,s.词面});
    const auto 来源字段=[](const 词典义项材料& m){return std::tie(m.记录键,m.词头语种,m.词面,m.义项键,m.汉语释义,
        m.例句原文,m.例句汉译,m.读音,m.来源页URL,m.来源版本,m.许可标识,m.署名,m.原始来源定位);};
    const bool 来源已核验=查询.状态==词典操作状态::已完成
        && std::any_of(查询.义项组.begin(),查询.义项组.end(),[&](const auto& m){return 来源字段(m)==来源字段(s);});
    const 新词典义项来源 来源{查询.包标识,
        s.记录键,s.词头语种,s.词面,s.义项键,s.汉语释义,s.例句原文,s.例句汉译,s.读音,
        s.来源页URL,s.来源版本,s.许可标识,s.署名,s.原始来源定位};
    for(std::size_t i=0;i<解读组.size();++i) {
        词典释义行转换结果 r;r.解读材料=解读组[i];
        try {
            if(!来源已核验 || !存在.是存在节点(消息.说话者词典) || !语言.是语言节点(消息.语言节点)
                || !有效(消息.规范化合同节点) || 来源.包标识.empty()) {
                if(查询.状态!=词典操作状态::已完成 && 查询.状态!=词典操作状态::未命中
                    && 查询.状态!=词典操作状态::输入不合法)r.状态=输入状态::工程未完成;
                r.诊断="词典说话者、语言未就绪或义项与当前来源不符："+查询.诊断;
                out.逐行结果.push_back(std::move(r));continue;
            }
            if(!out.场景节点) {
                const auto scene=世界.建立空场景();
                if(scene.状态!=新自然语言场景操作状态::已建立 || !scene.场景节点) {
                    r.状态=输入状态::场景建立未完成;
                    out.逐行结果.push_back(std::move(r));continue;
                }
                out.场景节点=scene.场景节点;
            }
            新词典语言材料 v{*out.场景节点,消息.说话者词典,来源,static_cast<std::int64_t>(i),
                r.解读材料.释义原文,"词典词头表",{},{},{}};
            if(r.解读材料.修饰起始标量) {
                v.M起始标量=static_cast<std::int64_t>(*r.解读材料.修饰起始标量);
                v.M结束标量=static_cast<std::int64_t>(*r.解读材料.修饰结束标量);
            }
            if(r.解读材料.状态==词典释义解读状态::缺规则)r.状态=输入状态::缺规则;
            else if(r.解读材料.状态==词典释义解读状态::辅助表未配置)r.状态=输入状态::工程未完成;
            else if(r.解读材料.状态==词典释义解读状态::输入不合法)r.状态=输入状态::输入拒绝;
            else {
                r.状态=输入状态::已形成且读回;
                const auto 查=[&](const std::string& text)->std::optional<稳定编码> {
                    const auto q=词.按规范化词面查询(消息.语言节点,消息.规范化合同节点,text);
                    if(q.状态==新词条查询状态::已找到 && q.信息)return q.信息->节点;
                    if(q.状态==新词条查询状态::未找到) {
                        r.未登记词面组.push_back(text);return {};
                    }
                    throw std::runtime_error("词条只读查询未完成，不能解释为未知词");
                };
                const auto xtext=源.繁简规范化(s.词面);
                if(!xtext || !r.解读材料.中心词)throw std::logic_error("已解读材料缺X规范化或N");
                const auto x=查(*xtext);
                std::optional<稳定编码> n;
                for(const auto& t:r.解读材料.词段组) {
                    const auto id=查(t.规范化词面);
                    if(t.起始标量==r.解读材料.中心词->起始标量
                        && t.结束标量==r.解读材料.中心词->结束标量)n=id;
                }
                if(!r.未登记词面组.empty())r.状态=输入状态::未知词;
                else if(!x || !n)throw std::logic_error("已解读材料中心词不在词段组");
                else v.归类=新词典归类词条对{*x,*n};
            }
            r.材料节点=语言.保存词典语言材料(v,世界,词,存在);
            r.读回=语言.读取词典语言材料(*r.材料节点);
            if(!r.读回 || r.读回->内容!=v)r.状态=输入状态::写后读回未完成;
        } catch(const std::exception& e) {
            r.状态=输入状态::工程未完成;r.诊断=e.what();
        }
        out.逐行结果.push_back(std::move(r));
    }
    return out;
}

