bool 合法范围(解释原文范围 范围, std::size_t 总数) noexcept {
    return 范围.起始标量 < 范围.结束标量
        && 范围.结束标量 <= 总数;
}

// 原文对齐只核验词条及位置，不要求原名称关系仍登记，也不重新分词旧原文。
输出状态 核验来源对齐(const 语言场景归类含义& 含义, 稳定编码 语言节点,
    const 新_词类& 词服务) {
    if (!新_语言类::严格UTF8字节串有效(含义.固定原文))
        return 输出状态::输入拒绝;
    std::vector<std::size_t> 字节边界{0};
    for (std::size_t i = 0; i < 含义.固定原文.size();) {
        const auto 首字节 = static_cast<unsigned char>(含义.固定原文[i]);
        i += 首字节 < 0x80 ? 1 : 首字节 < 0xE0 ? 2 : 首字节 < 0xF0 ? 3 : 4;
        字节边界.push_back(i);
    }
    const auto& 左 = 含义.出现组[0];
    const auto& 右 = 含义.出现组[1];
    const auto 总标量 = 字节边界.size() - 1;
    if (!合法范围(左.原文范围, 总标量) || !合法范围(右.原文范围, 总标量)
        || 左.原文范围.起始标量 != 0 || 右.原文范围.结束标量 != 总标量
        || 左.原文范围.结束标量 >= 右.原文范围.起始标量
        || !有效(左.词条节点) || !有效(右.词条节点)
        || !有效(左.名称关系节点) || !有效(右.名称关系节点))
        return 输出状态::输入拒绝;
    for (const auto& 出现 : 含义.出现组) {
        const auto 词 = 词服务.获取词条(出现.词条节点);
        if (词.状态 != 新词条查询状态::已找到 || !词.信息)
            return 词.状态 == 新词条查询状态::资源失败
                ? 输出状态::工程未完成 : 输出状态::引用不可读;
        const auto 起点 = 字节边界[出现.原文范围.起始标量];
        const auto 终点 = 字节边界[出现.原文范围.结束标量];
        if (词.信息->节点 != 出现.词条节点 || 词.信息->语言节点 != 语言节点
            || 含义.固定原文.substr(起点, 终点 - 起点) != 词.信息->规范化词面)
            return 输出状态::输入拒绝;
    }
    const auto 中间起点 = 字节边界[左.原文范围.结束标量];
    const auto 中间终点 = 字节边界[右.原文范围.起始标量];
    const auto 中间 = 含义.固定原文.substr(中间起点, 中间终点 - 中间起点);
    return 中间 == "是" || 中间 == " 是 "
        ? 输出状态::已生成且唯一回读 : 输出状态::输入拒绝;
}

bool 是S01知识(const 新语言知识信息& 知识, 稳定编码 语言节点) {
    const auto& 目标 = 知识.定义.目标;
    const auto& 结构 = 知识.定义.结构;
    if (目标.目的 != 新语言知识表达目的::陈述
        || !目标.适用条件组.empty() || 目标.角色组.size() != 2
        || 目标.含义组.size() != 1
        || 结构.类别 != 新语言知识结构类别::基础表达
        || 结构.语言节点 != 语言节点 || 结构.有序项组.size() != 3)
        return false;
    for (std::int64_t 编号 = 0; 编号 != 2; ++编号) {
        const auto 角色 = std::find_if(目标.角色组.begin(), 目标.角色组.end(),
            [编号](const auto& 项) { return 项.局部编号 == 编号; });
        if (角色 == 目标.角色组.end()
            || 角色->种类 != (编号 == 0
                ? 新语言知识角色种类::领域对象引用
                : 新语言知识角色种类::概念引用)
            || 角色->数量 != 新语言知识角色数量::单项
            || 角色->必要约束组.size() != 1
            || 角色->必要约束组.front().被约束角色 != 编号
            || 角色->必要约束组.front().允许类别组
                != std::vector<新语言知识角色类别>{编号 == 0
                    ? 新语言知识角色类别::存在
                    : 新语言知识角色类别::存在概念}) return false;
    }
    const auto& 含义 = 目标.含义组.front();
    if (含义.操作 != 新语言知识含义操作::概念归类
        || 含义.作用域 != 新语言知识作用域::普通陈述
        || 含义.特征值分支 || 含义.被询含义 || 含义.确认范围
        || 含义.参数组.size() != 2) return false;
    const auto 有参数 = [&](新语言知识参数角色 参数, std::int64_t 角色) {
        return std::count_if(含义.参数组.begin(), 含义.参数组.end(),
            [&](const auto& 项) {
                return 项.参数 == 参数 && 项.规则角色 == 角色;
            }) == 1;
    };
    if (!有参数(新语言知识参数角色::主体, 0)
        || !有参数(新语言知识参数角色::归类概念, 1)) return false;
    const auto& 项 = 结构.有序项组;
    if (项[0].局部编号 != 0 || 项[1].局部编号 != 1
        || 项[2].局部编号 != 2) return false;
    const auto* 左 = std::get_if<新语言知识角色表达项>(&项[0].载荷);
    const auto* 中 = std::get_if<新语言知识固定词项>(&项[1].载荷);
    const auto* 右 = std::get_if<新语言知识角色表达项>(&项[2].载荷);
    return 左 && 中 && 右 && 左->规则角色 == 0
        && 左->方式 == 新语言知识表达方式::明确对象描述
        && !左->指代概念节点 && 有效(中->词条节点)
        && 右->规则角色 == 1
        && 右->方式 == 新语言知识表达方式::名称表达
        && !右->指代概念节点;
}

输入状态 映射语言失败(新语言查询状态 状态) noexcept {
    switch (状态) {
    case 新语言查询状态::输入不合法: return 输入状态::输入拒绝;
    case 新语言查询状态::资源失败: return 输入状态::工程未完成;
    case 新语言查询状态::结构不一致: return 输入状态::内部不一致;
    default: return 输入状态::引用不可读;
    }
}

输入状态 映射知识失败(新语言知识状态 状态) noexcept {
    switch (状态) {
    case 新语言知识状态::未找到: return 输入状态::缺规则;
    case 新语言知识状态::额度不足: return 输入状态::额度不足;
    case 新语言知识状态::输入拒绝: return 输入状态::输入拒绝;
    case 新语言知识状态::内部不一致: return 输入状态::内部不一致;
    case 新语言知识状态::工程未完成: return 输入状态::工程未完成;
    default: return 输入状态::引用不可读;
    }
}

输入状态 映射名称失败(概念名称关系查询状态 状态) noexcept {
    switch (状态) {
    case 概念名称关系查询状态::未找到: return 输入状态::缺名称;
    case 概念名称关系查询状态::资源失败:
    case 概念名称关系查询状态::工程未完成:
        return 输入状态::工程未完成;
    case 概念名称关系查询状态::结构不一致:
        return 输入状态::内部不一致;
    default: return 输入状态::引用不可读;
    }
}

// 本叶只有完整单词条槽。空格若出现，只能恰好占两个槽间的一码点。
std::optional<std::array<新语言词条匹配片段, 3>> 读取三词布局(
    const std::vector<新语言词条匹配片段>& 片段组,
    const std::string& 原文) {
    if (原文.empty() || 原文.front() == ' ' || 原文.back() == ' ')
        return std::nullopt;
    std::array<新语言词条匹配片段, 3> 词;
    if (片段组.size() == 3) {
        for (std::size_t i = 0; i != 3; ++i) 词[i] = 片段组[i];
    } else if (片段组.size() == 5
        && 片段组[1].原文 == " " && 片段组[3].原文 == " "
        && 片段组[1].原文码点数量 == 1
        && 片段组[3].原文码点数量 == 1) {
        词 = {片段组[0], 片段组[2], 片段组[4]};
    } else return std::nullopt;
    if (!词[0].词条节点 || !词[1].词条节点 || !词[2].词条节点
        || !词[0].原文码点数量 || !词[1].原文码点数量
        || !词[2].原文码点数量 || 词[0].原文码点起点 != 0)
        return std::nullopt;
    std::size_t 字节位置 = 0, 标量位置 = 0;
    for (const auto& 片 : 片段组) {
        if (片.原文字节起点 != 字节位置
            || 片.原文码点起点 != 标量位置
            || 片.原文字节长度 != 片.原文.size()) return std::nullopt;
        字节位置 += 片.原文字节长度;
        标量位置 += 片.原文码点数量;
    }
    if (字节位置 != 原文.size()) return std::nullopt;
    return 词;
}

输入状态 读取类名候选(
    稳定编码 词条节点, const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务,
    std::vector<名称候选>& 结果) {
    const auto 普通 = 名称服务.查询词条候选概念(词条节点);
    if (普通.状态 != 概念名称关系查询状态::已找到)
        return 映射名称失败(普通.状态);
    std::set<稳定编码> 已见;
    for (const auto 关系节点 : 普通.名称关系节点组) {
        if (!已见.insert(关系节点).second) return 输入状态::内部不一致;
        // 查询返回普通及指代名称全集；指代关系已读回但不是类名候选。
        const auto 指代 = 名称服务.获取指代名称关系(关系节点);
        if (指代.状态 == 指代名称读取状态::已读取) {
            if (!指代.信息 || 指代.信息->节点 != 关系节点
                || 指代.信息->词条.节点 != 词条节点)
                return 输入状态::内部不一致;
            continue;
        }
        if (指代.状态 != 指代名称读取状态::未找到)
            return 指代.状态 == 指代名称读取状态::资源失败
                || 指代.状态 == 指代名称读取状态::工程未完成
                ? 输入状态::工程未完成 : 输入状态::引用不可读;
        const auto 关系 = 名称服务.获取名称关系(关系节点);
        if (关系.状态 == 概念名称关系查询状态::未找到)
            return 输入状态::读取漂移;
        if (关系.状态 != 概念名称关系查询状态::已找到)
            return 映射名称失败(关系.状态);
        if (!关系.信息 || 关系.信息->节点 != 关系节点
            || 关系.信息->词条节点 != 词条节点)
            return 输入状态::内部不一致;
        const auto 存在 = 存在概念服务.获取存在概念(关系.信息->概念节点);
        const auto 特征 = 特征概念服务.获取特征概念(关系.信息->概念节点);
        if (存在.has_value() == 特征.has_value()) return 输入状态::引用不可读;
        if (存在 && 存在->种类 == 存在概念种类::抽象)
            结果.push_back({存在->节点, 关系节点, 词条节点});
    }
    std::sort(结果.begin(), 结果.end(), [](const auto& 左, const auto& 右) {
        return std::tie(左.概念节点, 左.名称关系节点)
            < std::tie(右.概念节点, 右.名称关系节点);
    });
    return 结果.empty() ? 输入状态::角色不相容 : 输入状态::已形成且读回;
}

bool 候选顺序(const 语言场景归类候选& 左,
    const 语言场景归类候选& 右) {
    return std::tie(左.所用知识节点, 左.主体概念节点,
        左.归类概念节点, 左.出现组[0].名称关系节点,
        左.出现组[1].名称关系节点)
        < std::tie(右.所用知识节点, 右.主体概念节点,
            右.归类概念节点, 右.出现组[0].名称关系节点,
            右.出现组[1].名称关系节点);
}

bool 候选相同(const 语言场景归类候选& 左,
    const 语言场景归类候选& 右) {
    if (左.主体概念节点 != 右.主体概念节点
        || 左.归类概念节点 != 右.归类概念节点
        || 左.所用知识节点 != 右.所用知识节点
        || 左.出现组.size() != 2 || 右.出现组.size() != 2) return false;
    for (std::size_t i = 0; i != 2; ++i) {
        const auto& a = 左.出现组[i];
        const auto& b = 右.出现组[i];
        if (a.局部出现编号 != b.局部出现编号 || a.角色 != b.角色
            || a.原文范围.起始标量 != b.原文范围.起始标量
            || a.原文范围.结束标量 != b.原文范围.结束标量
            || a.词条节点 != b.词条节点
            || a.名称关系节点 != b.名称关系节点
            || a.概念节点 != b.概念节点) return false;
    }
    return true;
}

只读结果 只读解释语言场景S01(
    const 语言场景归类输入请求& 请求,
    const 新_语言类& 语言服务, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务,
    const 概念_存在类& 存在概念服务,
    const 概念_特征类& 特征概念服务) {
    只读结果 结果;
    if (!有效(请求.语言节点) || 请求.固定原文.empty()
        || 请求.最大知识条目数 == 0) return 结果;
    if (!新_语言类::严格UTF8字节串有效(请求.固定原文)) {
        结果.状态 = 输入状态::格式失败; return 结果;
    }
    const auto 语言 = 语言服务.获取语言(请求.语言节点);
    if (语言.状态 != 新语言查询状态::已找到 || !语言.信息
        || 语言.信息->节点 != 请求.语言节点) {
        结果.状态 = 映射语言失败(语言.状态); return 结果;
    }
    const auto 匹配 = 语言服务.按已登记词条最长匹配(
        请求.语言节点, 请求.固定原文, 词服务);
    if (匹配.状态 != 新语言查询状态::已找到) {
        结果.状态 = 映射语言失败(匹配.状态); return 结果;
    }
    const auto 布局 = 读取三词布局(匹配.片段组, 请求.固定原文);
    if (!布局) {
        结果.状态 = std::any_of(匹配.片段组.begin(), 匹配.片段组.end(),
            [](const auto& 项) { return !项.词条节点 && 项.原文 != " "; })
            ? 输入状态::未知词 : 输入状态::结构未支持;
        return 结果;
    }
    std::array<新词条信息, 3> 词;
    for (std::size_t i = 0; i != 3; ++i) {
        const auto 读回 = 词服务.获取词条(*(*布局)[i].词条节点);
        if (读回.状态 != 新词条查询状态::已找到 || !读回.信息) {
            结果.状态 = 读回.状态 == 新词条查询状态::资源失败
                ? 输入状态::工程未完成 : 输入状态::引用不可读;
            return 结果;
        }
        if (读回.信息->语言节点 != 请求.语言节点
            || 读回.信息->规范化词面 != (*布局)[i].原文) {
            结果.状态 = 输入状态::读取漂移; return 结果;
        }
        词[i] = *读回.信息;
    }
    if (词[1].规范化词面 != "是") {
        结果.状态 = 输入状态::结构未支持; return 结果;
    }
    const auto 知识组 = 语言服务.枚举语言知识候选(
        请求.语言节点, 请求.最大知识条目数, 词服务, 存在概念服务);
    if (知识组.状态 != 新语言知识状态::已完成) {
        结果.状态 = 映射知识失败(知识组.状态); return 结果;
    }
    std::vector<稳定编码> 规则组;
    for (const auto& 知识 : 知识组.信息组) {
        if (!是S01知识(知识, 请求.语言节点)) continue;
        const auto 固定 = std::get<新语言知识固定词项>(
            知识.定义.结构.有序项组[1].载荷).词条节点;
        const auto 固定词 = 词服务.获取词条(固定);
        if (固定词.状态 != 新词条查询状态::已找到 || !固定词.信息) {
            结果.状态 = 输入状态::引用不可读; return 结果;
        }
        if (固定词.信息->语言节点 != 请求.语言节点) continue;
        if (固定词.信息->节点 == 词[1].节点) 规则组.push_back(知识.节点);
    }
    if (规则组.empty()) { 结果.状态 = 输入状态::缺规则; return 结果; }
    std::vector<名称候选> 左, 右;
    结果.状态 = 读取类名候选(词[0].节点, 名称服务,
        存在概念服务, 特征概念服务, 左);
    if (结果.状态 != 输入状态::已形成且读回) return 结果;
    结果.状态 = 读取类名候选(词[2].节点, 名称服务,
        存在概念服务, 特征概念服务, 右);
    if (结果.状态 != 输入状态::已形成且读回) return 结果;
    const auto 左范围 = 解释原文范围{(*布局)[0].原文码点起点,
        (*布局)[0].原文码点起点 + (*布局)[0].原文码点数量};
    const auto 右范围 = 解释原文范围{(*布局)[2].原文码点起点,
        (*布局)[2].原文码点起点 + (*布局)[2].原文码点数量};
    for (auto 规则 : 规则组) for (const auto& a : 左) for (const auto& b : 右) {
        结果.候选组.push_back({a.概念节点, b.概念节点, 规则, {
            {1, 语言场景归类角色::主体, 左范围,
                a.词条节点, a.名称关系节点, a.概念节点},
            {2, 语言场景归类角色::归类概念, 右范围,
                b.词条节点, b.名称关系节点, b.概念节点}}});
    }
    std::sort(结果.候选组.begin(), 结果.候选组.end(), 候选顺序);
    if (规则组.size() != 1) 结果.状态 = 输入状态::多规则待解;
    else if (结果.候选组.size() != 1)
        结果.状态 = 输入状态::概念多义待解;
    return 结果;
}

输出状态 映射输出失败(输入状态 状态) noexcept {
    switch (状态) {
    case 输入状态::缺名称: return 输出状态::缺名称;
    case 输入状态::缺规则: return 输出状态::缺规则;
    case 输入状态::概念多义待解:
    case 输入状态::多规则待解: return 输出状态::回读多义;
    case 输入状态::额度不足: return 输出状态::额度不足;
    case 输入状态::内部不一致: return 输出状态::内部不一致;
    case 输入状态::工程未完成: return 输出状态::工程未完成;
    case 输入状态::引用不可读:
    case 输入状态::读取漂移: return 输出状态::读取漂移;
    default: return 输出状态::回读含义不一致;
    }
}

输出状态 读取当前名称(稳定编码 概念节点, 稳定编码 语言节点,
    const 概念_名称关系类& 名称服务, const 新_词类& 词服务,
    std::vector<std::pair<稳定编码, 新词条信息>>& 结果) {
    const auto 名称组 = 名称服务.查询概念名称(概念节点);
    if (名称组.状态 != 概念名称关系查询状态::已找到)
        return 名称组.状态 == 概念名称关系查询状态::未找到
            ? 输出状态::缺名称 : 输出状态::引用不可读;
    std::set<稳定编码> 已见;
    for (auto 节点 : 名称组.名称关系节点组) {
        if (!已见.insert(节点).second) return 输出状态::内部不一致;
        const auto 名称 = 名称服务.获取名称关系(节点);
        if (名称.状态 != 概念名称关系查询状态::已找到 || !名称.信息
            || 名称.信息->节点 != 节点
            || 名称.信息->概念节点 != 概念节点)
            return 输出状态::引用不可读;
        const auto 词 = 词服务.获取词条(名称.信息->词条节点);
        if (词.状态 != 新词条查询状态::已找到 || !词.信息
            || 词.信息->节点 != 名称.信息->词条节点)
            return 输出状态::引用不可读;
        if (词.信息->语言节点 == 语言节点)
            结果.emplace_back(节点, *词.信息);
    }
    std::sort(结果.begin(), 结果.end(), [](const auto& a, const auto& b) {
        return std::tie(a.second.规范化词面, a.first)
            < std::tie(b.second.规范化词面, b.first);
    });
    return 结果.empty() ? 输出状态::缺名称 : 输出状态::已生成且唯一回读;
}

