bool 合法范围(解释原文范围 范围, std::size_t 总数) noexcept {
    return 范围.起始标量 < 范围.结束标量
        && 范围.结束标量 <= 总数;
}

// 核验原词条、位置与仍存在的名称关系；不强求旧名称关系保留或重新分词。
输出状态 核验来源对齐(const 语言场景归类含义& 含义, 稳定编码 语言节点,
    const 新_词类& 词服务, const 概念_名称关系类& 名称服务) {
    using namespace 语言场景转换内部;
    const auto 原文 = 解码语言场景原文(含义.固定原文);
    if (!原文) return 输出状态::输入拒绝;
    const auto& a = 含义.出现组[0]; const auto& b = 含义.出现组[1];
    const auto 总数 = 原文->标量字节边界.size()-1;
    if (!合法范围(a.原文范围, 总数) || !合法范围(b.原文范围, 总数)
        || a.原文范围.起始标量 != 0 || b.原文范围.结束标量 != 总数
        || a.原文范围.结束标量 >= b.原文范围.起始标量) return 输出状态::输入拒绝;
    const auto 状态 = 核验语言场景命名来源(*原文,
        {{a.原文范围,a.词条节点,a.名称关系节点,a.概念节点},
         {b.原文范围,b.词条节点,b.名称关系节点,b.概念节点}}, 语言节点,词服务,名称服务);
    if (状态 != 读取状态::已完成) {
        if (状态 == 读取状态::输入拒绝) return 输出状态::输入拒绝;
        if (状态 == 读取状态::工程未完成) return 输出状态::工程未完成;
        if (状态 == 读取状态::内部不一致) return 输出状态::内部不一致;
        return 输出状态::引用不可读;
    }
    const auto 中间 = 读取语言场景原文范围(*原文,{a.原文范围.结束标量,b.原文范围.起始标量});
    return 中间 == "是" || 中间 == " 是 " ? 输出状态::已生成且唯一回读 : 输出状态::输入拒绝;
}

bool 候选相同(const 语言场景归类候选& 左,
    const 语言场景归类候选& 右) {
    if (左.主体概念节点 != 右.主体概念节点
        || 左.归类概念节点 != 右.归类概念节点
        || 左.所用知识节点 != 右.所用知识节点
        || 左.出现组.size() != 2 || 右.出现组.size() != 2) return false;
    for (std::size_t i = 0; i != 2; ++i) {
        const auto& a = 左.出现组[i];
        const auto& b = 右.出现组[i];
        if (a.局部出现编号 != b.局部出现编号 || a.角色 != b.角色
            || a.原文范围.起始标量 != b.原文范围.起始标量
            || a.原文范围.结束标量 != b.原文范围.结束标量
            || a.词条节点 != b.词条节点
            || a.名称关系节点 != b.名称关系节点
            || a.概念节点 != b.概念节点) return false;
    }
    return true;
}

输出状态 映射输出失败(输入状态 状态) noexcept {
    switch (状态) {
    case 输入状态::缺名称: return 输出状态::缺名称;
    case 输入状态::缺规则: return 输出状态::缺规则;
    case 输入状态::概念多义待解:
    case 输入状态::多规则待解: return 输出状态::回读多义;
    case 输入状态::额度不足: return 输出状态::额度不足;
    case 输入状态::内部不一致: return 输出状态::内部不一致;
    case 输入状态::工程未完成: return 输出状态::工程未完成;
    case 输入状态::引用不可读:
    case 输入状态::读取漂移: return 输出状态::读取漂移;
    default: return 输出状态::回读含义不一致;
    }
}

输出状态 读取当前名称(稳定编码 概念节点, 稳定编码 语言节点,
    const 概念_名称关系类& 名称服务, const 新_词类& 词服务,
    const 概念_存在类& 存在服务, const 概念_特征类& 特征服务,
    std::vector<std::pair<稳定编码, 新词条信息>>& 结果) {
    using namespace 语言场景转换内部;
    const auto 全部 = 读取概念当前名称完整(概念节点,语言节点,词服务,名称服务,存在服务,特征服务);
    if (全部.状态 != 读取状态::已完成) {
        if (全部.状态 == 读取状态::缺名称) return 输出状态::缺名称;
        if (全部.状态 == 读取状态::工程未完成) return 输出状态::工程未完成;
        if (全部.状态 == 读取状态::内部不一致) return 输出状态::内部不一致;
        return 输出状态::引用不可读;
    }
    for (const auto& 项 : 全部.完整普通名称材料组) 结果.emplace_back(项.名称关系.节点,项.词条);
    return 输出状态::已生成且唯一回读;
}

