方法问题学习服务::方法问题学习服务(const 新方法问题归档接口& 归档) noexcept : 归档_(归档) {}
新学习结束通知 方法问题学习服务::学习(const 新方法问题学习消息& 消息,
    const std::function<bool()>& 停止检查) {
    auto 拒绝 = [&](新学习运行异常原因 原因) { throw 新学习运行异常(消息.方法节点, 原因); };
    try {
        if (!有效(消息.方法节点) || !有效(消息.任务节点)
            || !有效(消息.执行实例节点) || !有效(消息.归档节点)) 拒绝(新学习运行异常原因::输入不合法);
        if (停止检查 && 停止检查()) 拒绝(新学习运行异常原因::停止取消);
        {
            std::lock_guard 锁(互斥_);
            if (const auto 位置=收集组_.find(消息.归档节点); 位置!=收集组_.end()) {
                if (位置->second.消息!=消息) 拒绝(新学习运行异常原因::结构不一致);
                return {消息.方法节点};
            }
        }
        const auto 读回=归档_.读取方法问题归档(消息.归档节点);
        if (读回.状态==新方法问题归档状态::资源失败) 拒绝(新学习运行异常原因::资源不足);
        if (读回.状态==新方法问题归档状态::发布结果未知) 拒绝(新学习运行异常原因::发布结果未知);
        if ((读回.状态!=新方法问题归档状态::已保存 && 读回.状态!=新方法问题归档状态::精确重复)
            || 读回.归档节点!=消息.归档节点 || !读回.材料) 拒绝(新学习运行异常原因::结构不一致);
        const auto& 材料=*读回.材料;
        if (材料.任务节点!=消息.任务节点 || 材料.执行实例节点!=消息.执行实例节点
            || 材料.来源抽象方法节点!=消息.方法节点 || !方法问题归档内部::采用身份有效(材料)
            || !有效(材料.影响评估节点) || 材料.问题组.empty()
            || !身份唯一(材料.实际状态组)
            || !核验快照(材料.动作前场景,新场景快照阶段::动作前)
            || !核验快照(材料.结果场景,新场景快照阶段::结果取得时)) 拒绝(新学习运行异常原因::结构不一致);
        for (const auto 问题 : 材料.问题组)
            if (问题<新方法问题种类::方向不符 || 问题>新方法问题种类::发生计划外变化)
                拒绝(新学习运行异常原因::结构不一致);
        for (const auto& 状态 : 材料.实际状态组) {
            const auto 位置=std::find_if(材料.结果场景.状态组.begin(),材料.结果场景.状态组.end(),
                [&](const auto& 项) { return 项.节点==状态.节点; });
            if (位置==材料.结果场景.状态组.end()) {
                if (!std::any_of(材料.结果场景.缺口组.begin(),材料.结果场景.缺口组.end(),
                    [&](const auto& 项) { return 项.种类==新场景快照对象种类::状态 && 项.来源节点==状态.节点; }))
                    拒绝(新学习运行异常原因::结构不一致);
            } else if (位置->被描述存在节点!=状态.被描述存在节点
                || 位置->来源实例特征节点!=状态.来源实例特征节点
                || 位置->特征类型概念节点!=状态.特征类型概念节点
                || 位置->固定准确值!=状态.固定准确值 || 位置->强时间!=状态.强时间) {
                // RC可在非原子采集窗口变化；不可变状态内容必须仍是同一事实。
                拒绝(新学习运行异常原因::结构不一致);
            }
        }
        if (停止检查 && 停止检查()) 拒绝(新学习运行异常原因::停止取消);
        新方法问题学习收集结果 收集{消息,读回.材料,
            材料.本次运行对.has_value() && 材料.动作前场景.缺口组.empty()
            && 材料.结果场景.缺口组.empty()};
        std::lock_guard 锁(互斥_);
        const auto [位置,插入]=收集组_.emplace(消息.归档节点,std::move(收集));
        if (!插入 && 位置->second.消息!=消息) 拒绝(新学习运行异常原因::结构不一致);
        return {消息.方法节点};
    } catch (const std::bad_alloc&) { 拒绝(新学习运行异常原因::资源不足); }
    throw 新学习运行异常(消息.方法节点,新学习运行异常原因::内部错误);
}
std::optional<新方法问题学习收集结果> 方法问题学习服务::读取收集结果(稳定编码 归档) const noexcept {
    try {
        std::lock_guard 锁(互斥_);
        if (const auto 位置=收集组_.find(归档); 位置!=收集组_.end()) return 位置->second;
    } catch (...) {}
    return std::nullopt;
}
