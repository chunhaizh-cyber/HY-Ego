template<class T> bool 身份唯一(const std::vector<T>& 项组) {
    std::set<稳定编码> 身份组;
    for (const auto& 项 : 项组)
        if (!有效(项.节点) || !身份组.insert(项.节点).second) return false;
    return true;
}
bool 核验快照(const 新执行场景快照& 快照, 新场景快照阶段 阶段) {
    if (快照.阶段 != 阶段
        || !身份唯一(快照.场景组) || !身份唯一(快照.存在组)
        || !身份唯一(快照.特征组) || !身份唯一(快照.特征概念组)
        || !身份唯一(快照.存在概念组) || !身份唯一(快照.值材料组)
        || !身份唯一(快照.状态组) || !身份唯一(快照.动态组)) return false;
    if ((!快照.采集开始 || !快照.采集结束) && 快照.缺口组.empty()) return false;
    if (快照.采集开始 && 快照.采集结束
        && 快照.采集开始->语义 != 快照.采集结束->语义) return false;
    auto 已描述 = [&](新场景快照对象种类 种类, 稳定编码 节点) {
        if (!有效(节点)) return false;
        auto 包含 = [节点](const auto& 组) {
            return std::any_of(组.begin(), 组.end(), [节点](const auto& 项) { return 项.节点 == 节点; });
        };
        bool 存在 = false;
        switch (种类) {
        case 新场景快照对象种类::场景: 存在=包含(快照.场景组); break;
        case 新场景快照对象种类::存在: 存在=包含(快照.存在组) || 包含(快照.场景组); break;
        case 新场景快照对象种类::特征: 存在=包含(快照.特征组); break;
        case 新场景快照对象种类::状态: 存在=包含(快照.状态组); break;
        case 新场景快照对象种类::动态: 存在=包含(快照.动态组); break;
        case 新场景快照对象种类::存在概念: 存在=包含(快照.存在概念组); break;
        case 新场景快照对象种类::特征概念: 存在=包含(快照.特征概念组); break;
        case 新场景快照对象种类::特征值材料: 存在=包含(快照.值材料组); break;
        default: break;
        }
        return 存在 || std::any_of(快照.外部引用组.begin(), 快照.外部引用组.end(),
            [&](const auto& 项) { return 项.种类==种类 && 项.来源节点==节点; })
            || std::any_of(快照.缺口组.begin(), 快照.缺口组.end(),
            [&](const auto& 项) { return 项.种类==种类 && 项.来源节点==节点; });
    };
    auto 全有 = [&](新场景快照对象种类 种类, const auto& 组) {
        return std::all_of(组.begin(), 组.end(), [&](稳定编码 节点) { return 已描述(种类, 节点); });
    };
    if (!全有(新场景快照对象种类::场景, 快照.入口场景组)) return false;
    for (const auto& 场景 : 快照.场景组) {
        if (!全有(新场景快照对象种类::存在, 场景.直接成员存在组)
            || !全有(新场景快照对象种类::存在, 场景.边界存在组)
            || !全有(新场景快照对象种类::场景, 场景.直接子场景组)
            || !全有(新场景快照对象种类::特征, 场景.特征节点组)
            || !全有(新场景快照对象种类::状态, 场景.状态节点组)
            || !全有(新场景快照对象种类::动态, 场景.动态节点组)
            || !已描述(新场景快照对象种类::存在概念, 场景.专属存在概念节点)
            || (场景.父场景节点 && !已描述(新场景快照对象种类::场景, *场景.父场景节点))) return false;
    }
    for (const auto& 存在 : 快照.存在组) {
        if (!全有(新场景快照对象种类::存在, 存在.子存在节点组)
            || !全有(新场景快照对象种类::特征, 存在.特征节点组)
            || !已描述(新场景快照对象种类::存在概念, 存在.专属存在概念节点)
            || (存在.父存在节点 && !已描述(新场景快照对象种类::存在, *存在.父存在节点))) return false;
    }
    auto 准确值已描述 = [&](const 新特征准确值& 值,稳定编码 概念) {
        const auto* 节点=std::get_if<稳定编码>(&值);
        if (!节点) return true;
        const auto 位置=std::find_if(快照.特征概念组.begin(),快照.特征概念组.end(),
            [&](const auto& 项) { return 项.节点==概念; });
        const auto 种类=位置==快照.特征概念组.end() ? 新场景快照对象种类::其它引用
            : 位置->材料类型==特征概念材料物理类型::存在节点引用
                ? 新场景快照对象种类::存在 : 新场景快照对象种类::特征值材料;
        return 已描述(种类,*节点);
    };
    for (const auto& 特征 : 快照.特征组) {
        if (!已描述(新场景快照对象种类::特征概念,特征.特征概念节点)
            || (特征.上级特征节点 && !已描述(新场景快照对象种类::特征,*特征.上级特征节点))
            || (特征.当前值 && !准确值已描述(*特征.当前值,特征.特征概念节点))
            || (特征.标准值 && !准确值已描述(*特征.标准值,特征.特征概念节点))
            || !std::all_of(特征.历史不同值.begin(),特征.历史不同值.end(),
                [&](const auto& 值) { return 准确值已描述(值,特征.特征概念节点); })) return false;
    }
    for (const auto& 状态 : 快照.状态组) {
        if (!已描述(新场景快照对象种类::特征,状态.来源实例特征节点)
            || !已描述(新场景快照对象种类::特征概念,状态.特征类型概念节点)
            || !准确值已描述(状态.固定准确值,状态.特征类型概念节点)) return false;
    }
    for (const auto& 动态 : 快照.动态组) {
        if (!全有(新场景快照对象种类::状态,动态.状态节点组)
            || !全有(新场景快照对象种类::动态,动态.成员动态节点组)
            || (动态.动态概念节点 && !已描述(新场景快照对象种类::动态概念,*动态.动态概念节点))) return false;
        for (const auto& 结果 : 动态.动作结果组)
            if (!已描述(新场景快照对象种类::动态,结果.结果动态节点)) return false;
    }
    return true;
}
