新_动态特征抽取类::新_动态特征抽取类(
    const 新_动态类& 动态服务,
    const 新_状态类& 状态服务,
    const 新_二次特征类& 二次特征服务,
    const 概念_动态类& 动态概念服务) noexcept
    : 动态服务_(动态服务),
      状态服务_(状态服务),
      二次特征服务_(二次特征服务),
      动态概念服务_(动态概念服务) {}

新动态特征抽取结果 新_动态特征抽取类::抽取(
    const 新动态特征抽取请求& 请求) const noexcept {
    新动态特征抽取结果 结果;
    try {
        if (!有效(请求.动态节点)) return 结果;
        const auto 动态 = 动态服务_.获取动态(请求.动态节点);
        if (!动态) {
            结果.状态 = 新动态特征抽取状态::动态不存在;
            return 结果;
        }
        if (动态->种类 == 新动态种类::复合) {
            if (动态->成员动态节点组.size() < 2
                || 动态->跨特征时间组.empty()) {
                结果.状态 = 新动态特征抽取状态::结构不一致;
                return 结果;
            }
            结果.特征组.reserve(动态->跨特征时间组.size());
            for (std::size_t i = 0; i < 动态->跨特征时间组.size(); ++i) {
                const auto& 时间 = 动态->跨特征时间组[i];
                结果.特征组.push_back({
                    static_cast<std::int64_t>(i),
                    时间.二次特征类型概念节点,
                    时间.时间差纳秒,
                    时间.结果值域概念节点,
                    std::optional<稳定编码>{时间.前状态节点},
                    std::optional<稳定编码>{时间.后状态节点}});
            }
            结果.状态 = 新动态特征抽取状态::已完成;
            结果.动态节点 = 请求.动态节点;
            return 结果;
        }
        if (动态->种类 != 新动态种类::原子
            || 动态->状态节点组.size() != 2
            || !动态->动态概念节点) {
            结果.状态 = 新动态特征抽取状态::状态不足;
            return 结果;
        }

        std::vector<新状态信息> 状态组;
        状态组.reserve(动态->状态节点组.size());
        for (const auto 状态节点 : 动态->状态节点组) {
            const auto 状态 = 状态服务_.获取状态(状态节点);
            if (!状态) {
                结果.状态 = 新动态特征抽取状态::状态不存在;
                return 结果;
            }
            状态组.push_back(*状态);
        }
        if (!状态轨迹有效(*动态, 状态组)) {
            结果.状态 = 新动态特征抽取状态::状态轨迹不一致;
            return 结果;
        }

        结果.特征组.reserve((状态组.size() - 1) * 3);
        for (std::size_t i = 1; i < 状态组.size(); ++i) {
            const auto 添加普通结果 = [&](const 新二次特征计算结果& 计算结果) {
                if (计算结果.状态 != 新二次特征计算状态::已完成
                    || !计算结果.二次特征类型概念节点
                    || !计算结果.结果值域概念节点
                    || !计算结果.结果值) {
                    结果.状态 = 新动态特征抽取状态::二次特征计算失败;
                    结果.二次特征失败状态 = 计算结果.状态;
                    结果.特征组.clear();
                    return false;
                }
                结果.特征组.push_back({
                    static_cast<std::int64_t>(i - 1),
                    *计算结果.二次特征类型概念节点,
                    *计算结果.结果值,
                    *计算结果.结果值域概念节点,
                    std::optional<稳定编码>{状态组[i - 1].节点},
                    std::optional<稳定编码>{状态组[i].节点}});
                return true;
            };
            if (!添加普通结果(二次特征服务_.计算(
                    形成值比较请求(状态组[i - 1], 状态组[i])))
                || !添加普通结果(二次特征服务_.计算(
                    形成时间间隔请求(状态组[i - 1], 状态组[i])))) {
                return 结果;
            }

            const auto 带时间请求 = 形成带时间计算请求(
                请求.动态节点, 状态组[i - 1], 状态组[i]);
            const auto 计算结果 = 二次特征服务_.比较跨特征类型变化(
                带时间请求);
            if (计算结果.状态 != 新二次跨类型变化比较状态::已完成
                || !计算结果.二次特征类型概念节点
                || !计算结果.结果值域概念节点
                || !计算结果.单位参照目标变化量) {
                结果.状态 = 新动态特征抽取状态::二次特征计算失败;
                结果.跨类型比较失败状态 = 计算结果.状态;
                结果.特征组.clear();
                return 结果;
            }
            结果.特征组.push_back({
                static_cast<std::int64_t>(i - 1),
                *计算结果.二次特征类型概念节点,
                *计算结果.单位参照目标变化量,
                *计算结果.结果值域概念节点,
                std::optional<稳定编码>{状态组[i - 1].节点},
                std::optional<稳定编码>{状态组[i].节点}});
        }
        std::sort(结果.特征组.begin(), 结果.特征组.end(),
            [](const auto& 左, const auto& 右) {
                if (左.状态间位置 != 右.状态间位置) {
                    return 左.状态间位置 < 右.状态间位置;
                }
                return 左.二次特征类型概念节点.值
                    < 右.二次特征类型概念节点.值;
            });
        结果.状态 = 新动态特征抽取状态::已完成;
        结果.动态节点 = 请求.动态节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新动态特征抽取状态::资源失败;
        结果.动态节点.reset();
        结果.二次特征失败状态.reset();
        结果.跨类型比较失败状态.reset();
        结果.特征组.clear();
        return 结果;
    }
}

新动态间特征比较结果 新_动态特征抽取类::比较动态特征(
    const 新动态间特征比较请求& 请求) const noexcept {
    新动态间特征比较结果 结果;
    try {
        if (!有效(请求.左动态节点) || !有效(请求.右动态节点)
            || 请求.左动态节点 == 请求.右动态节点) {
            return 结果;
        }
        const auto 左动态 = 动态服务_.获取动态(请求.左动态节点);
        const auto 右动态 = 动态服务_.获取动态(请求.右动态节点);
        if (!左动态 || !右动态) {
            结果.状态 = 新动态间特征比较状态::动态不存在;
            return 结果;
        }
        if (!左动态->动态概念节点 || !右动态->动态概念节点) {
            结果.状态 = 新动态间特征比较状态::动态概念不存在;
            return 结果;
        }
        const auto 左概念 = 动态概念服务_.获取动态概念(
            *左动态->动态概念节点);
        const auto 右概念 = 动态概念服务_.获取动态概念(
            *右动态->动态概念节点);
        if (!左概念 || !右概念) {
            结果.状态 = 新动态间特征比较状态::动态概念不存在;
            return 结果;
        }
        if (左概念->动态特征组.empty() || 右概念->动态特征组.empty()) {
            结果.状态 = 新动态间特征比较状态::内部特征尚未生成;
            return 结果;
        }

        using 特征键 = std::pair<std::int64_t, std::uint64_t>;
        std::map<特征键, const 动态概念特征项*> 左特征;
        std::map<特征键, const 动态概念特征项*> 右特征;
        const auto 建立索引 = [](const std::vector<动态概念特征项>& 特征组,
            auto& 索引) {
            for (const auto& 项 : 特征组) {
                if (!索引.emplace(特征键{项.状态间位置,
                        项.二次特征类型概念节点.值}, &项).second) {
                    return false;
                }
            }
            return true;
        };
        if (!建立索引(左概念->动态特征组, 左特征)
            || !建立索引(右概念->动态特征组, 右特征)
            || 左特征.size() != 右特征.size()) {
            结果.状态 = 新动态间特征比较状态::特征结构不一致;
            return 结果;
        }
        for (const auto& [键, 左项] : 左特征) {
            const auto 右位置 = 右特征.find(键);
            if (右位置 == 右特征.end()) {
                结果.状态 = 新动态间特征比较状态::特征结构不一致;
                结果.比较项组.clear();
                return 结果;
            }
            新二次特征计算请求 计算请求;
            计算请求.左输入 = 二次特征准确特征输入{
                请求.左动态节点, 左项->二次特征类型概念节点,
                左项->准确结果};
            计算请求.右输入 = 二次特征准确特征输入{
                请求.右动态节点, 右位置->second->二次特征类型概念节点,
                右位置->second->准确结果};
            const auto 比较 = 二次特征服务_.计算(计算请求);
            if (比较.状态 != 新二次特征计算状态::已完成
                || !比较.二次特征类型概念节点
                || !比较.结果值域概念节点
                || !比较.结果值) {
                结果.状态 = 新动态间特征比较状态::二次特征计算失败;
                结果.二次特征失败状态 = 比较.状态;
                结果.比较项组.clear();
                return 结果;
            }
            结果.比较项组.push_back({
                键.first,
                左项->二次特征类型概念节点,
                左项->准确结果,
                右位置->second->准确结果,
                *比较.二次特征类型概念节点,
                *比较.结果值,
                *比较.结果值域概念节点});
        }

        结果.状态 = 新动态间特征比较状态::已完成;
        结果.左动态节点 = 请求.左动态节点;
        结果.右动态节点 = 请求.右动态节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新动态间特征比较状态::资源失败;
        结果.左动态节点.reset();
        结果.右动态节点.reset();
        结果.二次特征失败状态.reset();
        结果.比较项组.clear();
        return 结果;
    }
}

