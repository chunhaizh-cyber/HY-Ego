新_动态特征抽取类::新_动态特征抽取类(
    const 新_动态类& 动态服务,
    const 新_状态类& 状态服务,
    const 新_二次特征类& 二次特征服务,
    const 概念_二次特征类& 二次特征概念服务) noexcept
    : 动态服务_(动态服务),
      状态服务_(状态服务),
      二次特征服务_(二次特征服务),
      二次特征概念服务_(二次特征概念服务) {}

新动态特征抽取结果 新_动态特征抽取类::抽取(
    const 新动态特征抽取请求& 请求) const noexcept {
    新动态特征抽取结果 结果;
    try {
        if (!有效(请求.动态节点)
            || 请求.二次特征类型概念节点组.empty()) {
            return 结果;
        }
        const auto 动态 = 动态服务_.获取动态(请求.动态节点);
        if (!动态) {
            结果.状态 = 新动态特征抽取状态::动态不存在;
            return 结果;
        }
        if (动态->状态节点组.size() < 2) {
            结果.状态 = 新动态特征抽取状态::状态不足;
            return 结果;
        }

        std::vector<新状态信息> 状态组;
        状态组.reserve(动态->状态节点组.size());
        for (const auto 状态节点 : 动态->状态节点组) {
            const auto 状态 = 状态服务_.获取状态(状态节点);
            if (!状态) {
                结果.状态 = 新动态特征抽取状态::状态不存在;
                return 结果;
            }
            状态组.push_back(*状态);
        }
        if (!状态轨迹有效(*动态, 状态组)) {
            结果.状态 = 新动态特征抽取状态::状态轨迹不一致;
            return 结果;
        }

        std::set<std::uint64_t> 已见类型;
        std::vector<二次特征概念信息> 定义组;
        定义组.reserve(请求.二次特征类型概念节点组.size());
        for (const auto 类型节点 : 请求.二次特征类型概念节点组) {
            if (!有效(类型节点) || !已见类型.insert(类型节点.值).second) {
                return 结果;
            }
            const auto 定义 = 二次特征概念服务_.获取二次特征概念(类型节点);
            if (!定义 || 定义->二次特征类型根节点 != 类型节点) {
                结果.状态 = 新动态特征抽取状态::二次特征概念不存在;
                return 结果;
            }
            定义组.push_back(*定义);
        }

        结果.特征组.reserve(
            (状态组.size() - 1) * 定义组.size());
        for (std::size_t i = 1; i < 状态组.size(); ++i) {
            for (std::size_t j = 0; j < 定义组.size(); ++j) {
                const auto 计算请求 = 形成计算请求(
                    请求.二次特征类型概念节点组[j],
                    定义组[j], 状态组[i - 1], 状态组[i]);
                if (!计算请求) {
                    结果.状态 = 新动态特征抽取状态::二次特征不适用;
                    结果.特征组.clear();
                    return 结果;
                }
                const auto 计算结果 = 二次特征服务_.计算(*计算请求);
                if (计算结果.状态 != 新二次特征计算状态::已完成
                    || !计算结果.二次特征类型概念节点
                    || !计算结果.结果值域概念节点
                    || !计算结果.结果值) {
                    结果.状态 = 新动态特征抽取状态::二次特征计算失败;
                    结果.二次特征失败状态 = 计算结果.状态;
                    结果.特征组.clear();
                    return 结果;
                }
                结果.特征组.push_back({
                    static_cast<std::int64_t>(i - 1),
                    *计算结果.二次特征类型概念节点,
                    *计算结果.结果值,
                    *计算结果.结果值域概念节点,
                    std::optional<稳定编码>{状态组[i - 1].节点},
                    std::optional<稳定编码>{状态组[i].节点}});
            }
        }

        std::sort(结果.特征组.begin(), 结果.特征组.end(),
            [](const auto& 左, const auto& 右) {
                if (左.状态间位置 != 右.状态间位置) {
                    return 左.状态间位置 < 右.状态间位置;
                }
                return 左.二次特征类型概念节点.值
                    < 右.二次特征类型概念节点.值;
            });
        结果.状态 = 新动态特征抽取状态::已完成;
        结果.动态节点 = 请求.动态节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新动态特征抽取状态::资源失败;
        结果.动态节点.reset();
        结果.二次特征失败状态.reset();
        结果.特征组.clear();
        return 结果;
    }
}

