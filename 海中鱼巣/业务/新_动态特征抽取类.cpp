bool 状态轨迹有效(
    const 新动态信息& 动态,
    const std::vector<新状态信息>& 状态组) noexcept {
    if (状态组.size() != 动态.状态节点组.size() || 状态组.size() < 2) {
        return false;
    }
    for (std::size_t i = 0; i < 状态组.size(); ++i) {
        const auto& 状态 = 状态组[i];
        if (状态.节点 != 动态.状态节点组[i]
            || 状态.被描述存在节点 != 动态.主题存在节点
            || 状态.强时间.语义 != 新状态时间语义::实例绝对UTC
            || (i > 0 && 状态.强时间.纳秒
                <= 状态组[i - 1].强时间.纳秒)) {
            return false;
        }
    }
    return true;
}

新二次跨类型变化比较请求 形成带时间计算请求(
    稳定编码 动态节点,
    const 新状态信息& 前,
    const 新状态信息& 后) {
    新二次跨类型变化比较请求 请求;
    请求.参照变化 = 二次特征时间变化输入{
        动态节点, 前.强时间.纳秒, 后.强时间.纳秒};
    请求.目标变化 = 二次特征类型变化输入{
        动态节点, 前.特征类型概念节点,
        前.固定准确值, 后.固定准确值};
    return 请求;
}

新二次特征计算请求 形成值比较请求(
    const 新状态信息& 前,
    const 新状态信息& 后) {
    新二次特征计算请求 请求;
    请求.左输入 = 二次特征准确特征输入{
        后.节点, 后.特征类型概念节点, 后.固定准确值};
    请求.右输入 = 二次特征准确特征输入{
        前.节点, 前.特征类型概念节点, 前.固定准确值};
    return 请求;
}

新二次特征计算请求 形成时间间隔请求(
    const 新状态信息& 前,
    const 新状态信息& 后) {
    新二次特征计算请求 请求;
    请求.左输入 = 二次特征强时间输入{前.节点, 前.强时间.纳秒};
    请求.右输入 = 二次特征强时间输入{后.节点, 后.强时间.纳秒};
    return 请求;
}

