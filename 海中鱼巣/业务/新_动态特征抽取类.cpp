bool 状态轨迹有效(
    const 新动态信息& 动态,
    const std::vector<新状态信息>& 状态组) noexcept {
    if (状态组.size() != 动态.状态节点组.size() || 状态组.size() < 2) {
        return false;
    }
    for (std::size_t i = 0; i < 状态组.size(); ++i) {
        const auto& 状态 = 状态组[i];
        if (状态.节点 != 动态.状态节点组[i]
            || 状态.被描述存在节点 != 动态.主题存在节点
            || 状态.强时间.语义 != 新状态时间语义::实例绝对UTC
            || (i > 0 && 状态.强时间.纳秒
                <= 状态组[i - 1].强时间.纳秒)) {
            return false;
        }
    }
    return true;
}

std::optional<新二次特征计算请求> 形成计算请求(
    稳定编码 二次特征类型概念节点,
    const 二次特征概念信息& 定义,
    const 新状态信息& 前,
    const 新状态信息& 后) {
    if (定义.二次特征类型根节点 != 二次特征类型概念节点
        || 定义.输入定义组.size() != 2) {
        return std::nullopt;
    }

    新二次特征计算请求 请求;
    请求.二次特征类型概念节点 = 二次特征类型概念节点;
    if (定义.算法 == 二次特征算法::强时间间隔) {
        if (定义.输入定义组[0].来源种类
                != 二次特征输入来源种类::强时间
            || 定义.输入定义组[1].来源种类
                != 二次特征输入来源种类::强时间) {
            return std::nullopt;
        }
        请求.左输入 = 二次特征强时间输入{前.节点, 前.强时间.纳秒};
        请求.右输入 = 二次特征强时间输入{后.节点, 后.强时间.纳秒};
        return 请求;
    }

    const auto& 左定义 = 定义.输入定义组[0];
    const auto& 右定义 = 定义.输入定义组[1];
    if (左定义.来源种类 != 二次特征输入来源种类::特征准确值
        || 右定义.来源种类 != 二次特征输入来源种类::特征准确值
        || !左定义.特征类型概念节点
        || !右定义.特征类型概念节点) {
        return std::nullopt;
    }
    请求.左输入 = 二次特征准确特征输入{
        前.节点, *左定义.特征类型概念节点, 前.固定准确值};
    请求.右输入 = 二次特征准确特征输入{
        后.节点, *右定义.特征类型概念节点, 后.固定准确值};
    return 请求;
}

