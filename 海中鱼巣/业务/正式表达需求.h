#pragma once

#include <cstdint>
#include <optional>
#include <string>

#include "../领域/字段询问.数据.h"
#include "../领域/新_语言类.h"
#include "../领域/接收认知来源.数据.h"

namespace 海中鱼巣 {

// 正式表达需求的对象/信息种类（与表达目的正交；首批只落地需求字段询问）。
enum class 正式表达对象种类 : std::uint8_t {
    需求字段 = 1, 词条归类, 指代澄清, 原文重述确认
};

// 运行期正式表达需求：由任务链上的出站本能提交，语言模块只消费并产出候选话语。
// 不入列、不写字段、不召回方法。详略由槽完备度体现，不另建固定分套。
struct 正式表达需求 final {
    新语言知识表达目的 目的 = 新语言知识表达目的::提问;
    正式表达对象种类 对象种类 = 正式表达对象种类::需求字段;
    std::optional<新语言知识含义操作> 含义操作{};
    正式内容引用定位 目标内容{};
    稳定编码 需求范围概念{};
    稳定编码 说话者{}, 受话者{}, 语言节点{};
    稳定编码 交互窗口{}, 交互作用域{};
    稳定编码 第三方指代概念{}, 选用指代名称关系{};
    // 0–100：槽位完备度/详略；语言模块按已填槽生成，不自行加戏。
    std::uint8_t 槽完备度 = 100;
    std::optional<稳定编码> 触发需求节点{};
    std::optional<稳定编码> 触发方法节点{};
    std::vector<稳定编码> 目标词条组{};
    std::optional<稳定编码> 指代实例{};
    std::optional<新接收认知来源> 原文来源{};
};

// 由现网字段询问目标形成正式表达需求（提问 × 需求字段）。
inline 正式表达需求 从字段询问目标形成表达需求(const 新正式字段询问目标& 目标) noexcept {
    正式表达需求 需求;
    需求.目的 = 新语言知识表达目的::提问;
    需求.对象种类 = 正式表达对象种类::需求字段;
    需求.含义操作 = 新语言知识含义操作::信息请求;
    需求.目标内容 = 目标.被询内容;
    需求.需求范围概念 = 目标.需求范围概念;
    需求.说话者 = 目标.说话者;
    需求.受话者 = 目标.受询者;
    需求.语言节点 = 目标.语言节点;
    需求.交互窗口 = 目标.交互窗口;
    需求.交互作用域 = 目标.交互作用域;
    需求.第三方指代概念 = 目标.第三方指代概念;
    需求.选用指代名称关系 = 目标.选用指代名称关系;
    需求.槽完备度 = 100;
    return 需求;
}

// 薄适配：把正式表达需求投影回现网字段询问目标，供尚未切换的调用方路径使用。
inline 新正式字段询问目标 投影为字段询问目标(const 正式表达需求& 需求) noexcept {
    新正式字段询问目标 目标;
    目标.被询内容 = 需求.目标内容;
    目标.需求范围概念 = 需求.需求范围概念;
    目标.语言节点 = 需求.语言节点;
    目标.说话者 = 需求.说话者;
    目标.受询者 = 需求.受话者;
    目标.交互窗口 = 需求.交互窗口;
    目标.交互作用域 = 需求.交互作用域;
    目标.第三方指代概念 = 需求.第三方指代概念;
    目标.选用指代名称关系 = 需求.选用指代名称关系;
    return 目标;
}


// 把正式表达需求投影到本地接缝，并填写候选上的正式表达需求节点（可空=值式本地请求）。
inline 新字段询问候选 装配字段询问候选(
    const 正式表达需求& 需求,
    新字段询问文字结果 话语,
    std::optional<稳定编码> 正式节点 = std::nullopt) noexcept {
    return 新字段询问候选{投影为字段询问目标(需求), std::move(话语), std::move(正式节点)};
}

// 本地接缝 → 正式表达需求（提问 × 需求字段）；与 从字段询问目标形成表达需求 同义，便于按接缝名调用。
inline 正式表达需求 从字段询问表达需求形成(
    const 新字段询问表达需求& 接缝) noexcept {
    return 从字段询问目标形成表达需求(接缝);
}

} // namespace 海中鱼巣
