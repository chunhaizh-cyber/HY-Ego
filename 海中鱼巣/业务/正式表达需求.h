#pragma once
#include <optional>
#include <variant>
#include "../领域/字段询问.数据.h"

namespace 海中鱼巣 {
struct 正式表达需求字段 final { 稳定编码 需求D{},字段特征类型{},需求范围概念{}; };
// 目标栏问题（7240 §5.5第1项，R120）：问D的目标存在或目标特征类型，问题主体＝D的需求主体，被问栏＝“需求”本身。
struct 正式表达需求目标栏 final { 稳定编码 需求D{},字段特征类型{},需求范围概念{},问题主体{}; };
// 招呼对象（CONV-EXPR-TEXT §3.5）：只携带招呼种类，表达用途须为招呼。
struct 正式表达招呼 final { 新招呼种类 种类=新招呼种类::发起; };
struct 正式表达成文参数 final {
    稳定编码 语言节点{},交互窗口{},交互作用域{},第三方指代概念{},选用指代名称关系{};
    std::uint8_t 槽完备度=100;
};
struct 正式表达来源关联 final {
    std::optional<稳定编码> 触发需求节点,触发方法节点,动作来源;
};
struct 正式表达需求 final {
    新表达用途 表达用途=新表达用途::疑问;
    // variant序号即组织知识适用对象种类：0 需求字段（载荷栏），1 招呼，2 需求目标栏。
    std::variant<正式表达需求字段,正式表达招呼,正式表达需求目标栏> 表达对象;
    新绑定指称 说话者,受话者;
    正式表达来源关联 来源关联;
    正式表达成文参数 成文参数;
};
inline 正式表达需求 从字段询问目标形成表达需求(const 新正式字段询问目标& 目标) {
    正式表达需求 r;
    // 多级路径不截断为首字段：保留为未绑定对象，由组织器返回范围未支持。
    const auto 字段=目标.被询内容.正式内容路径.size()==1?目标.被询内容.正式内容路径.front():稳定编码{};
    // 按被问结构选模板：被问栏＝需求（目标栏）→目标栏问题；否则→载荷栏问题（R120，用户裁决2026-11-12）。
    if(目标.目标栏问题)r.表达对象=正式表达需求目标栏{目标.被询内容.信息节点,字段,目标.需求范围概念,目标.问题主体};
    else r.表达对象=正式表达需求字段{目标.被询内容.信息节点,字段,目标.需求范围概念};
    r.说话者={新指称类别::存在,目标.说话者,{}};
    r.受话者={新指称类别::存在,目标.受询者,{}};
    r.成文参数={目标.语言节点,目标.交互窗口,目标.交互作用域,目标.第三方指代概念,目标.选用指代名称关系,100};
    return r;
}
inline 新正式字段询问目标 投影为字段询问目标(const 正式表达需求& 需求) {
    const auto& c=需求.成文参数;
    if(const auto* t=std::get_if<正式表达需求目标栏>(&需求.表达对象))
        return {{t->需求D,{t->字段特征类型}},t->需求范围概念,c.语言节点,需求.说话者.节点,需求.受话者.节点,
            c.交互窗口,c.交互作用域,c.第三方指代概念,c.选用指代名称关系,true,t->问题主体};
    const auto& d=std::get<正式表达需求字段>(需求.表达对象);
    return {{d.需求D,{d.字段特征类型}},d.需求范围概念,c.语言节点,需求.说话者.节点,需求.受话者.节点,
        c.交互窗口,c.交互作用域,c.第三方指代概念,c.选用指代名称关系};
}
} // namespace 海中鱼巣
