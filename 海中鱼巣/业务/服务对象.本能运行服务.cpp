新方法建立结果 服务对象本能运行服务::确保方法登记(const 新方法知识建立请求 &请求) noexcept
{
    try
    {
        const auto 配置材料 = 读取登记材料();
        const auto 连接关系 = 读取初始连接关系概念();
        if (!配置材料 || !连接关系)
            return {};
        新方法信息 声明;
        声明.作用域 = 请求.作用域;
        声明.行为 = 请求.行为;
        声明.实现方式 = 请求.实现方式;
        声明.方法头 = 请求.方法头;
        声明.参数规格组 = 请求.参数规格组;
        声明.初始模拟关系组 = 请求.初始模拟关系组;
        声明.初始模拟事件参数组 = 请求.初始模拟事件参数组;
        声明.初始必要条件 = 请求.初始必要条件;
        for (const auto& 分支 : 请求.执行分支组)
            声明.执行分支组.push_back({{}, 分支});
        声明.本能函数登记名 = 新本能函数登记名_获取服务对象;
        if (!请求.条件结果组.empty() || !声明一致(声明, *配置材料, *连接关系))
            服务对象故障(L"函数声明不符合四参数合同。");
        std::optional<稳定编码> 登记身份;
        {
            std::lock_guard 锁(实现_->互斥);
            登记身份 = 实现_->登记方法;
            if (!登记身份 && !实现_->初始化中)
                return {};
        }
        auto 原声明 = 请求;
        原声明.初始必要条件.reset();
        const auto 登记结果 =
            登记身份 ? 新方法建立结果{新方法操作状态::已找到, 登记身份}
                     : 实现_->方法.确保本能方法登记(std::string(新本能函数登记名_获取服务对象), 原声明);
        const auto 原信息 = 登记结果.方法节点 ? 实现_->方法.获取方法(*登记结果.方法节点) : std::nullopt;
        if (!原信息 || !请求.初始必要条件) 服务对象故障(L"补齐前的正式方法无法完整读回。");
        if (原信息->执行分支组.size() != 声明.执行分支组.size() ||
            原信息->执行分支组.front().定义 != 声明.执行分支组.front().定义)
            服务对象故障(L"正式执行分支声明冲突，保留原方法，不自动追加或迁移。");
        // 缓存身份不绕过补齐门；已有同义声明及后续C/R由方法owner只读复用。
        const auto 补齐 = 实现_->方法.补齐空头初始必要条件(*登记结果.方法节点, *原信息, *请求.初始必要条件);
        if (补齐.状态 != 新方法操作状态::已找到 || 补齐.方法节点 != 登记结果.方法节点)
            服务对象故障(L"初始必要条件补齐拒绝：声明冲突、已有知识缺声明或前提已变化。");
        const auto 登记读回 = 实现_->方法.获取方法(*补齐.方法节点);
        if (!登记读回 || !声明一致(*登记读回, *配置材料, *连接关系) || 登记读回->来源方法节点 || 登记读回->实例根节点 ||
            (登记结果.状态 == 新方法操作状态::已建立 && !登记读回->条件结果组.empty()))
            服务对象故障(L"登记读回不一致。");
        {
            std::lock_guard 锁(实现_->互斥);
            实现_->登记方法 = 登记结果.方法节点;
        }
        return 补齐;
    }
    catch (...)
    {
        服务对象故障(L"方法登记异常。");
    }
}
新本能函数本次条件结果对 服务对象本能运行服务::执行任务(const 方法参数场景 &参数场景,
                                                        稳定编码 执行身份) noexcept
{
    try
    {
        新本能函数本次条件结果对 运行;
        运行.结果.状态 = 新本能函数执行状态::参数不匹配;
        新服务对象获取配置 配置材料;
        稳定编码 登记身份{};
        稳定编码 连接关系{};
        {
            std::lock_guard 锁(实现_->互斥);
            if (!实现_->就绪 || 实现_->已关闭 || !实现_->配置 || !实现_->登记方法 || !实现_->初始连接关系)
                return 运行;
            配置材料 = *实现_->配置;
            登记身份 = *实现_->登记方法;
            连接关系 = *实现_->初始连接关系;
            ++实现_->活动;
        }
        实现::调用票 调用守卫{*实现_};
        if (参数场景.用途() != 新方法参数场景用途::执行 || 参数场景.全部角色绑定().size() != 5 ||
            新_本能函数管理类::读取本次执行实例(参数场景) != std::optional{执行身份})
            return 运行;
        std::array<稳定编码, 5> 参数节点{};
        for (std::uint32_t 序号 = 0; 序号 < 5; ++序号)
        {
            const auto *参数引用 = 参数场景.查询参数(序号 + 1);
            if (!参数引用 ||
                参数引用->信息类型 != (序号 >= 3 ? 新方法参数信息类型::特征 : 新方法参数信息类型::存在))
                return 运行;
            参数节点[序号] = 参数引用->信息节点;
            const auto &绑定 = 参数场景.全部角色绑定()[序号];
            if (绑定.有序引用 != *参数引用 || 绑定.参数角色节点.值 || 绑定.实际存在节点 ||
                !绑定.实际特征组.empty() || 绑定.任务虚拟存在引用 || 绑定.服务要求分项引用 ||
                绑定.服务要求确认引用)
                return 运行;
        }
        if (参数节点[1] != 配置材料.自我存在节点 || 参数节点[1] == 参数节点[2])
            return 运行;
        const auto 复核条件 = [&]() {
            const auto 方法信息 = 实现_->方法.获取方法(参数场景.方法节点());
            const auto 执行信息 = 实现_->任务.获取执行实例(执行身份);
            const auto 任务信息 = 执行信息 ? 实现_->任务.获取任务(执行信息->任务节点) : std::nullopt;
            if (!方法信息 || !执行信息 || !任务信息)
                服务对象故障(L"正式执行身份不能读回。");
            if (方法信息->节点 != 登记身份 || !声明一致(*方法信息, 配置材料, 连接关系) ||
                方法信息->启用状态 != 新方法启用状态::启用 || 方法信息->来源方法节点 ||
                方法信息->实例根节点 || 执行信息->状态 != 新任务执行状态::执行中 || 执行信息->结束时间 ||
                执行信息->方法节点 != 方法信息->节点 || 任务信息->当前状态 != 新任务状态::执行中 ||
                任务信息->最近执行实例节点 != std::optional{执行身份} ||
                任务信息->最近方法节点 != std::optional{方法信息->节点})
                return false;
            const auto 采用材料 = 实现_->任务.读取执行本能采用(执行身份);
            if (!采用材料 || 采用材料->来源方法节点 != 登记身份 ||
                采用材料->执行分支节点 != 参数场景.执行分支节点() ||
                采用材料->参数绑定组 != 参数场景.全部角色绑定() ||
                实现_->任务.复核执行本能输入(执行身份, 参数场景) != 新任务本能输入复核状态::仍具备)
                return false;
            if (!采用材料->执行分支节点 ||
                std::find(采用材料->来源执行分支节点组.begin(),采用材料->来源执行分支节点组.end(),
                    *采用材料->执行分支节点)==采用材料->来源执行分支节点组.end())
                服务对象故障(L"正式任务采用未保存所选执行分支的配对来源证明。");
            const auto 场景信息 = 实现_->世界.查询场景(参数节点[0]);
            const auto 自我信息 = 实现_->存在.获取存在(参数节点[1]);
            const auto 特征信息 = 实现_->特征.获取特征(参数节点[3]);
            if (!场景信息 || !自我信息 || !特征信息)
                return false;
            const auto 特征定义 = 实现_->特征.捕获特征匹配定义(特征信息->特征概念节点);
            if (!特征定义)
                服务对象故障(L"已绑定特征的正式定义不可读。");
            if (特征定义->特征类型根 != 配置材料.交互者特征类型节点 ||
                特征定义->材料类型 != 特征概念材料物理类型::存在节点引用 ||
                !实现_->存在.存在节点属于概念(参数节点[1], 配置材料.自我概念节点))
                return false;
            const auto &场景成员 = 场景信息->直接成员存在组;
            if (std::find(场景成员.begin(), 场景成员.end(), 参数节点[1]) == 场景成员.end() ||
                std::find(场景成员.begin(), 场景成员.end(), 参数节点[2]) == 场景成员.end())
                return false;
            const auto 所属=参数场景.读取存在参数特征(2,配置材料.交互者特征类型节点);
            using 查询状态=新方法参数特征读取状态;
            if(所属.状态==查询状态::参数未绑定||所属.状态==查询状态::信息类型不符||所属.状态==查询状态::未声明)
                服务对象故障(L"正式交互者所属窄读声明或参数不一致。");
            if((所属.状态!=查询状态::已读取&&所属.状态!=查询状态::当前值未取得)
                ||!所属.特征||所属.特征->节点!=参数节点[3])return false;
            // 结果特征：自我的服务对象特征（R93）。
            const auto 服务对象 = 参数场景.读取存在参数特征(2,配置材料.服务对象特征类型节点);
            if(服务对象.状态==查询状态::参数未绑定||服务对象.状态==查询状态::信息类型不符||服务对象.状态==查询状态::未声明)
                服务对象故障(L"正式服务对象特征所属窄读声明或参数不一致。");
            if((服务对象.状态!=查询状态::已读取&&服务对象.状态!=查询状态::当前值未取得)
                ||!服务对象.特征||服务对象.特征->节点!=参数节点[4])return false;
            // 每次使用正式方法当前声明，而不是用运行服务的私有配置替代条件。
            const auto 分支读取 = 实现_->方法.读取执行分支必要条件(方法信息->节点, 参数场景.执行分支节点());
            if (分支读取.状态 == 新方法执行分支读取状态::分支未指定 ||
                分支读取.状态 == 新方法执行分支读取状态::分支不属于方法 ||
                分支读取.状态 == 新方法执行分支读取状态::方法不存在)
                服务对象故障(L"已冻结执行分支或正式方法身份不一致。");
            if (分支读取.状态 != 新方法执行分支读取状态::已读取) return false;
            const auto &必要条件 = 分支读取.有效必要条件;
            const auto &人类条件 = 必要条件.条件.条件项组.front();
            const auto &不同条件 = 必要条件.条件.参数关系组.front();
            if (参数节点[不同条件.左参数序号 - 1] == 参数节点[不同条件.右参数序号 - 1])
                return false;
            const auto 人类匹配 = 实现_->存在.采集存在概念匹配材料(
                参数节点[人类条件.参数序号 - 1], *人类条件.存在概念节点);
            // 未知或冲突只表示本次必要条件未确认，不生成非人类事实。
            if (人类匹配.匹配.状态 != 新存在概念匹配状态::匹配)
                return false;
            const auto &连接限定 = 必要条件.场景事实限定组.front();
            const auto 关系保护 = 实现_->方法.读取初始场景事实概念保护(连接限定.关系概念节点);
            const 基础范围概念定义 预期关系{基础概念原语::具名领域身份, {14}, {}};
            if (关系保护.状态 != 正式结构操作状态::已读取 || !关系保护.信息 ||
                关系保护.信息->节点 != 连接关系 ||
                关系保护.信息->定义 != 正式结构定义{预期关系} || 关系保护.完整保护组.empty())
                服务对象故障(L"初始场景事实关系未取得正式定义保护。");
            const auto S = 参数节点[连接限定.场景参数序号 - 1];
            const auto A = 参数节点[连接限定.主体参数序号 - 1];
            const auto B = 参数节点[连接限定.对象参数序号 - 1];
            const auto F = 参数节点[连接限定.特征参数序号 - 1];
            const auto 连接事实组 = 实现_->连接.读取已确认连接事实(S, A, B, F);
            for (const auto &事实 : 连接事实组)
                if (事实.现实场景 != S || 事实.自我存在 != A || 事实.目标存在 != B || 事实.交互者特征 != F)
                    服务对象故障(L"连接事实owner返回的参数归属与必要条件不一致。");
            return !连接事实组.empty();
        };
        服务对象运行适配 后端;
        后端.事实读取=&实现_->连接;
        后端.条件读取=[&](const 方法参数场景& S) {
            const auto M=实现_->方法.获取方法(S.方法节点());
            if (!M||M->节点!=登记身份||!声明一致(*M,配置材料,连接关系))
                服务对象故障(L"共享核心读取必要声明不一致。");
            const auto 分支读取=实现_->方法.读取执行分支必要条件(M->节点,S.执行分支节点());
            if(分支读取.状态==新方法执行分支读取状态::分支未指定||
                分支读取.状态==新方法执行分支读取状态::分支不属于方法||
                分支读取.状态==新方法执行分支读取状态::方法不存在)
                服务对象故障(L"共享核心所选正式执行分支身份不一致。");
            if (分支读取.状态!=新方法执行分支读取状态::已读取)
                return std::optional<新方法初始必要条件定义>{};
            return std::optional{分支读取.有效必要条件};
        };
        后端.停止读取=[&]() { std::lock_guard 锁(实现_->互斥); return 实现_->已关闭; };
        后端.环境读取=[&](const 方法参数场景&,新交互绑定& B) {
            // 每次核心复核都重读原T/X/采用及场景，不缓存进入时的许可。
            if (!复核条件()) return 新交互求值状态::前提变化;
            // 绑定只承载连接条件（交互者特征为参数4）；写回目标由共享核心直接取容器参数5（R93）。
            B.场景=参数节点[0]; B.自我=参数节点[1]; B.对端=参数节点[2]; B.交互者特征=参数节点[3];
            return 新交互求值状态::已取得;
        };
        后端.概念核验=[&](稳定编码 E,稳定编码 C) {
            return 实现_->存在.采集存在概念匹配材料(E,C).匹配.状态;
        };
        后端.特征读取=[&](稳定编码 F) { return 实现_->特征.获取特征(F); };
        后端.动作建立=[&](const 方法参数场景& S,const 新交互绑定& B) {
            if (!复核条件()) return 稳定编码{};
            const auto 已有=实现_->动态.按来源查询动作(执行身份);
            if (已有.状态!=新动态操作状态::已完成||已有.动作)
                服务对象故障(L"执行动作来源重复或读取失败。");
            const auto 时间=UTC时钟适配器{}.读取当前UTC时间证据_v1({});
            if (!时间.成功()) 服务对象故障(L"UTC不可读取。");
            新_本能函数管理类::标记本次动作入口(S);
            const auto 发布=实现_->世界.建立动作动态(B.场景,{B.自我,S.方法节点(),执行身份,
                B.自我,B.交互者特征,{新状态时间语义::实例绝对UTC,时间.证据->UTC纳秒}});
            const auto 读=实现_->动态.按来源查询动作(执行身份);
            if (发布.状态!=新世界动作发布状态::已完成||!读.动作||读.状态!=新动态操作状态::已完成)
                服务对象故障(L"动作发布读回失败。");
            return 读.动作->节点;
        };
        后端.特征写入=[&](const 新交互绑定& B,稳定编码 动作) {
            新交互写入读回 回执;
            if (!复核条件()) { 回执.状态=新交互求值状态::前提变化; return 回执; }
            const auto 变化=实现_->世界.更新存在引用并形成动态(B.场景,B.自我,B.交互者特征,B.对端,动作);
            if (变化.状态==新世界特征变化状态::前提已变化) {
                回执.状态=新交互求值状态::前提变化; return 回执;
            }
            if (变化.状态!=新世界特征变化状态::已完成&&变化.状态!=新世界特征变化状态::无变化
                &&变化.状态!=新世界特征变化状态::已生成状态但无可连接前状态)
                服务对象故障(L"交互者引用更新未完成。");
            const auto F=实现_->特征.获取特征(B.交互者特征);
            if (!F||F->当前值!=std::optional<新特征准确值>{新特征准确值{B.对端}})
                服务对象故障(L"交互者引用读回不符。");
            回执.状态=新交互求值状态::已取得; 回执.新状态节点=变化.新状态节点;
            if (变化.动态发布结果&&变化.动态发布结果->动态建立结果)
                回执.变化动态节点=变化.动态发布结果->动态建立结果->动态节点;
            return 回执;
        };
        const auto 必要=后端.读取本次必要条件(参数场景);
        if (!必要) 服务对象故障(L"共享核心缺少已登记必要条件。");
        return 执行服务对象核心(参数场景,后端,*必要);
    }
    catch (...)
    {
        服务对象故障(L"任务执行异常。");
    }
}
