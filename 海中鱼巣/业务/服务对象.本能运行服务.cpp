// 2026-11-10用户裁决：交互者与服务对象分属两个方法确认。两者均无初始必要条件、单一执行分支；
// 获取服务对象的分支必要条件为“交互者有当前值”（参数2值属于交互者类型值域）。
新方法执行分支定义 预期执行分支(const 新服务对象获取配置 &配置材料, bool 交互者)
{
    新方法执行分支定义 单路径;
    单路径.必要条件.关系规则 = 新方法项关系规则::全部成立;
    if (交互者) return 单路径;
    新方法条件项定义 有交互者;
    有交互者.参数序号 = 2;
    有交互者.特征类型概念节点 = 配置材料.交互者特征类型节点;
    有交互者.特征值域概念节点 = 配置材料.交互者特征类型节点;
    单路径.必要条件.条件项组.push_back(std::move(有交互者));
    return 单路径;
}
bool 声明一致(const 新方法信息 &方法信息, const 新服务对象获取配置 &配置材料, bool 交互者)
{
    const auto 预期组 = 交互者 ? 获取交互者有序规格(配置材料) : 获取服务对象有序规格(配置材料);
    const auto 登记名 = 交互者 ? 新本能函数登记名_获取交互者 : 新本能函数登记名_获取服务对象;
    const auto 结果类型 = 交互者 ? 配置材料.交互者特征类型节点 : 配置材料.服务对象特征类型节点;
    if (方法信息.本能函数登记名 != 登记名 ||
        方法信息.作用域 != 新方法作用域::普通世界 || 方法信息.行为 != 新方法行为::改变 ||
        方法信息.实现方式 != 新方法实现方式::本能 ||
        方法信息.方法头.作用存在概念组 != std::vector<稳定编码>{配置材料.自我概念节点} ||
        方法信息.方法头.涉及特征类型概念组 != (交互者 ? std::vector<稳定编码>{配置材料.交互者特征类型节点}
            : 有序规格涉及特征类型(预期组)) ||
        方法信息.方法头.可能结果概念组 != std::vector<稳定编码>{结果类型} ||
        方法信息.参数规格组.size() != 预期组.size() || 方法信息.执行分支组.size() != (交互者 ? 0u : 1u))
        return false;
    if (!交互者 && 方法信息.执行分支组.front().定义 != 预期执行分支(配置材料, 交互者)) return false;
    for (std::size_t 序号 = 0; 序号 < 预期组.size(); ++序号)
    {
        const auto &参数规格 = 方法信息.参数规格组[序号];
        if (参数规格.有序规格 != std::optional{预期组[序号]} || 参数规格.参数角色节点.值 || 参数规格.存在概念节点 ||
            参数规格.要求场景 || !参数规格.特征规格组.empty() ||
            参数规格.对象种类 != 新方法参数对象种类::普通世界 || 参数规格.集合成员约束)
            return false;
    }
    return 方法信息.初始模拟关系组.empty() && 方法信息.初始模拟事件参数组.empty()
        && !方法信息.初始必要条件;
}
// 停用旧登记名的方法，保留历史执行记录。
template <class 方法服务类型>
void 停用旧版本(方法服务类型 &方法, std::string_view 登记名, const wchar_t *故障)
{
    const auto 旧 = 方法.查询本能登记(std::string(登记名));
    if (!旧.方法节点) return;
    const auto m = 方法.获取方法(*旧.方法节点);
    if (!m) 服务对象故障(故障);
    if (m->启用状态 != 新方法启用状态::启用) return;
    const auto 停用 = 方法.修改启用状态(m->节点, 新方法启用状态::停用);
    const auto 读回 = 方法.获取方法(m->节点);
    if ((停用 != 新方法操作状态::已修改 && 停用 != 新方法操作状态::无变化) || !读回 ||
        读回->启用状态 != 新方法启用状态::停用)
        服务对象故障(故障);
}
