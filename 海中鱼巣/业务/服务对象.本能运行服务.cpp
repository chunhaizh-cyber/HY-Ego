        const auto 已交互过 = [&](稳定编码 E) { return std::find(已交互.begin(), 已交互.end(), E) != 已交互.end(); };
        // 监听外设世界：按外设交互场景稳定编码升序（分配单调，即打开先后）。
        // 选取：优先已有现实对应存在且从未成为过交互者的；其次尚无现实对应存在的最早打开者；都没有时零动作。
        struct 候选 final { 稳定编码 外设场景, 外设交互者; std::optional<稳定编码> 对应存在; };
