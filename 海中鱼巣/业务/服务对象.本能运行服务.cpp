struct 服务对象本能运行服务::实现 final
{
    新_世界树类 &世界;
    新_方法类 &方法;
    新_任务类 &任务;
    新_存在类 &存在;
    新_特征类 &特征;
    新_动态类 &动态;
    连接本能运行服务 &连接;
    mutable std::mutex 互斥;
    std::condition_variable 退出条件;
    std::optional<新服务对象获取配置> 配置;
    std::optional<稳定编码> 登记方法;
    bool 初始化中 = false, 就绪 = false, 已关闭 = false;
    std::size_t 活动 = 0;
    struct 调用票
    {
        实现 &现场;
        ~调用票()
        {
            std::lock_guard 锁(现场.互斥);
            --现场.活动;
            现场.退出条件.notify_all();
        }
    };
};
服务对象本能运行服务::服务对象本能运行服务(新_世界树类 &世界服务, 新_方法类 &方法服务, 新_任务类 &任务服务,
                                           新_存在类 &存在服务, 新_特征类 &特征服务, 新_动态类 &动态服务,
                                           连接本能运行服务 &连接服务) noexcept
{
    try
    {
        实现_ = std::make_unique<实现>(世界服务, 方法服务, 任务服务, 存在服务, 特征服务, 动态服务, 连接服务);
    }
    catch (...)
    {
        服务对象故障(L"构造异常。");
    }
}
