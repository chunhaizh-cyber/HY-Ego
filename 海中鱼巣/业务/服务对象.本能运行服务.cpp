bool 服务对象本能运行服务::初始化(const 新服务对象获取配置 &配置材料) noexcept
{
    try
    {
        {
            std::lock_guard 锁(实现_->互斥);
            if (实现_->已关闭 || 实现_->初始化中)
                return false;
            if (实现_->配置 && *实现_->配置 != 配置材料)
                服务对象故障(L"重复初始化配置不一致。");
            if (实现_->就绪)
                return true;
            实现_->初始化中 = true;
        }
        // 服务对象特征与交互者特征是不同角色（R93）。
        if (!有效(配置材料.服务对象特征类型节点)
            || 配置材料.服务对象特征类型节点 == 配置材料.交互者特征类型节点
            || !有效(配置材料.参与自我类型) || !有效(配置材料.参与交互者类型) || !有效(配置材料.外设存在标识类型))
            服务对象故障(L"服务对象特征类型未配置或与交互者特征相同。");
        if (!实现_->存在.存在节点属于概念(配置材料.自我存在节点, 配置材料.自我概念节点) ||
            !实现_->存在.是存在概念节点(配置材料.通用存在概念节点) ||
            !实现_->存在.是存在概念节点(配置材料.人类概念节点))
            服务对象故障(L"登记概念或自我引用无效。");
        const auto 连接关系 = 实现_->方法.确保已确认消息连接概念();
        if (!有效(连接关系)) 服务对象故障(L"必要连接关系的正式概念没有完整建立。");
        // v2把交互者当作结果，与R93冲突：停用，保留历史执行记录。
        if (const auto v2 = 实现_->方法.查询本能登记(std::string(新本能函数登记名_旧四参数获取服务对象));
            v2.方法节点)
        {
            const auto m = 实现_->方法.获取方法(*v2.方法节点);
            if (!m) 服务对象故障(L"旧四参数获取服务对象方法不可读，保留并停止迁移。");
            if (m->启用状态 == 新方法启用状态::启用)
            {
                const auto 停用 = 实现_->方法.修改启用状态(m->节点, 新方法启用状态::停用);
                const auto 读回 = 实现_->方法.获取方法(m->节点);
                if ((停用 != 新方法操作状态::已修改 && 停用 != 新方法操作状态::无变化)
                    || !读回 || 读回->启用状态 != 新方法启用状态::停用)
                    服务对象故障(L"旧四参数获取服务对象停用读回失败。");
            }
        }
        const auto 旧登记 = 实现_->方法.查询本能登记(std::string(新本能函数登记名_旧两参数获取服务对象));
        if (旧登记.方法节点)
        {
            const auto 旧方法 = 实现_->方法.获取方法(*旧登记.方法节点);
            if (!旧方法 || 旧方法->参数规格组.size() != 2)
                服务对象故障(L"旧两参数方法不可确认，保留并停止迁移。");
            实现_->方法.退役旧网页本能登记(std::string(新本能函数登记名_旧两参数获取服务对象));
            const auto 返回材料 = 实现_->方法.获取方法(*旧登记.方法节点);
            if (!返回材料 || 返回材料->启用状态 != 新方法启用状态::停用)
                服务对象故障(L"旧方法退役未完成。");
        }
        {
            std::lock_guard 锁(实现_->互斥);
            实现_->配置 = 配置材料;
            实现_->初始连接关系 = 连接关系;
        }
        const auto 函数登记 = 新_本能函数管理类::初始化();
        const auto 端口装配 = 新_本能函数管理类::装配服务对象获取端口(shared_from_this());
        if ((函数登记 != 新本能函数登记状态::已登记 && 函数登记 != 新本能函数登记状态::精确重复) ||
            (端口装配 != 新本能函数端口装配状态::已装配 && 端口装配 != 新本能函数端口装配状态::精确重复))
            服务对象故障(L"端口登记失败。");
        const auto 登记参数 = 实现_->方法.建立服务需求登记参数场景();
        if (!登记参数.参数场景)
            服务对象故障(L"登记场景建立失败。");
        const auto 返回材料 = 新_本能函数管理类::执行(新本能函数登记名_获取服务对象, *登记参数.参数场景);
        if (返回材料.结果.状态 != 新本能函数执行状态::已按合同返回 || 返回材料.结果.动作动态节点 ||
            返回材料.结果.服务对象观察材料)
            服务对象故障(L"登记执行未完整返回或产生虚假动作。");
        {
            std::lock_guard 锁(实现_->互斥);
            实现_->就绪 = 实现_->登记方法.has_value();
            实现_->初始化中 = false;
        }
        return true;
    }
    catch (...)
    {
        服务对象故障(L"初始化异常。");
    }
}
bool 服务对象本能运行服务::关闭() noexcept
{
    try
    {
        {
            std::unique_lock 锁(实现_->互斥);
            if (实现_->初始化中)
                return false;
            if (实现_->已关闭)
                return true;
            实现_->已关闭 = true;
            实现_->就绪 = false;
            实现_->退出条件.wait(锁, [&] { return 实现_->活动 == 0; });
        }
        return 新_本能函数管理类::关闭服务对象获取端口(*this) == 新本能函数端口装配状态::已关闭;
    }
    catch (...)
    {
        服务对象故障(L"关闭异常。");
    }
}
