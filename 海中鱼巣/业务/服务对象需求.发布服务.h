    整体目标关联读取结果 读取整体目标关联(
        稳定编码 场景节点, 稳定编码 主体节点, 稳定编码 指定需求节点,
        const std::vector<基础联合节点快照>& 初始保护) const;
    新引用内容目标判定 求值内容内部(const 新需求完整目标&, bool 要求当前引用) const noexcept;
    struct 实现;
    std::unique_ptr<实现> 实现_;
