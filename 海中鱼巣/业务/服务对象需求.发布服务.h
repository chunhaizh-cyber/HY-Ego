enum class 服务对象需求发布状态 : std::uint8_t {
    已发布 = 1, 已复用, 需求不存在, 主体不符, 非被认知需求,
    需重新确认, 来源不符, 前提已变化, 已关闭, 已读取, 已发布但当前读回变化, 旧需求特征待迁移, 需求信息待完善, 需求未满足
};
struct 需求特征迁移缺口 final {
    稳定编码 原特征节点;
    std::optional<稳定编码> 需求节点, 动作节点, 状态节点;
    std::string 原因;
};
struct 服务对象需求发布请求 final {
    稳定编码 场景节点, 服务对象节点, 需求节点;
    稳定编码 动作定义节点, 动作来源节点, 执行主体节点;
    std::optional<稳定编码> 既有动作节点;
};
enum class 服务对象需求发生读取状态 : std::uint8_t {
    已读取=1, 状态未找到, 非需求状态, 发生来源未取得, 迁移恢复状态
};
struct 服务对象需求发生投影 final {
    新需求发生关联 关联;
    新状态信息 状态;
};
struct 服务对象需求发生读取结果 final {
    服务对象需求发生读取状态 状态=服务对象需求发生读取状态::状态未找到;
    std::optional<服务对象需求发生投影> 发生;
};
struct 服务对象需求发布结果 final {
    服务对象需求发布状态 状态 = 服务对象需求发布状态::来源不符;
    std::optional<稳定编码> 需求特征节点, 需求节点, 动作节点;
    std::optional<新世界特征变化结果> 变化;
    std::vector<需求特征迁移缺口> 迁移缺口组;
    std::optional<服务对象需求发生投影> 需求发生;
    bool 本次新建发生=false;
};
struct 服务对象需求读取结果 final {
    服务对象需求发布状态 状态 = 服务对象需求发布状态::来源不符;
    std::optional<稳定编码> 需求特征节点;
    std::optional<稳定编码> 当前需求节点;
    std::vector<稳定编码> 历史需求节点组, 需重新确认节点组;
    std::vector<需求特征迁移缺口> 迁移缺口组;
    std::vector<稳定编码> 待完善节点组;
};
enum class 服务对象需求内容读取状态 : std::uint8_t {
    已读取=1, 输入不合法, 未就绪, 主体不在场景,
    需求特征未取得, 当前需求未取得, 前提已变化,
    结构定义不适用, 内容项未支持, 旧需求特征待迁移, 资源失败
};
struct 服务对象当前需求结构内容 final {
    稳定编码 场景节点, 主体存在节点, 特征节点, 需求节点;
    正式结构有效内容 结构定义;
    新被认知需求直接内容 需求内容;
};
struct 服务对象需求内容读取结果 final {
    服务对象需求内容读取状态 状态=服务对象需求内容读取状态::输入不合法;
    std::optional<服务对象当前需求结构内容> 信息;
    std::vector<基础联合节点快照> 完整保护组;
};

// 编排正式owner；不拥有需求、特征或动作事实，不建立第二份需求账。
