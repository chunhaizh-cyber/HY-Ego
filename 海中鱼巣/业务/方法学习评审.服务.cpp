bool 结果为空(const 新方法结果定义& r) {
    return r.结果项组.empty() && r.参数关系组.empty() && r.场景事实限定组.empty();
}
const 新本能函数条件角色材料* 查参数(const 新本能函数本次条件& 条件, std::uint32_t 序号,
    新方法参数信息类型 类型) {
    for (const auto& 角色 : 条件.参数角色组)
        if (角色.有序引用 && 角色.有序引用->序号 == 序号 && 角色.有序引用->信息类型 == 类型) return &角色;
    return nullptr;
}
bool 含差异(const 新尝试补全候选& c, 新尝试补全差异种类 种类, std::uint32_t p, std::uint32_t q = 0) {
    return std::count(c.差异项组.begin(), c.差异项组.end(), 新尝试补全差异项{种类, p, q}) == 1;
}
// §5 第2项：不经导出函数，按归档原始数据逐项独立核对收窄值、结果值与差异。
bool 依据独立核验(const 新方法问题反馈材料& 材料, const 新尝试补全候选& c) {
    const auto& 原条件 = 材料.任务采用->原始条件;
    const auto& 运行 = *材料.本次运行对;
    if (c.实际条件.条件项组.size() != 原条件.条件项组.size()
        || c.实际条件.参数关系组 != 原条件.参数关系组
        || c.实际条件.场景事实限定组 != 原条件.场景事实限定组
        || c.实际条件.关系规则 != 原条件.关系规则) return false;
    std::size_t 收窄数 = 0;
    for (std::size_t k = 0; k < 原条件.条件项组.size(); ++k) {
        const auto& a = 原条件.条件项组[k];
        const auto& b = c.实际条件.条件项组[k];
        if (a == b) continue;
        auto 仅值域不同 = a; 仅值域不同.精确数值域 = b.精确数值域;
        if (仅值域不同 != b || !a.精确数值域 || !b.精确数值域
            || b.精确数值域->下界 != b.精确数值域->上界) return false;
        const auto v = b.精确数值域->下界;
        if (v < a.精确数值域->下界 || v > a.精确数值域->上界) return false;
        const auto* 角色 = 查参数(运行.条件, b.参数序号, 新方法参数信息类型::特征);
        if (!角色) return false;
        const auto 实际 = std::find_if(角色->实际特征组.begin(), 角色->实际特征组.end(),
            [&](const auto& f) { return f.特征节点 == 角色->有序引用->信息节点; });
        if (实际 == 角色->实际特征组.end() || 实际->动作前准确值 != std::optional<新特征准确值>{新特征准确值{v}})
            return false;
        if (!含差异(c, 新尝试补全差异种类::条件收窄, b.参数序号)) return false;
        ++收窄数;
    }
    if (c.与原条件相同 != (收窄数 == 0)) return false;
    const auto 本次形成 = [&](const 新状态信息& s) {
        return std::find(运行.结果.已形成状态节点组.begin(), 运行.结果.已形成状态节点组.end(), s.节点)
            != 运行.结果.已形成状态节点组.end();
    };
    for (const auto& r : c.实际结果.结果项组) {
        const auto* 角色 = 查参数(运行.条件, r.参数序号, 新方法参数信息类型::特征);
        if (!角色) return false;
        const auto s = std::find_if(材料.实际状态组.begin(), 材料.实际状态组.end(), [&](const auto& x) {
            return x.来源实例特征节点 == 角色->有序引用->信息节点 && 本次形成(x);
        });
        if (s == 材料.实际状态组.end() || !s->固定准确值) return false;
        if (r.精确数值域) {
            if (r.精确数值域->下界 != r.精确数值域->上界
                || *s->固定准确值 != 新特征准确值{r.精确数值域->下界}) return false;
        } else {
            const auto 关系 = std::find_if(c.实际结果.参数关系组.begin(), c.实际结果.参数关系组.end(),
                [&](const auto& x) { return x.种类 == 新方法参数关系种类::特征引用存在 && x.左参数序号 == r.参数序号; });
            if (关系 == c.实际结果.参数关系组.end()) return false;
            const auto* q = 查参数(运行.条件, 关系->右参数序号, 新方法参数信息类型::存在);
            if (!q || *s->固定准确值 != 新特征准确值{q->有序引用->信息节点}) return false;
            if (!含差异(c, 新尝试补全差异种类::结果关系新增, r.参数序号, 关系->右参数序号)) return false;
        }
        if (!含差异(c, 新尝试补全差异种类::结果新增, r.参数序号)) return false;
    }
    for (const auto& x : c.实际结果.参数关系组)
        if (x.种类 != 新方法参数关系种类::特征引用存在
            || std::none_of(c.实际结果.结果项组.begin(), c.实际结果.结果项组.end(),
                [&](const auto& r) { return r.参数序号 == x.左参数序号; })) return false;
    return c.差异项组.size() == 收窄数 + c.实际结果.结果项组.size() + c.实际结果.参数关系组.size();
}
// §5 第5项：知识不得引用本次运行的实例身份（参数实参、实际存在/特征、状态）。
bool 不含实例身份(const 新方法问题反馈材料& 材料, const 新方法条件结果定义& 定义) {
    std::set<稳定编码> 实例;
    for (const auto& 角色 : 材料.本次运行对->条件.参数角色组) {
        if (角色.有序引用) 实例.insert(角色.有序引用->信息节点);
        if (角色.实际存在节点) 实例.insert(*角色.实际存在节点);
        if (角色.世界场景节点) 实例.insert(*角色.世界场景节点);
        for (const auto& f : 角色.实际特征组) 实例.insert(f.特征节点);
    }
    for (const auto& s : 材料.实际状态组) { 实例.insert(s.节点); 实例.insert(s.被描述存在节点); 实例.insert(s.来源实例特征节点); }
    const auto 含 = [&](const std::optional<稳定编码>& x) { return x && 实例.contains(*x); };
    for (const auto& c : 定义.条件.条件项组)
        if (含(c.存在概念节点) || 含(c.特征类型概念节点) || 含(c.特征值域概念节点)
            || 含(c.二次特征概念节点) || 含(c.状态或动态概念节点)
            || (c.引用内容条件 && 实例.contains(c.引用内容条件->要求概念节点))) return false;
    for (const auto& r : 定义.结果.结果项组)
        if (含(r.特征类型概念节点) || 含(r.特征值域概念节点) || 含(r.变化方向概念节点)
            || 含(r.状态或动态概念节点)
            || (r.引用内容结果 && 实例.contains(r.引用内容结果->要求概念节点))) return false;
    return true;
}
