方法学习评审服务::方法学习评审服务(const 新方法问题归档接口& 归档, const 新_方法类& 方法) noexcept
    : 归档_(归档), 方法_(方法) {}

新学习评审结论 方法学习评审服务::评审尝试补全(const 新尝试补全候选& 候选,
    std::optional<新尝试补全授权>& 输出) const {
    输出.reset();
    try {
        // 1 自行读取来源
        const auto 读回 = 归档_.读取方法问题归档(候选.归档节点);
        if (读回.状态 == 新方法问题归档状态::资源失败) return 新学习评审结论::资源失败;
        if ((读回.状态 != 新方法问题归档状态::已保存 && 读回.状态 != 新方法问题归档状态::精确重复)
            || 读回.归档节点 != std::optional{候选.归档节点} || !读回.材料) return 新学习评审结论::来源不可重建;
        const auto& 材料 = *读回.材料;
        if (!材料.任务采用 || !材料.本次运行对 || 材料.来源抽象方法节点 != 候选.方法节点
            || 材料.任务采用->来源配对节点 != 候选.原配对节点) return 新学习评审结论::来源不可重建;
        const auto 方法 = 方法_.获取方法(候选.方法节点);
        if (!方法) return 新学习评审结论::方法入口已变化;
        // 4（重复消费）：前次已落地
        if (方法_.查找尝试配对(候选.方法节点, 候选.实际条件, 候选.实际结果)) return 新学习评审结论::已发布;
        // 3 方法入口
        if (方法->实现方式 != 新方法实现方式::本能 || 方法->启用状态 != 新方法启用状态::启用
            || 方法->来源方法节点 || 方法->实例根节点 || !方法->本能函数登记名
            || 方法->参数规格组 != 材料.任务采用->参数要求组) return 新学习评审结论::方法入口已变化;
        for (const auto B : 候选.来源执行分支节点组)
            if (std::none_of(方法->执行分支组.begin(), 方法->执行分支组.end(),
                [&](const auto& x) { return x.节点 == B; })) return 新学习评审结论::方法入口已变化;
        // 4 前提
        const auto 原 = std::find_if(方法->条件结果组.begin(), 方法->条件结果组.end(),
            [&](const auto& p) { return p.配对节点 == 候选.原配对节点; });
        if (原 == 方法->条件结果组.end() || 原->条件 != 材料.任务采用->原始条件 || !结果为空(原->结果))
            return 新学习评审结论::前提已变化;
        if (!候选.与原条件相同)
            for (const auto& p : 方法->条件结果组)
                if (p.条件 == 候选.实际条件) return 新学习评审结论::前提已变化;
        // 1 来源可重建：以独立读取的归档与方法重算
        const auto 重算 = 形成尝试补全候选(材料, 候选.归档节点, *方法, 方法_);
        if (重算.种类 != 新尝试补全导出种类::候选 || !重算.候选 || *重算.候选 != 候选)
            return 新学习评审结论::来源不可重建;
        // 2 依据独立核验
        if (!依据独立核验(材料, 候选)) return 新学习评审结论::依据不符;
        // 5 结构自足
        新方法条件结果定义 定义;
        定义.条件 = 候选.实际条件; 定义.结果 = 候选.实际结果; 定义.来源执行分支节点组 = 候选.来源执行分支节点组;
        const auto 核验 = 方法_.核验条件结果定义(候选.方法节点, 定义);
        if (核验 == 新方法学习发布状态::资源失败) return 新学习评审结论::资源失败;
        if (核验 != 新方法学习发布状态::已发布 || !不含实例身份(材料, 定义)) return 新学习评审结论::结构不自足;
        新尝试补全评审依据 依据;
        依据.本能函数登记名 = *方法->本能函数登记名;
        依据.参数规格组 = 方法->参数规格组;
        依据.原配对节点 = 原->配对节点;
        依据.原配对条件 = 原->条件;
        依据.原配对结果 = 原->结果;
        for (const auto& p : 方法->条件结果组) 依据.方法现有配对节点组.push_back(p.配对节点);
        输出.emplace(新尝试补全授权(候选, std::move(依据)));
        return 新学习评审结论::已授权;
    } catch (const std::bad_alloc&) {
        输出.reset();
        return 新学习评审结论::资源失败;
    }
}
