namespace 海中鱼巣 {

struct 治理时间概念集合 final {
    稳定编码 时间窗口余量;
    稳定编码 时间不足;
    稳定编码 恰好足够;
    稳定编码 时间有余量;
};

enum class 治理二次特征状态 : std::uint8_t {
    已完成 = 1, 尚未初始化, 输入不合法, 材料不足,
    计算不可表示, 结构不一致, 资源失败
};

struct 治理时间概念初始化结果 final {
    治理二次特征状态 状态 = 治理二次特征状态::尚未初始化;
    std::optional<治理时间概念集合> 概念;
};

struct 治理时间余量解释 final {
    需求时序顺序 顺序 = 需求时序顺序::第一后第二;
    时序耗时依据 依据 = 时序耗时依据::保证最大;
    稳定编码 需求节点;
    稳定编码 二次特征类型根;
    稳定编码 结果值域概念;
    std::int64_t 满足时刻纳秒 = 0;
    std::int64_t 最晚允许时刻纳秒 = 0;
    std::int64_t 准确余量纳秒 = 0;
};

struct 治理时序解释结果 final {
    治理二次特征状态 状态 = 治理二次特征状态::尚未初始化;
    std::optional<需求时序可达性裁决请求> 来源请求;
    std::optional<需求时序可达性裁决结果> 裁决;
    std::vector<治理时间余量解释> 时间比较组;
};

// 不拥有依赖，不解释词面，不生成世界事实或执行授权。
// 初始化逐调用发布；计算只读。依赖服务须比本服务活得更久。
class 治理二次特征应用服务 final {
public:
    治理二次特征应用服务(概念_二次特征类&, 新_词类&,
        概念_名称关系类&) noexcept;
    治理时间概念初始化结果 初始化(稳定编码 中文语言节点) noexcept;
    治理时序解释结果 裁决时序(
        const 需求时序可达性裁决请求&) const noexcept;

private:
    概念_二次特征类& 概念服务_;
    新_词类& 词服务_;
    概念_名称关系类& 名称服务_;
    mutable std::mutex 锁_;
    // 保留分步成功身份以支持失败后重试；不构成第二事实存储。
    治理时间概念集合 定位_;
    std::optional<稳定编码> 语言_;
    bool 已初始化_ = false;
};

} // namespace 海中鱼巣
