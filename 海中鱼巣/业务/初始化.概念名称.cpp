初始化概念名称环境 读取先天概念名称环境(const 概念_特征类& 特征概念服务) {
    const auto 先天 = 特征概念服务.获取先天特征概念();
    if (!先天) throw std::runtime_error("先天特征概念集合读取失败");
    初始化概念名称环境 环境;
    for (const auto 目标 : 先天名称顺序) {
        const auto 身份 = 先天身份(*先天, 目标);
        const auto 定义 = 特征概念服务.获取特征概念(身份);
        if (!有效(身份) || !定义 || 定义->节点 != 身份
            || std::any_of(环境.目标组.begin(), 环境.目标组.end(),
                [身份](const auto& 项) { return 项.定义依据.节点 == 身份; }))
            throw std::runtime_error("先天特征概念身份或完整定义读取失败");
        环境.目标组.push_back({目标, std::string{标准名称(目标)}, *定义});
    }
    return 环境;
}

