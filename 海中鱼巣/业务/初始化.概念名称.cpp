bool 定义一致(const 特征概念信息& 左, const 特征概念信息& 右) {
    return 左.节点 == 右.节点 && 左.材料类型 == 右.材料类型
        && 左.值域 == 右.值域 && 左.单位 == 右.单位
        && 左.比较规则 == 右.比较规则 && 左.聚合规则 == 右.聚合规则;
}

bool 源范围一致(const 初始化源范围& 左, const 初始化源范围& 右) noexcept {
    return 左.行号 == 右.行号 && 左.字节起点 == 右.字节起点
        && 左.字节终点 == 右.字节终点 && 左.标量起点 == 右.标量起点
        && 左.标量终点 == 右.标量终点;
}

bool 定义载荷一致(const 初始化定义载荷& 左, const 初始化定义载荷& 右) {
    if (左.valueless_by_exception() || 右.valueless_by_exception()
        || 左.index() != 右.index()) return false;
    return std::visit([&](const auto& 左值) {
        using 载荷类型 = std::decay_t<decltype(左值)>;
        const auto& 右值 = std::get<载荷类型>(右);
        if constexpr (std::is_same_v<载荷类型, 初始化概念归类材料>) {
            return 左值.下位.局部编号 == 右值.下位.局部编号
                && 左值.上位.局部编号 == 右值.上位.局部编号;
        } else if constexpr (std::is_same_v<载荷类型, 初始化特征定义材料>) {
            if (左值.主体概念.局部编号 != 右值.主体概念.局部编号
                || 左值.特征类型.局部编号 != 右值.特征类型.局部编号
                || 左值.值.valueless_by_exception() || 右值.值.valueless_by_exception()
                || 左值.值.index() != 右值.值.index()) return false;
            if (const auto* 整数 = std::get_if<std::int64_t>(&左值.值))
                return *整数 == std::get<std::int64_t>(右值.值);
            return std::get<初始化符号引用>(左值.值).局部编号
                == std::get<初始化符号引用>(右值.值).局部编号;
        } else if constexpr (std::is_same_v<载荷类型, 初始化组成定义材料>) {
            return 左值.部分.局部编号 == 右值.部分.局部编号
                && 左值.整体.局部编号 == 右值.整体.局部编号;
        } else if constexpr (std::is_same_v<载荷类型, 初始化名称提议材料>) {
            return 左值.概念.局部编号 == 右值.概念.局部编号
                && 左值.别名词面 == 右值.别名词面;
        } else if constexpr (std::is_same_v<载荷类型, 初始化结构化分量区间材料>) {
            return 左值.主体概念.局部编号 == 右值.主体概念.局部编号
                && 左值.分量序号 == 右值.分量序号
                && 左值.下界 == 右值.下界 && 左值.上界 == 右值.上界;
        } else {
            return false;
        }
    }, 左);
}

bool 定义材料一致(const 初始化定义材料& 左, const 初始化定义材料& 右) {
    if (左.原文 != 右.原文 || 左.符号组.size() != 右.符号组.size()
        || 左.定义组.size() != 右.定义组.size()) return false;
    if (!std::equal(左.符号组.begin(), 左.符号组.end(), 右.符号组.begin(),
            [](const auto& 左符号, const auto& 右符号) {
                return 左符号.引用.局部编号 == 右符号.引用.局部编号
                    && 左符号.角色类型 == 右符号.角色类型 && 左符号.词面 == 右符号.词面
                    && 源范围一致(左符号.来源, 右符号.来源);
            })) return false;
    return std::equal(左.定义组.begin(), 左.定义组.end(), 右.定义组.begin(),
        [](const auto& 左定义, const auto& 右定义) {
            return 左定义.局部编号 == 右定义.局部编号 && 左定义.模板 == 右定义.模板
                && 左定义.作用域 == 右定义.作用域
                && 源范围一致(左定义.来源, 右定义.来源)
                && 左定义.角色来源组.size() == 右定义.角色来源组.size()
                && std::equal(左定义.角色来源组.begin(), 左定义.角色来源组.end(),
                    右定义.角色来源组.begin(), [](const auto& 左角色, const auto& 右角色) {
                        return 左角色.角色 == 右角色.角色 && 左角色.行内词序 == 右角色.行内词序
                            && 源范围一致(左角色.来源, 右角色.来源);
                    })
                && 定义载荷一致(左定义.载荷, 右定义.载荷);
        });
}

bool 未完成(初始化概念名称结果& 结果, 初始化概念名称状态 状态,
    const char* 原因) {
    结果.状态 = 状态;
    结果.诊断说明 = 原因;
    return false;
}

bool 核对名称语言(初始化概念名称结果& 结果,
    稳定编码 语言节点, 稳定编码 规范化合同节点, const 新_语言类& 语言服务) {
    if (!有效(语言节点) || !有效(规范化合同节点)
        || 规范化合同节点 != 严格UTF8字节精确规范化合同节点)
        return 未完成(结果, 初始化概念名称状态::前置拒绝, "语言或规范化合同不合法");
    const auto 语言 = 语言服务.获取语言(语言节点);
    const auto 登记键 = 语言服务.按登记键查询("zh-CN");
    if (语言.状态 != 新语言查询状态::已找到 || !语言.信息
        || 登记键.状态 != 新语言查询状态::已找到 || !登记键.信息)
        return 未完成(结果, 初始化概念名称状态::工程未完成, "中文语言身份无法完整读回");
    if (语言.信息->节点 != 语言节点 || 语言.信息->登记键 != "zh-CN"
        || *语言.信息 != *登记键.信息)
        return 未完成(结果, 初始化概念名称状态::前置拒绝, "请求语言与正式中文登记身份不一致");
    return true;
}

bool 核对来源解释(初始化概念名称结果& 结果, const 初始化最小解释结果& 来源) {
    结果.阶段 = 初始化概念名称阶段::标准文本解释;
    结果.解释结果 = 来源;
    if (来源.工程控制 != 初始化工程控制::已完成)
        return 未完成(结果, 初始化概念名称状态::工程未完成, "名称来源解释工程控制未完成");
    if (来源.解释状态 != 初始化解释状态::已完整解释)
        return 未完成(结果, 初始化概念名称状态::解释未完成, "名称来源没有完整解释");
    if (!来源.材料 || 来源.诊断)
        return 未完成(结果, 初始化概念名称状态::前置拒绝, "名称来源完整解释形状不合法");

    // 所有计数上界均不超过原文字节数；只复核既有固定材料，不复制语法或UTF8规则。
    const auto 上界 = std::max(std::size_t{1}, 来源.材料->原文.size());
    初始化最小资源额度 额度{上界, 上界, 上界, 上界, 上界, 上界, 上界};
    const auto 实际解释 = 解释初始化标准文本(来源.材料->原文, 额度);
    if (实际解释.工程控制 != 初始化工程控制::已完成)
        return 未完成(结果, 初始化概念名称状态::工程未完成, "固定名称来源重新解释未完成");
    if (实际解释.解释状态 != 初始化解释状态::已完整解释 || !实际解释.材料
        || 实际解释.诊断 || !定义材料一致(*来源.材料, *实际解释.材料))
        return 未完成(结果, 初始化概念名称状态::前置拒绝, "名称来源载荷或范围与固定原文不一致");
    return true;
}

const 初始化已知概念目标& 环境目标(
    const 初始化概念名称环境& 环境, 初始化先天名称目标 目标) {
    const auto 位置 = std::find_if(环境.目标组.begin(), 环境.目标组.end(),
        [目标](const auto& 项) { return 项.来源 == 目标; });
    if (位置 == 环境.目标组.end())
        throw std::logic_error("已经核验的名称环境缺少目标");
    return *位置;
}

std::size_t 出现所属定义(const 初始化定义材料& 材料,
    const 初始化词面符号& 符号) {
    const auto 位置 = std::find_if(材料.定义组.begin(), 材料.定义组.end(),
        [&](const auto& 项) {
            return 项.来源.行号 == 符号.来源.行号
                && 项.来源.字节起点 <= 符号.来源.字节起点
                && 符号.来源.字节终点 <= 项.来源.字节终点;
        });
    if (位置 == 材料.定义组.end())
        throw std::logic_error("完整解释材料的符号没有所属定义");
    return 位置->局部编号;
}

void 添加来源(初始化名称发布项& 项, const 初始化源范围& 范围,
    std::size_t 定义编号) {
    if (std::none_of(项.来源范围组.begin(), 项.来源范围组.end(),
            [&](const auto& 已有) { return 源范围一致(已有, 范围); }))
        项.来源范围组.push_back(范围);
    if (std::find(项.来源定义编号组.begin(), 项.来源定义编号组.end(), 定义编号)
        == 项.来源定义编号组.end()) {
        项.来源定义编号组.push_back(定义编号);
    }
}

初始化概念名称结果 准备名称材料(const 初始化概念名称请求& 请求,
    const 新_语言类& 语言服务, const 概念_特征类& 特征概念服务,
    std::vector<特征概念信息>& 定义依据组) {
    初始化概念名称结果 结果;
    结果.阶段 = 初始化概念名称阶段::标准文本解释;
    结果.解释结果 = 解释初始化标准文本(请求.标准文本, 请求.解释额度);
    const auto& 解释 = *结果.解释结果;
    if (解释.工程控制 != 初始化工程控制::已完成) {
        未完成(结果, 初始化概念名称状态::工程未完成, "标准文本解释工程控制未完成");
        return 结果;
    }
    if (解释.解释状态 != 初始化解释状态::已完整解释) {
        未完成(结果, 初始化概念名称状态::解释未完成, "标准文本没有完整解释");
        return 结果;
    }
    if (!解释.材料) throw std::logic_error("完整解释缺少定义材料");

    结果.阶段 = 初始化概念名称阶段::前置核验;
    if (!有效(请求.语言节点) || !有效(请求.规范化合同节点)
        || 请求.规范化合同节点 != 严格UTF8字节精确规范化合同节点
        || 请求.环境.目标组.size() != 先天名称顺序.size()) {
        未完成(结果, 初始化概念名称状态::前置拒绝, "语言、规范化合同或环境形状不合法");
        return 结果;
    }
    if (!核对名称语言(结果, 请求.语言节点, 请求.规范化合同节点, 语言服务)) return 结果;
    const auto 先天 = 特征概念服务.获取先天特征概念();
    if (!先天) {
        未完成(结果, 初始化概念名称状态::工程未完成, "先天特征概念集合无法读回");
        return 结果;
    }
    std::vector<稳定编码> 身份组;
    for (const auto 目标 : 先天名称顺序) {
        const auto 数量 = std::count_if(请求.环境.目标组.begin(), 请求.环境.目标组.end(),
            [目标](const auto& 项) { return 项.来源 == 目标; });
        if (数量 != 1) {
            未完成(结果, 初始化概念名称状态::前置拒绝, "环境目标缺失或重复");
            return 结果;
        }
        const auto& 环境项 = 环境目标(请求.环境, 目标);
        const auto 身份 = 先天身份(*先天, 目标);
        if (环境项.标准词面 != 标准名称(目标) || !有效(身份)
            || 环境项.定义依据.节点 != 身份
            || std::find(身份组.begin(), 身份组.end(), 身份) != 身份组.end()) {
            未完成(结果, 初始化概念名称状态::前置拒绝, "环境词面或先天身份不相容");
            return 结果;
        }
        const auto 当前 = 特征概念服务.获取特征概念(身份);
        if (!当前) {
            未完成(结果, 初始化概念名称状态::工程未完成, "正式先天特征概念无法读回");
            return 结果;
        }
        if (!定义一致(*当前, 环境项.定义依据)) {
            未完成(结果, 初始化概念名称状态::前置拒绝, "环境定义依据与当前概念不一致");
            return 结果;
        }
        身份组.push_back(身份);
        初始化名称发布项 项{};
        项.目标 = 目标;
        项.来源 = 初始化名称来源::显式先天标准词面;
        项.词面 = 环境项.标准词面;
        项.概念节点 = 身份;
        结果.名称项组.push_back(std::move(项));
        定义依据组.push_back(*当前);
    }
    初始化名称发布项 别名{};
    别名.目标 = 初始化先天名称目标::RGB颜色;
    别名.来源 = 初始化名称来源::显式允许别名;
    别名.词面 = RGB允许别名;
    别名.概念节点 = 先天->RGB颜色;
    结果.名称项组.push_back(std::move(别名));
    定义依据组.push_back(环境目标(请求.环境, 初始化先天名称目标::RGB颜色).定义依据);

    结果.阶段 = 初始化概念名称阶段::目标覆盖;
    const auto& 材料 = *解释.材料;
    for (const auto& 符号 : 材料.符号组) {
        const auto 匹配 = std::find_if(结果.名称项组.begin(),
            结果.名称项组.begin() + 先天名称顺序.size(),
            [&](const auto& 项) { return 项.词面 == 符号.词面; });
        if (匹配 == 结果.名称项组.begin() + 先天名称顺序.size()) {
            结果.未绑定符号组.push_back(符号.引用);
            continue;
        }
        结果.符号绑定组.push_back({符号.引用, 匹配->概念节点});
        添加来源(*匹配, 符号.来源, 出现所属定义(材料, 符号));
    }
    for (const auto& 定义 : 材料.定义组) {
        const auto* 提议 = std::get_if<初始化名称提议材料>(&定义.载荷);
        bool 已采用 = false;
        if (提议) {
            if (提议->概念.局部编号 >= 材料.符号组.size())
                throw std::logic_error("完整解释中的别名概念引用越界");
            const auto& 主体 = 材料.符号组[提议->概念.局部编号];
            if (主体.词面 == "RGB颜色" && 提议->别名词面 == RGB允许别名) {
                const auto 来源 = std::find_if(定义.角色来源组.begin(), 定义.角色来源组.end(),
                    [](const auto& 项) { return 项.角色 == 初始化源角色::别名词面; });
                if (来源 == 定义.角色来源组.end())
                    throw std::logic_error("完整解释中的别名缺少词面来源");
                添加来源(结果.名称项组.back(), 来源->来源, 定义.局部编号);
                已采用 = true;
            } else {
                结果.未处理别名定义编号组.push_back(定义.局部编号);
            }
        }
        if (!已采用) 结果.未应用定义编号组.push_back(定义.局部编号);
    }
    if (std::any_of(结果.名称项组.begin(), 结果.名称项组.end(),
            [](const auto& 项) { return 项.来源范围组.empty(); })) {
        未完成(结果, 初始化概念名称状态::目标未覆盖, "标准文本未覆盖全部五个名称及允许RGB别名");
        return 结果;
    }
    结果.状态 = 初始化概念名称状态::已完成;
    return 结果;
}

void 添加符号绑定(初始化概念名称结果& 结果,
    初始化符号引用 出现, 稳定编码 概念节点) {
    if (std::none_of(结果.符号绑定组.begin(), 结果.符号绑定组.end(),
            [&](const auto& 已有) {
                return 已有.出现.局部编号 == 出现.局部编号 && 已有.概念节点 == 概念节点;
            }))
        结果.符号绑定组.push_back({出现, 概念节点});
}

初始化概念名称结果 准备已确认名称材料(const 初始化已确认特征名称请求& 请求,
    const 新_语言类& 语言服务, const 概念_特征类& 特征概念服务,
    std::vector<特征概念信息>& 定义依据组) {
    初始化概念名称结果 结果;
    if (!核对来源解释(结果, 请求.来源解释)) return 结果;
    结果.阶段 = 初始化概念名称阶段::前置核验;
    if (!核对名称语言(结果, 请求.语言节点, 请求.规范化合同节点, 语言服务)) return 结果;
    if (请求.目标组.empty()) {
        未完成(结果, 初始化概念名称状态::前置拒绝, "没有显式已确认特征名称目标");
        return 结果;
    }
    const auto& 材料 = *请求.来源解释.材料;
    std::vector<bool> 已采用别名(材料.定义组.size(), false);
    for (const auto& 目标 : 请求.目标组) {
        结果.阶段 = 初始化概念名称阶段::前置核验;
        if (!有效(目标.定义依据.节点) || 目标.词面.empty()
            || 目标.来源范围组.empty() || 目标.来源定义编号组.empty()
            || std::any_of(目标.来源定义编号组.begin(), 目标.来源定义编号组.end(),
                [&](const auto 编号) { return 编号 >= 材料.定义组.size(); })) {
            未完成(结果, 初始化概念名称状态::前置拒绝, "已确认FT身份或名称来源形状不合法");
            return 结果;
        }
        const auto 当前 = 特征概念服务.获取特征概念(目标.定义依据.节点);
        if (!当前) {
            未完成(结果, 初始化概念名称状态::工程未完成, "已确认FT完整定义无法读回");
            return 结果;
        }
        if (!定义一致(*当前, 目标.定义依据)) {
            未完成(结果, 初始化概念名称状态::前置拒绝, "已确认FT定义依据与当前正式定义不一致");
            return 结果;
        }
        auto 名称位置 = std::find_if(结果.名称项组.begin(), 结果.名称项组.end(),
            [&](const auto& 已有) {
                return 已有.概念节点 == 目标.定义依据.节点 && 已有.词面 == 目标.词面;
            });
        if (名称位置 == 结果.名称项组.end()) {
            初始化名称发布项 项{};
            项.目标 = 初始化先天名称目标::已确认特征概念;
            项.来源 = 初始化名称来源::显式已确认特征概念;
            项.词面 = 目标.词面;
            项.概念节点 = 目标.定义依据.节点;
            结果.名称项组.push_back(std::move(项));
            定义依据组.push_back(*当前);
            名称位置 = 结果.名称项组.end() - 1;
        }
        结果.阶段 = 初始化概念名称阶段::目标覆盖;
        std::vector<bool> 编号已覆盖(目标.来源定义编号组.size(), false);
        for (const auto& 范围 : 目标.来源范围组) {
            bool 已覆盖 = false;
            for (std::size_t i = 0; i < 目标.来源定义编号组.size(); ++i) {
                const auto 编号 = 目标.来源定义编号组[i];
                const auto& 定义 = 材料.定义组[编号];
                const auto 来源角色 = 定义.模板 == 初始化最小模板::概念归类
                    ? 初始化源角色::下位概念 : 初始化源角色::别名词面;
                if (定义.模板 != 初始化最小模板::概念归类
                    && 定义.模板 != 初始化最小模板::显式别名) continue;
                const auto 来源 = std::find_if(定义.角色来源组.begin(), 定义.角色来源组.end(),
                    [&](const auto& 项) {
                        return 项.角色 == 来源角色 && 源范围一致(项.来源, 范围);
                    });
                if (来源 == 定义.角色来源组.end()) continue;
                if (std::string_view(材料.原文).substr(范围.字节起点,
                        范围.字节终点 - 范围.字节起点) != 目标.词面) continue;
                const auto 引用 = 定义.模板 == 初始化最小模板::概念归类
                    ? std::get<初始化概念归类材料>(定义.载荷).下位
                    : std::get<初始化名称提议材料>(定义.载荷).概念;
                添加来源(*名称位置, 范围, 编号);
                添加符号绑定(结果, 引用, 目标.定义依据.节点);
                编号已覆盖[i] = true;
                if (定义.模板 == 初始化最小模板::显式别名) 已采用别名[编号] = true;
                已覆盖 = true;
            }
            if (!已覆盖) {
                未完成(结果, 初始化概念名称状态::前置拒绝, "名称来源不是所列定义的声明A或显式别名V");
                return 结果;
            }
        }
        if (std::any_of(编号已覆盖.begin(), 编号已覆盖.end(), [](bool 覆盖) { return !覆盖; })) {
            未完成(结果, 初始化概念名称状态::前置拒绝, "名称来源含有未实际覆盖范围的定义编号");
            return 结果;
        }
    }
    for (const auto& 符号 : 材料.符号组) {
        if (std::none_of(结果.符号绑定组.begin(), 结果.符号绑定组.end(),
                [&](const auto& 绑定) { return 绑定.出现.局部编号 == 符号.引用.局部编号; }))
            结果.未绑定符号组.push_back(符号.引用);
    }
    for (const auto& 定义 : 材料.定义组) {
        if (!已采用别名[定义.局部编号]) {
            结果.未应用定义编号组.push_back(定义.局部编号);
            if (定义.模板 == 初始化最小模板::显式别名)
                结果.未处理别名定义编号组.push_back(定义.局部编号);
        }
    }
    结果.状态 = 初始化概念名称状态::已完成;
    return 结果;
}

bool 核对词条(初始化概念名称结果& 结果, 稳定编码 语言节点, 稳定编码 规范化合同节点,
    const 新_词类& 词服务, 稳定编码 词条) {
    结果.阶段 = 初始化概念名称阶段::词条读回;
    auto& 项 = 结果.名称项组[*结果.当前名称项];
    项.词条读回 = 词服务.获取词条(词条);
    const auto& 读取 = *项.词条读回;
    if (读取.状态 != 新词条查询状态::已找到 || !读取.信息
        || 读取.信息->节点 != 词条 || 读取.信息->语言节点 != 语言节点
        || 读取.信息->规范化合同节点 != 规范化合同节点
        || 读取.信息->规范化词面 != 项.词面) {
        return 未完成(结果, 初始化概念名称状态::工程未完成, "词条身份、语言、规范化合同或精确词面读回不一致");
    }
    return true;
}

bool 核对当前概念(初始化概念名称结果& 结果, const 特征概念信息& 定义依据,
    const 概念_特征类& 特征概念服务, std::optional<稳定编码> 名称关系 = std::nullopt) {
    const auto& 项 = 结果.名称项组[*结果.当前名称项];
    const auto 当前 = 特征概念服务.获取特征概念(项.概念节点);
    if (!当前 || !定义一致(*当前, 定义依据)
        || (名称关系 && std::count(当前->名称关系.begin(), 当前->名称关系.end(), *名称关系) != 1)) {
        return 未完成(结果, 初始化概念名称状态::工程未完成, "目标概念定义或名称挂接读回不一致");
    }
    return true;
}

bool 核对关系列表(const 概念名称关系列表查询结果& 列表,
    const 概念_名称关系类& 名称服务, 稳定编码 名称关系,
    稳定编码 端点, bool 概念端) {
    if (列表.状态 != 概念名称关系查询状态::已找到
        || std::count(列表.名称关系节点组.begin(), 列表.名称关系节点组.end(), 名称关系) != 1)
        return false;
    for (const auto 关系 : 列表.名称关系节点组) {
        const auto 读取 = 名称服务.获取名称关系(关系);
        if (读取.状态 != 概念名称关系查询状态::已找到 || !读取.信息
            || 读取.信息->节点 != 关系
            || (概念端 ? 读取.信息->概念节点 : 读取.信息->词条节点) != 端点)
            return false;
    }
    return true;
}

bool 三路读回(初始化概念名称结果& 结果, const 特征概念信息& 定义依据,
    const 概念_名称关系类& 名称服务, const 概念_特征类& 特征概念服务,
    稳定编码 词条, 稳定编码 名称关系) {
    结果.阶段 = 初始化概念名称阶段::三路读回;
    auto& 项 = 结果.名称项组[*结果.当前名称项];
    项.名称读回 = 名称服务.获取名称关系(名称关系);
    if (项.名称读回->状态 != 概念名称关系查询状态::已找到 || !项.名称读回->信息
        || 项.名称读回->信息->节点 != 名称关系
        || 项.名称读回->信息->概念节点 != 项.概念节点
        || 项.名称读回->信息->词条节点 != 词条) {
        return 未完成(结果, 初始化概念名称状态::工程未完成, "名称关系端点读回不一致");
    }
    项.概念正向读回 = 名称服务.查询概念名称(项.概念节点);
    if (!核对关系列表(*项.概念正向读回, 名称服务, 名称关系, 项.概念节点, true))
        return 未完成(结果, 初始化概念名称状态::工程未完成, "概念正向完整名称关系读回不一致");
    项.词条反向读回 = 名称服务.查询词条候选概念(词条);
    if (!核对关系列表(*项.词条反向读回, 名称服务, 名称关系, 词条, false))
        return 未完成(结果, 初始化概念名称状态::工程未完成, "词条反向完整名称关系读回不一致");
    return 核对当前概念(结果, 定义依据, 特征概念服务, 名称关系);
}

void 标记全部完成(初始化概念名称结果& 结果) {
    结果.状态 = 初始化概念名称状态::已完成;
    结果.阶段 = 初始化概念名称阶段::完成;
    结果.当前名称项.reset();
}

