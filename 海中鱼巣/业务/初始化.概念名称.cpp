初始化概念名称结果 发布名称材料(初始化概念名称结果 结果,
    稳定编码 语言节点, 稳定编码 规范化合同节点,
    const std::vector<特征概念信息>& 定义依据组, 新_词类& 词服务,
    概念_名称关系类& 名称服务, const 概念_特征类& 特征概念服务) {
    if (结果.状态 != 初始化概念名称状态::已完成
        || 结果.名称项组.size() != 定义依据组.size())
        throw std::logic_error("完整名称材料与逐项目标定义依据不相容");
    for (std::size_t i = 0; i < 结果.名称项组.size(); ++i) {
        结果.当前名称项 = i;
        结果.阶段 = 初始化概念名称阶段::词条发布;
        auto& 项 = 结果.名称项组[i];
        项.词条发布 = 词服务.建立或取得词条({
            语言节点, 规范化合同节点, 项.词面, std::nullopt});
        const auto& 词发布 = *项.词条发布;
        if ((词发布.状态 != 新词条建立状态::已建立 && 词发布.状态 != 新词条建立状态::已复用)
            || !词发布.词条节点 || !有效(*词发布.词条节点)) {
            未完成(结果, 初始化概念名称状态::工程未完成, "词条发布没有取得正式身份");
            return 结果;
        }
        const auto 词条 = *词发布.词条节点;
        if (!核对词条(结果, 语言节点, 规范化合同节点, 词服务, 词条)) return 结果;
        结果.阶段 = 初始化概念名称阶段::名称发布;
        if (!核对当前概念(结果, 定义依据组[i], 特征概念服务)) return 结果;
        项.名称发布 = 名称服务.建立或取得名称关系(项.概念节点, 词条);
        const auto& 名称发布 = *项.名称发布;
        if ((名称发布.状态 != 概念名称关系建立状态::已建立
                && 名称发布.状态 != 概念名称关系建立状态::已复用)
            || !名称发布.名称关系节点 || !有效(*名称发布.名称关系节点)) {
            未完成(结果, 初始化概念名称状态::工程未完成, "名称发布没有取得正式身份");
            return 结果;
        }
        if (!三路读回(结果, 定义依据组[i], 名称服务, 特征概念服务, 词条, *名称发布.名称关系节点))
            return 结果;
    }
    标记全部完成(结果);
    return 结果;
}

初始化概念名称结果 读取名称材料(初始化概念名称结果 结果,
    稳定编码 语言节点, 稳定编码 规范化合同节点,
    const std::vector<特征概念信息>& 定义依据组, const 新_词类& 词服务,
    const 概念_名称关系类& 名称服务, const 概念_特征类& 特征概念服务) {
    if (结果.状态 != 初始化概念名称状态::已完成
        || 结果.名称项组.size() != 定义依据组.size())
        throw std::logic_error("完整只读名称材料与逐项目标定义依据不相容");
    for (std::size_t i = 0; i < 结果.名称项组.size(); ++i) {
        结果.当前名称项 = i;
        结果.阶段 = 初始化概念名称阶段::词条读回;
        auto& 项 = 结果.名称项组[i];
        项.词条读回 = 词服务.按规范化词面查询(语言节点, 规范化合同节点, 项.词面);
        if (项.词条读回->状态 != 新词条查询状态::已找到 || !项.词条读回->信息
            || !有效(项.词条读回->信息->节点)) {
            未完成(结果, 初始化概念名称状态::工程未完成, "正式词条没有读回，未进行修补");
            return 结果;
        }
        const auto 词条 = 项.词条读回->信息->节点;
        if (!核对词条(结果, 语言节点, 规范化合同节点, 词服务, 词条)) return 结果;
        结果.阶段 = 初始化概念名称阶段::三路读回;
        项.词条反向读回 = 名称服务.查询词条候选概念(词条);
        if (项.词条反向读回->状态 != 概念名称关系查询状态::已找到) {
            未完成(结果, 初始化概念名称状态::工程未完成, "名称候选没有完整读回，未进行修补");
            return 结果;
        }
        std::optional<稳定编码> 对应关系;
        for (const auto 关系 : 项.词条反向读回->名称关系节点组) {
            const auto 读取 = 名称服务.获取名称关系(关系);
            if (读取.状态 != 概念名称关系查询状态::已找到 || !读取.信息
                || 读取.信息->节点 != 关系 || 读取.信息->词条节点 != 词条) {
                未完成(结果, 初始化概念名称状态::工程未完成, "名称候选端点读回不一致");
                return 结果;
            }
            if (读取.信息->概念节点 == 项.概念节点) {
                项.名称读回 = 读取;
                if (对应关系) {
                    未完成(结果, 初始化概念名称状态::工程未完成, "同一概念与词条存在重复名称关系");
                    return 结果;
                }
                对应关系 = 关系;
            }
        }
        if (!对应关系) {
            未完成(结果, 初始化概念名称状态::工程未完成, "明确目标的名称关系缺失，未进行修补");
            return 结果;
        }
        if (!三路读回(结果, 定义依据组[i], 名称服务, 特征概念服务, 词条, *对应关系)) return 结果;
    }
    标记全部完成(结果);
    return 结果;
}

