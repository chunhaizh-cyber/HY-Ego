bool 角色有效(const 本能根角色 角色) noexcept {
  return 角色 == 本能根角色::安全 || 角色 == 本能根角色::服务;
}

bool 触发有效(const 自我线程复核触发根 触发) noexcept {
  return 触发 == 自我线程复核触发根::双根
      || 触发 == 自我线程复核触发根::安全根
      || 触发 == 自我线程复核触发根::服务根;
}

bool 业务结果有效(const 自我线程根复核业务结果_v2 结果) noexcept {
  return 结果 == 自我线程根复核业务结果_v2::当前满足
      || 结果 == 自我线程根复核业务结果_v2::正差距;
}

技术状态 映射根材料状态(const 本能根材料状态 状态) noexcept {
  switch (状态) {
  case 本能根材料状态::入口拒绝:
    return 技术状态::入口拒绝;
  case 本能根材料状态::实际特征未找到:
  case 本能根材料状态::根材料未闭合:
    return 技术状态::材料不足;
  case 本能根材料状态::实际特征已退出:
  case 本能根材料状态::根材料已退出:
    return 技术状态::退役不可用;
  case 本能根材料状态::实际特征类型不匹配:
    return 技术状态::类型不相容;
  case 本能根材料状态::事实代次漂移:
    return 技术状态::当前性漂移;
  case 本能根材料状态::资源失败:
    return 技术状态::资源失败;
  default:
    return 技术状态::内部不一致;
  }
}

