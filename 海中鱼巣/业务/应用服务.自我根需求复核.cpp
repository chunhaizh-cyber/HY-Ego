bool 自我线程根需求复核请求_v2::完整() const noexcept {
  if (合同版本 != 自我线程根需求复核合同版本_v2 || !上下文.完整()
      || !触发有效(触发根) || !来源消息.完整() || !原请求.完整())
    return false;
  if (触发根 == 自我线程复核触发根::双根)
    return !正式需求定位.完整();
  if (触发根 == 自我线程复核触发根::安全根)
    return 正式需求定位 == 上下文.安全根.需求;
  return 正式需求定位 == 上下文.服务根.需求;
}

bool 自我线程单根复核投影_v2::完整() const noexcept {
  if (!角色有效(角色) || !根材料.完整() || 根材料.角色 != 角色
      || !有效(当前实际特征) || !有效(FT) || !有效(K) || !有效(RC.值)
      || 当前I64 < 0 || 目标I64 != 根材料.目标I64值
      || 目标I64 != (std::numeric_limits<std::int64_t>::max)()
      || 准确差异 != 目标I64 - 当前I64 || !业务结果有效(业务结果)
      || 求值见证.版本 != 2 || !求值见证.Gread
      || 求值见证.H != 求值见证.Gread
      || 求值见证.定义H != 求值见证.Gread || !求值见证.请求身份
      || 求值见证.来源组.size() != 2 || 求值见证.条件组.size() != 1)
    return false;
  const auto *目标来源 =
      std::get_if<二次关系本能根目标合同值来源>(&求值见证.来源组[0].来源);
  const auto *当前来源 =
      std::get_if<二次关系准确F来源>(&求值见证.来源组[1].来源);
  const auto &A = 求值见证.来源组[0];
  const auto &B = 求值见证.来源组[1];
  if (!目标来源 || !当前来源 || 目标来源->角色 != 角色
      || 目标来源->根需求 != 根材料.根需求
      || 目标来源->根目标合同 != 根材料.根目标合同
      || 目标来源->目标值事实 != 根材料.目标值
      || 目标来源->对应实际特征.编码 != 根材料.实际特征
      || 当前来源->F != 当前实际特征 || A.E != B.E
      || A.FT != FT || B.FT != FT || A.值 != 目标I64 || B.值 != 当前I64)
    return false;
  if (!单根来源内容完整(A, B, 根材料, 当前实际特征, FT, A.E,
                          求值见证.Gread))
    return false;
  const auto &条件 = 求值见证.条件组.front();
  const auto *差异 = 唯一差异(条件.计算);
  if (!来源见证逐字段对应(条件.A, A)
      || !来源见证逐字段对应(条件.B, B)
      || 条件.K.身份 != K || 条件.定义.K != K || 条件.定义.D.掩码 != 4
      || 条件.定义.输出 != 特征类标量结果角色::差异
      || !条件.计算.成功() || 条件.计算.请求身份 != 求值见证.请求身份
      || 条件.计算.K != K || !差异 || 差异->输出FT != FT
      || 差异->值 != 准确差异)
    return false;
  if (业务结果 == 自我线程根复核业务结果_v2::正差距)
    return 准确差异 > 0 && 求值见证.状态 == 二次关系判断状态::命中
        && 条件.FC命中 && 条件.EC命中 && 条件.域命中;
  return 准确差异 == 0 && 求值见证.状态 == 二次关系判断状态::不命中
      && 条件.FC命中 && 条件.EC命中 && !条件.域命中;
}

bool 自我线程根需求复核结果_v2::成功(
    const 自我线程根需求复核请求_v2 &请求) const noexcept {
  if (合同版本 != 自我线程根需求复核合同版本_v2
      || 状态 != 总状态::已复核 || 原请求 != 请求 || !请求.完整()
      || Gread != 请求.上下文.Gread || !Gread
      || 安全根技术状态 != 技术状态::已复核
      || 服务根技术状态 != 技术状态::已复核
      || !安全根 || !服务根 || !安全根->完整() || !服务根->完整()
      || !投影匹配上下文(*安全根, 请求.上下文.安全根, 本能根角色::安全)
      || !投影匹配上下文(*服务根, 请求.上下文.服务根, 本能根角色::服务)
      || 安全根->求值见证.请求身份 != 请求.原请求.值
      || 服务根->求值见证.请求身份 != 请求.原请求.值
      || 安全根->求值见证.Gread != Gread
      || 服务根->求值见证.Gread != Gread
      || 安全根->求值见证.来源组[0].E.值 != 请求.上下文.自我.值
      || 安全根->求值见证.来源组[1].E.值 != 请求.上下文.自我.值
      || 服务根->求值见证.来源组[0].E.值 != 请求.上下文.自我.值
      || 服务根->求值见证.来源组[1].E.值 != 请求.上下文.自我.值
      || 写业务事实)
    return false;
  return 安全根->根材料.根需求 != 服务根->根材料.根需求
      && 安全根->根材料.根列表项 != 服务根->根材料.根列表项
      && 安全根->根材料.实际特征 != 服务根->根材料.实际特征
      && 安全根->根材料.根目标合同 != 服务根->根材料.根目标合同
      && 安全根->当前实际特征 != 服务根->当前实际特征
      && 安全根->FT != 服务根->FT && 安全根->K != 服务根->K
      && 安全根->RC != 服务根->RC;
}

自我根需求复核提供者::自我根需求复核提供者(
    const L1事实基座服务 &l1,
    const 需求类数据服务 &需求,
    const 存在类数据服务 &存在,
    const 二次关系求值应用服务 &求值,
    const 本能双根二次关系概念初始化结果 &交付)
    : l1_(l1), 需求_(需求), 存在_(存在), 求值_(求值) {
  if (!需求_.绑定于(l1_) || !存在_.绑定于(l1_) || !求值_.绑定于(l1_)
      || !交付.成功() || !交付.安全根 || !交付.服务根)
    throw std::invalid_argument("自我根需求复核服务绑定");
  安全根_ = {交付.安全根->先天.类型.身份,
             交付.安全根->目标判断K.身份,
             交付.安全根->正差距RC.身份};
  服务根_ = {交付.服务根->先天.类型.身份,
             交付.服务根->目标判断K.身份,
             交付.服务根->正差距RC.身份};
  if (!有效(安全根_.FT) || !有效(安全根_.K) || !有效(安全根_.RC.值)
      || !有效(服务根_.FT) || !有效(服务根_.K) || !有效(服务根_.RC.值)
      || 安全根_.FT == 服务根_.FT || 安全根_.K == 服务根_.K
      || 安全根_.RC == 服务根_.RC)
    throw std::invalid_argument("自我根需求复核角色锚点");
}

