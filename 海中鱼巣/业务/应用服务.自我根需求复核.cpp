自我线程根需求复核结果_v2 自我根需求复核提供者::复核双根当前需求(
    const 自我线程根需求复核请求_v2 &请求) const noexcept {
  自我线程根需求复核结果_v2 out;
  out.原请求 = 请求;
  if (!请求.完整()) return out;
  out.Gread = 请求.上下文.Gread;

  auto 安全 = 保护单根复核(
      需求_, 存在_, 求值_, 请求, 请求.上下文.安全根,
      本能根角色::安全, 安全根_);
  out.安全根技术状态 = 安全.状态;
  if (安全.提前停止) {
    out.状态 = 映射总状态(安全.状态);
    return out;
  }

  auto 服务 = 保护单根复核(
      需求_, 存在_, 求值_, 请求, 请求.上下文.服务根,
      本能根角色::服务, 服务根_);
  out.服务根技术状态 = 服务.状态;
  if (服务.提前停止) {
    out.状态 = 映射总状态(服务.状态);
    return out;
  }

  const auto 尾守卫 = 需求_.核验当前事实代次(out.Gread);
  if (!尾守卫.成功()) {
    out.状态 = 尾守卫.状态 == 需求类数据状态::事实代次漂移
        ? 总状态::当前性漂移
        : 尾守卫.状态 == 需求类数据状态::资源失败
            ? 总状态::资源失败 : 总状态::内部不一致;
    return out;
  }

  if (安全.状态 != 技术状态::已复核 || 服务.状态 != 技术状态::已复核) {
    out.状态 = 映射总状态(安全.状态 != 技术状态::已复核
                              ? 安全.状态 : 服务.状态);
    return out;
  }
  if (!安全.投影 || !服务.投影) {
    out.状态 = 总状态::内部不一致;
    out.安全根技术状态 = 技术状态::内部不一致;
    out.服务根技术状态 = 技术状态::内部不一致;
    return out;
  }
  out.安全根 = std::move(安全.投影);
  out.服务根 = std::move(服务.投影);
  out.状态 = 总状态::已复核;
  if (!out.成功(请求)) {
    out.状态 = 总状态::内部不一致;
    out.安全根.reset();
    out.服务根.reset();
  }
  return out;
}

