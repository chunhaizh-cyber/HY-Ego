bool 根材料匹配上下文(const 本能根材料 &材料,
                       const 自我线程单根启动材料_v1 &上下文,
                       const 本能根角色 角色,
                       const std::uint64_t g) noexcept {
  return 材料.完整() && 材料.角色 == 角色
      && 材料.根需求.值 == 上下文.需求.值
      && 材料.根列表项.值 == 上下文.列表项.值
      && 材料.实际特征.值 == 上下文.实际特征.值
      && 材料.根目标合同.值 == 上下文.目标合同.值
      && 材料.读取事实代次 == g
      && 材料.目标I64值 == (std::numeric_limits<std::int64_t>::max)();
}

const 特征比较执行输出 *唯一差异(
    const 特征比较执行结果 &结果) noexcept {
  const 特征比较执行输出 *差异 = nullptr;
  for (const auto &输出 : 结果.输出组) {
    if (输出.角色 != 特征类标量结果角色::差异) continue;
    if (差异) return nullptr;
    差异 = &输出;
  }
  return 差异;
}

bool 同一存在身份生命周期(const 存在身份来源生命周期 &左,
                           const 存在身份来源生命周期 &右) noexcept {
  return 左.创建事实代次 == 右.创建事实代次
      && 左.退出事实代次 == 右.退出事实代次;
}

bool 同一存在身份见证(const 存在身份来源历史见证 &左,
                      const 存在身份来源历史见证 &右) noexcept {
  return 左.身份 == 右.身份 && 左.族锚点 == 右.族锚点
      && 左.族归属关系类型 == 右.族归属关系类型
      && 左.族归属关系 == 右.族归属关系 && 左.角色 == 右.角色
      && 同一存在身份生命周期(左.节点生命周期, 右.节点生命周期)
      && 同一存在身份生命周期(左.族锚点生命周期, 右.族锚点生命周期)
      && 同一存在身份生命周期(左.关系类型生命周期, 右.关系类型生命周期)
      && 同一存在身份生命周期(左.归属关系生命周期, 右.归属关系生命周期);
}

bool 同一状态内容事实(const 状态内容事实 &左,
                       const 状态内容事实 &右) noexcept {
  return 左.Gread == 右.Gread && 左.H == 右.H && 左.信息 == 右.信息
      && 左.族归属关系 == 右.族归属关系
      && 左.正式特征类型关系 == 右.正式特征类型关系
      && 左.准确值事实 == 右.准确值事实
      && 左.强时间事实 == 右.强时间事实
      && 左.首次形成UTC事实 == 右.首次形成UTC事实
      && 左.首次形成UTC纳秒 == 右.首次形成UTC纳秒
      && 左.创建事实代次 == 右.创建事实代次
      && 左.退出事实代次 == 右.退出事实代次;
}

const std::int64_t *读取准确特征I64值(
    const 准确特征读取事实 &事实) noexcept {
  if (const auto *内联 = std::get_if<std::int64_t>(&事实.完整值)) return 内联;
  const auto *独立值 = std::get_if<特征值信息>(&事实.完整值);
  return 独立值 ? std::get_if<std::int64_t>(&独立值->值内容) : nullptr;
}

bool 来源见证逐字段对应(const 二次关系准确来源见证 &左,
                         const 二次关系准确来源见证 &右) noexcept {
  if (左.E != 右.E || 左.来源 != 右.来源
      || !同一存在身份见证(左.存在见证, 右.存在见证)
      || 左.FT != 右.FT || 左.值 != 右.值 || 左.绑定 != 右.绑定
      || 左.采用 != 右.采用 || 左.内容.index() != 右.内容.index())
    return false;
  if (const auto *左目标 =
          std::get_if<二次关系本能根目标合同值见证>(&左.内容)) {
    const auto *右目标 =
        std::get_if<二次关系本能根目标合同值见证>(&右.内容);
    return 右目标 && 左目标->根材料 == 右目标->根材料
        && 左目标->根形成采用 == 右目标->根形成采用;
  }
  if (const auto *左特征 = std::get_if<准确特征读取事实>(&左.内容)) {
    const auto *右特征 = std::get_if<准确特征读取事实>(&右.内容);
    return 右特征 && *左特征 == *右特征;
  }
  const auto *左状态 = std::get_if<状态内容事实>(&左.内容);
  const auto *右状态 = std::get_if<状态内容事实>(&右.内容);
  return 左状态 && 右状态 && 同一状态内容事实(*左状态, *右状态);
}

bool 单根来源内容完整(const 二次关系准确来源见证 &目标,
                      const 二次关系准确来源见证 &当前,
                      const 本能根材料 &根材料,
                      const 特征信息身份 当前F,
                      const 特征类型身份 FT,
                      const 稳定编码 self,
                      const std::uint64_t g) noexcept {
  const auto *目标内容 =
      std::get_if<二次关系本能根目标合同值见证>(&目标.内容);
  const auto *当前内容 = std::get_if<准确特征读取事实>(&当前.内容);
  const auto *当前I64 = 当前内容 ? 读取准确特征I64值(*当前内容) : nullptr;
  return 目标内容 && 当前内容 && 目标.存在见证.身份 == self
      && 当前.存在见证.身份 == self && 目标内容->根材料 == 根材料
      && 根材料.读取事实代次 == g && 根材料.创建事实代次 <= g
      && 目标内容->根形成采用.E == self
      && 目标内容->根形成采用.FT == FT
      && 目标内容->根形成采用.F.编码 == 根材料.实际特征
      && !目标.绑定 && !目标.采用 && 当前内容->Gread == g
      && 当前内容->H == g && 当前内容->信息.身份 == 当前F
      && 当前内容->信息.类型 == FT && 当前I64 && *当前I64 == 当前.值
      && !当前.绑定 && 当前.采用
      && 当前.采用->E == self && 当前.采用->FT == FT
      && 当前.采用->F == 当前F;
}

