#pragma once

#include "初始化.概念名称.h"

namespace 海中鱼巣 {

enum class 初始化结构化子概念状态 : std::uint8_t {
    已完成, 解释未完成, 声明不合法, 父定义未完成,
    分量域不合法, 父域比较未完成, 直接子查询未完成, 概念建立未完成,
    身份读回未完成, 名称未完成
};
enum class 初始化结构化子概念阶段 : std::uint8_t {
    完整解释, 声明与类型, 分量完整性, 父域包含,
    写前直接子查询, 概念建立, 写后直接子查询, 概念读回, 名称处理, 完成
};
struct 初始化结构化子概念请求 final {
    std::string 标准文本;
    稳定编码 语言节点, 规范化合同节点;
    初始化最小资源额度 解释额度;
};
struct 初始化结构化子概念项 final {
    std::size_t 声明编号 = 0;
    std::string 主体词面;
    稳定编码 直接父概念;
    特征概念定义 完整定义;
    std::vector<std::size_t> 来源定义编号组;
    std::optional<特征概念值域比较结果> 父域比较;
    std::optional<特征概念直接子查询结果> 写前匹配;
    std::optional<稳定编码> 建立调用身份;
    std::optional<特征概念直接子查询结果> 写后匹配;
    std::optional<特征概念信息> 概念读回;
};
struct 初始化结构化子概念结果 final {
    初始化结构化子概念状态 状态 = 初始化结构化子概念状态::解释未完成;
    初始化结构化子概念阶段 阶段 = 初始化结构化子概念阶段::完整解释;
    std::optional<初始化最小解释结果> 解释结果;
    std::vector<初始化结构化子概念项> 子概念组;
    std::vector<初始化名称符号绑定> 符号绑定组;
    std::optional<初始化概念名称结果> 名称结果;
    std::optional<std::size_t> 当前声明编号;
    std::string 诊断说明;
};

// 整批解释、声明、完整分量、父域和命名来源预检先于写入。
// 只细化三个明确先天FT；不建新类型根或实例，不改父定义、不补实例引用。
// 逐项实际步骤保留，不承诺全批原子。工程异常向上送至生产诊断边界。
初始化结构化子概念结果 初始化结构化子概念(
    const 初始化结构化子概念请求& 请求,
    const 新_语言类& 语言服务, 概念_特征类& 特征概念服务,
    const 新_特征值类& 特征值服务, 新_词类& 词服务,
    概念_名称关系类& 名称服务);

// 只读复核同一直接父、完整定义和名称；缺失不修补，建立调用身份保持空。
初始化结构化子概念结果 读取结构化子概念(
    const 初始化结构化子概念请求& 请求,
    const 新_语言类& 语言服务, const 概念_特征类& 特征概念服务,
    const 新_词类& 词服务, const 概念_名称关系类& 名称服务);

} // namespace 海中鱼巣
