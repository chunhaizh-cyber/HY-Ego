constexpr std::array<std::string_view, 6> 六词{"我", "你", "他", "这", "那", "谁"};
constexpr std::array<指代声明规则, 6> 六规则{
    指代声明规则::作用域说话者, 指代声明规则::作用域受话者,
    指代声明规则::作用域第三方, 指代声明规则::相对近指,
    指代声明规则::相对远指, 指代声明规则::受限身份变量};

bool 拒绝(初始化指代种子结果& 结果, 初始化指代种子状态 状态,
    std::string_view 诊断) {
    结果.状态 = 状态;
    结果.诊断说明.assign(诊断);
    return false;
}
bool 工程拒绝(初始化指代种子结果& 结果, std::string_view 诊断) {
    结果.工程控制 = 初始化指代种子工程控制::提供者未完成;
    结果.状态.reset();
    结果.诊断说明.assign(诊断);
    return false;
}
bool 定义查询可用(const 指代概念查询结果& 结果) noexcept {
    return (结果.状态 == 指代概念查询状态::已找到 && 结果.信息)
        || (结果.状态 == 指代概念查询状态::未找到 && !结果.信息);
}
bool 词条查询可用(const 新词条查询结果& 结果) noexcept {
    return (结果.状态 == 新词条查询状态::已找到 && 结果.信息)
        || (结果.状态 == 新词条查询状态::未找到 && !结果.信息);
}
bool 同一来源(const 新语言知识来源信息& 实际,
    const 新语言知识来源请求& 请求) noexcept {
    return 有效(实际.节点) && 实际.种类 == 请求.种类
        && 实际.语言节点 == 请求.语言节点 && 实际.固定原文 == 请求.固定原文;
}
bool 同一来源(const 新语言知识来源信息& a,
    const 新语言知识来源信息& b) noexcept {
    return a.节点 == b.节点 && a.种类 == b.种类
        && a.语言节点 == b.语言节点 && a.固定原文 == b.固定原文;
}
bool 同一名称(const 指代名称关系信息& a, const 指代名称关系信息& b) noexcept {
    return a.节点 == b.节点 && a.概念 == b.概念 && a.词条 == b.词条
        && a.语言 == b.语言 && a.角色 == b.角色
        && a.来源.节点 == b.来源.节点 && a.来源.种类 == b.来源.种类
        && a.来源.语言节点 == b.来源.语言节点
        && a.来源.固定原文 == b.来源.固定原文;
}
std::string_view 词面(const 初始化指代种子结果& 结果, std::size_t i) {
    const auto& 材料 = *结果.解释结果->材料;
    const auto& r = *结果.项组[i].词面来源;
    return std::string_view(材料.原文).substr(r.字节起点, r.字节终点 - r.字节起点);
}

bool 准备首批(const 初始化指代种子请求& 请求, 初始化指代种子结果& 结果) {
    结果.阶段 = 初始化指代种子阶段::完整解释;
    结果.解释结果 = 解释初始化标准文本(请求.标准文本, 请求.解释额度);
    if (结果.解释结果->工程控制 != 初始化工程控制::已完成)
        return 工程拒绝(结果, "标准文本解释额度或资源未完成");
    if (结果.解释结果->解释状态 != 初始化解释状态::已完整解释
        || !结果.解释结果->材料)
        return 拒绝(结果, 初始化指代种子状态::文本未完成, "标准文本未完整解释");
    结果.阶段 = 初始化指代种子阶段::首批核验;
    const auto& 材料 = *结果.解释结果->材料;
    if (材料.定义组.size() != 六词.size() || 材料.符号组.size() != 六词.size())
        return 拒绝(结果, 初始化指代种子状态::首批范围不符, "必须恰有六项独立指代声明");
    std::array<bool, 6> 已见{};
    for (const auto& 定义 : 材料.定义组) {
        if (定义.模板 != 初始化最小模板::指代定义声明
            || !std::holds_alternative<初始化指代声明材料>(定义.载荷))
            return 拒绝(结果, 初始化指代种子状态::首批范围不符, "混入非指代模板");
        const auto& 载荷 = std::get<初始化指代声明材料>(定义.载荷);
        if (载荷.指代概念.局部编号 >= 材料.符号组.size())
            throw std::logic_error("pronoun symbol index invariant");
        const auto& 符号 = 材料.符号组[载荷.指代概念.局部编号];
        const auto it = std::find(六词.begin(), 六词.end(), 符号.词面);
        if (it == 六词.end())
            return 拒绝(结果, 初始化指代种子状态::首批范围不符, "首批包含未批准词面");
        const auto i = static_cast<std::size_t>(it - 六词.begin());
        if (已见[i] || 载荷.定义.规则 != 六规则[i]
            || 符号.角色类型 != 初始化符号角色类型::指代概念引用)
            return 拒绝(结果, 初始化指代种子状态::首批范围不符, "重复词面或词面与规则不符");
        已见[i] = true;
        auto& 项 = 结果.项组[i];
        项.声明局部编号 = 定义.局部编号;
        项.词面来源 = 符号.来源;
        项.定稿 = 载荷.定义;
    }
    if (std::find(已见.begin(), 已见.end(), false) != 已见.end())
        return 拒绝(结果, 初始化指代种子状态::首批范围不符, "缺少首批声明");
    return true;
}

bool 核验语言(const 初始化指代种子请求& 请求, const 新_语言类& 语言,
    const 新_词类& 词, 初始化指代种子结果& 结果) {
    结果.阶段 = 初始化指代种子阶段::前置读取;
    if (&词.取得语言服务() != &语言 || !有效(请求.语言节点)
        || !有效(请求.规范化合同节点)
        || 请求.规范化合同节点 != 严格UTF8字节精确规范化合同节点)
        return 拒绝(结果, 初始化指代种子状态::前置材料不符, "语言服务实例或规范化合同不符");
    结果.语言读回 = 语言.获取语言(请求.语言节点);
    auto 中文 = 语言.按登记键查询("zh-CN");
    if ((结果.语言读回->状态 != 新语言查询状态::已找到
            && 结果.语言读回->状态 != 新语言查询状态::未找到)
        || (结果.语言读回->状态 == 新语言查询状态::已找到 && !结果.语言读回->信息))
        return 工程拒绝(结果, "正式中文语言读取未完成");
    if ((中文.状态 != 新语言查询状态::已找到
            && 中文.状态 != 新语言查询状态::未找到)
        || (中文.状态 == 新语言查询状态::已找到 && !中文.信息)) {
        结果.语言读回 = std::move(中文);
        return 工程拒绝(结果, "正式中文登记键查询未完成");
    }
    if (结果.语言读回->状态 == 新语言查询状态::未找到)
        return 拒绝(结果, 初始化指代种子状态::前置材料不符, "正式中文语言缺失");
    if (中文.状态 == 新语言查询状态::未找到) {
        结果.语言读回 = std::move(中文);
        return 拒绝(结果, 初始化指代种子状态::前置材料不符, "正式中文登记键缺失");
    }
    if (结果.语言读回->信息->节点 != 请求.语言节点
        || 结果.语言读回->信息->登记键 != "zh-CN"
        || *结果.语言读回->信息 != *中文.信息)
        return 拒绝(结果, 初始化指代种子状态::前置材料不符, "正式中文身份与登记键不一致");
    return true;
}

bool 预查(const 初始化指代种子请求& 请求, const 新_词类& 词,
    const 概念_存在类& 概念, 初始化指代种子结果& 结果, bool 只读) {
    for (std::size_t i = 0; i < 六词.size(); ++i) {
        结果.当前项 = i;
        auto& 项 = 结果.项组[i];
        项.结构前定义查询 = 概念.查询指代概念(*项.定稿);
        项.词条查询 = 词.按规范化词面查询(请求.语言节点,
            请求.规范化合同节点, std::string(词面(结果, i)));
        if (!定义查询可用(*项.结构前定义查询)
            && !(项.结构前定义查询->状态 == 指代概念查询状态::依赖缺失 && !只读))
            return 工程拒绝(结果, "指代定义前置查询未完成");
        if (!词条查询可用(*项.词条查询))
            return 工程拒绝(结果, "词条前置查询未完成");
        if (只读 && (项.结构前定义查询->状态 == 指代概念查询状态::未找到
            || 项.词条查询->状态 == 新词条查询状态::未找到))
            return 拒绝(结果, 初始化指代种子状态::已发布材料缺失, "已装配指代定义或词条缺失");
    }
    结果.当前项.reset();
    return true;
}

bool 核验来源(const 初始化指代种子请求& 请求, const 新_语言类& 语言,
    初始化指代种子结果& 结果, const 新语言知识来源请求& 来源请求) {
    结果.来源读回 = 语言.查询知识先天来源(来源请求);
    if (结果.来源读回->状态 == 新语言知识状态::未找到)
        return 拒绝(结果, 初始化指代种子状态::已发布材料缺失, "当前标准文本的来源缺失");
    if (结果.来源读回->状态 != 新语言知识状态::已完成
        || !结果.来源读回->信息)
        return 工程拒绝(结果, "先天来源查询未完成");
    const auto 查询 = *结果.来源读回->信息;
    结果.来源读回 = 语言.获取知识先天来源(查询.节点);
    if (结果.来源读回->状态 == 新语言知识状态::未找到)
        return 拒绝(结果, 初始化指代种子状态::已发布材料缺失,
            "先天来源按身份读取缺失");
    if (结果.来源读回->状态 != 新语言知识状态::已完成
        || !结果.来源读回->信息)
        return 工程拒绝(结果, "先天来源身份读取未完成");
    if (结果.来源读回->发布种类 || !同一来源(查询, 来源请求)
        || !同一来源(*结果.来源读回->信息, 来源请求)
        || 查询.节点 != 结果.来源读回->信息->节点)
        return 拒绝(结果, 初始化指代种子状态::已发布材料不符, "先天来源身份或原文字节不一致");
    return true;
}

bool 完整核验项(const 初始化指代种子请求& 请求, const 新_词类& 词,
    const 概念_存在类& 概念, const 概念_名称关系类& 名称,
    const 新语言知识来源信息& 来源, 初始化指代种子结果& 结果,
    std::size_t i, std::optional<稳定编码> 预期名称身份) {
    auto& 项 = 结果.项组[i];
    结果.当前项 = i;
    结果.阶段 = 初始化指代种子阶段::逐项完整读回;
    项.定义查询 = 概念.查询指代概念(*项.定稿);
    项.词条查询 = 词.按规范化词面查询(请求.语言节点,
        请求.规范化合同节点, std::string(词面(结果, i)));
    if (!定义查询可用(*项.定义查询) || !词条查询可用(*项.词条查询))
        return 工程拒绝(结果, "定义或词条查询未完成");
    if (项.定义查询->状态 == 指代概念查询状态::未找到
        || 项.词条查询->状态 == 新词条查询状态::未找到)
        return 拒绝(结果, 初始化指代种子状态::已发布材料缺失, "定义或词条读回缺失");
    const auto& d = *项.定义查询->信息;
    const auto& w = *项.词条查询->信息;
    if (!有效(d.节点) || d.定义 != *项.定稿 || !有效(w.节点)
        || w.语言节点 != 请求.语言节点
        || w.规范化合同节点 != 请求.规范化合同节点
        || w.规范化词面 != 词面(结果, i))
        return 拒绝(结果, 初始化指代种子状态::已发布材料不符, "定义或词条当前内容不符");
    项.定义读回 = 概念.获取指代概念(d.节点);
    项.词条读回 = 词.获取词条(w.节点);
    if ((项.定义读回->状态 != 指代概念查询状态::已找到
            && 项.定义读回->状态 != 指代概念查询状态::未找到)
        || (项.词条读回->状态 != 新词条查询状态::已找到
            && 项.词条读回->状态 != 新词条查询状态::未找到)
        || (项.定义读回->状态 == 指代概念查询状态::已找到 && !项.定义读回->信息)
        || (项.词条读回->状态 == 新词条查询状态::已找到 && !项.词条读回->信息))
        return 工程拒绝(结果, "定义或词条按身份读取未完成");
    if (项.定义读回->状态 == 指代概念查询状态::未找到
        || 项.词条读回->状态 == 新词条查询状态::未找到)
        return 拒绝(结果, 初始化指代种子状态::已发布材料缺失,
            "定义或词条按身份读取缺失");
    if (*项.定义读回->信息 != d || *项.词条读回->信息 != w)
        return 拒绝(结果, 初始化指代种子状态::已发布材料不符, "定义或词条身份读回不一致");
    项.概念名称读回 = 名称.查询指代概念名称(d.节点);
    if (项.概念名称读回->状态 == 指代名称读取状态::未找到)
        return 拒绝(结果, 初始化指代种子状态::已发布材料缺失,
            "概念名称查询目标缺失");
    if (项.概念名称读回->状态 != 指代名称读取状态::已读取)
        return 工程拒绝(结果, "概念名称全集读取未完成");
    const 指代名称关系信息* 命中 = nullptr;
    std::size_t 同语言首选数 = 0;
    for (const auto& n : 项.概念名称读回->信息组) {
        if (n.角色 == 指代名称角色::首选名称
            && n.语言.节点 == 请求.语言节点) ++同语言首选数;
        if (n.词条 == w && n.角色 == 指代名称角色::首选名称
            && n.语言.节点 == 请求.语言节点
            && n.来源.节点 == 来源.节点
            && 同一来源(n.来源, 来源)) {
            if (命中) return 拒绝(结果, 初始化指代种子状态::已发布材料不符,
                "同槽存在多个精确名称");
            命中 = &n;
        }
    }
    if (!命中) return 拒绝(结果,
        同语言首选数 == 0 ? 初始化指代种子状态::已发布材料缺失
            : 初始化指代种子状态::已发布材料不符,
        "当前标准文本的首选名称缺失或来源不符");
    if (同语言首选数 != 1 || (预期名称身份 && 命中->节点 != *预期名称身份))
        return 拒绝(结果, 初始化指代种子状态::已发布材料不符,
            "同语言首选名称冲突或发布身份变化");
    const auto 名称身份 = 命中->节点;
    const auto 名称快照 = *命中;
    项.关系读回 = 名称.获取指代名称关系(名称身份);
    项.词条候选读回 = 名称.查询词条指代名称(w.节点);
    if ((项.关系读回->状态 != 指代名称读取状态::已读取
            && 项.关系读回->状态 != 指代名称读取状态::未找到)
        || (项.词条候选读回->状态 != 指代名称读取状态::已读取
            && 项.词条候选读回->状态 != 指代名称读取状态::未找到)
        || (项.关系读回->状态 == 指代名称读取状态::已读取
            && !项.关系读回->信息))
        return 工程拒绝(结果, "关系或词条候选完整读取未完成");
    if (项.关系读回->状态 == 指代名称读取状态::未找到
        || 项.词条候选读回->状态 == 指代名称读取状态::未找到)
        return 拒绝(结果, 初始化指代种子状态::已发布材料缺失,
            "关系或词条候选目标缺失");
    const auto& n = *项.关系读回->信息;
    if (!同一名称(n, 名称快照) || n.概念 != d || n.词条 != w
        || n.语言 != *结果.语言读回->信息
        || n.来源.节点 != 来源.节点
        || !同一来源(n.来源, 来源)
        || std::count(d.名称关系.begin(), d.名称关系.end(), 名称身份) != 1)
        return 拒绝(结果, 初始化指代种子状态::已发布材料不符, "关系端点或概念反向持有不符");
    std::size_t 候选命中 = 0;
    for (const auto& 候选 : 项.词条候选读回->信息组)
        if (候选.节点 == 名称身份 && 同一名称(候选, n)) ++候选命中;
    if (候选命中 != 1)
        return 拒绝(结果, 初始化指代种子状态::已发布材料不符, "词条反向候选不唯一");
    项.逐项核验完成 = true;
    return true;
}

template<class 语言服务, class 词服务>
void 确认未返回的写入(const 新语言知识来源请求& 来源请求,
    const std::array<std::optional<新词条建立请求>, 6>& 词请求,
    语言服务& 语言, 词服务& 词, 初始化指代种子结果& 结果) noexcept {
    auto& sf = 结果.来源事实;
    if (sf.已调用写入口 && !sf.写入口已返回) {
        try {
            auto q = 语言.查询知识先天来源(来源请求);
            if (q.状态 == 新语言知识状态::已完成 && q.信息
                && 同一来源(*q.信息, 来源请求)) sf.后续确认当前身份 = q.信息->节点;
            else sf.调用后事实未能确认 = true;
            结果.来源读回 = std::move(q);
        } catch (...) {
            sf.调用后事实未能确认 = true;
            sf.确认读取异常 = std::current_exception();
        }
    }
    for (std::size_t i = 0; i < 六词.size(); ++i) {
        auto& f = 结果.项组[i].词条事实;
        if (!f.已调用写入口 || f.写入口已返回 || !词请求[i]) continue;
        try {
            const auto& r = *词请求[i];
            auto q = 词.按规范化词面查询(r.语言节点, r.规范化合同节点, r.规范化词面);
            if (q.状态 == 新词条查询状态::已找到 && q.信息
                && q.信息->语言节点 == r.语言节点
                && q.信息->规范化合同节点 == r.规范化合同节点
                && q.信息->规范化词面 == r.规范化词面)
                f.后续确认当前身份 = q.信息->节点;
            else f.调用后事实未能确认 = true;
            结果.项组[i].词条读回 = std::move(q);
        } catch (...) {
            f.调用后事实未能确认 = true;
            f.确认读取异常 = std::current_exception();
        }
    }
}

template<bool 只读, class 语言服务, class 词服务, class 概念服务, class 名称服务>
初始化指代种子结果 处理指代种子(const 初始化指代种子请求& 请求,
    语言服务& 语言, 词服务& 词, 概念服务& 概念, 名称服务& 名称) {
    初始化指代种子结果 结果;
    std::optional<新语言知识来源请求> 来源请求;
    std::array<std::optional<新词条建立请求>, 6> 词请求;
    try {
        来源请求.emplace(新语言知识来源种类::经确认先天定义,
            请求.语言节点, 请求.标准文本);
        const auto& 来源参数 = *来源请求;
        if (!准备首批(请求, 结果) || !核验语言(请求, 语言, 词, 结果)
            || !预查(请求, 词, 概念, 结果, 只读)) return 结果;
        if constexpr (!只读) {
            结果.阶段 = 初始化指代种子阶段::定义结构;
            结果.定义结构处理 = 概念.初始化指代定义结构();
            if (*结果.定义结构处理 != 指代定义结构状态::已就绪)
                { 工程拒绝(结果, "指代定义结构未就绪"); return 结果; }
            结果.阶段 = 初始化指代种子阶段::名称结构;
            结果.名称结构处理 = 名称.初始化指代名称结构();
            if (*结果.名称结构处理 != 指代名称读取状态::已读取)
                { 工程拒绝(结果, "指代名称结构未就绪"); return 结果; }
        }
        结果.阶段 = 初始化指代种子阶段::来源处理;
        for (std::size_t i = 0; i < 六词.size(); ++i) {
            结果.当前项 = i;
            auto& 项 = 结果.项组[i];
            项.定义查询 = 概念.查询指代概念(*项.定稿);
            if (!定义查询可用(*项.定义查询))
                { 工程拒绝(结果, "结构就绪后的定义查询未完成"); return 结果; }
            if constexpr (只读) {
                if (项.定义查询->状态 == 指代概念查询状态::未找到)
                    { 拒绝(结果, 初始化指代种子状态::已发布材料缺失, "已装配定义缺失"); return 结果; }
            }
        }
        结果.当前项.reset();
        结果.来源读回 = 语言.查询知识先天来源(来源参数);
        const auto& 旧来源 = *结果.来源读回;
        if (旧来源.状态 != 新语言知识状态::已完成
            && 旧来源.状态 != 新语言知识状态::未找到)
            { 工程拒绝(结果, "先天来源前置查询未完成"); return 结果; }
        if (旧来源.状态 == 新语言知识状态::已完成 && !旧来源.信息)
            { 工程拒绝(结果, "先天来源前置查询缺少完整载荷"); return 结果; }
        if (旧来源.状态 == 新语言知识状态::已完成
            && !同一来源(*旧来源.信息, 来源参数))
            { 拒绝(结果, 初始化指代种子状态::已发布材料不符, "先天来源前置内容不符"); return 结果; }
        if constexpr (!只读) {
            if (旧来源.状态 == 新语言知识状态::未找到) {
                auto& f = 结果.来源事实;
                f.已调用写入口 = true;
                auto p = 语言.建立或取得知识先天来源(来源参数);
                f.写入口已返回 = true;
                if (p.信息) f.提供者返回身份 = p.信息->节点;
                结果.来源发布种类 = p.状态 == 新语言知识状态::已完成
                    ? p.发布种类 : std::nullopt;
                结果.来源发布 = std::move(p);
                if (结果.来源发布->状态 != 新语言知识状态::已完成
                    || !结果.来源发布->信息 || !结果.来源发布种类) {
                    try {
                        auto q = 语言.查询知识先天来源(来源参数);
                        if (q.状态 == 新语言知识状态::已完成 && q.信息
                            && 同一来源(*q.信息, 来源参数))
                            f.后续确认当前身份 = q.信息->节点;
                        else f.调用后事实未能确认 = true;
                        结果.来源读回 = std::move(q);
                    } catch (...) { f.调用后事实未能确认 = true;
                        f.确认读取异常 = std::current_exception(); }
                    工程拒绝(结果, "先天来源写入未完成，保留可确认的当前身份"); return 结果;
                }
            }
        }
        if (!核验来源(请求, 语言, 结果, 来源参数)) return 结果;
        if (结果.来源发布 && (!结果.来源发布->信息
            || 结果.来源发布->信息->节点 != 结果.来源读回->信息->节点
            || !同一来源(*结果.来源发布->信息, 来源参数)))
            { 拒绝(结果, 初始化指代种子状态::已发布材料不符, "来源发布与完整读回不符"); return 结果; }
        const auto 来源 = *结果.来源读回->信息;

        for (std::size_t i = 0; i < 六词.size(); ++i) {
            结果.当前项 = i;
            auto& 项 = 结果.项组[i];
            结果.阶段 = 初始化指代种子阶段::定义处理;
            if constexpr (!只读) {
                auto& f = 项.定义事实;
                f.已调用写入口 = true;
                auto p = 概念.建立或取得指代概念(*项.定稿);
                f.写入口已返回 = true;
                f.提供者返回身份 = p.已发生身份;
                项.定义写入状态 = p.状态;
                项.定义发布阶段 = p.阶段;
                项.定义发布 = std::move(p);
                if ((项.定义写入状态 != 指代概念写入状态::已建立
                    && 项.定义写入状态 != 指代概念写入状态::已复用)
                    || 项.定义发布阶段 != 指代概念发布阶段::已完整读回
                    || !项.定义发布->信息 || !f.提供者返回身份
                    || 项.定义发布->发布后异常) {
                    工程拒绝(结果, "指代定义发布或核验未完成"); return 结果;
                }
            }
            项.定义查询 = 概念.查询指代概念(*项.定稿);
            if (项.定义查询->状态 == 指代概念查询状态::未找到)
                { 拒绝(结果, 初始化指代种子状态::已发布材料缺失, "指代定义发布后缺失"); return 结果; }
            if (!定义查询可用(*项.定义查询))
                { 工程拒绝(结果, "指代定义发布后查询未完成"); return 结果; }
            const auto 概念身份 = 项.定义查询->信息->节点;
            if (项.定义发布 && (项.定义事实.提供者返回身份 != 概念身份
                || 项.定义发布->信息 != 项.定义查询->信息))
                { 拒绝(结果, 初始化指代种子状态::已发布材料不符, "定义发布身份与查询不符"); return 结果; }

            结果.阶段 = 初始化指代种子阶段::词条处理;
            if constexpr (!只读) {
                词请求[i] = 新词条建立请求{请求.语言节点, 请求.规范化合同节点,
                    std::string(词面(结果, i)), 来源.节点};
                auto& f = 项.词条事实;
                f.已调用写入口 = true;
                const auto p = 词.建立或取得词条(*词请求[i]);
                f.写入口已返回 = true;
                f.提供者返回身份 = p.词条节点;
                项.词条写入状态 = p.状态;
                项.词条发布 = p;
                if ((p.状态 != 新词条建立状态::已建立
                    && p.状态 != 新词条建立状态::已复用) || !p.词条节点) {
                    try {
                        auto q = 词.按规范化词面查询(词请求[i]->语言节点,
                            词请求[i]->规范化合同节点, 词请求[i]->规范化词面);
                        if (q.状态 == 新词条查询状态::已找到 && q.信息
                            && q.信息->语言节点 == 词请求[i]->语言节点
                            && q.信息->规范化合同节点 == 词请求[i]->规范化合同节点
                            && q.信息->规范化词面 == 词请求[i]->规范化词面)
                            f.后续确认当前身份 = q.信息->节点;
                        else f.调用后事实未能确认 = true;
                        项.词条读回 = std::move(q);
                    } catch (...) { f.调用后事实未能确认 = true;
                        f.确认读取异常 = std::current_exception(); }
                    工程拒绝(结果, "词条写入未完成，保留可确认的当前身份"); return 结果;
                }
            }
            项.词条查询 = 词.按规范化词面查询(请求.语言节点,
                请求.规范化合同节点, std::string(词面(结果, i)));
            if (项.词条查询->状态 == 新词条查询状态::未找到)
                { 拒绝(结果, 初始化指代种子状态::已发布材料缺失, "词条发布后缺失"); return 结果; }
            if (!词条查询可用(*项.词条查询))
                { 工程拒绝(结果, "词条发布后查询未完成"); return 结果; }
            if (项.词条发布 && (项.词条发布->词条节点 != 项.词条查询->信息->节点
                || (项.词条发布->状态 == 新词条建立状态::已建立
                    && 项.词条查询->信息->创建来源节点 != 来源.节点)))
                { 拒绝(结果, 初始化指代种子状态::已发布材料不符, "词条身份或新建来源不符"); return 结果; }

            结果.阶段 = 初始化指代种子阶段::名称处理;
            if constexpr (!只读) {
                const auto& r = *项.词面来源;
                if (r.标量终点 > static_cast<std::size_t>(std::numeric_limits<std::int64_t>::max())
                    || r.字节终点 > 请求.标准文本.size()
                    || std::string_view(请求.标准文本).substr(r.字节起点,
                        r.字节终点 - r.字节起点) != 项.词条查询->信息->规范化词面)
                    { 工程拒绝(结果, "词面来源区间溢出或与词条不符"); return 结果; }
                const 指代名称建立请求 n{概念身份, *项.定稿, *项.词条查询->信息,
                    指代名称角色::首选名称, 来源,
                    {static_cast<std::int64_t>(r.标量起点),
                        static_cast<std::int64_t>(r.标量终点)}};
                auto& f = 项.名称事实;
                f.已调用写入口 = true;
                auto p = 名称.建立或取得指代名称关系(n);
                f.写入口已返回 = true;
                f.提供者返回身份 = p.已取得关系身份;
                项.名称写入状态 = p.状态;
                项.名称本次处理 = p.本次处理;
                项.名称核验阶段 = p.阶段;
                项.名称发布 = std::move(p);
                if ((项.名称写入状态 != 指代名称变更状态::已建立
                    && 项.名称写入状态 != 指代名称变更状态::已复用)
                    || 项.名称核验阶段 != 指代名称核验阶段::已完成核验
                    || !项.名称发布->信息 || !f.提供者返回身份
                    || 项.名称发布->取得身份后异常) {
                    if (项.名称写入状态 == 指代名称变更状态::首选名称冲突
                        || 项.名称写入状态 == 指代名称变更状态::请求内容冲突)
                        拒绝(结果, 初始化指代种子状态::已发布材料不符,
                            "指代名称首选或来源合同冲突");
                    else 工程拒绝(结果, "指代名称发布或核验未完成");
                    return 结果;
                }
            }
            if (!完整核验项(请求, 词, 概念, 名称, 来源, 结果, i,
                项.名称事实.提供者返回身份)) return 结果;
            if (项.名称发布 && (!项.名称发布->信息
                || !同一名称(*项.名称发布->信息, *项.关系读回->信息)))
                { 拒绝(结果, 初始化指代种子状态::已发布材料不符, "名称发布与关系读回不符"); return 结果; }
        }
        结果.阶段 = 初始化指代种子阶段::全部复核;
        for (std::size_t i = 0; i < 六词.size(); ++i) {
            结果.项组[i].全部复核完成 = false;
            const auto 已复核 = 完整核验项(请求, 词, 概念, 名称, 来源, 结果, i,
                结果.项组[i].关系读回->信息->节点);
            结果.阶段 = 初始化指代种子阶段::全部复核;
            if (!已复核) return 结果;
            结果.项组[i].全部复核完成 = true;
        }
        if (!核验来源(请求, 语言, 结果, 来源参数)) return 结果;
        for (std::size_t i = 0; i < 六词.size(); ++i) {
            const auto& a = 结果.项组[i];
            if (!a.逐项核验完成 || !a.全部复核完成 || !a.定义读回->信息
                || !a.词条读回->信息 || !a.关系读回->信息)
                { 工程拒绝(结果, "六项复核材料不完整"); return 结果; }
            for (std::size_t j = 0; j < i; ++j) {
                const auto& b = 结果.项组[j];
                if (a.定义读回->信息->节点 == b.定义读回->信息->节点
                    || a.词条读回->信息->节点 == b.词条读回->信息->节点
                    || a.关系读回->信息->节点 == b.关系读回->信息->节点)
                    { 拒绝(结果, 初始化指代种子状态::已发布材料不符, "六槽身份未分别唯一"); return 结果; }
            }
        }
        结果.当前项.reset();
        结果.阶段 = 初始化指代种子阶段::完成;
        结果.状态 = 初始化指代种子状态::已完成;
        return 结果;
    } catch (...) {
        结果.工程异常 = std::current_exception();
        结果.工程控制 = 初始化指代种子工程控制::异常中止;
        结果.状态.reset();
        if constexpr (!只读) {
            if (来源请求) 确认未返回的写入(*来源请求, 词请求, 语言, 词, 结果);
        }
        return 结果;
    }
}

