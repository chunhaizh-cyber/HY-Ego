初始化指代种子结果 初始化指代概念名称(const 初始化指代种子请求& 请求,
    新_语言类& 语言, 新_词类& 词, 概念_存在类& 概念, 概念_名称关系类& 名称) {
    return 处理指代种子<false>(请求, 语言, 词, 概念, 名称);
}
