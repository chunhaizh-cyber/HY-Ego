bool 分界材料可用(材料状态 状态) {
    switch (状态) {
    case 材料状态::已完成: return true;
    case 材料状态::未找到:
    case 材料状态::前提已变化:
    case 材料状态::材料未就绪: return false;
    case 材料状态::资源失败: throw std::bad_alloc{};
    default: throw std::logic_error("分界材料入口返回不合法状态");
    }
}

新方法条件项定义 当前材料已取得(std::uint32_t 位置, 稳定编码 类型) {
    新方法条件项定义 条件;
    条件.参数序号 = 位置;
    条件.特征类型概念节点 = 类型;
    条件.特征值域概念节点 = 类型;
    return 条件;
}
