新字段询问文字结果 字段询问语言服务::生成字段询问(
    const 新正式字段询问目标& 目标,const 正式信息参数读取接口& 正式读取) const {
    using 状态=新字段询问文字状态;
    const auto 返回=[](状态 值){新字段询问文字结果 r;r.状态=值;return r;};
    if(目标.被询内容.正式内容路径.size()!=1)return 返回(状态::范围未支持);
    if(!有效(目标.被询内容.信息节点)||!有效(目标.需求范围概念)||!有效(目标.语言节点)
        ||!有效(目标.说话者)||!有效(目标.受询者)||!有效(目标.交互窗口)||!有效(目标.交互作用域)
        ||!有效(目标.第三方指代概念)||!有效(目标.选用指代名称关系)
        ||目标.被询内容.信息节点==目标.说话者||目标.被询内容.信息节点==目标.受询者)return 返回(状态::缺指称);
    const auto D=正式读取.读取正式信息参数保护(目标.被询内容.信息节点,目标.需求范围概念);
    if(D.状态==正式信息参数读取状态::前提已变化)return 返回(状态::前提已变化);
    if(D.状态==正式信息参数读取状态::范围未支持)return 返回(状态::范围未支持);
    if(D.状态!=正式信息参数读取状态::已读取||!D.信息)throw std::logic_error("字段询问正式需求读取未完成");
    const auto FT=目标.被询内容.正式内容路径.front();
    const auto 内容=std::find_if(D.信息->直接内容组.begin(),D.信息->直接内容组.end(),[&](const auto& 项){return 项.特征类型==FT;});
    if(内容==D.信息->直接内容组.end())return 返回(状态::范围未支持);
    if(内容->内容.状态!=正式内容值状态::当前未知)return 返回(状态::前提已变化);
    const auto 范围=读取正式字段询问范围(D,FT,存在概念_,特征概念_);
    if(范围.状态==结构项概念保护状态::前提已变化)return 返回(状态::前提已变化);
    if(范围.状态==结构项概念保护状态::未取得正式概念证明||范围.状态==结构项概念保护状态::输入拒绝)return 返回(状态::范围未支持);
    if(范围.状态!=结构项概念保护状态::已读取||!范围.内容概念)throw std::logic_error("字段询问需求结构范围读取未完成");
    const auto 代名=名称_.获取指代名称关系(目标.选用指代名称关系);
    if(代名.状态==指代名称读取状态::未找到)return 返回(状态::缺名称);
    if(代名.状态!=指代名称读取状态::已读取||!代名.信息)throw std::logic_error("字段询问指代名称读取未完成");
    if(代名.信息->概念.节点!=目标.第三方指代概念||代名.信息->概念.定义.规则!=指代声明规则::作用域第三方
        ||代名.信息->语言.节点!=目标.语言节点)return 返回(状态::缺指称);
    using 种类=新语言知识角色种类;using 类别=新语言知识角色类别;using 参数=新语言知识参数角色;
    const auto 角色=[](std::int64_t 编号,种类 种,类别 类){return 新语言知识角色定义{编号,种,新语言知识角色数量::单项,{{编号,{类}}}};};
    语言图含义材料 图;图.语言节点=目标.语言节点;图.定义图.根含义编号=1;图.根出现编号=0;
    图.定义图.节点组={
        {1,新语言知识含义操作::信息请求,新语言知识作用域::提问范围,{角色(0,种类::子含义引用,类别::子含义)},
            {{参数::被询内容,0}},{},新语言知识确认范围::填项内容,{},{{0,2,新语言子含义用途::被询内容,{}}}},
        {2,新语言知识含义操作::特征描述,新语言知识作用域::提问范围,
            {角色(0,种类::领域对象引用,类别::正式信息节点),角色(1,种类::特征类型引用,类别::正式特征类型),角色(2,种类::查询变量,类别::查询特征值)},
            {{参数::主体,0},{参数::特征类型,1},{参数::特征值,2}},{},{},{},{}}
    };
    图.出现组={
        {0,{},1,新语言知识作用域::提问范围,{},{{0,语言图子出现引用{1}}},{}},
        {1,{},2,新语言知识作用域::提问范围,{},{{0,语言图引用值{类别::正式信息节点,目标.被询内容.信息节点,目标.需求范围概念,{}}},
            {1,语言图引用值{类别::正式特征类型,FT,FT,{}}},{2,语言图待求值{0,*范围.内容概念}}},{}}
    };
    图.被询正式内容=目标.被询内容;
    图.正式指称作用域=目标.交互作用域;
    const auto 无限=(std::numeric_limits<std::size_t>::max)();
    const 语言基础统一输出请求 请求{目标.语言节点,图,无限,无限,无限,无限,无限,无限};
    const auto 输出=从基础信息生成可回读单句(请求,语言世界_,语言_,词_,名称_,存在概念_,特征概念_,存在_,&正式读取);
    switch(输出.状态) {
    case 语言场景基础输出状态::已生成且唯一回读:return {状态::已生成且唯一回读,输出.文本,输出.所用知识节点组};
    case 语言场景基础输出状态::缺规则:return 返回(状态::缺知识);
    case 语言场景基础输出状态::缺名称:return 返回(状态::缺名称);
    case 语言场景基础输出状态::名称待选:
    case 语言场景基础输出状态::回读多义:return 返回(状态::多义);
    case 语言场景基础输出状态::读取漂移:return 返回(状态::前提已变化);
    case 语言场景基础输出状态::输入拒绝:return 返回(状态::缺指称);
    default:throw std::logic_error("字段询问统一生成或独立回读未完成");
    }
}
