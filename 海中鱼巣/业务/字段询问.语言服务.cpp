新字段询问文字结果 字段询问语言服务::生成字段询问(
    const 新正式字段询问目标& 目标,const 正式信息参数读取接口& 正式读取) const {
    if(目标.被询内容.正式内容路径.size()!=1){新字段询问文字结果 r;r.状态=新字段询问文字状态::范围未支持;return r;}
    // 薄适配：现网本能仍传字段询问目标；正式合同是表达需求。
    return 生成候选话语(从字段询问目标形成表达需求(目标),正式读取);
}

新字段询问文字结果 字段询问语言服务::生成候选话语(
    const 正式表达需求& 需求,const 正式信息参数读取接口& 正式读取) const {
    using 状态=新字段询问文字状态;
    const auto 返回=[](状态 值){新字段询问文字结果 r;r.状态=值;return r;};
    const auto 组织=组织具体表达结构(需求,语言_,正式读取,存在概念_,特征概念_);
    switch(组织.状态){
    case 新表达结构组织状态::已组织:break;
    case 新表达结构组织状态::缺组织知识:
    case 新表达结构组织状态::多规则待选:return 返回(状态::缺知识);
    case 新表达结构组织状态::缺材:
    case 新表达结构组织状态::范围未支持:return 返回(状态::范围未支持);
    case 新表达结构组织状态::条件不成立:
    case 新表达结构组织状态::前提已变化:return 返回(状态::前提已变化);
    default:throw std::logic_error("字段询问组织器状态未定义");
    }
    const auto& 成文=需求.成文参数;
    const auto 投影=含义网投影旧图(组织.含义网,{成文.语言节点,成文.交互作用域,需求.说话者,需求.受话者});
    if(投影.状态!=新含义网投影状态::已投影)return 返回(状态::范围未支持);
    if(!投影.图)throw std::logic_error("含义网投影已投影但无图");
    const auto& 对象=std::get<正式表达需求字段>(需求.表达对象);
    if(!有效(成文.语言节点)||!有效(需求.说话者.节点)||!有效(需求.受话者.节点)
        ||!有效(成文.交互窗口)||!有效(成文.交互作用域)||!有效(成文.第三方指代概念)||!有效(成文.选用指代名称关系)
        ||对象.需求D==需求.说话者.节点||对象.需求D==需求.受话者.节点)return 返回(状态::缺指称);
    const auto 代名=名称_.获取指代名称关系(成文.选用指代名称关系);
    if(代名.状态==指代名称读取状态::未找到)return 返回(状态::缺名称);
    if(代名.状态!=指代名称读取状态::已读取||!代名.信息)throw std::logic_error("字段询问指代名称读取未完成");
    if(代名.信息->概念.节点!=成文.第三方指代概念||代名.信息->概念.定义.规则!=指代声明规则::作用域第三方
        ||代名.信息->语言.节点!=成文.语言节点)return 返回(状态::缺指称);
    const auto& 图=*投影.图;
    const auto 无限=(std::numeric_limits<std::size_t>::max)();
    const 语言基础统一输出请求 请求{成文.语言节点,图,无限,无限,无限,无限,无限,无限};
    const auto 输出=从基础信息生成可回读单句(请求,语言世界_,语言_,词_,名称_,存在概念_,特征概念_,存在_,&正式读取);
    switch(输出.状态) {
    case 语言场景基础输出状态::已生成且唯一回读:
        return {状态::已生成且唯一回读,输出.文本,输出.所用知识节点组,组织.含义网,组织.所用组织知识节点};
    case 语言场景基础输出状态::缺规则:return 返回(状态::缺知识);
    case 语言场景基础输出状态::缺名称:return 返回(状态::缺名称);
    case 语言场景基础输出状态::名称待选:
    case 语言场景基础输出状态::回读多义:return 返回(状态::多义);
    case 语言场景基础输出状态::读取漂移:return 返回(状态::前提已变化);
    case 语言场景基础输出状态::输入拒绝:return 返回(状态::缺指称);
    default:throw std::logic_error("字段询问统一生成或独立回读未完成");
    }
}
