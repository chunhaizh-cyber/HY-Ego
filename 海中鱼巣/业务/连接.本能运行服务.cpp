新连接返回 连接本能运行服务::开始内部(const 新连接请求& r,
    const 方法参数场景* 任务场景, std::optional<稳定编码> X) noexcept {
    try {
        if (!实现_->进入(true)) return {};
        实现::入口票 票{实现_.get()};
        // v4：据参数6（交互窗口副本的外设场景标识）在函数内部读取外设交互场景（R91）。
        const auto 标识 = 实现_->特征.获取特征(r.外设标识特征);
        const auto* 编码 = 标识 && 标识->当前值 ? std::get_if<std::int64_t>(&*标识->当前值) : nullptr;
        if (!编码 || *编码 <= 0) return {新连接状态::条件未具备};
        const auto 外设读取 = 实现_->外设.按场景读取交互场景(
            稳定编码{static_cast<std::uint64_t>(*编码)});
        if (!外设读取 || !外设读取->交互者节点) return {新连接状态::条件未具备};
        const auto 来源 = std::optional{外设读取->来源};
        auto q = std::make_shared<实现::调用>();
        q->请求 = r;
        q->请求.外设窗口 = 来源->定位.窗口节点;
        q->现场.方法身份 = 任务场景 ? 任务场景->方法节点() : *实现_->方法节点;
        q->页面 = *来源;
        q->现场.绑定 = 实现_->建立绑定(q->请求, 来源->定位);
        if (X) {
            if (!任务场景 || q->现场.绑定.size() != 任务场景->全部角色绑定().size()) return {};
            for (const auto& b : q->现场.绑定) {
                const auto* p = 任务场景->查询参数(b.有序引用->序号);
                if (!p || *p != *b.有序引用) return {};
            }
            q->现场.绑定 = 任务场景->全部角色绑定();
            q->任务执行 = true;
        }
        // 任务入口已经持有正式参数场景；仅直接调用需要在此建立封套。
        const auto 参数 = X ? 新方法参数场景结果{}
            : 实现_->方法.建立参数场景(q->现场.方法身份, q->现场.绑定);
        if (!X && (参数.状态 != 新方法操作状态::已建立 || !参数.参数场景)) {
            if (参数场景业务缺口(参数.状态)) return {新连接状态::条件未具备};
            连接工程故障(L"连接开始参数场景发生非业务缺口。");
        }
        if (X) q->现场.身份 = *X;
        else q->现场.身份 = 实现_->方法.建立直接调用身份(
            *实现_->方法节点, q->现场.绑定, r.现实场景, r.窗口副本).节点;
        {
            std::lock_guard 锁(实现_->互斥);
            if (!实现_->调用表.emplace(q->现场.身份, q).second)
                连接工程故障(L"连接调用身份重复。");
        }
        std::lock_guard 单步锁(q->操作锁);
        if (X) {
            q->现场.运行 = 推进本次(*任务场景, *X);
            return 实现_->投影(*q);
        }
        新_本能函数管理类::本能直接调用守卫 守卫(*参数.参数场景, q->现场.身份);
        const auto 调用 = 实现_->方法.调用本能函数(*实现_->方法节点, *参数.参数场景);
        if (调用.状态 != 新方法本能调用状态::已调用 || !调用.本次条件结果对)
            连接工程故障(L"连接本能首次调用未进入正式注册入口。");
        q->现场.运行 = *调用.本次条件结果对;
        return 实现_->投影(*q);
    } catch (...) { 连接工程故障(L"连接开始入口异常。"); }
}

新本能函数本次条件结果对 连接本能运行服务::执行任务(
    const 方法参数场景& 场景, 稳定编码 X) noexcept {
    try {
        新本能函数本次条件结果对 拒绝;
        拒绝.结果.状态 = 新本能函数执行状态::入口拒绝;
        if (新_本能函数管理类::读取本次执行实例(场景) != std::optional{X}
            || !新_本能函数管理类::本次停止可用()
            || 新_本能函数管理类::本次停止已请求() || !实现_->进入(true)) return 拒绝;
        实现::入口票 票{实现_.get()};
        const auto M = 实现_->方法.获取方法(场景.方法节点());
        if (!M || M->本能函数登记名 != 新本能函数登记名_建立连接
            || (M->来源方法节点.value_or(M->节点) != *实现_->方法节点)) return 拒绝;
        const auto& 绑定 = 场景.全部角色绑定();
        if (绑定.size() != 6) return 拒绝;
        std::array<稳定编码, 6> 参数{};
        for (std::uint32_t i = 0; i < 6; ++i) {
            const auto* p = 场景.查询参数(i + 1);
            if (!p || p->信息类型 != (i == 3 || i >= 5 ? 新方法参数信息类型::特征
                : 新方法参数信息类型::存在)) return 拒绝;
            参数[i] = p->信息节点;
        }
        新连接请求 请求{参数[1], 参数[2], 参数[3], 参数[0], {}, 参数[4], 参数[5]};
        const auto 首次 = 开始内部(请求, &场景, X);
        const auto q = 实现_->查找(X);
        if (!q) return 首次.运行材料.value_or(拒绝);
        for (;;) {
            bool 关闭 = false;
            { std::lock_guard 锁(实现_->互斥); 关闭 = 实现_->关闭中; }
            {
                std::lock_guard 锁(q->操作锁);
                if (连接终态(q->现场.阶段) || q->已释放) return q->现场.运行;
                if (关闭 || 新_本能函数管理类::本次停止已请求()) {
                    q->现场.阶段 = 新连接状态::已取消;
                    q->现场.运行.结果.状态 = q->现场.动作 ? 新本能函数执行状态::动作结果未知
                        : 新本能函数执行状态::入口拒绝;
                    q->现场.运行.结果.结果取得状态 = q->现场.动作 ? 新本能函数结果取得状态::部分取得
                        : 新本能函数结果取得状态::未取得;
                    实现_->收束(*q);
                    return q->现场.运行;
                }
                q->现场.运行 = 推进本次(场景, X);
                if (连接终态(q->现场.阶段) || q->已释放) return q->现场.运行;
            }
            // 只控制工程轮询频率；没有业务超时。等待期间不持任何领域/现场锁。
            新_本能函数管理类::等待本次停止(std::chrono::milliseconds(50));
        }
    } catch (...) { 连接工程故障(L"连接任务执行入口异常。"); }
}

新连接返回 连接本能运行服务::推进(稳定编码 身份) noexcept {
    try {
        if (!实现_->进入(false)) return {新连接状态::来源失效};
        实现::入口票 票{实现_.get()};
        const auto q = 实现_->查找(身份);
        if (!q) return {新连接状态::来源失效};
        std::lock_guard 单步锁(q->操作锁);
        if (连接终态(q->现场.阶段) || q->已释放) return 实现_->投影(*q);
        const auto 参数 = 实现_->方法.建立参数场景(q->现场.方法身份, q->现场.绑定);
        if (参数.状态 != 新方法操作状态::已建立 || !参数.参数场景) {
            if (!参数场景业务缺口(参数.状态))
                连接工程故障(L"连接推进参数场景发生非业务缺口。");
            q->现场.阶段 = 新连接状态::来源失效;
            q->现场.运行.结果.状态 = 新本能函数执行状态::动作结果未知;
            实现_->收束(*q);
            return 实现_->投影(*q);
        }
        新_本能函数管理类::本能直接调用守卫 守卫(*参数.参数场景, 身份);
        const auto 调用 = 实现_->方法.调用本能函数(*实现_->方法节点, *参数.参数场景);
        if (调用.状态 != 新方法本能调用状态::已调用 || !调用.本次条件结果对)
            连接工程故障(L"连接本能推进未进入注册入口。");
        q->现场.运行 = *调用.本次条件结果对;
        return 实现_->投影(*q);
    } catch (...) { 连接工程故障(L"连接推进入口异常。"); }
}

新连接返回 连接本能运行服务::取消(稳定编码 身份) noexcept {
    try {
        if (!实现_->进入(false)) return {新连接状态::来源失效};
        实现::入口票 票{实现_.get()};
        const auto q = 实现_->查找(身份);
        if (!q) return {新连接状态::来源失效};
        std::lock_guard 单步锁(q->操作锁);
        if (连接终态(q->现场.阶段) || q->已释放) return 实现_->投影(*q);
        q->现场.阶段 = 新连接状态::已取消;
        q->现场.运行.结果.状态 = q->现场.动作
            ? 新本能函数执行状态::动作结果未知
            : 新本能函数执行状态::入口拒绝;
        q->现场.运行.结果.结果取得状态 = q->现场.动作
            ? 新本能函数结果取得状态::部分取得
            : 新本能函数结果取得状态::未取得;
        实现_->收束(*q);
        return 实现_->投影(*q);
    } catch (...) { 连接工程故障(L"连接取消入口异常。"); }
}

void 连接本能运行服务::关闭() noexcept {
    try {
        std::vector<std::shared_ptr<实现::调用>> 全部;
        {
            std::unique_lock 锁(实现_->互斥);
            if (实现_->关闭中 && 实现_->调用表.empty()) return;
            实现_->关闭中 = true;
            实现_->闲置.wait(锁, [&] { return 实现_->活动入口 == 0; });
            for (const auto& [_, q] : 实现_->调用表) 全部.push_back(q);
        }
        for (const auto& q : 全部) {
            std::lock_guard 单步锁(q->操作锁);
            if (!q->已释放) {
                q->现场.阶段 = 新连接状态::已取消;
                q->现场.运行.结果.状态 = q->现场.动作
                    ? 新本能函数执行状态::动作结果未知
                    : 新本能函数执行状态::入口拒绝;
                实现_->收束(*q);
            }
            实现_->释放状态(*q);
        }
        { std::lock_guard 锁(实现_->互斥); 实现_->调用表.clear(); }
        const auto 端口 = 新_本能函数管理类::关闭连接端口(*this);
        if (端口 != 新本能函数端口装配状态::已关闭
            && 端口 != 新本能函数端口装配状态::所有者冲突)
            连接工程故障(L"连接端口关闭失败。");
    } catch (...) { 连接工程故障(L"连接关闭入口异常。"); }
}

