新连接返回 连接本能运行服务::开始内部(const 新连接请求& r,
    const 方法参数场景* 任务场景, std::optional<稳定编码> X) noexcept {
    try {
        if (!实现_->进入(true)) return {};
        实现::入口票 票{实现_.get()};
        const auto 配置 = 读取登记配置();
        if (!配置 || r.自我存在 != 配置->自我存在
            || !有效(r.目标存在) || !有效(r.外设窗口)
            || !有效(r.现实场景) || !有效(r.交互对象特征)
            || r.自我存在 == r.目标存在
            || !实现_->存在.是存在节点(r.目标存在)
            || !实现_->现实场景.是场景节点(r.现实场景)
            || 实现_->现实场景.查询所属场景(r.自我存在) != r.现实场景)
            return {};
        const auto 来源 = 实现_->外设.读取对话框来源(r.外设窗口);
        if (!来源 || !来源->定位.发送数量特征 || !来源->定位.发送内容特征)
            return {新连接状态::条件未具备};
        const auto f = 实现_->特征.获取特征(r.交互对象特征);
        const auto e = 实现_->存在.获取存在(r.自我存在);
        if (!f || !e || !f->当前值
            || std::count(e->特征节点组.begin(), e->特征节点组.end(),
                r.交互对象特征) != 1) return {新连接状态::条件未具备};
        const auto 类型匹配 = 实现_->特征概念.比较单特征概念(
            f->特征概念节点, 配置->交互对象类型);
        if (类型匹配.状态 != 特征概念规则状态::已完成)
            连接工程故障(L"交互对象特征概念比较未完成。");
        if (类型匹配.特征类型根 != 配置->交互对象类型)
            return {新连接状态::条件未具备};
        auto q = std::make_shared<实现::调用>();
        q->请求 = r;
        q->方法身份 = 任务场景 ? 任务场景->方法节点() : *实现_->方法节点;
        q->页面 = *来源;
        q->宿主目标 = {来源->公开宿主会话, 来源->对话框标识};
        q->绑定 = 实现_->建立绑定(r, 来源->定位);
        if (X) {
            if (!任务场景 || q->绑定.size() != 任务场景->全部角色绑定().size()) return {};
            // 场景定位由任务冻结，不要求任务填写连接内部生成的同一份封套。
            for (const auto& b : q->绑定) {
                const auto* p = 任务场景->查询参数(b.有序引用->序号);
                if (!p || *p != *b.有序引用) return {};
            }
            q->绑定 = 任务场景->全部角色绑定();
            q->任务执行 = true;
        }
        const auto 参数 = 实现_->方法.建立参数场景(q->方法身份, q->绑定);
        if (参数.状态 != 新方法操作状态::已建立 || !参数.参数场景) {
            if (参数场景业务缺口(参数.状态))
                return {新连接状态::条件未具备};
            连接工程故障(L"连接开始参数场景发生非业务缺口。");
        }
        const auto 目标场景 = 实现_->现实场景.查询所属场景(r.目标存在);
        if (!目标场景 || !实现_->固定存在状态(*q, r.自我存在, r.现实场景, false)
            || !实现_->固定存在状态(*q, r.目标存在, *目标场景, false)
            || !实现_->固定存在状态(*q, r.外设窗口, 来源->定位.场景节点, true)) {
            实现_->释放状态(*q);
            return {新连接状态::条件未具备};
        }
        if (!实现_->fresh(*q)) {
            实现_->释放状态(*q);
            return {新连接状态::来源失效};
        }
        if (X) q->身份 = *X;
        else q->身份 = 实现_->方法.建立直接调用身份(
            *实现_->方法节点, q->绑定, r.现实场景, 来源->定位.场景节点).节点;
        if (!取得网页对话框出站占用(q->宿主目标, q->身份.值)) {
            q->阶段 = 新连接状态::页面正被使用;
            实现_->收束(*q);
            return 实现_->投影(*q);
        }
        q->已占用 = true;
        // 租约取得后才冻结计数；取得前其它正常提交仍可能完整写出。
        const auto 收数 = 实现::当前非负计数(实现_->特征, 来源->定位.接收数量特征);
        const auto 发数 = 实现::当前非负计数(实现_->特征, *来源->定位.发送数量特征);
        if (!收数 || !发数) 连接工程故障(L"正式收发计数不是非负I64。");
        if (*发数 == (std::numeric_limits<std::int64_t>::max)())
            连接工程故障(L"正式发送计数已达I64上限，不能安全递增。");
        q->起点接收数 = *收数;
        q->起点发送数 = *发数;
        q->收先 = r.本次起点接收状态.has_value();
        if (q->收先) {
            const auto s = 实现_->状态.获取状态(*r.本次起点接收状态);
            const auto 列表 = 实现_->外设.获取场景只读视图().查询状态列表(来源->定位.场景节点);
            if (!s || *收数 == 0 || s->被描述存在节点 != r.外设窗口
                || s->来源实例特征节点 != 来源->定位.接收数量特征
                || s->固定准确值 != 新特征准确值{*收数}
                || std::count(列表.begin(), 列表.end(), s->节点) != 1) {
                q->阶段 = 新连接状态::条件未具备;
                实现_->收束(*q);
                return 实现_->投影(*q);
            }
            q->起点收状态 = s->节点;
        }
        {
            std::lock_guard 锁(实现_->互斥);
            if (!实现_->调用表.emplace(q->身份, q).second)
                连接工程故障(L"直接调用身份重复。");
        }
        std::lock_guard 单步锁(q->操作锁);
        if (X) {
            q->运行 = 推进本次(*任务场景, *X);
            return 实现_->投影(*q);
        }
        新_本能函数管理类::本能直接调用守卫 守卫(*参数.参数场景, q->身份);
        const auto 调用 = 实现_->方法.调用本能函数(*实现_->方法节点, *参数.参数场景);
        if (调用.状态 != 新方法本能调用状态::已调用 || !调用.本次条件结果对)
            连接工程故障(L"连接本能首次调用未进入正式注册入口。");
        q->运行 = *调用.本次条件结果对;
        return 实现_->投影(*q);
    } catch (...) { 连接工程故障(L"连接开始入口异常。"); }
}

新本能函数本次条件结果对 连接本能运行服务::执行任务(
    const 方法参数场景& 场景, 稳定编码 X) noexcept {
    try {
        新本能函数本次条件结果对 拒绝;
        拒绝.结果.状态 = 新本能函数执行状态::入口拒绝;
        if (新_本能函数管理类::读取本次执行实例(场景) != std::optional{X}
            || !新_本能函数管理类::本次停止可用()
            || 新_本能函数管理类::本次停止已请求() || !实现_->进入(true)) return 拒绝;
        实现::入口票 票{实现_.get()};
        if (实现_->任务.复核执行本能输入(X, 场景) != 新任务本能输入复核状态::仍具备)
            return 拒绝;
        const auto M = 实现_->方法.获取方法(场景.方法节点());
        if (!M || M->本能函数登记名 != 新本能函数登记名_建立连接
            || (M->来源方法节点.value_or(M->节点) != *实现_->方法节点)) return 拒绝;
        const auto& 绑定 = 场景.全部角色绑定();
        if (绑定.size() != 6 || !绑定.front().世界场景节点) return 拒绝;
        std::array<稳定编码, 6> 参数{};
        for (std::uint32_t i = 0; i < 6; ++i) {
            const auto* p = 场景.查询参数(i + 1);
            if (!p || p->信息类型 != (i == 2 || i >= 4 ? 新方法参数信息类型::特征
                : 新方法参数信息类型::存在)) return 拒绝;
            参数[i] = p->信息节点;
        }
        新连接请求 请求{参数[0], 参数[1], 参数[2], *绑定.front().世界场景节点, 参数[3]};
        const auto 首次 = 开始内部(请求, &场景, X);
        const auto q = 实现_->查找(X);
        if (!q) return 首次.运行材料.value_or(拒绝);
        for (;;) {
            bool 关闭 = false;
            { std::lock_guard 锁(实现_->互斥); 关闭 = 实现_->关闭中; }
            {
                std::lock_guard 锁(q->操作锁);
                if (连接终态(q->阶段) || q->已释放) return q->运行;
                if (关闭 || 新_本能函数管理类::本次停止已请求()) {
                    q->阶段 = 新连接状态::已取消;
                    q->运行.结果.状态 = q->动作 ? 新本能函数执行状态::动作结果未知
                        : 新本能函数执行状态::入口拒绝;
                    q->运行.结果.结果取得状态 = q->动作 ? 新本能函数结果取得状态::部分取得
                        : 新本能函数结果取得状态::未取得;
                    实现_->收束(*q);
                    return q->运行;
                }
                q->运行 = 推进本次(场景, X);
                if (连接终态(q->阶段) || q->已释放) return q->运行;
            }
            // 只控制工程轮询频率；没有业务超时。等待期间不持任何领域/现场锁。
            新_本能函数管理类::等待本次停止(std::chrono::milliseconds(50));
        }
    } catch (...) { 连接工程故障(L"连接任务执行入口异常。"); }
}

新连接返回 连接本能运行服务::推进(稳定编码 身份) noexcept {
    try {
        if (!实现_->进入(false)) return {新连接状态::来源失效};
        实现::入口票 票{实现_.get()};
        const auto q = 实现_->查找(身份);
        if (!q) return {新连接状态::来源失效};
        std::lock_guard 单步锁(q->操作锁);
        if (连接终态(q->阶段) || q->已释放) return 实现_->投影(*q);
        const auto 参数 = 实现_->方法.建立参数场景(q->方法身份, q->绑定);
        if (参数.状态 != 新方法操作状态::已建立 || !参数.参数场景) {
            if (!参数场景业务缺口(参数.状态))
                连接工程故障(L"连接推进参数场景发生非业务缺口。");
            q->阶段 = 新连接状态::来源失效;
            q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
            实现_->收束(*q);
            return 实现_->投影(*q);
        }
        新_本能函数管理类::本能直接调用守卫 守卫(*参数.参数场景, 身份);
        const auto 调用 = 实现_->方法.调用本能函数(*实现_->方法节点, *参数.参数场景);
        if (调用.状态 != 新方法本能调用状态::已调用 || !调用.本次条件结果对)
            连接工程故障(L"连接本能推进未进入注册入口。");
        q->运行 = *调用.本次条件结果对;
        return 实现_->投影(*q);
    } catch (...) { 连接工程故障(L"连接推进入口异常。"); }
}

新连接返回 连接本能运行服务::取消(稳定编码 身份) noexcept {
    try {
        if (!实现_->进入(false)) return {新连接状态::来源失效};
        实现::入口票 票{实现_.get()};
        const auto q = 实现_->查找(身份);
        if (!q) return {新连接状态::来源失效};
        std::lock_guard 单步锁(q->操作锁);
        if (连接终态(q->阶段) || q->已释放) return 实现_->投影(*q);
        q->阶段 = 新连接状态::已取消;
        q->运行.结果.状态 = q->动作
            ? 新本能函数执行状态::动作结果未知
            : 新本能函数执行状态::入口拒绝;
        q->运行.结果.结果取得状态 = q->动作
            ? 新本能函数结果取得状态::部分取得
            : 新本能函数结果取得状态::未取得;
        实现_->收束(*q);
        return 实现_->投影(*q);
    } catch (...) { 连接工程故障(L"连接取消入口异常。"); }
}

void 连接本能运行服务::关闭() noexcept {
    try {
        std::vector<std::shared_ptr<实现::调用>> 全部;
        {
            std::unique_lock 锁(实现_->互斥);
            if (实现_->关闭中 && 实现_->调用表.empty()) return;
            实现_->关闭中 = true;
            实现_->闲置.wait(锁, [&] { return 实现_->活动入口 == 0; });
            for (const auto& [_, q] : 实现_->调用表) 全部.push_back(q);
        }
        for (const auto& q : 全部) {
            std::lock_guard 单步锁(q->操作锁);
            if (!q->已释放) {
                q->阶段 = 新连接状态::已取消;
                q->运行.结果.状态 = q->动作
                    ? 新本能函数执行状态::动作结果未知
                    : 新本能函数执行状态::入口拒绝;
                实现_->收束(*q);
            }
        }
        const auto 端口 = 新_本能函数管理类::关闭连接端口(*this);
        if (端口 != 新本能函数端口装配状态::已关闭
            && 端口 != 新本能函数端口装配状态::所有者冲突)
            连接工程故障(L"连接端口关闭失败。");
    } catch (...) { 连接工程故障(L"连接关闭入口异常。"); }
}

