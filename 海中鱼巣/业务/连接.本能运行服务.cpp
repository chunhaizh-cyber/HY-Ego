[[noreturn]] void 连接工程故障(const wchar_t* 原因) noexcept {
    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"建立连接本能", 原因);
}

新状态强时间 当前连接时间() {
    const auto 结果 = UTC时钟适配器{}.读取当前UTC时间证据_v1({});
    if (!结果.成功()) 连接工程故障(L"真实UTC时间不可用。");
    return {新状态时间语义::实例绝对UTC, 结果.证据->UTC纳秒};
}

bool 方法声明相同(const 新方法信息& 已有, const 新方法知识建立请求& 请求) {
    return 已有.作用域 == 请求.作用域
        && 已有.实现方式 == 请求.实现方式
        && 已有.行为 == 请求.行为
        && 已有.方法头 == 请求.方法头
        && 已有.参数规格组 == 请求.参数规格组
        && 已有.本能函数登记名 == 新本能函数登记名_建立连接
        && !已有.来源方法节点 && !已有.实例根节点;
}

bool 连接终态(新连接状态 s) noexcept {
    return s == 新连接状态::已确认关系 || s == 新连接状态::已取消
        || s == 新连接状态::传输未完成 || s == 新连接状态::来源失效
        || s == 新连接状态::前提已变化;
}

bool 参数场景业务缺口(新方法操作状态 s) noexcept {
    return s == 新方法操作状态::参数引用失效
        || s == 新方法操作状态::参数概念不相容
        || s == 新方法操作状态::参数材料未到;
}

