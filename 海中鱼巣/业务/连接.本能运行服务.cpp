struct 连接本能运行服务::实现 final {
    struct 引用 final { 稳定编码 状态, 存在, 场景; bool 外设 = false; };
    struct 调用 final {
        std::mutex 操作锁;
        新连接请求 请求;
        新外设对话框来源 页面;
        std::vector<引用> 固定状态;
        bool 任务执行 = false;
        bool 已释放 = false;
        新连接执行现场 现场;
    };

    实现(新_世界树类& w, 新_外设世界树类& p, 新_方法类& m,
        新_存在类& e, 新_特征类& f, 新_特征值类& v, 新_状态类& s,
        新_动态类& d, 概念_存在类& ec, 概念_特征类& fc, 新_任务类& t) noexcept
        : 世界(w), 外设(p), 方法(m), 任务(t), 存在(e), 特征(f), 值(v), 状态(s), 动态(d),
          存在概念(ec), 特征概念(fc), 现实场景(w.获取事实服务引用().场景服务),
          二次特征(f, w.获取事实服务引用().二次特征概念服务) {}

    新_世界树类& 世界;
    新_外设世界树类& 外设;
    新_方法类& 方法;
    新_任务类& 任务;
    新_存在类& 存在;
    新_特征类& 特征;
    新_特征值类& 值;
    新_状态类& 状态;
    新_动态类& 动态;
    概念_存在类& 存在概念;
    概念_特征类& 特征概念;
    新_场景类& 现实场景;
    新_二次特征类 二次特征;
    std::mutex 互斥;
    std::condition_variable 闲置;
    std::map<稳定编码, std::shared_ptr<调用>> 调用表;
    std::optional<新连接登记配置> 配置;
    std::optional<稳定编码> 方法节点;
    std::optional<稳定编码> 动作概念;
    std::optional<稳定编码> 连接关系;
    std::size_t 活动入口 = 0;
    bool 初始化中 = false, 关闭中 = false;

    std::shared_ptr<调用> 查找(稳定编码 n) {
        std::lock_guard 锁(互斥);
        const auto it = 调用表.find(n);
        return it == 调用表.end() ? nullptr : it->second;
    }
    bool 进入(bool 开始) {
        std::lock_guard 锁(互斥);
        if (关闭中 || !配置 || !方法节点) return false;
        ++活动入口;
        return true;
    }
    void 离开() {
        std::lock_guard 锁(互斥);
        if (!活动入口) 连接工程故障(L"公共入口计数下溢。");
        --活动入口;
        闲置.notify_all();
    }
    struct 入口票 final {
        实现* 自身 = nullptr;
        ~入口票() { if (自身) 自身->离开(); }
    };

    bool 状态仍由场景持有(const 引用& r) const {
        const auto& c = r.外设 ? 外设.获取场景只读视图() : 现实场景;
        const auto E = 存在.获取存在(r.存在);
        const auto S = 状态.获取状态(r.状态);
        const auto 场景 = c.获取场景(r.场景);
        if (!E || !S || !场景 || S->被描述存在节点 != r.存在
            || std::count(E->特征节点组.begin(), E->特征节点组.end(),
                S->来源实例特征节点) != 1) return false;
        const auto 列表 = c.查询状态列表(r.场景);
        return std::count(列表.begin(), 列表.end(), r.状态) == 1;
    }

    void 释放状态(调用& q) {
        for (auto it = q.固定状态.rbegin(); it != q.固定状态.rend(); ++it)
            if (状态.减少引用(it->状态) != 新状态操作状态::已完成)
                连接工程故障(L"释放现场状态引用失败。");
        q.固定状态.clear();
    }
    std::optional<新状态信息> 最新接收数量状态(调用& q) {
        // v4：接收数量特征属外设窗口，只在本次调用内存中持有（不是参数）。
        const auto F = q.页面.定位.接收数量特征;
        const auto 特征信息 = 特征.获取特征(F);
        if (!特征信息) return std::nullopt;
        const auto 定义 = 特征.捕获特征匹配定义(特征信息->特征概念节点);
        if (!定义 || !配置 || 定义->特征类型根 != 配置->接收数量类型
            || 定义->材料类型 != 特征概念材料物理类型::I64标量)
            连接工程故障(L"接收数量特征定义不可读取。");
        std::optional<新状态信息> 最新;
        bool 最大时间多解 = false;
        for (const auto S : 外设.获取场景只读视图().查询状态列表(q.页面.定位.场景节点)) {
            const auto 候选 = 状态.获取状态(S);
            if (!候选) 连接工程故障(L"外设场景状态引用损坏。");
            if (候选->被描述存在节点 != q.请求.外设窗口 || 候选->来源实例特征节点 != F) continue;
            const auto 类型 = 特征.捕获特征匹配定义(候选->特征类型概念节点);
            const auto* 数量 = std::get_if<std::int64_t>(&候选->固定准确值);
            if (!类型 || 类型->特征类型根 != 定义->特征类型根 || !数量 || *数量 < 0
                || 候选->强时间.语义 != 新状态时间语义::实例绝对UTC)
                连接工程故障(L"接收数量正式状态类型、值或强时间不合法。");
            if (!最新 || 最新->强时间.纳秒 < 候选->强时间.纳秒) {
                最新 = *候选;
                最大时间多解 = false;
            } else if (最新->强时间 == 候选->强时间 && 最新->节点 != 候选->节点)
                最大时间多解 = true;
        }
        if (最大时间多解) 连接工程故障(L"接收数量最大时间存在多个不同状态。");
        if (最新 && std::none_of(q.固定状态.begin(), q.固定状态.end(),
                [&](const auto& 已有) { return 已有.状态 == 最新->节点; })) {
            q.固定状态.reserve(q.固定状态.size()+1);
            if (状态.增加引用(最新->节点) != 新状态操作状态::已完成)
                连接工程故障(L"接收数量基准或更新状态保护失败。");
            const auto 读回 = 状态.获取状态(最新->节点);
            const 引用 保护{最新->节点,q.请求.外设窗口,q.页面.定位.场景节点,true};
            if (!读回 || !状态内容相同(*读回, *最新) || !状态仍由场景持有(保护)) {
                if (状态.撤销增加引用(最新->节点)!=新状态操作状态::已完成)
                    连接工程故障(L"撤销未采用数量状态引用失败。");
                return std::nullopt;
            }
            q.固定状态.push_back(保护);
        }
        for (auto it=q.固定状态.begin();it!=q.固定状态.end();) {
            const auto S=it->状态;
            if ((最新&&S==最新->节点)||(q.现场.基准状态&&S==q.现场.基准状态->节点)
                ||(q.现场.更新状态&&S==q.现场.更新状态->节点)) { ++it; continue; }
            if (状态.减少引用(S)!=新状态操作状态::已完成)
                连接工程故障(L"释放已替换数量基准引用失败。");
            it=q.固定状态.erase(it);
        }
        return 最新;
    }
    bool 数量证据仍具备(const 调用& q) const {
        if (!q.现场.基准状态 || !q.现场.更新状态) return false;
        for (const auto* S : {&*q.现场.基准状态, &*q.现场.更新状态}) {
            const auto 读回 = 状态.获取状态(S->节点);
            if (!读回 || !状态内容相同(*读回, *S) || !状态仍由场景持有(
                    {S->节点, q.请求.外设窗口, q.页面.定位.场景节点, true})) return false;
        }
        return true;
    }
    std::vector<新方法参数角色绑定> 建立绑定(const 新连接请求& r,
        const 新外设对话框定位& p) const {
        (void)p;
        const std::array<std::pair<新方法参数信息类型, 稳定编码>, 6> 项{{
            {新方法参数信息类型::存在, r.现实场景},
            {新方法参数信息类型::存在, r.自我存在},
            {新方法参数信息类型::存在, r.目标存在},
            {新方法参数信息类型::特征, r.交互对象特征},
            {新方法参数信息类型::存在, r.窗口副本},
            {新方法参数信息类型::特征, r.外设标识特征}}};
        const auto 自我场景 = 世界.读取自我所在场景();
        std::vector<新方法参数角色绑定> 结果;
        for (std::uint32_t i = 0; i < 项.size(); ++i) {
            新方法参数角色绑定 b;
            b.有序引用 = 新方法有序参数引用{i + 1, 项[i].first, 项[i].second};
            // v4全部参数在内部世界：自我及其交互者特征在自我当前所在场景，其余在现实交互场景。
            if (i == 1 || i == 3) b.世界场景节点 = 自我场景;
            else if (i > 0) b.世界场景节点 = r.现实场景;
            结果.push_back(std::move(b));
        }
        return 结果;
    }
    新连接动作读回 建立连接动作(调用& q, const 方法参数场景& 场景) {
        const auto 前 = 特征.获取特征(q.请求.交互对象特征);
        if (!前 || 前->上级特征节点) return {};
        const auto 时间 = 当前连接时间();
        const auto 自我场景 = 世界.读取自我所在场景();
        if (!自我场景) 连接工程故障(L"连接动作前自我所在场景未登记。");
        if (q.任务执行) 新_本能函数管理类::标记本次动作入口(场景);
        // 动作动态挂执行主体（自我）所在场景。
        const auto 动作结果 = 世界.建立动作动态(*自我场景,
            {q.请求.自我存在, q.现场.方法身份, q.现场.身份,
                q.请求.自我存在, q.请求.交互对象特征, 时间});
        if (!动作结果.成功() || !动作结果.动作建立结果
            || !动作结果.动作建立结果->动态节点)
            连接工程故障(L"连接动作未正式挂入现实场景。");
        const auto 动作 = *动作结果.动作建立结果->动态节点;
        if (!q.任务执行) 方法.绑定直接调用动作(q.现场.身份, 动作);
        const auto 后 = 特征.获取特征(q.请求.交互对象特征);
        return {动作, 后 && 后->当前值 == 前->当前值};
    }
    新交互写入读回 写入连接交互者(调用& q, 稳定编码 动作) {
        if (!q.现场.关系发布许可已冻结 || q.已释放
            || q.现场.阶段 != 新连接状态::待关系发布 || q.现场.动作 != std::optional{动作})
            连接工程故障(L"未经本次数量状态更新许可进入关系写入。");
        const auto 原 = 特征.获取特征(q.请求.交互对象特征);
        if (!原) 连接工程故障(L"关系发布前交互者特征不可读。");
        const auto 自我场景 = 世界.读取自我所在场景();
        if (!自我场景) 连接工程故障(L"关系发布前自我所在场景未登记。");
        // 交互者值为交互者副本（内部节点），状态挂自我当前所在场景。
        const auto 变化 = 世界.更新存在引用并形成动态(*自我场景,
            q.请求.自我存在, q.请求.交互对象特征, q.请求.目标存在, 动作);
        if (变化.状态 == 新世界特征变化状态::前提已变化)
            return {新交互求值状态::前提变化, {}, {}};
        if (变化.状态 != 新世界特征变化状态::已完成
            && 变化.状态 != 新世界特征变化状态::已生成状态但无可连接前状态
            && 变化.状态 != 新世界特征变化状态::无变化)
            连接工程故障(L"连接交互者发布或状态动态形成失败。");
        const auto 后 = 特征.获取特征(q.请求.交互对象特征);
        if (!后 || 后->当前值 != std::optional<新特征准确值>{新特征准确值{q.请求.目标存在}})
            连接工程故障(L"连接交互者发布后读回不符。");
        // 交互者当前值变化后迁入自我（6120 §11.1，R92）；未变化不迁移。
        if (变化.状态 != 新世界特征变化状态::无变化 && *自我场景 != q.请求.现实场景) {
            const auto 迁入 = 世界.迁移自我(q.请求.现实场景);
            if (迁入 != 新场景操作状态::已完成 && 迁入 != 新场景操作状态::无变化)
                连接工程故障(L"交互者变化后自我迁入现实交互场景失败，已发生动作与写入保留。");
        }
        新交互写入读回 结果{新交互求值状态::已取得, 变化.新状态节点, {}};
        if (变化.动态发布结果 && 变化.动态发布结果->动态建立结果)
            结果.变化动态节点 = 变化.动态发布结果->动态建立结果->动态节点;
        return 结果;
    }
    class 真实连接后端 final : public 新连接执行后端 {
        实现& 服务;
        调用& 本次;
    public:
        真实连接后端(实现& 服务, 调用& 本次) : 服务(服务), 本次(本次) {}
        bool 已请求停止() const override {
            std::lock_guard 锁(服务.互斥);
            return 服务.关闭中 || 新_本能函数管理类::本次停止已请求();
        }
        新连接动作读回 建立动作(const 方法参数场景& 场景) override {
            return 服务.建立连接动作(本次, 场景);
        }
        std::optional<新状态信息> 读取最新接收数量状态() override {
            return 服务.最新接收数量状态(本次);
        }
        新二次特征计算结果 比较状态(const 新状态信息& 最新, const 新状态信息& 上轮) const override {
            const auto FT=服务.配置->接收数量类型;
            return 服务.二次特征.计算({{},
                二次特征准确特征输入{最新.节点, FT, 最新.固定准确值},
                二次特征准确特征输入{上轮.节点, FT, 上轮.固定准确值}, {}});
        }
        新交互写入读回 写入交互者(稳定编码 A) override { return 服务.写入连接交互者(本次, A); }
        稳定编码 读取连接关系() const override {
            if (!服务.连接关系) 连接工程故障(L"已确认连接缺少正式关系定义。");
            return *服务.连接关系;
        }
    };
    void 收束(调用& q) {
        if (q.已释放) return;
        if (有效(q.现场.身份) && !q.任务执行) 方法.收束直接调用身份(q.现场.身份);
        // 成功过程的两状态由调用表继续保护，供后续正式结果读取；表退出时释放。
        if (q.现场.阶段 != 新连接状态::已确认关系) 释放状态(q);
        else {
            for (auto it = q.固定状态.begin(); it != q.固定状态.end();) {
                if ((q.现场.基准状态 && it->状态 == q.现场.基准状态->节点)
                    || (q.现场.更新状态 && it->状态 == q.现场.更新状态->节点)) { ++it; continue; }
                if (状态.减少引用(it->状态) != 新状态操作状态::已完成)
                    连接工程故障(L"释放已替换的数量观察基准失败。");
                it = q.固定状态.erase(it);
            }
        }
        q.已释放 = true;
    }
    新连接返回 投影(const 调用& q) const {
        新连接返回 r;
        r.状态 = q.现场.阶段;
        if (有效(q.现场.身份)) r.调用身份 = q.现场.身份;
        r.动作节点 = q.现场.动作;
        r.运行材料 = q.现场.运行;
        return r;
    }
};

