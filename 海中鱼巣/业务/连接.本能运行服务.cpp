std::vector<新连接事实> 连接本能运行服务::读取已确认连接事实(
    稳定编码 现实场景, 稳定编码 自我存在,
    稳定编码 目标存在, 稳定编码 交互者特征) noexcept {
    try {
        if (!有效(现实场景) || !有效(自我存在) || !有效(目标存在)
            || !有效(交互者特征) || 自我存在 == 目标存在) return {};
        if (!实现_->进入(false)) return {};
        实现::入口票 入口{实现_.get()};
        const auto 配置 = 读取登记配置();
        if (!配置 || 配置->自我存在 != 自我存在
            || !实现_->现实场景.是场景节点(现实场景)) return {};
        std::vector<std::shared_ptr<实现::调用>> 候选;
        {
            std::lock_guard 锁(实现_->互斥);
            for (const auto& [身份, 调用] : 实现_->调用表) 候选.push_back(调用);
        }
        std::vector<新连接事实> 结果;
        for (const auto& 调用 : 候选) {
            std::lock_guard 锁(调用->操作锁);
            const auto& 请求 = 调用->请求;
            if (请求.现实场景 != 现实场景 || 请求.自我存在 != 自我存在
                || 请求.目标存在 != 目标存在 || 请求.交互对象特征 != 交互者特征
                || 调用->阶段 != 新连接状态::已确认关系) continue;
            if (!调用->关系发布许可已冻结 || !调用->动作
                || !调用->发送消息 || !调用->接收消息)
                连接工程故障(L"已确认连接缺少正式过程证据。");
            if (!实现_->两步消息仍具备(*调用)) continue;
            const auto 自我 = 实现_->存在.获取存在(自我存在);
            const auto 对端 = 实现_->存在.获取存在(目标存在);
            if (!自我 || !对端
                || 实现_->现实场景.查询所属场景(自我存在) != 现实场景
                || 实现_->现实场景.查询所属场景(目标存在) != 现实场景) continue;
            if (std::count(自我->特征节点组.begin(), 自我->特征节点组.end(), 交互者特征) != 1)
                continue;
            const auto 特征 = 实现_->特征.获取特征(交互者特征);
            if (!特征) 连接工程故障(L"自我持有的交互者特征不可读取。");
            const auto 类型匹配 = 实现_->特征概念.比较单特征概念(
                特征->特征概念节点, 配置->交互对象类型);
            if (类型匹配.状态 != 特征概念规则状态::已完成)
                连接工程故障(L"连接事实的交互者特征类型无法读取。");
            if (类型匹配.特征类型根 != 配置->交互对象类型) continue;
            const 新特征准确值 目标引用{目标存在};
            if (特征->当前值 != std::optional<新特征准确值>{目标引用}
                && std::find(特征->历史不同值.begin(), 特征->历史不同值.end(), 目标引用)
                    == 特征->历史不同值.end()) continue;
            const auto 动作 = 实现_->动态.按来源查询动作(调用->身份);
            if (动作.状态 != 新动态操作状态::已完成 || !动作.动作
                || 动作.动作->节点 != *调用->动作
                || 动作.动作->动作定义节点 != 调用->方法身份
                || 动作.动作->动作来源节点 != 调用->身份
                || 动作.动作->主题存在节点 != 自我存在
                || 动作.动作->动作目标存在节点 != 自我存在)
                连接工程故障(L"已确认连接的正式动作来源无法读回。");
            结果.push_back({调用->身份, *调用->动作, 现实场景, 自我存在, 目标存在,
                交互者特征, 请求.外设窗口, 调用->发送消息->消息节点, 调用->接收消息->消息节点});
        }
        return 结果;
    } catch (...) { 连接工程故障(L"已确认连接事实读取异常。"); }
}

新方法建立结果 连接本能运行服务::确保方法登记(
    const 新方法知识建立请求& 请求) noexcept {
    try {
        if (!请求.条件结果组.empty()) 连接工程故障(L"连接本能登记不得预造条件结果对。");
        bool 初始化中;
        std::optional<稳定编码> 已登记;
        {
            std::lock_guard 锁(实现_->互斥);
            if (!实现_->配置 || 实现_->关闭中) return {};
            初始化中 = 实现_->初始化中;
            已登记 = 实现_->方法节点;
        }
        if (!初始化中 && !已登记) return {};
        const auto r = 已登记
            ? 新方法建立结果{新方法操作状态::已找到, 已登记}
            : 实现_->方法.确保本能方法登记(std::string(新本能函数登记名_建立连接), 请求);
        const auto m = r.方法节点 ? 实现_->方法.获取方法(*r.方法节点) : std::nullopt;
        if (!m || !方法声明相同(*m, 请求)
            || (r.状态 == 新方法操作状态::已建立 && !m->条件结果组.empty()))
            连接工程故障(L"连接本能正式方法登记读回不符。");
        {
            std::lock_guard 锁(实现_->互斥);
            if (实现_->方法节点 && 实现_->方法节点 != r.方法节点)
                连接工程故障(L"连接本能方法身份变化。");
            实现_->方法节点 = r.方法节点;
        }
        return r;
    } catch (...) { 连接工程故障(L"连接本能方法登记异常。"); }
}

bool 连接本能运行服务::初始化(const 新连接登记配置& c) noexcept {
    try {
        if (!有效(c.自我存在) || !有效(c.自我概念) || !有效(c.通用存在概念)
            || !有效(c.交互对象类型) || !有效(c.接收消息类型)
            || !有效(c.发送消息类型)
            || !实现_->存在.存在节点属于概念(c.自我存在, c.自我概念)) return false;
        const auto 通用 = 实现_->存在概念.获取存在概念(c.通用存在概念);
        if (!通用 || 通用->种类 != 存在概念种类::抽象
            || !通用->特征组.empty()) return false;
        const auto 旧 = 实现_->方法.查询本能登记(std::string(新本能函数登记名_旧六参数建立连接));
        if (旧.方法节点) {
            const auto m = 实现_->方法.获取方法(*旧.方法节点);
            if (!m || m->参数规格组.size() != 6)
                连接工程故障(L"旧连接规格不可确认，保留并停止迁移。");
            if (m->启用状态 == 新方法启用状态::启用) {
                const auto 停用 = 实现_->方法.修改启用状态(m->节点, 新方法启用状态::停用);
                const auto 读回 = 实现_->方法.获取方法(m->节点);
                if ((停用 != 新方法操作状态::已修改 && 停用 != 新方法操作状态::无变化)
                    || !读回 || 读回->启用状态 != 新方法启用状态::停用)
                    连接工程故障(L"旧连接方法停用读回失败，未改写旧参数或执行。");
            }
        }
        {
            std::lock_guard 锁(实现_->互斥);
            if (实现_->配置) return *实现_->配置 == c && 实现_->方法节点.has_value();
            if (实现_->关闭中) return false;
            实现_->配置 = c;
            实现_->初始化中 = true;
        }
        const auto 空 = 实现_->方法.建立服务需求登记参数场景();
        if (空.状态 != 新方法操作状态::已建立 || !空.参数场景)
            连接工程故障(L"连接本能登记参数场景不可用。");
        const auto 运行 = 新_本能函数集::建立连接(*空.参数场景);
        {
            std::lock_guard 锁(实现_->互斥);
            实现_->初始化中 = false;
            return 运行.结果.状态 == 新本能函数执行状态::已按合同返回
                && 实现_->方法节点.has_value();
        }
    } catch (...) { 连接工程故障(L"连接本能初始化异常。"); }
}

新本能函数本次条件结果对 连接本能运行服务::推进本次(
    const 方法参数场景& 场景, 稳定编码 身份) noexcept {
    try {
        新本能函数本次条件结果对 拒绝;
        const auto q = 实现_->查找(身份);
        const auto 守卫 = q && q->任务执行
            ? 新_本能函数管理类::读取本次执行实例(场景)
            : 新_本能函数管理类::读取本次直接调用(场景);
        if (!守卫 || *守卫 != 身份 || !q || q->已释放
            || 场景.用途() != 新方法参数场景用途::执行
            || 场景.方法节点() != q->方法身份
            || 场景.全部角色绑定() != q->绑定) return 拒绝;
        if (q->任务执行) {
            const auto X = 实现_->任务.获取执行实例(身份);
            const auto T = X ? 实现_->任务.获取任务(X->任务节点) : std::nullopt;
            if (!X || !T || X->方法节点 != 场景.方法节点() || !X->本能采用
                || X->本能采用->参数绑定组 != q->绑定
                || X->状态 != 新任务执行状态::执行中
                || T->当前状态 != 新任务状态::执行中 || T->最近执行实例节点 != 身份) {
                q->阶段 = 新连接状态::来源失效;
                q->运行.结果.状态 = q->动作 ? 新本能函数执行状态::动作结果未知
                    : 新本能函数执行状态::入口拒绝;
                q->运行.结果.结果取得状态 = q->动作 ? 新本能函数结果取得状态::部分取得
                    : 新本能函数结果取得状态::未取得;
                实现_->收束(*q);
                return q->运行;
            }
        } else {
            const auto 来源 = 实现_->方法.读取直接调用身份(身份);
            if (!来源 || 来源->已收束 || 来源->动作节点 != q->动作
                || 来源->现实场景 != q->请求.现实场景
                || 来源->外设场景 != q->页面.定位.场景节点) return 拒绝;
        }
        if (!实现_->fresh(*q)) {
            q->阶段 = 新连接状态::来源失效;
            q->运行.结果.状态 = q->动作 ? 新本能函数执行状态::动作结果未知
                : 新本能函数执行状态::入口拒绝;
            q->运行.结果.结果取得状态 = q->动作
                ? 新本能函数结果取得状态::部分取得
                : 新本能函数结果取得状态::未取得;
            实现_->收束(*q);
            return q->运行;
        }
        if (!q->动作) {
            for (const auto& b : q->绑定) {
                新本能函数条件角色材料 材料;
                材料.有序引用 = b.有序引用;
                材料.世界场景节点 = b.世界场景节点;
                if (b.有序引用->信息类型 == 新方法参数信息类型::特征) {
                    const auto F = 场景.读取绑定特征(b.有序引用->信息节点);
                    if (!F || (!F->当前值 && b.有序引用->序号 != 4)) return 拒绝;
                    材料.实际特征组.push_back({b.有序引用->信息节点, F->当前值});
                }
                q->运行.条件.参数角色组.push_back(std::move(材料));
            }
            if (q->任务执行) {
                if (新_本能函数管理类::本次停止已请求()
                    || 实现_->任务.复核执行本能输入(身份, 场景) != 新任务本能输入复核状态::仍具备) {
                    q->阶段 = 新连接状态::来源失效;
                    q->运行.结果.状态 = 新本能函数执行状态::入口拒绝;
                    实现_->收束(*q);
                    return q->运行;
                }
            }
            if (!实现_->建立连接动作(*q, 场景)) {
                q->阶段 = 新连接状态::前提已变化;
                q->运行.结果.状态 = q->动作 ? 新本能函数执行状态::动作结果未知
                    : 新本能函数执行状态::入口拒绝;
                实现_->收束(*q);
                return q->运行;
            }
        }
        if (!q->提交序号) {
            if (q->收先) {
                if (!q->接收消息 || !实现_->消息仍有效(*q, *q->接收消息, 新外设消息方向::接收)) {
                    q->阶段 = 新连接状态::前提已变化;
                    q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
                    实现_->收束(*q);
                    return q->运行;
                }
            }
            const auto 发 = 提交网页对话框消息({q->宿主目标, ".", q->身份.值});
            if (发.状态 == 网页定向发送状态::页面被占用
                || 发.状态 == 网页定向发送状态::会话失效
                || 发.状态 == 网页定向发送状态::对话框未登记
                || 发.状态 == 网页定向发送状态::宿主未运行) {
                q->阶段 = 新连接状态::来源失效;
                q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
                实现_->收束(*q);
                return q->运行;
            }
            if (发.状态 != 网页定向发送状态::已排队 || !发.提交序号)
                连接工程故障(L"占用后的唯一次网页提交失败。");
            q->提交序号 = 稳定编码{*发.提交序号};
            q->运行.结果.状态 = 新本能函数执行状态::异步已受理;
            q->运行.结果.结果取得状态 = 新本能函数结果取得状态::待取得;
            return q->运行;
        }
        if (q->阶段 == 新连接状态::待发送完成) {
            const auto 发送 = 查询网页对话框发送(q->宿主目标, q->提交序号->值);
            if (发送.状态 == 网页定向发送状态::已排队
                || 发送.状态 == 网页定向发送状态::正在写出) return q->运行;
            if (发送.状态 == 网页定向发送状态::写出未完成
                || 发送.状态 == 网页定向发送状态::已取消) {
                q->阶段 = 新连接状态::传输未完成;
                q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
                q->运行.结果.结果取得状态 = 新本能函数结果取得状态::部分取得;
                实现_->收束(*q);
                return q->运行;
            }
            if (发送.状态 != 网页定向发送状态::已完整写出) {
                q->阶段 = 新连接状态::来源失效;
                q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
                实现_->收束(*q);
                return q->运行;
            }
            const auto 消息 = 实现_->外设.查找消息({q->页面.公开宿主会话,
                q->页面.对话框标识, 新外设消息方向::发送, q->提交序号->值});
            if (!消息 || !实现_->消息同源(*q, *消息, 新外设消息方向::发送)) {
                q->阶段 = 新连接状态::来源失效;
                q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
                实现_->收束(*q);
                return q->运行;
            }
            const auto s = 实现_->固定消息状态(*q, *消息);
            const auto a = 实现_->动态.获取动态(*q->动作);
            if (!s || !a || !a->动作时间
                || s->强时间.纳秒 < a->动作时间->纳秒)
                连接工程故障(L"完整发送没有对应的正式发送状态。");
            q->发送状态 = s->节点;
            q->发送消息 = *消息;
            if (q->收先) {
                const auto r = 实现_->状态.获取状态(*q->起点收状态);
                if (!r || !实现_->两步消息仍具备(*q)) {
                    q->阶段 = 新连接状态::前提已变化;
                    q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
                    实现_->收束(*q);
                    return q->运行;
                }
                q->回复状态 = r->节点;
                if (!实现_->冻结关系发布许可(*q)) {
                    q->阶段 = 新连接状态::来源失效;
                    q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
                    q->运行.结果.结果取得状态 = 新本能函数结果取得状态::部分取得;
                    实现_->收束(*q);
                    return q->运行;
                }
            } else q->阶段 = 新连接状态::待接收;
        }
        if (q->阶段 == 新连接状态::待接收) {
            if (!q->发送消息) 连接工程故障(L"本次发送消息身份丢失。");
            std::optional<新外设消息信息> 收消息;
            bool 最早多解 = false;
            for (const auto& 消息 : 实现_->读取接收消息事实(*q)) {
                if (!实现_->消息同源(*q, 消息, 新外设消息方向::接收)
                    || 消息.正式记录时间.纳秒 <= q->发送消息->正式记录时间.纳秒) continue;
                if (!收消息 || 消息.正式记录时间.纳秒 < 收消息->正式记录时间.纳秒) {
                    收消息 = 消息;
                    最早多解 = false;
                } else if (消息.正式记录时间.纳秒 == 收消息->正式记录时间.纳秒) 最早多解 = true;
            }
            if (!收消息 || 最早多解) return q->运行;
            const auto 收 = 实现_->固定消息状态(*q, *收消息);
            if (!收) return q->运行;
            q->接收消息 = *收消息;
            q->回复状态 = 收->节点;
            if (!实现_->冻结关系发布许可(*q)) {
                q->阶段 = 新连接状态::来源失效;
                q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
                q->运行.结果.结果取得状态 = 新本能函数结果取得状态::部分取得;
                实现_->收束(*q);
                return q->运行;
            }
        }
        if (q->阶段 == 新连接状态::待关系发布) {
            if (!实现_->发布关系(*q)
                && q->阶段 == 新连接状态::待关系发布) {
                q->运行.结果.状态 = 新本能函数执行状态::异步已受理;
                q->运行.结果.结果取得状态 = 新本能函数结果取得状态::部分取得;
            }
        }
        return q->运行;
    } catch (...) { 连接工程故障(L"连接单步推进异常。"); }
}

新连接返回 连接本能运行服务::开始(const 新连接请求& r) noexcept {
    return 开始内部(r, nullptr, std::nullopt);
}

新连接返回 连接本能运行服务::开始内部(const 新连接请求& r,
    const 方法参数场景* 任务场景, std::optional<稳定编码> X) noexcept {
    try {
        if (!实现_->进入(true)) return {};
        实现::入口票 票{实现_.get()};
        const auto 配置 = 读取登记配置();
        if (!配置 || r.自我存在 != 配置->自我存在
            || !有效(r.目标存在) || !有效(r.外设窗口)
            || !有效(r.现实场景) || !有效(r.交互对象特征)
            || r.自我存在 == r.目标存在
            || !实现_->存在.是存在节点(r.目标存在)
            || !实现_->现实场景.是场景节点(r.现实场景)
            || 实现_->现实场景.查询所属场景(r.自我存在) != r.现实场景
            || 实现_->现实场景.查询所属场景(r.目标存在) != r.现实场景)
            return {};
        const auto 来源 = 实现_->外设.读取对话框来源(r.外设窗口);
        if (!来源 || !来源->定位.接收消息特征 || !来源->定位.发送消息特征)
            return {新连接状态::条件未具备};
        const auto f = 实现_->特征.获取特征(r.交互对象特征);
        const auto e = 实现_->存在.获取存在(r.自我存在);
        if (!f || !e
            || std::count(e->特征节点组.begin(), e->特征节点组.end(),
                r.交互对象特征) != 1) return {新连接状态::条件未具备};
        const auto 类型匹配 = 实现_->特征概念.比较单特征概念(
            f->特征概念节点, 配置->交互对象类型);
        if (类型匹配.状态 != 特征概念规则状态::已完成)
            连接工程故障(L"交互对象特征概念比较未完成。");
        if (类型匹配.特征类型根 != 配置->交互对象类型)
            return {新连接状态::条件未具备};
        auto q = std::make_shared<实现::调用>();
        q->请求 = r;
        q->方法身份 = 任务场景 ? 任务场景->方法节点() : *实现_->方法节点;
        q->页面 = *来源;
        q->宿主目标 = {来源->公开宿主会话, 来源->对话框标识};
        q->绑定 = 实现_->建立绑定(r, 来源->定位);
        if (X) {
            if (!任务场景 || q->绑定.size() != 任务场景->全部角色绑定().size()) return {};
            // 场景定位由任务冻结，不要求任务填写连接内部生成的同一份封套。
            for (const auto& b : q->绑定) {
                const auto* p = 任务场景->查询参数(b.有序引用->序号);
                if (!p || *p != *b.有序引用) return {};
            }
            q->绑定 = 任务场景->全部角色绑定();
            q->任务执行 = true;
        }
        const auto 参数 = 实现_->方法.建立参数场景(q->方法身份, q->绑定);
        if (参数.状态 != 新方法操作状态::已建立 || !参数.参数场景) {
            if (参数场景业务缺口(参数.状态))
                return {新连接状态::条件未具备};
            连接工程故障(L"连接开始参数场景发生非业务缺口。");
        }
        if (!实现_->固定存在状态(*q, r.自我存在, r.现实场景, false)
            || !实现_->固定存在状态(*q, r.外设窗口, 来源->定位.场景节点, true)) {
            实现_->释放状态(*q);
            return {新连接状态::条件未具备};
        }
        // 目标存在有历史状态时可保护，但“必须已观测过某个特征值”不是连接前提。
        // 目标身份/在场在fresh核验，最终引用与身份退出竞争由F同CAS关闭。
        (void)实现_->固定存在状态(*q, r.目标存在, r.现实场景, false);
        if (!实现_->fresh(*q)) {
            实现_->释放状态(*q);
            return {新连接状态::来源失效};
        }
        if (X) q->身份 = *X;
        else q->身份 = 实现_->方法.建立直接调用身份(
            *实现_->方法节点, q->绑定, r.现实场景, 来源->定位.场景节点).节点;
        if (!取得网页对话框出站占用(q->宿主目标, q->身份.值)) {
            q->阶段 = 新连接状态::页面正被使用;
            实现_->收束(*q);
            return 实现_->投影(*q);
        }
        q->已占用 = true;
        q->收先 = r.本次起点接收状态.has_value();
        if (q->收先) {
            const auto s = 实现_->状态.获取状态(*r.本次起点接收状态);
            const auto 列表 = 实现_->外设.获取场景只读视图().查询状态列表(来源->定位.场景节点);
            if (!s || s->被描述存在节点 != r.外设窗口
                || s->来源实例特征节点 != *来源->定位.接收消息特征
                || std::count(列表.begin(), 列表.end(), s->节点) != 1) {
                q->阶段 = 新连接状态::条件未具备;
                实现_->收束(*q);
                return 实现_->投影(*q);
            }
            std::optional<新外设消息信息> 起点消息;
            bool 多解 = false;
            for (const auto& 消息 : 实现_->读取接收消息事实(*q)) {
                if (!实现_->消息同源(*q, 消息, 新外设消息方向::接收)
                    || 消息.正式记录时间 != s->强时间) continue;
                if (起点消息) { 多解 = true; break; }
                起点消息 = 消息;
            }
            const auto 消息状态 = 起点消息 && !多解 ? 实现_->固定消息状态(*q, *起点消息) : std::nullopt;
            if (!消息状态) {
                q->阶段 = 新连接状态::条件未具备;
                实现_->收束(*q);
                return 实现_->投影(*q);
            }
            q->接收消息 = *起点消息;
            q->起点收状态 = 消息状态->节点;
        }
        {
            std::lock_guard 锁(实现_->互斥);
            if (!实现_->调用表.emplace(q->身份, q).second)
                连接工程故障(L"直接调用身份重复。");
        }
        std::lock_guard 单步锁(q->操作锁);
        if (X) {
            q->运行 = 推进本次(*任务场景, *X);
            return 实现_->投影(*q);
        }
        新_本能函数管理类::本能直接调用守卫 守卫(*参数.参数场景, q->身份);
        const auto 调用 = 实现_->方法.调用本能函数(*实现_->方法节点, *参数.参数场景);
        if (调用.状态 != 新方法本能调用状态::已调用 || !调用.本次条件结果对)
            连接工程故障(L"连接本能首次调用未进入正式注册入口。");
        q->运行 = *调用.本次条件结果对;
        return 实现_->投影(*q);
    } catch (...) { 连接工程故障(L"连接开始入口异常。"); }
}

新本能函数本次条件结果对 连接本能运行服务::执行任务(
    const 方法参数场景& 场景, 稳定编码 X) noexcept {
    try {
        新本能函数本次条件结果对 拒绝;
        拒绝.结果.状态 = 新本能函数执行状态::入口拒绝;
        if (新_本能函数管理类::读取本次执行实例(场景) != std::optional{X}
            || !新_本能函数管理类::本次停止可用()
            || 新_本能函数管理类::本次停止已请求() || !实现_->进入(true)) return 拒绝;
        实现::入口票 票{实现_.get()};
        if (实现_->任务.复核执行本能输入(X, 场景) != 新任务本能输入复核状态::仍具备)
            return 拒绝;
        const auto M = 实现_->方法.获取方法(场景.方法节点());
        if (!M || M->本能函数登记名 != 新本能函数登记名_建立连接
            || (M->来源方法节点.value_or(M->节点) != *实现_->方法节点)) return 拒绝;
        const auto& 绑定 = 场景.全部角色绑定();
        if (绑定.size() != 7) return 拒绝;
        std::array<稳定编码, 7> 参数{};
        for (std::uint32_t i = 0; i < 7; ++i) {
            const auto* p = 场景.查询参数(i + 1);
            if (!p || p->信息类型 != (i == 3 || i >= 5 ? 新方法参数信息类型::特征
                : 新方法参数信息类型::存在)) return 拒绝;
            参数[i] = p->信息节点;
        }
        新连接请求 请求{参数[1], 参数[2], 参数[3], 参数[0], 参数[4]};
        const auto 首次 = 开始内部(请求, &场景, X);
        const auto q = 实现_->查找(X);
        if (!q) return 首次.运行材料.value_or(拒绝);
        for (;;) {
            bool 关闭 = false;
            { std::lock_guard 锁(实现_->互斥); 关闭 = 实现_->关闭中; }
            {
                std::lock_guard 锁(q->操作锁);
                if (连接终态(q->阶段) || q->已释放) return q->运行;
                if (关闭 || 新_本能函数管理类::本次停止已请求()) {
                    q->阶段 = 新连接状态::已取消;
                    q->运行.结果.状态 = q->动作 ? 新本能函数执行状态::动作结果未知
                        : 新本能函数执行状态::入口拒绝;
                    q->运行.结果.结果取得状态 = q->动作 ? 新本能函数结果取得状态::部分取得
                        : 新本能函数结果取得状态::未取得;
                    实现_->收束(*q);
                    return q->运行;
                }
                q->运行 = 推进本次(场景, X);
                if (连接终态(q->阶段) || q->已释放) return q->运行;
            }
            // 只控制工程轮询频率；没有业务超时。等待期间不持任何领域/现场锁。
            新_本能函数管理类::等待本次停止(std::chrono::milliseconds(50));
        }
    } catch (...) { 连接工程故障(L"连接任务执行入口异常。"); }
}

新连接返回 连接本能运行服务::推进(稳定编码 身份) noexcept {
    try {
        if (!实现_->进入(false)) return {新连接状态::来源失效};
        实现::入口票 票{实现_.get()};
        const auto q = 实现_->查找(身份);
        if (!q) return {新连接状态::来源失效};
        std::lock_guard 单步锁(q->操作锁);
        if (连接终态(q->阶段) || q->已释放) return 实现_->投影(*q);
        const auto 参数 = 实现_->方法.建立参数场景(q->方法身份, q->绑定);
        if (参数.状态 != 新方法操作状态::已建立 || !参数.参数场景) {
            if (!参数场景业务缺口(参数.状态))
                连接工程故障(L"连接推进参数场景发生非业务缺口。");
            q->阶段 = 新连接状态::来源失效;
            q->运行.结果.状态 = 新本能函数执行状态::动作结果未知;
            实现_->收束(*q);
            return 实现_->投影(*q);
        }
        新_本能函数管理类::本能直接调用守卫 守卫(*参数.参数场景, 身份);
        const auto 调用 = 实现_->方法.调用本能函数(*实现_->方法节点, *参数.参数场景);
        if (调用.状态 != 新方法本能调用状态::已调用 || !调用.本次条件结果对)
            连接工程故障(L"连接本能推进未进入注册入口。");
        q->运行 = *调用.本次条件结果对;
        return 实现_->投影(*q);
    } catch (...) { 连接工程故障(L"连接推进入口异常。"); }
}

新连接返回 连接本能运行服务::取消(稳定编码 身份) noexcept {
    try {
        if (!实现_->进入(false)) return {新连接状态::来源失效};
        实现::入口票 票{实现_.get()};
        const auto q = 实现_->查找(身份);
        if (!q) return {新连接状态::来源失效};
        std::lock_guard 单步锁(q->操作锁);
        if (连接终态(q->阶段) || q->已释放) return 实现_->投影(*q);
        q->阶段 = 新连接状态::已取消;
        q->运行.结果.状态 = q->动作
            ? 新本能函数执行状态::动作结果未知
            : 新本能函数执行状态::入口拒绝;
        q->运行.结果.结果取得状态 = q->动作
            ? 新本能函数结果取得状态::部分取得
            : 新本能函数结果取得状态::未取得;
        实现_->收束(*q);
        return 实现_->投影(*q);
    } catch (...) { 连接工程故障(L"连接取消入口异常。"); }
}

void 连接本能运行服务::关闭() noexcept {
    try {
        std::vector<std::shared_ptr<实现::调用>> 全部;
        {
            std::unique_lock 锁(实现_->互斥);
            if (实现_->关闭中 && 实现_->调用表.empty()) return;
            实现_->关闭中 = true;
            实现_->闲置.wait(锁, [&] { return 实现_->活动入口 == 0; });
            for (const auto& [_, q] : 实现_->调用表) 全部.push_back(q);
        }
        for (const auto& q : 全部) {
            std::lock_guard 单步锁(q->操作锁);
            if (!q->已释放) {
                q->阶段 = 新连接状态::已取消;
                q->运行.结果.状态 = q->动作
                    ? 新本能函数执行状态::动作结果未知
                    : 新本能函数执行状态::入口拒绝;
                实现_->收束(*q);
            }
        }
        const auto 端口 = 新_本能函数管理类::关闭连接端口(*this);
        if (端口 != 新本能函数端口装配状态::已关闭
            && 端口 != 新本能函数端口装配状态::所有者冲突)
            连接工程故障(L"连接端口关闭失败。");
    } catch (...) { 连接工程故障(L"连接关闭入口异常。"); }
}

