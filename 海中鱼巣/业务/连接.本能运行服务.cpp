struct 连接本能运行服务::实现 final {
    struct 引用 final { 稳定编码 状态, 存在, 场景; bool 外设 = false; };
    struct 调用 final {
        std::mutex 操作锁;
        新连接请求 请求;
        新外设对话框来源 页面;
        网页对话框目标 宿主目标;
        std::vector<新方法参数角色绑定> 绑定;
        std::vector<引用> 固定状态;
        稳定编码 身份{}, 方法身份{};
        bool 任务执行 = false;
        std::optional<稳定编码> 动作, 提交序号, 起点收状态, 发送状态, 回复状态;
        std::optional<新外设消息信息> 发送消息, 接收消息;
        bool 已占用 = false, 已释放 = false, 收先 = false;
        bool 关系发布许可已冻结 = false;
        新连接状态 阶段 = 新连接状态::待发送完成;
        新本能函数本次条件结果对 运行;
    };

    实现(新_世界树类& w, 新_外设世界树类& p, 新_方法类& m,
        新_存在类& e, 新_特征类& f, 新_特征值类& v, 新_状态类& s,
        新_动态类& d, 概念_存在类& ec, 概念_特征类& fc, 新_任务类& t) noexcept
        : 世界(w), 外设(p), 方法(m), 任务(t), 存在(e), 特征(f), 值(v), 状态(s), 动态(d),
          存在概念(ec), 特征概念(fc), 现实场景(w.获取事实服务引用().场景服务) {}

    新_世界树类& 世界;
    新_外设世界树类& 外设;
    新_方法类& 方法;
    新_任务类& 任务;
    新_存在类& 存在;
    新_特征类& 特征;
    新_特征值类& 值;
    新_状态类& 状态;
    新_动态类& 动态;
    概念_存在类& 存在概念;
    概念_特征类& 特征概念;
    新_场景类& 现实场景;
    std::mutex 互斥;
    std::condition_variable 闲置;
    std::map<稳定编码, std::shared_ptr<调用>> 调用表;
    std::optional<新连接登记配置> 配置;
    std::optional<稳定编码> 方法节点;
    std::size_t 活动入口 = 0;
    bool 初始化中 = false, 关闭中 = false;

    std::shared_ptr<调用> 查找(稳定编码 n) {
        std::lock_guard 锁(互斥);
        const auto it = 调用表.find(n);
        return it == 调用表.end() ? nullptr : it->second;
    }
    bool 进入(bool 开始) {
        std::lock_guard 锁(互斥);
        if (关闭中 || !配置 || !方法节点) return false;
        ++活动入口;
        return true;
    }
    void 离开() {
        std::lock_guard 锁(互斥);
        if (!活动入口) 连接工程故障(L"公共入口计数下溢。");
        --活动入口;
        闲置.notify_all();
    }
    struct 入口票 final {
        实现* 自身 = nullptr;
        ~入口票() { if (自身) 自身->离开(); }
    };

    bool 状态仍由场景持有(const 引用& r) const {
        const auto& c = r.外设 ? 外设.获取场景只读视图() : 现实场景;
        const auto E = 存在.获取存在(r.存在);
        const auto S = 状态.获取状态(r.状态);
        const auto 场景 = c.获取场景(r.场景);
        if (!E || !S || !场景 || S->被描述存在节点 != r.存在
            || std::count(E->特征节点组.begin(), E->特征节点组.end(),
                S->来源实例特征节点) != 1) return false;
        const auto 列表 = c.查询状态列表(r.场景);
        return std::count(列表.begin(), 列表.end(), r.状态) == 1;
    }

    bool 固定存在状态(调用& q, 稳定编码 E, 稳定编码 C, bool 外设场景) {
        const auto& 场景 = 外设场景 ? 外设.获取场景只读视图() : 现实场景;
        if (!存在.是存在节点(E) || !场景.是场景节点(C)) return false;
        for (const auto s : 场景.查询状态列表(C)) {
            const auto 读 = 状态.获取状态(s);
            if (!读) 连接工程故障(L"场景状态列表引用已损坏。");
            if (读->被描述存在节点 != E) continue;
            if (!存在.获取存在(E)) return false;
            const auto e = 存在.获取存在(E);
            if (!e || std::count(e->特征节点组.begin(), e->特征节点组.end(),
                读->来源实例特征节点) != 1) continue;
            if (std::any_of(q.固定状态.begin(), q.固定状态.end(),
                    [&](const 引用& 已有) { return 已有.状态 == s; })) return true;
            const auto 加 = 状态.增加引用(s);
            if (加 == 新状态操作状态::状态不存在) continue;
            if (加 != 新状态操作状态::已完成)
                连接工程故障(L"取得真实状态引用失败。");
            q.固定状态.push_back({s, E, C, 外设场景});
            return true;
        }
        return false;
    }
    void 释放状态(调用& q) {
        for (auto it = q.固定状态.rbegin(); it != q.固定状态.rend(); ++it)
            if (状态.减少引用(it->状态) != 新状态操作状态::已完成)
                连接工程故障(L"释放现场状态引用失败。");
        q.固定状态.clear();
    }
    bool 消息同源(const 调用& q, const 新外设消息信息& 消息, 新外设消息方向 方向) const {
        return 消息.场景节点 == q.页面.定位.场景节点 && 消息.窗口节点 == q.请求.外设窗口
            && 消息.来源.方向 == 方向 && 消息.来源.公开宿主会话 == q.页面.公开宿主会话
            && 消息.来源.对话框标识 == q.页面.对话框标识;
    }
    bool 消息仍有效(const 调用& q, const 新外设消息信息& 消息, 新外设消息方向 方向) const {
        const auto 当前 = 外设.读取消息(消息.消息节点);
        return 当前 && 消息同源(q, *当前, 方向) && 当前->来源 == 消息.来源
            && 当前->正文材料节点 == 消息.正文材料节点 && 当前->UTF8正文 == 消息.UTF8正文
            && 当前->正式记录时间 == 消息.正式记录时间;
    }
    std::vector<新外设消息信息> 读取接收消息事实(const 调用& q) const {
        if (!q.页面.定位.接收消息特征) 连接工程故障(L"正式接收消息特征缺失。");
        const auto F = 特征.获取特征(*q.页面.定位.接收消息特征);
        if (!F || !F->当前值) 连接工程故障(L"正式接收消息集合不可读。");
        std::set<稳定编码> 消息身份;
        // 只沿本窗口正式消息F的完整材料引用枚举，不读取旧计数/最后正文。
        // 历史集合仍引用同一消息，当前移除不撤销已经发生的两步事实。
        for (const auto& 历史 : F->历史不同值) {
            const auto* 编码 = std::get_if<稳定编码>(&历史);
            const auto 材料 = 编码 ? 值.获取特征值(*编码) : std::nullopt;
            const auto* 成员 = 材料 ? std::get_if<std::vector<std::uint64_t>>(&材料->材料) : nullptr;
            if (!成员 || 材料->物理类型 != 材料物理类型::U64数组)
                连接工程故障(L"正式接收消息历史材料损坏。");
            for (const auto n : *成员) 消息身份.insert(稳定编码{n});
        }
        std::vector<新外设消息信息> 结果;
        for (const auto n : 消息身份) {
            const auto 消息 = 外设.读取消息(n);
            if (!消息 || !消息同源(q, *消息, 新外设消息方向::接收))
                连接工程故障(L"正式接收消息历史引用跨来源或失效。");
            结果.push_back(*消息);
        }
        return 结果;
    }
    std::optional<新状态信息> 固定消息状态(调用& q, const 新外设消息信息& 消息) {
        const auto F = 消息.来源.方向 == 新外设消息方向::接收
            ? q.页面.定位.接收消息特征 : q.页面.定位.发送消息特征;
        if (!F) return std::nullopt;
        std::optional<新状态信息> 命中;
        for (const auto n : 外设.获取场景只读视图().查询状态列表(q.页面.定位.场景节点)) {
            const auto s = 状态.获取状态(n);
            if (!s) 连接工程故障(L"消息证据状态不可读。");
            if (s->被描述存在节点 != q.请求.外设窗口 || s->来源实例特征节点 != *F
                || s->强时间 != 消息.正式记录时间) continue;
            const auto* 编码 = std::get_if<稳定编码>(&s->固定准确值);
            const auto 材料 = 编码 ? 值.获取特征值(*编码) : std::nullopt;
            const auto* 成员 = 材料 ? std::get_if<std::vector<std::uint64_t>>(&材料->材料) : nullptr;
            if (!成员 || 材料->物理类型 != 材料物理类型::U64数组)
                连接工程故障(L"消息集合状态材料形状损坏。");
            if (std::count(成员->begin(), 成员->end(), 消息.消息节点.值) != 1) continue;
            if (命中) return std::nullopt;
            命中 = *s;
        }
        if (!命中) return std::nullopt;
        if (std::none_of(q.固定状态.begin(), q.固定状态.end(),
                [&](const auto& 已有) { return 已有.状态 == 命中->节点; })) {
            if (状态.增加引用(命中->节点) != 新状态操作状态::已完成)
                连接工程故障(L"消息证据状态引用保护失败。");
            q.固定状态.push_back({命中->节点, q.请求.外设窗口, q.页面.定位.场景节点, true});
        }
        return 命中;
    }
    bool 两步消息仍具备(const 调用& q) const {
        if (!q.发送消息 || !q.接收消息 || !q.提交序号
            || q.发送消息->来源.来源序号 != q.提交序号->值
            || !消息仍有效(q, *q.发送消息, 新外设消息方向::发送)
            || !消息仍有效(q, *q.接收消息, 新外设消息方向::接收)) return false;
        const auto 发时 = q.发送消息->正式记录时间.纳秒;
        const auto 收时 = q.接收消息->正式记录时间.纳秒;
        return q.收先 ? 收时 < 发时 : 发时 < 收时;
    }
    bool fresh(调用& q) {
        if (q.关系发布许可已冻结 && !两步消息仍具备(q)) return false;
        if (!存在.是存在节点(q.请求.目标存在)
            || (!q.关系发布许可已冻结
                && 现实场景.查询所属场景(q.请求.目标存在) != q.请求.现实场景)) return false;
        if (q.已占用 && !q.关系发布许可已冻结
            && !核验网页对话框出站占用可用(q.宿主目标, q.身份.值))
            return false;
        for (const auto& r : q.固定状态)
            if (!状态仍由场景持有(r)) return false;
        const auto 来源 = 外设.读取对话框来源(q.请求.外设窗口);
        if (!来源 || 来源->定位 != q.页面.定位
            || 来源->公开宿主会话 != q.页面.公开宿主会话
            || 来源->对话框标识 != q.页面.对话框标识) return false;
        const auto E = 存在.获取存在(q.请求.自我存在);
        const auto F = 特征.获取特征(q.请求.交互对象特征);
        return E && F
            && std::count(E->特征节点组.begin(), E->特征节点组.end(),
                q.请求.交互对象特征) == 1
            && 现实场景.查询所属场景(q.请求.自我存在) == q.请求.现实场景;
    }
    bool 冻结关系发布许可(调用& q) {
        if (q.已释放 || !q.已占用 || !q.动作 || !q.发送状态
            || !q.回复状态 || q.关系发布许可已冻结)
            连接工程故障(L"连接两步证据或许可阶段不完整。");
        // 世界事实先重读，宿主会话/停止信号/本次占用是唯一最后许可读口。
        if (!两步消息仍具备(q) || !fresh(q)
            || !核验网页对话框出站占用可用(q.宿主目标, q.身份.值))
            return false;
        q.关系发布许可已冻结 = true;
        q.阶段 = 新连接状态::待关系发布;
        return true;
    }
    std::vector<新方法参数角色绑定> 建立绑定(const 新连接请求& r,
        const 新外设对话框定位& p) const {
        const std::array<std::pair<新方法参数信息类型, 稳定编码>, 7> 项{{
            {新方法参数信息类型::存在, r.现实场景},
            {新方法参数信息类型::存在, r.自我存在},
            {新方法参数信息类型::存在, r.目标存在},
            {新方法参数信息类型::特征, r.交互对象特征},
            {新方法参数信息类型::存在, r.外设窗口},
            {新方法参数信息类型::特征, *p.接收消息特征},
            {新方法参数信息类型::特征, *p.发送消息特征}}};
        std::vector<新方法参数角色绑定> 结果;
        for (std::uint32_t i = 0; i < 项.size(); ++i) {
            新方法参数角色绑定 b;
            b.有序引用 = 新方法有序参数引用{i + 1, 项[i].first, 项[i].second};
            if (i > 0 && i < 4) b.世界场景节点 = r.现实场景;
            结果.push_back(std::move(b));
        }
        return 结果;
    }
    bool 建立连接动作(调用& q, const 方法参数场景& 场景) {
        const auto 前 = 特征.获取特征(q.请求.交互对象特征);
        if (!前 || 前->上级特征节点) return false;
        const auto 时间 = 当前连接时间();
        if (q.任务执行) 新_本能函数管理类::标记本次动作入口(场景);
        const auto 动作结果 = 世界.建立动作动态(q.请求.现实场景,
            {q.请求.自我存在, q.方法身份, q.身份,
                q.请求.自我存在, q.请求.交互对象特征, 时间});
        if (!动作结果.成功() || !动作结果.动作建立结果
            || !动作结果.动作建立结果->动态节点)
            连接工程故障(L"连接动作未正式挂入现实场景。");
        q.动作 = *动作结果.动作建立结果->动态节点;
        if (!q.任务执行) 方法.绑定直接调用动作(q.身份, *q.动作);
        q.运行.结果.动作动态节点 = q.动作;
        q.运行.结果.动作阶段 = 新本能函数动作阶段::已进入动作;
        const auto 后 = 特征.获取特征(q.请求.交互对象特征);
        return 后 && 后->当前值 == 前->当前值;
    }
    bool 发布关系(调用& q) {
        if (!q.关系发布许可已冻结 || q.已释放 || q.阶段 != 新连接状态::待关系发布)
            连接工程故障(L"未经本次两步事实许可进入关系发布。");
        if (!fresh(q)) {
            q.阶段 = 新连接状态::来源失效;
            q.运行.结果.状态 = 新本能函数执行状态::动作结果未知;
            q.运行.结果.结果取得状态 = 新本能函数结果取得状态::部分取得;
            收束(q);
            return false;
        }
        const auto 原 = 特征.获取特征(q.请求.交互对象特征);
        if (!原) 连接工程故障(L"关系发布前交互者特征不可读。");
        if (!q.动作) 连接工程故障(L"交互者发布缺少本次动作。");
        const auto 变化 = 世界.更新存在引用并形成动态(q.请求.现实场景,
            q.请求.自我存在, q.请求.交互对象特征, q.请求.目标存在, *q.动作);
        if (变化.状态 == 新世界特征变化状态::前提已变化) {
            q.阶段 = 新连接状态::待关系发布;
            return false;
        }
        if (变化.状态 != 新世界特征变化状态::已完成
            && 变化.状态 != 新世界特征变化状态::已生成状态但无可连接前状态
            && 变化.状态 != 新世界特征变化状态::无变化)
            连接工程故障(L"连接交互者发布或状态动态形成失败。");
        const auto 后 = 特征.获取特征(q.请求.交互对象特征);
        if (!后 || 后->当前值 != std::optional<新特征准确值>{新特征准确值{q.请求.目标存在}})
            连接工程故障(L"连接交互者发布后读回不符。");
        if (变化.新状态节点) q.运行.结果.已形成状态节点组.push_back(*变化.新状态节点);
        if (变化.动态发布结果 && 变化.动态发布结果->动态建立结果
            && 变化.动态发布结果->动态建立结果->动态节点)
            q.运行.结果.已形成动态节点组.push_back(
                *变化.动态发布结果->动态建立结果->动态节点);
        q.运行.结果.建议观察特征节点组 = {q.请求.交互对象特征};
        q.运行.结果.状态 = 新本能函数执行状态::已按合同返回;
        q.运行.结果.动作阶段 = 新本能函数动作阶段::已按函数合同返回;
        q.运行.结果.结果取得状态 = 新本能函数结果取得状态::已取得;
        q.阶段 = 新连接状态::已确认关系;
        收束(q);
        return true;
    }
    void 收束(调用& q) {
        if (q.已释放) return;
        if (q.提交序号 && q.已占用) {
            const auto 取消 = 取消网页对话框提交(q.宿主目标, q.提交序号->值, q.身份.值);
            // 停止接纳会清除旧租约；是否被另一调用占用由下面的精确释放读口裁决。
            if (取消.状态 == 网页定向发送状态::输入拒绝)
                连接工程故障(L"本次提交取消请求结构不合法。");
        }
        if (有效(q.身份) && !q.任务执行) 方法.收束直接调用身份(q.身份);
        if (q.已占用 && !释放网页对话框出站占用(q.宿主目标, q.身份.值))
            连接工程故障(L"同一页面已被其它调用占用，旧占用不能安全释放。");
        q.已占用 = false;
        释放状态(q);
        q.已释放 = true;
    }
    新连接返回 投影(const 调用& q) const {
        新连接返回 r;
        r.状态 = q.阶段;
        if (有效(q.身份)) r.调用身份 = q.身份;
        r.动作节点 = q.动作;
        r.运行材料 = q.运行;
        return r;
    }
};

