#include <new>

namespace 海中鱼巣 {
namespace {
方法登记根生产初始化状态 映射状态(方法登记根结构状态 状态) noexcept {
  switch (状态) {
  case 方法登记根结构状态::事实代次漂移:
    return 方法登记根生产初始化状态::当前性漂移;
  case 方法登记根结构状态::资源失败:
    return 方法登记根生产初始化状态::资源失败;
  case 方法登记根结构状态::数量预算不足:
    return 方法登记根生产初始化状态::数量预算不足;
  case 方法登记根结构状态::入口拒绝:
    return 方法登记根生产初始化状态::入口拒绝;
  default:
    return 方法登记根生产初始化状态::根结构失败;
  }
}
}

bool 方法登记根生产初始化结果::成功() const noexcept {
  return (状态 == 方法登记根生产初始化状态::已初始化 ||
          状态 == 方法登记根生产初始化状态::精确重复) &&
      请求回显.合同版本 == 1 && 请求回显.最大空域核验事实数 != 0 &&
      最终Gread != 0 && 根 &&
      有效(根->身份.结点) && 根->创建事实代次 != 0;
}

方法登记根生产初始化提供者::方法登记根生产初始化提供者(
    L2方法结构聚合服务 &聚合) noexcept : 方法结构聚合服务_(聚合) {}

方法登记根生产初始化结果 方法登记根生产初始化提供者::初始化(
    const 方法登记根生产初始化请求 &请求) noexcept {
  方法登记根生产初始化结果 结果;
  结果.请求回显 = 请求;
  if (请求.合同版本 != 1 || 请求.最大空域核验事实数 == 0) return 结果;
  try {
    auto &服务 = 方法结构聚合服务_.取得L2方法结构服务();
    auto 全组 = 服务.读取全部当前方法登记根({1, 0});
    if (全组.状态 == 方法登记根结构状态::尚未建立) {
      const auto 建立 = 服务.建立或读取方法登记根(
          {1, 全组.Gread, 方法登记根首次写入幂等身份,
              请求.最大空域核验事实数});
      if (!建立.成功()) {
        if (建立.状态 == 方法登记根结构状态::已可能发布) {
          全组 = 服务.读取全部当前方法登记根({1, 0});
          if (!全组.成功()) {
            结果.状态 = 映射状态(全组.状态);
            结果.最终Gread = 全组.Gread;
            return 结果;
          }
          结果 = {方法登记根生产初始化状态::精确重复, 请求,
              全组.Gread, 全组.根组.front()};
          return 结果;
        }
        结果.状态 = 映射状态(建立.状态);
        结果.最终Gread = 建立.Gread;
        return 结果;
      }
      const auto 单根 = 服务.读取当前方法登记根({1, 建立.Gread});
      全组 = 服务.读取全部当前方法登记根({1, 建立.Gread});
      if (!单根.成功() || !全组.成功() ||
          !单根.根 || *单根.根 != 全组.根组.front() ||
          单根.Gread != 全组.Gread) {
        结果.状态 = !单根.成功() ? 映射状态(单根.状态) : 映射状态(全组.状态);
        结果.最终Gread = 全组.Gread;
        return 结果;
      }
      结果 = {建立.状态 == 方法登记根结构状态::已建立
              ? 方法登记根生产初始化状态::已初始化
              : 方法登记根生产初始化状态::精确重复,
          请求, 全组.Gread, 单根.根};
      return 结果;
    }
    if (!全组.成功()) {
      结果.状态 = 映射状态(全组.状态);
      结果.最终Gread = 全组.Gread;
      return 结果;
    }
    const auto 单根 = 服务.读取当前方法登记根({1, 全组.Gread});
    const auto 最终全组 = 服务.读取全部当前方法登记根({1, 全组.Gread});
    if (!单根.成功() || !最终全组.成功() || !单根.根 ||
        *单根.根 != 最终全组.根组.front() ||
        单根.Gread != 最终全组.Gread) {
      结果.状态 = !单根.成功() ? 映射状态(单根.状态) : 映射状态(最终全组.状态);
      结果.最终Gread = 最终全组.Gread;
      return 结果;
    }
    return {方法登记根生产初始化状态::精确重复, 请求,
        最终全组.Gread, 单根.根};
  } catch (const std::bad_alloc &) {
    结果.状态 = 方法登记根生产初始化状态::资源失败;
  } catch (...) {
    结果.状态 = 方法登记根生产初始化状态::内部不一致;
  }
  return 结果;
}

}  // namespace 海中鱼巣
