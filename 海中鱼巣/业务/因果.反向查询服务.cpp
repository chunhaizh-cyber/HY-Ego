// 仅调用期工作材料。所有缓存来自公开只读owner；不查询或写入基础表。
class 反向查询工作 final
{
  public:
    反向查询工作(const 新_因果类 &因果, const 新_特征类 &特征, const 概念_特征类 &特征概念,
                 const 概念_存在类 &存在概念, const 概念_动态类 &动态概念, const 新_动态类 &动态,
                 const 新_存在类 &存在, const 新_场景类 &场景)
        : 因果_(因果), 特征_(特征), 特征概念_(特征概念), 存在概念_(存在概念), 动态概念_(动态概念),
          动态_(动态), 存在_(存在), 场景_(场景)
    {
    }
    反向因果查询结果 执行(const 反向因果查询请求 &请求);

  private:
    template <class 类型, class 读取器>
    const 类型 &缓存读取(稳定编码 节点, std::map<稳定编码, 类型> &缓存, 读取器 读取,
                         const char *原因)
    {
        const auto 位置 = 缓存.find(节点);
        if (位置 != 缓存.end())
            return 位置->second;
        const auto 内容 = 读取(节点);
        if (!有效(节点) || !内容)
            查询错误(原因);
        return 缓存.emplace(节点, *内容).first->second;
    }
    const 特征概念信息 &读取FC(稳定编码 节点)
    {
        return 缓存读取(
            节点, 特征概念缓存_, [&](稳定编码 编码) { return 特征概念_.获取特征概念(编码); },
            "特征概念不可读");
    }
    const 存在概念信息 &读取EC(稳定编码 节点)
    {
        return 缓存读取(
            节点, 存在概念缓存_, [&](稳定编码 编码) { return 存在概念_.获取存在概念(编码); },
            "存在概念不可读");
    }
    const 动态概念信息 &读取DC(稳定编码 节点)
    {
        const auto &概念 = 缓存读取(
            节点, 动态概念缓存_, [&](稳定编码 编码) { return 动态概念_.获取动态概念(编码); },
            "动态概念不可读");
        for (const auto &状态 : 概念.状态变化组)
        {
            (void)解析类型根(状态.特征类型概念节点);
            (void)解析类型根(状态.前值域概念节点);
            (void)解析类型根(状态.后值域概念节点);
        }
        for (const auto &特征 : 概念.动态特征组)
            (void)解析类型根(特征.结果值域概念节点);
        return 概念;
    }
    const 新动态信息 &读取D(稳定编码 节点)
    {
        return 缓存读取(
            节点, 动态缓存_, [&](稳定编码 编码) { return 动态_.获取动态(编码); }, "动作实例不可读");
    }
    const 新存在信息 &读取E(稳定编码 节点)
    {
        return 缓存读取(
            节点, 存在缓存_, [&](稳定编码 编码) { return 存在_.获取存在(编码); }, "实际存在不可读");
    }
    const 新场景信息 &读取场景(稳定编码 节点)
    {
        return 缓存读取(
            节点, 场景缓存_, [&](稳定编码 编码) { return 场景_.获取场景(编码); }, "场景不可读");
    }
    const 新特征信息 &读取F(稳定编码 节点)
    {
        return 缓存读取(
            节点, 特征缓存_, [&](稳定编码 编码) { return 特征_.获取特征(编码); },
            "动作目标特征不可读");
    }
    稳定编码 解析类型根(稳定编码 概念);
    稳定编码 参与概念(稳定编码 实际存在);
    bool 概念包含(稳定编码 所需, 稳定编码 实际);
    反向因果参与者键 输入键(std::int64_t 标识) const;
    std::optional<稳定编码> 键概念(const 反向因果参与者键 &键);
    反向因果状态条件 规范状态(反向因果状态条件 条件, bool 输入条件);
    新特征值域比较输入 域材料(const 反向因果状态条件 &条件);
    std::optional<bool> 条件包含(const 反向因果状态条件 &所需, const 反向因果状态条件 &实际);
    void 读取规则();
    void 校验请求(const 反向因果查询请求 &请求);
    std::size_t 取得节点(查询节点键 键);
    void 起点覆盖(std::size_t 编号, const 查询规则 *规则 = nullptr);
    void 展开状态(std::size_t 编号);
    void 传播覆盖();
    void 识别环();
    bool 场景属于范围(稳定编码 子场景, 稳定编码 上层);
    bool 检查变化();
    template <class 类型, class 读取器>
    bool 缓存变化(const std::map<稳定编码, 类型> &缓存, 读取器 读取) const
    {
        bool 变化 = false;
        for (const auto &[编号, 原值] : 缓存)
        {
            const auto 新值 = 读取(编号);
            if (!新值)
                查询错误("查询读回身份消失或结构故障");
            if (*新值 != 原值)
                变化 = true;
        }
        return 变化;
    }
    const 新_因果类 &因果_;
    const 新_特征类 &特征_;
    const 概念_特征类 &特征概念_;
    const 概念_存在类 &存在概念_;
    const 概念_动态类 &动态概念_;
    const 新_动态类 &动态_;
    const 新_存在类 &存在_;
    const 新_场景类 &场景_;
    const 反向因果查询请求 *请求_ = nullptr;
    std::map<std::int64_t, 反向因果参与者> 输入参与者_;
    std::map<稳定编码, 新因果信息> 具体缓存_;
    std::map<稳定编码, 新因果共同抽象结果> 概念因果缓存_;
    std::map<稳定编码, 特征概念信息> 特征概念缓存_;
    std::map<稳定编码, 存在概念信息> 存在概念缓存_;
    std::map<稳定编码, 动态概念信息> 动态概念缓存_;
    std::map<稳定编码, 新动态信息> 动态缓存_;
    std::map<稳定编码, 新存在信息> 存在缓存_;
    std::map<稳定编码, 新场景信息> 场景缓存_;
    std::map<稳定编码, 新特征信息> 特征缓存_;
    std::map<稳定编码, 稳定编码> 类型根缓存_;
    std::vector<查询规则> 规则组_;
    std::vector<稳定编码> 具体全集_, 概念全集_;
    std::vector<查询节点键> 节点键组_;
    std::vector<反向因果起点条件> 起点组_;
    反向因果查询结果 结果_;
    bool 有未解释候选_ = false;
};

稳定编码 反向查询工作::解析类型根(稳定编码 概念)
{
    读取FC(概念);
    const auto 已有 = 类型根缓存_.find(概念);
    if (已有 != 类型根缓存_.end())
        return 已有->second;
    const auto 关系 = 特征概念_.比较单特征概念(概念, 概念);
    if (关系.状态 != 特征概念规则状态::已完成 || !关系.特征类型根)
        查询错误("特征根归属不可读");
    读取FC(*关系.特征类型根);
    类型根缓存_.emplace(概念, *关系.特征类型根);
    return *关系.特征类型根;
}
稳定编码 反向查询工作::参与概念(稳定编码 实际存在)
{
    const auto 概念 = 场景_.是场景节点(实际存在) ? 读取场景(实际存在).专属存在概念节点
                                                 : 读取E(实际存在).专属存在概念节点;
    读取EC(概念);
    return 概念;
}
bool 反向查询工作::概念包含(稳定编码 所需, 稳定编码 实际)
{
    const auto &所需概念 = 读取EC(所需);
    const auto &实际概念 = 读取EC(实际);
    for (const auto &条件 : 所需概念.特征组)
    {
        const auto 位置 =
            std::find_if(实际概念.特征组.begin(), 实际概念.特征组.end(),
                         [&](const auto &项) { return 项.特征类型概念 == 条件.特征类型概念; });
        if (位置 == 实际概念.特征组.end())
            return false;
        const auto &左 = 读取FC(条件.具体特征概念);
        const auto &右 = 读取FC(位置->具体特征概念);
        if (左.材料类型 != 右.材料类型 || 左.单位 != 右.单位)
            return false;
        const auto 比较 = 特征概念_.比较值域(左.材料类型, 左.值域, 右.值域);
        if (比较.状态 != 特征概念规则状态::已完成 || !比较.关系)
            查询错误("存在概念完整包含比较故障");
        if (*比较.关系 != 特征概念值域关系::相等 && *比较.关系 != 特征概念值域关系::左包含右)
            return false;
    }
    return true;
}
反向因果参与者键 反向查询工作::输入键(std::int64_t 标识) const
{
    const auto 位置 = 输入参与者_.find(标识);
    if (位置 == 输入参与者_.end())
        查询错误("参与者未声明");
    if (位置->second.实际存在节点)
        return {反向因果参与者键类::实际存在, 0, *位置->second.实际存在节点, {}, 0, 0};
    return {反向因果参与者键类::输入符号, 标识, {}, {}, 0, 0};
}
std::optional<稳定编码> 反向查询工作::键概念(const 反向因果参与者键 &键)
{
    if (键.类别 == 反向因果参与者键类::实际存在)
        return 参与概念(键.实际存在节点);
    if (键.类别 == 反向因果参与者键类::输入符号)
        return 输入参与者_.at(键.输入标识).存在概念节点;
    const auto 规则 = std::find_if(规则组_.begin(), 规则组_.end(), [&](const auto &项) {
        return 项.节点 == 键.规则因果节点 && 项.分支 == 键.规则分支;
    });
    if (规则 == 规则组_.end())
        查询错误("规则局部符号来源缺失");
    const auto 角色 = std::find_if(规则->角色组.begin(), 规则->角色组.end(),
                                   [&](const auto &项) { return 项.角色 == 键.局部角色; });
    if (角色 == 规则->角色组.end())
        查询错误("规则角色不存在");
    return 角色->概念;
}
反向因果状态条件 反向查询工作::规范状态(反向因果状态条件 条件, bool 输入条件)
{
    if (输入条件)
        (void)输入键(条件.参与者标识);
    条件.特征类型概念节点 = 解析类型根(条件.特征类型概念节点);
    if (const auto *概念域 = std::get_if<反向因果概念域约束>(&条件.约束))
    {
        if (解析类型根(概念域->值域概念节点) != 条件.特征类型概念节点)
            查询错误("查询值域不是同一特征类型");
    }
    else if (const auto *直接域 = std::get_if<反向因果直接I64区间约束>(&条件.约束))
    {
        if (直接域->值域.下界 > 直接域->值域.上界 ||
            读取FC(条件.特征类型概念节点).材料类型 != 特征概念材料物理类型::I64标量)
            查询错误("直接I64查询域非法");
    }
    if (std::holds_alternative<反向因果准确约束>(条件.约束))
    {
        const auto 自检 = 特征_.比较特征值域(域材料(条件), 域材料(条件));
        if (自检.状态 != 新特征比较状态::已完成 && 自检.状态 != 新特征比较状态::规则不支持)
            查询错误("准确查询材料无法合法读取");
    }
    return 条件;
}
新特征值域比较输入 反向查询工作::域材料(const 反向因果状态条件 &条件)
{
    新特征值域比较输入 材料;
    材料.特征类型概念节点 = 条件.特征类型概念节点;
    材料.单位 = 读取FC(条件.特征类型概念节点).单位;
    if (const auto *准确 = std::get_if<反向因果准确约束>(&条件.约束))
        材料.材料 = 新特征准确值比较材料{准确->值};
    else if (const auto *概念 = std::get_if<反向因果概念域约束>(&条件.约束))
    {
        读取FC(概念->值域概念节点);
        材料.材料 = 新特征概念值域比较材料{概念->值域概念节点};
    }
    else
        材料.材料 = 新特征直接I64值域比较材料{std::get<反向因果直接I64区间约束>(条件.约束).值域};
    return 材料;
}
std::optional<bool> 反向查询工作::条件包含(const 反向因果状态条件 &所需,
                                           const 反向因果状态条件 &实际)
{
    if (所需.特征类型概念节点 != 实际.特征类型概念节点)
        return false;
    const auto 比较 = 特征_.比较特征值域(域材料(所需), 域材料(实际));
    if (比较.状态 == 新特征比较状态::规则不支持)
        return {};
    if (比较.状态 == 新特征比较状态::概念不相容 || 比较.状态 == 新特征比较状态::单位不相容 ||
        比较.状态 == 新特征比较状态::材料类型不相容)
        return false;
    if (比较.状态 != 新特征比较状态::已完成 || !比较.关系编码)
        查询错误("特征查询比较工程故障");
    return *比较.关系编码 == static_cast<std::int64_t>(特征概念值域关系::相等) ||
           *比较.关系编码 == static_cast<std::int64_t>(特征概念值域关系::左包含右);
}

void 反向查询工作::读取规则()
{
    具体全集_ = 因果_.查询具体因果();
    概念全集_ = 因果_.查询概念因果();
    for (const auto 编号 : 具体全集_)
    {
        const auto 内容 = 因果_.获取因果(编号);
        if (!内容 || 内容->节点 != 编号 || !具体缓存_.emplace(编号, *内容).second)
            查询错误("具体因果全集读回不完整");
        查询规则 规则;
        规则.节点 = 编号;
        规则.实际场景 = 内容->发生场景节点;
        std::vector<稳定编码> 参与者组;
        const auto 分配角色 = [&](稳定编码 存在) {
            auto 位置 = std::find(参与者组.begin(), 参与者组.end(), 存在);
            if (位置 == 参与者组.end())
            {
                参与者组.push_back(存在);
                const auto 角色 = static_cast<std::int64_t>(参与者组.size());
                规则.角色组.push_back({角色, 参与概念(存在), 存在});
                return 角色;
            }
            return static_cast<std::int64_t>(位置 - 参与者组.begin() + 1);
        };
        const auto 状态 = [&](const 新因果状态模式 &项) {
            return 查询规则状态{
                分配角色(项.被描述存在节点),
                规范状态({0, 项.特征类型概念节点, 反向因果准确约束{项.准确值}}, false)};
        };
        规则.结果 = 状态(内容->定义.结果状态);
        if (内容->定义.动作)
        {
            const auto &动作 = *内容->定义.动作;
            const auto &概念 = 读取DC(动作.动作概念节点);
            if (概念.定义类别 != 动态概念定义类别::动作 || !概念.动作定义)
                查询错误("具体因果动作不是正式动作概念");
            新因果概念动作项 动作项{动作.动作概念节点, 分配角色(动作.执行主体存在节点), {}, {}};
            if (动作.作用部位存在节点)
                动作项.作用部位角色 = 分配角色(*动作.作用部位存在节点);
            if (动作.作用对象存在节点)
                动作项.作用对象角色 = 分配角色(*动作.作用对象存在节点);
            规则.动作 = 动作项;
        }
        for (const auto &项 : 内容->定义.条件状态组)
            规则.状态组.push_back(状态(项));
        for (const auto &项 : 内容->定义.条件动态组)
        {
            读取DC(项.动态概念节点);
            规则.动态组.push_back({分配角色(项.主题存在节点), 项.动态概念节点});
        }
        if (规则.实际场景)
            读取场景(*规则.实际场景);
        规则组_.push_back(std::move(规则));
    }
    for (const auto 编号 : 概念全集_)
    {
        const auto 内容 = 因果_.获取概念因果(编号);
        if (!概念因果缓存_.emplace(编号, 内容).second)
            查询错误("概念因果全集重复身份");
        if (内容.状态 == 新因果共同抽象状态::概念已不相容)
        {
            结果_.已不相容概念因果组.push_back(编号);
            continue;
        }
        if (内容.状态 != 新因果共同抽象状态::已读取 || !内容.信息)
            查询错误("概念因果全集不完整");
        const auto &定义 = 内容.信息->定义;
        读取EC(定义.场景概念节点);
        for (std::size_t 序号 = 0; 序号 < 定义.分支组.size(); ++序号)
        {
            const auto &分支 = 定义.分支组[序号];
            查询规则 规则;
            规则.节点 = 编号;
            规则.分支 = static_cast<std::int64_t>(序号 + 1);
            规则.概念规则 = true;
            规则.场景概念 = 定义.场景概念节点;
            规则.动作 = 定义.动作;
            const auto 来源 = 具体缓存_.find(分支.来源具体因果节点);
            if (来源 == 具体缓存_.end())
                查询错误("概念分支来源不在完整具体全集");
            规则.实际场景 = 来源->second.发生场景节点;
            if (规则.实际场景)
                读取场景(*规则.实际场景);
            for (const auto &角色 : 定义.角色组)
            {
                读取EC(角色.存在概念节点);
                规则.角色组.push_back({角色.角色, 角色.存在概念节点, {}});
            }
            const auto 状态 = [&](const 新因果概念状态项 &项) {
                return 查询规则状态{
                    项.角色,
                    规范状态({0, 项.特征类型概念节点, 反向因果概念域约束{项.值域概念节点}}, false)};
            };
            规则.结果 = 状态(分支.结果状态);
            for (const auto &项 : 分支.条件状态组)
                规则.状态组.push_back(状态(项));
            for (const auto &项 : 分支.条件动态组)
            {
                读取DC(项.动态概念节点);
                规则.动态组.push_back({项.角色, 项.动态概念节点});
            }
            if (规则.动作)
            {
                const auto &动作 = 读取DC(规则.动作->动作概念节点);
                if (动作.定义类别 != 动态概念定义类别::动作 || !动作.动作定义)
                    查询错误("概念规则动作类别错误");
            }
            规则组_.push_back(std::move(规则));
        }
    }
}

void 反向查询工作::校验请求(const 反向因果查询请求 &请求)
{
    请求_ = &请求;
    for (const auto &参与者 : 请求.参与者组)
    {
        if (参与者.标识 <= 0 || (!参与者.实际存在节点 && !参与者.存在概念节点) ||
            !输入参与者_.emplace(参与者.标识, 参与者).second)
            查询错误("查询参与者身份不合法");
        if (参与者.存在概念节点)
            读取EC(*参与者.存在概念节点);
        if (参与者.实际存在节点)
        {
            const auto 实际 = 参与概念(*参与者.实际存在节点);
            if (参与者.存在概念节点 && !概念包含(*参与者.存在概念节点, 实际))
                查询错误("实际参与者不符合声明概念");
        }
    }
    if (请求.共同场景节点)
        读取场景(*请求.共同场景节点);
    (void)规范状态(请求.目标结果, true);
    std::map<std::tuple<稳定编码, std::int64_t, std::int64_t>, 反向因果参与者键> 绑定集合;
    for (const auto &绑定 : 请求.角色绑定组)
    {
        const auto 键 = 输入键(绑定.参与者标识);
        const auto 规则 = std::find_if(规则组_.begin(), 规则组_.end(), [&](const auto &项) {
            return 项.概念规则 && 项.节点 == 绑定.因果节点 && 项.分支 == 绑定.分支序号;
        });
        if (规则 == 规则组_.end())
            查询错误("显式绑定没有合法概念分支");
        if (std::none_of(规则->角色组.begin(), 规则->角色组.end(),
                         [&](const auto &项) { return 项.角色 == 绑定.局部角色; }))
            查询错误("显式绑定角色不存在");
        const auto [位置, 已增加] =
            绑定集合.emplace(std::make_tuple(绑定.因果节点, 绑定.分支序号, 绑定.局部角色), 键);
        if (!已增加 && 位置->second != 键)
            查询错误("同一局部角色绑定冲突");
    }
    if (请求.起点条件组)
    {
        for (const auto &条件 : *请求.起点条件组)
        {
            if (const auto *状态 = std::get_if<反向因果状态条件>(&条件))
                起点组_.push_back(规范状态(*状态, true));
            else if (const auto *动态 = std::get_if<反向因果动态条件>(&条件))
            {
                (void)输入键(动态->参与者标识);
                读取DC(动态->动态概念节点);
                起点组_.push_back(*动态);
            }
            else
            {
                const auto &动作 = std::get<反向因果动作条件>(条件);
                const auto &实例 = 读取D(动作.动作动态节点);
                if (实例.种类 != 新动态种类::动作 || !实例.动态概念节点)
                    查询错误("起点不是实际动作实例");
                const auto &概念 = 读取DC(*实例.动态概念节点);
                if (概念.定义类别 != 动态概念定义类别::动作 || !概念.动作定义)
                    查询错误("起点动作缺正式概念");
                参与概念(实例.主题存在节点);
                if (实例.动作目标种类 == 新动作目标种类::普通存在)
                {
                    if (!实例.动作目标存在节点)
                        查询错误("起点普通动作目标缺失");
                    参与概念(*实例.动作目标存在节点);
                    if (实例.动作目标特征节点)
                        (void)读取F(*实例.动作目标特征节点);
                }
                起点组_.push_back(动作);
            }
        }
    }
}

bool 反向查询工作::场景属于范围(稳定编码 子场景, 稳定编码 上层)
{
    std::set<稳定编码> 已经过;
    auto 当前 = 子场景;
    for (;;)
    {
        if (!已经过.insert(当前).second)
            查询错误("场景关系存在环");
        const auto &内容 = 读取场景(当前);
        if (当前 == 上层)
            return true;
        if (!内容.父场景节点)
            return false;
        当前 = *内容.父场景节点;
    }
}
std::size_t 反向查询工作::取得节点(查询节点键 键)
{
    // 覆盖等可变结果不参与memo；所有条件、场景和完整角色上下文参与。
    键.内容.编号 = 0;
    键.内容.起点已覆盖 = false;
    键.内容.完整覆盖 = false;
    for (std::size_t 序号 = 0; 序号 < 节点键组_.size(); ++序号)
        if (节点键组_[序号] == 键)
            return 序号 + 1;
    const auto 编号 = 节点键组_.size() + 1;
    节点键组_.push_back(std::move(键));
    auto 输出 = 节点键组_.back().内容;
    输出.编号 = 编号;
    结果_.节点组.push_back(std::move(输出));
    return 编号;
}

void 反向查询工作::起点覆盖(std::size_t 编号, const 查询规则 *规则)
{
    const auto 键 = 节点键组_.at(编号 - 1);
    bool 覆盖 = false;
    if (键.内容.类型 == 反向因果端类型::参与者绑定)
        return;
    if (键.内容.未解释原因 == 反向因果未解释原因::未绑定递归角色边界)
        return;
    if (键.内容.类型 == 反向因果端类型::场景)
    {
        覆盖 = 请求_->共同场景节点 && 键.内容.场景节点 &&
               场景属于范围(*键.内容.场景节点, *请求_->共同场景节点);
    }
    else if (键.内容.类型 == 反向因果端类型::动作)
    {
        if (!规则 || !规则->动作)
            查询错误("动作依赖没有规则上下文");
        const auto &定义 = 读取DC(规则->动作->动作概念节点);
        if (!定义.动作定义)
            查询错误("动作能力定义不完整");
        if (!定义.动作定义->参数规格组.empty())
        {
            结果_.节点组[编号 - 1].未解释原因 = 反向因果未解释原因::动作参数未确认;
            return;
        }
        // 现有D不含独立作用部位及全部角色实参；不可用当前值补证。
        if (规则->动作->作用部位角色)
            return;
        const auto 实际角色 = [&](std::int64_t 角色) -> std::optional<稳定编码> {
            const auto 位置 = std::find_if(键.角色上下文.begin(), 键.角色上下文.end(),
                                           [&](const auto &项) { return 项.局部角色 == 角色; });
            if (位置 == 键.角色上下文.end() || 位置->参与者.类别 != 反向因果参与者键类::实际存在)
                return {};
            return 位置->参与者.实际存在节点;
        };
        for (const auto &角色 : 键.角色上下文)
            if (角色.参与者.类别 != 反向因果参与者键类::实际存在)
                return;
        const auto 主体 = 实际角色(规则->动作->执行主体角色);
        const auto 对象 =
            规则->动作->作用对象角色 ? 实际角色(*规则->动作->作用对象角色) : std::nullopt;
        if (!主体 || (规则->动作->作用对象角色 && !对象))
            return;
        for (const auto &起点 : 起点组_)
        {
            const auto *动作 = std::get_if<反向因果动作条件>(&起点);
            if (!动作)
                continue;
            const auto &实例 = 读取D(动作->动作动态节点);
            if (实例.动态概念节点 == 规则->动作->动作概念节点 && 实例.主题存在节点 == *主体 &&
                (!规则->动作->作用对象角色 ||
                 (实例.动作目标种类 == 新动作目标种类::普通存在 && 实例.动作目标存在节点 == 对象)))
            {
                覆盖 = true;
                break;
            }
        }
    }
    else
    {
        for (const auto &起点 : 起点组_)
        {
            if (键.内容.类型 == 反向因果端类型::状态)
            {
                const auto *状态 = std::get_if<反向因果状态条件>(&起点);
                if (!状态 || !键.内容.参与者 || 输入键(状态->参与者标识) != *键.内容.参与者)
                    continue;
                const auto 包含 = 条件包含(*键.内容.状态, *状态);
                if (!包含)
                {
                    结果_.节点组[编号 - 1].未解释原因 = 反向因果未解释原因::比较材料尚不支持;
                    continue;
                }
                if (*包含)
                {
                    覆盖 = true;
                    break;
                }
            }
            else
            {
                const auto *动态 = std::get_if<反向因果动态条件>(&起点);
                if (!动态 || !键.内容.参与者 || 输入键(动态->参与者标识) != *键.内容.参与者)
                    continue;
                const auto &所需 = 读取DC(*键.内容.动态概念节点);
                const auto &实际 = 读取DC(动态->动态概念节点);
                if (所需.定义类别 != 实际.定义类别)
                    continue;
                const auto 包含 = 动态概念_.判断动态概念包含(所需.节点, 实际.节点);
                if (包含.状态 != 动态概念操作状态::已判断 || !包含.包含)
                    查询错误("动态包含比较工程故障");
                if (*包含.包含)
                {
                    覆盖 = true;
                    break;
                }
            }
        }
    }
    if (覆盖)
    {
        结果_.节点组[编号 - 1].起点已覆盖 = true;
        结果_.节点组[编号 - 1].完整覆盖 = true;
        结果_.节点组[编号 - 1].未解释原因.reset();
    }
}

void 反向查询工作::展开状态(std::size_t 编号)
{
    const auto 当前 = 节点键组_.at(编号 - 1);
    if (当前.内容.类型 != 反向因果端类型::状态 || 结果_.节点组[编号 - 1].起点已覆盖 ||
        当前.内容.未解释原因 == 反向因果未解释原因::未绑定递归角色边界)
        return;
    if (!当前.内容.状态 || !当前.内容.参与者)
        查询错误("状态查询节点不完整");
    bool 有候选 = false;
    for (const auto &规则 : 规则组_)
    {
        if (规则.结果.条件.特征类型概念节点 != 当前.内容.状态->特征类型概念节点)
            continue;
        const auto 结果角色 =
            std::find_if(规则.角色组.begin(), 规则.角色组.end(),
                         [&](const auto &项) { return 项.角色 == 规则.结果.角色; });
        if (结果角色 == 规则.角色组.end())
            查询错误("规则结果角色缺失");
        const auto 当前概念 = 当前.参与者概念 ? 当前.参与者概念 : 键概念(*当前.内容.参与者);
        if (!当前概念)
            continue;
        const bool 结果角色相容 =
            (!规则.概念规则 && 当前.内容.参与者->类别 != 反向因果参与者键类::实际存在)
                ? 概念包含(*当前概念, 结果角色->概念)
                : 概念包含(结果角色->概念, *当前概念);
        if (!结果角色相容)
            continue;
        if (!规则.概念规则 && 当前.内容.参与者->类别 == 反向因果参与者键类::实际存在 &&
            结果角色->实际存在 != 当前.内容.参与者->实际存在节点)
            continue;
        const auto 支持 = 条件包含(*当前.内容.状态, 规则.结果.条件);
        if (!支持)
        {
            有未解释候选_ = true;
            结果_.节点组[编号 - 1].未解释原因 = 反向因果未解释原因::比较材料尚不支持;
            continue;
        }
        if (!*支持)
            continue;
        std::optional<稳定编码> 语境 = 当前.场景语境;
        if (请求_->共同场景节点)
        {
            if (规则.实际场景 && !场景属于范围(*规则.实际场景, *请求_->共同场景节点))
                continue;
            if (规则.场景概念 &&
                !概念包含(*规则.场景概念,
                          读取场景(规则.实际场景.value_or(*请求_->共同场景节点)).专属存在概念节点))
                continue;
            语境 = 请求_->共同场景节点;
        }
        else
        {
            if (语境 && 规则.实际场景 && 语境 != 规则.实际场景)
                continue;
            if (!语境 && 规则.实际场景)
                语境 = 规则.实际场景;
        }
        std::vector<反向因果图角色绑定> 映射;
        bool 相容 = true;
        std::vector<std::int64_t> 碰撞角色组;
        for (const auto &角色 : 规则.角色组)
        {
            反向因果参与者键 键;
            if (角色.实际存在)
                键 = {反向因果参与者键类::实际存在, 0, *角色.实际存在, {}, 0, 0};
            else if (角色.角色 == 规则.结果.角色)
                键 = *当前.内容.参与者;
            else
                键 = {反向因果参与者键类::规则局部符号, 0, {}, 规则.节点, 规则.分支, 角色.角色};
            for (const auto &显式 : 请求_->角色绑定组)
                if (显式.因果节点 == 规则.节点 && 显式.分支序号 == 规则.分支 &&
                    显式.局部角色 == 角色.角色)
                {
                    const auto 已绑定 = 输入键(显式.参与者标识);
                    if (角色.角色 == 规则.结果.角色 && 已绑定 != 键)
                        相容 = false;
                    键 = 已绑定;
                }
            const auto 概念 = 键概念(键);
            if (!概念)
                相容 = false;
            else if (!概念包含(角色.概念, *概念))
                相容 = false;
            for (const auto &已有 : 映射)
                if (已有.参与者 == 键)
                {
                    if (键.类别 == 反向因果参与者键类::规则局部符号)
                        碰撞角色组.push_back(角色.角色);
                    else
                        相容 = false;
                }
            映射.push_back({角色.角色, 键});
        }
        if (!相容)
            continue;
        // 新局部符号与结果继承的符号碰撞时，不合槽、不冒充真实环。
        for (std::size_t 左 = 0; 左 < 映射.size(); ++左)
            for (std::size_t 右 = 左 + 1; 右 < 映射.size(); ++右)
                if (映射[左].参与者 == 映射[右].参与者 &&
                    映射[左].参与者.类别 == 反向因果参与者键类::规则局部符号)
                {
                    碰撞角色组.push_back(映射[左].局部角色);
                    碰撞角色组.push_back(映射[右].局部角色);
                }
        std::sort(碰撞角色组.begin(), 碰撞角色组.end());
        碰撞角色组.erase(std::unique(碰撞角色组.begin(), 碰撞角色组.end()), 碰撞角色组.end());
        反向因果图分支 分支;
        分支.结果节点 = 编号;
        分支.因果节点 = 规则.节点;
        分支.来源分支 = 规则.分支;
        分支.概念因果 = 规则.概念规则;
        分支.角色映射 = 映射;
        const auto 寻角色 = [&](std::int64_t 角色) -> 反向因果参与者键 {
            const auto 位置 = std::find_if(映射.begin(), 映射.end(),
                                           [&](const auto &项) { return 项.局部角色 == 角色; });
            if (位置 == 映射.end())
                查询错误("前提局部角色未映射");
            return 位置->参与者;
        };
        const auto 添加前提 = [&](查询节点键 键, std::optional<std::int64_t> 角色) {
            键.场景语境 = 语境;
            键.来源规则 = 规则.节点;
            键.来源分支 = 规则.分支;
            键.角色上下文 = 映射;
            if (角色 && std::binary_search(碰撞角色组.begin(), 碰撞角色组.end(), *角色))
                键.内容.未解释原因 = 反向因果未解释原因::未绑定递归角色边界;
            const auto 节点 = 取得节点(std::move(键));
            分支.全部前提节点.push_back(节点);
            if (角色 && std::binary_search(碰撞角色组.begin(), 碰撞角色组.end(), *角色))
            {
                反向因果未绑定角色边界 边界{节点, 规则.节点, 规则.分支, *角色, 映射};
                if (std::find(结果_.未绑定递归角色边界组.begin(), 结果_.未绑定递归角色边界组.end(),
                              边界) == 结果_.未绑定递归角色边界组.end())
                    结果_.未绑定递归角色边界组.push_back(std::move(边界));
            }
            else
                起点覆盖(节点, &规则);
        };
        for (const auto &条件 : 规则.状态组)
        {
            查询节点键 键;
            键.内容.类型 = 反向因果端类型::状态;
            键.内容.参与者 = 寻角色(条件.角色);
            键.内容.状态 = 条件.条件;
            if (键.内容.参与者->类别 == 反向因果参与者键类::输入符号)
                键.内容.状态->参与者标识 = 键.内容.参与者->输入标识;
            键.参与者概念 = 键概念(*键.内容.参与者);
            键.内容.角色尚未实际绑定 = 键.内容.参与者->类别 != 反向因果参与者键类::实际存在;
            添加前提(std::move(键), 条件.角色);
        }
        for (const auto &条件 : 规则.动态组)
        {
            查询节点键 键;
            键.内容.类型 = 反向因果端类型::动态;
            键.内容.参与者 = 寻角色(条件.角色);
            键.内容.动态概念节点 = 条件.概念;
            键.参与者概念 = 键概念(*键.内容.参与者);
            键.内容.角色尚未实际绑定 = 键.内容.参与者->类别 != 反向因果参与者键类::实际存在;
            添加前提(std::move(键), 条件.角色);
        }
        if (规则.动作)
        {
            查询节点键 键;
            键.内容.类型 = 反向因果端类型::动作;
            键.内容.动作概念节点 = 规则.动作->动作概念节点;
            键.内容.参与者 = 寻角色(规则.动作->执行主体角色);
            键.内容.角色尚未实际绑定 = std::any_of(映射.begin(), 映射.end(), [](const auto &项) {
                return 项.参与者.类别 != 反向因果参与者键类::实际存在;
            });
            添加前提(std::move(键), {});
        }
        查询节点键 场景键;
        场景键.内容.类型 = 反向因果端类型::场景;
        场景键.内容.场景节点 = 规则.实际场景;
        场景键.内容.角色尚未实际绑定 = !请求_->共同场景节点 || !规则.实际场景;
        添加前提(std::move(场景键), {});
        if (!规则.概念规则 && 当前.内容.参与者->类别 != 反向因果参与者键类::实际存在)
        {
            if (!结果角色->实际存在)
                查询错误("具体规律结果缺少真实存在身份");
            查询节点键 绑定键;
            绑定键.内容.类型 = 反向因果端类型::参与者绑定;
            绑定键.内容.参与者 = 当前.内容.参与者;
            绑定键.内容.待绑定实际存在节点 = 结果角色->实际存在;
            绑定键.内容.角色尚未实际绑定 = true;
            绑定键.内容.未解释原因 = 反向因果未解释原因::具体实体待绑定;
            添加前提(std::move(绑定键), {});
        }
        std::sort(分支.全部前提节点.begin(), 分支.全部前提节点.end());
        分支.全部前提节点.erase(std::unique(分支.全部前提节点.begin(), 分支.全部前提节点.end()),
                                分支.全部前提节点.end());
        const auto 既有 =
            std::find_if(结果_.分支组.begin(), 结果_.分支组.end(), [&](const auto &项) {
                auto 比较 = 分支;
                比较.编号 = 项.编号;
                比较.完整覆盖 = 项.完整覆盖;
                return 项 == 比较;
            });
        if (既有 == 结果_.分支组.end())
        {
            分支.编号 = 结果_.分支组.size() + 1;
            结果_.分支组.push_back(std::move(分支));
        }
        有候选 = true;
    }
    if (!有候选 && !结果_.节点组[编号 - 1].未解释原因)
        结果_.节点组[编号 - 1].未解释原因 = 反向因果未解释原因::无更前规则;
}

void 反向查询工作::传播覆盖()
{
    bool 有变化 = true;
    while (有变化)
    {
        有变化 = false;
        for (auto &分支 : 结果_.分支组)
        {
            if (分支.完整覆盖)
                continue;
            const bool 前提完整 =
                std::all_of(分支.全部前提节点.begin(), 分支.全部前提节点.end(),
                            [&](std::size_t 节点) { return 结果_.节点组.at(节点 - 1).完整覆盖; });
            if (前提完整)
            {
                分支.完整覆盖 = true;
                auto &结果 = 结果_.节点组.at(分支.结果节点 - 1);
                if (!结果.完整覆盖)
                {
                    结果.完整覆盖 = true;
                    有变化 = true;
                }
            }
        }
    }
}
void 反向查询工作::识别环()
{
    std::vector<std::vector<std::size_t>> 邻接(结果_.节点组.size());
    for (const auto &分支 : 结果_.分支组)
        for (const auto 前提 : 分支.全部前提节点)
            邻接.at(分支.结果节点 - 1).push_back(前提);
    for (auto &组 : 邻接)
    {
        std::sort(组.begin(), 组.end());
        组.erase(std::unique(组.begin(), 组.end()), 组.end());
    }
    std::vector<std::uint8_t> 颜色(结果_.节点组.size(), 0);
    struct 栈项
    {
        std::size_t 节点 = 0, 下一个 = 0;
    };
    for (std::size_t 起点 = 1; 起点 <= 结果_.节点组.size(); ++起点)
    {
        if (颜色[起点 - 1])
            continue;
        std::vector<栈项> 栈{{起点, 0}};
        颜色[起点 - 1] = 1;
        while (!栈.empty())
        {
            auto &当前 = 栈.back();
            if (当前.下一个 == 邻接[当前.节点 - 1].size())
            {
                颜色[当前.节点 - 1] = 2;
                栈.pop_back();
                continue;
            }
            const auto 子节点 = 邻接[当前.节点 - 1][当前.下一个++];
            if (颜色[子节点 - 1] == 0)
            {
                颜色[子节点 - 1] = 1;
                栈.push_back({子节点, 0});
            }
            else if (颜色[子节点 - 1] == 1)
            {
                const 反向因果环边 环边{子节点, 当前.节点};
                if (std::find(结果_.环边组.begin(), 结果_.环边组.end(), 环边) == 结果_.环边组.end())
                    结果_.环边组.push_back(环边);
            }
        }
    }
}
bool 反向查询工作::检查变化()
{
    bool 变化 = false;
    // 不短路，全部已读取材料均重新核验；任何读回工程失败都必须终止。
    变化 |= 缓存变化(具体缓存_, [&](稳定编码 编码) { return 因果_.获取因果(编码); });
    for (const auto &[编号, 原值] : 概念因果缓存_)
    {
        const auto 新值 = 因果_.获取概念因果(编号);
        if (新值.状态 != 新因果共同抽象状态::已读取 &&
            新值.状态 != 新因果共同抽象状态::概念已不相容)
            查询错误("概念因果读回工程故障");
        if (新值 != 原值)
            变化 = true;
    }
    变化 |= 缓存变化(特征概念缓存_, [&](稳定编码 编码) { return 特征概念_.获取特征概念(编码); });
    变化 |= 缓存变化(存在概念缓存_, [&](稳定编码 编码) { return 存在概念_.获取存在概念(编码); });
    变化 |= 缓存变化(动态概念缓存_, [&](稳定编码 编码) { return 动态概念_.获取动态概念(编码); });
    变化 |= 缓存变化(动态缓存_, [&](稳定编码 编码) { return 动态_.获取动态(编码); });
    变化 |= 缓存变化(存在缓存_, [&](稳定编码 编码) { return 存在_.获取存在(编码); });
    变化 |= 缓存变化(场景缓存_, [&](稳定编码 编码) { return 场景_.获取场景(编码); });
    变化 |= 缓存变化(特征缓存_, [&](稳定编码 编码) { return 特征_.获取特征(编码); });
    for (const auto &[概念, 原根] : 类型根缓存_)
    {
        const auto 关系 = 特征概念_.比较单特征概念(概念, 概念);
        if (关系.状态 != 特征概念规则状态::已完成 || !关系.特征类型根)
            查询错误("特征归属读回工程故障");
        if (*关系.特征类型根 != 原根)
            变化 = true;
    }
    if (因果_.查询具体因果() != 具体全集_)
        变化 = true;
    if (因果_.查询概念因果() != 概念全集_)
        变化 = true;
    return 变化;
}
反向因果查询结果 反向查询工作::执行(const 反向因果查询请求 &请求)
{
    读取规则();
    校验请求(请求);
    查询节点键 目标;
    目标.内容.类型 = 反向因果端类型::状态;
    目标.内容.参与者 = 输入键(请求.目标结果.参与者标识);
    目标.内容.状态 = 规范状态(请求.目标结果, true);
    目标.参与者概念 = 键概念(*目标.内容.参与者);
    目标.场景语境 = 请求.共同场景节点;
    目标.内容.角色尚未实际绑定 = 目标.内容.参与者->类别 != 反向因果参与者键类::实际存在;
    结果_.目标节点 = 取得节点(std::move(目标));
    起点覆盖(结果_.目标节点);
    // vector可在循环中增加节点，编号工作队列逐项展开，每个memo节点最多一次。
    for (std::size_t 编号 = 1; 编号 <= 节点键组_.size(); ++编号)
        展开状态(编号);
    传播覆盖();
    识别环();
    for (const auto &节点 : 结果_.节点组)
    {
        const bool 有前驱 =
            std::any_of(结果_.分支组.begin(), 结果_.分支组.end(),
                        [&](const auto &分支) { return 分支.结果节点 == 节点.编号; });
        const bool 未解决环 =
            std::any_of(结果_.环边组.begin(), 结果_.环边组.end(), [&](const auto &边) {
                return 边.返回节点 == 节点.编号 || 边.前提节点 == 节点.编号;
            });
        if (节点.起点已覆盖 || !有前驱 || (!节点.完整覆盖 && 未解决环))
            结果_.已知最前端节点组.push_back(节点.编号);
        if (!节点.完整覆盖)
            结果_.未覆盖节点组.push_back(节点.编号);
    }
    const bool 有规则 = !结果_.分支组.empty() || 有未解释候选_;
    if (!请求.起点条件组)
        结果_.覆盖 = 有规则 ? 反向因果覆盖::未指定起点 : 反向因果覆盖::无已知路径;
    else if (结果_.节点组.at(结果_.目标节点 - 1).完整覆盖)
        结果_.覆盖 = 反向因果覆盖::完整;
    else
        结果_.覆盖 = 有规则 ? 反向因果覆盖::部分 : 反向因果覆盖::无已知路径;
    if (检查变化())
    {
        反向因果查询结果 变化结果;
        变化结果.材料已变化 = true;
        return 变化结果;
    }
    return std::move(结果_);
}
