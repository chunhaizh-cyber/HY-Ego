std::optional<动作概念定义>
内部治理先天因果初始化服务::读取关系治理动作定义(稳定编码 治理定义) const {
    // 此入口会在动态锁内调用，不能回调任何领域owner。
    const auto 目录 = 动作目录_.load(std::memory_order_acquire);
    if (!目录) return std::nullopt;
    const auto 项 = std::find_if(目录->begin(),目录->end(),[&](const auto& 定义){
        return 定义.能力定义节点==治理定义;
    });
    return 项==目录->end() ? std::nullopt : std::optional{*项};
}

std::vector<动作概念定义> 内部治理先天因果初始化服务::构造动作目录(
    const 新关系先天元数据& 元数据) const {
    const auto& 材料=元数据.材料;
    动作概念定义 投影;
    投影.能力定义节点=查唯一概念(元数据.治理定义组,新关系先天治理操作::同步正式服务任务投影);
    投影.能力类别=动作能力定义类别::内部治理能力;
    投影.执行主体.存在概念节点=材料.自我概念;
    投影.作用目标.存在概念节点=材料.自我概念;
    投影.目标特征类型概念节点=材料.服务任务特征类型;
    动作概念定义 完成;
    完成.能力定义节点=查唯一概念(元数据.治理定义组,新关系先天治理操作::发布自我任务完成决议);
    完成.能力类别=动作能力定义类别::内部治理能力;
    完成.执行主体.存在概念节点=材料.自我概念;
    完成.作用目标={std::nullopt,材料.任务概念,动作参数对象类别::任务虚拟存在};
    完成.目标特征类型概念节点=材料.任务状态特征类型;
    动作参数规格 规格;
    规格.参数角色节点=材料.任务概念;
    规格.对象类别=动作参数对象类别::任务虚拟存在;
    规格.特征规格组.push_back({材料.任务状态特征类型,std::nullopt,{}});
    完成.参数规格组.push_back(std::move(规格));
    return {投影,完成};
}

std::vector<新关系先天因果定义> 内部治理先天因果初始化服务::构造规则(
    const 新关系先天元数据& 元数据,const std::vector<稳定编码>& 动作概念组) const {
    if (元数据.规则概念组.size()!=4 || 动作概念组.size()!=2)
        throw std::logic_error("关系先天初始化：规则或动作数量错误");
    const auto& 材料=元数据.材料;
    using 条件种类=新关系先天条件种类;
    using 角色类别=新关系先天角色类别;
    std::vector<新关系先天因果定义> 规则组;
    for (std::size_t 槽=0;槽<4;++槽) {
        const bool 投影=槽<2;
        新关系先天因果定义 规则;
        规则.规则概念=元数据.规则概念组[槽];
        规则.治理定义=查唯一概念(元数据.治理定义组,投影
            ? 新关系先天治理操作::同步正式服务任务投影:新关系先天治理操作::发布自我任务完成决议);
        规则.作用场景范围概念 = 投影 ? 材料.服务任务投影场景范围概念 : 材料.任务治理场景范围概念;
        规则.动作概念 = 动作概念组[投影 ? 0 : 1];
        规则.触发方式=新因果动作触发方式::被动触发;
        const auto 添加角色=[&](角色类别 类别){
            规则.角色组.push_back({static_cast<std::int64_t>(规则.角色组.size()),类别,
                查唯一概念(元数据.角色范围组,类别)});
        };
        const auto 添加条件=[&](条件种类 种类,std::vector<std::int64_t> 角色,
            std::vector<稳定编码> 参数){
            规则.全部条件.push_back({static_cast<std::int64_t>(规则.全部条件.size()),种类,
                查唯一概念(元数据.关系概念组,种类),std::move(角色),std::move(参数)});
        };
        添加角色(角色类别::普通存在);
        if (投影) {
            添加角色(角色类别::需求信息);添加角色(角色类别::需求信息);
        } else {
            添加角色(角色类别::任务信息);添加角色(角色类别::需求信息);
            添加角色(角色类别::执行实例);添加角色(角色类别::影响评估);
        }
        for (const auto& 角色:规则.角色组)
            添加条件(条件种类::角色有效,{角色.序号},{角色.范围概念});
        if (投影) {
            添加条件(条件种类::自我服务投影绑定,{0,1,2},{材料.服务任务特征类型});
            添加条件(条件种类::需求父链归根,{1},{材料.需求概念});
            添加条件(条件种类::排除需求有父,{2,1},{});
            添加条件(条件种类::投影源对应完整,{0,1,2},{材料.服务任务特征类型});
            if (槽==0) 添加条件(条件种类::投影待写入,{0,1,2},{材料.服务任务特征类型});
            else {
                添加条件(条件种类::当前引用集合合法,{0},{材料.服务任务特征类型});
                添加条件(条件种类::当前集合等于投影,{0,1,2},{材料.服务任务特征类型});
            }
            规则.唯一结果={新关系先天结果种类::正式服务任务投影,槽==0
                ?新关系先天结果变化::改变:新关系先天结果变化::保持,0,
                材料.服务任务特征类型,材料.服务任务特征类型,{1,2},元数据.投影结果关系};
        } else {
            const auto 执行范围=查唯一概念(元数据.角色范围组,角色类别::执行实例);
            const auto 评估范围=查唯一概念(元数据.角色范围组,角色类别::影响评估);
            添加条件(条件种类::任务关联需求,{1,2},{材料.需求概念});
            添加条件(条件种类::需求准备非待完善,{1,2},{材料.需求概念});
            添加条件(条件种类::任务最近执行,{1,3},{执行范围});
            添加条件(条件种类::执行关联任务,{3,1},{材料.任务概念});
            添加条件(条件种类::执行关联评估,{3,4},{评估范围});
            添加条件(条件种类::评估关联任务,{4,1},{材料.任务概念});
            添加条件(条件种类::评估关联执行,{4,3},{执行范围});
            // 七个有序子约束属于正式关系概念定义，参数不是额外伪FT。
            添加条件(条件种类::评估允许完成,{4},{});
            添加条件(条件种类::自我接受完成决议,{0,1,3,4},{元数据.完成决议范围});
            添加条件(条件种类::任务状态属于,{1},{材料.任务状态特征类型,
                槽==2?材料.等待自我决议值域:材料.已完成值域});
            if (槽==2) 添加条件(条件种类::执行状态属于,{3},{元数据.执行已评估范围});
            规则.唯一结果={新关系先天结果种类::特征值域,槽==2
                ?新关系先天结果变化::改变:新关系先天结果变化::保持,1,
                材料.任务状态特征类型,材料.已完成值域,{1,3,4},元数据.状态结果关系};
        }
        规则组.push_back(std::move(规则));
    }
    return 规则组;
}

void 内部治理先天因果初始化服务::核验初始化读回(
    const 内部治理先天初始化回执& 回执) const {
    const auto 目录=动作目录_.load(std::memory_order_acquire);
    if (!目录) throw std::logic_error("关系先天初始化：动作目录未发布");
    核验动作子目录(*目录,构造动作目录(回执.元数据));
    const auto 预期=构造规则(回执.元数据,回执.动作概念组);
    if (回执.规则组.size()!=预期.size()) throw std::logic_error("关系先天初始化：回执不完整");
    for (std::size_t 位置=0;位置<预期.size();++位置) {
        const auto 读回=因果_.读取关系先天因果(回执.规则组[位置].节点);
        if (!读回 || 读回->定义!=预期[位置] || *读回!=回执.规则组[位置])
            throw std::logic_error("关系先天初始化：完整定义读回不一致");
        const auto 查询=因果_.查询关系先天结果(预期[位置].唯一结果.结果特征类型,
            预期[位置].唯一结果.种类);
        if (std::count(查询.begin(),查询.end(),*读回)!=1)
            throw std::logic_error("关系先天初始化：正式结果查询未唯一返回规则");
    }
}

内部治理先天初始化回执 内部治理先天因果初始化服务::初始化(
    const 新关系先天元数据请求& 请求) {
    try {
    if (!存在概念_.获取存在概念(请求.自我概念)
        || !特征概念_.获取特征概念(请求.服务任务特征类型))
        throw std::logic_error("关系先天初始化：正式初始化依赖不可读");
    内部治理先天初始化回执 回执;
    回执.元数据=因果_.确保关系先天元数据(请求);
    const auto 新目录=构造动作目录(回执.元数据);
    合并动作子目录(动作目录_,新目录);
    for (const auto& 定义:新目录) {
        动作方法投影请求 动作请求;
        动作请求.动作定义节点=定义.能力定义节点;
        动作请求.执行主体概念节点=定义.执行主体.存在概念节点;
        动作请求.普通目标概念节点=定义.作用目标.存在概念节点;
        动作请求.目标特征类型概念节点=定义.目标特征类型概念节点;
        动作请求.任务虚拟目标=定义.作用目标.对象类别==动作参数对象类别::任务虚拟存在;
        const auto 动作=动态_.确保动作定义概念(动作请求);
        if (!动作.概念节点) throw std::logic_error("关系先天初始化：正式动作概念缺失");
        回执.动作概念组.push_back(*动作.概念节点);
    }
    for (const auto& 规则:构造规则(回执.元数据,回执.动作概念组))
        回执.规则组.push_back(因果_.确保关系先天因果(规则));
    核验初始化读回(回执);
    return 回执;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"初始化治理先天因果",
            L"正式关系规则初始化失败，不进入应用已装配状态。",异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"初始化治理先天因果",L"未知工程异常。");
    }
}

std::vector<动作概念定义> 内部治理先天因果初始化服务::构造来源前驱动作目录(
    const 新服务取得来源前驱元数据& 元数据) const {
    using 角色=新来源前驱角色;
    using 步骤=新来源前驱治理步骤;
    using 结果=新来源前驱关系结果;
    std::vector<动作概念定义> 目录;
    for (const auto 当前步骤:{步骤::自我采用请求,步骤::管理关联任务}) {
        const bool 采用=当前步骤==步骤::自我采用请求;
        动作概念定义 定义;
        定义.能力定义节点=查唯一概念(元数据.治理定义组,当前步骤);
        定义.能力类别=动作能力定义类别::内部治理能力;
        定义.执行主体.存在概念节点=元数据.配置.自我概念;
        定义.作用目标.存在概念节点=元数据.配置.自我概念;
        新信息关系治理动作规格 规格;
        规格.操作=采用 ? 新信息关系治理操作::自我采用正式请求
            : 新信息关系治理操作::管理关联唯一任务;
        规格.结果关系概念=查唯一概念(元数据.结果关系组,
            采用 ? 结果::同源自我需求 : 结果::需求唯一任务);
        for (std::uint8_t 序号=1;序号<=9;++序号) {
            const auto 当前角色=static_cast<角色>(序号);
            if (采用 && 当前角色==角色::任务) continue;
            规格.角色范围组.push_back({序号,查唯一概念(元数据.角色范围组,当前角色)});
        }
        规格.结果角色组=采用 ? std::vector<std::int64_t>{1,2,3,4,9,5,6,8}
            : std::vector<std::int64_t>{6,7};
        定义.信息关系规格=std::move(规格);
        目录.push_back(std::move(定义));
    }
    return 目录;
}

std::vector<新来源前驱规则定义> 内部治理先天因果初始化服务::构造来源前驱规则(
    const 新服务取得来源前驱元数据& 元数据,const std::vector<稳定编码>& 动作概念组) const {
    if (元数据.规则概念组.size()!=4 || 动作概念组.size()!=2
        || 元数据.治理定义组.size()!=2 || 元数据.角色范围组.size()!=9
        || 元数据.条件关系组.size()!=19 || 元数据.结果关系组.size()!=2)
        throw std::logic_error("来源前驱初始化：元数据或动作数量不完整");
    using 角色=新来源前驱角色;
    using 条件=新来源前驱条件种类;
    using 阶段=新来源前驱求值阶段;
    const auto& 配置=元数据.配置;
    std::vector<新来源前驱规则定义> 规则组;
    for (std::size_t 槽=0;槽<4;++槽) {
        const bool 采用=槽<2,新建=槽%2==0;
        新来源前驱规则定义 规则;
        规则.规则概念=元数据.规则概念组[槽];
        规则.步骤=采用 ? 新来源前驱治理步骤::自我采用请求
            : 新来源前驱治理步骤::管理关联任务;
        规则.分支=新建 ? 新来源前驱发生分支::新建 : 新来源前驱发生分支::复用;
        规则.治理定义=查唯一概念(元数据.治理定义组,规则.步骤);
        规则.动作概念=动作概念组[采用 ? 0 : 1];
        规则.场景范围=采用 ? 配置.自我采用场景范围 : 配置.管理关联场景范围;
        规则.触发方式=新因果动作触发方式::被动触发;
        const auto 输出角色=采用 ? 角色::自我需求 : 角色::任务;
        for (std::uint8_t 序号=1;序号<=9;++序号) {
            const auto 当前角色=static_cast<角色>(序号);
            if (采用 && 当前角色==角色::任务) continue;
            规则.角色范围组.push_back({当前角色,查唯一概念(元数据.角色范围组,当前角色)});
            if (新建 && 当前角色==输出角色) 规则.动作引入角色组.push_back(当前角色);
            else 规则.输入角色组.push_back(当前角色);
        }
        const auto 添加=[&](阶段 当前阶段,条件 种类,std::vector<角色> 角色组,
            std::vector<稳定编码> 参数){
            auto& 组=当前阶段==阶段::动作前输入 ? 规则.输入条件组
                : 当前阶段==阶段::动作接纳 ? 规则.接纳核验组 : 规则.结果校验组;
            组.push_back({当前阶段,static_cast<std::uint32_t>(组.size()),种类,
                查唯一概念(元数据.条件关系组,种类),std::move(角色组),std::move(参数)});
        };
        for (const auto 当前角色:规则.输入角色组)
            添加(阶段::动作前输入,条件::角色合法,{当前角色},
                {查唯一概念(元数据.角色范围组,当前角色)});
        if (采用) {
            添加(阶段::动作前输入,条件::人类主体,{角色::人类},{配置.人类概念});
            添加(阶段::动作前输入,条件::被认知需求归属,
                {角色::人类,角色::被认知需求},{配置.需求概念});
            添加(阶段::动作前输入,条件::需求完整,
                {角色::被认知需求},{配置.完整被认知需求概念});
            添加(阶段::动作前输入,条件::正式行动请求,
                {角色::接收消息,角色::采用含义,角色::认知出现定位,角色::人类,角色::被认知需求,角色::自我},{});
            添加(阶段::动作前输入,条件::请求受话者,
                {角色::采用含义,角色::自我},{配置.自我概念});
            添加(阶段::动作前输入,条件::请求内容同需求,
                {角色::采用含义,角色::认知出现定位,角色::被认知需求},{配置.需求概念});
            添加(阶段::动作前输入,条件::合法完成服务父域,
                {角色::自我,角色::完成服务父需求},{配置.需求概念});
            auto 同源角色=std::vector<角色>{角色::接收消息,角色::采用含义,角色::认知出现定位,
                角色::人类,角色::被认知需求,角色::自我};
            if (!新建) 同源角色.push_back(角色::自我需求);
            添加(阶段::动作前输入,新建 ? 条件::同源自我需求尚无 : 条件::同源自我需求已存在,
                std::move(同源角色),{配置.需求概念});
            添加(阶段::动作接纳,条件::自我请求采用机制,
                {角色::自我,角色::接收消息,角色::采用含义,角色::认知出现定位,
                 角色::人类,角色::被认知需求,角色::完成服务父需求},{});
            添加(阶段::动作后结果,条件::角色合法,{角色::自我需求},
                {查唯一概念(元数据.角色范围组,角色::自我需求)});
            添加(阶段::动作后结果,条件::自我需求来源合法,
                {角色::自我,角色::人类,角色::接收消息,角色::采用含义,角色::认知出现定位,
                 角色::被认知需求,角色::自我需求,角色::完成服务父需求},{配置.需求概念});
            添加(阶段::动作后结果,条件::来源自我需求对应,
                {角色::被认知需求,角色::自我需求},{配置.需求概念});
            规则.结果=新来源前驱关系结果::同源自我需求;
            规则.结果角色组={角色::自我,角色::人类,角色::接收消息,角色::采用含义,
                角色::认知出现定位,角色::被认知需求,角色::自我需求,角色::完成服务父需求};
        } else {
            添加(阶段::动作前输入,条件::自我需求来源合法,
                {角色::自我,角色::人类,角色::接收消息,角色::采用含义,角色::认知出现定位,
                 角色::被认知需求,角色::自我需求,角色::完成服务父需求},{配置.需求概念});
            添加(阶段::动作前输入,条件::自我需求活动且准备允许,
                {角色::自我需求},{配置.需求概念});
            添加(阶段::动作前输入,条件::合法完成服务父域,
                {角色::自我,角色::完成服务父需求},{配置.需求概念});
            添加(阶段::动作前输入,条件::来源自我需求对应,
                {角色::被认知需求,角色::自我需求},{配置.需求概念});
            if (新建) 添加(阶段::动作前输入,条件::需求尚无任务,{角色::自我需求},{配置.任务概念});
            else 添加(阶段::动作前输入,条件::需求已有唯一任务,
                {角色::自我需求,角色::任务},{配置.任务概念});
            添加(阶段::动作接纳,条件::管理承接机制,{角色::自我,角色::自我需求},{});
            添加(阶段::动作后结果,条件::角色合法,{角色::任务},
                {查唯一概念(元数据.角色范围组,角色::任务)});
            添加(阶段::动作后结果,条件::需求已有唯一任务,
                {角色::自我需求,角色::任务},{配置.任务概念});
            规则.结果=新来源前驱关系结果::需求唯一任务;
            规则.结果角色组={角色::自我需求,角色::任务};
        }
        规则.结果关系概念=查唯一概念(元数据.结果关系组,规则.结果);
        规则组.push_back(std::move(规则));
    }
    return 规则组;
}

void 内部治理先天因果初始化服务::核验来源前驱初始化读回(
    const 内部治理来源前驱初始化回执& 回执) const {
    if (回执.动作概念组.size()!=2 || 回执.规则组.size()!=4)
        throw std::logic_error("来源前驱初始化：完整元数据读回不一致");
    const auto 目录=动作目录_.load(std::memory_order_acquire);
    const auto 动作定义组=构造来源前驱动作目录(回执.元数据);
    if (!目录 || 目录->size()!=4)
        throw std::logic_error("来源前驱初始化：原两动作及来源两动作未完整发布");
    核验动作子目录(*目录,动作定义组);
    const auto 预期=构造来源前驱规则(回执.元数据,回执.动作概念组);
    // 元数据和每条规则的确保入口已经完成源头校验、发布和正式读回。
    // 这里只核对本次回执的组装，不再为四条回执逐次重读整个元数据/规则全集。
    for (std::size_t 槽=0;槽<预期.size();++槽) {
        if (回执.规则组[槽].定义!=预期[槽])
            throw std::logic_error("来源前驱初始化：三阶段规则完整读回不一致");
    }
}

内部治理来源前驱初始化回执 内部治理先天因果初始化服务::初始化来源前驱(
    const 新服务取得来源前驱配置& 配置) {
    try {
        const auto 原目录=动作目录_.load(std::memory_order_acquire);
        if (!原目录 || (原目录->size()!=2 && 原目录->size()!=4))
            throw std::logic_error("来源前驱初始化：必须先完成原治理动作初始化");
        内部治理来源前驱初始化回执 回执;
        回执.元数据=因果_.确保服务取得来源前驱元数据(配置);
        const auto 新目录=构造来源前驱动作目录(回执.元数据);
        合并动作子目录(动作目录_,新目录);
        for (const auto& 定义:新目录) {
            动作方法投影请求 请求;
            请求.动作定义节点=定义.能力定义节点;
            请求.执行主体概念节点=定义.执行主体.存在概念节点;
            请求.普通目标概念节点=定义.作用目标.存在概念节点;
            const auto 动作=动态_.确保动作定义概念(请求);
            if (!动作.概念节点) throw std::logic_error("来源前驱初始化：正式信息关系动作概念缺失");
            回执.动作概念组.push_back(*动作.概念节点);
        }
        for (const auto& 规则:构造来源前驱规则(回执.元数据,回执.动作概念组))
            回执.规则组.push_back(因果_.确保来源前驱规则(规则));
        核验来源前驱初始化读回(回执);
        return 回执;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"初始化服务取得来源前驱",
            L"正式来源前驱规则初始化失败，不开放新筹办分支。",异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"初始化服务取得来源前驱",L"未知工程异常。");
    }
}
