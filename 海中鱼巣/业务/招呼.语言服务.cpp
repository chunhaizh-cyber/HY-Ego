namespace {
// 招呼不读正式信息：组织器招呼分支无条件、无取材，不会调用；万一调用，按范围未支持返回。
class 无正式读取 final : public 正式信息参数读取接口 {
public:
    正式信息参数读取结果 读取正式信息参数保护(稳定编码,稳定编码) const noexcept override {
        正式信息参数读取结果 r;r.状态=正式信息参数读取状态::范围未支持;return r;
    }
};
} // namespace

新招呼话语结果 招呼语言服务::生成招呼话语(新招呼种类 种类,const 新绑定指称& 说话者,const 新绑定指称& 受话者,
    const 正式表达成文参数& 成文) const {
    using 状态=新招呼话语状态;
    const auto 返回=[](状态 值){新招呼话语结果 r;r.状态=值;return r;};
    if(!有效(成文.语言节点)||!有效(说话者.节点)||!有效(受话者.节点)||说话者.节点==受话者.节点)
        throw std::logic_error("招呼成文参与者或语言节点不合法");
    正式表达需求 需求;
    需求.表达用途=新表达用途::招呼;需求.表达对象=正式表达招呼{种类};
    需求.说话者=说话者;需求.受话者=受话者;需求.成文参数=成文;
    const 无正式读取 正式读取;
    const auto 组织=组织具体表达结构(需求,语言_,正式读取,存在概念_,特征概念_);
    switch(组织.状态){
    case 新表达结构组织状态::已组织:break;
    case 新表达结构组织状态::缺组织知识:return 返回(状态::缺知识);
    case 新表达结构组织状态::多规则待选:return 返回(状态::多规则待选);
    case 新表达结构组织状态::前提已变化:return 返回(状态::前提已变化);
    case 新表达结构组织状态::范围未支持:return 返回(状态::范围未支持);
    default:throw std::logic_error("招呼组织器状态不属于招呼分支");
    }
    const auto 投影=含义网投影旧图(组织.含义网,{成文.语言节点,std::nullopt,说话者,受话者});
    if(投影.状态!=新含义网投影状态::已投影)return 返回(状态::范围未支持);
    if(!投影.图)throw std::logic_error("招呼含义网投影已投影但无图");
    const auto 无限=(std::numeric_limits<std::size_t>::max)();
    const 语言基础统一输出请求 请求{成文.语言节点,*投影.图,无限,无限,无限,无限,无限,无限};
    const auto 输出=从基础信息生成可回读单句(请求,语言世界_,语言_,词_,名称_,存在概念_,特征概念_,存在_,nullptr);
    switch(输出.状态){
    case 语言场景基础输出状态::已生成且唯一回读:
        return {状态::已生成且唯一回读,输出.文本,输出.所用知识节点组,组织.含义网,组织.所用组织知识节点};
    case 语言场景基础输出状态::缺规则:return 返回(状态::缺知识);
    case 语言场景基础输出状态::名称待选:
    case 语言场景基础输出状态::回读多义:return 返回(状态::多义);
    case 语言场景基础输出状态::读取漂移:return 返回(状态::前提已变化);
    case 语言场景基础输出状态::结构未支持:return 返回(状态::范围未支持);
    default:throw std::logic_error("招呼统一生成或独立回读未完成");
    }
}
