struct 恢复特征值见证 final {
    新特征值恢复结构读回 结构;
    新特征值保护读取结果 空集合;
};

bool 核验恢复特征值(const 基础持久视图& 视图, 恢复特征值见证& 见证) {
    using S = 新特征值保护读取状态;
    见证.结构 = 读取恢复特征值结构(视图);
    if (见证.结构.状态 != S::已读取) return false;
    // 普通装配已为自我的交互对象建立此空集合。它不承载权限数值。
    见证.空集合 = 读取恢复特征值材料(视图, 见证.结构,
        材料物理类型::U64数组, std::vector<std::uint64_t>{});
    return 见证.空集合.状态 == S::已读取 && 见证.空集合.信息.has_value();
}

基础持久状态 特征值复核失败状态(const 恢复特征值见证& 见证) noexcept {
    using V = 新特征值保护读取状态;
    using S = 基础持久状态;
    if (见证.结构.状态 == V::格式不支持) return S::格式不支持;
    if (见证.结构.状态 == V::资源失败 || 见证.空集合.状态 == V::资源失败) return S::资源失败;
    return S::结构冲突;
}

基础持久状态 特征值索引失败状态(新特征值运行恢复状态 状态) noexcept {
    using V = 新特征值运行恢复状态;
    using S = 基础持久状态;
    if (状态 == V::格式不支持) return S::格式不支持;
    if (状态 == V::资源失败) return S::资源失败;
    if (状态 == V::前提已变化) return S::前提已变化;
    return S::结构冲突;
}

基础持久状态 概念准入失败状态(基础结构操作状态 状态) noexcept {
    using B = 基础结构操作状态;
    using S = 基础持久状态;
    if (状态 == B::节点不存在) return S::材料不完整;
    if (状态 == B::资源失败) return S::资源失败;
    return S::结构冲突;
}

基础持久状态 特征概念恢复失败状态(特征概念规则状态 状态) noexcept {
    using C = 特征概念规则状态;
    using S = 基础持久状态;
    if (状态 == C::值不存在) return S::材料不完整;
    if (状态 == C::前提已变化) return S::前提已变化;
    if (状态 == C::资源失败) return S::资源失败;
    return S::结构冲突;
}

基础持久状态 状态读回复核失败状态(新状态持久读取状态 状态) noexcept {
    using R = 新状态持久读取状态;
    using S = 基础持久状态;
    if (状态 == R::材料不完整) return S::材料不完整;
    if (状态 == R::前提已变化) return S::前提已变化;
    if (状态 == R::资源失败) return S::资源失败;
    return S::结构冲突;
}

std::optional<基础持久状态> 核验已绑定全局根(const 基础持久运行包& 会话,
    const 基础持久运行包::视图& 准入视图, const 全局根读回结果& 准入根) noexcept {
    using S = 基础持久状态;
    if (会话.读取() != 准入视图) return S::前提已变化;
    const auto 正式根 = 新_全局根类::完整读回();
    if (会话.读取() != 准入视图) return S::前提已变化;
    if (正式根.状态 == 全局根操作状态::资源失败) return S::资源失败;
    if (正式根.状态 != 全局根操作状态::已完成 || 正式根.全局根节点 != 准入根.全局根节点
        || 正式根.挂接组 != 准入根.挂接组) return S::结构冲突;
    return std::nullopt;
}

struct 服务登记恢复见证 final {
    // 依次为特征、存在、场景、状态、本窗三组。
    std::array<基础结构自键读回, 5> 键组;
    基础结构操作状态 冷建校验 = 基础结构操作状态::入口拒绝;
    基础结构操作状态 自我复核 = 基础结构操作状态::入口拒绝;
    稳定编码 自我, 场景, 当前所属, 服务特征, 服务类型;
};

基础结构操作状态 核验恢复服务登记结构(
    const 基础持久视图& 视图, 服务登记恢复见证& 见证) {
    using S = 基础结构操作状态;
    见证.键组 = {读取恢复服务特征结构(视图), 读取恢复服务存在结构(视图),
        读取恢复服务场景结构(视图), 读取恢复服务状态结构(视图),
        读取恢复本窗角色结构(视图)};
    const auto 失败 = std::ranges::find_if(见证.键组,
        [](const auto& 组) { return 组.状态 != S::已完成; });
    return 失败 == 见证.键组.end() ? S::已完成 : 失败->状态;
}

基础结构操作状态 核验恢复自我身份(const 基础持久视图& 视图,
    const 全局根读回结果& 根, 服务登记恢复见证& 见证) {
    using S = 基础结构操作状态;
    const auto 现实 = std::ranges::find_if(根.挂接组, [](const auto& 项) {
        return 项.登记键 == static_cast<std::int64_t>(世界类型登记键::现实);
    });
    if (现实 == 根.挂接组.end()) return S::入口拒绝;
    const auto [状态, E] = 读取恢复自我单例角色(视图);
    if (状态 != S::已完成) return 状态;
    const auto 归属 = 核验恢复服务对象场景(视图, 见证.键组[2], 现实->世界根节点, E, E);
    if (归属 != S::已完成) return 归属;
    见证.自我 = E;
    见证.场景 = E;
    见证.当前所属 = 现实->世界根节点;
    return S::已完成;
}

基础结构操作状态 核验冷建服务特征持有(const 基础持久视图& 视图,
    const 普通应用装配结果& 装配, 服务登记恢复见证& 见证) {
    using S = 基础结构操作状态;
    if (!装配.自我 || 装配.自我->自我存在 != 见证.自我
        || 装配.自我->自我所在场景 != 见证.当前所属 || !装配.自我->服务对象特征节点
        || !装配.自我->服务对象特征类型根) return S::入口拒绝;

    const auto E = 见证.自我;
    const auto F = *装配.自我->服务对象特征节点;
    const auto 类型 = *装配.自我->服务对象特征类型根;
    const auto 特征 = 核验恢复服务对象特征(视图, 见证.键组[0], F, 类型);
    if (特征 != S::已完成) return 特征;
    const auto 持有 = 核验恢复自我服务特征持有(视图, 见证.键组[1], E, F);
    if (持有 != S::已完成) return 持有;
    见证.服务特征 = F;
    见证.服务类型 = 类型;
    return S::已完成;
}

程序运行结果 引导持久空仓(
    const 启动选项& 选项, 基础持久运行包& 运行包, 全局根读回结果& 根, 恢复特征值见证& 值,
    特征概念恢复读回结果& 概念, 服务登记恢复见证& 登记) {
    using S = 基础持久状态;
    using P = 程序失败阶段;
    using R = 程序运行状态;
    const auto 模式 = 选项.模式;
    if (!选项.本次网页会话服务对象登录名.empty()
        || !基础持久运行包::可开始首份(全局基础数据集))
        return {模式, R::装配失败, P::持久库准入失败, S::入口拒绝};

    普通上下文作用域回收 回收;
    普通应用配置 配置;
    配置.持久空仓形成自我 = true;
    const auto 装配 = 构造普通应用上下文(配置);
    if (!装配.成功())
        return {模式, R::装配失败, 装配失败阶段(装配.状态), S::空仓};

    const auto 外设标记 = 新_外设世界树类::发表已初始化外设消息持久自键();
    if (外设标记 != 基础结构操作状态::已完成)
        return {模式, R::装配失败, P::持久库准入失败,
            外设标记 == 基础结构操作状态::资源失败 ? S::资源失败 : S::结构冲突};

    const auto [准备状态, 候选] = 运行包.准备首份(全局基础数据集);
    if (!候选)
        return {模式, R::装配失败, P::持久库准入失败, 准备状态};
    根 = 新_全局根类::读取恢复全局根(候选->读取());
    const auto 原根 = 新_全局根类::完整读回();
    if (根.状态 != 全局根操作状态::已完成
        || 原根.状态 != 全局根操作状态::已完成
        || 根.全局根节点 != 原根.全局根节点 || 根.挂接组 != 原根.挂接组)
        return {模式, R::装配失败, P::持久根复核失败,
            根.状态 == 全局根操作状态::资源失败 ? S::资源失败 : S::结构冲突};

    if (!核验恢复特征值(候选->读取(), 值))
        return {模式, R::装配失败, P::持久特征值复核失败,
            特征值复核失败状态(值)};
    const auto 值索引 = 核验恢复特征值索引(候选->读取());
    if (值索引 != 新特征值运行恢复状态::已恢复)
        return {模式, R::装配失败, P::持久特征值复核失败, 特征值索引失败状态(值索引)};

    概念 = 读取恢复特征概念结构(候选->读取());
    if (概念.状态 != 基础结构操作状态::已完成)
        return {模式, R::装配失败, P::持久特征概念复核失败,
            概念准入失败状态(概念.状态)};

    const auto 存在概念 = 读取恢复存在概念结构(候选->读取());
    if (存在概念.状态 != 基础结构操作状态::已完成)
        return {模式, R::装配失败, P::持久存在概念复核失败,
            概念准入失败状态(存在概念.状态)};

    const auto 所有者 = 核验恢复服务登记结构(候选->读取(), 登记);
    if (所有者 != 基础结构操作状态::已完成)
        return {模式, R::装配失败, P::持久服务所有者结构失败,
            所有者 == 基础结构操作状态::资源失败 ? S::资源失败 : S::结构冲突};
    登记.自我复核 = 核验恢复自我身份(候选->读取(), 根, 登记);
    if (登记.自我复核 != 基础结构操作状态::已完成)
        return {模式, R::装配失败, P::持久自我单例身份未恢复,
            登记.自我复核 == 基础结构操作状态::资源失败 ? S::资源失败 : S::结构冲突};
    登记.冷建校验 = 核验冷建服务特征持有(候选->读取(), 装配, 登记);
    if (登记.冷建校验 != 基础结构操作状态::已完成)
        return {模式, R::装配失败, P::持久服务所有者结构失败,
            登记.冷建校验 == 基础结构操作状态::资源失败 ? S::资源失败 : S::结构冲突};

    const auto 外设核验 = 新_外设世界树类::核验外设消息持久自键(候选->读取(), true);
    if (外设核验 != 基础结构操作状态::已完成)
        return {模式, R::装配失败, P::持久库准入失败,
            外设核验 == 基础结构操作状态::资源失败 ? S::资源失败 : S::结构冲突};

    const auto 提交 = 运行包.提交首份(*候选);
    return {模式, R::装配失败,
        提交 == S::已提交 ? P::持久业务运行者未重绑 : P::持久库准入失败, 提交};
}

程序运行结果 检查普通启动持久准入(const 启动选项& 选项) {
    using S = 基础持久状态;
    using P = 程序失败阶段;
    using R = 程序运行状态;
    程序运行结果 结果{选项.模式, R::装配失败, P::持久库准入失败, S::资源失败};
    全局根读回结果 根;
    恢复特征值见证 值;
    特征概念恢复读回结果 概念;
    服务登记恢复见证 登记;
    bool 视图存在 = false;
    bool 唯一权威已绑定 = false;
    try {
        const auto& 参数 = 选项.当前事实持久目录;
        const std::filesystem::path 目录{std::u8string(参数.begin(), 参数.end())};
        auto [打开状态, 运行包] = 基础持久运行包::打开(目录);
        const auto 视图 = 运行包 ? 运行包->读取() : nullptr;
        结果.持久库状态 = 打开状态;
        视图存在 = static_cast<bool>(视图);
        if (打开状态 == S::空仓 && 运行包 && !视图) {
            结果 = 引导持久空仓(选项, *运行包, 根, 值, 概念, 登记);
            视图存在 = static_cast<bool>(运行包->读取());
        } else if (打开状态 == S::已读取 && 视图) {
            根 = 新_全局根类::读取恢复全局根(*视图);
            if (根.状态 != 全局根操作状态::已完成) 结果.失败阶段 = P::持久根复核失败;
            else if (!核验恢复特征值(*视图, 值)) {
                结果.失败阶段 = P::持久特征值复核失败;
                结果.持久库状态 = 特征值复核失败状态(值);
            }
            else {
                概念 = 读取恢复特征概念结构(*视图);
                if (概念.状态 != 基础结构操作状态::已完成) {
                    结果.失败阶段 = P::持久特征概念复核失败;
                    结果.持久库状态 = 概念准入失败状态(概念.状态);
                } else if (const auto 存在概念 = 读取恢复存在概念结构(*视图);
                    存在概念.状态 != 基础结构操作状态::已完成) {
                    结果.失败阶段 = P::持久存在概念复核失败;
                    结果.持久库状态 = 概念准入失败状态(存在概念.状态);
                } else if (核验恢复服务登记结构(*视图, 登记) != 基础结构操作状态::已完成)
                    结果.失败阶段 = P::持久服务所有者结构失败;
                else {
                    登记.自我复核 = 核验恢复自我身份(*视图, 根, 登记);
                    if (登记.自我复核 != 基础结构操作状态::已完成) {
                        结果.失败阶段 = P::持久自我单例身份未恢复;
                    } else {
                        const auto 外设核验 = 新_外设世界树类::核验外设消息持久自键(*视图, false);
                        if (外设核验 != 基础结构操作状态::已完成) {
                            结果.持久库状态 = 外设核验 == 基础结构操作状态::资源失败
                                ? S::资源失败 : S::结构冲突;
                            结果.失败阶段 = P::持久库准入失败;
                        } else {
                            const std::shared_ptr<基础持久运行包> 会话(std::move(运行包));
                            const auto 绑定 = 基础持久运行包::绑定恢复权威(全局基础数据集, 会话);
                            唯一权威已绑定 = 绑定 == S::已读取
                                && 全局基础数据集.查询节点(登记.自我) == std::optional{基础节点{登记.自我}}
                                && 全局基础数据集.查询节点(登记.当前所属) == std::optional{基础节点{登记.当前所属}};
                            if (!唯一权威已绑定) {
                                结果.失败阶段 = P::持久库准入失败;
                            } else if (const auto 根失败 = 核验已绑定全局根(*会话, 视图, 根)) {
                                结果.失败阶段 = P::持久根复核失败;
                                结果.持久库状态 = *根失败;
                            } else {
                                普通上下文作用域回收 上下文回收;
                                普通应用配置 配置;
                                配置.本次网页会话服务对象登录名 = 选项.本次网页会话服务对象登录名;
                                const auto 已恢复 = 恢复普通应用基础事实(
                                    配置, *视图, *值.空集合.信息, 登记.自我);
                                using V = 新特征值运行恢复状态;
                                using C = 特征概念规则状态;
                                if (已恢复.值 != V::已恢复 && 已恢复.值 != V::精确复用) {
                                    结果.失败阶段 = P::持久特征值复核失败;
                                    结果.持久库状态 = 特征值索引失败状态(已恢复.值);
                                } else if (已恢复.概念 != C::已完成 && 已恢复.概念 != C::无变化) {
                                    结果.失败阶段 = P::持久特征概念复核失败;
                                    结果.持久库状态 = 特征概念恢复失败状态(已恢复.概念);
                                } else if (已恢复.状态 != 新状态持久读取状态::已读取) {
                                    结果.失败阶段 = P::持久状态读回复核失败;
                                    结果.持久库状态 = 状态读回复核失败状态(已恢复.状态);
                                } else if (已恢复.存在概念 != S::已读取) {
                                    结果.失败阶段 = P::持久存在概念复核失败;
                                    结果.持久库状态 = 已恢复.存在概念;
                                } else if (已恢复.存在与特征 != S::已读取) {
                                    结果.失败阶段 = P::持久存在与特征复核失败;
                                    结果.持久库状态 = 已恢复.存在与特征;
                                } else if (已恢复.语言词条 != S::已读取) {
                                    结果.失败阶段 = P::持久语言词条复核失败;
                                    结果.持久库状态 = 已恢复.语言词条;
                                } else if (已恢复.名称与人类 != S::已读取) {
                                    结果.失败阶段 = P::持久名称与人类复核失败;
                                    结果.持久库状态 = 已恢复.名称与人类;
                                } else {
                                    结果.失败阶段 = P::持久业务运行者未重绑;
                                }
                            }
                        }
                    }
                }
            }
        } else if (打开状态 == S::空仓 || 打开状态 == S::已读取) {
            结果.持久库状态 = S::内部不一致;
        }
    } catch (const std::bad_alloc&) {
        结果.持久库状态 = S::资源失败;
    } catch (const std::length_error&) {
        结果.持久库状态 = S::资源失败;
    } catch (const std::filesystem::filesystem_error&) {
        结果.持久库状态 = S::资源失败;
    }
    记录启动返回(L"普通持久准入返回", [&](auto& 文本) {
        文本 << L"存储状态=" << static_cast<int>(*结果.持久库状态)
            << L"；失败阶段=" << static_cast<int>(结果.失败阶段)
            << L"；隔离视图=" << 视图存在
            << L"；唯一持久权威绑定=" << 唯一权威已绑定
            << L"；根复核=" << static_cast<int>(根.状态);
        if (根.全局根节点) {
            文本 << L"；全局根=" << 根.全局根节点->值;
            for (const auto& 项 : 根.挂接组)
                文本 << L"；登记=" << 项.登记键 << L":" << 项.世界类型节点.值 << L":" << 项.世界根节点.值;
        }
        文本 << L"；特征值结构=" << static_cast<int>(值.结构.状态)
            << L"；空U64读取=" << static_cast<int>(值.空集合.状态);
        if (值.结构.状态 == 新特征值保护读取状态::已读取) {
            for (const auto 键 : 值.结构.键) 文本 << L"；特征值键=" << 键.值;
        }
        if (值.空集合.信息) 文本 << L"；空U64材料=" << 值.空集合.信息->节点.值;
        文本 << L"；特征概念结构=" << static_cast<int>(概念.状态);
        if (概念.状态 == 基础结构操作状态::已完成) {
            文本 << L"；特征概念根=" << 概念.根.值
                << L"；特征概念键数=" << 概念.键数
                << L"；词典来源批次类型根=" << 概念.词典来源批次类型根.值
                << L"；服务权限类型根=" << 概念.服务权限类型根.值;
        }
        for (const auto& 组 : 登记.键组)
            文本 << L"；所有者结构=" << static_cast<int>(组.状态) << L":" << 组.节点组.size();
        文本 << L"；自我单例互证=" << static_cast<int>(登记.自我复核);
        if (登记.自我复核 == 基础结构操作状态::已完成)
            文本 << L"；自我E=" << 登记.自我.值 << L"；自我内部场景=" << 登记.场景.值
                << L"；当前所属=" << 登记.当前所属.值;
        文本 << L"；冷建E-F互证=" << static_cast<int>(登记.冷建校验);
        if (登记.冷建校验 == 基础结构操作状态::已完成)
            文本 << L"；冷建服务F=" << 登记.服务特征.值 << L"；冷建服务FT=" << 登记.服务类型.值;
    });
    return 结果;
}

程序运行结果 运行新版普通程序(const 启动选项& 选项) {
    if (!选项.验证当前快照存储参数[0].empty()) {
        const bool 通过 = 运行当前快照存储工程验证(选项.验证当前快照存储参数);
        return {选项.模式, 通过 ? 程序运行状态::已完成 : 程序运行状态::初始化失败,
            通过 ? 程序失败阶段::无 : 程序失败阶段::普通应用装配};
    }
    if (选项.验证限定I64需求目标) {
        const bool 通过 = 运行限定I64需求目标准入验证();
        return {选项.模式, 通过 ? 程序运行状态::已完成 : 程序运行状态::初始化失败,
            通过 ? 程序失败阶段::无 : 程序失败阶段::普通应用装配};
    }
    if (选项.验证服务权限登记) {
        const bool 通过 = 运行服务权限登记工程验证();
        return {选项.模式, 通过 ? 程序运行状态::已完成 : 程序运行状态::初始化失败,
            通过 ? 程序失败阶段::无 : 程序失败阶段::普通应用装配};
    }
    if (!选项.当前事实持久目录.empty()) return 检查普通启动持久准入(选项);

    // 声明在宿主、停止信号等局部对象之前，逆序收尾时先结束宿主和回调，
    // 再销毁应用上下文；不能留到跨翻译单元全局服务的静态析构阶段。
    普通上下文作用域回收 上下文回收;
    const auto 模式 = 选项.模式;
    普通应用配置 配置;
    配置.本次网页会话服务对象登录名 = 选项.本次网页会话服务对象登录名;
    const auto 装配起点 = std::chrono::steady_clock::now();
    记录启动返回(L"装配开始", [](auto& 文本) { 文本 << L"即将构造普通应用上下文"; });
    const auto 装配 = 构造普通应用上下文(配置);
    const bool 装配成功 = 装配.成功();
    记录启动返回(L"装配返回", [&](auto& 文本) {
        文本 << L"普通应用装配状态=" << static_cast<int>(装配.状态)
            << L"；成功=" << 装配成功 << L"；耗时毫秒=" << 启动观察耗时(装配起点);
    });
    if (!装配成功) {
        return {模式, 程序运行状态::装配失败,
            装配失败阶段(装配.状态)};
    }

    if (选项.验证关系概念出站) {
        记录启动返回(L"关系概念出站验证开始", [](auto& 文本) {
            文本 << L"即将运行普通应用关系概念出站验证";
        });
        const bool 通过 = 运行普通应用关系概念出站验证();
        记录启动返回(L"关系概念出站验证返回", [&](auto& 文本) {
            文本 << L"通过=" << 通过;
        });
        return {模式,
            通过 ? 程序运行状态::已完成 : 程序运行状态::初始化失败,
            通过 ? 程序失败阶段::无 : 程序失败阶段::关系概念出站验证};
    }

    if (选项.验证同窗需求主体) {
        wchar_t 受控水温[2]{};
        if (GetEnvironmentVariableW(L"HY_EGO_VERIFY_ISOLATED_WATER_TARGET",受控水温,2)==1
            && 受控水温[0]==L'1' && !准备同窗需求水温隔离验证())
            return {模式,程序运行状态::初始化失败,程序失败阶段::普通应用装配};
    }

    auto 信号 = 安装程序停止信号();
    记录启动返回(L"停止信号安装返回", [&](auto& 文本) {
        文本 << L"停止信号安装状态=" << static_cast<int>(信号.状态)
            << L"；有租约=" << static_cast<bool>(信号.租约) << L"；成功=" << 信号.成功();
    });
    if (!信号.成功()) {
        return {模式, 程序运行状态::宿主失败,
            程序失败阶段::停止信号};
    }

    const auto 治理起点 = std::chrono::steady_clock::now();
    记录启动返回(L"治理启动开始", [](auto& 文本) { 文本 << L"即将启动管理与自我线程"; });
    const auto 治理 = 启动普通应用治理线程();
    记录治理返回(L"治理启动返回", 治理);
    记录启动返回(L"治理启动耗时", [&](auto& 文本) { 文本 << L"耗时毫秒=" << 启动观察耗时(治理起点); });
    if (!治理.成功()) {
        const auto 回收 = 停止并回收普通应用治理线程();
        记录治理返回(L"启动失败回收返回", 回收);
        return {模式, 程序运行状态::初始化失败,
            程序失败阶段::自我线程启动};
    }

    std::jthread 同窗主体验证;
    if (选项.验证同窗需求主体) {
        同窗主体验证 = 启动同窗需求主体隔离验证();
        if (!同窗主体验证.joinable()) {
            (void)停止并回收普通应用治理线程();
            return {模式, 程序运行状态::初始化失败, 程序失败阶段::自我线程启动};
        }
    }
    程序运行结果 运行结果;
    if (模式 == 启动模式::普通控制面板) {
        const 网页服务输入回调组 服务输入{
            &开始普通应用网页会话,
            &结束普通应用网页会话,
            &查询普通应用服务目标选项,
            &预览普通应用服务要求,
            &读取普通应用服务要求预览,
            &确认普通应用服务要求,
            &提交普通应用部分服务要求,
            &读取普通应用部分服务要求,
            &通知普通应用接收事实已记录,
            &读取普通应用原文分界引文
        };
        记录启动返回(L"网页宿主开始", [](auto& 文本) { 文本 << L"即将调用本地网页对话宿主"; });
        const auto 网页宿主 = 运行本地网页对话宿主(
            信号.租约->停止请求, 取得普通应用网页外设运行回调(), 服务输入,
            取得普通应用控制面板回调());
        记录启动返回(L"网页宿主返回", [&](auto& 文本) {
            文本 << L"网页对话宿主状态=" << static_cast<int>(网页宿主.状态)
                << L"；成功=" << 网页宿主.成功();
        });
        运行结果 = {模式,
            网页宿主.成功()
                ? 程序运行状态::已完成
                : 程序运行状态::宿主失败,
            网页宿主.成功()
                ? 程序失败阶段::无
                : 程序失败阶段::控制面板窗口};
    } else {
        运行结果 = 运行无窗口宿主(*信号.租约);
        运行结果.模式 = 模式;
        if (!运行结果.成功()) {
            运行结果.失败阶段 = 程序失败阶段::无窗口常驻;
        }
    }

    if (同窗主体验证.joinable()) {
        同窗主体验证.request_stop();
        同窗主体验证.join();
    }
    const auto 回收 = 停止并回收普通应用治理线程();
    记录治理返回(L"宿主结束回收返回", 回收);
    if (!回收.成功()) {
        return {模式, 程序运行状态::宿主失败,
            模式 == 启动模式::普通控制面板
                ? 程序失败阶段::自我线程启动
                : 程序失败阶段::无窗口常驻};
    }
    记录启动返回(L"普通程序返回", [&](auto& 文本) {
        文本 << L"程序运行状态=" << static_cast<int>(运行结果.状态)
            << L"；程序失败阶段=" << static_cast<int>(运行结果.失败阶段);
    });
    return 运行结果;
}

