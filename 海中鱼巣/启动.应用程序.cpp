程序运行结果 运行海中鱼巣(const 启动选项& 选项) {
    if (!选项.本次网页会话服务对象登录名.empty()
        && 选项.模式 != 启动模式::普通控制面板) {
        return {选项.模式, 程序运行状态::启动模式拒绝,
            程序失败阶段::启动模式拒绝};
    }
    switch (选项.模式) {
    case 启动模式::普通控制面板:
    case 启动模式::无窗口常驻:
    case 启动模式::生产运行期:
        return 运行新版普通程序(选项);
    }
    return {选项.模式, 程序运行状态::启动模式拒绝,
        程序失败阶段::启动模式拒绝};
}

