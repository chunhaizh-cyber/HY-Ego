template<class 写入函数>
void 记录启动返回(const wchar_t* 阶段, 写入函数 写入) noexcept {
    try {
        std::wostringstream 文本;
        写入(文本);
        (void)记录运行日志(L"普通启动", 阶段, 文本.str());
    } catch (...) { /* 观察失败不改变已有返回和收尾。 */ }
}

auto 启动观察耗时(std::chrono::steady_clock::time_point 起点) noexcept {
    return std::chrono::duration_cast<std::chrono::milliseconds>(
        std::chrono::steady_clock::now() - 起点).count();
}

void 记录治理返回(const wchar_t* 阶段, const 普通应用治理操作结果& 结果) noexcept {
    记录启动返回(阶段, [&](auto& 文本) {
        文本 << L"普通应用治理操作状态=" << static_cast<int>(结果.状态)
            << L"；成功=" << 结果.成功();
        if (结果.任务管理) {
            文本 << L"；新任务管理操作状态=" << static_cast<int>(结果.任务管理->状态)
                << L"；新任务管理生命周期=" << static_cast<int>(结果.任务管理->生命周期);
        } else { 文本 << L"；任务管理=无返回材料"; }
        if (结果.自我线程) {
            文本 << L"；新自我线程操作状态=" << static_cast<int>(结果.自我线程->状态)
                << L"；新自我线程生命周期=" << static_cast<int>(结果.自我线程->生命周期);
        } else { 文本 << L"；自我线程=无返回材料"; }
    });
}

程序失败阶段 装配失败阶段(普通应用装配状态 状态) noexcept {
    switch (状态) {
    case 普通应用装配状态::世界树初始化失败:
        return 程序失败阶段::现实世界树根初始化;
    case 普通应用装配状态::自我初始化失败:
        return 程序失败阶段::自我线程初始化;
    default:
        return 程序失败阶段::普通应用装配;
    }
}

