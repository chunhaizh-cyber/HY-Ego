#include "装配.普通应用.h"

namespace 海中鱼巣 {
namespace {

程序运行结果 运行普通程序(启动模式 模式) {
    auto 装配 = 构造普通应用上下文();
    if (!装配.成功()) {
        if (装配.状态 == 普通应用装配状态::概念结构失败)
            return {模式, 程序运行状态::初始化失败,
                程序失败阶段::概念依附结构初始化};
        if (装配.状态 == 普通应用装配状态::世界树根失败 ||
            装配.状态 == 普通应用装配状态::世界树应用失败)
            return {模式, 程序运行状态::初始化失败,
                程序失败阶段::现实世界树根初始化};
        if (装配.状态 == 普通应用装配状态::单例角色结构失败 ||
            装配.状态 == 普通应用装配状态::自我服务建立失败)
            return {模式, 程序运行状态::初始化失败,
                程序失败阶段::真实自我形成};
        return {模式, 程序运行状态::装配失败, 程序失败阶段::普通应用装配};
    }
    if (!装配.根事实代次) {
        return {模式, 程序运行状态::初始化失败,
            程序失败阶段::现实世界树根初始化};
    }
    const auto 自我 = 初始化普通应用自我();
    if (!自我.请求回显 || !自我.成功(*自我.请求回显))
        return {模式, 程序运行状态::初始化失败,
            程序失败阶段::真实自我形成};
    const auto 方法登记根 = 初始化普通应用方法登记根();
    if (!方法登记根.成功())
        return {模式, 程序运行状态::初始化失败,
            程序失败阶段::方法登记根生产初始化};
    const auto 本能根运行 = 初始化普通应用本能根运行锚点(方法登记根);
    if (!本能根运行.成功())
        return {模式, 程序运行状态::初始化失败,
            程序失败阶段::本能根运行初始化};
    const auto 自我线程 = 创建并停门普通应用自我线程();
    if (!自我线程.成功())
        return {模式, 程序运行状态::初始化失败,
            程序失败阶段::自我线程创建并停门};

    if (模式 == 启动模式::普通控制面板) {
        const auto 回收 = 停止并回收普通应用自我线程();
        if (!回收.成功())
            return {模式, 程序运行状态::初始化失败,
                程序失败阶段::自我线程创建并停门};
        return {模式, 程序运行状态::宿主失败,
            程序失败阶段::控制面板窗口};
    }

    auto 信号 = 安装程序停止信号();
    if (!信号.成功()) {
        const auto 回收 = 停止并回收普通应用自我线程();
        if (!回收.成功())
            return {模式, 程序运行状态::初始化失败,
                程序失败阶段::自我线程创建并停门};
        return {模式, 程序运行状态::宿主失败,
            程序失败阶段::停止信号};
    }
    auto 结果 = 运行无窗口宿主(*信号.租约);
    const auto 回收 = 停止并回收普通应用自我线程();
    if (!回收.成功())
        return {模式, 程序运行状态::初始化失败,
            程序失败阶段::自我线程创建并停门};
    结果.模式 = 模式;
    return 结果;
}

程序运行结果 运行生产运行期(const 启动选项& 选项) {
    if (选项.模式 != 启动模式::生产运行期) {
        return {选项.模式, 程序运行状态::内部不一致,
            程序失败阶段::启动模式拒绝};
    }
    auto 信号 = 安装程序停止信号();
    if (!信号.成功()) {
        return {选项.模式, 程序运行状态::宿主失败,
            程序失败阶段::停止信号};
    }
    auto 结果 = 运行无窗口宿主(*信号.租约);
    结果.模式 = 启动模式::生产运行期;
    return 结果;
}

} // namespace

程序运行结果 运行海中鱼巣(const 启动选项& 选项) {
    switch (选项.模式) {
    case 启动模式::普通控制面板:
    case 启动模式::无窗口常驻:
        return 运行普通程序(选项.模式);
    case 启动模式::生产运行期:
        return 运行生产运行期(选项);
    }
    return {选项.模式, 程序运行状态::启动模式拒绝,
        程序失败阶段::启动模式拒绝};
}

} // namespace 海中鱼巣
