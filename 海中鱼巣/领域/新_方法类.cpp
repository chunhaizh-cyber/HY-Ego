bool 新_方法类::初始化() noexcept {
    try {
        const auto 函数集 = 新_本能函数管理类::初始化();
        if (函数集 != 新本能函数登记状态::已登记
            && 函数集 != 新本能函数登记状态::精确重复) return false;
        std::lock_guard 锁(新方法互斥);
        if (结构已分配()) return 结构仍存在();
        if (存在部分架构编码()) return false;
        std::vector<稳定编码> 已建节点;
        std::vector<稳定编码> 已写字段;
        const auto 编码指针 = 架构编码组();
        for (auto* 编码 : 编码指针) {
            *编码 = 全局基础数据集.新建节点();
            if (!有效(*编码)) {
                回滚(已写字段, 已建节点);
                for (auto* 清空 : 编码指针) *清空 = {};
                return false;
            }
            已建节点.push_back(*编码);
        }
        if (!写入节点字段(新方法组织根节点, 节点类型字段,
                方法组织根类型, 已写字段)) {
            回滚(已写字段, 已建节点);
            for (auto* 清空 : 编码指针) *清空 = {};
            return false;
        }
        return 结构仍存在();
    } catch (...) {
        return false;
    }
}

新方法建立结果 新_方法类::登记方法(
    const 新方法登记请求& 请求) noexcept {
    新方法建立结果 结果;
    try {
        std::lock_guard 锁(新方法互斥);
        if (!结构仍存在()) {
            结果.状态 = 新方法操作状态::尚未初始化;
            return 结果;
        }
        if (!是作用域(static_cast<std::int64_t>(请求.作用域))
            || !是实现方式(static_cast<std::int64_t>(请求.实现方式))) {
            return 结果;
        }
        if (!方法头有效(请求.方法头)) {
            结果.状态 = 新方法操作状态::方法头不合法;
            return 结果;
        }
        if (!参数规格有效(请求.参数规格组)) {
            结果.状态 = 新方法操作状态::参数规格不合法;
            return 结果;
        }
        if (请求.条件结果组.empty()
            || !std::all_of(请求.条件结果组.begin(), 请求.条件结果组.end(),
                [&](const 新方法条件结果定义& 定义) {
                    return 条件结果有效(定义)
                        && 条件结果角色已声明(请求.参数规格组, 定义);
                })) {
            结果.状态 = 新方法操作状态::条件结果不合法;
            return 结果;
        }
        if ((请求.实现方式 == 新方法实现方式::本能
                && 请求.本能函数登记名.empty())
            || (请求.实现方式 == 新方法实现方式::组合
                && !请求.本能函数登记名.empty())) {
            结果.状态 = 新方法操作状态::函数登记不合法;
            return 结果;
        }
        if (请求.实现方式 == 新方法实现方式::本能) {
            const auto 函数 = 新_本能函数管理类::解析(请求.本能函数登记名);
            if (!函数.函数) {
                结果.状态 = 新方法操作状态::函数登记不合法;
                return 结果;
            }
        }
        const auto 成员组 = 读取多节点字段(新方法组织根节点, 方法成员字段);
        if (!成员组) {
            结果.状态 = 新方法操作状态::结构不一致;
            return 结果;
        }
        for (const auto 已有节点 : *成员组) {
            const auto 已有 = 读取方法信息(已有节点);
            if (!已有) {
                结果.状态 = 新方法操作状态::结构不一致;
                return 结果;
            }
            std::vector<新方法条件结果定义> 已有配对;
            for (const auto& 项 : 已有->条件结果组) {
                已有配对.push_back({项.条件, 项.结果});
            }
            if (已有->作用域 == 请求.作用域
                && 已有->实现方式 == 请求.实现方式
                && 已有->方法头 == 请求.方法头
                && 已有->参数规格组 == 请求.参数规格组
                && 已有配对 == 请求.条件结果组
                && 已有->本能函数登记名.value_or("") == 请求.本能函数登记名) {
                结果.状态 = 新方法操作状态::已找到;
                结果.方法节点 = 已有节点;
                return 结果;
            }
        }

        std::vector<稳定编码> 已建节点;
        std::vector<稳定编码> 已写字段;
        const auto 方法节点 = 新建类型化节点(
            方法节点类型, 已建节点, 已写字段);
        const auto 头节点 = 新建类型化节点(
            方法头节点类型, 已建节点, 已写字段);
        const auto 虚拟存在 = 新建类型化节点(
            方法虚拟存在节点类型, 已建节点, 已写字段);
        bool 完整 = 有效(方法节点) && 有效(头节点) && 有效(虚拟存在)
            && 写入I64字段(方法节点, 方法作用域字段,
                static_cast<std::int64_t>(请求.作用域), 已写字段)
            && 写入I64字段(方法节点, 方法实现方式字段,
                static_cast<std::int64_t>(请求.实现方式), 已写字段)
            && 写入I64字段(方法节点, 方法启用状态字段,
                static_cast<std::int64_t>(新方法启用状态::启用), 已写字段)
            && 写入节点字段(方法节点, 方法头字段, 头节点, 已写字段)
            && 写入节点字段(方法节点, 方法虚拟存在字段,
                虚拟存在, 已写字段)
            && 写入节点字段(虚拟存在, 虚拟存在所属方法字段,
                方法节点, 已写字段)
            && 写入有序引用组(头节点, 方法头作用存在概念字段,
                请求.方法头.作用存在概念组, 已写字段)
            && 写入有序引用组(头节点, 方法头特征类型概念字段,
                请求.方法头.涉及特征类型概念组, 已写字段)
            && 写入有序引用组(头节点, 方法头结果概念字段,
                请求.方法头.可能结果概念组, 已写字段);
        if (完整 && 请求.实现方式 == 新方法实现方式::本能) {
            完整 = 写入字符串字段(方法节点, 方法本能函数登记名字段,
                请求.本能函数登记名, 已写字段);
        }
        for (std::size_t i = 0; 完整 && i < 请求.参数规格组.size(); ++i) {
            完整 = 写入参数规格(虚拟存在, 请求.参数规格组[i],
                static_cast<std::int64_t>(i), 已建节点, 已写字段);
        }
        for (std::size_t i = 0; 完整 && i < 请求.条件结果组.size(); ++i) {
            完整 = 写入条件结果(方法节点, 请求.条件结果组[i],
                static_cast<std::int64_t>(i), 已建节点, 已写字段);
        }
        // 方法成员字段是唯一发布点，所有内部结构完成后才对查询可见。
        if (完整) 完整 = 写入节点字段(新方法组织根节点,
            方法成员字段, 方法节点, 已写字段);
        if (!完整) {
            回滚(已写字段, 已建节点);
            结果.状态 = 新方法操作状态::资源失败;
            return 结果;
        }
        const auto 读回 = 读取方法信息(方法节点);
        if (!读回) {
            结果.状态 = 新方法操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新方法操作状态::已建立;
        结果.方法节点 = 方法节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新方法操作状态::资源失败;
        return 结果;
    }
}

std::optional<新方法信息> 新_方法类::获取方法(
    稳定编码 方法节点) const noexcept {
    try {
        std::lock_guard 锁(新方法互斥);
        return 读取方法信息(方法节点);
    } catch (...) {
        return std::nullopt;
    }
}

bool 新_方法类::是方法节点(稳定编码 节点) const noexcept {
    try {
        std::lock_guard 锁(新方法互斥);
        return 读取方法信息(节点).has_value();
    } catch (...) {
        return false;
    }
}

新方法候选结果 新_方法类::查询候选方法(
    const 新方法候选查询& 查询) const noexcept {
    新方法候选结果 结果;
    try {
        std::lock_guard 锁(新方法互斥);
        if (!结构仍存在()) {
            结果.状态 = 新方法操作状态::尚未初始化;
            return 结果;
        }
        if ((查询.作用域
                && !是作用域(static_cast<std::int64_t>(*查询.作用域)))
            || (查询.实现方式
                && !是实现方式(static_cast<std::int64_t>(*查询.实现方式)))
            || !引用组有效(查询.作用存在概念组)
            || !引用组有效(查询.涉及特征类型概念组)
            || !引用组有效(查询.可能结果概念组)) return 结果;
        const auto 成员组 = 读取多节点字段(新方法组织根节点, 方法成员字段);
        if (!成员组) {
            结果.状态 = 新方法操作状态::结构不一致;
            return 结果;
        }
        for (const auto 方法节点 : *成员组) {
            const auto 方法 = 读取方法信息(方法节点);
            if (!方法) {
                结果.状态 = 新方法操作状态::结构不一致;
                结果.方法节点组.clear();
                return 结果;
            }
            if (方法->启用状态 != 新方法启用状态::启用
                || (查询.作用域 && 方法->作用域 != *查询.作用域)
                || (查询.实现方式 && 方法->实现方式 != *查询.实现方式)
                || !包含全部(方法->方法头.作用存在概念组,
                    查询.作用存在概念组)
                || !包含全部(方法->方法头.涉及特征类型概念组,
                    查询.涉及特征类型概念组)
                || !包含全部(方法->方法头.可能结果概念组,
                    查询.可能结果概念组)) continue;
            结果.方法节点组.push_back(方法节点);
        }
        std::sort(结果.方法节点组.begin(), 结果.方法节点组.end());
        结果.状态 = 新方法操作状态::已找到;
        return 结果;
    } catch (...) {
        结果.状态 = 新方法操作状态::资源失败;
        结果.方法节点组.clear();
        return 结果;
    }
}

新方法操作状态 新_方法类::修改启用状态(
    稳定编码 方法节点,
    新方法启用状态 新状态) noexcept {
    try {
        std::lock_guard 锁(新方法互斥);
        if (!结构仍存在()) return 新方法操作状态::尚未初始化;
        const auto 方法 = 读取方法信息(方法节点);
        if (!方法) return 新方法操作状态::方法不存在;
        if (新状态 != 新方法启用状态::停用
            && 新状态 != 新方法启用状态::启用) {
            return 新方法操作状态::入口拒绝;
        }
        if (方法->启用状态 == 新状态) return 新方法操作状态::无变化;
        const auto 记录 = 读取唯一I64字段记录(方法节点, 方法启用状态字段);
        if (!记录) return 新方法操作状态::结构不一致;
        return 全局基础数据集.修改字段值(记录->关系,
                基础值{static_cast<std::int64_t>(新状态)})
            ? 新方法操作状态::已修改 : 新方法操作状态::资源失败;
    } catch (...) {
        return 新方法操作状态::资源失败;
    }
}

新方法结构节点结果 新_方法类::添加组合步骤(
    const 新方法组合步骤添加请求& 请求) noexcept {
    新方法结构节点结果 结果;
    try {
        std::lock_guard 锁(新方法互斥);
        if (!结构仍存在()) {
            结果.状态 = 新方法操作状态::尚未初始化;
            return 结果;
        }
        const auto 组合 = 读取方法信息(请求.组合方法节点);
        const auto 调用 = 读取方法信息(请求.调用方法节点);
        if (!组合 || !调用) {
            结果.状态 = 新方法操作状态::方法不存在;
            return 结果;
        }
        if (组合->实现方式 != 新方法实现方式::组合
            || 调用->实现方式 != 新方法实现方式::本能
            || 组合->作用域 != 调用->作用域 || 请求.顺序 < 0
            || 请求.组合方法节点 == 请求.调用方法节点) {
            结果.状态 = 新方法操作状态::方法类型不符;
            return 结果;
        }
        for (const auto& 步骤 : 组合->组合步骤组) {
            if (步骤.顺序 == 请求.顺序) {
                if (步骤.调用方法节点 == 请求.调用方法节点) {
                    结果.状态 = 新方法操作状态::已找到;
                    结果.节点 = 步骤.步骤节点;
                } else {
                    结果.状态 = 新方法操作状态::结构不一致;
                }
                return 结果;
            }
        }
        std::vector<稳定编码> 已建节点;
        std::vector<稳定编码> 已写字段;
        const auto 步骤 = 新建类型化节点(
            组合步骤节点类型, 已建节点, 已写字段);
        bool 完整 = 有效(步骤)
            && 写入节点字段(步骤, 步骤所属组合方法字段,
                请求.组合方法节点, 已写字段)
            && 写入节点字段(步骤, 步骤调用方法字段,
                请求.调用方法节点, 已写字段)
            && 写入I64字段(步骤, 顺序字段, 请求.顺序, 已写字段)
            && 写入节点字段(请求.组合方法节点, 方法组合步骤字段,
                步骤, 已写字段);
        if (完整 && !组合->组合入口步骤节点) {
            完整 = 写入节点字段(请求.组合方法节点,
                方法组合入口步骤字段, 步骤, 已写字段);
        }
        if (!完整) {
            回滚(已写字段, 已建节点);
            结果.状态 = 新方法操作状态::资源失败;
            return 结果;
        }
        结果.状态 = 新方法操作状态::已建立;
        结果.节点 = 步骤;
        return 结果;
    } catch (...) {
        结果.状态 = 新方法操作状态::资源失败;
        return 结果;
    }
}

新方法操作状态 新_方法类::设置组合入口步骤(
    稳定编码 组合方法节点,
    稳定编码 步骤节点) noexcept {
    try {
        std::lock_guard 锁(新方法互斥);
        const auto 方法 = 读取方法信息(组合方法节点);
        if (!方法) return 新方法操作状态::方法不存在;
        if (方法->实现方式 != 新方法实现方式::组合) {
            return 新方法操作状态::方法类型不符;
        }
        const auto 找到 = std::find_if(方法->组合步骤组.begin(),
            方法->组合步骤组.end(), [&](const 新方法组合步骤信息& 步骤) {
                return 步骤.步骤节点 == 步骤节点;
            });
        if (找到 == 方法->组合步骤组.end()) return 新方法操作状态::步骤不存在;
        if (方法->组合入口步骤节点 == 步骤节点) return 新方法操作状态::无变化;
        const auto 当前组 = 全局基础数据集.查询字段(
            组合方法节点, 方法组合入口步骤字段);
        if (当前组.size() != 1) return 新方法操作状态::结构不一致;
        return 全局基础数据集.修改字段节点(
                当前组.front().编码, 步骤节点)
            ? 新方法操作状态::已修改 : 新方法操作状态::资源失败;
    } catch (...) {
        return 新方法操作状态::资源失败;
    }
}

新方法结构节点结果 新_方法类::添加结果转移(
    const 新方法结果转移添加请求& 请求) noexcept {
    新方法结构节点结果 结果;
    try {
        std::lock_guard 锁(新方法互斥);
        const auto 组合 = 读取方法信息(请求.组合方法节点);
        if (!组合) {
            结果.状态 = 新方法操作状态::方法不存在;
            return 结果;
        }
        if (组合->实现方式 != 新方法实现方式::组合
            || !可选引用有效(请求.匹配结果概念节点)) {
            结果.状态 = 新方法操作状态::方法类型不符;
            return 结果;
        }
        const auto 当前步骤 = std::find_if(组合->组合步骤组.begin(),
            组合->组合步骤组.end(), [&](const 新方法组合步骤信息& 步骤) {
                return 步骤.步骤节点 == 请求.当前步骤节点;
            });
        const auto 下一步骤 = std::find_if(组合->组合步骤组.begin(),
            组合->组合步骤组.end(), [&](const 新方法组合步骤信息& 步骤) {
                return 步骤.步骤节点 == 请求.下一步骤节点;
            });
        if (当前步骤 == 组合->组合步骤组.end()
            || 下一步骤 == 组合->组合步骤组.end()) {
            结果.状态 = 新方法操作状态::步骤不存在;
            return 结果;
        }
        const auto 被调方法 = 读取方法信息(当前步骤->调用方法节点);
        if (!被调方法) {
            结果.状态 = 新方法操作状态::结构不一致;
            return 结果;
        }
        bool 结果属于方法 = false;
        for (const auto& 配对 : 被调方法->条件结果组) {
            if (配对.结果节点 == 请求.当前结果节点) {
                结果属于方法 = true;
                break;
            }
        }
        if (!结果属于方法) {
            结果.状态 = 新方法操作状态::结果节点不属于步骤方法;
            return 结果;
        }
        for (const auto& 转移 : 组合->结果转移组) {
            if (转移.当前步骤节点 == 请求.当前步骤节点
                && 转移.当前结果节点 == 请求.当前结果节点
                && 转移.匹配结果概念节点 == 请求.匹配结果概念节点) {
                if (转移.下一步骤节点 == 请求.下一步骤节点) {
                    结果.状态 = 新方法操作状态::已找到;
                    结果.节点 = 转移.转移节点;
                } else {
                    结果.状态 = 新方法操作状态::结构不一致;
                }
                return 结果;
            }
        }
        std::vector<稳定编码> 已建节点;
        std::vector<稳定编码> 已写字段;
        const auto 转移 = 新建类型化节点(
            结果转移节点类型, 已建节点, 已写字段);
        bool 完整 = 有效(转移)
            && 写入节点字段(转移, 转移所属组合方法字段,
                请求.组合方法节点, 已写字段)
            && 写入节点字段(转移, 转移当前步骤字段,
                请求.当前步骤节点, 已写字段)
            && 写入节点字段(转移, 转移当前结果字段,
                请求.当前结果节点, 已写字段)
            && 写入节点字段(转移, 转移下一步骤字段,
                请求.下一步骤节点, 已写字段);
        if (完整 && 请求.匹配结果概念节点) {
            完整 = 写入节点字段(转移, 转移匹配结果概念字段,
                *请求.匹配结果概念节点, 已写字段);
        }
        if (完整) 完整 = 写入节点字段(请求.组合方法节点,
            方法结果转移字段, 转移, 已写字段);
        if (!完整) {
            回滚(已写字段, 已建节点);
            结果.状态 = 新方法操作状态::资源失败;
            return 结果;
        }
        结果.状态 = 新方法操作状态::已建立;
        结果.节点 = 转移;
        return 结果;
    } catch (...) {
        结果.状态 = 新方法操作状态::资源失败;
        return 结果;
    }
}

新方法参数场景结果 新_方法类::建立参数场景(
    稳定编码 方法节点,
    std::vector<新方法参数角色绑定> 角色绑定组) const noexcept {
    新方法参数场景结果 结果;
    try {
        std::optional<新方法信息> 方法;
        {
            // 这里只在复制方法规格时持有本类锁；后续调用场景、存在、
            // 特征与概念服务时不跨服务持锁。
            std::lock_guard 锁(新方法互斥);
            方法 = 读取方法信息(方法节点);
        }
        if (!方法) {
            结果.状态 = 新方法操作状态::方法不存在;
            return 结果;
        }
        std::set<稳定编码> 已有角色;
        for (const auto& 绑定 : 角色绑定组) {
            if (!节点仍存在(绑定.参数角色节点)
                || !已有角色.insert(绑定.参数角色节点).second) {
                结果.状态 = 新方法操作状态::参数角色重复;
                return 结果;
            }
            if (绑定.世界场景节点
                && !场景服务_.是场景节点(*绑定.世界场景节点)) {
                结果.状态 = 新方法操作状态::参数引用失效;
                return 结果;
            }
            if (绑定.实际存在节点
                && !存在服务_.是存在节点(*绑定.实际存在节点)
                && !场景服务_.是场景节点(*绑定.实际存在节点)) {
                结果.状态 = 新方法操作状态::参数引用失效;
                return 结果;
            }
            if (绑定.世界场景节点 && 绑定.实际存在节点
                && *绑定.世界场景节点 != *绑定.实际存在节点
                && !场景服务_.存在属于场景范围(
                    *绑定.世界场景节点, *绑定.实际存在节点)) {
                结果.状态 = 新方法操作状态::参数引用失效;
                return 结果;
            }
            std::set<稳定编码> 已有特征;
            for (const auto& 特征 : 绑定.实际特征组) {
                if (!特征服务_.是特征节点(特征.特征节点)
                    || !已有特征.insert(特征.特征节点).second) {
                    结果.状态 = 新方法操作状态::参数引用失效;
                    return 结果;
                }
            }
        }
        if (角色绑定组.size() != 方法->参数规格组.size()) {
            结果.状态 = 新方法操作状态::参数角色缺失;
            return 结果;
        }
        for (const auto& 规格 : 方法->参数规格组) {
            const auto 绑定位置 = std::find_if(角色绑定组.begin(),
                角色绑定组.end(), [&](const 新方法参数角色绑定& 绑定) {
                    return 绑定.参数角色节点 == 规格.参数角色节点;
                });
            if (绑定位置 == 角色绑定组.end()) {
                结果.状态 = 新方法操作状态::参数角色缺失;
                return 结果;
            }
            const auto& 绑定 = *绑定位置;
            if (规格.要求场景 && !绑定.世界场景节点) {
                结果.状态 = 新方法操作状态::参数角色缺失;
                return 结果;
            }
            if (规格.存在概念节点) {
                const auto 实际节点 = 绑定.实际存在节点
                    ? 绑定.实际存在节点 : 绑定.世界场景节点;
                if (!实际节点) {
                    结果.状态 = 新方法操作状态::参数角色缺失;
                    return 结果;
                }
                std::optional<稳定编码> 实际概念;
                if (场景服务_.是场景节点(*实际节点)) {
                    const auto 场景 = 场景服务_.获取场景(*实际节点);
                    if (场景) 实际概念 = 场景->专属存在概念节点;
                } else {
                    实际概念 = 存在服务_.查询专属存在概念(*实际节点);
                }
                if (!实际概念 || !存在概念为或从属于(
                        *实际概念, *规格.存在概念节点, 存在概念服务_)) {
                    结果.状态 = 新方法操作状态::参数概念不相容;
                    return 结果;
                }
            }
            for (const auto& 特征规格 : 规格.特征规格组) {
                std::size_t 命中数量 = 0;
                for (const auto& 特征绑定 : 绑定.实际特征组) {
                    const auto 特征 = 特征服务_.获取特征(特征绑定.特征节点);
                    if (!特征) {
                        结果.状态 = 新方法操作状态::参数引用失效;
                        return 结果;
                    }
                    const bool 类型命中 = 特征概念为或从属于(
                        特征->特征概念节点,
                        特征规格.特征类型概念节点,
                        特征概念服务_);
                    const bool 值域命中 = !特征规格.值域概念节点
                        || 特征概念为或从属于(
                            特征->特征概念节点,
                            *特征规格.值域概念节点,
                            特征概念服务_);
                    if (类型命中 && 值域命中) ++命中数量;
                }
                if (命中数量 != 1) {
                    结果.状态 = 新方法操作状态::参数概念不相容;
                    return 结果;
                }
            }
        }
        std::sort(角色绑定组.begin(), 角色绑定组.end(),
            [](const 新方法参数角色绑定& 左,
               const 新方法参数角色绑定& 右) {
                return 左.参数角色节点 < 右.参数角色节点;
            });
        结果.参数场景 = std::shared_ptr<const 方法参数场景>(
            new 方法参数场景(方法节点, std::move(角色绑定组),
                特征服务_, 特征值服务_));
        结果.状态 = 新方法操作状态::已建立;
        return 结果;
    } catch (...) {
        结果.状态 = 新方法操作状态::资源失败;
        结果.参数场景.reset();
        return 结果;
    }
}

新方法本能调用结果 新_方法类::调用本能函数(
    稳定编码 方法节点,
    const 方法参数场景& 参数场景) const noexcept {
    新方法本能调用结果 结果;
    if (!有效(方法节点) || 参数场景.方法节点() != 方法节点) {
        结果.状态 = 新方法本能调用状态::参数场景不匹配;
        return 结果;
    }
    try {
        std::optional<新方法信息> 方法;
        {
            // 外部函数调用期间不得持有方法结构互斥。
            std::lock_guard 锁(新方法互斥);
            方法 = 读取方法信息(方法节点);
        }
        if (!方法) {
            结果.状态 = 新方法本能调用状态::方法不存在;
            return 结果;
        }
        if (方法->启用状态 != 新方法启用状态::启用) {
            结果.状态 = 新方法本能调用状态::方法停用;
            return 结果;
        }
        if (方法->实现方式 != 新方法实现方式::本能) {
            结果.状态 = 新方法本能调用状态::不是本能方法;
            return 结果;
        }
        if (!方法->本能函数登记名 || 方法->本能函数登记名->empty()) {
            结果.状态 = 新方法本能调用状态::函数未登记;
            return 结果;
        }
        const auto 函数 = 新_本能函数管理类::解析(*方法->本能函数登记名);
        if (!函数.函数) {
            结果.状态 = 函数.状态 == 新本能函数解析状态::内部错误
                ? 新方法本能调用状态::内部错误
                : 新方法本能调用状态::函数未登记;
            return 结果;
        }
        结果.本次条件结果对 = 函数.函数(参数场景);
        结果.状态 = 新方法本能调用状态::已调用;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 新方法本能调用状态::资源失败;
    } catch (...) {
        结果.状态 = 新方法本能调用状态::内部错误;
    }
    结果.本次条件结果对.reset();
    return 结果;
}

