inline bool 本能被动维护基础快照完整_v1(
    const 本能被动维护基础快照_v1& 快照) noexcept {
    if (!快照.本能根锚点.完整() || 快照.本次正式读回截止 == 0
        || 快照.本能根锚点.事实截止代次 > 快照.本次正式读回截止
        || !安全根定义与当前值快照完整_v1(快照.安全根)
        || 快照.安全根.本次正式读回截止 != 快照.本次正式读回截止
        || 快照.安全根.定义.自我 != 快照.本能根锚点.唯一自我
        || 快照.安全根.定义.安全根特征定义
            != 快照.本能根锚点.安全根特征定义
        || 快照.安全根.定义.安全根特征实例
            != 快照.本能根锚点.安全根特征实例
        || !L2特征值事实截止投影完整(
            快照.服务值当前值事实, 快照.本次正式读回截止)
        || 快照.服务值当前值事实.特征实例
            != 快照.本能根锚点.服务根特征实例
        || 快照.服务值当前值事实.生命周期.退出事实代次
        || !本能被动维护游标事实完整_v1(快照.游标)
        || 快照.游标.自我 != 快照.本能根锚点.唯一自我
        || 快照.游标.形成事实代次 > 快照.本次正式读回截止
        || 快照.当前服务值 < 0
        || 快照.当前服务值 > 本能根I64最大目标_v1)
        return false;
    const auto* 服务值 = std::get_if<std::int64_t>(
        &快照.服务值当前值事实.类型化不可变材料);
    if (!服务值 || *服务值 != 快照.当前服务值
        || 快照.时间观察.合同版本 != 完整秒边界读取合同版本
        || 快照.时间观察.运行代次 != 快照.游标.运行代次
        || 快照.时间观察.时间纪元身份 != 快照.游标.时间纪元身份
        || 快照.时间观察.上一已消费完整秒边界
            != 快照.游标.上一已维护完整秒边界
        || 快照.时间观察.时间源版本 != 快照.游标.时间源版本
        || 快照.时间观察.当前完整秒边界
            < 快照.时间观察.上一已消费完整秒边界)
        return false;
    if (快照.时间状态 == 完整秒边界读取状态::无新完整秒)
        return !快照.待维护区间
            && 快照.时间观察.当前完整秒边界
                == 快照.时间观察.上一已消费完整秒边界;
    if (快照.时间状态 != 完整秒边界读取状态::已读取
        || !快照.待维护区间)
        return false;
    const auto& 区间 = *快照.待维护区间;
    if (快照.时间观察.上一已消费完整秒边界
            == (std::numeric_limits<std::int64_t>::max)())
        return false;
    const auto 差 = 快照.时间观察.当前完整秒边界
        - 快照.时间观察.上一已消费完整秒边界;
    return 差 > 0
        && 区间.首个未消费完整秒边界
            == 快照.时间观察.上一已消费完整秒边界 + 1
        && 区间.最后完整秒边界 == 快照.时间观察.当前完整秒边界
        && 区间.完整秒数量 == static_cast<std::uint64_t>(差);
}

