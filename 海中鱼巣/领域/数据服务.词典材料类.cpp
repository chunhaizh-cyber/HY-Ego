新词典材料提交结果 提交共同准备(共同准备& 准备, 新共同发表回执接收接口& 参与者) {
    try { 加入新字段引用身份(准备.请求); }
    catch (材料状态 状态) {
        if (状态 == 材料状态::资源失败) return {追加状态::资源失败, {}};
        if (状态 == 材料状态::未找到) return {追加状态::引用不存在, {}};
        throw;
    }
    const auto 封存 = 全局基础数据集.封存原子追加片段(准备.请求);
    if (封存.状态 != 追加状态::已完成) return {封存.状态, {}};
    if (!封存.片段) 材料故障(L"材料封存成功但缺少片段");
    准备.片段 = *封存.片段;
    const auto 发布 = 全局基础数据集.原子追加封存片段组({*准备.片段});
    if (发布.状态 != 追加状态::已完成) return {发布.状态, {}};
    if (发布.片段回执组.size() != 1) 材料故障(L"材料共同发表缺少回执");
    // 下列三步均无分配、无日志、无新快照：成功后首先登记双方回执。
    准备.回执 = 发布.片段回执组.front();
    参与者.登记共同发表回执(*准备.回执);
    return {追加状态::已完成, 准备.回执};
}
