新词典材料操作状态 词典材料类::释放材料闭包(稳定编码 Q) noexcept {
    for (;;) {
        try {
            auto 准备 = 准备材料闭包退出(Q);
            if (!准备.准备) return 准备.状态;
            const auto 片段 = 封存材料退出(*准备.准备);
            基础片段组合结果 发布;
            {
                std::lock_guard 锁(材料互斥);
                发布 = 全局基础数据集.原子追加封存片段组({片段});
                if (发布.状态 == 追加状态::已完成) {
                    if (发布.片段回执组.size() != 1) 材料故障(L"材料退出缺少回执");
                    登记材料退出发表(*准备.准备, 发布.片段回执组.front());
                }
            }
            if (发布.状态 == 追加状态::已完成) {
                完成材料退出(*准备.准备);
                return 材料状态::已完成;
            }
            取消材料退出(*准备.准备);
            if (发布.状态 == 追加状态::引用仍存在) return 材料状态::引用仍存在;
            if (发布.状态 == 追加状态::资源失败) return 材料状态::资源失败;
            if (发布.状态 != 追加状态::预期不符 && 发布.状态 != 追加状态::节点不存在
                && 发布.状态 != 追加状态::引用不存在) 材料故障(L"材料闭包退出请求不合法");
        } catch (材料状态 状态) { return 状态; }
        catch (const std::bad_alloc&) { return 材料状态::资源失败; }
        catch (const std::length_error&) { return 材料状态::资源失败; }
        catch (...) { 材料故障(L"材料闭包退出异常"); }
        std::this_thread::yield();
    }
}

