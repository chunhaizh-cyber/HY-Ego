using 本族快照组 = std::map<稳定编码, 基础联合节点快照>;
bool 含类型(const 基础节点结构& 节点, 稳定编码 键, 稳定编码 类型) {
    const auto f = std::find_if(节点.字段组.begin(), 节点.字段组.end(),
        [&](const auto& x) { return x.字段节点 == 键; });
    return f != 节点.字段组.end() && 解码字段<稳定编码>(*f) == 类型;
}
// 每次消费同一次L1联合读取的当前材料。首读只发现闭包位置，绝不证明旧快照未变。
// 模拟共同退出在外部提交，故单靠本族互斥不足以保护跨次读取。
本族快照组 读取本族闭包(稳定编码 起点, bool 展开组织, bool 展开义项, bool 删除宿主 = false) {
    std::set<稳定编码> 节点{起点};
    for (;;) {
        const auto 读 = 全局基础数据集.查询节点组完整结构({节点.begin(), 节点.end()});
        if (读.状态 == 基础结构操作状态::资源失败) throw 材料状态::资源失败;
        if (读.状态 == 基础结构操作状态::节点不存在) throw 材料状态::未找到;
        if (读.状态 != 基础结构操作状态::已完成) 材料故障(L"材料闭包当前读取失败");
        本族快照组 当前;
        for (const auto& 项 : 读.节点组) if (项.快照) 当前.emplace(项.查询节点, *项.快照);
        if (!当前.contains(起点)) throw 材料状态::未找到;
        std::set<稳定编码> 必需{起点}, 处理过;
        bool 需要扩展 = false;
        for (auto i = 必需.begin(); i != 必需.end(); ) {
            const auto n = *i;
            if (处理过.contains(n)) { ++i; continue; }
            处理过.insert(n);
            const auto it = 当前.find(n);
            if (it == 当前.end()) {
                if (节点.contains(n)) 材料故障(L"同次L1读取中材料仍引用缺失节点");
                需要扩展 = true;
                ++i; continue;
            }
            const auto& 快照 = it->second;
            const bool 是O = 含类型(快照.结构, 组织类型字段, 组织类型);
            const bool 是Q = 含类型(快照.结构, 材料类型字段, 材料类型);
            const bool 是I = 含类型(快照.结构, 内部义项类型字段, 义项类型);
            if (是Q) for (const auto& 边 : 读取组织材料边(快照, false)) 必需.insert(边.源节点);
            if ((n == 技术根 && n == 起点 && 展开组织)
                || (是O && 展开组织 && 起点 != 技术根) || (是Q && 展开义项))
                for (const auto& 边 : 读取组织边(快照, true)) 必需.insert(边.目标节点);
            if (删除宿主 && (是Q || 是I || (是O && n == 起点 && 展开组织)))
                for (const auto& f : 快照.结构.字段组)
                    if (const auto* 引用 = std::get_if<稳定编码>(&f.内容)) 必需.insert(*引用);
            // 新插入的节点可能比当前编码小；从头继续，仅处理尚未见过的位置。
            i = 必需.begin();
        }
        if (!需要扩展) return 当前;
        节点.insert(必需.begin(), 必需.end());
    }
}
