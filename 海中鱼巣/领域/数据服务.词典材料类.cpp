基础联合节点快照 读取快照(稳定编码 节点) {
    const auto 读 = 全局基础数据集.查询节点组完整结构({节点});
    if (读.状态 == 基础结构操作状态::资源失败) throw 材料状态::资源失败;
    if (读.状态 == 基础结构操作状态::节点不存在) throw 材料状态::未找到;
    if (读.状态 != 基础结构操作状态::已完成 || 读.节点组.size() != 1)
        材料故障(L"材料当前结构读取失败");
    if (!读.节点组[0].快照) throw 材料状态::未找到;
    return *读.节点组[0].快照;
}
const 基础字段关系& 读取字段项(const 基础节点结构& 结构, 稳定编码 字段) {
    const 基础字段关系* 项 = nullptr;
    for (const auto& f : 结构.字段组) if (f.字段节点 == 字段) {
        if (项) 材料故障(L"材料必需字段重复");
        项 = &f;
    }
    if (!项) 材料故障(L"材料必需字段缺失");
    return *项;
}
template<class T> T 解码字段(const 基础字段关系& 字段) {
    if constexpr (std::is_same_v<T, 稳定编码>) {
        const auto* 值 = std::get_if<稳定编码>(&字段.内容);
        if (!值 || !有效(*值)) 材料故障(L"材料节点引用字段损坏");
        return *值;
    } else {
        const auto* 内容 = std::get_if<基础值>(&字段.内容);
        if (!内容) 材料故障(L"材料直接值字段损坏");
        if constexpr (std::is_same_v<T, std::uint64_t>) {
            const auto* 值 = std::get_if<std::vector<std::uint64_t>>(&内容->材料);
            if (!值 || 值->size() != 1) 材料故障(L"材料来源数值字段损坏");
            return 值->front();
        } else {
            const auto* 值 = std::get_if<T>(&内容->材料);
            if (!值) 材料故障(L"材料文本字段损坏");
            return *值;
        }
    }
}
template<class T> 基础组内字段内容 编码字段(const T& 值) {
    if constexpr (std::is_same_v<T, 稳定编码>) return 值;
    else if constexpr (std::is_same_v<T, std::uint64_t>) return 基础值{std::vector<std::uint64_t>{值}};
    else return 基础值{值};
}
void 新增字段(基础组内新节点& 节点, 稳定编码 字段, 基础组内字段内容 值) {
    节点.字段组.push_back({字段, std::move(值)});
}
void 修改字段准备(基础组内新节点& 节点, 稳定编码 字段, 基础组内字段内容 值) {
    const auto p = std::find_if(节点.字段组.begin(), 节点.字段组.end(),
        [&](const auto& f) { return f.字段节点 == 字段; });
    if (p == 节点.字段组.end()) 材料故障(L"修改不存在的未封存材料字段");
    p->内容 = std::move(值);
}
void 删除字段构造(基础节点组追加请求& 请求, const 基础节点结构& 节点, 稳定编码 字段) {
    请求.删除字段关系组.push_back(读取字段项(节点, 字段).编码);
}
