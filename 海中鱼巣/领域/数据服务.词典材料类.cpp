std::vector<基础外部关系> 读取有序义项边(const 基础联合节点快照& 当前) {
    auto 边组 = 读取材料义项边(当前);
    std::sort(边组.begin(), 边组.end(), [](const auto& a, const auto& b) {
        return a.角色或顺序 < b.角色或顺序;
    });
    if (边组.empty()) 材料故障(L"正式材料没有义项");
    for (std::size_t i = 0; i < 边组.size(); ++i)
        if (边组[i].角色或顺序 != static_cast<std::int64_t>(i + 1))
            材料故障(L"正式材料义项顺序不连续");
    return 边组;
}
新词典材料信息 读取材料本体(材料身份 身份) {
    const auto 全组 = 读取本族闭包(身份.节点, false, true);
    const auto& 当前 = 全组.at(身份.节点);
    auto 结果 = 解码材料头(当前, 全组);
    for (const auto& 边 : 读取有序义项边(当前))
        结果.义项组.push_back(读取内部义项({边.目标节点}, 身份.节点,
            static_cast<std::size_t>(边.角色或顺序), 全组.at(边.目标节点)));
    return 结果;
}
void 补正文(新词典材料信息& 信息, 新_特征值类& 服务) {
    for (auto& 项 : 信息.义项组) {
        const auto 正文 = 服务.获取特征值(项.正文材料);
        if (!正文) 材料故障(L"材料正文不能读取");
        const auto* 文本 = std::get_if<std::string>(&正文->材料);
        if (正文->物理类型 != 材料物理类型::UTF8字符串 || !文本)
            材料故障(L"材料正文类型损坏");
        项.内容.汉语释义 = *文本;
    }
}
std::optional<稳定编码> 查当前材料(const 基础联合节点快照& O, const 新词典外设来源标识& 来源, const 本族快照组& 全组) {
    (void)解码组织(O);
    // 必须扫描这同一份O成员，随后以它作为L1宿主；不能扫描后另读O作为提交依据。
    const 材料键 键{O.结构.节点.编码, 来源.场景, 来源.查询记录};
    const auto 成员 = 读取组织材料边(O);
    const auto 缓存 = 材料索引.find(键);
    if (缓存 != 材料索引.end()) {
        if (std::any_of(成员.begin(), 成员.end(), [&](const auto& 边) { return 边.目标节点 == 缓存->second; })) {
            const auto& 当前 = 全组.at(缓存->second);
            if (读取材料外设场景标识({当前.结构}) == 来源.场景
                && 读取材料外设查询记录标识({当前.结构}) == 来源.查询记录) return 缓存->second;
        }
        材料索引.erase(缓存);
    }
    std::optional<稳定编码> 找到;
    for (const auto& 边 : 成员) {
        if (边.角色或顺序 != 0) 材料故障(L"材料组织成员角色损坏");
        const auto& 当前 = 全组.at(边.目标节点);
        const 材料字段投影 视图{当前.结构};
        if (读取材料类型(视图) != 材料类型) 材料故障(L"材料组织含非材料节点");
        if (读取材料外设场景标识(视图) == 来源.场景
            && 读取材料外设查询记录标识(视图) == 来源.查询记录) {
            if (找到) 材料故障(L"同一材料来源键重复");
            找到 = 边.目标节点;
        }
    }
    if (找到) 材料索引.emplace(键, *找到);
    return 找到;
}
bool 输入完整(const 新词典内部材料建立请求& 输入) {
    return 有效(输入.内部组织) && 有效(输入.内部词典来源) && 有效(输入.释义语言)
        && 有效(输入.查询键.词条语言) && 有效(输入.查询键.规范化合同)
        && !输入.查询键.原规范化词面.empty() && !输入.查询键.查询词面.empty()
        && !输入.查询键.源语种.empty() && !输入.可信批次标识.empty()
        && !输入.原包标识.empty() && 输入.外设来源.场景 && 输入.外设来源.查询记录
        && !输入.义项组.empty();
}
std::vector<稳定编码> 保存正文组(const 新词典内部材料建立请求& 输入, 新_特征值类& 值服务) {
    if (!输入完整(输入)) throw 材料状态::输入拒绝;
    std::vector<稳定编码> 结果;
    结果.reserve(输入.义项组.size());
    for (const auto& 项 : 输入.义项组) {
        if (!项.外设消息标识) throw 材料状态::输入拒绝;
        const auto V = 值服务.保存或取得特征值(材料物理类型::UTF8字符串, 新特征值材料{项.内容.汉语释义});
        if (!有效(V)) throw 材料状态::资源失败;
        结果.push_back(V);
    }
    return 结果;
}
新同组材料端点 构造材料候选(基础节点组追加请求& 请求,
    const 新词典内部材料建立请求& 输入, const std::vector<稳定编码>& 正文组,
    const 基础联合节点快照& O, const 本族快照组& 全组) {
    const auto 已有 = 查当前材料(O, 输入.外设来源, 全组);
    if (已有) {
        // 复用也要给本次结果持有；不把“存在Q”当作“本次已经采用”。
        return {*已有, 输入.内部组织, 正式材料范围, 请求.新节点组.size()};
    }
    加入联合宿主(请求, O);
    const auto q = 请求.新节点组.size();
    请求.新节点组.push_back(std::move(构造新增材料(输入).节点));
    构造新增组织材料边(请求, 输入.内部组织, 基础组内节点引用{q});
    for (std::size_t i = 0; i < 输入.义项组.size(); ++i) {
        const auto slot = 请求.新节点组.size();
        请求.新节点组.push_back(std::move(构造新增内部义项(输入.义项组[i], 正文组[i]).节点));
        构造新增材料义项边(请求, 基础组内节点引用{q}, 基础组内节点引用{slot},
            static_cast<std::int64_t>(i + 1));
    }
    return {基础组内节点引用{q}, 输入.内部组织, 正式材料范围, 请求.新节点组.size()};
}
void 加入新字段引用身份(基础节点组追加请求& 请求) {
    std::set<稳定编码> 引用;
    const auto 收集 = [&](const 基础组内字段内容& 内容) {
        if (const auto* p = std::get_if<稳定编码>(&内容)) 引用.insert(*p);
    };
    for (const auto& n : 请求.新节点组) for (const auto& f : n.字段组) 收集(f.内容);
    for (const auto& f : 请求.追加字段组) 收集(f.内容);
    for (const auto& n : 请求.预期联合节点组) 引用.erase(n.结构.节点.编码);
    for (const auto& n : 请求.只读预期.节点组) 引用.erase(n.编码);
    if (引用.empty()) return;
    const auto 读 = 全局基础数据集.查询节点组完整结构({引用.begin(), 引用.end()});
    if (读.状态 == 基础结构操作状态::资源失败) throw 材料状态::资源失败;
    if (读.状态 == 基础结构操作状态::节点不存在) throw 材料状态::未找到;
    if (读.状态 != 基础结构操作状态::已完成) 材料故障(L"新材料字段引用身份读取失败");
    for (const auto& 项 : 读.节点组) {
        if (!项.快照) throw 材料状态::未找到;
        请求.只读预期.节点组.push_back(项.快照->结构.节点);
    }
}
bool 构造含材料引用(const 基础节点组追加请求& 构造, const 新同组材料端点& 端点) {
    const auto 命中 = [&](const 基础组内字段内容& 内容) {
        if (const auto* q = std::get_if<稳定编码>(&端点.材料定位)) {
            const auto* v = std::get_if<稳定编码>(&内容);
            return v && *v == *q;
        }
        const auto* v = std::get_if<基础组内节点引用>(&内容);
        return v && v->索引 == std::get<基础组内节点引用>(端点.材料定位).索引;
    };
    for (const auto& n : 构造.新节点组) for (const auto& f : n.字段组) if (命中(f.内容)) return true;
    for (const auto& f : 构造.追加字段组) if (命中(f.内容)) return true;
    for (const auto& f : 构造.替换字段组)
        if (std::visit([&](const auto& v) { return 命中(基础组内字段内容{v}); }, f.新内容)) return true;
    return false;
}
// 参与者已使用合并后的绝对槽位。合并只移动材料，不再次偏移组内引用。
void 合并参与构造(基础节点组追加请求& 目标, 基础节点组追加请求 来源) {
    const auto 追加 = [](auto& a, auto& b) {
        a.insert(a.end(), std::make_move_iterator(b.begin()), std::make_move_iterator(b.end()));
    };
    追加(目标.新节点组, 来源.新节点组);
    追加(目标.追加字段组, 来源.追加字段组);
    追加(目标.预期既有节点组, 来源.预期既有节点组);
    // 保留各参与者的真实依据；重复宿主由L1规范化，冲突时零发表重读。
    追加(目标.预期联合节点组, 来源.预期联合节点组);
    追加(目标.容许新增入向预期组, 来源.容许新增入向预期组);
    追加(目标.替换字段组, 来源.替换字段组);
    追加(目标.追加外部关系组, 来源.追加外部关系组);
    追加(目标.删除字段关系组, 来源.删除字段关系组);
    追加(目标.只读预期.节点组, 来源.只读预期.节点组);
    追加(目标.只读预期.字段集合组, 来源.只读预期.字段集合组);
    追加(目标.只读预期.外部关系集合组, 来源.只读预期.外部关系集合组);
    追加(目标.删除节点组, 来源.删除节点组);
    追加(目标.删除外部关系组, 来源.删除外部关系组);
}
