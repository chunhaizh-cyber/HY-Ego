新_二次特征类::新_二次特征类(
    新_特征类& 特征服务,
    概念_二次特征类& 二次特征概念服务) noexcept
    : 特征服务_(特征服务), 二次特征概念服务_(二次特征概念服务) {}

新二次特征计算结果 新_二次特征类::计算(
    const 新二次特征计算请求& 请求) const noexcept {
    新二次特征计算结果 结果;
    try {
        auto 类型节点 = 请求.二次特征类型概念节点;
        if (!有效(类型节点)) {
            二次特征概念建立结果 建立;
            if (请求.概念定义) {
                建立 = 二次特征概念服务_.建立或取得二次特征概念(
                    *请求.概念定义);
            } else {
                const auto 输入定义 = 形成准确输入定义(
                    请求.左输入, 请求.右输入);
                if (!输入定义) {
                    结果.状态 = 新二次特征计算状态::输入种类不匹配;
                    return 结果;
                }
                二次特征算法 算法;
                if (std::holds_alternative<二次特征强时间输入>(请求.左输入)) {
                    算法 = 二次特征算法::强时间间隔;
                } else if (std::holds_alternative<二次特征状态出现时间输入>(
                    请求.左输入)) {
                    const auto& 左 = std::get<二次特征状态出现时间输入>(
                        请求.左输入);
                    const auto& 右 = std::get<二次特征状态出现时间输入>(
                        请求.右输入);
                    if (左.特征类型概念节点 == 右.特征类型概念节点) {
                        结果.状态 = 新二次特征计算状态::特征类型不匹配;
                        return 结果;
                    }
                    算法 = 二次特征算法::状态出现时间间隔;
                } else {
                    const auto& 左 = std::get<二次特征准确特征输入>(请求.左输入);
                    const auto& 右 = std::get<二次特征准确特征输入>(请求.右输入);
                    if (左.特征类型概念节点 != 右.特征类型概念节点) {
                        结果.状态 = 新二次特征计算状态::特征类型不匹配;
                        return 结果;
                    }
                    const auto 比较 = 特征服务_.按概念比较特征值(
                        左.特征类型概念节点, 左.值, 右.值);
                    if (比较.状态 != 新特征比较状态::已完成
                        || !比较.数值类型 || !比较.比较值) {
                        结果.状态 = 映射特征比较状态(比较.状态);
                        return 结果;
                    }
                    算法 = *比较.数值类型 == 新特征比较数值类型::有向差值
                        ? 二次特征算法::有向特征差值
                        : 二次特征算法::特征材料相似度;
                }
                建立 = 二次特征概念服务_.建立或取得默认二次特征概念(
                    算法, *输入定义);
            }
            if ((建立.状态 != 二次特征概念操作状态::已建立
                    && 建立.状态 != 二次特征概念操作状态::已复用)
                || !建立.概念节点) {
                结果.状态 = 建立.状态 == 二次特征概念操作状态::资源失败
                    ? 新二次特征计算状态::资源失败
                    : 新二次特征计算状态::概念不存在;
                return 结果;
            }
            类型节点 = *建立.概念节点;
        }
        const auto 概念 = 二次特征概念服务_.获取二次特征概念(
            类型节点);
        if (!概念) {
            结果.状态 = 新二次特征计算状态::概念不存在;
            return 结果;
        }
        if (概念->二次特征类型根节点 != 类型节点
            || 概念->输入定义组.size() != 2) {
            结果.状态 = 新二次特征计算状态::派生定义不完整;
            return 结果;
        }
        if (!输入符合定义(请求.左输入, 概念->输入定义组[0])
            || !输入符合定义(请求.右输入, 概念->输入定义组[1])) {
            结果.状态 = 新二次特征计算状态::输入种类不匹配;
            return 结果;
        }

        std::optional<std::int64_t> 准确结果;
        if (概念->算法 == 二次特征算法::强时间间隔) {
            const auto* 左 = std::get_if<二次特征强时间输入>(&请求.左输入);
            const auto* 右 = std::get_if<二次特征强时间输入>(&请求.右输入);
            if (!左 || !右) {
                结果.状态 = 新二次特征计算状态::输入种类不匹配;
                return 结果;
            }
            准确结果 = 计算饱和时间间隔(左->纳秒, 右->纳秒);
        } else if (概念->算法 == 二次特征算法::状态出现时间间隔) {
            const auto* 左 =
                std::get_if<二次特征状态出现时间输入>(&请求.左输入);
            const auto* 右 =
                std::get_if<二次特征状态出现时间输入>(&请求.右输入);
            if (!左 || !右
                || !概念->输入定义组[0].特征类型概念节点
                || !概念->输入定义组[1].特征类型概念节点
                || 左->特征类型概念节点
                    != *概念->输入定义组[0].特征类型概念节点
                || 右->特征类型概念节点
                    != *概念->输入定义组[1].特征类型概念节点
                || 左->特征类型概念节点 == 右->特征类型概念节点) {
                结果.状态 = 新二次特征计算状态::特征类型不匹配;
                return 结果;
            }
            准确结果 = 计算饱和时间间隔(左->纳秒, 右->纳秒);
        } else {
            const auto* 左 = std::get_if<二次特征准确特征输入>(&请求.左输入);
            const auto* 右 = std::get_if<二次特征准确特征输入>(&请求.右输入);
            if (!左 || !右) {
                结果.状态 = 新二次特征计算状态::输入种类不匹配;
                return 结果;
            }
            if (!概念->输入定义组[0].特征类型概念节点
                || !概念->输入定义组[1].特征类型概念节点
                || 左->特征类型概念节点
                    != *概念->输入定义组[0].特征类型概念节点
                || 右->特征类型概念节点
                    != *概念->输入定义组[1].特征类型概念节点) {
                结果.状态 = 新二次特征计算状态::特征类型不匹配;
                return 结果;
            }
            if (左->特征类型概念节点 != 右->特征类型概念节点) {
                结果.状态 = 新二次特征计算状态::特征类型不匹配;
                return 结果;
            }
            const auto 比较 = 特征服务_.按概念比较特征值(
                左->特征类型概念节点, 左->值, 右->值);
            if (比较.状态 != 新特征比较状态::已完成
                || !比较.数值类型 || !比较.比较值) {
                结果.状态 = 映射特征比较状态(比较.状态);
                return 结果;
            }
            const auto 期望数值类型 = 概念->算法 == 二次特征算法::有向特征差值
                ? 新特征比较数值类型::有向差值
                : 新特征比较数值类型::相似度;
            if (*比较.数值类型 != 期望数值类型) {
                结果.状态 = 新二次特征计算状态::规则不支持;
                return 结果;
            }
            if (*比较.比较值 < 0
                && 期望数值类型 == 新特征比较数值类型::相似度) {
                结果.状态 = 新二次特征计算状态::规则不支持;
                return 结果;
            }
            准确结果 = *比较.比较值;
        }

        const auto 值域 = 二次特征概念服务_.建立或取得准确结果概念(
            类型节点, *准确结果);
        if (值域.状态 != 二次特征概念操作状态::已找到
            || !值域.概念节点) {
            结果.状态 = 值域.状态 == 二次特征概念操作状态::未找到
                ? 新二次特征计算状态::结果不在值域
                : 新二次特征计算状态::结构不一致;
            return 结果;
        }

        结果.状态 = 新二次特征计算状态::已完成;
        结果.二次特征类型概念节点 = 类型节点;
        结果.结果值域概念节点 = *值域.概念节点;
        结果.结果值 = *准确结果;
        结果.左来源 = 请求.左输入;
        结果.右来源 = 请求.右输入;
        return 结果;
    } catch (...) {
        结果.状态 = 新二次特征计算状态::资源失败;
        return 结果;
    }
}

新二次特征计算结果 新_二次特征类::比较状态出现时间(
    const 二次特征状态出现时间输入& 前,
    const 二次特征状态出现时间输入& 后) const noexcept {
    新二次特征计算结果 结果;
    if (!有效(前.来源状态节点) || !有效(后.来源状态节点)
        || 前.来源状态节点 == 后.来源状态节点
        || !有效(前.特征类型概念节点)
        || !有效(后.特征类型概念节点)
        || 前.特征类型概念节点 == 后.特征类型概念节点) {
        return 结果;
    }
    新二次特征计算请求 请求;
    请求.左输入 = 前;
    请求.右输入 = 后;
    return 计算(请求);
}

新二次跨类型变化比较结果 新_二次特征类::比较跨特征类型变化(
    const 新二次跨类型变化比较请求& 请求) const noexcept {
    新二次跨类型变化比较结果 结果;
    try {
        if (请求.参照变化.valueless_by_exception()
            || 请求.目标变化.valueless_by_exception()) {
            return 结果;
        }
        if (是同一输入类型(请求.参照变化, 请求.目标变化)) {
            结果.状态 = 新二次跨类型变化比较状态::不是跨类型比较;
            return 结果;
        }

        const auto 参照 = 计算变化量(请求.参照变化, 特征服务_);
        if (参照.状态 != 新二次跨类型变化比较状态::已完成
            || !参照.变化量) {
            结果.状态 = 参照.状态;
            return 结果;
        }
        const auto 目标 = 计算变化量(请求.目标变化, 特征服务_);
        if (目标.状态 != 新二次跨类型变化比较状态::已完成
            || !目标.变化量) {
            结果.状态 = 目标.状态;
            return 结果;
        }
        结果.参照原始变化量 = *参照.变化量;
        结果.目标原始变化量 = *目标.变化量;
        结果.参照来源 = 请求.参照变化;
        结果.目标来源 = 请求.目标变化;
        if (*参照.变化量 == 0) {
            结果.状态 = 新二次跨类型变化比较状态::参照无变化;
            return 结果;
        }

        const auto 最小 = (std::numeric_limits<std::int64_t>::min)();
        const auto 最大 = (std::numeric_limits<std::int64_t>::max)();
        if (*目标.变化量 == 最小 && *参照.变化量 == -1) {
            结果.单位参照目标变化量 = 最大;
            结果.归一化余数 = 0;
            结果.结果已饱和 = true;
        } else {
            结果.单位参照目标变化量 =
                *目标.变化量 / *参照.变化量;
            结果.归一化余数 =
                *目标.变化量 % *参照.变化量;
        }
        const std::vector<二次特征概念输入定义> 输入定义组{
            形成变化输入定义(请求.参照变化, 0,
                二次特征输入角色::参照变化),
            形成变化输入定义(请求.目标变化, 1,
                二次特征输入角色::目标变化)};
        const auto 概念 = 二次特征概念服务_.建立或取得默认二次特征概念(
            二次特征算法::跨特征类型单位变化,
            输入定义组, 请求.参照特征概念节点);
        if ((概念.状态 != 二次特征概念操作状态::已建立
                && 概念.状态 != 二次特征概念操作状态::已复用)
            || !概念.概念节点) {
            结果.状态 = 概念.状态 == 二次特征概念操作状态::资源失败
                ? 新二次跨类型变化比较状态::资源失败
                : 新二次跨类型变化比较状态::概念不存在;
            return 结果;
        }
        const auto 结果概念 = 二次特征概念服务_.建立或取得准确结果概念(
            *概念.概念节点, *结果.单位参照目标变化量);
        if (结果概念.状态 != 二次特征概念操作状态::已找到
            || !结果概念.概念节点) {
            结果.状态 = 结果概念.状态 == 二次特征概念操作状态::资源失败
                ? 新二次跨类型变化比较状态::资源失败
                : 新二次跨类型变化比较状态::结构不一致;
            return 结果;
        }
        结果.二次特征类型概念节点 = *概念.概念节点;
        结果.结果值域概念节点 = *结果概念.概念节点;
        结果.状态 = 新二次跨类型变化比较状态::已完成;
        return 结果;
    } catch (...) {
        结果.状态 = 新二次跨类型变化比较状态::资源失败;
        结果.参照原始变化量.reset();
        结果.目标原始变化量.reset();
        结果.单位参照目标变化量.reset();
        结果.归一化余数.reset();
        结果.二次特征类型概念节点.reset();
        结果.结果值域概念节点.reset();
        结果.参照来源.reset();
        结果.目标来源.reset();
        结果.结果已饱和 = false;
        return 结果;
    }
}

