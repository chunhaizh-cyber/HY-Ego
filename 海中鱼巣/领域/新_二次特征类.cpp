新二次特征计算状态 映射特征比较状态(新特征比较状态 状态) noexcept {
    switch (状态) {
    case 新特征比较状态::已完成:
        return 新二次特征计算状态::已完成;
    case 新特征比较状态::入口拒绝:
        return 新二次特征计算状态::入口拒绝;
    case 新特征比较状态::特征不存在:
    case 新特征比较状态::概念不存在:
    case 新特征比较状态::概念不相容:
        return 新二次特征计算状态::概念不存在;
    case 新特征比较状态::单位不相容:
        return 新二次特征计算状态::单位不相容;
    case 新特征比较状态::材料类型不相容:
    case 新特征比较状态::值不存在:
        return 新二次特征计算状态::材料类型不相容;
    case 新特征比较状态::规则不支持:
        return 新二次特征计算状态::规则不支持;
    case 新特征比较状态::结构不一致:
        return 新二次特征计算状态::结构不一致;
    case 新特征比较状态::资源失败:
        return 新二次特征计算状态::资源失败;
    }
    return 新二次特征计算状态::结构不一致;
}

std::int64_t 计算饱和时间间隔(
    std::int64_t 左纳秒, std::int64_t 右纳秒) noexcept {
    const auto 最小 = (std::numeric_limits<std::int64_t>::min)();
    const auto 最大 = (std::numeric_limits<std::int64_t>::max)();
    if (左纳秒 < 0 && 右纳秒 > 最大 + 左纳秒) return 最大;
    if (左纳秒 > 0 && 右纳秒 < 最小 + 左纳秒) return 最小;
    return 右纳秒 - 左纳秒;
}

bool 输入符合定义(
    const 二次特征准确输入& 输入,
    const 二次特征概念输入定义& 定义) noexcept {
    if (定义.来源种类 == 二次特征输入来源种类::特征准确值) {
        const auto* 特征 = std::get_if<二次特征准确特征输入>(&输入);
        return 特征 && 定义.特征类型概念节点;
    }
    if (定义.来源种类 == 二次特征输入来源种类::强时间) {
        return std::holds_alternative<二次特征强时间输入>(输入)
            && !定义.特征类型概念节点;
    }
    if (定义.来源种类 == 二次特征输入来源种类::状态出现时间) {
        const auto* 状态时间 =
            std::get_if<二次特征状态出现时间输入>(&输入);
        return 状态时间 && 定义.特征类型概念节点
            && 状态时间->特征类型概念节点
                == *定义.特征类型概念节点
            && 有效(状态时间->来源状态节点);
    }
    return false;
}

std::optional<std::vector<二次特征概念输入定义>> 形成准确输入定义(
    const 二次特征准确输入& 左,
    const 二次特征准确输入& 右) {
    if (const auto* 左特征 = std::get_if<二次特征准确特征输入>(&左)) {
        const auto* 右特征 = std::get_if<二次特征准确特征输入>(&右);
        if (!右特征 || !有效(左特征->特征类型概念节点)
            || !有效(右特征->特征类型概念节点)) return std::nullopt;
        return std::vector<二次特征概念输入定义>{
            {0, 二次特征输入角色::左输入,
                二次特征输入来源种类::特征准确值,
                左特征->特征类型概念节点},
            {1, 二次特征输入角色::右输入,
                二次特征输入来源种类::特征准确值,
                右特征->特征类型概念节点}};
    }
    if (std::holds_alternative<二次特征强时间输入>(左)
        && std::holds_alternative<二次特征强时间输入>(右)) {
        return std::vector<二次特征概念输入定义>{
            {0, 二次特征输入角色::左输入,
                二次特征输入来源种类::强时间, std::nullopt},
            {1, 二次特征输入角色::右输入,
                二次特征输入来源种类::强时间, std::nullopt}};
    }
    const auto* 左状态时间 = std::get_if<二次特征状态出现时间输入>(&左);
    const auto* 右状态时间 = std::get_if<二次特征状态出现时间输入>(&右);
    if (!左状态时间 || !右状态时间
        || !有效(左状态时间->来源状态节点)
        || !有效(右状态时间->来源状态节点)
        || !有效(左状态时间->特征类型概念节点)
        || !有效(右状态时间->特征类型概念节点)) {
        return std::nullopt;
    }
    return std::vector<二次特征概念输入定义>{
        {0, 二次特征输入角色::左输入,
            二次特征输入来源种类::状态出现时间,
            左状态时间->特征类型概念节点},
        {1, 二次特征输入角色::右输入,
            二次特征输入来源种类::状态出现时间,
            右状态时间->特征类型概念节点}};
}

二次特征概念输入定义 形成变化输入定义(
    const 二次特征变化输入& 输入,
    std::int64_t 顺序,
    二次特征输入角色 角色) {
    二次特征概念输入定义 定义;
    定义.顺序 = 顺序;
    定义.角色 = 角色;
    if (const auto* 特征 = std::get_if<二次特征类型变化输入>(&输入)) {
        定义.来源种类 = 二次特征输入来源种类::特征变化;
        定义.特征类型概念节点 = 特征->特征类型概念节点;
    } else {
        定义.来源种类 = 二次特征输入来源种类::时间变化;
    }
    return 定义;
}

新二次跨类型变化比较状态 映射跨类型比较状态(
    新特征比较状态 状态) noexcept {
    switch (状态) {
    case 新特征比较状态::已完成:
        return 新二次跨类型变化比较状态::已完成;
    case 新特征比较状态::入口拒绝:
        return 新二次跨类型变化比较状态::入口拒绝;
    case 新特征比较状态::特征不存在:
    case 新特征比较状态::概念不存在:
    case 新特征比较状态::概念不相容:
        return 新二次跨类型变化比较状态::概念不存在;
    case 新特征比较状态::材料类型不相容:
    case 新特征比较状态::值不存在:
        return 新二次跨类型变化比较状态::材料类型不相容;
    case 新特征比较状态::单位不相容:
        return 新二次跨类型变化比较状态::单位不相容;
    case 新特征比较状态::规则不支持:
        return 新二次跨类型变化比较状态::规则不支持;
    case 新特征比较状态::结构不一致:
        return 新二次跨类型变化比较状态::结构不一致;
    case 新特征比较状态::资源失败:
        return 新二次跨类型变化比较状态::资源失败;
    }
    return 新二次跨类型变化比较状态::结构不一致;
}

bool 来源动态有效(const std::optional<稳定编码>& 来源) noexcept {
    return !来源 || 有效(*来源);
}

bool 是同一输入类型(
    const 二次特征变化输入& 左,
    const 二次特征变化输入& 右) noexcept {
    if (const auto* 左特征 = std::get_if<二次特征类型变化输入>(&左)) {
        const auto* 右特征 = std::get_if<二次特征类型变化输入>(&右);
        return 右特征
            && 左特征->特征类型概念节点 == 右特征->特征类型概念节点;
    }
    return std::holds_alternative<二次特征时间变化输入>(右);
}

struct 变化量计算结果 final {
    新二次跨类型变化比较状态 状态 =
        新二次跨类型变化比较状态::入口拒绝;
    std::optional<std::int64_t> 变化量;
};

变化量计算结果 计算变化量(
    const 二次特征变化输入& 输入,
    新_特征类& 特征服务) noexcept {
    变化量计算结果 结果;
    if (输入.valueless_by_exception()) return 结果;
    if (const auto* 特征 = std::get_if<二次特征类型变化输入>(&输入)) {
        if (!有效(特征->特征类型概念节点)
            || !来源动态有效(特征->来源动态节点)) {
            return 结果;
        }
        const auto 比较 = 特征服务.按概念比较特征值(
            特征->特征类型概念节点, 特征->结束值, 特征->开始值);
        if (比较.状态 != 新特征比较状态::已完成
            || !比较.数值类型 || !比较.比较值) {
            结果.状态 = 映射跨类型比较状态(比较.状态);
            return 结果;
        }
        if (*比较.数值类型 != 新特征比较数值类型::有向差值) {
            结果.状态 = 新二次跨类型变化比较状态::规则不支持;
            return 结果;
        }
        结果.状态 = 新二次跨类型变化比较状态::已完成;
        结果.变化量 = *比较.比较值;
        return 结果;
    }

    const auto& 时间 = std::get<二次特征时间变化输入>(输入);
    if (!来源动态有效(时间.来源动态节点)) {
        return 结果;
    }
    结果.状态 = 新二次跨类型变化比较状态::已完成;
    结果.变化量 = 计算饱和时间间隔(时间.开始纳秒, 时间.结束纳秒);
    return 结果;
}

