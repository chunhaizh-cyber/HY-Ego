新二次特征计算状态 映射特征比较状态(新特征比较状态 状态) noexcept {
    switch (状态) {
    case 新特征比较状态::已完成:
        return 新二次特征计算状态::已完成;
    case 新特征比较状态::入口拒绝:
        return 新二次特征计算状态::入口拒绝;
    case 新特征比较状态::特征不存在:
    case 新特征比较状态::概念不存在:
    case 新特征比较状态::概念不相容:
        return 新二次特征计算状态::概念不存在;
    case 新特征比较状态::单位不相容:
        return 新二次特征计算状态::单位不相容;
    case 新特征比较状态::材料类型不相容:
    case 新特征比较状态::值不存在:
        return 新二次特征计算状态::材料类型不相容;
    case 新特征比较状态::规则不支持:
        return 新二次特征计算状态::规则不支持;
    case 新特征比较状态::结构不一致:
        return 新二次特征计算状态::结构不一致;
    case 新特征比较状态::资源失败:
        return 新二次特征计算状态::资源失败;
    }
    return 新二次特征计算状态::结构不一致;
}

std::int64_t 计算饱和时间间隔(
    std::int64_t 左纳秒, std::int64_t 右纳秒) noexcept {
    const auto 最小 = (std::numeric_limits<std::int64_t>::min)();
    const auto 最大 = (std::numeric_limits<std::int64_t>::max)();
    if (左纳秒 < 0 && 右纳秒 > 最大 + 左纳秒) return 最大;
    if (左纳秒 > 0 && 右纳秒 < 最小 + 左纳秒) return 最小;
    return 右纳秒 - 左纳秒;
}

bool 输入符合定义(
    const 二次特征准确输入& 输入,
    const 二次特征概念输入定义& 定义) noexcept {
    if (定义.来源种类 == 二次特征输入来源种类::特征准确值) {
        const auto* 特征 = std::get_if<二次特征准确特征输入>(&输入);
        return 特征 && 定义.特征类型概念节点;
    }
    return 定义.来源种类 == 二次特征输入来源种类::强时间
        && std::holds_alternative<二次特征强时间输入>(输入)
        && !定义.特征类型概念节点;
}

