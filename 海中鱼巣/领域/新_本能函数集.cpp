bool 新服务值结算请求::完整() const noexcept {
    return 世界树服务
        && 任务服务
        && 有效(自我所在场景)
        && 有效(自我存在)
        && 有效(服务值特征)
        && 有效(来源任务完成结算)
        && 强时间.语义 == 新状态时间语义::实例绝对UTC
        && 强时间.纳秒 >= 0;
}

