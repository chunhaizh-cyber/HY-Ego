// 通用本能“进入场景”（6220 §2，R94/R95）：1自我、2自我的“所在场景”特征、3目标场景。
新本能函数本次条件结果对 新_本能函数集::进入场景(const 方法参数场景& 场景) noexcept {
    新本能函数本次条件结果对 运行;
    运行.结果.状态 = 新本能函数执行状态::参数不匹配;
    if (场景.用途() == 新方法参数场景用途::任务贡献治理) return 运行;
    // 进入场景在模拟中不迁移（本地迁移未实现）：只记录条件实参，结果未取得（R96）。
    if (场景.用途() == 新方法参数场景用途::模拟) {
        try { return 仅条件模拟返回(场景, {新方法参数信息类型::存在, 新方法参数信息类型::特征,
            新方法参数信息类型::存在}); }
        catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"进入场景模拟", L"条件实参读取异常。"); }
    }
    const auto 端口 = 新_本能函数管理类::租用进入场景端口();
    if (!端口) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
    try {
        const auto 配置 = 端口->读取登记配置();
        if (!配置) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
        新方法知识建立请求 声明;
        声明.作用域 = 新方法作用域::普通世界;
        声明.实现方式 = 新方法实现方式::本能;
        声明.行为 = 新方法行为::改变;
        // R97：1自我{所在场景}、2所在场景特征/1、3目标场景{}。
        const std::vector<新方法有序参数规格> 规格{
            {1, 新方法参数信息类型::存在, 配置->自我概念, {配置->所在场景类型}, 0},
            {2, 新方法参数信息类型::特征, 配置->所在场景类型, {}, 1},
            {3, 新方法参数信息类型::存在, 配置->通用存在概念, {}, 0}};
        声明.方法头.作用存在概念组 = {配置->自我概念};
        声明.方法头.涉及特征类型概念组 = 有序规格涉及特征类型(规格);
        声明.方法头.可能结果概念组 = {配置->所在场景类型};
        // 登记结果组（R110，5380 §3.1）：参数1（自我）的所在场景。
        声明.登记结果组 = {{1, std::nullopt, 配置->所在场景类型}};
        for (const auto& 项 : 规格) {
            新方法参数规格 p;
            p.有序规格 = 项;
            声明.参数规格组.push_back(std::move(p));
        }
        声明.初始模拟关系组 = {{新方法参数关系种类::不同, 1, 3}};
        const auto 登记 = 端口->确保方法登记(声明);
        if (!登记.方法节点) return 运行;
        if (场景.用途() == 新方法参数场景用途::登记) {
            运行.结果.状态 = 场景.全部角色绑定().empty()
                ? 新本能函数执行状态::已按合同返回 : 新本能函数执行状态::参数不匹配;
            return 运行;
        }
        if (const auto X = 新_本能函数管理类::读取本次执行实例(场景))
            return 端口->执行任务(场景, *X);
        运行.结果.状态 = 新本能函数执行状态::入口拒绝;
        return 运行;
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"进入场景本能", L"声明或执行入口异常。");
    }
}

