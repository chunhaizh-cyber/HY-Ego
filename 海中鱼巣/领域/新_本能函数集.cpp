// 仅条件模拟返回（5370 §5.3，R96）：核验参数形状，记录条件实参（特征当前值），不进入动作，结果未取得。
新本能函数本次条件结果对 仅条件模拟返回(const 方法参数场景& 场景,
    const std::vector<新方法参数信息类型>& 类型组) {
    新本能函数本次条件结果对 运行;
    运行.结果.状态 = 新本能函数执行状态::参数不匹配;
    auto* 后端 = 场景.获取交互运行接口();
    if (!后端) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
    if (场景.全部角色绑定().size() != 类型组.size()) return 运行;
    for (std::uint32_t i = 0; i < 类型组.size(); ++i) {
        const auto* p = 场景.查询参数(i + 1);
        if (!p || p->信息类型 != 类型组[i] || !有效(p->信息节点)) return 运行;
    }
    运行.条件.执行分支节点 = 场景.执行分支节点();
    for (const auto& 项 : 场景.全部角色绑定()) {
        新本能函数条件角色材料 条件;
        条件.有序引用 = 项.有序引用; 条件.世界场景节点 = 项.世界场景节点;
        if (项.有序引用 && 项.有序引用->信息类型 == 新方法参数信息类型::特征) {
            const auto F = 后端->读取交互者(项.有序引用->信息节点);
            if (!F) return 运行;
            条件.实际特征组.push_back({F->节点, F->当前值});
        }
        运行.条件.参数角色组.push_back(std::move(条件));
    }
    运行.结果.状态 = 新本能函数执行状态::已按合同返回;
    运行.结果.动作阶段 = 新本能函数动作阶段::未进入动作;
    运行.结果.结果取得状态 = 新本能函数结果取得状态::未取得;
    return 运行;
}
