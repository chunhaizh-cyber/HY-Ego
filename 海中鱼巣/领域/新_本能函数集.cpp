新本能函数本次条件结果对 新_本能函数集::获取服务对象(const 方法参数场景& 场景) noexcept {
    新本能函数本次条件结果对 运行;
    // 本叶没有隔离模拟读取实现，不能借模拟场景租用现实来源。
    if (场景.用途() == 新方法参数场景用途::模拟) {
        运行.结果.状态 = 新本能函数执行状态::参数不匹配;
        return 运行;
    }
    const auto 端口 = 新_本能函数管理类::租用服务对象获取端口();
    if (!端口) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
    try {
        const auto 配置 = 端口->读取登记材料();
        if (!配置) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
        const auto& 定义 = *配置;
        新方法知识建立请求 声明;
        声明.作用域 = 新方法作用域::普通世界;
        声明.方法头.作用存在概念组 = {定义.窗口专属存在概念节点};
        声明.方法头.可能结果概念组 = {定义.人类概念节点};
        新方法参数规格 规格;
        规格.参数角色节点 = 定义.窗口专属存在概念节点;
        规格.存在概念节点 = 定义.窗口专属存在概念节点;
        规格.要求场景 = true;
        规格.特征规格组.push_back({定义.消息数量特征类型节点, 定义.消息数量特征类型节点, {}});
        声明.参数规格组.push_back(std::move(规格));
        const auto 登记 = 端口->确保方法登记(声明);
        if (!登记.方法节点) return 运行;
        if (场景.用途() == 新方法参数场景用途::登记) {
            if (!场景.全部角色绑定().empty()) {
                运行.结果.状态 = 新本能函数执行状态::参数不匹配;
                return 运行;
            }
            运行.结果.状态 = 新本能函数执行状态::已按合同返回;
            return 运行;
        }
        const auto 来源 = 端口->读取窗口来源();
        if (!来源 || !端口->核验执行(场景, *来源)) return 运行;
        const auto 数量 = 场景.读取绑定特征(定义.消息数量特征节点);
        const auto* 当前数 = 数量 && 数量->当前值 ? std::get_if<std::int64_t>(&*数量->当前值) : nullptr;
        if (!当前数 || *当前数 < 0)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务对象", L"已绑定消息数量特征无法读取非负I64。");
        if (*当前数 == 0) return 运行;
        运行.条件.参数角色组.push_back({定义.窗口专属存在概念节点,
            定义.所在场景节点, 定义.窗口存在节点, {{定义.消息数量特征节点, 数量->当前值}}});
        const auto 动作 = 端口->建立动作(场景, *来源);
        if (!动作) return 运行;
        运行.结果.动作动态节点 = 动作;
        运行.结果.动作阶段 = 新本能函数动作阶段::已进入动作;
        const auto 材料 = 端口->读取存在材料(*来源);
        if (!材料) {
            // 动作确已进入，但来源已失效。不把失效解释为“非人类”。
            运行.结果.状态 = 新本能函数执行状态::动作结果未知;
            运行.结果.动作阶段 = 新本能函数动作阶段::结果未知;
            运行.结果.结果取得状态 = 新本能函数结果取得状态::待取得;
            return 运行;
        }
        运行.结果.服务对象观察材料 = *材料;
        运行.结果.状态 = 新本能函数执行状态::已按合同返回;
        运行.结果.动作阶段 = 新本能函数动作阶段::已按函数合同返回;
        运行.结果.结果取得状态 = 新本能函数结果取得状态::已取得;
        return 运行;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务对象", L"本能观察异常。", 异常.what());
    } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务对象", L"本能观察未知异常。"); }
}
