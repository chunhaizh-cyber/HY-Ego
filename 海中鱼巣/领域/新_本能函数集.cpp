        声明.作用域 = 新方法作用域::普通世界;
        声明.实现方式 = 新方法实现方式::本能;
        声明.行为 = 新方法行为::改变;
        // R97：1人类{对象需求}、2对象需求特征/1、3需求身份{}。
        const auto 规格 = 服务对象新需求有序规格(*配置);
        声明.方法头.作用存在概念组 = {配置->人类概念节点};
        声明.方法头.涉及特征类型概念组 = 有序规格涉及特征类型(规格);
        声明.方法头.可能结果概念组 = {配置->完整被认知需求概念};
