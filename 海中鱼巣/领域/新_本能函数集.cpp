// 获取交互者 / 获取服务对象共用：真实外设监听与概念归入不能重定向到模拟信息（R96口径），模拟只记录条件实参。
template<class 端口类型>
新本能函数本次条件结果对 执行服务对象族本能(const 方法参数场景& 场景, bool 交互者,
    const wchar_t* 入口, const 端口类型& 端口) noexcept {
    新本能函数本次条件结果对 运行;
    运行.结果.状态 = 新本能函数执行状态::参数不匹配;
    if (场景.用途() == 新方法参数场景用途::模拟) {
        try {
            return 交互者 ? 仅条件模拟返回(场景, {})
                : 仅条件模拟返回(场景, {新方法参数信息类型::存在, 新方法参数信息类型::特征, 新方法参数信息类型::特征});
        } catch (...) {
            工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,入口,L"模拟条件实参读取异常。");
        }
    }
    if (场景.用途() == 新方法参数场景用途::任务贡献治理) return 运行;
    if (!端口) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
    try {
        const auto 配置 = 端口->读取登记材料();
        if (!配置) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
        const auto& 定义 = *配置;
        新方法知识建立请求 声明;
        声明.作用域 = 新方法作用域::普通世界;
        声明.实现方式 = 新方法实现方式::本能;
        声明.行为 = 新方法行为::改变;
        const auto 规格 = 交互者 ? 获取交互者有序规格(定义) : 获取服务对象有序规格(定义);
        声明.方法头.作用存在概念组 = {定义.自我概念节点};
        // 获取交互者无参数：涉及特征类型直接声明为交互者类型（供按目标特征类型召回）。
        声明.方法头.涉及特征类型概念组 = 交互者 ? std::vector<稳定编码>{定义.交互者特征类型节点} : 有序规格涉及特征类型(规格);
        声明.方法头.可能结果概念组 = {交互者 ? 定义.交互者特征类型节点 : 定义.服务对象特征类型节点};
        // 登记结果组（R110，5380 §3.3/§3.4）：获取交互者不依附参数，作用对象为自我；获取服务对象为参数1（自我）。
        if (交互者) 声明.登记结果组 = {{0, 定义.自我概念节点, 定义.交互者特征类型节点}};
        else 声明.登记结果组 = {{1, std::nullopt, 定义.服务对象特征类型节点}};
        for (const auto& 项 : 规格) {
            新方法参数规格 参数;
            参数.有序规格 = 项;
            声明.参数规格组.push_back(std::move(参数));
        }
        声明.初始模拟关系组 = {};
        // 获取交互者无条件：不设执行分支（先天配对不带分支来源）。
        新方法执行分支定义 单路径;
        单路径.必要条件.关系规则 = 新方法项关系规则::全部成立;
        if (!交互者) {
            // 2026-11-10用户裁决：获取服务对象以交互者为条件——参数2交互者须有当前值（值属于交互者类型值域）。
            // 通用初始必要条件只表达类型具备，值域条件放在执行分支必要条件中。
            新方法条件项定义 有交互者;
            有交互者.参数序号 = 2;
            有交互者.特征类型概念节点 = 定义.交互者特征类型节点;
            有交互者.特征值域概念节点 = 定义.交互者特征类型节点;
            单路径.必要条件.条件项组.push_back(std::move(有交互者));
        }
        if (!交互者) 声明.执行分支组.push_back(std::move(单路径));
        const auto 登记 = 交互者 ? 端口->确保交互者方法登记(声明) : 端口->确保方法登记(声明);
        if (!登记.方法节点) return 运行;
        if (场景.用途() == 新方法参数场景用途::登记) {
            if (!场景.全部角色绑定().empty()) return 运行;
            运行.结果.状态 = 新本能函数执行状态::已按合同返回;
            return 运行;
        }
        const auto 执行 = 新_本能函数管理类::读取本次执行实例(场景);
        if (!执行 || 场景.方法节点() != *登记.方法节点) return 运行;
        return 交互者 ? 端口->执行交互者任务(场景, *执行) : 端口->执行任务(场景, *执行);
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, 入口, L"本能观察异常。", 异常.what());
    } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, 入口, L"本能观察未知异常。"); }
}
