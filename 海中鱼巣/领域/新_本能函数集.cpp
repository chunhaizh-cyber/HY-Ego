#include "新_本能函数集.h"

#include <map>
#include <mutex>
#include <new>
#include <string>

namespace 海中鱼巣 {
namespace {

std::mutex 新本能函数登记互斥;
std::map<std::string, 新本能函数, std::less<>> 新本能函数登记表;
新本能对话框函数端口 对话框端口;

新本能函数执行结果 读取对话框显示文本(
    const 方法参数场景& 参数场景) noexcept {
    新本能函数 函数 = nullptr;
    try {
        std::lock_guard 锁(新本能函数登记互斥);
        函数 = 对话框端口.读取显示文本;
    } catch (...) {
        return {新本能函数执行状态::内部错误,
            新本能函数动作阶段::未进入动作};
    }
    // 待实现依赖：普通控制面板尚未装配真实对话框读取端口。
    if (!函数) return {新本能函数执行状态::依赖未装配,
        新本能函数动作阶段::未进入动作};
    return 函数(参数场景);
}

新本能函数执行结果 设置对话框显示文本(
    const 方法参数场景& 参数场景) noexcept {
    新本能函数 函数 = nullptr;
    try {
        std::lock_guard 锁(新本能函数登记互斥);
        函数 = 对话框端口.设置显示文本;
    } catch (...) {
        return {新本能函数执行状态::内部错误,
            新本能函数动作阶段::未进入动作};
    }
    // 待实现依赖：普通控制面板尚未装配真实对话框写入端口。
    if (!函数) return {新本能函数执行状态::依赖未装配,
        新本能函数动作阶段::未进入动作};
    return 函数(参数场景);
}

} // namespace

新本能函数登记状态 新_本能函数集::初始化() noexcept {
    const auto 读取登记 = 登记(
        新本能函数登记名_读取对话框显示文本,
        &读取对话框显示文本);
    if (读取登记 != 新本能函数登记状态::已登记
        && 读取登记 != 新本能函数登记状态::精确重复) {
        return 读取登记;
    }
    const auto 写入登记 = 登记(
        新本能函数登记名_设置对话框显示文本,
        &设置对话框显示文本);
    if (写入登记 != 新本能函数登记状态::已登记
        && 写入登记 != 新本能函数登记状态::精确重复) {
        return 写入登记;
    }
    return 读取登记 == 新本能函数登记状态::精确重复
            && 写入登记 == 新本能函数登记状态::精确重复
        ? 新本能函数登记状态::精确重复
        : 新本能函数登记状态::已登记;
}

新本能函数端口装配状态 新_本能函数集::装配对话框端口(
    const 新本能对话框函数端口& 端口) noexcept {
    if (!端口.读取显示文本 || !端口.设置显示文本) {
        return 新本能函数端口装配状态::入口拒绝;
    }
    try {
        std::lock_guard 锁(新本能函数登记互斥);
        if (对话框端口.读取显示文本 || 对话框端口.设置显示文本) {
            return 对话框端口 == 端口
                ? 新本能函数端口装配状态::精确重复
                : 新本能函数端口装配状态::所有者冲突;
        }
        对话框端口 = 端口;
        return 新本能函数端口装配状态::已装配;
    } catch (...) {
        return 新本能函数端口装配状态::内部错误;
    }
}

新本能函数登记状态 新_本能函数集::登记(
    std::string_view 登记名,
    新本能函数 函数) noexcept {
    if (登记名.empty() || !函数) return 新本能函数登记状态::入口拒绝;
    try {
        std::lock_guard 锁(新本能函数登记互斥);
        const auto 已有 = 新本能函数登记表.find(登记名);
        if (已有 != 新本能函数登记表.end()) {
            return 已有->second == 函数
                ? 新本能函数登记状态::精确重复
                : 新本能函数登记状态::登记名冲突;
        }
        新本能函数登记表.emplace(std::string(登记名), 函数);
        return 新本能函数登记状态::已登记;
    } catch (const std::bad_alloc&) {
        return 新本能函数登记状态::资源失败;
    } catch (...) {
        return 新本能函数登记状态::内部错误;
    }
}

新本能函数解析结果 新_本能函数集::解析(
    std::string_view 登记名) noexcept {
    if (登记名.empty()) return {};
    try {
        std::lock_guard 锁(新本能函数登记互斥);
        const auto 已有 = 新本能函数登记表.find(登记名);
        if (已有 == 新本能函数登记表.end()) {
            return {新本能函数解析状态::未登记, nullptr};
        }
        return {新本能函数解析状态::已解析, 已有->second};
    } catch (...) {
        return {新本能函数解析状态::内部错误, nullptr};
    }
}

新本能函数执行结果 新_本能函数集::执行(
    std::string_view 登记名,
    const 方法参数场景& 参数场景) noexcept {
    const auto 解析结果 = 解析(登记名);
    if (!解析结果.函数) {
        return {解析结果.状态 == 新本能函数解析状态::内部错误
                ? 新本能函数执行状态::内部错误
                : 新本能函数执行状态::函数未登记,
            新本能函数动作阶段::未进入动作};
    }
    return 解析结果.函数(参数场景);
}

} // namespace 海中鱼巣
