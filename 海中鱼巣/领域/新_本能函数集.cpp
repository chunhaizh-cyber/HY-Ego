新本能函数本次条件结果对 新_本能函数集::获取服务需求(
    const 方法参数场景& 场景, 新服务需求获取方式 方式) noexcept {
    新本能函数本次条件结果对 运行;
    // 没有模拟材料提供者；不得回落到真实端口或产生真实动作。
    if (场景.用途() == 新方法参数场景用途::模拟) {
        运行.结果.状态 = 新本能函数执行状态::参数不匹配;
        return 运行;
    }
    const auto 端口 = 新_本能函数管理类::租用服务需求获取端口();
    if (!端口) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
    const auto 停止 = [&](const char* 原因) -> 新本能函数本次条件结果对 {
        端口->报告工程故障(原因);
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求", L"本能函数工程故障，保留已发生事实。", 原因);
    };
    const auto 条件已变化 = [&]() {
        运行.结果.状态 = 新本能函数执行状态::参数不匹配;
        return std::move(运行);
    };
    try {
        if (场景.用途() != 新方法参数场景用途::登记
            && 场景.用途() != 新方法参数场景用途::执行)
            return 停止("获取服务需求：非法场景用途");
        const auto 配置 = 端口->读取登记材料();
        if (!配置) return 场景.用途() == 新方法参数场景用途::执行
            ? 条件已变化() : 停止("获取服务需求：未装配登记材料");
        const auto& 角色 = 配置->参数角色概念组;
        if (场景.用途() == 新方法参数场景用途::登记) {
            if (!场景.全部角色绑定().empty()) return 停止("获取服务需求：登记场景必须无角色绑定");
            新方法知识建立请求 声明;
            声明.作用域 = 新方法作用域::内部治理;
            声明.实现方式 = 新方法实现方式::本能;
            声明.方法头.可能结果概念组 = {配置->信息包存在概念节点};
            constexpr 新方法参数对象种类 种类[] = {
                新方法参数对象种类::服务要求来源人类, 新方法参数对象种类::服务要求目标存在,
                新方法参数对象种类::服务要求目标特征类型, 新方法参数对象种类::服务要求目标定义,
                新方法参数对象种类::服务要求确认};
            for (std::size_t i = 0; i < 角色.size(); ++i) {
                新方法参数规格 规格;
                规格.参数角色节点 = 角色[i]; 规格.对象种类 = 种类[i];
                声明.参数规格组.push_back(std::move(规格));
            }
            const auto 登记 = 端口->确保方法登记(方式, 声明);
            if (!登记.方法节点 || (登记.状态 != 新方法操作状态::已建立
                && 登记.状态 != 新方法操作状态::已找到)) return 停止("获取服务需求：方法登记失败");
            运行.结果.状态 = 新本能函数执行状态::已按合同返回;
            return 运行;
        }
        // 执行分支只读既有方法，不借登记重入修改方法树。
        if (场景.全部角色绑定().size() != 5) return 停止("获取服务需求：执行角色数量错误");
        for (std::size_t i = 0; i < 角色.size(); ++i) {
            const auto* 绑定 = 场景.查询角色(角色[i]);
            if (!绑定 || 绑定->世界场景节点 || 绑定->实际存在节点
                || 绑定->任务虚拟存在引用 || !绑定->实际特征组.empty()
                || (i < 4 && (!绑定->服务要求分项引用 || 绑定->服务要求确认引用))
                || (i == 4 && (!绑定->服务要求确认引用 || 绑定->服务要求分项引用)))
                return 停止("获取服务需求：执行角色强引用形状错误");
            if ((i < 4 && (绑定->服务要求分项引用->理解节点.值 == 0
                    || 绑定->服务要求分项引用->分项 != static_cast<新服务要求分项种类>(i + 1)))
                || (i == 4 && 绑定->服务要求确认引用->确认节点.值 == 0))
                return 停止("获取服务需求：执行角色强引用身份错误");
        }
        if (!端口->核验执行(方式, 场景)) return 条件已变化();
        std::array<新服务要求分项材料, 4> 分项;
        for (std::size_t i = 0; i < 分项.size(); ++i) {
            const auto* 绑定 = 场景.查询角色(角色[i]);
            const auto 读取 = 场景.读取绑定服务要求分项(角色[i]);
            if (读取.状态 == 新服务要求材料读取状态::材料不存在)
                return 条件已变化();
            if (!绑定 || !绑定->服务要求分项引用 || !读取.材料
                || 读取.状态 != 新服务要求材料读取状态::已读取
                || 读取.材料->引用 != *绑定->服务要求分项引用
                || 读取.材料->引用.分项 != static_cast<新服务要求分项种类>(i + 1))
                return 停止("获取服务需求：分项材料缺失、失效或类型不一致");
            分项[i] = *读取.材料;
            if (i && 分项[i].引用.理解节点 != 分项[0].引用.理解节点)
                return 停止("获取服务需求：禁止拼接不同理解的分项");
            新本能函数条件角色材料 快照;
            快照.参数角色节点 = 角色[i]; 快照.服务要求分项引用 = 分项[i].引用;
            快照.服务要求分项快照 = 分项[i];
            运行.条件.参数角色组.push_back(std::move(快照));
        }
        const auto* 来源 = std::get_if<稳定编码>(&分项[0].值);
        const auto* 目标存在 = std::get_if<稳定编码>(&分项[1].值);
        const auto* 特征类型 = std::get_if<稳定编码>(&分项[2].值);
        const auto* 定义 = std::get_if<新服务要求目标分项>(&分项[3].值);
        if (!来源 || !目标存在 || !特征类型 || !定义)
            return 停止("获取服务需求：分项值形状不合法");
        const 新需求目标定义 目标{*特征类型, 定义->目标形式, 定义->目标值域概念节点,
            定义->目标比较关系概念节点, 定义->目标变化方向};
        const auto* 确认绑定 = 场景.查询角色(角色[4]);
        const auto 身份 = 场景.读取绑定服务要求确认身份(角色[4]);
        if (身份.状态 == 新服务要求确认状态::确认不存在) return 条件已变化();
        if (!身份.确认 || 身份.状态 != 新服务要求确认状态::已读取
            || 身份.确认->确认节点 != 确认绑定->服务要求确认引用->确认节点)
            return 停止("获取服务需求：确认身份读取故障");
        const auto 复核 = 场景.复核绑定服务要求确认语义(角色[4]);
        if (复核.状态 == 新服务要求确认状态::确认不存在) return 条件已变化();
        if (复核.状态 == 新服务要求确认状态::需重新确认) {
            if (!复核.确认 || *身份.确认 != *复核.确认)
                return 停止("获取服务需求：重新确认材料身份不一致");
            return 条件已变化();
        }
        if (!复核.确认
            || 复核.状态 != 新服务要求确认状态::当前有效 || *身份.确认 != *复核.确认)
            return 停止("获取服务需求：确认语义读取故障或身份不一致");
        const auto& 确认 = *复核.确认;
        if (确认.确认节点 != 确认绑定->服务要求确认引用->确认节点
            || 确认.理解节点 != 分项[0].引用.理解节点 || 确认.来源人类节点 != *来源
            || 确认.目标存在节点 != *目标存在 || 确认.目标 != 目标)
            return 停止("获取服务需求：确认与组装目标不一致");
        新本能函数条件角色材料 确认快照;
        确认快照.参数角色节点 = 角色[4]; 确认快照.服务要求确认引用 = *确认绑定->服务要求确认引用;
        确认快照.服务要求确认快照 = 确认;
        运行.条件.参数角色组.push_back(std::move(确认快照));
        const auto 动作 = 端口->建立动作(方式, 场景, *来源);
        运行.结果.动作动态节点 = 动作.动作节点;
        if (动作.动作节点) 运行.结果.动作阶段 = 新本能函数动作阶段::已进入动作;
        if (!动作.已新建 && !动作.动作节点) return 条件已变化();
        if (!动作.已新建 || !动作.动作节点) return 停止("获取服务需求：动作未新建，禁止重复执行");
        新服务需求信息包 包;
        包.来源人类节点 = *来源; 包.目标存在节点 = *目标存在; 包.目标 = 目标;
        for (std::size_t i = 0; i < 分项.size(); ++i) 包.分项来源[i] = 分项[i].引用;
        包.确认 = *确认绑定->服务要求确认引用;
        运行.结果.服务需求信息包 = std::move(包);
        运行.结果.状态 = 新本能函数执行状态::已按合同返回;
        运行.结果.动作阶段 = 新本能函数动作阶段::已按函数合同返回;
        运行.结果.结果取得状态 = 新本能函数结果取得状态::已取得;
        return 运行;
    } catch (...) { return 停止("获取服务需求：内部资源或结构异常"); }
}
