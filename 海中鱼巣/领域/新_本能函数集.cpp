新本能函数本次条件结果对 新_本能函数集::获取服务需求(
    const 方法参数场景& 场景, 新服务需求获取方式 方式) noexcept {
    新本能函数本次条件结果对 运行;
    运行.结果.状态 = 新本能函数执行状态::参数不匹配;
    if (场景.用途() == 新方法参数场景用途::模拟) {
        运行.结果.状态 = 新本能函数执行状态::依赖未装配;
        return 运行;
    }
    if (场景.用途() == 新方法参数场景用途::任务贡献治理
        || (方式 != 新服务需求获取方式::主动 && 方式 != 新服务需求获取方式::被动)) return 运行;
    const auto 端口 = 新_本能函数管理类::租用服务需求获取端口();
    if (!端口) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
    try {
        const auto 配置 = 端口->读取登记材料();
        if (!配置) { 运行.结果.状态 = 新本能函数执行状态::依赖未装配; return 运行; }
        新方法知识建立请求 声明;
        声明.作用域 = 新方法作用域::普通世界;
        声明.行为 = 新方法行为::改变;
        声明.实现方式 = 新方法实现方式::本能;
        声明.方法头.作用存在概念组 = {配置->自我存在概念节点};
        声明.方法头.涉及特征类型概念组 = {配置->数量变化量类型};
        声明.方法头.可能结果概念组 = {配置->已新增值域};
        const std::array<新方法有序参数规格, 6> 规格{{
            {1, 新方法参数信息类型::存在, 配置->通用存在概念节点},
            {2, 新方法参数信息类型::存在, 配置->自我存在概念节点},
            {3, 新方法参数信息类型::特征, 配置->交互者特征类型节点},
            {4, 新方法参数信息类型::存在, 配置->人类概念节点},
            {5, 新方法参数信息类型::特征, 配置->对象需求类型},
            {6, 新方法参数信息类型::特征, 配置->服务任务集合类型}}};
        for (const auto& 项 : 规格) {
            新方法参数规格 参数;
            参数.有序规格 = 项;
            声明.参数规格组.push_back(std::move(参数));
        }
        声明.初始模拟关系组 = {
            {新方法参数关系种类::特征所属存在, 3, 2},
            {新方法参数关系种类::特征所属存在, 5, 4},
            {新方法参数关系种类::特征所属存在, 6, 2},
            {新方法参数关系种类::同属场景, 2, 4}};
        const auto 登记 = 端口->确保方法登记(方式, 声明);
        if (!登记.方法节点) return 运行;
        if (场景.用途() == 新方法参数场景用途::登记) {
            if (场景.全部角色绑定().empty())
                运行.结果.状态 = 新本能函数执行状态::已按合同返回;
            return 运行;
        }
        const auto 执行 = 新_本能函数管理类::读取本次执行实例(场景);
        if (!执行 || 场景.方法节点() != *登记.方法节点) return 运行;
        return 端口->执行任务(方式, 场景, *执行);
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"获取服务需求",
            L"六参数登记或执行发生工程异常，保留已发生事实。");
    }
}
