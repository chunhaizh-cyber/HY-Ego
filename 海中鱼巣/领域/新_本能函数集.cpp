bool 新服务值结算请求::完整() const noexcept {
    return 世界树服务
        && 任务服务
        && 有效(自我所在场景)
        && 有效(自我存在)
        && 有效(服务值特征)
        && 有效(来源任务完成结算)
        && 强时间.语义 == 新状态时间语义::实例绝对UTC
        && 强时间.纳秒 >= 0;
}

新本能函数登记状态 新_本能函数集::初始化() noexcept {
    const auto 读取登记 = 登记(
        新本能函数登记名_读取网页对话消息,
        &读取网页对话消息);
    if (读取登记 != 新本能函数登记状态::已登记
        && 读取登记 != 新本能函数登记状态::精确重复) {
        return 读取登记;
    }
    const auto 输入登记 = 登记(
        新本能函数登记名_设置网页对话输入文本,
        &设置网页对话输入文本);
    if (输入登记 != 新本能函数登记状态::已登记
        && 输入登记 != 新本能函数登记状态::精确重复) {
        return 输入登记;
    }
    const auto 提交登记 = 登记(
        新本能函数登记名_提交网页对话消息,
        &提交网页对话消息);
    if (提交登记 != 新本能函数登记状态::已登记
        && 提交登记 != 新本能函数登记状态::精确重复) {
        return 提交登记;
    }
    return 读取登记 == 新本能函数登记状态::精确重复
            && 输入登记 == 新本能函数登记状态::精确重复
            && 提交登记 == 新本能函数登记状态::精确重复
        ? 新本能函数登记状态::精确重复
        : 新本能函数登记状态::已登记;
}

新本能函数端口装配状态 新_本能函数集::装配网页对话端口(
    const 新本能网页对话函数端口& 端口) noexcept {
    if (!端口.读取已显示消息 || !端口.设置输入框文本 || !端口.提交消息) {
        return 新本能函数端口装配状态::入口拒绝;
    }
    try {
        std::lock_guard 锁(新本能函数登记互斥);
        if (网页对话端口.读取已显示消息
            || 网页对话端口.设置输入框文本
            || 网页对话端口.提交消息) {
            return 网页对话端口 == 端口
                ? 新本能函数端口装配状态::精确重复
                : 新本能函数端口装配状态::所有者冲突;
        }
        网页对话端口 = 端口;
        return 新本能函数端口装配状态::已装配;
    } catch (...) {
        return 新本能函数端口装配状态::内部错误;
    }
}

新本能函数登记状态 新_本能函数集::登记(
    std::string_view 登记名,
    新本能函数 函数) noexcept {
    if (登记名.empty() || !函数) return 新本能函数登记状态::入口拒绝;
    try {
        std::lock_guard 锁(新本能函数登记互斥);
        const auto 已有 = 新本能函数登记表.find(登记名);
        if (已有 != 新本能函数登记表.end()) {
            return 已有->second == 函数
                ? 新本能函数登记状态::精确重复
                : 新本能函数登记状态::登记名冲突;
        }
        新本能函数登记表.emplace(std::string(登记名), 函数);
        return 新本能函数登记状态::已登记;
    } catch (const std::bad_alloc&) {
        return 新本能函数登记状态::资源失败;
    } catch (...) {
        return 新本能函数登记状态::内部错误;
    }
}

新本能函数解析结果 新_本能函数集::解析(
    std::string_view 登记名) noexcept {
    if (登记名.empty()) return {};
    try {
        std::lock_guard 锁(新本能函数登记互斥);
        const auto 已有 = 新本能函数登记表.find(登记名);
        if (已有 == 新本能函数登记表.end()) {
            return {新本能函数解析状态::未登记, nullptr};
        }
        return {新本能函数解析状态::已解析, 已有->second};
    } catch (...) {
        return {新本能函数解析状态::内部错误, nullptr};
    }
}

新本能函数可用状态 新_本能函数集::检查可用(
    std::string_view 登记名) noexcept {
    if (登记名.empty()) return 新本能函数可用状态::入口拒绝;
    try {
        std::lock_guard 锁(新本能函数登记互斥);
        const auto 已有 = 新本能函数登记表.find(登记名);
        if (已有 == 新本能函数登记表.end() || !已有->second) {
            return 新本能函数可用状态::未登记;
        }
        if (登记名 == 新本能函数登记名_读取网页对话消息
            && !网页对话端口.读取已显示消息) {
            return 新本能函数可用状态::依赖未装配;
        }
        if (登记名 == 新本能函数登记名_设置网页对话输入文本
            && !网页对话端口.设置输入框文本) {
            return 新本能函数可用状态::依赖未装配;
        }
        if (登记名 == 新本能函数登记名_提交网页对话消息
            && !网页对话端口.提交消息) {
            return 新本能函数可用状态::依赖未装配;
        }
        return 新本能函数可用状态::可调用;
    } catch (...) {
        return 新本能函数可用状态::内部错误;
    }
}

新本能函数执行结果 新_本能函数集::执行(
    std::string_view 登记名,
    const 方法参数场景& 参数场景) noexcept {
    const auto 解析结果 = 解析(登记名);
    if (!解析结果.函数) {
        return {解析结果.状态 == 新本能函数解析状态::内部错误
                ? 新本能函数执行状态::内部错误
                : 新本能函数执行状态::函数未登记,
            新本能函数动作阶段::未进入动作};
    }
    return 解析结果.函数(参数场景);
}

新服务值结算结果 新_本能函数集::执行服务值结算(
    const 新服务值结算请求& 请求) noexcept {
    新服务值结算结果 结果;
    if (!请求.完整()) return 结果;
    try {
        std::lock_guard 锁(服务值结算互斥);
        const auto 已兑现 = 已兑现服务结算.find(
            请求.来源任务完成结算.值);
        if (已兑现 != 已兑现服务结算.end()) {
            结果 = 已兑现->second;
            结果.状态 = 新服务值结算状态::精确重复;
            return 结果;
        }

        const auto [占位, 已插入] = 已兑现服务结算.emplace(
            请求.来源任务完成结算.值, 新服务值结算结果{});
        if (!已插入) {
            结果.状态 = 新服务值结算状态::内部错误;
            return 结果;
        }
        const auto 失败 = [&](新服务值结算状态 状态) noexcept {
            已兑现服务结算.erase(占位);
            结果.状态 = 状态;
            return 结果;
        };

        if (!请求.世界树服务->已初始化()) {
            return 失败(新服务值结算状态::世界事实不一致);
        }
        const auto 来源结算 =
            请求.任务服务->获取完成结算(请求.来源任务完成结算);
        if (!来源结算 || 来源结算->节点 != 请求.来源任务完成结算) {
            return 失败(新服务值结算状态::来源结算不存在);
        }
        const auto 场景 = 请求.世界树服务->查询场景(请求.自我所在场景);
        const auto 自我 = 请求.世界树服务->查询存在(请求.自我存在);
        const auto 特征 = 请求.世界树服务->查询特征(请求.服务值特征);
        if (!场景 || !自我 || !特征
            || std::find(场景->直接成员存在组.begin(),
                场景->直接成员存在组.end(), 请求.自我存在)
                == 场景->直接成员存在组.end()
            || std::find(自我->特征节点组.begin(), 自我->特征节点组.end(),
                请求.服务值特征) == 自我->特征节点组.end()) {
            return 失败(新服务值结算状态::世界事实不一致);
        }
        if (!特征->当前值) {
            return 失败(新服务值结算状态::服务值不是非负I64);
        }
        const auto* 当前值 = std::get_if<std::int64_t>(&*特征->当前值);
        if (!当前值 || *当前值 < 0) {
            return 失败(新服务值结算状态::服务值不是非负I64);
        }
        结果.结算前值 = *当前值;
        constexpr auto 最大值 = (std::numeric_limits<std::int64_t>::max)();
        if (*当前值 == 最大值) {
            结果.结算后值 = 最大值;
            结果.状态 = 新服务值结算状态::已达最大值;
            占位->second = 结果;
            return 结果;
        }

        const auto 更新 = 请求.世界树服务->更新存在特征并形成动态(
            请求.自我所在场景, 请求.自我存在, 请求.服务值特征,
            新特征准确值{*当前值 + 1}, 请求.强时间);
        if (更新.状态 != 新世界特征变化状态::已完成
            && 更新.状态
                != 新世界特征变化状态::已生成状态但无可连接前状态) {
            const auto 写后特征 =
                请求.世界树服务->查询特征(请求.服务值特征);
            const auto* 写后值 = 写后特征 && 写后特征->当前值
                ? std::get_if<std::int64_t>(&*写后特征->当前值)
                : nullptr;
            if (写后值 && *写后值 == *当前值 + 1
                && 更新.新状态节点) {
                结果.结算后值 = *写后值;
                结果.状态节点 = 更新.新状态节点;
                结果.状态 = 新服务值结算状态::已更新但动态未完成;
                占位->second = 结果;
                return 结果;
            }
            if (!写后值 || *写后值 != *当前值) {
                结果.结算后值 = 写后值
                    ? std::optional<std::int64_t>{*写后值} : std::nullopt;
                结果.状态节点 = 更新.新状态节点;
                结果.状态 = 新服务值结算状态::世界事实不一致;
                占位->second = 结果;
                return 结果;
            }
            return 失败(更新.状态 == 新世界特征变化状态::资源失败
                ? 新服务值结算状态::资源失败
                : (更新.状态 == 新世界特征变化状态::时间不合法
                        || 更新.状态 == 新世界特征变化状态::时间非递增
                    ? 新服务值结算状态::时间不可用
                    : 新服务值结算状态::特征更新失败));
        }
        if (!更新.新状态节点) {
            return 失败(新服务值结算状态::特征更新失败);
        }
        结果.结算后值 = *当前值 + 1;
        结果.状态节点 = 更新.新状态节点;
        if (更新.动态发布结果 && 更新.动态发布结果->动态建立结果) {
            结果.动态节点 = 更新.动态发布结果->动态建立结果->动态节点;
        }
        结果.状态 = 新服务值结算状态::已结算;
        占位->second = 结果;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 新服务值结算状态::资源失败;
        return 结果;
    } catch (...) {
        结果.状态 = 新服务值结算状态::内部错误;
        return 结果;
    }
}

