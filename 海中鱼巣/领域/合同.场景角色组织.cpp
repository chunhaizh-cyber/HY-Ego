bool 场景直接包含组结果::父组读取成功(
    const 场景直接包含反向读取请求 &请求) const noexcept {
  if (!有效(请求.成员) || 结果头.状态 != 场景直接包含状态::已读取 ||
      包含组.size() > 1)
    return false;
  return std::ranges::all_of(包含组, [&](const auto &事实) {
    return 场景直接包含事实完整(事实) && 事实.成员 == 请求.成员;
  });
}

bool 场景直接包含组结果::子组读取成功(
    const 场景直接包含组读取请求 &请求) const noexcept {
  if (!有效(请求.父场景) || 结果头.状态 != 场景直接包含状态::已读取)
    return false;
  for (std::size_t i = 0; i < 包含组.size(); ++i)
    if (!场景直接包含事实完整(包含组[i]) ||
        包含组[i].父场景 != 请求.父场景 ||
        (i && 包含组[i - 1].关系.编码.值 >= 包含组[i].关系.编码.值))
      return false;
  return true;
}

bool 场景树当前结果::成功(const 场景树当前读取请求 &请求) const noexcept {
  if (!有效(请求.根场景) || 结果头.状态 != 场景直接包含状态::已读取 ||
      !树 || 树->根场景 != 请求.根场景 || 树->场景组.empty())
    return false;
  std::size_t 根数量 = 0;
  for (const auto &节点 : 树->场景组) {
    const auto 场景 = 节点.场景角色.场景;
    if (!角色完整(节点.场景角色) || 节点.树证明.场景 != 场景 ||
        节点.树证明.树根 != 请求.根场景)
      return false;
    if (场景 == 请求.根场景) {
      ++根数量;
      if (节点.树证明.种类 != 场景树证明种类::根标记 || 节点.直接父)
        return false;
    } else if (节点.树证明.种类 != 场景树证明种类::树归属 || !节点.直接父 ||
               !联合父载荷完整(*节点.直接父, 节点.直接父->父, 场景)) {
      return false;
    }
  }
  return 根数量 == 1;
}

