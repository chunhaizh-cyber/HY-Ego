bool 场景角色写结果::启用成功(const 场景角色启用请求 &请求) const noexcept {
  if (!有效(请求.幂等身份) || !有效(请求.对象存在) || !角色 ||
      !角色完整(*角色) || 角色->对象存在来源.身份 != 请求.对象存在 ||
      状态 != 场景角色数据状态::已启用)
    return false;
  if (!有效(请求.父场景语境))
    return !结构父 && !父语境投影;
  return 结构父 && 父语境投影 &&
         联合父载荷完整(*结构父, 请求.父场景语境, 角色->场景) &&
         (!有效(请求.预期结构父关系) ||
          结构父->关系 == 请求.预期结构父关系) &&
         父语境投影->结构父.关系 == 结构父->关系;
}

