bool 合法角色(场景根角色 角色) noexcept {
  return 角色 == 场景根角色::特征 || 角色 == 场景根角色::状态 ||
         角色 == 场景根角色::动态 || 角色 == 场景根角色::关系;
}

bool 节点完整(const 场景节点见证 &节点) noexcept { return 有效(节点.编码); }

bool 边完整(const 场景组织边见证 &边) noexcept {
  return 有效(边.编码) && 有效(边.源) && 有效(边.目标) &&
         有效(边.关系类型) && 边.源 != 边.目标 && 边.角色或顺序 != 0;
}

bool 角色完整(const 场景角色当前事实 &事实) noexcept {
  if (!有效(事实.场景) ||
      !存在身份来源当前见证完整(事实.对象存在来源,
                                  事实.对象存在来源.身份) ||
      !节点完整(事实.场景族锚点) || !节点完整(事实.场景族归属类型) ||
      !节点完整(事实.根绑定类型) || !边完整(事实.场景角色登记边) ||
      事实.场景角色登记边.目标 != 事实.场景 ||
      事实.场景角色登记边.源 != 事实.对象存在来源.身份)
    return false;

  std::unordered_set<std::uint64_t> 根节点;
  std::unordered_set<std::uint64_t> 绑定边;
  for (std::size_t i = 0; i < 事实.四根.size(); ++i) {
    const auto &根 = 事实.四根[i];
    if (!合法角色(根.角色) ||
        static_cast<std::uint8_t>(根.角色) != i + 1 || !节点完整(根.根) ||
        !边完整(根.绑定) || 根.绑定.源 != 事实.场景 ||
        根.绑定.目标 != 根.根.编码 ||
        根.绑定.关系类型 != 事实.根绑定类型.编码 ||
        !根节点.insert(根.根.编码.值).second ||
        !绑定边.insert(根.绑定.编码.值).second)
      return false;
  }
  return true;
}

bool 组织边匹配(const 场景组织边见证 &边, 稳定编码 源,
                稳定编码 目标) noexcept {
  return 边完整(边) && 边.源 == 源 && 边.目标 == 目标;
}

bool 组织完整(const 场景实例组织事实 &事实) noexcept {
  if (!角色完整(事实.场景角色) || !合法角色(事实.角色) ||
      !有效(事实.根) || !有效(事实.实例) ||
      事实.场景角色.四根[static_cast<std::size_t>(事实.角色) - 1].根.编码 !=
          事实.根 ||
      事实.路径节点.empty() || 事实.路径边.empty() ||
      事实.路径节点.size() != 事实.路径边.size() + 1 ||
      事实.路径节点.front().编码 != 事实.根 ||
      事实.路径节点.back().编码 != 事实.实例)
    return false;
  for (std::size_t i = 0; i < 事实.路径节点.size(); ++i) {
    if (!节点完整(事实.路径节点[i]))
      return false;
    if (i != 0 && !组织边匹配(事实.路径边[i - 1],
                               事实.路径节点[i - 1].编码,
                               事实.路径节点[i].编码))
      return false;
  }
  return true;
}

bool 结构交付完整(const 场景角色结构交付 &交付) noexcept {
  return 有效(交付.根绑定关系类型) && 有效(交付.状态组织关系类型) &&
         有效(交付.动态组织关系类型) && 有效(交付.父场景语境关系类型);
}

直接归属联合事实 转换存在组成(const 存在组成关系事实 &事实) noexcept {
  return {直接归属来源::存在组成, 事实.关系, 事实.父存在, 事实.子存在};
}

直接归属联合事实 转换场景包含(const 场景直接包含事实 &事实) noexcept {
  return {事实.种类 == 场景直接包含种类::存在成员
              ? 直接归属来源::场景成员
              : 直接归属来源::直接子场景,
          事实.关系.编码, 事实.父场景, 事实.成员};
}

