auto 准确值排序键(const 新特征准确值 &值)
{
    if (const auto *I64 = std::get_if<std::int64_t>(&值))
    {
        return std::tuple<std::size_t, std::uint64_t>{0, static_cast<std::uint64_t>(*I64) ^
                                                             (std::uint64_t{1} << 63)};
    }
    return std::tuple<std::size_t, std::uint64_t>{1, std::get<稳定编码>(值).值};
}

