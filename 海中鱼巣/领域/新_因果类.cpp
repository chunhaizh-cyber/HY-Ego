新因果世界范围 新_因果类::查询当前场景树因果() const noexcept
{
    try
    {
        if (!场景服务_) 抽象错误("限定因果查询缺少场景依赖");
        const auto 根 = 场景服务_->获取根场景();
        if (!根) 抽象错误("限定因果查询世界根缺失");
        新因果世界范围 范围{*根, {}, {}};
        std::lock_guard 锁(新因果互斥);
        if (!结构仍存在()) 抽象错误("限定因果查询未初始化");
        for (const auto &关系 : 全局基础数据集.查询源关系(新因果信息图根节点, 基础外部关系类型::父子))
            if (关系.角色或顺序 == 新因果根成员关系角色 && !节点仍存在(关系.目标节点))
                抽象错误("限定因果根成员端点失效");
        for (const auto q : 查询全部因果节点())
        {
            // 原始场景先过滤，禁止先展开其它世界的参与者。
            const auto c = 读取可选节点字段(q, 发生场景字段);
            if (!c) 抽象错误("因果原始场景字段破损");
            if (有效(*c) && 场景服务_->是场景节点(*c))
                范围.具体因果节点组.push_back(q);
        }
        std::sort(范围.具体因果节点组.begin(), 范围.具体因果节点组.end());
        for (const auto q : 查询概念节点())
        {
            const auto 定义 = 解码概念(q);
            if (std::all_of(定义.分支组.begin(), 定义.分支组.end(), [&](const auto &分支) {
                return std::binary_search(范围.具体因果节点组.begin(), 范围.具体因果节点组.end(),
                                           分支.来源具体因果节点);
            })) 范围.概念因果节点组.push_back(q);
        }
        std::sort(范围.概念因果节点组.begin(), 范围.概念因果节点组.end());
        return 范围;
    }
    catch (const std::exception &e)
    {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"限定世界因果查询", L"工程故障", e.what());
    }
    catch (...)
    {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"限定世界因果查询", L"未知工程故障");
    }
}
void 新_因果类::尝试共同抽象(稳定编码 因果编码) noexcept
{
    if (!存在服务_ || !存在概念服务_ || !特征概念服务_ || !动态概念服务_ || !特征值服务_ ||
        !场景服务_)
        return;
    try
    {
        const auto 来源信息 = 获取因果(因果编码);
        if (!来源信息)
            抽象错误("自动抽象来源不可读");
        if (!来源信息->发生场景节点)
            return;
        std::vector<新因果信息> 来源材料;
        for (const auto q : 查询当前场景树因果().具体因果节点组)
        {
            const auto 信息 = 获取因果(q);
            if (!信息) 抽象错误("自动抽象具体全集破损");
            if (信息->发生场景节点 == 来源信息->发生场景节点) 来源材料.push_back(*信息);
        }
        const auto 投影 = 冻结治理投影(来源材料, 治理参与者_, 场景服务_);
        新因果共同抽象状态 抽象状态{};
        const auto 基准布局 = 对齐来源(*来源信息, *特征概念服务_, *动态概念服务_, 抽象状态, 投影);
        if (!基准布局)
            return;
        std::vector<稳定编码> 来源组;
        for (const auto &具体材料 : 来源材料)
        {
            const auto 来源布局 = 对齐来源(具体材料, *特征概念服务_, *动态概念服务_, 抽象状态, 投影);
            if (来源布局 && 同布局(*基准布局, *来源布局))
                来源组.push_back(具体材料.节点);
        }
        if (来源组.size() >= 2)
            (void)抽象共同因果(来源组);
    }
    catch (...)
    {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"自动因果抽象",
                     L"自动抽象工程故障");
    }
}

bool 新_因果类::初始化() noexcept
{
    try
    {
        std::lock_guard 锁(新因果互斥);
        if (!状态服务_.初始化() || !动态服务_.初始化())
            抽象错误("因果依赖初始化失败");
        if (结构已分配())
        {
            if (!结构仍存在())
                抽象错误("因果初始化结构破损");
            return true;
        }
        for (auto *编码 : 架构编码组())
        {
            *编码 = 全局基础数据集.新建节点();
            if (!有效(*编码))
                抽象错误("因果架构节点分配失败");
        }
        if (!有效(全局基础数据集.添加字段节点(新因果信息图根节点, 节点类型字段, 因果图根类型)))
            抽象错误("因果根类型发布失败");
        return true;
    }
    catch (...)
    {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"初始化因果",
                     L"因果初始化工程故障");
    }
}

新因果处理结果 新_因果类::处理发生(const 新因果发生记录 &输入, 新因果形成来源 来源,
                                   const std::optional<新因果动作定义> &动作) noexcept
{
    新因果处理结果 结果;
    try
    {
        if (场景服务_ && !场景服务_->是场景节点(输入.场景节点))
        {
            结果.状态 = 新因果操作状态::入口拒绝;
            return 结果;
        }
        新因果操作状态 失败状态{};
        const auto 发生 = 规范化发生(状态服务_, 动态服务_, 输入, 来源, 动作, 失败状态);
        if (!发生)
        {
            结果.状态 = 失败状态;
            return 结果;
        }
        新因果信息 投影输入;
        投影输入.发生场景节点 = 输入.场景节点;
        投影输入.定义 = {动作 ? 新因果类型::已知动作 : 新因果类型::未知动作,
                           发生->条件状态组, 发生->条件动态组, 动作, 发生->结果状态};
        const auto 投影 = 冻结治理投影({投影输入}, 治理参与者_, 场景服务_);
        if (动作 && 动作->作用对象任务虚拟存在 && !治理参与者_)
        {
            结果.状态 = 新因果操作状态::入口拒绝;
            return 结果;
        }
        std::unique_lock 锁(新因果互斥);
        if (!结构仍存在())
        {
            结果.状态 = 新因果操作状态::尚未初始化;
            return 结果;
        }
        待形成发生组.erase(std::remove_if(待形成发生组.begin(), 待形成发生组.end(),
                                          [](const auto &项) { return !节点仍存在(项.发生身份); }),
                           待形成发生组.end());

        if (场景服务_)
        {
            if (!场景服务_->获取场景(输入.场景节点))
                throw std::runtime_error("因果发生场景无法读取");
            std::set<稳定编码> 场景状态集合, 场景动态集合, 场景集合;
            std::vector<稳定编码> 待核验场景组{输入.场景节点};
            for (std::size_t 序号 = 0; 序号 < 待核验场景组.size(); ++序号)
            {
                if (!场景集合.insert(待核验场景组[序号]).second)
                    抽象错误("因果场景范围存在环或重复归属");
                const auto 概念编码 = 场景服务_->获取场景(待核验场景组[序号]);
                if (!概念编码)
                    抽象错误("因果子场景不可读");
                场景状态集合.insert(概念编码->状态节点组.begin(), 概念编码->状态节点组.end());
                场景动态集合.insert(概念编码->动态节点组.begin(), 概念编码->动态节点组.end());
                待核验场景组.insert(待核验场景组.end(), 概念编码->直接子场景组.begin(),
                                    概念编码->直接子场景组.end());
            }
            if (!场景状态集合.contains(输入.结果状态节点) ||
                (输入.结果动态节点 && !场景动态集合.contains(*输入.结果动态节点)) ||
                (输入.动作证据节点 && !场景动态集合.contains(*输入.动作证据节点)))
            {
                结果.状态 = 新因果操作状态::入口拒绝;
                return 结果;
            }
            for (const auto 读取数量 : 输入.前置状态节点组)
                if (!场景状态集合.contains(读取数量))
                {
                    结果.状态 = 新因果操作状态::入口拒绝;
                    return 结果;
                }
            for (const auto 读取数量 : 输入.前置动态节点组)
                if (!场景动态集合.contains(读取数量))
                {
                    结果.状态 = 新因果操作状态::入口拒绝;
                    return 结果;
                }
            const auto 核验E = [&](稳定编码 参与存在组) {
                if (治理参与者_)
                    return 场景服务_->是场景节点(参与存在组) ||
                           投影.contains({输入.场景节点, 参与存在组});
                return 场景服务_->存在属于场景范围(输入.场景节点, 参与存在组);
            };
            if (!核验E(发生->结果状态.被描述存在节点))
            {
                结果.状态 = 新因果操作状态::入口拒绝;
                return 结果;
            }
            for (const auto &状态材料 : 发生->条件状态组)
                if (!核验E(状态材料.被描述存在节点))
                {
                    结果.状态 = 新因果操作状态::入口拒绝;
                    return 结果;
                }
            for (const auto &定义材料 : 发生->条件动态组)
                if (!核验E(定义材料.主题存在节点))
                {
                    结果.状态 = 新因果操作状态::入口拒绝;
                    return 结果;
                }
            if (动作 && (!核验E(动作->执行主体存在节点) ||
                         (动作->作用部位存在节点 && !核验E(*动作->作用部位存在节点)) ||
                         (动作->作用对象存在节点 && !核验E(*动作->作用对象存在节点)) ||
                         (动作->作用对象任务虚拟存在 && !核验E(动作->作用对象任务虚拟存在->虚拟存在节点))))
            {
                结果.状态 = 新因果操作状态::入口拒绝;
                return 结果;
            }
        }
        if (const auto 已有 = 查找最具体匹配因果(*发生, 场景服务_ != nullptr))
        {
            const auto 更新 = 更新普通统计(已有->节点, 发生->发生身份, true, 来源);
            结果.状态 = 更新;
            结果.因果节点 = 已有->节点;
            结果.因果信息 = 读取因果信息(已有->节点);
            if (!结果.因果信息 || 更新 == 新因果操作状态::资源失败 ||
                更新 == 新因果操作状态::结构不一致 || 更新 == 新因果操作状态::计数溢出)
                throw std::runtime_error("因果统计更新失败");
            锁.unlock();
            尝试共同抽象(已有->节点);
            return 结果;
        }

        if (std::any_of(待形成发生组.begin(), 待形成发生组.end(),
                        [&](const auto &项) { return 项.发生身份 == 发生->发生身份; }))
        {
            结果.状态 = 新因果操作状态::重复发生;
            return 结果;
        }

        bool 找到同组但无共同条件 = false;
        for (auto 位置 = 待形成发生组.begin(); 位置 != 待形成发生组.end(); ++位置)
        {
            if (!同一形成分组(*位置, *发生))
                continue;
            auto 共同状态 = 求交集(位置->条件状态组, 发生->条件状态组);
            auto 共同动态 = 求交集(位置->条件动态组, 发生->条件动态组);
            if (共同状态.empty() && 共同动态.empty())
            {
                找到同组但无共同条件 = true;
                continue;
            }
            新因果定义 定义;
            定义.类型 = 动作 ? 新因果类型::已知动作 : 新因果类型::未知动作;
            定义.条件状态组 = std::move(共同状态);
            定义.条件动态组 = std::move(共同动态);
            定义.动作 = 动作;
            定义.结果状态 = 发生->结果状态;
            const auto 已建立 = 发布因果(定义, {位置->来源, 来源}, {位置->发生身份, 发生->发生身份},
                                         场景服务_ ? 发生->场景节点 : 稳定编码{});
            if (!已建立)
            {
                throw std::runtime_error("具体因果发布失败");
            }
            const auto 旧身份 = 位置->发生身份;
            待形成发生组.erase(std::remove_if(待形成发生组.begin(), 待形成发生组.end(),
                                              [&](const auto &项) {
                                                  return 项.发生身份 == 旧身份 ||
                                                         项.发生身份 == 发生->发生身份;
                                              }),
                               待形成发生组.end());
            结果.状态 = 新因果操作状态::已建立;
            结果.因果节点 = 已建立->节点;
            结果.因果信息 = *已建立;
            锁.unlock();
            尝试共同抽象(已建立->节点);
            return 结果;
        }
        待形成发生组.push_back(*发生);
        结果.状态 = 找到同组但无共同条件 ? 新因果操作状态::无共同条件 : 新因果操作状态::已记录首例;
        return 结果;
    }
    catch (...)
    {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"具体因果形成",
                     L"因果读取或发布工程异常");
    }
}

