std::vector<稳定编码> 读取多节点字段(稳定编码 节点, 稳定编码 字段, bool &完整)
{
    std::vector<稳定编码> 结果;
    完整 = true;
    for (const auto &关系 : 全局基础数据集.查询字段(节点, 字段))
    {
        const auto *目标 = std::get_if<稳定编码>(&关系.内容);
        if (!目标 || !节点仍存在(*目标))
        {
            完整 = false;
            return {};
        }
        结果.push_back(*目标);
    }
    std::sort(结果.begin(), 结果.end());
    if (std::adjacent_find(结果.begin(), 结果.end()) != 结果.end())
    {
        完整 = false;
        return {};
    }
    return 结果;
}

