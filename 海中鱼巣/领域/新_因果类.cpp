std::optional<稳定编码> 读取唯一节点字段(稳定编码 节点, 稳定编码 字段)
{
    const auto 组 = 全局基础数据集.查询字段(节点, 字段);
    if (组.size() != 1)
        return std::nullopt;
    const auto *目标 = std::get_if<稳定编码>(&组.front().内容);
    return 目标 && 节点仍存在(*目标) ? std::optional<稳定编码>{*目标} : std::nullopt;
}

