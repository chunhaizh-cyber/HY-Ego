bool 节点仍存在(稳定编码 节点) noexcept
{
    return 有效(节点) && 全局基础数据集.查询节点(节点).has_value();
}

bool 结构已分配() noexcept
{
    const auto 组 = 架构编码组();
    return std::any_of(组.begin(), 组.end(), [](const auto *编码) { return 有效(*编码); });
}

bool 结构仍存在() noexcept
{
    const auto 组 = 架构编码组();
    return std::all_of(组.begin(), 组.end(), [](const auto *编码) { return 节点仍存在(*编码); })
        && 来源前驱存储::架构仍存在();
}

bool 是因果类型值(std::int64_t 值) noexcept
{
    return 值 == static_cast<std::int64_t>(新因果类型::未知动作) ||
           值 == static_cast<std::int64_t>(新因果类型::已知动作);
}

bool 是形成来源值(std::int64_t 值) noexcept
{
    return 值 >= static_cast<std::int64_t>(新因果形成来源::结果状态筛选) &&
           值 <= static_cast<std::int64_t>(新因果形成来源::外部动作动态反向);
}

bool 动作触发方式有效(新因果动作触发方式 方式) noexcept
{
    return 方式 == 新因果动作触发方式::尚未确定 ||
           方式 == 新因果动作触发方式::主动调用 ||
           方式 == 新因果动作触发方式::被动触发;
}

[[noreturn]] void 动作触发方式工程错误() noexcept
{
    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"因果动作触发方式",
                 L"动作触发方式字段读取异常、重复、类型或枚举值非法，或无动作却保存触发方式。");
}

新因果动作触发方式 读取动作触发方式(稳定编码 节点)
{
    try
    {
        const auto 字段组 = 全局基础数据集.查询字段(节点, 动作触发方式字段);
        // 只有旧字段缺失可解释为尚未确定；损坏不能进入旧读取入口的空返回分支。
        if (字段组.empty())
            return 新因果动作触发方式::尚未确定;
        if (字段组.size() != 1)
            动作触发方式工程错误();
        const auto *值 = std::get_if<基础值>(&字段组.front().内容);
        const auto *I64 = 值 ? std::get_if<std::int64_t>(&值->材料) : nullptr;
        if (!I64 || !动作触发方式有效(static_cast<新因果动作触发方式>(*I64)))
            动作触发方式工程错误();
        return static_cast<新因果动作触发方式>(*I64);
    }
    catch (...)
    {
        动作触发方式工程错误();
    }
}

void 核验没有动作触发方式字段(稳定编码 节点)
{
    try
    {
        if (!全局基础数据集.查询字段(节点, 动作触发方式字段).empty())
            动作触发方式工程错误();
    }
    catch (...)
    {
        动作触发方式工程错误();
    }
}

