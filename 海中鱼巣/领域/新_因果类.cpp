template <class T> std::vector<T> 求交集(const std::vector<T> &左, const std::vector<T> &右)
{
    std::vector<T> 结果;
    for (const auto &项 : 左)
    {
        if (std::find(右.begin(), 右.end(), 项) != 右.end())
            结果.push_back(项);
    }
    return 结果;
}

