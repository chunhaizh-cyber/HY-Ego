    if (!记节点字段(记录, 节点, 节点类型字段, 状态模式节点类型) ||
        !记节点字段(记录, 节点, 状态模式存在字段, 模式.被描述存在节点) ||
        !记节点字段(记录, 节点, 状态模式特征类型字段, 模式.特征类型概念节点) ||
        !记准确值字段(记录, 节点, 状态模式准确值字段, 模式.准确值))
        return std::nullopt;
