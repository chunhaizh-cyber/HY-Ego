    const auto 概念 = 读取唯一节点字段(节点, 动作概念字段);
    const auto 主体 = 读取唯一节点字段(节点, 动作执行主体字段);
    const auto 部位 = 读取可选节点字段(节点, 动作作用部位字段);
    const auto 对象 = 读取可选节点字段(节点, 动作作用对象字段);
    const auto 方法 = 读取可选节点字段(节点, 动作本能方法字段);
