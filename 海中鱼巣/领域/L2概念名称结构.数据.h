// 诊断责任：无适用错误分支；只判断名称角色枚举的纯值范围。
inline bool L2概念名称角色有效(L2概念名称角色 角色) noexcept {
    return 角色 == L2概念名称角色::首选名称
        || 角色 == L2概念名称角色::别名
        || 角色 == L2概念名称角色::简称;
}

// 诊断责任：无适用错误分支；只判断名称事实在具名截止的值式投影。
inline bool L2概念名称事实截止投影完整(
    const L2概念名称事实& 事实, std::uint64_t 截止) noexcept {
    return 截止 != 0 && 有效(事实.名称关系.值) && 有效(事实.概念.值)
        && 有效(事实.词条.值) && L2概念名称角色有效(事实.角色)
        && 有效(事实.适用语言.值) && 有效(事实.来源稳定编码)
        && L2生命周期完整(事实.生命周期)
        && 事实.生命周期.创建事实代次 <= 截止
        && (!事实.生命周期.退出事实代次
            || *事实.生命周期.退出事实代次 <= 截止);
}

// 诊断责任：无适用错误分支；只判断名称新增请求的纯值入口形状。
inline bool L2概念名称新增请求有效(
    const L2概念名称新增请求& 请求) noexcept {
    return L2结构请求头合同有效(请求.请求头)
        && 请求.名称合同版本 == L2概念名称结构合同版本
        && 请求.请求头.期望事实代次 != 0
        && L2结构幂等身份有效(请求.幂等身份)
        && 有效(请求.概念.值) && 有效(请求.词条.值)
        && L2概念名称角色有效(请求.角色)
        && 有效(请求.适用语言.值) && 有效(请求.来源稳定编码);
}

// 诊断责任：无适用错误分支；只判断名称替换请求的纯值入口形状。
inline bool L2概念名称替换请求有效(
    const L2概念名称替换请求& 请求) noexcept {
    const bool 旧关系形状有效 = 有效(请求.旧关系.名称关系.值)
        && 有效(请求.旧关系.概念.值) && 有效(请求.旧关系.词条.值)
        && L2概念名称角色有效(请求.旧关系.角色)
        && 有效(请求.旧关系.适用语言.值)
        && 有效(请求.旧关系.来源稳定编码);
    const bool 替换无变化 = 请求.旧关系.概念 == 请求.新概念
        && 请求.旧关系.词条 == 请求.新词条
        && 请求.旧关系.角色 == 请求.新角色
        && 请求.旧关系.适用语言 == 请求.新适用语言
        && 请求.旧关系.来源稳定编码 == 请求.新来源稳定编码;
    return L2结构请求头合同有效(请求.请求头)
        && 请求.名称合同版本 == L2概念名称结构合同版本
        && 请求.请求头.期望事实代次 != 0
        && L2结构幂等身份有效(请求.幂等身份)
        && 旧关系形状有效
        && 有效(请求.新概念.值) && 有效(请求.新词条.值)
        && L2概念名称角色有效(请求.新角色)
        && 有效(请求.新适用语言.值) && 有效(请求.新来源稳定编码)
        && !替换无变化;
}

// 诊断责任：无适用错误分支；只判断名称退出请求的纯值入口形状。
inline bool L2概念名称退出请求有效(
    const L2概念名称退出请求& 请求) noexcept {
    return L2结构请求头合同有效(请求.请求头)
        && 请求.名称合同版本 == L2概念名称结构合同版本
        && 请求.请求头.期望事实代次 != 0
        && L2结构幂等身份有效(请求.幂等身份)
        && 有效(请求.关系.名称关系.值)
        && 有效(请求.关系.概念.值) && 有效(请求.关系.词条.值)
        && L2概念名称角色有效(请求.关系.角色)
        && 有效(请求.关系.适用语言.值)
        && 有效(请求.关系.来源稳定编码);
}

// 诊断责任：无适用错误分支；只判断单项读取请求的纯值入口形状。
inline bool L2概念名称读取请求有效(
    const L2概念名称读取请求& 请求) noexcept {
    const bool 当前读取 = 请求.读取类别 == L2读取类别::当前
        && 请求.历史截止事实代次 == 0;
    const bool 历史读取 = 请求.读取类别 == L2读取类别::历史
        && 请求.历史截止事实代次 != 0
        && 请求.历史截止事实代次 <= 请求.请求头.期望事实代次;
    return L2结构请求头合同有效(请求.请求头)
        && 请求.名称合同版本 == L2概念名称结构合同版本
        && 请求.请求头.期望事实代次 != 0
        && 有效(请求.名称关系.值) && (当前读取 || 历史读取);
}

