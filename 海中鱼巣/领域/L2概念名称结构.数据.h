inline bool L2概念名称写入结果::成功() const noexcept {
    if ((结果头.状态 != L2结构状态::已提交
            && 结果头.状态 != L2结构状态::精确重复)
        || 结果头.合同版本 != L2结构合同版本
        || 结果头.事实截止代次 == 0 || !结果头.变更事实代次
        || *结果头.变更事实代次 != 结果头.事实截止代次)
        return false;
    const std::uint64_t 截止 = 结果头.事实截止代次;
    const bool 新增形状 = 当前关系 && !已退出关系
        && L2概念名称事实截止投影完整(*当前关系, 截止)
        && !当前关系->生命周期.退出事实代次
        && 当前关系->生命周期.创建事实代次 == 截止;
    const bool 替换形状 = 当前关系 && 已退出关系
        && L2概念名称事实截止投影完整(*当前关系, 截止)
        && L2概念名称事实截止投影完整(*已退出关系, 截止)
        && 当前关系->名称关系 != 已退出关系->名称关系
        && !当前关系->生命周期.退出事实代次
        && 当前关系->生命周期.创建事实代次 == 截止
        && 已退出关系->生命周期.创建事实代次 < 截止
        && 已退出关系->生命周期.退出事实代次
        && *已退出关系->生命周期.退出事实代次 == 截止;
    const bool 退出形状 = !当前关系 && 已退出关系
        && L2概念名称事实截止投影完整(*已退出关系, 截止)
        && 已退出关系->生命周期.退出事实代次
        && *已退出关系->生命周期.退出事实代次 == 截止;
    return 新增形状 || 替换形状 || 退出形状;
}

inline bool L2概念名称读取结果::成功() const noexcept {
    if (结果头.状态 != L2结构状态::已读取
        || 结果头.合同版本 != L2结构合同版本
        || 结果头.事实截止代次 == 0 || 结果头.变更事实代次
        || !名称关系
        || !L2概念名称事实截止投影完整(*名称关系, 结果头.事实截止代次))
        return false;
    if (读取类别 == L2读取类别::当前)
        return 历史截止事实代次 == 0
            && !名称关系->生命周期.退出事实代次;
    return 读取类别 == L2读取类别::历史
        && 历史截止事实代次 == 结果头.事实截止代次;
}

inline bool L2概念名称组读取结果::成功() const noexcept {
    if (结果头.状态 != L2结构状态::已读取
        || 结果头.合同版本 != L2结构合同版本
        || 结果头.事实截止代次 == 0 || 结果头.变更事实代次)
        return false;
    for (const auto& 事实 : 名称关系组)
        if (!L2概念名称事实截止投影完整(事实, 结果头.事实截止代次)
            || 事实.生命周期.退出事实代次)
            return false;
    return true;
}

