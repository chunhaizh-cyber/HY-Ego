bool 特征值类数据服务::内容结构有效(
    const 特征值内容& 内容) noexcept {
    if (内容.valueless_by_exception()) return false;
    if (const auto* 引用 = std::get_if<特征值独立材料引用>(&内容)) {
        return 有效(引用->身份);
    }
    return true;
}

