bool 新_动态类::初始化() noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        if (!状态服务_.初始化() || !动态概念服务_.初始化()) return false;
        if (结构已初始化()) return 结构仍存在();
        auto 建立 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        return 建立(动态节点类型字段)
            && 建立(动态节点类型)
            && 建立(动态种类字段)
            && 建立(动态主题存在字段)
            && 建立(动态状态项字段)
            && 建立(动态状态项节点类型)
            && 建立(动态状态项顺序字段)
            && 建立(动态状态节点字段)
            && 建立(动态概念字段)
            && 建立(动态被引用次数字段)
            && 建立(复合时间项字段)
            && 建立(复合时间项节点类型)
            && 建立(复合前状态字段)
            && 建立(复合后状态字段)
            && 建立(复合前特征类型字段)
            && 建立(复合后特征类型字段)
            && 建立(复合二次特征类型字段)
            && 建立(复合结果值域字段)
            && 建立(复合时间差字段)
            && 建立(动作定义字段)
            && 建立(动作来源字段)
            && 建立(动作目标存在字段)
            && 建立(动作目标种类字段)
            && 建立(动作目标任务字段)
            && 建立(动作目标虚拟存在字段)
            && 建立(动作目标特征字段)
            && 建立(动作时间语义字段)
            && 建立(动作时间纳秒字段);
    } catch (...) {
        return false;
    }
}

新动态建立结果 新_动态类::建立原子动态(
    稳定编码 主题存在节点,
    稳定编码 前状态节点,
    稳定编码 后状态节点) noexcept {
    新动态建立结果 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        const std::vector<稳定编码> 状态节点组{前状态节点, 后状态节点};
        if (!结构仍存在() || !有效(主题存在节点)
            || !节点仍存在(主题存在节点)) return 结果;
        std::set<std::uint64_t> 唯一状态;
        std::vector<新状态信息> 状态信息组;
        状态信息组.reserve(状态节点组.size());
        for (const auto 状态节点 : 状态节点组) {
            if (!唯一状态.insert(状态节点.值).second) {
                结果.状态 = 新动态操作状态::状态重复;
                return 结果;
            }
            const auto 状态 = 状态服务_.获取状态(状态节点);
            if (!状态) {
                结果.状态 = 新动态操作状态::状态不存在;
                return 结果;
            }
            if (状态->被描述存在节点 != 主题存在节点) {
                结果.状态 = 新动态操作状态::主题不一致;
                return 结果;
            }
            状态信息组.push_back(*状态);
        }
        for (std::size_t i = 0; i < 状态信息组.size(); ++i) {
            if (状态信息组[i].强时间.语义 != 新状态时间语义::实例绝对UTC
                || (i > 0 && 状态信息组[i].强时间.纳秒
                    <= 状态信息组[i - 1].强时间.纳秒)) {
                结果.状态 = 新动态操作状态::时间不合法;
                return 结果;
            }
        }
        if (状态信息组[0].特征类型概念节点
            != 状态信息组[1].特征类型概念节点) {
            结果.状态 = 新动态操作状态::特征类型不一致;
            return 结果;
        }
        auto 状态引用组 = 建立状态引用组(状态节点组);
        if (!状态引用组) {
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        const auto 动态节点 = 全局基础数据集.新建节点();
        std::vector<稳定编码> 已写字段;
        if (!有效(动态节点)) {
            清理状态引用组(*状态引用组);
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        auto 记录 = [&](稳定编码 字段) {
            if (!有效(字段)) return false;
            已写字段.push_back(字段);
            return true;
        };
        bool 完整 = 记录(全局基础数据集.添加字段节点(
                动态节点, 动态节点类型字段, 动态节点类型))
            && 记录(全局基础数据集.添加字段值(
                动态节点, 动态种类字段,
                基础值{static_cast<std::int64_t>(新动态种类::原子)}))
            && 记录(全局基础数据集.添加字段节点(
                动态节点, 动态主题存在字段, 主题存在节点))
            && 记录(全局基础数据集.添加字段值(
                动态节点, 动态被引用次数字段, 基础值{std::int64_t{0}}));
        for (auto& 引用 : *状态引用组) {
            if (!完整) break;
            const auto 字段 = 全局基础数据集.添加字段节点(
                动态节点, 动态状态项字段, 引用.节点);
            if (!有效(字段)) {
                完整 = false;
                break;
            }
            引用.持有字段 = 字段;
        }
        if (!完整) {
            清理动态基础字段(动态节点, 已写字段, *状态引用组);
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        std::vector<稳定编码> 已增加引用;
        for (const auto 状态节点 : 状态节点组) {
            if (状态服务_.增加引用(状态节点) != 新状态操作状态::已完成) {
                for (auto 位置 = 已增加引用.rbegin();
                    位置 != 已增加引用.rend(); ++位置) {
                    (void)状态服务_.撤销增加引用(*位置);
                }
                清理动态基础字段(动态节点, 已写字段, *状态引用组);
                结果.状态 = 新动态操作状态::资源失败;
                return 结果;
            }
            已增加引用.push_back(状态节点);
        }
        const auto 概念结果 = 动态概念服务_.建立实例动态概念(
            动态节点, 状态信息组);
        if (概念结果.状态 != 动态概念操作状态::已建立
            || !概念结果.概念节点) {
            for (auto 位置 = 已增加引用.rbegin();
                位置 != 已增加引用.rend(); ++位置) {
                (void)状态服务_.撤销增加引用(*位置);
            }
            清理动态基础字段(动态节点, 已写字段, *状态引用组);
            结果.状态 = 新动态操作状态::实例概念失败;
            return 结果;
        }
        const auto 概念字段关系 = 全局基础数据集.添加字段节点(
            动态节点, 动态概念字段, *概念结果.概念节点);
        if (!有效(概念字段关系)) {
            (void)动态概念服务_.删除实例动态概念(
                *概念结果.概念节点, 动态节点);
            for (auto 位置 = 已增加引用.rbegin();
                位置 != 已增加引用.rend(); ++位置) {
                (void)状态服务_.撤销增加引用(*位置);
            }
            清理动态基础字段(动态节点, 已写字段, *状态引用组);
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        已写字段.push_back(概念字段关系);
        const auto 读回 = 获取动态(动态节点);
        if (!读回 || 读回->种类 != 新动态种类::原子
            || 读回->主题存在节点 != 主题存在节点
            || 读回->状态节点组 != 状态节点组
            || 读回->动态概念节点 != 概念结果.概念节点
            || 读回->被引用次数 != 0) {
            (void)全局基础数据集.删除字段(概念字段关系);
            已写字段.pop_back();
            (void)动态概念服务_.删除实例动态概念(
                *概念结果.概念节点, 动态节点);
            for (auto 位置 = 已增加引用.rbegin();
                位置 != 已增加引用.rend(); ++位置) {
                (void)状态服务_.撤销增加引用(*位置);
            }
            清理动态基础字段(动态节点, 已写字段, *状态引用组);
            结果.状态 = 新动态操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新动态操作状态::已完成;
        结果.动态节点 = 动态节点;
        结果.动态概念节点 = *概念结果.概念节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新动态操作状态::资源失败;
        结果.动态节点.reset();
        结果.动态概念节点.reset();
        return 结果;
    }
}

新动态建立结果 新_动态类::建立动态(
    稳定编码 主题存在节点,
    const std::vector<稳定编码>& 状态节点组) noexcept {
    if (状态节点组.size() != 2) {
        新动态建立结果 结果;
        结果.状态 = 新动态操作状态::状态数量不合法;
        return 结果;
    }
    return 建立原子动态(
        主题存在节点, 状态节点组.front(), 状态节点组.back());
}

新动态建立结果 新_动态类::建立动作动态(
    const 新动作动态建立请求& 请求) noexcept {
    return 建立已核验动作动态(请求, std::nullopt);
}

新动态建立结果 新_动态类::建立内部治理动作动态(
    const 新内部治理动作动态建立请求& 请求,
    const 新内部治理对象读取接口& 目标读取服务) noexcept {
    // 回调必须在动态锁外，避免 dynamic -> task 的逆向锁序。
    const auto 目标 = 目标读取服务.读取任务虚拟存在引用(请求.目标);
    if (!目标 || 目标->引用 != 请求.目标
        || !节点仍存在(目标->状态特征类型概念节点)
        || !节点仍存在(请求.目标.任务节点)
        || !节点仍存在(请求.目标.虚拟存在节点)
        || !节点仍存在(请求.目标.状态特征节点)) {
        新动态建立结果 结果;
        结果.状态 = 新动态操作状态::动作信息不合法;
        return 结果;
    }
    return 建立已核验动作动态({请求.执行主体节点, 请求.动作定义节点,
        请求.动作来源节点, {}, 请求.目标.状态特征节点, 请求.动作时间},
        请求.目标);
}

新动态建立结果 新_动态类::建立已核验动作动态(
    const 新动作动态建立请求& 请求,
    const std::optional<新任务虚拟存在引用>& 内部目标) noexcept {
    新动态建立结果 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        if (!结构仍存在() || !存在服务_
            || !有效(请求.执行主体节点)
            || !有效(请求.动作定义节点)
            || !有效(请求.动作来源节点)
            || (!内部目标 && !有效(请求.目标存在节点))
            || !节点仍存在(请求.动作定义节点)
            || !节点仍存在(请求.动作来源节点)
            || 请求.动作时间.语义 != 新状态时间语义::实例绝对UTC
            || 请求.动作时间.纳秒 < 0) {
            结果.状态 = 新动态操作状态::动作信息不合法;
            return 结果;
        }
        const auto 主体 = 存在服务_->获取存在(请求.执行主体节点);
        const auto 目标 = 内部目标 ? std::nullopt
            : 存在服务_->获取存在(请求.目标存在节点);
        if (!主体 || (!内部目标 && !目标)) {
            结果.状态 = 新动态操作状态::动作信息不合法;
            return 结果;
        }
        if (!内部目标 && 请求.目标特征节点
            && std::find(目标->特征节点组.begin(), 目标->特征节点组.end(),
                *请求.目标特征节点) == 目标->特征节点组.end()) {
            结果.状态 = 新动态操作状态::动作信息不合法;
            return 结果;
        }

        const auto 来源引用 = 全局基础数据集.查询目标字段(
            请求.动作来源节点, 动作来源字段);
        if (来源引用.size() > 1) {
            结果.状态 = 新动态操作状态::结构不一致;
            return 结果;
        }
        if (来源引用.size() == 1) {
            const auto 已有 = 获取动态(来源引用.front().所属节点);
            if (!已有 || 已有->种类 != 新动态种类::动作
                || !已有->动作定义节点 || !已有->动作来源节点
                || !已有->动作时间) {
                结果.状态 = 新动态操作状态::结构不一致;
                return 结果;
            }
            if (已有->主题存在节点 == 请求.执行主体节点
                && *已有->动作定义节点 == 请求.动作定义节点
                && *已有->动作来源节点 == 请求.动作来源节点
                && 已有->动作目标种类 == (内部目标
                    ? 新动作目标种类::任务虚拟存在 : 新动作目标种类::普通存在)
                && 已有->动作目标任务虚拟存在 == 内部目标
                && 已有->动作目标存在节点 == (内部目标
                    ? std::nullopt : std::optional<稳定编码>{请求.目标存在节点})
                && 已有->动作目标特征节点 == 请求.目标特征节点
                && *已有->动作时间 == 请求.动作时间) {
                结果.状态 = 新动态操作状态::无变化;
                结果.动态节点 = 已有->节点;
                return 结果;
            }
            结果.状态 = 新动态操作状态::动作来源冲突;
            return 结果;
        }

        const auto 动态节点 = 全局基础数据集.新建节点();
        std::vector<稳定编码> 已写字段;
        if (!有效(动态节点)) {
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        const auto 记录节点 = [&](稳定编码 字段, 稳定编码 值) {
            const auto 记录 = 全局基础数据集.添加字段节点(动态节点, 字段, 值);
            if (!有效(记录)) return false;
            已写字段.push_back(记录);
            return true;
        };
        const auto 记录I64 = [&](稳定编码 字段, std::int64_t 值) {
            const auto 记录 = 全局基础数据集.添加字段值(
                动态节点, 字段, 基础值{值});
            if (!有效(记录)) return false;
            已写字段.push_back(记录);
            return true;
        };
        const auto 清理未发布动作 = [&]() noexcept {
            for (auto 位置 = 已写字段.rbegin(); 位置 != 已写字段.rend(); ++位置) {
                (void)全局基础数据集.删除字段(*位置);
            }
            已写字段.clear();
            (void)全局基础数据集.删除节点(动态节点);
        };
        bool 完整 = 记录节点(动态节点类型字段, 动态节点类型)
            && 记录I64(动态种类字段,
                static_cast<std::int64_t>(新动态种类::动作))
            && 记录节点(动态主题存在字段, 请求.执行主体节点)
            && 记录I64(动态被引用次数字段, 0)
            && 记录节点(动作定义字段, 请求.动作定义节点)
            && 记录节点(动作来源字段, 请求.动作来源节点)
            && 记录I64(动作目标种类字段, static_cast<std::int64_t>(内部目标
                ? 新动作目标种类::任务虚拟存在 : 新动作目标种类::普通存在))
            && 记录I64(动作时间语义字段,
                static_cast<std::int64_t>(请求.动作时间.语义))
            && 记录I64(动作时间纳秒字段, 请求.动作时间.纳秒);
        if (完整) {
            完整 = 内部目标
                ? 记录节点(动作目标任务字段, 内部目标->任务节点)
                    && 记录节点(动作目标虚拟存在字段, 内部目标->虚拟存在节点)
                : 记录节点(动作目标存在字段, 请求.目标存在节点);
        }
        if (完整 && 请求.目标特征节点) {
            完整 = 记录节点(动作目标特征字段, *请求.目标特征节点);
        }
        if (!完整) {
            清理未发布动作();
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        const auto 读回 = 获取动态(动态节点);
        if (!读回 || 读回->种类 != 新动态种类::动作
            || 读回->主题存在节点 != 请求.执行主体节点
            || 读回->动作定义节点 != 请求.动作定义节点
            || 读回->动作来源节点 != 请求.动作来源节点
            || 读回->动作目标任务虚拟存在 != 内部目标
            || 读回->动作目标存在节点 != (内部目标
                ? std::nullopt : std::optional<稳定编码>{请求.目标存在节点})
            || 读回->动作目标特征节点 != 请求.目标特征节点
            || 读回->动作时间 != 请求.动作时间
            || !读回->动作结果组.empty()
            || 读回->被引用次数 != 0) {
            清理未发布动作();
            结果.状态 = 新动态操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新动态操作状态::已完成;
        结果.动态节点 = 动态节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新动态操作状态::资源失败;
        结果.动态节点.reset();
        return 结果;
    }
}

新动态操作状态 新_动态类::关联动作结果(
    稳定编码 动作动态节点,
    稳定编码 结果动态节点,
    新动作结果关系类型 关系类型) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 动作 = 获取动态(动作动态节点);
        const auto 结果 = 获取动态(结果动态节点);
        if (!动作) return 节点仍存在(动作动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        if (动作->种类 != 新动态种类::动作 || !动作->动作目标存在节点
            || !动作->动作时间) return 新动态操作状态::不是动作动态;
        if (!结果 || 结果->种类 == 新动态种类::动作
            || 结果->状态节点组.empty()) {
            return 新动态操作状态::动作结果不匹配;
        }

        std::int64_t 最早时间 = (std::numeric_limits<std::int64_t>::max)();
        std::int64_t 最晚时间 = (std::numeric_limits<std::int64_t>::min)();
        bool 命中目标特征 = !动作->动作目标特征节点.has_value();
        bool 命中目标存在 = false;
        for (const auto 状态节点 : 结果->状态节点组) {
            const auto 状态 = 状态服务_.获取状态(状态节点);
            if (!状态 || 状态->强时间.语义 != 新状态时间语义::实例绝对UTC) {
                return 新动态操作状态::结构不一致;
            }
            最早时间 = (std::min)(最早时间, 状态->强时间.纳秒);
            最晚时间 = (std::max)(最晚时间, 状态->强时间.纳秒);
            if (状态->被描述存在节点 == *动作->动作目标存在节点) {
                命中目标存在 = true;
                if (动作->动作目标特征节点
                    && 状态->来源实例特征节点 == *动作->动作目标特征节点) {
                    命中目标特征 = true;
                }
            }
        }
        if (!命中目标存在 || !命中目标特征) {
            return 新动态操作状态::动作结果不匹配;
        }
        const auto 动作时间 = 动作->动作时间->纳秒;
        const bool 时间成立 = 关系类型 == 新动作结果关系类型::导致变化
            ? 最早时间 <= 动作时间 && 动作时间 <= 最晚时间
            : 最晚时间 <= 动作时间;
        if (!时间成立) return 新动态操作状态::时间不合法;

        const auto 目标角色 = 动作结果关系角色(关系类型);
        for (const auto& 关系 : 全局基础数据集.查询源关系(
            动作动态节点, 基础外部关系类型::父子)) {
            const auto 已有类型 = 读取动作结果关系类型(关系.角色或顺序);
            if (!已有类型) return 新动态操作状态::结构不一致;
            if (关系.目标节点 == 结果动态节点) {
                return 关系.角色或顺序 == 目标角色
                    ? 新动态操作状态::无变化
                    : 新动态操作状态::动作关系冲突;
            }
        }

        const auto 增加引用结果 = 增加引用(结果动态节点);
        if (增加引用结果 != 新动态操作状态::已完成) {
            return 增加引用结果;
        }
        const auto 关系 = 全局基础数据集.添加关系(
            动作动态节点, 结果动态节点, 基础外部关系类型::父子, 目标角色);
        if (!有效(关系)) {
            (void)撤销增加引用(结果动态节点);
            return 新动态操作状态::资源失败;
        }
        const auto 读回 = 获取动态(动作动态节点);
        if (!读回 || std::none_of(读回->动作结果组.begin(),
                读回->动作结果组.end(), [&](const auto& 项) {
                    return 项.类型 == 关系类型
                        && 项.结果动态节点 == 结果动态节点;
                })) {
            (void)全局基础数据集.删除关系(关系);
            (void)撤销增加引用(结果动态节点);
            return 新动态操作状态::结构不一致;
        }
        return 新动态操作状态::已完成;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

新动态建立结果 新_动态类::建立复合动态(
    稳定编码 主题存在节点,
    const std::vector<稳定编码>& 成员动态组) noexcept {
    新动态建立结果 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        if (!结构仍存在()) return 结果;
        if (!存在服务_ || !二次特征服务_) {
            结果.状态 = 新动态操作状态::依赖未配置;
            return 结果;
        }
        if (成员动态组.size() < 2) {
            结果.状态 = 新动态操作状态::复合成员不足;
            return 结果;
        }
        if (!存在服务_->获取存在(主题存在节点)) {
            结果.状态 = 新动态操作状态::主题不属于存在树;
            return 结果;
        }

        std::set<std::uint64_t> 主题树{主题存在节点.值};
        std::vector<稳定编码> 待展开{主题存在节点};
        for (std::size_t i = 0; i < 待展开.size(); ++i) {
            for (const auto 子存在 : 存在服务_->查询直接子存在(待展开[i])) {
                if (主题树.insert(子存在.值).second) 待展开.push_back(子存在);
            }
        }

        auto 规范成员 = 成员动态组;
        std::sort(规范成员.begin(), 规范成员.end());
        if (std::adjacent_find(规范成员.begin(), 规范成员.end())
            != 规范成员.end()) {
            结果.状态 = 新动态操作状态::状态重复;
            return 结果;
        }

        struct 时间状态 final {
            新状态信息 状态;
        };
        struct 原子成员材料 final {
            新动态信息 动态;
            新状态信息 前状态;
            新状态信息 后状态;
        };
        std::map<std::uint64_t, 时间状态> 唯一状态;
        std::map<std::pair<std::uint64_t, std::uint64_t>,
            std::vector<原子成员材料>> 串行通道;
        std::set<std::uint64_t> 特征类型组;
        std::vector<稳定编码> 有序成员动态概念组;
        有序成员动态概念组.reserve(规范成员.size());
        for (const auto 成员节点 : 规范成员) {
            const auto 成员 = 获取动态(成员节点);
            if (!成员) {
                结果.状态 = 新动态操作状态::动态不存在;
                return 结果;
            }
            if (成员->种类 != 新动态种类::原子
                || 成员->状态节点组.size() != 2
                || !成员->动态概念节点) {
                结果.状态 = 新动态操作状态::不是原子动态;
                return 结果;
            }
            const auto 成员概念 = 动态概念服务_.获取动态概念(
                *成员->动态概念节点);
            if (!成员概念 || 成员概念->状态变化组.size() != 1) {
                结果.状态 = 新动态操作状态::概念不合法;
                return 结果;
            }
            有序成员动态概念组.push_back(*成员->动态概念节点);
            if (!主题树.contains(成员->主题存在节点.值)) {
                结果.状态 = 新动态操作状态::主题不属于存在树;
                return 结果;
            }
            const auto 前状态 = 状态服务_.获取状态(成员->状态节点组[0]);
            const auto 后状态 = 状态服务_.获取状态(成员->状态节点组[1]);
            if (!前状态 || !后状态) {
                结果.状态 = 新动态操作状态::状态不存在;
                return 结果;
            }
            if (前状态->被描述存在节点 != 成员->主题存在节点
                || 后状态->被描述存在节点 != 成员->主题存在节点) {
                结果.状态 = 新动态操作状态::主题不一致;
                return 结果;
            }
            if (前状态->特征类型概念节点
                    != 后状态->特征类型概念节点) {
                结果.状态 = 新动态操作状态::特征类型不一致;
                return 结果;
            }
            if (前状态->强时间.语义 != 新状态时间语义::实例绝对UTC
                || 后状态->强时间.语义 != 新状态时间语义::实例绝对UTC
                || 后状态->强时间.纳秒 <= 前状态->强时间.纳秒) {
                结果.状态 = 新动态操作状态::时间不合法;
                return 结果;
            }
            for (const auto& 状态 : {*前状态, *后状态}) {
                const auto [位置, 新增] = 唯一状态.emplace(
                    状态.节点.值, 时间状态{状态});
                if (!新增 && 位置->second.状态 != 状态) {
                    结果.状态 = 新动态操作状态::结构不一致;
                    return 结果;
                }
            }
            const auto 特征类型 = 前状态->特征类型概念节点;
            特征类型组.insert(特征类型.值);
            串行通道[{成员->主题存在节点.值, 特征类型.值}].push_back(
                {*成员, *前状态, *后状态});
        }
        for (auto& [_, 通道] : 串行通道) {
            std::sort(通道.begin(), 通道.end(), [](const auto& 左, const auto& 右) {
                if (左.前状态.强时间.纳秒 != 右.前状态.强时间.纳秒) {
                    return 左.前状态.强时间.纳秒 < 右.前状态.强时间.纳秒;
                }
                return 左.动态.节点 < 右.动态.节点;
            });
            for (std::size_t i = 1; i < 通道.size(); ++i) {
                if (通道[i - 1].后状态.节点 != 通道[i].前状态.节点) {
                    结果.状态 = 新动态操作状态::端点不连续;
                    return 结果;
                }
            }
        }
        if (特征类型组.size() < 2) {
            结果.状态 = 新动态操作状态::跨特征不足;
            return 结果;
        }

        std::vector<新状态信息> 时间轴;
        时间轴.reserve(唯一状态.size());
        for (const auto& [_, 项] : 唯一状态) 时间轴.push_back(项.状态);
        std::sort(时间轴.begin(), 时间轴.end(), [](const auto& 左, const auto& 右) {
            if (左.强时间.纳秒 != 右.强时间.纳秒) {
                return 左.强时间.纳秒 < 右.强时间.纳秒;
            }
            return 左.节点 < 右.节点;
        });

        std::vector<std::pair<std::size_t, std::size_t>> 时间组;
        for (std::size_t 开始 = 0; 开始 < 时间轴.size();) {
            auto 结束 = 开始 + 1;
            while (结束 < 时间轴.size()
                && 时间轴[结束].强时间.纳秒 == 时间轴[开始].强时间.纳秒) {
                ++结束;
            }
            时间组.push_back({开始, 结束});
            开始 = 结束;
        }

        std::vector<新动态跨特征时间项> 跨特征时间组;
        std::set<std::pair<std::uint64_t, std::uint64_t>> 已比较;
        const auto 计算一对 = [&](const 新状态信息& 前,
            const 新状态信息& 后) -> bool {
            if (前.特征类型概念节点 == 后.特征类型概念节点) return true;
            const auto 键 = std::pair{前.节点.值, 后.节点.值};
            if (!已比较.insert(键).second) return true;
            const auto 计算 = 二次特征服务_->比较状态出现时间(
                {前.节点, 前.特征类型概念节点, 前.强时间.纳秒},
                {后.节点, 后.特征类型概念节点, 后.强时间.纳秒});
            if (计算.状态 != 新二次特征计算状态::已完成
                || !计算.二次特征类型概念节点
                || !计算.结果值域概念节点 || !计算.结果值) {
                return false;
            }
            跨特征时间组.push_back({前.节点, 后.节点,
                前.特征类型概念节点, 后.特征类型概念节点,
                *计算.二次特征类型概念节点,
                *计算.结果值域概念节点, *计算.结果值});
            return true;
        };
        for (std::size_t g = 0; g < 时间组.size(); ++g) {
            const auto [开始, 结束] = 时间组[g];
            for (auto i = 开始; i < 结束; ++i) {
                for (auto j = i + 1; j < 结束; ++j) {
                    if (!计算一对(时间轴[i], 时间轴[j])) {
                        结果.状态 = 新动态操作状态::二次特征计算失败;
                        return 结果;
                    }
                }
            }
            if (g + 1 == 时间组.size()) continue;
            const auto [下开始, 下结束] = 时间组[g + 1];
            for (auto i = 开始; i < 结束; ++i) {
                for (auto j = 下开始; j < 下结束; ++j) {
                    if (!计算一对(时间轴[i], 时间轴[j])) {
                        结果.状态 = 新动态操作状态::二次特征计算失败;
                        return 结果;
                    }
                }
            }
        }
        if (跨特征时间组.empty()) {
            结果.状态 = 新动态操作状态::跨特征不足;
            return 结果;
        }
        std::sort(跨特征时间组.begin(), 跨特征时间组.end(),
            [](const auto& 左, const auto& 右) {
                if (左.前状态节点 != 右.前状态节点) {
                    return 左.前状态节点 < 右.前状态节点;
                }
                return 左.后状态节点 < 右.后状态节点;
            });

        auto 时间项组 = 建立复合时间项组(跨特征时间组);
        if (!时间项组) {
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        const auto 动态节点 = 全局基础数据集.新建节点();
        std::vector<稳定编码> 已写字段;
        std::vector<稳定编码> 已写关系;
        std::vector<稳定编码> 已增加引用;
        std::optional<稳定编码> 已建实例概念;
        std::optional<稳定编码> 已写概念字段;
        auto 失败清理 = [&]() noexcept {
            if (已写概念字段) {
                (void)全局基础数据集.删除字段(*已写概念字段);
                已写概念字段.reset();
            }
            if (已建实例概念) {
                (void)动态概念服务_.删除实例动态概念(
                    *已建实例概念, 动态节点);
                已建实例概念.reset();
            }
            for (auto 关系 = 已写关系.rbegin(); 关系 != 已写关系.rend(); ++关系) {
                (void)全局基础数据集.删除关系(*关系);
            }
            for (auto 引用 = 已增加引用.rbegin(); 引用 != 已增加引用.rend(); ++引用) {
                (void)撤销增加引用(*引用);
            }
            for (auto 字段 = 已写字段.rbegin(); 字段 != 已写字段.rend(); ++字段) {
                (void)全局基础数据集.删除字段(*字段);
            }
            清理复合时间项组(*时间项组);
            if (有效(动态节点)) (void)全局基础数据集.删除节点(动态节点);
        };
        if (!有效(动态节点)) {
            失败清理();
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        auto 记录 = [&](稳定编码 字段) {
            if (!有效(字段)) return false;
            已写字段.push_back(字段);
            return true;
        };
        bool 完整 = 记录(全局基础数据集.添加字段节点(
                动态节点, 动态节点类型字段, 动态节点类型))
            && 记录(全局基础数据集.添加字段值(
                动态节点, 动态种类字段,
                基础值{static_cast<std::int64_t>(新动态种类::复合)}))
            && 记录(全局基础数据集.添加字段节点(
                动态节点, 动态主题存在字段, 主题存在节点))
            && 记录(全局基础数据集.添加字段值(
                动态节点, 动态被引用次数字段, 基础值{std::int64_t{0}}));
        for (auto& 时间项 : *时间项组) {
            if (!完整) break;
            const auto 字段 = 全局基础数据集.添加字段节点(
                动态节点, 复合时间项字段, 时间项.节点);
            if (!有效(字段)) 完整 = false;
            else 时间项.持有字段 = 字段;
        }
        if (!完整) {
            失败清理();
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        for (const auto 成员节点 : 规范成员) {
            if (增加引用(成员节点) != 新动态操作状态::已完成) {
                失败清理();
                结果.状态 = 新动态操作状态::资源失败;
                return 结果;
            }
            已增加引用.push_back(成员节点);
            const auto 关系 = 全局基础数据集.添加关系(
                动态节点, 成员节点, 基础外部关系类型::父子,
                新复合动态成员关系角色);
            if (!有效(关系)) {
                失败清理();
                结果.状态 = 新动态操作状态::资源失败;
                return 结果;
            }
            已写关系.push_back(关系);
        }

        std::vector<动态概念特征项> 概念特征组;
        概念特征组.reserve(跨特征时间组.size());
        for (std::size_t i = 0; i < 跨特征时间组.size(); ++i) {
            const auto& 时间项 = 跨特征时间组[i];
            概念特征组.push_back({static_cast<std::int64_t>(i),
                时间项.二次特征类型概念节点, 时间项.时间差纳秒,
                时间项.结果值域概念节点,
                时间项.前状态节点, 时间项.后状态节点});
        }
        const auto 概念结果 = 动态概念服务_.建立复合实例动态概念(
            动态节点, 有序成员动态概念组, 概念特征组);
        if (概念结果.状态 != 动态概念操作状态::已建立
            || !概念结果.概念节点) {
            失败清理();
            结果.状态 = 新动态操作状态::实例概念失败;
            return 结果;
        }
        已建实例概念 = *概念结果.概念节点;
        const auto 概念字段 = 全局基础数据集.添加字段节点(
            动态节点, 动态概念字段, *概念结果.概念节点);
        if (!有效(概念字段)) {
            失败清理();
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        已写概念字段 = 概念字段;

        const auto 读回 = 获取动态(动态节点);
        if (!读回 || 读回->种类 != 新动态种类::复合
            || 读回->主题存在节点 != 主题存在节点
            || 读回->成员动态节点组 != 规范成员
            || 读回->状态节点组.size() != 时间轴.size()
            || 读回->跨特征时间组 != 跨特征时间组
            || 读回->动态概念节点 != 概念结果.概念节点
            || 读回->被引用次数 != 0) {
            失败清理();
            结果.状态 = 新动态操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新动态操作状态::已完成;
        结果.动态节点 = 动态节点;
        结果.动态概念节点 = *概念结果.概念节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新动态操作状态::资源失败;
        结果.动态节点.reset();
        结果.动态概念节点.reset();
        return 结果;
    }
}

std::optional<新动态信息> 新_动态类::获取动态(
    稳定编码 动态节点) const noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        if (!是动态节点(动态节点)) return std::nullopt;
        const auto 种类值 = 读取唯一I64字段(动态节点, 动态种类字段);
        const auto 主题 = 读取唯一节点字段(动态节点, 动态主题存在字段);
        const auto 引用 = 读取唯一I64字段(动态节点, 动态被引用次数字段);
        if (!种类值 || !主题 || !引用 || 引用->second < 0) return std::nullopt;

        if (种类值->second == static_cast<std::int64_t>(新动态种类::原子)) {
            const auto 状态组 = 读取有序状态组(动态节点);
            const auto 概念 = 读取唯一节点字段(动态节点, 动态概念字段);
            const auto 概念信息 = 概念
                ? 动态概念服务_.获取动态概念(*概念) : std::nullopt;
            if (!状态组 || 状态组->size() != 2
                || !读取复合成员组(动态节点).empty()
                || !全局基础数据集.查询字段(
                    动态节点, 复合时间项字段).empty()
                || !概念信息
                || (概念信息->种类 == 动态概念种类::实例
                    && 概念信息->对应动态节点 != 动态节点)) {
                return std::nullopt;
            }
            新动态信息 信息;
            信息.节点 = 动态节点;
            信息.种类 = 新动态种类::原子;
            信息.主题存在节点 = *主题;
            信息.状态节点组 = *状态组;
            信息.动态概念节点 = *概念;
            信息.被引用次数 = 引用->second;
            return 信息;
        }
        if (种类值->second == static_cast<std::int64_t>(新动态种类::动作)) {
            const auto 定义 = 读取唯一节点字段(动态节点, 动作定义字段);
            const auto 来源 = 读取唯一节点字段(动态节点, 动作来源字段);
            const auto 目标存在 = 读取唯一节点字段(动态节点, 动作目标存在字段);
            const auto 目标种类组 = 全局基础数据集.查询字段(动态节点, 动作目标种类字段);
            const auto 目标种类值 = 读取唯一I64字段(动态节点, 动作目标种类字段);
            if (目标种类组.size() > 1
                || (!目标种类组.empty() && !目标种类值)) return std::nullopt;
            const auto 目标种类 = 目标种类值 ? 目标种类值->second
                : static_cast<std::int64_t>(新动作目标种类::普通存在);
            if (目标种类 != static_cast<std::int64_t>(新动作目标种类::普通存在)
                && 目标种类 != static_cast<std::int64_t>(新动作目标种类::任务虚拟存在)) {
                return std::nullopt;
            }
            const bool 内部目标 = 目标种类
                == static_cast<std::int64_t>(新动作目标种类::任务虚拟存在);
            const auto 目标任务 = 读取唯一节点字段(动态节点, 动作目标任务字段);
            const auto 目标虚拟存在 = 读取唯一节点字段(动态节点, 动作目标虚拟存在字段);
            if (内部目标) {
                if (!目标任务 || !目标虚拟存在
                    || !全局基础数据集.查询字段(动态节点, 动作目标存在字段).empty()) {
                    return std::nullopt;
                }
            } else if (!目标存在
                || !全局基础数据集.查询字段(动态节点, 动作目标任务字段).empty()
                || !全局基础数据集.查询字段(动态节点, 动作目标虚拟存在字段).empty()) {
                return std::nullopt;
            }
            const auto 目标特征组 = 全局基础数据集.查询字段(
                动态节点, 动作目标特征字段);
            const auto 时间语义 = 读取唯一I64字段(动态节点, 动作时间语义字段);
            const auto 时间纳秒 = 读取唯一I64字段(动态节点, 动作时间纳秒字段);
            const auto 结果组 = 读取动作结果组(动态节点);
            const auto 直接状态组 = 读取有序状态组(动态节点);
            if (!定义 || !来源
                || 目标特征组.size() > 1 || !时间语义 || !时间纳秒
                || 时间语义->second
                    != static_cast<std::int64_t>(新状态时间语义::实例绝对UTC)
                || 时间纳秒->second < 0 || !结果组
                || !直接状态组 || !直接状态组->empty()
                || !读取复合成员组(动态节点).empty()
                || !全局基础数据集.查询字段(
                    动态节点, 复合时间项字段).empty()
                || !全局基础数据集.查询字段(
                    动态节点, 动态概念字段).empty()) {
                return std::nullopt;
            }
            std::optional<稳定编码> 目标特征;
            if (!目标特征组.empty()) {
                const auto* 节点 = std::get_if<稳定编码>(
                    &目标特征组.front().内容);
                if (!节点 || !节点仍存在(*节点)) return std::nullopt;
                目标特征 = *节点;
            }
            if (内部目标 && !目标特征) return std::nullopt;
            for (const auto& 关联 : *结果组) {
                if (关联.结果动态节点 == 动态节点) return std::nullopt;
                const auto 结果种类 = 读取唯一I64字段(
                    关联.结果动态节点, 动态种类字段);
                if (!结果种类
                    || 结果种类->second
                        == static_cast<std::int64_t>(新动态种类::动作)
                    || !获取动态(关联.结果动态节点)) {
                    return std::nullopt;
                }
            }
            新动态信息 信息;
            信息.节点 = 动态节点;
            信息.种类 = 新动态种类::动作;
            信息.主题存在节点 = *主题;
            信息.动作定义节点 = *定义;
            信息.动作来源节点 = *来源;
            信息.动作目标种类 = static_cast<新动作目标种类>(目标种类);
            if (内部目标) {
                信息.动作目标任务虚拟存在 = 新任务虚拟存在引用{
                    *目标任务, *目标虚拟存在, *目标特征};
            } else {
                信息.动作目标存在节点 = *目标存在;
            }
            信息.动作目标特征节点 = 目标特征;
            信息.动作时间 = 新状态强时间{
                新状态时间语义::实例绝对UTC, 时间纳秒->second};
            信息.动作结果组 = *结果组;
            信息.被引用次数 = 引用->second;
            return 信息;
        }
        if (种类值->second != static_cast<std::int64_t>(新动态种类::复合)) {
            return std::nullopt;
        }
        const auto 直接状态组 = 读取有序状态组(动态节点);
        const auto 成员组 = 读取复合成员组(动态节点);
        const auto 时间特征组 = 读取复合时间组(动态节点);
        const auto 概念 = 读取唯一节点字段(动态节点, 动态概念字段);
        const auto 概念信息 = 概念
            ? 动态概念服务_.获取动态概念(*概念) : std::nullopt;
        if (!直接状态组 || !直接状态组->empty()
            || 成员组.size() < 2 || !时间特征组 || 时间特征组->empty()
            || !概念信息
            || (概念信息->种类 == 动态概念种类::实例
                && 概念信息->对应动态节点 != 动态节点)) {
            return std::nullopt;
        }
        std::map<std::uint64_t, 新状态信息> 状态索引;
        std::set<std::uint64_t> 特征类型组;
        std::map<std::pair<std::uint64_t, std::uint64_t>,
            std::vector<std::pair<新状态信息, 新状态信息>>> 串行通道;
        for (const auto 成员节点 : 成员组) {
            const auto 成员 = 获取动态(成员节点);
            if (!成员 || 成员->种类 != 新动态种类::原子
                || 成员->状态节点组.size() != 2
                || !成员->动态概念节点) return std::nullopt;
            const auto 前状态 = 状态服务_.获取状态(成员->状态节点组[0]);
            const auto 后状态 = 状态服务_.获取状态(成员->状态节点组[1]);
            if (!前状态 || !后状态
                || 前状态->被描述存在节点 != 成员->主题存在节点
                || 后状态->被描述存在节点 != 成员->主题存在节点
                || 前状态->特征类型概念节点
                    != 后状态->特征类型概念节点
                || 前状态->强时间.语义 != 新状态时间语义::实例绝对UTC
                || 后状态->强时间.语义 != 新状态时间语义::实例绝对UTC
                || 后状态->强时间.纳秒 <= 前状态->强时间.纳秒) {
                return std::nullopt;
            }
            for (const auto& 状态 : {*前状态, *后状态}) {
                const auto [位置, 新增] = 状态索引.emplace(状态.节点.值, 状态);
                if (!新增 && 位置->second != 状态) return std::nullopt;
            }
            const auto 特征类型 = 前状态->特征类型概念节点;
            特征类型组.insert(特征类型.值);
            串行通道[{成员->主题存在节点.值, 特征类型.值}].push_back(
                {*前状态, *后状态});
        }
        if (特征类型组.size() < 2) return std::nullopt;
        for (auto& [_, 通道] : 串行通道) {
            std::sort(通道.begin(), 通道.end(), [](const auto& 左, const auto& 右) {
                if (左.first.强时间.纳秒 != 右.first.强时间.纳秒) {
                    return 左.first.强时间.纳秒 < 右.first.强时间.纳秒;
                }
                return 左.first.节点 < 右.first.节点;
            });
            for (std::size_t i = 1; i < 通道.size(); ++i) {
                if (通道[i - 1].second.节点 != 通道[i].first.节点) {
                    return std::nullopt;
                }
            }
        }
        for (const auto& 时间 : *时间特征组) {
            const auto 前 = 状态索引.find(时间.前状态节点.值);
            const auto 后 = 状态索引.find(时间.后状态节点.值);
            if (前 == 状态索引.end() || 后 == 状态索引.end()
                || 前->second.特征类型概念节点 != 时间.前特征类型概念节点
                || 后->second.特征类型概念节点 != 时间.后特征类型概念节点
                || 前->second.特征类型概念节点
                    == 后->second.特征类型概念节点
                || 计算饱和时间差(前->second.强时间.纳秒,
                    后->second.强时间.纳秒) != 时间.时间差纳秒) {
                return std::nullopt;
            }
        }
        std::vector<新状态信息> 排序状态;
        for (const auto& [_, 状态] : 状态索引) 排序状态.push_back(状态);
        std::sort(排序状态.begin(), 排序状态.end(), [](const auto& 左, const auto& 右) {
            if (左.强时间.纳秒 != 右.强时间.纳秒) {
                return 左.强时间.纳秒 < 右.强时间.纳秒;
            }
            return 左.节点 < 右.节点;
        });
        新动态信息 信息;
        信息.节点 = 动态节点;
        信息.种类 = 新动态种类::复合;
        信息.主题存在节点 = *主题;
        for (const auto& 状态 : 排序状态) 信息.状态节点组.push_back(状态.节点);
        信息.成员动态节点组 = 成员组;
        信息.跨特征时间组 = *时间特征组;
        信息.动态概念节点 = *概念;
        信息.被引用次数 = 引用->second;
        return 信息;
    } catch (...) {
        return std::nullopt;
    }
}

bool 新_动态类::是动态节点(稳定编码 节点) const noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        if (!结构仍存在() || !节点仍存在(节点)) return false;
        const auto 类型 = 读取唯一节点字段(节点, 动态节点类型字段);
        return 类型 && *类型 == 动态节点类型;
    } catch (...) {
        return false;
    }
}

std::vector<稳定编码> 新_动态类::按主题查询动态(
    稳定编码 主题存在节点) const noexcept {
    std::vector<稳定编码> 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        for (const auto 节点 : 查询全部动态节点()) {
            const auto 信息 = 获取动态(节点);
            if (信息 && 信息->主题存在节点 == 主题存在节点) 结果.push_back(节点);
        }
    } catch (...) {}
    return 结果;
}

std::vector<稳定编码> 新_动态类::按状态查询动态(
    稳定编码 状态节点) const noexcept {
    std::vector<稳定编码> 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        for (const auto 节点 : 查询全部动态节点()) {
            const auto 信息 = 获取动态(节点);
            if (信息 && std::find(信息->状态节点组.begin(),
                信息->状态节点组.end(), 状态节点) != 信息->状态节点组.end()) {
                结果.push_back(节点);
            }
        }
    } catch (...) {}
    return 结果;
}

std::vector<稳定编码> 新_动态类::按概念查询动态(
    稳定编码 动态概念节点) const noexcept {
    std::vector<稳定编码> 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        for (const auto 节点 : 查询全部动态节点()) {
            const auto 信息 = 获取动态(节点);
            if (信息 && 信息->动态概念节点
                && *信息->动态概念节点 == 动态概念节点) 结果.push_back(节点);
        }
    } catch (...) {}
    return 结果;
}

新动态操作状态 新_动态类::采用聚合动态概念(
    稳定编码 动态节点,
    稳定编码 聚合动态概念节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 动态信息 = 获取动态(动态节点);
        if (!动态信息) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        if (动态信息->种类 == 新动态种类::动作) {
            return 新动态操作状态::概念不合法;
        }
        if (!动态信息->动态概念节点) {
            return 新动态操作状态::概念不合法;
        }
        const auto 原概念 = 动态概念服务_.获取动态概念(
            *动态信息->动态概念节点);
        const auto 新概念 = 动态概念服务_.获取动态概念(
            聚合动态概念节点);
        if (!原概念 || 原概念->种类 != 动态概念种类::实例
            || 原概念->对应动态节点 != 动态节点
            || !新概念 || 新概念->种类 != 动态概念种类::聚合) {
            return 新动态操作状态::概念不合法;
        }
        const auto 上位 = 动态概念服务_.查询上位动态概念(
            *动态信息->动态概念节点);
        if (std::find(上位.begin(), 上位.end(), 聚合动态概念节点)
            == 上位.end()) return 新动态操作状态::概念不合法;

        const auto 字段组 = 全局基础数据集.查询字段(动态节点, 动态概念字段);
        if (字段组.size() != 1) return 新动态操作状态::结构不一致;
        const auto* 原目标 = std::get_if<稳定编码>(&字段组.front().内容);
        if (!原目标 || *原目标 != *动态信息->动态概念节点) {
            return 新动态操作状态::结构不一致;
        }
        if (!全局基础数据集.修改字段节点(
            字段组.front().编码, 聚合动态概念节点)) {
            return 新动态操作状态::资源失败;
        }
        const auto 更新后 = 获取动态(动态节点);
        if (!更新后 || !更新后->动态概念节点
            || *更新后->动态概念节点 != 聚合动态概念节点) {
            (void)全局基础数据集.修改字段节点(
                字段组.front().编码, *动态信息->动态概念节点);
            return 新动态操作状态::结构不一致;
        }
        if (!动态概念服务_.删除实例动态概念(
            *动态信息->动态概念节点, 动态节点)) {
            (void)全局基础数据集.修改字段节点(
                字段组.front().编码, *动态信息->动态概念节点);
            return 新动态操作状态::资源失败;
        }
        return 新动态操作状态::已完成;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

新动态操作状态 新_动态类::增加引用(稳定编码 动态节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 引用 = 读取唯一I64字段(动态节点, 动态被引用次数字段);
        if (!引用 || 引用->second < 0) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        if (引用->second == (std::numeric_limits<std::int64_t>::max)()) {
            return 新动态操作状态::引用计数溢出;
        }
        const auto 新计数 = 引用->second + 1;
        if (!全局基础数据集.修改字段值(引用->first, 基础值{新计数})) {
            return 新动态操作状态::资源失败;
        }
        const auto 读回 = 获取动态(动态节点);
        if (读回 && 读回->被引用次数 == 新计数) return 新动态操作状态::已完成;
        (void)全局基础数据集.修改字段值(引用->first, 基础值{引用->second});
        return 新动态操作状态::结构不一致;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

新动态操作状态 新_动态类::撤销增加引用(稳定编码 动态节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 引用 = 读取唯一I64字段(动态节点, 动态被引用次数字段);
        if (!引用 || 引用->second <= 0) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        const auto 新计数 = 引用->second - 1;
        if (!全局基础数据集.修改字段值(引用->first, 基础值{新计数})) {
            return 新动态操作状态::资源失败;
        }
        const auto 读回 = 获取动态(动态节点);
        if (读回 && 读回->被引用次数 == 新计数) {
            return 新动态操作状态::已完成;
        }
        (void)全局基础数据集.修改字段值(引用->first, 基础值{引用->second});
        return 新动态操作状态::结构不一致;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

新动态操作状态 新_动态类::减少组成引用(稳定编码 动态节点) noexcept {
    // 复合关系只是多父组成关系。关系退出只减少引用，不能据此取得成员
    // 动态的删除所有权。
    return 撤销增加引用(动态节点);
}

新动态操作状态 新_动态类::减少引用(稳定编码 动态节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 引用 = 读取唯一I64字段(动态节点, 动态被引用次数字段);
        if (!引用) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        if (引用->second <= 0) return 新动态操作状态::结构不一致;
        const auto 新计数 = 引用->second - 1;
        if (!全局基础数据集.修改字段值(引用->first, 基础值{新计数})) {
            return 新动态操作状态::资源失败;
        }
        const auto 读回 = 获取动态(动态节点);
        if (!读回 || 读回->被引用次数 != 新计数) {
            (void)全局基础数据集.修改字段值(引用->first, 基础值{引用->second});
            return 新动态操作状态::结构不一致;
        }
        if (新计数 != 0) return 新动态操作状态::已完成;
        const auto 删除结果 = 删除动态(动态节点);
        if (删除结果 == 新动态操作状态::已完成) return 删除结果;
        const auto 恢复字段 = 读取唯一I64字段(
            动态节点, 动态被引用次数字段);
        if (!恢复字段 || !全局基础数据集.修改字段值(
            恢复字段->first, 基础值{引用->second})) {
            return 新动态操作状态::结构不一致;
        }
        return 删除结果;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

新动态操作状态 新_动态类::删除动态(稳定编码 动态节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 信息 = 获取动态(动态节点);
        if (!信息) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        if (信息->被引用次数 != 0) return 新动态操作状态::动态仍被引用;
        // 动作来源是强引用，但不属于场景/组成引用计数。必须在删除任何
        // 字段之前检查，否则最终节点删除被 L1 拒绝时已无法恢复动作。
        if (!全局基础数据集.查询目标字段(
                动态节点, 动作来源字段).empty()) {
            return 新动态操作状态::动态仍被引用;
        }

        if (信息->种类 != 新动态种类::动作) {
            if (!信息->动态概念节点) return 新动态操作状态::结构不一致;
            const auto 概念字段组 = 全局基础数据集.查询字段(
                动态节点, 动态概念字段);
            if (概念字段组.size() != 1
                || !全局基础数据集.删除字段(概念字段组.front().编码)) {
                return 新动态操作状态::结构不一致;
            }
            const auto 概念信息 = 动态概念服务_.获取动态概念(
                *信息->动态概念节点);
            if (!概念信息) {
                (void)全局基础数据集.添加字段节点(
                    动态节点, 动态概念字段, *信息->动态概念节点);
                return 新动态操作状态::结构不一致;
            }
            if (概念信息->种类 == 动态概念种类::实例
                && !动态概念服务_.删除实例动态概念(
                    *信息->动态概念节点, 动态节点)) {
                (void)全局基础数据集.添加字段节点(
                    动态节点, 动态概念字段, *信息->动态概念节点);
                return 新动态操作状态::结构不一致;
            }
        }

        if (信息->种类 == 新动态种类::动作) {
            for (const auto& 关系 : 全局基础数据集.查询源关系(
                动态节点, 基础外部关系类型::父子)) {
                if (!读取动作结果关系类型(关系.角色或顺序)
                    || !全局基础数据集.删除关系(关系.编码)) {
                    return 新动态操作状态::结构不一致;
                }
            }
            for (const auto 字段 : {
                动作定义字段, 动作来源字段,
                动作时间语义字段, 动作时间纳秒字段}) {
                const auto 字段组 = 全局基础数据集.查询字段(动态节点, 字段);
                if (字段组.size() != 1
                    || !全局基础数据集.删除字段(字段组.front().编码)) {
                    return 新动态操作状态::结构不一致;
                }
            }
            // 旧普通动作没有种类字段；新内部目标的两个引用不可缺少。
            for (const auto 字段 : {动作目标种类字段, 动作目标存在字段,
                    动作目标任务字段, 动作目标虚拟存在字段}) {
                const auto 字段组 = 全局基础数据集.查询字段(动态节点, 字段);
                if (字段组.size() > 1 || (!字段组.empty()
                    && !全局基础数据集.删除字段(字段组.front().编码))) {
                    return 新动态操作状态::结构不一致;
                }
            }
            const auto 可选特征字段组 = 全局基础数据集.查询字段(
                动态节点, 动作目标特征字段);
            if (可选特征字段组.size() > 1
                || (!可选特征字段组.empty()
                    && !全局基础数据集.删除字段(
                        可选特征字段组.front().编码))) {
                return 新动态操作状态::结构不一致;
            }
        } else if (信息->种类 == 新动态种类::复合) {
            for (const auto& 关系 : 全局基础数据集.查询源关系(
                动态节点, 基础外部关系类型::父子)) {
                if (关系.角色或顺序 != 新复合动态成员关系角色
                    || !全局基础数据集.删除关系(关系.编码)) {
                    return 新动态操作状态::结构不一致;
                }
            }
            for (const auto& 持有 : 全局基础数据集.查询字段(
                动态节点, 复合时间项字段)) {
                const auto* 项节点 = std::get_if<稳定编码>(&持有.内容);
                if (!项节点 || !全局基础数据集.删除字段(持有.编码)) {
                    return 新动态操作状态::结构不一致;
                }
                for (const auto 字段 : {
                    动态节点类型字段, 复合前状态字段, 复合后状态字段,
                    复合前特征类型字段, 复合后特征类型字段,
                    复合二次特征类型字段, 复合结果值域字段,
                    复合时间差字段}) {
                    const auto 项字段组 = 全局基础数据集.查询字段(*项节点, 字段);
                    if (项字段组.size() != 1
                        || !全局基础数据集.删除字段(项字段组.front().编码)) {
                        return 新动态操作状态::结构不一致;
                    }
                }
                if (!全局基础数据集.删除节点(*项节点)) {
                    return 新动态操作状态::结构不一致;
                }
            }
        } else {
            for (const auto& 持有 : 全局基础数据集.查询字段(
                动态节点, 动态状态项字段)) {
                const auto* 项节点 = std::get_if<稳定编码>(&持有.内容);
                if (!项节点 || !全局基础数据集.删除字段(持有.编码)) {
                    return 新动态操作状态::结构不一致;
                }
                for (const auto 字段 : {
                    动态节点类型字段, 动态状态项顺序字段,
                    动态状态节点字段}) {
                    const auto 项字段组 = 全局基础数据集.查询字段(*项节点, 字段);
                    if (项字段组.size() != 1
                        || !全局基础数据集.删除字段(项字段组.front().编码)) {
                        return 新动态操作状态::结构不一致;
                    }
                }
                if (!全局基础数据集.删除节点(*项节点)) {
                    return 新动态操作状态::结构不一致;
                }
            }
        }
        for (const auto 字段 : {
            动态节点类型字段, 动态种类字段,
            动态主题存在字段, 动态被引用次数字段}) {
            const auto 字段组 = 全局基础数据集.查询字段(动态节点, 字段);
            if (字段组.size() != 1
                || !全局基础数据集.删除字段(字段组.front().编码)) {
                return 新动态操作状态::结构不一致;
            }
        }
        if (!全局基础数据集.删除节点(动态节点)) {
            return 新动态操作状态::结构不一致;
        }
        bool 引用完整退出 = true;
        if (信息->种类 == 新动态种类::原子) {
            for (const auto 状态节点 : 信息->状态节点组) {
                const auto 状态 = 状态服务_.减少引用(状态节点);
                if (状态 != 新状态操作状态::已完成) 引用完整退出 = false;
            }
        } else if (信息->种类 == 新动态种类::复合) {
            for (const auto 成员节点 : 信息->成员动态节点组) {
                const auto 状态 = 减少组成引用(成员节点);
                if (状态 != 新动态操作状态::已完成) 引用完整退出 = false;
            }
        } else {
            for (const auto& 关联 : 信息->动作结果组) {
                const auto 状态 = 减少组成引用(关联.结果动态节点);
                if (状态 != 新动态操作状态::已完成) 引用完整退出 = false;
            }
        }
        return 引用完整退出
            ? 新动态操作状态::已完成
            : 新动态操作状态::结构不一致;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

