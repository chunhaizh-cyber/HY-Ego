std::int64_t 计算饱和时间差(
    std::int64_t 前纳秒, std::int64_t 后纳秒) noexcept {
    const auto 最小 = (std::numeric_limits<std::int64_t>::min)();
    const auto 最大 = (std::numeric_limits<std::int64_t>::max)();
    if (前纳秒 < 0 && 后纳秒 > 最大 + 前纳秒) return 最大;
    if (前纳秒 > 0 && 后纳秒 < 最小 + 前纳秒) return 最小;
    return 后纳秒 - 前纳秒;
}

