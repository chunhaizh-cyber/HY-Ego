新_动态类::新_动态类(
    新_状态类& 状态服务,
    概念_动态类& 动态概念服务) noexcept
    : 状态服务_(状态服务), 动态概念服务_(动态概念服务) {}

bool 新_动态类::初始化() noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        if (!状态服务_.初始化() || !动态概念服务_.初始化()) return false;
        if (结构已初始化()) return 结构仍存在();
        auto 建立 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        return 建立(动态节点类型字段)
            && 建立(动态节点类型)
            && 建立(动态种类字段)
            && 建立(动态主题存在字段)
            && 建立(动态状态项字段)
            && 建立(动态状态项节点类型)
            && 建立(动态状态项顺序字段)
            && 建立(动态状态节点字段)
            && 建立(动态概念字段)
            && 建立(动态被引用次数字段)
            && 建立(动态成员项字段)
            && 建立(动态成员项节点类型)
            && 建立(动态成员项顺序字段)
            && 建立(动态成员节点字段);
    } catch (...) {
        return false;
    }
}

新动态建立结果 新_动态类::建立原子动态(
    稳定编码 主题存在节点,
    稳定编码 前状态节点,
    稳定编码 后状态节点) noexcept {
    新动态建立结果 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        const std::vector<稳定编码> 状态节点组{前状态节点, 后状态节点};
        if (!结构仍存在() || !有效(主题存在节点)
            || !节点仍存在(主题存在节点)) return 结果;
        std::set<std::uint64_t> 唯一状态;
        std::vector<新状态信息> 状态信息组;
        状态信息组.reserve(状态节点组.size());
        for (const auto 状态节点 : 状态节点组) {
            if (!唯一状态.insert(状态节点.值).second) {
                结果.状态 = 新动态操作状态::状态重复;
                return 结果;
            }
            const auto 状态 = 状态服务_.获取状态(状态节点);
            if (!状态) {
                结果.状态 = 新动态操作状态::状态不存在;
                return 结果;
            }
            if (状态->被描述存在节点 != 主题存在节点) {
                结果.状态 = 新动态操作状态::主题不一致;
                return 结果;
            }
            状态信息组.push_back(*状态);
        }
        for (std::size_t i = 0; i < 状态信息组.size(); ++i) {
            if (状态信息组[i].强时间.语义 != 新状态时间语义::实例绝对UTC
                || (i > 0 && 状态信息组[i].强时间.纳秒
                    <= 状态信息组[i - 1].强时间.纳秒)) {
                结果.状态 = 新动态操作状态::时间不合法;
                return 结果;
            }
        }
        if (状态信息组[0].特征类型概念节点
            != 状态信息组[1].特征类型概念节点) {
            结果.状态 = 新动态操作状态::特征类型不一致;
            return 结果;
        }
        auto 状态引用组 = 建立状态引用组(状态节点组);
        if (!状态引用组) {
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        const auto 动态节点 = 全局基础数据集.新建节点();
        std::vector<稳定编码> 已写字段;
        if (!有效(动态节点)) {
            清理状态引用组(*状态引用组);
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        auto 记录 = [&](稳定编码 字段) {
            if (!有效(字段)) return false;
            已写字段.push_back(字段);
            return true;
        };
        bool 完整 = 记录(全局基础数据集.添加字段节点(
                动态节点, 动态节点类型字段, 动态节点类型))
            && 记录(全局基础数据集.添加字段值(
                动态节点, 动态种类字段,
                基础值{static_cast<std::int64_t>(新动态种类::原子)}))
            && 记录(全局基础数据集.添加字段节点(
                动态节点, 动态主题存在字段, 主题存在节点))
            && 记录(全局基础数据集.添加字段值(
                动态节点, 动态被引用次数字段, 基础值{std::int64_t{0}}));
        for (auto& 引用 : *状态引用组) {
            if (!完整) break;
            const auto 字段 = 全局基础数据集.添加字段节点(
                动态节点, 动态状态项字段, 引用.节点);
            if (!有效(字段)) {
                完整 = false;
                break;
            }
            引用.持有字段 = 字段;
        }
        if (!完整) {
            清理动态基础字段(动态节点, 已写字段, *状态引用组);
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        std::vector<稳定编码> 已增加引用;
        for (const auto 状态节点 : 状态节点组) {
            if (状态服务_.增加引用(状态节点) != 新状态操作状态::已完成) {
                for (auto 位置 = 已增加引用.rbegin();
                    位置 != 已增加引用.rend(); ++位置) {
                    (void)状态服务_.撤销增加引用(*位置);
                }
                清理动态基础字段(动态节点, 已写字段, *状态引用组);
                结果.状态 = 新动态操作状态::资源失败;
                return 结果;
            }
            已增加引用.push_back(状态节点);
        }
        const auto 概念结果 = 动态概念服务_.建立实例动态概念(
            动态节点, 状态信息组);
        if (概念结果.状态 != 动态概念操作状态::已建立
            || !概念结果.概念节点) {
            for (auto 位置 = 已增加引用.rbegin();
                位置 != 已增加引用.rend(); ++位置) {
                (void)状态服务_.撤销增加引用(*位置);
            }
            清理动态基础字段(动态节点, 已写字段, *状态引用组);
            结果.状态 = 新动态操作状态::实例概念失败;
            return 结果;
        }
        const auto 概念字段关系 = 全局基础数据集.添加字段节点(
            动态节点, 动态概念字段, *概念结果.概念节点);
        if (!有效(概念字段关系)) {
            (void)动态概念服务_.删除实例动态概念(
                *概念结果.概念节点, 动态节点);
            for (auto 位置 = 已增加引用.rbegin();
                位置 != 已增加引用.rend(); ++位置) {
                (void)状态服务_.撤销增加引用(*位置);
            }
            清理动态基础字段(动态节点, 已写字段, *状态引用组);
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        已写字段.push_back(概念字段关系);
        const auto 读回 = 获取动态(动态节点);
        if (!读回 || 读回->种类 != 新动态种类::原子
            || 读回->主题存在节点 != 主题存在节点
            || 读回->状态节点组 != 状态节点组
            || !读回->原子动态节点组.empty()
            || 读回->动态概念节点 != 概念结果.概念节点
            || 读回->被引用次数 != 0) {
            (void)全局基础数据集.删除字段(概念字段关系);
            已写字段.pop_back();
            (void)动态概念服务_.删除实例动态概念(
                *概念结果.概念节点, 动态节点);
            for (auto 位置 = 已增加引用.rbegin();
                位置 != 已增加引用.rend(); ++位置) {
                (void)状态服务_.撤销增加引用(*位置);
            }
            清理动态基础字段(动态节点, 已写字段, *状态引用组);
            结果.状态 = 新动态操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新动态操作状态::已完成;
        结果.动态节点 = 动态节点;
        结果.动态概念节点 = *概念结果.概念节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新动态操作状态::资源失败;
        结果.动态节点.reset();
        结果.动态概念节点.reset();
        return 结果;
    }
}

新动态建立结果 新_动态类::建立动态(
    稳定编码 主题存在节点,
    const std::vector<稳定编码>& 状态节点组) noexcept {
    if (状态节点组.size() != 2) {
        新动态建立结果 结果;
        结果.状态 = 新动态操作状态::状态数量不合法;
        return 结果;
    }
    return 建立原子动态(
        主题存在节点, 状态节点组.front(), 状态节点组.back());
}

新动态建立结果 新_动态类::连接原子动态(
    const std::vector<稳定编码>& 有序原子动态组) noexcept {
    新动态建立结果 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        if (!结构仍存在()) return 结果;
        if (有序原子动态组.size() < 2) {
            结果.状态 = 新动态操作状态::原子动态不足;
            return 结果;
        }

        std::set<std::uint64_t> 唯一成员;
        std::vector<新动态信息> 成员信息组;
        std::vector<std::array<新状态信息, 2>> 成员状态组;
        成员信息组.reserve(有序原子动态组.size());
        成员状态组.reserve(有序原子动态组.size());
        for (const auto 原子节点 : 有序原子动态组) {
            if (!唯一成员.insert(原子节点.值).second) {
                结果.状态 = 新动态操作状态::状态重复;
                return 结果;
            }
            const auto 原子 = 获取动态(原子节点);
            if (!原子) {
                结果.状态 = 新动态操作状态::动态不存在;
                return 结果;
            }
            if (原子->种类 != 新动态种类::原子
                || 原子->状态节点组.size() != 2
                || !原子->原子动态节点组.empty()
                || !原子->动态概念节点) {
                结果.状态 = 新动态操作状态::不是原子动态;
                return 结果;
            }
            const auto 前 = 状态服务_.获取状态(原子->状态节点组[0]);
            const auto 后 = 状态服务_.获取状态(原子->状态节点组[1]);
            if (!前 || !后) {
                结果.状态 = 新动态操作状态::状态不存在;
                return 结果;
            }
            if (前->被描述存在节点 != 原子->主题存在节点
                || 后->被描述存在节点 != 原子->主题存在节点) {
                结果.状态 = 新动态操作状态::主题不一致;
                return 结果;
            }
            if (前->特征类型概念节点 != 后->特征类型概念节点) {
                结果.状态 = 新动态操作状态::特征类型不一致;
                return 结果;
            }
            if (前->强时间.语义 != 新状态时间语义::实例绝对UTC
                || 后->强时间.语义 != 新状态时间语义::实例绝对UTC
                || 后->强时间.纳秒 <= 前->强时间.纳秒) {
                结果.状态 = 新动态操作状态::时间不合法;
                return 结果;
            }
            if (!成员信息组.empty()) {
                const auto& 上一个 = 成员信息组.back();
                const auto& 上一状态 = 成员状态组.back();
                if (上一个.主题存在节点 != 原子->主题存在节点) {
                    结果.状态 = 新动态操作状态::主题不一致;
                    return 结果;
                }
                if (上一状态[0].特征类型概念节点
                    != 前->特征类型概念节点) {
                    结果.状态 = 新动态操作状态::特征类型不一致;
                    return 结果;
                }
                if (上一个.状态节点组[1] != 原子->状态节点组[0]) {
                    结果.状态 = 新动态操作状态::端点不连续;
                    return 结果;
                }
                if (后->强时间.纳秒 <= 上一状态[1].强时间.纳秒) {
                    结果.状态 = 新动态操作状态::时间不合法;
                    return 结果;
                }
            }
            成员信息组.push_back(*原子);
            成员状态组.push_back({*前, *后});
        }

        auto 成员引用组 = 建立成员引用组(有序原子动态组);
        if (!成员引用组) {
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        const auto 动态节点 = 全局基础数据集.新建节点();
        std::vector<稳定编码> 已写字段;
        if (!有效(动态节点)) {
            清理状态引用组(*成员引用组);
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }
        auto 记录 = [&](稳定编码 字段) {
            if (!有效(字段)) return false;
            已写字段.push_back(字段);
            return true;
        };
        bool 完整 = 记录(全局基础数据集.添加字段节点(
                动态节点, 动态节点类型字段, 动态节点类型))
            && 记录(全局基础数据集.添加字段值(
                动态节点, 动态种类字段,
                基础值{static_cast<std::int64_t>(新动态种类::组合)}))
            && 记录(全局基础数据集.添加字段节点(
                动态节点, 动态主题存在字段,
                成员信息组.front().主题存在节点))
            && 记录(全局基础数据集.添加字段值(
                动态节点, 动态被引用次数字段, 基础值{std::int64_t{0}}));
        for (auto& 引用 : *成员引用组) {
            if (!完整) break;
            const auto 字段 = 全局基础数据集.添加字段节点(
                动态节点, 动态成员项字段, 引用.节点);
            if (!有效(字段)) {
                完整 = false;
                break;
            }
            引用.持有字段 = 字段;
        }
        if (!完整) {
            清理动态基础字段(动态节点, 已写字段, *成员引用组);
            结果.状态 = 新动态操作状态::资源失败;
            return 结果;
        }

        std::vector<稳定编码> 已增加引用;
        for (const auto 原子节点 : 有序原子动态组) {
            if (增加引用(原子节点) != 新动态操作状态::已完成) {
                for (auto 位置 = 已增加引用.rbegin();
                    位置 != 已增加引用.rend(); ++位置) {
                    (void)撤销增加引用(*位置);
                }
                清理动态基础字段(动态节点, 已写字段, *成员引用组);
                结果.状态 = 新动态操作状态::资源失败;
                return 结果;
            }
            已增加引用.push_back(原子节点);
        }

        const auto 读回 = 获取动态(动态节点);
        if (!读回 || 读回->种类 != 新动态种类::组合
            || 读回->主题存在节点 != 成员信息组.front().主题存在节点
            || 读回->原子动态节点组 != 有序原子动态组
            || 读回->状态节点组.size() != 有序原子动态组.size() + 1
            || 读回->动态概念节点 || 读回->被引用次数 != 0) {
            for (auto 位置 = 已增加引用.rbegin();
                位置 != 已增加引用.rend(); ++位置) {
                (void)撤销增加引用(*位置);
            }
            清理动态基础字段(动态节点, 已写字段, *成员引用组);
            结果.状态 = 新动态操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新动态操作状态::已完成;
        结果.动态节点 = 动态节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新动态操作状态::资源失败;
        结果.动态节点.reset();
        结果.动态概念节点.reset();
        return 结果;
    }
}

std::optional<新动态信息> 新_动态类::获取动态(
    稳定编码 动态节点) const noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        if (!是动态节点(动态节点)) return std::nullopt;
        const auto 种类值 = 读取唯一I64字段(动态节点, 动态种类字段);
        const auto 主题 = 读取唯一节点字段(动态节点, 动态主题存在字段);
        const auto 引用 = 读取唯一I64字段(动态节点, 动态被引用次数字段);
        if (!种类值 || !主题 || !引用 || 引用->second < 0) return std::nullopt;

        if (种类值->second == static_cast<std::int64_t>(新动态种类::原子)) {
            const auto 状态组 = 读取有序状态组(动态节点);
            const auto 成员组 = 读取有序成员组(动态节点);
            const auto 概念 = 读取唯一节点字段(动态节点, 动态概念字段);
            if (!状态组 || 状态组->size() != 2 || !成员组 || !成员组->empty()
                || !概念 || !动态概念服务_.是动态概念节点(*概念)) {
                return std::nullopt;
            }
            return 新动态信息{动态节点, 新动态种类::原子, *主题,
                *状态组, {}, std::optional<稳定编码>{*概念}, 引用->second};
        }
        if (种类值->second != static_cast<std::int64_t>(新动态种类::组合)) {
            return std::nullopt;
        }
        const auto 直接状态组 = 读取有序状态组(动态节点);
        const auto 成员组 = 读取有序成员组(动态节点);
        if (!直接状态组 || !直接状态组->empty() || !成员组
            || 成员组->size() < 2
            || !全局基础数据集.查询字段(动态节点, 动态概念字段).empty()) {
            return std::nullopt;
        }
        std::vector<稳定编码> 推导状态组;
        推导状态组.reserve(成员组->size() + 1);
        for (const auto 成员节点 : *成员组) {
            const auto 成员 = 获取动态(成员节点);
            if (!成员 || 成员->种类 != 新动态种类::原子
                || 成员->主题存在节点 != *主题
                || 成员->状态节点组.size() != 2) return std::nullopt;
            if (推导状态组.empty()) {
                推导状态组.push_back(成员->状态节点组[0]);
            } else if (推导状态组.back() != 成员->状态节点组[0]) {
                return std::nullopt;
            }
            推导状态组.push_back(成员->状态节点组[1]);
        }
        return 新动态信息{动态节点, 新动态种类::组合, *主题,
            std::move(推导状态组), *成员组, std::nullopt, 引用->second};
    } catch (...) {
        return std::nullopt;
    }
}

bool 新_动态类::是动态节点(稳定编码 节点) const noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        if (!结构仍存在() || !节点仍存在(节点)) return false;
        const auto 类型 = 读取唯一节点字段(节点, 动态节点类型字段);
        return 类型 && *类型 == 动态节点类型;
    } catch (...) {
        return false;
    }
}

std::vector<稳定编码> 新_动态类::按主题查询动态(
    稳定编码 主题存在节点) const noexcept {
    std::vector<稳定编码> 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        for (const auto 节点 : 查询全部动态节点()) {
            const auto 信息 = 获取动态(节点);
            if (信息 && 信息->主题存在节点 == 主题存在节点) 结果.push_back(节点);
        }
    } catch (...) {}
    return 结果;
}

std::vector<稳定编码> 新_动态类::按状态查询动态(
    稳定编码 状态节点) const noexcept {
    std::vector<稳定编码> 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        for (const auto 节点 : 查询全部动态节点()) {
            const auto 信息 = 获取动态(节点);
            if (信息 && std::find(信息->状态节点组.begin(),
                信息->状态节点组.end(), 状态节点) != 信息->状态节点组.end()) {
                结果.push_back(节点);
            }
        }
    } catch (...) {}
    return 结果;
}

std::vector<稳定编码> 新_动态类::按概念查询动态(
    稳定编码 动态概念节点) const noexcept {
    std::vector<稳定编码> 结果;
    try {
        std::lock_guard 锁(新动态互斥);
        for (const auto 节点 : 查询全部动态节点()) {
            const auto 信息 = 获取动态(节点);
            if (信息 && 信息->动态概念节点
                && *信息->动态概念节点 == 动态概念节点) 结果.push_back(节点);
        }
    } catch (...) {}
    return 结果;
}

新动态操作状态 新_动态类::采用聚合动态概念(
    稳定编码 动态节点,
    稳定编码 聚合动态概念节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 动态信息 = 获取动态(动态节点);
        if (!动态信息) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        if (动态信息->种类 != 新动态种类::原子
            || !动态信息->动态概念节点) {
            return 新动态操作状态::概念不合法;
        }
        const auto 原概念 = 动态概念服务_.获取动态概念(
            *动态信息->动态概念节点);
        const auto 新概念 = 动态概念服务_.获取动态概念(
            聚合动态概念节点);
        if (!原概念 || 原概念->种类 != 动态概念种类::实例
            || 原概念->对应动态节点 != 动态节点
            || !新概念 || 新概念->种类 != 动态概念种类::聚合) {
            return 新动态操作状态::概念不合法;
        }
        const auto 上位 = 动态概念服务_.查询上位动态概念(
            *动态信息->动态概念节点);
        if (std::find(上位.begin(), 上位.end(), 聚合动态概念节点)
            == 上位.end()) return 新动态操作状态::概念不合法;

        const auto 字段组 = 全局基础数据集.查询字段(动态节点, 动态概念字段);
        if (字段组.size() != 1) return 新动态操作状态::结构不一致;
        const auto* 原目标 = std::get_if<稳定编码>(&字段组.front().内容);
        if (!原目标 || *原目标 != *动态信息->动态概念节点) {
            return 新动态操作状态::结构不一致;
        }
        if (!全局基础数据集.修改字段节点(
            字段组.front().编码, 聚合动态概念节点)) {
            return 新动态操作状态::资源失败;
        }
        const auto 更新后 = 获取动态(动态节点);
        if (!更新后 || !更新后->动态概念节点
            || *更新后->动态概念节点 != 聚合动态概念节点) {
            (void)全局基础数据集.修改字段节点(
                字段组.front().编码, *动态信息->动态概念节点);
            return 新动态操作状态::结构不一致;
        }
        if (!动态概念服务_.删除实例动态概念(
            *动态信息->动态概念节点, 动态节点)) {
            (void)全局基础数据集.修改字段节点(
                字段组.front().编码, *动态信息->动态概念节点);
            return 新动态操作状态::资源失败;
        }
        return 新动态操作状态::已完成;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

新动态操作状态 新_动态类::增加引用(稳定编码 动态节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 引用 = 读取唯一I64字段(动态节点, 动态被引用次数字段);
        if (!引用 || 引用->second < 0) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        if (引用->second == (std::numeric_limits<std::int64_t>::max)()) {
            return 新动态操作状态::引用计数溢出;
        }
        const auto 新计数 = 引用->second + 1;
        if (!全局基础数据集.修改字段值(引用->first, 基础值{新计数})) {
            return 新动态操作状态::资源失败;
        }
        const auto 读回 = 获取动态(动态节点);
        if (读回 && 读回->被引用次数 == 新计数) return 新动态操作状态::已完成;
        (void)全局基础数据集.修改字段值(引用->first, 基础值{引用->second});
        return 新动态操作状态::结构不一致;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

新动态操作状态 新_动态类::撤销增加引用(稳定编码 动态节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 引用 = 读取唯一I64字段(动态节点, 动态被引用次数字段);
        if (!引用 || 引用->second <= 0) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        const auto 新计数 = 引用->second - 1;
        if (!全局基础数据集.修改字段值(引用->first, 基础值{新计数})) {
            return 新动态操作状态::资源失败;
        }
        const auto 读回 = 获取动态(动态节点);
        if (读回 && 读回->被引用次数 == 新计数) {
            return 新动态操作状态::已完成;
        }
        (void)全局基础数据集.修改字段值(引用->first, 基础值{引用->second});
        return 新动态操作状态::结构不一致;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

新动态操作状态 新_动态类::减少引用(稳定编码 动态节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 引用 = 读取唯一I64字段(动态节点, 动态被引用次数字段);
        if (!引用) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        if (引用->second <= 0) return 新动态操作状态::结构不一致;
        const auto 新计数 = 引用->second - 1;
        if (!全局基础数据集.修改字段值(引用->first, 基础值{新计数})) {
            return 新动态操作状态::资源失败;
        }
        const auto 读回 = 获取动态(动态节点);
        if (!读回 || 读回->被引用次数 != 新计数) {
            (void)全局基础数据集.修改字段值(引用->first, 基础值{引用->second});
            return 新动态操作状态::结构不一致;
        }
        if (新计数 != 0) return 新动态操作状态::已完成;
        const auto 删除结果 = 删除动态(动态节点);
        if (删除结果 == 新动态操作状态::已完成) return 删除结果;
        const auto 恢复字段 = 读取唯一I64字段(
            动态节点, 动态被引用次数字段);
        if (!恢复字段 || !全局基础数据集.修改字段值(
            恢复字段->first, 基础值{引用->second})) {
            return 新动态操作状态::结构不一致;
        }
        return 删除结果;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

新动态操作状态 新_动态类::删除动态(稳定编码 动态节点) noexcept {
    try {
        std::lock_guard 锁(新动态互斥);
        const auto 信息 = 获取动态(动态节点);
        if (!信息) return 节点仍存在(动态节点)
            ? 新动态操作状态::结构不一致 : 新动态操作状态::动态不存在;
        if (信息->被引用次数 != 0) return 新动态操作状态::动态仍被引用;

        if (信息->种类 == 新动态种类::原子) {
            if (!信息->动态概念节点) return 新动态操作状态::结构不一致;
            const auto 概念字段组 = 全局基础数据集.查询字段(
                动态节点, 动态概念字段);
            if (概念字段组.size() != 1
                || !全局基础数据集.删除字段(概念字段组.front().编码)) {
                return 新动态操作状态::结构不一致;
            }
            const auto 概念信息 = 动态概念服务_.获取动态概念(
                *信息->动态概念节点);
            if (!概念信息) {
                (void)全局基础数据集.添加字段节点(
                    动态节点, 动态概念字段, *信息->动态概念节点);
                return 新动态操作状态::结构不一致;
            }
            if (概念信息->种类 == 动态概念种类::实例
                && !动态概念服务_.删除实例动态概念(
                    *信息->动态概念节点, 动态节点)) {
                (void)全局基础数据集.添加字段节点(
                    动态节点, 动态概念字段, *信息->动态概念节点);
                return 新动态操作状态::结构不一致;
            }
        }

        const auto 持有项字段 = 信息->种类 == 新动态种类::原子
            ? 动态状态项字段 : 动态成员项字段;
        const auto 顺序字段 = 信息->种类 == 新动态种类::原子
            ? 动态状态项顺序字段 : 动态成员项顺序字段;
        const auto 目标字段 = 信息->种类 == 新动态种类::原子
            ? 动态状态节点字段 : 动态成员节点字段;
        for (const auto& 持有 : 全局基础数据集.查询字段(
            动态节点, 持有项字段)) {
            const auto* 项节点 = std::get_if<稳定编码>(&持有.内容);
            if (!项节点 || !全局基础数据集.删除字段(持有.编码)) {
                return 新动态操作状态::结构不一致;
            }
            for (const auto 字段 : {
                动态节点类型字段, 顺序字段, 目标字段}) {
                const auto 项字段组 = 全局基础数据集.查询字段(*项节点, 字段);
                if (项字段组.size() != 1
                    || !全局基础数据集.删除字段(项字段组.front().编码)) {
                    return 新动态操作状态::结构不一致;
                }
            }
            if (!全局基础数据集.删除节点(*项节点)) {
                return 新动态操作状态::结构不一致;
            }
        }
        for (const auto 字段 : {
            动态节点类型字段, 动态种类字段,
            动态主题存在字段, 动态被引用次数字段}) {
            const auto 字段组 = 全局基础数据集.查询字段(动态节点, 字段);
            if (字段组.size() != 1
                || !全局基础数据集.删除字段(字段组.front().编码)) {
                return 新动态操作状态::结构不一致;
            }
        }
        if (!全局基础数据集.删除节点(动态节点)) {
            return 新动态操作状态::结构不一致;
        }
        bool 引用完整退出 = true;
        if (信息->种类 == 新动态种类::原子) {
            for (const auto 状态节点 : 信息->状态节点组) {
                const auto 状态 = 状态服务_.减少引用(状态节点);
                if (状态 != 新状态操作状态::已完成) 引用完整退出 = false;
            }
        } else {
            for (const auto 原子节点 : 信息->原子动态节点组) {
                const auto 状态 = 减少引用(原子节点);
                if (状态 != 新动态操作状态::已完成) 引用完整退出 = false;
            }
        }
        return 引用完整退出
            ? 新动态操作状态::已完成
            : 新动态操作状态::结构不一致;
    } catch (...) {
        return 新动态操作状态::资源失败;
    }
}

