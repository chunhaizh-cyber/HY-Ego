std::optional<稳定编码> 读取唯一节点字段(
    稳定编码 节点, 稳定编码 字段) {
    const auto 字段组 = 全局基础数据集.查询字段(节点, 字段);
    if (字段组.size() != 1) return std::nullopt;
    const auto* 目标 = std::get_if<稳定编码>(&字段组.front().内容);
    return 目标 && 节点仍存在(*目标)
        ? std::optional<稳定编码>{*目标} : std::nullopt;
}

std::optional<std::pair<稳定编码, std::int64_t>> 读取唯一I64字段(
    稳定编码 节点, 稳定编码 字段) {
    const auto 字段组 = 全局基础数据集.查询字段(节点, 字段);
    if (字段组.size() != 1) return std::nullopt;
    const auto* 值 = std::get_if<基础值>(&字段组.front().内容);
    if (!值) return std::nullopt;
    const auto* I64 = std::get_if<std::int64_t>(&值->材料);
    return I64
        ? std::optional<std::pair<稳定编码, std::int64_t>>{
            std::pair{字段组.front().编码, *I64}}
        : std::nullopt;
}

struct 已建状态引用 final {
    稳定编码 节点;
    std::vector<稳定编码> 字段组;
    std::optional<稳定编码> 持有字段;
};

void 清理状态引用组(std::vector<已建状态引用>& 引用组) noexcept {
    for (auto 位置 = 引用组.rbegin(); 位置 != 引用组.rend(); ++位置) {
        if (位置->持有字段) (void)全局基础数据集.删除字段(*位置->持有字段);
        for (auto 字段 = 位置->字段组.rbegin(); 字段 != 位置->字段组.rend(); ++字段) {
            (void)全局基础数据集.删除字段(*字段);
        }
        (void)全局基础数据集.删除节点(位置->节点);
    }
}

std::optional<std::vector<已建状态引用>> 建立状态引用组(
    const std::vector<稳定编码>& 状态节点组) {
    std::vector<已建状态引用> 结果;
    for (std::size_t i = 0; i < 状态节点组.size(); ++i) {
        已建状态引用 已建;
        已建.节点 = 全局基础数据集.新建节点();
        if (!有效(已建.节点)) {
            清理状态引用组(结果);
            return std::nullopt;
        }
        auto 记录 = [&](稳定编码 字段) {
            if (!有效(字段)) return false;
            已建.字段组.push_back(字段);
            return true;
        };
        const bool 完整 =
            记录(全局基础数据集.添加字段节点(
                已建.节点, 动态节点类型字段, 动态状态项节点类型))
            && 记录(全局基础数据集.添加字段值(
                已建.节点, 动态状态项顺序字段,
                基础值{static_cast<std::int64_t>(i)}))
            && 记录(全局基础数据集.添加字段节点(
                已建.节点, 动态状态节点字段, 状态节点组[i]));
        结果.push_back(std::move(已建));
        if (!完整) {
            清理状态引用组(结果);
            return std::nullopt;
        }
    }
    return 结果;
}

std::optional<std::vector<稳定编码>> 读取有序状态组(稳定编码 动态节点) {
    std::vector<std::pair<std::int64_t, 稳定编码>> 排序项;
    for (const auto& 持有 : 全局基础数据集.查询字段(
        动态节点, 动态状态项字段)) {
        const auto* 项节点 = std::get_if<稳定编码>(&持有.内容);
        if (!项节点 || !节点仍存在(*项节点)) return std::nullopt;
        const auto 类型 = 读取唯一节点字段(*项节点, 动态节点类型字段);
        const auto 顺序 = 读取唯一I64字段(*项节点, 动态状态项顺序字段);
        const auto 状态 = 读取唯一节点字段(*项节点, 动态状态节点字段);
        if (!类型 || *类型 != 动态状态项节点类型
            || !顺序 || 顺序->second < 0 || !状态) return std::nullopt;
        排序项.push_back({顺序->second, *状态});
    }
    std::sort(排序项.begin(), 排序项.end(), [](const auto& 左, const auto& 右) {
        return 左.first < 右.first;
    });
    std::vector<稳定编码> 结果;
    结果.reserve(排序项.size());
    for (std::size_t i = 0; i < 排序项.size(); ++i) {
        if (排序项[i].first != static_cast<std::int64_t>(i)) return std::nullopt;
        结果.push_back(排序项[i].second);
    }
    return 结果;
}

std::vector<稳定编码> 读取复合成员组(稳定编码 动态节点) {
    std::vector<稳定编码> 结果;
    for (const auto& 关系 : 全局基础数据集.查询源关系(
        动态节点, 基础外部关系类型::父子)) {
        if (关系.角色或顺序 == 新复合动态成员关系角色) {
            结果.push_back(关系.目标节点);
        }
    }
    std::sort(结果.begin(), 结果.end());
    if (std::adjacent_find(结果.begin(), 结果.end()) != 结果.end()) {
        return {};
    }
    return 结果;
}

