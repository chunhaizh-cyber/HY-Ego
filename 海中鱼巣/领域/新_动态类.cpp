void 清理复合时间项组(std::vector<已建复合时间项>& 项组) noexcept {
    for (auto 位置 = 项组.rbegin(); 位置 != 项组.rend(); ++位置) {
        if (位置->持有字段) (void)全局基础数据集.删除字段(*位置->持有字段);
        for (auto 字段 = 位置->字段组.rbegin(); 字段 != 位置->字段组.rend(); ++字段) {
            (void)全局基础数据集.删除字段(*字段);
        }
        (void)全局基础数据集.删除节点(位置->节点);
    }
}

std::optional<std::vector<已建复合时间项>> 建立复合时间项组(
    const std::vector<新动态跨特征时间项>& 时间组) {
    std::vector<已建复合时间项> 结果;
    for (const auto& 时间 : 时间组) {
        已建复合时间项 已建{全局基础数据集.新建节点(), {}};
        if (!有效(已建.节点)) {
            清理复合时间项组(结果);
            return std::nullopt;
        }
        auto 记节点 = [&](稳定编码 字段, 稳定编码 目标) {
            const auto 关系 = 全局基础数据集.添加字段节点(已建.节点, 字段, 目标);
            if (!有效(关系)) return false;
            已建.字段组.push_back(关系);
            return true;
        };
        auto 记值 = [&](稳定编码 字段, std::int64_t 值) {
            const auto 关系 = 全局基础数据集.添加字段值(
                已建.节点, 字段, 基础值{值});
            if (!有效(关系)) return false;
            已建.字段组.push_back(关系);
            return true;
        };
        const bool 完整 = 记节点(动态节点类型字段, 复合时间项节点类型)
            && 记节点(复合前状态字段, 时间.前状态节点)
            && 记节点(复合后状态字段, 时间.后状态节点)
            && 记节点(复合前特征类型字段, 时间.前特征类型概念节点)
            && 记节点(复合后特征类型字段, 时间.后特征类型概念节点)
            && 记节点(复合二次特征类型字段, 时间.二次特征类型概念节点)
            && 记节点(复合结果值域字段, 时间.结果值域概念节点)
            && 记值(复合时间差字段, 时间.时间差纳秒);
        结果.push_back(std::move(已建));
        if (!完整) {
            清理复合时间项组(结果);
            return std::nullopt;
        }
    }
    return 结果;
}

std::optional<std::vector<新动态跨特征时间项>> 读取复合时间组(
    稳定编码 动态节点) {
    std::vector<新动态跨特征时间项> 结果;
    for (const auto& 持有 : 全局基础数据集.查询字段(
        动态节点, 复合时间项字段)) {
        const auto* 项节点 = std::get_if<稳定编码>(&持有.内容);
        if (!项节点 || !节点仍存在(*项节点)) return std::nullopt;
        const auto 类型 = 读取唯一节点字段(*项节点, 动态节点类型字段);
        const auto 前状态 = 读取唯一节点字段(*项节点, 复合前状态字段);
        const auto 后状态 = 读取唯一节点字段(*项节点, 复合后状态字段);
        const auto 前类型 = 读取唯一节点字段(*项节点, 复合前特征类型字段);
        const auto 后类型 = 读取唯一节点字段(*项节点, 复合后特征类型字段);
        const auto 二次类型 = 读取唯一节点字段(*项节点, 复合二次特征类型字段);
        const auto 值域 = 读取唯一节点字段(*项节点, 复合结果值域字段);
        const auto 时间差 = 读取唯一I64字段(*项节点, 复合时间差字段);
        if (!类型 || *类型 != 复合时间项节点类型 || !前状态 || !后状态
            || !前类型 || !后类型 || !二次类型 || !值域 || !时间差) {
            return std::nullopt;
        }
        结果.push_back({*前状态, *后状态, *前类型, *后类型,
            *二次类型, *值域, 时间差->second});
    }
    std::sort(结果.begin(), 结果.end(), [](const auto& 左, const auto& 右) {
        if (左.前状态节点 != 右.前状态节点) {
            return 左.前状态节点 < 右.前状态节点;
        }
        return 左.后状态节点 < 右.后状态节点;
    });
    return 结果;
}

std::vector<稳定编码> 查询全部动态节点() {
    std::vector<稳定编码> 结果;
    for (const auto& 字段 : 全局基础数据集.查询目标字段(
        动态节点类型, 动态节点类型字段)) {
        if (节点仍存在(字段.所属节点)) 结果.push_back(字段.所属节点);
    }
    std::sort(结果.begin(), 结果.end());
    结果.erase(std::unique(结果.begin(), 结果.end()), 结果.end());
    return 结果;
}

