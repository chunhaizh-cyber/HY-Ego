std::vector<稳定编码> 查询全部动态节点() {
    std::vector<稳定编码> 结果;
    for (const auto& 字段 : 全局基础数据集.查询目标字段(
        动态节点类型, 动态节点类型字段)) {
        if (节点仍存在(字段.所属节点)) 结果.push_back(字段.所属节点);
    }
    std::sort(结果.begin(), 结果.end());
    结果.erase(std::unique(结果.begin(), 结果.end()), 结果.end());
    return 结果;
}

void 清理动态基础字段(
    稳定编码 动态节点,
    const std::vector<稳定编码>& 已写字段,
    std::vector<已建状态引用>& 状态引用组) noexcept {
    for (auto 字段 = 已写字段.rbegin(); 字段 != 已写字段.rend(); ++字段) {
        (void)全局基础数据集.删除字段(*字段);
    }
    清理状态引用组(状态引用组);
    (void)全局基础数据集.删除节点(动态节点);
}

