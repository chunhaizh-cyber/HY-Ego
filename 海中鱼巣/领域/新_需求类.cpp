新需求全集结果 新_需求类::查询全部需求() const noexcept {
    新需求全集结果 结果;
    try {
        std::lock_guard 锁(新需求互斥);
        if (!结构仍存在()) {
            结果.状态 = 新需求操作状态::尚未初始化;
            return 结果;
        }
        const auto 安全 = 读取需求信息(安全根需求节点);
        const auto 服务 = 读取需求信息(服务根需求节点);
        if (!安全 || !服务 || 安全根需求节点 == 服务根需求节点
            || 安全->根角色 != 新需求根角色::安全
            || 服务->根角色 != 新需求根角色::服务
            || 安全->父需求节点 || 服务->父需求节点) {
            结果.状态 = 新需求操作状态::结构不一致;
            return 结果;
        }

        std::vector<稳定编码> 待访问{安全根需求节点, 服务根需求节点};
        std::set<稳定编码> 已发现{安全根需求节点, 服务根需求节点};
        for (std::size_t 位置 = 0; 位置 < 待访问.size(); ++位置) {
            const auto 父 = 待访问[位置];
            if (!读取需求信息(父)) {
                结果.状态 = 新需求操作状态::结构不一致;
                结果.需求节点组.clear();
                return 结果;
            }
            for (const auto& 关系 : 查询子需求关系(父)) {
                const auto 子 = 关系.目标节点;
                const auto 子信息 = 读取需求信息(子);
                if (!子信息 || 子信息->父需求节点 != 父
                    || 子信息->根角色 || !已发现.insert(子).second) {
                    结果.状态 = 新需求操作状态::结构不一致;
                    结果.需求节点组.clear();
                    return 结果;
                }
                待访问.push_back(子);
            }
        }

        std::vector<稳定编码> 全部类型节点;
        for (const auto& 字段 : 全局基础数据集.查询目标字段(
            需求节点类型, 节点类型字段)) {
            if (!是需求类型节点(字段.所属节点)) {
                结果.状态 = 新需求操作状态::结构不一致;
                return 结果;
            }
            全部类型节点.push_back(字段.所属节点);
        }
        std::sort(全部类型节点.begin(), 全部类型节点.end());
        if (std::adjacent_find(全部类型节点.begin(), 全部类型节点.end())
                != 全部类型节点.end()) {
            结果.状态 = 新需求操作状态::结构不一致;
            return 结果;
        }
        std::sort(待访问.begin(), 待访问.end());
        if (待访问 != 全部类型节点) {
            结果.状态 = 新需求操作状态::结构不一致;
            return 结果;
        }
        结果.需求节点组 = std::move(待访问);
        结果.状态 = 新需求操作状态::已找到;
        return 结果;
    } catch (...) {
        结果.状态 = 新需求操作状态::资源失败;
        结果.需求节点组.clear();
        return 结果;
    }
}

新需求列表全集结果 新_需求类::查询全部需求列表() const noexcept {
    新需求列表全集结果 结果;
    结果.状态 = 新需求操作状态::结构不一致;
    try {
        std::lock_guard 锁(新需求互斥);
        const auto 全集 = 查询全部需求();
        if (全集.状态 != 新需求操作状态::已找到) {
            结果.状态 = 全集.状态;
            return 结果;
        }
        std::map<稳定编码, 新需求信息> 需求映射;
        for (const auto 节点 : 全集.需求节点组) {
            const auto 信息 = 读取需求信息(节点);
            if (!信息 || !原始目标字段一致(节点, 信息->目标)
                || !需求映射.emplace(节点, *信息).second) return 结果;
        }

        std::set<稳定编码> 登记列表;
        for (const auto& 字段 : 全局基础数据集.查询字段(
                需求树根节点, 需求列表项字段)) {
            const auto* 节点 = std::get_if<稳定编码>(&字段.内容);
            if (!节点 || !是列表项类型节点(*节点)
                || !登记列表.insert(*节点).second) return 结果;
        }
        std::set<稳定编码> 类型列表;
        for (const auto& 字段 : 全局基础数据集.查询目标字段(
                需求列表项节点类型, 节点类型字段)) {
            if (!是列表项类型节点(字段.所属节点)
                || !类型列表.insert(字段.所属节点).second) return 结果;
        }
        if (登记列表 != 类型列表) return 结果;

        // 根列表与普通列表分账；普通需求可合法具有与根相同的目标。
        using 列表键 = std::tuple<std::optional<新需求根角色>, 稳定编码,
            稳定编码, 新需求目标形式, std::optional<稳定编码>,
            std::optional<稳定编码>, std::optional<新需求变化方向>>;
        std::set<列表键> 目标键组;
        std::set<稳定编码> 已覆盖需求;
        std::vector<新需求列表项信息> 列表候选;
        for (const auto 节点 : 登记列表) {
            auto 信息 = 读取列表项信息(节点);
            if (!信息 || !原始目标字段一致(节点, 信息->目标)) return 结果;
            const auto& 目标 = 信息->目标;
            if (!目标键组.emplace(信息->根角色, 信息->目标存在节点,
                    目标.目标特征类型概念节点, 目标.目标形式,
                    目标.目标值域概念节点, 目标.目标比较关系概念节点,
                    目标.目标变化方向).second) return 结果;
            std::set<稳定编码> 成员;
            for (const auto& 字段 : 全局基础数据集.查询字段(节点, 列表成员字段)) {
                const auto* 需求节点 = std::get_if<稳定编码>(&字段.内容);
                if (!需求节点 || !成员.insert(*需求节点).second
                    || !已覆盖需求.insert(*需求节点).second) return 结果;
                const auto 需求 = 需求映射.find(*需求节点);
                if (需求 == 需求映射.end()
                    || 需求->second.目标存在节点 != 信息->目标存在节点
                    || 需求->second.目标 != 目标
                    || 需求->second.根角色 != 信息->根角色) return 结果;
            }
            if (成员.empty() || (信息->根角色 && 成员.size() != 1)) return 结果;
            信息->需求节点组.assign(成员.begin(), 成员.end());
            列表候选.push_back(std::move(*信息));
        }
        if (已覆盖需求.size() != 需求映射.size()) return 结果;
        std::vector<新需求信息> 需求候选;
        需求候选.reserve(需求映射.size());
        for (auto& [节点, 信息] : 需求映射) {
            (void)节点;
            需求候选.push_back(std::move(信息));
        }
        结果.列表项组 = std::move(列表候选);
        结果.需求组 = std::move(需求候选);
        结果.状态 = 新需求操作状态::已找到;
        return 结果;
    } catch (...) {
        结果.状态 = 新需求操作状态::资源失败;
        结果.列表项组.clear();
        结果.需求组.clear();
        return 结果;
    }
}

std::vector<稳定编码> 新_需求类::查询直接子需求(
    稳定编码 需求节点) const noexcept {
    try {
        std::lock_guard 锁(新需求互斥);
        std::vector<稳定编码> 结果;
        if (!读取需求信息(需求节点)) return 结果;
        for (const auto& 关系 : 查询子需求关系(需求节点)) {
            if (读取需求信息(关系.目标节点)) 结果.push_back(关系.目标节点);
        }
        std::sort(结果.begin(), 结果.end());
        结果.erase(std::unique(结果.begin(), 结果.end()), 结果.end());
        return 结果;
    } catch (...) {
        return {};
    }
}

