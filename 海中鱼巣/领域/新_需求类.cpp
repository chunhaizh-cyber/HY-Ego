新需求精确查询结果 新_需求类::按完整目标查询(
    稳定编码 目标存在节点,
    const 新需求目标定义& 目标) const noexcept {
    新需求精确查询结果 结果;
    try {
        std::lock_guard 锁(新需求互斥);
        if (!结构仍存在()) {
            结果.状态 = 新需求操作状态::尚未初始化;
            return 结果;
        }
        std::optional<新需求列表项信息> 唯一命中;
        for (const auto 列表项 : 读取多节点字段(需求树根节点, 需求列表项字段)) {
            const auto 信息 = 读取列表项信息(列表项);
            if (!信息) {
                结果.状态 = 新需求操作状态::结构不一致;
                return 结果;
            }
            if (信息->根角色) continue;
            if (信息->目标存在节点 == 目标存在节点
                && 目标相同(信息->目标, 目标)) {
                if (唯一命中) {
                    结果.状态 = 新需求操作状态::结构不一致;
                    return 结果;
                }
                唯一命中 = *信息;
            }
        }
        if (唯一命中) {
            结果.状态 = 新需求操作状态::已找到;
            结果.需求列表项节点 = 唯一命中->节点;
            结果.需求节点组 = 唯一命中->需求节点组;
            return 结果;
        }
        结果.状态 = 新需求操作状态::需求不存在;
        return 结果;
    } catch (...) {
        结果.状态 = 新需求操作状态::资源失败;
        return 结果;
    }
}

新需求当前满足结果 新_需求类::复核当前满足(
    稳定编码 需求节点) const noexcept {
    新需求当前满足结果 结果;
    try {
        std::lock_guard 锁(新需求互斥);
        const auto 需求 = 读取需求信息(需求节点);
        if (!需求) {
            结果.状态 = 结构仍存在()
                ? 新需求当前满足状态::需求不存在
                : 新需求当前满足状态::结构不一致;
            return 结果;
        }

        std::optional<稳定编码> 实际特征;
        const auto 目标存在 = 存在服务_.获取存在(需求->目标存在节点);
        if (!目标存在) {
            结果.状态 = 新需求当前满足状态::结构不一致;
            return 结果;
        }
        for (const auto 候选 : 目标存在->特征节点组) {
            const auto 特征 = 特征服务_.获取特征(候选);
            if (!特征) {
                结果.状态 = 新需求当前满足状态::结构不一致;
                return 结果;
            }
            const auto 类型根 = 取得特征类型根(
                特征->特征概念节点, 特征概念服务_);
            if (类型根 && *类型根 == 需求->目标.目标特征类型概念节点) {
                if (实际特征) {
                    结果.状态 = 新需求当前满足状态::结构不一致;
                    return 结果;
                }
                实际特征 = 候选;
            }
        }
        if (!实际特征) {
            结果.状态 = 新需求当前满足状态::目标特征尚未形成;
            return 结果;
        }
        结果.实际特征节点 = *实际特征;

        const auto 特征 = 特征服务_.获取特征(*实际特征);
        if (!特征) {
            结果.状态 = 新需求当前满足状态::结构不一致;
            return 结果;
        }
        if (!特征->当前值) {
            结果.状态 = 新需求当前满足状态::当前值不存在;
            return 结果;
        }
        if (需求->目标.目标形式 == 新需求目标形式::变化方向) {
            结果.状态 = 新需求当前满足状态::需要执行前后比较;
            return 结果;
        }
        if (!需求->目标.目标值域概念节点
            || !需求->目标.目标比较关系概念节点) {
            结果.状态 = 新需求当前满足状态::结构不一致;
            return 结果;
        }
        const auto 目标概念 = 特征概念服务_.获取特征概念(
            *需求->目标.目标值域概念节点);
        const auto 比较概念 = 二次特征概念服务_.获取二次特征概念(
            *需求->目标.目标比较关系概念节点);
        if (!目标概念 || !比较概念) {
            结果.状态 = 新需求当前满足状态::结构不一致;
            return 结果;
        }
        const auto 实际根 = 取得特征类型根(
            特征->特征概念节点, 特征概念服务_);
        const auto 目标根 = 取得特征类型根(
            *需求->目标.目标值域概念节点, 特征概念服务_);
        if (!实际根 || !目标根 || *实际根 != *目标根
            || *目标根 != 需求->目标.目标特征类型概念节点) {
            结果.状态 = 新需求当前满足状态::结构不一致;
            return 结果;
        }
        if (!比较关系适用于目标(*比较概念, *目标根,
                *需求->目标.目标值域概念节点, 特征概念服务_)) {
            结果.状态 = 新需求当前满足状态::比较关系不适用;
            return 结果;
        }

        const auto 定位 = 定位准确值(
            *特征->当前值, *目标概念, 特征值服务_, 存在服务_);
        if (!定位.结构有效) {
            结果.状态 = 新需求当前满足状态::比较关系不适用;
            return 结果;
        }
        结果.准确差异 = 定位.准确差异;

        auto 关系组 = 比较概念->结果域种类组;
        if (关系组.empty()) 关系组.push_back(二次特征结果域种类::任意);
        if (std::any_of(关系组.begin(), 关系组.end(), [&](auto 关系) {
            return 关系接受位置(关系, 定位.位置);
        })) {
            结果.状态 = 新需求当前满足状态::已满足;
            if (定位.位置 == 准确值目标位置::命中) 结果.准确差异 = 0;
            return 结果;
        }

        auto 方向 = 所需方向::无;
        for (const auto 关系 : 关系组) {
            方向 = 合并方向(方向, 关系所需方向(关系, 定位.位置));
        }
        if (方向 == 所需方向::增加) {
            结果.状态 = 新需求当前满足状态::需增加;
            return 结果;
        }
        if (方向 == 所需方向::减少) {
            结果.状态 = 需求->根角色
                ? 新需求当前满足状态::双根负差非法
                : 新需求当前满足状态::需减少;
            return 结果;
        }
        结果.状态 = 需求->根角色
            ? 新需求当前满足状态::比较关系不适用
            : 新需求当前满足状态::未满足但无有向差值;
        return 结果;
    } catch (...) {
        结果.状态 = 新需求当前满足状态::资源失败;
        return 结果;
    }
}

