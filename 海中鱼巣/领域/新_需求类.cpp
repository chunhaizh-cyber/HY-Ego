bool 新_需求类::绑定关联检查通知(
    const void* 所有者, std::function<void()> 通知) noexcept {
    try {
        std::lock_guard 锁(新需求互斥);
        if (!所有者 || !通知) return false;
        if (关联检查通知所有者_) return 关联检查通知所有者_ == 所有者;
        关联检查通知_ = std::move(通知);
        关联检查通知所有者_ = 所有者;
        return true;
    } catch (...) { return false; }
}

void 新_需求类::解除关联检查通知(const void* 所有者) noexcept {
    try {
        std::lock_guard 锁(新需求互斥);
        if (!所有者 || 关联检查通知所有者_ != 所有者) return;
        关联检查通知_ = {};
        关联检查通知所有者_ = nullptr;
    } catch (...) {}
}

bool 新_需求类::初始化() noexcept {
    try {
        std::lock_guard 锁(新需求互斥);
        if (结构已初始化()) return 结构仍存在();

        std::vector<稳定编码*> 待建{
            &节点类型字段, &需求树根节点类型, &需求节点类型,
            &需求列表项节点类型, &目标存在字段,
            &目标特征类型字段, &目标形式字段,
            &目标值域字段, &目标比较关系字段, &目标变化方向字段,
            &来源类型字段, &来源承接字段, &服务要求确认字段, &服务需求取得执行字段, &活动状态字段, &需求权重字段, &根角色字段,
            &需求列表项字段, &列表成员字段,
            &安全根登记字段, &服务根登记字段, &需求树根节点};
        std::vector<稳定编码*> 已建;
        for (auto* 身份 : 待建) {
            *身份 = 全局基础数据集.新建节点();
            if (!有效(*身份)) {
                for (auto 位置 = 已建.rbegin(); 位置 != 已建.rend(); ++位置) {
                    全局基础数据集.删除节点(**位置);
                    **位置 = {};
                }
                return false;
            }
            已建.push_back(身份);
        }
        const auto 根类型字段 = 全局基础数据集.添加字段节点(
            需求树根节点, 节点类型字段, 需求树根节点类型);
        if (!有效(根类型字段)) {
            for (auto 位置 = 已建.rbegin(); 位置 != 已建.rend(); ++位置) {
                全局基础数据集.删除节点(**位置);
                **位置 = {};
            }
            return false;
        }
        return true;
    } catch (...) {
        return false;
    }
}

新需求双根初始化结果 新_需求类::建立或取得本能双根(
    const 新需求双根初始化请求& 请求) noexcept {
    新需求双根初始化结果 结果;
    try {
        std::lock_guard 锁(新需求互斥);
        if (!结构仍存在()) {
            结果.状态 = 新需求操作状态::尚未初始化;
            return 结果;
        }
        if (请求.安全根.初始权重 < 0 || 请求.服务根.初始权重 < 0) {
            结果.状态 = 新需求操作状态::权重不合法;
            return 结果;
        }

        const auto 核验根定义 = [&](const 新根需求定义& 定义, bool 服务方向)
            -> std::optional<稳定编码> {
            if (!存在服务_.是存在节点(定义.目标存在节点)
                || !目标形状合法(定义.目标)
                || (服务方向
                    ? (定义.目标.目标形式 != 新需求目标形式::变化方向
                        || 定义.目标.目标变化方向 != 新需求变化方向::增加)
                    : 定义.目标.目标形式 != 新需求目标形式::值)) {
                return std::nullopt;
            }
            const auto 目标存在 = 存在服务_.获取存在(定义.目标存在节点);
            const auto 目标根 = 取得特征类型根(
                定义.目标.目标特征类型概念节点, 特征概念服务_);
            if (!目标存在 || !目标根
                || *目标根 != 定义.目标.目标特征类型概念节点) {
                return std::nullopt;
            }
            if (!服务方向) {
                const auto 目标值域 = 特征概念服务_.获取特征概念(
                    *定义.目标.目标值域概念节点);
                const auto 比较关系 = 二次特征概念服务_.获取二次特征概念(
                    *定义.目标.目标比较关系概念节点);
                if (!目标值域 || !比较关系
                    || !比较关系适用于目标(*比较关系, *目标根,
                        *定义.目标.目标值域概念节点, 特征概念服务_)) return std::nullopt;
            }
            std::size_t 命中数量 = 0;
            for (const auto 特征节点 : 目标存在->特征节点组) {
                const auto 特征 = 特征服务_.获取特征(特征节点);
                const auto 实际根 = 特征
                    ? 取得特征类型根(特征->特征概念节点, 特征概念服务_)
                    : std::nullopt;
                if (!特征 || !实际根) return std::nullopt;
                if (*实际根 == *目标根) ++命中数量;
            }
            return 命中数量 == 1 ? 目标根 : std::nullopt;
        };

        const auto 安全类型根 = 核验根定义(请求.安全根, false);
        const auto 服务类型根 = 核验根定义(请求.服务根, true);
        if (!安全类型根 || !服务类型根) {
            结果.状态 = 新需求操作状态::双根定义冲突;
            return 结果;
        }
        if (请求.安全根.目标存在节点 != 请求.服务根.目标存在节点
            || 请求.安全根.目标.目标特征类型概念节点
                == 请求.服务根.目标.目标特征类型概念节点) {
            结果.状态 = 新需求操作状态::双根定义冲突;
            return 结果;
        }

        const bool 已有安全 = 有效(安全根需求节点);
        const bool 已有服务 = 有效(服务根需求节点);
        if (已有安全 || 已有服务) {
            if (!已有安全 || !已有服务) {
                结果.状态 = 新需求操作状态::结构不一致;
                return 结果;
            }
            const auto 安全信息 = 读取需求信息(安全根需求节点);
            const auto 服务信息 = 读取需求信息(服务根需求节点);
            if (!安全信息 || !服务信息
                || 安全信息->根角色 != 新需求根角色::安全
                || 服务信息->根角色 != 新需求根角色::服务
                || 安全信息->目标存在节点 != 请求.安全根.目标存在节点
                || 服务信息->目标存在节点 != 请求.服务根.目标存在节点
                || 安全信息->目标 != 请求.安全根.目标
                || 服务信息->目标 != 请求.服务根.目标
                || 安全信息->权重 != 请求.安全根.初始权重
                || 服务信息->权重 != 请求.服务根.初始权重) {
                结果.状态 = 新需求操作状态::双根定义冲突;
                return 结果;
            }
            const auto 安全列表字段组 = 全局基础数据集.查询目标字段(
                安全根需求节点, 列表成员字段);
            const auto 服务列表字段组 = 全局基础数据集.查询目标字段(
                服务根需求节点, 列表成员字段);
            const auto 安全登记 = 读取唯一节点字段(
                需求树根节点, 安全根登记字段);
            const auto 服务登记 = 读取唯一节点字段(
                需求树根节点, 服务根登记字段);
            const auto 安全列表项 = 安全列表字段组.size() == 1
                ? 读取列表项信息(安全列表字段组.front().所属节点)
                : std::nullopt;
            const auto 服务列表项 = 服务列表字段组.size() == 1
                ? 读取列表项信息(服务列表字段组.front().所属节点)
                : std::nullopt;
            if (安全列表字段组.size() != 1 || 服务列表字段组.size() != 1
                || !安全登记 || *安全登记 != 安全根需求节点
                || !服务登记 || *服务登记 != 服务根需求节点
                || !安全列表项 || !服务列表项
                || 安全列表项->根角色 != 新需求根角色::安全
                || 服务列表项->根角色 != 新需求根角色::服务
                || 安全列表项->目标存在节点 != 请求.安全根.目标存在节点
                || 服务列表项->目标存在节点 != 请求.服务根.目标存在节点
                || 安全列表项->目标 != 请求.安全根.目标
                || 服务列表项->目标 != 请求.服务根.目标
                || 安全列表项->需求节点组.size() != 1
                || 服务列表项->需求节点组.size() != 1
                || 安全列表项->需求节点组.front() != 安全根需求节点
                || 服务列表项->需求节点组.front() != 服务根需求节点) {
                结果.状态 = 新需求操作状态::结构不一致;
                return 结果;
            }
            结果.状态 = 新需求操作状态::已复用;
            结果.安全根 = 安全根需求节点;
            结果.服务根 = 服务根需求节点;
            结果.安全根列表项 = 安全列表字段组.front().所属节点;
            结果.服务根列表项 = 服务列表字段组.front().所属节点;
            return 结果;
        }

        if (!全局基础数据集.查询字段(需求树根节点, 安全根登记字段).empty()
            || !全局基础数据集.查询字段(需求树根节点, 服务根登记字段).empty()) {
            结果.状态 = 新需求操作状态::结构不一致;
            return 结果;
        }

        const 关联检查离域通知 变更通知{关联检查通知_};
        auto 安全材料 = 建立根材料(
            新需求根角色::安全, 请求.安全根);
        if (!安全材料) {
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        auto 服务材料 = 建立根材料(
            新需求根角色::服务, 请求.服务根);
        if (!服务材料) {
            回滚根材料(*安全材料);
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }

        std::vector<稳定编码> 根字段;
        auto 注册 = [&](稳定编码 字段, 稳定编码 目标) {
            const auto 关系 = 全局基础数据集.添加字段节点(需求树根节点, 字段, 目标);
            if (有效(关系)) 根字段.push_back(关系);
            return 有效(关系);
        };
        if (!注册(安全根登记字段, 安全材料->需求)
            || !注册(服务根登记字段, 服务材料->需求)
            || !注册(需求列表项字段, 安全材料->列表项)
            || !注册(需求列表项字段, 服务材料->列表项)) {
            回滚字段(根字段);
            回滚根材料(*服务材料);
            回滚根材料(*安全材料);
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }

        安全根需求节点 = 安全材料->需求;
        服务根需求节点 = 服务材料->需求;
        结果.状态 = 新需求操作状态::已建立;
        结果.安全根 = 安全根需求节点;
        结果.服务根 = 服务根需求节点;
        结果.安全根列表项 = 安全材料->列表项;
        结果.服务根列表项 = 服务材料->列表项;
        return 结果;
    } catch (...) {
        结果.状态 = 新需求操作状态::资源失败;
        return 结果;
    }
}

