bool 新_需求类::初始化() noexcept {
    try {
        std::lock_guard 锁(新需求互斥);
        if (结构已初始化()) return 结构仍存在();

        std::vector<稳定编码*> 待建{
            &节点类型字段, &需求树根节点类型, &需求节点类型,
            &需求列表项节点类型, &目标存在字段,
            &目标特征类型字段, &目标形式字段,
            &目标值域字段, &目标比较关系字段, &目标变化方向字段,
            &来源类型字段, &来源承接字段, &活动状态字段, &需求权重字段, &根角色字段,
            &需求列表项字段, &列表成员字段,
            &安全根登记字段, &服务根登记字段, &需求树根节点};
        std::vector<稳定编码*> 已建;
        for (auto* 身份 : 待建) {
            *身份 = 全局基础数据集.新建节点();
            if (!有效(*身份)) {
                for (auto 位置 = 已建.rbegin(); 位置 != 已建.rend(); ++位置) {
                    全局基础数据集.删除节点(**位置);
                    **位置 = {};
                }
                return false;
            }
            已建.push_back(身份);
        }
        const auto 根类型字段 = 全局基础数据集.添加字段节点(
            需求树根节点, 节点类型字段, 需求树根节点类型);
        if (!有效(根类型字段)) {
            for (auto 位置 = 已建.rbegin(); 位置 != 已建.rend(); ++位置) {
                全局基础数据集.删除节点(**位置);
                **位置 = {};
            }
            return false;
        }
        return true;
    } catch (...) {
        return false;
    }
}

新需求双根初始化结果 新_需求类::建立或取得本能双根(
    const 新需求双根初始化请求& 请求) noexcept {
    新需求双根初始化结果 结果;
    try {
        std::lock_guard 锁(新需求互斥);
        if (!结构仍存在()) {
            结果.状态 = 新需求操作状态::尚未初始化;
            return 结果;
        }
        if (请求.安全根.初始权重 < 0 || 请求.服务根.初始权重 < 0) {
            结果.状态 = 新需求操作状态::权重不合法;
            return 结果;
        }

        const auto 核验根定义 = [&](const 新根需求定义& 定义)
            -> std::optional<稳定编码> {
            if (!存在服务_.是存在节点(定义.目标存在节点)
                || !目标形状合法(定义.目标)
                || 定义.目标.目标形式 != 新需求目标形式::值) {
                return std::nullopt;
            }
            const auto 目标存在 = 存在服务_.获取存在(定义.目标存在节点);
            const auto 目标值域 = 特征概念服务_.获取特征概念(
                *定义.目标.目标值域概念节点);
            const auto 比较关系 = 二次特征概念服务_.获取二次特征概念(
                *定义.目标.目标比较关系概念节点);
            if (!目标存在 || !目标值域 || !比较关系) return std::nullopt;
            const auto 目标根 = 取得特征类型根(
                *定义.目标.目标值域概念节点, 特征概念服务_);
            if (!目标根
                || *目标根 != 定义.目标.目标特征类型概念节点
                || !比较关系适用于目标(*比较关系, *目标根,
                    *定义.目标.目标值域概念节点, 特征概念服务_)) {
                return std::nullopt;
            }
            std::size_t 命中数量 = 0;
            for (const auto 特征节点 : 目标存在->特征节点组) {
                const auto 特征 = 特征服务_.获取特征(特征节点);
                const auto 实际根 = 特征
                    ? 取得特征类型根(特征->特征概念节点, 特征概念服务_)
                    : std::nullopt;
                if (!特征 || !实际根) return std::nullopt;
                if (*实际根 == *目标根) ++命中数量;
            }
            return 命中数量 == 1 ? 目标根 : std::nullopt;
        };

        const auto 安全类型根 = 核验根定义(请求.安全根);
        const auto 服务类型根 = 核验根定义(请求.服务根);
        if (!安全类型根 || !服务类型根) {
            结果.状态 = 新需求操作状态::双根定义冲突;
            return 结果;
        }
        if (请求.安全根.目标存在节点 != 请求.服务根.目标存在节点
            || 请求.安全根.目标.目标特征类型概念节点
                == 请求.服务根.目标.目标特征类型概念节点) {
            结果.状态 = 新需求操作状态::双根定义冲突;
            return 结果;
        }

        const bool 已有安全 = 有效(安全根需求节点);
        const bool 已有服务 = 有效(服务根需求节点);
        if (已有安全 || 已有服务) {
            if (!已有安全 || !已有服务) {
                结果.状态 = 新需求操作状态::结构不一致;
                return 结果;
            }
            const auto 安全信息 = 读取需求信息(安全根需求节点);
            const auto 服务信息 = 读取需求信息(服务根需求节点);
            if (!安全信息 || !服务信息
                || 安全信息->根角色 != 新需求根角色::安全
                || 服务信息->根角色 != 新需求根角色::服务
                || 安全信息->目标存在节点 != 请求.安全根.目标存在节点
                || 服务信息->目标存在节点 != 请求.服务根.目标存在节点
                || 安全信息->目标 != 请求.安全根.目标
                || 服务信息->目标 != 请求.服务根.目标
                || 安全信息->权重 != 请求.安全根.初始权重
                || 服务信息->权重 != 请求.服务根.初始权重) {
                结果.状态 = 新需求操作状态::双根定义冲突;
                return 结果;
            }
            const auto 安全列表字段组 = 全局基础数据集.查询目标字段(
                安全根需求节点, 列表成员字段);
            const auto 服务列表字段组 = 全局基础数据集.查询目标字段(
                服务根需求节点, 列表成员字段);
            const auto 安全登记 = 读取唯一节点字段(
                需求树根节点, 安全根登记字段);
            const auto 服务登记 = 读取唯一节点字段(
                需求树根节点, 服务根登记字段);
            const auto 安全列表项 = 安全列表字段组.size() == 1
                ? 读取列表项信息(安全列表字段组.front().所属节点)
                : std::nullopt;
            const auto 服务列表项 = 服务列表字段组.size() == 1
                ? 读取列表项信息(服务列表字段组.front().所属节点)
                : std::nullopt;
            if (安全列表字段组.size() != 1 || 服务列表字段组.size() != 1
                || !安全登记 || *安全登记 != 安全根需求节点
                || !服务登记 || *服务登记 != 服务根需求节点
                || !安全列表项 || !服务列表项
                || 安全列表项->根角色 != 新需求根角色::安全
                || 服务列表项->根角色 != 新需求根角色::服务
                || 安全列表项->目标存在节点 != 请求.安全根.目标存在节点
                || 服务列表项->目标存在节点 != 请求.服务根.目标存在节点
                || 安全列表项->目标 != 请求.安全根.目标
                || 服务列表项->目标 != 请求.服务根.目标
                || 安全列表项->需求节点组.size() != 1
                || 服务列表项->需求节点组.size() != 1
                || 安全列表项->需求节点组.front() != 安全根需求节点
                || 服务列表项->需求节点组.front() != 服务根需求节点) {
                结果.状态 = 新需求操作状态::结构不一致;
                return 结果;
            }
            结果.状态 = 新需求操作状态::已复用;
            结果.安全根 = 安全根需求节点;
            结果.服务根 = 服务根需求节点;
            结果.安全根列表项 = 安全列表字段组.front().所属节点;
            结果.服务根列表项 = 服务列表字段组.front().所属节点;
            return 结果;
        }

        if (!全局基础数据集.查询字段(需求树根节点, 安全根登记字段).empty()
            || !全局基础数据集.查询字段(需求树根节点, 服务根登记字段).empty()) {
            结果.状态 = 新需求操作状态::结构不一致;
            return 结果;
        }

        auto 安全材料 = 建立根材料(
            新需求根角色::安全, 请求.安全根);
        if (!安全材料) {
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        auto 服务材料 = 建立根材料(
            新需求根角色::服务, 请求.服务根);
        if (!服务材料) {
            回滚根材料(*安全材料);
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }

        std::vector<稳定编码> 根字段;
        auto 注册 = [&](稳定编码 字段, 稳定编码 目标) {
            const auto 关系 = 全局基础数据集.添加字段节点(需求树根节点, 字段, 目标);
            if (有效(关系)) 根字段.push_back(关系);
            return 有效(关系);
        };
        if (!注册(安全根登记字段, 安全材料->需求)
            || !注册(服务根登记字段, 服务材料->需求)
            || !注册(需求列表项字段, 安全材料->列表项)
            || !注册(需求列表项字段, 服务材料->列表项)) {
            回滚字段(根字段);
            回滚根材料(*服务材料);
            回滚根材料(*安全材料);
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }

        安全根需求节点 = 安全材料->需求;
        服务根需求节点 = 服务材料->需求;
        结果.状态 = 新需求操作状态::已建立;
        结果.安全根 = 安全根需求节点;
        结果.服务根 = 服务根需求节点;
        结果.安全根列表项 = 安全材料->列表项;
        结果.服务根列表项 = 服务材料->列表项;
        return 结果;
    } catch (...) {
        结果.状态 = 新需求操作状态::资源失败;
        return 结果;
    }
}

新需求建立结果 新_需求类::建立或取得普通需求(
    const 新普通需求建立请求& 请求) noexcept {
    return 建立或取得普通需求已核验(请求, false);
}

新需求建立结果 新_需求类::建立或取得普通需求已核验(
    const 新普通需求建立请求& 请求,
    bool 允许任务子目标) noexcept {
    新需求建立结果 结果;
    try {
        std::lock_guard 锁(新需求互斥);
        if (!结构仍存在()) {
            结果.状态 = 新需求操作状态::尚未初始化;
            return 结果;
        }
        const auto 来源类型值 = static_cast<std::int64_t>(请求.来源类型);
        if (!转换来源类型(来源类型值)
            || (请求.来源类型 == 新需求来源类型::本能定义
                && 请求.来源承接节点)
            || (请求.来源类型 == 新需求来源类型::任务子目标
                && (!请求.来源承接节点
                    || !有效(*请求.来源承接节点)))) {
            结果.状态 = 新需求操作状态::入口拒绝;
            return 结果;
        }
        const auto 父需求 = 读取需求信息(请求.父需求节点);
        if (!父需求) {
            结果.状态 = 新需求操作状态::父需求不合法;
            return 结果;
        }
        if (!存在服务_.是存在节点(请求.目标存在节点)) {
            结果.状态 = 新需求操作状态::目标存在不合法;
            return 结果;
        }
        if (!目标形状合法(请求.目标)) {
            结果.状态 = 新需求操作状态::目标形式不合法;
            return 结果;
        }
        if (!特征概念服务_.是特征概念节点(
                请求.目标.目标特征类型概念节点)) {
            结果.状态 = 新需求操作状态::目标特征类型不合法;
            return 结果;
        }
        if (请求.目标.目标形式 == 新需求目标形式::值) {
            if (!特征概念服务_.是特征概念节点(
                    *请求.目标.目标值域概念节点)) {
                结果.状态 = 新需求操作状态::目标值域不合法;
                return 结果;
            }
            if (!二次特征概念服务_.是二次特征概念(
                    *请求.目标.目标比较关系概念节点)) {
                结果.状态 = 新需求操作状态::比较关系不合法;
                return 结果;
            }
            const auto 类型根 = 取得特征类型根(
                *请求.目标.目标值域概念节点, 特征概念服务_);
            if (!类型根 || *类型根 != 请求.目标.目标特征类型概念节点) {
                结果.状态 = 新需求操作状态::目标值域不合法;
                return 结果;
            }
            const auto 比较关系 = 二次特征概念服务_.获取二次特征概念(
                *请求.目标.目标比较关系概念节点);
            if (!比较关系 || !比较关系适用于目标(*比较关系, *类型根,
                    *请求.目标.目标值域概念节点, 特征概念服务_)) {
                结果.状态 = 新需求操作状态::比较关系不合法;
                return 结果;
            }
        }

        if (请求.来源类型 == 新需求来源类型::任务子目标
            && !允许任务子目标) {
            结果.状态 = 新需求操作状态::任务来源未接通;
            return 结果;
        }

        std::optional<新需求列表项信息> 列表项;
        for (const auto 候选 : 读取多节点字段(
            需求树根节点, 需求列表项字段)) {
            const auto 信息 = 读取列表项信息(候选);
            if (!信息) {
                结果.状态 = 新需求操作状态::结构不一致;
                return 结果;
            }
            if (信息->根角色) continue;
            if (信息->目标存在节点 == 请求.目标存在节点
                && 目标相同(信息->目标, 请求.目标)) {
                if (列表项) {
                    结果.状态 = 新需求操作状态::结构不一致;
                    return 结果;
                }
                列表项 = *信息;
            }
        }
        if (列表项) {
            for (const auto 候选 : 列表项->需求节点组) {
                const auto 信息 = 读取需求信息(候选);
                if (!信息 || 信息->根角色 || !信息->父需求节点
                    || !信息->来源类型) {
                    结果.状态 = 新需求操作状态::结构不一致;
                    return 结果;
                }
                if (*信息->父需求节点 == 请求.父需求节点
                    && *信息->来源类型 == 请求.来源类型
                    && 信息->来源承接节点 == 请求.来源承接节点) {
                    结果.状态 = 新需求操作状态::已复用;
                    结果.需求节点 = 信息->节点;
                    结果.需求列表项节点 = 列表项->节点;
                    return 结果;
                }
            }
        }

        const auto 需求节点 = 全局基础数据集.新建节点();
        if (!有效(需求节点)) {
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        std::vector<稳定编码> 需求字段组;
        std::optional<稳定编码> 父子关系;
        std::optional<稳定编码> 列表成员关系;
        std::optional<稳定编码> 新列表节点;
        std::vector<稳定编码> 新列表字段组;
        std::optional<稳定编码> 新列表登记字段;

        const auto 回滚 = [&]() noexcept {
            if (列表成员关系) {
                (void)全局基础数据集.删除字段(*列表成员关系);
            }
            if (父子关系) (void)全局基础数据集.删除关系(*父子关系);
            回滚字段(需求字段组);
            (void)全局基础数据集.删除节点(需求节点);
            if (新列表登记字段) {
                (void)全局基础数据集.删除字段(*新列表登记字段);
            }
            回滚字段(新列表字段组);
            if (新列表节点) {
                (void)全局基础数据集.删除节点(*新列表节点);
            }
        };
        const auto 加需求节点字段 = [&](稳定编码 字段, 稳定编码 目标) {
            const auto 关系 = 全局基础数据集.添加字段节点(
                需求节点, 字段, 目标);
            if (有效(关系)) 需求字段组.push_back(关系);
            return 有效(关系);
        };
        const auto 加需求I64字段 = [&](稳定编码 字段, std::int64_t 值) {
            const auto 关系 = 全局基础数据集.添加字段值(
                需求节点, 字段, 基础值{值});
            if (有效(关系)) 需求字段组.push_back(关系);
            return 有效(关系);
        };
        if (!加需求节点字段(节点类型字段, 需求节点类型)
            || !加需求节点字段(目标存在字段, 请求.目标存在节点)
            || !加需求节点字段(目标特征类型字段,
                请求.目标.目标特征类型概念节点)
            || !加需求I64字段(目标形式字段,
                static_cast<std::int64_t>(请求.目标.目标形式))
            || !加需求I64字段(来源类型字段, 来源类型值)
            || !加需求I64字段(活动状态字段,
                static_cast<std::int64_t>(新需求活动状态::活动))
            || !加需求I64字段(需求权重字段, 0)) {
            回滚();
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        if (请求.目标.目标值域概念节点
            && !加需求节点字段(目标值域字段,
                *请求.目标.目标值域概念节点)) {
            回滚();
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        if (请求.目标.目标比较关系概念节点
            && !加需求节点字段(目标比较关系字段,
                *请求.目标.目标比较关系概念节点)) {
            回滚();
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        if (请求.目标.目标变化方向
            && !加需求I64字段(目标变化方向字段,
                static_cast<std::int64_t>(*请求.目标.目标变化方向))) {
            回滚();
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        if (请求.来源承接节点
            && !加需求节点字段(
                来源承接字段, *请求.来源承接节点)) {
            回滚();
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        const auto 已建父子关系 = 全局基础数据集.添加关系(
            请求.父需求节点, 需求节点,
            基础外部关系类型::父子, 需求父子关系角色);
        if (!有效(已建父子关系)) {
            回滚();
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        父子关系 = 已建父子关系;

        稳定编码 列表节点{};
        if (列表项) {
            列表节点 = 列表项->节点;
        } else {
            列表节点 = 全局基础数据集.新建节点();
            if (!有效(列表节点)) {
                回滚();
                结果.状态 = 新需求操作状态::资源失败;
                return 结果;
            }
            新列表节点 = 列表节点;
            const auto 加列表节点字段 = [&](稳定编码 字段, 稳定编码 目标) {
                const auto 关系 = 全局基础数据集.添加字段节点(
                    列表节点, 字段, 目标);
                if (有效(关系)) 新列表字段组.push_back(关系);
                return 有效(关系);
            };
            if (!加列表节点字段(节点类型字段, 需求列表项节点类型)
                || !加列表节点字段(目标存在字段, 请求.目标存在节点)
                || !加列表节点字段(目标特征类型字段,
                    请求.目标.目标特征类型概念节点)) {
                回滚();
                结果.状态 = 新需求操作状态::资源失败;
                return 结果;
            }
            const auto 形式关系 = 全局基础数据集.添加字段值(
                列表节点, 目标形式字段,
                基础值{static_cast<std::int64_t>(请求.目标.目标形式)});
            if (!有效(形式关系)) {
                回滚();
                结果.状态 = 新需求操作状态::资源失败;
                return 结果;
            }
            新列表字段组.push_back(形式关系);
            if (请求.目标.目标值域概念节点
                && !加列表节点字段(目标值域字段,
                    *请求.目标.目标值域概念节点)) {
                回滚();
                结果.状态 = 新需求操作状态::资源失败;
                return 结果;
            }
            if (请求.目标.目标比较关系概念节点
                && !加列表节点字段(目标比较关系字段,
                    *请求.目标.目标比较关系概念节点)) {
                回滚();
                结果.状态 = 新需求操作状态::资源失败;
                return 结果;
            }
            if (请求.目标.目标变化方向) {
                const auto 方向关系 = 全局基础数据集.添加字段值(
                    列表节点, 目标变化方向字段,
                    基础值{static_cast<std::int64_t>(
                        *请求.目标.目标变化方向)});
                if (!有效(方向关系)) {
                    回滚();
                    结果.状态 = 新需求操作状态::资源失败;
                    return 结果;
                }
                新列表字段组.push_back(方向关系);
            }
            const auto 登记 = 全局基础数据集.添加字段节点(
                需求树根节点, 需求列表项字段, 列表节点);
            if (!有效(登记)) {
                回滚();
                结果.状态 = 新需求操作状态::资源失败;
                return 结果;
            }
            新列表登记字段 = 登记;
        }
        const auto 成员 = 全局基础数据集.添加字段节点(
            列表节点, 列表成员字段, 需求节点);
        if (!有效(成员)) {
            回滚();
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        列表成员关系 = 成员;

        if (!读取需求信息(需求节点) || !读取列表项信息(列表节点)) {
            回滚();
            结果.状态 = 新需求操作状态::结构不一致;
            return 结果;
        }
        std::vector<需求权重修改项> 权重修改组;
        std::set<稳定编码> 已访问{请求.父需求节点};
        if (!构建子树权重修改(请求.父需求节点, 父需求->权重,
                std::nullopt, 已访问, 权重修改组)) {
            回滚();
            结果.状态 = 新需求操作状态::结构不一致;
            return 结果;
        }
        const auto 权重状态 = 应用需求权重修改(权重修改组);
        if (权重状态 != 需求权重写入状态::成功) {
            回滚();
            结果.状态 = 权重状态 == 需求权重写入状态::资源失败
                ? 新需求操作状态::资源失败
                : 新需求操作状态::结构不一致;
            return 结果;
        }

        结果.状态 = 新需求操作状态::已建立;
        结果.需求节点 = 需求节点;
        结果.需求列表项节点 = 列表节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新需求操作状态::资源失败;
        return 结果;
    }
}

