bool 新_需求类::初始化() noexcept {
    try {
        std::lock_guard 锁(新需求互斥);
        if (结构已初始化()) return 结构仍存在();

        std::vector<稳定编码*> 待建{
            &节点类型字段, &需求树根节点类型, &需求节点类型,
            &需求列表项节点类型, &所属存在字段, &目标宿主字段,
            &目标特征类型字段, &目标值域字段, &目标比较关系字段,
            &来源承接字段, &活动状态字段, &根角色字段,
            &根实际特征字段, &需求列表项字段, &列表成员字段,
            &安全根登记字段, &服务根登记字段, &需求树根节点};
        std::vector<稳定编码*> 已建;
        for (auto* 身份 : 待建) {
            *身份 = 全局基础数据集.新建节点();
            if (!有效(*身份)) {
                for (auto 位置 = 已建.rbegin(); 位置 != 已建.rend(); ++位置) {
                    全局基础数据集.删除节点(**位置);
                    **位置 = {};
                }
                return false;
            }
            已建.push_back(身份);
        }
        const auto 根类型字段 = 全局基础数据集.添加字段节点(
            需求树根节点, 节点类型字段, 需求树根节点类型);
        if (!有效(根类型字段)) {
            for (auto 位置 = 已建.rbegin(); 位置 != 已建.rend(); ++位置) {
                全局基础数据集.删除节点(**位置);
                **位置 = {};
            }
            return false;
        }
        return true;
    } catch (...) {
        return false;
    }
}

新需求双根初始化结果 新_需求类::建立或取得本能双根(
    const 新需求双根初始化请求& 请求) noexcept {
    新需求双根初始化结果 结果;
    try {
        std::lock_guard 锁(新需求互斥);
        if (!结构仍存在()) {
            结果.状态 = 新需求操作状态::尚未初始化;
            return 结果;
        }

        const auto 核验根定义 = [&](const 新根需求定义& 定义)
            -> std::optional<稳定编码> {
            const auto 实际特征 = 特征服务_.获取特征(定义.实际特征节点);
            const auto 目标值域 = 特征概念服务_.获取特征概念(
                定义.目标值域概念节点);
            const auto 比较关系 = 二次特征概念服务_.获取二次特征概念(
                定义.目标比较关系概念节点);
            if (!实际特征 || !目标值域 || !比较关系) return std::nullopt;
            const auto 实际根 = 取得特征类型根(
                实际特征->特征概念节点, 特征概念服务_);
            const auto 目标根 = 取得特征类型根(
                定义.目标值域概念节点, 特征概念服务_);
            if (!实际根 || !目标根 || *实际根 != *目标根
                || !比较关系适用于目标(*比较关系, *目标根,
                    定义.目标值域概念节点, 特征概念服务_)) {
                return std::nullopt;
            }
            return 实际根;
        };

        const auto 安全类型根 = 核验根定义(请求.安全根);
        const auto 服务类型根 = 核验根定义(请求.服务根);
        if (!安全类型根 || !服务类型根) {
            结果.状态 = 新需求操作状态::双根定义冲突;
            return 结果;
        }
        if (请求.安全根.实际特征节点 == 请求.服务根.实际特征节点) {
            结果.状态 = 新需求操作状态::双根定义冲突;
            return 结果;
        }

        const bool 已有安全 = 有效(安全根需求节点);
        const bool 已有服务 = 有效(服务根需求节点);
        if (已有安全 || 已有服务) {
            if (!已有安全 || !已有服务) {
                结果.状态 = 新需求操作状态::结构不一致;
                return 结果;
            }
            const auto 安全信息 = 读取需求信息(安全根需求节点);
            const auto 服务信息 = 读取需求信息(服务根需求节点);
            if (!安全信息 || !服务信息
                || 安全信息->根角色 != 新需求根角色::安全
                || 服务信息->根角色 != 新需求根角色::服务
                || 安全信息->根实际特征节点 != 请求.安全根.实际特征节点
                || 服务信息->根实际特征节点 != 请求.服务根.实际特征节点
                || 安全信息->目标.目标值域概念节点
                    != 请求.安全根.目标值域概念节点
                || 服务信息->目标.目标值域概念节点
                    != 请求.服务根.目标值域概念节点
                || 安全信息->目标.目标比较关系概念节点
                    != 请求.安全根.目标比较关系概念节点
                || 服务信息->目标.目标比较关系概念节点
                    != 请求.服务根.目标比较关系概念节点) {
                结果.状态 = 新需求操作状态::双根定义冲突;
                return 结果;
            }
            const auto 安全列表字段组 = 全局基础数据集.查询目标字段(
                安全根需求节点, 列表成员字段);
            const auto 服务列表字段组 = 全局基础数据集.查询目标字段(
                服务根需求节点, 列表成员字段);
            const auto 安全登记 = 读取唯一节点字段(
                需求树根节点, 安全根登记字段);
            const auto 服务登记 = 读取唯一节点字段(
                需求树根节点, 服务根登记字段);
            if (安全列表字段组.size() != 1 || 服务列表字段组.size() != 1
                || !安全登记 || *安全登记 != 安全根需求节点
                || !服务登记 || *服务登记 != 服务根需求节点) {
                结果.状态 = 新需求操作状态::结构不一致;
                return 结果;
            }
            结果.状态 = 新需求操作状态::已复用;
            结果.安全根 = 安全根需求节点;
            结果.服务根 = 服务根需求节点;
            结果.安全根列表项 = 安全列表字段组.front().所属节点;
            结果.服务根列表项 = 服务列表字段组.front().所属节点;
            return 结果;
        }

        if (!全局基础数据集.查询字段(需求树根节点, 安全根登记字段).empty()
            || !全局基础数据集.查询字段(需求树根节点, 服务根登记字段).empty()) {
            结果.状态 = 新需求操作状态::结构不一致;
            return 结果;
        }

        auto 安全材料 = 建立根材料(
            新需求根角色::安全, 请求.安全根, *安全类型根);
        if (!安全材料) {
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }
        auto 服务材料 = 建立根材料(
            新需求根角色::服务, 请求.服务根, *服务类型根);
        if (!服务材料) {
            回滚根材料(*安全材料);
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }

        std::vector<稳定编码> 根字段;
        auto 注册 = [&](稳定编码 字段, 稳定编码 目标) {
            const auto 关系 = 全局基础数据集.添加字段节点(需求树根节点, 字段, 目标);
            if (有效(关系)) 根字段.push_back(关系);
            return 有效(关系);
        };
        if (!注册(安全根登记字段, 安全材料->需求)
            || !注册(服务根登记字段, 服务材料->需求)
            || !注册(需求列表项字段, 安全材料->列表项)
            || !注册(需求列表项字段, 服务材料->列表项)) {
            回滚字段(根字段);
            回滚根材料(*服务材料);
            回滚根材料(*安全材料);
            结果.状态 = 新需求操作状态::资源失败;
            return 结果;
        }

        安全根需求节点 = 安全材料->需求;
        服务根需求节点 = 服务材料->需求;
        结果.状态 = 新需求操作状态::已建立;
        结果.安全根 = 安全根需求节点;
        结果.服务根 = 服务根需求节点;
        结果.安全根列表项 = 安全材料->列表项;
        结果.服务根列表项 = 服务材料->列表项;
        return 结果;
    } catch (...) {
        结果.状态 = 新需求操作状态::资源失败;
        return 结果;
    }
}

新需求建立结果 新_需求类::建立或取得普通需求(
    const 新普通需求建立请求& 请求) noexcept {
    新需求建立结果 结果;
    try {
        std::lock_guard 锁(新需求互斥);
        if (!结构仍存在()) {
            结果.状态 = 新需求操作状态::尚未初始化;
            return 结果;
        }
        if (!有效(请求.来源承接节点)) {
            结果.状态 = 新需求操作状态::入口拒绝;
            return 结果;
        }
        if (!读取需求信息(请求.父需求节点)) {
            结果.状态 = 新需求操作状态::父需求不合法;
            return 结果;
        }
        if (!存在服务_.是存在节点(请求.所属存在节点)) {
            结果.状态 = 新需求操作状态::所属存在不合法;
            return 结果;
        }
        if (!存在服务_.是存在节点(请求.目标宿主节点)) {
            结果.状态 = 新需求操作状态::目标宿主不合法;
            return 结果;
        }
        if (!特征概念服务_.是特征概念节点(
                请求.目标.目标特征类型概念节点)) {
            结果.状态 = 新需求操作状态::目标特征类型不合法;
            return 结果;
        }
        if (!特征概念服务_.是特征概念节点(
                请求.目标.目标值域概念节点)) {
            结果.状态 = 新需求操作状态::目标值域不合法;
            return 结果;
        }
        if (!二次特征概念服务_.是二次特征概念(
                请求.目标.目标比较关系概念节点)) {
            结果.状态 = 新需求操作状态::比较关系不合法;
            return 结果;
        }
        const auto 类型根 = 取得特征类型根(
            请求.目标.目标值域概念节点, 特征概念服务_);
        if (!类型根 || *类型根 != 请求.目标.目标特征类型概念节点) {
            结果.状态 = 新需求操作状态::目标值域不合法;
            return 结果;
        }
        const auto 比较关系 = 二次特征概念服务_.获取二次特征概念(
            请求.目标.目标比较关系概念节点);
        if (!比较关系 || !比较关系适用于目标(*比较关系, *类型根,
                请求.目标.目标值域概念节点, 特征概念服务_)) {
            结果.状态 = 新需求操作状态::比较关系不合法;
            return 结果;
        }

        // 待实现：只有新版任务类能证明该节点确为当前父任务发布的正式
        // 子目标承接。基础数据集“节点存在”不足以取得这一业务资格。
        结果.状态 = 新需求操作状态::任务来源未接通;
        return 结果;
    } catch (...) {
        结果.状态 = 新需求操作状态::资源失败;
        return 结果;
    }
}

