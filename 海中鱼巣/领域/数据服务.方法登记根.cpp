std::uint64_t 当前代次(const L1事实基座服务 &服务) {
  const auto 读取 = 服务.读取中性当前事实代次({L1中性CRUD合同版本});
  if (读取.状态 != L1中性读取状态::成功 || !读取.事实代次)
    throw std::runtime_error("L1 current generation unavailable");
  return 读取.事实代次;
}

方法登记根结构状态 映射读取(L1所有者范围读取状态 状态) noexcept {
  switch (状态) {
  case L1所有者范围读取状态::未找到: return 方法登记根结构状态::当前根缺失;
  case L1所有者范围读取状态::已退出: return 方法登记根结构状态::当前根已退出;
  case L1所有者范围读取状态::事实代次漂移: return 方法登记根结构状态::事实代次漂移;
  case L1所有者范围读取状态::资源失败: return 方法登记根结构状态::资源失败;
  default: return 方法登记根结构状态::内部不一致;
  }
}

方法登记根结构状态 映射写入(L1所有者范围写入状态 状态) noexcept {
  switch (状态) {
  case L1所有者范围写入状态::成功: return 方法登记根结构状态::已建立;
  case L1所有者范围写入状态::精确重复: return 方法登记根结构状态::精确重复;
  case L1所有者范围写入状态::事实代次漂移: return 方法登记根结构状态::事实代次漂移;
  case L1所有者范围写入状态::资源失败: return 方法登记根结构状态::资源失败;
  case L1所有者范围写入状态::幂等冲突: return 方法登记根结构状态::首次材料冲突;
  default: return 方法登记根结构状态::内部不一致;
  }
}

bool 是空根(const L1所有者范围节点事实 &节点,
           const L1结构所有者身份 所有者) noexcept {
  return 有效(节点.编码) && 节点.种类 == 节点种类::普通 &&
      !节点.属性类型表示 && 节点.当前属性.empty() &&
      节点.写入所有者 == 所有者 && 节点.创建事实代次 != 0 &&
      !节点.退出事实代次;
}

std::optional<稳定编码> 取得根编码(const L1所有者范围写入结果 &写入) noexcept {
  if (写入.新编码映射.size() != 1) return std::nullopt;
  const auto &[本地键, 编码] = 写入.新编码映射.front();
  if (本地键 != 方法登记根本地键 || !有效(编码)) return std::nullopt;
  return 编码;
}

