bool L2方法登记根初始化结果::成功() const noexcept {
  return (状态 == 方法登记根结构状态::已建立 ||
          状态 == 方法登记根结构状态::精确重复) &&
      请求回显.合同版本 == 1 && 请求回显.最大空域核验事实数 != 0 &&
      Gread != 0 && H != 0 && 根 &&
      有效(根->身份.结点) && 根->创建事实代次 != 0;
}
bool L2方法登记根读取结果::成功() const noexcept {
  return 状态 == 方法登记根结构状态::已读取 && Gread != 0 && 根 &&
      有效(根->身份.结点) && 根->创建事实代次 != 0;
}
bool L2方法登记根全组读取结果::成功() const noexcept {
  return 状态 == 方法登记根结构状态::已读取 && Gread != 0 &&
      根组.size() == 1 && 有效(根组.front().身份.结点) &&
      根组.front().创建事实代次 != 0;
}

L2方法结构服务::L2方法结构服务(const L1事实基座服务 &服务,
    L1所有者范围写端口 &端口) : 第一层服务_(服务), 写入端口_(端口) {
  if (!端口.有效() || !端口.绑定于(服务))
    throw std::invalid_argument("method registry port invalid");
  const auto 所有者 = 服务.读取当前结构所有者(
      {L1所有者范围CRUD合同版本, 端口.所有者身份()});
  if (所有者.状态 != L1所有者范围读取状态::成功 || !所有者.所有者事实 ||
      所有者.所有者事实->范围种类 != L1所有者范围种类::独占结构范围 ||
      所有者.所有者事实->退出事实代次)
    throw std::invalid_argument("method registry owner invalid");
}

bool L2方法结构服务::绑定于(const L1事实基座服务 &服务) const noexcept {
  return &第一层服务_ == &服务 && 写入端口_.有效() && 写入端口_.绑定于(服务);
}

L2方法登记根读取结果 L2方法结构服务::读取当前方法登记根(
    const L2方法登记根读取请求 &请求) const {
  L2方法登记根读取结果 结果;
  if (请求.合同版本 != 1 || 请求.Gread == 0) return 结果;
  try {
    const auto 首次 = 写入端口_.读取首次写入材料(
        {L1所有者范围首次写入读取合同版本, 方法登记根首次写入幂等身份});
    if (首次.状态 == L1所有者范围读取状态::未找到) {
      结果.状态 = 方法登记根结构状态::尚未建立;
      结果.Gread = 首次.读取事实代次;
      return 结果;
    }
    if (首次.状态 != L1所有者范围读取状态::成功 ||
        首次.读取事实代次 != 请求.Gread || !首次.首次规范化写集 ||
        !首次.首次写入结果 ||
        首次.所有者 != 写入端口_.所有者身份() ||
        首次.写入幂等身份 != 方法登记根首次写入幂等身份) {
      结果.状态 = 映射读取(首次.状态);
      结果.Gread = 首次.读取事实代次;
      return 结果;
    }
    const auto &写集 = *首次.首次规范化写集;
    const auto &写入 = *首次.首次写入结果;
    if (写集.合同版本 != L1所有者范围CRUD合同版本 ||
        写集.写入幂等身份 != 方法登记根首次写入幂等身份 ||
        写集.节点.size() != 1 || 写集.节点.front().本地键 != 方法登记根本地键 ||
        写集.节点.front().种类 != 节点种类::普通 ||
        写集.节点.front().属性类型表示 || !写集.关系.empty() ||
        !写集.值.empty() || !写集.属性槽变更.empty() || !写集.退出事实.empty() ||
        !写集.期望事实代次 || 写入.状态 != L1所有者范围写入状态::成功 ||
        写入.所有者 != 写入端口_.所有者身份() ||
        写入.写入幂等身份 != 方法登记根首次写入幂等身份 ||
        !写入.是否形成内存权威发布 ||
        写入.事实代次 != 写集.期望事实代次 + 1) {
      结果.状态 = 方法登记根结构状态::首次材料冲突;
      结果.Gread = 请求.Gread;
      return 结果;
    }
    const auto 编码 = 取得根编码(写入);
    if (!编码) {
      结果.状态 = 方法登记根结构状态::首次材料不完整;
      结果.Gread = 请求.Gread;
      return 结果;
    }
    const auto 节点 = 第一层服务_.读取所有者范围当前节点(
        {L1所有者范围CRUD合同版本, *编码});
    结果.Gread = 节点.读取事实代次;
    if (节点.状态 != L1所有者范围读取状态::成功 || !节点.事实) {
      结果.状态 = 映射读取(节点.状态);
      return 结果;
    }
    const auto *事实 = std::get_if<L1所有者范围节点事实>(&*节点.事实);
    if (!事实 || !是空根(*事实, 写入端口_.所有者身份())) {
      结果.状态 = 方法登记根结构状态::当前根形状错误;
      return 结果;
    }
    if (结果.Gread != 请求.Gread) {
      结果.状态 = 方法登记根结构状态::事实代次漂移;
      return 结果;
    }
    结果.状态 = 方法登记根结构状态::已读取;
    结果.根 = 方法登记根事实{{*编码}, 事实->创建事实代次};
    return 结果;
  } catch (const std::bad_alloc &) {
    结果.状态 = 方法登记根结构状态::资源失败;
  } catch (...) {
    结果.状态 = 方法登记根结构状态::内部不一致;
  }
  return 结果;
}

L2方法登记根全组读取结果 L2方法结构服务::读取全部当前方法登记根(
    const L2方法登记根全组读取请求 &请求) const {
  L2方法登记根全组读取结果 结果;
  if (请求.合同版本 != 1) return 结果;
  try {
    const auto Gread = 请求.Gread ? 请求.Gread : 当前代次(第一层服务_);
    const auto 单根 = 读取当前方法登记根({1, Gread});
    结果.Gread = 单根.Gread;
    if (单根.状态 == 方法登记根结构状态::尚未建立) {
      结果.状态 = 方法登记根结构状态::尚未建立;
      return 结果;
    }
    if (!单根.成功()) { 结果.状态 = 单根.状态; return 结果; }
    结果.状态 = 方法登记根结构状态::已读取;
    结果.根组.push_back(*单根.根);
  } catch (const std::bad_alloc &) {
    结果.状态 = 方法登记根结构状态::资源失败;
  } catch (...) {
    结果.状态 = 方法登记根结构状态::内部不一致;
  }
  return 结果;
}

L2方法登记根初始化结果 L2方法结构服务::建立或读取方法登记根(
    const L2方法登记根初始化请求 &请求) {
  L2方法登记根初始化结果 结果;
  结果.请求回显 = 请求;
  if (请求.合同版本 != 1 || 请求.G0 == 0 ||
      请求.最大空域核验事实数 == 0 ||
      请求.幂等身份 != 方法登记根首次写入幂等身份) return 结果;
  try {
    const auto 当前 = 当前代次(第一层服务_);
    if (当前 != 请求.G0) {
      结果.状态 = 方法登记根结构状态::事实代次漂移;
      结果.Gread = 当前;
      return 结果;
    }
    const auto 已有 = 读取当前方法登记根({1, 当前});
    if (已有.成功()) {
      结果 = {方法登记根结构状态::精确重复, 请求, 当前, 当前, 已有.根};
      return 结果;
    }
    if (已有.状态 != 方法登记根结构状态::尚未建立) {
      结果.状态 = 已有.状态;
      结果.Gread = 已有.Gread;
      return 结果;
    }
    const L1所有者范围空域读取请求 空域请求{
        L1所有者范围空域读取合同版本, 写入端口_.所有者身份(), 当前,
        请求.最大空域核验事实数};
    const auto 空域 = 第一层服务_.读取所有者范围空域(空域请求);
    if (!空域.确认空域(空域请求)) {
      结果.Gread = 空域.读取事实代次;
      if (空域.状态 == L1所有者范围空域读取状态::成功 &&
          空域.空域 && !*空域.空域)
        结果.状态 = 方法登记根结构状态::所有者非空冲突;
      else if (空域.状态 == L1所有者范围空域读取状态::事实代次漂移)
        结果.状态 = 方法登记根结构状态::事实代次漂移;
      else if (空域.状态 == L1所有者范围空域读取状态::数量预算不足)
        结果.状态 = 方法登记根结构状态::数量预算不足;
      else if (空域.状态 == L1所有者范围空域读取状态::资源失败)
        结果.状态 = 方法登记根结构状态::资源失败;
      else 结果.状态 = 方法登记根结构状态::内部不一致;
      return 结果;
    }
    L1所有者范围写集请求 写集{L1所有者范围CRUD合同版本, 当前,
        方法登记根首次写入幂等身份};
    写集.节点.push_back({方法登记根本地键, 节点种类::普通, std::nullopt});
    const auto 写入 = 写入端口_.提交所有者范围中性写集(写集);
    const auto 状态 = 映射写入(写入.状态);
    if (状态 != 方法登记根结构状态::已建立 &&
        状态 != 方法登记根结构状态::精确重复) {
      结果.状态 = 写入.是否形成内存权威发布 ? 方法登记根结构状态::已可能发布 : 状态;
      结果.H = 写入.事实代次;
      结果.Gread = 当前代次(第一层服务_);
      return 结果;
    }
    const auto 读回 = 读取当前方法登记根({1, 写入.事实代次});
    if (!读回.成功()) { 结果.状态 = 读回.状态; 结果.Gread = 读回.Gread; return 结果; }
    const auto 全组 = 读取全部当前方法登记根({1, 写入.事实代次});
    if (!全组.成功() || 全组.根组.front() != *读回.根) {
      结果.状态 = 全组.状态 == 方法登记根结构状态::已读取
          ? 方法登记根结构状态::内部不一致 : 全组.状态;
      结果.Gread = 全组.Gread;
      return 结果;
    }
    结果 = {状态, 请求, 全组.Gread, 写入.事实代次, 读回.根};
  } catch (const std::bad_alloc &) {
    结果.状态 = 方法登记根结构状态::资源失败;
  } catch (...) {
    结果.状态 = 方法登记根结构状态::内部不一致;
  }
  return 结果;
}

