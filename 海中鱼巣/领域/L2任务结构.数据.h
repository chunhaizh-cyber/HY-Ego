inline bool L2任务身份来源事实完整(
    const L2任务身份来源事实& 来源) noexcept {
    return 有效(来源.任务所有者.编码)
        && 有效(来源.任务节点)
        && 有效(来源.任务族锚点)
        && 有效(来源.任务族归属关系类型)
        && 有效(来源.任务族归属关系)
        && 来源.任务节点生命周期.创建事实代次 != 0
        && 来源.族归属关系生命周期.创建事实代次 != 0;
}

