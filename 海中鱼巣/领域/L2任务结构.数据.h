inline bool L2任务当前筹办准备事实完整(
    const L2任务当前筹办准备事实& 事实) noexcept {
    if (!L2任务筹办轮次权威记录事实完整(事实.轮次权威)
        || !L2任务初次筹办准备记录事实完整(事实.首次准备记录)
        || 事实.任务.身份 != 事实.轮次权威.任务
        || 事实.任务.身份 != 事实.首次准备记录.任务
        || 事实.轮次权威.任务虚拟存在 != 事实.首次准备记录.任务虚拟存在
        || 事实.轮次权威.需求列表项 != 事实.首次准备记录.需求列表项
        || 事实.轮次权威.首次准备记录 != 事实.首次准备记录.身份)
        return false;
    if (!事实.当前后继准备记录)
        return 事实.当前筹办轮次 == 1;
    const auto& 后继 = *事实.当前后继准备记录;
    return L2任务后继筹办准备记录事实完整(后继)
        && 后继.轮次权威 == 事实.轮次权威.身份
        && 后继.任务 == 事实.任务.身份
        && 后继.任务虚拟存在 == 事实.轮次权威.任务虚拟存在
        && 后继.需求列表项 == 事实.轮次权威.需求列表项
        && 后继.首次准备记录 == 事实.首次准备记录.身份
        && 事实.当前筹办轮次 == 后继.新筹办轮次;
}

