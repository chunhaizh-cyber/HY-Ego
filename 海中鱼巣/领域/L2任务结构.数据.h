inline bool L2任务执行路径完整有序动作组_v2有效(
    const std::vector<L2任务执行路径动作冻结项_v2>& 组,
    L2方法身份 方法,
    L2方法内容版本 方法内容版本,
    std::uint64_t 事实截止) noexcept {
    if (组.empty() || !有效(方法.值)
        || !L2方法内容版本有效(方法内容版本) || 事实截止 == 0)
        return false;
    for (std::size_t i = 0; i < 组.size(); ++i) {
        const auto& 当前 = 组[i];
        if (!L2任务执行路径动作冻结项_v2有效(当前, 事实截止)
            || 当前.方法 != 方法 || 当前.方法内容版本 != 方法内容版本
            || 当前.顺序 != i + 1U)
            return false;
        for (std::size_t j = i + 1; j < 组.size(); ++j)
            if (当前.动作入口 == 组[j].动作入口
                || 当前.稳定动作键 == 组[j].稳定动作键)
                return false;
    }
    return true;
}

inline bool L2任务执行路径动作组_v2匹配方法正式读回(
    const std::vector<L2任务执行路径动作冻结项_v2>& 冻结组,
    const L2方法完整有序动作组读取结果& 读回) noexcept {
    if (!读回.成功() || 冻结组.size() != 读回.完整有序动作入口组.size())
        return false;
    for (std::size_t i = 0; i < 冻结组.size(); ++i)
        if (!L2任务执行路径动作冻结项_v2匹配来源(
                冻结组[i], 读回.完整有序动作入口组[i]))
            return false;
    return true;
}

