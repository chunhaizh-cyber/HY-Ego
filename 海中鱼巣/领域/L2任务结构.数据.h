inline bool L2任务轮次授权收口引用完整(
    const 任务轮次授权收口引用& 引用) noexcept {
    switch (引用.形态) {
    case 任务轮次授权收口形态::无需授权:
        return !引用.授权 && !引用.收口;
    case 任务轮次授权收口形态::已消费:
    case 任务轮次授权收口形态::已撤回:
    case 任务轮次授权收口形态::已失效:
        return 引用.授权 && 引用.收口
            && 有效(引用.授权->值) && 有效(引用.收口->值);
    default:
        return false;
    }
}

inline bool L2任务轮次结算事实完整(
    const L2任务轮次结算事实& 事实) noexcept {
    if (!有效(事实.身份.值) || !有效(事实.任务.值)
        || !有效(事实.任务轮次.值)
        || (事实.实际结果 && !有效(事实.实际结果->值))
        || !有效(事实.验证归因收口.值)
        || !有效(事实.结果消费分配记录.值)
        || !有效(事实.执行冻结收口.值)
        || !L2任务轮次授权收口引用完整(事实.授权收口)
        || !有效(事实.任务运行停止证据.值)
        || (事实.结论 != 任务轮次结论::目标已达成
            && 事实.结论 != 任务轮次结论::目标未达成
            && 事实.结论 != 任务轮次结论::合法业务失败
            && 事实.结论 != 任务轮次结论::取消)
        || 事实.来源共同事实截止 == 0
        || 事实.结算规则版本 != L2任务轮次结算规则版本
        || 事实.生命周期.创建事实代次 == 0
        || 事实.生命周期.退出事实代次) return false;
    if (事实.需求核算结果组.empty()) return false;
    for (std::size_t i = 0; i < 事实.需求核算结果组.size(); ++i) {
        if (!有效(事实.需求核算结果组[i].值)) return false;
        for (std::size_t j = 0; j < i; ++j)
            if (事实.需求核算结果组[j] == 事实.需求核算结果组[i])
                return false;
    }
    std::uint64_t 前值 = 0;
    std::uint8_t 前分支 = 0;
    for (const auto& 项 : 事实.适用后继结果组) {
        const auto 分支 = static_cast<std::uint8_t>(项.index() + 1U);
        const auto 值 = std::visit([](const auto& 身份) { return 身份.值.值; }, 项);
        if (值 == 0 || (前分支 != 0 && (分支 < 前分支
            || (分支 == 前分支 && 值 <= 前值)))) return false;
        前分支 = 分支; 前值 = 值;
    }
    return true;
}

