    L2结构结果头 结果头;
    std::optional<L2任务治理状态事实> 目标状态;
    std::optional<L2任务治理状态事实> 前驱状态;
    std::optional<L2任务目标裁决证据事实> 目标裁决证据;
    std::optional<L2任务方法路径事实> 旧路径;
    std::optional<L2实例方法事实> 旧实例;
    L2任务筹办轮次分区 轮次分区 = L2任务筹办轮次分区::内部不一致;
    std::optional<L2任务后继筹办准备记录事实> 后继准备记录;
