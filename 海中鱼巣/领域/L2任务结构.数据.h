inline bool L2提交统一轮次推进材料完整(
    const L2提交统一轮次推进材料& 材料) noexcept {
    return 有效(材料.轮次权威.值) && 有效(材料.首次准备记录.值)
        && 材料.期望前一筹办轮次 != 0
        && L2结构幂等身份有效(材料.准备幂等身份)
        && 材料.触发请求身份 != 0 && 材料.运行代次 != 0
        && L2结构幂等身份有效(材料.触发业务幂等身份)
        && 材料.来源共同事实截止 != 0
        && (材料.期望前一筹办轮次 == 1
            ? !材料.期望前一后继准备记录
            : 材料.期望前一后继准备记录
                && 有效(材料.期望前一后继准备记录->值));
}

struct L2提交目标未达成待重筹办迁移请求 final {
    L2结构请求头 请求头;
    L2结构幂等身份 幂等身份;
    L2任务身份 任务;
    L2任务虚拟存在身份 任务虚拟存在;
    std::int64_t 生命周期发生时间 = 0;
    L2任务治理状态身份 前一治理状态;
    L2任务目标裁决证据身份 目标裁决证据;
    L2任务方法路径身份 旧当前路径;
    L2实例方法身份 旧当前实例;
    L2任务筹办轮次分区 轮次分区 = L2任务筹办轮次分区::内部不一致;
    std::optional<L2提交统一轮次推进材料> 统一轮次推进;
    friend bool operator==(const L2提交目标未达成待重筹办迁移请求&,
        const L2提交目标未达成待重筹办迁移请求&) = default;
};

inline bool L2提交目标未达成待重筹办迁移请求有效(
    const L2提交目标未达成待重筹办迁移请求& 请求) noexcept {
    return L2任务结构请求头合同有效(请求.请求头)
        && 请求.请求头.期望事实代次 != 0
        && L2结构幂等身份有效(请求.幂等身份)
        && 有效(请求.任务.值) && 有效(请求.任务虚拟存在.值)
        && 请求.生命周期发生时间 != 0
        && 有效(请求.前一治理状态.值)
        && 有效(请求.目标裁决证据.值)
        && 有效(请求.旧当前路径.值)
        && 有效(请求.旧当前实例.值)
        && ((请求.轮次分区 == L2任务筹办轮次分区::遗留实例轮次
                && !请求.统一轮次推进)
            || (请求.轮次分区 == L2任务筹办轮次分区::统一轮次权威
                && 请求.统一轮次推进
                && L2提交统一轮次推进材料完整(*请求.统一轮次推进)
                && 请求.统一轮次推进->准备幂等身份 == 请求.幂等身份
                && 请求.统一轮次推进->来源共同事实截止
                    == 请求.请求头.期望事实代次));
}

