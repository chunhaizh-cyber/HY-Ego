    std::uint64_t 期望前一筹办轮次 = 0;
    L2结构幂等身份 准备幂等身份;
    std::uint64_t 触发请求身份 = 0;
    std::uint64_t 运行代次 = 0;
    L2结构幂等身份 触发业务幂等身份;
    std::uint64_t 来源共同事实截止 = 0;
