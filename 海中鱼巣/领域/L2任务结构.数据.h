struct L2按任务读取来源需求关系组结果 final {
    L2结构结果头 结果头;
    std::uint32_t 合同版本 = L2按任务读取来源需求关系组合同版本;
    L2任务身份 任务;
    std::vector<L2任务来源需求关系事实> 来源需求关系组;
    std::uint64_t 本次正式读回截止 = 0;

    bool 成功() const noexcept {
        if (结果头.合同版本 != L2结构合同版本
            || 结果头.状态 != L2结构状态::已读取
            || 结果头.事实截止代次 == 0
            || 结果头.变更事实代次
            || 合同版本 != L2按任务读取来源需求关系组合同版本
            || !有效(任务.值)
            || 本次正式读回截止 != 结果头.事实截止代次)
            return false;
        for (std::size_t i = 0; i < 来源需求关系组.size(); ++i) {
            const auto& 当前 = 来源需求关系组[i];
            if (!有效(当前.关系稳定编码) || 当前.任务 != 任务
                || !有效(当前.来源需求.值) || 当前.来源顺序 != 1
                || 当前.生命周期.创建事实代次 == 0
                || 当前.生命周期.创建事实代次 > 结果头.事实截止代次
                || 当前.生命周期.退出事实代次)
                return false;
            if (i != 0) {
                const auto& 前项 = 来源需求关系组[i - 1];
                if (前项.来源需求.值.值 > 当前.来源需求.值.值
                    || (前项.来源需求 == 当前.来源需求
                        && 前项.关系稳定编码.值
                            >= 当前.关系稳定编码.值))
                    return false;
            }
            for (std::size_t j = 0; j < i; ++j)
                if (来源需求关系组[j].关系稳定编码
                    == 当前.关系稳定编码)
                    return false;
        }
        return true;
    }

    friend bool operator==(const L2按任务读取来源需求关系组结果&,
        const L2按任务读取来源需求关系组结果&) = default;
};

