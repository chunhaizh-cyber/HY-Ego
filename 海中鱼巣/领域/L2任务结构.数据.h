inline bool L2任务目标裁决结构材料完整(
    const L2任务目标裁决结构材料& 材料) noexcept {
    const bool 关系有效 = 材料.具名关系 ==
            L2特征比较具名关系::当前低于目标
        || 材料.具名关系 == L2特征比较具名关系::当前达到目标
        || 材料.具名关系 == L2特征比较具名关系::当前高于目标;
    const bool 组合有效 =
        (材料.目标达成状态 == L2任务目标达成状态::已达成
            && 材料.后继准备 ==
                L2任务目标裁决后继准备::待验证后完成)
        || (材料.目标达成状态 == L2任务目标达成状态::未达成
            && 材料.后继准备 ==
                L2任务目标裁决后继准备::目标未达成待重筹办);
    return 材料.治理输入幂等键 != 0 && 有效(材料.任务.值)
        && 有效(材料.实例方法.值) && 材料.执行轮次 != 0
        && 有效(材料.任务实际结果.值)
        && 有效(材料.任务目标来源.值) && 有效(材料.目标宿主.值)
        && 有效(材料.目标特征.值) && 有效(材料.目标状态合同.值)
        && 有效(材料.实际状态.值) && 有效(材料.动态证据.值)
        && 有效(材料.方法.值) && 有效(材料.路径预期结果)
        && 有效(材料.路径验证合同) && 有效(材料.比较注册.值)
        && 材料.比较算法版本 != 0 && 关系有效
        && 材料.允许关系位 >= 1 && 材料.允许关系位 <= 7
        && 组合有效
        && 材料.来源共同事实截止 != 0;
}

