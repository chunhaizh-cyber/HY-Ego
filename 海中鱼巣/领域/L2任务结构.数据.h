inline bool L2任务初次筹办首次需求裁决材料完整(
    const L2任务初次筹办首次需求裁决材料& 材料) noexcept {
    const auto G0 = 材料.首次共同事实截止G0;
    const auto 关系位 = L2任务目标判断关系位(材料.具名关系);
    return 材料.裁决规则版本 != 0
        && 材料.裁决请求身份 != 0 && G0 != 0
        && L2需求事实完整(材料.需求事实, G0)
        && !材料.需求事实.生命周期.退出事实代次
        && L2需求列表成员关系事实截止投影完整(
            材料.当前成员关系, G0)
        && !材料.当前成员关系.生命周期.退出事实代次
        && L2需求列表项事实完整(材料.所属列表项, G0)
        && !材料.所属列表项.生命周期.退出事实代次
        && L2特征实例事实完整(材料.当前特征实例, G0)
        && !材料.当前特征实例.生命周期.退出事实代次
        && 材料.当前特征实例.当前值
        && L2任务初次筹办特征值事实相同(
            *材料.当前特征实例.当前值, 材料.当前特征值)
        && L2特征值事实截止投影完整(材料.当前特征值, G0)
        && !材料.当前特征值.生命周期.退出事实代次
        && L2目标状态合同事实完整(材料.目标合同, G0)
        && !材料.目标合同.生命周期.退出事实代次
        && 有效(材料.比较注册.值)
        && 材料.比较算法版本 != 0 && 关系位
        && 材料.当前成员关系.需求 == 材料.需求事实.身份
        && 材料.当前成员关系.列表项 == 材料.所属列表项.身份
        && 材料.当前特征实例.宿主存在
            == 材料.需求事实.目标宿主存在
        && 材料.当前特征实例.特征定义
            == 材料.需求事实.目标特征定义
        && 材料.当前特征值.特征实例
            == 材料.当前特征实例.身份
        && 材料.目标合同.身份 == 材料.需求事实.目标状态合同
        && 材料.目标合同.特征定义
            == 材料.需求事实.目标特征定义
        && 材料.目标合同.比较注册 == 材料.比较注册
        && 材料.目标合同.允许关系位 == 材料.允许关系位
        && (材料.允许关系位 & *关系位) == 0;
}

