inline bool L2任务治理状态事实完整(
    const L2任务治理状态事实& 事实) noexcept {
    const bool 公共完整 = 有效(事实.身份.值) && 有效(事实.任务.值)
        && 有效(事实.任务虚拟存在.值) && 有效(事实.运行场景.值)
        && 事实.生命周期发生时间 != 0 && 事实.生命周期版本 != 0
        && 事实.方法运行当前性 == L2任务方法运行当前性::已结束
        && 事实.执行结果类型 == L2任务执行结果类型::产生可比较结果
        && 事实.本轮推进状态 == L2任务本轮推进状态::未裁决
        && 事实.验证裁决状态 == L2任务验证裁决状态::未验证
        && 事实.结果当前性 == L2任务结果当前性::当前
        && 有效(事实.来源方法路径.值) && 有效(事实.来源实例方法.值)
        && 事实.来源执行轮次 != 0 && 有效(事实.来源任务实际结果.值)
        && 有效(事实.目标裁决证据.值)
        && 事实.来源共同事实截止 != 0
        && 事实.生命周期.创建事实代次 != 0;
    if (!公共完整) return false;
    if (事实.业务状态段 == L2任务业务状态段::执行结果待验证)
        return 事实.生命周期版本 == 1 && !事实.前一治理状态
            && 事实.重新触发状态 == L2任务重新触发状态::未触发
            && 事实.执行冻结当前性 == L2任务执行冻结当前性::当前;
    return 事实.业务状态段 ==
            L2任务业务状态段::目标未达成待重筹办
        && 事实.生命周期版本 > 1 && 事实.前一治理状态
        && 有效(事实.前一治理状态->值)
        && 事实.重新触发状态 == L2任务重新触发状态::已触发
        && 事实.执行冻结当前性 == L2任务执行冻结当前性::已失效
        && 事实.目标达成状态 == L2任务目标达成状态::未达成;
}

