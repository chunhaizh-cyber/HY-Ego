inline std::optional<稳定编码> 查找唯一编码(const L1所有者范围写入结果& 结果,
    L1所有者范围写集本地键 本地键) noexcept {
    std::optional<稳定编码> 找到;
    for (const auto& [键, 编码] : 结果.新编码映射) {
        if (键 != 本地键) continue;
        if (找到 || !有效(编码)) return std::nullopt;
        找到 = 编码;
    }
    return 找到;
}

