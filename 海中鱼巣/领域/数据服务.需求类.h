    bool 根写入头完整(const L1所有者范围写入结果& 写入,
        L1所有者范围写入幂等身份 身份) const noexcept {
        const bool 首次 = 写入.状态 == L1所有者范围写入状态::成功
            && 写入.是否形成内存权威发布
            && 写入.重试边界 == L1所有者范围重试边界::不适用;
        const bool 重放 = 写入.状态 == L1所有者范围写入状态::精确重复
            && !写入.是否形成内存权威发布
            && 写入.重试边界 == L1所有者范围重试边界::原幂等身份读回收敛;
        return 写入.合同版本 == L1所有者范围CRUD合同版本 && 写入.所有者 == 所有者_
            && 写入.写入幂等身份 == 身份 && 写入.事实代次 != 0 && (首次 || 重放);
    }

