#include "合同.世界树根.h"

namespace 海中鱼巣 {

bool 世界树根组读取结果::成功(const 世界树根组读取请求 &请求) const noexcept {
  return 请求.版本 == 世界树根合同版本 &&
         状态 == 世界树根状态::精确重复 &&
         根组.size() <= 请求.最大关系数量;
}

bool 世界树根初始化结果::成功(const 世界树根初始化请求 &请求) const noexcept {
  if (请求.版本 != 世界树根合同版本 || 版本 != 世界树根合同版本 ||
      (状态 != 世界树根状态::已建立 && 状态 != 世界树根状态::精确重复) ||
      !原请求 || *原请求 != 请求 || !事实 || !有效(事实->根) ||
      事实->根 != 事实->根场景.场景角色.场景 || 事实->根场景.直接父 ||
      事实->根场景.树证明.种类 != 场景树证明种类::根标记 ||
      事实->根场景.树证明.场景 != 事实->根 ||
      事实->根场景.树证明.树根 != 事实->根 ||
      !事实->根场景.从上游场景到本场景路径.empty() ||
      事实->根场景.父语境投影)
    return false;
  return 事实->根场景.场景角色.四根.size() == 4;
}

} // namespace 海中鱼巣
