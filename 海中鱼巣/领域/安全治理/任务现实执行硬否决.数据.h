#pragma once

#ifndef TASK_REALITY_EXECUTION_HARD_DENIAL_NO_INCLUDES
#include <cstdint>
#include <optional>
#include <vector>
#include "../L2任务结构.数据.h"
#include "L2任务现实执行硬否决规则结构.数据.h"
#endif

namespace 海中鱼巣 {

inline constexpr std::uint32_t 任务现实执行硬否决合同版本 = 2;

enum class 任务现实执行硬否决复核阶段 : std::uint8_t {
    无效 = 0,
    授权前预检 = 1,
    动作前最终复核 = 2
};

enum class 任务现实影响分类 : std::uint8_t {
    无效 = 0,
    零现实改变 = 1,
    含现实改变 = 2
};

enum class 任务现实执行硬否决状态 : std::uint8_t {
    不适用 = 1,
    未命中 = 2,
    已命中 = 3,
    材料不足 = 4,
    当前性漂移 = 5,
    资源失败 = 6,
    内部错误 = 7
};

struct 任务现实执行硬否决作用范围证据 final {
    L2任务执行冻结身份 冻结;
    std::uint64_t 冻结版本 = 0;
    std::uint64_t 动作总数 = 0;
    std::uint64_t 内部治理动作数 = 0;
    std::uint64_t 纯观察动作数 = 0;
    std::uint64_t 现实改变动作数 = 0;
    std::uint64_t 作用范围正式读回截止 = 0;
    friend bool operator==(const 任务现实执行硬否决作用范围证据&,
        const 任务现实执行硬否决作用范围证据&) = default;
};

struct 任务现实执行硬否决安全读回见证 final {
    L2任务现实执行硬否决规则宇宙身份 规则宇宙;
    std::uint64_t 硬否决规则版本 = 0;
    std::uint64_t 成员集合版本 = 0;
    std::vector<L2任务现实执行硬否决规则事实身份> 适用规则事实身份组;
    L2任务现实执行硬否决规则完整集合见证_v2 完整集合见证;
    std::uint64_t 安全事实正式读回截止 = 0;
    friend bool operator==(const 任务现实执行硬否决安全读回见证&,
        const 任务现实执行硬否决安全读回见证&) = default;
};

struct 任务现实执行硬否决请求 final {
    std::uint32_t 合同版本 = 任务现实执行硬否决合同版本;
    任务现实执行硬否决复核阶段 复核阶段 = 任务现实执行硬否决复核阶段::无效;
    L2存在身份 自我;
    L2任务身份 任务;
    L2任务轮次身份 任务轮次;
    L2任务筹办轮次权威记录身份 筹办轮次;
    L2任务执行轮次身份 执行轮次;
    L2任务执行冻结身份 冻结;
    std::uint64_t 冻结版本 = 0;
    L2实例方法身份 实例方法;
    L2方法身份 方法;
    稳定编码 方法内容版本;
    std::vector<任务冻结动作项> 完整有序冻结动作范围;
    任务现实影响分类 现实影响 = 任务现实影响分类::无效;
    L2任务现实执行硬否决规则全集读取结果_v2 正式规则全集;
    std::uint64_t 来源共同事实截止 = 0;
    friend bool operator==(const 任务现实执行硬否决请求&,
        const 任务现实执行硬否决请求&) = default;
};

struct 任务现实执行硬否决结果 final {
    任务现实执行硬否决状态 状态 = 任务现实执行硬否决状态::内部错误;
    任务现实执行硬否决复核阶段 复核阶段 = 任务现实执行硬否决复核阶段::无效;
    任务现实影响分类 现实影响 = 任务现实影响分类::无效;
    std::optional<任务现实执行硬否决作用范围证据> 作用范围证据;
    std::optional<任务现实执行硬否决安全读回见证> 安全读回见证;
    std::vector<L2任务现实执行硬否决规则事实身份> 命中证据;
    std::uint64_t 本次裁决截止 = 0;

    bool 结果形状有效() const noexcept {
        if (复核阶段 != 任务现实执行硬否决复核阶段::授权前预检
            && 复核阶段 != 任务现实执行硬否决复核阶段::动作前最终复核)
            return false;
        if (状态 == 任务现实执行硬否决状态::不适用) {
            return 现实影响 == 任务现实影响分类::零现实改变
                && 作用范围证据 && 作用范围证据->现实改变动作数 == 0
                && 作用范围证据->作用范围正式读回截止 != 0
                && !安全读回见证 && 命中证据.empty()
                && 本次裁决截止 == 作用范围证据->作用范围正式读回截止;
        }
        if (状态 == 任务现实执行硬否决状态::未命中) {
            return 现实影响 == 任务现实影响分类::含现实改变
                && 作用范围证据 && 作用范围证据->现实改变动作数 != 0
                && 安全读回见证 && 命中证据.empty()
                && 本次裁决截止 != 0
                && 本次裁决截止 == 作用范围证据->作用范围正式读回截止
                && 本次裁决截止 == 安全读回见证->安全事实正式读回截止;
        }
        if (状态 == 任务现实执行硬否决状态::已命中) {
            return 现实影响 == 任务现实影响分类::含现实改变
                && 作用范围证据 && 安全读回见证 && !命中证据.empty()
                && 本次裁决截止 != 0
                && 本次裁决截止 == 作用范围证据->作用范围正式读回截止
                && 本次裁决截止 == 安全读回见证->安全事实正式读回截止;
        }
        return !作用范围证据 && !安全读回见证
            && 命中证据.empty() && 本次裁决截止 == 0;
    }

    bool 允许继续() const noexcept {
        return 结果形状有效()
            && (状态 == 任务现实执行硬否决状态::不适用
                || 状态 == 任务现实执行硬否决状态::未命中);
    }

    friend bool operator==(const 任务现实执行硬否决结果&,
        const 任务现实执行硬否决结果&) = default;
};

} // namespace 海中鱼巣
