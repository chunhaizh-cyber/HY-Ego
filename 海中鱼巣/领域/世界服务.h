// 文件规则：世界服务只做世界树初始化所需的最小聚合编排；不直接写其它领域原子结构。
#pragma once

#include "../核心/节点仓库.h"
#include "../核心/主信息仓库.h"
#include "存在服务.h"
#include "场景服务.h"

namespace 海中鱼巣 {

class 世界服务 {
public:
    世界服务(主信息仓库& 主信息, 节点仓库& 节点, 存在服务& 存在, 场景服务& 场景)
        : 主信息_(主信息), 节点_(节点), 存在_(存在), 场景_(场景) {
    }

    节点句柄 创建基础信息() {
        const auto 主信息句柄 = 主信息_.创建主信息();
        const auto 基础信息 = 节点_.创建节点(节点类型::基础信息, 主信息句柄);
        const auto 记录 = 节点_.读取节点(基础信息);
        if (!记录.has_value() || 记录->类型 != 节点类型::基础信息
            || !主信息_.主信息是否有效(记录->主信息)) {
            return {};
        }
        return 基础信息;
    }

    节点句柄 创建存在() {
        return 存在_.创建实际存在();
    }

    节点句柄 创建场景() {
        return 场景_.创建场景();
    }

    关系句柄 接纳存在(节点句柄 场景, 节点句柄 存在) {
        return 场景_.接纳存在(场景, 存在);
    }

private:
    主信息仓库& 主信息_;
    节点仓库& 节点_;
    存在服务& 存在_;
    场景服务& 场景_;
};

}
