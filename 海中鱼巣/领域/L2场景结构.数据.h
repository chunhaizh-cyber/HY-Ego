// 诊断责任：无适用错误分支；整树值式投影须单根、单父、连通、无环且稳定有序。
inline bool L2场景树事实完整(const L2场景树事实& 树) noexcept {
    const auto 截止 = 树.事实截止代次;
    if (截止 == 0 || !有效(树.树.值) || 树.树.值 != 树.根场景.值
        || !L2场景树结构登记完整(树.结构登记)
        || 树.结构登记.事实截止代次 != 截止
        || !L2场景树归属事实完整(树.根标记, 截止)
        || 树.根标记.类别 != L2场景树归属类别::根
        || 树.根标记.树 != 树.树 || 树.根标记.场景 != 树.根场景
        || 树.根标记.物理目标稳定编码
            != 树.结构登记.树登记锚点稳定编码
        || 树.场景组.empty() || 树.父子关系组.size() + 1 != 树.场景组.size())
        return false;
    std::size_t 根数量 = 0;
    for (std::size_t 索引 = 0; 索引 < 树.场景组.size(); ++索引) {
        const auto& 节点 = 树.场景组[索引];
        if (!L2场景树节点事实完整(节点, 截止)
            || 节点.树归属.树 != 树.树
            || (索引 != 0 && !(树.场景组[索引 - 1].场景.身份.值
                < 节点.场景.身份.值))) return false;
        if (节点.场景.身份 == 树.根场景) {
            ++根数量;
            if (节点.树归属 != 树.根标记) return false;
        } else if (节点.树归属.类别 != L2场景树归属类别::非根) return false;
    }
    if (根数量 != 1) return false;
    for (std::size_t 索引 = 0; 索引 < 树.父子关系组.size(); ++索引) {
        const auto& 关系 = 树.父子关系组[索引];
        if (!L2场景父子关系事实截止投影完整(关系, 截止)
            || 关系.生命周期.退出事实代次
            || (索引 != 0 && !(树.父子关系组[索引 - 1].关系稳定编码
                < 关系.关系稳定编码))) return false;
        bool 父在树内 = false, 子在树内 = false;
        for (const auto& 节点 : 树.场景组) {
            父在树内 = 父在树内 || 节点.场景.身份 == 关系.父场景;
            子在树内 = 子在树内 || 节点.场景.身份 == 关系.子场景;
        }
        if (!父在树内 || !子在树内 || 关系.子场景 == 树.根场景) return false;
    }
    for (const auto& 节点 : 树.场景组) {
        std::size_t 入边数量 = 0;
        for (const auto& 关系 : 树.父子关系组)
            if (关系.子场景 == 节点.场景.身份) ++入边数量;
        if (入边数量 != (节点.场景.身份 == 树.根场景 ? 0U : 1U)) return false;
    }
    std::vector<bool> 已到达(树.场景组.size(), false);
    for (std::size_t 索引 = 0; 索引 < 树.场景组.size(); ++索引)
        if (树.场景组[索引].场景.身份 == 树.根场景) 已到达[索引] = true;
    for (std::size_t 轮次 = 1; 轮次 < 树.场景组.size(); ++轮次)
        for (const auto& 关系 : 树.父子关系组) {
            bool 父已到达 = false;
            for (std::size_t 索引 = 0; 索引 < 树.场景组.size(); ++索引)
                if (树.场景组[索引].场景.身份 == 关系.父场景)
                    父已到达 = 已到达[索引];
            if (父已到达)
                for (std::size_t 索引 = 0; 索引 < 树.场景组.size(); ++索引)
                    if (树.场景组[索引].场景.身份 == 关系.子场景)
                        已到达[索引] = true;
        }
    for (const auto 到达 : 已到达) if (!到达) return false;
    return true;
}

