inline bool L2场景退出请求有效(const L2场景退出请求& 请求) noexcept {
    if (!L2结构请求头合同有效(请求.请求头)
        || 请求.请求头.期望事实代次 == 0
        || !L2结构幂等身份有效(请求.幂等身份)
        || !有效(请求.场景.值)
        || !有效(请求.族归属关系稳定编码)
        || (请求.当前树归属关系 && !有效(*请求.当前树归属关系))
        || (请求.当前直接父关系 && !有效(*请求.当前直接父关系))
        || (请求.当前宿主关系 && !有效(*请求.当前宿主关系))) return false;
    const auto 检查组 = [](const std::vector<稳定编码>& 组) noexcept {
        for (std::size_t 索引 = 0; 索引 < 组.size(); ++索引) {
            if (!有效(组[索引]) || (索引 != 0 && !(组[索引 - 1] < 组[索引])))
                return false;
        }
        return true;
    };
    if (!检查组(请求.当前直接子关系)
        || !检查组(请求.当前直接成员关系)
        || !检查组(请求.当前固定属性值)) return false;
    const auto 与组重复 = [](稳定编码 编码,
        const std::vector<稳定编码>& 组) noexcept {
        for (const auto 项 : 组) if (项 == 编码) return true;
        return false;
    };
    if (请求.当前树归属关系
        && (与组重复(*请求.当前树归属关系, 请求.当前直接子关系)
            || 与组重复(*请求.当前树归属关系, 请求.当前直接成员关系)
            || 与组重复(*请求.当前树归属关系, 请求.当前固定属性值))) return false;
    if (请求.当前直接父关系
        && (与组重复(*请求.当前直接父关系, 请求.当前直接子关系)
            || 与组重复(*请求.当前直接父关系, 请求.当前直接成员关系)
            || 与组重复(*请求.当前直接父关系, 请求.当前固定属性值))) return false;
    if ((请求.当前树归属关系
            && *请求.当前树归属关系 == 请求.族归属关系稳定编码)
        || (请求.当前直接父关系
            && *请求.当前直接父关系 == 请求.族归属关系稳定编码)
        || (请求.当前树归属关系 && 请求.当前直接父关系
            && *请求.当前树归属关系 == *请求.当前直接父关系)
        || 与组重复(请求.族归属关系稳定编码, 请求.当前直接子关系)
        || 与组重复(请求.族归属关系稳定编码, 请求.当前直接成员关系)
        || 与组重复(请求.族归属关系稳定编码, 请求.当前固定属性值)
        || (请求.当前宿主关系
            && (*请求.当前宿主关系 == 请求.族归属关系稳定编码
                || (请求.当前树归属关系
                    && *请求.当前宿主关系 == *请求.当前树归属关系)
                || (请求.当前直接父关系
                    && *请求.当前宿主关系 == *请求.当前直接父关系)
                || 与组重复(*请求.当前宿主关系, 请求.当前直接子关系)
                || 与组重复(*请求.当前宿主关系, 请求.当前直接成员关系)
                || 与组重复(*请求.当前宿主关系, 请求.当前固定属性值))))
        return false;
    const auto 两组重复 = [](const std::vector<稳定编码>& 左组,
        const std::vector<稳定编码>& 右组) noexcept {
        for (const auto 左 : 左组)
            for (const auto 右 : 右组)
                if (左 == 右) return true;
        return false;
    };
    return !两组重复(请求.当前直接子关系, 请求.当前直接成员关系)
        && !两组重复(请求.当前直接子关系, 请求.当前固定属性值)
        && !两组重复(请求.当前直接成员关系, 请求.当前固定属性值);
}

