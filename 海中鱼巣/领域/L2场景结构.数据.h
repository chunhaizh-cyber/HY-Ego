// 诊断责任：无适用错误分支；只判断可无损映射到 L1 有符号顺序的范围。
inline bool L2场景关系顺序有效(std::uint64_t 顺序) noexcept {
    return 顺序 != 0
        && 顺序 <= static_cast<std::uint64_t>(
            std::numeric_limits<std::int64_t>::max());
}

// 诊断责任：无适用错误分支；固定属性类型登记只接受唯一规则与幂等身份。
inline bool L2场景属性类型登记请求有效(
    const L2场景属性类型登记请求& 请求) noexcept {
    return L2结构请求头合同有效(请求.请求头)
        && 请求.规则版本 == L2场景属性类型登记规则版本
        && 请求.幂等身份 == L2结构幂等身份{1};
}

// 诊断责任：无适用错误分支；四种场景属性类型必须唯一且来自同次登记。
inline bool L2场景属性类型登记完整(
    const L2场景属性类型登记& 登记) noexcept {
    const auto 有符号64位 = 登记.I64属性类型.值;
    const auto 有符号64位组 = 登记.I64组属性类型.值;
    const auto 无符号64位组 = 登记.U64组属性类型.值;
    const auto 独立材料 = 登记.独立材料属性类型.值;
    return 登记.合同版本 == L2结构合同版本
        && 登记.规则版本 == L2场景属性类型登记规则版本
        && 登记.首次幂等身份 == L2结构幂等身份{1}
        && 登记.建立事实代次 != 0
        && 登记.首次期望事实代次 < 登记.建立事实代次
        && 登记.事实截止代次 >= 登记.建立事实代次
        && 有效(有符号64位) && 有效(有符号64位组)
        && 有效(无符号64位组) && 有效(独立材料)
        && 有符号64位 != 有符号64位组 && 有符号64位 != 无符号64位组
        && 有符号64位 != 独立材料 && 有符号64位组 != 无符号64位组
        && 有符号64位组 != 独立材料 && 无符号64位组 != 独立材料;
}

// 诊断责任：无适用错误分支；只判断属性类型登记成功状态与完整载荷。
inline bool L2场景属性类型登记结果::成功() const noexcept {
    return (状态 == L2场景属性类型登记状态::已提交
            || 状态 == L2场景属性类型登记状态::精确重复
            || 状态 == L2场景属性类型登记状态::已读取)
        && 登记 && 事实截止代次 == 登记->事实截止代次
        && L2场景属性类型登记完整(*登记);
}

// 诊断责任：无适用错误分支；来源请求的类别与截止必须闭合。
inline bool L2场景身份来源读取请求有效(
    const L2场景身份来源读取请求& 请求) noexcept {
    if (!L2结构请求头合同有效(请求.请求头)
        || 请求.请求头.期望事实代次 == 0 || !有效(请求.场景.值)) return false;
    if (请求.读取类别 == L2读取类别::当前)
        return 请求.历史截止事实代次 == 0;
    return 请求.读取类别 == L2读取类别::历史
        && 请求.历史截止事实代次 != 0
        && 请求.历史截止事实代次 <= 请求.请求头.期望事实代次;
}

// 诊断责任：无适用错误分支；场景来源成功必须闭合场景族、类别和截止。
inline bool L2场景身份来源读取结果::成功() const noexcept {
    return 结果头.状态 == L2结构状态::已读取
        && 结果头.事实截止代次 != 0 && !结果头.变更事实代次
        && 身份来源 && 身份来源->节点族 == L2节点族::场景
        && L2节点族身份来源事实完整(*身份来源, 结果头.事实截止代次)
        && (读取类别 == L2读取类别::当前
            ? 历史截止事实代次 == 0
            : 读取类别 == L2读取类别::历史
                && 历史截止事实代次 == 结果头.事实截止代次);
}

