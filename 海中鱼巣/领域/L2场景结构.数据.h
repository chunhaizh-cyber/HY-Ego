// 诊断责任：无适用错误分支；只判断最终场景完整值式投影及稳定顺序。
inline bool L2场景事实完整(
    const L2场景事实& 场景, std::uint64_t 截止) noexcept {
    if (截止 == 0 || !有效(场景.身份.值) || !L2生命周期完整(场景.生命周期)
        || 场景.生命周期.创建事实代次 > 截止
        || (场景.生命周期.退出事实代次
            && *场景.生命周期.退出事实代次 > 截止)) return false;
    for (std::size_t 索引 = 0; 索引 < 场景.固定属性.size(); ++索引) {
        const auto& 属性 = 场景.固定属性[索引];
        if (!L2属性事实截止投影完整(属性, 截止) || 属性.退出事实代次)
            return false;
        if (索引 != 0) {
            const auto& 前项 = 场景.固定属性[索引 - 1];
            if (!(前项.属性类型身份 < 属性.属性类型身份)) return false;
        }
    }
    for (std::size_t 索引 = 0; 索引 < 场景.直接子场景.size(); ++索引) {
        const auto& 关系 = 场景.直接子场景[索引];
        if (!L2场景父子关系事实截止投影完整(关系, 截止)
            || 关系.父场景 != 场景.身份 || 关系.生命周期.退出事实代次)
            return false;
        if (索引 != 0) {
            const auto& 前项 = 场景.直接子场景[索引 - 1];
            if (前项.顺序 > 关系.顺序
                || (前项.顺序 == 关系.顺序
                    && !(前项.子场景.值 < 关系.子场景.值))) return false;
        }
    }
    for (std::size_t 索引 = 0; 索引 < 场景.直接成员.size(); ++索引) {
        const auto& 关系 = 场景.直接成员[索引];
        if (!L2场景成员关系事实截止投影完整(关系, 截止)
            || 关系.场景 != 场景.身份 || 关系.生命周期.退出事实代次)
            return false;
        if (索引 != 0) {
            const auto& 前项 = 场景.直接成员[索引 - 1];
            if (前项.顺序 > 关系.顺序
                || (前项.顺序 == 关系.顺序
                    && !(前项.存在.值 < 关系.存在.值))) return false;
        }
    }
    if (场景.当前宿主关系
        && (!L2场景宿主存在关系事实截止投影完整(
                *场景.当前宿主关系, 截止)
            || 场景.当前宿主关系->场景 != 场景.身份
            || 场景.当前宿主关系->生命周期.退出事实代次)) return false;
    return true;
}

