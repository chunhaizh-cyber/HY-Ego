新_场景类::新_场景类(新_存在类& 存在服务) noexcept
    : 存在服务_(存在服务) {}

bool 新_场景类::初始化() noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        if (!存在服务_.初始化()) return false;
        if (结构已初始化()) return 结构仍存在();
        auto 建立 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        return 建立(场景身份字段)
            && 建立(场景节点类型)
            && 建立(成员存在字段);
    } catch (...) {
        return false;
    }
}

新场景建立结果 新_场景类::建立根场景() noexcept {
    新场景建立结果 结果;
    try {
        std::lock_guard 锁(新场景互斥);
        if (!结构仍存在()) return 结果;
        if (有效(场景树根节点)) {
            const auto 信息 = 获取场景(场景树根节点);
            if (!信息 || 信息->父场景节点) {
                结果.状态 = 新场景操作状态::结构不一致;
                return 结果;
            }
            结果.状态 = 新场景操作状态::无变化;
            结果.场景节点 = 信息->节点;
            结果.专属存在概念节点 = 信息->专属存在概念节点;
            return 结果;
        }

        const auto 节点 = 全局基础数据集.新建节点();
        if (!有效(节点)) {
            结果.状态 = 新场景操作状态::资源失败;
            return 结果;
        }
        const auto 场景字段 = 全局基础数据集.添加字段节点(
            节点, 场景身份字段, 场景节点类型);
        if (!有效(场景字段)) {
            (void)全局基础数据集.删除节点(节点);
            结果.状态 = 新场景操作状态::资源失败;
            return 结果;
        }
        const auto 存在结果 = 存在服务_.初始化存在节点(
            节点, 新存在建立请求{}, true);
        if (存在结果.状态 != 新存在操作状态::已完成
            || !存在结果.专属存在概念节点) {
            (void)全局基础数据集.删除字段(场景字段);
            (void)全局基础数据集.删除节点(节点);
            结果.状态 = 映射存在失败(存在结果.状态);
            return 结果;
        }
        场景树根节点 = 节点;
        结果.状态 = 新场景操作状态::已完成;
        结果.场景节点 = 节点;
        结果.专属存在概念节点 = 存在结果.专属存在概念节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新场景操作状态::资源失败;
        return 结果;
    }
}

新场景建立结果 新_场景类::建立场景(
    稳定编码 父场景节点) noexcept {
    新场景建立结果 结果;
    try {
        std::lock_guard 锁(新场景互斥);
        if (!是场景节点(父场景节点)) {
            结果.状态 = 新场景操作状态::父场景不合法;
            return 结果;
        }
        const auto 节点 = 全局基础数据集.新建节点();
        if (!有效(节点)) {
            结果.状态 = 新场景操作状态::资源失败;
            return 结果;
        }
        const auto 场景字段 = 全局基础数据集.添加字段节点(
            节点, 场景身份字段, 场景节点类型);
        const auto 父子关系 = 有效(场景字段)
            ? 全局基础数据集.添加关系(
                父场景节点, 节点, 基础外部关系类型::父子,
                场景组成子场景关系角色)
            : 稳定编码{};
        if (!有效(父子关系)) {
            if (有效(场景字段)) (void)全局基础数据集.删除字段(场景字段);
            (void)全局基础数据集.删除节点(节点);
            结果.状态 = 新场景操作状态::资源失败;
            return 结果;
        }
        const auto 存在结果 = 存在服务_.初始化存在节点(
            节点, 新存在建立请求{}, true);
        if (存在结果.状态 != 新存在操作状态::已完成
            || !存在结果.专属存在概念节点) {
            (void)全局基础数据集.删除关系(父子关系);
            (void)全局基础数据集.删除字段(场景字段);
            (void)全局基础数据集.删除节点(节点);
            结果.状态 = 映射存在失败(存在结果.状态);
            return 结果;
        }
        结果.状态 = 新场景操作状态::已完成;
        结果.场景节点 = 节点;
        结果.专属存在概念节点 = 存在结果.专属存在概念节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新场景操作状态::资源失败;
        return 结果;
    }
}

新场景操作状态 新_场景类::迁移子场景(
    稳定编码 场景节点,
    稳定编码 新父场景节点) noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        if (!是场景节点(场景节点)) {
            return 新场景操作状态::场景不存在;
        }
        if (!是场景节点(新父场景节点)) {
            return 新场景操作状态::父场景不合法;
        }
        if (场景节点 == 场景树根节点) {
            return 新场景操作状态::根场景不可操作;
        }
        if (场景节点 == 新父场景节点
            || 子场景向下可达(场景节点, 新父场景节点)) {
            return 新场景操作状态::会形成环;
        }
        const auto 原父关系 = 查询父场景关系(场景节点);
        if (原父关系.size() != 1
            || !是场景节点(原父关系.front().源节点)) {
            return 新场景操作状态::结构不一致;
        }
        if (原父关系.front().源节点 == 新父场景节点) {
            return 新场景操作状态::无变化;
        }
        return 全局基础数据集.修改关系(
            原父关系.front().编码,
            新父场景节点,
            场景节点,
            基础外部关系类型::父子,
            场景组成子场景关系角色)
            ? 新场景操作状态::已完成
            : 新场景操作状态::资源失败;
    } catch (...) {
        return 新场景操作状态::资源失败;
    }
}

新场景操作状态 新_场景类::删除空场景(
    稳定编码 场景节点) noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        if (!是场景节点(场景节点)) {
            return 新场景操作状态::场景不存在;
        }
        if (场景节点 == 场景树根节点) {
            return 新场景操作状态::根场景不可操作;
        }
        const auto 子场景关系组 = 查询子场景关系(场景节点);
        const auto 成员字段组 = 全局基础数据集.查询字段(
            场景节点, 成员存在字段);
        if (!子场景关系组.empty() || !成员字段组.empty()) {
            return 新场景操作状态::场景非空;
        }
        const auto 父关系 = 查询父场景关系(场景节点);
        const auto 场景字段组 = 全局基础数据集.查询字段(
            场景节点, 场景身份字段);
        if (父关系.size() != 1
            || !是场景节点(父关系.front().源节点)
            || 场景字段组.size() != 1) {
            return 新场景操作状态::结构不一致;
        }
        const auto 清理状态 = 存在服务_.清理存在节点内容(场景节点);
        if (清理状态 != 新存在操作状态::已完成) {
            return 映射存在失败(清理状态);
        }
        if (!全局基础数据集.删除关系(父关系.front().编码)
            || !全局基础数据集.删除字段(场景字段组.front().编码)
            || !全局基础数据集.删除节点(场景节点)) {
            return 新场景操作状态::结构不一致;
        }
        return 新场景操作状态::已完成;
    } catch (...) {
        return 新场景操作状态::资源失败;
    }
}

std::optional<新场景信息> 新_场景类::获取场景(
    稳定编码 场景节点) const noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        if (!是场景节点(场景节点)) return std::nullopt;
        const auto 存在信息 = 存在服务_.获取存在(场景节点);
        if (!存在信息) return std::nullopt;
        const auto 父关系 = 查询父场景关系(场景节点);
        if ((场景节点 == 场景树根节点 && !父关系.empty())
            || (场景节点 != 场景树根节点 && 父关系.size() != 1)) {
            return std::nullopt;
        }
        新场景信息 结果;
        结果.节点 = 场景节点;
        if (!父关系.empty()) 结果.父场景节点 = 父关系.front().源节点;
        结果.专属存在概念节点 = 存在信息->专属存在概念节点;
        结果.特征节点组 = 存在信息->特征节点组;
        结果.直接成员存在组 = 查询直接成员存在(场景节点);
        结果.直接子场景组 = 查询直接子场景(场景节点);
        return 结果;
    } catch (...) {
        return std::nullopt;
    }
}

bool 新_场景类::是场景节点(稳定编码 节点) const noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        if (!结构仍存在() || !节点仍存在(节点)
            || !存在服务_.是存在节点(节点)) return false;
        const auto 类型 = 读取唯一节点字段(节点, 场景身份字段);
        return 类型 && *类型 == 场景节点类型;
    } catch (...) {
        return false;
    }
}

新场景成员建立结果 新_场景类::建立成员存在(
    稳定编码 场景节点,
    const 新存在建立请求& 请求) noexcept {
    新场景成员建立结果 结果;
    try {
        std::lock_guard 锁(新场景互斥);
        if (!是场景节点(场景节点)) {
            结果.状态 = 新场景操作状态::场景不存在;
            return 结果;
        }
        if (请求.父存在节点) {
            const auto 父场景 = 查询所属场景(*请求.父存在节点);
            if (!父场景 || *父场景 != 场景节点) {
                结果.状态 = 新场景操作状态::存在已属于其它场景;
                return 结果;
            }
        }
        const auto 节点 = 全局基础数据集.新建节点();
        if (!有效(节点)) {
            结果.状态 = 新场景操作状态::资源失败;
            return 结果;
        }
        const auto 成员字段 = 全局基础数据集.添加字段节点(
            场景节点, 成员存在字段, 节点);
        if (!有效(成员字段)) {
            (void)全局基础数据集.删除节点(节点);
            结果.状态 = 新场景操作状态::资源失败;
            return 结果;
        }
        const auto 存在结果 = 存在服务_.初始化存在节点(
            节点, 请求, false);
        if (存在结果.状态 != 新存在操作状态::已完成) {
            (void)全局基础数据集.删除字段(成员字段);
            (void)全局基础数据集.删除节点(节点);
            结果.状态 = 映射存在失败(存在结果.状态);
            return 结果;
        }
        结果.状态 = 新场景操作状态::已完成;
        结果.存在节点 = 节点;
        结果.专属存在概念节点 = 存在结果.专属存在概念节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新场景操作状态::资源失败;
        return 结果;
    }
}

新场景操作状态 新_场景类::迁移成员存在(
    稳定编码 存在节点,
    稳定编码 目标场景节点) noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        if (!存在服务_.是存在节点(存在节点) || 是场景节点(存在节点)) {
            return 新场景操作状态::存在不存在;
        }
        if (!是场景节点(目标场景节点)) {
            return 新场景操作状态::场景不存在;
        }
        const auto 原场景 = 查询所属场景(存在节点);
        if (!原场景) return 新场景操作状态::结构不一致;
        if (*原场景 == 目标场景节点) return 新场景操作状态::无变化;

        const auto 原字段组 = 全局基础数据集.查询目标字段(
            存在节点, 成员存在字段);
        if (原字段组.size() != 1
            || 原字段组.front().所属节点 != *原场景) {
            return 新场景操作状态::结构不一致;
        }
        const auto 新字段 = 全局基础数据集.添加字段节点(
            目标场景节点, 成员存在字段, 存在节点);
        if (!有效(新字段)) return 新场景操作状态::资源失败;
        if (!全局基础数据集.删除字段(原字段组.front().编码)) {
            (void)全局基础数据集.删除字段(新字段);
            return 新场景操作状态::资源失败;
        }
        return 新场景操作状态::已完成;
    } catch (...) {
        return 新场景操作状态::资源失败;
    }
}

新场景操作状态 新_场景类::删除成员存在(
    稳定编码 场景节点,
    稳定编码 存在节点) noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        if (!是场景节点(场景节点)) return 新场景操作状态::场景不存在;
        if (!存在服务_.是存在节点(存在节点) || 是场景节点(存在节点)) {
            return 新场景操作状态::存在不存在;
        }
        const auto 字段组 = 全局基础数据集.查询目标字段(
            存在节点, 成员存在字段);
        if (字段组.size() != 1 || 字段组.front().所属节点 != 场景节点) {
            return 新场景操作状态::结构不一致;
        }
        if (!存在服务_.查询直接子存在(存在节点).empty()) {
            return 新场景操作状态::存在仍有子存在;
        }
        if (!全局基础数据集.删除字段(字段组.front().编码)) {
            return 新场景操作状态::资源失败;
        }
        const auto 清理状态 = 存在服务_.清理存在节点内容(存在节点);
        if (清理状态 != 新存在操作状态::已完成) {
            (void)全局基础数据集.添加字段节点(
                场景节点, 成员存在字段, 存在节点);
            return 映射存在失败(清理状态);
        }
        return 全局基础数据集.删除节点(存在节点)
            ? 新场景操作状态::已完成
            : 新场景操作状态::结构不一致;
    } catch (...) {
        return 新场景操作状态::资源失败;
    }
}

std::optional<稳定编码> 新_场景类::查询所属场景(
    稳定编码 存在节点) const noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        if (!存在服务_.是存在节点(存在节点) || 是场景节点(存在节点)) {
            return std::nullopt;
        }
        const auto 字段组 = 全局基础数据集.查询目标字段(
            存在节点, 成员存在字段);
        if (字段组.size() != 1 || !是场景节点(字段组.front().所属节点)) {
            return std::nullopt;
        }
        return 字段组.front().所属节点;
    } catch (...) {
        return std::nullopt;
    }
}

std::optional<稳定编码> 新_场景类::查询父场景(
    稳定编码 场景节点) const noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        if (!是场景节点(场景节点)) return std::nullopt;
        const auto 关系组 = 查询父场景关系(场景节点);
        if (关系组.empty() && 场景节点 == 场景树根节点) return std::nullopt;
        return 关系组.size() == 1 && 是场景节点(关系组.front().源节点)
            ? std::optional<稳定编码>{关系组.front().源节点}
            : std::nullopt;
    } catch (...) {
        return std::nullopt;
    }
}

std::vector<稳定编码> 新_场景类::查询直接子场景(
    稳定编码 场景节点) const noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        std::vector<稳定编码> 结果;
        if (!是场景节点(场景节点)) return 结果;
        for (const auto& 关系 : 查询子场景关系(场景节点)) {
            if (!是场景节点(关系.目标节点)) return {};
            结果.push_back(关系.目标节点);
        }
        排序去重(结果);
        return 结果;
    } catch (...) {
        return {};
    }
}

std::vector<稳定编码> 新_场景类::查询直接成员存在(
    稳定编码 场景节点) const noexcept {
    try {
        std::lock_guard 锁(新场景互斥);
        std::vector<稳定编码> 结果;
        if (!是场景节点(场景节点)) return 结果;
        for (const auto& 字段 : 全局基础数据集.查询字段(
            场景节点, 成员存在字段)) {
            const auto* 存在节点 = std::get_if<稳定编码>(&字段.内容);
            if (!存在节点 || !存在服务_.是存在节点(*存在节点)
                || 是场景节点(*存在节点)) return {};
            结果.push_back(*存在节点);
        }
        排序去重(结果);
        return 结果;
    } catch (...) {
        return {};
    }
}

