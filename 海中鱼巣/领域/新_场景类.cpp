场景相对坐标刷新结果 新_场景类::刷新场景存在相对坐标(
    const 场景定位坐标读取接口& 定位读取,
    const 自我场景姿态& 自我姿态,
    std::uint64_t 当前时刻) const noexcept {
    场景相对坐标刷新结果 结果;
    try {
        if (!是场景节点(自我姿态.场景节点)) {
            结果.状态 = 场景相对坐标刷新状态::场景不存在;
            return 结果;
        }
        const auto 场景信息 = 获取场景(自我姿态.场景节点);
        if (!场景信息) {
            结果.状态 = 场景相对坐标刷新状态::结构不一致;
            return 结果;
        }
        结果.状态 = 核验自我姿态(
            自我姿态.场景节点, 自我姿态, 当前时刻);
        if (结果.状态 != 场景相对坐标刷新状态::已完成) return 结果;

        结果.相对坐标组.reserve(场景信息->直接成员存在组.size());
        for (const auto 存在节点 : 场景信息->直接成员存在组) {
            const auto 定位 = 存在节点 == 自我姿态.自我节点
                ? std::optional<场景定位坐标读回>{
                    形成自我定位读回(自我姿态)}
                : 定位读取.读取存在定位坐标(
                    自我姿态.场景节点, 存在节点);
            const auto 形成结果 = 定位
                ? 形成相对坐标项(
                    存在节点, *定位, 自我姿态, 当前时刻)
                : 相对坐标项形成结果{};
            if (形成结果.状态 == 相对坐标项形成状态::坐标超出范围) {
                结果.状态 = 场景相对坐标刷新状态::坐标超出范围;
                结果.相对坐标组.clear();
                结果.需要获取定位坐标的存在组.clear();
                return 结果;
            }
            if (!形成结果.坐标项) {
                结果.需要获取定位坐标的存在组.push_back(存在节点);
                continue;
            }
            结果.相对坐标组.push_back(*形成结果.坐标项);
        }
        结果.状态 = 结果.需要获取定位坐标的存在组.empty()
            ? 场景相对坐标刷新状态::已完成
            : 场景相对坐标刷新状态::部分完成;
        return 结果;
    } catch (...) {
        结果.状态 = 场景相对坐标刷新状态::资源失败;
        结果.相对坐标组.clear();
        结果.需要获取定位坐标的存在组.clear();
        return 结果;
    }
}

场景相对坐标刷新结果 新_场景类::刷新单个存在相对坐标(
    const 场景定位坐标读取接口& 定位读取,
    const 自我场景姿态& 自我姿态,
    稳定编码 存在节点,
    std::uint64_t 当前时刻) const noexcept {
    场景相对坐标刷新结果 结果;
    try {
        if (!是场景节点(自我姿态.场景节点)) {
            结果.状态 = 场景相对坐标刷新状态::场景不存在;
            return 结果;
        }
        const auto 场景信息 = 获取场景(自我姿态.场景节点);
        if (!场景信息) {
            结果.状态 = 场景相对坐标刷新状态::结构不一致;
            return 结果;
        }
        结果.状态 = 核验自我姿态(
            自我姿态.场景节点, 自我姿态, 当前时刻);
        if (结果.状态 != 场景相对坐标刷新状态::已完成) return 结果;
        if (std::find(
                场景信息->直接成员存在组.begin(),
                场景信息->直接成员存在组.end(),
                存在节点)
            == 场景信息->直接成员存在组.end()) {
            结果.状态 = 场景相对坐标刷新状态::存在不属于场景;
            return 结果;
        }

        const auto 定位 = 存在节点 == 自我姿态.自我节点
            ? std::optional<场景定位坐标读回>{
                形成自我定位读回(自我姿态)}
            : 定位读取.读取存在定位坐标(
                自我姿态.场景节点, 存在节点);
        const auto 形成结果 = 定位
            ? 形成相对坐标项(存在节点, *定位, 自我姿态, 当前时刻)
            : 相对坐标项形成结果{};
        if (形成结果.状态 == 相对坐标项形成状态::坐标超出范围) {
            结果.状态 = 场景相对坐标刷新状态::坐标超出范围;
            return 结果;
        }
        if (!形成结果.坐标项) {
            结果.状态 = 场景相对坐标刷新状态::部分完成;
            结果.需要获取定位坐标的存在组.push_back(存在节点);
            return 结果;
        }
        结果.状态 = 场景相对坐标刷新状态::已完成;
        结果.相对坐标组.push_back(*形成结果.坐标项);
        return 结果;
    } catch (...) {
        结果.状态 = 场景相对坐标刷新状态::资源失败;
        结果.相对坐标组.clear();
        结果.需要获取定位坐标的存在组.clear();
        return 结果;
    }
}

