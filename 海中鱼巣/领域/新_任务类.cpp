新任务列表结果 新_任务类::查询全部任务() const noexcept {
    新任务列表结果 结果;
    try {
        std::lock_guard 锁(新任务互斥);
        if (!结构仍存在()) {
            结果.状态 = 新任务操作状态::尚未初始化;
            return 结果;
        }
        for (const auto& 字段 : 全局基础数据集.查询字段(
            任务集合根节点, 任务成员字段)) {
            const auto* 任务 = std::get_if<稳定编码>(&字段.内容);
            if (!任务 || !读取任务信息(*任务, 特征服务_)) {
                结果.状态 = 新任务操作状态::结构不一致;
                结果.任务节点组.clear();
                return 结果;
            }
            结果.任务节点组.push_back(*任务);
        }
        std::sort(结果.任务节点组.begin(), 结果.任务节点组.end());
        if (std::adjacent_find(结果.任务节点组.begin(),
            结果.任务节点组.end()) != 结果.任务节点组.end()) {
            结果.状态 = 新任务操作状态::结构不一致;
            结果.任务节点组.clear();
            return 结果;
        }
        结果.状态 = 新任务操作状态::已找到;
        return 结果;
    } catch (...) {
        结果.状态 = 新任务操作状态::资源失败;
        结果.任务节点组.clear();
        return 结果;
    }
}

新任务列表结果 新_任务类::查询活动任务() const noexcept {
    auto 结果 = 查询全部任务();
    if (结果.状态 != 新任务操作状态::已找到) return 结果;
    try {
        std::lock_guard 锁(新任务互斥);
        std::erase_if(结果.任务节点组, [&](稳定编码 任务) {
            const auto 信息 = 读取任务信息(任务, 特征服务_);
            return !信息 || 是终结状态(信息->当前状态);
        });
        return 结果;
    } catch (...) {
        结果.状态 = 新任务操作状态::资源失败;
        结果.任务节点组.clear();
        return 结果;
    }
}

