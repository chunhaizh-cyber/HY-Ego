bool 节点仍存在(稳定编码 节点) noexcept {
    return 有效(节点) && 全局基础数据集.查询节点(节点).has_value();
}

bool 是任务状态值(std::int64_t 值) noexcept {
    return 值 >= static_cast<std::int64_t>(新任务状态::已建立)
        && 值 <= static_cast<std::int64_t>(新任务状态::已取消);
}

bool 是执行状态值(std::int64_t 值) noexcept {
    return 值 >= static_cast<std::int64_t>(新任务执行状态::执行中)
        && 值 <= static_cast<std::int64_t>(新任务执行状态::已评估);
}

bool 是终结状态(新任务状态 状态) noexcept {
    return 状态 == 新任务状态::已完成
        || 状态 == 新任务状态::已失败
        || 状态 == 新任务状态::已取消;
}

bool 是合法状态迁移(新任务状态 原状态, 新任务状态 新状态) noexcept {
    if (原状态 == 新状态) return true;
    if (是终结状态(原状态)) return false;
    switch (原状态) {
    case 新任务状态::已建立:
        return 新状态 == 新任务状态::待查找方法
            || 新状态 == 新任务状态::等待条件
            || 新状态 == 新任务状态::已取消;
    case 新任务状态::待查找方法:
        return 新状态 == 新任务状态::待检查条件
            || 新状态 == 新任务状态::等待条件
            || 新状态 == 新任务状态::已失败
            || 新状态 == 新任务状态::已取消;
    case 新任务状态::待检查条件:
        return 新状态 == 新任务状态::待执行
            || 新状态 == 新任务状态::待查找方法
            || 新状态 == 新任务状态::等待条件
            || 新状态 == 新任务状态::已失败
            || 新状态 == 新任务状态::已取消;
    case 新任务状态::待执行:
        return 新状态 == 新任务状态::执行中
            || 新状态 == 新任务状态::待查找方法
            || 新状态 == 新任务状态::等待条件
            || 新状态 == 新任务状态::已取消;
    case 新任务状态::执行中:
        return 新状态 == 新任务状态::待影响评估;
    case 新任务状态::待影响评估:
        return 新状态 == 新任务状态::等待自我决议;
    case 新任务状态::等待自我决议:
        return 新状态 == 新任务状态::待查找方法
            || 新状态 == 新任务状态::待检查条件
            || 新状态 == 新任务状态::待执行
            || 新状态 == 新任务状态::等待条件
            || 新状态 == 新任务状态::已完成
            || 新状态 == 新任务状态::已失败
            || 新状态 == 新任务状态::已取消;
    case 新任务状态::等待条件:
        return 新状态 == 新任务状态::待查找方法
            || 新状态 == 新任务状态::待检查条件
            || 新状态 == 新任务状态::待执行
            || 新状态 == 新任务状态::已失败
            || 新状态 == 新任务状态::已取消;
    case 新任务状态::已完成:
    case 新任务状态::已失败:
    case 新任务状态::已取消:
        return false;
    }
    return false;
}

