新任务建立结果 新_任务类::建立或取得任务(
    稳定编码 需求节点) noexcept {
    新任务建立结果 结果;
    try {
        std::lock_guard 锁(新任务互斥);
        if (!结构仍存在()) {
            结果.状态 = 新任务操作状态::尚未初始化;
            return 结果;
        }
        if (!需求服务_.获取需求(需求节点)) {
            结果.状态 = 新任务操作状态::需求不存在;
            return 结果;
        }
        std::vector<稳定编码> 已有任务;
        for (const auto& 字段 : 全局基础数据集.查询目标字段(
            需求节点, 任务需求字段)) {
            if (!节点类型为(字段.所属节点, 任务节点类型)) {
                结果.状态 = 新任务操作状态::结构不一致;
                return 结果;
            }
            已有任务.push_back(字段.所属节点);
        }
        std::sort(已有任务.begin(), 已有任务.end());
        已有任务.erase(std::unique(已有任务.begin(), 已有任务.end()),
            已有任务.end());
        if (已有任务.size() > 1) {
            结果.状态 = 新任务操作状态::需求已有多个任务;
            return 结果;
        }
        if (已有任务.size() == 1) {
            const auto 现有 = 读取任务信息(已有任务.front(), 特征服务_);
            if (!现有 || 现有->需求节点 != 需求节点) {
                结果.状态 = 新任务操作状态::结构不一致;
                return 结果;
            }
            结果.状态 = 新任务操作状态::已复用;
            结果.任务节点 = 现有->节点;
            结果.任务虚拟存在节点 = 现有->任务虚拟存在节点;
            return 结果;
        }

        const auto 状态特征 = 特征服务_.建立特征(任务状态特征概念);
        if (!有效(状态特征)) {
            结果.状态 = 新任务操作状态::资源失败;
            return 结果;
        }
        const auto 初始写入 = 特征服务_.添加特征值(
            状态特征, 新特征准确值{
                static_cast<std::int64_t>(新任务状态::已建立)});
        if (初始写入.状态 != 新特征写入状态::已完成
            && 初始写入.状态 != 新特征写入状态::无变化) {
            (void)特征服务_.删除特征(状态特征);
            结果.状态 = 新任务操作状态::资源失败;
            return 结果;
        }

        const auto 任务节点 = 全局基础数据集.新建节点();
        const auto 虚拟存在 = 全局基础数据集.新建节点();
        if (!有效(任务节点) || !有效(虚拟存在)) {
            if (有效(任务节点)) (void)全局基础数据集.删除节点(任务节点);
            if (有效(虚拟存在)) (void)全局基础数据集.删除节点(虚拟存在);
            (void)特征服务_.删除特征(状态特征);
            结果.状态 = 新任务操作状态::资源失败;
            return 结果;
        }

        std::vector<稳定编码> 已写字段;
        const bool 完成 =
            写入节点字段(任务节点, 节点类型字段,
                任务节点类型, 已写字段)
            && 写入节点字段(任务节点, 任务需求字段,
                需求节点, 已写字段)
            && 写入节点字段(任务节点, 任务虚拟存在字段,
                虚拟存在, 已写字段)
            && 写入节点字段(虚拟存在, 节点类型字段,
                任务虚拟存在节点类型, 已写字段)
            && 写入节点字段(虚拟存在, 虚拟存在所属任务字段,
                任务节点, 已写字段)
            && 写入节点字段(虚拟存在, 虚拟存在状态特征字段,
                状态特征, 已写字段)
            && 写入节点字段(任务集合根节点, 任务成员字段,
                任务节点, 已写字段);
        if (!完成) {
            回滚字段(已写字段);
            (void)全局基础数据集.删除节点(虚拟存在);
            (void)全局基础数据集.删除节点(任务节点);
            (void)特征服务_.删除特征(状态特征);
            结果.状态 = 新任务操作状态::资源失败;
            return 结果;
        }
        const auto 读回 = 读取任务信息(任务节点, 特征服务_);
        if (!读回 || 读回->需求节点 != 需求节点
            || 读回->任务虚拟存在节点 != 虚拟存在
            || 读回->当前状态 != 新任务状态::已建立) {
            回滚字段(已写字段);
            (void)全局基础数据集.删除节点(虚拟存在);
            (void)全局基础数据集.删除节点(任务节点);
            (void)特征服务_.删除特征(状态特征);
            结果.状态 = 新任务操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新任务操作状态::已建立;
        结果.任务节点 = 任务节点;
        结果.任务虚拟存在节点 = 虚拟存在;
        return 结果;
    } catch (...) {
        结果.状态 = 新任务操作状态::资源失败;
        return 结果;
    }
}

