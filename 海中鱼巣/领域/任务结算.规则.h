#pragma once

#include "新_任务类.h"

namespace 海中鱼巣 {

// 调用期的贡献计值投影；不是可写任务仓，也不代表最终消费资格已经核验。
struct 新结算事实图 final {
    bool 需求任务对应已完整 = false;
    std::map<稳定编码, std::pair<新需求治理信息, std::optional<新任务信息>>> 需求任务对应;
    std::map<稳定编码, 新任务完成结算信息> 完成结算组;
    std::map<稳定编码, std::vector<新任务直接子结算接收信息>> 父直接接收组;
    std::map<稳定编码, 新任务贡献计值类型> 叶子类别组;
    // R108：本轮执行服务需求Ds；直接子集 = 父需求为Ds的需求。对应表中同项成员可映射到同一服务任务。
    稳定编码 本轮服务需求;
    // R108：已被本任务既有K（K链）计入的R；新K不重复计入。
    std::set<稳定编码> 已计入接收;
};

struct 新结算贡献决策 final {
    新任务贡献推进状态 状态 = 新任务贡献推进状态::工程故障;
    std::optional<新任务完成贡献> 贡献;
    新任务贡献反馈定位 来源;
    std::vector<稳定编码> 待归集直接子需求节点组;
};

// 向上送出：不完整/矛盾的事实图抛工程异常，由调用方既有诊断边界终止。
// X/A、状态闭包与提交前复核仍归各owner；本入口只决定直接子贡献如何计值。
新结算贡献决策 计算结算贡献(const 新结算事实图&, 新任务贡献反馈定位);

} // namespace 海中鱼巣
