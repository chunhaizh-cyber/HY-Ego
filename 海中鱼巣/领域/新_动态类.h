#pragma once

#include <cstdint>
#include <optional>
#include <vector>

#include "新_状态类.h"
#include "新_二次特征类.h"
#include "概念_动态类.h"

namespace 海中鱼巣 {

class 新_存在类;

inline constexpr std::int64_t 新复合动态成员关系角色 = 0x44594E4D;
inline constexpr std::int64_t 新动作导致变化关系角色 = 0x41435401;
inline constexpr std::int64_t 新动作观察取得关系角色 = 0x41435402;

enum class 新动态种类 : std::uint8_t {
    原子 = 1,
    动作 = 2,
    复合 = 3
};

enum class 新动作结果关系类型 : std::int64_t {
    导致变化 = 1,
    观察取得 = 2
};

struct 新动作动态建立请求 final {
    稳定编码 执行主体节点;
    稳定编码 动作定义节点;
    稳定编码 动作来源节点;
    稳定编码 目标存在节点;
    std::optional<稳定编码> 目标特征节点;
    新状态强时间 动作时间;

    friend bool operator==(const 新动作动态建立请求&,
        const 新动作动态建立请求&) = default;
};

struct 新动作结果关联 final {
    新动作结果关系类型 类型 = 新动作结果关系类型::导致变化;
    稳定编码 结果动态节点;

    friend bool operator==(const 新动作结果关联&,
        const 新动作结果关联&) = default;
};

struct 新动态跨特征时间项 final {
    稳定编码 前状态节点;
    稳定编码 后状态节点;
    稳定编码 前特征类型概念节点;
    稳定编码 后特征类型概念节点;
    稳定编码 二次特征类型概念节点;
    稳定编码 结果值域概念节点;
    std::int64_t 时间差纳秒 = 0;
    friend bool operator==(const 新动态跨特征时间项&,
        const 新动态跨特征时间项&) = default;
};

struct 新动态信息 final {
    稳定编码 节点;
    新动态种类 种类 = 新动态种类::原子;
    稳定编码 主题存在节点;
    // 原子动态直接保存两个状态；复合动态从外部原子成员关系汇总、
    // 去重并按状态时间排序。同特征原子在读回后按时间串行，跨特征并行。
    std::vector<稳定编码> 状态节点组;
    std::vector<稳定编码> 成员动态节点组;
    std::vector<新动态跨特征时间项> 跨特征时间组;
    // 动作动态不复制结果变化。它保存本次动作的定义、来源、目标与发生
    // 时间，并通过强类型外部关系引用零到多个结果动态。
    std::optional<稳定编码> 动作定义节点;
    std::optional<稳定编码> 动作来源节点;
    std::optional<稳定编码> 动作目标存在节点;
    std::optional<稳定编码> 动作目标特征节点;
    std::optional<新状态强时间> 动作时间;
    std::vector<新动作结果关联> 动作结果组;
    // 每个正式动态实例都先引用自己的专属实例动态概念；聚合稳定后可改为
    // 引用共享聚合动态概念。
    std::optional<稳定编码> 动态概念节点;
    std::int64_t 被引用次数 = 0;
    friend bool operator==(const 新动态信息&, const 新动态信息&) = default;
};

enum class 新动态操作状态 : std::uint8_t {
    已完成 = 1,
    入口拒绝 = 2,
    状态不足 = 3,
    状态不存在 = 4,
    主题不一致 = 5,
    特征类型不一致 = 6,
    时间不合法 = 7,
    状态重复 = 8,
    动态不存在 = 9,
    实例概念失败 = 10,
    动态仍被引用 = 11,
    引用计数溢出 = 12,
    结构不一致 = 13,
    资源失败 = 14,
    概念不合法 = 15,
    状态数量不合法 = 16,
    不是原子动态 = 18,
    端点不连续 = 19,
    复合成员不足 = 20,
    主题不属于存在树 = 22,
    跨特征不足 = 23,
    二次特征计算失败 = 24,
    依赖未配置 = 25,
    会形成环 = 26,
    无变化 = 27,
    动作信息不合法 = 28,
    动作来源冲突 = 29,
    不是动作动态 = 30,
    动作结果不匹配 = 31,
    动作关系冲突 = 32
};

struct 新动态建立结果 final {
    新动态操作状态 状态 = 新动态操作状态::入口拒绝;
    std::optional<稳定编码> 动态节点;
    std::optional<稳定编码> 动态概念节点;
};

class 新_动态类 final {
public:
    新_动态类(
        新_状态类& 状态服务,
        概念_动态类& 动态概念服务) noexcept;

    新_动态类(
        新_状态类& 状态服务,
        概念_动态类& 动态概念服务,
        新_存在类& 存在服务,
        新_二次特征类& 二次特征服务) noexcept;

    bool 初始化() noexcept;

    // 建立恰好由前、后两个状态组成的原子动态，并立即建立实例动态概念。
    新动态建立结果 建立原子动态(
        稳定编码 主题存在节点,
        稳定编码 前状态节点,
        稳定编码 后状态节点) noexcept;

    // 兼容调用形状，但不再允许任意多状态动态；状态组必须恰好为两个。
    新动态建立结果 建立动态(
        稳定编码 主题存在节点,
        const std::vector<稳定编码>& 状态节点组) noexcept;

    // 建立一个存在在同一时间段内的多特征复合动态。成员只能是原子动态，
    // 使用外部父子关系保存；成员集合不表达统一顺序。同特征成员按状态时间
    // 串行，跨特征成员并行，主题可为本存在或其任意层子存在。
    新动态建立结果 建立复合动态(
        稳定编码 主题存在节点,
        const std::vector<稳定编码>& 成员动态组) noexcept;

    // 动作动态先于真实动作建立。动作来源是本次执行或治理事实身份；
    // 相同来源和相同内容精确重放时复用，异义重放拒绝。
    新动态建立结果 建立动作动态(
        const 新动作动态建立请求& 请求) noexcept;

    // 调用方必须显式给出动作节点。实现只校验目标和时间关系，不扫描
    // 场景动态列表猜测“最近动作”。
    新动态操作状态 关联动作结果(
        稳定编码 动作动态节点,
        稳定编码 结果动态节点,
        新动作结果关系类型 关系类型) noexcept;

    std::optional<新动态信息> 获取动态(
        稳定编码 动态节点) const noexcept;
    bool 是动态节点(稳定编码 节点) const noexcept;

    std::vector<稳定编码> 按主题查询动态(
        稳定编码 主题存在节点) const noexcept;
    std::vector<稳定编码> 按状态查询动态(
        稳定编码 状态节点) const noexcept;
    std::vector<稳定编码> 按概念查询动态(
        稳定编码 动态概念节点) const noexcept;

    // 只在上层已经确认聚合结果稳定后调用。成功后动态改为引用共享聚合
    // 概念，并删除原来的实例动态概念节点。
    新动态操作状态 采用聚合动态概念(
        稳定编码 动态节点,
        稳定编码 聚合动态概念节点) noexcept;

    新动态操作状态 删除动态(稳定编码 动态节点) noexcept;

    // 上层组织者通过这些中立入口维护自己的动态引用；动态类不知道引用
    // 来自哪个场景树或其它组合结构。
    新动态操作状态 增加引用(稳定编码 动态节点) noexcept;
    新动态操作状态 撤销增加引用(稳定编码 动态节点) noexcept;
    新动态操作状态 减少引用(稳定编码 动态节点) noexcept;

private:
    新动态操作状态 减少组成引用(稳定编码 动态节点) noexcept;

    新_状态类& 状态服务_;
    概念_动态类& 动态概念服务_;
    新_存在类* 存在服务_ = nullptr;
    新_二次特征类* 二次特征服务_ = nullptr;
};

} // namespace 海中鱼巣
