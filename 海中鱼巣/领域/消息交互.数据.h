#pragma once
#include <cstdint>
#include "新_动态类.h"
#include <string>

namespace 海中鱼巣 {
enum class 新连接状态 : std::uint8_t {
    待接收状态更新 = 1, 待关系发布, 已确认关系, 已取消,
    输入拒绝, 条件未具备, 页面正被使用, 传输未完成, 来源失效, 前提已变化
};
enum class 新外设消息方向 : std::int64_t { 接收 = 1, 发送 = 2, 输出 = 3 };
struct 新外设消息来源键 final {
    std::string 公开宿主会话, 对话框标识;
    新外设消息方向 方向 = 新外设消息方向::接收;
    std::uint64_t 来源序号 = 0;
    friend bool operator==(const 新外设消息来源键&, const 新外设消息来源键&) = default;
};
struct 新外设消息信息 final {
    稳定编码 消息节点, 场景节点, 窗口节点, 正文材料节点;
    新外设消息来源键 来源;
    std::string UTF8正文;
    新状态强时间 正式记录时间;
};
struct 新连接事实 final {
    稳定编码 调用身份, 动作节点, 现实场景, 自我存在, 目标存在;
    稳定编码 交互者特征, 外设窗口, 外设场景, 接收数量特征, 基准状态, 更新状态;
};
enum class 新交互求值状态 : std::uint8_t {
    已取得=1,尚未具备,材料不足,冲突,不支持,前提变化,不符合
};
struct 新交互绑定 final {
    稳定编码 场景,自我,对端,交互者特征,窗口,接收数量特征,外设场景;
};
struct 新交互消息证据 final {
    新外设消息信息 消息;
    新状态信息 状态;
    新特征值信息 状态材料;
    新特征匹配定义快照 消息特征定义;
    稳定编码 状态所属场景;
};
struct 新交互连接过程 final {
    稳定编码 过程节点,来源身份,动作节点;
    新交互绑定 绑定;
    新状态信息 基准状态,更新状态;
    新特征匹配定义快照 接收数量定义;
    新动态信息 动作;
    稳定编码 预期连接方法,预期动作概念;
};
struct 新消息连接输入构成 final {
    稳定编码 关系概念,连接方法,连接动作概念;
    稳定编码 通用存在概念,窗口范围概念,接收数量特征概念;
};
struct 新场景事实构成读取结果 final {
    新交互求值状态 状态=新交互求值状态::材料不足;
    std::optional<新消息连接输入构成> 构成;
    std::vector<基础联合节点快照> 完整保护;
};
struct 新交互写入读回 final {
    新交互求值状态 状态=新交互求值状态::材料不足;
    std::optional<稳定编码> 新状态节点,变化动态节点;
};
} // namespace 海中鱼巣
