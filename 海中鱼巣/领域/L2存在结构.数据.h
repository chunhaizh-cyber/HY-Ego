// 诊断责任：无适用错误分支；当前和历史角色读取具有互斥截止形状。
inline bool L2存在单例角色读取请求有效(
    const L2存在单例角色读取请求& 请求) noexcept {
    if (!L2结构请求头合同有效(请求.请求头)
        || 请求.请求头.期望事实代次 == 0 || 请求.角色.值 <= 0) return false;
    if (请求.读取类别 == L2读取类别::当前)
        return 请求.历史截止事实代次 == 0;
    return 请求.读取类别 == L2读取类别::历史
        && 请求.历史截止事实代次 != 0
        && 请求.历史截止事实代次 <= 请求.请求头.期望事实代次;
}

// 诊断责任：无适用错误分支；登记节点必须同代创建、永久活跃且来源互异。
inline bool L2存在单例角色结构登记完整(
    const L2存在单例角色结构登记& 登记) noexcept {
    return 登记.合同版本 == L2结构合同版本
        && 登记.规则版本 == L2存在单例角色登记规则版本
        && 登记.首次幂等身份 == L2存在单例角色登记固定幂等身份
        && 登记.首次期望事实代次 != 0
        && 登记.首次期望事实代次 != ~std::uint64_t{0}
        && 登记.建立事实代次 == 登记.首次期望事实代次 + 1
        && 登记.事实截止代次 >= 登记.建立事实代次
        && 有效(登记.角色登记锚点稳定编码)
        && 有效(登记.角色关系类型.值)
        && 登记.角色登记锚点稳定编码 != 登记.角色关系类型.值
        && L2生命周期完整(登记.锚点生命周期)
        && L2生命周期完整(登记.类型生命周期)
        && 登记.锚点生命周期.创建事实代次 == 登记.建立事实代次
        && 登记.类型生命周期.创建事实代次 == 登记.建立事实代次
        && !登记.锚点生命周期.退出事实代次
        && !登记.类型生命周期.退出事实代次;
}

// 诊断责任：无适用错误分支；角色关系只接受具名截止内的完整生命周期。
inline bool L2存在单例角色事实完整(
    const L2存在单例角色事实& 事实, std::uint64_t 截止) noexcept {
    return 截止 != 0 && 事实.角色.值 > 0 && 有效(事实.存在.值)
        && 有效(事实.关系稳定编码) && L2生命周期完整(事实.生命周期)
        && 事实.生命周期.创建事实代次 <= 截止
        && (!事实.生命周期.退出事实代次
            || *事实.生命周期.退出事实代次 <= 截止);
}

// 诊断责任：无适用错误分支；登记成功只接受三种成功状态与完整值式登记。
inline bool L2存在单例角色结构登记结果::成功() const noexcept {
    const bool 成功状态 = 结果头.状态 == L2结构状态::已提交
        || 结果头.状态 == L2结构状态::精确重复
        || 结果头.状态 == L2结构状态::已读取;
    return 成功状态 && 结果头.事实截止代次 != 0 && 登记
        && L2存在单例角色结构登记完整(*登记)
        && 登记->事实截止代次 == 结果头.事实截止代次
        && (结果头.状态 == L2结构状态::已读取
            ? !结果头.变更事实代次
            : 结果头.变更事实代次 == 登记->建立事实代次);
}

// 诊断责任：无适用错误分支；绑定、替换和退出各自只允许完整载荷格。
inline bool L2存在单例角色写入结果::成功() const noexcept {
    const bool 成功状态 = 结果头.状态 == L2结构状态::已提交
        || 结果头.状态 == L2结构状态::精确重复;
    if (!成功状态 || 结果头.事实截止代次 == 0
        || 结果头.变更事实代次 != 结果头.事实截止代次
        || (!当前角色关系 && !已退出角色关系)) return false;
    if (当前角色关系
        && (!L2存在单例角色事实完整(
                *当前角色关系, 结果头.事实截止代次)
            || 当前角色关系->生命周期.退出事实代次
            || 当前角色关系->生命周期.创建事实代次
                != 结果头.事实截止代次)) return false;
    if (已退出角色关系
        && (!L2存在单例角色事实完整(
                *已退出角色关系, 结果头.事实截止代次)
            || 已退出角色关系->生命周期.退出事实代次
                != 结果头.事实截止代次)) return false;
    return !当前角色关系 || !已退出角色关系
        || (当前角色关系->角色 == 已退出角色关系->角色
            && 当前角色关系->存在 != 已退出角色关系->存在
            && 当前角色关系->关系稳定编码
                != 已退出角色关系->关系稳定编码);
}

