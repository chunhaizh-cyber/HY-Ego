// 诊断责任：无适用错误分支；显式属性闭包须严格升序且无重复。
inline bool L2存在退出请求有效(const L2存在退出请求& 请求) noexcept {
    if (!L2结构请求头合同有效(请求.请求头)
        || 请求.请求头.期望事实代次 == 0
        || !L2结构幂等身份有效(请求.幂等身份)
        || !有效(请求.存在.值)
        || !有效(请求.族归属关系稳定编码)) return false;
    for (std::size_t 索引 = 0; 索引 < 请求.当前固定属性值.size(); ++索引) {
        if (!有效(请求.当前固定属性值[索引])
            || (索引 != 0
                && !(请求.当前固定属性值[索引 - 1] < 请求.当前固定属性值[索引])))
            return false;
    }
    return true;
}

