需求时序可达性裁决结果 任务时序可达性裁决器::裁决(
    const 需求时序可达性裁决请求& 请求) noexcept {
    try {
        if (!请求合法(请求)) {
            return 建立保守结果(需求时序裁决状态::输入不合法);
        }
        auto 结果 = 建立保守结果(需求时序裁决状态::输入不合法);
        结果.第一后第二 = 评估顺序(请求, 需求时序顺序::第一后第二);
        结果.第二后第一 = 评估顺序(请求, 需求时序顺序::第二后第一);

        const bool 第一保证 = 结果.第一后第二.状态 == 时序路线状态::可保证同时满足;
        const bool 第二保证 = 结果.第二后第一.状态 == 时序路线状态::可保证同时满足;
        if (第一保证 || 第二保证) {
            结果.状态 = 需求时序裁决状态::可保证同时满足;
            结果.采用顺序 = 选择保证顺序(结果.第一后第二, 结果.第二后第一,
                请求.当前绝对时间纳秒);
            return 结果;
        }
        if (是计算不可表示(结果.第一后第二.状态)
            || 是计算不可表示(结果.第二后第一.状态)) {
            结果.状态 = 需求时序裁决状态::计算不可表示;
            return 结果;
        }
        if (是材料不足(结果.第一后第二.状态)
            || 是材料不足(结果.第二后第一.状态)) {
            结果.状态 = 需求时序裁决状态::材料不足;
            return 结果;
        }
        if (是风险路线(结果.第一后第二.状态)
            || 是风险路线(结果.第二后第一.状态)) {
            结果.状态 = 需求时序裁决状态::仅存在风险路线;
            return 结果;
        }

        if (结果.第一后第二.状态 == 时序路线状态::未能保证同时满足
            || 结果.第二后第一.状态 == 时序路线状态::未能保证同时满足) {
            结果.状态 = 需求时序裁决状态::可达性未确定;
            return 结果;
        }
        const auto 第一单独 = 评估单需求(请求, 请求.第一需求);
        const auto 第二单独 = 评估单需求(请求, 请求.第二需求);
        if (!第一单独.可表示 || !第二单独.可表示) {
            结果.状态 = 需求时序裁决状态::计算不可表示;
            return 结果;
        }
        if (第一单独.材料不足 || 第二单独.材料不足) {
            结果.状态 = 需求时序裁决状态::材料不足;
            return 结果;
        }
        if (!第一单独.可保证 && !第二单独.可保证) {
            结果.状态 = 需求时序裁决状态::两个需求均不可保证;
            return 结果;
        }

        int 优先级 = 0;
        if (第一单独.可保证 != 第二单独.可保证) {
            优先级 = 第一单独.可保证 ? 1 : -1;
        } else {
            优先级 = 比较需求优先级(请求.第一需求, 请求.第二需求);
        }
        if (优先级 == 0) {
            结果.状态 = 需求时序裁决状态::时序冲突无法裁决;
            return 结果;
        }
        const bool 选择第一 = 优先级 > 0;
        结果.状态 = 选择第一 ? 需求时序裁决状态::时序冲突选择第一需求
                              : 需求时序裁决状态::时序冲突选择第二需求;
        结果.优先需求节点 = 选择第一 ? 请求.第一需求.需求节点 : 请求.第二需求.需求节点;
        结果.等待重新确认需求节点 = 选择第一 ? 请求.第二需求.需求节点 : 请求.第一需求.需求节点;
        return 结果;
    } catch (const std::bad_alloc&) {
        return 建立保守结果(需求时序裁决状态::资源失败);
    } catch (...) {
        return 建立保守结果(需求时序裁决状态::结构不一致);
    }
}

