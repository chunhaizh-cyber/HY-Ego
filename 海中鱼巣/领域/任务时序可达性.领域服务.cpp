enum class 腿状态 : std::uint8_t {
    可用 = 1,
    转换合同缺失,
    前置材料不足,
    安全硬门否决,
    方法保护约束不兼容
};

struct 腿选择 final {
    腿状态 状态 = 腿状态::转换合同缺失;
    时序转换选择 保证;
    时序转换选择 预计;
    时序转换选择 最短;
};

struct 时间计算 final {
    bool 可表示 = true;
    bool 满足 = false;
    std::int64_t 先需求满足时刻 = 0;
    std::int64_t 后需求满足时刻 = 0;
    std::int64_t 最小余量 = 0;
    std::int64_t 先余量 = 0;
    std::int64_t 后余量 = 0;
};

struct 单需求计算 final {
    bool 可表示 = true;
    bool 材料不足 = false;
    bool 可保证 = false;
};

bool 是合法枚举(需求时间硬度 值) noexcept {
    return 值 == 需求时间硬度::硬约束 || 值 == 需求时间硬度::软约束;
}

bool 是合法枚举(转换候选前置状态 值) noexcept {
    return 值 == 转换候选前置状态::已通过
        || 值 == 转换候选前置状态::安全硬门否决
        || 值 == 转换候选前置状态::方法保护约束不兼容
        || 值 == 转换候选前置状态::材料不足;
}

bool 是合法需求(const 需求时序约束投影& 需求) noexcept {
    return 有效(需求.需求节点)
        && 有效(需求.目标位置节点)
        && 需求.最早满足纳秒 >= 0
        && 需求.最晚满足纳秒 >= 需求.最早满足纳秒
        && 需求.最小保持纳秒 >= 0
        && 需求.错过损失 >= 0
        && 需求.需求权重 >= 0
        && 是合法枚举(需求.时间硬度);
}

bool 是合法合同(const 转换时间合同投影& 合同) noexcept {
    return 有效(合同.方法节点)
        && 有效(合同.起点位置节点)
        && 有效(合同.终点位置节点)
        && 合同.起点位置节点 != 合同.终点位置节点
        && 合同.最短耗时纳秒 >= 0
        && 合同.预计耗时纳秒 >= 合同.最短耗时纳秒
        && 合同.保证最大耗时纳秒 >= 合同.预计耗时纳秒
        && 是合法枚举(合同.前置状态);
}

bool 请求合法(const 需求时序可达性裁决请求& 请求) noexcept {
    if (请求.当前绝对时间纳秒 < 0 || !有效(请求.当前位置节点)
        || !是合法需求(请求.第一需求) || !是合法需求(请求.第二需求)
        || 请求.第一需求.需求节点 == 请求.第二需求.需求节点) {
        return false;
    }
    for (std::size_t i = 0; i < 请求.转换候选组.size(); ++i) {
        const auto& 当前 = 请求.转换候选组[i];
        if (!是合法合同(当前)) {
            return false;
        }
        for (std::size_t j = 0; j < i; ++j) {
            const auto& 之前 = 请求.转换候选组[j];
            if (当前.方法节点 == 之前.方法节点
                && 当前.起点位置节点 == 之前.起点位置节点
                && 当前.终点位置节点 == 之前.终点位置节点
                && !(当前 == 之前)) {
                return false;
            }
        }
    }
    return true;
}

bool 安全相加(std::int64_t 左, std::int64_t 右, std::int64_t& 结果) noexcept {
    if (左 < 0 || 右 < 0 || 左 > std::numeric_limits<std::int64_t>::max() - 右) {
        return false;
    }
    结果 = 左 + 右;
    return true;
}

腿选择 选择腿(const 需求时序可达性裁决请求& 请求,
    稳定编码 起点, 稳定编码 终点) {
    腿选择 结果;
    结果.保证.起点位置节点 = 起点;
    结果.保证.终点位置节点 = 终点;
    结果.预计.起点位置节点 = 起点;
    结果.预计.终点位置节点 = 终点;
    结果.最短.起点位置节点 = 起点;
    结果.最短.终点位置节点 = 终点;
    if (起点 == 终点) {
        结果.状态 = 腿状态::可用;
        return 结果;
    }

    const 转换时间合同投影* 最佳保证 = nullptr;
    const 转换时间合同投影* 最佳预计 = nullptr;
    const 转换时间合同投影* 最佳最短 = nullptr;
    bool 有合同 = false;
    bool 有材料不足 = false;
    bool 有安全否决 = false;
    bool 有保护不兼容 = false;
    for (const auto& 合同 : 请求.转换候选组) {
        if (合同.起点位置节点 != 起点 || 合同.终点位置节点 != 终点) {
            continue;
        }
        有合同 = true;
        if (合同.前置状态 == 转换候选前置状态::材料不足) {
            有材料不足 = true;
        } else if (合同.前置状态 == 转换候选前置状态::安全硬门否决) {
            有安全否决 = true;
        } else if (合同.前置状态 == 转换候选前置状态::方法保护约束不兼容) {
            有保护不兼容 = true;
        } else {
            if (最佳最短 == nullptr
                || std::tie(合同.最短耗时纳秒, 合同.预计耗时纳秒,
                    合同.保证最大耗时纳秒, 合同.方法节点)
                    < std::tie(最佳最短->最短耗时纳秒, 最佳最短->预计耗时纳秒,
                        最佳最短->保证最大耗时纳秒, 最佳最短->方法节点)) {
                最佳最短 = &合同;
            }
            if (最佳保证 == nullptr
                || std::tie(合同.保证最大耗时纳秒, 合同.预计耗时纳秒, 合同.方法节点)
                    < std::tie(最佳保证->保证最大耗时纳秒, 最佳保证->预计耗时纳秒,
                        最佳保证->方法节点)) {
                最佳保证 = &合同;
            }
            if (最佳预计 == nullptr
                || std::tie(合同.预计耗时纳秒, 合同.保证最大耗时纳秒, 合同.方法节点)
                    < std::tie(最佳预计->预计耗时纳秒, 最佳预计->保证最大耗时纳秒,
                        最佳预计->方法节点)) {
                最佳预计 = &合同;
            }
        }
    }

    if (最佳保证 != nullptr) {
        结果.状态 = 腿状态::可用;
        结果.保证.方法节点 = 最佳保证->方法节点;
        结果.保证.采用耗时纳秒 = 最佳保证->保证最大耗时纳秒;
        结果.预计.方法节点 = 最佳预计->方法节点;
        结果.预计.采用耗时纳秒 = 最佳预计->预计耗时纳秒;
        结果.最短.方法节点 = 最佳最短->方法节点;
        结果.最短.采用耗时纳秒 = 最佳最短->最短耗时纳秒;
    } else if (!有合同) {
        结果.状态 = 腿状态::转换合同缺失;
    } else if (有材料不足) {
        结果.状态 = 腿状态::前置材料不足;
    } else if (有安全否决) {
        结果.状态 = 腿状态::安全硬门否决;
    } else if (有保护不兼容) {
        结果.状态 = 腿状态::方法保护约束不兼容;
    }
    return 结果;
}

时序路线状态 汇总腿状态(腿状态 第一, 腿状态 第二) noexcept {
    const 腿状态 状态组[] = { 第一, 第二 };
    for (const auto 状态 : 状态组) {
        if (状态 == 腿状态::转换合同缺失) return 时序路线状态::转换合同缺失;
    }
    for (const auto 状态 : 状态组) {
        if (状态 == 腿状态::前置材料不足) return 时序路线状态::前置材料不足;
    }
    for (const auto 状态 : 状态组) {
        if (状态 == 腿状态::安全硬门否决) return 时序路线状态::安全硬门否决;
    }
    return 时序路线状态::方法保护约束不兼容;
}

时间计算 计算顺序时间(const 需求时序可达性裁决请求& 请求,
    const 需求时序约束投影& 先需求, const 需求时序约束投影& 后需求,
    std::int64_t 第一腿耗时, std::int64_t 第二腿耗时) noexcept {
    时间计算 结果;
    std::int64_t 到达先 = 0;
    std::int64_t 离开先 = 0;
    std::int64_t 到达后 = 0;
    if (!安全相加(请求.当前绝对时间纳秒, 第一腿耗时, 到达先)) {
        结果.可表示 = false;
        return 结果;
    }
    结果.先需求满足时刻 = std::max(到达先, 先需求.最早满足纳秒);
    if (!安全相加(结果.先需求满足时刻, 先需求.最小保持纳秒, 离开先)
        || !安全相加(离开先, 第二腿耗时, 到达后)) {
        结果.可表示 = false;
        return 结果;
    }
    结果.后需求满足时刻 = std::max(到达后, 后需求.最早满足纳秒);
    结果.满足 = 结果.先需求满足时刻 <= 先需求.最晚满足纳秒
        && 结果.后需求满足时刻 <= 后需求.最晚满足纳秒;
    结果.先余量 = 先需求.最晚满足纳秒 - 结果.先需求满足时刻;
    结果.后余量 = 后需求.最晚满足纳秒 - 结果.后需求满足时刻;
    结果.最小余量 = std::min(结果.先余量, 结果.后余量);
    return 结果;
}

void 写入满足时刻(时序路线评估& 输出, 需求时序顺序 顺序,
    const 时间计算& 计算) {
    if (顺序 == 需求时序顺序::第一后第二) {
        输出.第一需求满足时刻 = 计算.先需求满足时刻;
        输出.第二需求满足时刻 = 计算.后需求满足时刻;
    } else {
        输出.第一需求满足时刻 = 计算.后需求满足时刻;
        输出.第二需求满足时刻 = 计算.先需求满足时刻;
    }
    输出.最小窗口余量纳秒 = 计算.最小余量;
}

时序路线评估 评估顺序(const 需求时序可达性裁决请求& 请求,
    需求时序顺序 顺序) {
    时序路线评估 输出;
    输出.顺序 = 顺序;
    输出.最短比较.依据 = 时序耗时依据::最短;
    输出.预计比较.依据 = 时序耗时依据::预计;
    输出.保证比较.依据 = 时序耗时依据::保证最大;
    const auto& 先需求 = 顺序 == 需求时序顺序::第一后第二
        ? 请求.第一需求 : 请求.第二需求;
    const auto& 后需求 = 顺序 == 需求时序顺序::第一后第二
        ? 请求.第二需求 : 请求.第一需求;
    const auto 第一腿 = 选择腿(请求, 请求.当前位置节点, 先需求.目标位置节点);
    const auto 第二腿 = 选择腿(请求, 先需求.目标位置节点, 后需求.目标位置节点);
    if (第一腿.状态 != 腿状态::可用 || 第二腿.状态 != 腿状态::可用) {
        输出.状态 = 汇总腿状态(第一腿.状态, 第二腿.状态);
        return 输出;
    }

    输出.保证路线 = { 第一腿.保证, 第二腿.保证 };
    输出.预计路线 = { 第一腿.预计, 第二腿.预计 };
    const auto 保证计算 = 计算顺序时间(请求, 先需求, 后需求,
        第一腿.保证.采用耗时纳秒, 第二腿.保证.采用耗时纳秒);
    const auto 预计计算 = 计算顺序时间(请求, 先需求, 后需求,
        第一腿.预计.采用耗时纳秒, 第二腿.预计.采用耗时纳秒);
    const auto 最短计算 = 计算顺序时间(请求, 先需求, 后需求,
        第一腿.最短.采用耗时纳秒, 第二腿.最短.采用耗时纳秒);
    const auto 写入比较 = [顺序](时序时间比较材料& 材料,
        const 时间计算& 计算, const 时序转换选择& 先, const 时序转换选择& 后) {
        材料.路线 = {先, 后};
        if (!计算.可表示) return;
        const bool 正序 = 顺序 == 需求时序顺序::第一后第二;
        材料.第一需求满足时刻 = 正序 ? 计算.先需求满足时刻 : 计算.后需求满足时刻;
        材料.第二需求满足时刻 = 正序 ? 计算.后需求满足时刻 : 计算.先需求满足时刻;
        材料.第一需求窗口余量纳秒 = 正序 ? 计算.先余量 : 计算.后余量;
        材料.第二需求窗口余量纳秒 = 正序 ? 计算.后余量 : 计算.先余量;
        材料.最小窗口余量纳秒 = 计算.最小余量;
        材料.可表示 = true;
    };
    写入比较(输出.保证比较, 保证计算, 第一腿.保证, 第二腿.保证);
    写入比较(输出.预计比较, 预计计算, 第一腿.预计, 第二腿.预计);
    写入比较(输出.最短比较, 最短计算, 第一腿.最短, 第二腿.最短);
    if (!保证计算.可表示 || !预计计算.可表示 || !最短计算.可表示) {
        输出.状态 = 时序路线状态::计算不可表示;
        return 输出;
    }
    if (保证计算.满足) {
        输出.状态 = 时序路线状态::可保证同时满足;
        写入满足时刻(输出, 顺序, 保证计算);
        return 输出;
    }
    if (预计计算.满足) {
        输出.状态 = 时序路线状态::仅按预计耗时可同时满足;
        写入满足时刻(输出, 顺序, 预计计算);
    } else {
        输出.状态 = 最短计算.满足 ? 时序路线状态::未能保证同时满足
            : 时序路线状态::不可同时满足;
    }
    return 输出;
}

单需求计算 评估单需求(const 需求时序可达性裁决请求& 请求,
    const 需求时序约束投影& 需求) {
    单需求计算 输出;
    const auto 腿 = 选择腿(请求, 请求.当前位置节点, 需求.目标位置节点);
    if (腿.状态 == 腿状态::前置材料不足) {
        输出.材料不足 = true;
        return 输出;
    }
    if (腿.状态 != 腿状态::可用) {
        return 输出;
    }
    std::int64_t 到达 = 0;
    if (!安全相加(请求.当前绝对时间纳秒, 腿.保证.采用耗时纳秒, 到达)) {
        输出.可表示 = false;
        return 输出;
    }
    const auto 满足时刻 = std::max(到达, 需求.最早满足纳秒);
    输出.可保证 = 满足时刻 <= 需求.最晚满足纳秒;
    return 输出;
}

int 比较需求优先级(const 需求时序约束投影& 左,
    const 需求时序约束投影& 右) noexcept {
    const auto 左键 = std::tuple(左.安全硬约束,
        左.时间硬度 == 需求时间硬度::硬约束, 左.错过损失, 左.需求权重);
    const auto 右键 = std::tuple(右.安全硬约束,
        右.时间硬度 == 需求时间硬度::硬约束, 右.错过损失, 右.需求权重);
    if (左键 < 右键) return -1;
    if (右键 < 左键) return 1;
    return 0;
}

bool 是材料不足(时序路线状态 状态) noexcept {
    return 状态 == 时序路线状态::前置材料不足;
}

bool 是计算不可表示(时序路线状态 状态) noexcept {
    return 状态 == 时序路线状态::计算不可表示;
}

bool 是风险路线(时序路线状态 状态) noexcept {
    return 状态 == 时序路线状态::仅按预计耗时可同时满足;
}

需求时序顺序 选择保证顺序(const 时序路线评估& 第一后第二,
    const 时序路线评估& 第二后第一, std::int64_t 当前时刻) noexcept {
    if (第一后第二.状态 != 时序路线状态::可保证同时满足) {
        return 需求时序顺序::第二后第一;
    }
    if (第二后第一.状态 != 时序路线状态::可保证同时满足) {
        return 需求时序顺序::第一后第二;
    }
    if (*第一后第二.最小窗口余量纳秒 != *第二后第一.最小窗口余量纳秒) {
        return *第一后第二.最小窗口余量纳秒 > *第二后第一.最小窗口余量纳秒
            ? 需求时序顺序::第一后第二 : 需求时序顺序::第二后第一;
    }
    const auto 第一完成耗时 = *第一后第二.第二需求满足时刻 - 当前时刻;
    const auto 第二完成耗时 = *第二后第一.第一需求满足时刻 - 当前时刻;
    if (第一完成耗时 != 第二完成耗时) {
        return 第一完成耗时 < 第二完成耗时
            ? 需求时序顺序::第一后第二 : 需求时序顺序::第二后第一;
    }
    return 需求时序顺序::第一后第二;
}

需求时序可达性裁决结果 建立保守结果(需求时序裁决状态 状态) {
    需求时序可达性裁决结果 结果;
    结果.状态 = 状态;
    结果.第一后第二.顺序 = 需求时序顺序::第一后第二;
    结果.第二后第一.顺序 = 需求时序顺序::第二后第一;
    return 结果;
}

