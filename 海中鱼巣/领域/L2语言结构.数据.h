// 诊断责任：无适用错误分支；只判断语言登记键的纯值形状。
inline bool L2语言登记键有效(const L2语言登记键& 登记键) noexcept {
    return 有效(登记键.材料.值);
}

// 诊断责任：无适用错误分支；只判断语言完整事实在具名截止的值式投影。
inline bool L2语言事实完整(
    const L2语言事实& 事实, std::uint64_t 截止) noexcept {
    if (截止 == 0 || !有效(事实.语言.值)
        || !L2语言登记键有效(事实.登记键.登记键)
        || !有效(事实.来源.来源材料.值)
        || !有效(事实.登记键.关系稳定编码)
        || !有效(事实.来源.关系稳定编码)
        || 事实.登记键.关系稳定编码 == 事实.来源.关系稳定编码
        || !L2节点族身份来源事实完整(事实.身份来源, 截止)
        || 事实.身份来源.节点族 != L2节点族::语言
        || 事实.身份来源.节点稳定编码 != 事实.语言.值
        || 事实.登记键.语言 != 事实.语言
        || 事实.来源.语言 != 事实.语言
        || 事实.生命周期 != 事实.身份来源.节点生命周期
        || 事实.生命周期 != 事实.身份来源.归属关系生命周期
        || 事实.生命周期 != 事实.登记键.生命周期
        || 事实.生命周期 != 事实.来源.生命周期
        || 事实.身份来源.所有者生命周期.退出事实代次
        || 事实.身份来源.族锚点生命周期.退出事实代次
        || 事实.身份来源.关系类型生命周期.退出事实代次)
        return false;
    return L2生命周期完整(事实.生命周期)
        && 事实.生命周期.创建事实代次 <= 截止
        && (!事实.生命周期.退出事实代次
            || *事实.生命周期.退出事实代次 <= 截止);
}

// 诊断责任：无适用错误分支；只判断语言新增请求的纯值入口形状。
inline bool L2语言新增请求有效(const L2语言新增请求& 请求) noexcept {
    return L2结构请求头合同有效(请求.请求头)
        && 请求.语言合同版本 == L2语言结构合同版本
        && 请求.请求头.期望事实代次 != 0
        && L2结构幂等身份有效(请求.幂等身份)
        && L2语言登记键有效(请求.登记键)
        && 有效(请求.来源材料.值);
}

// 诊断责任：无适用错误分支；只判断语言替换请求的纯值入口形状。
inline bool L2语言替换请求有效(const L2语言替换请求& 请求) noexcept {
    const bool 前后完全相同 = 请求.旧登记键 == 请求.新登记键
        && 请求.旧来源材料 == 请求.新来源材料;
    return L2结构请求头合同有效(请求.请求头)
        && 请求.语言合同版本 == L2语言结构合同版本
        && 请求.请求头.期望事实代次 != 0
        && L2结构幂等身份有效(请求.幂等身份)
        && 有效(请求.旧语言.值)
        && L2语言登记键有效(请求.旧登记键)
        && 有效(请求.旧来源材料.值)
        && L2语言登记键有效(请求.新登记键)
        && 有效(请求.新来源材料.值)
        && !前后完全相同;
}

// 诊断责任：无适用错误分支；只判断语言退出请求的纯值入口形状。
inline bool L2语言退出请求有效(const L2语言退出请求& 请求) noexcept {
    return L2结构请求头合同有效(请求.请求头)
        && 请求.语言合同版本 == L2语言结构合同版本
        && 请求.请求头.期望事实代次 != 0
        && L2结构幂等身份有效(请求.幂等身份)
        && 有效(请求.语言.值)
        && L2语言登记键有效(请求.登记键)
        && 有效(请求.来源材料.值);
}

// 诊断责任：无适用错误分支；只判断按身份读取请求的纯值入口形状。
inline bool L2语言读取请求有效(const L2语言读取请求& 请求) noexcept {
    const bool 当前读取 = 请求.读取类别 == L2读取类别::当前
        && 请求.历史截止事实代次 == 0;
    const bool 历史读取 = 请求.读取类别 == L2读取类别::历史
        && 请求.历史截止事实代次 != 0
        && 请求.历史截止事实代次 <= 请求.请求头.期望事实代次;
    return L2结构请求头合同有效(请求.请求头)
        && 请求.语言合同版本 == L2语言结构合同版本
        && 请求.请求头.期望事实代次 != 0
        && 有效(请求.语言.值) && (当前读取 || 历史读取);
}

// 诊断责任：无适用错误分支；只判断按登记键读取请求的纯值入口形状。
inline bool L2语言按登记键读取请求有效(
    const L2语言按登记键读取请求& 请求) noexcept {
    const bool 当前读取 = 请求.读取类别 == L2读取类别::当前
        && 请求.历史截止事实代次 == 0;
    const bool 历史读取 = 请求.读取类别 == L2读取类别::历史
        && 请求.历史截止事实代次 != 0
        && 请求.历史截止事实代次 <= 请求.请求头.期望事实代次;
    return L2结构请求头合同有效(请求.请求头)
        && 请求.语言合同版本 == L2语言结构合同版本
        && 请求.请求头.期望事实代次 != 0
        && L2语言登记键有效(请求.登记键)
        && (当前读取 || 历史读取);
}

inline bool L2语言新增结果::成功() const noexcept {
    return (结果头.状态 == L2结构状态::已提交
            || 结果头.状态 == L2结构状态::精确重复)
        && 结果头.合同版本 == L2结构合同版本
        && 结果头.事实截止代次 != 0 && 结果头.变更事实代次
        && *结果头.变更事实代次 == 结果头.事实截止代次
        && 当前语言
        && L2语言事实完整(*当前语言, 结果头.事实截止代次)
        && !当前语言->生命周期.退出事实代次
        && 当前语言->生命周期.创建事实代次 == 结果头.事实截止代次;
}

inline bool L2语言替换结果::成功() const noexcept {
    return (结果头.状态 == L2结构状态::已提交
            || 结果头.状态 == L2结构状态::精确重复)
        && 结果头.合同版本 == L2结构合同版本
        && 结果头.事实截止代次 != 0 && 结果头.变更事实代次
        && *结果头.变更事实代次 == 结果头.事实截止代次
        && 当前语言 && 已退出语言
        && L2语言事实完整(*当前语言, 结果头.事实截止代次)
        && L2语言事实完整(*已退出语言, 结果头.事实截止代次)
        && 当前语言->语言 != 已退出语言->语言
        && !当前语言->生命周期.退出事实代次
        && 当前语言->生命周期.创建事实代次 == 结果头.事实截止代次
        && 已退出语言->生命周期.退出事实代次
        && *已退出语言->生命周期.退出事实代次
            == 结果头.事实截止代次;
}

inline bool L2语言退出结果::成功() const noexcept {
    return (结果头.状态 == L2结构状态::已提交
            || 结果头.状态 == L2结构状态::精确重复)
        && 结果头.合同版本 == L2结构合同版本
        && 结果头.事实截止代次 != 0 && 结果头.变更事实代次
        && *结果头.变更事实代次 == 结果头.事实截止代次
        && 已退出语言
        && L2语言事实完整(*已退出语言, 结果头.事实截止代次)
        && 已退出语言->生命周期.退出事实代次
        && *已退出语言->生命周期.退出事实代次
            == 结果头.事实截止代次;
}

inline bool L2语言读取结果::成功() const noexcept {
    if (结果头.状态 != L2结构状态::已读取
        || 结果头.合同版本 != L2结构合同版本
        || 结果头.事实截止代次 == 0 || 结果头.变更事实代次
        || !语言 || !L2语言事实完整(*语言, 结果头.事实截止代次))
        return false;
    if (读取类别 == L2读取类别::当前)
        return 历史截止事实代次 == 0
            && !语言->生命周期.退出事实代次;
    return 读取类别 == L2读取类别::历史
        && 历史截止事实代次 == 结果头.事实截止代次;
}

inline bool L2语言按登记键读取结果::成功() const noexcept {
    if (结果头.状态 != L2结构状态::已读取
        || 结果头.合同版本 != L2结构合同版本
        || 结果头.事实截止代次 == 0 || 结果头.变更事实代次
        || !语言 || !L2语言事实完整(*语言, 结果头.事实截止代次)
        || 语言->生命周期.退出事实代次)
        return false;
    if (读取类别 == L2读取类别::当前)
        return 历史截止事实代次 == 0;
    return 读取类别 == L2读取类别::历史
        && 历史截止事实代次 == 结果头.事实截止代次;
}

