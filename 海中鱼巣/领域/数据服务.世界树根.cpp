世界树根数据服务::世界树根数据服务(存在类数据服务 &存在,
                                         场景类数据服务 &场景)
    : existence_(存在), scene_(场景) {
  if (&存在.世界树根底座() != &场景.世界树根底座() ||
      !存在.世界树根结构已就绪() || !场景.世界树根结构已就绪() ||
      !存在.世界树根协调端口().绑定于(存在.世界树根底座()) ||
      !场景.世界树根协调端口().绑定于(存在.世界树根底座()) ||
      存在.世界树根所有者() == 场景.世界树根所有者())
    throw std::invalid_argument("world root participants");
}

世界树根初始化结果 世界树根数据服务::初始化世界树根(
    const 世界树根初始化请求 &请求) noexcept {
  世界树根初始化结果 结果;
  结果.原请求 = 请求;
  bool 已提交 = false;
  try {
    if (!请求有效(请求))
      return 结果;

    const 世界树根组读取请求 根组请求{世界树根合同版本,
                                           请求.最大关系数量};
    const auto 根组 = scene_.读取当前世界树根组(根组请求);
    if (!根组.成功(根组请求)) {
      结果.状态 = 根组.状态;
      return 结果;
    }
    if (根组.根组.size() > 1) {
      结果.状态 = 世界树根状态::内部不一致;
      return 结果;
    }

    const auto 存在首次 =
        existence_.读取世界树根存在首次材料(请求.存在幂等身份);
    const auto 场景首次 =
        scene_.读取世界树根场景首次材料(请求.场景幂等身份);
    const auto 首次状态 = [](const L1所有者范围首次写入读取结果 &材料) {
      if (材料.状态 == L1所有者范围读取状态::成功)
        return 1;
      if (材料.状态 == L1所有者范围读取状态::未找到)
        return 0;
      return -1;
    };
    const int 存在状态 = 首次状态(存在首次);
    const int 场景状态 = 首次状态(场景首次);
    if (存在状态 < 0 || 场景状态 < 0) {
      结果.状态 = 存在首次.状态 == L1所有者范围读取状态::资源失败 ||
                          场景首次.状态 == L1所有者范围读取状态::资源失败
                      ? 世界树根状态::资源失败
                      : 世界树根状态::内部不一致;
      return 结果;
    }
    if (存在状态 != 场景状态) {
      结果.状态 = 世界树根状态::内部不一致;
      return 结果;
    }

    const bool 重放 = 存在状态 == 1;
    if (!根组.根组.empty()) {
      结果.状态 = 重放 ? 世界树根状态::已可能发布
                       : 世界树根状态::已有不同根;
      return 结果;
    }
    if (重放) {
      结果.状态 = 世界树根状态::内部不一致;
      return 结果;
    }

    auto 存在片段 = existence_.准备世界树根存在片段(请求).写集;
    auto 场景片段 = scene_.准备世界树根场景片段(请求).写集;
    if (存在片段.参与者.值 != 1 || 场景片段.参与者.值 != 2 ||
        存在片段.所有者 != existence_.世界树根所有者() ||
        场景片段.所有者 != scene_.世界树根所有者() ||
        存在片段.写集.写入幂等身份 != 请求.存在幂等身份 ||
        场景片段.写集.写入幂等身份 != 请求.场景幂等身份) {
      结果.状态 = 世界树根状态::内部不一致;
      return 结果;
    }

    const L1有限N分区原子事务请求 原子请求{
        请求.组合幂等身份, {存在片段, 场景片段}};
    const std::vector<const L1所有者范围写端口 *> 其它参与者{
        &scene_.世界树根协调端口()};
    已提交 = true;
    const auto 写入 = existence_.世界树根协调端口()
                          .提交有限N分区原子事务(原子请求, 其它参与者);
    using 写入状态 = L1有限N分区原子事务状态;
    if (写入.状态 == 写入状态::已提交 ||
        写入.状态 == 写入状态::精确重复) {
      已提交 = false;
      if (写入.组合写入幂等身份 != 请求.组合幂等身份 ||
          写入.参与者结果组.size() != 2) {
        结果.状态 = 世界树根状态::内部不一致;
        return 结果;
      }
      // 当前没有一次锁内完成“根存在来源 + 根场景完整事实”的组合读取。
      // 多次 current-only 读取不能拼接成一个成功快照。
      结果.状态 = 世界树根状态::已可能发布;
      return 结果;
    }

    if (写入.状态 == 写入状态::已可能发布 ||
        写入.是否已确认形成内存权威发布 ||
        写入.重试边界 == L1所有者范围重试边界::原幂等身份读回收敛) {
      结果.状态 = 世界树根状态::已可能发布;
      return 结果;
    }
    已提交 = false;
    switch (写入.状态) {
    case 写入状态::幂等冲突:
      结果.状态 = 世界树根状态::幂等冲突;
      break;
    case 写入状态::引用冲突:
      结果.状态 = 世界树根状态::引用冲突;
      break;
    case 写入状态::资源失败:
      结果.状态 = 世界树根状态::资源失败;
      break;
    case 写入状态::入口拒绝:
      结果.状态 = 世界树根状态::入口拒绝;
      break;
    default:
      结果.状态 = 世界树根状态::内部不一致;
      break;
    }
  } catch (const std::bad_alloc &) {
    结果.状态 = 已提交 ? 世界树根状态::已可能发布
                        : 世界树根状态::资源失败;
  } catch (const std::length_error &) {
    结果.状态 = 已提交 ? 世界树根状态::已可能发布
                        : 世界树根状态::资源失败;
  } catch (...) {
    结果.状态 = 已提交 ? 世界树根状态::已可能发布
                        : 世界树根状态::内部不一致;
  }
  return 结果;
}

bool 世界树根数据服务::请求有效(const 世界树根初始化请求 &请求) const noexcept {
  return 请求.版本 == 世界树根合同版本 && 请求.组合幂等身份.值 &&
         请求.存在幂等身份.值 && 请求.场景幂等身份.值 &&
         请求.组合幂等身份 != 请求.存在幂等身份 &&
         请求.组合幂等身份 != 请求.场景幂等身份 &&
         请求.存在幂等身份 != 请求.场景幂等身份 &&
         请求.最大关系数量 >= 1 && 请求.最大关系数量 <= 4096 &&
         请求.最大场景数量 >= 1 && 请求.最大场景数量 <= 4096 &&
         existence_.世界树根结构已就绪() && scene_.世界树根结构已就绪() &&
         existence_.世界树根幂等键可用(请求.存在幂等身份) &&
         scene_.世界树根幂等键可用(请求.场景幂等身份) &&
         (请求.组合幂等身份.值 >> 48) != 0x4E43;
}

