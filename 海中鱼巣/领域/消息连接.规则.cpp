#include "消息连接.规则.h"
#include <algorithm>
namespace 海中鱼巣 {
新交互求值状态 核验消息连接过程(const 新交互连接过程& 过程,const 新特征信息& 特征,
    const 新交互绑定& 绑定,const 新消息连接输入构成& 定义) {
    const auto& 原=过程.绑定;
    if (!有效(过程.过程节点)||!有效(过程.来源身份)||!有效(过程.动作节点)
        ||!有效(定义.连接方法)||!有效(定义.连接动作概念)) return 新交互求值状态::材料不足;
    if (原.场景!=绑定.场景||原.自我!=绑定.自我||原.对端!=绑定.对端
        ||原.交互者特征!=绑定.交互者特征||原.窗口!=绑定.窗口
        ||原.接收数量特征!=绑定.接收数量特征||原.外设场景!=绑定.外设场景
        ||原.自我==原.对端||特征.节点!=绑定.交互者特征) return 新交互求值状态::不符合;
    if (过程.预期连接方法!=定义.连接方法||过程.预期动作概念!=定义.连接动作概念)
        return 新交互求值状态::前提变化;
    const auto& 动作=过程.动作;
    if (动作.节点!=过程.动作节点||动作.种类!=新动态种类::动作
        ||动作.动作定义节点!=定义.连接方法||动作.动作来源节点!=过程.来源身份
        ||动作.主题存在节点!=绑定.自我||动作.动作目标存在节点!=绑定.自我
        ||动作.动作目标特征节点!=绑定.交互者特征||!动作.动作时间||!动作.动态概念节点)
        return 新交互求值状态::不符合;
    const auto& 前=过程.基准状态;
    const auto& 后=过程.更新状态;
    const auto& FT=过程.接收数量定义;
    const auto 核状态=[&](const 新状态信息& s) {
        return 有效(s.节点)&&s.被描述存在节点==绑定.窗口
            &&s.来源实例特征节点==绑定.接收数量特征
            &&有效(s.特征类型概念节点)
            &&(s.固定准确值 && std::holds_alternative<std::int64_t>(*s.固定准确值));
    };
    if (FT.特征类型根!=定义.接收数量特征概念
        ||FT.材料类型!=特征概念材料物理类型::I64标量
        ||FT.比较规则!=特征概念比较规则::I64数值
        ||!核状态(前)||!核状态(后)||前.节点==后.节点
        ||前.强时间.语义!=后.强时间.语义||后.强时间.纳秒<=前.强时间.纳秒)
        return 新交互求值状态::不符合;
    // 这里只核对固定材料的一致性；二次计算由执行/结果服务完成。
    // 不对节点编码求差，也不保存一个脱离两状态来源的计算结果。
    if (前.固定准确值==后.固定准确值) return 新交互求值状态::不符合;
    const 新特征准确值 对端{绑定.对端};
    if (特征.当前值!=std::optional<新特征准确值>{对端}
        &&std::find(特征.历史不同值.begin(),特征.历史不同值.end(),对端)==特征.历史不同值.end())
        return 新交互求值状态::尚未具备;
    return 新交互求值状态::已取得;
}
}
