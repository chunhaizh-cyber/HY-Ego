存在组成读取结果
存在类数据服务::读取当前组成父(const 存在组成父读取请求 &请求) const {
  存在组成读取结果 结果;
  if (!有效(请求.子存在))
    return 结果;
  try {
    L1所有者范围一致当前读取请求 读取请求;
    读取请求.所有者 = {所有者_};
    读取请求.节点 = {请求.子存在, 存在族锚点_, 存在族归属关系类型_};
    读取请求.源关系组 = {{请求.子存在, 存在族归属关系类型_}};
    读取请求.目标关系组 = {{请求.子存在, 子存在关系类型_}};
    const auto 读取 = 第一层服务_.尝试读取所有者范围一致当前投影(读取请求);
    if (读取.状态 != L1所有者范围一致当前读取状态::成功) {
      结果.状态 = 映射组合读取状态(读取.状态);
      return 结果;
    }
    const auto *身份组 = 查找源关系组(读取, 请求.子存在, 存在族归属关系类型_);
    const auto *父组 = 查找目标关系组(读取, 请求.子存在, 子存在关系类型_);
    const auto *子项 = 查找节点(读取, 请求.子存在);
    if (!身份组 || 身份组->成员.size() != 1 || !父组 || !子项 ||
        !子项->事实 || !普通存在节点(*子项->事实, 请求.子存在, 所有者_)) {
      结果.状态 = 存在结构身份只读状态::内部不一致;
      return 结果;
    }
    if (父组->成员.size() > 1) {
      结果.状态 = 存在结构身份只读状态::内部不一致;
      return 结果;
    }
    if (!父组->成员.empty()) {
      const auto &成员 = 父组->成员.front();
      const auto &关系 = 成员.关系;
      if (!有效(关系.编码) || 关系.目标节点 != 请求.子存在 ||
          关系.关系类型节点 != 子存在关系类型_ || 关系.角色或顺序 != 1 ||
          关系.写入所有者 != 所有者_ || 关系.源节点 == 请求.子存在 ||
          !普通存在节点(成员.对端节点, 关系.源节点, 所有者_)) {
        结果.状态 = 存在结构身份只读状态::内部不一致;
        return 结果;
      }
      结果.父 = 存在组成关系事实{关系.编码, 关系.源节点, 关系.目标节点};
    }
    结果.状态 = 存在结构身份只读状态::已读取;
  } catch (const std::bad_alloc &) {
    结果.状态 = 存在结构身份只读状态::资源失败;
  } catch (...) {
    结果.状态 = 存在结构身份只读状态::内部不一致;
  }
  return 结果;
}

存在组成读取结果
存在类数据服务::读取当前组成子组(const 存在组成子组读取请求 &请求) const {
  存在组成读取结果 结果;
  if (!有效(请求.父存在))
    return 结果;
  try {
    L1所有者范围一致当前读取请求 读取请求;
    读取请求.所有者 = {所有者_};
    读取请求.节点 = {请求.父存在, 存在族锚点_, 存在族归属关系类型_};
    读取请求.源关系组 = {{请求.父存在, 存在族归属关系类型_},
                          {请求.父存在, 子存在关系类型_}};
    const auto 读取 = 第一层服务_.尝试读取所有者范围一致当前投影(读取请求);
    if (读取.状态 != L1所有者范围一致当前读取状态::成功) {
      结果.状态 = 映射组合读取状态(读取.状态);
      return 结果;
    }
    const auto *身份组 = 查找源关系组(读取, 请求.父存在, 存在族归属关系类型_);
    const auto *子组 = 查找源关系组(读取, 请求.父存在, 子存在关系类型_);
    const auto *父项 = 查找节点(读取, 请求.父存在);
    if (!身份组 || 身份组->成员.size() != 1 || !子组 || !父项 ||
        !父项->事实 || !普通存在节点(*父项->事实, 请求.父存在, 所有者_)) {
      结果.状态 = 存在结构身份只读状态::内部不一致;
      return 结果;
    }
    for (const auto &成员 : 子组->成员) {
      const auto &关系 = 成员.关系;
      if (!有效(关系.编码) || 关系.源节点 != 请求.父存在 ||
          关系.关系类型节点 != 子存在关系类型_ || 关系.角色或顺序 != 1 ||
          关系.写入所有者 != 所有者_ || 关系.目标节点 == 请求.父存在 ||
          !普通存在节点(成员.对端节点, 关系.目标节点, 所有者_)) {
        结果.状态 = 存在结构身份只读状态::内部不一致;
        结果.子组.clear();
        return 结果;
      }
      结果.子组.push_back(
          存在组成关系事实{关系.编码, 关系.源节点, 关系.目标节点});
    }
    结果.状态 = 存在结构身份只读状态::已读取;
  } catch (const std::bad_alloc &) {
    结果.状态 = 存在结构身份只读状态::资源失败;
    结果.子组.clear();
  } catch (...) {
    结果.状态 = 存在结构身份只读状态::内部不一致;
    结果.子组.clear();
  }
  return 结果;
}

