存在身份来源当前见证读取结果
存在类数据服务::读取当前存在身份来源见证(稳定编码 身份) const {
  存在身份来源当前见证读取结果 结果;
  if (!有效(身份) || 身份 == 存在族锚点_ || 身份 == 存在族归属关系类型_)
    return 结果;
  try {
    L1所有者范围一致当前读取请求 请求;
    请求.所有者 = {所有者_};
    请求.节点 = {身份, 存在族锚点_, 存在族归属关系类型_};
    请求.源关系组 = {{身份, 存在族归属关系类型_}};
    const auto 读取 = 第一层服务_.尝试读取所有者范围一致当前投影(请求);
    if (读取.状态 != L1所有者范围一致当前读取状态::成功) {
      结果.状态 = 映射组合读取状态(读取.状态);
      return 结果;
    }
    if (读取.所有者.size() != 1 || 读取.节点.size() != 3 ||
        !读取.关系.empty() || !读取.值.empty() || !读取.属性值.empty() ||
        读取.源关系组.size() != 1 || !读取.目标关系组.empty()) {
      结果.状态 = 存在结构身份只读状态::内部不一致;
      return 结果;
    }
    const auto &所有者项 = 读取.所有者.front();
    if (所有者项.查询所有者 != 所有者_ ||
        所有者项.状态 != L1所有者范围一致当前读取项目状态::成功 ||
        !所有者项.所有者事实 || 所有者项.所有者事实->所有者 != 所有者_ ||
        所有者项.所有者事实->范围种类 != L1所有者范围种类::独占结构范围) {
      结果.状态 = 存在结构身份只读状态::内部不一致;
      return 结果;
    }
    const auto *身份项 = 查找节点(读取, 身份);
    if (!身份项 || 身份项->状态 == L1所有者范围一致当前读取项目状态::未找到) {
      结果.状态 = 存在结构身份只读状态::未找到;
      return 结果;
    }
    const auto *锚点项 = 查找节点(读取, 存在族锚点_);
    const auto *类型项 = 查找节点(读取, 存在族归属关系类型_);
    if (!身份项->事实 || !锚点项 || !锚点项->事实 || !类型项 ||
        !类型项->事实 || !普通存在节点(*身份项->事实, 身份, 所有者_) ||
        !普通存在节点(*锚点项->事实, 存在族锚点_, 所有者_) ||
        !普通存在节点(*类型项->事实, 存在族归属关系类型_, 所有者_)) {
      结果.状态 = 存在结构身份只读状态::内部不一致;
      return 结果;
    }
    const auto *关系组 = 查找源关系组(读取, 身份, 存在族归属关系类型_);
    if (!关系组 || 关系组->成员.empty()) {
      结果.状态 = 存在结构身份只读状态::未找到;
      return 结果;
    }
    if (关系组->成员.size() != 1) {
      结果.状态 = 存在结构身份只读状态::内部不一致;
      return 结果;
    }
    const auto &成员 = 关系组->成员.front();
    const auto &关系 = 成员.关系;
    if (!有效(关系.编码) || 关系.源节点 != 身份 ||
        关系.目标节点 != 存在族锚点_ ||
        关系.关系类型节点 != 存在族归属关系类型_ ||
        关系.角色或顺序 != 1 || 关系.写入所有者 != 所有者_ ||
        成员.对端节点 != *锚点项->事实) {
      结果.状态 = 存在结构身份只读状态::内部不一致;
      return 结果;
    }
    结果.状态 = 存在结构身份只读状态::已读取;
    结果.见证 = 存在身份来源当前见证{
        身份, 存在族锚点_, 存在族归属关系类型_, 关系.编码, 1};
    if (!结果.成功(身份)) {
      结果.状态 = 存在结构身份只读状态::内部不一致;
      结果.见证.reset();
    }
  } catch (const std::bad_alloc &) {
    结果.状态 = 存在结构身份只读状态::资源失败;
    结果.见证.reset();
  } catch (...) {
    结果.状态 = 存在结构身份只读状态::内部不一致;
    结果.见证.reset();
  }
  return 结果;
}

