const L1所有者范围一致节点读取结果项 *查找节点(
    const L1所有者范围一致当前读取结果 &读取, 稳定编码 编码) noexcept {
  const auto it = std::find_if(
      读取.节点.begin(), 读取.节点.end(),
      [编码](const auto &项) noexcept { return 项.查询编码 == 编码; });
  return it == 读取.节点.end() ? nullptr : &*it;
}

const L1所有者范围一致源关系组读取结果项 *查找源关系组(
    const L1所有者范围一致当前读取结果 &读取, 稳定编码 源,
    稳定编码 类型) noexcept {
  const auto it = std::find_if(
      读取.源关系组.begin(), 读取.源关系组.end(),
      [源, 类型](const auto &项) noexcept {
        return 项.源节点 == 源 && 项.关系类型节点 == 类型;
      });
  return it == 读取.源关系组.end() ? nullptr : &*it;
}

const L1所有者范围一致目标关系组读取结果项 *查找目标关系组(
    const L1所有者范围一致当前读取结果 &读取, 稳定编码 目标,
    稳定编码 类型) noexcept {
  const auto it = std::find_if(
      读取.目标关系组.begin(), 读取.目标关系组.end(),
      [目标, 类型](const auto &项) noexcept {
        return 项.目标节点 == 目标 && 项.关系类型节点 == 类型;
      });
  return it == 读取.目标关系组.end() ? nullptr : &*it;
}

bool 普通存在节点(const L1所有者范围节点事实 &节点, 稳定编码 编码,
                  L1结构所有者身份 所有者) noexcept {
  return 节点.编码 == 编码 && 节点.写入所有者 == 所有者 &&
         节点.种类 == 节点种类::普通 && !节点.属性类型表示 &&
         节点.当前属性.empty();
}

存在结构身份只读状态 映射组合读取状态(
    L1所有者范围一致当前读取状态 状态) noexcept {
  if (状态 == L1所有者范围一致当前读取状态::资源失败)
    return 存在结构身份只读状态::资源失败;
  if (状态 == L1所有者范围一致当前读取状态::入口拒绝 ||
      状态 == L1所有者范围一致当前读取状态::许可拒绝)
    return 存在结构身份只读状态::入口拒绝;
  return 存在结构身份只读状态::内部不一致;
}

