原子I64特征窄读取结果<原子I64特征holder事实>
存在类数据服务::读取原子I64holder(
    const 原子I64特征holder读取请求 &请求) const {
  原子I64特征窄读取结果<原子I64特征holder事实> 结果;
  if (!有效(请求.holder) || !有效(请求.F) || 请求.holder == 请求.F)
    return 结果;
  try {
    L1所有者范围一致当前读取请求 请求体;
    请求体.所有者 = {所有者_};
    请求体.节点 = {请求.holder};
    请求体.源关系组 = {{请求.holder, 特征关系类型_}};
    const auto 读取 = 第一层服务_.尝试读取所有者范围一致当前投影(请求体);
    if (读取.状态 == L1所有者范围一致当前读取状态::资源失败) {
      结果.状态 = 原子I64特征窄读取状态::资源失败;
      return 结果;
    }
    if (读取.状态 != L1所有者范围一致当前读取状态::成功 ||
        读取.节点.size() != 1 || 读取.源关系组.size() != 1) {
      结果.状态 = 读取.状态 == L1所有者范围一致当前读取状态::成功
                        ? 原子I64特征窄读取状态::内部不一致
                        : 原子I64特征窄读取状态::未找到;
      return 结果;
    }
    const auto *组 = 查找源关系组(读取, 请求.holder, 特征关系类型_);
    const L1所有者范围关系事实 *命中 = nullptr;
    if (!组) {
      结果.状态 = 原子I64特征窄读取状态::内部不一致;
      return 结果;
    }
    for (const auto &成员 : 组->成员) {
      const auto &关系 = 成员.关系;
      if (关系.目标节点 != 请求.F)
        continue;
      if (命中 || !有效(关系.编码) || 关系.源节点 != 请求.holder ||
          关系.关系类型节点 != 特征关系类型_ ||
          关系.写入所有者 != 所有者_ || 关系.角色或顺序 != 1) {
        结果.状态 = 原子I64特征窄读取状态::内部不一致;
        return 结果;
      }
      命中 = &关系;
    }
    if (!命中) {
      结果.状态 = 原子I64特征窄读取状态::未找到;
      return 结果;
    }
    结果.状态 = 原子I64特征窄读取状态::已读取;
    结果.事实 = 原子I64特征holder事实{
        请求.holder, 请求.F, 命中->编码, 命中->关系类型节点};
  } catch (const std::bad_alloc &) {
    结果.状态 = 原子I64特征窄读取状态::资源失败;
    结果.事实.reset();
  } catch (...) {
    结果.状态 = 原子I64特征窄读取状态::内部不一致;
    结果.事实.reset();
  }
  return 结果;
}

