void 存在类数据服务::接受存在族首次材料(
    const L1所有者范围首次写入读取结果 &首次) {
  const auto 期望 = 形成存在族初始化写集();
  if (首次.状态 != L1所有者范围读取状态::成功 ||
      首次.所有者 != 所有者_ ||
      首次.写入幂等身份 != 存在族来源初始化幂等身份 ||
      !首次.首次规范化写集 || *首次.首次规范化写集 != 期望 ||
      !首次.首次写入结果)
    throw std::logic_error("存在族首次材料无效");
  const auto &写入 = *首次.首次写入结果;
  if ((写入.状态 != L1所有者范围写入状态::成功 &&
       写入.状态 != L1所有者范围写入状态::精确重复) ||
      写入.所有者 != 所有者_ ||
      写入.写入幂等身份 != 存在族来源初始化幂等身份 ||
      写入.新编码映射.size() != 2)
    throw std::logic_error("存在族首次写入结果无效");

  auto 查找 = [&](L1所有者范围写集本地键 键) {
    稳定编码 输出{};
    for (const auto &[候选键, 编码] : 写入.新编码映射)
      if (候选键 == 键) {
        if (有效(输出))
          throw std::logic_error("存在族本地键重复");
        输出 = 编码;
      }
    return 输出;
  };
  const auto 锚点 = 查找({1});
  const auto 类型 = 查找({2});
  if (!有效(锚点) || !有效(类型) || 锚点 == 类型)
    throw std::logic_error("存在族编码映射无效");

  L1所有者范围一致当前读取请求 请求;
  请求.所有者 = {所有者_};
  请求.节点 = {锚点, 类型};
  const auto 读取 = 第一层服务_.尝试读取所有者范围一致当前投影(请求);
  if (读取.状态 != L1所有者范围一致当前读取状态::成功 ||
      读取.所有者.size() != 1 || 读取.节点.size() != 2 ||
      !读取.关系.empty() || !读取.值.empty() || !读取.属性值.empty() ||
      !读取.源关系组.empty() || !读取.目标关系组.empty())
    throw std::logic_error("存在族当前投影无效");
  const auto *锚点项 = 查找节点(读取, 锚点);
  const auto *类型项 = 查找节点(读取, 类型);
  if (!锚点项 || !锚点项->事实 || !类型项 || !类型项->事实 ||
      !普通存在节点(*锚点项->事实, 锚点, 所有者_) ||
      !普通存在节点(*类型项->事实, 类型, 所有者_))
    throw std::logic_error("存在族当前节点无效");
  存在族锚点_ = 锚点;
  存在族归属关系类型_ = 类型;
}

void 存在类数据服务::初始化存在族来源() {
  auto 首次 = 写入端口_.读取首次写入材料({存在族来源初始化幂等身份});
  if (首次.状态 == L1所有者范围读取状态::未找到) {
    const auto 写入 = 写入端口_.提交所有者范围中性写集(
        形成存在族初始化写集());
    if (写入.状态 == L1所有者范围写入状态::资源失败)
      throw std::runtime_error("存在族初始化资源失败");
    if (写入.状态 != L1所有者范围写入状态::成功 &&
        写入.状态 != L1所有者范围写入状态::精确重复)
      throw std::logic_error("存在族初始化写入失败");
    首次 = 写入端口_.读取首次写入材料({存在族来源初始化幂等身份});
  }
  if (首次.状态 == L1所有者范围读取状态::资源失败)
    throw std::runtime_error("存在族首次材料资源失败");
  接受存在族首次材料(首次);
}

