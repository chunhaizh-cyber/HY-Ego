#include "新_本能函数管理类.h"

#include <map>
#include <mutex>
#include <new>
#include <string>

namespace 海中鱼巣 {
namespace {

std::mutex 本能函数管理互斥;
std::map<std::string, 新本能函数, std::less<>> 本能函数登记表;
新本能网页对话函数端口 网页对话端口;

} // namespace

新本能函数登记状态 新_本能函数管理类::初始化() noexcept {
    const auto 读取登记 = 登记(
        新本能函数登记名_读取网页对话消息,
        &新_本能函数集::读取网页对话消息);
    if (读取登记 != 新本能函数登记状态::已登记
        && 读取登记 != 新本能函数登记状态::精确重复) {
        return 读取登记;
    }
    const auto 输入登记 = 登记(
        新本能函数登记名_设置网页对话输入文本,
        &新_本能函数集::设置网页对话输入文本);
    if (输入登记 != 新本能函数登记状态::已登记
        && 输入登记 != 新本能函数登记状态::精确重复) {
        return 输入登记;
    }
    const auto 提交登记 = 登记(
        新本能函数登记名_提交网页对话消息,
        &新_本能函数集::提交网页对话消息);
    if (提交登记 != 新本能函数登记状态::已登记
        && 提交登记 != 新本能函数登记状态::精确重复) {
        return 提交登记;
    }
    return 读取登记 == 新本能函数登记状态::精确重复
            && 输入登记 == 新本能函数登记状态::精确重复
            && 提交登记 == 新本能函数登记状态::精确重复
        ? 新本能函数登记状态::精确重复
        : 新本能函数登记状态::已登记;
}

新本能函数端口装配状态 新_本能函数管理类::装配网页对话端口(
    const 新本能网页对话函数端口& 端口) noexcept {
    if (!端口.读取已显示消息 || !端口.设置输入框文本 || !端口.提交消息) {
        return 新本能函数端口装配状态::入口拒绝;
    }
    try {
        std::lock_guard 锁(本能函数管理互斥);
        if (网页对话端口.读取已显示消息
            || 网页对话端口.设置输入框文本
            || 网页对话端口.提交消息) {
            return 网页对话端口 == 端口
                ? 新本能函数端口装配状态::精确重复
                : 新本能函数端口装配状态::所有者冲突;
        }
        网页对话端口 = 端口;
        return 新本能函数端口装配状态::已装配;
    } catch (...) {
        return 新本能函数端口装配状态::内部错误;
    }
}

新本能函数登记状态 新_本能函数管理类::登记(
    std::string_view 登记名,
    新本能函数 函数) noexcept {
    if (登记名.empty() || !函数) return 新本能函数登记状态::入口拒绝;
    try {
        std::lock_guard 锁(本能函数管理互斥);
        const auto 已有 = 本能函数登记表.find(登记名);
        if (已有 != 本能函数登记表.end()) {
            return 已有->second == 函数
                ? 新本能函数登记状态::精确重复
                : 新本能函数登记状态::登记名冲突;
        }
        本能函数登记表.emplace(std::string(登记名), 函数);
        return 新本能函数登记状态::已登记;
    } catch (const std::bad_alloc&) {
        return 新本能函数登记状态::资源失败;
    } catch (...) {
        return 新本能函数登记状态::内部错误;
    }
}

新本能函数解析结果 新_本能函数管理类::解析(
    std::string_view 登记名) noexcept {
    if (登记名.empty()) return {};
    try {
        std::lock_guard 锁(本能函数管理互斥);
        const auto 已有 = 本能函数登记表.find(登记名);
        if (已有 == 本能函数登记表.end()) {
            return {新本能函数解析状态::未登记, nullptr};
        }
        return {新本能函数解析状态::已解析, 已有->second};
    } catch (...) {
        return {新本能函数解析状态::内部错误, nullptr};
    }
}

新本能函数可用状态 新_本能函数管理类::检查可用(
    std::string_view 登记名) noexcept {
    if (登记名.empty()) return 新本能函数可用状态::入口拒绝;
    try {
        std::lock_guard 锁(本能函数管理互斥);
        const auto 已有 = 本能函数登记表.find(登记名);
        if (已有 == 本能函数登记表.end() || !已有->second) {
            return 新本能函数可用状态::未登记;
        }
        if (登记名 == 新本能函数登记名_读取网页对话消息
            && !网页对话端口.读取已显示消息) {
            return 新本能函数可用状态::依赖未装配;
        }
        if (登记名 == 新本能函数登记名_设置网页对话输入文本
            && !网页对话端口.设置输入框文本) {
            return 新本能函数可用状态::依赖未装配;
        }
        if (登记名 == 新本能函数登记名_提交网页对话消息
            && !网页对话端口.提交消息) {
            return 新本能函数可用状态::依赖未装配;
        }
        return 新本能函数可用状态::可调用;
    } catch (...) {
        return 新本能函数可用状态::内部错误;
    }
}

新本能函数执行结果 新_本能函数管理类::执行(
    std::string_view 登记名,
    const 方法参数场景& 参数场景) noexcept {
    const auto 解析结果 = 解析(登记名);
    if (!解析结果.函数) {
        return {解析结果.状态 == 新本能函数解析状态::内部错误
                ? 新本能函数执行状态::内部错误
                : 新本能函数执行状态::函数未登记,
            新本能函数动作阶段::未进入动作};
    }
    return 解析结果.函数(参数场景);
}

新本能函数执行结果 新_本能函数管理类::调用网页对话入口(
    网页对话入口 入口,
    const 方法参数场景& 参数场景) noexcept {
    新本能函数 函数 = nullptr;
    try {
        {
            std::lock_guard 锁(本能函数管理互斥);
            switch (入口) {
            case 网页对话入口::读取已显示消息:
                函数 = 网页对话端口.读取已显示消息;
                break;
            case 网页对话入口::设置输入框文本:
                函数 = 网页对话端口.设置输入框文本;
                break;
            case 网页对话入口::提交消息:
                函数 = 网页对话端口.提交消息;
                break;
            }
        }
        if (!函数) return {新本能函数执行状态::依赖未装配,
            新本能函数动作阶段::未进入动作};
        return 函数(参数场景);
    } catch (...) {
        return {新本能函数执行状态::内部错误,
            新本能函数动作阶段::未进入动作};
    }
}

} // namespace 海中鱼巣
