新本能函数端口装配状态 新_本能函数管理类::装配服务需求获取端口(
    std::shared_ptr<新服务需求获取本能端口> 端口) noexcept {
    if (!端口) return 新本能函数端口装配状态::入口拒绝;
    try {
        std::lock_guard 锁(本能函数管理互斥);
        if (服务需求获取端口) return 服务需求获取端口 == 端口
            ? 新本能函数端口装配状态::精确重复 : 新本能函数端口装配状态::所有者冲突;
        // 关闭后旧调用或调用者仍持有owner时，不允许另一个owner顶替它。
        if (!退役服务需求获取端口.expired()) return 新本能函数端口装配状态::存在活动调用;
        服务需求获取端口 = std::move(端口);
        return 新本能函数端口装配状态::已装配;
    } catch (...) { return 新本能函数端口装配状态::内部错误; }
}
