新本能函数端口装配状态 新_本能函数管理类::装配连接端口(
    std::shared_ptr<新连接本能端口> 端口) noexcept {
    if (!端口) return 新本能函数端口装配状态::入口拒绝;
    try {
        std::lock_guard 锁(本能函数管理互斥);
        if (连接端口) return 连接端口 == 端口
            ? 新本能函数端口装配状态::精确重复
            : 新本能函数端口装配状态::所有者冲突;
        if (!退役连接端口.expired())
            return 新本能函数端口装配状态::存在活动调用;
        连接端口 = std::move(端口);
        return 新本能函数端口装配状态::已装配;
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"装配连接端口", L"端口装配异常。");
    }
}

新本能函数端口装配状态 新_本能函数管理类::关闭连接端口(
    新连接本能端口& 端口) noexcept {
    std::shared_ptr<新连接本能端口> 待释放;
    try {
        {
            std::lock_guard 锁(本能函数管理互斥);
            if (连接端口.get() != &端口)
                return 新本能函数端口装配状态::所有者冲突;
            退役连接端口 = 连接端口;
            待释放 = std::move(连接端口);
        }
        return 新本能函数端口装配状态::已关闭;
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"关闭连接端口", L"端口关闭异常。");
    }
}

