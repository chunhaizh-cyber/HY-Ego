概念_二次特征类::概念_二次特征类(
    概念_特征类& 特征概念服务,
    const 新_特征值类& 特征值服务) noexcept
    : 特征概念服务_(特征概念服务), 特征值服务_(特征值服务) {}

bool 概念_二次特征类::初始化() noexcept {
    try {
        std::lock_guard 锁(二次特征概念互斥);
        if (结构已初始化()) return 结构仍存在();
        auto 建立 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        return 建立(辅助节点类型字段)
            && 建立(派生定义节点类型)
            && 建立(输入定义节点类型)
            && 建立(派生定义字段)
            && 建立(算法字段)
            && 建立(输入定义项字段)
            && 建立(顺序字段)
            && 建立(输入角色字段)
            && 建立(输入来源种类字段)
            && 建立(输入特征概念字段)
            && 建立(纳秒单位节点);
    } catch (...) {
        return false;
    }
}

std::optional<稳定编码> 概念_二次特征类::获取纳秒单位节点() const noexcept {
    try {
        std::lock_guard 锁(二次特征概念互斥);
        return 结构仍存在()
            ? std::optional<稳定编码>{纳秒单位节点} : std::nullopt;
    } catch (...) {
        return std::nullopt;
    }
}

二次特征概念建立结果 概念_二次特征类::建立或取得二次特征概念(
    const 二次特征概念定义& 定义) noexcept {
    二次特征概念建立结果 结果;
    try {
        std::lock_guard 锁(二次特征概念互斥);
        if (!结构仍存在()) return 结果;
        const auto 输入定义组 = 规范化输入定义(定义.输入定义组);
        if (!输入定义组) {
            结果.状态 = 二次特征概念操作状态::输入定义不合法;
            return 结果;
        }
        const auto 校验 = 校验定义(定义, *输入定义组, 特征概念服务_);
        if (校验 != 二次特征概念操作状态::已找到) {
            结果.状态 = 校验;
            return 结果;
        }

        std::vector<稳定编码> 相同定义;
        for (const auto 候选 : 特征概念服务_.查询特征概念(
            定义.输出特征定义)) {
            const auto 派生 = 读取直接派生定义(候选, 特征概念服务_);
            if (派生 && 派生->first == 定义.算法
                && 派生->second == *输入定义组) 相同定义.push_back(候选);
        }
        if (相同定义.size() > 1) {
            结果.状态 = 二次特征概念操作状态::结构不一致;
            return 结果;
        }
        if (相同定义.size() == 1) {
            结果.状态 = 二次特征概念操作状态::已复用;
            结果.概念节点 = 相同定义.front();
            return 结果;
        }

        auto 派生节点 = 建立派生定义节点(定义.算法, *输入定义组);
        if (!派生节点) {
            结果.状态 = 二次特征概念操作状态::资源失败;
            return 结果;
        }
        const auto 概念节点 = 特征概念服务_.建立或取得特征概念(
            定义.输出特征定义, 特征值服务_);
        if (!有效(概念节点)) {
            清理辅助节点组(派生节点->second);
            结果.状态 = 二次特征概念操作状态::输出定义不合法;
            return 结果;
        }
        const auto 持有字段 = 全局基础数据集.添加字段节点(
            概念节点, 派生定义字段, 派生节点->first);
        if (!有效(持有字段)) {
            清理辅助节点组(派生节点->second);
            结果.状态 = 二次特征概念操作状态::资源失败;
            return 结果;
        }
        const auto 读回 = 获取二次特征概念(概念节点);
        if (!读回 || 读回->二次特征类型根节点 != 概念节点
            || 读回->算法 != 定义.算法
            || 读回->输入定义组 != *输入定义组) {
            (void)全局基础数据集.删除字段(持有字段);
            清理辅助节点组(派生节点->second);
            结果.状态 = 二次特征概念操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 二次特征概念操作状态::已建立;
        结果.概念节点 = 概念节点;
        return 结果;
    } catch (...) {
        结果.状态 = 二次特征概念操作状态::资源失败;
        return 结果;
    }
}

二次特征概念建立结果 概念_二次特征类::建立或取得结果值域概念(
    稳定编码 上位二次特征概念节点,
    const 特征概念值域& 结果值域,
    const std::vector<稳定编码>& 名称关系) noexcept {
    二次特征概念建立结果 结果;
    try {
        std::lock_guard 锁(二次特征概念互斥);
        const auto 上位 = 获取二次特征概念(上位二次特征概念节点);
        if (!上位) {
            结果.状态 = 二次特征概念操作状态::概念不存在;
            return 结果;
        }
        特征概念定义 定义;
        定义.材料类型 = 上位->输出特征概念.材料类型;
        定义.值域 = 结果值域;
        定义.单位 = 上位->输出特征概念.单位;
        定义.比较规则 = 上位->输出特征概念.比较规则;
        定义.聚合规则 = 上位->输出特征概念.聚合规则;
        定义.名称关系 = 名称关系;
        bool 已存在 = false;
        for (const auto 候选 : 特征概念服务_.查询特征概念(定义)) {
            const auto 父关系 = 全局基础数据集.查询目标关系(
                候选, 基础外部关系类型::父子);
            if (父关系.size() == 1
                && 父关系.front().源节点 == 上位二次特征概念节点) {
                已存在 = true;
                break;
            }
        }
        const auto 节点 = 特征概念服务_.建立或取得特征概念(
            定义, 特征值服务_, 上位二次特征概念节点);
        if (!有效(节点)) {
            结果.状态 = 二次特征概念操作状态::值域不合法;
            return 结果;
        }
        const auto 读回 = 获取二次特征概念(节点);
        if (!读回
            || 读回->二次特征类型根节点 != 上位->二次特征类型根节点) {
            结果.状态 = 二次特征概念操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 已存在
            ? 二次特征概念操作状态::已复用
            : 二次特征概念操作状态::已建立;
        结果.概念节点 = 节点;
        return 结果;
    } catch (...) {
        结果.状态 = 二次特征概念操作状态::资源失败;
        return 结果;
    }
}

std::optional<二次特征概念信息> 概念_二次特征类::获取二次特征概念(
    稳定编码 概念节点) const noexcept {
    try {
        std::lock_guard 锁(二次特征概念互斥);
        if (!结构仍存在() || !有效(概念节点)) return std::nullopt;
        const auto 输出概念 = 特征概念服务_.获取特征概念(概念节点);
        const auto 类型根 = 查找派生类型根(概念节点, 特征概念服务_);
        if (!输出概念 || !类型根) return std::nullopt;
        const auto 派生 = 读取直接派生定义(*类型根, 特征概念服务_);
        if (!派生) return std::nullopt;
        return 二次特征概念信息{
            概念节点, *类型根, *输出概念, 派生->first, 派生->second};
    } catch (...) {
        return std::nullopt;
    }
}

bool 概念_二次特征类::是二次特征概念(稳定编码 概念节点) const noexcept {
    return 获取二次特征概念(概念节点).has_value();
}

二次特征概念查找结果 概念_二次特征类::查找结果对应最具体概念(
    稳定编码 二次特征类型根节点,
    std::int64_t 准确结果) const noexcept {
    二次特征概念查找结果 结果;
    try {
        std::lock_guard 锁(二次特征概念互斥);
        const auto 信息 = 获取二次特征概念(二次特征类型根节点);
        if (!信息 || 信息->二次特征类型根节点 != 二次特征类型根节点) {
            结果.状态 = 二次特征概念操作状态::概念不存在;
            return 结果;
        }
        const auto 查找 = 特征概念服务_.查找值对应的最具体概念(
            二次特征类型根节点, 特征概念准确值{准确结果},
            信息->输出特征概念.单位, 特征值服务_);
        if (查找.状态 == 特征概念查找状态::已找到
            && 查找.概念节点) {
            结果.状态 = 二次特征概念操作状态::已找到;
            结果.概念节点 = *查找.概念节点;
            return 结果;
        }
        if (查找.状态 == 特征概念查找状态::未找到) {
            结果.状态 = 二次特征概念操作状态::未找到;
            return 结果;
        }
        结果.状态 = 二次特征概念操作状态::结构不一致;
        return 结果;
    } catch (...) {
        结果.状态 = 二次特征概念操作状态::资源失败;
        return 结果;
    }
}

