bool 概念_二次特征类::初始化() noexcept {
    try {
        std::lock_guard 锁(二次特征概念互斥);
        if (结构已初始化()) return 结构仍存在();
        auto 建立 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        return 建立(辅助节点类型字段)
            && 建立(派生定义节点类型)
            && 建立(输入定义节点类型)
            && 建立(派生定义字段)
            && 建立(算法字段)
            && 建立(输入定义项字段)
            && 建立(顺序字段)
            && 建立(输入角色字段)
            && 建立(输入来源种类字段)
            && 建立(输入特征概念字段)
            && 建立(参照特征概念字段)
            && 建立(结果域种类字段)
            && 建立(纳秒单位节点);
    } catch (...) {
        return false;
    }
}

