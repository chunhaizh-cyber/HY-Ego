bool 节点仍存在(稳定编码 节点) noexcept {
    return 有效(节点) && 全局基础数据集.查询节点(节点).has_value();
}

bool 结构已初始化() noexcept {
    return 有效(辅助节点类型字段)
        && 有效(派生定义节点类型)
        && 有效(输入定义节点类型)
        && 有效(派生定义字段)
        && 有效(算法字段)
        && 有效(输入定义项字段)
        && 有效(顺序字段)
        && 有效(输入角色字段)
        && 有效(输入来源种类字段)
        && 有效(输入特征概念字段)
        && 有效(参照特征概念字段)
        && 有效(结果域种类字段)
        && 有效(纳秒单位节点);
}

bool 结构仍存在() noexcept {
    return 结构已初始化()
        && 节点仍存在(辅助节点类型字段)
        && 节点仍存在(派生定义节点类型)
        && 节点仍存在(输入定义节点类型)
        && 节点仍存在(派生定义字段)
        && 节点仍存在(算法字段)
        && 节点仍存在(输入定义项字段)
        && 节点仍存在(顺序字段)
        && 节点仍存在(输入角色字段)
        && 节点仍存在(输入来源种类字段)
        && 节点仍存在(输入特征概念字段)
        && 节点仍存在(参照特征概念字段)
        && 节点仍存在(结果域种类字段)
        && 节点仍存在(纳秒单位节点);
}

std::optional<稳定编码> 读取唯一节点字段(
    稳定编码 节点, 稳定编码 字段) {
    const auto 字段组 = 全局基础数据集.查询字段(节点, 字段);
    if (字段组.size() != 1) return std::nullopt;
    const auto* 目标 = std::get_if<稳定编码>(&字段组.front().内容);
    return 目标 && 节点仍存在(*目标)
        ? std::optional<稳定编码>{*目标} : std::nullopt;
}

std::optional<std::int64_t> 读取唯一I64字段(
    稳定编码 节点, 稳定编码 字段) {
    const auto 字段组 = 全局基础数据集.查询字段(节点, 字段);
    if (字段组.size() != 1) return std::nullopt;
    const auto* 值 = std::get_if<基础值>(&字段组.front().内容);
    const auto* I64 = 值 ? std::get_if<std::int64_t>(&值->材料) : nullptr;
    return I64 ? std::optional<std::int64_t>{*I64} : std::nullopt;
}

std::optional<std::vector<二次特征概念输入定义>> 规范化输入定义(
    const std::vector<二次特征概念输入定义>& 输入定义组) {
    if (输入定义组.size() != 2) return std::nullopt;
    auto 结果 = 输入定义组;
    std::sort(结果.begin(), 结果.end(), [](const auto& 左, const auto& 右) {
        return 左.顺序 < 右.顺序;
    });
    if (结果[0].顺序 != 0 || 结果[1].顺序 != 1) {
        return std::nullopt;
    }
    const bool 准确输入角色 = 结果[0].角色 == 二次特征输入角色::左输入
        && 结果[1].角色 == 二次特征输入角色::右输入;
    const bool 变化输入角色 = 结果[0].角色 == 二次特征输入角色::参照变化
        && 结果[1].角色 == 二次特征输入角色::目标变化;
    if (!准确输入角色 && !变化输入角色) return std::nullopt;
    for (const auto& 输入 : 结果) {
        if (输入.来源种类 == 二次特征输入来源种类::特征准确值
            || 输入.来源种类 == 二次特征输入来源种类::特征变化) {
            if (!输入.特征类型概念节点
                || !有效(*输入.特征类型概念节点)) return std::nullopt;
        } else if (输入.来源种类 == 二次特征输入来源种类::强时间
            || 输入.来源种类 == 二次特征输入来源种类::时间变化) {
            if (输入.特征类型概念节点) return std::nullopt;
        } else if (输入.来源种类
            == 二次特征输入来源种类::状态出现时间) {
            if (!输入.特征类型概念节点
                || !有效(*输入.特征类型概念节点)) return std::nullopt;
        } else {
            return std::nullopt;
        }
    }
    return 结果;
}

std::optional<稳定编码> 取得特征类型根(
    稳定编码 概念节点, 概念_特征类& 特征概念服务) {
    const auto 定位 = 特征概念服务.比较单特征概念(概念节点, 概念节点);
    return 定位.状态 == 特征概念规则状态::已完成
        ? 定位.特征类型根 : std::nullopt;
}

bool I64值域位于相似度范围(const 特征概念值域& 值域) {
    const auto* 区间组 = std::get_if<std::vector<特征概念I64闭区间>>(&值域);
    if (!区间组 || 区间组->empty()) return false;
    return std::all_of(区间组->begin(), 区间组->end(), [](const auto& 区间) {
        return 区间.下界 >= 0 && 区间.上界 <= 10000;
    });
}

二次特征概念操作状态 校验定义(
    const 二次特征概念定义& 定义,
    const std::vector<二次特征概念输入定义>& 输入定义组,
    概念_特征类& 特征概念服务) {
    if (定义.输出特征定义.材料类型
            != 特征概念材料物理类型::I64标量
        || 定义.输出特征定义.比较规则
            != 特征概念比较规则::I64数值) {
        return 二次特征概念操作状态::输出定义不合法;
    }
    if (定义.参照特征概念节点) {
        const auto 参照 = 特征概念服务.获取特征概念(
            *定义.参照特征概念节点);
        if (!参照 || 参照->材料类型 != 特征概念材料物理类型::I64标量
            || 参照->单位 != 定义.输出特征定义.单位) {
            return 二次特征概念操作状态::输入定义不合法;
        }
    }

    if (定义.算法 == 二次特征算法::强时间间隔) {
        return 输入定义组[0].角色 == 二次特征输入角色::左输入
            && 输入定义组[1].角色 == 二次特征输入角色::右输入
            && 输入定义组[0].来源种类 == 二次特征输入来源种类::强时间
            && 输入定义组[1].来源种类 == 二次特征输入来源种类::强时间
            && 定义.输出特征定义.单位 == 纳秒单位节点
            ? 二次特征概念操作状态::已找到
            : 二次特征概念操作状态::输入定义不合法;
    }
    if (定义.算法 == 二次特征算法::状态出现时间间隔) {
        if (输入定义组[0].角色 != 二次特征输入角色::左输入
            || 输入定义组[1].角色 != 二次特征输入角色::右输入
            || 输入定义组[0].来源种类
                != 二次特征输入来源种类::状态出现时间
            || 输入定义组[1].来源种类
                != 二次特征输入来源种类::状态出现时间
            || !输入定义组[0].特征类型概念节点
            || !输入定义组[1].特征类型概念节点
            || 定义.输出特征定义.单位 != 纳秒单位节点) {
            return 二次特征概念操作状态::输入定义不合法;
        }
        const auto 左根 = 取得特征类型根(
            *输入定义组[0].特征类型概念节点, 特征概念服务);
        const auto 右根 = 取得特征类型根(
            *输入定义组[1].特征类型概念节点, 特征概念服务);
        if (!左根 || !右根) {
            return 二次特征概念操作状态::特征概念不存在;
        }
        return *左根 != *右根
            ? 二次特征概念操作状态::已找到
            : 二次特征概念操作状态::算法不适用;
    }
    if (定义.算法 == 二次特征算法::跨特征类型单位变化) {
        if (输入定义组[0].角色 != 二次特征输入角色::参照变化
            || 输入定义组[1].角色 != 二次特征输入角色::目标变化) {
            return 二次特征概念操作状态::输入定义不合法;
        }
        for (const auto& 输入 : 输入定义组) {
            if (输入.来源种类 == 二次特征输入来源种类::特征变化) {
                if (!输入.特征类型概念节点) {
                    return 二次特征概念操作状态::输入定义不合法;
                }
                const auto 特征 = 特征概念服务.获取特征概念(
                    *输入.特征类型概念节点);
                if (!特征 || 特征->材料类型
                        != 特征概念材料物理类型::I64标量) {
                    return 二次特征概念操作状态::算法不适用;
                }
            } else if (输入.来源种类
                != 二次特征输入来源种类::时间变化) {
                return 二次特征概念操作状态::输入定义不合法;
            }
        }
        if (输入定义组[0].来源种类 == 输入定义组[1].来源种类
            && 输入定义组[0].特征类型概念节点
                == 输入定义组[1].特征类型概念节点) {
            return 二次特征概念操作状态::算法不适用;
        }
        return !定义.输出特征定义.单位
            ? 二次特征概念操作状态::已找到
            : 二次特征概念操作状态::算法不适用;
    }
    if (定义.算法 != 二次特征算法::有向特征差值
        && 定义.算法 != 二次特征算法::特征材料相似度) {
        return 二次特征概念操作状态::算法不适用;
    }
    if (输入定义组[0].角色 != 二次特征输入角色::左输入
        || 输入定义组[1].角色 != 二次特征输入角色::右输入
        || 输入定义组[0].来源种类 != 二次特征输入来源种类::特征准确值
        || 输入定义组[1].来源种类 != 二次特征输入来源种类::特征准确值
        || !输入定义组[0].特征类型概念节点
        || !输入定义组[1].特征类型概念节点) {
        return 二次特征概念操作状态::输入定义不合法;
    }
    const auto 左根 = 取得特征类型根(
        *输入定义组[0].特征类型概念节点, 特征概念服务);
    const auto 右根 = 取得特征类型根(
        *输入定义组[1].特征类型概念节点, 特征概念服务);
    if (!左根 || !右根) {
        return 二次特征概念操作状态::特征概念不存在;
    }
    if (*左根 != *右根) return 二次特征概念操作状态::算法不适用;
    const auto 左概念 = 特征概念服务.获取特征概念(
        *输入定义组[0].特征类型概念节点);
    const auto 右概念 = 特征概念服务.获取特征概念(
        *输入定义组[1].特征类型概念节点);
    if (!左概念 || !右概念) {
        return 二次特征概念操作状态::特征概念不存在;
    }
    if (左概念->材料类型 != 右概念->材料类型
        || 左概念->单位 != 右概念->单位) {
        return 二次特征概念操作状态::算法不适用;
    }
    if (定义.算法 == 二次特征算法::有向特征差值) {
        return 左概念->材料类型 == 特征概念材料物理类型::I64标量
            && 定义.输出特征定义.单位 == 左概念->单位
            ? 二次特征概念操作状态::已找到
            : 二次特征概念操作状态::算法不适用;
    }
    return 左概念->材料类型 != 特征概念材料物理类型::I64标量
        && !定义.输出特征定义.单位
        && I64值域位于相似度范围(定义.输出特征定义.值域)
        ? 二次特征概念操作状态::已找到
        : 二次特征概念操作状态::算法不适用;
}

struct 已建辅助节点 final {
    稳定编码 节点;
    std::vector<稳定编码> 字段组;
};

void 清理辅助节点组(std::vector<已建辅助节点>& 节点组) noexcept {
    for (auto 位置 = 节点组.rbegin(); 位置 != 节点组.rend(); ++位置) {
        for (auto 字段 = 位置->字段组.rbegin(); 字段 != 位置->字段组.rend(); ++字段) {
            (void)全局基础数据集.删除字段(*字段);
        }
    }
    for (auto 位置 = 节点组.rbegin(); 位置 != 节点组.rend(); ++位置) {
        (void)全局基础数据集.删除节点(位置->节点);
    }
    节点组.clear();
}

std::optional<std::pair<稳定编码, std::vector<已建辅助节点>>> 建立派生定义节点(
    二次特征算法 算法,
    const std::vector<二次特征概念输入定义>& 输入定义组,
    std::optional<稳定编码> 参照特征概念节点) {
    std::vector<已建辅助节点> 已建;
    已建.push_back({全局基础数据集.新建节点(), {}});
    if (!有效(已建.back().节点)) return std::nullopt;
    const auto 定义节点 = 已建.back().节点;
    auto 写I64 = [&](已建辅助节点& 节点, 稳定编码 字段, std::int64_t 值) {
        const auto 关系 = 全局基础数据集.添加字段值(
            节点.节点, 字段, 基础值{基础原始值{值}});
        if (有效(关系)) 节点.字段组.push_back(关系);
        return 有效(关系);
    };
    auto 写节点 = [&](已建辅助节点& 节点, 稳定编码 字段, 稳定编码 目标) {
        const auto 关系 = 全局基础数据集.添加字段节点(节点.节点, 字段, 目标);
        if (有效(关系)) 节点.字段组.push_back(关系);
        return 有效(关系);
    };
    if (!写节点(已建.front(), 辅助节点类型字段, 派生定义节点类型)
        || !写I64(已建.front(), 算法字段, static_cast<std::int64_t>(算法))) {
        清理辅助节点组(已建);
        return std::nullopt;
    }
    if (参照特征概念节点
        && !写节点(已建.front(), 参照特征概念字段,
            *参照特征概念节点)) {
        清理辅助节点组(已建);
        return std::nullopt;
    }
    for (const auto& 输入 : 输入定义组) {
        已建.push_back({全局基础数据集.新建节点(), {}});
        if (!有效(已建.back().节点)) {
            已建.pop_back();
            清理辅助节点组(已建);
            return std::nullopt;
        }
        auto& 项 = 已建.back();
        bool 完成 = 写节点(项, 辅助节点类型字段, 输入定义节点类型)
            && 写I64(项, 顺序字段, 输入.顺序)
            && 写I64(项, 输入角色字段, static_cast<std::int64_t>(输入.角色))
            && 写I64(项, 输入来源种类字段,
                static_cast<std::int64_t>(输入.来源种类));
        if (完成 && 输入.特征类型概念节点) {
            完成 = 写节点(项, 输入特征概念字段,
                *输入.特征类型概念节点);
        }
        if (完成) {
            完成 = 写节点(已建.front(), 输入定义项字段, 项.节点);
        }
        if (!完成) {
            清理辅助节点组(已建);
            return std::nullopt;
        }
    }
    return std::pair{定义节点, std::move(已建)};
}

struct 派生定义读回 final {
    二次特征算法 算法 = 二次特征算法::有向特征差值;
    std::vector<二次特征概念输入定义> 输入定义组;
    std::optional<稳定编码> 参照特征概念节点;
};

std::optional<派生定义读回> 读取直接派生定义(
    稳定编码 特征概念节点,
    概念_特征类& 特征概念服务) {
    if (!特征概念服务.是特征概念节点(特征概念节点)) return std::nullopt;
    const auto 派生字段组 = 全局基础数据集.查询字段(
        特征概念节点, 派生定义字段);
    if (派生字段组.size() != 1) return std::nullopt;
    const auto* 定义节点 = std::get_if<稳定编码>(&派生字段组.front().内容);
    if (!定义节点 || !节点仍存在(*定义节点)) return std::nullopt;
    const auto 类型 = 读取唯一节点字段(*定义节点, 辅助节点类型字段);
    const auto 算法值 = 读取唯一I64字段(*定义节点, 算法字段);
    if (!类型 || *类型 != 派生定义节点类型 || !算法值) return std::nullopt;
    const auto 算法 = static_cast<二次特征算法>(*算法值);
    if (算法 != 二次特征算法::有向特征差值
        && 算法 != 二次特征算法::特征材料相似度
        && 算法 != 二次特征算法::强时间间隔
        && 算法 != 二次特征算法::跨特征类型单位变化
        && 算法 != 二次特征算法::状态出现时间间隔) return std::nullopt;

    std::optional<稳定编码> 参照特征概念节点;
    const auto 参照字段组 = 全局基础数据集.查询字段(
        *定义节点, 参照特征概念字段);
    if (参照字段组.size() > 1) return std::nullopt;
    if (参照字段组.size() == 1) {
        const auto* 参照 = std::get_if<稳定编码>(&参照字段组.front().内容);
        if (!参照 || !特征概念服务.是特征概念节点(*参照)) {
            return std::nullopt;
        }
        参照特征概念节点 = *参照;
    }

    std::vector<二次特征概念输入定义> 输入定义组;
    for (const auto& 持有 : 全局基础数据集.查询字段(
        *定义节点, 输入定义项字段)) {
        const auto* 项节点 = std::get_if<稳定编码>(&持有.内容);
        if (!项节点 || !节点仍存在(*项节点)) return std::nullopt;
        const auto 项类型 = 读取唯一节点字段(*项节点, 辅助节点类型字段);
        const auto 顺序 = 读取唯一I64字段(*项节点, 顺序字段);
        const auto 角色 = 读取唯一I64字段(*项节点, 输入角色字段);
        const auto 来源 = 读取唯一I64字段(*项节点, 输入来源种类字段);
        if (!项类型 || *项类型 != 输入定义节点类型
            || !顺序 || !角色 || !来源) return std::nullopt;
        二次特征概念输入定义 输入;
        输入.顺序 = *顺序;
        输入.角色 = static_cast<二次特征输入角色>(*角色);
        输入.来源种类 = static_cast<二次特征输入来源种类>(*来源);
        const auto 特征字段组 = 全局基础数据集.查询字段(
            *项节点, 输入特征概念字段);
        if (特征字段组.size() > 1) return std::nullopt;
        if (特征字段组.size() == 1) {
            const auto* 目标 = std::get_if<稳定编码>(&特征字段组.front().内容);
            if (!目标 || !特征概念服务.是特征概念节点(*目标)) {
                return std::nullopt;
            }
            输入.特征类型概念节点 = *目标;
        }
        输入定义组.push_back(输入);
    }
    const auto 规范输入 = 规范化输入定义(输入定义组);
    return 规范输入
        ? std::optional{派生定义读回{算法, *规范输入, 参照特征概念节点}}
        : std::nullopt;
}

std::optional<稳定编码> 查找派生类型根(
    稳定编码 概念节点,
    概念_特征类& 特征概念服务) {
    稳定编码 当前 = 概念节点;
    while (特征概念服务.是特征概念节点(当前)) {
        if (读取直接派生定义(当前, 特征概念服务)) return 当前;
        const auto 父关系 = 全局基础数据集.查询目标关系(
            当前, 基础外部关系类型::父子);
        if (父关系.size() != 1) return std::nullopt;
        当前 = 父关系.front().源节点;
    }
    return std::nullopt;
}

using I64区间组 = std::vector<特征概念I64闭区间>;

std::optional<I64区间组> 读取I64值域(const 特征概念信息& 信息) {
    if (信息.材料类型 != 特征概念材料物理类型::I64标量) {
        return std::nullopt;
    }
    const auto* 区间组 = std::get_if<I64区间组>(&信息.值域);
    return 区间组 && !区间组->empty()
        ? std::optional<I64区间组>{*区间组} : std::nullopt;
}

I64区间组 取交集(const I64区间组& 左, const I64区间组& 右) {
    I64区间组 结果;
    for (const auto& 左区间 : 左) {
        for (const auto& 右区间 : 右) {
            const auto 下界 = (std::max)(左区间.下界, 右区间.下界);
            const auto 上界 = (std::min)(左区间.上界, 右区间.上界);
            if (下界 <= 上界) 结果.push_back({下界, 上界});
        }
    }
    std::sort(结果.begin(), 结果.end(), [](const auto& 左区间, const auto& 右区间) {
        return 左区间.下界 < 右区间.下界
            || (左区间.下界 == 右区间.下界 && 左区间.上界 < 右区间.上界);
    });
    I64区间组 合并;
    const auto 最大 = (std::numeric_limits<std::int64_t>::max)();
    for (const auto& 区间 : 结果) {
        if (合并.empty()
            || (合并.back().上界 != 最大
                && 区间.下界 > 合并.back().上界 + 1)) {
            合并.push_back(区间);
        } else if (区间.上界 > 合并.back().上界) {
            合并.back().上界 = 区间.上界;
        }
    }
    return 合并;
}

I64区间组 取补集(const I64区间组& 原域) {
    I64区间组 结果;
    const auto 最小 = (std::numeric_limits<std::int64_t>::min)();
    const auto 最大 = (std::numeric_limits<std::int64_t>::max)();
    std::int64_t 游标 = 最小;
    bool 已到末端 = false;
    for (const auto& 区间 : 原域) {
        if (游标 < 区间.下界) 结果.push_back({游标, 区间.下界 - 1});
        if (区间.上界 == 最大) {
            已到末端 = true;
            break;
        }
        游标 = 区间.上界 + 1;
    }
    if (!已到末端) 结果.push_back({游标, 最大});
    return 结果;
}

std::optional<I64区间组> 形成关系值域(
    const I64区间组& 类型允许域,
    const I64区间组& 参照域,
    二次特征结果域种类 种类) {
    const auto 最小 = (std::numeric_limits<std::int64_t>::min)();
    const auto 最大 = (std::numeric_limits<std::int64_t>::max)();
    if (类型允许域.empty() || 参照域.empty()) return std::nullopt;

    I64区间组 候选;
    const auto 最低 = 参照域.front().下界;
    const auto 最高 = 参照域.back().上界;
    switch (种类) {
    case 二次特征结果域种类::任意:
        return 类型允许域;
    case 二次特征结果域种类::低于参照值域:
        if (最低 == 最小) return std::nullopt;
        候选.push_back({最小, 最低 - 1});
        break;
    case 二次特征结果域种类::包含于参照值域:
        候选 = 参照域;
        break;
    case 二次特征结果域种类::高于参照值域:
        if (最高 == 最大) return std::nullopt;
        候选.push_back({最高 + 1, 最大});
        break;
    case 二次特征结果域种类::不包含于参照值域:
        候选 = 取补集(参照域);
        break;
    case 二次特征结果域种类::小于:
    case 二次特征结果域种类::小于等于:
    case 二次特征结果域种类::等于:
    case 二次特征结果域种类::大于等于:
    case 二次特征结果域种类::大于: {
        if (参照域.size() != 1
            || 参照域.front().下界 != 参照域.front().上界) {
            return std::nullopt;
        }
        const auto 基准 = 参照域.front().下界;
        if (种类 == 二次特征结果域种类::小于) {
            if (基准 == 最小) return std::nullopt;
            候选.push_back({最小, 基准 - 1});
        } else if (种类 == 二次特征结果域种类::小于等于) {
            候选.push_back({最小, 基准});
        } else if (种类 == 二次特征结果域种类::等于) {
            候选.push_back({基准, 基准});
        } else if (种类 == 二次特征结果域种类::大于等于) {
            候选.push_back({基准, 最大});
        } else {
            if (基准 == 最大) return std::nullopt;
            候选.push_back({基准 + 1, 最大});
        }
        break;
    }
    }
    auto 交集 = 取交集(类型允许域, 候选);
    return 交集.empty() ? std::nullopt : std::optional<I64区间组>{std::move(交集)};
}

bool 值命中域(std::int64_t 值, const I64区间组& 域) noexcept {
    return std::any_of(域.begin(), 域.end(), [&](const auto& 区间) {
        return 值 >= 区间.下界 && 值 <= 区间.上界;
    });
}

