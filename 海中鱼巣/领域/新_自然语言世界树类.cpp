    if (有效(概念实例类型)) {
        (void)全局基础数据集.删除节点(概念实例类型);
    }
    if (有效(概念字段节点)) {
        (void)全局基础数据集.删除节点(概念字段节点);
    }
    if (有效(场景类型)) (void)全局基础数据集.删除节点(场景类型);
    if (有效(根类型)) (void)全局基础数据集.删除节点(根类型);
    if (有效(类型字段)) (void)全局基础数据集.删除节点(类型字段);
