bool 节点仍存在(稳定编码 节点) noexcept {
    return 有效(节点) && 全局基础数据集.查询节点(节点).has_value();
}

std::optional<稳定编码> 读取唯一节点字段(
    稳定编码 节点, 稳定编码 字段) {
    const auto 字段组 = 全局基础数据集.查询字段(节点, 字段);
    if (字段组.size() != 1) return std::nullopt;
    const auto* 目标 = std::get_if<稳定编码>(&字段组.front().内容);
    return 目标 && 节点仍存在(*目标)
        ? std::optional<稳定编码>{*目标} : std::nullopt;
}

bool 类型为(稳定编码 节点, 稳定编码 类型) {
    const auto 实际类型 = 读取唯一节点字段(节点, 节点类型字段);
    return 实际类型 && *实际类型 == 类型;
}

bool 有唯一父节点(稳定编码 节点, 稳定编码 父节点) {
    const auto 关系组 = 全局基础数据集.查询目标关系(
        节点, 基础外部关系类型::父子);
    return 关系组.size() == 1
        && 关系组.front().源节点 == 父节点
        && 关系组.front().角色或顺序 == 0;
}

bool 结构句柄完整() noexcept {
    return 有效(自然语言世界树根节点)
        && 有效(节点类型字段)
        && 有效(自然语言世界树根类型)
        && 有效(自然语言场景节点类型)
        && 有效(自然语言概念实例节点类型)
        && 有效(概念字段);
}

std::optional<新自然语言场景信息> 读取场景(稳定编码 节点) {
    if (!节点仍存在(节点)
        || !类型为(节点, 自然语言场景节点类型)
        || !有唯一父节点(节点, 自然语言世界树根节点)) {
        return std::nullopt;
    }
    return 新自然语言场景信息{节点};
}

struct 自然语言概念实例结构 final {
    稳定编码 节点;
    稳定编码 所属场景节点;
    稳定编码 概念节点;
};

std::optional<自然语言概念实例结构> 读取概念实例结构(
    稳定编码 节点) {
    if (!节点仍存在(节点)
        || !类型为(节点, 自然语言概念实例节点类型)) {
        return std::nullopt;
    }
    const auto 父关系组 = 全局基础数据集.查询目标关系(
        节点, 基础外部关系类型::父子);
    if (父关系组.size() != 1 || 父关系组.front().角色或顺序 != 0
        || !读取场景(父关系组.front().源节点)) {
        return std::nullopt;
    }
    const auto 概念节点 = 读取唯一节点字段(节点, 概念字段);
    if (!概念节点) return std::nullopt;
    return 自然语言概念实例结构{
        节点, 父关系组.front().源节点, *概念节点};
}

std::optional<新自然语言概念实例信息> 读取概念实例(
    稳定编码 节点,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务) {
    const auto 结构 = 读取概念实例结构(节点);
    if (!结构) return std::nullopt;
    const bool 是特征概念 =
        特征概念服务.是特征概念节点(结构->概念节点);
    const bool 是存在概念 =
        存在概念服务.是存在概念节点(结构->概念节点);
    if (是特征概念 == 是存在概念) return std::nullopt;
    return 新自然语言概念实例信息{
        结构->节点,
        结构->所属场景节点,
        结构->概念节点,
        是存在概念 ? 新自然语言概念实例种类::存在概念
                     : 新自然语言概念实例种类::特征概念};
}

std::optional<std::vector<新自然语言概念实例信息>> 读取场景全部概念实例(
    稳定编码 场景节点,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务) {
    if (!读取场景(场景节点)) return std::nullopt;
    std::vector<新自然语言概念实例信息> 结果;
    for (const auto& 关系 : 全局基础数据集.查询源关系(
        场景节点, 基础外部关系类型::父子)) {
        if (关系.角色或顺序 != 0) return std::nullopt;
        const auto 实例 = 读取概念实例(
            关系.目标节点, 特征概念服务, 存在概念服务);
        if (!实例 || 实例->所属场景节点 != 场景节点) {
            return std::nullopt;
        }
        结果.push_back(*实例);
    }
    return 结果;
}

enum class 概念配对检查状态 : std::uint8_t {
    可配对 = 1,
    不可配对 = 2,
    结构不一致 = 3,
    资源失败 = 4
};

std::optional<bool> 是上位存在概念(
    稳定编码 上位概念,
    稳定编码 下位概念,
    const 概念_存在类& 存在概念服务) {
    std::vector<稳定编码> 待查{下位概念};
    std::unordered_set<std::uint64_t> 已查;
    while (!待查.empty()) {
        const auto 当前 = 待查.back();
        待查.pop_back();
        if (!已查.insert(当前.值).second) continue;
        const auto 信息 = 存在概念服务.获取存在概念(当前);
        if (!信息) return std::nullopt;
        for (const auto 父概念 : 信息->上位概念组) {
            if (父概念 == 上位概念) return true;
            待查.push_back(父概念);
        }
    }
    return false;
}

概念配对检查状态 检查概念可配对(
    const 新自然语言概念实例信息& 左,
    const 新自然语言概念实例信息& 右,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务) {
    if (左.种类 != 右.种类) return 概念配对检查状态::不可配对;
    if (左.概念节点 == 右.概念节点) return 概念配对检查状态::可配对;
    if (左.种类 == 新自然语言概念实例种类::特征概念) {
        const auto 关系 = 特征概念服务.比较单特征概念(
            左.概念节点, 右.概念节点);
        if (关系.状态 == 特征概念规则状态::资源失败) {
            return 概念配对检查状态::资源失败;
        }
        if (关系.状态 != 特征概念规则状态::已完成 || !关系.关系) {
            return 概念配对检查状态::结构不一致;
        }
        return *关系.关系 == 单特征概念关系::左为上位
                || *关系.关系 == 单特征概念关系::右为上位
            ? 概念配对检查状态::可配对
            : 概念配对检查状态::不可配对;
    }

    if (!存在概念服务.是存在概念节点(左.概念节点)
        || !存在概念服务.是存在概念节点(右.概念节点)) {
        return 概念配对检查状态::结构不一致;
    }
    const auto 左包含右 = 是上位存在概念(
        左.概念节点, 右.概念节点, 存在概念服务);
    const auto 右包含左 = 是上位存在概念(
        右.概念节点, 左.概念节点, 存在概念服务);
    if (!左包含右 || !右包含左) {
        return 概念配对检查状态::结构不一致;
    }
    return *左包含右 || *右包含左
        ? 概念配对检查状态::可配对
        : 概念配对检查状态::不可配对;
}

std::int64_t 饱和场景差异(
    std::size_t 左数量,
    std::size_t 右数量,
    std::size_t 相同配对数量,
    std::size_t 上下位配对数量) noexcept {
    const auto 最大 = static_cast<std::uint64_t>(
        (std::numeric_limits<std::int64_t>::max)());
    const auto 左未配对 = 左数量 - 相同配对数量 - 上下位配对数量;
    const auto 右未配对 = 右数量 - 相同配对数量 - 上下位配对数量;
    std::uint64_t 差异 = static_cast<std::uint64_t>(上下位配对数量);
    const auto 增加 = [&差异, 最大](std::size_t 数量) noexcept {
        const auto 值 = static_cast<std::uint64_t>(数量);
        差异 = 值 > 最大 - 差异 ? 最大 : 差异 + 值;
    };
    增加(左未配对);
    增加(右未配对);
    return static_cast<std::int64_t>(差异);
}

bool 结构仍存在() {
    if (!结构句柄完整()
        || !节点仍存在(自然语言世界树根节点)
        || !节点仍存在(节点类型字段)
        || !节点仍存在(自然语言世界树根类型)
        || !节点仍存在(自然语言场景节点类型)
        || !节点仍存在(自然语言概念实例节点类型)
        || !节点仍存在(概念字段)
        || !类型为(自然语言世界树根节点, 自然语言世界树根类型)
        || !全局基础数据集.查询目标关系(
            自然语言世界树根节点,
            基础外部关系类型::父子).empty()) {
        return false;
    }
    for (const auto& 关系 : 全局基础数据集.查询源关系(
        自然语言世界树根节点, 基础外部关系类型::父子)) {
        const auto 场景 = 读取场景(关系.目标节点);
        if (关系.角色或顺序 != 0 || !场景) {
            return false;
        }
        for (const auto& 子关系 : 全局基础数据集.查询源关系(
            场景->节点, 基础外部关系类型::父子)) {
            if (子关系.角色或顺序 != 0
                || !读取概念实例结构(子关系.目标节点)) {
                return false;
            }
        }
    }
    return true;
}

void 回滚场景节点(稳定编码 节点, 稳定编码 类型字段) noexcept {
    if (有效(类型字段)) (void)全局基础数据集.删除字段(类型字段);
    for (const auto& 关系 : 全局基础数据集.查询目标关系(
        节点, 基础外部关系类型::父子)) {
        if (关系.源节点 == 自然语言世界树根节点) {
            (void)全局基础数据集.删除关系(关系.编码);
        }
    }
    (void)全局基础数据集.删除节点(节点);
}

