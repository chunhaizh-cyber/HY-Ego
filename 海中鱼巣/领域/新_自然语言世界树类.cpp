        自然语言世界树根类型 = 新根类型;
        自然语言场景节点类型 = 新场景类型;
        自然语言概念实例节点类型 = 新概念实例类型;
        概念字段 = 新概念字段;
        自然语言世界树根节点 = 新根节点;
