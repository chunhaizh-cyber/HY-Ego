新自然语言世界初始化结果 新_自然语言世界树类::初始化() noexcept {
    新自然语言世界初始化结果 结果;
    try {
        std::lock_guard 锁(自然语言世界树互斥);
        if (结构句柄完整()) {
            if (!结构仍存在()) return 结果;
            结果.状态 = 新自然语言世界初始化状态::无变化;
            结果.根节点 = 自然语言世界树根节点;
            return 结果;
        }
        if (有效(自然语言世界树根节点)
            || 有效(节点类型字段)
            || 有效(自然语言世界树根类型)
            || 有效(自然语言场景节点类型)
            || 有效(自然语言概念实例节点类型)
            || 有效(概念字段)) {
            return 结果;
        }

        const auto 新节点类型字段 = 全局基础数据集.新建节点();
        const auto 新根类型 = 全局基础数据集.新建节点();
        const auto 新场景类型 = 全局基础数据集.新建节点();
        const auto 新概念实例类型 = 全局基础数据集.新建节点();
        const auto 新概念字段 = 全局基础数据集.新建节点();
        const auto 新根节点 = 全局基础数据集.新建节点();
        if (!有效(新节点类型字段) || !有效(新根类型)
            || !有效(新场景类型) || !有效(新概念实例类型)
            || !有效(新概念字段) || !有效(新根节点)) {
            回滚初始化节点(
                新根节点, {}, 新概念实例类型, 新概念字段,
                新场景类型, 新根类型, 新节点类型字段);
            结果.状态 = 新自然语言世界初始化状态::资源失败;
            return 结果;
        }
        const auto 新类型字段关系 = 全局基础数据集.添加字段节点(
            新根节点, 新节点类型字段, 新根类型);
        if (!有效(新类型字段关系)) {
            回滚初始化节点(
                新根节点, {}, 新概念实例类型, 新概念字段,
                新场景类型, 新根类型, 新节点类型字段);
            结果.状态 = 新自然语言世界初始化状态::资源失败;
            return 结果;
        }
        const auto 类型字段组 = 全局基础数据集.查询字段(
            新根节点, 新节点类型字段);
        const auto* 类型目标 = 类型字段组.size() == 1
            ? std::get_if<稳定编码>(&类型字段组.front().内容) : nullptr;
        if (!类型目标 || *类型目标 != 新根类型
            || !全局基础数据集.查询目标关系(
                新根节点, 基础外部关系类型::父子).empty()) {
            回滚初始化节点(新根节点, 新类型字段关系,
                新概念实例类型, 新概念字段,
                新场景类型, 新根类型, 新节点类型字段);
            return 结果;
        }

        节点类型字段 = 新节点类型字段;
        自然语言世界树根类型 = 新根类型;
        自然语言场景节点类型 = 新场景类型;
        自然语言概念实例节点类型 = 新概念实例类型;
        概念字段 = 新概念字段;
        自然语言世界树根节点 = 新根节点;
        if (!结构仍存在()) {
            自然语言世界树根节点 = {};
            概念字段 = {};
            自然语言概念实例节点类型 = {};
            自然语言场景节点类型 = {};
            自然语言世界树根类型 = {};
            节点类型字段 = {};
            回滚初始化节点(新根节点, 新类型字段关系,
                新概念实例类型, 新概念字段,
                新场景类型, 新根类型, 新节点类型字段);
            return 结果;
        }
        结果.状态 = 新自然语言世界初始化状态::已完成;
        结果.根节点 = 自然语言世界树根节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新自然语言世界初始化状态::资源失败;
        return 结果;
    }
}

