新自然语言概念实例建立结果 新_自然语言世界树类::实例化概念(
    稳定编码 场景节点,
    稳定编码 概念节点) noexcept {
    新自然语言概念实例建立结果 结果;
    稳定编码 已建节点{};
    稳定编码 已建类型字段{};
    稳定编码 已建概念字段{};
    try {
        std::lock_guard 锁(自然语言世界树互斥);
        if (!结构句柄完整()) {
            结果.状态 = 新自然语言概念实例操作状态::未初始化;
            return 结果;
        }
        if (!结构仍存在()) {
            结果.状态 = 新自然语言概念实例操作状态::结构不一致;
            return 结果;
        }
        if (!读取场景(场景节点)) {
            结果.状态 = 新自然语言概念实例操作状态::场景不存在;
            return 结果;
        }
        const bool 是特征概念 =
            特征概念服务_.是特征概念节点(概念节点);
        const bool 是存在概念 =
            存在概念服务_.是存在概念节点(概念节点);
        if (!是特征概念 && !是存在概念) {
            结果.状态 = 新自然语言概念实例操作状态::概念不存在;
            return 结果;
        }
        if (是特征概念 && 是存在概念) {
            结果.状态 = 新自然语言概念实例操作状态::结构不一致;
            return 结果;
        }

        已建节点 = 全局基础数据集.新建节点(场景节点);
        if (!有效(已建节点)) {
            结果.状态 = 新自然语言概念实例操作状态::资源失败;
            return 结果;
        }
        已建类型字段 = 全局基础数据集.添加字段节点(
            已建节点, 节点类型字段, 自然语言概念实例节点类型);
        if (!有效(已建类型字段)) {
            回滚概念实例节点(已建节点, {}, {});
            结果.状态 = 新自然语言概念实例操作状态::资源失败;
            return 结果;
        }
        已建概念字段 = 全局基础数据集.添加字段节点(
            已建节点, 概念字段, 概念节点);
        if (!有效(已建概念字段)) {
            回滚概念实例节点(已建节点, 已建类型字段, {});
            结果.状态 = 新自然语言概念实例操作状态::资源失败;
            return 结果;
        }
        const auto 读回 = 读取概念实例(
            已建节点, 特征概念服务_, 存在概念服务_);
        if (!读回 || 读回->所属场景节点 != 场景节点
            || 读回->概念节点 != 概念节点) {
            回滚概念实例节点(
                已建节点, 已建类型字段, 已建概念字段);
            结果.状态 = 新自然语言概念实例操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新自然语言概念实例操作状态::已建立;
        结果.实例 = *读回;
        return 结果;
    } catch (...) {
        if (有效(已建节点)) {
            回滚概念实例节点(
                已建节点, 已建类型字段, 已建概念字段);
        }
        结果.状态 = 新自然语言概念实例操作状态::资源失败;
        return 结果;
    }
}

