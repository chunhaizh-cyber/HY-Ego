bool 节点仍存在(稳定编码 节点) noexcept {
    return 有效(节点) && 全局基础数据集.查询节点(节点).has_value();
}

std::optional<稳定编码> 读取唯一节点字段(
    稳定编码 节点, 稳定编码 字段) {
    const auto 字段组 = 全局基础数据集.查询字段(节点, 字段);
    if (字段组.size() != 1) return std::nullopt;
    const auto* 目标 = std::get_if<稳定编码>(&字段组.front().内容);
    return 目标 && 节点仍存在(*目标)
        ? std::optional<稳定编码>{*目标} : std::nullopt;
}

bool 类型为(稳定编码 节点, 稳定编码 类型) {
    const auto 实际类型 = 读取唯一节点字段(节点, 节点类型字段);
    return 实际类型 && *实际类型 == 类型;
}

bool 有唯一父节点(稳定编码 节点, 稳定编码 父节点) {
    const auto 关系组 = 全局基础数据集.查询目标关系(
        节点, 基础外部关系类型::父子);
    return 关系组.size() == 1
        && 关系组.front().源节点 == 父节点
        && 关系组.front().角色或顺序 == 0;
}

bool 结构句柄完整() noexcept {
    return 有效(自然语言世界树根节点)
        && 有效(节点类型字段)
        && 有效(自然语言世界树根类型)
        && 有效(自然语言场景节点类型)
        && 有效(自然语言概念实例节点类型)
        && 有效(概念字段);
}

std::optional<新自然语言场景信息> 读取场景(稳定编码 节点) {
    if (!节点仍存在(节点)
        || !类型为(节点, 自然语言场景节点类型)
        || !有唯一父节点(节点, 自然语言世界树根节点)) {
        return std::nullopt;
    }
    return 新自然语言场景信息{节点};
}

struct 自然语言概念实例结构 final {
    稳定编码 节点;
    稳定编码 所属场景节点;
    稳定编码 概念节点;
};

std::optional<自然语言概念实例结构> 读取概念实例结构(
    稳定编码 节点) {
    if (!节点仍存在(节点)
        || !类型为(节点, 自然语言概念实例节点类型)) {
        return std::nullopt;
    }
    const auto 父关系组 = 全局基础数据集.查询目标关系(
        节点, 基础外部关系类型::父子);
    if (父关系组.size() != 1 || 父关系组.front().角色或顺序 != 0
        || !读取场景(父关系组.front().源节点)) {
        return std::nullopt;
    }
    const auto 概念节点 = 读取唯一节点字段(节点, 概念字段);
    if (!概念节点) return std::nullopt;
    return 自然语言概念实例结构{
        节点, 父关系组.front().源节点, *概念节点};
}

std::optional<新自然语言概念实例信息> 读取概念实例(
    稳定编码 节点,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务) {
    const auto 结构 = 读取概念实例结构(节点);
    if (!结构) return std::nullopt;
    const bool 是特征概念 =
        特征概念服务.是特征概念节点(结构->概念节点);
    const bool 是存在概念 =
        存在概念服务.是存在概念节点(结构->概念节点);
    if (是特征概念 == 是存在概念) return std::nullopt;
    return 新自然语言概念实例信息{
        结构->节点,
        结构->所属场景节点,
        结构->概念节点,
        是存在概念 ? 新自然语言概念实例种类::存在概念
                     : 新自然语言概念实例种类::特征概念};
}

bool 结构仍存在() {
    if (!结构句柄完整()
        || !节点仍存在(自然语言世界树根节点)
        || !节点仍存在(节点类型字段)
        || !节点仍存在(自然语言世界树根类型)
        || !节点仍存在(自然语言场景节点类型)
        || !节点仍存在(自然语言概念实例节点类型)
        || !节点仍存在(概念字段)
        || !类型为(自然语言世界树根节点, 自然语言世界树根类型)
        || !全局基础数据集.查询目标关系(
            自然语言世界树根节点,
            基础外部关系类型::父子).empty()) {
        return false;
    }
    for (const auto& 关系 : 全局基础数据集.查询源关系(
        自然语言世界树根节点, 基础外部关系类型::父子)) {
        const auto 场景 = 读取场景(关系.目标节点);
        if (关系.角色或顺序 != 0 || !场景) {
            return false;
        }
        for (const auto& 子关系 : 全局基础数据集.查询源关系(
            场景->节点, 基础外部关系类型::父子)) {
            if (子关系.角色或顺序 != 0
                || !读取概念实例结构(子关系.目标节点)) {
                return false;
            }
        }
    }
    return true;
}

void 回滚场景节点(稳定编码 节点, 稳定编码 类型字段) noexcept {
    if (有效(类型字段)) (void)全局基础数据集.删除字段(类型字段);
    for (const auto& 关系 : 全局基础数据集.查询目标关系(
        节点, 基础外部关系类型::父子)) {
        if (关系.源节点 == 自然语言世界树根节点) {
            (void)全局基础数据集.删除关系(关系.编码);
        }
    }
    (void)全局基础数据集.删除节点(节点);
}

void 回滚初始化节点(稳定编码 根节点, 稳定编码 类型字段关系,
    稳定编码 概念实例类型, 稳定编码 概念字段节点,
    稳定编码 场景类型, 稳定编码 根类型,
    稳定编码 类型字段) noexcept {
    if (有效(类型字段关系)) {
        (void)全局基础数据集.删除字段(类型字段关系);
    }
    if (有效(根节点)) (void)全局基础数据集.删除节点(根节点);
    if (有效(概念实例类型)) {
        (void)全局基础数据集.删除节点(概念实例类型);
    }
    if (有效(概念字段节点)) {
        (void)全局基础数据集.删除节点(概念字段节点);
    }
    if (有效(场景类型)) (void)全局基础数据集.删除节点(场景类型);
    if (有效(根类型)) (void)全局基础数据集.删除节点(根类型);
    if (有效(类型字段)) (void)全局基础数据集.删除节点(类型字段);
}

void 回滚概念实例节点(
    稳定编码 节点,
    稳定编码 类型字段关系,
    稳定编码 概念字段关系) noexcept {
    if (有效(概念字段关系)) {
        (void)全局基础数据集.删除字段(概念字段关系);
    }
    if (有效(类型字段关系)) {
        (void)全局基础数据集.删除字段(类型字段关系);
    }
    for (const auto& 关系 : 全局基础数据集.查询目标关系(
        节点, 基础外部关系类型::父子)) {
        (void)全局基础数据集.删除关系(关系.编码);
    }
    (void)全局基础数据集.删除节点(节点);
}

