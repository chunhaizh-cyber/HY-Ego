新自然语言场景建立结果 新_自然语言世界树类::建立空场景() noexcept {
    新自然语言场景建立结果 结果;
    try {
        std::lock_guard 锁(自然语言世界树互斥);
        if (!结构句柄完整()) {
            结果.状态 = 新自然语言场景操作状态::未初始化;
            return 结果;
        }
        if (!结构仍存在()) {
            结果.状态 = 新自然语言场景操作状态::结构不一致;
            return 结果;
        }
        const auto 节点 = 全局基础数据集.新建节点(
            自然语言世界树根节点);
        if (!有效(节点)) {
            结果.状态 = 新自然语言场景操作状态::资源失败;
            return 结果;
        }
        const auto 类型字段 = 全局基础数据集.添加字段节点(
            节点, 节点类型字段, 自然语言场景节点类型);
        if (!有效(类型字段)) {
            回滚场景节点(节点, {});
            结果.状态 = 新自然语言场景操作状态::资源失败;
            return 结果;
        }
        if (!读取场景(节点)) {
            回滚场景节点(节点, 类型字段);
            结果.状态 = 新自然语言场景操作状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新自然语言场景操作状态::已建立;
        结果.场景节点 = 节点;
        return 结果;
    } catch (...) {
        结果.状态 = 新自然语言场景操作状态::资源失败;
        return 结果;
    }
}

std::optional<新自然语言场景信息> 新_自然语言世界树类::获取场景(
    稳定编码 场景节点) const noexcept {
    try {
        std::lock_guard 锁(自然语言世界树互斥);
        return 结构仍存在() ? 读取场景(场景节点) : std::nullopt;
    } catch (...) {
        return std::nullopt;
    }
}

std::vector<稳定编码> 新_自然语言世界树类::查询全部场景() const noexcept {
    try {
        std::lock_guard 锁(自然语言世界树互斥);
        std::vector<稳定编码> 结果;
        if (!结构仍存在()) return 结果;
        for (const auto& 关系 : 全局基础数据集.查询源关系(
            自然语言世界树根节点, 基础外部关系类型::父子)) {
            if (!读取场景(关系.目标节点)) return {};
            结果.push_back(关系.目标节点);
        }
        return 结果;
    } catch (...) {
        return {};
    }
}

bool 新_自然语言世界树类::是自然语言场景节点(稳定编码 节点) const noexcept {
    try {
        std::lock_guard 锁(自然语言世界树互斥);
        return 结构仍存在() && 读取场景(节点).has_value();
    } catch (...) {
        return false;
    }
}

