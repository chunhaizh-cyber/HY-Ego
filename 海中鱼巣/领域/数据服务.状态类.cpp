bool 状态类数据服务::退出写集形状有效(
    const L1所有者范围写集请求& 写集,
    L1所有者范围写入幂等身份 幂等) noexcept {
    if (写集.写入幂等身份 != 幂等 || !写集.节点.empty()
        || !写集.关系.empty() || !写集.值.empty()
        || !写集.属性槽变更.empty() || 写集.退出事实.size() != 6
        || !std::is_sorted(写集.退出事实.begin(), 写集.退出事实.end())) {
        return false;
    }
    for (std::size_t i = 0; i < 写集.退出事实.size(); ++i) {
        if (!有效(写集.退出事实[i])
            || (i != 0 && 写集.退出事实[i] == 写集.退出事实[i - 1])) {
            return false;
        }
    }
    return true;
}

std::optional<状态退出结果> 状态类数据服务::重放退出(
    const 状态退出请求& 请求) {
    const auto 首次 = port_.读取首次写入材料({请求.幂等身份});
    if (!首次读取回显完整(首次, 请求.幂等身份)) {
        return 退出失败(状态类数据状态::内部不一致);
    }
    if (首次.状态 == L1所有者范围读取状态::未找到) {
        if (首次.首次规范化写集 || 首次.首次写入结果) {
            return 退出失败(状态类数据状态::内部不一致);
        }
        return std::nullopt;
    }
    if (首次.状态 != L1所有者范围读取状态::成功) {
        if (首次.首次规范化写集 || 首次.首次写入结果) {
            return 退出失败(状态类数据状态::内部不一致);
        }
        return 退出失败(映射读取(首次.状态));
    }
    if (!首次.首次规范化写集 || !首次.首次写入结果) {
        return 退出失败(状态类数据状态::内部不一致);
    }
    const auto& 写集 = *首次.首次规范化写集;
    if (!退出写集形状有效(写集, 请求.幂等身份)
        || !std::binary_search(写集.退出事实.begin(), 写集.退出事实.end(),
            请求.身份.编码)
        || 首次.首次写入结果->状态 != L1所有者范围写入状态::成功
        || !写入头完整(*首次.首次写入结果, owner_, 请求.幂等身份)
        || !首次.首次写入结果->新编码映射.empty()) {
        return 退出失败(状态类数据状态::幂等冲突);
    }
    const auto 保存 = port_.提交所有者范围中性写集(写集);
    if (保存.状态 != L1所有者范围写入状态::精确重复
        || !写入头完整(保存, owner_, 请求.幂等身份)
        || !保存.新编码映射.empty()) {
        return 退出失败(映射写入(保存.状态, 状态类数据状态::已删除));
    }
    return 状态退出结果{头(状态类数据状态::精确重复)};
}

状态退出结果 状态类数据服务::退出状态(const 状态退出请求& 请求) {
    if (请求.合同版本 != 状态类数据合同版本
        || !有效(请求.幂等身份) || !有效(请求.身份)) {
        return 退出失败(状态类数据状态::入口拒绝);
    }
    try {
        if (auto 重放 = 重放退出(请求)) return *重放;
        const auto 当前 = 读取当前内容(请求.身份);
        if (当前.结果头.状态 != 状态类数据状态::已读取 || !当前.内容) {
            return 退出失败(当前.结果头.状态);
        }
        const auto 写集 = 形成退出写集(*当前.内容, 请求.幂等身份);
        const auto 保存 = port_.提交所有者范围中性写集(写集);
        const auto 状态 = 映射写入(保存.状态, 状态类数据状态::已删除);
        if ((状态 != 状态类数据状态::已删除
                && 状态 != 状态类数据状态::精确重复)
            || !写入头完整(保存, owner_, 请求.幂等身份)
            || !保存.新编码映射.empty()) {
            return 退出失败(状态 == 状态类数据状态::已删除
                || 状态 == 状态类数据状态::精确重复
                ? 状态类数据状态::内部不一致 : 状态);
        }
        return 状态退出结果{头(状态)};
    } catch (const std::bad_alloc&) {
        return 退出失败(状态类数据状态::资源失败);
    } catch (...) {
        return 退出失败(状态类数据状态::内部不一致);
    }
}

状态类结果头 状态类数据服务::确认当前状态结构身份(
    const 状态当前身份确认请求& 请求) const {
    if (请求.合同版本 != 状态类数据合同版本 || !有效(请求.身份)) {
        return 头(状态类数据状态::入口拒绝);
    }
    const auto 读取 = 读取当前状态({状态类数据合同版本, 请求.身份});
    return 读取.结果头.状态 == 状态类数据状态::已读取 && 读取.内容
        ? 头(状态类数据状态::已读取) : 读取.结果头;
}

状态类结果头 状态类数据服务::头(状态类数据状态 状态) noexcept {
    return {状态, 状态类数据合同版本};
}

