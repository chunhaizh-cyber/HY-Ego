bool 属性未设置(const L1所有者范围一致属性值读取结果项* 项) noexcept {
    return 项 && 项->状态 == 项状态::属性未设置 && !项->投影;
}

const L1所有者范围值事实* 属性值(
    const L1所有者范围一致属性值读取结果项* 项,
    L1结构所有者身份 所有者, 稳定编码 节点, 稳定编码 类型) noexcept {
    if (!项 || 项->状态 != 项状态::成功 || !项->投影
        || 项->节点 != 节点 || 项->属性类型 != 类型
        || 项->投影->属性槽.属性类型节点 != 类型
        || 项->投影->属性槽.当前值 != 项->投影->当前值事实.编码) {
        return nullptr;
    }
    const auto& 值 = 项->投影->当前值事实;
    if (值.写入所有者 != 所有者 || 值.所属节点 != 节点
        || 值.来源节点 != 节点 || 值.属性类型节点 != 类型
        || !有效(值.编码)) {
        return nullptr;
    }
    return &值;
}

