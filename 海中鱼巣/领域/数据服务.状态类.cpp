状态组查询结果 状态类数据服务::读取全部当前状态() const {
    L1所有者范围一致关系类型闭包读取请求 请求;
    请求.所有者.push_back(owner_);
    L1所有者范围一致关系类型闭包选择项 选择;
    选择.入口关系类型节点 = layout_.状态族归属关系类型;
    选择.源节点属性类型 = {layout_.内联准确值属性类型,
        layout_.引用准确值属性类型, layout_.实例绝对时间属性类型,
        layout_.抽象相对时间属性类型, layout_.首次形成UTC属性类型};
    选择.源节点源关系类型 = {layout_.正式特征类型关系类型};
    请求.关系类型闭包.push_back(std::move(选择));
    const auto 读取 = l1_.尝试读取所有者范围一致关系类型闭包投影(请求);
    if (读取.状态 != L1所有者范围一致当前读取状态::成功) {
        return 组失败(映射一致读取(读取.状态));
    }
    if (读取.所有者.size() != 1 || 读取.关系类型闭包.size() != 1
        || 读取.所有者.front().状态 != 项状态::成功
        || 读取.所有者.front().查询所有者 != owner_
        || !读取.所有者.front().所有者事实) {
        return 组失败(状态类数据状态::内部不一致);
    }
    const auto& 闭包 = 读取.关系类型闭包.front();
    if (闭包.入口关系类型节点 != layout_.状态族归属关系类型
        || 闭包.状态 != 项状态::成功 || !闭包.关系类型事实) {
        return 组失败(状态类数据状态::内部不一致);
    }
    状态组查询结果 输出{头(状态类数据状态::已读取), {}};
    for (const auto& 成员 : 闭包.成员) {
        auto 状态 = 解析闭包状态(成员);
        if (!状态) return 组失败(状态类数据状态::旧格式不支持);
        输出.状态组.push_back(std::move(*状态));
    }
    std::sort(输出.状态组.begin(), 输出.状态组.end(),
        [](const auto& 左, const auto& 右) {
            return 左.信息.身份.编码 < 右.信息.身份.编码;
        });
    const auto 重复 = std::adjacent_find(输出.状态组.begin(), 输出.状态组.end(),
        [](const auto& 左, const auto& 右) {
            return 左.信息.身份 == 右.信息.身份;
        });
    if (重复 != 输出.状态组.end()) return 组失败(状态类数据状态::内部不一致);
    return 输出;
}

