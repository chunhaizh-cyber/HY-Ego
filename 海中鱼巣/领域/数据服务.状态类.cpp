bool 状态内容事实完整(const 状态内容事实& 值) noexcept {
    if (!有效(值.信息.身份) || !有效(值.信息.正式特征类型)
        || !浅层结构有效(值.信息.固定准确值)
        || (值.信息.强时间.语义 != 状态强时间语义::实例绝对UTC纳秒
            && 值.信息.强时间.语义 != 状态强时间语义::抽象相对纳秒)
        || 值.信息.强时间.纳秒 < 0 || 值.首次形成UTC纳秒 < 0) {
        return false;
    }
    const 稳定编码 身份组[]{值.信息.身份.编码, 值.族归属关系,
        值.正式特征类型关系, 值.准确值事实, 值.强时间事实,
        值.首次形成UTC事实};
    for (std::size_t i = 0; i < std::size(身份组); ++i) {
        if (!有效(身份组[i])) return false;
        for (std::size_t j = 0; j < i; ++j) {
            if (身份组[i] == 身份组[j]) return false;
        }
    }
    return true;
}

状态类数据服务::状态类数据服务(L1事实基座服务& 第一层服务,
    const 特征类数据服务& 特征服务, L1所有者范围写端口&& 写端口,
    const 状态类结构交付& 结构)
    : l1_(第一层服务), feature_(特征服务), port_(std::move(写端口)),
      owner_(port_.所有者身份()), layout_(结构) {
    if (!绑定于(l1_) || !有效(owner_) || !布局浅层有效()) {
        throw std::invalid_argument("invalid state configuration");
    }
    if (!布局材料有效()) {
        throw std::invalid_argument("invalid state structure");
    }
}

bool 状态类数据服务::绑定于(const L1事实基座服务& 服务) const noexcept {
    return &服务 == &l1_ && feature_.绑定于(服务) && port_.绑定于(服务);
}

bool 状态类数据服务::布局浅层有效() const noexcept {
    const 稳定编码 身份组[]{layout_.状态族锚点,
        layout_.状态族归属关系类型, layout_.正式特征类型关系类型,
        layout_.内联准确值属性类型, layout_.引用准确值属性类型,
        layout_.实例绝对时间属性类型, layout_.抽象相对时间属性类型,
        layout_.首次形成UTC属性类型};
    for (std::size_t i = 0; i < std::size(身份组); ++i) {
        if (!有效(身份组[i])) return false;
        for (std::size_t j = 0; j < i; ++j) {
            if (身份组[i] == 身份组[j]) return false;
        }
    }
    return true;
}

bool 状态类数据服务::布局材料有效() const {
    L1所有者范围一致当前读取请求 请求;
    请求.所有者.push_back(owner_);
    请求.节点 = {layout_.状态族锚点, layout_.状态族归属关系类型,
        layout_.正式特征类型关系类型, layout_.内联准确值属性类型,
        layout_.引用准确值属性类型, layout_.实例绝对时间属性类型,
        layout_.抽象相对时间属性类型, layout_.首次形成UTC属性类型};
    const auto 读取 = l1_.尝试读取所有者范围一致当前投影(请求);
    if (读取.状态 != L1所有者范围一致当前读取状态::成功
        || 读取.所有者.size() != 1 || 读取.节点.size() != 请求.节点.size()
        || 读取.所有者.front().状态 != 项状态::成功
        || 读取.所有者.front().查询所有者 != owner_
        || !读取.所有者.front().所有者事实
        || 读取.所有者.front().所有者事实->范围种类
            != L1所有者范围种类::独占结构范围) {
        return false;
    }

    const auto 核验 = [&](稳定编码 编码, 节点种类 种类,
            std::optional<L1所有者范围值表示种类> 表示) {
        const L1所有者范围一致节点读取结果项* 命中 = nullptr;
        for (const auto& 项 : 读取.节点) {
            if (项.查询编码 != 编码) continue;
            if (命中) return false;
            命中 = &项;
        }
        return 命中 && 命中->状态 == 项状态::成功 && 命中->事实
            && 命中->事实->编码 == 编码
            && 命中->事实->写入所有者 == owner_
            && 命中->事实->种类 == 种类
            && 命中->事实->属性类型表示 == 表示;
    };

    return 核验(layout_.状态族锚点, 节点种类::普通, std::nullopt)
        && 核验(layout_.状态族归属关系类型, 节点种类::普通, std::nullopt)
        && 核验(layout_.正式特征类型关系类型, 节点种类::普通, std::nullopt)
        && 核验(layout_.内联准确值属性类型, 节点种类::属性类型,
            L1所有者范围值表示种类::I64)
        && 核验(layout_.引用准确值属性类型, 节点种类::属性类型,
            L1所有者范围值表示种类::U64组)
        && 核验(layout_.实例绝对时间属性类型, 节点种类::属性类型,
            L1所有者范围值表示种类::I64)
        && 核验(layout_.抽象相对时间属性类型, 节点种类::属性类型,
            L1所有者范围值表示种类::I64)
        && 核验(layout_.首次形成UTC属性类型, 节点种类::属性类型,
            L1所有者范围值表示种类::I64);
}

bool 状态类数据服务::时间语义有效(状态强时间语义 语义) noexcept {
    return 语义 == 状态强时间语义::实例绝对UTC纳秒
        || 语义 == 状态强时间语义::抽象相对纳秒;
}

bool 状态类数据服务::创建请求有效(const 状态创建请求& 请求) noexcept {
    return 请求.合同版本 == 状态类数据合同版本
        && 有效(请求.幂等身份) && 有效(请求.正式特征类型)
        && 浅层结构有效(请求.固定准确值)
        && 时间语义有效(请求.强时间.语义)
        && 请求.强时间.纳秒 >= 0;
}

std::int64_t 状态类数据服务::当前UTC纳秒() noexcept {
    return std::chrono::duration_cast<std::chrono::nanoseconds>(
        std::chrono::system_clock::now().time_since_epoch()).count();
}

L1所有者范围写集请求 状态类数据服务::形成创建写集(
    const 状态创建请求& 请求, std::int64_t 首次UTC) const {
    L1所有者范围写集请求 写集{请求.幂等身份};
    写集.节点 = {{节点键, 节点种类::普通, std::nullopt}};
    写集.关系 = {
        {族关系键, 节点键, layout_.状态族锚点,
            layout_.状态族归属关系类型, 1},
        {FT关系键, 节点键, 请求.正式特征类型.编码,
            layout_.正式特征类型关系类型, 1}
    };
    const auto 准确类型 = std::holds_alternative<std::int64_t>(请求.固定准确值)
        ? layout_.内联准确值属性类型 : layout_.引用准确值属性类型;
    L1所有者范围原始值材料 准确材料 =
        std::holds_alternative<std::int64_t>(请求.固定准确值)
        ? L1所有者范围原始值材料{std::get<std::int64_t>(请求.固定准确值)}
        : L1所有者范围原始值材料{std::vector<std::uint64_t>{
            std::get<特征值身份>(请求.固定准确值).编码.值}};
    const auto 时间类型 = 请求.强时间.语义 == 状态强时间语义::实例绝对UTC纳秒
        ? layout_.实例绝对时间属性类型 : layout_.抽象相对时间属性类型;
    写集.值 = {
        {准确值键, 节点键, 准确类型, std::move(准确材料), 节点键},
        {时间键, 节点键, 时间类型, 请求.强时间.纳秒, 节点键},
        {首次UTC键, 节点键, layout_.首次形成UTC属性类型, 首次UTC, 节点键}
    };
    写集.属性槽变更 = {{节点键, 准确类型, 准确值键},
        {节点键, 时间类型, 时间键},
        {节点键, layout_.首次形成UTC属性类型, 首次UTC键}};
    return 写集;
}

std::optional<std::int64_t> 状态类数据服务::查找首次UTC(
    const L1所有者范围写集请求& 写集) {
    for (const auto& 值 : 写集.值) {
        if (值.本地键 != 首次UTC键) continue;
        if (const auto* 纳秒 = std::get_if<std::int64_t>(&值.材料)) return *纳秒;
    }
    return std::nullopt;
}

bool 状态类数据服务::首次读取回显完整(
    const L1所有者范围首次写入读取结果& 首次,
    L1所有者范围写入幂等身份 幂等) const noexcept {
    return 首次.所有者 == owner_ && 首次.写入幂等身份 == 幂等;
}

bool 状态类数据服务::写入头完整(const L1所有者范围写入结果& 结果,
    L1结构所有者身份 所有者,
    L1所有者范围写入幂等身份 幂等) noexcept {
    const bool 首次 = 结果.状态 == L1所有者范围写入状态::成功
        && 结果.是否形成内存权威发布
        && 结果.重试边界 == L1所有者范围重试边界::不适用;
    const bool 重放 = 结果.状态 == L1所有者范围写入状态::精确重复
        && !结果.是否形成内存权威发布
        && 结果.重试边界 == L1所有者范围重试边界::原幂等身份读回收敛;
    return 结果.所有者 == 所有者 && 结果.写入幂等身份 == 幂等
        && (首次 || 重放);
}

std::optional<稳定编码> 状态类数据服务::映射编码(
    const L1所有者范围写入结果& 结果, L1所有者范围写集本地键 键) {
    std::optional<稳定编码> 输出;
    for (const auto& [本地键, 编码] : 结果.新编码映射) {
        if (本地键 != 键) continue;
        if (输出 || !有效(编码)) return std::nullopt;
        输出 = 编码;
    }
    return 输出;
}

bool 状态类数据服务::创建映射完整(
    const L1所有者范围写入结果& 结果) noexcept {
    const L1所有者范围写集本地键 键组[]{节点键, 族关系键, FT关系键,
        准确值键, 时间键, 首次UTC键};
    if (结果.新编码映射.size() != std::size(键组)) return false;
    for (std::size_t i = 0; i < std::size(键组); ++i) {
        const auto 编码 = 映射编码(结果, 键组[i]);
        if (!编码) return false;
        for (std::size_t j = 0; j < i; ++j) {
            const auto 先前 = 映射编码(结果, 键组[j]);
            if (!先前 || *先前 == *编码) return false;
        }
    }
    return true;
}

std::optional<状态创建结果> 状态类数据服务::重放创建(
    const 状态创建请求& 请求) {
    const auto 首次 = port_.读取首次写入材料({请求.幂等身份});
    if (!首次读取回显完整(首次, 请求.幂等身份)) {
        return 创建失败(状态类数据状态::内部不一致);
    }
    if (首次.状态 == L1所有者范围读取状态::未找到) {
        if (首次.首次规范化写集 || 首次.首次写入结果) {
            return 创建失败(状态类数据状态::内部不一致);
        }
        return std::nullopt;
    }
    if (首次.状态 != L1所有者范围读取状态::成功) {
        if (首次.首次规范化写集 || 首次.首次写入结果) {
            return 创建失败(状态类数据状态::内部不一致);
        }
        return 创建失败(映射读取(首次.状态));
    }
    if (!首次.首次规范化写集 || !首次.首次写入结果) {
        return 创建失败(状态类数据状态::内部不一致);
    }
    const auto& 写集 = *首次.首次规范化写集;
    const auto 首次UTC = 查找首次UTC(写集);
    if (!首次UTC || 写集 != 形成创建写集(请求, *首次UTC)) {
        return 创建失败(状态类数据状态::幂等冲突);
    }
    if (首次.首次写入结果->状态 != L1所有者范围写入状态::成功
        || !写入头完整(*首次.首次写入结果, owner_, 请求.幂等身份)
        || !创建映射完整(*首次.首次写入结果)) {
        return 创建失败(状态类数据状态::内部不一致);
    }
    const auto 保存 = port_.提交所有者范围中性写集(写集);
    if (保存.状态 != L1所有者范围写入状态::精确重复
        || !写入头完整(保存, owner_, 请求.幂等身份)
        || !创建映射完整(保存)
        || 保存.新编码映射 != 首次.首次写入结果->新编码映射) {
        return 创建失败(映射写入(保存.状态, 状态类数据状态::已创建));
    }
    const auto 身份 = 映射编码(保存, 节点键);
    if (!身份) return 创建失败(状态类数据状态::内部不一致);
    auto 读取 = 读取当前内容({*身份});
    if (读取.结果头.状态 != 状态类数据状态::已读取 || !读取.内容) {
        return 创建失败(读取.结果头.状态);
    }
    return 状态创建结果{头(状态类数据状态::精确重复),
        std::move(读取.内容)};
}

状态创建结果 状态类数据服务::创建状态(const 状态创建请求& 请求) {
    if (!创建请求有效(请求)) return 创建失败(状态类数据状态::入口拒绝);
    try {
        if (auto 重放 = 重放创建(请求)) return *重放;

        // 待实现：特征类 current-only 准确值核验接口迁移完成后在此接线。
        // 当前旧接口强制使用已退出的读截止，不能伪造后继续发布状态。
        return 创建失败(状态类数据状态::内部不一致);
    } catch (const std::bad_alloc&) {
        return 创建失败(状态类数据状态::资源失败);
    } catch (...) {
        return 创建失败(状态类数据状态::内部不一致);
    }
}

bool 状态类数据服务::当前值事实完整(const L1所有者范围值事实& 值,
    L1结构所有者身份 所有者, 稳定编码 所属节点,
    稳定编码 属性类型) noexcept {
    return 有效(值.编码) && 值.所属节点 == 所属节点
        && 值.属性类型节点 == 属性类型 && 值.来源节点 == 所属节点
        && 值.写入所有者 == 所有者;
}

状态读取结果 状态类数据服务::读取当前内容(状态信息身份 身份) const {
    L1所有者范围一致当前读取请求 请求;
    请求.所有者.push_back(owner_);
    请求.节点.push_back(身份.编码);
    请求.属性值 = {{身份.编码, layout_.内联准确值属性类型},
        {身份.编码, layout_.引用准确值属性类型},
        {身份.编码, layout_.实例绝对时间属性类型},
        {身份.编码, layout_.抽象相对时间属性类型},
        {身份.编码, layout_.首次形成UTC属性类型}};
    请求.源关系组 = {{身份.编码, layout_.状态族归属关系类型},
        {身份.编码, layout_.正式特征类型关系类型}};
    const auto 读取 = l1_.尝试读取所有者范围一致当前投影(请求);
    if (读取.状态 != L1所有者范围一致当前读取状态::成功) {
        return 读取失败(映射一致读取(读取.状态));
    }
    if (读取.所有者.size() != 1 || 读取.节点.size() != 1
        || 读取.属性值.size() != 请求.属性值.size()
        || 读取.源关系组.size() != 请求.源关系组.size()
        || 读取.所有者.front().状态 != 项状态::成功
        || 读取.所有者.front().查询所有者 != owner_
        || !读取.所有者.front().所有者事实) {
        return 读取失败(状态类数据状态::内部不一致);
    }
    const auto& 节点项 = 读取.节点.front();
    if (节点项.状态 == 项状态::未找到 && !节点项.事实) {
        return 读取失败(状态类数据状态::未找到);
    }
    if (节点项.状态 != 项状态::成功 || !节点项.事实) {
        return 读取失败(状态类数据状态::内部不一致);
    }
    const auto& 节点 = *节点项.事实;
    if (节点.编码 != 身份.编码 || 节点.写入所有者 != owner_
        || 节点.种类 != 节点种类::普通 || 节点.属性类型表示) {
        return 读取失败(状态类数据状态::旧格式不支持);
    }

    const auto* 族组 = 查找源关系组(读取.源关系组, 身份.编码,
        layout_.状态族归属关系类型);
    const auto* 类型组 = 查找源关系组(读取.源关系组, 身份.编码,
        layout_.正式特征类型关系类型);
    if (!族组 || !类型组 || 族组->成员.size() != 1 || 类型组->成员.size() != 1) {
        return 读取失败(族组 && 类型组 && 族组->成员.empty() && 类型组->成员.empty()
            ? 状态类数据状态::旧格式不支持 : 状态类数据状态::内部不一致);
    }
    const auto& 族 = 族组->成员.front().关系;
    const auto& 类型 = 类型组->成员.front().关系;
    if (族.写入所有者 != owner_ || 类型.写入所有者 != owner_
        || 族.源节点 != 身份.编码 || 类型.源节点 != 身份.编码
        || 族.关系类型节点 != layout_.状态族归属关系类型
        || 类型.关系类型节点 != layout_.正式特征类型关系类型
        || 族.目标节点 != layout_.状态族锚点
        || 族.角色或顺序 != 1 || 类型.角色或顺序 != 1
        || !有效(类型.目标节点)) {
        return 读取失败(状态类数据状态::旧格式不支持);
    }

    const auto* 内联项 = 查找属性项(读取.属性值, 身份.编码,
        layout_.内联准确值属性类型);
    const auto* 引用项 = 查找属性项(读取.属性值, 身份.编码,
        layout_.引用准确值属性类型);
    const auto* 绝对项 = 查找属性项(读取.属性值, 身份.编码,
        layout_.实例绝对时间属性类型);
    const auto* 相对项 = 查找属性项(读取.属性值, 身份.编码,
        layout_.抽象相对时间属性类型);
    const auto* UTC项 = 查找属性项(读取.属性值, 身份.编码,
        layout_.首次形成UTC属性类型);
    const auto* 内联 = 属性值(内联项, owner_, 身份.编码,
        layout_.内联准确值属性类型);
    const auto* 引用 = 属性值(引用项, owner_, 身份.编码,
        layout_.引用准确值属性类型);
    const auto* 绝对 = 属性值(绝对项, owner_, 身份.编码,
        layout_.实例绝对时间属性类型);
    const auto* 相对 = 属性值(相对项, owner_, 身份.编码,
        layout_.抽象相对时间属性类型);
    const auto* UTC = 属性值(UTC项, owner_, 身份.编码,
        layout_.首次形成UTC属性类型);
    if ((内联 != nullptr) == (引用 != nullptr)
        || (绝对 != nullptr) == (相对 != nullptr) || !UTC
        || (内联 ? !属性未设置(引用项) : !属性未设置(内联项))
        || (绝对 ? !属性未设置(相对项) : !属性未设置(绝对项))) {
        return 读取失败(状态类数据状态::旧格式不支持);
    }

    状态固定准确值 准确值;
    const L1所有者范围值事实* 准确事实 = 内联 ? 内联 : 引用;
    if (内联) {
        const auto* 数值 = std::get_if<std::int64_t>(&内联->材料);
        if (!数值) return 读取失败(状态类数据状态::旧格式不支持);
        准确值 = *数值;
    } else {
        const auto* 编码组 = std::get_if<std::vector<std::uint64_t>>(&引用->材料);
        if (!编码组 || 编码组->size() != 1 || 编码组->front() == 0) {
            return 读取失败(状态类数据状态::旧格式不支持);
        }
        准确值 = 特征值身份{{编码组->front()}};
    }
    const auto* 时间事实 = 绝对 ? 绝对 : 相对;
    const auto* 时间值 = std::get_if<std::int64_t>(&时间事实->材料);
    const auto* UTC值 = std::get_if<std::int64_t>(&UTC->材料);
    if (!时间值 || !UTC值 || *时间值 < 0 || *UTC值 < 0) {
        return 读取失败(状态类数据状态::旧格式不支持);
    }
    状态内容事实 输出{{身份, {类型.目标节点}, std::move(准确值),
        {绝对 ? 状态强时间语义::实例绝对UTC纳秒
              : 状态强时间语义::抽象相对纳秒, *时间值}},
        族.编码, 类型.编码, 准确事实->编码, 时间事实->编码,
        UTC->编码, *UTC值};
    if (!状态内容事实完整(输出)) {
        return 读取失败(状态类数据状态::内部不一致);
    }
    return {头(状态类数据状态::已读取), std::move(输出)};
}

