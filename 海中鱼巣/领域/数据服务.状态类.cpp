状态类数据状态 状态类数据服务::映射读取(
    L1所有者范围读取状态 状态) noexcept {
    switch (状态) {
    case L1所有者范围读取状态::未找到:
        return 状态类数据状态::未找到;
    case L1所有者范围读取状态::资源失败:
        return 状态类数据状态::资源失败;
    case L1所有者范围读取状态::入口拒绝:
        return 状态类数据状态::入口拒绝;
    default:
        return 状态类数据状态::内部不一致;
    }
}

状态类数据状态 状态类数据服务::映射一致读取(
    L1所有者范围一致当前读取状态 状态) noexcept {
    switch (状态) {
    case L1所有者范围一致当前读取状态::资源失败:
        return 状态类数据状态::资源失败;
    case L1所有者范围一致当前读取状态::入口拒绝:
        return 状态类数据状态::入口拒绝;
    default:
        return 状态类数据状态::内部不一致;
    }
}

状态类数据状态 状态类数据服务::映射写入(
    L1所有者范围写入状态 状态, 状态类数据状态 成功状态) noexcept {
    switch (状态) {
    case L1所有者范围写入状态::成功:
        return 成功状态;
    case L1所有者范围写入状态::精确重复:
        return 状态类数据状态::精确重复;
    case L1所有者范围写入状态::幂等冲突:
        return 状态类数据状态::幂等冲突;
    case L1所有者范围写入状态::引用冲突:
        return 状态类数据状态::引用冲突;
    case L1所有者范围写入状态::资源失败:
        return 状态类数据状态::资源失败;
    case L1所有者范围写入状态::入口拒绝:
    case L1所有者范围写入状态::许可拒绝:
        return 状态类数据状态::入口拒绝;
    default:
        return 状态类数据状态::内部不一致;
    }
}

