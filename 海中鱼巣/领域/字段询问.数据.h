#pragma once

#include <cstddef>
#include <cstdint>
#include <optional>
#include <string>
#include <vector>
#include "信息内容.数据.h"

namespace 海中鱼巣 {

// 调用期表达目标，不是需求树中的新需求或字段已明确的事实。
struct 新正式字段询问目标 final {
    正式内容引用定位 被询内容;
    稳定编码 需求范围概念{}, 语言节点{};
    稳定编码 说话者{}, 受询者{}, 交互窗口{}, 交互作用域{};
    稳定编码 第三方指代概念{}, 选用指代名称关系{};
};
// 本地最小表达请求接缝。正式 正式表达需求 经业务侧投影函数落到此形状；
// 候选上的 正式表达需求节点 由装配函数填写（值式本地请求可空）。
using 新字段询问表达需求 = 新正式字段询问目标;

enum class 新字段询问文字状态 : std::uint8_t {
    已生成且唯一回读=1, 缺知识, 缺名称, 缺指称,
    多义, 范围未支持, 前提已变化
};
struct 新字段询问文字结果 final {
    新字段询问文字状态 状态=新字段询问文字状态::缺知识;
    std::string UTF8正文;
    std::vector<稳定编码> 所用知识节点组;
    // 生成与唯一回读共同使用的完整保护；发送合同只在此非空时才可接通。
    std::vector<基础联合节点快照> 完整保护组;
};

// 值式接缝：正式表达需求须先投影为表达目标；此处不创建正式对象。
// 正式节点为空表示当前本地值式请求；非空表示已填写的正式表达需求身份，由装配函数写入。
struct 新字段询问候选 final {
    新正式字段询问目标 表达目标;
    新字段询问文字结果 话语;
    std::optional<稳定编码> 正式表达需求节点;
    friend bool operator==(const 新字段询问候选& a,const 新字段询问候选& b) {
        const auto& x=a.表达目标;const auto& y=b.表达目标;
        return x.被询内容.信息节点==y.被询内容.信息节点
            && x.被询内容.正式内容路径==y.被询内容.正式内容路径
            && x.需求范围概念==y.需求范围概念 && x.语言节点==y.语言节点
            && x.说话者==y.说话者 && x.受询者==y.受询者
            && x.交互窗口==y.交互窗口 && x.交互作用域==y.交互作用域
            && x.第三方指代概念==y.第三方指代概念 && x.选用指代名称关系==y.选用指代名称关系
            && a.话语.状态==b.话语.状态 && a.话语.UTF8正文==b.话语.UTF8正文
            && a.话语.所用知识节点组==b.话语.所用知识节点组
            && a.话语.完整保护组.size()==b.话语.完整保护组.size()
            && [&]{
                for(std::size_t i=0;i<a.话语.完整保护组.size();++i){
                    const auto& x=a.话语.完整保护组[i];const auto& y=b.话语.完整保护组[i];
                    if(x.结构.节点!=y.结构.节点||x.结构.字段组!=y.结构.字段组
                        ||x.入向外部关系组!=y.入向外部关系组||x.出向外部关系组!=y.出向外部关系组
                        ||x.入向字段组!=y.入向字段组)return false;
                }
                return true;
            }()
            && a.正式表达需求节点==b.正式表达需求节点;
    }
};

} // namespace 海中鱼巣
