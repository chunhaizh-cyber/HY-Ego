bool 存在单例角色结构登记结果::成功(
    const 存在单例角色结构登记请求 &请求) const noexcept {
  return 有效(请求.幂等身份) &&
         (状态 == 存在单例角色状态::已登记 ||
          状态 == 存在单例角色状态::精确重复) &&
         交付 && 有效(交付->角色登记类型) &&
         有效(交付->角色目标类型) && 有效(交付->项目角色.值);
}

bool 存在单例角色读取结果::成功(
    const 存在单例角色读取请求 &请求) const noexcept {
  return 有效(请求.角色.值) && 状态 == 存在单例角色状态::已读取 &&
         事实 && 事实->角色 == 请求.角色 && 有效(事实->登记关系) &&
         有效(事实->目标关系) && 有效(事实->存在) &&
         存在身份来源当前见证完整(事实->存在身份, 事实->存在);
}

bool 存在单例角色读取结果::确认未绑定(
    const 存在单例角色读取请求 &请求) const noexcept {
  return 有效(请求.角色.值) && 状态 == 存在单例角色状态::未绑定 &&
         !事实;
}

bool 已发布概念绑定创建结果::成功(
    const 绑定存在创建请求 &请求) const noexcept {
  if ((状态 != 已发布概念绑定状态::已创建 &&
       状态 != 已发布概念绑定状态::精确重复) ||
      !原请求 || *原请求 != 请求 || !投影)
    return false;
  const auto &值 = *投影;
  if (值.绑定.种类 != 请求.绑定.种类 ||
      值.绑定.绑定节点 != 请求.绑定.绑定节点 ||
      !有效(值.绑定.新存在) || !有效(值.绑定.绑定关系) ||
      值.概念 != 请求.概念 ||
      !存在身份来源当前见证完整(值.存在身份, 值.绑定.新存在))
    return false;
  if (请求.初始角色)
    return 值.角色 && 值.角色->角色 == *请求.初始角色 &&
           值.角色->存在 == 值.绑定.新存在;
  return !值.角色;
}

绑定存在数据服务::绑定存在数据服务(
    绑定存在内容参与者 &存在参与者,
    绑定存在场景参与者 &场景参与者)
    : 存在参与者_(存在参与者), 场景参与者_(场景参与者),
      联合提供者_(存在参与者.绑定存在组成提供者(),
                 场景参与者.绑定存在场景提供者()) {
  const auto &底座 = 存在参与者_.绑定存在底座();
  if (&场景参与者_.绑定存在底座() != &底座 ||
      !存在参与者_.绑定存在端口().绑定于(底座) ||
      !场景参与者_.绑定存在端口().绑定于(底座) ||
      !联合提供者_.绑定于(底座))
    throw std::invalid_argument("绑定存在参与者不属于同一事实基座");
}

bool 绑定存在数据服务::使用存在提供者(
    const 绑定存在内容参与者 &提供者) const noexcept {
  return &提供者 == &存在参与者_;
}

bool 绑定存在数据服务::使用场景提供者(
    const 绑定存在场景参与者 &提供者) const noexcept {
  return &提供者 == &场景参与者_;
}

已发布概念绑定创建结果
绑定存在数据服务::创建绑定存在并引用概念(
    const 绑定存在创建请求 &请求,
    已发布概念引用参与者 &概念参与者) noexcept {
  已发布概念绑定创建结果 输出;
  if (!请求形状有效(请求))
    return 输出;

  const auto &底座 = 存在参与者_.绑定存在底座();
  if (!概念参与者.绑定于(底座) ||
      !存在参与者_.绑定存在结构已就绪() ||
      !场景参与者_.绑定存在结构已就绪()) {
    输出.状态 = 已发布概念绑定状态::内部不一致;
    return 输出;
  }

  // 待实现：存在、场景和概念参与者尚未提供current-only原子准备与一次
  // 锁内联合读回合同。这里不得把连续读取伪装成共同快照，也不得先写后补。
  输出.状态 = 已发布概念绑定状态::未实现;
  输出.绑定原因 = 绑定存在创建状态::未实现;
  输出.原请求 = 请求;
  return 输出;
}

bool 绑定存在数据服务::请求形状有效(
    const 绑定存在创建请求 &请求) noexcept {
  if (!有效(请求.绑定.绑定节点) || !有效(请求.期望现实树根) ||
      !有效(请求.概念.编码) ||
      (请求.初始角色 && !有效(请求.初始角色->值)))
    return false;

  if (请求.绑定.种类 == 存在初始绑定种类::父存在组成) {
    const auto *键 = std::get_if<存在组成绑定创建键>(&请求.幂等键);
    return 键 && 有效(键->幂等身份);
  }

  if (请求.绑定.种类 != 存在初始绑定种类::场景成员 &&
      请求.绑定.种类 != 存在初始绑定种类::直接子场景)
    return false;
  const auto *键 = std::get_if<存在场景绑定创建键>(&请求.幂等键);
  return 键 && 有效(键->组合幂等身份) && 有效(键->存在幂等身份) &&
         有效(键->场景幂等身份) &&
         键->组合幂等身份 != 键->存在幂等身份 &&
         键->组合幂等身份 != 键->场景幂等身份 &&
         键->存在幂等身份 != 键->场景幂等身份;
}

