// 新增结果成功谓词
inline bool L2新增需求并建立列表项结果::成功() const noexcept {
    const bool 写成功 = 结果头.状态 == L2结构状态::已提交
        || 结果头.状态 == L2结构状态::精确重复;
    if (!写成功 || 结果头.事实截止代次 == 0
        || !结果头.变更事实代次
        || *结果头.变更事实代次 != 结果头.事实截止代次
        || !新建列表项 || !新建需求
        || !列表项自有关系 || !需求自有关系
        || !当前成员关系) return false;
    const auto 截止 = 结果头.事实截止代次;
    if (!L2需求列表项事实完整(*新建列表项, 截止)
        || 新建列表项->生命周期.退出事实代次) return false;
    if (!L2需求事实完整(*新建需求, 截止)
        || 新建需求->生命周期.退出事实代次) return false;
    // 成员关系连接两者，且不退出
    if (!L2需求列表成员关系事实截止投影完整(*当前成员关系, 截止)
        || 当前成员关系->生命周期.退出事实代次
        || 当前成员关系->列表项 != 新建列表项->身份
        || 当前成员关系->需求 != 新建需求->身份) return false;
    // 列表项与需求目标逐字段完全一致（强不变量）
    if (新建列表项->所属存在 != 新建需求->所属存在
        || 新建列表项->目标宿主存在 != 新建需求->目标宿主存在
        || 新建列表项->目标特征定义 != 新建需求->目标特征定义
        || 新建列表项->目标状态合同 != 新建需求->目标状态合同)
        return false;
    // 父关系可选
    if (当前父关系) {
        if (!L2需求父子关系事实截止投影完整(*当前父关系, 截止)
            || 当前父关系->生命周期.退出事实代次
            || 当前父关系->子需求 != 新建需求->身份) return false;
    }
    return true;
}

inline bool L2新增需求并加入既有列表项结果::成功() const noexcept {
    const bool 写成功 = 结果头.状态 == L2结构状态::已提交
        || 结果头.状态 == L2结构状态::精确重复;
    if (!写成功 || 结果头.事实截止代次 == 0
        || !结果头.变更事实代次
        || *结果头.变更事实代次 != 结果头.事实截止代次
        || !新建需求 || !需求自有关系 || !当前成员关系) return false;
    const auto 截止 = 结果头.事实截止代次;
    if (!L2需求事实完整(*新建需求, 截止)
        || 新建需求->生命周期.退出事实代次) return false;
    if (!L2需求列表成员关系事实截止投影完整(*当前成员关系, 截止)
        || 当前成员关系->生命周期.退出事实代次
        || 当前成员关系->需求 != 新建需求->身份) return false;
    if (当前父关系) {
        if (!L2需求父子关系事实截止投影完整(*当前父关系, 截止)
            || 当前父关系->生命周期.退出事实代次
            || 当前父关系->子需求 != 新建需求->身份) return false;
    }
    return true;
}

inline bool L2需求任务子目标来源写结果成功(
    const L2结构结果头& 结果头,
    const std::optional<L2需求事实>& 子需求,
    const std::optional<L2需求事实>& 父需求,
    const std::optional<L2需求列表项事实>& 所属列表项,
    const std::optional<L2需求列表成员关系事实>& 当前成员关系,
    const std::optional<L2需求父子关系事实>& 当前父关系,
    const std::optional<L2需求任务子目标来源关系事实>& 来源关系) noexcept {
    const bool 写成功 = 结果头.状态 == L2结构状态::已提交
        || 结果头.状态 == L2结构状态::精确重复;
    if (!写成功 || 结果头.事实截止代次 == 0
        || !结果头.变更事实代次
        || *结果头.变更事实代次 != 结果头.事实截止代次
        || !子需求 || !父需求 || !所属列表项 || !当前成员关系
        || !当前父关系 || !来源关系) return false;
    const auto 截止 = 结果头.事实截止代次;
    return L2需求事实完整(*子需求, 截止)
        && L2需求事实完整(*父需求, 截止)
        && L2需求列表项事实完整(*所属列表项, 截止)
        && L2需求列表成员关系事实截止投影完整(*当前成员关系, 截止)
        && L2需求父子关系事实截止投影完整(*当前父关系, 截止)
        && L2需求任务子目标来源关系事实截止投影完整(*来源关系, 截止)
        && !子需求->生命周期.退出事实代次
        && !父需求->生命周期.退出事实代次
        && !所属列表项->生命周期.退出事实代次
        && !当前成员关系->生命周期.退出事实代次
        && !当前父关系->生命周期.退出事实代次
        && 当前成员关系->需求 == 子需求->身份
        && 当前成员关系->列表项 == 所属列表项->身份
        && 当前父关系->子需求 == 子需求->身份
        && 当前父关系->父需求 == 父需求->身份
        && 来源关系->子需求 == 子需求->身份
        && 子需求->所属存在 == 父需求->所属存在
        && 子需求->所属存在 == 所属列表项->所属存在
        && 子需求->目标宿主存在 == 所属列表项->目标宿主存在
        && 子需求->目标特征定义 == 所属列表项->目标特征定义
        && 子需求->目标状态合同 == 所属列表项->目标状态合同;
}

inline bool L2新增需求并建立列表项及任务子目标来源结果::成功() const noexcept {
    return L2需求任务子目标来源写结果成功(结果头, 子需求, 父需求,
        所属列表项, 当前成员关系, 当前父关系, 来源关系);
}

inline bool L2新增需求并加入既有列表项及任务子目标来源结果::成功() const noexcept {
    return L2需求任务子目标来源写结果成功(结果头, 子需求, 父需求,
        所属列表项, 当前成员关系, 当前父关系, 来源关系);
}

inline bool L2为既有需求建立任务子目标来源结果::成功() const noexcept {
    return L2需求任务子目标来源写结果成功(结果头, 子需求, 父需求,
        所属列表项, 当前成员关系, 当前父关系, 来源关系);
}

inline bool L2按任务子目标记录读取需求来源结果::成功() const noexcept {
    if (结果头.状态 != L2结构状态::已读取
        || 结果头.事实截止代次 == 0 || 结果头.变更事实代次
        || 来源关系组.size() > 1) return false;
    return std::all_of(来源关系组.begin(), 来源关系组.end(),
        [&](const auto& 关系) noexcept {
            return L2需求任务子目标来源关系事实截止投影完整(
                关系, 结果头.事实截止代次);
        });
}

inline bool L2按任务子目标记录读取需求来源结果::空结果() const noexcept {
    return 成功() && 来源关系组.empty();
}

inline bool L2按任务子目标记录读取需求来源结果::唯一结果() const noexcept {
    return 成功() && 来源关系组.size() == 1;
}

// 替换父结果成功谓词
inline bool L2替换父需求结果::成功() const noexcept {
    const bool 写成功 = 结果头.状态 == L2结构状态::已提交
        || 结果头.状态 == L2结构状态::精确重复;
    if (!写成功 || 结果头.事实截止代次 == 0
        || !结果头.变更事实代次
        || *结果头.变更事实代次 != 结果头.事实截止代次
        || !已退出父关系) return false;
    const auto 截止 = 结果头.事实截止代次;
    if (!L2需求父子关系事实截止投影完整(*已退出父关系, 截止)
        || 已退出父关系->生命周期.退出事实代次 != 截止) return false;
    // 当前父关系可选（升到根时为空，但此时必须已退出旧关系）
    if (当前父关系) {
        if (!L2需求父子关系事实截止投影完整(*当前父关系, 截止)
            || 当前父关系->生命周期.退出事实代次) return false;
        if (当前父关系->关系稳定编码
            == 已退出父关系->关系稳定编码) return false;
    }
    return true;
}

// 退出需求结果成功谓词
inline bool L2需求退出结果::成功() const noexcept {
    const bool 写成功 = 结果头.状态 == L2结构状态::已提交
        || 结果头.状态 == L2结构状态::精确重复;
    if (!写成功 || 结果头.事实截止代次 == 0
        || !结果头.变更事实代次
        || *结果头.变更事实代次 != 结果头.事实截止代次
        || !已退出需求 || !已退出自有关系
        || !已退出列表成员关系) return false;
    const auto 截止 = 结果头.事实截止代次;
    if (已退出需求->生命周期.退出事实代次 != 截止) return false;
    if (!L2需求事实完整(*已退出需求, 截止)) return false;
    // 自有关系五项退出
    const auto 检查关系退出 = [截止](
        const L2需求关系退出事实& 关系) noexcept {
        return 截止 != 0 && 有效(关系.关系稳定编码)
            && L2生命周期完整(关系.生命周期)
            && 关系.生命周期.退出事实代次 == 截止;
    };
    if (!检查关系退出(已退出自有关系->族归属关系)
        || !检查关系退出(已退出自有关系->所属存在关系)
        || !检查关系退出(已退出自有关系->目标宿主关系)
        || !检查关系退出(已退出自有关系->目标特征关系)
        || !检查关系退出(已退出自有关系->目标合同关系))
        return false;
    // 列表成员关系退出
    if (!L2需求列表成员关系事实截止投影完整(
            *已退出列表成员关系, 截止)
        || 已退出列表成员关系->生命周期.退出事实代次 != 截止)
        return false;
    // 父关系可选
    if (已退出父关系) {
        if (!L2需求父子关系事实截止投影完整(*已退出父关系, 截止)
            || 已退出父关系->生命周期.退出事实代次 != 截止)
            return false;
    }
    return true;
}

// 树与列表成员读取守卫
inline bool L2需求直接子读取请求有效(
    const L2需求直接子读取请求& 请求) noexcept {
    if (!L2结构请求头合同有效(请求.请求头)
        || 请求.请求头.期望事实代次 == 0
        || !有效(请求.父需求.值)) return false;
    return 请求.读取类别 == L2读取类别::当前
        ? 请求.历史截止事实代次 == 0
        : 请求.读取类别 == L2读取类别::历史
            && 请求.历史截止事实代次 != 0
            && 请求.历史截止事实代次 <= 请求.请求头.期望事实代次;
}

