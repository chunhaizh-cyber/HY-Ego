// 替换父需求守卫
inline bool L2替换父需求请求有效(
    const L2替换父需求请求& 请求) noexcept {
    if (!L2结构请求头合同有效(请求.请求头)
        || 请求.请求头.期望事实代次 == 0
        || !L2结构幂等身份有效(请求.幂等身份)
        || !有效(请求.旧关系稳定编码)
        || !有效(请求.旧父需求.值)
        || !有效(请求.子需求.值)
        || 请求.旧父需求 == 请求.子需求
        || !L2需求关系顺序有效(请求.旧顺序)) return false;
    // 新父需求存在时
    if (请求.新父需求) {
        if (!有效(请求.新父需求->值)) return false;
        if (*请求.新父需求 == 请求.子需求) return false;
        if (!L2需求关系顺序有效(请求.新顺序)) return false;
    }
    // 至少一项变化：父变或序变（新父为空时，只要旧父非空就有效）
    const bool 父变化 = 请求.新父需求
        ? (*请求.新父需求 != 请求.旧父需求)
        : true;
    const bool 序变化 = 请求.新父需求
        ? L2需求关系顺序有效(请求.新顺序)
              && (请求.旧顺序 != 请求.新顺序)
        : false;
    if (!父变化 && !序变化) return false;
    return true;
}

// 退出需求守卫
inline bool L2需求退出请求有效(const L2需求退出请求& 请求) noexcept {
    if (!L2结构请求头合同有效(请求.请求头)
        || 请求.请求头.期望事实代次 == 0
        || !L2结构幂等身份有效(请求.幂等身份)
        || !有效(请求.需求.值)) return false;
    const 稳定编码 编码组[] = {
        请求.自有事实闭包.自有关系.族归属关系稳定编码,
        请求.自有事实闭包.自有关系.所属存在关系稳定编码,
        请求.自有事实闭包.自有关系.目标宿主关系稳定编码,
        请求.自有事实闭包.自有关系.目标特征关系稳定编码,
        请求.自有事实闭包.自有关系.目标合同关系稳定编码,
        请求.自有事实闭包.当前列表成员关系稳定编码
    };
    for (std::size_t 左 = 0; 左 < std::size(编码组); ++左) {
        if (!有效(编码组[左]) || 编码组[左] == 请求.需求.值)
            return false;
        for (std::size_t 右 = 0; 右 < 左; ++右)
            if (编码组[左] == 编码组[右]) return false;
    }
    // 当前父关系
    if (请求.自有事实闭包.当前父关系稳定编码) {
        const auto 编码 = *请求.自有事实闭包.当前父关系稳定编码;
        if (!有效(编码) || 编码 == 请求.需求.值) return false;
        for (const auto 其他 : 编码组) if (编码 == 其他) return false;
    }
    // 直接子关系组：排序无重复
    const auto& 子组 = 请求.自有事实闭包.当前直接子关系稳定编码组;
    for (std::size_t 索引 = 0; 索引 < 子组.size(); ++索引) {
        if (!有效(子组[索引]) || 子组[索引] == 请求.需求.值)
            return false;
        for (const auto 其他 : 编码组) if (子组[索引] == 其他) return false;
        if (请求.自有事实闭包.当前父关系稳定编码
            && 子组[索引] == *请求.自有事实闭包.当前父关系稳定编码)
            return false;
        if (索引 != 0 && !(子组[索引 - 1] < 子组[索引])) return false;
    }
    return true;
}

