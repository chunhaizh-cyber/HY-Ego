inline bool 任务执行派发当前阶段证据有效(
    const 任务执行当前阶段证据& 证据) noexcept {
    return 任务阶段值有效(证据.当前阶段)
        && 有效(证据.任务正式存在.值) && 有效(证据.阶段特征实例.值)
        && 有效(证据.当前阶段状态.值) && 有效(证据.当前选择.值)
        && 证据.状态事实代次 != 0 && 证据.引用事实代次 != 0
        && 证据.状态事实代次 <= 证据.引用事实代次
        && 证据.引用事实代次 <= 证据.正式读回截止
        && 证据.正式读回截止 != 0;
}

inline bool 任务执行派发生存控制态证据有效(
    const 任务执行生存控制态证据& 证据) noexcept {
    const bool 竞争一致 = 证据.控制态 == 生存安全控制态::主动运行
        ? 证据.普通任务竞争 == 任务普通竞争适用性::适用
        : 证据.普通任务竞争 == 任务普通竞争适用性::不适用;
    return 竞争一致 && 有效(证据.来源事实或快照身份)
        && 证据.控制态规则版本 != 0 && 证据.正式读回截止 != 0;
}

inline bool 任务执行派发调度资格证据有效(
    const 任务执行调度资格证据& 证据) noexcept {
    if (证据.当前任务需求来源组.empty() || 证据.调度规则版本 == 0
        || 证据.正式读回截止 == 0)
        return false;
    bool 有安全来源 = false;
    bool 有服务来源 = false;
    for (std::size_t i = 0; i < 证据.当前任务需求来源组.size(); ++i) {
        const auto& 来源 = 证据.当前任务需求来源组[i];
        if (!有效(来源.需求.值) || 来源.来源调度配额 == 0
            || 来源.来源版本组.empty()
            || (来源.类别 == 任务调度来源类别::安全
                ? !来源.安全分层倍率 || *来源.安全分层倍率 == 0
                : 来源.类别 != 任务调度来源类别::服务
                    || 来源.安全分层倍率))
            return false;
        有安全来源 = 有安全来源 || 来源.类别 == 任务调度来源类别::安全;
        有服务来源 = 有服务来源 || 来源.类别 == 任务调度来源类别::服务;
        for (const auto 版本 : 来源.来源版本组)
            if (!有效(版本)) return false;
        for (std::size_t j = 0; j < i; ++j)
            if (证据.当前任务需求来源组[j].需求 == 来源.需求) return false;
    }
    return (!有安全来源 || 证据.安全根调度配额 != 0)
        && (!有服务来源 || 证据.服务根调度配额 != 0)
        && (证据.最终调度资格 == 0 || 证据.最终任务优先级 != 0);
}

inline bool 任务执行授权绑定派发(
    const L2自我现实执行授权事实& 授权,
    const 任务执行派发门控请求& 请求) noexcept {
    return 有效(授权.身份.值) && 有效(授权.自我.值)
        && 授权.任务 == 请求.任务 && 授权.任务轮次 == 请求.任务轮次
        && 授权.筹办轮次 == 请求.筹办轮次
        && 授权.执行轮次 == 请求.执行轮次
        && 授权.冻结 == 请求.冻结 && 授权.冻结版本 == 请求.冻结版本
        && 授权.实例方法 == 请求.实例方法 && 授权.方法 == 请求.方法
        && 授权.方法内容版本.值 == 请求.方法内容版本.值
        && 授权.有序冻结动作范围 == 请求.完整有序冻结动作范围
        && 授权.来源共同事实截止 == 请求.共同事实截止
        && 授权.授权规则版本 != 0 && 授权.发生时间 != 0
        && 授权.有效截止时间 >= 授权.发生时间
        && 授权.生命周期.创建事实代次 != 0
        && 授权.生命周期.创建事实代次 <= 请求.共同事实截止
        && !授权.生命周期.退出事实代次;
}

inline bool 任务执行授权事实相同(
    const L2自我现实执行授权事实& 左,
    const L2自我现实执行授权事实& 右) noexcept {
    return 左.身份 == 右.身份 && 左.自我 == 右.自我
        && 左.任务 == 右.任务 && 左.任务轮次 == 右.任务轮次
        && 左.筹办轮次 == 右.筹办轮次 && 左.执行轮次 == 右.执行轮次
        && 左.冻结 == 右.冻结 && 左.冻结版本 == 右.冻结版本
        && 左.实例方法 == 右.实例方法 && 左.方法 == 右.方法
        && 左.方法内容版本 == 右.方法内容版本
        && 左.有序冻结动作范围 == 右.有序冻结动作范围
        && 左.来源共同事实截止 == 右.来源共同事实截止
        && 左.授权规则版本 == 右.授权规则版本
        && 左.发生时间 == 右.发生时间
        && 左.有效截止时间 == 右.有效截止时间
        && 左.生命周期.创建事实代次
            == 右.生命周期.创建事实代次
        && 左.生命周期.退出事实代次
            == 右.生命周期.退出事实代次;
}

inline bool 任务执行强类型请求基本有效(
    const 任务强类型执行请求& 请求) noexcept {
    if (!(请求.合同版本 == 任务强类型执行请求合同版本
        && 有效(请求.执行幂等身份) && 有效(请求.任务.值)
        && 有效(请求.任务轮次.值) && 有效(请求.筹办轮次.值)
        && 有效(请求.执行轮次.值) && 有效(请求.冻结.值)
        && 请求.冻结版本 != 0 && 有效(请求.实例方法.值)
        && 有效(请求.方法.值) && L2方法内容版本有效(请求.方法内容版本)
        && 实例方法技术许可动作范围有效(请求.完整有序冻结动作范围)
        && L2任务治理动作调用事实完整(请求.执行进入治理动作)
        && 请求.执行进入治理动作.任务 == 请求.任务
        && 请求.执行进入治理动作.任务轮次 == 请求.任务轮次
        && 请求.执行进入治理动作.筹办轮次 == 请求.筹办轮次
        && 请求.派发冻结.合同版本 == 任务执行派发门控合同版本
        && 请求.派发冻结.任务 == 请求.任务
        && 请求.派发冻结.任务轮次 == 请求.任务轮次
        && 请求.派发冻结.筹办轮次 == 请求.筹办轮次
        && 请求.派发冻结.执行轮次 == 请求.执行轮次
        && 请求.派发冻结.冻结 == 请求.冻结
        && 请求.派发冻结.冻结版本 == 请求.冻结版本
        && 请求.派发冻结.实例方法 == 请求.实例方法
        && 请求.派发冻结.方法 == 请求.方法
        && 请求.派发冻结.方法内容版本 == 请求.方法内容版本
        && 请求.派发冻结.适用授权.has_value()
            == 请求.适用授权.has_value()
        && (!请求.适用授权
            || 任务执行授权事实相同(
                *请求.派发冻结.适用授权, *请求.适用授权))
        && L2结构幂等身份有效(请求.授权收口幂等身份)
        && 请求.运行代次 != 0))
        return false;
    const auto& 冻结 = 请求.派发冻结;
    if (冻结.共同事实截止 == 0 || 冻结.派发规则版本 == 0
        || !任务执行派发当前阶段证据有效(冻结.当前阶段证据)
        || 冻结.当前阶段证据.正式读回截止 != 冻结.共同事实截止
        || !任务执行派发生存控制态证据有效(冻结.控制态证据)
        || 冻结.控制态证据.控制态 != 生存安全控制态::主动运行
        || 冻结.控制态证据.普通任务竞争 != 任务普通竞争适用性::适用
        || 冻结.控制态证据.正式读回截止 != 冻结.共同事实截止
        || !任务执行派发调度资格证据有效(冻结.调度资格证据)
        || 冻结.调度资格证据.最终调度资格 == 0
        || 冻结.调度资格证据.正式读回截止 != 冻结.共同事实截止
        || 冻结.技术许可证据.正式读回截止 != 冻结.共同事实截止
        || 冻结.技术许可证据.逐项许可见证.size()
            != 请求.完整有序冻结动作范围.size()
        || !冻结.授权前硬否决证据.允许继续()
        || 冻结.授权前硬否决证据.复核阶段
            != 任务现实执行硬否决复核阶段::授权前预检
        || !冻结.动作前最终硬否决证据.允许继续()
        || 冻结.动作前最终硬否决证据.复核阶段
            != 任务现实执行硬否决复核阶段::动作前最终复核
        || 冻结.授权前硬否决证据.本次裁决截止 != 冻结.共同事实截止
        || 冻结.动作前最终硬否决证据.本次裁决截止 != 冻结.共同事实截止)
        return false;
    bool 含现实改变 = false;
    for (std::size_t i = 0; i < 请求.完整有序冻结动作范围.size(); ++i) {
        const auto& 动作 = 请求.完整有序冻结动作范围[i];
        const auto& 许可 = 冻结.技术许可证据.逐项许可见证[i];
        含现实改变 = 含现实改变
            || 动作.作用范围 == 任务动作作用范围::现实改变;
        if (许可.任务 != 请求.任务 || 许可.任务轮次 != 请求.任务轮次
            || 许可.筹办轮次 != 请求.筹办轮次
            || 许可.执行轮次 != 请求.执行轮次
            || 许可.冻结 != 请求.冻结 || 许可.冻结版本 != 请求.冻结版本
            || 许可.实例方法 != 请求.实例方法 || 许可.方法 != 请求.方法
            || 许可.方法内容版本 != 请求.方法内容版本
            || 许可.动作入口 != 动作.动作入口
            || !L2方法稳定动作键有效(许可.稳定动作键)
            || 许可.稳定动作键 != 动作.稳定动作键
            || 许可.端口技术许可合同版本 == 0
            || 许可.正式读回截止 != 冻结.共同事实截止)
            return false;
    }
    if (含现实改变 != 请求.适用授权.has_value()) return false;
    const auto 现实影响 = 含现实改变 ? 任务现实影响分类::含现实改变
        : 任务现实影响分类::零现实改变;
    if (冻结.授权前硬否决证据.现实影响 != 现实影响
        || 冻结.动作前最终硬否决证据.现实影响 != 现实影响)
        return false;
    if (请求.适用授权) {
        const auto& 授权 = *请求.适用授权;
        if (!有效(授权.身份.值) || 授权.任务 != 请求.任务
            || 授权.任务轮次 != 请求.任务轮次
            || 授权.筹办轮次 != 请求.筹办轮次
            || 授权.执行轮次 != 请求.执行轮次
            || 授权.冻结 != 请求.冻结 || 授权.冻结版本 != 请求.冻结版本
            || 授权.实例方法 != 请求.实例方法 || 授权.方法 != 请求.方法
            || 授权.方法内容版本.值 != 请求.方法内容版本.值
            || 授权.有序冻结动作范围 != 请求.完整有序冻结动作范围
            || 授权.来源共同事实截止 != 冻结.共同事实截止
            || 授权.生命周期.创建事实代次 == 0
            || 授权.生命周期.创建事实代次 > 冻结.共同事实截止
            || 授权.生命周期.退出事实代次)
            return false;
    }
    return true;
}

inline bool 任务动作待验证材料有效(
    const 任务动作待验证材料& 材料) noexcept {
    if (材料.合同版本 != 1 || !有效(材料.执行幂等身份)
        || !有效(材料.任务.值) || !有效(材料.任务轮次.值)
        || !有效(材料.筹办轮次.值) || !有效(材料.执行轮次.值)
        || !有效(材料.冻结.值) || 材料.冻结版本 == 0
        || !有效(材料.实例方法.值) || !有效(材料.方法.值)
        || !L2方法内容版本有效(材料.方法内容版本)
        || !有效(材料.执行进入治理动作.值)
        || 材料.运行代次 == 0
        || 材料.预计动态组.empty()
        || 材料.预计动态组.size() != 材料.动作键逐项返回.size()
        || 材料.动作键逐项返回.empty()
        || 材料.动作键逐项返回.size()
            != 材料.派发冻结.技术许可证据.逐项许可见证.size()
        || 材料.动作开始时间 == 0
        || 材料.动作结束时间 < 材料.动作开始时间
        || (材料.执行提供者状态 != 实例方法动作返回状态::动作已结束
            && 材料.执行提供者状态 != 实例方法动作返回状态::精确重复))
        return false;
    for (std::size_t i = 0; i < 材料.动作键逐项返回.size(); ++i) {
        const auto& 返回 = 材料.动作键逐项返回[i];
        const auto& 许可 = 材料.派发冻结.技术许可证据.逐项许可见证[i];
        const auto& 预计 = 材料.预计动态组[i];
        if (返回.顺序 != i + 1 || !有效(返回.动作入口.值)
            || !L2方法稳定动作键有效(返回.稳定动作键)
            || 返回.动作入口 != 许可.动作入口
            || 返回.稳定动作键 != 许可.稳定动作键
            || !返回.结果候选
            || !任务动作结果候选定位有效(*返回.结果候选)
            || 预计.合同版本 != 1
            || 预计.执行幂等身份 != 材料.执行幂等身份
            || 预计.动作顺序 != 返回.顺序
            || 预计.动作入口 != 返回.动作入口
            || 预计.稳定动作键 != 返回.稳定动作键
            || !有效(预计.作用主体.值)
            || (预计.场景约束 && !有效(预计.场景约束->值))
            || !有效(预计.预期结果材料)
            || !有效(预计.结果验证合同)
            || !有效(预计.动作归因合同)
            || (返回.状态 != 实例方法动作返回状态::动作已结束
                && 返回.状态 != 实例方法动作返回状态::精确重复)
            || 返回.动作开始时间 == 0
            || 返回.动作结束时间 < 返回.动作开始时间
            || (i != 0 && 返回.动作开始时间
                < 材料.动作键逐项返回[i - 1].动作结束时间))
            return false;
    }
    return 材料.动作开始时间 == 材料.动作键逐项返回.front().动作开始时间
        && 材料.动作结束时间 == 材料.动作键逐项返回.back().动作结束时间;
}

inline bool 实例方法执行结果::成功() const noexcept {
    return (状态 == 实例方法动作返回状态::动作已结束
            || 状态 == 实例方法动作返回状态::精确重复)
        && 待验证材料 && 待验证材料->执行提供者状态 == 状态
        && 任务动作待验证材料有效(*待验证材料);
}

