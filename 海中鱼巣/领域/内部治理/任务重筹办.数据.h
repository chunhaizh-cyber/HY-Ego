#pragma once

#ifndef 任务重筹办数据_NO_INCLUDES
#include <cstdint>
#include <optional>
#include "../L2任务结构.数据.h"
#endif

namespace 海中鱼巣 {

enum class 任务重筹办触发状态 : std::uint8_t {
    已形成 = 1,
    精确重复 = 2,
    合法等待 = 3,
    当前性漂移 = 4,
    引用冲突 = 5,
    入口拒绝 = 6,
    资源失败 = 7,
    内部错误 = 8
};

struct 下一筹办工作包 final {
    L2任务身份 任务;
    L2任务方法路径身份 旧路径;
    L2实例方法身份 旧实例;
    std::uint64_t 旧执行轮次 = 0;
    L2任务实际结果身份 旧实际结果;
    L2任务目标裁决证据身份 正式目标裁决证据;
    L2任务治理状态身份 正式待重筹办状态;
    std::uint64_t 原共同事实截止 = 0;
    std::uint64_t 迁移后事实代次 = 0;
    std::uint64_t 旧筹办轮次 = 0;
    std::uint64_t 新筹办轮次 = 0;
    std::uint64_t 运行代次 = 0;
    std::uint64_t 原重筹办意图幂等键 = 0;
    friend bool operator==(const 下一筹办工作包&,
        const 下一筹办工作包&) = default;
};

inline bool 下一筹办工作包完整(const 下一筹办工作包& 工作包) noexcept {
    return 有效(工作包.任务.值) && 有效(工作包.旧路径.值)
        && 有效(工作包.旧实例.值) && 工作包.旧执行轮次 != 0
        && 有效(工作包.旧实际结果.值)
        && 有效(工作包.正式目标裁决证据.值)
        && 有效(工作包.正式待重筹办状态.值)
        && 工作包.原共同事实截止 != 0
        && 工作包.迁移后事实代次 != 0
        && 工作包.旧筹办轮次 != 0
        && 工作包.新筹办轮次 == 工作包.旧筹办轮次 + 1
        && 工作包.新筹办轮次 > 工作包.旧筹办轮次
        && 工作包.运行代次 != 0
        && 工作包.原重筹办意图幂等键 != 0;
}

struct 任务重筹办触发结果 final {
    任务重筹办触发状态 状态 = 任务重筹办触发状态::入口拒绝;
    std::optional<下一筹办工作包> 工作包;
    bool 成功() const noexcept {
        return (状态 == 任务重筹办触发状态::已形成
                || 状态 == 任务重筹办触发状态::精确重复)
            && 工作包 && 下一筹办工作包完整(*工作包);
    }
};

} // namespace 海中鱼巣
