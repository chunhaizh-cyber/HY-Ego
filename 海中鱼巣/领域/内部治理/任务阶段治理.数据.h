inline bool 任务阶段值有效(const 任务阶段值& 阶段) noexcept {
    switch (阶段.主阶段) {
    case 任务主阶段::筹办:
        return 阶段.状态段 == 任务业务状态段::待初次筹办
            || 阶段.状态段 == 任务业务状态段::筹办中
            || 阶段.状态段 == 任务业务状态段::筹办等待
            || 阶段.状态段 == 任务业务状态段::可执行已冻结
            || 阶段.状态段 == 任务业务状态段::待自我现实执行授权;
    case 任务主阶段::执行:
        return 阶段.状态段 == 任务业务状态段::执行动作中
            || 阶段.状态段 == 任务业务状态段::执行结果待结算;
    case 任务主阶段::结算:
        return 阶段.状态段 == 任务业务状态段::任务轮次结算中;
    case 任务主阶段::轮次已收束:
        return 阶段.状态段 == 任务业务状态段::轮次已收束待自我决议;
    default:
        return false;
    }
}

