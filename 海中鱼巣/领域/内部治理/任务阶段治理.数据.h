inline bool 任务阶段无动态首态请求有效(
    const 任务阶段无动态首态请求& 请求) noexcept {
    return 请求.合同版本 == 任务阶段结构消费合同版本
        && L2结构请求头合同有效(请求.请求头)
        && 请求.请求头.期望事实代次 != 0
        && L2结构幂等身份有效(请求.幂等身份)
        && 有效(请求.任务正式存在.值)
        && 有效(请求.阶段特征实例.值)
        && 任务阶段值有效(请求.首态)
        && 有效(请求.来源任务轮次)
        && 请求.任务轮次序号 != 0 && 请求.发生时间 != 0
        && 请求.发生时间 <= static_cast<std::uint64_t>(
            (std::numeric_limits<std::int64_t>::max)());
}

inline bool 任务阶段迁移请求有效(
    const 任务阶段迁移请求& 请求) noexcept {
    return 请求.合同版本 == 任务阶段结构消费合同版本
        && L2结构请求头合同有效(请求.请求头)
        && 请求.请求头.期望事实代次 != 0
        && L2结构幂等身份有效(请求.幂等身份)
        && 有效(请求.任务正式存在.值)
        && 有效(请求.阶段特征实例.值)
        && 有效(请求.当前状态.值)
        && L2中性状态引用事实完整_v1(请求.旧当前选择)
        && 请求.旧当前选择.类别 == L2中性状态引用类别_v1::当前选择
        && 请求.旧当前选择.引用方 == 请求.任务正式存在.值
        && 请求.旧当前选择.引用角色 == 请求.阶段特征实例.值
        && 请求.旧当前选择.目标状态 == 请求.当前状态
        && 请求.旧当前选择.生命周期.创建事实代次
            <= 请求.请求头.期望事实代次
        && (!请求.旧当前选择.生命周期.退出事实代次
            || *请求.旧当前选择.生命周期.退出事实代次
                > 请求.请求头.期望事实代次)
        && 任务阶段值有效(请求.目标阶段)
        && 有效(请求.来源治理动作)
        && 请求.任务轮次序号 != 0
        && 请求.当前阶段发生时间 != 0
        && 请求.目标阶段发生时间 != 0
        && 请求.目标阶段发生时间 >= 请求.当前阶段发生时间
        && 请求.当前阶段发生时间 <= static_cast<std::uint64_t>(
            (std::numeric_limits<std::int64_t>::max)())
        && 请求.目标阶段发生时间 <= static_cast<std::uint64_t>(
            (std::numeric_limits<std::int64_t>::max)());
}

inline std::optional<任务阶段中性状态载荷_v2> 解码任务阶段中性状态_v2(
    const L2中性状态事实_v1& 状态) noexcept {
    if (!L2中性状态事实完整_v1(状态)
        || 状态.材料类别 != L2中性材料类别_v1::实例
        || 状态.时间.语义 != L2中性时间语义_v1::绝对UTC纳秒
        || 状态.时间.纳秒 <= 0)
        return {};
    const auto* 材料 = std::get_if<std::vector<std::uint64_t>>(&状态.特征值);
    if (!材料 || 材料->size() != 5 || (*材料)[0] == 0 || (*材料)[1] == 0
        || (*材料)[2] == 0 || (*材料)[3] == 0 || (*材料)[4] == 0)
        return {};
    任务阶段中性状态载荷_v2 载荷{
        {static_cast<任务主阶段>((*材料)[0]),
            static_cast<任务业务状态段>((*材料)[1])},
        static_cast<任务阶段来源种类>((*材料)[2]), (*材料)[3],
        稳定编码{(*材料)[4]}, static_cast<std::uint64_t>(状态.时间.纳秒)};
    return 任务阶段值有效(载荷.阶段)
            && (载荷.来源种类 == 任务阶段来源种类::首态任务轮次
                || 载荷.来源种类 == 任务阶段来源种类::迁移治理动作)
        ? std::optional<任务阶段中性状态载荷_v2>{载荷}
        : std::optional<任务阶段中性状态载荷_v2>{};
}

