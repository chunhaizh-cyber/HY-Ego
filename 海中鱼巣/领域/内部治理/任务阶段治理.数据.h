inline bool 任务阶段写入结果::成功() const noexcept {
    if (合同版本 != 任务阶段结构消费合同版本
        || (状态 != 任务阶段结构状态::已形成
            && 状态 != 任务阶段结构状态::精确重复)
        || 提交见证 || 本次正式读回截止 == 0)
        return false;
    if (写入种类 == 任务阶段写入种类::无动态首态) {
        if (!首态证据 || 迁移证据 || 首态证据->状态事实代次 == 0
            || 首态证据->引用事实代次 == 0
            || 首态证据->状态事实代次 > 首态证据->引用事实代次
            || 首态证据->引用事实代次 > 本次正式读回截止)
            return false;
        return 首态证据->状态.身份 == 首态证据->当前选择.目标状态
            && L2中性状态事实完整_v1(首态证据->状态)
            && 首态证据->状态.形成事实代次 == 首态证据->状态事实代次
            && L2中性状态引用事实完整_v1(首态证据->当前选择)
            && 首态证据->当前选择.类别
                == L2中性状态引用类别_v1::当前选择
            && 首态证据->当前选择.生命周期.创建事实代次
                == 首态证据->引用事实代次
            && !首态证据->当前选择.生命周期.退出事实代次;
    }
    if (写入种类 != 任务阶段写入种类::阶段迁移
        || 首态证据 || !迁移证据 || 迁移证据->状态事实代次 == 0
        || 迁移证据->动态事实代次 == 0 || 迁移证据->引用事实代次 == 0
        || 迁移证据->状态事实代次 > 迁移证据->动态事实代次
        || 迁移证据->动态事实代次 > 迁移证据->引用事实代次
        || 迁移证据->引用事实代次 > 本次正式读回截止)
        return false;
    const auto& 证据 = *迁移证据;
    return 证据.新状态.身份 == 证据.新当前选择.目标状态
        && L2中性状态事实完整_v1(证据.新状态)
        && 证据.新状态.形成事实代次 == 证据.状态事实代次
        && L2中性动态事实完整_v1(证据.新动态)
        && 证据.新动态.形成事实代次 == 证据.动态事实代次
        && 证据.新动态.有序状态组.size() == 2
        && 证据.新动态.有序状态组[0].状态
            == 证据.已退出旧当前选择.目标状态
        && 证据.新动态.有序状态组[1].状态 == 证据.新状态.身份
        && L2中性状态引用事实完整_v1(证据.新当前选择)
        && L2中性状态引用事实完整_v1(证据.已退出旧当前选择)
        && 证据.新当前选择.类别 == L2中性状态引用类别_v1::当前选择
        && 证据.已退出旧当前选择.类别
            == L2中性状态引用类别_v1::当前选择
        && 证据.新当前选择.引用方 == 证据.已退出旧当前选择.引用方
        && 证据.新当前选择.引用角色 == 证据.已退出旧当前选择.引用角色
        && 证据.新当前选择.生命周期.创建事实代次 == 证据.引用事实代次
        && !证据.新当前选择.生命周期.退出事实代次
        && 证据.已退出旧当前选择.生命周期.退出事实代次
        && *证据.已退出旧当前选择.生命周期.退出事实代次
            == 证据.引用事实代次;
}

inline bool 任务阶段当前读取结果::成功() const noexcept {
    return 合同版本 == 任务阶段结构消费合同版本
        && 状态 == 任务阶段结构状态::已读取
        && 提供者结果头.状态 == L2中性结构状态_v1::已读取
        && 当前选择 && 当前状态
        && 本次正式读回截止 != 0
        && 本次正式读回截止 == 提供者结果头.事实截止代次
        && 当前选择->目标状态 == 当前状态->身份
        && L2中性状态引用事实完整_v1(*当前选择)
        && L2中性状态事实完整_v1(*当前状态)
        && 当前状态->形成事实代次 <= 本次正式读回截止
        && 当前选择->生命周期.创建事实代次 <= 本次正式读回截止
        && !当前选择->生命周期.退出事实代次;
}

inline bool 任务阶段历史读取结果::成功() const noexcept {
    if (合同版本 != 任务阶段结构消费合同版本
        || 历史截止事实代次 == 0 || 本次正式读回截止 == 0
        || 历史截止事实代次 > 本次正式读回截止
        || 提供者结果头.事实截止代次 != 本次正式读回截止
        || static_cast<bool>(当前选择) != static_cast<bool>(状态事实))
        return false;
    if (状态 == 任务阶段结构状态::已读取空集)
        return 提供者结果头.状态 == L2中性结构状态_v1::未找到
            && !当前选择 && !状态事实;
    return 状态 == 任务阶段结构状态::已读取 && 当前选择 && 状态事实
        && 提供者结果头.状态 == L2中性结构状态_v1::已读取
        && 当前选择->目标状态 == 状态事实->身份
        && L2中性状态引用事实完整_v1(*当前选择)
        && L2中性状态事实完整_v1(*状态事实)
        && 当前选择->生命周期.创建事实代次 <= 历史截止事实代次
        && (!当前选择->生命周期.退出事实代次
            || *当前选择->生命周期.退出事实代次 > 历史截止事实代次);
}

