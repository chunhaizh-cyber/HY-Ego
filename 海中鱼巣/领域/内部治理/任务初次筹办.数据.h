#pragma once

#ifndef 任务初次筹办数据_NO_INCLUDES
#include <cstdint>
#include <optional>
#include "../L2任务结构.数据.h"
#include "../运行期只读查询.数据.h"
#endif

namespace 海中鱼巣 {

inline constexpr std::uint32_t 需求初次筹办准备合同版本 = 1;

struct 初次筹办准备幂等身份 final {
    std::uint64_t 值 = 0;
    friend bool operator==(const 初次筹办准备幂等身份&,
        const 初次筹办准备幂等身份&) = default;
};

struct 需求初次筹办准备请求 final {
    std::uint32_t 合同版本 = 需求初次筹办准备合同版本;
    初次筹办准备幂等身份 准备幂等身份;
    std::uint64_t 请求身份 = 0;
    std::uint64_t 运行代次 = 0;
    L2结构请求头 请求头;
    L2需求身份 需求;
    L2结构幂等身份 任务建立幂等身份;
    friend bool operator==(const 需求初次筹办准备请求&,
        const 需求初次筹办准备请求&) = default;
};

enum class 需求初次筹办准备状态 : std::uint8_t {
    已形成 = 1,
    精确重复 = 2,
    幂等冲突 = 3,
    目标已满足 = 4,
    已有当前任务 = 5,
    证据不足 = 6,
    当前性漂移 = 7,
    引用冲突 = 8,
    不可比较 = 9,
    入口拒绝 = 10,
    许可拒绝 = 11,
    资源失败 = 12,
    内部错误 = 13
};

struct 任务初次筹办工作包 final {
    std::uint32_t 合同版本 = 需求初次筹办准备合同版本;
    std::uint64_t 运行代次 = 0;
    L2任务事实 任务;
    L2任务身份来源事实 任务身份来源;
    L2需求事实 来源需求;
    L2需求列表成员关系事实 当前成员关系;
    L2需求列表项事实 需求列表项;
    std::uint64_t 筹办轮次 = 1;
    std::uint64_t 原共同事实截止G0 = 0;
    std::uint64_t 任务建立事实代次G1 = 0;
    friend bool operator==(const 任务初次筹办工作包&,
        const 任务初次筹办工作包&) = default;
};

struct 需求初次筹办准备结果 final {
    需求初次筹办准备状态 状态 = 需求初次筹办准备状态::入口拒绝;
    std::optional<需求当前满足裁决快照> 需求裁决;
    std::optional<L2任务事实> 已有当前任务;
    std::optional<L2任务初次筹办准备记录身份> 首次准备记录;
    std::optional<任务初次筹办工作包> 工作包;
    bool 成功() const noexcept;
    friend bool operator==(const 需求初次筹办准备结果&,
        const 需求初次筹办准备结果&) = default;
};

inline bool 需求初次筹办准备请求有效(
    const 需求初次筹办准备请求& 请求) noexcept {
    return 请求.合同版本 == 需求初次筹办准备合同版本
        && 请求.准备幂等身份.值 != 0
        && 请求.请求身份 != 0 && 请求.运行代次 != 0
        && L2结构请求头合同有效(请求.请求头)
        && 请求.请求头.期望事实代次 != 0
        && 有效(请求.需求.值)
        && L2结构幂等身份有效(请求.任务建立幂等身份)
        && 请求.准备幂等身份.值 == 请求.任务建立幂等身份.值;
}

inline bool 任务初次筹办工作包完整(
    const 任务初次筹办工作包& 工作包) noexcept {
    const auto G0 = 工作包.原共同事实截止G0;
    const auto G1 = 工作包.任务建立事实代次G1;
    return 工作包.合同版本 == 需求初次筹办准备合同版本
        && 工作包.运行代次 != 0 && G0 != 0 && G1 > G0
        && 工作包.筹办轮次 == 1
        && 有效(工作包.任务.身份.值)
        && 有效(工作包.任务.任务虚拟存在.值)
        && 工作包.任务.需求列表项 == 工作包.需求列表项.身份
        && 工作包.任务.生命周期.创建事实代次 == G1
        && !工作包.任务.生命周期.退出事实代次
        && L2任务身份来源事实完整(工作包.任务身份来源)
        && 工作包.任务身份来源.任务节点 == 工作包.任务.身份.值
        && 工作包.任务身份来源.任务节点生命周期.创建事实代次 == G1
        && !工作包.任务身份来源.任务节点生命周期.退出事实代次
        && 工作包.任务身份来源.族归属关系生命周期.创建事实代次 == G1
        && !工作包.任务身份来源.族归属关系生命周期.退出事实代次
        && L2需求事实完整(工作包.来源需求, G0)
        && !工作包.来源需求.生命周期.退出事实代次
        && L2需求列表成员关系事实截止投影完整(
            工作包.当前成员关系, G0)
        && !工作包.当前成员关系.生命周期.退出事实代次
        && L2需求列表项事实完整(工作包.需求列表项, G0)
        && !工作包.需求列表项.生命周期.退出事实代次
        && 工作包.当前成员关系.需求 == 工作包.来源需求.身份
        && 工作包.当前成员关系.列表项 == 工作包.需求列表项.身份
        && 工作包.来源需求.所属存在 == 工作包.需求列表项.所属存在
        && 工作包.来源需求.目标宿主存在
            == 工作包.需求列表项.目标宿主存在
        && 工作包.来源需求.目标特征定义
            == 工作包.需求列表项.目标特征定义
        && 工作包.来源需求.目标状态合同
            == 工作包.需求列表项.目标状态合同;
}

inline bool 需求初次筹办准备结果::成功() const noexcept {
    return (状态 == 需求初次筹办准备状态::已形成
            || 状态 == 需求初次筹办准备状态::精确重复)
        && 需求裁决 && !已有当前任务 && 首次准备记录 && 工作包
        && 有效(首次准备记录->值)
        && 需求裁决->事实截止代次 == 工作包->原共同事实截止G0
        && 需求裁决->需求事实.身份 == 工作包->来源需求.身份
        && 需求裁决->当前成员关系 == 工作包->当前成员关系
        && 需求裁决->所属列表项 == 工作包->需求列表项
        && 任务初次筹办工作包完整(*工作包);
}

} // namespace 海中鱼巣
