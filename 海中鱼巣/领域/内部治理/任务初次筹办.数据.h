struct 需求初次筹办准备结果 final {
    需求初次筹办准备状态 状态 = 需求初次筹办准备状态::入口拒绝;
    std::optional<需求当前满足裁决快照> 需求裁决;
    std::optional<L2任务事实> 已有当前任务;
    std::optional<L2任务初次筹办准备记录身份> 首次准备记录;
    std::optional<任务初次筹办工作包> 工作包;
    bool 成功() const noexcept;
    friend bool operator==(const 需求初次筹办准备结果&,
        const 需求初次筹办准备结果&) = default;
};

inline bool 需求初次筹办准备请求有效(
    const 需求初次筹办准备请求& 请求) noexcept {
    return 请求.合同版本 == 需求初次筹办准备合同版本
        && 请求.准备幂等身份.值 != 0
        && 请求.请求身份 != 0 && 请求.运行代次 != 0
        && L2结构请求头合同有效(请求.请求头)
        && 请求.请求头.期望事实代次 != 0
        && 有效(请求.需求.值)
        && L2任务初次筹办阶段幂等身份组有效(请求.阶段幂等身份)
        && 请求.准备幂等身份.值 == 请求.阶段幂等身份.P1建立.值
        && 请求.治理函数合同版本 == L2任务治理函数合同版本
        && 请求.初次筹办推进规则版本 == L2初次筹办推进规则版本;
}

inline bool 任务初次筹办工作包完整(
    const 任务初次筹办工作包& 工作包) noexcept {
    const auto G0 = 工作包.原共同事实截止G0;
    const auto G1 = 工作包.任务核心结果头.事实截止代次;
    return 工作包.合同版本 == 需求初次筹办准备合同版本
        && 工作包.运行代次 != 0 && G0 != 0 && G1 > G0
        && 工作包.筹办轮次 == 1
        && 工作包.任务建立事实代次G1 == G1
        && 工作包.存在结果头.事实截止代次 > G0
        && 工作包.任务核心结果头.事实截止代次
            >= 工作包.存在结果头.事实截止代次
        && 工作包.阶段定义结果头.事实截止代次 >= G1
        && 工作包.阶段实例结果头.事实截止代次
            >= 工作包.阶段定义结果头.事实截止代次
        && 工作包.首态结果头.事实截止代次
            >= 工作包.阶段实例结果头.事实截止代次
        && 工作包.P1结果头.事实截止代次
            >= 工作包.首态结果头.事实截止代次
        && 工作包.首迁移结果头.事实截止代次
            >= 工作包.P1结果头.事实截止代次
        && 有效(工作包.任务.身份.值)
        && 有效(工作包.任务.任务虚拟存在.值)
        && 工作包.任务.需求列表项 == 工作包.需求列表项.身份
        && 工作包.任务.生命周期.创建事实代次 == G1
        && !工作包.任务.生命周期.退出事实代次
        && L2任务身份来源事实完整(工作包.任务身份来源)
        && 工作包.任务身份来源.任务节点 == 工作包.任务.身份.值
        && 工作包.任务身份来源.任务节点生命周期.创建事实代次 == G1
        && !工作包.任务身份来源.任务节点生命周期.退出事实代次
        && 工作包.任务身份来源.族归属关系生命周期.创建事实代次 == G1
        && !工作包.任务身份来源.族归属关系生命周期.退出事实代次
        && L2需求事实完整(工作包.来源需求, G0)
        && !工作包.来源需求.生命周期.退出事实代次
        && L2需求列表成员关系事实截止投影完整(
            工作包.当前成员关系, G0)
        && !工作包.当前成员关系.生命周期.退出事实代次
        && L2需求列表项事实完整(工作包.需求列表项, G0)
        && !工作包.需求列表项.生命周期.退出事实代次
        && 工作包.当前成员关系.需求 == 工作包.来源需求.身份
        && 工作包.当前成员关系.列表项 == 工作包.需求列表项.身份
        && 工作包.来源需求.所属存在 == 工作包.需求列表项.所属存在
        && 工作包.来源需求.目标宿主存在
            == 工作包.需求列表项.目标宿主存在
        && 工作包.来源需求.目标特征定义
            == 工作包.需求列表项.目标特征定义
        && 工作包.来源需求.目标状态合同
            == 工作包.需求列表项.目标状态合同
        && L2任务来源需求关系事实完整(工作包.来源需求关系)
        && 工作包.来源需求关系.任务 == 工作包.任务.身份
        && 工作包.来源需求关系.来源需求 == 工作包.来源需求.身份
        && L2任务正式存在关系事实完整(工作包.正式存在关系)
        && 工作包.正式存在关系.任务 == 工作包.任务.身份
        && 工作包.正式存在关系.正式存在 == 工作包.正式存在.身份
        && 工作包.任务.任务虚拟存在.值 == 工作包.正式存在.身份.值
        && L2任务轮次事实完整(工作包.任务轮次)
        && 工作包.任务轮次.任务 == 工作包.任务.身份
        && 工作包.阶段特征实例.宿主存在 == 工作包.正式存在.身份
        && 工作包.阶段特征实例.特征定义 == 工作包.阶段特征定义.身份
        && L2中性状态事实完整_v1(工作包.待初次筹办首态)
        && L2中性状态事实完整_v1(工作包.筹办中后态)
        && 工作包.待初次筹办首态.特征类型 == 工作包.阶段特征定义.身份
        && 工作包.筹办中后态.特征类型 == 工作包.阶段特征定义.身份
        && L2中性状态引用事实完整_v1(工作包.待初次筹办当前选择)
        && L2中性状态引用事实完整_v1(工作包.筹办中当前选择)
        && L2中性状态引用事实完整_v1(
            工作包.已退出待初次筹办当前选择)
        && 工作包.待初次筹办当前选择.引用方 == 工作包.正式存在.身份.值
        && 工作包.待初次筹办当前选择.引用角色
            == 工作包.阶段特征实例.身份.值
        && 工作包.待初次筹办当前选择.目标状态
            == 工作包.待初次筹办首态.身份
        && 工作包.筹办中当前选择.引用方 == 工作包.正式存在.身份.值
        && 工作包.筹办中当前选择.引用角色
            == 工作包.阶段特征实例.身份.值
        && 工作包.筹办中当前选择.目标状态 == 工作包.筹办中后态.身份
        && 工作包.首次准备记录事实.任务 == 工作包.任务.身份
        && 工作包.首次准备记录事实.任务轮次
            == std::optional{工作包.任务轮次.身份}
        && L2任务初次筹办P1事实完整(工作包.P1)
        && 工作包.P1.任务 == 工作包.任务.身份
        && L2任务治理函数定义事实完整(工作包.治理函数定义)
        && L2任务治理动作调用事实完整(工作包.A1)
        && 工作包.A1.被调用治理函数 == 工作包.治理函数定义.身份
        && 工作包.A1.筹办轮次 == 工作包.P1.身份
        && L2中性动态事实完整_v1(工作包.首迁移动)
        && 工作包.首迁移动.有序状态组.size() == 2
        && 工作包.首迁移动.有序状态组[0].状态
            == 工作包.待初次筹办首态.身份
        && 工作包.首迁移动.有序状态组[1].状态 == 工作包.筹办中后态.身份
        && 工作包.已退出待初次筹办当前选择.身份
            == 工作包.待初次筹办当前选择.身份
        && 工作包.已退出待初次筹办当前选择.生命周期.退出事实代次
        && 工作包.首态状态事实代次
            == 工作包.待初次筹办首态.形成事实代次
        && 工作包.首态引用事实代次
            == 工作包.待初次筹办当前选择.生命周期.创建事实代次
        && 工作包.首迁移状态事实代次 == 工作包.筹办中后态.形成事实代次
        && 工作包.首迁移动事实代次 == 工作包.首迁移动.形成事实代次
        && 工作包.首迁移引用事实代次
            == 工作包.筹办中当前选择.生命周期.创建事实代次
        && *工作包.已退出待初次筹办当前选择.生命周期.退出事实代次
            == 工作包.首迁移引用事实代次
        && 工作包.首态状态事实代次 <= 工作包.首态引用事实代次
        && 工作包.首态引用事实代次 <= 工作包.首态正式读回截止
        && 工作包.首迁移状态事实代次 <= 工作包.首迁移动事实代次
        && 工作包.首迁移动事实代次 <= 工作包.首迁移引用事实代次
        && 工作包.首迁移引用事实代次 <= 工作包.首迁移正式读回截止;
}

