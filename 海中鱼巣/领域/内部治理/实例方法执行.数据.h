namespace 海中鱼巣 {

inline constexpr std::uint32_t 实例方法技术许可合同版本 = 1;

struct 实例方法技术许可请求 final {
    std::uint32_t 合同版本 = 实例方法技术许可合同版本;
    L2任务身份 任务;
    L2任务轮次身份 任务轮次;
    L2任务筹办轮次权威记录身份 筹办轮次;
    L2任务执行轮次身份 执行轮次;
    L2任务执行冻结身份 冻结;
    std::uint64_t 冻结版本 = 0;
    L2实例方法身份 实例方法;
    L2方法身份 方法;
    L2方法内容版本 方法内容版本;
    L2方法动作入口事实_v2 当前动作入口;
    std::vector<任务冻结动作项> 完整有序冻结动作范围;
    std::uint64_t 来源共同事实截止 = 0;
    friend bool operator==(const 实例方法技术许可请求&,
        const 实例方法技术许可请求&) = default;
};

struct 实例方法技术许可见证 final {
    std::uint32_t 合同版本 = 实例方法技术许可合同版本;
    L2任务身份 任务;
    L2任务轮次身份 任务轮次;
    L2任务筹办轮次权威记录身份 筹办轮次;
    L2任务执行轮次身份 执行轮次;
    L2任务执行冻结身份 冻结;
    std::uint64_t 冻结版本 = 0;
    L2实例方法身份 实例方法;
    L2方法身份 方法;
    L2方法内容版本 方法内容版本;
    L2方法动作入口身份 动作入口;
    L2方法稳定动作键 稳定动作键;
    std::uint32_t 端口技术许可合同版本 = 0;
    std::uint64_t 正式读回截止 = 0;
    friend bool operator==(const 实例方法技术许可见证&,
        const 实例方法技术许可见证&) = default;
};

enum class 实例方法技术许可状态 : std::uint8_t {
    已许可 = 1,
    已拒绝 = 2,
    端口不存在 = 3,
    端口冲突 = 4,
    合同不匹配 = 5,
    当前性漂移 = 6,
    资源失败 = 7,
    内部错误 = 8
};

struct 实例方法技术许可结果 final {
    实例方法技术许可状态 状态 = 实例方法技术许可状态::内部错误;
    std::optional<实例方法技术许可见证> 许可见证;
    std::uint64_t 本次正式读回截止 = 0;
    bool 成功() const noexcept {
        return 状态 == 实例方法技术许可状态::已许可
            && 许可见证
            && 许可见证->正式读回截止 == 本次正式读回截止
            && 本次正式读回截止 != 0;
    }
    friend bool operator==(const 实例方法技术许可结果&,
        const 实例方法技术许可结果&) = default;
};

inline bool 实例方法技术许可动作范围有效(
    const std::vector<任务冻结动作项>& 动作范围) noexcept {
    if (动作范围.empty()) return false;
    for (std::size_t i = 0; i < 动作范围.size(); ++i) {
        const auto& 动作 = 动作范围[i];
        if (动作.顺序 != i + 1 || !有效(动作.动作入口.值)
            || !L2方法稳定动作键有效(动作.稳定动作键)
            || (动作.作用范围 != 任务动作作用范围::内部治理
                && 动作.作用范围 != 任务动作作用范围::纯现实观察
                && 动作.作用范围 != 任务动作作用范围::现实改变)
            || !有效(动作.作用主体.值)
            || (动作.作用场景 && !有效(动作.作用场景->值))
            || !有效(动作.动作范围材料)
            || !有效(动作.预期结果材料)
            || !有效(动作.结果验证合同)
            || !有效(动作.动作归因合同))
            return false;
        for (std::size_t j = 0; j < i; ++j)
            if (动作范围[j].动作入口 == 动作.动作入口) return false;
    }
    return true;
}

inline bool 实例方法技术许可请求有效(
    const 实例方法技术许可请求& 请求) noexcept {
    if (请求.合同版本 != 实例方法技术许可合同版本
        || !有效(请求.任务.值) || !有效(请求.任务轮次.值)
        || !有效(请求.筹办轮次.值) || !有效(请求.执行轮次.值)
        || !有效(请求.冻结.值) || 请求.冻结版本 == 0
        || !有效(请求.实例方法.值) || !有效(请求.方法.值)
        || !L2方法内容版本有效(请求.方法内容版本)
        || !实例方法技术许可动作范围有效(请求.完整有序冻结动作范围)
        || 请求.来源共同事实截止 == 0)
        return false;
    const auto& 入口 = 请求.当前动作入口;
    if (!有效(入口.身份.值) || 入口.方法 != 请求.方法
        || 入口.方法内容版本 != 请求.方法内容版本
        || 入口.顺序 == 0 || 入口.顺序 > 请求.完整有序冻结动作范围.size()
        || !L2方法稳定动作键有效(入口.稳定动作键)
        || !L2方法动作作用范围有效(入口.作用范围)
        || !有效(入口.作用主体约束.值)
        || (入口.场景约束 && !有效(入口.场景约束->值))
        || !有效(入口.动作范围材料) || 入口.技术许可合同版本 == 0
        || !有效(入口.预期结果材料) || !有效(入口.结果验证合同)
        || !有效(入口.动作归因合同)
        || 入口.生命周期.创建事实代次 == 0
        || 入口.生命周期.创建事实代次 > 请求.来源共同事实截止
        || 入口.生命周期.退出事实代次)
        return false;
    const auto& 冻结动作 = 请求.完整有序冻结动作范围[
        static_cast<std::size_t>(入口.顺序 - 1)];
    return 冻结动作.动作入口 == 入口.身份
        && 冻结动作.稳定动作键 == 入口.稳定动作键
        && static_cast<std::uint8_t>(冻结动作.作用范围)
            == static_cast<std::uint8_t>(入口.作用范围)
        && 冻结动作.作用主体 == 入口.作用主体约束
        && 冻结动作.作用场景 == 入口.场景约束
        && 冻结动作.动作范围材料 == 入口.动作范围材料
        && 冻结动作.预期结果材料 == 入口.预期结果材料
        && 冻结动作.结果验证合同 == 入口.结果验证合同
        && 冻结动作.动作归因合同 == 入口.动作归因合同;
}

inline bool 实例方法技术许可见证绑定请求(
    const 实例方法技术许可见证& 见证,
    const 实例方法技术许可请求& 请求) noexcept {
    return 见证.合同版本 == 实例方法技术许可合同版本
        && 见证.任务 == 请求.任务 && 见证.任务轮次 == 请求.任务轮次
        && 见证.筹办轮次 == 请求.筹办轮次
        && 见证.执行轮次 == 请求.执行轮次
        && 见证.冻结 == 请求.冻结 && 见证.冻结版本 == 请求.冻结版本
        && 见证.实例方法 == 请求.实例方法 && 见证.方法 == 请求.方法
        && 见证.方法内容版本 == 请求.方法内容版本
        && 见证.动作入口 == 请求.当前动作入口.身份
        && 见证.稳定动作键 == 请求.当前动作入口.稳定动作键
        && 见证.端口技术许可合同版本
            == 请求.当前动作入口.技术许可合同版本
        && 见证.正式读回截止 == 请求.来源共同事实截止
        && 见证.正式读回截止 != 0;
}

inline bool 实例方法技术许可结果形状有效(
    const 实例方法技术许可结果& 结果) noexcept {
    if (结果.状态 == 实例方法技术许可状态::已许可)
        return 结果.成功();
    return !结果.许可见证 && 结果.本次正式读回截止 == 0;
}

} // namespace 海中鱼巣
