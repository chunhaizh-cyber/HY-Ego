inline constexpr std::uint32_t 任务筹办编排合同版本 = 1;

// 筹办闭合结果类型（对齐 5230 §4）
enum class 筹办闭合结果类型 : std::uint8_t {
    可执行冻结 = 1,
    子目标承接 = 2,
    学习需求承接 = 3,
    方法补齐承接 = 4,
    合法等待 = 5,
    目标已完成 = 6,
    授权失效或取消 = 7,
    入口拒绝 = 8,
    资源失败 = 9,
    内部不一致 = 10
};

// 就绪链检查项（对齐 5250 §4）
struct 就绪链检查结果 final {
    bool 方法生命周期当前 = false;
    bool 结果能力命中 = false;
    bool 动作入口当前 = false;
    bool 条件结果对完整 = false;
    bool 输入参数绑定闭合 = false;
    bool 禁止项未命中 = false;
    bool 验证归因合同成立 = false;
    bool 因果状态证据当前 = false;

    bool 全部就绪() const noexcept {
        return 方法生命周期当前 && 结果能力命中 && 动作入口当前
            && 条件结果对完整 && 输入参数绑定闭合 && 禁止项未命中
            && 验证归因合同成立 && 因果状态证据当前;
    }

    bool 存在具体缺口() const noexcept {
        return !全部就绪();
    }
};

// 可执行冻结材料
struct 可执行冻结材料 final {
    L2任务方法路径身份 路径身份;
    L2实例方法身份 实例方法身份;
    L2方法身份 方法;
    稳定编码 方法内容版本;
    L2完整路径材料 完整路径材料;
};

// 学习需求承接材料
struct 学习需求承接材料 final {
    L2特征定义身份 目标特征定义;
    L2目标状态合同身份 目标状态合同;
    L2场景身份 场景;
    L2方法规格材料 作用对象绑定;
    L2方法规格版本 规格版本;
    // 无匹配方法证据：候选读取结果为空
};

// 方法补齐承接材料
struct 方法补齐承接材料 final {
    L2方法身份 候选方法;
    稳定编码 方法内容版本;
    就绪链检查结果 缺口详情;
};

// 执行权状态（对齐 BIZ-L3-004-03-01）
enum class 执行权状态 : std::uint8_t {
    已取得 = 1,
    精确重复 = 2,
    已有有效占用 = 3,
    旧代次待核验 = 4,
    轮次冲突 = 5,
    版本漂移 = 6,
    入口拒绝 = 7,
    内部不一致 = 8
};

// 任务状态分支（对齐 BIZ-L3-004-03-02 N07）
enum class 任务状态分支 : std::uint8_t {
    目标已完成 = 1,
    授权失效或取消 = 2,
    有活动子链或等待条件 = 3,
    普通原子任务可召回 = 4
};

// 筹办方法基线（对齐 BIZ-L3-004-03-02 N04）
// 从任务当前选中路径读取已登记的方法路径事实
// 首轮筹办无路径合法（方法基线为空），非首轮筹办有路径
struct 筹办方法基线 final {
    std::optional<L2任务方法路径身份> 当前选中路径;
    std::optional<L2任务方法路径事实> 路径事实;

    bool 有基线() const noexcept {
        return 当前选中路径 && 路径事实;
    }

    // 已登记的筹办轮次（来自路径事实）
    std::uint64_t 已登记轮次() const noexcept {
        return 路径事实 ? 路径事实->筹办轮次 : 0;
    }
};

// 筹办一致事实快照（对齐 BIZ-L3-004-03-02 N08）
// 冻结同一事实截止版本下任务/需求/列表项/方法基线的一致投影
struct 筹办一致事实 final {
    std::optional<L2任务事实> 任务事实;
    std::optional<L2任务身份来源事实> 任务身份来源;
    std::optional<L2需求事实> 需求事实;
    std::optional<L2需求列表项事实> 列表项事实;
    std::optional<筹办方法基线> 方法基线;
    std::uint64_t 事实截止代次 = 0;

    bool 完整() const noexcept {
        return 任务事实 && 任务身份来源 && 需求事实 && 列表项事实;
    }
};

