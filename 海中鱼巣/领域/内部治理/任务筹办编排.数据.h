// 筹办请求
struct 筹办请求 final {
    L2结构请求头 请求头;
    std::uint32_t 合同版本 = 任务筹办编排合同版本;
    L2需求身份 需求;
    L2任务身份 任务;
    std::uint64_t 筹办轮次 = 0;
    std::uint64_t 运行代次 = 0;  // 运行代次（对齐 5230 §2.3 执行权裁决）
    // 目标状态解析的上下文输入（由调用方从当前世界状态提供）
    L2场景身份 场景;
    L2方法规格材料 作用对象绑定;
    L2方法规格版本 规格版本;
    std::uint64_t 最大扫描结果事实数 = 100;
    std::uint64_t 最大候选方法数 = 10;
};

// 筹办结果
struct 筹办结果 final {
    L2结构结果头 结果头;
    std::uint32_t 合同版本 = 任务筹办编排合同版本;
    筹办闭合结果类型 结果类型 = 筹办闭合结果类型::入口拒绝;
    std::optional<可执行冻结材料> 可执行冻结;
    std::optional<学习需求承接材料> 学习需求承接;
    std::optional<方法补齐承接材料> 方法补齐承接;
    std::optional<合法等待材料> 合法等待;
    std::optional<子目标承接材料> 子目标承接;
    std::optional<授权失效材料> 授权失效;
    std::optional<目标已完成材料> 目标已完成;
    std::string 诊断信息;

    bool 成功() const noexcept {
        return 结果类型 == 筹办闭合结果类型::可执行冻结
            || 结果类型 == 筹办闭合结果类型::学习需求承接
            || 结果类型 == 筹办闭合结果类型::方法补齐承接
            || 结果类型 == 筹办闭合结果类型::合法等待
            || 结果类型 == 筹办闭合结果类型::目标已完成;
    }
};

inline bool 筹办请求有效(const 筹办请求& 请求) noexcept {
    return L2结构请求头合同有效(请求.请求头)
        && 请求.请求头.期望事实代次 != 0
        && 请求.合同版本 == 任务筹办编排合同版本
        && 有效(请求.需求.值)
        && 有效(请求.任务.值)
        && 请求.筹办轮次 != 0
        && 请求.运行代次 != 0
        && 有效(请求.场景.值)
        && L2方法规格材料有效(请求.作用对象绑定)
        && L2方法规格版本有效(请求.规格版本)
        && 请求.最大扫描结果事实数 != 0
        && 请求.最大候选方法数 != 0;
}

