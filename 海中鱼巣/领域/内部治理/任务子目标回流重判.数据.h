namespace 海中鱼巣 {

inline constexpr std::uint32_t 任务子目标回流重判合同版本 = 1;

struct 任务子目标回流重判请求 final {
    std::uint32_t 合同版本 = 任务子目标回流重判合同版本;
    std::uint64_t 请求身份 = 0;
    std::uint64_t 运行代次 = 0;
    L2结构请求头 请求头;
    L2任务子目标承接记录身份 回流记录;
    friend bool operator==(const 任务子目标回流重判请求&,
        const 任务子目标回流重判请求&) = default;
};

enum class 任务子目标回流重判状态 : std::uint8_t {
    目标已满足不筹办 = 1,
    已形成初次筹办 = 2,
    初次筹办精确重复 = 3,
    已形成后继筹办 = 4,
    后继筹办精确重复 = 5,
    轮次权威待迁移 = 6,
    当前任务冲突 = 7,
    回流触发冲突 = 8,
    记录不可消费 = 9,
    证据不足 = 10,
    当前性漂移 = 11,
    幂等冲突 = 12,
    引用冲突 = 13,
    不可比较 = 14,
    入口拒绝 = 15,
    许可拒绝 = 16,
    资源失败 = 17,
    内部错误 = 18
};

struct 任务子目标回流后继筹办工作包 final {
    std::uint32_t 合同版本 = 任务子目标回流重判合同版本;
    std::uint64_t 运行代次 = 0;
    L2任务身份 任务;
    L2任务子目标承接记录身份 回流记录;
    L2需求身份 父需求;
    L2需求列表项身份 需求列表项;
    L2任务后继筹办准备记录事实 后继准备记录;
    std::uint64_t 原共同事实截止G0 = 0;
    std::uint64_t 准备发布事实代次G1 = 0;
    friend bool operator==(const 任务子目标回流后继筹办工作包&,
        const 任务子目标回流后继筹办工作包&) = default;
};

struct 任务子目标回流重判结果 final {
    任务子目标回流重判状态 状态 = 任务子目标回流重判状态::入口拒绝;
    std::optional<需求当前满足裁决快照> 已满足裁决;
    std::optional<任务初次筹办工作包> 初次筹办工作包;
    std::optional<任务子目标回流后继筹办工作包> 后继筹办工作包;
    std::optional<L2任务后继筹办准备记录身份> 冲突后继准备记录;
    bool 已处理() const noexcept;
    friend bool operator==(const 任务子目标回流重判结果&,
        const 任务子目标回流重判结果&) = default;
};

inline bool 任务子目标回流重判请求有效(
    const 任务子目标回流重判请求& 请求) noexcept {
    return 请求.合同版本 == 任务子目标回流重判合同版本
        && 请求.请求身份 != 0 && 请求.运行代次 != 0
        && L2结构请求头合同有效(请求.请求头)
        && 请求.请求头.期望事实代次 != 0
        && 有效(请求.回流记录.值);
}

inline bool 任务子目标回流后继筹办工作包完整(
    const 任务子目标回流后继筹办工作包& 工作包) noexcept {
    const auto& 后继 = 工作包.后继准备记录;
    return 工作包.合同版本 == 任务子目标回流重判合同版本
        && 工作包.运行代次 != 0
        && 有效(工作包.任务.值) && 有效(工作包.回流记录.值)
        && 有效(工作包.父需求.值) && 有效(工作包.需求列表项.值)
        && 工作包.原共同事实截止G0 != 0
        && 工作包.准备发布事实代次G1 > 工作包.原共同事实截止G0
        && L2任务后继筹办准备记录事实完整(后继)
        && 后继.任务 == 工作包.任务
        && 后继.需求列表项 == 工作包.需求列表项
        && 后继.触发类型 == L2任务后继筹办触发类型::子目标回流
        && 后继.触发事实 == 工作包.回流记录.值
        && 后继.来源共同事实截止 == 工作包.原共同事实截止G0
        && 后继.准备发布事实代次 == 工作包.准备发布事实代次G1
        && !后继.旧路径 && !后继.旧实例 && !后继.目标裁决证据
        && !后继.正式待重筹办状态;
}

inline bool 任务子目标回流重判结果::已处理() const noexcept {
    const bool 无初次 = !初次筹办工作包;
    const bool 无后继 = !后继筹办工作包;
    const bool 无裁决 = !已满足裁决;
    const bool 无冲突 = !冲突后继准备记录;
    if (状态 == 任务子目标回流重判状态::目标已满足不筹办) {
        return 已满足裁决 && 无初次 && 无后继 && 无冲突
            && 已满足裁决->事实截止代次 != 0;
    }
    if (状态 == 任务子目标回流重判状态::已形成初次筹办
        || 状态 == 任务子目标回流重判状态::初次筹办精确重复) {
        return 无裁决 && 初次筹办工作包 && 无后继 && 无冲突
            && 任务初次筹办工作包完整(*初次筹办工作包);
    }
    if (状态 == 任务子目标回流重判状态::已形成后继筹办
        || 状态 == 任务子目标回流重判状态::后继筹办精确重复) {
        return 无裁决 && 无初次 && 后继筹办工作包 && 无冲突
            && 任务子目标回流后继筹办工作包完整(*后继筹办工作包);
    }
    return false;
}

} // namespace 海中鱼巣
