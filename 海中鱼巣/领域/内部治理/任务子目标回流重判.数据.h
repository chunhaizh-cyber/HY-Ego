namespace 海中鱼巣 {

inline constexpr std::uint32_t 任务子目标回流重判合同版本 = 2;

struct 任务子目标回流重判请求 final {
    std::uint32_t 合同版本 = 任务子目标回流重判合同版本;
    std::uint64_t 请求身份 = 0;
    std::uint64_t 运行代次 = 0;
    L2结构请求头 请求头;
    L2任务子目标承接记录身份 回流记录;
    L2任务身份 任务;
    L2任务轮次身份 任务轮次;
    L2任务筹办轮次权威记录身份 筹办轮次;
    std::uint64_t 当前筹办轮次序号 = 0;
    friend bool operator==(const 任务子目标回流重判请求&,
        const 任务子目标回流重判请求&) = default;
};

enum class 任务子目标回流重判状态 : std::uint8_t {
    目标已满足不筹办 = 1,
    已形成同轮次新筹办 = 2,
    同轮次新筹办精确重复 = 3,
    轮次权威待迁移 = 6,
    当前任务冲突 = 7,
    回流触发冲突 = 8,
    记录不可消费 = 9,
    证据不足 = 10,
    当前性漂移 = 11,
    幂等冲突 = 12,
    引用冲突 = 13,
    不可比较 = 14,
    入口拒绝 = 15,
    许可拒绝 = 16,
    资源失败 = 17,
    内部错误 = 18,
    发布未知 = 20
};

struct 任务子目标回流同轮次筹办定位 final {
    std::uint32_t 合同版本 = 任务子目标回流重判合同版本;
    std::uint64_t 运行代次 = 0;
    L2任务身份 任务;
    L2任务轮次身份 任务轮次;
    L2任务筹办轮次权威记录身份 筹办轮次;
    L2任务子目标承接记录身份 回流记录;
    L2需求身份 父需求;
    L2需求列表项身份 需求列表项;
    L2任务后继筹办准备记录事实 新筹办准备记录;
    std::uint64_t 原共同事实截止G0 = 0;
    std::uint64_t 准备发布事实代次G1 = 0;
    friend bool operator==(const 任务子目标回流同轮次筹办定位&,
        const 任务子目标回流同轮次筹办定位&) = default;
};

struct 任务子目标回流重判结果 final {
    任务子目标回流重判状态 状态 = 任务子目标回流重判状态::入口拒绝;
    std::optional<需求当前满足裁决快照> 已满足裁决;
    std::optional<任务子目标回流同轮次筹办定位> 同轮次筹办定位;
    std::optional<L2任务后继筹办准备记录身份> 冲突筹办准备记录;
    bool 已处理() const noexcept;
    friend bool operator==(const 任务子目标回流重判结果&,
        const 任务子目标回流重判结果&) = default;
};

inline bool 任务子目标回流重判请求有效(
    const 任务子目标回流重判请求& 请求) noexcept {
    return 请求.合同版本 == 任务子目标回流重判合同版本
        && 请求.请求身份 != 0 && 请求.运行代次 != 0
        && L2结构请求头合同有效(请求.请求头)
        && 请求.请求头.期望事实代次 != 0
        && 有效(请求.回流记录.值)
        && 有效(请求.任务.值) && 有效(请求.任务轮次.值)
        && 有效(请求.筹办轮次.值)
        && 请求.当前筹办轮次序号 != 0;
}

inline bool 任务子目标回流同轮次筹办定位完整(
    const 任务子目标回流同轮次筹办定位& 定位) noexcept {
    const auto& 新筹办 = 定位.新筹办准备记录;
    return 定位.合同版本 == 任务子目标回流重判合同版本
        && 定位.运行代次 != 0 && 有效(定位.任务.值)
        && 有效(定位.任务轮次.值) && 有效(定位.筹办轮次.值)
        && 有效(定位.回流记录.值) && 有效(定位.父需求.值)
        && 有效(定位.需求列表项.值) && 定位.原共同事实截止G0 != 0
        && 定位.准备发布事实代次G1 > 定位.原共同事实截止G0
        && L2任务后继筹办准备记录事实完整(新筹办)
        && 新筹办.轮次权威 == 定位.筹办轮次
        && 新筹办.任务 == 定位.任务
        && 新筹办.需求列表项 == 定位.需求列表项
        && 新筹办.触发类型 == L2任务后继筹办触发类型::子目标回流
        && 新筹办.触发事实 == 定位.回流记录.值
        && 新筹办.来源共同事实截止 == 定位.原共同事实截止G0
        && 新筹办.准备发布事实代次 == 定位.准备发布事实代次G1;
}

inline bool 任务子目标回流重判结果::已处理() const noexcept {
    const bool 无筹办 = !同轮次筹办定位;
    const bool 无裁决 = !已满足裁决;
    const bool 无冲突 = !冲突筹办准备记录;
    if (状态 == 任务子目标回流重判状态::目标已满足不筹办) {
        return 已满足裁决 && 无筹办 && 无冲突
            && 已满足裁决->事实截止代次 != 0;
    }
    if (状态 == 任务子目标回流重判状态::已形成同轮次新筹办
        || 状态 == 任务子目标回流重判状态::同轮次新筹办精确重复)
        return 无裁决 && 同轮次筹办定位 && 无冲突
            && 任务子目标回流同轮次筹办定位完整(*同轮次筹办定位);
    return false;
}

} // namespace 海中鱼巣
