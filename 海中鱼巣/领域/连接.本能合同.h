class 方法参数场景;

struct 新连接登记配置 final {
    稳定编码 自我存在, 自我概念, 通用存在概念;
    稳定编码 交互对象类型, 接收消息类型, 发送消息类型;
    稳定编码 消息正文范围;
    稳定编码 输出队列类型;
    稳定编码 接收数量类型;
    // v4第6参数：交互窗口副本持有的外设场景标识特征类型（R91、R92）。
    稳定编码 外设场景标识类型;
    // R97：v4参数3（交互者副本）、参数1（现实交互场景）的必需特征类型。
    稳定编码 外设存在标识类型, 参与自我类型, 参与交互者类型;
    friend bool operator==(const 新连接登记配置&, const 新连接登记配置&) = default;
};

// 建立连接 v4 唯一有序规格（R97）：1现实交互场景{参与自我,参与交互者}、2自我{交互者}、
// 3交互者副本{外设存在标识}、4交互者特征/2、5交互窗口副本{外设场景标识}、6外设场景标识/5。
inline std::vector<新方法有序参数规格> 建立连接有序规格(const 新连接登记配置& c) {
    using T = 新方法参数信息类型;
    return {
        整理有序参数规格({1, T::存在, c.通用存在概念, {c.参与自我类型, c.参与交互者类型}, 0}),
        整理有序参数规格({2, T::存在, c.自我概念, {c.交互对象类型}, 0}),
        整理有序参数规格({3, T::存在, c.通用存在概念, {c.外设存在标识类型}, 0}),
        {4, T::特征, c.交互对象类型, {}, 2},
        整理有序参数规格({5, T::存在, c.通用存在概念, {c.外设场景标识类型}, 0}),
        {6, T::特征, c.外设场景标识类型, {}, 5}};
}
