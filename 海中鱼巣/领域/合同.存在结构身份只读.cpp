#include "合同.存在结构身份只读.h"

#include <cstddef>

namespace 海中鱼巣 {

bool 存在当前身份确认结果::成功() const noexcept {
  return 状态 == 存在结构身份只读状态::已读取;
}

bool 存在身份来源当前见证完整(
    const 存在身份来源当前见证 &值, 稳定编码 请求身份) noexcept {
  if (!有效(请求身份) || 值.身份 != 请求身份 || 值.角色 != 1)
    return false;
  const 稳定编码 编码组[]{值.身份, 值.族锚点, 值.族归属关系类型,
                             值.族归属关系};
  for (std::size_t i = 0; i < 4; ++i) {
    if (!有效(编码组[i]))
      return false;
    for (std::size_t j = i + 1; j < 4; ++j)
      if (编码组[i] == 编码组[j])
        return false;
  }
  return true;
}

bool 存在身份来源当前见证读取结果::成功(
    稳定编码 请求身份) const noexcept {
  return 状态 == 存在结构身份只读状态::已读取 && 见证 &&
         存在身份来源当前见证完整(*见证, 请求身份);
}

bool 存在已知准确特征见证完整(
    const 存在已知准确特征见证 &值, 稳定编码 请求特征) noexcept {
  return 有效(请求特征) && 有效(值.已知关系) && 有效(值.特征) &&
         值.已知关系 != 值.特征 && 值.特征 == 请求特征;
}

bool 存在已知准确特征读取结果::当前成功(
    const 存在已知准确特征当前请求 &请求) const noexcept {
  return 有效(请求.存在) && 有效(请求.特征) && 请求.存在 != 请求.特征 &&
         状态 == 存在已知准确特征只读状态::已读取 &&
         存在 == 请求.存在 && 特征 == 请求.特征 && 见证 &&
         存在已知准确特征见证完整(*见证, 请求.特征);
}

bool 存在组成读取结果::父读取成功(
    const 存在组成父读取请求 &请求) const noexcept {
  if (!有效(请求.子存在) ||
      状态 != 存在结构身份只读状态::已读取 || !子组.empty())
    return false;
  return !父 || (父->子存在 == 请求.子存在 && 有效(父->关系) &&
                  有效(父->父存在) && 父->父存在 != 父->子存在);
}

bool 存在组成读取结果::子组读取成功(
    const 存在组成子组读取请求 &请求) const noexcept {
  if (!有效(请求.父存在) ||
      状态 != 存在结构身份只读状态::已读取 || 父)
    return false;
  for (std::size_t i = 0; i < 子组.size(); ++i) {
    const auto &项 = 子组[i];
    if (项.父存在 != 请求.父存在 || !有效(项.关系) ||
        !有效(项.子存在) || 项.父存在 == 项.子存在 ||
        (i && 子组[i - 1].关系.值 >= 项.关系.值))
      return false;
  }
  return true;
}

bool 直接归属联合读取结果::父读取成功(
    const 直接归属联合父读取请求 &请求) const noexcept {
  if (!有效(请求.成员) || 状态 != 直接归属联合只读状态::已读取 ||
      !子组.empty())
    return false;
  if (!父)
    return true;
  return 父->成员 == 请求.成员 && 有效(父->关系) && 有效(父->父) &&
         父->父 != 父->成员 &&
         (父->来源 == 直接归属来源::存在组成 ||
          父->来源 == 直接归属来源::场景成员 ||
          父->来源 == 直接归属来源::直接子场景);
}

bool 直接归属联合读取结果::子组读取成功(
    const 直接归属联合子组读取请求 &请求) const noexcept {
  if (!有效(请求.父) || 状态 != 直接归属联合只读状态::已读取 || 父)
    return false;
  for (std::size_t i = 0; i < 子组.size(); ++i) {
    const auto &项 = 子组[i];
    if (项.父 != 请求.父 || !有效(项.关系) || !有效(项.成员) ||
        项.父 == 项.成员 ||
        (项.来源 != 直接归属来源::存在组成 &&
         项.来源 != 直接归属来源::场景成员 &&
         项.来源 != 直接归属来源::直接子场景))
      return false;
    if (i) {
      const auto &前项 = 子组[i - 1];
      if (前项.成员.值 >= 项.成员.值)
        return false;
    }
  }
  return true;
}

bool 直接归属场景角色读取结果::成功(
    const 直接归属场景角色读取请求 &请求) const noexcept {
  if (!有效(请求.对象) || 状态 != 直接归属联合只读状态::已读取)
    return false;
  if (!角色)
    return true;
  if (角色->场景 != 请求.对象)
    return false;
  switch (角色->位置) {
  case 直接归属场景位置::未纳入场景树:
    return !角色->树根 && !角色->树证明关系;
  case 直接归属场景位置::场景树根:
    return 角色->树根 && 角色->树证明关系 && 有效(*角色->树根) &&
           有效(*角色->树证明关系) && *角色->树根 == 请求.对象;
  case 直接归属场景位置::场景树非根:
    return 角色->树根 && 角色->树证明关系 && 有效(*角色->树根) &&
           有效(*角色->树证明关系) && *角色->树根 != 请求.对象;
  default:
    return false;
  }
}

} // namespace 海中鱼巣
