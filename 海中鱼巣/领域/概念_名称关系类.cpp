指代名称读取状态 概念_名称关系类::初始化指代名称结构() {
    using 状态 = 指代名称读取状态;
    std::lock_guard 锁(概念名称关系互斥);
    if (!结构句柄完整()) return 状态::依赖缺失;
    if (!结构仍存在()) return 状态::结构不一致;
    const auto 根 = 全局基础数据集.查询节点组完整结构(
        {自然语言组织根节点, 概念名称关系根节点,
            节点类型字段, 名称关系根类型, 名称关系节点类型,
            被命名概念字段, 目标词条字段});
    if (根.状态 == 基础结构操作状态::资源失败) return 状态::资源失败;
    if (根.状态 != 基础结构操作状态::已完成) return 状态::读取未完成;
    for (const auto& 项 : 根.节点组) {
        if (!项.快照) return 状态::结构不一致;
        if (项.查询节点 == 概念名称关系根节点) {
            if (项.快照->结构.字段组.size() != 1
                || 项.快照->入向外部关系组.size() != 1
                || 项.快照->入向外部关系组.front().源节点
                    != 自然语言组织根节点
                || 项.快照->入向外部关系组.front().类型
                    != 基础外部关系类型::父子
                || 项.快照->入向外部关系组.front().角色或顺序 != 0)
                return 状态::结构不一致;
        } else if (项.查询节点 != 自然语言组织根节点
            && !项.快照->结构.字段组.empty())
            return 状态::结构不一致;
    }
    const auto 键状态 = 指代名称键状态();
    if (键状态 == 状态::已读取 || 键状态 == 状态::资源失败)
        return 键状态;
    if (std::any_of(指代名称键.begin(), 指代名称键.end(),
        [](稳定编码 值) { return 有效(值); }))
        return 状态::结构不一致;
    if (std::all_of(指代名称待核验键.begin(), 指代名称待核验键.end(),
        [](稳定编码 值) { return !有效(值); })) {
        const auto 建立 = 全局基础数据集.原子建立节点组(
            std::vector<基础组内新节点>(3));
        if (建立.状态 == 基础结构操作状态::资源失败)
            return 状态::资源失败;
        if (建立.状态 != 基础结构操作状态::已完成)
            return 状态::结构不一致;
        if (建立.节点组.size() != 3)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
                L"初始化指代名称结构", L"L1 已发布字段键但返回身份数量错误。");
        std::copy(建立.节点组.begin(), 建立.节点组.end(),
            指代名称待核验键.begin());
    }
    std::set<稳定编码> 身份;
    for (const auto 键 : 指代名称待核验键) {
        if (!有效(键) || !身份.insert(键).second)
            return 状态::结构不一致;
        const auto 读取 = 全局基础数据集.查询完整节点结构(键);
        if (读取.状态 == 基础结构操作状态::资源失败)
            return 状态::资源失败;
        if (读取.状态 != 基础结构操作状态::已完成
            || !读取.结构 || !读取.结构->字段组.empty())
            return 状态::结构不一致;
    }
    指代名称键 = 指代名称待核验键;
    return 状态::已读取;
}

bool 概念_名称关系类::初始化() noexcept {
    try {
        if (!词服务_.初始化()) return false;
        {
        std::lock_guard 锁(概念名称关系互斥);
        auto 建立独立节点 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        if (!建立独立节点(节点类型字段)
            || !建立独立节点(名称关系根类型)
            || !建立独立节点(名称关系节点类型)
            || !建立独立节点(被命名概念字段)
            || !建立独立节点(目标词条字段)) {
            return false;
        }
        if (!有效(概念名称关系根节点)) {
            概念名称关系根节点 =
                全局基础数据集.新建节点(自然语言组织根节点);
            if (!有效(概念名称关系根节点)) return false;
        } else if (!节点仍存在(概念名称关系根节点)
            || !有唯一父节点(
                概念名称关系根节点, 自然语言组织根节点)) {
            return false;
        }
        const auto 类型字段组 = 全局基础数据集.查询字段(
            概念名称关系根节点, 节点类型字段);
        if (类型字段组.empty()) {
            if (!有效(全局基础数据集.添加字段节点(
                概念名称关系根节点, 节点类型字段,
                名称关系根类型))) {
                return false;
            }
        } else if (类型字段组.size() != 1
            || !类型为(概念名称关系根节点, 名称关系根类型)) {
            return false;
        }
        if (!结构仍存在()) return false;
        }
        return 准备名称核验全集(
            词服务_, 特征概念服务_, 存在概念服务_, 动态概念服务_).状态
                == 指代名称读取状态::已读取;
    } catch (...) {
        return false;
    }
}

std::vector<稳定编码> 概念_名称关系类::读取词条当前概念组(稳定编码 W) const {
    std::lock_guard 锁(概念名称关系互斥);
    return 当前概念集合(读取当前词条名称(W));
}

std::vector<新词条当前概念候选> 概念_名称关系类::读取词条当前归类候选(稳定编码 W) const {
    std::lock_guard 锁(概念名称关系互斥);
    std::map<稳定编码, bool> 概念组;
    for (const auto& 项 : 读取当前词条名称(W))
        概念组[项.概念] = 概念组[项.概念] || !项.角色;
    std::vector<新词条当前概念候选> 结果;
    结果.reserve(概念组.size());
    for (const auto& [C, 有普通名称] : 概念组) 结果.push_back({C, 有普通名称});
    return 结果;
}

概念名称关系建立结果 概念_名称关系类::建立或取得名称关系(
    稳定编码 概念节点, 稳定编码 词条节点) noexcept {
    try {
        const auto 组 = 建立或取得名称关系组(词条节点, {概念节点});
        if (组.状态 == 概念名称关系建立状态::已建立
            || 组.状态 == 概念名称关系建立状态::已复用)
            return {组.状态, 组.名称关系组.at(0).节点};
        return {组.状态};
    } catch (const std::bad_alloc&) {
        return {概念名称关系建立状态::资源失败};
    } catch (const std::length_error&) {
        return {概念名称关系建立状态::资源失败};
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
            L"建立名称关系", L"批量名称返回缺少单项身份，保留已发表事实。");
    }
}

概念名称关系组建立结果 概念_名称关系类::建立或取得名称关系组(
    稳定编码 词条节点, const std::vector<稳定编码>& 概念组) noexcept {
    return 按实时名称材料执行([&]() -> 概念名称关系组建立结果 {
        bool 已发布 = false;
        try {
            if (!有效(词条节点) || 概念组.empty()) return {};
            auto 有序概念 = 概念组;
            std::sort(有序概念.begin(), 有序概念.end());
            有序概念.erase(std::unique(有序概念.begin(), 有序概念.end()), 有序概念.end());
            for (const auto C : 有序概念)
                if (!有效(C)) return {};
            std::lock_guard 锁(概念名称关系互斥);
            if (!节点仍存在(概念名称关系根节点) || !词服务_.已装配概念挂接()
                || !词服务_.是词条节点(词条节点))
                return {概念名称关系建立状态::依赖不存在};

            std::vector<概念类别> 类别组;
            类别组.reserve(有序概念.size());
            for (const auto C : 有序概念) {
                const auto 类别 = 识别概念类别(C, 特征概念服务_, 存在概念服务_, 动态概念服务_);
                if (!类别) return {概念名称关系建立状态::依赖不存在};
                类别组.push_back(*类别);
            }
            const auto 名称 = 读取当前词条名称(词条节点);
            概念名称关系组建立结果 结果;
            结果.名称关系组.resize(有序概念.size());
            std::vector<基础封存追加片段> 片段组;
            std::vector<std::size_t> 新增输出槽;
            片段组.reserve(有序概念.size());
            新增输出槽.reserve(有序概念.size());
            for (std::size_t i = 0; i < 有序概念.size(); ++i) {
                const auto C = 有序概念[i];
                auto& 输出 = 结果.名称关系组[i];
                输出.概念节点 = C;
                输出.词条节点 = 词条节点;
                const auto 已有 = std::find_if(名称.begin(), 名称.end(),
                    [&](const auto& 项) { return !项.角色 && 项.概念 == C; });
                if (已有 != 名称.end()) {
                    输出.节点 = 已有->快照.结构.节点.编码;
                    continue;
                }
                新增输出槽.push_back(i);
            }
            if (新增输出槽.empty()) {
                结果.状态 = 概念名称关系建立状态::已复用;
                return 结果;
            }
            const auto 原概念 = 当前概念集合(名称);
            std::set<稳定编码> 全部概念(原概念.begin(), 原概念.end());
            全部概念.insert(有序概念.begin(), 有序概念.end());
            const std::vector<稳定编码> 新概念组(全部概念.begin(), 全部概念.end());
            // 集合保护会改变C的入向引用，必须在封存C的联合快照前准备。
            词服务_.准备名称集合材料(新概念组);
            for (const auto i : 新增输出槽) {
                const auto C = 有序概念[i];
                const auto 请求 = 构造名称建立(C, 词条节点);
                const auto 类别 = 类别组[i];
                auto 封存 = 类别 == 概念类别::动态
                    ? 动态概念服务_.封存建立名称参与(请求, 0, C)
                    : (类别 == 概念类别::特征 || 类别 == 概念类别::特征类别根)
                        ? 特征概念服务_.封存建立名称参与(请求, 0, C)
                        : 存在概念服务_.封存建立名称参与(请求, 0, C);
                if (封存.状态 != 基础节点组追加状态::已完成)
                    return {普通发布失败(封存.状态)};
                片段组.push_back(std::move(封存.片段.value()));
            }
            const auto 发布 = 词服务_.发布名称挂接变化(词条节点, 新概念组, 片段组);
            if (发布.状态 != 基础节点组追加状态::已完成) return {普通发布失败(发布.状态)};
            已发布 = true;
            for (std::size_t i = 0; i < 新增输出槽.size(); ++i)
                结果.名称关系组[新增输出槽[i]].节点 = 发布.附加片段回执组.at(i).新节点组().at(0);
            结果.状态 = 概念名称关系建立状态::已建立;
            结果.新状态 = 发布.新状态;
            结果.变化动态 = 发布.变化动态;
            结果.动态原因 = 发布.动态原因;
            return 结果;
        } catch (基础节点组追加状态 状态) {
            if (已发布) 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
                L"建立名称关系组", L"联合发布后发生依赖错误，保留已发表事实。");
            if (本轮名称材料已变化(状态)) throw;
            return {普通发布失败(状态)};
        } catch (const std::bad_alloc&) {
            if (已发布) 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
                L"建立名称关系组", L"联合发布后发生资源错误，保留已发表事实。");
            return {概念名称关系建立状态::资源失败};
        } catch (const std::length_error&) {
            if (已发布) 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
                L"建立名称关系组", L"联合发布后发生长度错误，保留已发表事实。");
            return {概念名称关系建立状态::资源失败};
        } catch (const std::exception& 异常) {
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"建立名称关系组", L"名称联合发布发生工程异常，保留已发表事实。", 异常.what());
        } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"建立名称关系组", L"名称联合发布发生未知工程异常，保留已发表事实。"); }
    });
}

概念名称关系删除状态 概念_名称关系类::删除名称关系(稳定编码 N) noexcept {
    return 按实时名称材料执行([&]() -> 概念名称关系删除状态 {
        try {
            if (!有效(N)) return 概念名称关系删除状态::输入不合法;
            std::lock_guard 锁(概念名称关系互斥);
            if (!节点仍存在(N)) return 概念名称关系删除状态::不存在;
            if (!类型为(N, 名称关系节点类型)) return 概念名称关系删除状态::输入不合法;
            if (!词服务_.已装配概念挂接()) return 概念名称关系删除状态::依赖已变化;
            const auto 项 = 读取当前名称(N);
            if (项.角色) return 概念名称关系删除状态::输入不合法;
            const auto 类别 = 识别概念类别(项.概念, 特征概念服务_, 存在概念服务_, 动态概念服务_);
            if (!类别) return 概念名称关系删除状态::结构不一致;
            const auto 名称 = 读取当前词条名称(项.词条);
            词服务_.准备名称集合材料(当前概念集合(名称, std::nullopt, N));
            const auto 自身 = 封存名称删除(项);
            if (自身.状态 != 基础节点组追加状态::已完成) return 普通删除失败(自身.状态);
            const auto 反向 = *类别 == 概念类别::动态
                ? 动态概念服务_.封存删除名称参与(项.概念, N)
                : (*类别 == 概念类别::特征 || *类别 == 概念类别::特征类别根)
                    ? 特征概念服务_.封存删除名称参与(项.概念, N)
                    : 存在概念服务_.封存删除名称参与(项.概念, N);
            if (反向.状态 != 基础节点组追加状态::已完成) return 普通删除失败(反向.状态);
            const auto 发布 = 词服务_.发布名称挂接变化(项.词条,
                当前概念集合(名称, std::nullopt, N), {自身.片段.value(), 反向.片段.value()});
            return 发布.状态 == 基础节点组追加状态::已完成
                ? 概念名称关系删除状态::已删除 : 普通删除失败(发布.状态);
        } catch (基础节点组追加状态 状态) {
            if (本轮名称材料已变化(状态)) throw;
            return 普通删除失败(状态);
        } catch (const std::bad_alloc&) { return 概念名称关系删除状态::资源失败;
        } catch (const std::length_error&) { return 概念名称关系删除状态::资源失败;
        } catch (const std::exception& 异常) {
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"删除名称关系", L"名称联合删除发生工程异常。", 异常.what());
        } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"删除名称关系", L"名称联合删除发生未知工程异常。"); }
    });
}

概念名称关系查询结果 概念_名称关系类::获取名称关系(
    稳定编码 名称关系节点) const noexcept {
    概念名称关系查询结果 结果;
    try {
        if (!有效(名称关系节点)) return 结果;
        const auto 全集 = 准备名称核验全集(
            词服务_, 特征概念服务_, 存在概念服务_, 动态概念服务_,nullptr,std::nullopt,名称关系节点);
        if (全集.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 普通查询状态(全集.状态); return 结果;
        }
        for (const auto& 项 : 全集.普通)
            if (项.节点 == 名称关系节点) {
                结果.状态 = 概念名称关系查询状态::已找到;
                结果.信息 = 项;
                return 结果;
            }
        for (const auto& 项 : 全集.指代)
            if (项.节点 == 名称关系节点) {
                结果.状态 = 概念名称关系查询状态::已找到;
                结果.信息 = 概念名称关系信息{
                    项.节点, 项.概念.节点, 项.词条.节点};
                return 结果;
            }
        结果.状态 = 概念名称关系查询状态::未找到;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    } catch (const std::length_error&) {
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
            L"获取名称关系", L"混合名称读取发生工程异常。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
            L"获取名称关系", L"混合名称读取发生未知工程异常。");
    }
}

概念名称关系列表查询结果 概念_名称关系类::查询概念名称(
    稳定编码 概念节点) const noexcept {
    概念名称关系列表查询结果 结果;
    try {
        if (!有效(概念节点)) return 结果;
        std::optional<指代概念查询结果> 指代概念;
        if (!识别概念类别(概念节点, 特征概念服务_, 存在概念服务_, 动态概念服务_))
            指代概念 = 存在概念服务_.获取指代概念(概念节点);
        if (指代概念 && 指代概念->状态 != 指代概念查询状态::已找到
            && 指代概念->状态 != 指代概念查询状态::未找到
            && 指代概念->状态 != 指代概念查询状态::输入拒绝
            && 指代概念->状态 != 指代概念查询状态::依赖缺失) {
            结果.状态 = 普通查询状态(映射指代状态(指代概念->状态));
            return 结果;
        }
        const auto 全集 = 准备名称核验全集(
            词服务_, 特征概念服务_, 存在概念服务_, 动态概念服务_,nullptr,概念节点);
        if (全集.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 普通查询状态(全集.状态); return 结果;
        }
        for (const auto& 项 : 全集.普通)
            if (项.概念节点 == 概念节点) 结果.名称关系节点组.push_back(项.节点);
        for (const auto& 项 : 全集.指代)
            if (项.概念.节点 == 概念节点) 结果.名称关系节点组.push_back(项.节点);
        std::sort(结果.名称关系节点组.begin(), 结果.名称关系节点组.end());
        if (指代概念 && 指代概念->状态 == 指代概念查询状态::已找到) {
            if (!指代概念->信息
                || 结果.名称关系节点组 != 指代概念->信息->名称关系) {
                结果.名称关系节点组.clear();
                结果.状态 = 概念名称关系查询状态::读取漂移;
                return 结果;
            }
        }
        结果.状态 = 结果.名称关系节点组.empty()
            ? 概念名称关系查询状态::未找到
            : 概念名称关系查询状态::已找到;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.名称关系节点组.clear();
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    } catch (const std::length_error&) {
        结果.名称关系节点组.clear();
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
            L"查询概念名称", L"混合名称列表读取发生工程异常。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
            L"查询概念名称", L"混合名称列表读取发生未知工程异常。");
    }
}

概念名称关系列表查询结果 概念_名称关系类::查询词条候选概念(
    稳定编码 词条节点) const noexcept {
    概念名称关系列表查询结果 结果;
    try {
        if (!有效(词条节点)) return 结果;
        const auto 词 = 词服务_.获取词条(词条节点);
        if (词.状态 == 新词条查询状态::资源失败) {
            结果.状态 = 概念名称关系查询状态::资源失败;
            return 结果;
        }
        if (词.状态 != 新词条查询状态::已找到) {
            结果.状态 = 词.状态 == 新词条查询状态::未找到
                ? 概念名称关系查询状态::未找到
                : 词.状态 == 新词条查询状态::输入不合法
                    ? 概念名称关系查询状态::输入不合法
                    : 概念名称关系查询状态::结构不一致;
            return 结果;
        }
        if (!词.信息) {
            结果.状态 = 概念名称关系查询状态::结构不一致;
            return 结果;
        }
        // 查询只涉及该词条的完整候选；复用现有保护口的正式端点及快照核同，
        // 不再为返回一个词条的候选而完整审计其它全部词条的名称。
        const auto 候选 = 读取词条名称候选保护(词条节点);
        结果.状态 = 候选.状态;
        if (候选.状态 != 概念名称关系查询状态::已找到) return 结果;
        结果.名称关系节点组.reserve(候选.候选组.size());
        for (const auto& 项 : 候选.候选组)
            结果.名称关系节点组.push_back(std::visit(
                [](const auto& 信息) { return 信息.节点; }, 项));
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.名称关系节点组.clear();
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    } catch (const std::length_error&) {
        结果.名称关系节点组.clear();
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
            L"查询词条候选概念", L"混合名称列表读取发生工程异常。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
            L"查询词条候选概念", L"混合名称列表读取发生未知工程异常。");
    }
}

概念名称候选保护结果 概念_名称关系类::读取词条名称候选保护(
    稳定编码 词条) const noexcept {
    using S = 概念名称关系查询状态;
    try {
        if (!有效(词条)) return {};
        const auto 词 = 词服务_.读取词条保护(词条);
        switch (词.状态) {
        case 新词条保护状态::已读取: break;
        case 新词条保护状态::未找到: return {S::未找到, {}, 词.完整保护};
        case 新词条保护状态::输入拒绝: return {};
        case 新词条保护状态::前提已变化: return {S::读取漂移, {}, {}};
        case 新词条保护状态::资源失败: return {S::资源失败, {}, {}};
        default: throw std::logic_error("word protection state invalid");
        }
        if (!词.信息)
            throw std::logic_error("name word protection payload missing");
        名称保护读集 保护;
        并名称保护(保护, 词.完整保护);
        名称原始全集 原始;
        {
            std::lock_guard 锁(概念名称关系互斥);
            原始 = 读取名称原始全集(std::nullopt, std::nullopt, 词条, true);
            核名称原始保护状态(原始.状态);
            并名称保护(保护, 原始.快照组);
            补名称角色键保护(原始, 保护);
        }
        std::vector<概念名称候选正式信息> 候选;
        std::set<稳定编码> 普通概念, 已核指代概念;
        // 不持名称锁调用其它owner；最后以自身登记和完整读集重核。
        for (const auto& 项 : 原始.项组) {
            if (!项.角色) {
                const 概念名称关系信息 信息{项.快照.结构.节点.编码, 项.概念, 项.词条};
                if (!普通概念.insert(项.概念).second)
                    throw std::logic_error("ordinary name endpoints duplicated");
                核普通名称概念保护(信息, 特征概念服务_, 存在概念服务_, 动态概念服务_, 保护);
                候选.emplace_back(信息);
                continue;
            }
            const auto 概念 = 存在概念服务_.读取指代概念保护(项.概念);
            if (概念.状态 != 指代概念查询状态::已找到) {
                if (概念.状态 == 指代概念查询状态::未找到)
                    throw S::依赖已变化;
                const auto 状态 = 映射指代状态(概念.状态);
                if (状态 == 指代名称读取状态::结构不一致
                    || 状态 == 指代名称读取状态::输入拒绝)
                    throw std::logic_error("pronoun endpoint protection invalid");
                throw 普通查询状态(状态);
            }
            if (!概念.信息
                || std::count(概念.信息->名称关系.begin(), 概念.信息->名称关系.end(),
                    项.快照.结构.节点.编码) != 1)
                throw std::logic_error("pronoun endpoint reverse ownership corrupt");
            并名称保护(保护, 概念.完整保护);
            if (已核指代概念.insert(项.概念).second)
                核指代名称同概念组织(*概念.信息, 保护);
            const auto 来源 = 词服务_.取得语言服务().读取知识先天来源保护(项.来源);
            switch (来源.状态) {
            case 新语言知识来源保护状态::已读取: break;
            case 新语言知识来源保护状态::来源不存在: throw S::依赖已变化;
            case 新语言知识来源保护状态::尚未初始化: throw S::读取未完成;
            case 新语言知识来源保护状态::前提已变化: throw S::读取漂移;
            case 新语言知识来源保护状态::资源失败: throw S::资源失败;
            default: throw std::logic_error("pronoun source protection invalid");
            }
            if (!来源.信息 || !来源.语言信息
                || 来源.信息->语言节点 != 项.语言
                || 词.信息->语言节点 != 项.语言
                || 来源.信息->种类 != 新语言知识来源种类::经确认先天定义
                || 来源.信息->固定原文.find(词.信息->规范化词面) == std::string::npos)
                throw std::logic_error("pronoun source language or content corrupt");
            并名称保护(保护, 来源.完整保护);
            候选.emplace_back(指代名称关系信息{项.快照.结构.节点.编码,
                *概念.信息, *词.信息, *来源.语言信息, *项.角色, *来源.信息});
        }
        {
            std::lock_guard 锁(概念名称关系互斥);
            const auto 再读 = 读取名称原始全集(std::nullopt, std::nullopt, 词条, true);
            核名称原始保护状态(再读.状态);
            if (!同一名称全集(原始, 再读)) throw S::读取漂移;
        }
        std::sort(候选.begin(), 候选.end(), [](const auto& 左, const auto& 右) {
            return std::visit([](const auto& 值) { return 值.节点; }, 左)
                < std::visit([](const auto& 值) { return 值.节点; }, 右);
        });
        const auto 状态 = 候选.empty() ? S::未找到 : S::已找到;
        return {状态, std::move(候选), 完成名称保护(保护)};
    } catch (S 状态) { return {状态, {}, {}}; }
    catch (const std::bad_alloc&) { return {S::资源失败, {}, {}}; }
    catch (const std::length_error&) { return {S::资源失败, {}, {}}; }
    catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取词条名称候选保护",
            L"完整混合名称候选保护发生工程故障。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取词条名称候选保护",
            L"完整混合名称候选保护发生未知工程故障。");
    }
}

bool 概念_名称关系类::是概念名称关系节点(
    稳定编码 节点) const noexcept {
    return 获取名称关系(节点).状态 == 概念名称关系查询状态::已找到;
}

指代名称读取结果 概念_名称关系类::获取指代名称关系(
    稳定编码 名称关系节点) const {
    指代名称读取结果 结果;
    if (!有效(名称关系节点)) return 结果;
    const auto 全集 = 准备名称核验全集(
        词服务_, 特征概念服务_, 存在概念服务_, 动态概念服务_);
    if (全集.状态 != 指代名称读取状态::已读取) {
        结果.状态 = 全集.状态; return 结果;
    }
    const auto 位置 = std::find_if(全集.指代.begin(), 全集.指代.end(),
        [&](const auto& 项) { return 项.节点 == 名称关系节点; });
    if (位置 == 全集.指代.end()) {
        结果.状态 = 指代名称读取状态::未找到; return 结果;
    }
    结果.状态 = 指代名称读取状态::已读取;
    结果.信息 = *位置;
    return 结果;
}

指代名称列表读取结果 概念_名称关系类::查询指代概念名称(
    稳定编码 概念节点) const {
    指代名称列表读取结果 结果;
    if (!有效(概念节点)) return 结果;
    const auto 概念 = 存在概念服务_.获取指代概念(概念节点);
    结果.状态 = 映射指代状态(概念.状态);
    if (结果.状态 != 指代名称读取状态::已读取) return 结果;
    if (!概念.信息) { 结果.状态 = 指代名称读取状态::结构不一致; return 结果; }
    const auto 全集 = 准备名称核验全集(
        词服务_, 特征概念服务_, 存在概念服务_, 动态概念服务_);
    if (全集.状态 != 指代名称读取状态::已读取) {
        结果.状态 = 全集.状态; return 结果;
    }
    for (const auto& 项 : 全集.指代)
        if (项.概念.节点 == 概念节点) 结果.信息组.push_back(项);
    std::sort(结果.信息组.begin(), 结果.信息组.end(),
        [](const auto& 左, const auto& 右) { return 左.节点 < 右.节点; });
    std::vector<稳定编码> 名称身份;
    for (const auto& 项 : 结果.信息组) 名称身份.push_back(项.节点);
    if (名称身份 != 概念.信息->名称关系) {
        结果.信息组.clear();
        结果.状态 = 指代名称读取状态::读取漂移;
    }
    return 结果;
}

指代名称列表读取结果 概念_名称关系类::查询词条指代名称(
    稳定编码 词条节点) const {
    指代名称列表读取结果 结果;
    if (!有效(词条节点)) return 结果;
    const auto 词 = 词服务_.获取词条(词条节点);
    if (词.状态 == 新词条查询状态::资源失败) {
        结果.状态 = 指代名称读取状态::资源失败; return 结果;
    }
    if (词.状态 != 新词条查询状态::已找到) {
        结果.状态 = 词.状态 == 新词条查询状态::未找到
            ? 指代名称读取状态::依赖缺失
            : 词.状态 == 新词条查询状态::输入不合法
                ? 指代名称读取状态::输入拒绝
                : 指代名称读取状态::结构不一致;
        return 结果;
    }
    if (!词.信息) {
        结果.状态 = 指代名称读取状态::结构不一致;
        return 结果;
    }
    const auto 全集 = 准备名称核验全集(
        词服务_, 特征概念服务_, 存在概念服务_, 动态概念服务_);
    if (全集.状态 != 指代名称读取状态::已读取) {
        结果.状态 = 全集.状态; return 结果;
    }
    for (const auto& 项 : 全集.指代)
        if (项.词条.节点 == 词条节点) 结果.信息组.push_back(项);
    std::sort(结果.信息组.begin(), 结果.信息组.end(),
        [](const auto& 左, const auto& 右) { return 左.节点 < 右.节点; });
    结果.状态 = 指代名称读取状态::已读取;
    return 结果;
}

指代名称变更结果 概念_名称关系类::建立或取得指代名称关系(
    const 指代名称建立请求& 请求) {
    return 按实时名称材料执行([&]() -> 指代名称变更结果 {
        指代名称变更结果 结果;
        try {
            if (!有效(请求.概念节点) || !有效(请求.预期词条.节点)
                || !有效(请求.预期来源.节点)
                || 请求.角色 < 指代名称角色::首选名称
                || 请求.角色 > 指代名称角色::简称) return 结果;
            const auto 词 = 词服务_.获取词条(请求.预期词条.节点);
            if (词.状态 == 新词条查询状态::资源失败) {
                结果.状态 = 指代名称变更状态::资源失败; return 结果;
            }
            if (词.状态 != 新词条查询状态::已找到) {
                结果.状态 = 词.状态 == 新词条查询状态::未找到
                    ? 指代名称变更状态::依赖缺失
                    : 词.状态 == 新词条查询状态::输入不合法
                        ? 指代名称变更状态::输入拒绝
                        : 指代名称变更状态::结构不一致;
                return 结果;
            }
            if (!词.信息) {
                结果.状态 = 指代名称变更状态::结构不一致; return 结果;
            }
            const auto 语言 = 词服务_.取得语言服务().获取语言(词.信息->语言节点);
            if (语言.状态 == 新语言查询状态::资源失败) {
                结果.状态 = 指代名称变更状态::资源失败; return 结果;
            }
            if (语言.状态 != 新语言查询状态::已找到) {
                结果.状态 = 语言.状态 == 新语言查询状态::未找到
                    ? 指代名称变更状态::依赖缺失
                    : 语言.状态 == 新语言查询状态::输入不合法
                        ? 指代名称变更状态::输入拒绝
                        : 指代名称变更状态::结构不一致;
                return 结果;
            }
            if (!语言.信息) {
                结果.状态 = 指代名称变更状态::结构不一致; return 结果;
            }
            const auto 来源 = 词服务_.取得语言服务().获取知识先天来源(
                请求.预期来源.节点);
            if (来源.状态 == 新语言知识状态::读取漂移) throw 基础节点组追加状态::预期不符;
            if (来源.状态 != 新语言知识状态::已完成) {
                结果.状态 = 写状态(映射来源状态(来源.状态)); return 结果;
            }
            if (!来源.信息) {
                结果.状态 = 指代名称变更状态::结构不一致; return 结果;
            }
            const auto 截取 = 标量片段(来源.信息->固定原文,
                请求.来源范围.起始标量, 请求.来源范围.结束标量);
            if (!截取 || *截取 != 词.信息->规范化词面
                || 来源.信息->种类 != 新语言知识来源种类::经确认先天定义
                || 来源.信息->语言节点 != 词.信息->语言节点) return 结果;
            const auto 概念 = 存在概念服务_.获取指代概念(请求.概念节点);
            if (概念.状态 == 指代概念查询状态::依赖已变化
                || 概念.状态 == 指代概念查询状态::读取漂移) throw 基础节点组追加状态::预期不符;
            if (概念.状态 != 指代概念查询状态::已找到) {
                结果.状态 = 写状态(映射指代状态(概念.状态)); return 结果;
            }
            if (!概念.信息) {
                结果.状态 = 指代名称变更状态::结构不一致; return 结果;
            }
            std::lock_guard 锁(概念名称关系互斥);
            if (!节点仍存在(概念名称关系根节点) || !词服务_.已装配概念挂接()) { 结果.状态 = 指代名称变更状态::依赖缺失; return 结果; }
            if (指代名称键状态() != 指代名称读取状态::已读取) {
                结果.状态 = 指代名称变更状态::依赖缺失; return 结果;
            }
            // 首选唯一性只查询本概念；词条的集合只查询本词条，不读取名称全集。
            for (const auto& 边 : 全局基础数据集.查询目标字段(请求.概念节点, 被命名概念字段)) {
                const auto 项 = 读取当前名称(边.所属节点);
                if (!项.角色 || 项.语言 != 词.信息->语言节点) continue;
                if (*项.角色 == 指代名称角色::首选名称 && 请求.角色 == 指代名称角色::首选名称
                    && 项.词条 != 词.信息->节点) {
                    结果.状态 = 指代名称变更状态::首选名称冲突;
                    结果.已取得关系身份 = 项.快照.结构.节点.编码; return 结果;
                }
                if (项.词条 == 词.信息->节点 && *项.角色 == 请求.角色) {
                    结果.已取得关系身份 = 项.快照.结构.节点.编码;
                    if (项.来源 != 来源.信息->节点) {
                        结果.状态 = 指代名称变更状态::请求内容冲突; return 结果;
                    }
                    结果.信息 = 指代名称关系信息{*结果.已取得关系身份, *概念.信息,
                        *词.信息, *语言.信息, 请求.角色, *来源.信息};
                    结果.状态 = 指代名称变更状态::已复用;
                    结果.本次处理 = 指代名称本次处理::复用;
                    结果.阶段 = 指代名称核验阶段::已完成核验;
                    return 结果;
                }
            }
            const auto 名称 = 读取当前词条名称(词.信息->节点);
            词服务_.准备名称集合材料(当前概念集合(名称, 请求.概念节点));
            const auto 新名 = 构造名称建立(请求.概念节点, 词.信息->节点,
                请求.角色, 词.信息->语言节点, 来源.信息->节点);
            const auto 封存 = 存在概念服务_.封存建立名称参与(新名, 0, 请求.概念节点);
            if (封存.状态 != 基础节点组追加状态::已完成) {
                结果.状态 = 写状态(封存.状态); return 结果;
            }
            auto 当前概念 = *概念.信息;
            当前概念.名称关系.reserve(当前概念.名称关系.size() + 1);
            const auto 发布 = 词服务_.发布名称挂接变化(词.信息->节点,
                当前概念集合(名称, 请求.概念节点), {封存.片段.value()});
            if (发布.状态 != 基础节点组追加状态::已完成) {
                结果.状态 = 写状态(发布.状态); return 结果;
            }
            结果.已取得关系身份 = 发布.附加片段回执组.at(0).新节点组().at(0);
            结果.本次处理 = 指代名称本次处理::新建;
            当前概念.名称关系.push_back(*结果.已取得关系身份);
            std::sort(当前概念.名称关系.begin(), 当前概念.名称关系.end());
            结果.信息 = 指代名称关系信息{*结果.已取得关系身份, std::move(当前概念),
                *词.信息, *语言.信息, 请求.角色, *来源.信息};
            结果.阶段 = 指代名称核验阶段::已完成核验;
            结果.状态 = 指代名称变更状态::已建立;
            return 结果;
        } catch (基础节点组追加状态 状态) {
            if (本轮名称材料已变化(状态)) throw;
            结果.状态 = 写状态(状态); return 结果;
        } catch (const std::bad_alloc&) {
            if (!结果.已取得关系身份) { 结果.状态 = 指代名称变更状态::资源失败; return 结果; }
            结果.信息.reset(); 结果.状态 = 指代名称变更状态::工程未完成;
            结果.取得身份后异常 = std::current_exception(); return 结果;
        } catch (const std::length_error&) {
            if (!结果.已取得关系身份) { 结果.状态 = 指代名称变更状态::资源失败; return 结果; }
            结果.信息.reset(); 结果.状态 = 指代名称变更状态::工程未完成;
            结果.取得身份后异常 = std::current_exception(); return 结果;
        } catch (...) {
            if (!结果.已取得关系身份) throw;
            结果.信息.reset();
            结果.状态 = 指代名称变更状态::工程未完成;
            结果.取得身份后异常 = std::current_exception();
            return 结果;
        }
    });
}

指代名称变更结果 概念_名称关系类::删除指代名称关系(稳定编码 N) {
    return 按实时名称材料执行([&]() -> 指代名称变更结果 {
        指代名称变更结果 结果;
        try {
            if (!有效(N)) return 结果;
            std::lock_guard 锁(概念名称关系互斥);
            if (!词服务_.已装配概念挂接()) { 结果.状态 = 指代名称变更状态::依赖缺失; return 结果; }
            if (!节点仍存在(N)) { 结果.状态 = 指代名称变更状态::不存在; return 结果; }
            if (!类型为(N, 名称关系节点类型)) return 结果;
            const auto 项 = 读取当前名称(N);
            if (!项.角色) return 结果;
            const auto 名称 = 读取当前词条名称(项.词条);
            词服务_.准备名称集合材料(当前概念集合(名称, std::nullopt, N));
            const auto 自身 = 封存名称删除(项);
            if (自身.状态 != 基础节点组追加状态::已完成) {
                结果.状态 = 写状态(自身.状态); return 结果;
            }
            const auto 反向 = 存在概念服务_.封存删除名称参与(项.概念, N);
            if (反向.状态 != 基础节点组追加状态::已完成) {
                结果.状态 = 写状态(反向.状态); return 结果;
            }
            const auto 发布 = 词服务_.发布名称挂接变化(项.词条,
                当前概念集合(名称, std::nullopt, N), {自身.片段.value(), 反向.片段.value()});
            if (发布.状态 != 基础节点组追加状态::已完成) {
                结果.状态 = 写状态(发布.状态); return 结果;
            }
            结果.已取得关系身份 = N;
            结果.本次处理 = 指代名称本次处理::删除;
            结果.阶段 = 指代名称核验阶段::已完成核验;
            结果.状态 = 指代名称变更状态::已删除;
            return 结果;
        } catch (基础节点组追加状态 状态) {
            if (本轮名称材料已变化(状态)) throw;
            结果.状态 = 写状态(状态); return 结果;
        } catch (const std::bad_alloc&) {
            if (!结果.已取得关系身份) { 结果.状态 = 指代名称变更状态::资源失败; return 结果; }
            结果.信息.reset(); 结果.状态 = 指代名称变更状态::工程未完成;
            结果.取得身份后异常 = std::current_exception(); return 结果;
        } catch (const std::length_error&) {
            if (!结果.已取得关系身份) { 结果.状态 = 指代名称变更状态::资源失败; return 结果; }
            结果.信息.reset(); 结果.状态 = 指代名称变更状态::工程未完成;
            结果.取得身份后异常 = std::current_exception(); return 结果;
        } catch (...) {
            if (!结果.已取得关系身份) throw;
            结果.状态 = 指代名称变更状态::工程未完成;
            结果.取得身份后异常 = std::current_exception();
            return 结果;
        }
    });
}

