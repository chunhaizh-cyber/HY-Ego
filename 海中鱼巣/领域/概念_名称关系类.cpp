概念_名称关系类::概念_名称关系类(
    新_词类& 词服务,
    概念_特征类& 特征概念服务,
    概念_存在类& 存在概念服务) noexcept
    : 词服务_(词服务),
      特征概念服务_(特征概念服务),
      存在概念服务_(存在概念服务) {}

bool 概念_名称关系类::初始化() noexcept {
    try {
        if (!词服务_.初始化()) return false;
        std::lock_guard 锁(概念名称关系互斥);
        auto 建立独立节点 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        if (!建立独立节点(节点类型字段)
            || !建立独立节点(名称关系根类型)
            || !建立独立节点(名称关系节点类型)
            || !建立独立节点(被命名概念字段)
            || !建立独立节点(目标词条字段)) {
            return false;
        }
        if (!有效(概念名称关系根节点)) {
            概念名称关系根节点 =
                全局基础数据集.新建节点(自然语言组织根节点);
            if (!有效(概念名称关系根节点)) return false;
        } else if (!节点仍存在(概念名称关系根节点)
            || !有唯一父节点(
                概念名称关系根节点, 自然语言组织根节点)) {
            return false;
        }
        const auto 类型字段组 = 全局基础数据集.查询字段(
            概念名称关系根节点, 节点类型字段);
        if (类型字段组.empty()) {
            if (!有效(全局基础数据集.添加字段节点(
                概念名称关系根节点, 节点类型字段,
                名称关系根类型))) {
                return false;
            }
        } else if (类型字段组.size() != 1
            || !类型为(概念名称关系根节点, 名称关系根类型)) {
            return false;
        }
        if (!结构仍存在()) return false;
        for (const auto& 关系 : 全局基础数据集.查询源关系(
            概念名称关系根节点, 基础外部关系类型::父子)) {
            if (关系.角色或顺序 != 0) return false;
            const auto 信息 = 读取关系端点(
                关系.目标节点, 词服务_, 特征概念服务_, 存在概念服务_);
            if (!信息 || !概念持有关系(
                *信息, 特征概念服务_, 存在概念服务_)) {
                return false;
            }
        }
        return true;
    } catch (...) {
        return false;
    }
}

概念名称关系建立结果 概念_名称关系类::建立或取得名称关系(
    稳定编码 概念节点,
    稳定编码 词条节点) noexcept {
    概念名称关系建立结果 结果;
    try {
        std::lock_guard 锁(概念名称关系互斥);
        if (!结构仍存在() || !有效(概念节点) || !有效(词条节点)) {
            return 结果;
        }
        const auto 类别 = 识别概念类别(
            概念节点, 特征概念服务_, 存在概念服务_);
        if (!类别 || !词服务_.是词条节点(词条节点)) {
            结果.状态 = 概念名称关系建立状态::依赖不存在;
            return 结果;
        }
        for (const auto& 组织关系 : 全局基础数据集.查询源关系(
            概念名称关系根节点, 基础外部关系类型::父子)) {
            if (组织关系.角色或顺序 != 0) {
                结果.状态 = 概念名称关系建立状态::结构不一致;
                return 结果;
            }
            const auto 信息 = 读取关系端点(
                组织关系.目标节点, 词服务_,
                特征概念服务_, 存在概念服务_);
            if (!信息 || !概念持有关系(
                *信息, 特征概念服务_, 存在概念服务_)) {
                结果.状态 = 概念名称关系建立状态::结构不一致;
                return 结果;
            }
            if (信息->概念节点 == 概念节点
                && 信息->词条节点 == 词条节点) {
                结果.状态 = 概念名称关系建立状态::已复用;
                结果.名称关系节点 = 信息->节点;
                return 结果;
            }
        }

        const auto 节点 = 全局基础数据集.新建节点();
        if (!有效(节点)) {
            结果.状态 = 概念名称关系建立状态::资源失败;
            return 结果;
        }
        std::vector<稳定编码> 字段组;
        const auto 写字段 = [&](稳定编码 字段, 稳定编码 目标) {
            const auto 关系 = 全局基础数据集.添加字段节点(节点, 字段, 目标);
            if (有效(关系)) 字段组.push_back(关系);
            return 有效(关系);
        };
        const bool 字段完成 = 写字段(节点类型字段, 名称关系节点类型)
            && 写字段(被命名概念字段, 概念节点)
            && 写字段(目标词条字段, 词条节点);
        const auto 组织关系 = 字段完成
            ? 全局基础数据集.添加关系(
                概念名称关系根节点, 节点,
                基础外部关系类型::父子, 0)
            : 稳定编码{};
        const bool 绑定完成 = 有效(组织关系)
            && (*类别 == 概念类别::特征
                ? 特征概念服务_.绑定名称关系(概念节点, 节点)
                : 存在概念服务_.绑定名称关系(概念节点, 节点));
        if (!绑定完成) {
            回滚关系节点(节点, 字段组);
            结果.状态 = 概念名称关系建立状态::资源失败;
            return 结果;
        }
        const auto 读回 = 获取名称关系(节点);
        if (读回.状态 == 概念名称关系查询状态::已找到
            && 读回.信息
            && 读回.信息->概念节点 == 概念节点
            && 读回.信息->词条节点 == 词条节点) {
            结果.状态 = 概念名称关系建立状态::已建立;
            结果.名称关系节点 = 节点;
            return 结果;
        }
        if (*类别 == 概念类别::特征) {
            (void)特征概念服务_.解除名称关系(概念节点, 节点);
        } else {
            (void)存在概念服务_.解除名称关系(概念节点, 节点);
        }
        回滚关系节点(节点, 字段组);
        结果.状态 = 概念名称关系建立状态::结构不一致;
        return 结果;
    } catch (...) {
        结果.状态 = 概念名称关系建立状态::资源失败;
        return 结果;
    }
}

概念名称关系删除状态 概念_名称关系类::删除名称关系(
    稳定编码 名称关系节点) noexcept {
    try {
        std::lock_guard 锁(概念名称关系互斥);
        if (!有效(名称关系节点)) {
            return 概念名称关系删除状态::输入不合法;
        }
        if (!节点仍存在(名称关系节点)) {
            return 概念名称关系删除状态::不存在;
        }
        if (!结构仍存在()) return 概念名称关系删除状态::结构不一致;
        const auto 信息 = 读取关系端点(
            名称关系节点, 词服务_, 特征概念服务_, 存在概念服务_);
        const auto 类别 = 信息 ? 识别概念类别(
            信息->概念节点, 特征概念服务_, 存在概念服务_)
            : std::nullopt;
        if (!信息 || !类别 || !概念持有关系(
            *信息, 特征概念服务_, 存在概念服务_)) {
            return 概念名称关系删除状态::结构不一致;
        }
        const bool 已解除 = *类别 == 概念类别::特征
            ? 特征概念服务_.解除名称关系(
                信息->概念节点, 名称关系节点)
            : 存在概念服务_.解除名称关系(
                信息->概念节点, 名称关系节点);
        if (!已解除) {
            return 概念名称关系删除状态::资源失败;
        }

        bool 删除成功 = true;
        for (const auto 字段 : {
            节点类型字段, 被命名概念字段, 目标词条字段}) {
            for (const auto& 关系 : 全局基础数据集.查询字段(
                名称关系节点, 字段)) {
                删除成功 = 全局基础数据集.删除字段(关系.编码) && 删除成功;
            }
        }
        for (const auto& 关系 : 全局基础数据集.查询目标关系(
            名称关系节点, 基础外部关系类型::父子)) {
            if (关系.源节点 == 概念名称关系根节点) {
                删除成功 = 全局基础数据集.删除关系(关系.编码) && 删除成功;
            }
        }
        删除成功 = 删除成功
            && 全局基础数据集.删除节点(名称关系节点);
        if (!删除成功) {
            if (*类别 == 概念类别::特征) {
                (void)特征概念服务_.绑定名称关系(
                    信息->概念节点, 名称关系节点);
            } else {
                (void)存在概念服务_.绑定名称关系(
                    信息->概念节点, 名称关系节点);
            }
            return 概念名称关系删除状态::资源失败;
        }
        return 概念名称关系删除状态::已删除;
    } catch (...) {
        return 概念名称关系删除状态::资源失败;
    }
}

概念名称关系查询结果 概念_名称关系类::获取名称关系(
    稳定编码 名称关系节点) const noexcept {
    概念名称关系查询结果 结果;
    try {
        std::lock_guard 锁(概念名称关系互斥);
        if (!有效(名称关系节点)) return 结果;
        if (!节点仍存在(名称关系节点)) {
            结果.状态 = 概念名称关系查询状态::未找到;
            return 结果;
        }
        if (!结构仍存在()) {
            结果.状态 = 概念名称关系查询状态::结构不一致;
            return 结果;
        }
        const auto 信息 = 读取关系端点(
            名称关系节点, 词服务_, 特征概念服务_, 存在概念服务_);
        if (!信息 || !概念持有关系(
            *信息, 特征概念服务_, 存在概念服务_)) {
            结果.状态 = 概念名称关系查询状态::结构不一致;
            return 结果;
        }
        结果.状态 = 概念名称关系查询状态::已找到;
        结果.信息 = *信息;
        return 结果;
    } catch (...) {
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    }
}

概念名称关系列表查询结果 概念_名称关系类::查询概念名称(
    稳定编码 概念节点) const noexcept {
    概念名称关系列表查询结果 结果;
    try {
        std::lock_guard 锁(概念名称关系互斥);
        if (!有效(概念节点)) return 结果;
        if (!结构仍存在()) {
            结果.状态 = 概念名称关系查询状态::结构不一致;
            return 结果;
        }
        if (!识别概念类别(
            概念节点, 特征概念服务_, 存在概念服务_)) {
            结果.状态 = 概念名称关系查询状态::未找到;
            return 结果;
        }
        for (const auto& 组织关系 : 全局基础数据集.查询源关系(
            概念名称关系根节点, 基础外部关系类型::父子)) {
            const auto 信息 = 读取关系端点(
                组织关系.目标节点, 词服务_,
                特征概念服务_, 存在概念服务_);
            if (!信息 || !概念持有关系(
                *信息, 特征概念服务_, 存在概念服务_)) {
                结果.状态 = 概念名称关系查询状态::结构不一致;
                return 结果;
            }
            if (信息->概念节点 == 概念节点) {
                结果.名称关系节点组.push_back(信息->节点);
            }
        }
        std::sort(结果.名称关系节点组.begin(), 结果.名称关系节点组.end());
        结果.状态 = 结果.名称关系节点组.empty()
            ? 概念名称关系查询状态::未找到
            : 概念名称关系查询状态::已找到;
        return 结果;
    } catch (...) {
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    }
}

概念名称关系列表查询结果 概念_名称关系类::查询词条候选概念(
    稳定编码 词条节点) const noexcept {
    概念名称关系列表查询结果 结果;
    try {
        std::lock_guard 锁(概念名称关系互斥);
        if (!有效(词条节点)) return 结果;
        if (!结构仍存在()) {
            结果.状态 = 概念名称关系查询状态::结构不一致;
            return 结果;
        }
        if (!词服务_.是词条节点(词条节点)) {
            结果.状态 = 概念名称关系查询状态::未找到;
            return 结果;
        }
        for (const auto& 组织关系 : 全局基础数据集.查询源关系(
            概念名称关系根节点, 基础外部关系类型::父子)) {
            const auto 信息 = 读取关系端点(
                组织关系.目标节点, 词服务_,
                特征概念服务_, 存在概念服务_);
            if (!信息 || !概念持有关系(
                *信息, 特征概念服务_, 存在概念服务_)) {
                结果.状态 = 概念名称关系查询状态::结构不一致;
                return 结果;
            }
            if (信息->词条节点 == 词条节点) {
                结果.名称关系节点组.push_back(信息->节点);
            }
        }
        std::sort(结果.名称关系节点组.begin(), 结果.名称关系节点组.end());
        结果.状态 = 结果.名称关系节点组.empty()
            ? 概念名称关系查询状态::未找到
            : 概念名称关系查询状态::已找到;
        return 结果;
    } catch (...) {
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    }
}

bool 概念_名称关系类::是概念名称关系节点(
    稳定编码 节点) const noexcept {
    return 获取名称关系(节点).状态 == 概念名称关系查询状态::已找到;
}

