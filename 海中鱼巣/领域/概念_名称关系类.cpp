bool 节点仍存在(稳定编码 节点) noexcept {
    return 有效(节点) && 全局基础数据集.查询节点(节点).has_value();
}

std::optional<稳定编码> 读取唯一节点字段(
    稳定编码 节点, 稳定编码 字段) {
    const auto 字段组 = 全局基础数据集.查询字段(节点, 字段);
    if (字段组.size() != 1) return std::nullopt;
    const auto* 目标 = std::get_if<稳定编码>(&字段组.front().内容);
    return 目标 ? std::optional<稳定编码>{*目标} : std::nullopt;
}

bool 有唯一父节点(稳定编码 节点, 稳定编码 父节点) {
    const auto 关系组 = 全局基础数据集.查询目标关系(
        节点, 基础外部关系类型::父子);
    return 关系组.size() == 1
        && 关系组.front().源节点 == 父节点
        && 关系组.front().角色或顺序 == 0;
}

bool 类型为(稳定编码 节点, 稳定编码 类型) {
    const auto 实际类型 = 读取唯一节点字段(节点, 节点类型字段);
    return 实际类型 && *实际类型 == 类型;
}

bool 结构句柄完整() noexcept {
    const std::vector<稳定编码> 节点组{
        自然语言组织根节点, 概念名称关系根节点, 节点类型字段,
        名称关系根类型, 名称关系节点类型, 被命名概念字段,
        目标词条字段};
    return std::all_of(节点组.begin(), 节点组.end(), 有效);
}

bool 结构仍存在() {
    if (!结构句柄完整()) return false;
    const std::vector<稳定编码> 节点组{
        自然语言组织根节点, 概念名称关系根节点, 节点类型字段,
        名称关系根类型, 名称关系节点类型, 被命名概念字段,
        目标词条字段};
    return std::all_of(节点组.begin(), 节点组.end(), 节点仍存在)
        && 类型为(概念名称关系根节点, 名称关系根类型)
        && 有唯一父节点(概念名称关系根节点, 自然语言组织根节点);
}

enum class 概念类别 : std::uint8_t {
    特征 = 1,
    存在 = 2
};

std::optional<概念类别> 识别概念类别(
    稳定编码 概念节点,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务) {
    const bool 是特征 = 特征概念服务.是特征概念节点(概念节点);
    const bool 是存在 = 存在概念服务.是存在概念节点(概念节点);
    if (是特征 == 是存在) return std::nullopt;
    return 是特征 ? 概念类别::特征 : 概念类别::存在;
}

std::optional<概念名称关系信息> 读取关系端点(
    稳定编码 节点,
    const 新_词类& 词服务,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务) {
    if (!节点仍存在(节点) || !类型为(节点, 名称关系节点类型)
        || !有唯一父节点(节点, 概念名称关系根节点)) {
        return std::nullopt;
    }
    const auto 概念节点 = 读取唯一节点字段(节点, 被命名概念字段);
    const auto 词条节点 = 读取唯一节点字段(节点, 目标词条字段);
    if (!概念节点 || !词条节点
        || !识别概念类别(
            *概念节点, 特征概念服务, 存在概念服务)
        || !词服务.是词条节点(*词条节点)) {
        return std::nullopt;
    }
    return 概念名称关系信息{节点, *概念节点, *词条节点};
}

bool 概念持有关系(
    const 概念名称关系信息& 信息,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务) {
    std::vector<稳定编码> 关系组;
    if (const auto 特征 = 特征概念服务.获取特征概念(信息.概念节点)) {
        关系组 = 特征->名称关系;
    } else if (const auto 存在 = 存在概念服务.获取存在概念(信息.概念节点)) {
        关系组 = 存在->名称关系;
    } else {
        return false;
    }
    return std::count(关系组.begin(), 关系组.end(), 信息.节点) == 1;
}

void 回滚关系节点(
    稳定编码 节点,
    const std::vector<稳定编码>& 字段组) noexcept {
    for (auto 位置 = 字段组.rbegin(); 位置 != 字段组.rend(); ++位置) {
        if (有效(*位置)) (void)全局基础数据集.删除字段(*位置);
    }
    for (const auto& 关系 : 全局基础数据集.查询目标关系(
        节点, 基础外部关系类型::父子)) {
        if (关系.源节点 == 概念名称关系根节点) {
            (void)全局基础数据集.删除关系(关系.编码);
        }
    }
    (void)全局基础数据集.删除节点(节点);
}

