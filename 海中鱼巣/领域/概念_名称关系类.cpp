指代名称读取结果 概念_名称关系类::获取指代名称关系(
    稳定编码 名称关系节点) const {
    指代名称读取结果 结果;
    if (!有效(名称关系节点)) return 结果;
    const auto 全集 = 准备名称核验全集(
        词服务_, 特征概念服务_, 存在概念服务_);
    if (全集.状态 != 指代名称读取状态::已读取) {
        结果.状态 = 全集.状态; return 结果;
    }
    const auto 位置 = std::find_if(全集.指代.begin(), 全集.指代.end(),
        [&](const auto& 项) { return 项.节点 == 名称关系节点; });
    if (位置 == 全集.指代.end()) {
        结果.状态 = 指代名称读取状态::未找到; return 结果;
    }
    结果.状态 = 指代名称读取状态::已读取;
    结果.信息 = *位置;
    return 结果;
}

指代名称列表读取结果 概念_名称关系类::查询指代概念名称(
    稳定编码 概念节点) const {
    指代名称列表读取结果 结果;
    if (!有效(概念节点)) return 结果;
    const auto 概念 = 存在概念服务_.获取指代概念(概念节点);
    结果.状态 = 映射指代状态(概念.状态);
    if (结果.状态 != 指代名称读取状态::已读取) return 结果;
    if (!概念.信息) { 结果.状态 = 指代名称读取状态::结构不一致; return 结果; }
    const auto 全集 = 准备名称核验全集(
        词服务_, 特征概念服务_, 存在概念服务_);
    if (全集.状态 != 指代名称读取状态::已读取) {
        结果.状态 = 全集.状态; return 结果;
    }
    for (const auto& 项 : 全集.指代)
        if (项.概念.节点 == 概念节点) 结果.信息组.push_back(项);
    std::sort(结果.信息组.begin(), 结果.信息组.end(),
        [](const auto& 左, const auto& 右) { return 左.节点 < 右.节点; });
    std::vector<稳定编码> 名称身份;
    for (const auto& 项 : 结果.信息组) 名称身份.push_back(项.节点);
    if (名称身份 != 概念.信息->名称关系) {
        结果.信息组.clear();
        结果.状态 = 指代名称读取状态::读取漂移;
    }
    return 结果;
}

指代名称列表读取结果 概念_名称关系类::查询词条指代名称(
    稳定编码 词条节点) const {
    指代名称列表读取结果 结果;
    if (!有效(词条节点)) return 结果;
    const auto 词 = 词服务_.获取词条(词条节点);
    if (词.状态 == 新词条查询状态::资源失败) {
        结果.状态 = 指代名称读取状态::资源失败; return 结果;
    }
    if (词.状态 != 新词条查询状态::已找到) {
        结果.状态 = 词.状态 == 新词条查询状态::未找到
            ? 指代名称读取状态::依赖缺失
            : 词.状态 == 新词条查询状态::输入不合法
                ? 指代名称读取状态::输入拒绝
                : 指代名称读取状态::结构不一致;
        return 结果;
    }
    if (!词.信息) {
        结果.状态 = 指代名称读取状态::结构不一致;
        return 结果;
    }
    const auto 全集 = 准备名称核验全集(
        词服务_, 特征概念服务_, 存在概念服务_);
    if (全集.状态 != 指代名称读取状态::已读取) {
        结果.状态 = 全集.状态; return 结果;
    }
    for (const auto& 项 : 全集.指代)
        if (项.词条.节点 == 词条节点) 结果.信息组.push_back(项);
    std::sort(结果.信息组.begin(), 结果.信息组.end(),
        [](const auto& 左, const auto& 右) { return 左.节点 < 右.节点; });
    结果.状态 = 指代名称读取状态::已读取;
    return 结果;
}

指代名称变更结果 概念_名称关系类::建立或取得指代名称关系(
    const 指代名称建立请求& 请求) {
    指代名称变更结果 结果;
    try {
        if (!有效(请求.概念节点) || !有效(请求.预期词条.节点)
            || !有效(请求.预期来源.节点)
            || 请求.角色 < 指代名称角色::首选名称
            || 请求.角色 > 指代名称角色::简称) return 结果;
        const auto 截取 = 标量片段(请求.预期来源.固定原文,
            请求.来源范围.起始标量, 请求.来源范围.结束标量);
        if (!截取 || *截取 != 请求.预期词条.规范化词面
            || 请求.预期来源.种类
                != 新语言知识来源种类::经确认先天定义
            || 请求.预期来源.语言节点 != 请求.预期词条.语言节点)
            return 结果;
        const auto 词 = 词服务_.获取词条(请求.预期词条.节点);
        if (词.状态 == 新词条查询状态::资源失败) {
            结果.状态 = 指代名称变更状态::资源失败; return 结果;
        }
        if (词.状态 != 新词条查询状态::已找到) {
            结果.状态 = 词.状态 == 新词条查询状态::未找到
                ? 指代名称变更状态::依赖缺失
                : 词.状态 == 新词条查询状态::输入不合法
                    ? 指代名称变更状态::输入拒绝
                    : 指代名称变更状态::结构不一致;
            return 结果;
        }
        if (!词.信息) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        if (*词.信息 != 请求.预期词条) {
            结果.状态 = 指代名称变更状态::依赖已变化; return 结果;
        }
        const auto 语言 = 词服务_.取得语言服务().获取语言(词.信息->语言节点);
        if (语言.状态 == 新语言查询状态::资源失败) {
            结果.状态 = 指代名称变更状态::资源失败; return 结果;
        }
        if (语言.状态 != 新语言查询状态::已找到) {
            结果.状态 = 语言.状态 == 新语言查询状态::未找到
                ? 指代名称变更状态::依赖缺失
                : 语言.状态 == 新语言查询状态::输入不合法
                    ? 指代名称变更状态::输入拒绝
                    : 指代名称变更状态::结构不一致;
            return 结果;
        }
        if (!语言.信息) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        const auto 来源 = 词服务_.取得语言服务().获取知识先天来源(
            请求.预期来源.节点);
        if (来源.状态 != 新语言知识状态::已完成) {
            结果.状态 = 写状态(映射来源状态(来源.状态)); return 结果;
        }
        if (!来源.信息) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        if (!同一来源(*来源.信息, 请求.预期来源)) {
            结果.状态 = 指代名称变更状态::依赖已变化; return 结果;
        }
        const auto 预期概念 = 存在概念服务_.查询指代概念(请求.预期定义);
        if (预期概念.状态 != 指代概念查询状态::已找到) {
            结果.状态 = 写状态(映射指代状态(预期概念.状态)); return 结果;
        }
        if (!预期概念.信息) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        const auto 概念 = 存在概念服务_.获取指代概念(请求.概念节点);
        if (概念.状态 != 指代概念查询状态::已找到) {
            结果.状态 = 写状态(映射指代状态(概念.状态)); return 结果;
        }
        if (!概念.信息) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        if (预期概念.信息->节点 != 请求.概念节点
            || 概念.信息->定义 != 预期概念.信息->定义) {
            结果.状态 = 指代名称变更状态::依赖已变化; return 结果;
        }
        const auto 全集 = 准备名称核验全集(
            词服务_, 特征概念服务_, 存在概念服务_);
        if (全集.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 写状态(全集.状态); return 结果;
        }
        std::vector<稳定编码> 根内名称;
        for (const auto& 项 : 全集.指代)
            if (项.概念.节点 == 请求.概念节点) 根内名称.push_back(项.节点);
        std::sort(根内名称.begin(), 根内名称.end());
        if (根内名称 != 概念.信息->名称关系) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        {
            std::lock_guard 锁(概念名称关系互斥);
            const auto 键状态 = 指代名称键状态();
            if (键状态 != 指代名称读取状态::已读取) {
                结果.状态 = 写状态(键状态);
                return 结果;
            }
        }
        const auto 参与 = 存在概念服务_.准备指代名称反向参与(
            请求.概念节点, 请求.预期定义);
        if (参与.状态 != 指代概念查询状态::已找到 || !参与.规格) {
            结果.状态 = 参与.状态 == 指代概念查询状态::已找到
                ? 指代名称变更状态::结构不一致
                : 写状态(映射指代状态(参与.状态));
            return 结果;
        }
        std::optional<稳定编码> 复用身份;
        for (const auto& 项 : 全集.指代) {
            if (项.概念.节点 != 请求.概念节点
                || 项.语言.节点 != 词.信息->语言节点) continue;
            if (项.角色 == 指代名称角色::首选名称
                && 请求.角色 == 指代名称角色::首选名称
                && 项.词条.节点 != 词.信息->节点) {
                结果.已取得关系身份 = 项.节点;
                结果.状态 = 指代名称变更状态::首选名称冲突;
                return 结果;
            }
            if (项.词条.节点 == 词.信息->节点
                && 项.角色 == 请求.角色) {
                if (复用身份) {
                    结果.状态 = 指代名称变更状态::结构不一致; return 结果;
                }
                if (项.来源.节点 != 来源.信息->节点) {
                    结果.已取得关系身份 = 项.节点;
                    结果.状态 = 指代名称变更状态::请求内容冲突;
                    return 结果;
                }
                复用身份 = 项.节点;
            }
        }
        if (复用身份) {
            结果.已取得关系身份 = *复用身份;
            结果.本次处理 = 指代名称本次处理::复用;
            结果.阶段 = 指代名称核验阶段::已取得身份待核验;
        }
        std::vector<基础联合节点快照> 名称侧预期;
        const auto 预期状态 = 补齐名称侧预期(全集.原始, 名称侧预期,
            {请求.概念节点, 词.信息->节点, 词.信息->语言节点,
                来源.信息->节点, 全集.原始.指代键快照[角色键],
                全集.原始.指代键快照[语言键],
                全集.原始.指代键快照[来源键]});
        if (预期状态 != 指代名称读取状态::已读取) {
            结果.状态 = 写状态(预期状态); return 结果;
        }
        {
            std::lock_guard 锁(概念名称关系互斥);
            const auto 当前 = 读取名称原始全集();
            if (当前.状态 != 指代名称读取状态::已读取
                || !同一名称全集(全集.原始, 当前)) {
                结果.状态 = 当前.状态 == 指代名称读取状态::已读取
                    ? 指代名称变更状态::读取漂移 : 写状态(当前.状态);
                return 结果;
            }
            if (复用身份) {
                // 已在首次确认同键时保留真实身份与处理种类。
            } else {
                基础节点建立请求 新节点;
                新节点.上级节点 = 概念名称关系根节点;
                新节点.字段组 = {
                    {节点类型字段, 名称关系节点类型},
                    {被命名概念字段, 请求.概念节点},
                    {目标词条字段, 词.信息->节点},
                    {指代名称键[角色键],
                        基础值{static_cast<std::int64_t>(请求.角色)}},
                    {指代名称键[语言键], 词.信息->语言节点},
                    {指代名称键[来源键], 来源.信息->节点}};
                const auto 联合请求 = 参与.规格->形成建立请求(
                    新节点, 名称侧预期);
                if (联合请求.状态 != 基础互引节点操作状态::已完成
                    || !联合请求.请求) {
                    结果.状态 = 写状态(联合请求.状态); return 结果;
                }
                const auto 发布 = 全局基础数据集.原子建立互引节点(
                    *联合请求.请求);
                if (发布.状态 != 基础互引节点操作状态::已完成) {
                    结果.状态 = 写状态(发布.状态); return 结果;
                }
                if (!发布.节点 || !有效(*发布.节点)
                    || !发布.反向字段关系 || !有效(*发布.反向字段关系)
                    || !发布.组织关系 || !有效(*发布.组织关系))
                    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
                        L"建立或取得指代名称关系", L"L1 已完成但未返回完整真实身份。");
                结果.已取得关系身份 = *发布.节点;
                结果.本次处理 = 指代名称本次处理::新建;
            }
            结果.阶段 = 指代名称核验阶段::已取得身份待核验;
        }
        const auto 读回 = 获取指代名称关系(*结果.已取得关系身份);
        if (读回.状态 != 指代名称读取状态::已读取 || !读回.信息) {
            结果.状态 = 写状态(读回.状态); return 结果;
        }
        if (读回.信息->概念.定义 != 预期概念.信息->定义
            || 读回.信息->词条 != 请求.预期词条
            || !同一来源(读回.信息->来源, 请求.预期来源)
            || 读回.信息->角色 != 请求.角色
            || 读回.信息->语言.节点 != 请求.预期词条.语言节点) {
            结果.状态 = 指代名称变更状态::依赖已变化; return 结果;
        }
        const auto 按概念 = 查询指代概念名称(请求.概念节点);
        if (按概念.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 写状态(按概念.状态); return 结果;
        }
        const auto 按词条 = 查询词条指代名称(请求.预期词条.节点);
        if (按词条.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 写状态(按词条.状态); return 结果;
        }
        const auto 同一身份 = [&](const auto& 组) {
            return std::count_if(组.begin(), 组.end(), [&](const auto& 项) {
                return 同一指代名称信息(项, *读回.信息);
            }) == 1;
        };
        if (!同一身份(按概念.信息组) || !同一身份(按词条.信息组)) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        结果.信息 = *读回.信息;
        结果.阶段 = 指代名称核验阶段::已完成核验;
        结果.状态 = 结果.本次处理 == 指代名称本次处理::新建
            ? 指代名称变更状态::已建立 : 指代名称变更状态::已复用;
        return 结果;
    } catch (...) {
        if (!结果.已取得关系身份) throw;
        结果.信息.reset();
        结果.状态 = 指代名称变更状态::工程未完成;
        结果.取得身份后异常 = std::current_exception();
        return 结果;
    }
}

指代名称变更结果 概念_名称关系类::删除指代名称关系(
    稳定编码 名称关系节点) {
    指代名称变更结果 结果;
    try {
        if (!有效(名称关系节点)) return 结果;
        const auto 全集 = 准备名称核验全集(
            词服务_, 特征概念服务_, 存在概念服务_);
        if (全集.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 写状态(全集.状态); return 结果;
        }
        const auto 位置 = std::find_if(全集.指代.begin(), 全集.指代.end(),
            [&](const auto& 项) { return 项.节点 == 名称关系节点; });
        if (位置 == 全集.指代.end()) {
            const auto 普通 = std::find_if(全集.普通.begin(), 全集.普通.end(),
                [&](const auto& 项) { return 项.节点 == 名称关系节点; });
            结果.状态 = 普通 == 全集.普通.end()
                ? 指代名称变更状态::不存在
                : 指代名称变更状态::输入拒绝;
            return 结果;
        }
        const auto 参与 = 存在概念服务_.准备指代名称反向参与(
            位置->概念.节点, 位置->概念.定义);
        if (参与.状态 != 指代概念查询状态::已找到 || !参与.规格) {
            结果.状态 = 参与.状态 == 指代概念查询状态::已找到
                ? 指代名称变更状态::结构不一致
                : 写状态(映射指代状态(参与.状态));
            return 结果;
        }
        std::vector<基础联合节点快照> 名称侧预期;
        const auto 预期状态 = 补齐名称侧预期(全集.原始, 名称侧预期,
            {位置->概念.节点, 位置->词条.节点, 位置->语言.节点,
                位置->来源.节点, 全集.原始.指代键快照[角色键],
                全集.原始.指代键快照[语言键],
                全集.原始.指代键快照[来源键]});
        if (预期状态 != 指代名称读取状态::已读取) {
            结果.状态 = 写状态(预期状态); return 结果;
        }
        {
            std::lock_guard 锁(概念名称关系互斥);
            const auto 当前 = 读取名称原始全集();
            if (当前.状态 != 指代名称读取状态::已读取
                || !同一名称全集(全集.原始, 当前)) {
                结果.状态 = 当前.状态 == 指代名称读取状态::已读取
                    ? 指代名称变更状态::读取漂移 : 写状态(当前.状态);
                return 结果;
            }
            const auto 联合请求 = 参与.规格->形成删除请求(
                名称关系节点, 概念名称关系根节点, 名称侧预期);
            if (联合请求.状态 != 基础互引节点操作状态::已完成
                || !联合请求.请求) {
                结果.状态 = 写状态(联合请求.状态); return 结果;
            }
            const auto 删除 = 全局基础数据集.原子删除互引节点(
                *联合请求.请求);
            if (删除 != 基础互引节点操作状态::已完成) {
                结果.状态 = 写状态(删除); return 结果;
            }
            结果.已取得关系身份 = 名称关系节点;
            结果.本次处理 = 指代名称本次处理::删除;
            结果.阶段 = 指代名称核验阶段::已取得身份待核验;
        }
        const auto 联合 = 全局基础数据集.查询节点组完整结构(
            {名称关系节点, 位置->概念.节点, 概念名称关系根节点,
                位置->词条.节点, 位置->语言.节点, 位置->来源.节点});
        if (联合.状态 == 基础结构操作状态::资源失败) {
            结果.状态 = 指代名称变更状态::资源失败; return 结果;
        }
        if (联合.状态 != 基础结构操作状态::已完成) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        for (const auto& 项 : 联合.节点组) {
            if (项.查询节点 == 名称关系节点) {
                if (项.快照) {
                    结果.状态 = 指代名称变更状态::结构不一致; return 结果;
                }
            } else if (!项.快照) {
                结果.状态 = 指代名称变更状态::依赖缺失; return 结果;
            } else if (项.查询节点 == 位置->概念.节点) {
                for (const auto& 字段 : 项.快照->结构.字段组)
                    if (const auto* 引用 = std::get_if<稳定编码>(&字段.内容);
                        引用 && *引用 == 名称关系节点) {
                        结果.状态 = 指代名称变更状态::结构不一致; return 结果;
                    }
            } else if (项.查询节点 == 概念名称关系根节点) {
                for (const auto& 边 : 项.快照->出向外部关系组)
                    if (边.目标节点 == 名称关系节点) {
                        结果.状态 = 指代名称变更状态::结构不一致; return 结果;
                    }
            }
        }
        const auto 概念 = 存在概念服务_.获取指代概念(位置->概念.节点);
        if (概念.状态 != 指代概念查询状态::已找到) {
            结果.状态 = 写状态(映射指代状态(概念.状态)); return 结果;
        }
        if (!概念.信息) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        if (std::find(概念.信息->名称关系.begin(),
            概念.信息->名称关系.end(), 名称关系节点)
            != 概念.信息->名称关系.end()) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        const auto 词 = 词服务_.获取词条(位置->词条.节点);
        const auto 语言 = 词服务_.取得语言服务().获取语言(位置->语言.节点);
        const auto 来源 = 词服务_.取得语言服务().获取知识先天来源(
            位置->来源.节点);
        if (词.状态 != 新词条查询状态::已找到) {
            结果.状态 = 词.状态 == 新词条查询状态::资源失败
                ? 指代名称变更状态::资源失败
                : 词.状态 == 新词条查询状态::未找到
                    ? 指代名称变更状态::依赖缺失
                    : 词.状态 == 新词条查询状态::输入不合法
                        ? 指代名称变更状态::输入拒绝
                        : 指代名称变更状态::结构不一致;
            return 结果;
        }
        if (!词.信息) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        if (语言.状态 != 新语言查询状态::已找到) {
            结果.状态 = 语言.状态 == 新语言查询状态::资源失败
                ? 指代名称变更状态::资源失败
                : 语言.状态 == 新语言查询状态::未找到
                    ? 指代名称变更状态::依赖缺失
                    : 语言.状态 == 新语言查询状态::输入不合法
                        ? 指代名称变更状态::输入拒绝
                        : 指代名称变更状态::结构不一致;
            return 结果;
        }
        if (!语言.信息) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        if (来源.状态 != 新语言知识状态::已完成) {
            结果.状态 = 写状态(映射来源状态(来源.状态)); return 结果;
        }
        if (!来源.信息) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        const auto 按关系 = 获取指代名称关系(名称关系节点);
        if (按关系.状态 != 指代名称读取状态::未找到
            || 按关系.信息) {
            结果.状态 = 按关系.状态 == 指代名称读取状态::已读取
                ? 指代名称变更状态::结构不一致
                : 写状态(按关系.状态);
            return 结果;
        }
        const auto 按概念 = 查询指代概念名称(位置->概念.节点);
        if (按概念.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 写状态(按概念.状态); return 结果;
        }
        const auto 按词条 = 查询词条指代名称(位置->词条.节点);
        if (按词条.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 写状态(按词条.状态); return 结果;
        }
        if (std::any_of(按概念.信息组.begin(), 按概念.信息组.end(),
                [&](const auto& 项) { return 项.节点 == 名称关系节点; })
            || std::any_of(按词条.信息组.begin(), 按词条.信息组.end(),
                [&](const auto& 项) { return 项.节点 == 名称关系节点; })) {
            结果.状态 = 指代名称变更状态::结构不一致; return 结果;
        }
        结果.阶段 = 指代名称核验阶段::已完成核验;
        结果.状态 = 指代名称变更状态::已删除;
        return 结果;
    } catch (...) {
        if (!结果.已取得关系身份) throw;
        结果.状态 = 指代名称变更状态::工程未完成;
        结果.取得身份后异常 = std::current_exception();
        return 结果;
    }
}

