using 名称保护读集 = std::map<稳定编码, 基础联合节点快照>;

void 并名称保护(名称保护读集& 输出,
    const std::vector<基础联合节点快照>& 读集) {
    if (读集.empty()) throw std::logic_error("name protection closure missing");
    for (const auto& 快照 : 读集) {
        if (!有效(快照.结构.节点.编码))
            throw std::logic_error("name protection closure identity invalid");
        const auto [位置, 新增] = 输出.emplace(快照.结构.节点.编码, 快照);
        if (!新增 && !同一联合节点(位置->second, 快照))
            throw 概念名称关系查询状态::读取漂移;
    }
}

std::vector<基础联合节点快照> 完成名称保护(const 名称保护读集& 读集) {
    std::vector<稳定编码> 身份;
    for (const auto& [节点, 快照] : 读集) 身份.push_back(节点);
    const auto 当前 = 全局基础数据集.查询节点组完整结构(身份);
    if (当前.状态 == 基础结构操作状态::资源失败)
        throw 概念名称关系查询状态::资源失败;
    if (当前.状态 != 基础结构操作状态::已完成 || 当前.节点组.size() != 身份.size())
        throw std::logic_error("name protection final receipt invalid");
    std::vector<基础联合节点快照> 结果;
    for (std::size_t i = 0; i < 身份.size(); ++i) {
        const auto& 项 = 当前.节点组[i];
        if (项.查询节点 != 身份[i])
            throw std::logic_error("name protection final identity mismatch");
        if (!项.快照 || !同一联合节点(读集.at(身份[i]), *项.快照))
            throw 概念名称关系查询状态::读取漂移;
        结果.push_back(*项.快照);
    }
    return 结果;
}

void 核普通名称概念保护(const 概念名称关系信息& 项,
    const 概念_特征类& 特征服务, const 概念_存在类& 存在服务, const 概念_动态类& 动态服务,
    名称保护读集& 保护) {
    const auto 核持有 = [&](const std::vector<稳定编码>& 名称) {
        if (std::count(名称.begin(), 名称.end(), 项.节点) != 1)
            throw std::logic_error("name concept reverse ownership corrupt");
    };
    if (const auto 动态 = 动态服务.获取动态概念(项.概念节点)) {
        核持有(动态->名称关系);
        const auto 读取 = 全局基础数据集.查询节点组完整结构({项.概念节点});
        if (读取.状态 == 基础结构操作状态::资源失败)
            throw 概念名称关系查询状态::资源失败;
        if (读取.状态 != 基础结构操作状态::已完成 || 读取.节点组.size() != 1
            || !读取.节点组.front().快照)
            throw 概念名称关系查询状态::依赖已变化;
        并名称保护(保护, {*读取.节点组.front().快照});
        return;
    }
    const auto E = 存在服务.读取普通存在概念定义保护(项.概念节点);
    if (E.状态 == 正式概念读取状态::前提已变化)
        throw 概念名称关系查询状态::读取漂移;
    if (E.状态 == 正式概念读取状态::依赖未就绪)
        throw 概念名称关系查询状态::读取未完成;
    if (E.状态 == 正式概念读取状态::已读取) {
        if (!E.信息)
            throw std::logic_error("name existence endpoint receipt invalid");
        核持有(E.信息->名称关系);
        并名称保护(保护, E.完整保护组);
        return;
    }
    const auto 特征身份 = 特征服务.读取正式概念身份保护(项.概念节点);
    if (特征身份.状态 == 正式概念读取状态::前提已变化)
        throw 概念名称关系查询状态::读取漂移;
    if (特征身份.状态 == 正式概念读取状态::已读取) {
        if (!特征身份.身份)
            throw std::logic_error("name feature identity receipt invalid");
        并名称保护(保护, 特征身份.身份->完整保护组);
        const auto 根 = 特征服务.读取特征类别根概念保护();
        if (根.状态 == 正式概念读取状态::前提已变化)
            throw 概念名称关系查询状态::读取漂移;
        if (根.状态 == 正式概念读取状态::已读取 && 根.信息
            && 根.信息->节点 == 项.概念节点) {
            核持有(根.信息->名称关系);
            并名称保护(保护, 根.完整保护组);
            return;
        }
        const auto F = 特征服务.读取特征概念定义保护(项.概念节点);
        if (F.前提已变化) throw 概念名称关系查询状态::读取漂移;
        if (F.状态 == 基础结构操作状态::资源失败)
            throw 概念名称关系查询状态::资源失败;
        if (F.状态 != 基础结构操作状态::已完成 || !F.信息)
            throw std::logic_error("name feature endpoint unreadable");
        核持有(F.信息->定义.名称关系);
        并名称保护(保护, F.预期节点组);
        return;
    }
    const auto 结构 = 存在服务.读取正式结构概念保护(项.概念节点);
    if (结构.状态 == 正式结构操作状态::前提已变化)
        throw 概念名称关系查询状态::读取漂移;
    if (结构.状态 == 正式结构操作状态::依赖未就绪)
        throw 概念名称关系查询状态::读取未完成;
    if (结构.状态 == 正式结构操作状态::已读取) {
        if (!结构.信息)
            throw std::logic_error("name formal endpoint receipt invalid");
        核持有(结构.信息->名称关系);
        并名称保护(保护, 结构.完整保护组);
        return;
    }
    throw std::logic_error("name ordinary concept endpoint unrecognized");
}

void 核名称原始保护状态(指代名称读取状态 状态) {
    if (状态 == 指代名称读取状态::已读取) return;
    if (状态 == 指代名称读取状态::结构不一致)
        throw std::logic_error("name raw structure corrupt");
    throw 普通查询状态(状态);
}

void 补名称角色键保护(const 名称原始全集& 原始, 名称保护读集& 保护) {
    if (std::none_of(原始.项组.begin(), 原始.项组.end(),
        [](const auto& 项) { return 项.角色.has_value(); })) return;
    std::vector<稳定编码> 身份(原始.指代键快照.begin(), 原始.指代键快照.end());
    std::sort(身份.begin(), 身份.end());
    const auto 读取 = 全局基础数据集.查询节点组完整结构(身份);
    if (读取.状态 == 基础结构操作状态::资源失败)
        throw 概念名称关系查询状态::资源失败;
    if (读取.状态 != 基础结构操作状态::已完成 || 读取.节点组.size() != 身份.size())
        throw std::logic_error("name role schema receipt invalid");
    std::vector<基础联合节点快照> 快照;
    for (std::size_t i = 0; i < 身份.size(); ++i) {
        const auto& 项 = 读取.节点组[i];
        if (项.查询节点 != 身份[i] || !项.快照 || !项.快照->结构.字段组.empty())
            throw std::logic_error("name role schema corrupt");
        快照.push_back(*项.快照);
    }
    并名称保护(保护, 快照);
}

void 核指代名称同概念组织(const 指代概念信息& 概念,
    名称保护读集& 保护) {
    std::lock_guard 锁(概念名称关系互斥);
    const auto 同概念 = 读取名称原始全集(概念.节点, std::nullopt, std::nullopt, true);
    核名称原始保护状态(同概念.状态);
    并名称保护(保护, 同概念.快照组);
    补名称角色键保护(同概念, 保护);
    std::vector<稳定编码> 名称身份;
    std::set<std::tuple<稳定编码, 稳定编码, 指代名称角色>> 名称键;
    std::set<稳定编码> 首选语言;
    for (const auto& 项 : 同概念.项组) {
        if (!项.角色 || 项.概念 != 概念.节点
            || !名称键.emplace(项.语言, 项.词条, *项.角色).second)
            throw std::logic_error("pronoun name membership duplicated or mistyped");
        if (*项.角色 == 指代名称角色::首选名称
            && !首选语言.insert(项.语言).second)
            throw std::logic_error("pronoun preferred name duplicated");
        名称身份.push_back(项.快照.结构.节点.编码);
    }
    std::sort(名称身份.begin(), 名称身份.end());
    if (名称身份 != 概念.名称关系)
        throw std::logic_error("pronoun name reverse membership corrupt");
}

