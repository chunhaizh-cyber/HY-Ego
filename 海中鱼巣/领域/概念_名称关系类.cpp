指代名称读取状态 概念_名称关系类::初始化指代名称结构() {
    using 状态 = 指代名称读取状态;
    std::lock_guard 锁(概念名称关系互斥);
    if (!结构句柄完整()) return 状态::依赖缺失;
    if (!结构仍存在()) return 状态::结构不一致;
    const auto 根 = 全局基础数据集.查询节点组完整结构(
        {自然语言组织根节点, 概念名称关系根节点,
            节点类型字段, 名称关系根类型, 名称关系节点类型,
            被命名概念字段, 目标词条字段});
    if (根.状态 == 基础结构操作状态::资源失败) return 状态::资源失败;
    if (根.状态 != 基础结构操作状态::已完成) return 状态::读取未完成;
    for (const auto& 项 : 根.节点组) {
        if (!项.快照) return 状态::结构不一致;
        if (项.查询节点 == 概念名称关系根节点) {
            if (项.快照->结构.字段组.size() != 1
                || 项.快照->入向外部关系组.size() != 1
                || 项.快照->入向外部关系组.front().源节点
                    != 自然语言组织根节点
                || 项.快照->入向外部关系组.front().类型
                    != 基础外部关系类型::父子
                || 项.快照->入向外部关系组.front().角色或顺序 != 0)
                return 状态::结构不一致;
        } else if (项.查询节点 != 自然语言组织根节点
            && !项.快照->结构.字段组.empty())
            return 状态::结构不一致;
    }
    const auto 键状态 = 指代名称键状态();
    if (键状态 == 状态::已读取 || 键状态 == 状态::资源失败)
        return 键状态;
    if (std::any_of(指代名称键.begin(), 指代名称键.end(),
        [](稳定编码 值) { return 有效(值); }))
        return 状态::结构不一致;
    if (std::all_of(指代名称待核验键.begin(), 指代名称待核验键.end(),
        [](稳定编码 值) { return !有效(值); })) {
        const auto 建立 = 全局基础数据集.原子建立节点组(
            std::vector<基础组内新节点>(3));
        if (建立.状态 == 基础结构操作状态::资源失败)
            return 状态::资源失败;
        if (建立.状态 != 基础结构操作状态::已完成)
            return 状态::结构不一致;
        if (建立.节点组.size() != 3)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
                L"初始化指代名称结构", L"L1 已发布字段键但返回身份数量错误。");
        std::copy(建立.节点组.begin(), 建立.节点组.end(),
            指代名称待核验键.begin());
    }
    std::set<稳定编码> 身份;
    for (const auto 键 : 指代名称待核验键) {
        if (!有效(键) || !身份.insert(键).second)
            return 状态::结构不一致;
        const auto 读取 = 全局基础数据集.查询完整节点结构(键);
        if (读取.状态 == 基础结构操作状态::资源失败)
            return 状态::资源失败;
        if (读取.状态 != 基础结构操作状态::已完成
            || !读取.结构 || !读取.结构->字段组.empty())
            return 状态::结构不一致;
    }
    指代名称键 = 指代名称待核验键;
    return 状态::已读取;
}

bool 概念_名称关系类::初始化() noexcept {
    try {
        if (!词服务_.初始化()) return false;
        {
        std::lock_guard 锁(概念名称关系互斥);
        auto 建立独立节点 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        if (!建立独立节点(节点类型字段)
            || !建立独立节点(名称关系根类型)
            || !建立独立节点(名称关系节点类型)
            || !建立独立节点(被命名概念字段)
            || !建立独立节点(目标词条字段)) {
            return false;
        }
        if (!有效(概念名称关系根节点)) {
            概念名称关系根节点 =
                全局基础数据集.新建节点(自然语言组织根节点);
            if (!有效(概念名称关系根节点)) return false;
        } else if (!节点仍存在(概念名称关系根节点)
            || !有唯一父节点(
                概念名称关系根节点, 自然语言组织根节点)) {
            return false;
        }
        const auto 类型字段组 = 全局基础数据集.查询字段(
            概念名称关系根节点, 节点类型字段);
        if (类型字段组.empty()) {
            if (!有效(全局基础数据集.添加字段节点(
                概念名称关系根节点, 节点类型字段,
                名称关系根类型))) {
                return false;
            }
        } else if (类型字段组.size() != 1
            || !类型为(概念名称关系根节点, 名称关系根类型)) {
            return false;
        }
        if (!结构仍存在()) return false;
        }
        return 准备名称核验全集(
            词服务_, 特征概念服务_, 存在概念服务_).状态
                == 指代名称读取状态::已读取;
    } catch (...) {
        return false;
    }
}

概念名称关系建立结果 概念_名称关系类::建立或取得名称关系(
    稳定编码 概念节点,
    稳定编码 词条节点) noexcept {
    概念名称关系建立结果 结果;
    try {
        if (!有效(概念节点) || !有效(词条节点)) return 结果;
        if (!识别概念类别(概念节点, 特征概念服务_, 存在概念服务_)) {
            const auto 指代 = 存在概念服务_.获取指代概念(概念节点);
            if (指代.状态 == 指代概念查询状态::已找到)
                return 结果;
            if (指代.状态 != 指代概念查询状态::未找到
                && 指代.状态 != 指代概念查询状态::输入拒绝
                && 指代.状态 != 指代概念查询状态::依赖缺失) {
                结果.状态 = 普通建立状态(映射指代状态(指代.状态));
                return 结果;
            }
        }
        const auto 全集 = 准备名称核验全集(
            词服务_, 特征概念服务_, 存在概念服务_);
        if (全集.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 普通建立状态(全集.状态); return 结果;
        }
        std::lock_guard 锁(概念名称关系互斥);
        if (!结构仍存在() || !有效(概念节点) || !有效(词条节点)) {
            return 结果;
        }
        const auto 当前 = 读取名称原始全集();
        if (当前.状态 != 指代名称读取状态::已读取
            || !同一名称全集(全集.原始, 当前)) {
            结果.状态 = 当前.状态 == 指代名称读取状态::已读取
                ? 概念名称关系建立状态::读取漂移
                : 普通建立状态(当前.状态);
            return 结果;
        }
        const auto 类别 = 识别概念类别(
            概念节点, 特征概念服务_, 存在概念服务_);
        if (!类别 || !词服务_.是词条节点(词条节点)) {
            结果.状态 = 概念名称关系建立状态::依赖不存在;
            return 结果;
        }
        for (const auto& 信息 : 全集.普通) {
            if (信息.概念节点 == 概念节点
                && 信息.词条节点 == 词条节点) {
                结果.状态 = 概念名称关系建立状态::已复用;
                结果.名称关系节点 = 信息.节点;
                return 结果;
            }
        }

        const auto 节点 = 全局基础数据集.新建节点();
        if (!有效(节点)) {
            结果.状态 = 概念名称关系建立状态::资源失败;
            return 结果;
        }
        std::vector<稳定编码> 字段组;
        const auto 写字段 = [&](稳定编码 字段, 稳定编码 目标) {
            const auto 关系 = 全局基础数据集.添加字段节点(节点, 字段, 目标);
            if (有效(关系)) 字段组.push_back(关系);
            return 有效(关系);
        };
        const bool 字段完成 = 写字段(节点类型字段, 名称关系节点类型)
            && 写字段(被命名概念字段, 概念节点)
            && 写字段(目标词条字段, 词条节点);
        const auto 组织关系 = 字段完成
            ? 全局基础数据集.添加关系(
                概念名称关系根节点, 节点,
                基础外部关系类型::父子, 0)
            : 稳定编码{};
        const bool 绑定完成 = 有效(组织关系)
            && (*类别 == 概念类别::特征
                ? 特征概念服务_.绑定名称关系(概念节点, 节点)
                : 存在概念服务_.绑定名称关系(概念节点, 节点));
        if (!绑定完成) {
            回滚关系节点(节点, 字段组);
            结果.状态 = 概念名称关系建立状态::资源失败;
            return 结果;
        }
        const auto 读回 = 读取关系端点(
            节点, 词服务_, 特征概念服务_, 存在概念服务_);
        if (读回 && 概念持有关系(*读回, 特征概念服务_, 存在概念服务_)
            && 读回->概念节点 == 概念节点
            && 读回->词条节点 == 词条节点) {
            结果.状态 = 概念名称关系建立状态::已建立;
            结果.名称关系节点 = 节点;
            return 结果;
        }
        if (*类别 == 概念类别::特征) {
            (void)特征概念服务_.解除名称关系(概念节点, 节点);
        } else {
            (void)存在概念服务_.解除名称关系(概念节点, 节点);
        }
        回滚关系节点(节点, 字段组);
        结果.状态 = 概念名称关系建立状态::结构不一致;
        return 结果;
    } catch (...) {
        结果.状态 = 概念名称关系建立状态::资源失败;
        return 结果;
    }
}

概念名称关系删除状态 概念_名称关系类::删除名称关系(
    稳定编码 名称关系节点) noexcept {
    try {
        if (!有效(名称关系节点)) return 概念名称关系删除状态::输入不合法;
        const auto 全集 = 准备名称核验全集(
            词服务_, 特征概念服务_, 存在概念服务_);
        if (全集.状态 != 指代名称读取状态::已读取)
            return 全集.状态 == 指代名称读取状态::资源失败
                ? 概念名称关系删除状态::资源失败
                : 概念名称关系删除状态::结构不一致;
        if (std::any_of(全集.指代.begin(), 全集.指代.end(),
            [&](const auto& 项) { return 项.节点 == 名称关系节点; }))
            return 概念名称关系删除状态::输入不合法;
        std::lock_guard 锁(概念名称关系互斥);
        const auto 当前 = 读取名称原始全集();
        if (当前.状态 != 指代名称读取状态::已读取
            || !同一名称全集(全集.原始, 当前))
            return 概念名称关系删除状态::结构不一致;
        if (!节点仍存在(名称关系节点)) {
            return 概念名称关系删除状态::不存在;
        }
        if (!结构仍存在()) return 概念名称关系删除状态::结构不一致;
        const auto 信息 = 读取关系端点(
            名称关系节点, 词服务_, 特征概念服务_, 存在概念服务_);
        const auto 类别 = 信息 ? 识别概念类别(
            信息->概念节点, 特征概念服务_, 存在概念服务_)
            : std::nullopt;
        if (!信息 || !类别 || !概念持有关系(
            *信息, 特征概念服务_, 存在概念服务_)) {
            return 概念名称关系删除状态::结构不一致;
        }
        const bool 已解除 = *类别 == 概念类别::特征
            ? 特征概念服务_.解除名称关系(
                信息->概念节点, 名称关系节点)
            : 存在概念服务_.解除名称关系(
                信息->概念节点, 名称关系节点);
        if (!已解除) {
            return 概念名称关系删除状态::资源失败;
        }

        bool 删除成功 = true;
        for (const auto 字段 : {
            节点类型字段, 被命名概念字段, 目标词条字段}) {
            for (const auto& 关系 : 全局基础数据集.查询字段(
                名称关系节点, 字段)) {
                删除成功 = 全局基础数据集.删除字段(关系.编码) && 删除成功;
            }
        }
        for (const auto& 关系 : 全局基础数据集.查询目标关系(
            名称关系节点, 基础外部关系类型::父子)) {
            if (关系.源节点 == 概念名称关系根节点) {
                删除成功 = 全局基础数据集.删除关系(关系.编码) && 删除成功;
            }
        }
        删除成功 = 删除成功
            && 全局基础数据集.删除节点(名称关系节点);
        if (!删除成功) {
            if (*类别 == 概念类别::特征) {
                (void)特征概念服务_.绑定名称关系(
                    信息->概念节点, 名称关系节点);
            } else {
                (void)存在概念服务_.绑定名称关系(
                    信息->概念节点, 名称关系节点);
            }
            return 概念名称关系删除状态::资源失败;
        }
        return 概念名称关系删除状态::已删除;
    } catch (...) {
        return 概念名称关系删除状态::资源失败;
    }
}

概念名称关系查询结果 概念_名称关系类::获取名称关系(
    稳定编码 名称关系节点) const noexcept {
    概念名称关系查询结果 结果;
    try {
        if (!有效(名称关系节点)) return 结果;
        const auto 全集 = 准备名称核验全集(
            词服务_, 特征概念服务_, 存在概念服务_);
        if (全集.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 普通查询状态(全集.状态); return 结果;
        }
        for (const auto& 项 : 全集.普通)
            if (项.节点 == 名称关系节点) {
                结果.状态 = 概念名称关系查询状态::已找到;
                结果.信息 = 项;
                return 结果;
            }
        for (const auto& 项 : 全集.指代)
            if (项.节点 == 名称关系节点) {
                结果.状态 = 概念名称关系查询状态::已找到;
                结果.信息 = 概念名称关系信息{
                    项.节点, 项.概念.节点, 项.词条.节点};
                return 结果;
            }
        结果.状态 = 概念名称关系查询状态::未找到;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    } catch (const std::length_error&) {
        结果.状态 = 概念名称关系查询状态::资源失败;
        return 结果;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
            L"获取名称关系", L"混合名称读取发生工程异常。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__,
            L"获取名称关系", L"混合名称读取发生未知工程异常。");
    }
}

