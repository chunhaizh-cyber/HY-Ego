std::optional<稳定编码> 唯一字段引用(
    const 基础联合节点快照& 快照, 稳定编码 键) {
    std::optional<稳定编码> 值;
    for (const auto& 字段 : 快照.结构.字段组) if (字段.字段节点 == 键) {
        if (值) return std::nullopt;
        const auto* 引用 = std::get_if<稳定编码>(&字段.内容);
        if (!引用 || !有效(*引用)) return std::nullopt;
        值 = *引用;
    }
    return 值;
}
std::optional<std::int64_t> 唯一字段I64(
    const 基础联合节点快照& 快照, 稳定编码 键) {
    std::optional<std::int64_t> 值;
    for (const auto& 字段 : 快照.结构.字段组) if (字段.字段节点 == 键) {
        if (值) return std::nullopt;
        const auto* 原始 = std::get_if<基础值>(&字段.内容);
        const auto* 整数 = 原始 ? std::get_if<std::int64_t>(&原始->材料) : nullptr;
        if (!整数) return std::nullopt;
        值 = *整数;
    }
    return 值;
}
名称原始全集 读取名称原始全集(
    std::optional<稳定编码> 目标概念=std::nullopt,
    std::optional<稳定编码> 目标名称=std::nullopt,
    std::optional<稳定编码> 目标词条=std::nullopt,
    bool 保护读取=false) {
    名称原始全集 结果;
    结果.指代键快照 = 指代名称键;
    if (!结构句柄完整()) { 结果.状态 = 指代名称读取状态::依赖缺失; return 结果; }
    if (!目标词条 && !保护读取 && !结构仍存在()) return 结果;
    const auto 根首读 = 全局基础数据集.查询节点组完整结构(
        {概念名称关系根节点});
    if (根首读.状态 == 基础结构操作状态::资源失败) {
        结果.状态 = 指代名称读取状态::资源失败; return 结果;
    }
    if (根首读.状态 != 基础结构操作状态::已完成
        || 根首读.节点组.size() != 1 || !根首读.节点组.front().快照)
        return 结果;
    const auto& 根 = *根首读.节点组.front().快照;
    if ((目标词条 || 保护读取) && (根.结构.字段组.size() != 1
        || 唯一字段引用(根, 节点类型字段) != 名称关系根类型
        || 根.入向外部关系组.size() != 1
        || 根.入向外部关系组.front().类型 != 基础外部关系类型::父子
        || 根.入向外部关系组.front().源节点 != 自然语言组织根节点
        || 根.入向外部关系组.front().目标节点 != 概念名称关系根节点
        || 根.入向外部关系组.front().角色或顺序 != 0)) return 结果;
    std::set<稳定编码> 身份{
        自然语言组织根节点, 概念名称关系根节点,
        节点类型字段, 名称关系根类型, 名称关系节点类型,
        被命名概念字段, 目标词条字段};
    std::set<稳定编码> 根成员;
    for (const auto& 边 : 根.出向外部关系组) {
        if (边.源节点 != 概念名称关系根节点
            || 边.类型 != 基础外部关系类型::父子 || 边.角色或顺序 != 0
            || 身份.contains(边.目标节点) || !根成员.insert(边.目标节点).second)
            return 结果;
    }
    const bool 定向 = 目标概念.has_value() || 目标名称.has_value() || 目标词条.has_value();
    auto 查询概念 = 目标概念;
    std::optional<基础联合节点快照> 名称首读, 概念首读, 词条首读;
    if (目标名称) {
        查询概念.reset();
        if (根成员.contains(*目标名称)) {
            const auto 读取 = 全局基础数据集.查询节点组完整结构({*目标名称});
            if (读取.状态 == 基础结构操作状态::资源失败) {
                结果.状态 = 指代名称读取状态::资源失败; return 结果;
            }
            if (读取.状态 != 基础结构操作状态::已完成 || 读取.节点组.size() != 1
                || !读取.节点组.front().快照) return 结果;
            名称首读 = *读取.节点组.front().快照;
            查询概念 = 唯一字段引用(*名称首读, 被命名概念字段);
            if (!查询概念) return 结果;
        }
    }
    std::set<稳定编码> 选择名称;
    std::vector<基础字段关系> 索引字段;
    if (!定向) 选择名称 = 根成员;
    else if (目标词条) {
        const auto 读取 = 全局基础数据集.查询节点组完整结构({*目标词条});
        if (读取.状态 == 基础结构操作状态::资源失败) {
            结果.状态 = 指代名称读取状态::资源失败; return 结果;
        }
        if (读取.状态 != 基础结构操作状态::已完成 || 读取.节点组.size() != 1)
            return 结果;
        if (!读取.节点组.front().快照) {
            结果.状态 = 指代名称读取状态::依赖已变化; return 结果;
        }
        词条首读 = *读取.节点组.front().快照;
        const auto 反查 = 全局基础数据集.查询字段引用节点结构(*目标词条, 目标词条字段);
        if (反查.状态 == 基础结构操作状态::资源失败) {
            结果.状态 = 指代名称读取状态::资源失败; return 结果;
        }
        if (反查.状态 == 基础结构操作状态::节点不存在) {
            结果.状态 = 指代名称读取状态::读取漂移; return 结果;
        }
        if (反查.状态 != 基础结构操作状态::已完成) return 结果;
        索引字段 = 反查.引用字段组;
        for (const auto& 字段 : 索引字段) {
            const auto* 引用 = std::get_if<稳定编码>(&字段.内容);
            if (字段.字段节点 != 目标词条字段 || !引用 || *引用 != *目标词条
                || !根成员.contains(字段.所属节点)
                || !选择名称.insert(字段.所属节点).second) return 结果;
        }
        身份.insert(*目标词条);
    }
    else if (查询概念) {
        const auto 读取 = 全局基础数据集.查询节点组完整结构({*查询概念});
        if (读取.状态 == 基础结构操作状态::资源失败) {
            结果.状态 = 指代名称读取状态::资源失败; return 结果;
        }
        if (读取.状态 != 基础结构操作状态::已完成 || 读取.节点组.size() != 1) return 结果;
        if (读取.节点组.front().快照) {
            概念首读 = *读取.节点组.front().快照;
            const auto 反查 = 全局基础数据集.查询字段引用节点结构(*查询概念, 被命名概念字段);
            if (反查.状态 == 基础结构操作状态::资源失败) {
                结果.状态 = 指代名称读取状态::资源失败; return 结果;
            }
            if (反查.状态 == 基础结构操作状态::节点不存在) {
                结果.状态 = 指代名称读取状态::读取漂移; return 结果;
            }
            if (反查.状态 != 基础结构操作状态::已完成) return 结果;
            索引字段 = 反查.引用字段组;
            for (const auto& 字段 : 索引字段) {
                const auto* 引用 = std::get_if<稳定编码>(&字段.内容);
                if (字段.字段节点 != 被命名概念字段 || !引用 || *引用 != *查询概念
                    || !根成员.contains(字段.所属节点)
                    || !选择名称.insert(字段.所属节点).second) return 结果;
            }
            身份.insert(*查询概念);
        }
        if (目标名称 && 名称首读 && !选择名称.contains(*目标名称)) return 结果;
    }
    身份.insert(选择名称.begin(), 选择名称.end());
    const std::vector<稳定编码> 查询身份(身份.begin(), 身份.end());
    const auto 联合 = 全局基础数据集.查询节点组完整结构(查询身份);
    if (联合.状态 == 基础结构操作状态::资源失败) {
        结果.状态 = 指代名称读取状态::资源失败; return 结果;
    }
    if (联合.状态 != 基础结构操作状态::已完成
        || 联合.节点组.size() != 身份.size()) return 结果;
    for (const auto& 项 : 联合.节点组) {
        if (!项.快照) return 结果;
        if (项.查询节点 == 概念名称关系根节点
            && !同一联合节点(根, *项.快照)) {
            结果.状态 = 指代名称读取状态::读取漂移; return 结果;
        }
        if ((概念首读 && 项.查询节点 == *查询概念 && !同一联合节点(*概念首读, *项.快照))
            || (名称首读 && 项.查询节点 == *目标名称 && !同一联合节点(*名称首读, *项.快照))
            || (词条首读 && 项.查询节点 == *目标词条 && !同一联合节点(*词条首读, *项.快照))) {
            结果.状态 = 指代名称读取状态::读取漂移; return 结果;
        }
        if (概念首读 && 项.查询节点 == *查询概念) {
            // 真实入向字段独立校对索引，不能用索引自身证明未漏项。
            std::vector<基础字段关系> 真实字段;
            for (const auto& 字段 : 项.快照->入向字段组)
                if (字段.字段节点 == 被命名概念字段) 真实字段.push_back(字段);
            if (真实字段 != 索引字段) {
                结果.状态 = 指代名称读取状态::读取漂移; return 结果;
            }
        }
        if (词条首读 && 项.查询节点 == *目标词条) {
            std::vector<基础字段关系> 真实字段;
            for (const auto& 字段 : 项.快照->入向字段组)
                if (字段.字段节点 == 目标词条字段) 真实字段.push_back(字段);
            if (真实字段 != 索引字段) {
                结果.状态 = 指代名称读取状态::读取漂移; return 结果;
            }
        }
        结果.快照组.push_back(*项.快照);
    }
    for (const auto& 边 : 根.出向外部关系组) {
        if (!选择名称.contains(边.目标节点)) continue;
        const auto 位置 = std::find_if(结果.快照组.begin(), 结果.快照组.end(),
            [&](const auto& 项) { return 项.结构.节点.编码 == 边.目标节点; });
        if (位置 == 结果.快照组.end()) return 结果;
        const auto& 快照 = *位置;
        if (快照.入向外部关系组.size() != 1
            || 快照.入向外部关系组.front() != 边
            || !快照.出向外部关系组.empty()
            || 唯一字段引用(快照, 节点类型字段) != std::optional<稳定编码>{名称关系节点类型})
            return 结果;
        名称原始项 原始{快照};
        const auto 概念 = 唯一字段引用(快照, 被命名概念字段);
        const auto 词条 = 唯一字段引用(快照, 目标词条字段);
        if (!概念 || !词条) return 结果;
        if (定向 && 查询概念 && *概念 != *查询概念) {
            结果.状态 = 指代名称读取状态::读取漂移; return 结果;
        }
        原始.概念 = *概念; 原始.词条 = *词条;
        if (目标词条 && *词条 != *目标词条) {
            结果.状态 = 指代名称读取状态::读取漂移; return 结果;
        }
        if (快照.结构.字段组.size() == 6) {
            const auto 键状态 = 指代名称键状态();
            if (键状态 != 指代名称读取状态::已读取) {
                结果.状态 = 键状态; return 结果;
            }
            const auto 角色 = 唯一字段I64(快照, 指代名称键[角色键]);
            const auto 语言 = 唯一字段引用(快照, 指代名称键[语言键]);
            const auto 来源 = 唯一字段引用(快照, 指代名称键[来源键]);
            if (!角色 || *角色 < 1 || *角色 > 3 || !语言 || !来源) return 结果;
            原始.角色 = static_cast<指代名称角色>(*角色);
            原始.语言 = *语言; 原始.来源 = *来源;
        } else if (快照.结构.字段组.size() != 3) return 结果;
        for (const auto& 字段 : 快照.结构.字段组) {
            const bool 合法 = 字段.字段节点 == 节点类型字段
                || 字段.字段节点 == 被命名概念字段
                || 字段.字段节点 == 目标词条字段
                || (原始.角色 && (字段.字段节点 == 指代名称键[角色键]
                    || 字段.字段节点 == 指代名称键[语言键]
                    || 字段.字段节点 == 指代名称键[来源键]));
            if (!合法) return 结果;
        }
        结果.项组.push_back(std::move(原始));
    }
    结果.状态 = 指代名称读取状态::已读取;
    return 结果;
}

bool 同一名称全集(const 名称原始全集& 左, const 名称原始全集& 右) {
    if (左.指代键快照 != 右.指代键快照
        || 左.快照组.size() != 右.快照组.size()) return false;
    for (std::size_t i = 0; i < 左.快照组.size(); ++i)
        if (!同一联合节点(左.快照组[i], 右.快照组[i])) return false;
    return true;
}

指代名称读取状态 映射指代状态(指代概念查询状态 状态) {
    switch (状态) {
    case 指代概念查询状态::已找到: return 指代名称读取状态::已读取;
    case 指代概念查询状态::未找到:
    case 指代概念查询状态::依赖缺失: return 指代名称读取状态::依赖缺失;
    case 指代概念查询状态::输入拒绝: return 指代名称读取状态::输入拒绝;
    case 指代概念查询状态::依赖已变化: return 指代名称读取状态::依赖已变化;
    case 指代概念查询状态::读取未完成: return 指代名称读取状态::读取未完成;
    case 指代概念查询状态::读取漂移: return 指代名称读取状态::读取漂移;
    case 指代概念查询状态::资源失败: return 指代名称读取状态::资源失败;
    default: return 指代名称读取状态::结构不一致;
    }
}

指代名称读取状态 映射来源状态(新语言知识状态 状态) {
    switch (状态) {
    case 新语言知识状态::已完成: return 指代名称读取状态::已读取;
    case 新语言知识状态::未找到: return 指代名称读取状态::依赖缺失;
    case 新语言知识状态::尚未初始化:
    case 新语言知识状态::引用不可读: return 指代名称读取状态::读取未完成;
    case 新语言知识状态::读取漂移: return 指代名称读取状态::读取漂移;
    case 新语言知识状态::内部不一致: return 指代名称读取状态::结构不一致;
    case 新语言知识状态::工程未完成: return 指代名称读取状态::工程未完成;
    default: return 指代名称读取状态::输入拒绝;
    }
}

bool 同一来源(const 新语言知识来源信息& 左,
    const 新语言知识来源信息& 右) {
    return 左.节点 == 右.节点 && 左.种类 == 右.种类
        && 左.语言节点 == 右.语言节点 && 左.固定原文 == 右.固定原文;
}
bool 同一指代名称信息(const 指代名称关系信息& 左,
    const 指代名称关系信息& 右) {
    return 左.节点 == 右.节点 && 左.概念 == 右.概念
        && 左.词条 == 右.词条 && 左.语言 == 右.语言
        && 左.角色 == 右.角色 && 同一来源(左.来源, 右.来源);
}

std::optional<std::string> 标量片段(const std::string& 原文,
    std::int64_t 起点, std::int64_t 终点) {
    if (起点 < 0 || 终点 <= 起点
        || !新_语言类::严格UTF8字节串有效(原文)) return std::nullopt;
    std::vector<std::size_t> 边界{0};
    for (std::size_t i = 0; i < 原文.size();) {
        const auto 首 = static_cast<unsigned char>(原文[i]);
        i += 首 < 0x80 ? 1 : 首 < 0xE0 ? 2 : 首 < 0xF0 ? 3 : 4;
        边界.push_back(i);
    }
    if (static_cast<std::uint64_t>(终点) >= 边界.size()) return std::nullopt;
    const auto 开始 = 边界[static_cast<std::size_t>(起点)];
    const auto 结束 = 边界[static_cast<std::size_t>(终点)];
    return 原文.substr(开始, 结束 - 开始);
}

指代名称读取结果 完整读取指代项(const 名称原始项& 原始,
    const 新_词类& 词服务, const 概念_存在类& 概念服务) {
    指代名称读取结果 结果;
    if (!原始.角色) { 结果.状态 = 指代名称读取状态::未找到; return 结果; }
    const auto 概念 = 概念服务.获取指代概念(原始.概念);
    结果.状态 = 映射指代状态(概念.状态);
    if (结果.状态 != 指代名称读取状态::已读取) return 结果;
    if (!概念.信息 || std::count(概念.信息->名称关系.begin(),
        概念.信息->名称关系.end(), 原始.快照.结构.节点.编码) != 1) {
        结果.状态 = 指代名称读取状态::结构不一致; return 结果;
    }
    const auto 词 = 词服务.获取词条(原始.词条);
    if (词.状态 == 新词条查询状态::资源失败) {
        结果.状态 = 指代名称读取状态::资源失败; return 结果;
    }
    if (词.状态 != 新词条查询状态::已找到 || !词.信息) {
        结果.状态 = 词.状态 == 新词条查询状态::未找到
            ? 指代名称读取状态::依赖缺失
            : 指代名称读取状态::结构不一致;
        return 结果;
    }
    const auto 语言 = 词服务.取得语言服务().获取语言(原始.语言);
    if (语言.状态 == 新语言查询状态::资源失败) {
        结果.状态 = 指代名称读取状态::资源失败; return 结果;
    }
    if (语言.状态 != 新语言查询状态::已找到 || !语言.信息) {
        结果.状态 = 语言.状态 == 新语言查询状态::未找到
            ? 指代名称读取状态::依赖缺失
            : 指代名称读取状态::结构不一致;
        return 结果;
    }
    const auto 来源 = 词服务.取得语言服务().获取知识先天来源(原始.来源);
    结果.状态 = 映射来源状态(来源.状态);
    if (结果.状态 != 指代名称读取状态::已读取) return 结果;
    if (!来源.信息 || 词.信息->语言节点 != 原始.语言
        || 来源.信息->语言节点 != 原始.语言
        || 来源.信息->种类 != 新语言知识来源种类::经确认先天定义
        || 来源.信息->固定原文.find(词.信息->规范化词面) == std::string::npos) {
        结果.状态 = 指代名称读取状态::结构不一致; return 结果;
    }
    结果.信息 = 指代名称关系信息{
        原始.快照.结构.节点.编码, *概念.信息, *词.信息,
        *语言.信息, *原始.角色, *来源.信息};
    return 结果;
}

struct 名称核验全集 final {
    指代名称读取状态 状态 = 指代名称读取状态::输入拒绝;
    名称原始全集 原始;
    std::vector<指代名称关系信息> 指代;
    std::vector<概念名称关系信息> 普通;
};
名称核验全集 准备名称核验全集(const 新_词类& 词服务,
    const 概念_特征类& 特征服务, const 概念_存在类& 存在服务,
    名称正式读取上下文* 上下文=nullptr,
    std::optional<稳定编码> 目标概念=std::nullopt,
    std::optional<稳定编码> 目标名称=std::nullopt) {
    名称核验全集 结果;
    {
        std::lock_guard 锁(概念名称关系互斥);
        结果.原始 = 读取名称原始全集(目标概念,目标名称);
    }
    if (结果.原始.状态 != 指代名称读取状态::已读取) {
        结果.状态 = 结果.原始.状态; return 结果;
    }
    // 单项操作不承担其它概念的语义审计；目标概念的全体名称仍须互证。
    const bool 限定范围 = 目标概念.has_value() || 目标名称.has_value();
    auto 核验概念 = 目标概念;
    if (目标名称) {
        const auto 位置 = std::find_if(结果.原始.项组.begin(), 结果.原始.项组.end(),
            [&](const auto& 项) { return 项.快照.结构.节点.编码 == *目标名称; });
        if (位置 != 结果.原始.项组.end()) 核验概念 = 位置->概念;
        else 核验概念.reset();
    }
    const auto 属于核验范围 = [&](const 名称原始项& 项) {
        return !限定范围 || (核验概念 && 项.概念 == *核验概念);
    };
    名称正式读取上下文 本地正式读取;
    名称正式读取上下文* 正式读取 = &本地正式读取;
    if (上下文 != nullptr) 正式读取 = 上下文;
    for (const auto& 原始 : 结果.原始.项组) {
        if (!属于核验范围(原始)) continue;
        if (原始.角色) {
            const auto 读取 = 完整读取指代项(原始, 词服务, 存在服务);
            if (读取.状态 != 指代名称读取状态::已读取 || !读取.信息) {
                结果.状态 = 读取.状态 == 指代名称读取状态::已读取
                    ? 指代名称读取状态::结构不一致 : 读取.状态;
                return 结果;
            }
            结果.指代.push_back(*读取.信息);
        } else {
            const auto 信息 = 读取关系端点(原始.快照.结构.节点.编码,
                词服务, 特征服务, 存在服务,正式读取);
            if (!信息 || 信息->概念节点 != 原始.概念
                || 信息->词条节点 != 原始.词条
                || !概念持有关系(*信息, 特征服务, 存在服务,正式读取)) {
                结果.状态 = 名称端点读取期间变化(原始.快照.结构.节点.编码,
                        原始.概念, 原始.词条, 词服务, 特征服务, 存在服务, 正式读取)
                    ? 指代名称读取状态::读取漂移 : 指代名称读取状态::结构不一致;
                return 结果;
            }
            结果.普通.push_back(*信息);
        }
    }
    std::map<稳定编码, std::vector<稳定编码>> 根内名称;
    std::map<稳定编码, std::vector<稳定编码>> 概念持有名称;
    for (const auto& 项 : 结果.指代) {
        根内名称[项.概念.节点].push_back(项.节点);
        const auto [位置, 新增] = 概念持有名称.emplace(
            项.概念.节点, 项.概念.名称关系);
        if (!新增 && 位置->second != 项.概念.名称关系) {
            结果.状态 = 指代名称读取状态::读取漂移; return 结果;
        }
    }
    for (auto& [概念, 名称] : 根内名称) {
        std::sort(名称.begin(), 名称.end());
        if (名称 != 概念持有名称.at(概念)) {
            结果.状态 = 指代名称读取状态::结构不一致; return 结果;
        }
    }
    for (std::size_t i = 0; i < 结果.指代.size(); ++i) {
        const auto& 左 = 结果.指代[i];
        for (std::size_t j = i + 1; j < 结果.指代.size(); ++j) {
            const auto& 右 = 结果.指代[j];
            if (左.概念.节点 != 右.概念.节点
                || 左.语言.节点 != 右.语言.节点) continue;
            if ((左.词条.节点 == 右.词条.节点 && 左.角色 == 右.角色)
                || (左.角色 == 指代名称角色::首选名称
                    && 右.角色 == 指代名称角色::首选名称)) {
                结果.状态 = 指代名称读取状态::结构不一致; return 结果;
            }
        }
    }
    for (std::size_t i = 0; i < 结果.普通.size(); ++i)
        for (std::size_t j = i + 1; j < 结果.普通.size(); ++j)
            if (结果.普通[i].概念节点 == 结果.普通[j].概念节点
                && 结果.普通[i].词条节点 == 结果.普通[j].词条节点) {
                结果.状态 = 指代名称读取状态::结构不一致; return 结果;
            }
    {
        std::lock_guard 锁(概念名称关系互斥);
        const auto 当前 = 读取名称原始全集(目标概念,目标名称);
        if (当前.状态 != 指代名称读取状态::已读取) {
            结果.状态 = 当前.状态; return 结果;
        }
        if (!同一名称全集(结果.原始, 当前)) {
            结果.状态 = 指代名称读取状态::读取漂移; return 结果;
        }
    }
    for (const auto& 原始 : 结果.原始.项组) if (原始.角色 && 属于核验范围(原始)) {
        const auto 再读 = 完整读取指代项(原始, 词服务, 存在服务);
        if (再读.状态 != 指代名称读取状态::已读取 || !再读.信息) {
            结果.状态 = 再读.状态 == 指代名称读取状态::已读取
                ? 指代名称读取状态::结构不一致 : 再读.状态;
            return 结果;
        }
        const auto 位置 = std::find_if(结果.指代.begin(), 结果.指代.end(),
            [&](const auto& 项) { return 项.节点 == 再读.信息->节点; });
        if (位置 == 结果.指代.end() || !同一指代名称信息(*位置, *再读.信息)) {
            结果.状态 = 指代名称读取状态::依赖已变化; return 结果;
        }
    }
    结果.状态 = 指代名称读取状态::已读取;
    return 结果;
}

指代名称读取状态 补齐名称侧预期(
    const 名称原始全集& 原始, std::vector<基础联合节点快照>& 预期,
    const std::vector<稳定编码>& 新身份) {
    std::set<稳定编码> 身份(新身份.begin(), 新身份.end());
    for (const auto& 项 : 原始.快照组) {
        身份.insert(项.结构.节点.编码);
        for (const auto& 字段 : 项.结构.字段组) {
            身份.insert(字段.字段节点);
            if (const auto* 引用 = std::get_if<稳定编码>(&字段.内容))
                身份.insert(*引用);
        }
        for (const auto& 边 : 项.入向外部关系组) {
            身份.insert(边.源节点); 身份.insert(边.目标节点);
        }
        for (const auto& 边 : 项.出向外部关系组) {
            身份.insert(边.源节点); 身份.insert(边.目标节点);
        }
    }
    if (std::any_of(身份.begin(), 身份.end(),
        [](稳定编码 编码) { return !有效(编码); }))
        return 指代名称读取状态::结构不一致;
    const std::vector<稳定编码> 查询(身份.begin(), 身份.end());
    const auto 联合 = 全局基础数据集.查询节点组完整结构(查询);
    if (联合.状态 == 基础结构操作状态::资源失败)
        return 指代名称读取状态::资源失败;
    if (联合.状态 != 基础结构操作状态::已完成)
        return 指代名称读取状态::结构不一致;
    for (const auto& 项 : 联合.节点组) {
        if (!项.快照) return 指代名称读取状态::依赖缺失;
        const auto 原位置 = std::find_if(原始.快照组.begin(), 原始.快照组.end(),
            [&](const auto& 前) { return 前.结构.节点.编码 == 项.查询节点; });
        if (原位置 != 原始.快照组.end()
            && !同一联合节点(*原位置, *项.快照))
            return 指代名称读取状态::读取漂移;
        预期.push_back(*项.快照);
    }
    return 指代名称读取状态::已读取;
}

