std::optional<概念类别> 识别概念类别(
    稳定编码 概念节点,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务, const 概念_动态类& 动态概念服务,名称正式读取上下文* 上下文=nullptr) {
    if (动态概念服务.获取动态概念(概念节点)) return 概念类别::动态;
    const bool 是特征 = 特征概念服务.是特征概念节点(概念节点);
    const bool 是存在 = 存在概念服务.是存在概念节点(概念节点);
    // 类别根不具有FT值域；其owner证明独立于存在结构schema是否就绪。
    if(!是特征&&!是存在) {
        const auto 根=特征概念服务.读取特征类别根概念保护();
        if(根.状态==正式概念读取状态::已读取&&根.信息&&根.信息->节点==概念节点)
            return 概念类别::特征类别根;
        if(根.状态==正式概念读取状态::前提已变化)return std::nullopt;
    }
    const auto 正式定义 = 读取名称用正式定义(概念节点,存在概念服务,上下文);
    if (!是特征 && !是存在 && (正式定义.状态 == 正式结构操作状态::前提已变化
        || 正式定义.状态 == 正式结构操作状态::依赖未就绪)) return std::nullopt;
    const bool 是信息定义 = 正式定义.状态 == 正式结构操作状态::已读取 && 正式定义.信息.has_value();
    if (static_cast<unsigned>(是特征) + static_cast<unsigned>(是存在)
            + static_cast<unsigned>(是信息定义) > 1)
        throw std::logic_error("concept identity shapes overlap");
    if (是特征) return 概念类别::特征;
    if (是存在) return 概念类别::存在;
    if (是信息定义) return 概念类别::信息定义;
    return std::nullopt;
}

std::optional<概念名称关系信息> 读取关系端点(
    稳定编码 节点,
    const 新_词类& 词服务,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务, const 概念_动态类& 动态概念服务,名称正式读取上下文* 上下文=nullptr) {
    if (!节点仍存在(节点) || !类型为(节点, 名称关系节点类型)
        || !有唯一父节点(节点, 概念名称关系根节点)) {
        return std::nullopt;
    }
    const auto 概念节点 = 读取唯一节点字段(节点, 被命名概念字段);
    const auto 词条节点 = 读取唯一节点字段(节点, 目标词条字段);
    if (!概念节点 || !词条节点
        || !识别概念类别(
            *概念节点, 特征概念服务, 存在概念服务, 动态概念服务,上下文)
        || !词服务.是词条节点(*词条节点)) {
        return std::nullopt;
    }
    return 概念名称关系信息{节点, *概念节点, *词条节点};
}

bool 概念持有关系(
    const 概念名称关系信息& 信息,
    const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务, const 概念_动态类& 动态概念服务,名称正式读取上下文* 上下文=nullptr) {
    std::vector<稳定编码> 关系组;
    if (const auto 特征 = 特征概念服务.获取特征概念(信息.概念节点)) {
        关系组 = 特征->名称关系;
    } else if (const auto 存在 = 存在概念服务.获取存在概念(信息.概念节点)) {
        关系组 = 存在->名称关系;
    } else if (const auto 动态 = 动态概念服务.获取动态概念(信息.概念节点)) {
        关系组 = 动态->名称关系;
    } else {
        const auto 根=特征概念服务.读取特征类别根概念保护();
        if(根.状态==正式概念读取状态::前提已变化)return false;
        if(根.状态==正式概念读取状态::已读取&&根.信息&&根.信息->节点==信息.概念节点)
            return std::count(根.信息->名称关系.begin(),根.信息->名称关系.end(),信息.节点)==1;
        const auto 正式定义 = 读取名称用正式定义(信息.概念节点,存在概念服务,上下文);
        if (正式定义.状态 != 正式结构操作状态::已读取 || !正式定义.信息) return false;
        关系组 = 正式定义.信息->名称关系;
    }
    return std::count(关系组.begin(), 关系组.end(), 信息.节点) == 1;
}

// 名称端点或持有核对未通过时，区分读取期间发生并发变化（读取漂移）与名称结构确实不一致：
// 全集核验逐项读取概念与正式定义时不持有其它owner的锁，并发写入可使首读落在中间状态
// （再读即通过），信息定义概念的受保护读取也会返回前提已变化/依赖未就绪；这些属于正常变化，
// 不能当作名称结构不一致（调用方据此按读取漂移重读或零动作）。只有再读仍不通过才是结构不一致。
bool 名称端点读取期间变化(
    稳定编码 节点, 稳定编码 概念节点, 稳定编码 词条节点,
    const 新_词类& 词服务, const 概念_特征类& 特征概念服务,
    const 概念_存在类& 存在概念服务, const 概念_动态类& 动态概念服务,名称正式读取上下文* 上下文) {
    if (!节点仍存在(节点)) return true;
    if (!有效(概念节点)) return false;
    // 复核：同一名称关系再读时端点与持有核对已通过，说明首读落在并发写入的中间状态。
    if (const auto 再读 = 读取关系端点(节点, 词服务, 特征概念服务, 存在概念服务, 动态概念服务, 上下文);
        再读 && 再读->概念节点 == 概念节点 && 再读->词条节点 == 词条节点
        && 概念持有关系(*再读, 特征概念服务, 存在概念服务, 动态概念服务, 上下文))
        return true;
    if (特征概念服务.是特征概念节点(概念节点) || 存在概念服务.是存在概念节点(概念节点)) return false;
    const auto 根=特征概念服务.读取特征类别根概念保护();
    if(根.状态==正式概念读取状态::前提已变化)return true;
    if(根.状态==正式概念读取状态::已读取&&根.信息&&根.信息->节点==概念节点)return false;
    const auto 正式定义 = 读取名称用正式定义(概念节点,存在概念服务,上下文);
    return 正式定义.状态 == 正式结构操作状态::前提已变化
        || 正式定义.状态 == 正式结构操作状态::依赖未就绪;
}



bool 同一联合节点(const 基础联合节点快照& 左,
    const 基础联合节点快照& 右) {
    return 左.结构.节点 == 右.结构.节点
        && 左.结构.字段组 == 右.结构.字段组
        && 左.入向外部关系组 == 右.入向外部关系组
        && 左.出向外部关系组 == 右.出向外部关系组
        && 左.入向字段组 == 右.入向字段组;
}

// 只在一次名称调用的栈上存活；每次复用仍真实复核全部保护。
struct 名称正式读取上下文 final {
    std::map<稳定编码,正式结构概念保护结果> 已成功读取;
};
正式结构概念结果 读取名称用正式定义(稳定编码 节点,
    const 概念_存在类& 服务,名称正式读取上下文* 上下文) {
    if(!上下文)return 服务.读取正式结构概念(节点);
    try {
    const auto old=上下文->已成功读取.find(节点);
    if(old!=上下文->已成功读取.end()) {
        std::map<稳定编码,const 基础联合节点快照*> 保护;
        for(const auto& s:old->second.完整保护组) {
            if(!有效(s.结构.节点.编码))工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"名称正式读取复用",L"缓存保护身份无效。");
            const auto [it,added]=保护.emplace(s.结构.节点.编码,&s);
            if(!added&&!同一联合节点(*it->second,s))工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"名称正式读取复用",L"缓存保护内容冲突。");
        }
        if(保护.empty())工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"名称正式读取复用",L"缓存完整保护缺失。");
        std::vector<稳定编码> 身份;身份.reserve(保护.size());
        for(const auto& [n,s]:保护)身份.push_back(n);
        const auto 当前=全局基础数据集.查询节点组完整结构(身份);
        if(当前.状态!=基础结构操作状态::已完成||当前.节点组.size()!=身份.size())
            工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"名称正式读取复用",L"完整保护批量读取失败。");
        bool 相同=true;
        for(std::size_t i=0;i<身份.size();++i) {
            const auto& item=当前.节点组[i];
            if(item.查询节点!=身份[i]||(item.快照&&item.快照->结构.节点.编码!=身份[i]))
                工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"名称正式读取复用",L"完整保护批量回执身份无效。");
            if(!item.快照||!同一联合节点(*保护.at(身份[i]),*item.快照))相同=false;
        }
        if(相同)return {old->second.状态,old->second.信息};
    }
    // 正常变化不解释为否定；回到原正式owner完整读取并刷新本调用缓存。
    auto 当前=服务.读取正式结构概念保护(节点);
    if(当前.状态==正式结构操作状态::已读取) {
        if(!当前.信息||当前.信息->节点!=节点||当前.完整保护组.empty())
            工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"名称正式读取复用",L"正式读取成功但身份或完整保护缺失。");
        上下文->已成功读取.insert_or_assign(节点,当前);
    } else 上下文->已成功读取.erase(节点);
    return {当前.状态,std::move(当前.信息)};
    } catch(const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"名称正式读取复用",L"调用内正式读取复用发生工程异常。",异常.what());
    } catch(...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__),__LINE__,L"名称正式读取复用",L"调用内正式读取复用发生未知工程异常。");
    }
}

