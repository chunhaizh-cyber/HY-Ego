using 出生状态 = 原子I64特征出生状态;
using 窄读状态 = 原子I64特征窄读取状态;

出生状态 映射窄读状态(窄读状态 状态) noexcept {
    switch (状态) {
    case 窄读状态::入口拒绝: return 出生状态::入口拒绝;
    case 窄读状态::未找到: return 出生状态::未找到;
    case 窄读状态::位置冲突: return 出生状态::位置冲突;
    case 窄读状态::资源失败: return 出生状态::资源失败;
    default: return 出生状态::内部不一致;
    }
}

出生状态 映射使用状态(原子I64特征出生使用读取状态 状态) noexcept {
    using S = 原子I64特征出生使用读取状态;
    switch (状态) {
    case S::入口拒绝: return 出生状态::入口拒绝;
    case S::未找到: return 出生状态::未找到;
    case S::概念不适配: return 出生状态::概念不适配;
    case S::资源失败: return 出生状态::资源失败;
    default: return 出生状态::内部不一致;
    }
}

L1有限N分区原子写集请求 转换写集(const L1所有者范围写集请求& 输入) {
    L1有限N分区原子写集请求 输出;
    输出.写入幂等身份 = 输入.写入幂等身份;
    输出.退出事实 = 输入.退出事实;
    const auto 转换引用 = [](const L1所有者范围事实引用& 引用)
        -> L1有限N分区原子事实引用值 {
        return std::visit([](const auto& 值) -> L1有限N分区原子事实引用值 {
            return 值;
        }, 引用);
    };
    for (const auto& 节点 : 输入.节点)
        输出.节点.push_back({节点.本地键, 节点.种类, 节点.属性类型表示});
    for (const auto& 关系 : 输入.关系)
        输出.关系.push_back({关系.本地键, 转换引用(关系.源节点),
            转换引用(关系.目标节点), 转换引用(关系.关系类型节点),
            关系.角色或顺序});
    for (const auto& 值 : 输入.值)
        输出.值.push_back({值.本地键, 转换引用(值.所属节点),
            转换引用(值.属性类型节点), 值.材料, 转换引用(值.来源节点)});
    for (const auto& 属性 : 输入.属性槽变更)
        输出.属性槽变更.push_back({转换引用(属性.所属节点),
            转换引用(属性.属性类型节点), 属性.新当前值});
    return 输出;
}

稳定编码 查找编码(
    const std::vector<std::pair<L1所有者范围写集本地键, 稳定编码>>& 映射,
    std::uint32_t 本地键) {
    稳定编码 结果{};
    for (const auto& [键, 编码] : 映射) {
        if (键.值 != 本地键) continue;
        if (有效(结果) || !有效(编码)) throw 出生状态::内部不一致;
        结果 = 编码;
    }
    if (!有效(结果)) throw 出生状态::内部不一致;
    return 结果;
}

