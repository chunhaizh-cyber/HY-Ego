原子I64特征出生数据服务::原子I64特征出生数据服务(
    原子I64特征内容参与者& 内容, 原子I64特征holder参与者& holder,
    原子I64特征组织参与者& 组织, 原子I64特征概念参与者& 概念)
    : 内容_(内容), holder_(holder), 组织_(组织), 概念_(概念) {
    const auto& 底座 = 内容.原子I64底座();
    const std::array<L1所有者范围写端口*, 4> 端口{
        &内容.原子I64端口(), &holder.原子I64端口(),
        &组织.原子I64端口(), &概念.原子I64端口()};
    if (&底座 != &holder.原子I64底座() || &底座 != &组织.原子I64底座()
        || &底座 != &概念.原子I64底座())
        throw std::invalid_argument("four owner I64 providers");
    for (std::size_t i = 0; i < 端口.size(); ++i) {
        if (!端口[i]->有效() || !端口[i]->绑定于(底座))
            throw std::invalid_argument("four owner I64 providers");
        for (std::size_t j = 0; j < i; ++j)
            if (端口[i]->所有者身份() == 端口[j]->所有者身份())
                throw std::invalid_argument("four owner I64 providers");
    }
}

原子I64特征候选查询结果 原子I64特征出生数据服务::查询精确候选(
    const 原子I64特征候选查询请求& 请求) const {
    原子I64特征候选查询结果 结果;
    结果.原请求 = 请求;
    if (!有效(请求.位置.场景) || !有效(请求.位置.组织父)
        || !有效(请求.正式特征类型))
        return 结果;
    const auto 内容候选 = 内容_.查询原子I64内容候选(请求);
    if (内容候选.状态 != 原子I64特征候选查询状态::已读取)
        return 内容候选;
    if (内容候选.原请求 != 请求) {
        结果.状态 = 原子I64特征候选查询状态::内部不一致;
        return 结果;
    }
    try {
        for (const auto& 候选 : 内容候选.候选) {
            if (!有效(候选.F)) throw 原子I64特征候选查询状态::内部不一致;
            const auto holder = holder_.读取原子I64holder({请求.位置.场景, 候选.F});
            if (holder.状态 == 原子I64特征窄读取状态::未找到) continue;
            if (holder.状态 != 原子I64特征窄读取状态::已读取 || !holder.事实)
                throw holder.状态 == 原子I64特征窄读取状态::资源失败
                    ? 原子I64特征候选查询状态::资源失败
                    : 原子I64特征候选查询状态::内部不一致;
            if (holder.事实->holder != 请求.位置.场景 || holder.事实->F != 候选.F)
                throw 原子I64特征候选查询状态::内部不一致;
            const auto 组织 = 组织_.读取原子I64组织(
                {请求.位置.场景, 请求.位置.组织父, 候选.F});
            if (组织.状态 != 原子I64特征窄读取状态::已读取 || !组织.事实)
                throw 组织.状态 == 原子I64特征窄读取状态::资源失败
                    ? 原子I64特征候选查询状态::资源失败
                    : 原子I64特征候选查询状态::内部不一致;
            if (组织.事实->C != 请求.位置.场景 || 组织.事实->P != 请求.位置.组织父
                || 组织.事实->F != 候选.F)
                throw 原子I64特征候选查询状态::内部不一致;
            结果.候选.push_back(候选);
        }
        结果.状态 = 原子I64特征候选查询状态::已读取;
    } catch (原子I64特征候选查询状态 状态) {
        结果.状态 = 状态;
        结果.候选.clear();
    } catch (const std::bad_alloc&) {
        结果.状态 = 原子I64特征候选查询状态::资源失败;
        结果.候选.clear();
    } catch (...) {
        结果.状态 = 原子I64特征候选查询状态::内部不一致;
        结果.候选.clear();
    }
    return 结果;
}

原子I64特征出生结果 原子I64特征出生数据服务::创建(
    const 原子I64特征出生请求& 请求) {
    原子I64特征出生结果 结果;
    结果.原请求 = 请求;
    bool 已派发 = false;
    const auto 失败 = [&](出生状态 状态) {
        结果.状态 = 已派发 ? 出生状态::已可能发布 : 状态;
        结果.事实.reset();
    };
    try {
        std::lock_guard<std::mutex> 锁(mutex_);
        if (!有效(请求.位置.场景) || !有效(请求.位置.组织父)
            || !有效(请求.正式特征类型) || !有效(请求.FCv.值))
            throw 出生状态::入口拒绝;
        const std::array<L1所有者范围写入幂等身份, 5> 键{
            请求.键.组合, 请求.键.内容, 请求.键.已知, 请求.键.组织, 请求.键.概念使用};
        for (std::size_t i = 0; i < 键.size(); ++i) {
            if (!有效(键[i])) throw 出生状态::入口拒绝;
            for (std::size_t j = 0; j < i; ++j)
                if (键[i] == 键[j]) throw 出生状态::入口拒绝;
        }
        if (!内容_.原子I64结构已就绪() || !holder_.原子I64结构已就绪()
            || !组织_.原子I64结构已就绪() || !概念_.原子I64结构已就绪())
            throw 出生状态::入口拒绝;

        const std::array<L1所有者范围写端口*, 4> 端口{
            &内容_.原子I64端口(), &holder_.原子I64端口(),
            &组织_.原子I64端口(), &概念_.原子I64端口()};
        std::array<L1所有者范围首次写入读取结果, 4> 首次{};
        std::size_t 已存在 = 0;
        for (std::size_t i = 0; i < 端口.size(); ++i) {
            首次[i] = 端口[i]->读取首次写入材料({键[i + 1]});
            if (首次[i].所有者 != 端口[i]->所有者身份() || 首次[i].写入幂等身份 != 键[i + 1])
                throw 出生状态::内部不一致;
            if (首次[i].状态 == L1所有者范围读取状态::成功) {
                if (!首次[i].首次规范化写集 || !首次[i].首次写入结果
                    || 首次[i].首次写入结果->状态 != L1所有者范围写入状态::成功
                    || !首次[i].首次写入结果->是否形成内存权威发布)
                    throw 出生状态::已可能发布;
                ++已存在;
            } else if (首次[i].状态 == L1所有者范围读取状态::未找到) {
                if (首次[i].首次规范化写集 || 首次[i].首次写入结果)
                    throw 出生状态::内部不一致;
            } else if (首次[i].状态 == L1所有者范围读取状态::资源失败) {
                throw 出生状态::资源失败;
            } else {
                throw 出生状态::已可能发布;
            }
        }
        if (已存在 != 0 && 已存在 != 4) throw 出生状态::已可能发布;

        L1有限N分区原子事务请求 事务;
        事务.组合写入幂等身份 = 请求.键.组合;
        if (已存在 == 4) {
            for (std::size_t i = 0; i < 4; ++i)
                事务.参与者写集组.push_back({{static_cast<std::uint8_t>(i + 1)},
                    端口[i]->所有者身份(), 转换写集(*首次[i].首次规范化写集)});
        } else {
            const auto 接纳 = [&](auto 片段, std::uint8_t 序号) {
                if (片段.状态 != 出生状态::已创建 || !片段.数据
                    || 片段.数据->参与者.值 != 序号
                    || 片段.数据->所有者 != 端口[序号 - 1]->所有者身份()
                    || 片段.数据->写集.写入幂等身份 != 键[序号])
                    throw 出生状态::内部不一致;
                return std::move(*片段.数据);
            };
            事务.参与者写集组.push_back(接纳(内容_.准备原子I64出生片段(请求), 1));
            事务.参与者写集组.push_back(接纳(holder_.准备原子I64出生片段(请求), 2));
            事务.参与者写集组.push_back(接纳(组织_.准备原子I64出生片段(请求), 3));
            事务.参与者写集组.push_back(接纳(概念_.准备原子I64出生片段(请求), 4));
        }

        const std::vector<const L1所有者范围写端口*> 其它{端口[1], 端口[2], 端口[3]};
        已派发 = true;
        const auto 提交 = 内容_.原子I64端口().提交有限N分区原子事务(事务, 其它);
        using TS = L1有限N分区原子事务状态;
        if (提交.状态 != TS::已提交 && 提交.状态 != TS::精确重复) {
            if (提交.状态 == TS::已可能发布) throw 出生状态::已可能发布;
            已派发 = false;
            if (提交.状态 == TS::幂等冲突) throw 出生状态::幂等冲突;
            if (提交.状态 == TS::资源失败) throw 出生状态::资源失败;
            if (提交.状态 == TS::入口拒绝) throw 出生状态::入口拒绝;
            throw 出生状态::内部不一致;
        }
        if (提交.组合写入幂等身份 != 请求.键.组合
            || 提交.参与者结果组.size() != 4)
            throw 出生状态::已可能发布;
        std::array<std::vector<std::pair<L1所有者范围写集本地键, 稳定编码>>, 4> 映射;
        std::array<bool, 4> 已见{};
        for (const auto& 项 : 提交.参与者结果组) {
            if (项.参与者.值 == 0 || 项.参与者.值 > 4 || 已见[项.参与者.值 - 1]
                || 项.所有者 != 端口[项.参与者.值 - 1]->所有者身份())
                throw 出生状态::已可能发布;
            已见[项.参与者.值 - 1] = true;
            映射[项.参与者.值 - 1] = 项.新编码映射;
        }
        for (bool 见 : 已见) if (!见) throw 出生状态::已可能发布;
        const auto F = 查找编码(映射[0], 1);
        const auto 已知 = 查找编码(映射[1], 1);
        const auto 组织 = 查找编码(映射[2], 1);
        const auto 使用 = 查找编码(映射[3], 1);
        const auto 读回 = 读取({F, 请求.位置});
        if (读回.状态 != 出生状态::已读取 || !读回.事实
            || 读回.事实->已知关系 != 已知 || 读回.事实->组织关系 != 组织
            || 读回.事实->概念使用关系 != 使用
            || 读回.事实->正式特征类型 != 请求.正式特征类型
            || 读回.事实->准确I64 != 请求.准确I64
            || 读回.事实->FCv != 请求.FCv.值)
            throw 提交.状态 == TS::精确重复 ? 出生状态::幂等冲突 : 出生状态::已可能发布;
        结果.事实 = *读回.事实;
        结果.状态 = 提交.状态 == TS::精确重复 ? 出生状态::精确重复 : 出生状态::已创建;
    } catch (出生状态 状态) {
        失败(状态);
    } catch (const std::bad_alloc&) {
        失败(出生状态::资源失败);
    } catch (...) {
        失败(出生状态::内部不一致);
    }
    return 结果;
}

原子I64特征出生读取结果 原子I64特征出生数据服务::读取(
    const 原子I64特征出生读取请求& 请求) const {
    原子I64特征出生读取结果 结果;
    if (!有效(请求.F) || !有效(请求.位置.场景) || !有效(请求.位置.组织父))
        return 结果;
    const auto 内容 = 内容_.读取原子I64内容({请求.F});
    if (内容.状态 != 窄读状态::已读取 || !内容.事实) {
        结果.状态 = 映射窄读状态(内容.状态);
        return 结果;
    }
    const auto holder = holder_.读取原子I64holder({请求.位置.场景, 请求.F});
    if (holder.状态 != 窄读状态::已读取 || !holder.事实) {
        结果.状态 = 映射窄读状态(holder.状态);
        return 结果;
    }
    const auto 组织 = 组织_.读取原子I64组织({请求.位置.场景, 请求.位置.组织父, 请求.F});
    if (组织.状态 != 窄读状态::已读取 || !组织.事实) {
        结果.状态 = 映射窄读状态(组织.状态);
        return 结果;
    }
    const auto 使用 = 概念_.读取原子I64出生使用({请求.F});
    if (使用.状态 != 原子I64特征出生使用读取状态::已读取 || !使用.事实) {
        结果.状态 = 映射使用状态(使用.状态);
        return 结果;
    }
    if (内容.事实->F != 请求.F || !有效(内容.事实->正式特征类型)
        || !有效(内容.事实->类型关系) || !有效(内容.事实->I64值事实)
        || holder.事实->holder != 请求.位置.场景 || holder.事实->F != 请求.F
        || !有效(holder.事实->已知关系) || !有效(holder.事实->关系类型)
        || 组织.事实->C != 请求.位置.场景 || 组织.事实->P != 请求.位置.组织父
        || 组织.事实->F != 请求.F || !有效(组织.事实->组织关系)
        || !有效(组织.事实->组织关系类型) || 组织.事实->路径.empty()
        || 组织.事实->路径.back().关系 != 组织.事实->组织关系
        || 组织.事实->路径.back().源 != 请求.位置.组织父
        || 组织.事实->路径.back().目标 != 请求.F
        || 使用.事实->F != 请求.F || !有效(使用.事实->关系)
        || !有效(使用.事实->FCv.值)) {
        结果.状态 = 出生状态::内部不一致;
        return 结果;
    }
    结果.事实 = 原子I64特征出生事实{请求.F, 内容.事实->正式特征类型,
        使用.事实->FCv.值, 内容.事实->准确I64, 请求.位置, 请求.位置.场景,
        holder.事实->已知关系, 组织.事实->组织关系, 使用.事实->关系};
    结果.状态 = 出生状态::已读取;
    return 结果;
}

bool 原子I64特征出生结果::成功() const noexcept {
    return (状态 == 出生状态::已创建 || 状态 == 出生状态::精确重复)
        && 事实 && 有效(事实->F) && 有效(事实->FCv) && 有效(事实->概念使用关系);
}

bool 原子I64特征出生读取结果::成功(
    const 原子I64特征出生读取请求& 请求) const noexcept {
    return 状态 == 出生状态::已读取 && 事实 && 事实->F == 请求.F;
}

