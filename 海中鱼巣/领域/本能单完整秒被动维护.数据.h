inline bool 本能单完整秒被动维护载荷完整_v1(
    const 本能单完整秒被动维护载荷_v1& 载荷) noexcept {
    if (载荷.服务值前值 < 0 || 载荷.服务值前值 > 根值上界_v1
        || 载荷.服务值后值 < 0 || 载荷.服务值后值 > 载荷.服务值前值
        || 载荷.服务实际减少 != 载荷.服务值前值 - 载荷.服务值后值
        || (载荷.服务值后值 == 0 && 载荷.服务比例 != 0)
        || (载荷.服务值后值 > 0
            && (载荷.服务比例 < 1 || 载荷.服务比例 > 99))
        || 载荷.生存安全根前值 < 0 || 载荷.生存安全根前值 > 根值上界_v1
        || 载荷.生存安全根后值 < 0 || 载荷.生存安全根后值 > 根值上界_v1
        || 载荷.生存安全有符号变化
            != 载荷.生存安全根后值 - 载荷.生存安全根前值
        || !(1 < 载荷.低位阈值 && 载荷.低位阈值 < 载荷.高位阈值
            && 载荷.高位阈值 <= 根值上界_v1)
        || 载荷.安全根定义版本 == 0
        || 载荷.服务时间维护规则版本 != 服务时间维护规则版本_v1
        || 载荷.生存安全回归规则版本 != 生存安全回归规则版本_v1)
        return false;
    switch (载荷.服务分支) {
    case 服务被动维护分支_v1::无需求每秒一:
    case 服务被动维护分支_v1::最长等待衰减:
        break;
    case 服务被动维护分支_v1::三十天门禁归零:
        if (载荷.服务值后值 != 0) return false;
        break;
    case 服务被动维护分支_v1::三十天门禁最低一:
        if (载荷.服务值后值 != 1) return false;
        break;
    case 服务被动维护分支_v1::三十天门禁活动零保持:
        if (载荷.服务值前值 != 0 || 载荷.服务值后值 != 0) return false;
        break;
    default: return false;
    }
    switch (载荷.安全分支) {
    case 生存安全被动回归分支_v1::终止保持:
        return 载荷.生存安全根前值 == 0 && 载荷.生存安全根后值 == 0;
    case 生存安全被动回归分支_v1::主动安全优先:
        return 载荷.主动安全裁决 == 同秒主动安全裁决_v1::已改变A
            && 载荷.生存安全根后值 == 载荷.生存安全根前值;
    case 生存安全被动回归分支_v1::服务为零收敛休眠:
        return 载荷.服务值后值 == 0 && 载荷.生存安全根前值 >= 1
            && 载荷.生存安全根后值 == 1;
    case 生存安全被动回归分支_v1::低位回升:
        return 载荷.服务值后值 > 0
            && 载荷.生存安全根前值 < 载荷.低位阈值
            && 载荷.低位回升门禁 == 安全低位回升门禁_v1::允许
            && 载荷.生存安全根后值 > 载荷.生存安全根前值
            && 载荷.生存安全根后值 <= 载荷.低位阈值;
    case 生存安全被动回归分支_v1::低位禁止保持:
        return 载荷.服务值后值 > 0
            && 载荷.生存安全根前值 < 载荷.低位阈值
            && 载荷.低位回升门禁 == 安全低位回升门禁_v1::禁止
            && 载荷.生存安全根后值 == 载荷.生存安全根前值;
    case 生存安全被动回归分支_v1::闭区间保持:
        return 载荷.低位阈值 <= 载荷.生存安全根前值
            && 载荷.生存安全根前值 <= 载荷.高位阈值
            && 载荷.生存安全根后值 == 载荷.生存安全根前值;
    case 生存安全被动回归分支_v1::高位回落:
        return 载荷.服务值后值 > 0
            && 载荷.生存安全根前值 > 载荷.高位阈值
            && 载荷.高位阈值 <= 载荷.生存安全根后值
            && 载荷.生存安全根后值 < 载荷.生存安全根前值;
    default: return false;
    }
}

