新存在特征值更新结果 新_存在类::完成已提交准确特征变化(
    稳定编码 存在节点, 稳定编码 特征节点, const 新特征值添加结果& 已提交特征结果,
    稳定编码 预期特征类型概念节点, const 新特征准确值& 预期当前值,
    bool 引用集合, const 新状态强时间& 强时间) noexcept {
    新存在特征值更新结果 结果;
    结果.特征结果 = 已提交特征结果;
    结果.状态 = 新存在操作状态::特征已更新但专属概念未完成;
    try {
        if (!实例强时间有效(强时间)
            || 已提交特征结果.状态 != 新特征写入状态::已完成
            || !已提交特征结果.当前值已改变
            || !已提交特征结果.命中次数已增加
            || !有效(预期特征类型概念节点)) return 结果;

        // 这里只读E自己的物理成员。不能用持E锁的获取存在包住F/EC/S调用。
        const auto 原结构 = 读取匹配存在结构投影(存在节点);
        if (!原结构 || !std::binary_search(原结构->顶层特征节点组.begin(),
            原结构->顶层特征节点组.end(), 特征节点)) return 结果;

        std::map<稳定编码, 新特征信息> 特征投影组;
        std::map<稳定编码, 稳定编码> 概念投影;
        std::vector<稳定编码> 概念组;
        for (const auto F : 原结构->顶层特征节点组) {
            const auto 信息 = 特征服务_.获取特征(F);
            if (!信息 || 信息->节点 != F || 信息->上级特征节点) return 结果;
            const auto 定义 = 特征服务_.捕获特征匹配定义(信息->特征概念节点);
            if (!定义 || !概念投影.emplace(定义->特征类型根, 信息->特征概念节点).second)
                return 结果;
            if (F == 特征节点 && (定义->特征类型根 != 预期特征类型概念节点
                || (引用集合 ? 定义->比较规则 != 特征概念比较规则::需求集合身份判等
                    : 定义->材料类型 != 特征概念材料物理类型::I64标量)
                || 信息->当前值 != std::optional<新特征准确值>{新特征准确值{预期当前值}}))
                return 结果;
            特征投影组.emplace(F, *信息);
            概念组.push_back(信息->特征概念节点);
        }
        const auto 旧概念 = 存在概念服务_.获取存在概念(原结构->专属存在概念节点);
        if (!旧概念 || 旧概念->种类 != 存在概念种类::专属
            || 旧概念->对应存在节点 != std::optional<稳定编码>{存在节点}) return 结果;
        结果.专属概念结果 = 存在概念服务_.更新专属存在概念(
            原结构->专属存在概念节点, 概念组);
        if (*结果.专属概念结果 != 存在概念操作状态::已更新
            && *结果.专属概念结果 != 存在概念操作状态::无变化) return 结果;

        结果.状态 = 新存在操作状态::特征已更新但状态未完成;
        结果.状态结果 = 状态服务_.建立状态(存在节点, 特征节点, 强时间);
        if (结果.状态结果->状态 != 新状态操作状态::已完成
            || !结果.状态结果->状态节点) return 结果;
        const auto 状态 = 状态服务_.获取状态(*结果.状态结果->状态节点);
        if (!状态 || 状态->被描述存在节点 != 存在节点
            || 状态->来源实例特征节点 != 特征节点
            || 状态->特征类型概念节点 != 特征投影组.at(特征节点).特征概念节点
            || 状态->固定准确值 != 新特征准确值{预期当前值}
            || 状态->强时间 != 强时间) return 结果;

        // 新S的入边是本次真实派生，不能把旧L1入边快照当作不变条件。
        // 比较完整F信息投影与E成员；另一F并发改变时不交付假完整EC。
        结果.状态 = 新存在操作状态::特征已更新但专属概念未完成;
        for (const auto& [F, 原投影] : 特征投影组) {
            const auto 当前 = 特征服务_.获取特征(F);
            if (!当前 || *当前 != 原投影) return 结果;
            const auto 定义 = 特征服务_.捕获特征匹配定义(当前->特征概念节点);
            if (!定义 || !概念投影.contains(定义->特征类型根)
                || 概念投影.at(定义->特征类型根) != 当前->特征概念节点) return 结果;
        }
        const auto 最终概念 = 存在概念服务_.获取存在概念(原结构->专属存在概念节点);
        if (!最终概念 || 最终概念->种类 != 存在概念种类::专属
            || 最终概念->对应存在节点 != std::optional<稳定编码>{存在节点}
            || 最终概念->特征组.size() != 概念投影.size()) return 结果;
        auto 待读回项 = 概念投影;
        for (const auto& 项 : 最终概念->特征组) {
            const auto 位置 = 待读回项.find(项.特征类型概念);
            if (位置 == 待读回项.end() || 位置->second != 项.具体特征概念) return 结果;
            待读回项.erase(位置);
        }
        if (!待读回项.empty() || 读取匹配存在结构投影(存在节点) != 原结构) return 结果;
        结果.状态 = 新存在操作状态::已完成;
        return 结果;
    } catch (...) {
        // 独立派生工程状态由world唯一诊断边界消费，不成为业务运行结果。
        结果.状态 = 新存在操作状态::资源失败;
        return 结果;
    }
}

