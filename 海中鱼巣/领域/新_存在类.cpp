bool 新_存在类::存在概念相交(
    稳定编码 左概念, 稳定编码 右概念) const noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        if (!存在概念服务_.是存在概念节点(左概念)
            || !存在概念服务_.是存在概念节点(右概念)) {
            return false;
        }
        std::set<std::uint64_t> 左域;
        std::vector<稳定编码> 待访问{左概念};
        while (!待访问.empty()) {
            const auto 当前 = 待访问.back();
            待访问.pop_back();
            if (!左域.insert(当前.值).second) continue;
            const auto 下位组 = 存在概念服务_.查询下位存在概念(当前);
            待访问.insert(待访问.end(), 下位组.begin(), 下位组.end());
        }

        待访问.push_back(右概念);
        std::set<std::uint64_t> 右侧已访问;
        while (!待访问.empty()) {
            const auto 当前 = 待访问.back();
            待访问.pop_back();
            if (左域.contains(当前.值)) return true;
            if (!右侧已访问.insert(当前.值).second) continue;
            const auto 下位组 = 存在概念服务_.查询下位存在概念(当前);
            待访问.insert(待访问.end(), 下位组.begin(), 下位组.end());
        }
        return false;
    } catch (...) {
        return false;
    }
}

新存在特征添加结果 新_存在类::添加特征(
    稳定编码 存在节点,
    稳定编码 特征概念节点,
    const 新特征准确值& 初始值,
    const 新状态强时间& 强时间) noexcept {
    新存在特征添加结果 结果;
    try {
        std::lock_guard 锁(新存在互斥);
        if (!实例强时间有效(强时间)) {
            结果.状态 = 新存在操作状态::状态时间不合法;
            return 结果;
        }
        const auto 存在信息 = 获取存在(存在节点);
        if (!存在信息) {
            结果.状态 = 新存在操作状态::存在不存在;
            return 结果;
        }
        const auto 特征节点 = 特征服务_.建立特征(特征概念节点, 初始值);
        if (!有效(特征节点)) {
            结果.状态 = 新存在操作状态::特征概念不合法;
            return 结果;
        }
        const auto 持有字段 = 全局基础数据集.添加字段节点(
            存在节点, 实例特征字段, 特征节点);
        if (!有效(持有字段)) {
            (void)特征服务_.删除特征(特征节点);
            结果.状态 = 新存在操作状态::资源失败;
            return 结果;
        }
        const auto 写入结果 = 特征服务_.添加特征值(特征节点, 初始值);
        const auto 特征信息 = 特征服务_.获取特征(特征节点);
        if (!特征写入成功(写入结果) || !特征信息) {
            (void)全局基础数据集.删除字段(持有字段);
            (void)特征服务_.删除特征(特征节点);
            结果.状态 = 新存在操作状态::资源失败;
            return 结果;
        }

        std::vector<稳定编码> 概念组;
        for (const auto 已有特征 : 存在信息->特征节点组) {
            const auto 已有信息 = 特征服务_.获取特征(已有特征);
            if (!已有信息) {
                (void)全局基础数据集.删除字段(持有字段);
                (void)特征服务_.删除特征(特征节点);
                结果.状态 = 新存在操作状态::结构不一致;
                return 结果;
            }
            概念组.push_back(已有信息->特征概念节点);
        }
        概念组.push_back(特征信息->特征概念节点);
        const auto 更新状态 = 存在概念服务_.更新专属存在概念(
            存在信息->专属存在概念节点, 概念组);
        if (更新状态 != 存在概念操作状态::已更新) {
            (void)全局基础数据集.删除字段(持有字段);
            (void)特征服务_.删除特征(特征节点);
            结果.状态 = 更新状态
                    == 存在概念操作状态::特征概念不一致
                ? 新存在操作状态::特征类型重复
                : 新存在操作状态::专属概念失败;
            return 结果;
        }
        结果.特征节点 = 特征节点;
        结果.状态结果 = 状态服务_.建立状态(
            存在节点, 特征节点, 强时间);
        if (结果.状态结果->状态 != 新状态操作状态::已完成
            || !结果.状态结果->状态节点) {
            结果.状态 = 新存在操作状态::特征已更新但状态未完成;
            return 结果;
        }
        结果.状态 = 新存在操作状态::已完成;
        return 结果;
    } catch (...) {
        结果.状态 = 新存在操作状态::资源失败;
        return 结果;
    }
}

