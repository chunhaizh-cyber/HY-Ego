std::recursive_mutex 新存在互斥;

稳定编码 节点类型字段{};
稳定编码 存在节点类型{};
稳定编码 实例特征字段{};
稳定编码 专属存在概念字段{};

constexpr std::int64_t 存在组成子存在关系角色 = 2;

bool 节点仍存在(稳定编码 节点) noexcept {
    return 有效(节点) && 全局基础数据集.查询节点(节点).has_value();
}

bool 结构已初始化() noexcept {
    return 有效(节点类型字段)
        && 有效(存在节点类型)
        && 有效(实例特征字段)
        && 有效(专属存在概念字段);
}

bool 结构仍存在() noexcept {
    return 结构已初始化()
        && 节点仍存在(节点类型字段)
        && 节点仍存在(存在节点类型)
        && 节点仍存在(实例特征字段)
        && 节点仍存在(专属存在概念字段);
}

std::optional<稳定编码> 读取唯一节点字段(
    稳定编码 节点, 稳定编码 字段) {
    const auto 字段组 = 全局基础数据集.查询字段(节点, 字段);
    if (字段组.size() != 1) return std::nullopt;
    const auto* 目标 = std::get_if<稳定编码>(&字段组.front().内容);
    return 目标 ? std::optional<稳定编码>{*目标} : std::nullopt;
}

void 排序去重(std::vector<稳定编码>& 节点组) {
    std::sort(节点组.begin(), 节点组.end());
    节点组.erase(std::unique(节点组.begin(), 节点组.end()), 节点组.end());
}

std::vector<基础外部关系> 查询父存在关系(稳定编码 存在节点) {
    std::vector<基础外部关系> 结果;
    for (const auto& 关系 : 全局基础数据集.查询目标关系(
        存在节点, 基础外部关系类型::父子)) {
        if (关系.角色或顺序 == 存在组成子存在关系角色) 结果.push_back(关系);
    }
    return 结果;
}

std::vector<基础外部关系> 查询子存在关系(稳定编码 存在节点) {
    std::vector<基础外部关系> 结果;
    for (const auto& 关系 : 全局基础数据集.查询源关系(
        存在节点, 基础外部关系类型::父子)) {
        if (关系.角色或顺序 == 存在组成子存在关系角色) 结果.push_back(关系);
    }
    return 结果;
}

bool 子存在向下可达(稳定编码 起点, 稳定编码 目标) {
    std::vector<稳定编码> 待访问{起点};
    std::set<std::uint64_t> 已访问;
    while (!待访问.empty()) {
        const auto 当前 = 待访问.back();
        待访问.pop_back();
        if (当前 == 目标) return true;
        if (!已访问.insert(当前.值).second) continue;
        for (const auto& 关系 : 查询子存在关系(当前)) {
            待访问.push_back(关系.目标节点);
        }
    }
    return false;
}

bool 特征写入成功(const 新特征值添加结果& 结果) noexcept {
    return 结果.状态 == 新特征写入状态::已完成
        || 结果.状态 == 新特征写入状态::无变化;
}

bool 实例强时间有效(const 新状态强时间& 时间) noexcept {
    return 时间.语义 == 新状态时间语义::实例绝对UTC
        && 时间.纳秒 >= 0;
}

