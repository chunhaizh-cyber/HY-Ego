稳定编码 节点类型字段{};
稳定编码 存在节点类型{};
稳定编码 实例特征字段{};
稳定编码 专属存在概念字段{};

constexpr std::int64_t 存在组成子存在关系角色 = 2;

bool 节点仍存在(稳定编码 节点) noexcept {
    return 有效(节点) && 全局基础数据集.查询节点(节点).has_value();
}

bool 结构已初始化() noexcept {
    return 有效(节点类型字段)
        && 有效(存在节点类型)
        && 有效(实例特征字段)
        && 有效(专属存在概念字段);
}

bool 结构仍存在() noexcept {
    return 结构已初始化()
        && 节点仍存在(节点类型字段)
        && 节点仍存在(存在节点类型)
        && 节点仍存在(实例特征字段)
        && 节点仍存在(专属存在概念字段);
}

std::optional<稳定编码> 读取唯一节点字段(
    稳定编码 节点, 稳定编码 字段) {
    const auto 字段组 = 全局基础数据集.查询字段(节点, 字段);
    if (字段组.size() != 1) return std::nullopt;
    const auto* 目标 = std::get_if<稳定编码>(&字段组.front().内容);
    return 目标 ? std::optional<稳定编码>{*目标} : std::nullopt;
}

void 排序去重(std::vector<稳定编码>& 节点组) {
    std::sort(节点组.begin(), 节点组.end());
    节点组.erase(std::unique(节点组.begin(), 节点组.end()), 节点组.end());
}

std::vector<基础外部关系> 查询父存在关系(稳定编码 存在节点) {
    std::vector<基础外部关系> 结果;
    for (const auto& 关系 : 全局基础数据集.查询目标关系(
        存在节点, 基础外部关系类型::父子)) {
        if (关系.角色或顺序 == 存在组成子存在关系角色) 结果.push_back(关系);
    }
    return 结果;
}

std::vector<基础外部关系> 查询子存在关系(稳定编码 存在节点) {
    std::vector<基础外部关系> 结果;
    for (const auto& 关系 : 全局基础数据集.查询源关系(
        存在节点, 基础外部关系类型::父子)) {
        if (关系.角色或顺序 == 存在组成子存在关系角色) 结果.push_back(关系);
    }
    return 结果;
}

bool 子存在向下可达(稳定编码 起点, 稳定编码 目标) {
    std::vector<稳定编码> 待访问{起点};
    std::set<std::uint64_t> 已访问;
    while (!待访问.empty()) {
        const auto 当前 = 待访问.back();
        待访问.pop_back();
        if (当前 == 目标) return true;
        if (!已访问.insert(当前.值).second) continue;
        for (const auto& 关系 : 查询子存在关系(当前)) {
            待访问.push_back(关系.目标节点);
        }
    }
    return false;
}

bool 特征写入成功(const 新特征值添加结果& 结果) noexcept {
    return 结果.状态 == 新特征写入状态::已完成
        || 结果.状态 == 新特征写入状态::无变化;
}

bool 实例强时间有效(const 新状态强时间& 时间) noexcept {
    return 时间.语义 == 新状态时间语义::实例绝对UTC
        && 时间.纳秒 >= 0;
}

struct 匹配存在结构投影 final {
    稳定编码 存在节点, 专属存在概念节点;
    std::vector<稳定编码> 顶层特征节点组;
    friend bool operator==(const 匹配存在结构投影&, const 匹配存在结构投影&) = default;
};

std::optional<匹配存在结构投影> 读取匹配存在结构投影(稳定编码 节点) {
    std::lock_guard 锁(新存在互斥);
    if (!结构仍存在())
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取匹配存在结构投影", L"存在结构未初始化或已损坏。");
    if (!节点仍存在(节点)) return {};
    const auto 类型组 = 全局基础数据集.查询字段(节点, 节点类型字段);
    if (类型组.empty()) return {};
    const auto* 类型 = std::get_if<稳定编码>(&类型组.front().内容);
    if (类型组.size() != 1 || !类型 || !节点仍存在(*类型))
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取匹配存在结构投影", L"存在身份字段损坏或重复。");
    if (*类型 != 存在节点类型) return {};
    const auto 专属 = 读取唯一节点字段(节点, 专属存在概念字段);
    if (!专属 || !节点仍存在(*专属))
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取匹配存在结构投影", L"合法存在的专属概念引用不完整。");
    匹配存在结构投影 结果{节点, *专属, {}};
    std::set<稳定编码> 已见;
    for (const auto& 字段 : 全局基础数据集.查询字段(节点, 实例特征字段)) {
        const auto* F = std::get_if<稳定编码>(&字段.内容);
        if (!F || !节点仍存在(*F) || !已见.insert(*F).second)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取匹配存在结构投影", L"存在特征持有字段损坏或重复。");
        结果.顶层特征节点组.push_back(*F);
    }
    std::sort(结果.顶层特征节点组.begin(), 结果.顶层特征节点组.end());
    return 结果;
}

bool 匹配定义需要外部依据(const 新特征匹配定义快照& 定义) noexcept {
    return 定义.材料类型 == 特征概念材料物理类型::存在节点引用
        || 定义.比较规则 == 特征概念比较规则::存在身份精确
        || 定义.比较规则 == 特征概念比较规则::服务任务集合身份判等
        || std::holds_alternative<特征概念任务集合值域>(定义.值域)
        || std::holds_alternative<特征概念存在引用值域>(定义.值域);
}

新存在概念匹配结果 比较存在匹配快照(const 新_特征类& 特征服务,
    const 新存在概念匹配材料& 材料, std::vector<稳定编码>* 尚缺固定依据) {
    if (!有效(材料.存在节点) || !有效(材料.专属存在概念节点) || !有效(材料.目标存在概念节点))
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"比较存在匹配快照", L"捕获材料缺少正式身份。");
    std::map<稳定编码, const 新特征匹配实例快照*> 实际索引;
    for (const auto& 实际 : 材料.实际特征组) {
        if (!有效(实际.特征节点) || !有效(实际.定义.概念节点) || !有效(实际.定义.特征类型根)
            || 实际.上级特征节点 || !实际索引.emplace(实际.定义.特征类型根, &实际).second)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"比较存在匹配快照", L"实际顶层特征结构非法或同类型重复。");
    }
    新存在概念匹配结果 结果;
    std::set<稳定编码> 已见必需;
    for (const auto& 必需 : 材料.必需特征组) {
        const auto FT = 必需.来源.特征类型概念;
        if (!有效(FT) || !有效(必需.来源.具体特征概念)
            || 必需.定义.特征类型根 != FT || 必需.定义.概念节点 != 必需.来源.具体特征概念
            || !已见必需.insert(FT).second)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"比较存在匹配快照", L"必需特征清单与捕获定义不一致。");
        const auto 位置 = 实际索引.find(FT);
        if (位置 == 实际索引.end() || (!位置->second->当前值 && !位置->second->实例区间值)) {
            结果.缺少特征类型组.push_back(FT);
            continue;
        }
        const auto& 实际 = *位置->second;
        const auto 比较 = 特征服务.比较捕获特征值域(实际, 必需.定义);
        if (比较.状态 == 新特征比较状态::规则不支持 || 比较.状态 == 新特征比较状态::单位不相容
            || 比较.状态 == 新特征比较状态::材料类型不相容 || 比较.状态 == 新特征比较状态::概念不相容) {
            结果.缺少特征类型组.push_back(FT);
            if (尚缺固定依据 && 比较.状态 == 新特征比较状态::规则不支持
                && (匹配定义需要外部依据(实际.定义) || 匹配定义需要外部依据(必需.定义)
                    || (实际.实例区间值 && (std::holds_alternative<特征概念任务集合值域>(*实际.实例区间值)
                        || std::holds_alternative<特征概念存在引用值域>(*实际.实例区间值)))))
                尚缺固定依据->push_back(FT);
            continue;
        }
        if (比较.状态 != 新特征比较状态::已完成 || !比较.关系编码)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"比较存在匹配快照", L"固定材料比较未完成。");
        const auto 关系 = static_cast<特征概念值域关系>(*比较.关系编码);
        if (关系 == 特征概念值域关系::相等 || 关系 == 特征概念值域关系::右包含左) continue;
        if (关系 != 特征概念值域关系::左包含右 && 关系 != 特征概念值域关系::相交
            && 关系 != 特征概念值域关系::分离)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"比较存在匹配快照", L"固定材料比较返回非法关系。");
        if (实际.当前值 || 关系 == 特征概念值域关系::分离) 结果.不符合特征类型组.push_back(FT);
        else 结果.缺少特征类型组.push_back(FT);
    }
    排序去重(结果.缺少特征类型组);
    排序去重(结果.不符合特征类型组);
    if (尚缺固定依据) 排序去重(*尚缺固定依据);
    结果.状态 = !结果.不符合特征类型组.empty() ? 新存在概念匹配状态::不符合
        : !结果.缺少特征类型组.empty() ? 新存在概念匹配状态::材料不足 : 新存在概念匹配状态::匹配;
    return 结果;
}

