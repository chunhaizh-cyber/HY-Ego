新_存在类::新_存在类(
    新_特征类& 特征服务,
    概念_存在类& 存在概念服务,
    新_状态类& 状态服务) noexcept
    : 特征服务_(特征服务),
      存在概念服务_(存在概念服务),
      状态服务_(状态服务) {}

bool 新_存在类::初始化() noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        if (!特征服务_.初始化() || !存在概念服务_.初始化()
            || !状态服务_.初始化()) return false;
        if (结构已初始化()) return 结构仍存在();
        auto 建立 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        return 建立(节点类型字段)
            && 建立(存在节点类型)
            && 建立(实例特征字段)
            && 建立(专属存在概念字段);
    } catch (...) {
        return false;
    }
}

新存在建立结果 新_存在类::初始化存在节点(
    稳定编码 存在节点,
    const 新存在建立请求& 请求,
    bool 允许空特征,
    const std::optional<新状态强时间>& 初始状态时间) noexcept {
    新存在建立结果 结果;
    try {
        std::lock_guard 锁(新存在互斥);
        if (!结构仍存在() || !节点仍存在(存在节点)
            || 是存在节点(存在节点)) return 结果;
        if (请求.父存在节点 && !是存在节点(*请求.父存在节点)) {
            结果.状态 = 新存在操作状态::父存在不合法;
            return 结果;
        }
        if (!允许空特征 && 请求.初始特征组.empty()) {
            结果.状态 = 新存在操作状态::初始特征不足;
            return 结果;
        }
        if (!请求.初始特征组.empty()
            && (!初始状态时间 || !实例强时间有效(*初始状态时间))) {
            结果.状态 = 新存在操作状态::状态时间不合法;
            return 结果;
        }
        std::vector<稳定编码> 已写字段;
        std::vector<稳定编码> 已写关系;
        std::vector<std::pair<稳定编码, 稳定编码>> 已建特征;
        std::vector<稳定编码> 已建状态;
        std::optional<稳定编码> 专属概念;

        const auto 回滚 = [&]() noexcept {
            for (auto 位置 = 已建状态.rbegin(); 位置 != 已建状态.rend(); ++位置) {
                (void)状态服务_.删除状态(*位置);
            }
            if (专属概念) {
                (void)存在概念服务_.撤销未绑定专属存在概念(
                    *专属概念, 存在节点);
            }
            for (auto 位置 = 已建特征.rbegin(); 位置 != 已建特征.rend(); ++位置) {
                (void)全局基础数据集.删除字段(位置->second);
                (void)特征服务_.删除特征(位置->first);
            }
            for (auto 位置 = 已写字段.rbegin(); 位置 != 已写字段.rend(); ++位置) {
                (void)全局基础数据集.删除字段(*位置);
            }
            for (auto 位置 = 已写关系.rbegin(); 位置 != 已写关系.rend(); ++位置) {
                (void)全局基础数据集.删除关系(*位置);
            }
        };

        const auto 类型关系 = 全局基础数据集.添加字段节点(
            存在节点, 节点类型字段, 存在节点类型);
        if (!有效(类型关系)) {
            回滚();
            结果.状态 = 新存在操作状态::资源失败;
            return 结果;
        }
        已写字段.push_back(类型关系);
        if (请求.父存在节点) {
            const auto 父子关系 = 全局基础数据集.添加关系(
                *请求.父存在节点, 存在节点,
                基础外部关系类型::父子, 存在组成子存在关系角色);
            if (!有效(父子关系)) {
                回滚();
                结果.状态 = 新存在操作状态::资源失败;
                return 结果;
            }
            已写关系.push_back(父子关系);
        }

        std::vector<稳定编码> 具体特征概念组;
        for (const auto& 初始特征 : 请求.初始特征组) {
            const auto 特征节点 = 特征服务_.建立特征(
                初始特征.特征概念节点, 初始特征.初始值);
            if (!有效(特征节点)) {
                回滚();
                结果.状态 = 新存在操作状态::特征概念不合法;
                return 结果;
            }
            const auto 持有字段 = 全局基础数据集.添加字段节点(
                存在节点, 实例特征字段, 特征节点);
            if (!有效(持有字段)) {
                (void)特征服务_.删除特征(特征节点);
                回滚();
                结果.状态 = 新存在操作状态::资源失败;
                return 结果;
            }
            已建特征.push_back({特征节点, 持有字段});
            const auto 写入结果 = 特征服务_.添加特征值(
                特征节点, 初始特征.初始值);
            const auto 特征信息 = 特征服务_.获取特征(特征节点);
            if (!特征写入成功(写入结果) || !特征信息) {
                回滚();
                结果.状态 = 新存在操作状态::资源失败;
                return 结果;
            }
            const auto 状态结果 = 状态服务_.建立状态(
                存在节点, 特征节点, *初始状态时间);
            if (状态结果.状态 != 新状态操作状态::已完成
                || !状态结果.状态节点) {
                回滚();
                结果.状态 = 新存在操作状态::资源失败;
                return 结果;
            }
            已建状态.push_back(*状态结果.状态节点);
            具体特征概念组.push_back(特征信息->特征概念节点);
        }

        const auto 概念结果 = 存在概念服务_.建立专属存在概念(
            存在节点, 具体特征概念组);
        if (概念结果.状态 != 存在概念操作状态::已建立
            || !概念结果.概念节点) {
            回滚();
            结果.状态 = 概念结果.状态
                    == 存在概念操作状态::特征概念不一致
                ? 新存在操作状态::特征类型重复
                : 新存在操作状态::专属概念失败;
            return 结果;
        }
        专属概念 = *概念结果.概念节点;
        const auto 概念字段 = 全局基础数据集.添加字段节点(
            存在节点, 专属存在概念字段, *专属概念);
        if (!有效(概念字段)) {
            回滚();
            结果.状态 = 新存在操作状态::资源失败;
            return 结果;
        }
        已写字段.push_back(概念字段);
        专属概念.reset();

        结果.状态 = 新存在操作状态::已完成;
        结果.存在节点 = 存在节点;
        结果.专属存在概念节点 = *概念结果.概念节点;
        结果.初始状态节点组 = 已建状态;
        return 结果;
    } catch (...) {
        结果.状态 = 新存在操作状态::资源失败;
        return 结果;
    }
}

std::optional<新存在信息> 新_存在类::获取存在(
    稳定编码 存在节点) const noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        if (!是存在节点(存在节点)) return std::nullopt;
        const auto 父存在关系 = 查询父存在关系(存在节点);
        const auto 专属概念 = 读取唯一节点字段(
            存在节点, 专属存在概念字段);
        if (父存在关系.size() > 1 || !专属概念
            || !存在概念服务_.是专属存在概念节点(*专属概念)) {
            return std::nullopt;
        }
        const auto 概念信息 = 存在概念服务_.获取存在概念(*专属概念);
        if (!概念信息 || !概念信息->对应存在节点
            || *概念信息->对应存在节点 != 存在节点) {
            return std::nullopt;
        }

        新存在信息 结果;
        结果.节点 = 存在节点;
        if (!父存在关系.empty()) {
            if (!是存在节点(父存在关系.front().源节点)) return std::nullopt;
            结果.父存在节点 = 父存在关系.front().源节点;
        }
        结果.专属存在概念节点 = *专属概念;
        for (const auto& 字段 : 全局基础数据集.查询字段(
            存在节点, 实例特征字段)) {
            const auto* 特征节点 = std::get_if<稳定编码>(&字段.内容);
            if (!特征节点 || !特征服务_.是特征节点(*特征节点)) {
                return std::nullopt;
            }
            const auto 特征信息 = 特征服务_.获取特征(*特征节点);
            if (!特征信息 || 特征信息->上级特征节点) return std::nullopt;
            结果.特征节点组.push_back(*特征节点);
        }
        排序去重(结果.特征节点组);
        结果.子存在节点组 = 查询直接子存在(存在节点);
        return 结果;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"新_存在类::获取存在",
            L"存在内容读取异常，未形成业务结果。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"新_存在类::获取存在",
            L"存在内容读取未知异常，未形成业务结果。");
    }
}

新存在概念匹配结果 新_存在类::匹配存在概念(稳定编码 存在节点, 稳定编码 概念节点) const noexcept {
    try {
        新存在概念匹配结果 结果;
        if (!是存在节点(存在节点)) { 结果.状态 = 新存在概念匹配状态::不符合; return 结果; }
        const auto 定义 = 存在概念服务_.获取存在概念(概念节点);
        if (!定义) 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"匹配存在概念", L"目标概念无法完整读取。");
        const auto 存在 = 获取存在(存在节点);
        if (!存在) 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"匹配存在概念", L"合法存在无法完整读取。");
        if (定义->特征组.empty()) { 结果.状态 = 新存在概念匹配状态::匹配; return 结果; }
        // 各owner独立读取，不持存在锁跨服务比较；这里不承诺共同原子快照。
        for (const auto& 必需 : 定义->特征组) {
            const auto 目标 = 特征服务_.比较特征概念值域关系(必需.具体特征概念, 必需.具体特征概念);
            if (目标.状态 != 新特征比较状态::已完成)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"匹配存在概念", L"已定义特征概念无法读取比较规则。");
            std::optional<新特征信息> 命中;
            for (auto 编码 : 存在->特征节点组) {
                const auto 实际 = 特征服务_.获取特征(编码);
                if (!实际) 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"匹配存在概念", L"存在已声明特征无法读取。");
                // 不同FT正常无可比关系；同FT有包含、相交或分离关系。
                const auto 同类 = 特征服务_.比较特征概念值域关系(实际->特征概念节点, 必需.具体特征概念);
                if (同类.状态 == 新特征比较状态::概念不相容
                    || 同类.状态 == 新特征比较状态::材料类型不相容
                    || 同类.状态 == 新特征比较状态::单位不相容) continue;
                if (同类.状态 != 新特征比较状态::已完成)
                    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"匹配存在概念", L"特征类型对齐未完成。");
                if (命中) 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"匹配存在概念", L"同一必需特征类型出现多个顶层实例。");
                命中 = 实际;
            }
            if (!命中 || (!命中->当前值 && !命中->实例区间值)) {
                结果.缺少特征类型组.push_back(必需.特征类型概念); continue;
            }
            新特征值域比较输入 左{命中->特征概念节点, 命中->实例单位, {}};
            if (命中->当前值) 左.材料 = 新特征准确值比较材料{*命中->当前值};
            else 左.材料 = 新特征直接值域比较材料{*命中->实例区间值};
            const auto 比较 = 特征服务_.比较特征值域(左,
                {必需.具体特征概念, 命中->实例单位, 新特征概念值域比较材料{必需.具体特征概念}});
            if (比较.状态 == 新特征比较状态::规则不支持 || 比较.状态 == 新特征比较状态::单位不相容) {
                结果.缺少特征类型组.push_back(必需.特征类型概念); continue;
            }
            if (比较.状态 != 新特征比较状态::已完成 || !比较.关系编码)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"匹配存在概念", L"实际材料与必需值域比较未完成。");
            const auto 关系 = static_cast<特征概念值域关系>(*比较.关系编码);
            if (关系 == 特征概念值域关系::相等 || 关系 == 特征概念值域关系::右包含左) continue;
            if (命中->当前值 || 关系 == 特征概念值域关系::分离)
                结果.不符合特征类型组.push_back(必需.特征类型概念);
            else 结果.缺少特征类型组.push_back(必需.特征类型概念);
        }
        结果.状态 = !结果.不符合特征类型组.empty() ? 新存在概念匹配状态::不符合
            : !结果.缺少特征类型组.empty() ? 新存在概念匹配状态::材料不足 : 新存在概念匹配状态::匹配;
        return 结果;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"匹配存在概念", L"匹配读取异常。", 异常.what());
    } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"匹配存在概念", L"匹配读取未知异常。"); }
}

bool 新_存在类::是存在节点(稳定编码 节点) const noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        if (!结构仍存在() || !节点仍存在(节点)) return false;
        const auto 类型 = 读取唯一节点字段(节点, 节点类型字段);
        return 类型 && *类型 == 存在节点类型;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"新_存在类::是存在节点",
            L"存在身份读取发生C++异常，未形成业务结果。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"新_存在类::是存在节点",
            L"存在身份读取发生未知C++异常，未形成业务结果。");
    }
}

bool 新_存在类::是存在概念节点(稳定编码 概念节点) const noexcept {
    return 存在概念服务_.是存在概念节点(概念节点);
}

bool 新_存在类::存在概念包含(
    稳定编码 上位概念, 稳定编码 下位概念) const noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        if (!存在概念服务_.是存在概念节点(上位概念)
            || !存在概念服务_.是存在概念节点(下位概念)) {
            return false;
        }
        std::vector<稳定编码> 待访问{下位概念};
        std::set<std::uint64_t> 已访问;
        while (!待访问.empty()) {
            const auto 当前 = 待访问.back();
            待访问.pop_back();
            if (当前 == 上位概念) return true;
            if (!已访问.insert(当前.值).second) continue;
            const auto 上位组 = 存在概念服务_.查询上位存在概念(当前);
            待访问.insert(待访问.end(), 上位组.begin(), 上位组.end());
        }
        return false;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"新_存在类::存在概念包含",
            L"概念包含读取发生C++异常，未形成业务结果。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"新_存在类::存在概念包含",
            L"概念包含读取发生未知C++异常，未形成业务结果。");
    }
}

