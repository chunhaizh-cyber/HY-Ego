新存在特征值更新结果 新_存在类::更新特征值(
    稳定编码 存在节点,
    稳定编码 特征节点,
    const 新特征准确值& 新值,
    const 新状态强时间& 强时间) noexcept {
    新存在特征值更新结果 结果;
    try {
        std::lock_guard 锁(新存在互斥);
        if (!实例强时间有效(强时间)) {
            结果.状态 = 新存在操作状态::状态时间不合法;
            return 结果;
        }
        const auto 存在信息 = 获取存在(存在节点);
        if (!存在信息) {
            结果.状态 = 新存在操作状态::存在不存在;
            return 结果;
        }
        if (std::find(存在信息->特征节点组.begin(),
            存在信息->特征节点组.end(), 特征节点)
            == 存在信息->特征节点组.end()) {
            结果.状态 = 新存在操作状态::入口拒绝;
            return 结果;
        }

        结果.特征结果 = 特征服务_.添加特征值(特征节点, 新值);
        const bool 特征事实已更新 =
            结果.特征结果->状态 == 新特征写入状态::已完成
            || 结果.特征结果->状态 == 新特征写入状态::无变化
            || 结果.特征结果->状态
                == 新特征写入状态::值已更新但聚合未完成;
        if (!特征事实已更新) {
            结果.状态 = 新存在操作状态::资源失败;
            return 结果;
        }
        if (结果.特征结果->当前值已改变) {
            结果.状态结果 = 状态服务_.建立状态(
                存在节点, 特征节点, 强时间);
            if (结果.状态结果->状态 != 新状态操作状态::已完成
                || !结果.状态结果->状态节点) {
                结果.状态 = 新存在操作状态::特征已更新但状态未完成;
                return 结果;
            }
        }

        std::vector<稳定编码> 概念组;
        for (const auto 当前特征 : 存在信息->特征节点组) {
            const auto 特征信息 = 特征服务_.获取特征(当前特征);
            if (!特征信息) {
                结果.状态 = 新存在操作状态::特征已更新但专属概念未完成;
                return 结果;
            }
            概念组.push_back(特征信息->特征概念节点);
        }
        结果.专属概念结果 = 存在概念服务_.更新专属存在概念(
            存在信息->专属存在概念节点, 概念组);
        const bool 专属概念已同步 =
            *结果.专属概念结果 == 存在概念操作状态::已更新
            || *结果.专属概念结果 == 存在概念操作状态::无变化;

        if (!专属概念已同步) {
            结果.状态 = 新存在操作状态::特征已更新但专属概念未完成;
            return 结果;
        }
        结果.状态 = 结果.特征结果->当前值已改变
            ? 新存在操作状态::已完成
            : 新存在操作状态::无变化;
        return 结果;
    } catch (...) {
        结果.状态 = 新存在操作状态::资源失败;
        return 结果;
    }
}

