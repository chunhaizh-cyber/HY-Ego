新存在概念匹配采集结果 新_存在类::采集存在概念匹配材料(
    稳定编码 存在节点, 稳定编码 概念节点) const noexcept {
    try {
        // 每一遍只取得参与计算的投影，不调用会隐含live归属判定的完整getter。
        const auto 采集 = [&]() -> std::optional<新存在概念匹配材料> {
            const auto 存在 = 读取匹配存在结构投影(存在节点);
            if (!存在) return {};
            const auto 专属 = 存在概念服务_.获取存在概念(存在->专属存在概念节点);
            if (!专属 || 专属->种类 != 存在概念种类::专属 || 专属->对应存在节点 != 存在节点)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"采集存在概念匹配材料", L"专属概念未绑定当前存在。");
            const auto 目标 = 概念节点 == 存在->专属存在概念节点
                ? 专属 : 存在概念服务_.获取存在概念(概念节点);
            if (!目标)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"采集存在概念匹配材料", L"目标存在概念无法完整读取。");
            新存在概念匹配材料 材料{存在节点, 存在->专属存在概念节点, 概念节点, {}, {}};
            for (const auto& 必需 : 目标->特征组) {
                const auto 定义 = 特征服务_.捕获特征匹配定义(必需.具体特征概念);
                if (!定义 || 定义->特征类型根 != 必需.特征类型概念)
                    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"采集存在概念匹配材料", L"目标特征定义缺失或类型根不一致。");
                材料.必需特征组.push_back({必需, *定义});
            }
            std::sort(材料.必需特征组.begin(), 材料.必需特征组.end(),
                [](const auto& 左, const auto& 右) { return 左.来源.特征类型概念 < 右.来源.特征类型概念; });
            for (const auto F : 存在->顶层特征节点组) {
                const auto 实际 = 特征服务_.捕获特征匹配实例(F);
                if (!实际 || 实际->上级特征节点)
                    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"采集存在概念匹配材料", L"存在持有的顶层特征无法捕获。");
                材料.实际特征组.push_back(*实际);
            }
            return 材料;
        };
        新存在概念匹配采集结果 结果;
        结果.材料 = 采集();
        if (!结果.材料) {
            结果.匹配.状态 = 新存在概念匹配状态::不符合;
            return 结果;
        }
        结果.匹配 = 比较存在匹配快照(特征服务_, *结果.材料, &结果.尚缺固定比较依据特征组);
        const auto 复核 = 采集();
        if (!复核 || *复核 != *结果.材料) {
            结果.匹配 = {};
            结果.尚缺固定比较依据特征组.clear();
            结果.采集期间材料变化 = true;
        }
        return 结果;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"采集存在概念匹配材料", L"匹配采集异常。", 异常.what());
    } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"采集存在概念匹配材料", L"匹配采集未知异常。"); }
}

