新存在特征值更新结果 新_存在类::更新特征值(
    稳定编码 存在节点,
    稳定编码 特征节点,
    const 新特征准确值& 新值,
    const 新状态强时间& 强时间) noexcept {
    新存在特征值更新结果 结果;
    try {
        std::lock_guard 锁(新存在互斥);
        if (!实例强时间有效(强时间)) {
            结果.状态 = 新存在操作状态::状态时间不合法;
            return 结果;
        }
        const auto 存在信息 = 获取存在(存在节点);
        if (!存在信息) {
            结果.状态 = 新存在操作状态::存在不存在;
            return 结果;
        }
        if (std::find(存在信息->特征节点组.begin(),
            存在信息->特征节点组.end(), 特征节点)
            == 存在信息->特征节点组.end()) {
            结果.状态 = 新存在操作状态::入口拒绝;
            return 结果;
        }

        结果.特征结果 = 特征服务_.添加特征值(特征节点, 新值);
        const bool 特征事实已更新 =
            结果.特征结果->状态 == 新特征写入状态::已完成
            || 结果.特征结果->状态 == 新特征写入状态::无变化
            || 结果.特征结果->状态
                == 新特征写入状态::值已更新但聚合未完成;
        if (!特征事实已更新) {
            结果.状态 = 新存在操作状态::资源失败;
            return 结果;
        }
        if (结果.特征结果->当前值已改变) {
            结果.状态结果 = 状态服务_.建立状态(
                存在节点, 特征节点, 强时间);
            if (结果.状态结果->状态 != 新状态操作状态::已完成
                || !结果.状态结果->状态节点) {
                结果.状态 = 新存在操作状态::特征已更新但状态未完成;
                return 结果;
            }
        }

        std::vector<稳定编码> 概念组;
        for (const auto 当前特征 : 存在信息->特征节点组) {
            const auto 特征信息 = 特征服务_.获取特征(当前特征);
            if (!特征信息) {
                结果.状态 = 新存在操作状态::特征已更新但专属概念未完成;
                return 结果;
            }
            概念组.push_back(特征信息->特征概念节点);
        }
        结果.专属概念结果 = 存在概念服务_.更新专属存在概念(
            存在信息->专属存在概念节点, 概念组);
        const bool 专属概念已同步 =
            *结果.专属概念结果 == 存在概念操作状态::已更新
            || *结果.专属概念结果 == 存在概念操作状态::无变化;

        if (!专属概念已同步) {
            结果.状态 = 新存在操作状态::特征已更新但专属概念未完成;
            return 结果;
        }
        结果.状态 = 结果.特征结果->当前值已改变
            ? 新存在操作状态::已完成
            : 新存在操作状态::无变化;
        return 结果;
    } catch (...) {
        结果.状态 = 新存在操作状态::资源失败;
        return 结果;
    }
}

std::vector<稳定编码> 新_存在类::查询全部特征(
    稳定编码 存在节点) const noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        std::vector<稳定编码> 结果;
        if (!是存在节点(存在节点)) return 结果;
        for (const auto& 字段 : 全局基础数据集.查询字段(
            存在节点, 实例特征字段)) {
            const auto* 特征节点 = std::get_if<稳定编码>(&字段.内容);
            if (!特征节点 || !特征服务_.是特征节点(*特征节点)) return {};
            结果.push_back(*特征节点);
        }
        排序去重(结果);
        return 结果;
    } catch (...) {
        return {};
    }
}

新存在操作状态 新_存在类::清理存在节点内容(
    稳定编码 存在节点) noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        const auto 信息 = 获取存在(存在节点);
        if (!信息) return 新存在操作状态::存在不存在;
        if (!状态服务_.按存在查询状态(存在节点).empty()) {
            return 新存在操作状态::仍被状态引用;
        }
        if (!信息->子存在节点组.empty()) {
            return 新存在操作状态::仍有子存在;
        }
        const auto 概念信息 = 存在概念服务_.获取存在概念(
            信息->专属存在概念节点);
        if (!概念信息 || !概念信息->上位概念组.empty()
            || !概念信息->下位概念组.empty()) {
            return 新存在操作状态::结构不一致;
        }

        const auto 父关系 = 查询父存在关系(存在节点);
        if (父关系.size() > 1) return 新存在操作状态::结构不一致;
        if (!父关系.empty()
            && !全局基础数据集.删除关系(父关系.front().编码)) {
            return 新存在操作状态::资源失败;
        }

        const auto 特征字段组 = 全局基础数据集.查询字段(
            存在节点, 实例特征字段);
        for (const auto& 字段 : 特征字段组) {
            const auto* 特征节点 = std::get_if<稳定编码>(&字段.内容);
            if (!特征节点 || !特征服务_.是特征节点(*特征节点)) {
                return 新存在操作状态::结构不一致;
            }
        }
        for (const auto& 字段 : 特征字段组) {
            const auto 特征节点 = std::get<稳定编码>(字段.内容);
            if (!全局基础数据集.删除字段(字段.编码)
                || !特征服务_.删除特征(特征节点)) {
                return 新存在操作状态::资源失败;
            }
        }

        const auto 概念字段组 = 全局基础数据集.查询字段(
            存在节点, 专属存在概念字段);
        if (概念字段组.size() != 1) {
            return 新存在操作状态::结构不一致;
        }
        const auto* 概念节点 = std::get_if<稳定编码>(
            &概念字段组.front().内容);
        if (!概念节点
            || !存在概念服务_.是专属存在概念节点(*概念节点)) {
            return 新存在操作状态::结构不一致;
        }
        if (!全局基础数据集.删除字段(概念字段组.front().编码)
            || !存在概念服务_.撤销未绑定专属存在概念(
                *概念节点, 存在节点)) {
            return 新存在操作状态::资源失败;
        }

        const auto 类型字段组 = 全局基础数据集.查询字段(
            存在节点, 节点类型字段);
        if (类型字段组.size() != 1
            || !全局基础数据集.删除字段(类型字段组.front().编码)) {
            return 新存在操作状态::结构不一致;
        }
        return 新存在操作状态::已完成;
    } catch (...) {
        return 新存在操作状态::资源失败;
    }
}

std::optional<稳定编码> 新_存在类::查询专属存在概念(
    稳定编码 存在节点) const noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        if (!是存在节点(存在节点)) return std::nullopt;
        const auto 概念 = 读取唯一节点字段(存在节点, 专属存在概念字段);
        return 概念 && 存在概念服务_.是专属存在概念节点(*概念)
            ? 概念 : std::nullopt;
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"新_存在类::查询专属存在概念",
            L"专属概念读取发生C++异常，未形成业务结果。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"新_存在类::查询专属存在概念",
            L"专属概念读取发生未知C++异常，未形成业务结果。");
    }
}

新存在操作状态 新_存在类::添加子存在(
    稳定编码 父存在节点,
    稳定编码 子存在节点) noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        if (!是存在节点(父存在节点) || !是存在节点(子存在节点)
            || 父存在节点 == 子存在节点) {
            return 新存在操作状态::入口拒绝;
        }
        const auto 已有父关系 = 查询父存在关系(子存在节点);
        for (const auto& 关系 : 已有父关系) {
            if (关系.源节点 == 父存在节点) return 新存在操作状态::无变化;
        }
        if (!已有父关系.empty()) return 新存在操作状态::父存在不合法;
        if (子存在向下可达(子存在节点, 父存在节点)) {
            return 新存在操作状态::会形成环;
        }
        const auto 关系 = 全局基础数据集.添加关系(
            父存在节点, 子存在节点,
            基础外部关系类型::父子, 存在组成子存在关系角色);
        return 有效(关系)
            ? 新存在操作状态::已完成
            : 新存在操作状态::资源失败;
    } catch (...) {
        return 新存在操作状态::资源失败;
    }
}

新存在操作状态 新_存在类::移除子存在(
    稳定编码 父存在节点,
    稳定编码 子存在节点) noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        if (!是存在节点(父存在节点) || !是存在节点(子存在节点)) {
            return 新存在操作状态::入口拒绝;
        }
        std::optional<稳定编码> 目标关系;
        for (const auto& 关系 : 查询父存在关系(子存在节点)) {
            if (关系.源节点 == 父存在节点) {
                if (目标关系) return 新存在操作状态::结构不一致;
                目标关系 = 关系.编码;
            }
        }
        if (!目标关系) return 新存在操作状态::无变化;
        return 全局基础数据集.删除关系(*目标关系)
            ? 新存在操作状态::已完成
            : 新存在操作状态::资源失败;
    } catch (...) {
        return 新存在操作状态::资源失败;
    }
}

std::vector<稳定编码> 新_存在类::查询直接子存在(
    稳定编码 存在节点) const noexcept {
    try {
        std::lock_guard 锁(新存在互斥);
        std::vector<稳定编码> 结果;
        if (!是存在节点(存在节点)) return 结果;
        for (const auto& 关系 : 查询子存在关系(存在节点)) {
            if (!是存在节点(关系.目标节点)) return {};
            结果.push_back(关系.目标节点);
        }
        排序去重(结果);
        return 结果;
    } catch (...) {
        return {};
    }
}

