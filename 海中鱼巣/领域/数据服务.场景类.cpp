场景类数据服务::场景类数据服务(
    const L1事实基座服务 &第一层服务, L1所有者范围写端口 &&写端口,
    const 场景角色结构交付 &布局,
    const 存在结构身份只读提供者 &存在提供者,
    const 状态类数据服务 &,
    const 场景特征组织扩展结构交付 &特征布局,
    const 场景直接包含扩展结构交付 &包含布局)
    : 第一层服务_(第一层服务), 写端口_(std::move(写端口)),
      所有者_(写端口_.所有者身份()), 布局_(布局), 特征布局_(特征布局),
      包含布局_(包含布局), 存在提供者_(存在提供者) {
  if (!有效(所有者_) || !写端口_.有效() || !写端口_.绑定于(第一层服务_) ||
      !存在提供者_.绑定于(第一层服务_) || !布局形状有效(布局_) ||
      !特征布局形状有效(特征布局_) || !包含布局形状有效(包含布局_))
    throw std::invalid_argument("场景结构交付无效");
}

