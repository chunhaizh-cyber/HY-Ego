世界树根组读取结果 场景类数据服务::读取当前世界树根组(
    const 世界树根组读取请求 &) const {
  世界树根组读取结果 输出;
  try {
    const auto 读取 = 第一层服务_.读取所有者范围当前目标关系组(
        {包含布局_.树登记锚点, 包含布局_.根标记关系类型});
    if (读取.状态 == L1所有者范围读取状态::资源失败) {
      输出.状态 = 世界树根状态::资源失败;
      return 输出;
    }
    if (读取.状态 == L1所有者范围读取状态::未找到) {
      输出.状态 = 世界树根状态::精确重复;
      return 输出;
    }
    if (读取.状态 != L1所有者范围读取状态::成功) {
      输出.状态 = 世界树根状态::内部不一致;
      return 输出;
    }
    for (const auto &关系 : 读取.关系组) {
      if (!有效(关系.编码) || !有效(关系.源节点) ||
          关系.目标节点 != 包含布局_.树登记锚点 ||
          关系.关系类型节点 != 包含布局_.根标记关系类型 ||
          关系.角色或顺序 != 1 || 关系.写入所有者 != 所有者_) {
        输出.状态 = 世界树根状态::内部不一致;
        输出.根组.clear();
        return 输出;
      }
      输出.根组.push_back(关系.源节点);
    }
    std::ranges::sort(输出.根组,
                      [](稳定编码 左, 稳定编码 右) { return 左.值 < 右.值; });
    if (std::ranges::adjacent_find(输出.根组) != 输出.根组.end()) {
      输出.状态 = 世界树根状态::内部不一致;
      输出.根组.clear();
      return 输出;
    }
    输出.状态 = 世界树根状态::精确重复;
  } catch (const std::bad_alloc &) {
    输出.状态 = 世界树根状态::资源失败;
  } catch (...) {
    输出.状态 = 世界树根状态::内部不一致;
  }
  return 输出;
}

