世界树根场景片段 场景类数据服务::准备世界树根场景片段(
    const 世界树根初始化请求 &请求) const {
  世界树根场景片段 输出;
  if (!世界树根结构已就绪() || !世界树根幂等键可用(请求.场景幂等身份))
    return 输出;

  auto &片段 = 输出.写集;
  片段.参与者 = {2};
  片段.所有者 = 所有者_;
  片段.写集.写入幂等身份 = 请求.场景幂等身份;
  const L1有限N分区原子事实引用 根{{1}, {1}};
  for (std::uint32_t 序号 = 1; 序号 <= 4; ++序号)
    片段.写集.节点.push_back({{序号}, 节点种类::普通, std::nullopt});
  片段.写集.关系.push_back({{5}, 根, 布局_.绑定结构.场景族锚点,
                            布局_.绑定结构.场景族归属关系类型, 1});
  for (std::uint32_t 序号 = 1; 序号 <= 4; ++序号)
    片段.写集.关系.push_back(
        {{序号 + 5}, 根, L1所有者范围写集本地键{序号},
         布局_.根绑定关系类型, static_cast<std::int64_t>(序号)});
  片段.写集.关系.push_back({{10}, 根, 包含布局_.树登记锚点,
                            包含布局_.根标记关系类型, 1});
  return 输出;
}

