#pragma once

#include <cstdint>
#include <optional>
#include <vector>

#include "新_需求类.h"
#include "新_状态类.h"

namespace 海中鱼巣 {

// 任务集合根只登记全部任务，不表达任务之间的父子关系。
extern 稳定编码 任务集合根节点;

enum class 新任务状态 : std::int64_t {
    已建立 = 1,
    待查找方法 = 2,
    待检查条件 = 3,
    待执行 = 4,
    执行中 = 5,
    待影响评估 = 6,
    等待自我决议 = 7,
    等待条件 = 8,
    已完成 = 9,
    已失败 = 10,
    已取消 = 11
};

enum class 新任务执行状态 : std::int64_t {
    执行中 = 1,
    已结束待评估 = 2,
    已评估 = 3
};

enum class 新任务操作状态 : std::uint8_t {
    已建立 = 1,
    已复用 = 2,
    已找到 = 3,
    已修改 = 4,
    已开始执行 = 5,
    已结束执行 = 6,
    已完成评估 = 7,
    精确重复 = 8,
    无变化 = 9,
    入口拒绝 = 10,
    尚未初始化 = 11,
    需求不存在 = 12,
    需求已有多个任务 = 13,
    任务不存在 = 14,
    任务虚拟存在缺失 = 15,
    任务状态不允许 = 16,
    方法不存在 = 17,
    方法影响定义不合法 = 18,
    执行实例不存在 = 19,
    执行实例不属于任务 = 20,
    状态材料不足 = 21,
    状态不存在 = 22,
    状态时间不合法 = 23,
    结构不一致 = 24,
    资源失败 = 25,
    依赖未实现 = 26
};

struct 新任务预计特征变化 final {
    // 这里保存本次执行已经绑定的实际作用对象，不保存抽象角色。
    稳定编码 作用对象节点;
    稳定编码 特征类型概念节点;
    std::optional<稳定编码> 预期变化关系节点;
    std::optional<稳定编码> 预期值域概念节点;
    bool 必须出现 = true;
    friend bool operator==(const 新任务预计特征变化&,
        const 新任务预计特征变化&) = default;
};

struct 新任务预计变化阶段 final {
    // 阶段顺序必须从0连续递增；同一阶段内的变化没有先后关系。
    std::int64_t 顺序 = 0;
    std::vector<新任务预计特征变化> 变化组;
    friend bool operator==(const 新任务预计变化阶段&,
        const 新任务预计变化阶段&) = default;
};

struct 新任务执行开始请求 final {
    稳定编码 任务节点;
    // 方法身份由上层方法服务核验；任务类仍确认该节点当前存在。
    稳定编码 方法节点;
    新状态强时间 开始时间;
    std::vector<新任务预计变化阶段> 预计变化阶段组;
};

struct 新任务执行结束请求 final {
    稳定编码 任务节点;
    稳定编码 执行实例节点;
    新状态强时间 结束时间;
    // 只接受已经由新_状态类正式建立的状态节点。顺序由强时间确定。
    std::vector<稳定编码> 状态节点组;
};

struct 新任务虚拟存在信息 final {
    稳定编码 节点;
    稳定编码 任务节点;
    稳定编码 任务状态特征节点;
    新任务状态 当前状态 = 新任务状态::已建立;
    friend bool operator==(const 新任务虚拟存在信息&,
        const 新任务虚拟存在信息&) = default;
};

struct 新任务执行信息 final {
    稳定编码 节点;
    稳定编码 任务节点;
    稳定编码 方法节点;
    新任务执行状态 状态 = 新任务执行状态::执行中;
    新状态强时间 开始时间;
    std::optional<新状态强时间> 结束时间;
    std::vector<新任务预计变化阶段> 预计变化阶段组;
    std::vector<稳定编码> 实际状态节点组;
    std::optional<稳定编码> 影响评估节点;
    friend bool operator==(const 新任务执行信息&,
        const 新任务执行信息&) = default;
};

struct 新任务信息 final {
    稳定编码 节点;
    稳定编码 需求节点;
    稳定编码 任务虚拟存在节点;
    新任务状态 当前状态 = 新任务状态::已建立;
    std::optional<稳定编码> 最近方法节点;
    std::optional<稳定编码> 最近执行实例节点;
    std::vector<稳定编码> 影响评估节点组;
    friend bool operator==(const 新任务信息&, const 新任务信息&) = default;
};

struct 新任务影响评估信息 final {
    稳定编码 节点;
    稳定编码 任务节点;
    稳定编码 需求节点;
    稳定编码 执行实例节点;
    稳定编码 方法节点;
    新需求当前满足结果 目标需求结果;
    // 命中组和计划外组保存正式状态节点；缺失组保存预计变化项实现节点。
    std::vector<稳定编码> 符合预测状态组;
    std::vector<稳定编码> 预计但未发生项组;
    std::vector<稳定编码> 计划外状态组;
    friend bool operator==(const 新任务影响评估信息&,
        const 新任务影响评估信息&) = default;
};

struct 新任务建立结果 final {
    新任务操作状态 状态 = 新任务操作状态::入口拒绝;
    std::optional<稳定编码> 任务节点;
    std::optional<稳定编码> 任务虚拟存在节点;
};

struct 新任务执行结果 final {
    新任务操作状态 状态 = 新任务操作状态::入口拒绝;
    std::optional<稳定编码> 执行实例节点;
};

struct 新任务影响评估结果 final {
    新任务操作状态 状态 = 新任务操作状态::入口拒绝;
    std::optional<新任务影响评估信息> 评估;
};

struct 新任务列表结果 final {
    新任务操作状态 状态 = 新任务操作状态::入口拒绝;
    std::vector<稳定编码> 任务节点组;
};

class 新_任务类 final {
public:
    新_任务类(
        新_需求类& 需求服务,
        新_特征值类& 特征值服务,
        新_特征类& 特征服务,
        概念_特征类& 特征概念服务,
        新_状态类& 状态服务) noexcept;

    // 建立扁平任务集合根、类型/字段节点及任务状态特征概念。
    bool 初始化() noexcept;

    // 一个需求最多建立一个任务；重复调用返回既有任务。
    新任务建立结果 建立或取得任务(稳定编码 需求节点) noexcept;

    std::optional<新任务信息> 获取任务(
        稳定编码 任务节点) const noexcept;
    std::optional<新任务虚拟存在信息> 获取任务虚拟存在(
        稳定编码 任务节点) const noexcept;
    std::optional<新任务执行信息> 获取执行实例(
        稳定编码 执行实例节点) const noexcept;
    std::optional<新任务影响评估信息> 获取影响评估(
        稳定编码 评估节点) const noexcept;

    std::optional<稳定编码> 查询需求任务(
        稳定编码 需求节点) const noexcept;
    新任务列表结果 查询全部任务() const noexcept;
    新任务列表结果 查询活动任务() const noexcept;
    新任务列表结果 查询指定状态任务(
        新任务状态 状态) const noexcept;

    // 只修改Vt持有的唯一任务状态特征；非法状态跳转拒绝且零任务结构写入。
    新任务操作状态 修改任务状态(
        稳定编码 任务节点,
        新任务状态 新状态) noexcept;

    // 只供上层在fresh复核唯一需求仍需治理后调用。仅允许三种终结状态
    // 重新进入“待查找方法”；不放宽通用状态迁移合同。
    新任务操作状态 重新启用任务(
        稳定编码 任务节点) noexcept;

    // 待实现：新_需求类仍要求旧“任务子目标承接节点”。本入口只核验
    // 父需求必须是任务的唯一需求并转交需求服务；在需求来源合同切换为
    // “来源任务”以前，会原样返回“任务来源未接通”，不会旁路写需求。
    新需求建立结果 建立子需求(
        稳定编码 任务节点,
        新普通需求建立请求 请求) noexcept;

    // 任务类不解释方法知识。调用方必须先从方法服务取得并绑定本次预计影响。
    新任务执行结果 开始方法执行(
        const 新任务执行开始请求& 请求) noexcept;
    新任务操作状态 结束方法执行(
        const 新任务执行结束请求& 请求) noexcept;

    // 按实际状态的强时间顺序匹配“阶段串行、阶段内并行”的预计变化，
    // 并fresh调用需求服务复核唯一需求。结果供任务管理线程通知自我线程。
    新任务影响评估结果 评估方法执行影响(
        稳定编码 任务节点,
        稳定编码 执行实例节点) noexcept;

    新需求当前满足结果 复核任务需求(
        稳定编码 任务节点) const noexcept;

private:
    新_需求类& 需求服务_;
    新_特征值类& 特征值服务_;
    新_特征类& 特征服务_;
    概念_特征类& 特征概念服务_;
    新_状态类& 状态服务_;
};

} // namespace 海中鱼巣
