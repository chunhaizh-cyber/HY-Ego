// 方法查询材料只保存当前一次完整召回结果，不形成历史候选账。
// 查询条件是实际交给方法服务的条件；完整零候选仍是一份合法材料。
struct 新任务候选方法材料 final {
    稳定编码 节点;
    稳定编码 任务节点;
    稳定编码 需求节点;
    新需求目标定义 需求目标;
    新方法候选查询 查询;
    新方法操作状态 查询状态 = 新方法操作状态::入口拒绝;
    bool 查询完整 = false;
    std::vector<稳定编码> 候选方法节点组;
    friend bool operator==(const 新任务候选方法材料& 左,
        const 新任务候选方法材料& 右) noexcept {
        return 左.节点 == 右.节点
            && 左.任务节点 == 右.任务节点
            && 左.需求节点 == 右.需求节点
            && 左.需求目标 == 右.需求目标
            && 左.查询.作用域 == 右.查询.作用域
            && 左.查询.实现方式 == 右.查询.实现方式
            && 左.查询.作用存在概念组 == 右.查询.作用存在概念组
            && 左.查询.涉及特征类型概念组 == 右.查询.涉及特征类型概念组
            && 左.查询.可能结果概念组 == 右.查询.可能结果概念组
            && 左.查询状态 == 右.查询状态
            && 左.查询完整 == 右.查询完整
            && 左.候选方法节点组 == 右.候选方法节点组;
    }
};

