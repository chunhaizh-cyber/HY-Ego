新词条特征取得结果 新_词类::建立或取得词条特征(稳定编码 W, 稳定编码 FT) noexcept {
    using S = 新词条特征取得状态;
    for (;;) {
        try {
            std::optional<词条空特征持有> 持有;
            新_特征类* 特征 = nullptr;
            {
                std::lock_guard 锁(新词互斥);
                if (!特征服务_ || !场景绑定_) return {S::场景未装配, {}};
                特征 = 特征服务_;
                const auto 读 = 全局基础数据集.查询节点组完整结构({W});
                if (读.状态 == 基础结构操作状态::资源失败) return {S::资源失败, {}};
                if (读.状态 == 基础结构操作状态::节点不存在) return {S::词条不存在, {}};
                if (读.状态 != 基础结构操作状态::已完成 || 读.节点组.size() != 1)
                    词条挂接故障(L"词条空特征建立无法读取当前宿主");
                if (!读.节点组.front().快照) return {S::词条不存在, {}};
                const auto& 当前 = *读.节点组.front().快照;
                const auto 类型 = std::find_if(当前.结构.字段组.begin(), 当前.结构.字段组.end(),
                    [](const auto& f) { return f.字段节点 == 节点类型字段; });
                if (类型 == 当前.结构.字段组.end() || 类型->内容 != 基础字段内容{词条节点类型})
                    return {S::词条不存在, {}};
                const auto 扩展 = 解码词条扩展(当前.结构.字段组);
                if (!扩展) return {S::场景未装配, {}};
                bool 重读 = false;
                for (const auto F : 扩展->特征组) {
                    const auto 头 = 特征->读取当前特征类型(F);
                    if (头.状态 == 新特征类型读取状态::资源失败) return {S::资源失败, {}};
                    if (头.状态 == 新特征类型读取状态::特征不存在) { 重读 = true; break; }
                    if (头.状态 != 新特征类型读取状态::已读取 || !头.特征类型根)
                        return {S::场景未装配, {}};
                    if (*头.特征类型根 == FT) return {S::已复用, 新词条特征定位{FT, F}};
                }
                if (重读) continue;
                if (!有效(词典材料类型根_) || FT != 词典材料类型根_)
                    return {S::类型未支持, {}};
                持有.emplace(当前);
            }
            const auto r = 特征->建立并挂接空信息引用特征(FT, *持有);
            if (r.状态 == 新特征写入状态::前提已变化) continue;
            if (r.状态 == 新特征写入状态::资源失败) return {S::资源失败, {}};
            if (r.状态 == 新特征写入状态::材料类型不相容 || r.状态 == 新特征写入状态::概念不存在)
                return {S::类型未支持, {}};
            if (r.状态 != 新特征写入状态::已完成 || !r.特征节点)
                词条挂接故障(L"空词典材料特征共同建立没有成功回执");
            return {S::已建立, 新词条特征定位{FT, *r.特征节点}};
        } catch (const std::bad_alloc&) { return {S::资源失败, {}}; }
        catch (const std::length_error&) { return {S::资源失败, {}}; }
        catch (...) { 词条挂接故障(L"建立或取得词条特征异常"); }
    }
}

基础节点组追加状态 新_词类::补齐词条概念挂接(
    稳定编码 词条, const std::vector<稳定编码>& 概念组) {
    std::lock_guard 锁(新词互斥);
    if (!场景绑定_ || !状态绑定_) return 基础节点组追加状态::引用不存在;
    if (读取特征信息已加锁(词条)) return 基础节点组追加状态::已完成;
    const auto 旧 = 读取词条信息(词条, 语言服务_);
    if (!旧) return 基础节点组追加状态::节点不存在;
    return 发布词条初值已加锁({旧->语言节点, 旧->规范化合同节点,
        旧->规范化词面, 旧->创建来源节点}, 词条, 概念组).状态;
}

新词条挂接发布结果 新_词类::发布词条初值已加锁(
    const 新词条建立请求& 信息, std::optional<稳定编码> 既有词条,
    const std::vector<稳定编码>& 概念组) {
    bool 已发布 = false;
    try {
        const auto 值 = 保存词条概念集合(*特征值服务_, 概念组);
        const auto 建立 = 特征服务_->建立特征强类型(挂接类型根_);
        if (建立.状态 == 新特征写入状态::资源失败)
            return {基础节点组追加状态::资源失败};
        if (建立.状态 == 新特征写入状态::前提已变化)
            return {基础节点组追加状态::预期不符};
        if (建立.状态 == 新特征写入状态::概念不存在)
            return {基础节点组追加状态::节点不存在};
        if (建立.状态 != 新特征写入状态::已完成 || !建立.特征节点)
            词条挂接故障(L"词条独立空特征建立失败");
        未采用词条特征 回收{*特征服务_, *建立.特征节点};
        const auto 场景准备 = 场景绑定_->owner_->取得场景状态参与绑定(场景绑定_->场景_);
        auto 准备 = 特征服务_->准备特征当前值组({{*建立.特征节点, 新特征准确值{值}}});
        if (准备.状态 != 新特征I64准备状态::已准备)
            return {词条准备失败(准备.状态)};
        if (!准备.准备) 词条挂接故障(L"词条初值准备缺少句柄");
        基础节点组追加请求 请求;
        for (const auto n : {词条节点类型, 信息.语言节点, 信息.规范化合同节点,
            *建立.特征节点, 场景绑定_->场景_}) 请求.只读预期.节点组.push_back({n});
        if (信息.创建来源节点) 请求.只读预期.节点组.push_back({*信息.创建来源节点});
        std::variant<稳定编码, 基础组内节点引用> 词条定位;
        if (既有词条) {
            请求.预期联合节点组.push_back(读取词条写宿主(*既有词条));
            请求.追加字段组 = {{*既有词条, 词条特征成员字段, *建立.特征节点},
                {*既有词条, 所属自然语言场景字段, 场景绑定_->场景_}};
            词条定位 = *既有词条;
        } else {
            基础组内新节点 词;
            词.字段组 = {{节点类型字段, 词条节点类型}, {所属语言字段, 信息.语言节点},
                {规范化合同字段, 信息.规范化合同节点}, {规范化词面字段, 基础值{信息.规范化词面}},
                {词条特征成员字段, *建立.特征节点}, {所属自然语言场景字段, 场景绑定_->场景_}};
            if (信息.创建来源节点) 词.字段组.push_back({创建来源字段, *信息.创建来源节点});
            请求.新节点组.push_back(std::move(词));
            请求.预期联合节点组.push_back(读取词条写宿主(词组织根节点));
            请求.追加外部关系组.push_back({词组织根节点, 基础组内节点引用{0},
                基础外部关系类型::父子, 0});
            词条定位 = 基础组内节点引用{0};
        }
        const auto 候选 = 特征服务_->读取准备当前值候选(*准备.准备, *建立.特征节点);
        auto 状态材料 = 状态服务_->准备特征状态(*状态绑定_, 候选,
            词条定位, 词条当前UTC(), std::move(请求));
        const auto 封存 = 场景绑定_->owner_->封存场景状态挂接(场景准备, std::move(状态材料));
        if (封存.封存.状态 != 基础节点组追加状态::已完成) {
            特征服务_->取消特征当前值组(*准备.准备);
            return {封存.封存.状态};
        }
        if (!封存.封存.片段) 词条挂接故障(L"词条初值封存成功但无片段");
        auto 发布 = 特征服务_->提交特征当前值组(*准备.准备, {*封存.封存.片段});
        if (发布.状态 != 基础节点组追加状态::已完成) {
            特征服务_->取消特征当前值组(*准备.准备);
            return {发布.状态};
        }
        已发布 = true; 回收.已采用 = true;
        const auto& 新节点 = 发布.附加片段回执组.at(0).新节点组();
        新词条挂接发布结果 结果;
        结果.状态 = 基础节点组追加状态::已完成;
        结果.词条 = 既有词条 ? *既有词条 : 新节点.at(0);
        结果.新状态 = 新节点.at(封存.状态槽);
        结果.动态原因 = 新词条动态记录原因::无前态;
        (void)特征服务_->完成特征当前值组(*准备.准备);
        特征服务_->结束特征当前值组(*准备.准备);
        return 结果;
    } catch (基础节点组追加状态 状态) {
        if (已发布) 词条挂接故障(L"词条初值发布后发生依赖错误，保留事实");
        return {状态};
    } catch (const std::bad_alloc&) {
        if (已发布) 词条挂接故障(L"词条初值发布后资源错误，保留事实");
        return {基础节点组追加状态::资源失败};
    } catch (const std::length_error&) {
        if (已发布) 词条挂接故障(L"词条初值发布后长度错误，保留事实");
        return {基础节点组追加状态::资源失败};
    } catch (...) { 词条挂接故障(L"词条初值组合发布工程异常，保留已发布事实"); }
}

bool 新_词类::已装配概念挂接() const {
    std::lock_guard 锁(新词互斥);
    return 场景绑定_.has_value() && 状态绑定_.has_value();
}

void 新_词类::准备名称集合材料(const std::vector<稳定编码>& 概念组) {
    std::lock_guard 锁(新词互斥);
    if (!场景绑定_ || !状态绑定_) throw 基础节点组追加状态::引用不存在;
    const auto 值 = 保存词条概念集合(*特征值服务_, 概念组);
    const auto 状态 = 特征服务_->准备词条集合材料(挂接类型根_, 值);
    if (状态 == 特征概念规则状态::已完成 || 状态 == 特征概念规则状态::无变化) return;
    if (状态 == 特征概念规则状态::资源失败) throw 基础节点组追加状态::资源失败;
    if (状态 == 特征概念规则状态::前提已变化) throw 基础节点组追加状态::预期不符;
    词条挂接故障(L"名称集合材料准备失败");
}

新词条挂接发布结果 新_词类::发布名称挂接变化(稳定编码 词条,
    const std::vector<稳定编码>& 概念组, const std::vector<基础封存追加片段>& 附加) {
    bool 已发布 = false;
    try {
        std::lock_guard 锁(新词互斥);
        if (!场景绑定_ || !状态绑定_) return {基础节点组追加状态::引用不存在};
        const auto 挂接 = 读取特征信息已加锁(词条);
        if (!挂接) return {基础节点组追加状态::节点不存在};
        if (挂接->所属自然语言场景 != 场景绑定_->场景_)
            词条挂接故障(L"词条所属场景与装配不符");
        const auto 成员 = std::find_if(挂接->特征组.begin(), 挂接->特征组.end(),
            [&](const auto& 项) { return 项.特征类型根 == 挂接类型根_; });
        if (成员 == 挂接->特征组.end()) 词条挂接故障(L"词条名称特征尚未建立");
        const auto f = 成员->特征节点;
        const auto 原 = 特征服务_->获取特征(f);
        if (!原) return {基础节点组追加状态::节点不存在};
        const auto 前态 = 原->当前值
            ? 状态服务_->读取词条前状态(词条, f, *原->当前值) : std::nullopt;
        const auto 值 = 保存词条概念集合(*特征值服务_, 概念组);
        const auto 场景准备 = 场景绑定_->owner_->取得场景状态参与绑定(场景绑定_->场景_);
        auto 准备 = 特征服务_->准备特征当前值组({{f, 新特征准确值{值}}});
        if (准备.状态 != 新特征I64准备状态::已准备) return {词条准备失败(准备.状态)};
        if (!准备.准备) 词条挂接故障(L"词条名称更新准备缺少句柄");
        const auto 候选 = 特征服务_->读取准备当前值候选(*准备.准备, f);
        std::vector<基础封存追加片段> 片段 = 附加;
        std::optional<std::size_t> 新状态槽;
        std::optional<新状态强时间> 时间;
        if (候选.已改变_) {
            时间 = 词条当前UTC();
            auto 状态材料 = 状态服务_->准备特征状态(*状态绑定_, 候选, 词条, *时间);
            const auto 封存 = 场景绑定_->owner_->封存场景状态挂接(场景准备, std::move(状态材料));
            if (封存.封存.状态 != 基础节点组追加状态::已完成) {
                特征服务_->取消特征当前值组(*准备.准备);
                return {封存.封存.状态};
            }
            if (!封存.封存.片段) 词条挂接故障(L"词条变化状态封存成功但无片段");
            新状态槽 = 封存.状态槽;
            片段.push_back(*封存.封存.片段);
        }
        auto 发布 = 特征服务_->提交特征当前值组(*准备.准备, 片段);
        if (发布.状态 != 基础节点组追加状态::已完成) {
            特征服务_->取消特征当前值组(*准备.准备);
            return {发布.状态};
        }
        已发布 = true;
        新词条挂接发布结果 结果;
        结果.状态 = 基础节点组追加状态::已完成; 结果.词条 = 词条;
        if (新状态槽) {
            结果.新状态 = 发布.附加片段回执组.at(附加.size()).新节点组().at(*新状态槽);
            发布.附加片段回执组.pop_back();
        }
        结果.附加片段回执组 = std::move(发布.附加片段回执组);
        (void)特征服务_->完成特征当前值组(*准备.准备);
        特征服务_->结束特征当前值组(*准备.准备);
        if (!结果.新状态) return 结果;
        if (!前态) { 结果.动态原因 = 新词条动态记录原因::无前态; return 结果; }
        if (时间->纳秒 <= 前态->强时间.纳秒) {
            结果.动态原因 = 新词条动态记录原因::时间不递增; return 结果;
        }
        const auto 动态 = 动态服务_->建立原子动态(词条, 前态->节点, *结果.新状态);
        if (动态.状态 == 新动态操作状态::状态不存在 && !动态.动态节点) {
            结果.动态原因 = 新词条动态记录原因::无前态;
            return 结果;
        }
        if (动态.状态 != 新动态操作状态::已完成 || !动态.动态节点)
            词条挂接故障(L"名称特征及状态已发布，变化动态建立失败，保留事实");
        结果.变化动态 = *动态.动态节点;
        const auto 挂入 = 场景绑定_->owner_->添加动态(场景绑定_->场景_, *动态.动态节点);
        if (挂入 != 新场景操作状态::已完成 && 挂入 != 新场景操作状态::无变化)
            词条挂接故障(L"词条变化动态已建立，场景挂接失败，保留事实");
        结果.动态原因 = 新词条动态记录原因::已形成;
        return 结果;
    } catch (基础节点组追加状态 状态) {
        if (已发布) 词条挂接故障(L"名称挂接发布后依赖错误，保留事实");
        return {状态};
    } catch (const std::bad_alloc&) {
        if (已发布) 词条挂接故障(L"名称挂接发布后资源错误，保留事实");
        return {基础节点组追加状态::资源失败};
    } catch (const std::length_error&) {
        if (已发布) 词条挂接故障(L"名称挂接发布后长度错误，保留事实");
        return {基础节点组追加状态::资源失败};
    } catch (...) { 词条挂接故障(L"名称挂接组合发布工程异常，保留已发布事实"); }
}

新词条查询结果 新_词类::获取词条(稳定编码 词条节点) const noexcept {
    新词条查询结果 结果;
    try {
        std::lock_guard 锁(新词互斥);
        if (!有效(词条节点)) return 结果;
        if (!结构仍存在()) {
            结果.状态 = 新词条查询状态::结构不一致;
            return 结果;
        }
        if (!节点仍存在(词条节点)) {
            结果.状态 = 新词条查询状态::未找到;
            return 结果;
        }
        if (!类型为(词条节点, 词条节点类型)) {
            结果.状态 = 新词条查询状态::输入不合法;
            return 结果;
        }
        const auto 信息 = 读取词条信息(词条节点, 语言服务_);
        if (!信息) {
            结果.状态 = 新词条查询状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新词条查询状态::已找到;
        结果.信息 = 信息;
        return 结果;
    } catch (...) {
        结果.状态 = 新词条查询状态::资源失败;
        return 结果;
    }
}

新词条查询结果 新_词类::按规范化词面查询(
    稳定编码 语言节点,
    稳定编码 规范化合同节点,
    const std::string& 规范化词面) const noexcept {
    新词条查询结果 结果;
    try {
        std::lock_guard 锁(新词互斥);
        if (!有效(语言节点) || !有效(规范化合同节点)
            || !新_语言类::严格UTF8字节串有效(规范化词面)
            || 规范化合同节点 != 严格UTF8字节精确规范化合同节点) {
            return 结果;
        }
        if (!结构仍存在()) {
            结果.状态 = 新词条查询状态::结构不一致;
            return 结果;
        }
        const auto 语言结果 = 语言服务_.获取语言(语言节点);
        if (语言结果.状态 == 新语言查询状态::资源失败) {
            结果.状态 = 新词条查询状态::资源失败;
            return 结果;
        }
        if (语言结果.状态 == 新语言查询状态::结构不一致) {
            结果.状态 = 新词条查询状态::结构不一致;
            return 结果;
        }
        if (语言结果.状态 != 新语言查询状态::已找到) return 结果;
        const 词条键 键{语言节点, 规范化合同节点, 规范化词面};
        const auto 位置 = 词条索引.find(键);
        if (位置 == 词条索引.end()) {
            结果.状态 = 新词条查询状态::未找到;
            return 结果;
        }
        const auto 信息 = 读取词条信息(位置->second, 语言服务_);
        if (!信息 || 信息->语言节点 != 语言节点
            || 信息->规范化合同节点 != 规范化合同节点
            || 信息->规范化词面 != 规范化词面) {
            结果.状态 = 新词条查询状态::结构不一致;
            return 结果;
        }
        结果.状态 = 新词条查询状态::已找到;
        结果.信息 = 信息;
        return 结果;
    } catch (...) {
        结果.状态 = 新词条查询状态::资源失败;
        return 结果;
    }
}

新词条列表查询结果 新_词类::查询语言词条(
    稳定编码 语言节点) const noexcept {
    新词条列表查询结果 结果;
    try {
        std::lock_guard 锁(新词互斥);
        if (!有效(语言节点)) return 结果;
        if (!结构仍存在()) {
            结果.状态 = 新词条查询状态::结构不一致;
            return 结果;
        }
        const auto 语言结果 = 语言服务_.获取语言(语言节点);
        if (语言结果.状态 == 新语言查询状态::资源失败) {
            结果.状态 = 新词条查询状态::资源失败;
            return 结果;
        }
        if (语言结果.状态 == 新语言查询状态::结构不一致) {
            结果.状态 = 新词条查询状态::结构不一致;
            return 结果;
        }
        if (语言结果.状态 != 新语言查询状态::已找到) return 结果;
        for (const auto& [键, 节点] : 词条索引) {
            if (键.语言节点 == 语言节点) 结果.词条节点组.push_back(节点);
        }
        std::sort(结果.词条节点组.begin(), 结果.词条节点组.end());
        结果.状态 = 结果.词条节点组.empty()
            ? 新词条查询状态::未找到 : 新词条查询状态::已找到;
        return 结果;
    } catch (...) {
        结果.状态 = 新词条查询状态::资源失败;
        return 结果;
    }
}

bool 新_词类::是词条节点(稳定编码 节点) const noexcept {
    const auto 结果 = 获取词条(节点);
    return 结果.状态 == 新词条查询状态::已找到;
}

新词条保护结果 新_词类::读取词条保护(稳定编码 词条) const noexcept {
    try {
        if (!有效(词条)) return {};
        std::lock_guard 锁(新词互斥);
        词保护现场 现场;
        读取词保护结构(现场);
        const auto 快照 = 现场.读取(词条);
        if (!快照) return {新词条保护状态::未找到, {}, 现场.完成()};
        const auto 根 = 现场.必需(词组织根节点);
        const bool 已登记 = std::any_of(根.出向外部关系组.begin(),
            根.出向外部关系组.end(), [&](const auto& 边) {
                return 边.类型 == 基础外部关系类型::父子 && 边.目标节点 == 词条;
            });
        if (!已登记) return {};
        const auto 信息 = 解码词保护信息(*快照, 现场, 语言服务_);
        return {新词条保护状态::已读取, 信息, 现场.完成()};
    } catch (新词条保护状态 状态) { return {状态, {}, {}}; }
    catch (const std::bad_alloc&) { return {新词条保护状态::资源失败, {}, {}}; }
    catch (const std::length_error&) { return {新词条保护状态::资源失败, {}, {}}; }
    catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取词条保护",
            L"词条完整保护读取发生工程故障。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取词条保护",
            L"词条完整保护读取发生未知工程故障。");
    }
}

新词条保护结果 新_词类::按规范化词面查询保护(稳定编码 语言,
    稳定编码 规范化合同, const std::string& 规范化词面) const noexcept {
    try {
        if (!有效(语言) || !有效(规范化合同)
            || 规范化合同 != 严格UTF8字节精确规范化合同节点
            || !新_语言类::严格UTF8字节串有效(规范化词面)) return {};
        std::lock_guard 锁(新词互斥);
        词保护现场 现场;
        读取词保护结构(现场);
        if (!读取词保护语言(现场, 语言, 语言服务_)) return {};
        const auto 位置 = 词条索引.find({语言, 规范化合同, 规范化词面});
        if (位置 == 词条索引.end())
            return {新词条保护状态::未找到, {}, 现场.完成()};
        const auto 信息 = 解码词保护信息(现场.必需(位置->second), 现场, 语言服务_);
        if (信息.语言节点 != 语言 || 信息.规范化合同节点 != 规范化合同
            || 信息.规范化词面 != 规范化词面)
            throw std::logic_error("word exact query and result differ");
        return {新词条保护状态::已读取, 信息, 现场.完成()};
    } catch (新词条保护状态 状态) { return {状态, {}, {}}; }
    catch (const std::bad_alloc&) { return {新词条保护状态::资源失败, {}, {}}; }
    catch (const std::length_error&) { return {新词条保护状态::资源失败, {}, {}}; }
    catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"按规范化词面查询保护",
            L"词面精确查询保护发生工程故障。", 异常.what());
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"按规范化词面查询保护",
            L"词面精确查询保护发生未知工程故障。");
    }
}

