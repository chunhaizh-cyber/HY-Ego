[[noreturn]] void 词条挂接故障(const wchar_t* 原因) noexcept {
    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"词条名称特征联合发布", 原因);
}

基础联合节点快照 读取词条写宿主(稳定编码 节点) {
    const auto 读取 = 全局基础数据集.查询节点组完整结构({节点});
    if (读取.状态 == 基础结构操作状态::资源失败)
        throw 基础节点组追加状态::资源失败;
    if (读取.状态 == 基础结构操作状态::节点不存在
        || (读取.状态 == 基础结构操作状态::已完成 && 读取.节点组.size() == 1
            && !读取.节点组.front().快照)) throw 基础节点组追加状态::节点不存在;
    if (读取.状态 != 基础结构操作状态::已完成 || 读取.节点组.size() != 1)
        词条挂接故障(L"L1词条写宿主读取失败");
    return *读取.节点组.front().快照;
}

新状态强时间 词条当前UTC() {
    const auto t = std::chrono::duration_cast<std::chrono::nanoseconds>(
        std::chrono::system_clock::now().time_since_epoch()).count();
    if (!std::in_range<std::int64_t>(t) || t < 0)
        词条挂接故障(L"系统UTC不能表示为状态强时间");
    return {新状态时间语义::实例绝对UTC, static_cast<std::int64_t>(t)};
}

稳定编码 保存词条概念集合(新_特征值类& 服务, const std::vector<稳定编码>& 概念组) {
    std::vector<std::uint64_t> 材料;
    材料.reserve(概念组.size());
    for (const auto c : 概念组) 材料.push_back(c.值);
    std::sort(材料.begin(), 材料.end());
    材料.erase(std::unique(材料.begin(), 材料.end()), 材料.end());
    const auto v = 服务.保存或取得特征值(材料物理类型::U64数组, 新特征值材料{std::move(材料)});
    if (!有效(v)) throw 基础节点组追加状态::资源失败;
    return v;
}

基础节点组追加状态 词条准备失败(新特征I64准备状态 状态) {
    switch (状态) {
    case 新特征I64准备状态::资源失败: return 基础节点组追加状态::资源失败;
    case 新特征I64准备状态::特征不存在:
    case 新特征I64准备状态::概念不存在:
    case 新特征I64准备状态::预期已变化:
    case 新特征I64准备状态::联合更新占用: return 基础节点组追加状态::预期不符;
    default: 词条挂接故障(L"词条挂接特征准备合同不符");
    }
}

