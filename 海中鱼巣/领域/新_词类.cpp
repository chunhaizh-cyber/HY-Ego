bool 新_词类::初始化() noexcept {
    try {
        if (!语言服务_.初始化()) return false;
        std::lock_guard 锁(新词互斥);
        auto 建立独立节点 = [](稳定编码& 节点) {
            if (有效(节点)) return 节点仍存在(节点);
            节点 = 全局基础数据集.新建节点();
            return 有效(节点);
        };
        if (!建立独立节点(节点类型字段)
            || !建立独立节点(词组织根类型)
            || !建立独立节点(词条节点类型)
            || !建立独立节点(规范化合同节点类型)
            || !建立独立节点(所属语言字段)
            || !建立独立节点(规范化合同字段)
            || !建立独立节点(规范化词面字段)
            || !建立独立节点(创建来源字段)
            || !建立独立节点(词条特征成员字段)
            || !建立独立节点(所属自然语言场景字段)) {
            return false;
        }
        if (!有效(词组织根节点)) {
            词组织根节点 = 全局基础数据集.新建节点(自然语言组织根节点);
            if (!有效(词组织根节点)) return false;
        } else if (!节点仍存在(词组织根节点)
            || !有唯一父节点(词组织根节点, 自然语言组织根节点)) {
            return false;
        }
        if (!确保唯一类型字段(词组织根节点, 词组织根类型)) return false;

        if (!有效(严格UTF8字节精确规范化合同节点)) {
            严格UTF8字节精确规范化合同节点 =
                全局基础数据集.新建节点(自然语言组织根节点);
            if (!有效(严格UTF8字节精确规范化合同节点)) return false;
        } else if (!节点仍存在(严格UTF8字节精确规范化合同节点)
            || !有唯一父节点(严格UTF8字节精确规范化合同节点,
                自然语言组织根节点)) {
            return false;
        }
        if (!确保唯一类型字段(严格UTF8字节精确规范化合同节点,
            规范化合同节点类型)) {
            return false;
        }
        return 结构仍存在() && 重建词条索引(语言服务_);
    } catch (...) {
        return false;
    }
}

新词条建立结果 新_词类::建立或取得词条(
    const 新词条建立请求& 请求) noexcept {
    for (;;) {
        bool 已发布 = false;
        try {
            std::lock_guard 锁(新词互斥);
            if (!有效(请求.语言节点)
                || 请求.规范化合同节点 != 严格UTF8字节精确规范化合同节点
                || !新_语言类::严格UTF8字节串有效(请求.规范化词面)) return {};
            if (!场景绑定_ || !状态绑定_)
                return {新词条建立状态::依赖不存在, {}};
            if (!语言服务_.是语言节点(请求.语言节点))
                return {新词条建立状态::依赖不存在, {}};
            词条键 键{请求.语言节点, 请求.规范化合同节点, 请求.规范化词面};
            const auto 已有 = 词条索引.find(键);
            if (已有 != 词条索引.end()) {
                const auto 信息 = 读取特征信息已加锁(已有->second);
                if (!信息) 词条挂接故障(L"已登记词条尚未完成挂接装配");
                return {新词条建立状态::已复用, 已有->second};
            }
            if ((请求.创建来源节点 && !全局基础数据集.查询节点(*请求.创建来源节点))
                || !全局基础数据集.查询节点(场景绑定_->场景_)
                || !全局基础数据集.查询节点(挂接类型根_)
                || !全局基础数据集.查询节点(词组织根节点)
                || !全局基础数据集.查询节点(严格UTF8字节精确规范化合同节点))
                return {新词条建立状态::依赖不存在, {}};
            const auto 发布 = 发布词条初值已加锁(请求, {}, {});
            if (发布.状态 == 基础节点组追加状态::资源失败)
                return {新词条建立状态::资源失败, {}};
            if (发布.状态 == 基础节点组追加状态::预期不符
                || 发布.状态 == 基础节点组追加状态::节点不存在
                || 发布.状态 == 基础节点组追加状态::引用不存在)
                throw 发布.状态;
            if (发布.状态 != 基础节点组追加状态::已完成 || !发布.词条)
                词条挂接故障(L"新词条组合发布返回不合法状态");
            已发布 = true;
            const auto [位置, 新增] = 词条索引.emplace(std::move(键), *发布.词条);
            if (!新增) 词条挂接故障(L"新词条已发布但唯一键索引发生冲突");
            return {新词条建立状态::已建立, *发布.词条};
        } catch (基础节点组追加状态 状态) {
            if (已发布) 词条挂接故障(L"已发布词条不能重试");
            if (状态 != 基础节点组追加状态::预期不符
                && 状态 != 基础节点组追加状态::节点不存在
                && 状态 != 基础节点组追加状态::引用不存在)
                词条挂接故障(L"词条重读收到非变化状态");
            std::this_thread::yield();
        } catch (const std::bad_alloc&) {
            if (已发布) 词条挂接故障(L"词条已发布后索引分配失败，保留事实");
            return {新词条建立状态::资源失败, {}};
        } catch (const std::length_error&) {
            if (已发布) 词条挂接故障(L"词条已发布后索引长度失败，保留事实");
            return {新词条建立状态::资源失败, {}};
        } catch (...) { 词条挂接故障(L"建立词条发生工程异常，保留已发布事实"); }
    }
}
std::vector<稳定编码> 新_词类::读取启动词条组() const {
    std::lock_guard 锁(新词互斥);
    std::vector<稳定编码> 结果;
    结果.reserve(词条索引.size());
    for (const auto& [键, 节点] : 词条索引) 结果.push_back(节点);
    return 结果;
}

void 新_词类::装配概念挂接(新_特征类& 特征, 新_特征值类& 值,
    新_状态类& 状态, 新_动态类& 动态, 稳定编码 类型根,
    const 新场景状态参与绑定& 场景) {
    std::lock_guard 锁(新词互斥);
    if (场景绑定_) {
        if (特征服务_ != &特征 || 特征值服务_ != &值 || 状态服务_ != &状态
            || 动态服务_ != &动态 || 挂接类型根_ != 类型根
            || 场景绑定_->owner_ != 场景.owner_ || 场景绑定_->场景_ != 场景.场景_)
            词条挂接故障(L"不能在运行中更换词条挂接装配");
        return;
    }
    auto 状态绑定 = 状态.取得特征状态构造绑定();
    特征服务_ = &特征; 特征值服务_ = &值; 状态服务_ = &状态; 动态服务_ = &动态;
    挂接类型根_ = 类型根;
    状态绑定_ = std::move(状态绑定);
    场景绑定_ = 场景;
}

std::optional<新词条特征信息> 新_词类::读取特征信息已加锁(稳定编码 词条) const {
    auto 当前 = 读取词条特征信息(词条);
    if (当前.状态 == 新词条查询状态::资源失败) throw std::bad_alloc{};
    if (当前.状态 == 新词条查询状态::未找到) return {};
    if (当前.状态 != 新词条查询状态::已找到 || !当前.信息)
        词条挂接故障(L"词条当前特征读取不可用");
    return std::move(当前.信息);
}

新词条特征读取结果 新_词类::读取词条特征信息(稳定编码 词条) const noexcept {
    try {
        if (!有效(词条)) return {新词条查询状态::输入不合法, {}};
        // schema及服务在线程开放前装配；本读口不取得词锁。
        // 跨owner读取遇到正常变化时整轮重读，不向上层返回变化错误。
        for (;;) {
            if (!结构句柄完整() || !有效(词条特征成员字段) || !有效(所属自然语言场景字段))
                词条挂接故障(L"词条挂接读取尚未完成初始化");
            const auto 读取 = 全局基础数据集.查询节点组完整结构({词条});
            if (读取.状态 == 基础结构操作状态::资源失败)
                return {新词条查询状态::资源失败, {}};
            if (读取.状态 == 基础结构操作状态::节点不存在)
                return {新词条查询状态::未找到, {}};
            if (读取.状态 != 基础结构操作状态::已完成 || 读取.节点组.size() != 1
                || 读取.节点组.front().查询节点 != 词条)
                词条挂接故障(L"L1词条挂接快照读取失败");
            if (!读取.节点组.front().快照) return {新词条查询状态::未找到, {}};
            const auto& 快照 = *读取.节点组.front().快照;
            const auto& 字段组 = 快照.结构.字段组;
            std::optional<稳定编码> 类型;
            for (const auto& 字段 : 字段组) if (字段.字段节点 == 节点类型字段) {
                const auto* 引用 = std::get_if<稳定编码>(&字段.内容);
                if (类型 || !引用 || !有效(*引用))
                    词条挂接故障(L"词条类型字段无法解码");
                类型 = *引用;
            }
            if (类型 != 词条节点类型) return {新词条查询状态::未找到, {}};

            const 基础外部关系* 父边 = nullptr;
            for (const auto& 边 : 快照.入向外部关系组) if (边.类型 == 基础外部关系类型::父子) {
                if (父边 || 边.源节点 != 词组织根节点 || 边.目标节点 != 词条 || 边.角色或顺序 != 0)
                    词条挂接故障(L"词条父关系无法解码");
                父边 = &边;
            }
            if (!父边) 词条挂接故障(L"词条父关系缺失");
            const auto 语言 = 词保护唯一引用(快照, 所属语言字段);
            const auto 合同 = 词保护唯一引用(快照, 规范化合同字段);
            if (合同 != 严格UTF8字节精确规范化合同节点)
                词条挂接故障(L"词条规范化合同不支持");
            std::optional<std::string> 词面;
            std::optional<稳定编码> 来源;
            for (const auto& 字段 : 字段组) {
                if (字段.字段节点 == 规范化词面字段) {
                    const auto* 值 = std::get_if<基础值>(&字段.内容);
                    const auto* 文本 = 值 ? std::get_if<std::string>(&值->材料) : nullptr;
                    if (词面 || !文本) 词条挂接故障(L"词面字段无法解码");
                    词面 = *文本;
                } else if (字段.字段节点 == 创建来源字段) {
                    const auto* 引用 = std::get_if<稳定编码>(&字段.内容);
                    if (来源 || !引用 || !有效(*引用))
                        词条挂接故障(L"词条创建来源无法解码");
                    来源 = *引用;
                }
            }
            if (!词面) 词条挂接故障(L"词条词面缺失");
            const auto 扩展 = 解码词条扩展(字段组);
            if (!扩展) return {新词条查询状态::未找到, {}};
            if (!特征服务_) 词条挂接故障(L"词条特征类型读取未装配");
            新词条特征信息 信息{{词条, 语言, 合同, std::move(*词面), 来源}, 扩展->场景, {}};
            bool 需要重读 = false;
            for (const auto F : 扩展->特征组) {
                const auto 头 = 特征服务_->读取当前特征类型(F);
                if (头.状态 == 新特征类型读取状态::资源失败)
                    return {新词条查询状态::资源失败, {}};
                if (头.状态 == 新特征类型读取状态::特征不存在) {
                    // 旧成员可能已被删除；只读当前成员，不复核旧整组快照。
                    const auto 当前成员 = 全局基础数据集.查询字段(词条, 词条特征成员字段);
                    if (std::none_of(当前成员.begin(), 当前成员.end(), [&](const auto& 项) {
                        const auto* 节点 = std::get_if<稳定编码>(&项.内容);
                        return 节点 && *节点 == F;
                    })) { 需要重读 = true; break; }
                    词条挂接故障(L"词条当前成员引用了不存在的特征");
                }
                if (头.状态 != 新特征类型读取状态::已读取 || !头.特征类型根)
                    词条挂接故障(L"词条成员类型读取未就绪");
                信息.特征组.push_back({*头.特征类型根, F});
            }
            if (需要重读) { std::this_thread::yield(); continue; }
            return {新词条查询状态::已找到, std::move(信息)};
        }
    } catch (const std::bad_alloc&) { return {新词条查询状态::资源失败, {}}; }
    catch (const std::length_error&) { return {新词条查询状态::资源失败, {}}; }
    catch (...) { 词条挂接故障(L"读取词条特征信息发生工程异常"); }
}

新词条特征定位结果 新_词类::按类型读取词条特征(
    稳定编码 词条, 稳定编码 特征类型) const noexcept {
    if (!有效(特征类型)) return {新词条查询状态::输入不合法, {}};
    const auto 当前 = 读取词条特征信息(词条);
    if (当前.状态 != 新词条查询状态::已找到) return {当前.状态, {}};
    if (!当前.信息) 词条挂接故障(L"词条读取成功但缺少特征信息");
    for (const auto& 项 : 当前.信息->特征组)
        if (项.特征类型根 == 特征类型) return {新词条查询状态::已找到, 项};
    return {新词条查询状态::特征未建立, {}};
}

