bool 是I64最大值单点概念(
    const 概念_特征类& 特征概念服务,
    稳定编码 概念节点) noexcept {
    const auto 概念 = 特征概念服务.获取特征概念(概念节点);
    if (!概念 || 概念->材料类型 != 特征概念材料物理类型::I64标量) {
        return false;
    }
    const auto* 区间组 = std::get_if<std::vector<特征概念I64闭区间>>(
        &概念->值域);
    constexpr auto 最大值 = (std::numeric_limits<std::int64_t>::max)();
    return 区间组 && 区间组->size() == 1
        && 区间组->front().下界 == 最大值
        && 区间组->front().上界 == 最大值;
}

std::optional<std::int64_t> 读取非负I64当前值(
    const 新_特征类& 特征服务,
    稳定编码 特征节点) noexcept {
    const auto 特征 = 特征服务.获取特征(特征节点);
    if (!特征 || !特征->当前值) return std::nullopt;
    const auto* 值 = std::get_if<std::int64_t>(&*特征->当前值);
    return 值 && *值 >= 0 ? std::optional<std::int64_t>{*值} : std::nullopt;
}

新自我本能需求复核结果 复核自我本能需求(
    新_世界树类& 世界树服务,
    新_需求类& 需求服务,
    稳定编码 自我存在,
    稳定编码 安全需求,
    稳定编码 服务需求,
    std::optional<稳定编码> 来源状态) noexcept {
    新自我本能需求复核结果 结果;
    结果.自我存在 = 自我存在;
    结果.安全需求 = 安全需求;
    结果.服务需求 = 服务需求;
    结果.来源状态 = 来源状态;
    try {
        if (!世界树服务.已初始化()) {
            结果.状态 = 新自我需求复核状态::世界树未初始化;
            return 结果;
        }
        const auto 事实 = 世界树服务.获取事实服务引用();
        const auto 自我 = 事实.存在服务.获取存在(自我存在);
        const auto 安全 = 需求服务.获取需求(安全需求);
        const auto 服务 = 需求服务.获取需求(服务需求);
        if (!自我 || !安全 || !服务 || 安全需求 == 服务需求
            || 需求服务.查询根需求(新需求根角色::安全) != 安全需求
            || 需求服务.查询根需求(新需求根角色::服务) != 服务需求
            || 安全->根角色 != 新需求根角色::安全
            || 服务->根角色 != 新需求根角色::服务
            || 安全->目标存在节点 != 自我存在
            || 服务->目标存在节点 != 自我存在
            || 安全->目标.目标形式 != 新需求目标形式::值
            || 服务->目标.目标形式 != 新需求目标形式::变化方向
            || 服务->目标.目标变化方向 != 新需求变化方向::增加
            || 服务->目标.目标值域概念节点
            || 服务->目标.目标比较关系概念节点
            || !安全->目标.目标值域概念节点
            || !安全->目标.目标比较关系概念节点
            ) {
            return 结果;
        }
        if (来源状态) {
            const auto 来源 = 事实.状态服务.获取状态(*来源状态);
            if (!来源 || 来源->被描述存在节点 != 自我存在
                || 来源->强时间.语义 != 新状态时间语义::实例绝对UTC
                || 来源->强时间.纳秒 < 0) {
                结果.状态 = 新自我需求复核状态::来源状态不存在;
                return 结果;
            }
        }
        结果.安全结果 = 需求服务.复核当前满足(安全需求);
        结果.服务结果 = 需求服务.复核当前满足(服务需求);
        if (!结果.安全结果->实际特征节点
            || !结果.服务结果->实际特征节点
            || 结果.安全结果->实际特征节点
                == 结果.服务结果->实际特征节点) {
            结果.状态 = 新自我需求复核状态::需求比较失败;
            return 结果;
        }
        const auto 安全当前 = 读取非负I64当前值(
            事实.特征服务, *结果.安全结果->实际特征节点);
        const auto 服务当前 = 读取非负I64当前值(
            事实.特征服务, *结果.服务结果->实际特征节点);
        if (!安全当前 || !服务当前
            || !是I64最大值单点概念(
                事实.特征概念服务, *安全->目标.目标值域概念节点)) {
            结果.状态 = 新自我需求复核状态::需求比较失败;
            return 结果;
        }
        constexpr auto 最大值 = (std::numeric_limits<std::int64_t>::max)();
        const auto 根结果一致 = [最大值](
            std::int64_t 当前,
            const 新需求当前满足结果& 根结果) noexcept {
            if (当前 == 最大值) {
                return 根结果.状态 == 新需求当前满足状态::已满足
                    && 根结果.准确差异 == 0;
            }
            return 根结果.状态 == 新需求当前满足状态::需增加
                && 根结果.准确差异 == 最大值 - 当前;
        };
        if (!根结果一致(*安全当前, *结果.安全结果)
            || 结果.服务结果->状态 != 新需求当前满足状态::需要执行前后比较
            || 结果.服务结果->准确差异) {
            结果.状态 = 新自我需求复核状态::需求比较失败;
            return 结果;
        }
        const auto 安全状态 = 结果.安全结果->状态;
        const auto 服务状态 = 结果.服务结果->状态;
        const auto 比较错误 = [](新需求当前满足状态 状态) noexcept {
            switch (状态) {
            case 新需求当前满足状态::已满足:
            case 新需求当前满足状态::需增加:
            case 新需求当前满足状态::需要执行前后比较:
            case 新需求当前满足状态::未满足但无有向差值:
            case 新需求当前满足状态::当前值不存在:
            case 新需求当前满足状态::目标特征尚未形成:
            case 新需求当前满足状态::资源失败:
                return false;
            default:
                return true;
            }
        };
        if (安全状态 == 新需求当前满足状态::结构不一致
            || 服务状态 == 新需求当前满足状态::结构不一致
            || 安全状态 == 新需求当前满足状态::需求不存在
            || 服务状态 == 新需求当前满足状态::需求不存在) {
            结果.状态 = 新自我需求复核状态::自我或根关系不一致;
        } else if (比较错误(安全状态) || 比较错误(服务状态)) {
            结果.状态 = 新自我需求复核状态::需求比较失败;
        } else if (安全状态 == 新需求当前满足状态::资源失败
            || 服务状态 == 新需求当前满足状态::资源失败) {
            结果.状态 = 新自我需求复核状态::资源失败;
        } else if (安全状态 == 新需求当前满足状态::当前值不存在
            || 服务状态 == 新需求当前满足状态::当前值不存在
            || 安全状态 == 新需求当前满足状态::目标特征尚未形成
            || 服务状态 == 新需求当前满足状态::目标特征尚未形成) {
            结果.状态 = 新自我需求复核状态::需求材料未就绪;
        } else {
            结果.状态 = 新自我需求复核状态::已复核;
        }
        return 结果;
    } catch (...) {
        结果.状态 = 新自我需求复核状态::资源失败;
        return 结果;
    }
}

新自我本能双根初始化结果 建立或取得自我本能双根(
    新_世界树类& 世界树服务,
    新_需求类& 需求服务,
    稳定编码 自我存在节点,
    const 新自我本能双根定义& 定义) noexcept {
    新自我本能双根初始化结果 结果;
    try {
        if (!世界树服务.已初始化()) {
            结果.状态 = 新自我本能双根初始化状态::世界树未初始化;
            return 结果;
        }
        const auto 事实 = 世界树服务.获取事实服务引用();
        if (!有效(自我存在节点)
            || !有效(定义.安全根.特征类型根概念节点)
            || !有效(定义.服务根.特征类型根概念节点)
            || !有效(定义.安全根.目标值域概念节点)
            || !有效(定义.安全根.目标比较关系概念节点)
            || 定义.安全根.初始权重 < 0
            || 定义.服务根.初始权重 < 0) {
            return 结果;
        }
        if (定义.安全根.特征类型根概念节点
                == 定义.服务根.特征类型根概念节点) {
            结果.状态 = 新自我本能双根初始化状态::双根定义冲突;
            return 结果;
        }
        const auto 自我 = 事实.存在服务.获取存在(自我存在节点);
        if (!自我) {
            结果.状态 = 新自我本能双根初始化状态::自我不存在;
            return 结果;
        }

        const auto 读取类型根 = [&](稳定编码 概念节点)
            -> std::optional<稳定编码> {
            const auto 关系 = 事实.特征概念服务.比较单特征概念(
                概念节点, 概念节点);
            if (关系.状态 != 特征概念规则状态::已完成
                || !关系.特征类型根) {
                return std::nullopt;
            }
            return 关系.特征类型根;
        };
        const auto 安全根 = 读取类型根(
            定义.安全根.特征类型根概念节点);
        const auto 服务根 = 读取类型根(
            定义.服务根.特征类型根概念节点);
        if (!安全根 || !服务根
            || *安全根 != 定义.安全根.特征类型根概念节点
            || *服务根 != 定义.服务根.特征类型根概念节点) {
            结果.状态 = 新自我本能双根初始化状态::特征类型根不合法;
            return 结果;
        }

        std::vector<稳定编码> 安全候选;
        std::vector<稳定编码> 服务候选;
        for (const auto 特征节点 : 自我->特征节点组) {
            const auto 特征 = 事实.特征服务.获取特征(特征节点);
            if (!特征) {
                结果.状态 = 新自我本能双根初始化状态::结构不一致;
                return 结果;
            }
            const auto 类型根 = 读取类型根(特征->特征概念节点);
            if (!类型根) {
                结果.状态 = 新自我本能双根初始化状态::结构不一致;
                return 结果;
            }
            if (*类型根 == *安全根) 安全候选.push_back(特征节点);
            if (*类型根 == *服务根) 服务候选.push_back(特征节点);
        }
        if (安全候选.empty()) {
            结果.状态 = 新自我本能双根初始化状态::安全特征不存在;
            return 结果;
        }
        if (服务候选.empty()) {
            结果.状态 = 新自我本能双根初始化状态::服务特征不存在;
            return 结果;
        }
        if (安全候选.size() != 1) {
            结果.状态 = 新自我本能双根初始化状态::安全特征不唯一;
            return 结果;
        }
        if (服务候选.size() != 1) {
            结果.状态 = 新自我本能双根初始化状态::服务特征不唯一;
            return 结果;
        }
        if (安全候选.front() == 服务候选.front()) {
            结果.状态 = 新自我本能双根初始化状态::双根定义冲突;
            return 结果;
        }
        if (!是I64最大值单点概念(
                事实.特征概念服务, 定义.安全根.目标值域概念节点)) {
            结果.状态 = 新自我本能双根初始化状态::根目标不是I64最大值;
            return 结果;
        }
        if (!读取非负I64当前值(事实.特征服务, 安全候选.front())
            || !读取非负I64当前值(事实.特征服务, 服务候选.front())) {
            结果.状态 = 新自我本能双根初始化状态::根当前值不合法;
            return 结果;
        }
        结果.安全实际特征节点 = 安全候选.front();
        结果.服务实际特征节点 = 服务候选.front();
        结果.需求双根结果 = 需求服务.建立或取得本能双根({
            {自我存在节点,
                {定义.安全根.特征类型根概念节点,
                    新需求目标形式::值,
                    定义.安全根.目标值域概念节点,
                    定义.安全根.目标比较关系概念节点,
                    std::nullopt},
                定义.安全根.初始权重},
            {自我存在节点,
                {定义.服务根.特征类型根概念节点,
                    新需求目标形式::变化方向,
                    std::nullopt, std::nullopt,
                    新需求变化方向::增加},
                定义.服务根.初始权重}});
        switch (结果.需求双根结果->状态) {
        case 新需求操作状态::已建立:
            结果.状态 = 新自我本能双根初始化状态::已建立;
            break;
        case 新需求操作状态::已复用:
            结果.状态 = 新自我本能双根初始化状态::已复用;
            break;
        case 新需求操作状态::双根定义冲突:
        case 新需求操作状态::权重不合法:
            结果.状态 = 新自我本能双根初始化状态::双根定义冲突;
            break;
        case 新需求操作状态::结构不一致:
        case 新需求操作状态::尚未初始化:
            结果.状态 = 新自我本能双根初始化状态::结构不一致;
            break;
        case 新需求操作状态::资源失败:
            结果.状态 = 新自我本能双根初始化状态::资源失败;
            break;
        default:
            结果.状态 = 新自我本能双根初始化状态::需求双根建立失败;
            break;
        }
        return 结果;
    } catch (...) {
        结果.状态 = 新自我本能双根初始化状态::资源失败;
        return 结果;
    }
}

