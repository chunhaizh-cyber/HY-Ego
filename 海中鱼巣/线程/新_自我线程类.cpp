bool 新自我线程初始化请求::完整() const noexcept {
    if (既有自我所在场景 && 新场景父节点) return false;
    if (自我建立请求.父存在节点
        || 自我建立请求.初始特征组.empty()
        || 初始状态时间.语义 != 新状态时间语义::实例绝对UTC
        || 初始状态时间.纳秒 < 0
        || !有效(本能双根.安全根.特征类型根概念节点)
        || !有效(本能双根.服务根.特征类型根概念节点)
        || !有效(本能双根.安全根.目标值域概念节点)
        || !有效(本能双根.服务根.目标值域概念节点)
        || !有效(本能双根.安全根.目标比较关系概念节点)
        || !有效(本能双根.服务根.目标比较关系概念节点)
        || 本能双根.安全根.初始权重 < 0
        || 本能双根.服务根.初始权重 < 0
        || 本能双根.安全根.特征类型根概念节点
            == 本能双根.服务根.特征类型根概念节点) {
        return false;
    }
    if ((既有自我所在场景 && !有效(*既有自我所在场景))
        || (新场景父节点 && !有效(*新场景父节点))) {
        return false;
    }
    for (const auto& 特征 : 自我建立请求.初始特征组) {
        if (!有效(特征.特征概念节点)) return false;
    }
    return true;
}

bool operator==(
    const 新自我线程初始化请求& 左,
    const 新自我线程初始化请求& 右) noexcept {
    return 左.既有自我所在场景 == 右.既有自我所在场景
        && 左.新场景父节点 == 右.新场景父节点
        && 左.自我建立请求.父存在节点
            == 右.自我建立请求.父存在节点
        && 左.自我建立请求.初始特征组
            == 右.自我建立请求.初始特征组
        && 左.初始状态时间 == 右.初始状态时间
        && 左.本能双根 == 右.本能双根;
}

bool 新自我线程初始化结果::成功() const noexcept {
    return (状态 == 新自我线程操作状态::已完成
            || 状态 == 新自我线程操作状态::无变化)
        && 世界树结果.has_value()
        && 世界初始化成功(世界树结果->状态)
        && 世界树结果->世界树根场景.has_value()
        && 世界树结果->根场景专属存在概念.has_value()
        && 有效(*世界树结果->世界树根场景)
        && 有效(*世界树结果->根场景专属存在概念)
        && 自我所在场景.has_value()
        && 自我存在.has_value()
        && 需求树根.has_value()
        && 安全根需求.has_value()
        && 服务根需求.has_value()
        && 方法组织根.has_value()
        && 本能双根结果.has_value()
        && 本能双根结果->成功()
        && 有效(*自我所在场景)
        && 有效(*自我存在)
        && 有效(*需求树根)
        && 有效(*安全根需求)
        && 有效(*服务根需求)
        && 有效(*方法组织根)
        && *需求树根 == 需求树根节点
        && *方法组织根 == 新方法组织根节点
        && *安全根需求
            == *本能双根结果->需求双根结果->安全根
        && *服务根需求
            == *本能双根结果->需求双根结果->服务根;
}

bool 新自我线程操作结果::成功() const noexcept {
    return 状态 == 新自我线程操作状态::已完成
        || 状态 == 新自我线程操作状态::无变化;
}

struct 新_自我线程类::实现 final {
    explicit 实现(新_世界树类& 世界树) noexcept
        : 世界树服务(&世界树) {}

    新_世界树类* 世界树服务 = nullptr;
    mutable std::mutex 状态互斥;
    std::condition_variable 状态变化;
    std::mutex 加入互斥;
    std::optional<新自我线程初始化请求> 锁定初始化请求;
    std::optional<新自我线程初始化结果> 初始化结果;
    std::thread 工作线程;
    新自我线程生命周期 生命周期 = 新自我线程生命周期::未初始化;
    bool 线程已进入 = false;
    bool 停止已请求 = false;
    bool 线程已完成 = false;
    bool 已加入 = false;

    新自我线程操作结果 操作结果(
        新自我线程操作状态 状态) const noexcept {
        return {状态, 生命周期};
    }

    void 运行() noexcept {
        try {
            std::unique_lock 锁(状态互斥);
            线程已进入 = true;
            生命周期 = 停止已请求
                ? 新自我线程生命周期::正在停止
                : 新自我线程生命周期::等待治理消息;
            状态变化.notify_all();
            状态变化.wait(锁, [this] { return 停止已请求; });
            生命周期 = 新自我线程生命周期::正在停止;
            生命周期 = 新自我线程生命周期::已停止;
            线程已完成 = true;
            状态变化.notify_all();
        } catch (...) {
            try {
                std::lock_guard 锁(状态互斥);
                生命周期 = 新自我线程生命周期::内部错误;
                线程已完成 = true;
                状态变化.notify_all();
            } catch (...) {
            }
        }
    }
};

新_自我线程类::新_自我线程类(
    新_世界树类& 世界树服务) noexcept
    : 实现_(new (std::nothrow) 实现(世界树服务)) {}

新_自我线程类::~新_自我线程类() noexcept {
    if (!实现_) return;
    (void)请求停止();
    try {
        std::lock_guard 加入锁(实现_->加入互斥);
        if (实现_->工作线程.joinable()) {
            if (实现_->工作线程.get_id() == std::this_thread::get_id()) {
                std::terminate();
            }
            实现_->工作线程.join();
        }
    } catch (...) {
        std::terminate();
    }
    try {
        std::lock_guard 所有者锁(唯一自我互斥);
        if (唯一自我线程所有者 == this) 唯一自我线程所有者 = nullptr;
    } catch (...) {
    }
}

新自我线程初始化结果 新_自我线程类::初始化(
    const 新自我线程初始化请求& 请求) noexcept {
    新自我线程初始化结果 结果;
    if (!实现_) {
        结果.状态 = 新自我线程操作状态::资源失败;
        return 结果;
    }
    if (!请求.完整()) {
        结果.状态 = 新自我线程操作状态::初始化请求不完整;
        return 结果;
    }

    try {
        std::lock_guard 所有者锁(唯一自我互斥);
        if (唯一自我线程所有者 && 唯一自我线程所有者 != this) {
            结果.状态 = 新自我线程操作状态::唯一自我冲突;
            return 结果;
        }
        {
            std::lock_guard 状态锁(实现_->状态互斥);
            if (实现_->线程已进入 || 实现_->工作线程.joinable()) {
                结果.状态 = 新自我线程操作状态::已在运行;
                return 结果;
            }
            if (实现_->锁定初始化请求
                && *实现_->锁定初始化请求 != 请求) {
                结果.状态 = 新自我线程操作状态::唯一自我冲突;
                return 结果;
            }
            if (实现_->初始化结果 && 实现_->初始化结果->成功()) {
                结果 = *实现_->初始化结果;
                结果.状态 = 新自我线程操作状态::无变化;
                return 结果;
            }
            实现_->锁定初始化请求 = 请求;
        }

        结果.世界树结果 = 实现_->世界树服务->初始化();
        if (!世界初始化成功(结果.世界树结果->状态)
            || !结果.世界树结果->世界树根场景) {
            结果.状态 = 新自我线程操作状态::世界树初始化失败;
            std::lock_guard 状态锁(实现_->状态互斥);
            实现_->初始化结果 = 结果;
            return 结果;
        }

        if (唯一自我未完成前缀) {
            if (唯一自我未完成前缀->请求 != 请求) {
                结果.状态 = 新自我线程操作状态::唯一自我冲突;
                return 结果;
            }
            const auto 场景 = 实现_->世界树服务->查询场景(
                唯一自我未完成前缀->场景节点);
            const auto 自我 = 唯一自我未完成前缀->建立结果.存在节点
                ? 实现_->世界树服务->查询存在(
                    *唯一自我未完成前缀->建立结果.存在节点)
                : std::nullopt;
            if (!场景 || !自我) {
                结果.状态 = 新自我线程操作状态::结构不一致;
            } else {
                结果.状态 = 新自我线程操作状态::自我建立失败;
                结果.自我建立结果 = 唯一自我未完成前缀->建立结果;
            }
            唯一自我线程所有者 = this;
            std::lock_guard 状态锁(实现_->状态互斥);
            实现_->初始化结果 = 结果;
            return 结果;
        }

        const bool 已有场景 = 有效(新版自我所在场景节点);
        const bool 已有自我 = 有效(新版自我节点);
        if (已有场景 != 已有自我) {
            结果.状态 = 新自我线程操作状态::结构不一致;
            std::lock_guard 状态锁(实现_->状态互斥);
            实现_->初始化结果 = 结果;
            return 结果;
        }

        稳定编码 场景节点;
        稳定编码 自我节点;
        bool 本次建立自我 = false;
        if (已有场景) {
            if ((唯一自我初始化请求 && *唯一自我初始化请求 != 请求)
                || (请求.既有自我所在场景
                    && *请求.既有自我所在场景
                        != 新版自我所在场景节点)) {
                结果.状态 = 新自我线程操作状态::唯一自我冲突;
                return 结果;
            }
            const auto 场景 = 实现_->世界树服务->查询场景(
                新版自我所在场景节点);
            const auto 自我 = 实现_->世界树服务->查询存在(新版自我节点);
            if (!场景 || !自我
                || std::find(场景->直接成员存在组.begin(),
                    场景->直接成员存在组.end(), 新版自我节点)
                    == 场景->直接成员存在组.end()
                || (请求.新场景父节点
                    && 场景->父场景节点 != 请求.新场景父节点)) {
                结果.状态 = 新自我线程操作状态::结构不一致;
                return 结果;
            }
            场景节点 = 新版自我所在场景节点;
            自我节点 = 新版自我节点;
        } else {
            bool 本次建立场景 = false;
            if (请求.既有自我所在场景) {
                if (!实现_->世界树服务->查询场景(
                        *请求.既有自我所在场景)) {
                    结果.状态 = 新自我线程操作状态::自我所在场景失败;
                    return 结果;
                }
                场景节点 = *请求.既有自我所在场景;
            } else {
                const auto 父场景 = 请求.新场景父节点
                    ? 请求.新场景父节点
                    : 结果.世界树结果->世界树根场景;
                if (!父场景 || !实现_->世界树服务->查询场景(*父场景)) {
                    结果.状态 = 新自我线程操作状态::自我所在场景失败;
                    return 结果;
                }
                结果.场景建立结果 =
                    实现_->世界树服务->建立子场景(*父场景);
                if (!场景建立成功(结果.场景建立结果->状态)
                    || !结果.场景建立结果->场景节点) {
                    结果.状态 = 新自我线程操作状态::自我所在场景失败;
                    return 结果;
                }
                场景节点 = *结果.场景建立结果->场景节点;
                本次建立场景 = true;
            }

            结果.自我建立结果 = 实现_->世界树服务->建立场景内存在(
                场景节点, 请求.自我建立请求, 请求.初始状态时间);
            if (结果.自我建立结果->状态 != 新场景操作状态::已完成
                || !结果.自我建立结果->存在节点) {
                结果.状态 = 新自我线程操作状态::自我建立失败;
                if (结果.自我建立结果->状态
                        == 新场景操作状态::存在已建立但状态挂接未完成
                    && 结果.自我建立结果->存在节点) {
                    唯一自我未完成前缀 = 未完成自我建立前缀{
                        请求, 场景节点, *结果.自我建立结果};
                    唯一自我线程所有者 = this;
                    std::lock_guard 状态锁(实现_->状态互斥);
                    实现_->初始化结果 = 结果;
                    return 结果;
                }
                if (本次建立场景 && !结果.自我建立结果->存在节点) {
                    const auto 回滚 =
                        实现_->世界树服务->删除空场景(场景节点);
                    if (回滚 != 新场景操作状态::已完成) {
                        结果.状态 = 新自我线程操作状态::结构不一致;
                    }
                }
                return 结果;
            }
            自我节点 = *结果.自我建立结果->存在节点;
            本次建立自我 = true;
        }

        const auto 场景 = 实现_->世界树服务->查询场景(场景节点);
        const auto 自我 = 实现_->世界树服务->查询存在(自我节点);
        if (!场景 || !自我
            || std::find(场景->直接成员存在组.begin(),
                场景->直接成员存在组.end(), 自我节点)
                == 场景->直接成员存在组.end()) {
            结果.状态 = 新自我线程操作状态::结构不一致;
            return 结果;
        }

        新版自我所在场景节点 = 场景节点;
        新版自我节点 = 自我节点;
        唯一自我初始化请求 = 请求;
        唯一自我线程所有者 = this;
        结果.自我所在场景 = 场景节点;
        结果.自我存在 = 自我节点;
        bool 本次建立需求树 = false;
        结果.需求树根 = 实现_->世界树服务->初始化需求树结构(
            本次建立需求树);
        if (!结果.需求树根) {
            结果.状态 = 新自我线程操作状态::需求树初始化失败;
            std::lock_guard 状态锁(实现_->状态互斥);
            实现_->初始化结果 = 结果;
            return 结果;
        }
        结果.本能双根结果 =
            实现_->世界树服务->建立或取得自我本能双根(
                自我节点, 请求.本能双根);
        if (!结果.本能双根结果->成功()
            || !结果.本能双根结果->需求双根结果
            || !结果.本能双根结果->需求双根结果->安全根
            || !结果.本能双根结果->需求双根结果->服务根) {
            结果.状态 = 新自我线程操作状态::本能双根初始化失败;
            std::lock_guard 状态锁(实现_->状态互斥);
            实现_->初始化结果 = 结果;
            return 结果;
        }
        结果.安全根需求 =
            结果.本能双根结果->需求双根结果->安全根;
        结果.服务根需求 =
            结果.本能双根结果->需求双根结果->服务根;
        bool 本次建立方法根 = false;
        结果.方法组织根 = 实现_->世界树服务->初始化方法组织根(
            本次建立方法根);
        if (!结果.方法组织根) {
            结果.状态 = 新自我线程操作状态::方法根初始化失败;
            std::lock_guard 状态锁(实现_->状态互斥);
            实现_->初始化结果 = 结果;
            return 结果;
        }
        结果.状态 = !本次建立自我
                && !本次建立需求树
                && !本次建立方法根
                && 结果.本能双根结果->状态
                    == 新世界本能双根初始化状态::已复用
            ? 新自我线程操作状态::无变化
            : 新自我线程操作状态::已完成;
        {
            std::lock_guard 状态锁(实现_->状态互斥);
            实现_->初始化结果 = 结果;
            实现_->生命周期 = 新自我线程生命周期::已初始化;
        }
        return 结果;
    } catch (...) {
        结果.状态 = 新自我线程操作状态::内部错误;
        return 结果;
    }
}

新自我线程操作结果 新_自我线程类::启动(
    std::uint64_t 等待毫秒) noexcept {
    if (!实现_) {
        return {新自我线程操作状态::资源失败,
            新自我线程生命周期::内部错误};
    }
    if (!等待毫秒) {
        return {新自我线程操作状态::入口拒绝,
            新自我线程生命周期::未初始化};
    }
    try {
        std::lock_guard 加入锁(实现_->加入互斥);
        std::unique_lock 状态锁(实现_->状态互斥);
        if (!实现_->初始化结果 || !实现_->初始化结果->成功()) {
            return 实现_->操作结果(新自我线程操作状态::尚未初始化);
        }
        if (实现_->线程已进入 && !实现_->线程已完成) {
            return 实现_->操作结果(新自我线程操作状态::已在运行);
        }
        if (实现_->线程已完成 || 实现_->工作线程.joinable()) {
            return 实现_->操作结果(新自我线程操作状态::入口拒绝);
        }
        实现_->生命周期 = 新自我线程生命周期::启动中;
        状态锁.unlock();
        try {
            实现_->工作线程 = std::thread([p = 实现_.get()] { p->运行(); });
        } catch (...) {
            状态锁.lock();
            实现_->生命周期 = 新自我线程生命周期::启动失败;
            实现_->线程已完成 = true;
            实现_->状态变化.notify_all();
            return 实现_->操作结果(新自我线程操作状态::资源失败);
        }
        状态锁.lock();
        if (!实现_->状态变化.wait_for(
            状态锁, 有界等待时长(等待毫秒), [this] {
                return 实现_->线程已进入 || 实现_->线程已完成;
            })) {
            return 实现_->操作结果(新自我线程操作状态::等待超时);
        }
        if (实现_->生命周期 == 新自我线程生命周期::内部错误) {
            return 实现_->操作结果(新自我线程操作状态::内部错误);
        }
        return 实现_->操作结果(新自我线程操作状态::已完成);
    } catch (...) {
        return {新自我线程操作状态::内部错误,
            新自我线程生命周期::内部错误};
    }
}

新自我线程操作结果 新_自我线程类::请求停止() noexcept {
    if (!实现_) {
        return {新自我线程操作状态::资源失败,
            新自我线程生命周期::内部错误};
    }
    try {
        std::lock_guard 状态锁(实现_->状态互斥);
        if (!实现_->初始化结果 || !实现_->初始化结果->成功()) {
            return 实现_->操作结果(新自我线程操作状态::尚未初始化);
        }
        if (!实现_->线程已进入
            && 实现_->生命周期 == 新自我线程生命周期::已初始化) {
            return 实现_->操作结果(新自我线程操作状态::尚未启动);
        }
        if (实现_->停止已请求 || 实现_->线程已完成) {
            return 实现_->操作结果(新自我线程操作状态::无变化);
        }
        实现_->停止已请求 = true;
        实现_->生命周期 = 新自我线程生命周期::正在停止;
        实现_->状态变化.notify_all();
        return 实现_->操作结果(新自我线程操作状态::已完成);
    } catch (...) {
        return {新自我线程操作状态::内部错误,
            新自我线程生命周期::内部错误};
    }
}

新自我线程操作结果 新_自我线程类::等待停止(
    std::uint64_t 等待毫秒) noexcept {
    if (!实现_) {
        return {新自我线程操作状态::资源失败,
            新自我线程生命周期::内部错误};
    }
    try {
        std::lock_guard 加入锁(实现_->加入互斥);
        if (实现_->工作线程.joinable()
            && 实现_->工作线程.get_id() == std::this_thread::get_id()) {
            std::lock_guard 状态锁(实现_->状态互斥);
            return 实现_->操作结果(新自我线程操作状态::不能等待自身);
        }
        std::unique_lock 状态锁(实现_->状态互斥);
        if (!实现_->初始化结果 || !实现_->初始化结果->成功()) {
            return 实现_->操作结果(新自我线程操作状态::尚未初始化);
        }
        if (!实现_->工作线程.joinable()) {
            return 实现_->操作结果(实现_->已加入
                ? 新自我线程操作状态::无变化
                : 新自我线程操作状态::尚未启动);
        }
        if (!实现_->状态变化.wait_for(
            状态锁, 有界等待时长(等待毫秒), [this] {
                return 实现_->线程已完成;
            })) {
            return 实现_->操作结果(新自我线程操作状态::等待超时);
        }
        状态锁.unlock();
        实现_->工作线程.join();
        状态锁.lock();
        实现_->已加入 = true;
        实现_->生命周期 = 新自我线程生命周期::已停止;
        return 实现_->操作结果(新自我线程操作状态::已完成);
    } catch (...) {
        return {新自我线程操作状态::内部错误,
            新自我线程生命周期::内部错误};
    }
}

新自我线程快照 新_自我线程类::读取快照() const noexcept {
    新自我线程快照 快照;
    if (!实现_) {
        快照.生命周期 = 新自我线程生命周期::内部错误;
        return 快照;
    }
    try {
        std::lock_guard 状态锁(实现_->状态互斥);
        快照.生命周期 = 实现_->生命周期;
        if (实现_->初始化结果 && 实现_->初始化结果->成功()) {
            快照.自我所在场景 = 实现_->初始化结果->自我所在场景;
            快照.自我存在 = 实现_->初始化结果->自我存在;
            快照.需求树根 = 实现_->初始化结果->需求树根;
            快照.安全根需求 = 实现_->初始化结果->安全根需求;
            快照.服务根需求 = 实现_->初始化结果->服务根需求;
            快照.方法组织根 = 实现_->初始化结果->方法组织根;
        }
        快照.线程已进入 = 实现_->线程已进入;
        快照.停止已请求 = 实现_->停止已请求;
        快照.线程已完成 = 实现_->线程已完成;
        return 快照;
    } catch (...) {
        快照.生命周期 = 新自我线程生命周期::内部错误;
        return 快照;
    }
}

