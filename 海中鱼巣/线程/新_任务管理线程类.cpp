bool 新任务筹办反馈定位::完整() const noexcept {
    return 有效(任务节点)
        && 原工作.工作编号 != 0
        && 原工作.任务节点 == 任务节点
        && (原工作.种类 == 新任务工作种类::查找方法
            || 原工作.种类 == 新任务工作种类::检查条件);
}

bool 新任务结果反馈定位::完整() const noexcept {
    return 有效(任务节点) && 有效(执行实例节点)
        && 有效(影响评估节点) && 原工作.工作编号 != 0
        && 原工作.任务节点 == 任务节点
        && 原工作.种类 == 新任务工作种类::获取本能结果
        && 原工作.本能结果获取请求
        && 原工作.本能结果获取请求->任务节点 == 任务节点
        && 原工作.本能结果获取请求->执行实例节点 == 执行实例节点;
}

