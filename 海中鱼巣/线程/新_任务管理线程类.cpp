bool 新任务筹办反馈定位::完整() const noexcept {
    return 有效(任务节点)
        && 原工作.工作编号 != 0
        && 原工作.任务节点 == 任务节点
        && (原工作.种类 == 新任务工作种类::查找方法
            || 原工作.种类 == 新任务工作种类::检查条件);
}

