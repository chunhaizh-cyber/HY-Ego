struct 新_任务工作线程类::实现 final {
    实现(新_任务类& 任务, std::function<void()> 通知) noexcept
        : 任务服务(&任务), 完成通知(std::move(通知)) {}

    新_任务类* 任务服务;
    新服务值结算确认接口* 最终服务消费端口 = nullptr;
    std::function<void()> 完成通知;
    mutable std::mutex 互斥;
    std::mutex 加入互斥;
    std::condition_variable 变化;
    std::array<std::thread, 新任务工作并发上限> 线程组;
    新任务工作运行配置 配置;
    新任务工作生命周期 生命周期 = 新任务工作生命周期::未启动;
    bool 创建已尝试 = false;
    std::uint64_t 已创建线程数 = 0;
    std::uint64_t 已进入线程数 = 0;
    std::uint64_t 已退出线程数 = 0;
    std::uint64_t 执行中工作数 = 0;
    bool 创建完成 = false;
    bool 停止 = false;
    std::stop_source 停止源;
    bool 已完成 = false;
    bool 已加入 = false;
    bool 启动失败 = false;
    bool 内部错误发生 = false;

    struct 工作项 final {
        新任务工作请求 请求;
        // 在接收阶段完成原请求复制，停止/异常收束不再依赖一次分配成功。
        新任务工作处理结果 预置结果;
        std::optional<std::promise<新任务工作处理结果>> 承诺{std::in_place};
        std::shared_future<新任务工作处理结果> 结果 = 承诺->get_future().share();
        bool 已开始 = false;
        bool 已结束 = false;
    };
    std::vector<std::shared_ptr<工作项>> 活动;

    新任务工作操作结果 操作结果(新任务工作操作状态 状态) const noexcept {
        return {状态, 生命周期};
    }

    bool 启动就绪已加锁() const noexcept {
        return 创建完成 && 已创建线程数 == 新任务工作并发上限
            && 已进入线程数 == 新任务工作并发上限 && !停止 && !已完成;
    }

    void 刷新生命周期已加锁() noexcept {
        if (创建完成 && 已退出线程数 == 已创建线程数) {
            已完成 = true;
            生命周期 = 启动失败 ? 新任务工作生命周期::启动失败
                : 内部错误发生 ? 新任务工作生命周期::内部错误
                : 新任务工作生命周期::已停止;
        } else if (停止) 生命周期 = 新任务工作生命周期::停止中;
        else if (!创建完成 || 已进入线程数 != 新任务工作并发上限)
            生命周期 = 新任务工作生命周期::启动中;
        else 生命周期 = 执行中工作数 ? 新任务工作生命周期::处理工作
            : 新任务工作生命周期::等待工作;
    }

    // 必须持加入互斥，不能持请求表互斥；整个池join完才允许释放全局owner。
    bool 是工作线程自身() const noexcept {
        return std::any_of(线程组.begin(), 线程组.end(), [](const auto& 线程) {
            return 线程.joinable() && 线程.get_id() == std::this_thread::get_id();
        });
    }

    void 加入全部线程() {
        if (是工作线程自身()) std::terminate();
        for (auto& 线程 : 线程组) if (线程.joinable()) 线程.join();
        std::lock_guard 锁(互斥);
        已加入 = true;
    }

    void 发出完成通知() noexcept {
        if (!完成通知) return;
        try { 完成通知(); }
        catch (...) {}
    }

    void 发布结果已加锁(工作项& 项, 新任务工作处理结果&& 结果) noexcept {
        // 只有领取本项的线程、或停止时的未开始项取消者可以写promise。
        if (项.已结束) {
            内部错误发生 = true;
            停止 = true;
            return;
        }
        try { 项.承诺->set_value(std::move(结果)); }
        catch (...) {
            // 万一promise结构异常，让future以broken_promise就绪，不能永远悬空。
            项.承诺.reset();
            内部错误发生 = true;
            停止 = true;
        }
        项.已结束 = true;
        if (项.已开始) --执行中工作数;
    }

    bool 取消未开始工作已加锁() noexcept {
        bool 有取消 = false;
        for (const auto& 项 : 活动) {
            if (项->已开始 || 项->已结束) continue;
            auto 结果 = std::move(项->预置结果);
            结果.状态 = 新任务工作处理状态::停止取消;
            if(项->请求.种类==新任务工作种类::筹办前置语言输入&&项->请求.前置语言输入) {
                结果.前置语言输入=新任务前置语言输入结果{*项->请求.前置语言输入,新前置语言读取状态::停止取消,{}};
                结果.状态=新任务工作处理状态::前置语言输入已返回;
            }
            发布结果已加锁(*项, std::move(结果));
            有取消 = true;
        }
        return 有取消;
    }

    // DEP-READY-WAKE A：结果检测是结构依赖未就绪的消费边界。工作池运行中进工程诊断链；
    // 已请求停止返回true，由调用方按停止取消返回，不弹窗、不轮询。
    bool 结构依赖未就绪已停止(const wchar_t* 入口, int 状态值, const 新任务结果检测请求& 请求) const noexcept {
        if (停止源.get_token().stop_requested()) return true;
        char 说明[128] = {};
        (void)std::snprintf(说明, sizeof(说明), "入口状态值=%d；任务=%llu；执行=%llu", 状态值,
            static_cast<unsigned long long>(请求.任务节点.值), static_cast<unsigned long long>(请求.执行实例节点.值));
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, 入口, L"运行期结构依赖未就绪", 说明);
    }

    // 返回true表示停机期间遇结构依赖未就绪，调用方按停止取消返回。
    bool 处理结果检测(const 新任务结果检测请求& 请求, 新任务结果检测结果& 结果) {
        try {
            结果.原请求 = 请求;
            const auto 读取并分类 = [&]() {
                结果.正式读回 = 任务服务->读回任务执行(请求.任务节点, 请求.执行实例节点);
                switch (结果.正式读回.状态) {
                case 新任务治理执行读回状态::已读回等待观察:
                case 新任务治理执行读回状态::已读回等待评估:
                    结果.状态 = 新任务结果检测状态::等待结果材料;
                    return false;
                case 新任务治理执行读回状态::已读回影响评估:
                    if (!结果.正式读回.任务 || !结果.正式读回.执行 || !结果.正式读回.影响评估
                        || 结果.正式读回.任务->节点 != 请求.任务节点
                        || 结果.正式读回.执行->节点 != 请求.执行实例节点)
                        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"完整影响评估读回身份不符");
                    结果.状态 = 新任务结果检测状态::已完成影响评估;
                    return true;
                case 新任务治理执行读回状态::执行不在当前位:
                    结果.状态 = 新任务结果检测状态::定位已变化;
                    结果.材料核验.reset();
                    结果.结果获取.reset();
                    return true;
                case 新任务治理执行读回状态::任务或执行不存在:
                    结果.状态 = 新任务结果检测状态::正式记录不存在;
                    结果.材料核验.reset();
                    结果.结果获取.reset();
                    return true;
                case 新任务治理执行读回状态::结构不一致:
                case 新任务治理执行读回状态::资源失败:
                    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"正式任务执行读取工程故障");
                }
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"未知正式读回状态");
            };
            if (读取并分类()) return false;
            std::vector<稳定编码> 状态组;
            if (结果.正式读回.状态 == 新任务治理执行读回状态::已读回等待观察) {
                结果.材料核验 = 任务服务->查找任务结果材料(请求.任务节点, 请求.执行实例节点);
                switch (结果.材料核验->状态) {
                case 新任务治理结果材料核验状态::与本次执行无关:
                case 新任务治理结果材料核验状态::已接受但仍不足:
                case 新任务治理结果材料核验状态::任务或执行已变化:
                    (void)读取并分类();
                    return false;
                case 新任务治理结果材料核验状态::材料已足够:
                    状态组 = 结果.材料核验->已接受状态节点组;
                    break;
                case 新任务治理结果材料核验状态::结构依赖未就绪:
                    (void)结构依赖未就绪已停止(L"处理结果检测/查找任务结果材料",
                        static_cast<int>(结果.材料核验->状态), 请求);
                    return true;
                case 新任务治理结果材料核验状态::结构不一致:
                case 新任务治理结果材料核验状态::资源失败:
                    工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"正式结果材料读取工程故障");
                }
            } else {
                状态组 = 结果.正式读回.执行->实际状态节点组;
            }
            // CONV-INSTINCT 6.3：先天被动结果以需求owner复核作为材料，正式状态组为空。
            const bool 被动结果 = 结果.正式读回.执行 && 结果.正式读回.执行->结果获取方案.被动达成需求节点.has_value();
            if (状态组.empty() && !被动结果)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"足够材料或已结束执行缺少正式状态");
            if (!状态组.empty() && 被动结果)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"被动结果执行不得携带正式状态");
            结果.结果获取 = 任务服务->获取任务本能结果({请求.任务节点, 请求.执行实例节点, std::move(状态组)});
            switch (结果.结果获取->状态) {
            case 新任务治理结果获取状态::已完成影响评估:
                // 评估完成后重读遇并发推进（定位已变化/正式记录不存在）属正常变化；
                // 只有重读仍回退为等待结果材料才是正式读回不一致。
                (void)读取并分类();
                if (结果.状态 == 新任务结果检测状态::已完成影响评估
                    || 结果.状态 == 新任务结果检测状态::定位已变化
                    || 结果.状态 == 新任务结果检测状态::正式记录不存在)
                    return false;
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"影响评估完成后正式读回不一致");
            case 新任务治理结果获取状态::等待结果材料:
            case 新任务治理结果获取状态::任务状态已变化:
                (void)读取并分类();
                return false;
            case 新任务治理结果获取状态::结构依赖未就绪:
                (void)结构依赖未就绪已停止(L"处理结果检测/获取任务本能结果",
                    static_cast<int>(结果.结果获取->状态), 请求);
                return true;
            case 新任务治理结果获取状态::执行结束失败:
            case 新任务治理结果获取状态::影响评估失败:
            case 新任务治理结果获取状态::结构不一致:
            case 新任务治理结果获取状态::资源失败: {
                // 诊断：如实给出结果获取、执行结束与影响评估的具体状态值。
                const auto& 取 = *结果.结果获取;
                const std::string 说明 = "结果获取状态=" + std::to_string(static_cast<int>(取.状态))
                    + "；执行结束状态=" + (取.执行结束状态 ? std::to_string(static_cast<int>(*取.执行结束状态)) : std::string("无"))
                    + "；影响评估状态=" + (取.影响评估 ? std::to_string(static_cast<int>(取.影响评估->状态)) : std::string("无"))
                    + "；任务=" + std::to_string(请求.任务节点.值) + "；执行=" + std::to_string(请求.执行实例节点.值);
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"结果获取或评估工程故障", 说明.c_str());
            }
            }
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"未知结果获取状态");
        } catch (...) {
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理结果检测", L"结果检测抛出工程异常");
        }
    }

    void 处理工作(const std::shared_ptr<工作项>& 项, 新任务工作处理结果& 结果) {
#ifdef HY_EGO_DEBUG_LOG_WORKER_EXECUTION
        工作执行观察 观察(项->请求, 停止源.get_token());
#endif
        if (项->请求.种类 == 新任务工作种类::续接词典执行) {
            if (!项->请求.词典续接) throw std::logic_error("dictionary continuation locator missing");
            新_本能函数管理类::本能停止守卫 停止守卫(停止源.get_token());
            结果.词典推进 = 任务服务->继续任务词典执行(*项->请求.词典续接);
            if (结果.词典推进->状态 != 新任务词典推进状态::已返回正常处置
                || !结果.词典推进->正常处置)
                throw std::logic_error("dictionary continuation engineering failure");
            结果.状态 = 新任务工作处理状态::词典推进已返回;
            return;
        }
        if(项->请求.种类==新任务工作种类::筹办前置语言输入) {
            if(!项->请求.前置语言输入)throw std::logic_error("preunderstanding worker request missing");
            结果.前置语言输入=任务服务->筹办前置语言输入材料(*项->请求.前置语言输入,停止源.get_token());
            结果.状态=新任务工作处理状态::前置语言输入已返回;return;
        }
        if (项->请求.种类 == 新任务工作种类::执行任务贡献治理) {
            if (!最终服务消费端口 || !项->请求.贡献来源)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"贡献治理工作", L"端口或完成定位缺失");
            结果.贡献治理 = 最终服务消费端口->执行贡献治理工作(*项->请求.贡献来源);
            结果.状态 = 新任务工作处理状态::任务贡献治理已返回;
            return;
        }
        if (项->请求.种类 == 新任务工作种类::执行最终服务消费) {
            if (!最终服务消费端口 || !项->请求.最终来源)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理最终服务消费", L"最终消费端口或正式定位缺失");
            // 处理工作在池互斥外执行；同一十槽池承载本项，不另建线程。
            结果.最终消费 = 最终服务消费端口->执行最终来源工作(*项->请求.最终来源);
            if (结果.最终消费->来源 != *项->请求.最终来源)
                工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"处理最终服务消费", L"返回来源与正式请求不一致");
            结果.状态 = 新任务工作处理状态::最终服务消费已返回;
        } else if (项->请求.种类 == 新任务工作种类::检测本能结果 && 项->请求.本能结果检测请求) {
            结果.本能结果检测.emplace();
            if (处理结果检测(*项->请求.本能结果检测请求, *结果.本能结果检测)) {
                结果.本能结果检测.reset();
                结果.状态 = 新任务工作处理状态::停止取消;
                return;
            }
            结果.状态 = 新任务工作处理状态::本能结果检测已返回;
        } else if (项->请求.种类 == 新任务工作种类::读取任务调度材料) {
            结果.调度材料 = 任务服务->读取任务调度材料();
            结果.状态 = 新任务工作处理状态::调度材料已返回;
        } else if (项->请求.种类 == 新任务工作种类::查找方法) {
#ifdef HY_EGO_DEBUG_LOG_TASK_METHOD_RECALL
            记录召回诊断(项->请求, nullptr);
#endif
            结果.方法召回 = 任务服务->查询任务方法候选并发布(项->请求.任务节点, 项->请求.筹办排除);
            结果.复合目标提议=结果.方法召回->复合目标提议;
            switch (结果.方法召回->状态) {
            case 新任务治理方法召回状态::仅材料治理:结果.状态=新任务工作处理状态::组织能力暂不支持;break;
            case 新任务治理方法召回状态::未执行目标已满足:
                结果.执行前目标收束=结果.方法召回->执行前目标收束;
                结果.状态=新任务工作处理状态::未执行目标已满足;break;
            case 新任务治理方法召回状态::复合目标需自我确认:
                结果.状态=新任务工作处理状态::复合目标需自我确认;break;
            case 新任务治理方法召回状态::内容结果定位未支持:
                结果.状态=新任务工作处理状态::内容结果定位未支持;break;
            case 新任务治理方法召回状态::已发布有候选:
                结果.状态 = 新任务工作处理状态::已发布有候选; break;
            case 新任务治理方法召回状态::已发布完整无候选:
                结果.状态 = 新任务工作处理状态::已发布完整无候选; break;
            case 新任务治理方法召回状态::任务状态已变化:
                结果.状态 = 新任务工作处理状态::任务状态已变化; break;
            case 新任务治理方法召回状态::尚未初始化:
                结果.状态 = 新任务工作处理状态::服务未就绪; break;
            case 新任务治理方法召回状态::方法查询未完成:
                结果.状态 = 新任务工作处理状态::查找未完成; break;
            case 新任务治理方法召回状态::候选发布未完成:
                结果.状态 = 新任务工作处理状态::候选发布未完成; break;
            case 新任务治理方法召回状态::结构依赖未就绪:
                结果.状态 = 新任务工作处理状态::结构依赖未就绪; break;
            case 新任务治理方法召回状态::任务不存在:
            case 新任务治理方法召回状态::需求不存在:
            case 新任务治理方法召回状态::结构不一致:
            case 新任务治理方法召回状态::资源失败:
                结果.状态 = 新任务工作处理状态::需核查; break;
            }
#ifdef HY_EGO_DEBUG_LOG_TASK_METHOD_RECALL
            记录召回诊断(项->请求, &结果);
#endif
        } else if (项->请求.种类 == 新任务工作种类::检查条件) {
            结果.执行组织交付 = 任务服务->交付候选方法执行组织(项->请求.任务节点);
            const auto 交付 = 结果.执行组织交付->状态;
            if(交付==新任务执行组织状态::定义前提已变化) {
                结果.状态=新任务工作处理状态::执行组织定义前提已变化;
                return;
            }
            if (交付 == 新任务执行组织状态::增补结构暂不支持) {
                结果.状态 = 新任务工作处理状态::组织能力暂不支持;
                return; // 明确能力边界；不得继续用旧组织产生条件或子需求。
            }
            if (交付 == 新任务执行组织状态::已建立 || 交付 == 新任务执行组织状态::已增补
                || 交付 == 新任务执行组织状态::精确重复 || 交付 == 新任务执行组织状态::已读取) {
                新_本能函数管理类::本能停止守卫 停止守卫(停止源.get_token());
                const auto 落实 = 任务服务->落实任务词条材料特征(项->请求.任务节点);
                if (落实.状态 == 新任务词条特征落实状态::已停止 || 停止源.stop_requested()) {
                    结果.状态 = 新任务工作处理状态::停止取消;
                    return;
                }
                switch (落实.状态) {
                case 新任务词条特征落实状态::已建立:
                case 新任务词条特征落实状态::已复用:
                case 新任务词条特征落实状态::不涉及:
                case 新任务词条特征落实状态::条件未具备:
                    结果.条件筹办 = 任务服务->筹办任务条件和参数(项->请求.任务节点);
                    break;
                case 新任务词条特征落实状态::任务已退出:
                case 新任务词条特征落实状态::未装配:
                case 新任务词条特征落实状态::资源失败:
                    结果.条件筹办.emplace();
                    结果.条件筹办->任务节点 = 项->请求.任务节点;
                    结果.条件筹办->状态 = 落实.状态 == 新任务词条特征落实状态::任务已退出
                        ? 新任务治理条件筹办状态::任务状态已变化
                        : 落实.状态 == 新任务词条特征落实状态::未装配
                            ? 新任务治理条件筹办状态::尚未初始化 : 新任务治理条件筹办状态::资源失败;
                    break;
                case 新任务词条特征落实状态::已停止:
                    结果.状态 = 新任务工作处理状态::停止取消;
                    return;
                }
            } else {
                结果.条件筹办.emplace();
                结果.条件筹办->任务节点 = 项->请求.任务节点;
                结果.条件筹办->状态 = 交付 == 新任务执行组织状态::任务状态不允许
                    ? 新任务治理条件筹办状态::任务状态已变化
                    : 交付 == 新任务执行组织状态::尚未初始化
                        ? 新任务治理条件筹办状态::尚未初始化
                        : 新任务治理条件筹办状态::结构不一致;
            }
            switch (结果.条件筹办->状态) {
            case 新任务治理条件筹办状态::仅材料治理:
                结果.状态=新任务工作处理状态::组织能力暂不支持;break;
            case 新任务治理条件筹办状态::已完成:
                结果.状态 = 新任务工作处理状态::已完成条件筹办;
                结果.条件子需求提议 = 任务服务->提议任务条件子需求(项->请求.任务节点);
#ifdef HY_EGO_DEBUG_LOG_PARAM_BINDING
                try {
                    const auto& 提 = *结果.条件子需求提议;
                    std::wostringstream 文;
                    文 << L"任务=" << 项->请求.任务节点.值 << L" 提议状态=" << static_cast<int>(提.状态)
                       << L" 子需求项=" << 提.子需求项组.size() << L" 已知项=" << 提.已知条件项组.size()
                       << L" 方法=" << 提.方法节点.值 << L" 配对=" << 提.配对节点.值
                       << L" 未解析=" << (提.分解依据 ? 提.分解依据->未解析条件序号组.size() : 0);
                    (void)调试日志<调试切片::PARAM_BINDING>(L"条件子需求", L"提议结果", 文.str());
                } catch (...) {}
#endif
                break;
            case 新任务治理条件筹办状态::任务状态已变化:
                结果.状态 = 新任务工作处理状态::任务状态已变化;
                break;
            case 新任务治理条件筹办状态::尚未初始化:
                结果.状态 = 新任务工作处理状态::服务未就绪;
                break;
            case 新任务治理条件筹办状态::结构依赖未就绪:
                结果.状态 = 新任务工作处理状态::结构依赖未就绪;
                break;
            case 新任务治理条件筹办状态::任务不存在:
            case 新任务治理条件筹办状态::候选材料不存在:
            case 新任务治理条件筹办状态::结构不一致:
            case 新任务治理条件筹办状态::资源失败:
                结果.状态 = 新任务工作处理状态::需核查;
#ifdef HY_EGO_DEBUG_LOG_PARAM_BINDING
                try { std::wostringstream 文; 文 << L"检查条件需核查 任务=" << 项->请求.任务节点.值
                    << L" 组织交付=" << static_cast<int>(交付) << L" 条件筹办=" << static_cast<int>(结果.条件筹办->状态);
                    (void)调试日志<调试切片::PARAM_BINDING>(L"任务工作", L"检查条件", 文.str()); } catch (...) {}
#endif
                break;
            }
        } else if (项->请求.种类 == 新任务工作种类::执行本能动作 && 项->请求.本能执行请求) {
            新_本能函数管理类::本能停止守卫 停止守卫(停止源.get_token());
            结果.本能执行 = 任务服务->执行任务本能方法(*项->请求.本能执行请求);
            if(结果.本能执行->状态==新任务治理本能执行状态::仅材料治理) {
                结果.状态=新任务工作处理状态::组织能力暂不支持;
            } else if(结果.本能执行->状态==新任务治理本能执行状态::未执行目标已满足){
                结果.执行前目标收束=结果.本能执行->执行前目标收束;
                结果.状态=新任务工作处理状态::未执行目标已满足;
            } else 结果.状态 = 结果.本能执行->状态 == 新任务治理本能执行状态::任务状态已变化
                ? 新任务工作处理状态::任务状态已变化 : 新任务工作处理状态::本能动作已返回;
        } else if (项->请求.种类 == 新任务工作种类::获取本能结果 && 项->请求.本能结果获取请求) {
            结果.本能结果获取 = 任务服务->获取任务本能结果(*项->请求.本能结果获取请求);
            结果.状态 = 结果.本能结果获取->状态 == 新任务治理结果获取状态::任务状态已变化
                ? 新任务工作处理状态::任务状态已变化 : 新任务工作处理状态::本能结果获取已返回;
        } else {
            结果.状态 = 新任务工作处理状态::内部错误;
        }
    }

    void 运行() noexcept {
        当前工作池 = this;
        std::shared_ptr<工作项> 当前;
        新任务工作处理结果 返回结果;
        bool 异常退出 = false;
        try {
            std::unique_lock 锁(互斥);
            ++已进入线程数;
            刷新生命周期已加锁();
            变化.notify_all();
            // 未形成完整线程池前不消费工作，也不开启提交入口。
            变化.wait(锁, [this] { return 停止 || 启动就绪已加锁(); });
            while (!停止) {
                const auto 位置 = std::find_if(活动.begin(), 活动.end(),
                    [](const auto& 项) { return !项->已开始 && !项->已结束; });
                if (位置 == 活动.end()) {
                    刷新生命周期已加锁();
                    变化.wait(锁, [this] {
                        return 停止 || std::any_of(活动.begin(), 活动.end(),
                            [](const auto& 项) { return !项->已开始 && !项->已结束; });
                    });
                    continue;
                }
                当前 = *位置;
                返回结果 = std::move(当前->预置结果);
                当前->已开始 = true;
                ++执行中工作数;
                刷新生命周期已加锁();
                锁.unlock();

                处理工作(当前, 返回结果);

                锁.lock();
                发布结果已加锁(*当前, std::move(返回结果));
                当前.reset();
                刷新生命周期已加锁();
                变化.notify_all();
                锁.unlock();
                发出完成通知();
                锁.lock();
            }
        } catch (...) { 异常退出 = true; }
        // 正常停止和promise发布异常置停均唤醒其余正在执行的本能。
        // 此处已退出调度锁作用域，stop回调不在工作池锁内执行。
        停止源.request_stop();
        try {
            bool 需要通知 = false;
            {
                std::lock_guard 锁(互斥);
                if (异常退出) {
                    内部错误发生 = true;
                    停止 = true;
                    if (当前 && !当前->已结束) {
                        返回结果.状态 = 新任务工作处理状态::内部错误;
                        发布结果已加锁(*当前, std::move(返回结果));
                        需要通知 = true;
                    }
                }
                // 其它正在运行的项由它们自己的线程完成；绝不提前兑现其future。
                需要通知 = 取消未开始工作已加锁() || 需要通知;
                变化.notify_all();
            }
            if (需要通知) 发出完成通知();
            {
                std::lock_guard 锁(互斥);
                ++已退出线程数;
                刷新生命周期已加锁();
                变化.notify_all();
            }
            当前工作池 = nullptr;
        } catch (...) { std::terminate(); }
    }
};

新_任务工作线程类::新_任务工作线程类(
    新_任务类& 任务服务, std::function<void()> 完成通知) noexcept
    : 实现_(new (std::nothrow) 实现(任务服务, std::move(完成通知))) {}

新_任务工作线程类::~新_任务工作线程类() noexcept {
    if (!实现_) return;
    if (当前工作池 == 实现_.get()) std::terminate();
    (void)请求停止();
    try {
        std::lock_guard 加入锁(实现_->加入互斥);
        实现_->加入全部线程();
        std::lock_guard 所有者锁(工作所有者互斥);
        if (工作所有者 == this) 工作所有者 = nullptr;
    } catch (...) { std::terminate(); }
}

新任务工作操作结果 新_任务工作线程类::启动(
    const 新任务工作运行配置& 配置, std::uint64_t 等待毫秒) noexcept {
    if (!实现_) return {新任务工作操作状态::资源失败,
        新任务工作生命周期::内部错误};
    try {
        // 完成通知中的重入不能等待一个正在join本工作线程的调用者。
        if (当前工作池 == 实现_.get()) {
            std::lock_guard 锁(实现_->互斥);
            return 实现_->操作结果(等待毫秒 && 实现_->启动就绪已加锁()
                    && 实现_->配置 == 配置
                ? 新任务工作操作状态::已在运行
                : 新任务工作操作状态::入口拒绝);
        }
        std::lock_guard 加入锁(实现_->加入互斥);
        std::unique_lock 锁(实现_->互斥);
        if (!配置.邮箱容量 || 配置.邮箱容量 > 实现_->活动.max_size()
            || !等待毫秒) return 实现_->操作结果(新任务工作操作状态::入口拒绝);
        if (实现_->创建已尝试) return 实现_->操作结果(
            实现_->启动就绪已加锁()
                && 实现_->配置 == 配置
                ? 新任务工作操作状态::已在运行
                : 新任务工作操作状态::入口拒绝);
        {
            std::lock_guard 所有者锁(工作所有者互斥);
            if (工作所有者 && 工作所有者 != this) {
                return 实现_->操作结果(新任务工作操作状态::所有者冲突);
            }
            工作所有者 = this;
        }
        实现_->创建已尝试 = true;
        实现_->配置 = 配置;
        实现_->生命周期 = 新任务工作生命周期::启动中;
        新任务工作操作状态 失败状态 = 新任务工作操作状态::已完成;
        try {
            for (auto& 线程 : 实现_->线程组) {
                线程 = std::thread([p = 实现_.get()] { p->运行(); });
                ++实现_->已创建线程数;
            }
        } catch (...) { 失败状态 = 新任务工作操作状态::资源失败; }
        实现_->创建完成 = true;
        if (失败状态 != 新任务工作操作状态::已完成) {
            实现_->启动失败 = true;
            实现_->停止 = true;
        }
        实现_->刷新生命周期已加锁();
        实现_->变化.notify_all();
        if (失败状态 == 新任务工作操作状态::已完成) {
            try {
                if (!实现_->变化.wait_for(锁, 工作等待时长(等待毫秒), [this] {
                        return 实现_->启动就绪已加锁() || 实现_->停止 || 实现_->已完成;
                    })) 失败状态 = 新任务工作操作状态::等待超时;
                else if (!实现_->启动就绪已加锁()) 失败状态 = 新任务工作操作状态::内部错误;
            } catch (...) { 失败状态 = 新任务工作操作状态::内部错误; }
        }
        if (失败状态 == 新任务工作操作状态::已完成)
            return 实现_->操作结果(新任务工作操作状态::已完成);

        // 半池/超时不以仍存活的后台线程返回。创建门关闭接收，join时释放请求锁。
        实现_->启动失败 = true;
        实现_->停止 = true;
        实现_->刷新生命周期已加锁();
        实现_->变化.notify_all();
        锁.unlock();
        实现_->加入全部线程();
        {
            std::lock_guard 所有者锁(工作所有者互斥);
            if (工作所有者 == this) 工作所有者 = nullptr;
        }
        锁.lock();
        return 实现_->操作结果(失败状态);
    } catch (...) {
        return {新任务工作操作状态::内部错误,
            新任务工作生命周期::内部错误};
    }
}

新任务工作操作状态 新_任务工作线程类::绑定最终服务消费端口(
    新服务值结算确认接口& 端口) noexcept {
    if (!实现_) return 新任务工作操作状态::资源失败;
    try {
        std::lock_guard 锁(实现_->互斥);
        if (实现_->最终服务消费端口 == &端口) return 新任务工作操作状态::无变化;
        if (实现_->创建已尝试 || 实现_->最终服务消费端口)
            return 新任务工作操作状态::所有者冲突;
        实现_->最终服务消费端口 = &端口;
        return 新任务工作操作状态::已完成;
    } catch (...) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"绑定最终服务消费端口", L"端口装配工程异常");
    }
}

新任务工作接收结果 新_任务工作线程类::提交工作(
    const 新任务工作请求& 请求) noexcept {
    新任务工作接收结果 结果;
    if (!实现_) {
        结果.状态 = 新任务工作接收状态::资源失败;
        return 结果;
    }
    const bool 是动作 = 请求.种类 == 新任务工作种类::执行本能动作;
    const bool 是结果 = 请求.种类 == 新任务工作种类::获取本能结果;
    const bool 是扫描 = 请求.种类 == 新任务工作种类::读取任务调度材料;
    const bool 是检测 = 请求.种类 == 新任务工作种类::检测本能结果;
    const bool 是最终消费 = 请求.种类 == 新任务工作种类::执行最终服务消费;
    const bool 是贡献治理 = 请求.种类 == 新任务工作种类::执行任务贡献治理;
    const bool 是前置材料=请求.种类==新任务工作种类::筹办前置语言输入;
    const bool 是词典续接 = 请求.种类 == 新任务工作种类::续接词典执行;
    const bool 种类有效 = 请求.种类 == 新任务工作种类::查找方法
        || 请求.种类 == 新任务工作种类::检查条件 || 是动作 || 是结果 || 是扫描 || 是检测 || 是最终消费 || 是贡献治理 || 是前置材料 || 是词典续接;
    if (!请求.工作编号 || !种类有效 || (是扫描 ? 有效(请求.任务节点) : !有效(请求.任务节点))
        || (是动作 && (!请求.本能执行请求
            || !请求.本能执行请求->完整()
            || 请求.本能执行请求->任务节点 != 请求.任务节点))
        || (是结果 && (!请求.本能结果获取请求
            || !请求.本能结果获取请求->完整()
            || 请求.本能结果获取请求->任务节点 != 请求.任务节点))
        || (!是动作 && 请求.本能执行请求)
        || (!是结果 && 请求.本能结果获取请求)
        || (是检测 && (!请求.本能结果检测请求
            || !有效(请求.本能结果检测请求->任务节点)
            || !有效(请求.本能结果检测请求->执行实例节点)
            || 请求.本能结果检测请求->任务节点 != 请求.任务节点))
        || (!是检测 && 请求.本能结果检测请求)
        || (是最终消费 && (!请求.最终来源
            || 请求.最终来源->来源任务节点 != 请求.任务节点
            || !有效(请求.最终来源->完成结算节点) || !有效(请求.最终来源->直接接收节点)))
        || (!是最终消费 && 请求.最终来源)
        || (是贡献治理 && (!请求.贡献来源 || 请求.贡献来源->任务节点 != 请求.任务节点
            || !有效(请求.贡献来源->执行实例节点) || !有效(请求.贡献来源->影响评估节点)))
        || (!是贡献治理 && 请求.贡献来源)
        ||(是前置材料&&(!请求.前置语言输入||请求.前置语言输入->父任务节点!=请求.任务节点))
        ||(!是前置材料&&请求.前置语言输入)
        || (是词典续接 && (!请求.词典续接 || 请求.词典续接->任务节点 != 请求.任务节点
            || !有效(请求.词典续接->执行实例节点)))
        || (!是词典续接 && 请求.词典续接)) return 结果;
    try {
        std::lock_guard 锁(实现_->互斥);
        if ((是最终消费 || 是贡献治理) && !实现_->最终服务消费端口) return 结果;
        if (实现_->停止 || 实现_->已完成) {
            结果.状态 = 新任务工作接收状态::已停止接收;
            return 结果;
        }
        if (!实现_->启动就绪已加锁()) {
            结果.状态 = 新任务工作接收状态::尚未启动;
            return 结果;
        }
        for (const auto& 项 : 实现_->活动) {
            if (项->请求.工作编号 == 请求.工作编号) {
                if (项->请求 == 请求) {
                    结果.状态 = 新任务工作接收状态::精确重复;
                    结果.处理结果 = 项->结果;
                } else {
                    结果.状态 = 新任务工作接收状态::身份冲突;
                }
                return 结果;
            }
        }
        for (const auto& 项 : 实现_->活动) {
            if (项->请求.任务节点 == 请求.任务节点) {
                结果.状态 = 新任务工作接收状态::任务已占用;
                return 结果;
            }
        }
        if (实现_->活动.size() >= 实现_->配置.邮箱容量
            || static_cast<std::uint64_t>(std::count_if(实现_->活动.begin(), 实现_->活动.end(),
                [](const auto& 项) { return !项->已结束; })) >= 新任务工作并发上限) {
            结果.状态 = 新任务工作接收状态::邮箱已满;
            return 结果;
        }
        const auto 项 = std::make_shared<实现::工作项>();
        项->请求 = 请求;
        项->预置结果.原请求 = 请求;
        实现_->活动.push_back(项);
        结果.状态 = 新任务工作接收状态::已接收;
        结果.处理结果 = 项->结果;
        实现_->变化.notify_all();
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 新任务工作接收状态::资源失败;
    } catch (...) {
        结果.状态 = 新任务工作接收状态::内部错误;
    }
    return 结果;
}

新任务工作操作状态 新_任务工作线程类::确认结果已接收(
    std::uint64_t 工作编号, 稳定编码 任务节点) noexcept {
    if (!实现_ || !工作编号) {
        return 新任务工作操作状态::入口拒绝;
    }
    try {
        std::lock_guard 锁(实现_->互斥);
        if (!有效(任务节点)) {
            const auto 同号 = std::find_if(实现_->活动.begin(), 实现_->活动.end(),
                [&](const auto& 项) { return 项->请求.工作编号 == 工作编号; });
            if (同号 != 实现_->活动.end()
                && (*同号)->请求.种类 != 新任务工作种类::读取任务调度材料)
                return 新任务工作操作状态::入口拒绝;
        }
        const auto 位置 = std::find_if(实现_->活动.begin(), 实现_->活动.end(),
            [&](const auto& 项) {
                return 项->请求.工作编号 == 工作编号
                    && 项->请求.任务节点 == 任务节点;
            });
        if (位置 == 实现_->活动.end()) return 新任务工作操作状态::无变化;
        if (!(*位置)->已结束) return 新任务工作操作状态::入口拒绝;
        实现_->活动.erase(位置);
        实现_->变化.notify_all();
        return 新任务工作操作状态::已完成;
    } catch (...) {
        return 新任务工作操作状态::内部错误;
    }
}

新任务工作操作结果 新_任务工作线程类::请求停止() noexcept {
    if (!实现_) return {新任务工作操作状态::资源失败,
        新任务工作生命周期::内部错误};
    try {
        std::unique_lock 锁(实现_->互斥);
        if (!实现_->创建已尝试) {
            return 实现_->操作结果(新任务工作操作状态::尚未启动);
        }
        if (实现_->停止 || 实现_->已完成) {
            return 实现_->操作结果(新任务工作操作状态::无变化);
        }
        实现_->停止 = true;
        实现_->刷新生命周期已加锁();
        实现_->变化.notify_all();
        const auto 结果 = 实现_->操作结果(新任务工作操作状态::已完成);
        锁.unlock();
        实现_->停止源.request_stop();
        return 结果;
    } catch (...) {
        return {新任务工作操作状态::内部错误,
            新任务工作生命周期::内部错误};
    }
}

新任务工作操作结果 新_任务工作线程类::等待停止(
    std::uint64_t 等待毫秒) noexcept {
    if (!实现_) return {新任务工作操作状态::资源失败,
        新任务工作生命周期::内部错误};
    if (当前工作池 == 实现_.get()) {
        try {
            std::lock_guard 锁(实现_->互斥);
            return 实现_->操作结果(新任务工作操作状态::不能等待自身);
        } catch (...) {
            return {新任务工作操作状态::不能等待自身, 新任务工作生命周期::内部错误};
        }
    }
    try {
        std::lock_guard 加入锁(实现_->加入互斥);
        std::unique_lock 锁(实现_->互斥);
        if (!std::any_of(实现_->线程组.begin(), 实现_->线程组.end(),
                [](const auto& 线程) { return 线程.joinable(); })) return 实现_->操作结果(
            实现_->已加入 ? 新任务工作操作状态::无变化
                           : 新任务工作操作状态::尚未启动);
        if (实现_->是工作线程自身()) {
            return 实现_->操作结果(新任务工作操作状态::不能等待自身);
        }
        if (!实现_->变化.wait_for(锁, 工作等待时长(等待毫秒),
            [this] { return 实现_->已完成; })) {
            return 实现_->操作结果(新任务工作操作状态::等待超时);
        }
        锁.unlock();
        实现_->加入全部线程();
        {
            std::lock_guard 所有者锁(工作所有者互斥);
            if (工作所有者 == this) 工作所有者 = nullptr;
        }
        锁.lock();
        return 实现_->操作结果(实现_->生命周期
                == 新任务工作生命周期::内部错误
            ? 新任务工作操作状态::内部错误
            : 新任务工作操作状态::已完成);
    } catch (...) {
        return {新任务工作操作状态::内部错误,
            新任务工作生命周期::内部错误};
    }
}

新任务工作快照 新_任务工作线程类::读取快照() const noexcept {
    新任务工作快照 结果;
    if (!实现_) {
        结果.生命周期 = 新任务工作生命周期::内部错误;
        return 结果;
    }
    try {
        std::lock_guard 锁(实现_->互斥);
        结果.生命周期 = 实现_->生命周期;
        结果.活动工作数 = 实现_->活动.size();
        结果.停止已请求 = 实现_->停止;
        结果.线程已完成 = 实现_->已完成;
        结果.物理线程数 = 实现_->已创建线程数 - 实现_->已退出线程数;
        结果.执行中工作数 = 实现_->执行中工作数;
        for (const auto& 项 : 实现_->活动) {
            if (项->已结束) ++结果.待确认工作数;
            else if (!项->已开始) ++结果.待处理工作数;
        }
    } catch (...) {
        结果.生命周期 = 新任务工作生命周期::内部错误;
    }
    return 结果;
}

