enum class 新自我消息类型 : std::uint8_t {
    事实变化 = 1,
    需求承接 = 2,
    任务筹办反馈 = 3
};

struct 新自我治理消息 final {
    // 发送方为世界事实更新的上层调用者。编号仅关联进程内交接，
    // 来源状态节点取真实更新结果；这里没有 self 代次或第二业务身份。
    std::uint64_t 消息编号 = 0;
    新自我消息类型 类型 = 新自我消息类型::事实变化;
    稳定编码 来源状态节点;
    // 需求承接时来源状态必须为空；M1仅接纳初始化的两个根需求。
    稳定编码 需求节点;
    // manager反馈只携带定位；self必须重新读取manager当前筹办结果。
    std::optional<新任务筹办反馈定位> 筹办反馈;
    friend bool operator==(const 新自我治理消息&,
        const 新自我治理消息&) = default;
};

enum class 新自我消息处理状态 : std::uint8_t {
    // 等待材料是本次尝试的终结反馈，不表示原消息仍在邮箱内等待。
    // 当前尚未接通依赖就绪通知；材料补齐后由发送方提交真实变化通知。
    已复核 = 1, 入口拒绝, 等待材料, 比较失败, 内部不一致,
    停止取消, 内部错误, 任务已承接, 既有终结任务, 任务管理未就绪,
    任务承接需核查, 已交接未收回, 任务筹办已裁决,
    任务筹办定位已变化, 任务筹办需核查
};

