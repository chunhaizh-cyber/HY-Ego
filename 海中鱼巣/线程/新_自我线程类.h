// 当前复核本能需求、异步交接根任务，裁决W1/W2筹办与执行前判断，
// 消费W3正式结果并形成任务后继决议；方法知识和任务事实仍由各自owner持有。
class 新_自我线程类 final {
public:
    // 注入的世界事实、需求、方法和任务服务必须比本对象存活更久。
    新_自我线程类(
        新_世界树类& 世界树服务,
        新_需求类& 需求服务,
        新_方法类& 方法服务,
        新_任务类& 任务服务) noexcept;
    ~新_自我线程类() noexcept;

    新_自我线程类(const 新_自我线程类&) = delete;
    新_自我线程类& operator=(const 新_自我线程类&) = delete;
    新_自我线程类(新_自我线程类&&) = delete;
    新_自我线程类& operator=(新_自我线程类&&) = delete;

    // 本函数在调用线程中依次完成世界树、自我所在场景、唯一自我存在、
    // 需求双根和方法根的建立及读回；不会在内部创建 OS 线程。
    新自我线程初始化结果 初始化(
        const 新自我线程初始化请求& 请求) noexcept;

    // 在self初始化前建立或读回安全/服务根所需的特征和比较概念。
    新自我治理基础结果 建立或取得治理基础() noexcept;

    // 创建 OS 线程并等待其进入常驻等待态。停止采用独立的进程内控制
    // 信号，不伪装成治理消息。
    新自我线程操作结果 启动(std::uint64_t 等待毫秒) noexcept;
    // 启动前配置，启动后不可变。生命周期旧调用者可以不启用消息消费。
    新自我线程操作结果 配置消息处理(
        const 新自我消息运行配置& 配置) noexcept;
    // 启动前绑定，manager必须存活到self回收后；world须同时覆盖两者。
    新自我线程操作结果 绑定任务管理(新_任务管理线程类& 任务管理) noexcept;
    新自我消息接收结果 提交消息(
        const 新自我治理消息& 消息) noexcept;
    新自我线程操作结果 请求停止() noexcept;
    新自我线程操作结果 等待停止(std::uint64_t 等待毫秒) noexcept;
    新自我线程快照 读取快照() const noexcept;

private:
    struct 实现;
    std::unique_ptr<实现> 实现_;
};

