自我线程操作结果_v1 自我线程::提交根需求复核消息(
    const 自我线程根需求复核消息_v1& 消息) noexcept {
    if (实现_ == nullptr) {
        return { 自我线程操作状态::资源失败, 自我线程生命周期状态::启动失败, false };
    }
    try {
        std::lock_guard 锁{ 实现_->状态互斥 };
        if (消息.合同版本 != 自我线程合同版本_v1 || !消息.消息.完整() ||
            !消息.原请求.完整() || !触发根有效(消息.触发根)) {
            return 实现_->操作结果(自我线程操作状态::入口拒绝);
        }
        if (!实现_->创建已尝试 || !实现_->锁定请求.has_value() ||
            !实现_->停门见证.has_value() || 实现_->停止已请求 ||
            实现_->线程已完成 || 实现_->内部错误锁存) {
            return 实现_->操作结果(自我线程操作状态::入口拒绝);
        }
        const auto& 本能根 = 实现_->锁定请求->本能根;
        const bool 定位有效 =
            (消息.触发根 == 自我线程复核触发根::双根 && !消息.正式需求定位.完整()) ||
            (消息.触发根 == 自我线程复核触发根::安全根 &&
                消息.正式需求定位 == 本能根.安全根.需求) ||
            (消息.触发根 == 自我线程复核触发根::服务根 &&
                消息.正式需求定位 == 本能根.服务根.需求);
        if (!定位有效) {
            return 实现_->操作结果(自我线程操作状态::入口拒绝);
        }

        const auto 同身份 = [&消息](const 自我线程根需求复核消息_v1& 已有) {
            return 已有.消息 == 消息.消息;
        };
        if (实现_->当前处理消息.has_value() && 同身份(*实现_->当前处理消息)) {
            return 实现_->操作结果(*实现_->当前处理消息 == 消息
                ? 自我线程操作状态::精确重复
                : 自我线程操作状态::消息冲突);
        }
        for (const auto& 已有 : 实现_->邮箱) {
            if (同身份(已有)) {
                return 实现_->操作结果(已有 == 消息
                    ? 自我线程操作状态::精确重复
                    : 自我线程操作状态::消息冲突);
            }
        }
        if (实现_->邮箱.size() >= 实现_->锁定请求->邮箱容量) {
            return 实现_->操作结果(自我线程操作状态::队列已满);
        }
        try {
            实现_->邮箱.push_back(消息);
        }
        catch (const std::bad_alloc&) {
            return 实现_->操作结果(自我线程操作状态::资源失败);
        }
        catch (const std::length_error&) {
            return 实现_->操作结果(自我线程操作状态::资源失败);
        }
        catch (...) {
            实现_->内部错误锁存 = true;
            实现_->停止已请求 = true;
            实现_->生命周期 = 自我线程生命周期状态::内部错误;
            实现_->状态变化.notify_all();
            return 实现_->操作结果(自我线程操作状态::内部错误);
        }
        实现_->状态变化.notify_all();
        return 实现_->操作结果(自我线程操作状态::成功);
    }
    catch (...) {
        实现_->锁存内部错误();
        return { 自我线程操作状态::内部错误, 自我线程生命周期状态::内部错误, false };
    }
}

自我线程操作结果_v1 自我线程::请求停止() noexcept {
    if (实现_ == nullptr) {
        return { 自我线程操作状态::资源失败, 自我线程生命周期状态::启动失败, false };
    }
    try {
        std::lock_guard 锁{ 实现_->状态互斥 };
        if (!实现_->创建已尝试) {
            return 实现_->操作结果(自我线程操作状态::入口拒绝);
        }
        if (实现_->内部错误锁存) {
            return 实现_->操作结果(自我线程操作状态::内部错误);
        }
        if (实现_->停止已请求) {
            return 实现_->操作结果(自我线程操作状态::精确重复);
        }
        实现_->停止已请求 = true;
        if (!实现_->线程已完成) {
            实现_->生命周期 = 自我线程生命周期状态::正在停止;
        }
        实现_->状态变化.notify_all();
        return 实现_->操作结果(自我线程操作状态::成功);
    }
    catch (...) {
        实现_->锁存内部错误();
        return { 自我线程操作状态::内部错误, 自我线程生命周期状态::内部错误, false };
    }
}

自我线程操作结果_v1 自我线程::等待停止(const std::uint64_t 等待毫秒) noexcept {
    if (实现_ == nullptr) {
        return { 自我线程操作状态::资源失败, 自我线程生命周期状态::启动失败, false };
    }
    try {
        {
            std::unique_lock 锁{ 实现_->状态互斥 };
            if (!实现_->创建已尝试) {
                return 实现_->操作结果(自我线程操作状态::入口拒绝);
            }
            const auto 已完成 = 实现_->状态变化.wait_for(
                锁, 有界等待时长(等待毫秒),
                [this] { return 实现_->线程已完成; });
            if (!已完成) {
                return 实现_->操作结果(自我线程操作状态::等待超时);
            }
        }
        const bool 本次加入 = 实现_->加入工作线程();
        std::lock_guard 锁{ 实现_->状态互斥 };
        if (实现_->内部错误锁存) {
            return 实现_->操作结果(自我线程操作状态::内部错误);
        }
        return 实现_->操作结果(本次加入
            ? 自我线程操作状态::成功
            : 自我线程操作状态::精确重复);
    }
    catch (...) {
        实现_->锁存内部错误();
        return { 自我线程操作状态::内部错误, 自我线程生命周期状态::内部错误, false };
    }
}

自我线程诊断快照_v1 自我线程::读取诊断快照() const noexcept {
    if (实现_ == nullptr) {
        自我线程诊断快照_v1 快照;
        快照.生命周期 = 自我线程生命周期状态::启动失败;
        快照.内部错误锁存 = true;
        快照.最近外部调用 = 自我线程外部调用状态::资源失败;
        return 快照;
    }
    try {
        std::lock_guard 锁{ 实现_->状态互斥 };
        return {
            实现_->生命周期, 实现_->治理运行门开启,
            实现_->线程已进入, 实现_->线程已完成,
            static_cast<std::uint64_t>(实现_->邮箱.size()),
            实现_->锁定请求.has_value() ? 实现_->锁定请求->邮箱容量 : 0,
            实现_->当前处理消息.has_value()
                ? std::optional<自我线程消息身份>{ 实现_->当前处理消息->消息 }
                : std::nullopt,
            实现_->已冻结批次数量, 实现_->成功治理批次数量,
            实现_->最近外部调用, 实现_->内部错误锁存,
        };
    }
    catch (...) {
        自我线程诊断快照_v1 快照;
        快照.生命周期 = 自我线程生命周期状态::内部错误;
        快照.内部错误锁存 = true;
        快照.最近外部调用 = 自我线程外部调用状态::内部错误;
        return 快照;
    }
}

