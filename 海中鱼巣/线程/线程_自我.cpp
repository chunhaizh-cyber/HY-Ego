[[nodiscard]] std::chrono::milliseconds 有界等待时长(
    const std::uint64_t 等待毫秒) noexcept {
    using 表示 = std::chrono::milliseconds::rep;
    constexpr auto 最大值 = (std::numeric_limits<表示>::max)();
    return std::chrono::milliseconds{
        等待毫秒 > static_cast<std::uint64_t>(最大值)
            ? 最大值
            : static_cast<表示>(等待毫秒),
    };
}

