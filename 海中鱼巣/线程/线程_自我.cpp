struct 自我线程::实现 final {
    mutable std::mutex 状态互斥;
    std::condition_variable 状态变化;
    std::mutex 加入互斥;
    std::deque<自我线程根需求复核消息_v1> 邮箱;
    std::optional<自我线程根需求复核消息_v1> 当前处理消息;
    std::optional<自我线程创建请求_v1> 锁定请求;
    自我线程正式上下文端口* 正式上下文端口 = nullptr;
    std::optional<自我线程停门见证_v1> 停门见证;
    std::thread 工作线程;
    自我线程生命周期状态 生命周期 = 自我线程生命周期状态::未创建;
    自我线程外部调用状态 最近外部调用 = 自我线程外部调用状态::待实现;
    std::uint64_t 事件序号 = 0;
    std::uint64_t 完成序号 = 0;
    std::uint64_t 已冻结批次数量 = 0;
    std::uint64_t 成功治理批次数量 = 0;
    bool 创建已尝试 = false;
    bool 治理运行门开启 = false;
    bool 线程已进入 = false;
    bool 线程已完成 = false;
    bool 停止已请求 = false;
    bool 内部错误锁存 = false;

    [[nodiscard]] 自我线程操作结果_v1 操作结果(const 自我线程操作状态 状态) const noexcept {
        return { 状态, 生命周期, false };
    }

    void 锁存内部错误() noexcept {
        std::lock_guard 锁{ 状态互斥 };
        内部错误锁存 = true;
        停止已请求 = true;
        生命周期 = 自我线程生命周期状态::内部错误;
        最近外部调用 = 自我线程外部调用状态::内部错误;
        状态变化.notify_all();
    }

    void 运行() noexcept {
        try {
            std::unique_lock 锁{ 状态互斥 };
            线程已进入 = true;
            const auto 入口序号 = ++事件序号;
            if (!停止已请求 && 锁定请求.has_value()) {
                生命周期 = 自我线程生命周期状态::已停门;
                停门见证 = 自我线程停门见证_v1{
                    入口序号, ++事件序号, false, 0,
                };
                状态变化.notify_all();
            }
            状态变化.wait(锁, [this] { return 停止已请求 || 内部错误锁存; });
            if (!内部错误锁存) {
                生命周期 = 自我线程生命周期状态::正在停止;
            }
            线程已完成 = true;
            完成序号 = ++事件序号;
            if (!内部错误锁存) {
                生命周期 = 自我线程生命周期状态::已停止;
            }
            状态变化.notify_all();
        }
        catch (...) {
            std::lock_guard 锁{ 状态互斥 };
            内部错误锁存 = true;
            停止已请求 = true;
            线程已完成 = true;
            完成序号 = ++事件序号;
            生命周期 = 自我线程生命周期状态::内部错误;
            最近外部调用 = 自我线程外部调用状态::内部错误;
            状态变化.notify_all();
        }
    }

    [[nodiscard]] bool 加入工作线程() noexcept {
        std::lock_guard 加入锁{ 加入互斥 };
        if (!工作线程.joinable()) {
            return false;
        }
        try {
            工作线程.join();
            return true;
        }
        catch (...) {
            std::lock_guard 状态锁{ 状态互斥 };
            内部错误锁存 = true;
            生命周期 = 自我线程生命周期状态::内部错误;
            最近外部调用 = 自我线程外部调用状态::内部错误;
            return false;
        }
    }
};

自我线程::自我线程() noexcept : 实现_(new (std::nothrow) 实现{}) {}

自我线程::~自我线程() noexcept {
    if (实现_ == nullptr) {
        return;
    }
    {
        std::lock_guard 锁{ 实现_->状态互斥 };
        实现_->停止已请求 = true;
        if (实现_->创建已尝试 && !实现_->线程已完成 &&
            实现_->生命周期 != 自我线程生命周期状态::启动失败) {
            实现_->生命周期 = 自我线程生命周期状态::正在停止;
        }
        实现_->状态变化.notify_all();
    }
    (void)实现_->加入工作线程();
    delete 实现_;
    实现_ = nullptr;
}

自我线程创建结果_v1 自我线程::创建并停在治理运行门(
    const 自我线程创建请求_v1& 请求,
    自我线程正式上下文端口& 正式上下文端口,
    const std::uint64_t 等待毫秒) noexcept {
    if (!请求.完整()) {
        return {};
    }
    if (实现_ == nullptr) {
        return { 自我线程操作状态::资源失败, 自我线程生命周期状态::启动失败, std::nullopt, false };
    }
    try {
        std::unique_lock 锁{ 实现_->状态互斥 };
        bool 本次创建者 = false;
        if (实现_->创建已尝试) {
            if (实现_->停止已请求 || 实现_->线程已完成) {
                return { 自我线程操作状态::入口拒绝, 实现_->生命周期, std::nullopt, false };
            }
            if (!实现_->锁定请求.has_value() || 实现_->正式上下文端口 == nullptr) {
                实现_->内部错误锁存 = true;
                实现_->停止已请求 = true;
                实现_->生命周期 = 自我线程生命周期状态::内部错误;
                实现_->最近外部调用 = 自我线程外部调用状态::内部错误;
                实现_->状态变化.notify_all();
                return { 自我线程操作状态::内部错误, 实现_->生命周期, std::nullopt, false };
            }
            if (!创建选择相同(*实现_->锁定请求, 请求) ||
                实现_->正式上下文端口 != &正式上下文端口) {
                return { 自我线程操作状态::选择冲突, 实现_->生命周期, std::nullopt, false };
            }
            if (实现_->停门见证.has_value()) {
                return { 自我线程操作状态::精确重复, 实现_->生命周期, 实现_->停门见证, false };
            }
        }
        else {
            实现_->创建已尝试 = true;
            本次创建者 = true;
            实现_->锁定请求 = 请求;
            实现_->正式上下文端口 = &正式上下文端口;
            实现_->生命周期 = 自我线程生命周期状态::创建中;
            try {
                实现_->工作线程 = std::thread{ &实现::运行, 实现_ };
            }
            catch (...) {
                实现_->停止已请求 = true;
                实现_->线程已完成 = true;
                实现_->完成序号 = ++实现_->事件序号;
                实现_->生命周期 = 自我线程生命周期状态::启动失败;
                实现_->状态变化.notify_all();
                return { 自我线程操作状态::资源失败, 实现_->生命周期, std::nullopt, false };
            }
        }

        const auto 已就绪 = 实现_->状态变化.wait_for(
            锁, 有界等待时长(等待毫秒),
            [this] {
                return 实现_->停门见证.has_value() ||
                    实现_->线程已完成 || 实现_->内部错误锁存;
            });
        if (!已就绪) {
            return { 自我线程操作状态::等待超时, 实现_->生命周期, std::nullopt, false };
        }
        if (实现_->内部错误锁存) {
            return { 自我线程操作状态::内部错误, 实现_->生命周期, std::nullopt, false };
        }
        if (!实现_->停门见证.has_value() || 实现_->停止已请求 || 实现_->线程已完成) {
            return { 自我线程操作状态::入口拒绝, 实现_->生命周期, std::nullopt, false };
        }
        return {
            本次创建者 ? 自我线程操作状态::成功 : 自我线程操作状态::精确重复,
            实现_->生命周期, 实现_->停门见证, false,
        };
    }
    catch (const std::bad_alloc&) {
        return { 自我线程操作状态::资源失败, 自我线程生命周期状态::启动失败, std::nullopt, false };
    }
    catch (const std::length_error&) {
        return { 自我线程操作状态::资源失败, 自我线程生命周期状态::启动失败, std::nullopt, false };
    }
    catch (...) {
        实现_->锁存内部错误();
        return { 自我线程操作状态::内部错误, 自我线程生命周期状态::内部错误, std::nullopt, false };
    }
}

