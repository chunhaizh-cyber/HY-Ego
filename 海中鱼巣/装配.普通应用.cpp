bool 普通应用装配结果::成功() const noexcept {
    return 状态 == 普通应用装配状态::已装配
        && 世界树 && 普通应用装配内部::世界初始化成功(世界树->状态)
        && 自我治理基础 && 自我治理基础->成功()
        && 自我 && 自我->成功()
        && 任务管理绑定 && 任务管理绑定->成功()
        && 消息配置 && 消息配置->成功();
}

bool 普通应用治理操作结果::成功() const noexcept {
    return 状态 == 普通应用治理操作状态::已完成
        || 状态 == 普通应用治理操作状态::无变化;
}

bool 普通应用网页消息处理结果::成功() const noexcept {
    return 状态 == 普通应用网页消息状态::已接纳
        || 状态 == 普通应用网页消息状态::精确重复;
}

普通应用装配结果 构造普通应用上下文(
    const 普通应用配置& 配置) noexcept {
    using namespace 普通应用装配内部;
    std::lock_guard 锁(上下文锁);
    if (!配置有效(配置)) return {};
    try {
        if (!上下文) {
            上下文 = std::make_unique<普通应用上下文>(配置);
        } else if (上下文->配置 != 配置) {
            return {};
        }
        if (上下文->装配结果 && 上下文->装配结果->成功()) {
            return *上下文->装配结果;
        }
        上下文->装配结果 = 完成装配(*上下文);
        return *上下文->装配结果;
    } catch (const std::bad_alloc&) {
        普通应用装配结果 结果;
        结果.状态 = 普通应用装配状态::资源失败;
        return 结果;
    } catch (...) {
        普通应用装配结果 结果;
        结果.状态 = 普通应用装配状态::内部不一致;
        return 结果;
    }
}

普通应用装配结果 构造普通应用上下文() noexcept {
    return 构造普通应用上下文(普通应用配置{});
}

普通应用治理操作结果 启动普通应用治理线程() noexcept {
    using namespace 普通应用装配内部;
    std::lock_guard 锁(上下文锁);
    普通应用治理操作结果 结果;
    if (!上下文 || !上下文->装配结果
        || !上下文->装配结果->成功()) {
        return 结果;
    }
    try {
        结果.任务管理 = 上下文->任务管理线程.启动({
            上下文->配置.任务管理线程邮箱容量,
            上下文->配置.资源重试间隔毫秒},
            上下文->配置.线程进入等待毫秒);
        if (!管理启动成功(结果.任务管理->状态)) {
            (void)上下文->任务管理线程.请求停止();
            (void)上下文->任务管理线程.等待停止(
                上下文->配置.线程停止回收等待毫秒);
            结果.状态 = 普通应用治理操作状态::任务管理启动失败;
            return 结果;
        }

        结果.自我线程 = 上下文->自我线程.启动(
            上下文->配置.线程进入等待毫秒);
        if (!自我启动成功(结果.自我线程->状态)) {
            (void)上下文->自我线程.请求停止();
            (void)上下文->自我线程.等待停止(
                上下文->配置.线程停止回收等待毫秒);
            (void)上下文->任务管理线程.请求停止();
            (void)上下文->任务管理线程.等待停止(
                上下文->配置.线程停止回收等待毫秒);
            结果.状态 = 普通应用治理操作状态::自我线程启动失败;
            return 结果;
        }
        const bool 原已启动 = 上下文->治理线程已启动;
        上下文->治理线程已启动 = true;
        结果.状态 = 原已启动
            ? 普通应用治理操作状态::无变化
            : 普通应用治理操作状态::已完成;
        return 结果;
    } catch (...) {
        (void)上下文->自我线程.请求停止();
        (void)上下文->自我线程.等待停止(
            上下文->配置.线程停止回收等待毫秒);
        (void)上下文->任务管理线程.请求停止();
        (void)上下文->任务管理线程.等待停止(
            上下文->配置.线程停止回收等待毫秒);
        结果.状态 = 普通应用治理操作状态::内部不一致;
        return 结果;
    }
}

普通应用治理操作结果 停止并回收普通应用治理线程() noexcept {
    using namespace 普通应用装配内部;
    std::lock_guard 锁(上下文锁);
    普通应用治理操作结果 结果;
    if (!上下文) return 结果;
    try {
        const auto 自我停止 = 上下文->自我线程.请求停止();
        const auto 自我等待 = 上下文->自我线程.等待停止(
            上下文->配置.线程停止回收等待毫秒);
        结果.自我线程 = 自我等待;

        const auto 管理停止 = 上下文->任务管理线程.请求停止();
        const auto 管理等待 = 上下文->任务管理线程.等待停止(
            上下文->配置.线程停止回收等待毫秒);
        结果.任务管理 = 管理等待;

        if (!自我停止成功(自我停止.状态)
            || !自我停止成功(自我等待.状态)) {
            结果.状态 = 普通应用治理操作状态::自我线程停止失败;
            return 结果;
        }
        if (!管理停止成功(管理停止.状态)
            || !管理停止成功(管理等待.状态)) {
            结果.状态 = 普通应用治理操作状态::任务管理停止失败;
            return 结果;
        }
        const bool 原已启动 = 上下文->治理线程已启动;
        上下文->治理线程已启动 = false;
        结果.状态 = 原已启动
            ? 普通应用治理操作状态::已完成
            : 普通应用治理操作状态::无变化;
        return 结果;
    } catch (...) {
        结果.状态 = 普通应用治理操作状态::内部不一致;
        return 结果;
    }
}

普通应用网页消息处理结果 接收普通应用网页消息(
    std::string_view 会话标识,
    std::uint64_t 消息序号,
    std::string_view UTF8正文) noexcept {
    using namespace 普通应用装配内部;
    std::lock_guard 锁(上下文锁);
    if (!上下文 || !上下文->装配结果
        || !上下文->装配结果->成功()) {
        普通应用网页消息处理结果 结果;
        结果.状态 = 普通应用网页消息状态::上下文不存在;
        return 结果;
    }
    auto& 当前 = *上下文;
    try {
        if (!是有效UTF8(会话标识) || !是有效UTF8(UTF8正文)
            || 消息序号 == 0) {
            return 形成网页结果(普通应用网页消息状态::入口拒绝, 当前);
        }
        if (当前.网页会话标识 && *当前.网页会话标识 != 会话标识) {
            return 形成网页结果(普通应用网页消息状态::会话冲突, 当前);
        }
        if (当前.最近网页消息序号) {
            if (消息序号 == *当前.最近网页消息序号) {
                return 形成网页结果(
                    当前.最近网页消息正文 == UTF8正文
                        ? 普通应用网页消息状态::精确重复
                        : 普通应用网页消息状态::消息序号冲突,
                    当前);
            }
            if (*当前.最近网页消息序号
                    == (std::numeric_limits<std::uint64_t>::max)()
                || 消息序号 != *当前.最近网页消息序号 + 1) {
                return 形成网页结果(
                    普通应用网页消息状态::消息序号不连续, 当前);
            }
        } else if (消息序号 != 1) {
            return 形成网页结果(
                普通应用网页消息状态::消息序号不连续, 当前);
        }

        if (!当前.网页会话标识) {
            当前.网页会话标识 = std::string(会话标识);
        }
        if (!当前.会话标识值节点) {
            const auto 节点 = 当前.世界事实.特征值服务.保存或取得特征值(
                材料物理类型::UTF8字符串,
                新特征值材料{std::string(会话标识)});
            if (!有效(节点)) {
                return 形成网页结果(
                    普通应用网页消息状态::会话标识材料失败, 当前);
            }
            当前.会话标识值节点 = 节点;
        }
        if (!当前.会话标识特征类型根) {
            特征概念定义 定义;
            定义.材料类型 = 特征概念材料物理类型::UTF8字符串;
            定义.值域 = 特征概念全材料值域{};
            定义.比较规则 = 特征概念比较规则::完整材料精确;
            定义.聚合规则 = 特征概念聚合规则::完整材料精确集合;
            const auto 节点 = 当前.世界事实.特征概念服务.
                建立或取得特征概念(定义, 当前.世界事实.特征值服务);
            if (!有效(节点)) {
                return 形成网页结果(
                    普通应用网页消息状态::会话标识概念失败, 当前);
            }
            当前.会话标识特征类型根 = 节点;
        }
        if (!当前.会话标识精确概念) {
            特征概念定义 定义;
            定义.材料类型 = 特征概念材料物理类型::UTF8字符串;
            定义.值域 = std::vector<稳定编码>{*当前.会话标识值节点};
            定义.比较规则 = 特征概念比较规则::完整材料精确;
            定义.聚合规则 = 特征概念聚合规则::完整材料精确集合;
            const auto 节点 = 当前.世界事实.特征概念服务.
                建立或取得特征概念(定义, 当前.世界事实.特征值服务,
                    *当前.会话标识特征类型根);
            if (!有效(节点)) {
                return 形成网页结果(
                    普通应用网页消息状态::会话标识概念失败, 当前);
            }
            当前.会话标识精确概念 = 节点;
        }
        if (!当前.网页交互者存在节点) {
            const auto 时间 = 当前UTC纳秒();
            if (!时间 || !有效(新版自我所在场景节点)) {
                return 形成网页结果(
                    普通应用网页消息状态::结构不一致, 当前);
            }
            新存在建立请求 请求;
            请求.初始特征组.push_back({
                *当前.会话标识精确概念,
                新特征准确值{*当前.会话标识值节点}});
            const auto 建立 = 当前.世界树.建立场景内存在(
                新版自我所在场景节点, 请求,
                {新状态时间语义::实例绝对UTC, *时间});
            if (建立.状态 != 新场景操作状态::已完成
                || !建立.存在节点 || !建立.专属存在概念节点) {
                return 形成网页结果(
                    普通应用网页消息状态::交互者建立失败, 当前);
            }
            当前.网页交互者存在节点 = 建立.存在节点;
            当前.网页交互者专属概念 = 建立.专属存在概念节点;
        }
        if (!当前.网页交互者专属概念) {
            当前.网页交互者专属概念 =
                当前.世界事实.存在服务.查询专属存在概念(
                    *当前.网页交互者存在节点);
            if (!当前.网页交互者专属概念) {
                return 形成网页结果(
                    普通应用网页消息状态::结构不一致, 当前);
            }
        }
        if (!当前.当前交互者特征类型根) {
            特征概念定义 定义;
            定义.材料类型 = 特征概念材料物理类型::存在节点引用;
            定义.值域 = 特征概念存在引用值域{
                *当前.网页交互者专属概念};
            定义.比较规则 = 特征概念比较规则::存在身份精确;
            定义.聚合规则 = 特征概念聚合规则::不自动聚合;
            const auto 节点 = 当前.世界事实.特征概念服务.
                建立或取得特征概念(定义, 当前.世界事实.特征值服务);
            if (!有效(节点)) {
                return 形成网页结果(
                    普通应用网页消息状态::当前交互者概念失败, 当前);
            }
            当前.当前交互者特征类型根 = 节点;
        }
        if (!当前.当前交互者特征节点) {
            const auto 时间 = 当前UTC纳秒();
            if (!时间 || !有效(新版自我节点)
                || !有效(新版自我所在场景节点)) {
                return 形成网页结果(
                    普通应用网页消息状态::结构不一致, 当前);
            }
            const auto 添加 = 当前.世界树.给存在添加特征(
                新版自我所在场景节点, 新版自我节点,
                *当前.当前交互者特征类型根,
                新特征准确值{*当前.网页交互者存在节点},
                {新状态时间语义::实例绝对UTC, *时间});
            if (添加.状态 != 新场景操作状态::已完成
                || !添加.存在结果 || !添加.存在结果->特征节点) {
                return 形成网页结果(
                    普通应用网页消息状态::当前交互者特征失败, 当前);
            }
            当前.当前交互者特征节点 = 添加.存在结果->特征节点;
        }
        if (!当前.当前交互者比较类型根) {
            const std::vector<二次特征概念输入定义> 输入定义组{
                {0, 二次特征输入角色::左输入,
                    二次特征输入来源种类::特征准确值,
                    *当前.当前交互者特征类型根},
                {1, 二次特征输入角色::右输入,
                    二次特征输入来源种类::特征准确值,
                    *当前.当前交互者特征类型根}};
            const auto 建立 = 当前.世界事实.二次特征概念服务.
                建立或取得默认二次特征概念(
                    二次特征算法::特征材料相似度, 输入定义组,
                    *当前.当前交互者特征类型根);
            if (!二次概念建立成功(建立.状态) || !建立.概念节点) {
                return 形成网页结果(
                    普通应用网页消息状态::比较关系失败, 当前);
            }
            当前.当前交互者比较类型根 = 建立.概念节点;
        }
        if (!当前.当前交互者包含关系概念) {
            const auto 建立 = 当前.世界事实.二次特征概念服务.
                建立或取得参照结果域概念(
                    *当前.当前交互者比较类型根,
                    二次特征结果域种类::包含于参照值域);
            if (!二次概念建立成功(建立.状态) || !建立.概念节点) {
                return 形成网页结果(
                    普通应用网页消息状态::比较关系失败, 当前);
            }
            当前.当前交互者包含关系概念 = 建立.概念节点;
        }
        if (!当前.网页连接需求节点) {
            const auto 服务根 = 当前.需求服务.查询根需求(
                新需求根角色::服务);
            if (!服务根 || !有效(新版自我节点)) {
                return 形成网页结果(
                    普通应用网页消息状态::结构不一致, 当前);
            }
            新普通需求建立请求 请求;
            请求.父需求节点 = *服务根;
            请求.所属存在节点 = 新版自我节点;
            请求.目标宿主节点 = 新版自我节点;
            请求.目标 = {
                *当前.当前交互者特征类型根,
                *当前.当前交互者特征类型根,
                *当前.当前交互者包含关系概念};
            请求.来源类型 = 新需求来源类型::本能定义;
            请求.来源承接节点.reset();
            const auto 建立 = 当前.需求服务.建立或取得普通需求(请求);
            if ((建立.状态 != 新需求操作状态::已建立
                    && 建立.状态 != 新需求操作状态::已复用)
                || !建立.需求节点 || !建立.需求列表项节点) {
                return 形成网页结果(
                    普通应用网页消息状态::连接需求失败, 当前);
            }
            当前.网页连接需求节点 = 建立.需求节点;
            当前.网页连接需求列表项 = 建立.需求列表项节点;
        }
        const auto 复核 = 当前.需求服务.复核当前满足(
            *当前.网页连接需求节点);
        if (复核.状态 != 新需求当前满足状态::已满足
            || !复核.实际特征节点
            || *复核.实际特征节点 != *当前.当前交互者特征节点) {
            return 形成网页结果(
                普通应用网页消息状态::连接需求未满足, 当前);
        }

        当前.最近网页消息序号 = 消息序号;
        当前.最近网页消息正文.assign(UTF8正文);
        return 形成网页结果(普通应用网页消息状态::已接纳, 当前);
    } catch (const std::bad_alloc&) {
        return 形成网页结果(普通应用网页消息状态::资源失败, 当前);
    } catch (...) {
        return 形成网页结果(普通应用网页消息状态::结构不一致, 当前);
    }
}

