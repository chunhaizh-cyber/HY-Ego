std::unique_ptr<普通应用上下文> 上下文;

普通应用上下文* 读取治理启停上下文(bool 要求成功装配) noexcept {
    try {
        std::lock_guard 锁(上下文锁);
        if (!上下文 || (要求成功装配 && (!上下文->装配结果 || !上下文->装配结果->成功()))) return nullptr;
        return 上下文.get(); // 上下文只首次建立，启停期间不替换或销毁。
    } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取治理启停上下文", L"启停引用读取异常。"); }
}

std::optional<新服务对象窗口来源> 读取已接纳网页存在来源() noexcept {
    try {
        std::lock_guard 锁(上下文锁);
        if (!上下文 || !上下文->装配结果 || !上下文->装配结果->成功()) return {};
        const auto& 当前 = *上下文;
        if (!当前.活跃网页会话标识 || !当前.网页会话标识
            || *当前.活跃网页会话标识 != *当前.网页会话标识
            || !当前.最近网页消息序号 || !当前.网页交互者存在节点) return {};
        if (!当前.交互窗口节点 || *当前.最近网页消息序号 == 0)
            工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取已接纳网页存在来源", L"已接纳来源内部引用不完整。");
        return 新服务对象窗口来源{*当前.交互窗口节点, 新版自我所在场景节点,
            *当前.网页交互者存在节点, *当前.活跃网页会话标识, *当前.最近网页消息序号};
    } catch (const std::exception& 异常) {
        工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取已接纳网页存在来源", L"来源快照读取异常。", 异常.what());
    } catch (...) { 工程异常终止(HY_EGO_WIDEN(__FILE__), __LINE__, L"读取已接纳网页存在来源", L"来源快照未知异常。"); }
}

