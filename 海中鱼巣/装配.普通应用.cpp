std::optional<std::int64_t> 当前UTC纳秒() noexcept {
    try {
        const auto 计数 = std::chrono::duration_cast<std::chrono::nanoseconds>(
            std::chrono::system_clock::now().time_since_epoch()).count();
        if (计数 < 0
            || static_cast<std::uintmax_t>(计数)
                > static_cast<std::uintmax_t>(
                    (std::numeric_limits<std::int64_t>::max)())) {
            return std::nullopt;
        }
        return static_cast<std::int64_t>(计数);
    } catch (...) {
        return std::nullopt;
    }
}

std::optional<std::int64_t> 下一网页观察时间(
    普通应用上下文& 当前) noexcept {
    const auto 现在 = 当前UTC纳秒();
    if (!现在) return std::nullopt;
    auto 结果 = *现在;
    if (结果 <= 当前.最近网页观察时间) {
        if (当前.最近网页观察时间
            == (std::numeric_limits<std::int64_t>::max)()) {
            return std::nullopt;
        }
        结果 = 当前.最近网页观察时间 + 1;
    }
    当前.最近网页观察时间 = 结果;
    return 结果;
}

bool 是有效UTF8(std::string_view 文本) noexcept {
    if (文本.empty()) return false;
    std::size_t 位置 = 0;
    while (位置 < 文本.size()) {
        const auto 首字节 = static_cast<unsigned char>(文本[位置]);
        std::size_t 后续数量 = 0;
        std::uint32_t 码点 = 0;
        if (首字节 <= 0x7F) {
            ++位置;
            continue;
        }
        if ((首字节 & 0xE0) == 0xC0) {
            后续数量 = 1;
            码点 = 首字节 & 0x1F;
        } else if ((首字节 & 0xF0) == 0xE0) {
            后续数量 = 2;
            码点 = 首字节 & 0x0F;
        } else if ((首字节 & 0xF8) == 0xF0) {
            后续数量 = 3;
            码点 = 首字节 & 0x07;
        } else {
            return false;
        }
        if (位置 + 后续数量 >= 文本.size()) return false;
        for (std::size_t i = 1; i <= 后续数量; ++i) {
            const auto 字节 = static_cast<unsigned char>(文本[位置 + i]);
            if ((字节 & 0xC0) != 0x80) return false;
            码点 = (码点 << 6) | (字节 & 0x3F);
        }
        if ((后续数量 == 1 && 码点 < 0x80)
            || (后续数量 == 2 && 码点 < 0x800)
            || (后续数量 == 3 && 码点 < 0x10000)
            || (码点 >= 0xD800 && 码点 <= 0xDFFF)
            || 码点 > 0x10FFFF) {
            return false;
        }
        位置 += 后续数量 + 1;
    }
    return true;
}

