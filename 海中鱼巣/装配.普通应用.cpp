        const auto 值 = 值节点 ? 当前.世界事实.特征值服务.获取特征值(*值节点)
            : std::optional<新特征值信息>{};
        const auto* 实际编码 = 值 && 值->物理类型 == 材料物理类型::U64数组
            ? std::get_if<std::vector<std::uint64_t>>(&值->材料) : nullptr;
