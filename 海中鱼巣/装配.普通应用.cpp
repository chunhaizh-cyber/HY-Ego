bool 普通应用装配结果::成功() const noexcept {
    return 状态 == 普通应用装配状态::已装配
        && 世界树 && 普通应用装配内部::世界初始化成功(世界树->状态)
        && 自我治理基础 && 自我治理基础->成功()
        && 自我 && 自我->成功()
        && 任务管理绑定 && 任务管理绑定->成功()
        && 消息配置 && 消息配置->成功()
        && 交互窗口节点 && 有效(*交互窗口节点)
        && 交互窗口消息数量特征节点
        && 有效(*交互窗口消息数量特征节点)
        && 交互窗口最新消息特征节点
        && 有效(*交互窗口最新消息特征节点)
        && 是否收到消息二次特征类型根
        && 有效(*是否收到消息二次特征类型根)
        && 未收到消息结果概念 && 有效(*未收到消息结果概念)
        && 已收到消息结果概念 && 有效(*已收到消息结果概念);
}

