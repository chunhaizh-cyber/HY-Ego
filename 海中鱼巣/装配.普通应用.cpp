std::optional<新自我线程初始化请求> 形成自我初始化请求(
    const 普通应用配置& 配置,
    const 新世界初始化结果& 世界,
    const 新自我治理基础结果& 基础) noexcept {
    if (!世界.世界树根场景 || !基础.安全值特征类型根
        || !基础.服务值特征类型根 || !基础.安全值目标概念
        || !基础.服务值目标概念 || !基础.安全值目标比较关系
        || !基础.服务值目标比较关系) {
        return std::nullopt;
    }
    const auto 时间 = 当前UTC纳秒();
    if (!时间) return std::nullopt;
    constexpr auto 冷启动初值 =
        (std::numeric_limits<std::int64_t>::max)() / 2;

    新自我线程初始化请求 请求;
    请求.新场景父节点 = *世界.世界树根场景;
    请求.自我建立请求.初始特征组 = {
        {*基础.安全值特征类型根, 新特征准确值{冷启动初值}},
        {*基础.服务值特征类型根, 新特征准确值{冷启动初值}}};
    请求.初始状态时间 = {
        新状态时间语义::实例绝对UTC, *时间};
    请求.本能双根 = {
        {*基础.安全值特征类型根, *基础.安全值目标概念,
            *基础.安全值目标比较关系, 配置.安全根初始权重},
        {*基础.服务值特征类型根, *基础.服务值目标概念,
            *基础.服务值目标比较关系, 配置.服务根初始权重}};
    return 请求.完整()
        ? std::optional<新自我线程初始化请求>{std::move(请求)}
        : std::nullopt;
}

普通应用装配结果 完成装配(普通应用上下文& 当前) noexcept {
    普通应用装配结果 结果;
    try {
        结果.世界树 = 当前.世界树.初始化();
        if (!世界初始化成功(结果.世界树->状态)
            || !结果.世界树->世界树根场景) {
            结果.状态 = 普通应用装配状态::世界树初始化失败;
            return 结果;
        }

        结果.自我治理基础 = 当前.自我线程.建立或取得治理基础();
        if (!结果.自我治理基础->成功()) {
            结果.状态 = 普通应用装配状态::自我治理基础初始化失败;
            return 结果;
        }

        if (!当前.自我初始化请求) {
            当前.自我初始化请求 = 形成自我初始化请求(
                当前.配置, *结果.世界树, *结果.自我治理基础);
        }
        if (!当前.自我初始化请求) {
            结果.状态 = 普通应用装配状态::内部不一致;
            return 结果;
        }

        const auto 本能登记 = 新_本能函数集::初始化();
        if (本能登记 != 新本能函数登记状态::已登记
            && 本能登记 != 新本能函数登记状态::精确重复) {
            结果.状态 = 普通应用装配状态::本能函数登记失败;
            return 结果;
        }

        结果.自我 = 当前.自我线程.初始化(*当前.自我初始化请求);
        if (!结果.自我->成功()) {
            结果.状态 = 普通应用装配状态::自我初始化失败;
            return 结果;
        }

        if (!建立交互窗口存在(当前)) {
            结果.状态 = 普通应用装配状态::交互窗口初始化失败;
            return 结果;
        }
        结果.交互窗口节点 = 当前.交互窗口节点;
        结果.交互窗口消息数量特征节点 =
            当前.交互窗口消息数量特征节点;
        结果.交互窗口最新消息特征节点 =
            当前.交互窗口最新消息特征节点;
        结果.是否收到消息二次特征类型根 =
            当前.是否收到消息二次特征类型根;
        结果.未收到消息结果概念 = 当前.未收到消息结果概念;
        结果.已收到消息结果概念 = 当前.已收到消息结果概念;

        const auto 网页端口 = 新_本能函数集::装配网页对话端口({
            &读取网页对话消息本能函数,
            &设置网页对话输入文本本能函数,
            &提交网页对话消息本能函数});
        if (网页端口 != 新本能函数端口装配状态::已装配
            && 网页端口 != 新本能函数端口装配状态::精确重复) {
            结果.状态 = 普通应用装配状态::本能函数端口装配失败;
            return 结果;
        }

        结果.任务管理绑定 =
            当前.自我线程.绑定任务管理(当前.任务管理线程);
        if (!结果.任务管理绑定->成功()) {
            结果.状态 = 普通应用装配状态::线程绑定失败;
            return 结果;
        }

        结果.消息配置 = 当前.自我线程.配置消息处理({
            当前.配置.自我线程邮箱容量,
            当前.配置.资源重试间隔毫秒});
        if (!结果.消息配置->成功()) {
            结果.状态 = 普通应用装配状态::消息配置失败;
            return 结果;
        }

        结果.状态 = 普通应用装配状态::已装配;
        return 结果;
    } catch (const std::bad_alloc&) {
        结果.状态 = 普通应用装配状态::资源失败;
    } catch (...) {
        结果.状态 = 普通应用装配状态::内部不一致;
    }
    return 结果;
}

