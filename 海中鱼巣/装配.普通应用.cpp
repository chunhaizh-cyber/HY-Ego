void 记录普通装配观察(const 普通应用装配结果& 结果) noexcept {
    try {
        std::wostringstream 文本;
        文本 << L"普通应用装配返回；状态=" << static_cast<int>(结果.状态)
            << L"；自我=";
        if (结果.自我 && 结果.自我->自我存在) 文本 << 结果.自我->自我存在->值;
        else 文本 << L"无";
        文本 << L"；结算需求=";
        if (结果.自我 && 结果.自我->完成服务需求) 文本 << 结果.自我->完成服务需求->值;
        else 文本 << L"无";
        文本 << L"；服务任务类型=";
        if (结果.服务任务特征概念节点) 文本 << 结果.服务任务特征概念节点->值;
        else 文本 << L"无";
        文本 << L"；服务任务特征=";
        if (结果.服务任务特征节点) 文本 << 结果.服务任务特征节点->值;
        else 文本 << L"无";
        (void)记录运行日志(L"普通应用", L"构造普通应用上下文", 文本.str());
    } catch (...) {
        // 仅为人读投影，不改变装配返回值。
    }
}

void 报告结算工程异常(std::string_view 错误) noexcept {
    try {
        std::wstring 文本 = L"服务值结算已停止：";
        if (!错误.empty() && 错误.size() <= static_cast<std::size_t>((std::numeric_limits<int>::max)())) {
            const auto 长度 = MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS,
                错误.data(), static_cast<int>(错误.size()), nullptr, 0);
            if (长度 > 0) {
                std::wstring 详情(static_cast<std::size_t>(长度), L'\0');
                MultiByteToWideChar(CP_UTF8, MB_ERR_INVALID_CHARS, 错误.data(),
                    static_cast<int>(错误.size()), 详情.data(), 长度);
                文本 += 详情;
            }
        }
        // 弹窗只持有诊断副本；治理线程退出和端口卸载不等待用户关闭窗口。
        std::thread([文本 = std::move(文本)] {
            (void)记录逻辑错误日志(L"服务值结算", L"本能消费者", 文本);
            MessageBoxW(nullptr, 文本.c_str(), L"海中鱼巣：工程错误", MB_OK | MB_ICONERROR);
        }).detach();
    } catch (...) {
        OutputDebugStringW(L"服务值结算工程错误报告失败；保持停止。\n");
    }
}

