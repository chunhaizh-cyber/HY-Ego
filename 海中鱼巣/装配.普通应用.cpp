bool 是有效UTF8(std::string_view 文本) noexcept {
    if (文本.empty()) return false;
    std::size_t 位置 = 0;
    while (位置 < 文本.size()) {
        const auto 首字节 = static_cast<unsigned char>(文本[位置]);
        std::size_t 后续数量 = 0;
        std::uint32_t 码点 = 0;
        if (首字节 <= 0x7F) {
            ++位置;
            continue;
        }
        if ((首字节 & 0xE0) == 0xC0) {
            后续数量 = 1;
            码点 = 首字节 & 0x1F;
        } else if ((首字节 & 0xF0) == 0xE0) {
            后续数量 = 2;
            码点 = 首字节 & 0x0F;
        } else if ((首字节 & 0xF8) == 0xF0) {
            后续数量 = 3;
            码点 = 首字节 & 0x07;
        } else {
            return false;
        }
        if (位置 + 后续数量 >= 文本.size()) return false;
        for (std::size_t i = 1; i <= 后续数量; ++i) {
            const auto 字节 = static_cast<unsigned char>(文本[位置 + i]);
            if ((字节 & 0xC0) != 0x80) return false;
            码点 = (码点 << 6) | (字节 & 0x3F);
        }
        if ((后续数量 == 1 && 码点 < 0x80)
            || (后续数量 == 2 && 码点 < 0x800)
            || (后续数量 == 3 && 码点 < 0x10000)
            || (码点 >= 0xD800 && 码点 <= 0xDFFF)
            || 码点 > 0x10FFFF) {
            return false;
        }
        位置 += 后续数量 + 1;
    }
    return true;
}

