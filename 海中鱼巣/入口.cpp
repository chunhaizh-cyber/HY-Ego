    bool 数据库自检后退出 = false;
    bool 无窗口常驻 = false;
    bool D455真实样本后退出 = false;
    bool 关系仓库性能验收已请求 = false;
    bool 生产运行期已请求 = false;
    for (int 参数索引 = 1; 参数索引 < 参数数量; ++参数索引) {
        if (std::string_view(参数组[参数索引]) == "--self-test-exit") {
            自检后退出 = true;
        } else if (std::string_view(参数组[参数索引]) == "--warehouse-performance-self-test-exit") {
            关系仓库性能验收已请求 = true;
            自检后退出 = true;
        } else if (std::string_view(参数组[参数索引]) == "--database-self-test-exit") {
            数据库自检后退出 = true;
        } else if (std::string_view(参数组[参数索引]) == "--headless") {
            无窗口常驻 = true;
        } else if (std::string_view(参数组[参数索引]) == "--d455-real-sample-exit") {
            D455真实样本后退出 = true;
            自检后退出 = true;
        } else if (std::string_view(参数组[参数索引]) == "--runtime-context") {
            生产运行期已请求 = true;
        }
    }
#ifndef HY_EGO_ENABLE_D455_REALSENSE
    if (D455真实样本后退出) {
        std::cerr << "当前构建未启用 D455 RealSense 真实采集。" << std::endl;
        return 2;
    }
#endif
