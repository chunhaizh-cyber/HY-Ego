海中鱼巣::控制面板树结构材料 生成控制面板语素树结构材料(
    const 海中鱼巣::语素初始化结果& 语素初始化读数,
    const 海中鱼巣::概念图初始化结果& 概念图初始化读数) {
    海中鱼巣::控制面板树结构材料 结构材料;
    结构材料.分类 = 海中鱼巣::控制面板树分类::语素树;
    if (!语素初始化读数.成功()) {
        return 结构材料;
    }

    auto 根节点材料 = 生成语素树显示节点材料(语素初始化读数.语素类型, 语素初始化读数.语素类型);
    根节点材料.关系角色 = 海中鱼巣::控制面板树关系角色::真实根;
    const std::vector<const 海中鱼巣::语素初始化显示项*> 子项组{
        &语素初始化读数.通用节点名称,
        &语素初始化读数.世界名称,
        &语素初始化读数.场景名称,
        &语素初始化读数.自我名称,
        &语素初始化读数.未知类型,
        &语素初始化读数.基础信息类型,
        &语素初始化读数.存在类型,
        &语素初始化读数.场景类型,
        &语素初始化读数.特征类型,
        &语素初始化读数.值类型,
        &语素初始化读数.需求类型,
        &语素初始化读数.任务类型,
        &语素初始化读数.方法类型,
        &语素初始化读数.动态类型,
        &语素初始化读数.因果引用类型,
        &语素初始化读数.状态类型,
        &语素初始化读数.二次类型
    };
    for (const auto* 子项 : 子项组) {
        if (子项 == nullptr || !子项->成功()) {
            return {};
        }
        根节点材料.子节点组.push_back(生成语素树显示节点材料(*子项, 语素初始化读数.语素类型));
    }
    const std::array<const 海中鱼巣::概念根初始化项*, 4> 概念名称组{
        &概念图初始化读数.存在根,
        &概念图初始化读数.动态根,
        &概念图初始化读数.关系根,
        &概念图初始化读数.因果根
    };
    for (const auto* 概念名称 : 概念名称组) {
        if (概念名称 == nullptr || !概念名称->成功()) {
            return {};
        }
        根节点材料.子节点组.push_back(
            生成概念名称语素树显示节点材料(*概念名称, 语素初始化读数.语素类型));
    }

    结构材料.状态 = 海中鱼巣::控制面板请求状态::可展示;
    结构材料.可展示 = true;
    结构材料.只读快照 = true;
    结构材料.来源版本 = 1;
    结构材料.根节点组.push_back(std::move(根节点材料));
    return 结构材料;
}

