class 启动用时显示器 {
public:
    using 时钟 = std::chrono::steady_clock;

    启动用时显示器()
        : 总起点(时钟::now()), 步骤起点(总起点) {
    }

    void 完成步骤(std::string_view 步骤名称) {
        const auto 当前时刻 = 时钟::now();
        std::ostringstream 输出;
        输出 << std::fixed << std::setprecision(3)
            << "[启动用时] " << 步骤名称
            << ": " << 转为毫秒(当前时刻 - 步骤起点) << " ms"
            << " | 累计=" << 转为毫秒(当前时刻 - 总起点) << " ms";
        std::cout << 输出.str() << std::endl;
        步骤起点 = 时钟::now();
    }

    void 输出总用时(std::string_view 状态名称) const {
        const auto 当前时刻 = 时钟::now();
        std::ostringstream 输出;
        输出 << std::fixed << std::setprecision(3)
            << "[启动总用时] " << 状态名称
            << ": " << 转为毫秒(当前时刻 - 总起点) << " ms";
        std::cout << 输出.str() << std::endl;
    }

private:
    static double 转为毫秒(时钟::duration 用时) {
        return std::chrono::duration<double, std::milli>(用时).count();
    }

    时钟::time_point 总起点;
    时钟::time_point 步骤起点;
};

海中鱼巣::世界树名称语素角色 读取世界树节点名称角色(
    海中鱼巣::节点句柄 节点值,
    const 海中鱼巣::世界树初始化结果& 初始化结果) {
    if (节点值 == 初始化结果.世界树根节点) {
        return 海中鱼巣::世界树名称语素角色::世界;
    }
    if (节点值 == 初始化结果.自我所在场景) {
        return 海中鱼巣::世界树名称语素角色::场景;
    }
    if (节点值 == 初始化结果.自我存在节点) {
        return 海中鱼巣::世界树名称语素角色::自我;
    }
    return 海中鱼巣::世界树名称语素角色::通用节点;
}

std::optional<海中鱼巣::语素节点显示语义材料> 读取世界树节点显示语义(
    海中鱼巣::节点句柄 节点值,
    海中鱼巣::节点类型 类型,
    const 海中鱼巣::世界树初始化结果& 初始化结果,
    const 海中鱼巣::语素初始化结果& 语素初始化读数) {
    if (!语素初始化读数.成功()) {
        return std::nullopt;
    }
    海中鱼巣::语素节点显示语义材料 材料{
        语素初始化读数.读取世界树名称(读取世界树节点名称角色(节点值, 初始化结果)),
        语素初始化读数.读取节点类型名称(类型)
    };
    if (!材料.成功()) {
        return std::nullopt;
    }
    return 材料;
}

std::wstring 生成世界树节点显示名称(
    海中鱼巣::节点句柄 节点值,
    const 海中鱼巣::语素节点显示语义材料& 显示语义,
    const std::optional<海中鱼巣::世界树相对坐标>& 自我相对坐标) {
    std::wstring 名称 = 显示语义.名称.文本;
    名称 += L" | ";
    名称 += 显示语义.类型.文本;
    名称 += L" #";
    名称 += std::to_wstring(节点值.节点编号);
    if (自我相对坐标.has_value()) {
        名称 += L" | 相对坐标=(";
        名称 += std::to_wstring(static_cast<int>(自我相对坐标->横向));
        名称 += L".0,";
        名称 += std::to_wstring(static_cast<int>(自我相对坐标->纵向));
        名称 += L".0,";
        名称 += std::to_wstring(static_cast<int>(自我相对坐标->垂向));
        名称 += L".0)";
    }
    return 名称;
}

std::optional<海中鱼巣::控制面板树节点材料> 生成控制面板世界树节点材料(
    const 海中鱼巣::节点仓库& 节点,
    const 海中鱼巣::关系仓库& 关系,
    海中鱼巣::节点句柄 当前节点,
    const 海中鱼巣::世界树初始化结果& 初始化结果,
    const 海中鱼巣::语素初始化结果& 语素初始化读数,
    const std::optional<海中鱼巣::世界树相对坐标>& 自我相对坐标,
    std::vector<海中鱼巣::节点句柄>& 当前父链) {
    if (!海中鱼巣::句柄有效(当前节点) || 当前父链.size() > 4096) {
        return std::nullopt;
    }
    for (const auto& 已访问节点 : 当前父链) {
        if (已访问节点 == 当前节点) {
            return std::nullopt;
        }
    }
    const auto 记录 = 节点.读取节点(当前节点);
    if (!记录.has_value()) {
        return std::nullopt;
    }

    海中鱼巣::控制面板树节点材料 材料;
    材料.节点 = 当前节点;
    材料.类型 = 记录->类型;
    材料.关系角色 = 当前父链.empty()
        ? 海中鱼巣::控制面板树关系角色::真实根
        : 海中鱼巣::控制面板树关系角色::普通父子;
    const auto 显示语义 = 读取世界树节点显示语义(当前节点, 记录->类型, 初始化结果, 语素初始化读数);
    if (!显示语义.has_value()) {
        return std::nullopt;
    }
    材料.名称基础信息 = 显示语义->名称.基础信息;
    材料.类型基础信息 = 显示语义->类型.基础信息;
    材料.名称语素入口 = 显示语义->名称.语素入口结果.语素入口;
    材料.类型语素入口 = 显示语义->类型.语素入口结果.语素入口;
    材料.名称语素入口组 = {材料.名称语素入口, 材料.类型语素入口};
    const auto 节点相对坐标 = 当前节点 == 初始化结果.自我存在节点
        ? 自我相对坐标
        : std::optional<海中鱼巣::世界树相对坐标>{};
    材料.显示名称 = 生成世界树节点显示名称(当前节点, 显示语义.value(), 节点相对坐标);
    当前父链.push_back(当前节点);
    auto 子节点组 = 关系.获取子节点(当前节点);
    std::sort(子节点组.begin(), 子节点组.end(), [](const auto& 左, const auto& 右) {
        return 左.节点编号 < 右.节点编号;
    });
    for (const auto& 子节点 : 子节点组) {
        auto 子节点材料 = 生成控制面板世界树节点材料(
            节点, 关系, 子节点, 初始化结果, 语素初始化读数, 自我相对坐标, 当前父链);
        if (!子节点材料.has_value()) {
            当前父链.pop_back();
            return std::nullopt;
        }
        材料.子节点组.push_back(std::move(子节点材料.value()));
    }
    当前父链.pop_back();
    return 材料;
}

海中鱼巣::控制面板树结构材料 生成控制面板世界树结构材料(
    const 海中鱼巣::节点仓库& 节点,
    const 海中鱼巣::关系仓库& 关系,
    const 海中鱼巣::世界树初始化结果& 初始化结果,
    const 海中鱼巣::语素初始化结果& 语素初始化读数,
    const std::optional<海中鱼巣::世界树相对坐标>& 自我相对坐标) {
    海中鱼巣::控制面板树结构材料 结构材料;
    if (!初始化结果.成功() || !语素初始化读数.成功()) {
        return 结构材料;
    }
    std::vector<海中鱼巣::节点句柄> 当前父链;
    auto 根节点材料 = 生成控制面板世界树节点材料(
        节点, 关系, 初始化结果.世界树根节点, 初始化结果, 语素初始化读数, 自我相对坐标, 当前父链);
    if (!根节点材料.has_value()) {
        return 结构材料;
    }
    结构材料.状态 = 海中鱼巣::控制面板请求状态::可展示;
    结构材料.分类 = 海中鱼巣::控制面板树分类::世界树;
    结构材料.可展示 = true;
    结构材料.只读快照 = true;
    结构材料.来源版本 = 1;
    结构材料.根节点组.push_back(std::move(根节点材料.value()));
    return 结构材料;
}

