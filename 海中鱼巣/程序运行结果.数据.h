// 文件规则：只承载程序运行结构化结果；日志和文本不得改变成功语义。
#pragma once

#include "启动选项.数据.h"

#include <cstddef>
#include <cstdint>
#include <optional>

namespace 海中鱼巣 {

enum class 程序运行状态 : std::uint8_t {
    已完成 = 0,
    装配失败 = 1,
    初始化失败 = 2,
    投影失败 = 3,
    审计失败 = 4,
    宿主失败 = 5,
    自检失败 = 6,
    专项失败 = 7,
    内部不一致 = 8
};

enum class 程序失败阶段 : std::uint8_t {
    无 = 0,
    生产运行期首发 = 1,
    普通应用装配 = 2,
    方法登记根 = 3,
    自我线程启动 = 4,
    自我线程初始化 = 5,
    概念图初始化 = 6,
    自我存在根支持 = 7,
    控制面板投影 = 8,
    数据库写入 = 9,
    数据库读回 = 10,
    停止信号 = 11,
    控制面板窗口 = 12,
    无窗口常驻 = 13,
    完整自检 = 14,
    关系仓库性能 = 15,
    D455真实样本 = 16
};

enum class 程序专项类别 : std::uint8_t {
    无 = 0,
    完整自检 = 1,
    数据库 = 2,
    关系仓库性能 = 3,
    D455真实样本 = 4
};

struct 程序专项摘要 {
    程序专项类别 类别 = 程序专项类别::无;
    std::size_t 验收项数量 = 0;
    std::size_t 失败项数量 = 0;
    bool 结果可用 = false;
};

struct 程序运行结果 {
    启动模式 模式 = 启动模式::普通控制面板;
    程序运行状态 状态 = 程序运行状态::内部不一致;
    程序失败阶段 失败阶段 = 程序失败阶段::无;
    std::optional<程序专项摘要> 专项;

    bool 成功() const noexcept {
        return 状态 == 程序运行状态::已完成;
    }
};

}
