enum class 脚本异常 { 无, 分配失败, 其它 };

template<class 结果>
struct 脚本步骤 final {
    结果 值{};
    脚本异常 异常 = 脚本异常::无;
};

struct 脚本场景服务 final {
    mutable std::vector<脚本步骤<L2场景树结构登记结果>> 登记步骤;
    mutable std::vector<脚本步骤<L2场景树读取结果>> 整树步骤;
    mutable std::size_t 登记索引 = 0;
    mutable std::size_t 整树索引 = 0;
    mutable std::size_t 登记调用 = 0;
    mutable std::size_t 整树调用 = 0;
    mutable std::vector<L2场景树读取请求> 读取请求组;

    template<class 结果>
    static 结果 执行(const 脚本步骤<结果>& 步骤) {
        if (步骤.异常 == 脚本异常::分配失败) throw std::bad_alloc{};
        if (步骤.异常 == 脚本异常::其它) throw std::runtime_error("脚本异常");
        return 步骤.值;
    }

    L2场景树结构登记结果 读取当前场景树结构登记() const {
        ++登记调用;
        if (登记索引 >= 登记步骤.size()) throw std::runtime_error("登记脚本耗尽");
        return 执行(登记步骤[登记索引++]);
    }

    L2场景树读取结果 读取场景树(const L2场景树读取请求& 请求) const {
        ++整树调用;
        读取请求组.push_back(请求);
        if (整树索引 >= 整树步骤.size()) throw std::runtime_error("整树脚本耗尽");
        return 执行(整树步骤[整树索引++]);
    }
};

struct 验证器 final {
    int 总数 = 0;
    int 失败 = 0;

    void 检查(const char* 名称, bool 成立) {
        ++总数;
        if (!成立) ++失败;
        std::cout << (成立 ? "[PASS] " : "[FAIL] ") << 名称 << '\n';
    }
};

bool 生命周期相同(const L2生命周期& 左, const L2生命周期& 右) noexcept {
    return 左.创建事实代次 == 右.创建事实代次
        && 左.退出事实代次 == 右.退出事实代次;
}

bool 父子关系相同(const L2场景父子关系事实& 左,
    const L2场景父子关系事实& 右) noexcept {
    return 左.关系稳定编码 == 右.关系稳定编码
        && 左.父场景 == 右.父场景 && 左.子场景 == 右.子场景
        && 左.顺序 == 右.顺序 && 生命周期相同(左.生命周期, 右.生命周期);
}

bool 成员关系相同(const L2场景成员关系事实& 左,
    const L2场景成员关系事实& 右) noexcept {
    return 左.关系稳定编码 == 右.关系稳定编码
        && 左.场景 == 右.场景 && 左.存在 == 右.存在
        && 左.顺序 == 右.顺序 && 生命周期相同(左.生命周期, 右.生命周期);
}

bool 原始材料相同(const L2原始值材料& 左,
    const L2原始值材料& 右) noexcept {
    return std::visit([](const auto& 左值, const auto& 右值) noexcept {
        using 左类型 = std::remove_cvref_t<decltype(左值)>;
        using 右类型 = std::remove_cvref_t<decltype(右值)>;
        if constexpr (!std::is_same_v<左类型, 右类型>) return false;
        else if constexpr (std::is_same_v<左类型, L2独立材料引用>)
            return 左值.编码 == 右值.编码;
        else if constexpr (std::is_same_v<左类型, std::vector<std::int64_t>>
            || std::is_same_v<左类型, std::vector<std::uint64_t>>) {
            if (左值.size() != 右值.size()) return false;
            for (std::size_t 索引 = 0; 索引 < 左值.size(); ++索引)
                if (左值[索引] != 右值[索引]) return false;
            return true;
        } else return 左值 == 右值;
    }, 左, 右);
}

bool 属性事实相同(const L2属性事实& 左, const L2属性事实& 右) noexcept {
    return 左.属性类型身份 == 右.属性类型身份
        && 左.值稳定编码 == 右.值稳定编码
        && 原始材料相同(左.类型化不可变材料, 右.类型化不可变材料)
        && 左.来源稳定编码 == 右.来源稳定编码
        && 左.创建事实代次 == 右.创建事实代次
        && 左.退出事实代次 == 右.退出事实代次;
}

bool 场景事实相同(const L2场景事实& 左, const L2场景事实& 右) noexcept {
    if (左.身份 != 右.身份 || !生命周期相同(左.生命周期, 右.生命周期)
        || 左.固定属性.size() != 右.固定属性.size()
        || 左.直接子场景.size() != 右.直接子场景.size()
        || 左.直接成员.size() != 右.直接成员.size()) return false;
    for (std::size_t 索引 = 0; 索引 < 左.固定属性.size(); ++索引)
        if (!属性事实相同(左.固定属性[索引], 右.固定属性[索引])) return false;
    for (std::size_t 索引 = 0; 索引 < 左.直接子场景.size(); ++索引)
        if (!父子关系相同(左.直接子场景[索引], 右.直接子场景[索引])) return false;
    for (std::size_t 索引 = 0; 索引 < 左.直接成员.size(); ++索引)
        if (!成员关系相同(左.直接成员[索引], 右.直接成员[索引])) return false;
    return true;
}

bool 身份来源相同(const L2节点族身份来源事实& 左,
    const L2节点族身份来源事实& 右) noexcept {
    return 左.节点族 == 右.节点族 && 左.节点稳定编码 == 右.节点稳定编码
        && 左.写入所有者 == 右.写入所有者
        && 左.族锚点稳定编码 == 右.族锚点稳定编码
        && 左.族归属关系类型稳定编码 == 右.族归属关系类型稳定编码
        && 左.族归属关系稳定编码 == 右.族归属关系稳定编码
        && 左.角色或顺序 == 右.角色或顺序
        && 生命周期相同(左.所有者生命周期, 右.所有者生命周期)
        && 生命周期相同(左.节点生命周期, 右.节点生命周期)
        && 生命周期相同(左.族锚点生命周期, 右.族锚点生命周期)
        && 生命周期相同(左.关系类型生命周期, 右.关系类型生命周期)
        && 生命周期相同(左.归属关系生命周期, 右.归属关系生命周期);
}

bool 树归属相同(const L2场景树归属事实& 左,
    const L2场景树归属事实& 右) noexcept {
    return 左.树 == 右.树 && 左.场景 == 右.场景 && 左.根场景 == 右.根场景
        && 左.类别 == 右.类别 && 左.关系稳定编码 == 右.关系稳定编码
        && 左.物理目标稳定编码 == 右.物理目标稳定编码
        && 生命周期相同(左.生命周期, 右.生命周期);
}

bool 场景树事实相同(const L2场景树事实& 左,
    const L2场景树事实& 右) noexcept {
    if (左.树 != 右.树 || 左.根场景 != 右.根场景
        || 左.结构登记 != 右.结构登记 || 左.根标记 != 右.根标记
        || 左.事实截止代次 != 右.事实截止代次
        || 左.场景组.size() != 右.场景组.size()
        || 左.父子关系组.size() != 右.父子关系组.size()) return false;
    for (std::size_t 索引 = 0; 索引 < 左.场景组.size(); ++索引) {
        const auto& 左节点 = 左.场景组[索引];
        const auto& 右节点 = 右.场景组[索引];
        if (!场景事实相同(左节点.场景, 右节点.场景)
            || !身份来源相同(左节点.场景身份来源, 右节点.场景身份来源)
            || !树归属相同(左节点.树归属, 右节点.树归属)) return false;
    }
    for (std::size_t 索引 = 0; 索引 < 左.父子关系组.size(); ++索引)
        if (!父子关系相同(左.父子关系组[索引], 右.父子关系组[索引])) return false;
    return true;
}

bool 材料相同(const 自我世界树根消费材料& 左,
    const 自我世界树根消费材料& 右) noexcept {
    return 自我世界树根消费内部::请求相同(左.请求, 右.请求)
        && 左.当前结构登记 == 右.当前结构登记
        && 场景树事实相同(左.正式树读回, 右.正式树读回)
        && 左.本次事实截止代次 == 右.本次事实截止代次;
}

