bool 尝试创建目录符号链接(const std::filesystem::path& 链接,
    const std::filesystem::path& 目标) {
    constexpr DWORD 允许非特权创建 = 0x2;
    if (CreateSymbolicLinkW(链接.c_str(), 目标.c_str(),
            SYMBOLIC_LINK_FLAG_DIRECTORY | 允许非特权创建) != FALSE)
        return true;

    if (!CreateDirectoryW(链接.c_str(), nullptr)) return false;
    const HANDLE 句柄 = CreateFileW(链接.c_str(), GENERIC_WRITE, 0, nullptr,
        OPEN_EXISTING, FILE_FLAG_OPEN_REPARSE_POINT | FILE_FLAG_BACKUP_SEMANTICS,
        nullptr);
    if (句柄 == INVALID_HANDLE_VALUE) {
        RemoveDirectoryW(链接.c_str());
        return false;
    }
    struct 目录挂载点缓冲 final {
        ULONG 标签 = IO_REPARSE_TAG_MOUNT_POINT;
        USHORT 数据长度 = 0;
        USHORT 保留 = 0;
        USHORT 替代名偏移 = 0;
        USHORT 替代名长度 = 0;
        USHORT 显示名偏移 = 0;
        USHORT 显示名长度 = 0;
        WCHAR 路径缓冲[MAX_PATH * 4]{};
    } 缓冲;
    const std::wstring 显示名 = std::filesystem::absolute(目标).wstring();
    const std::wstring 替代名 = L"\\??\\" + 显示名;
    const auto 替代字节 = static_cast<USHORT>(替代名.size() * sizeof(wchar_t));
    const auto 显示字节 = static_cast<USHORT>(显示名.size() * sizeof(wchar_t));
    if (替代名.size() + 显示名.size() + 2 >= std::size(缓冲.路径缓冲)) {
        CloseHandle(句柄);
        RemoveDirectoryW(链接.c_str());
        return false;
    }
    缓冲.替代名长度 = 替代字节;
    缓冲.显示名偏移 = static_cast<USHORT>(替代字节 + sizeof(wchar_t));
    缓冲.显示名长度 = 显示字节;
    std::copy(替代名.begin(), 替代名.end(), 缓冲.路径缓冲);
    std::copy(显示名.begin(), 显示名.end(),
        reinterpret_cast<wchar_t*>(reinterpret_cast<std::byte*>(缓冲.路径缓冲)
            + 缓冲.显示名偏移));
    缓冲.数据长度 = static_cast<USHORT>(替代字节 + 显示字节 + 12);
    DWORD 已返回 = 0;
    const BOOL 成功 = DeviceIoControl(句柄, FSCTL_SET_REPARSE_POINT,
        &缓冲, 缓冲.数据长度 + 8, nullptr, 0, &已返回, nullptr);
    CloseHandle(句柄);
    if (!成功) RemoveDirectoryW(链接.c_str());
    return 成功 != FALSE;
}

