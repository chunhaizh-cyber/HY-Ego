海中鱼巣::材料SHA256摘要 计算摘要(const std::vector<std::uint8_t>& 字节) {
    BCRYPT_ALG_HANDLE 算法 = nullptr;
    BCRYPT_HASH_HANDLE 散列 = nullptr;
    DWORD 对象长度 = 0, 已写 = 0;
    std::vector<std::uint8_t> 对象;
    海中鱼巣::材料SHA256摘要 结果;
    if (BCryptOpenAlgorithmProvider(&算法, BCRYPT_SHA256_ALGORITHM, nullptr, 0) < 0
        || BCryptGetProperty(算法, BCRYPT_OBJECT_LENGTH,
            reinterpret_cast<PUCHAR>(&对象长度), sizeof(对象长度), &已写, 0) < 0)
        throw std::runtime_error("SHA-256 provider failed");
    对象.resize(对象长度);
    if (BCryptCreateHash(算法, &散列, 对象.data(),
            static_cast<ULONG>(对象.size()), nullptr, 0, 0) < 0
        || (!字节.empty() && BCryptHashData(散列,
            const_cast<PUCHAR>(字节.data()), static_cast<ULONG>(字节.size()), 0) < 0)
        || BCryptFinishHash(散列, 结果.字节.data(),
            static_cast<ULONG>(结果.字节.size()), 0) < 0) {
        if (散列) BCryptDestroyHash(散列);
        BCryptCloseAlgorithmProvider(算法, 0);
        throw std::runtime_error("SHA-256 failed");
    }
    BCryptDestroyHash(散列);
    BCryptCloseAlgorithmProvider(算法, 0);
    return 结果;
}

void 写文件(const std::filesystem::path& 路径,
    const std::vector<std::uint8_t>& 字节) {
    std::ofstream 输出(路径, std::ios::binary | std::ios::trunc);
    输出.write(reinterpret_cast<const char*>(字节.data()),
        static_cast<std::streamsize>(字节.size()));
    if (!输出) throw std::runtime_error("candidate write failed");
}

std::vector<std::uint8_t> 读文件(const std::filesystem::path& 路径) {
    std::ifstream 输入(路径, std::ios::binary);
    return {std::istreambuf_iterator<char>(输入), std::istreambuf_iterator<char>()};
}

std::wstring 摘要十六进制(const 海中鱼巣::材料SHA256摘要& 摘要) {
    static constexpr wchar_t 数字[] = L"0123456789abcdef";
    std::wstring 结果;
    结果.reserve(64);
    for (const auto 字节 : 摘要.字节) {
        结果.push_back(数字[字节 >> 4]);
        结果.push_back(数字[字节 & 0x0F]);
    }
    return 结果;
}

