struct 验证参数 final {
    std::uint32_t 合同版本 = 海中鱼巣::L1中性CRUD合同版本;
    std::uint64_t 起始幂等键 = 5101;
};

std::optional<std::uint64_t> 解析无符号整数(const wchar_t* 文本) noexcept {
    if (!文本 || *文本 == L'\0' || *文本 == L'-') return std::nullopt;
    errno = 0;
    wchar_t* 末尾 = nullptr;
    const auto 值 = std::wcstoull(文本, &末尾, 10);
    if (errno == ERANGE || !末尾 || *末尾 != L'\0') return std::nullopt;
    return static_cast<std::uint64_t>(值);
}

bool 解析参数(int 参数数量, wchar_t* 参数值[], 验证参数& 参数) noexcept {
    for (int 索引 = 1; 索引 < 参数数量; 索引 += 2) {
        if (索引 + 1 >= 参数数量) return false;
        const std::wstring_view 名称{参数值[索引]};
        const auto 值 = 解析无符号整数(参数值[索引 + 1]);
        if (!值) return false;
        if (名称 == L"--合同版本") {
            if (*值 > std::numeric_limits<std::uint32_t>::max()) return false;
            参数.合同版本 = static_cast<std::uint32_t>(*值);
        } else if (名称 == L"--起始幂等键") 参数.起始幂等键 = *值;
        else return false;
    }
    return 参数.起始幂等键 != 0
        && 参数.起始幂等键 <= std::numeric_limits<std::uint64_t>::max() - 10;
}

std::optional<海中鱼巣::稳定编码> 查新编码(
    const 海中鱼巣::L1中性写入结果& 结果,
    海中鱼巣::L1中性写集本地键 本地键) noexcept {
    for (const auto& [键, 编码] : 结果.新编码映射)
        if (键 == 本地键) return 编码;
    return std::nullopt;
}

std::optional<std::uint64_t> 读取当前代次(
    const 海中鱼巣::L1事实基座服务& 服务) {
    const auto 结果 = 服务.读取中性当前事实代次(
        {海中鱼巣::L1中性CRUD合同版本});
    return 结果.状态 == 海中鱼巣::L1中性读取状态::成功
        && 结果.合同版本 == 海中鱼巣::L1中性CRUD合同版本
        && 结果.事实代次 != 0
        ? std::optional<std::uint64_t>{结果.事实代次} : std::nullopt;
}

const 海中鱼巣::L1中性值事实* 查值(
    const 海中鱼巣::L1中性历史属性值组读取结果& 结果,
    海中鱼巣::稳定编码 编码) noexcept {
    const auto 位置 = std::find_if(结果.属性值组.begin(), 结果.属性值组.end(),
        [&](const auto& 事实) { return 事实.编码 == 编码; });
    return 位置 == 结果.属性值组.end() ? nullptr : &*位置;
}

bool 包含值(const 海中鱼巣::L1中性历史属性值组读取结果& 结果,
    海中鱼巣::稳定编码 编码) noexcept {
    return 查值(结果, 编码) != nullptr;
}

bool 历史组成功完整(const 海中鱼巣::L1中性历史属性值组读取结果& 结果,
    const 海中鱼巣::L1中性历史属性值组读取请求& 请求,
    std::uint64_t 实际代次) noexcept {
    if (结果.状态 != 海中鱼巣::L1中性历史属性值组读取状态::成功
        || 结果.合同版本 != 海中鱼巣::L1中性CRUD合同版本
        || 结果.所属节点 != 请求.所属节点
        || 结果.历史截止事实代次 != 请求.历史截止事实代次
        || 结果.读取事实代次 != 实际代次) return false;
    for (std::size_t 索引 = 0; 索引 < 结果.属性值组.size(); ++索引) {
        const auto& 事实 = 结果.属性值组[索引];
        if (事实.所属节点 != 请求.所属节点 || !海中鱼巣::有效(事实.编码)
            || !海中鱼巣::有效(事实.属性类型节点)
            || !海中鱼巣::有效(事实.来源节点) || 事实.创建事实代次 == 0
            || 事实.创建事实代次 > 请求.历史截止事实代次
            || (事实.退出事实代次
                && 请求.历史截止事实代次 >= *事实.退出事实代次)) return false;
        if (索引 != 0) {
            const auto& 前 = 结果.属性值组[索引 - 1];
            if (!(前.属性类型节点 < 事实.属性类型节点)
                && !(前.属性类型节点 == 事实.属性类型节点
                    && 前.编码 < 事实.编码)) return false;
        }
    }
    return true;
}

bool 非成功空组(const 海中鱼巣::L1中性历史属性值组读取结果& 结果,
    const 海中鱼巣::L1中性历史属性值组读取请求& 请求,
    海中鱼巣::L1中性历史属性值组读取状态 状态,
    std::uint64_t 读取代次 = 0) noexcept {
    return 结果.状态 == 状态
        && 结果.合同版本 == 海中鱼巣::L1中性CRUD合同版本
        && 结果.所属节点 == 请求.所属节点
        && 结果.历史截止事实代次 == 请求.历史截止事实代次
        && 结果.读取事实代次 == 读取代次 && 结果.属性值组.empty();
}

bool I64材料等于(const 海中鱼巣::L1中性值事实& 事实,
    std::int64_t 期望) noexcept {
    const auto* 值 = std::get_if<std::int64_t>(&事实.材料);
    return 值 && *值 == 期望;
}

