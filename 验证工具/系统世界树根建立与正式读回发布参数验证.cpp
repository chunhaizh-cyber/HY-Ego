template<class 类型>
bool 同址(const 类型& 左, const 类型& 右) noexcept {
    return std::addressof(左) == std::addressof(右);
}

enum class 脚本异常 { 无, 分配失败, 其它异常 };

template<class 结果类型>
struct 脚本步骤 final {
    结果类型 结果{};
    脚本异常 异常 = 脚本异常::无;
};

struct 脚本化场景结构访问器 final {
    std::vector<脚本步骤<L2场景树结构登记结果>> 登记步骤;
    std::vector<脚本步骤<L2场景树节点写入结果>> 建立步骤;
    std::vector<脚本步骤<L2场景树读取结果>> 读取步骤;
    std::size_t 登记索引 = 0;
    std::size_t 建立索引 = 0;
    std::size_t 读取索引 = 0;
    std::vector<std::string> 调用序列;
    std::vector<L2场景树根建立请求> 建立请求组;

    template<class 结果类型>
    static 结果类型 执行(const 脚本步骤<结果类型>& 步骤) {
        if (步骤.异常 == 脚本异常::分配失败) throw std::bad_alloc{};
        if (步骤.异常 == 脚本异常::其它异常) throw std::runtime_error("脚本异常");
        return 步骤.结果;
    }

    L2场景树结构登记结果 读取当前场景树结构登记() {
        调用序列.emplace_back("登记读");
        if (登记索引 >= 登记步骤.size())
            throw std::runtime_error("登记脚本耗尽");
        return 执行(登记步骤[登记索引++]);
    }

    L2场景树节点写入结果 建立场景树根(
        const L2场景树根建立请求& 请求) {
        调用序列.emplace_back("根建立");
        建立请求组.push_back(请求);
        if (建立索引 >= 建立步骤.size())
            throw std::runtime_error("建立脚本耗尽");
        return 执行(建立步骤[建立索引++]);
    }

    L2场景树读取结果 读取场景树(const L2场景树读取请求&) {
        调用序列.emplace_back("整树读");
        if (读取索引 >= 读取步骤.size())
            throw std::runtime_error("读取脚本耗尽");
        return 执行(读取步骤[读取索引++]);
    }
};

bool 发布值相同(const 系统世界树根读回& 左,
    const 系统世界树根读回& 右) noexcept {
    return 系统世界树根初始化内部::请求相同(左.选择, 右.选择)
        && 左.首次建立请求 == 右.首次建立请求
        && 左.树 == 右.树 && 左.根场景 == 右.根场景
        && 系统世界树根初始化内部::场景树事实相同(
            左.正式树读回, 右.正式树读回)
        && 左.事实截止代次 == 右.事实截止代次;
}

bool 发布槽相同(const std::optional<系统世界树根读回>& 左,
    const std::optional<系统世界树根读回>& 右) noexcept {
    return 左.has_value() == 右.has_value()
        && (!左 || 发布值相同(*左, *右));
}

std::string 序列文本(const std::vector<std::string>& 序列) {
    if (序列.empty()) return "零调用";
    std::string 文本;
    for (const auto& 当前 : 序列) {
        if (!文本.empty()) 文本 += " -> ";
        文本 += 当前;
    }
    return 文本;
}

void 输出用例结果(const char* 名称, const char* 输入脚本,
    const std::vector<std::string>& 序列,
    const 系统世界树根初始化结果& 结果,
    const std::optional<L2场景树根建立请求>& 待收敛前,
    const std::optional<L2场景树根建立请求>& 待收敛后,
    const std::optional<系统世界树根读回>& 发布前,
    const std::optional<系统世界树根读回>& 发布后,
    const std::optional<bool>& L2成功先验 = std::nullopt) {
    std::cout << "[CASE] " << 名称 << '\n'
        << "  输入脚本=" << 输入脚本 << '\n'
        << "  实际调用序列=" << 序列文本(序列) << '\n'
        << "  L2成功先验=";
    if (L2成功先验) std::cout << (*L2成功先验 ? "true" : "false") << '\n';
    else std::cout << "不适用\n";
    std::cout
        << "  结果状态=" << static_cast<int>(结果.状态) << '\n'
        << "  六optional=来源:" << 结果.来源.has_value()
        << ",根建立前登记:" << 结果.根建立前登记读取.has_value()
        << ",根建立:" << 结果.根建立.has_value()
        << ",根读回前登记:" << 结果.根读回前登记读取.has_value()
        << ",根读取:" << 结果.根读取.has_value()
        << ",已发布根:" << 结果.已发布根.has_value() << '\n'
        << "  待收敛槽前后=" << 待收敛前.has_value() << " -> "
        << 待收敛后.has_value() << '\n'
        << "  发布槽前后=" << 发布前.has_value() << " -> "
        << 发布后.has_value() << '\n';
}

