struct 参数 final {
    std::uint64_t 幂等基值 = 81000;
    std::int64_t 起始初始I64 = 101;
    std::uint64_t 起始换代U64一 = 202;
    std::uint64_t 起始换代U64二 = 303;
    std::int64_t 结束初始I64 = 404;
    std::int64_t 结束换代I64 = 505;
};

bool 解析参数(int 数量, char** 值, 参数& 结果) {
    try {
        for (int 索引 = 1; 索引 + 1 < 数量; 索引 += 2) {
            const std::string 名称 = 值[索引];
            const std::string 文本 = 值[索引 + 1];
            if (名称 == "--幂等基值") 结果.幂等基值 = std::stoull(文本);
            else if (名称 == "--起始初始I64") 结果.起始初始I64 = std::stoll(文本);
            else if (名称 == "--起始换代U64一") 结果.起始换代U64一 = std::stoull(文本);
            else if (名称 == "--起始换代U64二") 结果.起始换代U64二 = std::stoull(文本);
            else if (名称 == "--结束初始I64") 结果.结束初始I64 = std::stoll(文本);
            else if (名称 == "--结束换代I64") 结果.结束换代I64 = std::stoll(文本);
            else return false;
        }
        return 数量 % 2 == 1;
    } catch (...) { return false; }
}

struct 验证器 final {
    int 失败数 = 0;
    void 检查(bool 条件, const char* 名称) {
        std::cout << (条件 ? "[PASS] " : "[FAIL] ") << 名称 << '\n';
        if (!条件) ++失败数;
    }
};

std::vector<稳定编码> 形成闭包(
    const L2动态事实& 动态, const L2动态自有关系引用& 关系) {
    std::vector<稳定编码> 结果{关系.族归属关系稳定编码,
        关系.主体关系稳定编码, 关系.前状态关系稳定编码,
        关系.后状态关系稳定编码, 动态.起始时间值.值稳定编码,
        动态.结束时间值.值稳定编码};
    std::sort(结果.begin(), 结果.end());
    return 结果;
}

bool 包含动态(const L2当前动态组读取结果& 组, L2动态身份 动态) {
    return std::ranges::any_of(组.动态,
        [&](const auto& 项) { return 项.身份 == 动态; });
}
