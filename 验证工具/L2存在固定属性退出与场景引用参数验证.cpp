bool I64等于(const 海中鱼巣::L2属性事实& 属性, std::int64_t 值) noexcept {
    const auto* 实际 = std::get_if<std::int64_t>(&属性.类型化不可变材料);
    return 实际 && *实际 == 值;
}

std::vector<海中鱼巣::稳定编码> 属性编码(const 海中鱼巣::L2存在事实& 存在) {
    std::vector<海中鱼巣::稳定编码> 结果;
    for (const auto& 属性 : 存在.固定属性) 结果.push_back(属性.值稳定编码);
    std::sort(结果.begin(), 结果.end());
    return 结果;
}

