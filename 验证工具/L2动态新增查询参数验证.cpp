std::uint64_t 当前代次(const L1事实基座服务& 服务) {
    const auto 读取 = 服务.读取中性当前事实代次({L1中性CRUD合同版本});
    return 读取.状态 == L1中性读取状态::成功 ? 读取.事实代次 : 0;
}

