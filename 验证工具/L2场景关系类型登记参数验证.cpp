struct 验证参数 final {
    std::uint32_t 合同版本 = 海中鱼巣::L2结构合同版本;
    std::uint32_t 规则版本 = 海中鱼巣::L2场景关系类型登记规则版本;
    std::uint64_t 首次期望事实代次 = 0;
};

std::optional<std::uint64_t> 解析无符号整数(const wchar_t* 文本) noexcept {
    if (!文本 || *文本 == L'\0' || *文本 == L'-') return std::nullopt;
    errno = 0;
    wchar_t* 末尾 = nullptr;
    const auto 值 = std::wcstoull(文本, &末尾, 10);
    if (errno == ERANGE || !末尾 || *末尾 != L'\0') return std::nullopt;
    return static_cast<std::uint64_t>(值);
}

bool 解析参数(int 参数数量, wchar_t* 参数值[], 验证参数& 参数) noexcept {
    for (int 索引 = 1; 索引 < 参数数量; 索引 += 2) {
        if (索引 + 1 >= 参数数量) return false;
        const std::wstring_view 名称{参数值[索引]};
        const auto 值 = 解析无符号整数(参数值[索引 + 1]);
        if (!值) return false;
        if (名称 == L"--合同版本") {
            if (*值 > std::numeric_limits<std::uint32_t>::max()) return false;
            参数.合同版本 = static_cast<std::uint32_t>(*值);
        } else if (名称 == L"--规则版本") {
            if (*值 > std::numeric_limits<std::uint32_t>::max()) return false;
            参数.规则版本 = static_cast<std::uint32_t>(*值);
        } else if (名称 == L"--首次期望事实代次") {
            参数.首次期望事实代次 = *值;
        } else return false;
    }
    return 参数.首次期望事实代次 != std::numeric_limits<std::uint64_t>::max();
}

海中鱼巣::L1中性事实代次读取结果 读取代次(
    const 海中鱼巣::L1事实基座服务& 服务) {
    return 服务.读取中性当前事实代次({海中鱼巣::L1中性CRUD合同版本});
}

bool 登记核心相同(const 海中鱼巣::L2场景关系类型登记& 左,
    const 海中鱼巣::L2场景关系类型登记& 右) noexcept {
    return 左.合同版本 == 右.合同版本 && 左.规则版本 == 右.规则版本
        && 左.首次幂等身份 == 右.首次幂等身份
        && 左.首次期望事实代次 == 右.首次期望事实代次
        && 左.建立事实代次 == 右.建立事实代次
        && 左.父子关系类型 == 右.父子关系类型
        && 左.成员关系类型 == 右.成员关系类型;
}

bool 两节点权威投影完整(const 海中鱼巣::L1中性一致当前读取结果& 读取,
    const 海中鱼巣::L2场景关系类型登记& 登记) noexcept {
    if (读取.状态 != 海中鱼巣::L1中性一致当前读取状态::成功
        || 读取.合同版本 != 海中鱼巣::L1中性一致当前读取合同版本
        || 读取.期望事实代次 != 登记.事实截止代次
        || 读取.读取事实代次 != 登记.事实截止代次
        || 读取.节点.size() != 2 || !读取.关系.empty() || !读取.值.empty()
        || !读取.属性值.empty() || !读取.源关系组.empty()
        || !读取.目标关系组.empty()) return false;
    const auto& 父子 = 读取.节点[0];
    const auto& 成员 = 读取.节点[1];
    if (父子.查询编码 != 登记.父子关系类型.值
        || 成员.查询编码 != 登记.成员关系类型.值
        || 父子.状态 != 海中鱼巣::L1中性一致当前读取项目状态::成功
        || 成员.状态 != 海中鱼巣::L1中性一致当前读取项目状态::成功
        || !父子.事实 || !成员.事实) return false;
    const auto 节点完整 = [&](const auto& 节点, auto 编码) {
        return 节点.编码 == 编码 && 节点.种类 == 海中鱼巣::节点种类::普通
            && !节点.属性类型表示 && 节点.当前属性.empty()
            && 节点.创建事实代次 == 登记.建立事实代次
            && !节点.退出事实代次;
    };
    return 节点完整(*父子.事实, 登记.父子关系类型.值)
        && 节点完整(*成员.事实, 登记.成员关系类型.值);
}

海中鱼巣::L1中性一致当前读取结果 读取两节点投影(
    const 海中鱼巣::L1事实基座服务& L1,
    const 海中鱼巣::L2场景关系类型登记& 登记) {
    海中鱼巣::L1中性一致当前读取请求 请求;
    请求.合同版本 = 海中鱼巣::L1中性一致当前读取合同版本;
    请求.期望事实代次 = 登记.事实截止代次;
    请求.节点 = {登记.父子关系类型.值, 登记.成员关系类型.值};
    return L1.尝试读取中性一致当前投影(请求);
}

bool 失败无登记(const 海中鱼巣::L2场景关系类型登记结果& 结果,
    海中鱼巣::L2场景关系类型登记状态 状态,
    std::uint64_t 截止 = 0) noexcept {
    return 结果.状态 == 状态 && 结果.事实截止代次 == 截止
        && !结果.登记 && !结果.成功();
}

