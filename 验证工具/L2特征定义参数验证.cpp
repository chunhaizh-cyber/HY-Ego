struct 验证参数 final {
    std::uint64_t 幂等基值 = 21000;
    std::int64_t 初始I64 = 11;
    std::int64_t 换代I64 = 22;
};

std::optional<std::uint64_t> 解析无符号(const wchar_t* 文本) noexcept {
    if (!文本 || *文本 == L'\0' || *文本 == L'-') return std::nullopt;
    errno = 0;
    wchar_t* 末尾 = nullptr;
    const auto 值 = std::wcstoull(文本, &末尾, 10);
    if (errno == ERANGE || !末尾 || *末尾 != L'\0') return std::nullopt;
    return static_cast<std::uint64_t>(值);
}

std::optional<std::int64_t> 解析有符号(const wchar_t* 文本) noexcept {
    if (!文本 || *文本 == L'\0') return std::nullopt;
    errno = 0;
    wchar_t* 末尾 = nullptr;
    const auto 值 = std::wcstoll(文本, &末尾, 10);
    if (errno == ERANGE || !末尾 || *末尾 != L'\0') return std::nullopt;
    return static_cast<std::int64_t>(值);
}

bool 解析参数(int 数量, wchar_t* 值组[], 验证参数& 参数) noexcept {
    for (int 索引 = 1; 索引 < 数量; 索引 += 2) {
        if (索引 + 1 >= 数量) return false;
        const std::wstring_view 名称{值组[索引]};
        if (名称 == L"--初始I64" || 名称 == L"--换代I64") {
            const auto 值 = 解析有符号(值组[索引 + 1]);
            if (!值) return false;
            if (名称 == L"--初始I64") 参数.初始I64 = *值;
            else 参数.换代I64 = *值;
        } else if (名称 == L"--幂等基值") {
            const auto 值 = 解析无符号(值组[索引 + 1]);
            if (!值) return false;
            参数.幂等基值 = *值;
        } else {
            return false;
        }
    }
    const auto 最大 = static_cast<std::uint64_t>(
        std::numeric_limits<std::int64_t>::max());
    return 参数.幂等基值 > 100 && 参数.幂等基值 < 最大 - 10000;
}

std::uint64_t 当前代次(const 海中鱼巣::L1事实基座服务& 服务) {
    const auto 结果 = 服务.读取中性当前事实代次(
        {海中鱼巣::L1中性CRUD合同版本});
    return 结果.状态 == 海中鱼巣::L1中性读取状态::成功
        ? 结果.事实代次 : 0;
}

std::optional<海中鱼巣::稳定编码> 查编码(
    const 海中鱼巣::L1中性写入结果& 结果, std::uint32_t 键值) {
    std::optional<海中鱼巣::稳定编码> 找到;
    for (const auto& [键, 编码] : 结果.新编码映射) {
        if (键.值 != 键值) continue;
        if (找到) return std::nullopt;
        找到 = 编码;
    }
    return 找到;
}

bool 创建失败空载荷(const 海中鱼巣::L2特征定义写入结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.特征定义
        && !结果.结果头.变更事实代次;
}

bool 属性失败空载荷(const 海中鱼巣::L2特征定义固定属性写入结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.当前属性
        && !结果.已退出属性 && !结果.结果头.变更事实代次;
}

bool 退出失败空载荷(const 海中鱼巣::L2特征定义退出结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.已退出特征定义
        && !结果.结果头.变更事实代次;
}

bool 读取失败空载荷(const 海中鱼巣::L2特征定义完整读取结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.特征定义
        && !结果.结果头.变更事实代次;
}

bool 有符号材料等于(
    const 海中鱼巣::L2属性事实& 属性, std::int64_t 值) noexcept {
    const auto* 实际 = std::get_if<std::int64_t>(&属性.类型化不可变材料);
    return 实际 && *实际 == 值;
}

std::vector<海中鱼巣::稳定编码> 属性编码(
    const 海中鱼巣::L2特征定义事实& 特征定义) {
    std::vector<海中鱼巣::稳定编码> 结果;
    for (const auto& 属性 : 特征定义.固定属性)
        结果.push_back(属性.值稳定编码);
    std::sort(结果.begin(), 结果.end());
    return 结果;
}

海中鱼巣::L2特征定义身份 创建特征定义(
    海中鱼巣::L2特征结构服务& 服务, std::uint64_t 幂等身份,
    std::uint64_t 期望代次) {
    const auto 结果 = 服务.新增特征定义(
        {{海中鱼巣::L2结构合同版本, 期望代次}, {幂等身份}});
    return 结果.结果头.状态 == 海中鱼巣::L2结构状态::已提交
        && 结果.特征定义 ? 结果.特征定义->身份
        : 海中鱼巣::L2特征定义身份{};
}

