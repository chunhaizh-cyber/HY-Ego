bool 包含子场景(const 海中鱼巣::L2场景完整读取结果& 结果,
    海中鱼巣::L2场景身份 子场景) noexcept {
    if (!结果.场景) return false;
    for (const auto& 关系 : 结果.场景->直接子场景)
        if (关系.子场景 == 子场景) return true;
    return false;
}

bool 包含成员(const 海中鱼巣::L2场景完整读取结果& 结果,
    海中鱼巣::L2存在身份 存在) noexcept {
    if (!结果.场景) return false;
    for (const auto& 关系 : 结果.场景->直接成员)
        if (关系.存在 == 存在) return true;
    return false;
}

bool 稳定排序(const 海中鱼巣::L2场景事实& 场景) noexcept {
    for (std::size_t 索引 = 1; 索引 < 场景.直接子场景.size(); ++索引) {
        const auto& 前 = 场景.直接子场景[索引 - 1];
        const auto& 后 = 场景.直接子场景[索引];
        if (前.顺序 > 后.顺序 || (前.顺序 == 后.顺序
            && !(前.子场景.值 < 后.子场景.值))) return false;
    }
    for (std::size_t 索引 = 1; 索引 < 场景.直接成员.size(); ++索引) {
        const auto& 前 = 场景.直接成员[索引 - 1];
        const auto& 后 = 场景.直接成员[索引];
        if (前.顺序 > 后.顺序 || (前.顺序 == 后.顺序
            && !(前.存在.值 < 后.存在.值))) return false;
    }
    return true;
}

bool 场景投影相同(const 海中鱼巣::L2场景事实& 左,
    const 海中鱼巣::L2场景事实& 右) noexcept {
    if (左.身份 != 右.身份 || 左.生命周期 != 右.生命周期
        || !左.固定属性.empty() || !右.固定属性.empty()
        || 左.直接子场景.size() != 右.直接子场景.size()
        || 左.直接成员.size() != 右.直接成员.size()) return false;
    for (std::size_t 索引 = 0; 索引 < 左.直接子场景.size(); ++索引) {
        if (!父子核心相同(左.直接子场景[索引], 右.直接子场景[索引])
            || 左.直接子场景[索引].生命周期.退出事实代次
                != 右.直接子场景[索引].生命周期.退出事实代次) return false;
    }
    for (std::size_t 索引 = 0; 索引 < 左.直接成员.size(); ++索引) {
        if (!成员核心相同(左.直接成员[索引], 右.直接成员[索引])
            || 左.直接成员[索引].生命周期.退出事实代次
                != 右.直接成员[索引].生命周期.退出事实代次) return false;
    }
    return true;
}

