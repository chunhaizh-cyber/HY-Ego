struct 验证器 final {
    int 通过数 = 0;
    int 失败数 = 0;
    int 未运行数 = 0;

    void 检查(int 矩阵, bool 条件, const char* 名称) {
        std::cout << "[M" << (矩阵 < 10 ? "0" : "") << 矩阵 << "] "
            << (条件 ? "[PASS] " : "[FAIL] ") << 名称 << '\n';
        条件 ? ++通过数 : ++失败数;
    }

    void 未运行(const char* 名称, const char* 原因) {
        std::cout << "[NOT_RUN] " << 名称 << "：" << 原因 << '\n';
        ++未运行数;
    }
};

std::uint64_t 当前代次(const 海中鱼巣::L1事实基座服务& 服务) {
    const auto 结果 = 服务.读取中性当前事实代次(
        {海中鱼巣::L1中性CRUD合同版本});
    return 结果.状态 == 海中鱼巣::L1中性读取状态::成功
        ? 结果.事实代次 : 0;
}

std::optional<海中鱼巣::稳定编码> 查映射(
    const 海中鱼巣::L1所有者范围写入结果& 结果, std::uint32_t 本地键) {
    for (const auto& [键, 编码] : 结果.新编码映射)
        if (键.值 == 本地键) return 编码;
    return std::nullopt;
}

bool 顶层空载荷(
    const 海中鱼巣::L1所有者范围一致关系类型闭包读取结果& 结果) {
    return 结果.所有者.empty() && 结果.节点.empty()
        && 结果.关系.empty() && 结果.值.empty()
        && 结果.属性值.empty() && 结果.源关系组.empty()
        && 结果.目标关系组.empty() && 结果.关系类型闭包.empty();
}

std::vector<海中鱼巣::稳定编码> 升序(
    std::initializer_list<海中鱼巣::稳定编码> 输入) {
    std::vector<海中鱼巣::稳定编码> 结果(输入);
    std::sort(结果.begin(), 结果.end());
    return 结果;
}

const 海中鱼巣::L1所有者范围一致关系类型闭包成员* 查成员(
    const 海中鱼巣::L1所有者范围一致关系类型闭包读取结果项& 项,
    海中鱼巣::稳定编码 源, 海中鱼巣::稳定编码 目标) {
    const auto it = std::find_if(项.成员.begin(), 项.成员.end(),
        [&](const auto& 成员) {
            return 成员.关系.源节点 == 源 && 成员.关系.目标节点 == 目标;
        });
    return it == 项.成员.end() ? nullptr : &*it;
}

const 海中鱼巣::L1所有者范围一致闭包端点关系组读取结果项* 查关系组(
    const std::vector<海中鱼巣::L1所有者范围一致闭包端点关系组读取结果项>& 组,
    海中鱼巣::稳定编码 类型) {
    const auto it = std::find_if(组.begin(), 组.end(),
        [&](const auto& 项) { return 项.关系类型节点 == 类型; });
    return it == 组.end() ? nullptr : &*it;
}

const 海中鱼巣::L1所有者范围一致属性值读取结果项* 查属性(
    const std::vector<海中鱼巣::L1所有者范围一致属性值读取结果项>& 组,
    海中鱼巣::稳定编码 类型) {
    const auto it = std::find_if(组.begin(), 组.end(),
        [&](const auto& 项) { return 项.属性类型 == 类型; });
    return it == 组.end() ? nullptr : &*it;
}

