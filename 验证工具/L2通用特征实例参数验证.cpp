struct 验证参数 final {
    std::uint64_t 幂等基值 = 31000;
    std::uint64_t 实例数量 = 3;
};

std::optional<std::uint64_t> 解析无符号整数(const wchar_t* 文本) noexcept {
    if (!文本 || *文本 == L'\0' || *文本 == L'-') return std::nullopt;
    errno = 0;
    wchar_t* 末尾 = nullptr;
    const auto 值 = std::wcstoull(文本, &末尾, 10);
    if (errno == ERANGE || !末尾 || *末尾 != L'\0') return std::nullopt;
    return static_cast<std::uint64_t>(值);
}

bool 解析参数(int 参数数量, wchar_t* 参数值[], 验证参数& 参数) noexcept {
    for (int 索引 = 1; 索引 < 参数数量; 索引 += 2) {
        if (索引 + 1 >= 参数数量) return false;
        const std::wstring_view 名称{参数值[索引]};
        const auto 值 = 解析无符号整数(参数值[索引 + 1]);
        if (!值) return false;
        if (名称 == L"--幂等基值") 参数.幂等基值 = *值;
        else if (名称 == L"--实例数量") 参数.实例数量 = *值;
        else return false;
    }
    return 参数.幂等基值 > 100
        && 参数.幂等基值 < std::numeric_limits<std::uint64_t>::max() - 1000
        && 参数.实例数量 >= 1 && 参数.实例数量 <= 16;
}

std::uint64_t 读取当前代次(const 海中鱼巣::L1事实基座服务& 服务) {
    const auto 结果 = 服务.读取中性当前事实代次(
        {海中鱼巣::L1中性CRUD合同版本});
    return 结果.状态 == 海中鱼巣::L1中性读取状态::成功
        ? 结果.事实代次 : 0;
}

海中鱼巣::L2存在身份 创建存在(海中鱼巣::L2存在结构服务& 服务,
    std::uint64_t 幂等, std::uint64_t 期望) {
    const auto 结果 = 服务.新增存在节点(
        {{海中鱼巣::L2结构合同版本, 期望}, {幂等}});
    return 结果.结果头.状态 == 海中鱼巣::L2结构状态::已提交 && 结果.存在
        ? 结果.存在->身份 : 海中鱼巣::L2存在身份{};
}

海中鱼巣::L2特征定义身份 创建定义(海中鱼巣::L2特征结构服务& 服务,
    std::uint64_t 幂等, std::uint64_t 期望) {
    const auto 结果 = 服务.新增特征定义(
        {{海中鱼巣::L2结构合同版本, 期望}, {幂等}});
    return 结果.结果头.状态 == 海中鱼巣::L2结构状态::已提交 && 结果.特征定义
        ? 结果.特征定义->身份 : 海中鱼巣::L2特征定义身份{};
}

bool 写失败空载荷(const 海中鱼巣::L2特征实例写入结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.特征实例
        && !结果.结果头.变更事实代次;
}

bool 读失败空载荷(const 海中鱼巣::L2特征实例完整读取结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.特征实例
        && !结果.结果头.变更事实代次;
}

bool 组失败空载荷(const 海中鱼巣::L2按存在当前特征读取结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && 结果.特征实例组.empty()
        && !结果.结果头.变更事实代次;
}

bool 实例核心相同(const 海中鱼巣::L2特征实例事实& 左,
    const 海中鱼巣::L2特征实例事实& 右) noexcept {
    return 左.身份 == 右.身份 && 左.宿主存在 == 右.宿主存在
        && 左.特征定义 == 右.特征定义
        && 左.生命周期.创建事实代次 == 右.生命周期.创建事实代次
        && !左.当前值 && !右.当前值;
}

bool 严格升序且宿主一致(const 海中鱼巣::L2按存在当前特征读取结果& 结果,
    海中鱼巣::L2存在身份 宿主) noexcept {
    if (!结果.成功()) return false;
    for (std::size_t 索引 = 0; 索引 < 结果.特征实例组.size(); ++索引) {
        if (结果.特征实例组[索引].宿主存在 != 宿主
            || 结果.特征实例组[索引].当前值) return false;
        if (索引 != 0 && !(结果.特征实例组[索引 - 1].身份.值
            < 结果.特征实例组[索引].身份.值)) return false;
    }
    return true;
}

