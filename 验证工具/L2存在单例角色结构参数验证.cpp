namespace {

std::optional<std::uint64_t> 读取当前代次(
    const 海中鱼巣::L1事实基座服务& 第一层服务) {
    const auto 结果 = 第一层服务.读取中性当前事实代次(
        {海中鱼巣::L1中性CRUD合同版本});
    if (结果.状态 != 海中鱼巣::L1中性读取状态::成功
        || 结果.合同版本 != 海中鱼巣::L1中性CRUD合同版本
        || 结果.事实代次 == 0)
        return std::nullopt;
    return 结果.事实代次;
}

} // namespace

int wmain() {
    int 失败数 = 0;
    int 用例数 = 0;
    const auto 检查 = [&](bool 条件, const char* 名称) {
        ++用例数;
        std::cout << (条件 ? "[PASS] " : "[FAIL] ") << 名称 << '\n';
        if (!条件) ++失败数;
    };

    auto 运行包 = 海中鱼巣::建立L1事实基座运行包();
    auto 原始交付 = 运行包.所有者范围签发器().建立所有者范围(
        {海中鱼巣::L1所有者范围CRUD合同版本,
            海中鱼巣::存在所有者建立身份,
            海中鱼巣::L1所有者范围种类::独占结构范围});
    检查((原始交付.建立结果.状态
                == 海中鱼巣::L1所有者范围管理状态::成功
            || 原始交付.建立结果.状态
                == 海中鱼巣::L1所有者范围管理状态::精确重复)
            && 原始交付.写入端口.has_value(),
        "存在所有者范围建立");
    auto 存在所有者交付 = 海中鱼巣::尝试形成L2存在所有者交付(
        运行包.读取服务(), std::move(原始交付));
    检查(存在所有者交付.has_value(), "存在所有者交付形成");
    if (!存在所有者交付) return 1;

    auto 存在服务 = std::make_unique<海中鱼巣::L2存在结构服务>(
        运行包.读取服务(), std::move(*存在所有者交付));
    auto 当前代次 = 读取当前代次(运行包.读取服务());
    const auto 登记读取 = 存在服务->读取当前存在单例角色结构登记();
    检查(当前代次 && 登记读取.成功() && 登记读取.登记
            && 海中鱼巣::L2存在单例角色结构登记完整(*登记读取.登记)
            && 登记读取.登记->事实截止代次 == *当前代次,
        "构造期登记及正式读回");
    if (!当前代次 || !登记读取.登记) return 1;
    const auto 登记 = *登记读取.登记;

    const 海中鱼巣::L2存在单例角色结构登记请求 登记请求{
        {海中鱼巣::L2结构合同版本, 登记.首次期望事实代次},
        登记.规则版本, 登记.首次幂等身份};
    const auto 登记重复 = 存在服务->建立存在单例角色结构登记(登记请求);
    检查(登记重复.成功()
            && 登记重复.结果头.状态 == 海中鱼巣::L2结构状态::精确重复
            && 登记重复.登记 == 登记读取.登记,
        "固定登记精确重复");

    const 海中鱼巣::L2角色化存在新增请求 角色化请求{
        {海中鱼巣::L2结构合同版本, *当前代次}, {1001}, {101}};
    const auto 角色化 = 存在服务->新增角色化存在(角色化请求);
    检查(角色化.成功()
            && 角色化.结果头.状态 == 海中鱼巣::L2结构状态::已提交
            && 角色化.存在 && 角色化.存在身份来源 && 角色化.当前角色关系
            && 角色化.存在->身份 == 角色化.当前角色关系->存在
            && 角色化.存在->生命周期.创建事实代次
                == 角色化.当前角色关系->生命周期.创建事实代次
            && 角色化.存在->生命周期.创建事实代次
                == 角色化.结果头.事实截止代次,
        "存在族归属角色关系三项原子创建");
    if (!角色化.存在 || !角色化.存在身份来源 || !角色化.当前角色关系)
        return 1;
    const auto 角色化重复 = 存在服务->新增角色化存在(角色化请求);
    检查(角色化重复.成功()
            && 角色化重复.结果头.状态 == 海中鱼巣::L2结构状态::精确重复
            && 角色化重复.存在
            && 角色化重复.存在->身份 == 角色化.存在->身份
            && 角色化重复.存在->生命周期 == 角色化.存在->生命周期
            && 角色化重复.存在->固定属性.empty()
            && 角色化重复.当前角色关系 == 角色化.当前角色关系,
        "角色化存在精确重复");

    auto 同键异义请求 = 角色化请求;
    同键异义请求.角色 = {102};
    const auto 同键异义 = 存在服务->新增角色化存在(同键异义请求);
    检查(同键异义.结果头.状态 == 海中鱼巣::L2结构状态::幂等冲突
            && !同键异义.存在 && !同键异义.存在身份来源
            && !同键异义.当前角色关系,
        "同键异义拒绝");

    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 新增甲 = 存在服务->新增存在节点(
        {{海中鱼巣::L2结构合同版本, *当前代次}, {1101}});
    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 新增乙 = 存在服务->新增存在节点(
        {{海中鱼巣::L2结构合同版本, *当前代次}, {1102}});
    检查(新增甲.存在 && 新增乙.存在, "建立两个既有正式存在");
    if (!新增甲.存在 || !新增乙.存在) return 1;

    当前代次 = 读取当前代次(运行包.读取服务());
    const 海中鱼巣::L2存在单例角色绑定请求 绑定请求{
        {海中鱼巣::L2结构合同版本, *当前代次}, {1201}, {102},
        新增甲.存在->身份};
    const auto 绑定 = 存在服务->绑定存在单例角色(绑定请求);
    检查(绑定.成功() && 绑定.当前角色关系
            && !绑定.已退出角色关系
            && 绑定.当前角色关系->存在 == 新增甲.存在->身份,
        "既有存在绑定角色");
    if (!绑定.当前角色关系) return 1;

    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 唯一冲突 = 存在服务->绑定存在单例角色(
        {{海中鱼巣::L2结构合同版本, *当前代次}, {1202}, {102},
            新增乙.存在->身份});
    检查(唯一冲突.结果头.状态 == 海中鱼巣::L2结构状态::引用冲突
            && !唯一冲突.当前角色关系 && !唯一冲突.已退出角色关系,
        "角色唯一冲突拒绝");

    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 替换 = 存在服务->替换存在单例角色目标(
        {{海中鱼巣::L2结构合同版本, *当前代次}, {1301}, {102},
            绑定.当前角色关系->关系稳定编码, 新增甲.存在->身份,
            新增乙.存在->身份});
    检查(替换.成功() && 替换.当前角色关系 && 替换.已退出角色关系
            && 替换.当前角色关系->存在 == 新增乙.存在->身份
            && 替换.已退出角色关系->存在 == 新增甲.存在->身份,
        "角色目标原子替换");
    if (!替换.当前角色关系) return 1;

    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 当前读取 = 存在服务->读取存在单例角色(
        {{海中鱼巣::L2结构合同版本, *当前代次},
            海中鱼巣::L2读取类别::当前, {102}, 0});
    const auto 历史读取 = 存在服务->读取存在单例角色(
        {{海中鱼巣::L2结构合同版本, *当前代次},
            海中鱼巣::L2读取类别::历史, {102},
            绑定.结果头.事实截止代次});
    检查(当前读取.成功() && 当前读取.角色关系
            && 当前读取.角色关系->存在 == 新增乙.存在->身份
            && 历史读取.成功() && 历史读取.角色关系
            && 历史读取.角色关系->存在 == 新增甲.存在->身份,
        "当前与历史按截止读取");

    const auto 漂移 = 存在服务->绑定存在单例角色(
        {{海中鱼巣::L2结构合同版本, *当前代次 - 1}, {1401}, {103},
            新增甲.存在->身份});
    检查(漂移.结果头.状态 == 海中鱼巣::L2结构状态::事实代次漂移
            && !漂移.当前角色关系 && !漂移.已退出角色关系,
        "旧代次漂移拒绝");

    const auto 非法前代次 = 读取当前代次(运行包.读取服务());
    const auto 非法 = 存在服务->绑定存在单例角色(
        {{海中鱼巣::L2结构合同版本, *非法前代次}, {1402}, {},
            新增甲.存在->身份});
    const auto 非法后代次 = 读取当前代次(运行包.读取服务());
    检查(非法.结果头.状态 == 海中鱼巣::L2结构状态::入口拒绝
            && 非法前代次 == 非法后代次,
        "非法角色入口拒绝且零变化");

    const 海中鱼巣::L2存在单例角色绑定请求 裸节点请求{
        {海中鱼巣::L2结构合同版本, *非法后代次}, {1403}, {103},
        海中鱼巣::L2存在身份{登记.角色登记锚点稳定编码}};
    std::cout << "[INFO] 裸L1请求有效="
        << 海中鱼巣::L2存在单例角色绑定请求有效(裸节点请求)
        << " 截止=" << 裸节点请求.请求头.期望事实代次
        << " 幂等=" << 裸节点请求.幂等身份.值
        << " 角色=" << 裸节点请求.角色.值
        << " 目标=" << 裸节点请求.存在.值.值 << '\n';
    const auto 裸节点 = 存在服务->绑定存在单例角色(裸节点请求);
    std::cout << "[INFO] 裸L1绑定状态="
        << static_cast<unsigned>(裸节点.结果头.状态) << '\n';
    const auto 裸节点后代次 = 读取当前代次(运行包.读取服务());
    检查(裸节点.结果头.状态 == 海中鱼巣::L2结构状态::入口拒绝
            && !裸节点.当前角色关系 && !裸节点.已退出角色关系
            && 裸节点后代次 == 非法后代次,
        "裸L1节点不被接受为正式存在");

    auto 场景原始交付 = 运行包.所有者范围签发器().建立所有者范围(
        {海中鱼巣::L1所有者范围CRUD合同版本,
            海中鱼巣::场景所有者建立身份,
            海中鱼巣::L1所有者范围种类::独占结构范围});
    auto 场景所有者交付 = 海中鱼巣::尝试形成L2场景所有者交付(
        运行包.读取服务(), std::move(场景原始交付));
    if (!场景所有者交付) return 1;
    auto 场景服务 = std::make_unique<海中鱼巣::L2场景结构服务>(
        运行包.读取服务(), *存在服务, std::move(*场景所有者交付));
    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 场景根 = 场景服务->建立场景树根(
        {{海中鱼巣::L2结构合同版本, *当前代次}, {1900}});
    if (!场景根.成功() || !场景根.场景节点) return 1;
    const auto 错族前代次 = 读取当前代次(运行包.读取服务());
    const auto 错族 = 存在服务->绑定存在单例角色(
        {{海中鱼巣::L2结构合同版本, *错族前代次}, {1901}, {105},
            海中鱼巣::L2存在身份{场景根.场景节点->场景.身份.值}});
    const auto 错族后代次 = 读取当前代次(运行包.读取服务());
    检查(!错族.成功() && !错族.当前角色关系 && !错族.已退出角色关系
            && 错族前代次 == 错族后代次,
        "正式场景族节点不被接受为存在目标");

    const auto 保护前代次 = 读取当前代次(运行包.读取服务());
    const auto 引用保护 = 存在服务->退出存在(
        {{海中鱼巣::L2结构合同版本, *保护前代次}, {1501},
            角色化.存在->身份,
            角色化.存在身份来源->族归属关系稳定编码, {}});
    const auto 保护后代次 = 读取当前代次(运行包.读取服务());
    检查(引用保护.结果头.状态 == 海中鱼巣::L2结构状态::引用冲突
            && !引用保护.已退出存在 && 保护前代次 == 保护后代次,
        "当前角色引用保护存在退出");

    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 退出 = 存在服务->退出存在单例角色(
        {{海中鱼巣::L2结构合同版本, *当前代次}, {1601}, {102},
            替换.当前角色关系->关系稳定编码, 新增乙.存在->身份});
    检查(退出.成功() && !退出.当前角色关系 && 退出.已退出角色关系
            && 退出.已退出角色关系->存在 == 新增乙.存在->身份,
        "角色关系退出");

    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 退出后当前 = 存在服务->读取存在单例角色(
        {{海中鱼巣::L2结构合同版本, *当前代次},
            海中鱼巣::L2读取类别::当前, {102}, 0});
    const auto 退出前历史 = 存在服务->读取存在单例角色(
        {{海中鱼巣::L2结构合同版本, *当前代次},
            海中鱼巣::L2读取类别::历史, {102},
            替换.结果头.事实截止代次});
    检查(退出后当前.结果头.状态 == 海中鱼巣::L2结构状态::未找到
            && !退出后当前.角色关系 && 退出前历史.成功()
            && 退出前历史.角色关系
            && 退出前历史.角色关系->存在 == 新增乙.存在->身份,
        "退出后当前为空且历史守恒");

    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 并发甲存在 = 存在服务->新增存在节点(
        {{海中鱼巣::L2结构合同版本, *当前代次}, {1701}});
    当前代次 = 读取当前代次(运行包.读取服务());
    const auto 并发乙存在 = 存在服务->新增存在节点(
        {{海中鱼巣::L2结构合同版本, *当前代次}, {1702}});
    检查(并发甲存在.存在 && 并发乙存在.存在, "建立并发候选存在");
    if (!并发甲存在.存在 || !并发乙存在.存在) return 1;

    当前代次 = 读取当前代次(运行包.读取服务());
    std::atomic<bool> 开始{false};
    海中鱼巣::L2存在单例角色写入结果 并发甲;
    海中鱼巣::L2存在单例角色写入结果 并发乙;
    std::thread 线程甲([&] {
        while (!开始.load(std::memory_order_acquire)) std::this_thread::yield();
        并发甲 = 存在服务->绑定存在单例角色(
            {{海中鱼巣::L2结构合同版本, *当前代次}, {1801}, {104},
                并发甲存在.存在->身份});
    });
    std::thread 线程乙([&] {
        while (!开始.load(std::memory_order_acquire)) std::this_thread::yield();
        并发乙 = 存在服务->绑定存在单例角色(
            {{海中鱼巣::L2结构合同版本, *当前代次}, {1802}, {104},
                并发乙存在.存在->身份});
    });
    开始.store(true, std::memory_order_release);
    线程甲.join();
    线程乙.join();
    const int 并发成功数 = static_cast<int>(并发甲.成功())
        + static_cast<int>(并发乙.成功());
    检查(并发成功数 == 1
            && ((并发甲.成功() && !并发乙.成功())
                || (!并发甲.成功() && 并发乙.成功())),
        "并发同角色不同目标至多一个成功");

    std::cout << "验证结论：" << (失败数 == 0 ? "PASS" : "FAIL")
        << "，用例数=" << 用例数 << "，失败数=" << 失败数 << '\n';
    return 失败数 == 0 ? 0 : 1;
}
