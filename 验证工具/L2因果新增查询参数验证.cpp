struct 参数 final {
    std::uint64_t 幂等基值 = 91000, 条件一顺序 = 10, 条件二顺序 = 20;
    std::uint64_t 结果一顺序 = 10, 结果二顺序 = 20;
};

std::uint64_t 转换(const char* 值) { return std::stoull(值); }
参数 解析(int 数量, char** 值) {
    参数 结果;
    for (int i = 1; i + 1 < 数量; i += 2) {
        const std::string_view 名称{值[i]};
        const auto 数值 = 转换(值[i + 1]);
        if (名称 == "--幂等基值") 结果.幂等基值 = 数值;
        else if (名称 == "--条件一顺序") 结果.条件一顺序 = 数值;
        else if (名称 == "--条件二顺序") 结果.条件二顺序 = 数值;
        else if (名称 == "--结果一顺序") 结果.结果一顺序 = 数值;
        else if (名称 == "--结果二顺序") 结果.结果二顺序 = 数值;
        else throw std::invalid_argument("unknown argument");
    }
    return 结果;
}

struct 验证器 final {
    int 失败数 = 0;
    void 检查(bool 条件, const char* 名称) {
        std::cout << (条件 ? "[PASS] " : "[FAIL] ") << 名称 << '\n';
        if (!条件) ++失败数;
    }
};

std::uint64_t 当前代次(const L1事实基座服务& 服务) {
    const auto 读 = 服务.读取中性当前事实代次({L1中性CRUD合同版本});
    return 读.状态 == L1中性读取状态::成功 ? 读.事实代次 : 0;
}

bool 严格升序(const std::vector<L2因果事实>& 组) {
    return std::adjacent_find(组.begin(), 组.end(), [](const auto& 左, const auto& 右) {
        return 左.身份.值.值 >= 右.身份.值.值;
    }) == 组.end();
}

bool 空写失败(const L2因果写入结果& 结果, L2结构状态 状态,
    std::uint64_t 前, const L1事实基座服务& L1) {
    return 结果.结果头.状态 == 状态 && !结果.因果 && !结果.自有事实
        && 当前代次(L1) == 前;
}

bool 身份来源字段完整(const L2节点族身份来源事实& 来源,
    L2节点族 族, 稳定编码 节点, L1结构所有者身份 owner,
    std::uint64_t 截止) {
    return 来源.节点族 == 族 && 来源.节点稳定编码 == 节点
        && 来源.写入所有者 == owner && 有效(来源.族锚点稳定编码)
        && 有效(来源.族归属关系类型稳定编码)
        && 有效(来源.族归属关系稳定编码) && 来源.角色或顺序 == 1
        && L2节点族身份来源事实完整(来源, 截止)
        && 来源.所有者生命周期.创建事实代次 <= 截止
        && 来源.节点生命周期.创建事实代次 <= 截止
        && 来源.族锚点生命周期.创建事实代次 <= 截止
        && 来源.关系类型生命周期.创建事实代次 <= 截止
        && 来源.归属关系生命周期.创建事实代次 <= 截止;
}
