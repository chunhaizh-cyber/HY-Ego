struct 验证参数 final {
    std::uint32_t 合同版本 = 海中鱼巣::L1中性CRUD合同版本;
    std::uint64_t 起始幂等键 = 3101;
};

std::optional<std::uint64_t> 解析无符号整数(const wchar_t* 文本) noexcept {
    if (!文本 || *文本 == L'\0' || *文本 == L'-') return std::nullopt;
    errno = 0;
    wchar_t* 末尾 = nullptr;
    const auto 值 = std::wcstoull(文本, &末尾, 10);
    if (errno == ERANGE || !末尾 || *末尾 != L'\0') return std::nullopt;
    return static_cast<std::uint64_t>(值);
}

bool 解析参数(int 参数数量, wchar_t* 参数值[], 验证参数& 参数) noexcept {
    for (int 索引 = 1; 索引 < 参数数量; 索引 += 2) {
        if (索引 + 1 >= 参数数量) return false;
        const std::wstring_view 名称{参数值[索引]};
        const auto 值 = 解析无符号整数(参数值[索引 + 1]);
        if (!值) return false;
        if (名称 == L"--合同版本") {
            if (*值 > std::numeric_limits<std::uint32_t>::max()) return false;
            参数.合同版本 = static_cast<std::uint32_t>(*值);
        } else if (名称 == L"--起始幂等键") {
            参数.起始幂等键 = *值;
        } else return false;
    }
    return 参数.起始幂等键 != 0
        && 参数.起始幂等键 <= std::numeric_limits<std::uint64_t>::max() - 3;
}

std::optional<海中鱼巣::稳定编码> 查新编码(
    const 海中鱼巣::L1中性写入结果& 结果,
    海中鱼巣::L1中性写集本地键 本地键) {
    for (const auto& [键, 编码] : 结果.新编码映射)
        if (键 == 本地键) return 编码;
    return std::nullopt;
}

std::optional<std::uint64_t> 读取当前代次(
    const 海中鱼巣::L1事实基座服务& 服务) {
    const auto 结果 = 服务.读取中性当前事实代次(
        {海中鱼巣::L1中性CRUD合同版本});
    if (结果.状态 != 海中鱼巣::L1中性读取状态::成功
        || 结果.合同版本 != 海中鱼巣::L1中性CRUD合同版本
        || 结果.事实代次 == 0) return std::nullopt;
    return 结果.事实代次;
}

bool 关系组编码等于(const std::vector<海中鱼巣::L1中性关系事实>& 关系组,
    std::vector<海中鱼巣::稳定编码> 期望) {
    std::sort(期望.begin(), 期望.end(), [](const auto 左, const auto 右) {
        return 左.值 < 右.值;
    });
    if (关系组.size() != 期望.size()) return false;
    for (std::size_t 索引 = 0; 索引 < 关系组.size(); ++索引) {
        if (关系组[索引].编码 != 期望[索引]
            || (索引 != 0 && 关系组[索引 - 1].编码.值 >= 关系组[索引].编码.值))
            return false;
    }
    return true;
}

const 海中鱼巣::L1中性关系事实* 查关系(
    const std::vector<海中鱼巣::L1中性关系事实>& 关系组,
    海中鱼巣::稳定编码 编码) {
    const auto 关系 = std::find_if(关系组.begin(), 关系组.end(),
        [&](const auto& 事实) { return 事实.编码 == 编码; });
    return 关系 == 关系组.end() ? nullptr : &*关系;
}

bool 历史成功完整(const 海中鱼巣::L1中性历史关系组读取结果& 结果,
    const 海中鱼巣::L1中性历史关系组读取请求& 请求,
    std::uint64_t 实际代次) {
    if (结果.状态 != 海中鱼巣::L1中性历史关系组读取状态::成功
        || 结果.合同版本 != 海中鱼巣::L1中性CRUD合同版本
        || 结果.方向 != 请求.方向 || 结果.端点节点 != 请求.端点节点
        || 结果.关系类型节点 != 请求.关系类型节点
        || 结果.历史截止事实代次 != 请求.历史截止事实代次
        || 结果.读取事实代次 != 实际代次) return false;
    std::uint64_t 前一编码 = 0;
    for (const auto& 事实 : 结果.关系组) {
        if (事实.编码.值 == 0 || 事实.编码.值 <= 前一编码
            || 事实.关系类型节点 != 请求.关系类型节点
            || (请求.方向 == 海中鱼巣::L1中性关系端点方向::源
                ? 事实.源节点 != 请求.端点节点
                : 事实.目标节点 != 请求.端点节点)
            || 事实.创建事实代次 == 0
            || 事实.创建事实代次 > 请求.历史截止事实代次
            || (事实.退出事实代次
                && 请求.历史截止事实代次 >= *事实.退出事实代次)) return false;
        前一编码 = 事实.编码.值;
    }
    return true;
}

bool 入口拒绝完整(const 海中鱼巣::L1中性历史关系组读取结果& 结果,
    const 海中鱼巣::L1中性历史关系组读取请求& 请求) {
    return 结果.状态 == 海中鱼巣::L1中性历史关系组读取状态::入口拒绝
        && 结果.合同版本 == 海中鱼巣::L1中性CRUD合同版本
        && 结果.方向 == 请求.方向 && 结果.端点节点 == 请求.端点节点
        && 结果.关系类型节点 == 请求.关系类型节点
        && 结果.历史截止事实代次 == 请求.历史截止事实代次
        && 结果.读取事实代次 == 0 && 结果.关系组.empty();
}

