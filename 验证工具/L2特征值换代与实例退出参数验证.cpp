bool 值写失败(const 海中鱼巣::L2特征当前值写入结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.当前值 && !结果.已退出值
        && !结果.结果头.变更事实代次;
}

bool 实例读失败(const 海中鱼巣::L2特征实例完整读取结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.特征实例 && !结果.自有关系
        && !结果.结果头.变更事实代次;
}

bool 退出失败(const 海中鱼巣::L2特征实例退出结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.已退出特征实例
        && !结果.已退出自有关系 && !结果.结果头.变更事实代次;
}

bool 当前值是U64(const 海中鱼巣::L2特征实例完整读取结果& 结果,
    std::uint64_t 值) noexcept {
    if (结果.结果头.状态 != 海中鱼巣::L2结构状态::已读取
        || !结果.特征实例 || !结果.特征实例->当前值) return false;
    const auto* 组 = std::get_if<std::vector<std::uint64_t>>(
        &结果.特征实例->当前值->类型化不可变材料);
    return 组 && *组 == std::vector<std::uint64_t>{值};
}

