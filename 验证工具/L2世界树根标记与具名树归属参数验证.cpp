    代次 = 当前代次(L1);
    const auto 成员后归属 = 场景服务.读取场景树归属({
        {海中鱼巣::L2结构合同版本, 代次}, 海中鱼巣::L2读取类别::当前,
        子甲场景, 0});
    检查(成员.成功() && 成员前归属.树归属 && 成员后归属.树归属
        && 成员前归属.树归属->关系稳定编码
            == 成员后归属.树归属->关系稳定编码,
        "成员关系不改变场景树身份和归属关系");
    const auto 成员请求代次 = 成员.结果头.事实截止代次 - 1;
    const auto 成员关系编码 = 成员.当前关系
        ? 成员.当前关系->关系稳定编码 : 海中鱼巣::稳定编码{};
    const auto 成员重复 = 场景服务.新增场景成员关系({
        {海中鱼巣::L2结构合同版本, 成员请求代次}, {*幂等基值 + 10},
        子甲场景, 存在.存在 ? 存在.存在->身份 : 海中鱼巣::L2存在身份{}, 40});
    检查(成员重复.结果头.状态 == 海中鱼巣::L2结构状态::精确重复
        && 成员重复.成功(), "成员新增原请求精确重复绕过当前态前置");

