    检查(子甲.成功() && 子甲.场景节点 && 子甲.直接父关系
        && 子甲.场景节点->树归属.类别 == 海中鱼巣::L2场景树归属类别::非根
        && 子甲.场景节点->树归属.树 == 树甲
        && 子甲.直接父关系->父场景 == 根甲场景,
        "非根节点四项同代提交并读回");

    const auto 子甲首次代次 = 子甲.结果头.事实截止代次;
    const auto 子甲归属关系 = 子甲.场景节点
        ? 子甲.场景节点->树归属.关系稳定编码 : 海中鱼巣::稳定编码{};
