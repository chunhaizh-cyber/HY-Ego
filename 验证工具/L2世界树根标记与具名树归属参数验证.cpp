std::optional<std::uint64_t> 解析无符号整数(const wchar_t* 文本) noexcept {
    if (!文本 || *文本 == L'\0' || *文本 == L'-') return std::nullopt;
    errno = 0;
    wchar_t* 末尾 = nullptr;
    const auto 值 = std::wcstoull(文本, &末尾, 10);
    if (errno == ERANGE || !末尾 || *末尾 != L'\0') return std::nullopt;
    return static_cast<std::uint64_t>(值);
}

std::optional<std::uint64_t> 解析参数(int 数量, wchar_t* 值[]) noexcept {
    if (数量 == 1) return 81000;
    if (数量 != 3 || std::wstring_view{值[1]} != L"--幂等基值") return std::nullopt;
    const auto 基值 = 解析无符号整数(值[2]);
    const auto 最大 = static_cast<std::uint64_t>(std::numeric_limits<std::int64_t>::max());
    return 基值 && *基值 > 100 && *基值 < 最大 - 1000 ? 基值 : std::nullopt;
}

std::uint64_t 当前代次(const 海中鱼巣::L1事实基座服务& 服务) {
    const auto 结果 = 服务.读取中性当前事实代次({海中鱼巣::L1中性CRUD合同版本});
    return 结果.状态 == 海中鱼巣::L1中性读取状态::成功 ? 结果.事实代次 : 0;
}

bool 失败空载荷(const 海中鱼巣::L2场景树节点写入结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.树 && !结果.场景节点
        && !结果.直接父关系 && !结果.结果头.变更事实代次;
}

bool 失败空载荷(const 海中鱼巣::L2场景父子关系写入结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.当前关系
        && !结果.已退出关系 && !结果.结果头.变更事实代次;
}

bool 退出失败空载荷(const 海中鱼巣::L2场景退出结果& 结果,
    海中鱼巣::L2结构状态 状态) noexcept {
    return 结果.结果头.状态 == 状态 && !结果.已退出场景
        && !结果.已退出身份来源 && !结果.已退出树归属
        && !结果.已退出直接父关系 && !结果.结果头.变更事实代次;
}

bool 树含场景(const 海中鱼巣::L2场景树读取结果& 结果,
    海中鱼巣::L2场景身份 场景) noexcept {
    if (!结果.树) return false;
    for (const auto& 节点 : 结果.树->场景组)
        if (节点.场景.身份 == 场景) return true;
    return false;
}

