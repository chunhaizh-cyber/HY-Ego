    const auto 当前树甲 = 场景服务.读取场景树({
        {海中鱼巣::L2结构合同版本, 代次}, 海中鱼巣::L2读取类别::当前,
        树甲, 0});
    const auto 历史树甲 = 场景服务.读取场景树({
        {海中鱼巣::L2结构合同版本, 代次}, 海中鱼巣::L2读取类别::历史,
        树甲, 历史树截止});
    检查(当前树甲.成功() && 历史树甲.成功()
        && 当前树甲.树->场景组.size() == 3 && 当前树甲.树->父子关系组.size() == 2
        && 历史树甲.树->场景组.size() == 3, "当前和历史整树读回完整");

