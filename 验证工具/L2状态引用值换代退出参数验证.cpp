std::uint64_t 当前代次(const L1事实基座服务& 服务) {
    const auto 读取 = 服务.读取中性当前事实代次({L1中性CRUD合同版本});
    return 读取.状态 == L1中性读取状态::成功 ? 读取.事实代次 : 0;
}

struct 验证器 final {
    int 失败数 = 0;
    void 检查(bool 条件, const char* 名称) {
        std::cout << (条件 ? "[PASS] " : "[FAIL] ") << 名称 << '\n';
        if (!条件) ++失败数;
    }
};

bool 包含状态(const L2当前状态组读取结果& 结果, L2状态身份 状态) {
    return std::any_of(结果.状态.begin(), 结果.状态.end(),
        [&](const L2状态事实& 项) { return 项.身份 == 状态; });
}

template <typename 结果类型>
bool 精确重复保持首次载荷(const 结果类型& 重复, const 结果类型& 首次) {
    return 重复.结果头.状态 == L2结构状态::精确重复
        && 重复.结果头.事实截止代次 == 首次.结果头.事实截止代次
        && 重复.结果头.变更事实代次 == 首次.结果头.变更事实代次;
}
