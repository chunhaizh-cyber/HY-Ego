bool 快照位置升序(const std::vector<海中鱼巣::事件日志排队项> &项组) {
  for (std::size_t 索引 = 1; 索引 < 项组.size(); ++索引)
    if (项组[索引 - 1].接受位置 >= 项组[索引].接受位置)
      return false;
  return true;
}

bool 排队项组相同(const std::vector<海中鱼巣::事件日志排队项> &左,
                  const std::vector<海中鱼巣::事件日志排队项> &右) {
  if (左.size() != 右.size())
    return false;
  for (std::size_t 索引 = 0; 索引 < 左.size(); ++索引) {
    const auto &左项 = 左[索引];
    const auto &右项 = 右[索引];
    if (左项.接受位置 != 右项.接受位置 ||
        左项.摘要.合同版本 != 右项.摘要.合同版本 ||
        左项.摘要.运行代次 != 右项.摘要.运行代次 ||
        左项.摘要.摘要身份 != 右项.摘要.摘要身份 ||
        左项.摘要.事件发生时间毫秒 != 右项.摘要.事件发生时间毫秒 ||
        左项.摘要.所属模块 != 右项.摘要.所属模块 ||
        左项.摘要.入口或操作 != 右项.摘要.入口或操作 ||
        左项.摘要.诊断分类 != 右项.摘要.诊断分类 ||
        左项.摘要.稳定编码 != 右项.摘要.稳定编码 ||
        左项.摘要.来源请求摘要 != 右项.摘要.来源请求摘要 ||
        左项.摘要.人读摘要 != 右项.摘要.人读摘要)
      return false;
  }
  return true;
}

