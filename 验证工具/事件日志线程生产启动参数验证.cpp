std::optional<std::uint64_t> 解析无符号整数(const wchar_t *文本) noexcept {
  if (!文本 || *文本 == L'\0' || *文本 == L'-')
    return std::nullopt;
  errno = 0;
  wchar_t *末尾 = nullptr;
  const auto 值 = std::wcstoull(文本, &末尾, 10);
  if (errno == ERANGE || !末尾 || *末尾 != L'\0')
    return std::nullopt;
  return static_cast<std::uint64_t>(值);
}

bool 解析参数(int 参数数量, wchar_t *参数值[], 验证参数 &参数) noexcept {
  if (参数数量 == 1)
    return true;
  if (参数数量 != 3 || std::wstring_view{参数值[1]} != L"--运行代次")
    return false;
  const auto 值 = 解析无符号整数(参数值[2]);
  if (!值 || *值 == 0 || *值 >
      (std::numeric_limits<std::uint64_t>::max)() - 1000)
    return false;
  参数.运行代次 = *值;
  return true;
}

