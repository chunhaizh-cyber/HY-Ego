struct 验证器 final {
    int 失败数 = 0;
    void 检查(bool 条件, const char* 名称) {
        std::cout << (条件 ? "[PASS] " : "[FAIL] ") << 名称 << '\n';
        if (!条件) ++失败数;
    }
};

std::optional<std::uint64_t> 解析无符号整数(const wchar_t* 文本) noexcept {
    if (!文本 || *文本 == L'\0' || *文本 == L'-') return std::nullopt;
    errno = 0;
    wchar_t* 末尾 = nullptr;
    const auto 值 = std::wcstoull(文本, &末尾, 10);
    if (errno == ERANGE || !末尾 || *末尾 != L'\0') return std::nullopt;
    return static_cast<std::uint64_t>(值);
}

std::optional<std::uint64_t> 解析参数(int 数量, wchar_t* 参数[]) noexcept {
    if (数量 != 3 || std::wstring_view{参数[1]} != L"--起始幂等身份")
        return std::nullopt;
    return 解析无符号整数(参数[2]);
}

std::uint64_t 当前代次(const 海中鱼巣::L1事实基座服务& 服务) {
    const auto 读取 = 服务.读取中性当前事实代次(
        {海中鱼巣::L1中性CRUD合同版本});
    return 读取.状态 == 海中鱼巣::L1中性读取状态::成功
        && 读取.合同版本 == 海中鱼巣::L1中性CRUD合同版本
        ? 读取.事实代次 : 0;
}

std::optional<海中鱼巣::稳定编码> 查映射(
    const 海中鱼巣::L1所有者范围写入结果& 结果, std::uint32_t 本地键) {
    for (const auto& [键, 编码] : 结果.新编码映射)
        if (键.值 == 本地键) return 编码;
    return std::nullopt;
}

void 验证L1所有者范围(std::uint64_t 起始, 验证器& 验证) {
    using namespace 海中鱼巣;
    auto 运行包 = 建立L1事实基座运行包();
    auto 另一运行包 = 建立L1事实基座运行包();
    auto& 服务 = 运行包.读取服务();
    auto& 签发器 = 运行包.所有者范围签发器();

    auto 交付1 = 签发器.建立所有者范围(
        {L1所有者范围CRUD合同版本, {起始}, L1所有者范围种类::独占结构范围});
    auto 交付2 = 签发器.建立所有者范围(
        {L1所有者范围CRUD合同版本, {起始 + 1}, L1所有者范围种类::独占结构范围});
    auto 跨实例交付 = 另一运行包.所有者范围签发器().建立所有者范围(
        {L1所有者范围CRUD合同版本, {起始}, L1所有者范围种类::独占结构范围});
    验证.检查(交付1.写入端口 && 交付2.写入端口 && 跨实例交付.写入端口
        && 交付1.建立结果.所有者事实 && 交付2.建立结果.所有者事实
        && 交付1.建立结果.所有者事实->所有者
            != 交付2.建立结果.所有者事实->所有者,
        "同实例两个独占 owner 不同且另一实例独立建立");
    if (!交付1.写入端口 || !交付2.写入端口) return;

    const auto 所有者1 = 交付1.写入端口->所有者身份();
    const auto 所有者2 = 交付2.写入端口->所有者身份();
    auto 重复交付 = 签发器.建立所有者范围(
        {L1所有者范围CRUD合同版本, {起始}, L1所有者范围种类::独占结构范围});
    验证.检查(重复交付.建立结果.状态 == L1所有者范围管理状态::精确重复
        && 重复交付.建立结果.所有者事实
        && 重复交付.建立结果.所有者事实->所有者 == 所有者1
        && !重复交付.写入端口,
        "活动 owner 不交付第二端口");
    验证.检查(交付1.写入端口->绑定于(服务)
        && !交付1.写入端口->绑定于(另一运行包.读取服务()),
        "端口只绑定原实例");

    auto 移动源端口 = std::move(*交付1.写入端口);
    std::optional<L1所有者范围写端口> 端口1{std::move(移动源端口)};
    auto 端口2 = std::move(*交付2.写入端口);
    验证.检查(!移动源端口.有效() && 端口1->有效() && 端口2.有效(),
        "移动源立即失效且目标端口有效");

    L1所有者范围写集请求 所有者1节点;
    所有者1节点.期望事实代次 = 当前代次(服务);
    所有者1节点.写入幂等身份 = {起始 + 10};
    所有者1节点.节点 = {{{1}, 节点种类::普通, std::nullopt},
        {{2}, 节点种类::属性类型, L1所有者范围值表示种类::I64},
        {{3}, 节点种类::普通, std::nullopt}};
    const auto 写节点1 = 端口1->提交所有者范围中性写集(所有者1节点);
    const auto 主节点 = 查映射(写节点1, 1);
    const auto 属性类型 = 查映射(写节点1, 2);
    const auto 关系类型 = 查映射(写节点1, 3);
    验证.检查(写节点1.状态 == L1所有者范围写入状态::成功
        && 写节点1.所有者 == 所有者1 && 主节点 && 属性类型 && 关系类型,
        "owner1 建立普通节点、属性类型与关系类型");
    if (!主节点 || !属性类型 || !关系类型) return;

    L1所有者范围写集请求 所有者2节点;
    所有者2节点.期望事实代次 = 当前代次(服务);
    所有者2节点.写入幂等身份 = {起始 + 10};
    所有者2节点.节点 = {{{1}, 节点种类::普通, std::nullopt}};
    const auto 写节点2 = 端口2.提交所有者范围中性写集(所有者2节点);
    const auto 跨所有者来源 = 查映射(写节点2, 1);
    验证.检查(写节点2.状态 == L1所有者范围写入状态::成功
        && 写节点2.所有者 == 所有者2 && 跨所有者来源,
        "同数值写入幂等身份按 owner 隔离");
    if (!跨所有者来源) return;

    L1所有者范围写集请求 值写集;
    值写集.期望事实代次 = 当前代次(服务);
    值写集.写入幂等身份 = {起始 + 11};
    值写集.值 = {{{1}, *主节点, *属性类型, std::int64_t{42}, *跨所有者来源}};
    值写集.属性槽变更 = {{{*主节点}, {*属性类型}, {1}}};
    const auto 写值 = 端口1->提交所有者范围中性写集(值写集);
    const auto 值编码 = 查映射(写值, 1);
    验证.检查(写值.状态 == L1所有者范围写入状态::成功 && 值编码,
        "值所属和类型同 owner 且来源允许跨 owner");
    if (!值编码) return;

    L1所有者范围写集请求 关系写集;
    关系写集.期望事实代次 = 当前代次(服务);
    关系写集.写入幂等身份 = {起始 + 12};
    关系写集.关系 = {{{1}, *主节点, *跨所有者来源, *关系类型, 7}};
    const auto 写关系 = 端口1->提交所有者范围中性写集(关系写集);
    const auto 关系编码 = 查映射(写关系, 1);
    验证.检查(写关系.状态 == L1所有者范围写入状态::成功 && 关系编码,
        "关系类型同 owner 且端点允许跨 owner");
    if (!关系编码) return;

    const auto 截止 = 当前代次(服务);
    const auto 当前节点 = 服务.读取所有者范围当前节点(
        {L1所有者范围CRUD合同版本, *主节点});
    const auto 当前值 = 服务.读取所有者范围当前值(
        {L1所有者范围CRUD合同版本, *值编码});
    const auto 关系组 = 服务.读取所有者范围当前源关系组(
        {L1所有者范围CRUD合同版本, *主节点, *关系类型});
    L1所有者范围一致当前读取请求 一致请求;
    一致请求.期望事实代次 = 截止;
    一致请求.所有者 = {所有者1};
    一致请求.节点 = {*主节点};
    一致请求.值 = {*值编码};
    一致请求.属性值 = {{*主节点, *属性类型}};
    一致请求.源关系组 = {{*主节点, *关系类型}};
    const auto 一致 = 服务.尝试读取所有者范围一致当前投影(一致请求);
    验证.检查(当前节点.状态 == L1所有者范围读取状态::成功
        && 当前值.状态 == L1所有者范围读取状态::成功
        && 关系组.状态 == L1所有者范围读取状态::成功
        && 关系组.关系组.size() == 1
        && 一致.状态 == L1所有者范围一致当前读取状态::成功
        && 一致.读取事实代次 == 截止 && 一致.所有者.size() == 1
        && 一致.属性值.size() == 1 && 一致.源关系组.size() == 1,
        "owner-aware 当前、关系组、属性与一致投影同截止");

    L1中性写集请求 legacy写集;
    legacy写集.期望事实代次 = 当前代次(服务);
    legacy写集.幂等键 = {起始 + 20};
    legacy写集.节点 = {{{1}, 节点种类::普通, std::nullopt}};
    const auto legacy写入 = 服务.提交中性写集(legacy写集);
    const auto legacy节点 = legacy写入.新编码映射.front().second;
    L1中性写集请求 隔离写集;
    隔离写集.期望事实代次 = 当前代次(服务);
    隔离写集.幂等键 = {起始 + 21};
    隔离写集.关系 = {{{1}, *主节点, legacy节点, legacy节点, 0}};
    const auto 隔离 = 服务.提交中性写集(隔离写集);
    const auto legacy历史 = 服务.读取所有者范围历史事实(
        {L1所有者范围CRUD合同版本, legacy节点});
    const auto* legacy事实 = legacy历史.事实
        ? std::get_if<L1所有者范围节点事实>(&*legacy历史.事实) : nullptr;
    const auto legacy所有者 = legacy事实 ? 服务.读取当前结构所有者(
        {L1所有者范围CRUD合同版本, legacy事实->写入所有者})
        : L1结构所有者当前读取结果{};
    验证.检查(legacy写入.状态 == L1中性写入状态::成功
        && 隔离.状态 == L1中性写入状态::入口拒绝
        && legacy事实 && legacy事实->写入所有者 != 所有者1
        && legacy所有者.所有者事实
        && legacy所有者.所有者事实->范围种类 == L1所有者范围种类::旧共享范围,
        "v1 落 legacy owner 且触碰独占事实入口拒绝");

    L1所有者范围写集请求 清空;
    清空.期望事实代次 = 当前代次(服务);
    清空.写入幂等身份 = {起始 + 13};
    清空.退出事实 = {*关系编码, *值编码, *主节点, *属性类型, *关系类型};
    const auto 清空结果 = 端口1->提交所有者范围中性写集(清空);
    const auto 退出前代次 = 当前代次(服务);
    端口1.reset();
    const auto 退出 = 签发器.退出所有者范围(
        {L1所有者范围CRUD合同版本, 所有者1, {起始}, 退出前代次});
    const auto 失效提交 = 移动源端口.提交所有者范围中性写集(清空);
    const auto owner历史 = 服务.读取历史结构所有者(
        {L1所有者范围CRUD合同版本, 所有者1});
    验证.检查(清空结果.状态 == L1所有者范围写入状态::成功
        && 退出.状态 == L1所有者范围管理状态::成功
        && 退出.所有者事实 && 退出.所有者事实->退出事实代次
        && 失效提交.状态 == L1所有者范围写入状态::许可拒绝
        && owner历史.状态 == L1所有者范围读取状态::成功
        && owner历史.所有者事实 && owner历史.所有者事实->退出事实代次,
        "事实清零、租约释放后 owner 退出且失效端口许可拒绝");

    std::optional<L1所有者范围写端口> 包销毁后端口;
    {
        auto 临时包 = 建立L1事实基座运行包();
        auto 临时交付 = 临时包.所有者范围签发器().建立所有者范围(
            {L1所有者范围CRUD合同版本, {起始 + 90},
                L1所有者范围种类::独占结构范围});
        包销毁后端口.emplace(std::move(*临时交付.写入端口));
    }
    验证.检查(!包销毁后端口->有效(), "运行包析构使端口弱绑定失效");
}

void 验证普通应用工厂(std::uint64_t 起始, 验证器& 验证) {
    using namespace 海中鱼巣;
    auto 装配 = 构造普通应用上下文({});
    验证.检查(装配.成功(), "普通应用公开工厂装配成功");
    if (!装配.成功()) return;
    auto& 存在服务 = 装配.上下文->取得L2存在结构服务();
    const auto& 常量存在服务 = std::as_const(*装配.上下文).取得L2存在结构服务();
    验证.检查(&存在服务 == &常量存在服务, "重复取得同一存在服务地址");
    const auto 初始 = 存在服务.读取当前事实代次();
    验证.检查(初始.状态 == L2结构状态::已读取 && 初始.事实截止代次 != 0,
        "存在服务公开读取当前事实代次");

    const L2存在节点新增请求 请求{{L2结构合同版本, 初始.事实截止代次}, {起始 + 100}};
    const auto 首次 = 存在服务.新增存在节点(请求);
    const auto 重复 = 存在服务.新增存在节点(请求);
    auto 异义请求 = 请求;
    异义请求.请求头.期望事实代次 = 首次.结果头.事实截止代次;
    const auto 冲突 = 存在服务.新增存在节点(异义请求);
    验证.检查(首次.结果头.状态 == L2结构状态::已提交 && 首次.存在
        && 重复.结果头.状态 == L2结构状态::精确重复
        && 重复.存在 && 重复.存在->身份 == 首次.存在->身份
        && 重复.存在->生命周期.创建事实代次
            == 首次.存在->生命周期.创建事实代次
        && 重复.存在->固定属性.empty()
        && 冲突.结果头.状态 == L2结构状态::幂等冲突 && !冲突.存在,
        "真实存在新增、精确重复与同键异义冲突");
    if (!首次.存在) return;

    const L2存在完整读取请求 当前请求{
        {L2结构合同版本, 首次.结果头.事实截止代次},
        L2读取类别::当前, 首次.存在->身份, 0};
    const auto 当前 = 存在服务.读取完整存在(当前请求);
    验证.检查(当前.结果头.状态 == L2结构状态::已读取
        && 当前.存在 && 当前.存在->身份 == 首次.存在->身份
        && 当前.存在->生命周期.创建事实代次
            == 首次.存在->生命周期.创建事实代次
        && 当前.存在->固定属性.empty(), "真实存在当前完整读回逐字段一致");

    const L2存在退出请求 退出请求{
        {L2结构合同版本, 首次.结果头.事实截止代次},
        {起始 + 101}, 首次.存在->身份, {}};
    const auto 退出 = 存在服务.退出存在(退出请求);
    auto 已退出当前请求 = 当前请求;
    已退出当前请求.请求头.期望事实代次 = 退出.结果头.事实截止代次;
    const auto 已退出当前 = 存在服务.读取完整存在(已退出当前请求);
    auto 历史请求 = 已退出当前请求;
    历史请求.读取类别 = L2读取类别::历史;
    历史请求.历史截止事实代次 = 退出.结果头.事实截止代次;
    const auto 历史 = 存在服务.读取完整存在(历史请求);
    验证.检查(退出.结果头.状态 == L2结构状态::已提交 && 退出.已退出存在
        && 退出.已退出存在->生命周期.退出事实代次
            == 退出.结果头.事实截止代次
        && 已退出当前.结果头.状态 == L2结构状态::已退出 && !已退出当前.存在
        && 历史.结果头.状态 == L2结构状态::已读取 && 历史.存在
        && 历史.存在->身份 == 首次.存在->身份
        && 历史.存在->生命周期.退出事实代次 == 退出.结果头.事实截止代次,
        "退出后当前已退出且历史返回完整生命周期");
}

