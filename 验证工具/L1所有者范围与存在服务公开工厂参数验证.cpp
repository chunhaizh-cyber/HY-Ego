int wmain(int 参数数量, wchar_t* 参数[]) {
    const auto 起始 = 解析参数(参数数量, 参数);
    if (!起始 || *起始 == 0 || *起始 > std::numeric_limits<std::uint64_t>::max() - 200) {
        std::cerr << "参数错误：需要非零 --起始幂等身份。\n";
        return 2;
    }
    验证器 验证;
    验证L1所有者范围(*起始, 验证);
    验证普通应用工厂(*起始, 验证);
    std::cout << "验证结论：" << (验证.失败数 == 0 ? "PASS" : "FAIL")
        << "，失败数=" << 验证.失败数 << '\n';
    return 验证.失败数 == 0 ? 0 : 1;
}
