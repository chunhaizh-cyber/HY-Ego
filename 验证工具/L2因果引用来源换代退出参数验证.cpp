参数 解析(int 数量, char** 值) {
    参数 结果;
    for (int i = 1; i + 1 < 数量; i += 2) {
        const std::string_view 名称{值[i]}; const auto 数值 = std::stoull(值[i + 1]);
        if (名称 == "--幂等基值") 结果.幂等基值 = 数值;
        else if (名称 == "--条件一顺序") 结果.条件一顺序 = 数值;
        else if (名称 == "--条件二顺序") 结果.条件二顺序 = 数值;
        else if (名称 == "--结果一顺序") 结果.结果一顺序 = 数值;
        else if (名称 == "--结果二顺序") 结果.结果二顺序 = 数值;
        else throw std::invalid_argument("unknown argument");
    }
    return 结果;
}
struct 验证器 final {
    int 失败 = 0;
    void 检查(bool 条件, std::string_view 名称) {
        std::cout << (条件 ? "[PASS] " : "[FAIL] ") << 名称 << '\n';
        if (!条件) ++失败;
    }
};
std::uint64_t 当前代次(const L1事实基座服务& L1) {
    const auto 读 = L1.读取中性当前事实代次({L1中性CRUD合同版本});
    return 读.状态 == L1中性读取状态::成功 ? 读.事实代次 : 0;
}
std::vector<稳定编码> 展平(const L2因果自有关系引用& 自有) {
    std::vector<稳定编码> 组{自有.族归属关系稳定编码};
    组.insert(组.end(), 自有.条件关系稳定编码.begin(), 自有.条件关系稳定编码.end());
    if (自有.动作关系稳定编码) 组.push_back(*自有.动作关系稳定编码);
    组.insert(组.end(), 自有.结果关系稳定编码.begin(), 自有.结果关系稳定编码.end());
    组.push_back(自有.来源值稳定编码); std::sort(组.begin(), 组.end()); return 组;
}
template<class 结果类型> bool 空失败(const 结果类型& 结果, L2结构状态 状态,
    std::uint64_t 代次, const L1事实基座服务& L1) {
    return 结果.结果头.状态 == 状态 && 当前代次(L1) == 代次;
}
bool 含因果(const L2当前因果组读取结果& 结果, L2因果身份 身份) {
    return std::any_of(结果.因果.begin(), 结果.因果.end(), [&](const auto& 因果) {
        return 因果.身份 == 身份;
    });
}
bool 空载荷(const L2因果状态引用组替换结果& 结果) {
    return !结果.当前因果 && !结果.当前自有事实 && 结果.已退出关系.empty();
}
bool 空载荷(const L2因果动作引用替换结果& 结果) {
    return !结果.当前因果 && !结果.当前自有事实 && !结果.已退出动作关系;
}
bool 空载荷(const L2因果来源换代结果& 结果) {
    return !结果.当前因果 && !结果.当前自有事实 && !结果.已退出来源值;
}
bool 空载荷(const L2因果退出结果& 结果) {
    return !结果.已退出因果 && !结果.已退出自有事实;
}
