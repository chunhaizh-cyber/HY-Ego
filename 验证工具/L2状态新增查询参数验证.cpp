std::uint64_t 当前代次(const L1事实基座服务& 服务) {
    const auto 读取 = 服务.读取中性当前事实代次({L1中性CRUD合同版本});
    return 读取.状态 == L1中性读取状态::成功 ? 读取.事实代次 : 0;
}

struct 验证器 final {
    int 失败数 = 0;
    void 检查(bool 条件, const char* 名称) {
        std::cout << (条件 ? "[PASS] " : "[FAIL] ") << 名称 << '\n';
        if (!条件) ++失败数;
    }
};

bool 状态组严格升序(const L2当前状态组读取结果& 结果) {
    if (!结果.成功()) return false;
    return std::adjacent_find(结果.状态.begin(), 结果.状态.end(),
        [](const L2状态事实& 左, const L2状态事实& 右) {
            return 左.身份.值.值 >= 右.身份.值.值;
        }) == 结果.状态.end();
}

