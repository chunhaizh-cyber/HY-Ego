namespace {

template<std::size_t N>
bool 全部非零唯一(const std::array<std::uint64_t, N>& 编码组) {
    for (std::size_t i = 0; i < N; ++i) {
        if (编码组[i] == 0) return false;
        for (std::size_t j = i + 1; j < N; ++j)
            if (编码组[i] == 编码组[j]) return false;
    }
    return true;
}

}

