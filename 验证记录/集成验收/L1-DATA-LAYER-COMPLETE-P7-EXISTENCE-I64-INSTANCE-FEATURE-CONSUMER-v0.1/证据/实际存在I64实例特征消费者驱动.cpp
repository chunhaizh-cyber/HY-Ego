template<std::size_t N>
bool 全部非零唯一(const std::array<std::uint64_t, N>& 编码组) {
    for (std::size_t 左 = 0; 左 < N; ++左) {
        if (编码组[左] == 0) return false;
        for (std::size_t 右 = 左 + 1; 右 < N; ++右)
            if (编码组[左] == 编码组[右]) return false;
    }
    return true;
}

template<class 结果类型>
bool 定义完整(const 结果类型& 结果) {
    return 结果.事实 && I64特征定义事实完整(*结果.事实)
        && 全部非零唯一(std::array<std::uint64_t, 4>{
            结果.事实->特征定义.值, 结果.定义标记值.值,
            结果.下界值.值, 结果.上界值.值});
}

template<class 左类型, class 右类型>
bool 定义相同(const 左类型& 左, const 右类型& 右) {
    return 定义完整(左) && 定义完整(右)
        && 左.事实->合同版本 == 右.事实->合同版本
        && 左.事实->规则版本 == 右.事实->规则版本
        && 左.事实->事实截止代次 == 右.事实->事实截止代次
        && 左.事实->特征定义 == 右.事实->特征定义
        && 左.事实->下界 == 右.事实->下界
        && 左.事实->上界 == 右.事实->上界
        && 左.事实->来源服务 == 右.事实->来源服务
        && 左.定义标记值 == 右.定义标记值
        && 左.下界值 == 右.下界值 && 左.上界值 == 右.上界值;
}

template<class 左类型, class 右类型>
bool 登记相同(const 左类型& 左, const 右类型& 右) {
    return 左.登记 && 右.登记
        && 实例特征结构登记完整(*左.登记)
        && 实例特征结构登记完整(*右.登记)
        && 左.登记->合同版本 == 右.登记->合同版本
        && 左.登记->规则版本 == 右.登记->规则版本
        && 左.登记->事实截止代次 == 右.登记->事实截止代次
        && 左.登记->服务身份 == 右.登记->服务身份
        && 左.登记->宿主槽关系类型 == 右.登记->宿主槽关系类型
        && 左.登记->定义模板关系类型 == 右.登记->定义模板关系类型
        && 左.登记->当前I64值属性类型 == 右.登记->当前I64值属性类型;
}

template<class 左类型, class 右类型>
bool 实际存在相同(const 左类型& 左, const 右类型& 右) {
    return 左.状态 == 右.状态 && 左.事实 && 右.事实
        && 实际存在事实完整(*左.事实) && 实际存在事实完整(*右.事实)
        && 左.事实->合同版本 == 右.事实->合同版本
        && 左.事实->规则版本 == 右.事实->规则版本
        && 左.事实->事实截止代次 == 右.事实->事实截止代次
        && 左.事实->世界根 == 右.事实->世界根
        && 左.事实->存在 == 右.事实->存在
        && 左.事实->当前场景 == 右.事实->当前场景
        && 左.事实->资格 == 右.事实->资格
        && 左.事实->当前场景归属关系 == 右.事实->当前场景归属关系;
}

template<class 结果类型>
bool 实例完整(const 结果类型& 结果) {
    return 结果.事实 && I64实例特征事实完整(*结果.事实)
        && 有效(结果.宿主关系) && 有效(结果.定义关系)
        && 全部非零唯一(std::array<std::uint64_t, 4>{
            结果.事实->实例槽.值, 结果.宿主关系.值,
            结果.定义关系.值, 结果.事实->当前值.值});
}

template<class 左类型, class 右类型>
bool 实例相同(const 左类型& 左, const 右类型& 右) {
    return 实例完整(左) && 实例完整(右)
        && 左.事实->合同版本 == 右.事实->合同版本
        && 左.事实->规则版本 == 右.事实->规则版本
        && 左.事实->事实截止代次 == 右.事实->事实截止代次
        && 左.事实->宿主 == 右.事实->宿主
        && 左.事实->特征定义 == 右.事实->特征定义
        && 左.事实->实例槽 == 右.事实->实例槽
        && 左.事实->当前值 == 右.事实->当前值
        && 左.事实->I64值 == 右.事实->I64值
        && 左.事实->来源节点 == 右.事实->来源节点
        && 左.宿主关系 == 右.宿主关系
        && 左.定义关系 == 右.定义关系;
}

template<class 结果类型>
bool 无部分实例(const 结果类型& 结果) {
    return !结果.事实 && !有效(结果.宿主关系) && !有效(结果.定义关系);
}

template<class 世界类型>
std::uint64_t 世界截止(const 世界类型& 世界) {
    return 世界.成功() && 世界.登记 ? 世界.登记->已验证事实代次 : 0;
}

