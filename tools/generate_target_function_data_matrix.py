        "",
        "`BIZ-L1/L2/L3/L4`表示目标图分解深度，不等于0050定义的语义责任L1—L5。矩阵中的L1只指4015通用事实基座。",
        "",
        "## 2. 依据",
        "",
        "```text",
        "规范/0050_项目通用机器逻辑与禁止性规则总纲_20260721.md",
        "规范/4015_子规范_L1简化事实基座.md",
        "规范/4030_子规范_基础信息服务分层与领域写授权.md",
        "规范/4200_子规范_世界树业务服务与同代次完整事实快照.md",
        "流程图/目标业务流程图/README.md",
        "流程图/目标业务流程图/**/BIZ-L*_目标函数流程图_v*.md",
        "```",
        "",
        "## 3. L1有限访问模式",
        "",
        "| 模式 | 通用数据需求 | 当前裁决 |",
