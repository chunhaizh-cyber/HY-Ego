def 读取文本(路径: Path) -> str:
    return 路径.read_text(encoding="utf-8-sig")


def 提取字段(文本: str, 字段: str) -> str:
    匹配 = re.search(rf"^{re.escape(字段)}\s*[:：]\s*(.+)$", 文本, re.MULTILINE)
    return 匹配.group(1).strip() if 匹配 else "未登记"


def 拆表行(行: str) -> list[str]:
    return [格.strip() for 格 in 行.strip().strip("|").split("|")]


def 提取事实读写(文本: str) -> str:
    行组 = 文本.splitlines()
    结果: list[str] = []
    for 序号, 行 in enumerate(行组):
        if not 行.lstrip().startswith("|"):
            continue
        表头 = 拆表行(行)
        if "事实读写" not in 表头:
            continue
        列号 = 表头.index("事实读写")
        for 数据行 in 行组[序号 + 2 :]:
            if not 数据行.lstrip().startswith("|"):
                break
            单元格 = 拆表行(数据行)
            if 列号 >= len(单元格):
                continue
            值 = re.sub(r"`", "", 单元格[列号]).strip()
            if 值 and 值 not in 结果:
                结果.append(值)
    if not 结果:
        输入 = 提取字段(文本, "输入")
        输出 = 提取字段(文本, "输出")
        if 输入 != "未登记" or 输出 != "未登记":
            return f"输入：{输入}；输出：{输出}"
        return "未登记，需回到目标函数图补齐"
    摘要 = "；".join(结果)
    return 摘要 if len(摘要) <= 180 else 摘要[:177] + "…"


def 识别领域(材料: str) -> str:
    结果 = [名称 for 名称, 关键词组 in 领域关键词 if any(关键词 in 材料 for 关键词 in 关键词组)]
    return "、".join(结果) if 结果 else "平台/纯值"


def 识别读写(事实读写: str, 函数材料: str) -> str:
    材料 = 事实读写 + 函数材料
    判定材料 = 事实读写
    for 否定片段 in (
        "无业务写入", "零业务写入", "无写入", "不写业务事实", "不写世界事实",
        "不修改业务事实", "不反写事实", "不反写业务事实", "不得反写业务事实",
        "只写队列", "只写消息队列", "只写线程生命周期投影", "只改队列占用",
        "只形成材料", "只形成派生材料", "只改进程信号处理器",
    ):
        判定材料 = 判定材料.replace(否定片段, "")
    有读 = any(词 in 材料 for 词 in ("读取", "只读", "回读", "查询", "枚举", "快照", "复核", "定位", "观察"))
    有写 = any(词 in 判定材料 for 词 in ("发布事实", "提交写集", "写入事实", "原子发布", "领域提交", "领域写入", "结算", "退役", "接纳"))
    if 有读 and 有写:
        return "读写"
    if 有写:
        return "写"
    if 有读:
        return "读"
    return "无L1数据访问"


def 识别访问模式(事实读写: str, 函数材料: str, 读写: str, 调用边界: str, 复核状态: str) -> list[str]:
    材料 = 事实读写 + 函数材料
    if 复核状态 == "需按4015重基线":
        return ["A12"]
    if 调用边界 == "不消费L1":
        return ["A00"]
    if 调用边界 in {"只能调用具名领域服务", "经具名领域服务；待详细设计确认直连者"}:
        return ["A11"]
    模式: list[str] = []
    if "读" in 读写:
        模式.append("A01")
        if any(词 in 材料 for 词 in ("属性", "当前值", "特征值", "安全值", "服务值", "优先级", "时间值")):
            模式.append("A02")
        if any(词 in 材料 for 词 in ("组", "全部", "完整", "联合", "批量", "一致", "快照")):
            模式.append("A03")
        if any(词 in 材料 for 词 in ("关系", "父", "子", "来源", "归属", "引用", "挂载", "组成", "承接")):
            模式.append("A04")
        if any(词 in 材料 for 词 in ("代次", "截止", "发布见证", "同次", "同代")):
            模式.append("A05")
        if "历史" in 材料:
            模式.append("A08")
        if "审计" in 材料:
            模式.append("A09")
        if any(词 in 材料 for 词 in ("完整快照", "恢复材料", "恢复候选")):
            模式.append("A10")
    if "写" in 读写:
        模式.append("A06")
        if any(词 in 材料 for 词 in ("读回", "结果未知", "发布见证", "幂等", "联合")):
            模式.append("A07")
    return list(dict.fromkeys(模式 or ["A11"]))


def 识别调用边界(路径: Path, 函数材料: str, 读写: str, 事实读写: str) -> str:
    if "L1事实基座" in str(路径):
        return "L1公开服务"
    if 读写 == "无L1数据访问":
        return "不消费L1"
    禁止直连词 = ("组合器", "线程", "投影", "算法", "序列化", "路由", "队列", "邮箱", "桥::", "端口::", "适配器", "形成器")
    if any(词 in 函数材料 for 词 in 禁止直连词):
        有领域依赖 = any(词 in 事实读写 for 词 in ("领域服务", "领域提交", "领域写入", "业务事实", "世界事实", "需求事实", "任务事实", "服务值", "安全值"))
        return "只能调用具名领域服务" if 有领域依赖 else "不消费L1"
    if "世界树业务服务::" in 函数材料:
        return "只能调用具名领域服务"
    if any(词 in 函数材料 for 词 in ("数据操作::", "业务服务::", "服务::", "读取器::")):
        return "事实所有者内部可消费L1"
    return "经具名领域服务；待详细设计确认直连者"


def 识别复核状态(文本: str) -> str:
    旧口径 = ("节点直接", "旧四仓", "事实截止向量", "参与者组", "对象版本", "裸句柄")
    # 只把明确的设计治理缺口识别为“未决”。“待裁决”“待核验”和
    # “未冻结”同时也是许可申请、低置信事实、旧代次占用和执行冻结的
    # 合法业务状态，不能仅凭这些词出现在返回值或流程分支中阻断 L1 需求。
    明确未决 = (
        "待用户裁决",
        "机器语义未决",
        "未决机器语义",
        "依赖未决",
        "缺少正式裁决",
        "正式裁决缺失",
        "尚未裁决",
        "不得据此冻结L1",
    )
    if any(词 in 文本 for 词 in 旧口径):
        return "需按4015重基线"
    if any(词 in 文本 for 词 in 明确未决):
        return "存在未决，不能冻结L1需求"
    return "已提取，仍需详细设计逐字段冻结"


def Markdown转义(值: str) -> str:
    return 值.replace("|", "\\|").replace("\n", " ")


